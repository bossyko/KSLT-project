-- ============================================================
-- Убрать приглашения, отправленные самому себе
-- ============================================================
--
-- На сервере стоял запрет на такое приглашение, но его закомментировали
-- на время испытаний и не вернули. Пока он был выключен, человек мог
-- позвать сам себя и получить собственное приглашение.
--
-- Запрет вернули в send-game-invite. Здесь убираем то, что успело
-- накопиться, пока его не было.
--
-- Файл меняет базу. Смотреть, что уйдёт, — в self-invites-check.sql.
-- Запустить его сначала: удаление необратимо.

BEGIN;

DELETE FROM game_invites gi
 USING profiles p
 WHERE p.id = gi.sender_id
   AND p.player_id IS NOT NULL
   AND p.player_id = gi.receiver_player_id;

COMMIT;

