-- ============================================
-- Удаление тестовых новостей (все 10 штук)
-- Запускать в Supabase SQL Editor по шагам, не целиком.
-- ============================================
--
-- Настоящие новости переносим с tennis.kg, эти — остатки разработки:
-- четыре сгенерированы автоматически из тестовых турниров, остальные
-- набивались руками для проверки вёрстки.
--
-- Осторожно: у новостей есть связанная мелочь — реакции (22 записи)
-- и голоса в опросах (5). Если внешние ключи заведены без ON DELETE CASCADE,
-- удаление новостей упрётся в них, поэтому чистим сверху вниз.

-- ---- ШАГ 1. Что удаляем ----
SELECT id, published_at::date AS дата, title,
       (SELECT count(*) FROM news_reactions r WHERE r.news_id = n.id) AS реакций,
       (SELECT count(*) FROM news_poll_votes v WHERE v.news_id = n.id) AS голосов
FROM news n
ORDER BY published_at DESC;

-- Ожидается 10 строк. Если больше — значит появилось что-то новое,
-- разобраться до удаления.

-- ---- ШАГ 2. Реакции и голоса ----
DELETE FROM news_poll_votes;
DELETE FROM news_reactions;

-- ---- ШАГ 3. Сами новости ----
DELETE FROM news;

-- ---- ШАГ 4. Проверка ----
SELECT (SELECT count(*) FROM news)            AS новостей,
       (SELECT count(*) FROM news_reactions)  AS реакций,
       (SELECT count(*) FROM news_poll_votes) AS голосов;
-- Должны быть три нуля.

