-- ---- 5. Гости, за которыми ничего не тянется, — удаляем ----
--
-- Проверяем по самим записям, а не по счётчикам побед в карточке: счётчики
-- обновляются не всегда, и по ним карточка выглядела пустой, хотя матчи есть.

DELETE FROM players p
 WHERE p.is_guest
   AND NOT EXISTS (SELECT 1 FROM matches m
                    WHERE m.player1_id = p.id OR m.player2_id = p.id OR m.winner_id = p.id)
   AND NOT EXISTS (SELECT 1 FROM tournament_registrations r
                    WHERE r.player_id = p.id OR r.partner_id = p.id)
   AND NOT EXISTS (SELECT 1 FROM tournament_results tr
                    WHERE tr.player_id = p.id OR tr.partner_id = p.id)
   AND NOT EXISTS (SELECT 1 FROM challenges c
                    WHERE c.challenger_player_id = p.id OR c.opponent_player_id = p.id)
   AND NOT EXISTS (SELECT 1 FROM live_matches l
                    WHERE l.player1_id = p.id OR l.player2_id = p.id)
   AND NOT EXISTS (SELECT 1 FROM rating_history rh WHERE rh.player_id = p.id)
   AND NOT EXISTS (SELECT 1 FROM profiles pr WHERE pr.player_id = p.id);

COMMIT;

