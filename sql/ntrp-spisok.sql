-- вручную и подтверждены Costa.
--
-- Что делает файл:
--   1. добавляет поля ntrp_singles, ntrp_doubles и признак гостя;
--   2. проставляет рейтинги 286 игрокам, которые нашлись по имени;
--   3. заводит 61 новых карточек из списка;
--   4. помечает гостями всех, кого в списке нет;
--   5. удаляет тех гостей, за которыми не тянется ни матча, ни заявки, ни
--      привязанного аккаунта — они никому не нужны.
--
