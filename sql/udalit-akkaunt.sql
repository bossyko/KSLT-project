--
-- Нужно, когда человек хочет зарегистрироваться заново с нуля. Удаляется и
-- запись входа (почта, пароль, привязка Google), и профиль на сайте.
--
-- Порядок такой: сперва посмотреть, что именно найдено, и только потом
-- удалять. Почта вписывается в одном месте — в первой строке каждого блока.
--
-- Карточку игрока (таблица players) это не трогает: рейтинг, история матчей и
-- место в турнирах остаются. Пропадает только вход и личный кабинет.
