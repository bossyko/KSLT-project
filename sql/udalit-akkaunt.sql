-- Файл меняет базу.

-- ---- 1. Посмотреть, кого найдём ----
-- Впиши почту вместо ПОЧТА и запусти только этот запрос.

SELECT u.id            AS вход,
       u.email         AS почта,
       u.created_at    AS заведён,
       u.last_sign_in_at AS последний_вход,
       p.full_name     AS имя,
       p.role          AS роль,
       p.player_id     AS карточка_игрока
  FROM auth.users u
  LEFT JOIN public.profiles p ON p.id = u.id
 WHERE u.email ILIKE 'ПОЧТА';

