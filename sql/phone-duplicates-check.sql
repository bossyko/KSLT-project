-- ============================================
-- Двойники по телефону
-- ============================================
--
-- В таблице стоит запрет на повторение поля phone, но там лежит номер в
-- том виде, как его набрал человек. «+996 700 12-34-56», «0700123456» и
-- «996700123456» — три разные строки, запрет их не ловит, и один номер
-- спокойно заводится на несколько учётных записей.
--
-- Рядом есть phone_e164 — тот же номер, приведённый к единому виду:
-- только цифры, с кодом страны. Считает его сама база при каждой записи.
-- Запрет вешаем на него — тогда написание перестаёт иметь значение.
--
-- Пустые номера под запрет не попадают: телефон не обязателен, и людей
-- без него может быть сколько угодно.

-- Этот файл только смотрит и ничего не меняет — его можно смело
-- прогонять целиком. Запрет и проверка вынесены в phone-unique-index.sql:
-- их запускают, когда двойников не осталось.

-- ============================================
-- 1. Есть ли двойники сейчас
-- ============================================
-- Если что-то вернётся — сначала разобрать эти записи руками, иначе
-- запрет не создастся.

SELECT phone_e164 AS номер,
       count(*)   AS учётных_записей,
       string_agg(COALESCE(email, '—') || ' (' || COALESCE(full_name, 'без имени') || ')', ', ') AS кто
  FROM profiles
 WHERE phone_e164 <> ''
 GROUP BY phone_e164
HAVING count(*) > 1
 ORDER BY count(*) DESC;

-- ============================================
-- 2. Кто именно двоится
-- ============================================
-- Разворачивает найденное в список учётных записей: по почте и дате
-- видно, где живой человек, а где осталась отладочная запись.

SELECT id, email, full_name, phone, phone_e164, role, created_at, last_seen
  FROM profiles
 WHERE phone_e164 IN (
   SELECT phone_e164 FROM profiles
    WHERE phone_e164 <> ''
    GROUP BY phone_e164 HAVING count(*) > 1
 )
 ORDER BY phone_e164, created_at;

