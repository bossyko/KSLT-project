-- СЕКРЕТ. «Возьми значение в панели» — невыполнимое указание:
-- значение секрета после сохранения не показывается НИКОМУ.
-- Поэтому пароль, живущий в двух местах, не «списывается» из
-- одного в другое, а ЗАВОДИТСЯ ЗАНОВО СРАЗУ В ОБА.
--
-- ─────────────────────────────────────────────────────────────
-- ПОРЯДОК. Три шага, второй и третий — подряд, не откладывая:
--
-- 1. На Маке в терминале:
--        openssl rand -hex 32
--    Получится 64 знака. Это и есть новый пароль. В переписку его
--    не присылай — ни мне, ни кому.
--
-- 2. В панели: Edge Functions → Secrets → поле Name `CRON_SECRET`,
--    поле Value — новый пароль → Save. Имя то же самое: сохранение
--    перезапишет прежнее значение.
--
-- 3. Здесь: подставь тот же пароль вместо <НОВЫЙ_ПАРОЛЬ> и прогони.
--    Файл после прогона НЕ сохраняй с ключом внутри.
-- ─────────────────────────────────────────────────────────────

SELECT vault.update_secret(
    (SELECT id FROM vault.secrets WHERE name = 'cron_secret'),
    '<НОВЫЙ_ПАРОЛЬ>',
    'cron_secret',
    'Пароль заданий по расписанию. Совпадает с секретом CRON_SECRET у функций. Заведён заново 07.11.2026.'
);

-- Проверка — ЧТЕНИЕМ, а не ответом «Success». Сам пароль не виден:
SELECT length(ds.decrypted_secret)                       AS dlina,
       left(ds.decrypted_secret, 3)                      AS pervye_tri,
       (ds.decrypted_secret =
        'be35be13f9b22acc43c3d521df3b0eb18ff07b8ec43848c4928f0e720edcf2b0')
                                                         AS vsyo_eshchyo_otpechatok,
       s.updated_at
  FROM vault.secrets s
  JOIN vault.decrypted_secrets ds ON ds.id = s.id
 WHERE s.name = 'cron_secret';

