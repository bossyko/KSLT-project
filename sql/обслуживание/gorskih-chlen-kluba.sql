-- ============================================================
-- Евгений Горских: категория Futures, дальше как у всех
-- ============================================================
--
-- Карточка есть с прежних турниров, но категории у неё не было — значит, в
-- рейтинге его не видно и очки складывать некуда. Категорию проставляем и
-- заводим строку в рейтинге с нулём: прежние турниры он играл вне клуба.
--
-- Членство флагом не помечаем. До 31 декабря 2026 идёт бесплатный период:
-- заявки принимаются без проверки членства, а в рейтинге все показаны
-- членами. Выделять одного человека флагом незачем — оформим, когда период
-- закончится и начнутся оплаты.
--
-- NTRP проставит администратор в карточке игрока — здесь его не трогаем.
--
-- Аккаунт он заведёт сам при регистрации на сайте: карточка привяжется к
-- профилю по имени, и в кабинете подтянется вся его история — она уже в
-- базе, от карточки никуда не девалась.
--
-- Категорию поменяйте, если клуб определил его не в Futures.
--
-- Запускать можно повторно.

BEGIN;

UPDATE public.players
   SET is_member   = false,
       is_guest    = false,
       category_id = 'futures'
 WHERE id = 'evgeniy-gorskih';

-- Строка в рейтинге категории: без неё игрок в таблицу не попадёт. Очки
-- начнутся с нуля и пойдут от турниров
INSERT INTO public.player_categories (player_id, category_id, points)
VALUES ('evgeniy-gorskih', 'futures', 0)
ON CONFLICT (player_id, category_id) DO NOTHING;

COMMIT;

-- ---- Проверка ----

SELECT p.name         AS игрок,
       p.is_member    AS член_клуба,
       p.is_guest     AS гость,
       p.category_id  AS категория,
       p.ntrp_singles AS ntrp,
       pc.points      AS очки_в_категории
  FROM public.players p
  LEFT JOIN public.player_categories pc
         ON pc.player_id = p.id AND pc.category_id = p.category_id
 WHERE p.id = 'evgeniy-gorskih';
-- Ожидаем: член клуба false, гость false, категория futures, очки 0.
