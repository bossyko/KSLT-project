-- ПОВОД (07.11, 06:35). Замер `net._http_response`: до 05:15 все
-- задания отвечали 200, с 05:20 КАЖДОЕ отвечает 401 с телом
-- {"error":"Unauthorized"} — без пояснения. Это НЕ наш текст: наши
-- функции отвечают «Unauthorized — service role only» или
-- «— service role or cron secret only». Голое «Unauthorized» —
-- ответ шлюза Supabase, то есть запрос до кода функции не доходит.
--
-- Перелом в 05:15 совпадает с тем, что в Vault был положен legacy
-- `service_role` (219 знаков, JWT) — ключ, ОТОЗВАННЫЙ 27.10. Шлюз
-- такой ключ отвергает сам.
--
-- ЭТО ПРОВЕРЯЕТСЯ ЧТЕНИЕМ, А НЕ ПАМЯТЬЮ. Запрос показывает длину и
-- первые три знака — этого хватит, чтобы отличить JWT (начинается
-- с `eyJ`, длина ~200+) от нашего пароля расписания (64 знака, hex).
-- Сам ключ в переписку не попадает.
--
-- КАК ЧИТАТЬ:
--   dlina 64,  nachalo НЕ 'eyJ'  → лежит пароль расписания. Тогда
--       причина 401 в другом — смотреть `Verify JWT` у функций
--   dlina ~219, nachalo 'eyJ'    → лежит отозванный служебный ключ.
--       Чинится прогоном sql/обслуживание/cron-kluch-obnovit-07nov.sql
--       (возвращает 64-знаковый пароль, тот же, что в секрете
--        CRON_SECRET у функций)

SELECT  'cron_secret в Vault'                   AS chto,
        length(public.cron_secret())            AS dlina,
        left(public.cron_secret(), 3)           AS pervye_tri,
        (left(public.cron_secret(), 3) = 'eyJ') AS pohozhe_na_jwt,
        (SELECT count(*) FROM cron.job WHERE active) AS zadaniy_aktivno;
