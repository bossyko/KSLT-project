SELECT table_name                                            AS таблица,
       count(*)                                              AS колонок,
       md5(string_agg(column_name, ',' ORDER BY column_name)) AS отпечаток
  FROM information_schema.columns
 WHERE table_schema = 'public'
 GROUP BY table_name
 ORDER BY table_name;

