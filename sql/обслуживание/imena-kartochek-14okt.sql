-- ============================================================
-- Шесть карточек: имя впереди фамилии
-- ============================================================
--
-- ПРАВИЛО: в карточке сначала имя, потом фамилия. Ты назвал его словами
-- «имя и фамилия идут», и дальше оно действует на все карточки.
--
-- Часть карточек заведена сегодня заливкой заявок на одиночный Futures
-- (sql/обслуживание/zayavki-odinochka-futures-14okt.sql) — имена там взяты
-- буква в букву из формы клуба, а клуб местами пишет фамилию вперёд.
--
-- ПОСЧИТАНО по 46 заявкам этого турнира: фамилия вперёд стоит у пяти
-- карточек плюс одна из трёх слов. Все шесть здесь, других в турнире нет.
--
--   kanybek-uulu-belek     «Каныбек уулу Белек»    → «Белек Каныбек уулу»
--   asankulov-timur        «Асанкулов Тимур»       → «Тимур Асанкулов»
--   isabekov-tsken         «Исабеков Тскен»        → «Искен Исабеков»
--   majnazarov-nursultan   «Майназаров Нурсултан»  → «Нурсултам Майназаров»
--   pogorelov-roman        «Погорелов Роман»       → «Роман Погарелов»
--   saliev-aziz            «Салиев Азиз»           → «Азиз Салиев»
--
-- Пять первых заведены сегодня, шестая (saliev-aziz) — старая карточка
-- клуба, у неё меняется только порядок слов.
--
-- Написание беру твоё, не формы: у троих меняется не только порядок слов,
-- но и буквы — Тскен→Искен, Нурсултан→Нурсултам, Погорелов→Погарелов.
-- У «Асанкулов Тимур» меняется только порядок, буквы прежние.
--
-- АДРЕС КАРТОЧКИ (id) НЕ ТРОГАЕМ. На players.id ссылаются двадцать внешних
-- ключей (sql/схема/schema-snapshot.sql:1006–1283), и НИ НА ОДНОМ нет
-- ON UPDATE CASCADE: переименование id не поехало бы по связям, а молча
-- упёрлось бы в отказ или оставило сирот. Адрес остаётся прежним, в
-- карточке и в списках человек виден под новым именем.
--
-- Условие на старое имя — чтобы повторный прогон не перебил имя, если ты
-- к тому времени поправишь его руками в админке.
--
-- КАК ЗАПУСКАТЬ: ничего не выделяй мышью, поставь курсор в текст и нажми
-- Ctrl+Enter. Ответ последнего запроса и есть проверка.

BEGIN;

UPDATE public.players p
   SET name       = д.было_стало,
       updated_at = now()
  FROM (VALUES
         ('kanybek-uulu-belek'::text,   'Каныбек уулу Белек'::text,   'Белек Каныбек уулу'::text),
         ('asankulov-timur'::text,      'Асанкулов Тимур'::text,      'Тимур Асанкулов'::text),
         ('isabekov-tsken'::text,       'Исабеков Тскен'::text,       'Искен Исабеков'::text),
         ('majnazarov-nursultan'::text, 'Майназаров Нурсултан'::text, 'Нурсултам Майназаров'::text),
         ('pogorelov-roman'::text,      'Погорелов Роман'::text,      'Роман Погарелов'::text),
         ('saliev-aziz'::text,          'Салиев Азиз'::text,          'Азиз Салиев'::text)
       ) AS д (id, было, было_стало)
 WHERE p.id   = д.id
   AND p.name = д.было;

COMMIT;


-- ---- ПРОВЕРКА ----------------------------------------------------
-- Ждём шесть строк с новыми именами и прежними адресами.

SELECT id, name, ntrp_singles, gender, category_id
  FROM public.players
 WHERE id IN ('kanybek-uulu-belek', 'asankulov-timur', 'isabekov-tsken',
              'majnazarov-nursultan', 'pogorelov-roman', 'saliev-aziz')
 ORDER BY id;
