-- ОДИН ЗАПРОС НА ФАЙЛ: редактор Supabase отдаёт только последнюю выдачу.
--
-- ЗАЧЕМ. Шаг 4 показал двенадцать ключей (`js/admin/sections/players.js:131`).
-- Экран очков переезжает с раундов на места — значит каждый ключ, который
-- РЕАЛЬНО встречается в истории, должен получить своё место. А мапится не
-- всякий:
--   W → 1, F → 2, 3RD → 3, 4TH → 4            — однозначно;
--   SF → 3-4, QF → 5-8, R16 → 9-16, R32 → 17-32 — место внутри вилки;
--   G3…G6 — «3-е…6-е в группе» (`js/admin/core/constants.js:910`), а место
--           в группе становится местом в турнире только вместе с размером
--           группы и плей-офф. Без этого соответствия НЕТ.
--
-- Поэтому сначала измеряем, какими ключами история записана на самом деле.
-- Если G5, G6 и R32 не встречаются ни разу — вилки нет и переезд простой.
-- Если встречаются — нужен разбор с сеткой, и это отдельный кусок.
--
-- `— пусто —` в выдаче — это те самые строки без этапа (замер, шаг 10б).

SELECT coalesce(nullif(и.round_reached, ''), '— пусто —') AS раунд,
       count(*)                                           AS строк,
       count(DISTINCT и.tournament_id)                    AS турниров,
       count(*) FILTER (WHERE и.points_earned = 0)        AS нулевых,
       min(и.points_earned)                               AS от,
       max(и.points_earned)                               AS до
  FROM public.tournament_results и
 GROUP BY coalesce(nullif(и.round_reached, ''), '— пусто —')
 ORDER BY count(*) DESC;
