-- ============================================================
-- Карточка Мурата Норузбаева — ПРАВКА имени и пола
-- ============================================================
--
-- Найдено при сверке заявок MASTERS 09.10: единственная из 48 карточек
-- турнира, у которой ПОЛ ПУСТОЙ, а имя записано латиницей.
--
--   id                 murat-noruzbaev-2
--   name               Murat Noruzbaev   -> Мурат Норузбаев
--   gender             null              -> men
--   category_id        null              -> masters (слово Кости 07.10)
--
-- Адрес карточки (id) не меняется: он и есть ссылка на человека, на нём
-- висят заявки и матчи. Суффикс -2 остаётся как есть.
--
-- Имя пишется в том же порядке, что у остальных карточек базы:
-- «Имя Фамилия», как «Денис Ли» и «Эсен Азимов».
--
-- Разряд нужен не для порядка, а чтобы человека было ВИДНО: рейтинг
-- показывает строку, если разряд совпал ИЛИ очков больше нуля
-- (`KSLT_RULES.рейтингКатегории`, js/kslt-rules.js:892). Без разряда
-- Норузбаев появился бы в рейтинге только после первых очков.
--
-- Запускать можно повторно: UPDATE ставит те же значения.

BEGIN;

UPDATE public.players
   SET name = 'Мурат Норузбаев',
       gender = 'men',
       category_id = 'masters'
 WHERE id = 'murat-noruzbaev-2';

COMMIT;
