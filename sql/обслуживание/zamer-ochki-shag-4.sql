-- Редактор Supabase показывает выдачу ТОЛЬКО ПОСЛЕДНЕГО запроса — замерено
-- дважды: из файла в четырнадцать шагов пришёл шаг 10в (последний), из файла
-- в два шага пришёл снова шаг 10в (последний). Шаг 4 оба раза пропал.
-- Я написал в том файле «здесь ровно два запроса» вместо того, чтобы убрать
-- второй: ШАГ, КОТОРЫЙ МОЖНО УБРАТЬ, УБИРАЕТСЯ, А НЕ ОПИСЫВАЕТСЯ В ПАМЯТКЕ.
--
-- ЗАЧЕМ. Экран «Рейтинговые очки» в админке правит `points_rules` — очки по
-- РАУНДАМ (`js/settings.js:309`). Начисление читает `points_by_place` — очки
-- по МЕСТАМ (`js/bracket.js:2328`). Два определения одного понятия. Прежде
-- чем переносить экран на места, надо знать, что именно потеряется.
-- Читателя `points_rules` я нашёл один: `js/players.js:142` — ручной ввод
-- прошлых результатов.
--
-- Если выдача пуста — таблицы нет или она пуста, и тогда переезд экрана
-- ничего не теряет вовсе.

SELECT coalesce(у.name, '— без уровня —') AS уровень,
       count(п.id)                        AS строк,
       string_agg(п.round || '=' || п.points, ', ' ORDER BY п.points DESC) AS содержимое
  FROM public.points_rules п
  LEFT JOIN public.tournament_levels у ON у.id = п.level_id
 GROUP BY у.name
 ORDER BY (у.name IS NULL) DESC, у.name;
