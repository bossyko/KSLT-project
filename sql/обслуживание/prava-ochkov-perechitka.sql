-- ============================================================
-- ЧИТАЕТ, НЕ МЕНЯЕТ. ОДИН ЗАПРОС НА ФАЙЛ.
--
-- Слово Кости 02.10: «изменить очки может только администратор, не
-- менеджер». Замер шага 6 нашёл обратное: писать могли оба, и у
-- `points_rules` три пишущие политики НАЗВАНЫ `..._admin_...`, а внутри
-- стоит `role = ANY (ARRAY['admin','manager'])`.
-- ИМЯ ПОЛИТИКИ ВРЁТ — читаем тело, а не название.
--
-- ЖДЁМ после миграции версий:
--   points_by_place · чтение true · запись только is_admin()
--   points_versions · чтение true · запись только is_admin()
--   points_rules    · ПИШЕТ ЕЩЁ И МЕНЕДЖЕР — это ОТКРЫТАЯ беда: миграция
--                     версий её не касалась, а ручной ввод прошлых
--                     результатов эту таблицу читает.

SELECT tablename              AS таблица,
       policyname             AS политика,
       cmd                    AS на_что,
       coalesce(qual, '—')       AS кому_видно,
       coalesce(with_check, '—') AS кому_писать
  FROM pg_policies
 WHERE schemaname = 'public'
   AND tablename IN ('points_by_place', 'points_versions', 'points_rules')
 ORDER BY tablename, cmd, policyname;
