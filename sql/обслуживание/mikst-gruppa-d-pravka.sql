-- ============================================================
-- Микст FUTURES, группа D: лишний матч и разъехавшийся состав — ПРАВКА
-- ============================================================
--
-- Что случилось. Замена человека в заявке переписывала матчи по всему
-- турниру: «где стоит прежний — поставить нового». Новый уже играл в этой
-- же группе, и его имя попало в чужой матч. В итоге:
--
--   • матч №6 по заявкам — Нурсултан/Аажара против Айгерим/Евгений, а в
--     игроках у него стоял Алымбек. Для таблицы это вторая встреча
--     Алымбек — Нурсултан, и она шла в зачёт наравне с настоящей (№2);
--   • клетка Айгерим — Нурсултан осталась пустой, счёт вписали заново, и
--     завёлся матч №7 — уже без ссылок на заявки.
--
-- Приводим группу к шести встречам: матчу №6 возвращаем состав из его
-- заявок и последний введённый счёт, лишнюю запись №7 убираем.
--
-- Счёт берём последний, как решил Costa: Нурсултан выиграл 6:5 на
-- тай-брейке 7-5. В матче №6 Нурсултан стоит первым, поэтому счёт
-- записываем с его стороны.
--
-- Сама причина исправлена в админке: замена теперь правит только матчи
-- своей заявки.
--
-- Запускать можно повторно.

BEGIN;

-- Матч №6: состав из заявок, счёт последний
UPDATE public.matches m
   SET player1_id = r1.player_id,
       player2_id = r2.player_id,
       score      = '6/5(7-5)',
       winner_id  = r1.player_id
  FROM public.tournament_registrations r1,
       public.tournament_registrations r2
 WHERE m.tournament_id = 'c0a30bae-30ee-4a38-a26a-4c6b339bd695'
   AND m.group_number  = 4
   AND m.match_order   = 6
   AND r1.id = m.reg1_id
   AND r2.id = m.reg2_id;

-- Матч №7: та же встреча, заведённая руками поверх испорченной клетки
DELETE FROM public.matches
 WHERE tournament_id = 'c0a30bae-30ee-4a38-a26a-4c6b339bd695'
   AND group_number  = 4
   AND match_order   = 7;

COMMIT;
