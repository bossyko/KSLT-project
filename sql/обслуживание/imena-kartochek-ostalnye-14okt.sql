-- ============================================================
-- Ещё десять карточек: имя впереди фамилии
-- ============================================================
--
-- Продолжение `imena-kartochek-14okt.sql`, где то же правило применено к
-- шести карточкам турнира Futures. Правило твоё: «имя и фамилия идут» —
-- в карточке сначала имя, потом фамилия.
--
-- ПОСЧИТАНО по всем 493 карточкам базы: первое слово похоже на фамилию
-- (-ов, -ев, -ин, -ова, -ева…), а второе — нет, у четырнадцати. Шесть уже
-- поправлены прошлым запросом, одна (saliev-aziz) была среди них. Из
-- оставшихся прибор ВРЁТ на трёх — там имя само кончается как фамилия:
--
--   konstantin-han   «Константин Хан»  — порядок уже верный
--   ramina-ushur     «Рамина Ушур»     — Ушур фамилия (ср. rustam-ushur)
--   yan-skazka       «Ян Сказка»       — не разберу, не трогаю
--
-- Эти три НЕ правим. Остаются десять:
--
--   almanbetova-zhamilya   «Алманбетова Жамиля»   → «Жамиля Алманбетова»
--   asankulova-kamsariyat  «Асанкулова Камсарият» → «Камсарият Асанкулова»
--   baitikov-adel          «Баитиков Адел»        → «Адел Баитиков»
--   dajyrbekova-altynaj    «Дайырбекова Алтынай»  → «Алтынай Дайырбекова»
--   derbishaliev-arzymat   «Дербишалиев Арзымат»  → «Арзымат Дербишалиев»
--   kapalova-perizat       «Капалова Перизат»     → «Перизат Капалова»
--   kudaybergenov-askar    «Кудайбергенов Аскар»  → «Аскар Кудайбергенов»
--   mashirova-bermet       «Маширова Бермет»      → «Бермет Маширова»
--   minina-natalya         «Минина Наталья»       → «Наталья Минина»
--   shamurzaeva-ajdaj      «Шамурзаева Айдай»     → «Айдай Шамурзаева»
--
-- Переставляю ТОЛЬКО порядок слов, буквы не трогаю: людей знаешь ты, и
-- где написание неверное — скажешь отдельно.
--
-- АДРЕС КАРТОЧКИ (id) НЕ ТРОГАЕМ, по той же причине: на players.id висят
-- двадцать внешних ключей (sql/схема/schema-snapshot.sql:1006–1283), и ни
-- на одном нет ON UPDATE CASCADE.
--
-- Условие на старое имя — чтобы повторный прогон не перебил имя, если ты
-- к тому времени поправишь его руками в админке.
--
-- КАК ЗАПУСКАТЬ: ничего не выделяй мышью, поставь курсор в текст и нажми
-- Ctrl+Enter. Ответ последнего запроса и есть проверка.

BEGIN;

UPDATE public.players p
   SET name       = д.стало,
       updated_at = now()
  FROM (VALUES
         ('almanbetova-zhamilya'::text,  'Алманбетова Жамиля'::text,   'Жамиля Алманбетова'::text),
         ('asankulova-kamsariyat'::text, 'Асанкулова Камсарият'::text, 'Камсарият Асанкулова'::text),
         ('baitikov-adel'::text,         'Баитиков Адел'::text,        'Адел Баитиков'::text),
         ('dajyrbekova-altynaj'::text,   'Дайырбекова Алтынай'::text,  'Алтынай Дайырбекова'::text),
         ('derbishaliev-arzymat'::text,  'Дербишалиев Арзымат'::text,  'Арзымат Дербишалиев'::text),
         ('kapalova-perizat'::text,      'Капалова Перизат'::text,     'Перизат Капалова'::text),
         ('kudaybergenov-askar'::text,   'Кудайбергенов Аскар'::text,  'Аскар Кудайбергенов'::text),
         ('mashirova-bermet'::text,      'Маширова Бермет'::text,      'Бермет Маширова'::text),
         ('minina-natalya'::text,        'Минина Наталья'::text,       'Наталья Минина'::text),
         ('shamurzaeva-ajdaj'::text,     'Шамурзаева Айдай'::text,     'Айдай Шамурзаева'::text)
       ) AS д (id, было, стало)
 WHERE p.id   = д.id
   AND p.name = д.было;

COMMIT;


-- ---- ПРОВЕРКА 1 --------------------------------------------------
-- Ждём десять строк с новыми именами.

SELECT id, name, gender
  FROM public.players
 WHERE id IN ('almanbetova-zhamilya', 'asankulova-kamsariyat', 'baitikov-adel',
              'dajyrbekova-altynaj', 'derbishaliev-arzymat', 'kapalova-perizat',
              'kudaybergenov-askar', 'mashirova-bermet', 'minina-natalya',
              'shamurzaeva-ajdaj')
 ORDER BY name;


-- ---- ПРОВЕРКА 2: СТОРОЖ ------------------------------------------
-- Тот же прибор, что считал, — по всей базе заново. Ждём ровно три
-- строки: Константин Хан, Рамина Ушур, Ян Сказка. Всё, что появится
-- сверх них, — новая карточка, записанная фамилией вперёд.

SELECT id, name
  FROM public.players
 WHERE name ~ '^\S+\s+\S+$'
   AND split_part(name, ' ', 1) ~* '(ов|ев|ёв|ин|ын|ский|цкий|енко|ко|ук|юк|ян|ова|ева|ина)$'
   AND split_part(name, ' ', 2) !~* '(ов|ев|ёв|ин|ын|ский|цкий|енко|ко|ук|юк|ян|ова|ева|ина)$'
 ORDER BY name;
