-- ============================================================
-- Снять флаги членства: до конца года все на бесплатном периоде
-- ============================================================
--
-- В настройках стоит free_access_until = 2026-12-31. Пока дата не прошла,
-- заявки принимаются без проверки членства и оплаты, а рейтинг показывает
-- членами всех подряд. Флаг is_member в это время не значит ничего.
--
-- А стоял он у двоих: у Татьяны Нечаевой с марта и у Евгения Горских с
-- сегодняшнего дня. Двое помеченных среди четырёх сотен — это не правило, а
-- след от ручных правок. Снимаем: пусть все будут в равном положении, а
-- членство начнём отмечать с января, когда пойдут оплаты.
--
-- Карточки, категории и очки не трогаем — уходит только флаг.
--
-- Запускать можно повторно.

BEGIN;

UPDATE public.players
   SET is_member = false
 WHERE is_member;

COMMIT;

-- ---- Проверка ----

SELECT count(*) FILTER (WHERE is_member)  AS с_флагом_членства,
       count(*) FILTER (WHERE is_guest)   AS гостей,
       count(*)                           AS всего_карточек
  FROM public.players;
-- Ожидаем: с флагом членства 0.
