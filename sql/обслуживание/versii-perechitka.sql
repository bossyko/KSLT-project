--
-- «Success. No rows returned» ничего не доказывает: миграция кончается
-- `COMMIT;` и по устройству молчит. РЕЗУЛЬТАТ ПРОВЕРЯЕТСЯ ЧТЕНИЕМ БАЗЫ.
--
-- ЖДЁМ ровно одну строку:
--   версия 2021-01-01 · за_победу 25 · за_участие 10
--   строк_мест 320 · уровней 5 · строк_без_версии 0
--
-- 320 — замер шага 2: по 64 места у всех пяти уровней. Строки за пределом
-- итогового в базе лежат и к версии привязаны тоже: предел прячет их на
-- чтении, а не удаляет.
-- Если строк_без_версии не ноль — часть таблицы осталась вне версий, и
-- начисление по ней считать не станет.

SELECT в.effective_from AS версия,
       в.per_win        AS за_победу,
       в.per_entry      AS за_участие,
       count(п.id)                  AS строк_мест,
       count(DISTINCT п.level_id)   AS уровней,
       (SELECT count(*) FROM public.points_by_place WHERE version_id IS NULL)
                                    AS строк_без_версии
  FROM public.points_versions в
  LEFT JOIN public.points_by_place п ON п.version_id = в.id
 GROUP BY в.effective_from, в.per_win, в.per_entry
 ORDER BY в.effective_from;
