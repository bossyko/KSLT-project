-- СТОРОЖ ИМЁН, РАСШИРЕННЫЙ НА ТРИ СЛОВА. ТОЛЬКО ЧТЕНИЕ.
--
-- ЗАЧЕМ. Сторож 14.10
-- (`sql/обслуживание/imena-kartochek-ostalnye-14okt.sql`, ПРОВЕРКА 2)
-- требует РОВНО два слова: `name ~ '^\S+\s+\S+$'`. Карточку из трёх слов
-- он не видит вовсе — и 04.11 это доказано на живом примере:
-- `abakirov-ermek-kurmanbekovich` = «Абакиров Эрмек Курманбекович»,
-- фамилия впереди, а сторож молчал и возвращал свои «ровно три строки».
-- ПРИБОР, КОТОРЫЙ СЧИТАЕТ ДВА СЛОВА, НЕ СЧИТАЕТ ТРЁХ.
--
-- Здесь признак тот же, но берётся ПЕРВОЕ слово против ПОСЛЕДНЕГО, и
-- число слов не ограничено. Отчество учтено отдельно: `-ович/-евич/
-- -овна/-евна` — не фамилия, и слово с таким окончанием в середине
-- строку не оправдывает.
--
--   ЖДЁМ: три известные строки (Константин Хан, Рамина Ушур, Ян Сказка)
--   плюс то, что сторож 14.10 не умел видеть. Всё сверх — разобрать.

WITH разбор AS (
    SELECT p.id, p.name, p.gender,
           regexp_split_to_array(btrim(regexp_replace(p.name, '\s+', ' ', 'g')), ' ') AS слова
      FROM public.players p
     WHERE btrim(coalesce(p.name, '')) <> ''
),
края AS (
    SELECT id, name, gender, слова,
           array_length(слова, 1)          AS slov,
           слова[1]                        AS pervoe,
           слова[array_length(слова, 1)]   AS poslednee
      FROM разбор
)
SELECT id, name, gender, slov, pervoe, poslednee
  FROM края
 WHERE slov >= 2
   AND pervoe    ~* '(ов|ев|ёв|ин|ын|ский|цкий|енко|ко|ук|юк|ян|ова|ева|ина)$'
   AND pervoe    !~* '(ович|евич|овна|евна)$'
   AND poslednee !~* '(ов|ев|ёв|ин|ын|ский|цкий|енко|ко|ук|юк|ян|ова|ева|ина)$'
 ORDER BY slov DESC, name;
