-- ОДИН ЗАПРОС. ТОЛЬКО ЧИТАЕТ. Отдай мне вывод целиком.
--
-- ТРОЕ ИЗ ФОРМЫ НАПИСАНЫ ЛАТИНИЦЕЙ, И ПЕРВЫЙ ПРИБОР ПРО НИХ ПРОМОЛЧАЛ:
-- `Barno Tursunova`, `Allayar Nasirov`, `K.u.Azat`. Латинское `azat` и
-- русское `азат` для машины не совпадают НИ ОДНОЙ буквой — правило
-- 04.11: ПРИБОР, ИЩУЩИЙ В ОДНОМ АЛФАВИТЕ, НЕ НАХОДИТ В ДРУГОМ, и его
-- молчание ничего не доказывает.
--
-- Поэтому ищем ПО-РУССКИ, по частям имени. `K.u.` — это, по опыту
-- 04.11, «Кубанычбек уулу»: тогда так нашёлся `azat-kubanychbek-uulu`.
-- Барно Турсунова заявлялась 04.11 в женских парах — карточка должна
-- быть.

WITH искомое(из_формы, часть) AS (VALUES
  ('Barno Tursunova', 'барно'),
  ('Barno Tursunova', 'турсунов'),
  ('Allayar Nasirov', 'аллаяр'),
  ('Allayar Nasirov', 'алаяр'),
  ('Allayar Nasirov', 'насиров'),
  ('K.u.Azat',        'азат'),
  ('K.u.Azat',        'кубанычбек')
)
SELECT  и.из_формы,
        и.часть,
        p.id      AS kartochka,
        p.name,
        p.gender  AS pol,
        /* СТОЛБЕЦ ЗОВЁТСЯ `category_id`, А НЕ `category` — сверено со
           снимком схемы `sql/схема/schema-snapshot.sql`. Я выдумал имя
           второй раз за день, хотя снимок лежит в репозитории: имя
           столбца — такое же число, которое нельзя называть, не померив. */
        p.category_id,
        p.is_guest,
        p.is_member,
        p.points
  FROM  искомое и
  LEFT JOIN players p
         ON lower(translate(p.name,'ёЁ','ее')) LIKE '%' || и.часть || '%'
 ORDER BY и.из_формы, и.часть, p.name;
