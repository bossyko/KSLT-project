-- ============================================================
-- Futures: чиним третий матч в группах B и C
-- ============================================================
--
-- В обеих группах третья встреча круга заведена не с той парой: вместо
-- сеяного в ней стоит соперник, который уже отыграл свои два матча.
-- Получилось, что одна пара встречается дважды, а другой встречи нет —
-- и счёт для неё некуда вписать: в таблице стоит глухой прочерк.
--
--   Группа B, круг 3, посев 2 — сейчас Шавкат — Азат, должно Эрбол — Азат
--   Группа C, круг 3, посев 3 — сейчас Бексултан — Салман, должно Алымбек — Салман
--
-- Что здесь важно: посев в этих записях уже правильный (2 и 3), то есть
-- это и есть третьи матчи круга — ошибочно записан только первый игрок.
-- Поэтому меняем его в тех же записях, а не удаляем и создаём заново:
-- сохраняются номер матча, круг, корт и время, если их успели проставить.
--
-- Сыгранные матчи и счета не затрагиваются: правим только записи без счёта.
--
-- Перед запуском и после — futures-gruppy-bc-proverka.sql.
--
-- Запускать можно повторно: условия проверяют нынешнее состояние, второй
-- раз ничего не изменится.

BEGIN;

-- ---- Группа B: третий матч играет Эрбол Кылычев, а не Шавкат ----

UPDATE public.matches
   SET player1_id = 'erbol-kylychev'
 WHERE id = 'b8e6a748-887f-4b3d-8d40-e063f587733c'
   AND tournament_id = '7094e2bd-02e6-476b-9e0c-efc7bffc8418'
   AND group_number = 2
   AND player1_id = 'shavkat-mihmanov'
   AND player2_id = 'azat-bazarkulov'
   AND score IS NULL;

-- ---- Группа C: третий матч играет Алымбек Ороков, а не Бексултан ----

UPDATE public.matches
   SET player1_id = 'alymbek-orokov'
 WHERE id = 'c50c761f-07f0-4985-b2f7-aeb0749cf2af'
   AND tournament_id = '7094e2bd-02e6-476b-9e0c-efc7bffc8418'
   AND group_number = 3
   AND player1_id = 'beksultan-rustamov'
   AND player2_id = 'salman-beyshenaliev'
   AND score IS NULL;

COMMIT;

-- ---- Проверка ----

SELECT CASE m.group_number WHEN 2 THEN 'B' WHEN 3 THEN 'C' END AS группа,
       m.round_number AS круг,
       p1.name        AS первый,
       p2.name        AS второй,
       m.status       AS состояние,
       COALESCE(m.score, '—') AS счёт
  FROM public.matches m
  LEFT JOIN public.players p1 ON p1.id = m.player1_id
  LEFT JOIN public.players p2 ON p2.id = m.player2_id
 WHERE m.tournament_id = '7094e2bd-02e6-476b-9e0c-efc7bffc8418'
   AND m.group_number IN (2, 3)
 ORDER BY m.group_number, m.match_order;

-- Ожидаем:
--   B: Азат — Шавкат (6/0), Эрбол — Шавкат (6/0), Эрбол — Азат (пусто)
--   C: Салман — Бексултан (6/1), Алымбек — Бексултан (6/0), Алымбек — Салман (пусто)
--
-- Сыгранных матчей по-прежнему 11 — счета на месте.
-- В таблице групп клетки этих встреч станут нажимаемыми, а места
-- пересчитаются, как только впишете счёт.
