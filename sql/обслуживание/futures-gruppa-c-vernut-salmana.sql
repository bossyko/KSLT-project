-- ============================================================
-- Futures, группа C: в матче 6:2 вторым должен быть Салман
-- ============================================================
--
-- Сейчас в группе три записи, но только на две пары: «Алымбек — Бексултан»
-- значится дважды (6:0 и 6:2), а встречи «Алымбек — Салман» нет вовсе.
--
-- По игре: Алымбек выиграл у Салмана 6:2 — это и есть третья запись.
-- В ней ошибочно стоит Бексултан. Возвращаем Салмана.
--
-- Счёт и победитель не трогаем: Алымбек выиграл, счёт 6:2 записан от него.
-- Соперник меняется с Бексултана на Салмана — это и есть вся правка.
--
-- Условия в WHERE проверяют нынешнее состояние: если запись уже поправлена
-- или изменилась, ничего не произойдёт. Запускать можно повторно.

BEGIN;

UPDATE public.matches
   SET player2_id = 'salman-beyshenaliev'
 WHERE id = 'a5b61d9b-54a5-46b0-b8ea-e8cd75631fa4'
   AND tournament_id = '7094e2bd-02e6-476b-9e0c-efc7bffc8418'
   AND group_number = 3
   AND player1_id = 'alymbek-orokov'
   AND player2_id = 'beksultan-rustamov'
   AND score = '6/2';

COMMIT;

-- ---- Проверка ----

SELECT m.match_order AS номер,
       p1.name       AS первый,
       p2.name       AS второй,
       m.score       AS счёт,
       pw.name       AS победитель
  FROM public.matches m
  LEFT JOIN public.players p1 ON p1.id = m.player1_id
  LEFT JOIN public.players p2 ON p2.id = m.player2_id
  LEFT JOIN public.players pw ON pw.id = m.winner_id
 WHERE m.tournament_id = '7094e2bd-02e6-476b-9e0c-efc7bffc8418'
   AND m.group_number = 3
 ORDER BY m.match_order;

-- Ожидаем три разные пары:
--   Салман — Бексултан   1/6
