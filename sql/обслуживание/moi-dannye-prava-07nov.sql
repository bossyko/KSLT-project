--
-- ПОВОД. Проверка после прогона показала `mozhet_gost = true`: роль
-- `anon` могла выполнять `public.мои_данные()`. Функция и так упала бы
-- на первой строке — без входа `auth.uid()` пуст, и она бросает
-- исключение, — но ПРАВО, КОТОРОЕ НЕ НУЖНО, НЕ ДОЛЖНО СУЩЕСТВОВАТЬ:
-- защита должна стоять на правах, а не на том, что внутри функции
-- есть ещё одна проверка. Два замка лучше одного, и внешний дешевле.
--
-- ПОЧЕМУ `REVOKE FROM public` НЕ ХВАТИЛО. Право у `anon` выдано ему
-- САМОМУ (Supabase раздаёт его ролям при создании функции), а отзыв у
-- PUBLIC чужих личных прав не трогает. Отзывать надо поимённо.

REVOKE EXECUTE ON FUNCTION public.мои_данные() FROM anon;

-- ПРОВЕРКА ЧТЕНИЕМ: вошедший может, гость — нет.
SELECT  has_function_privilege('authenticated', 'public.мои_данные()', 'EXECUTE') AS mozhet_voshedshiy,
        has_function_privilege('anon',          'public.мои_данные()', 'EXECUTE') AS mozhet_gost;

-- ЖДЁМ: true, false
