-- ============================================================
-- Микст FUTURES: что осталось после снятия плей-оффа — ПРОВЕРКА
-- ============================================================
--
-- Только читает. Групповых матчей должно остаться 36 (шесть групп по
-- шесть встреч), все сыгранные. Матчей вне групп — ноль: сетка и доп.
-- матчи сняты.

SELECT CASE WHEN group_number IS NULL THEN 'вне групп (сетка и доп. матчи)'
            ELSE 'группа ' || group_number END          AS где,
       count(*)                                         AS матчей,
       count(*) FILTER (WHERE status = 'completed')      AS сыграно
  FROM public.matches
 WHERE tournament_id = 'c0a30bae-30ee-4a38-a26a-4c6b339bd695'
 GROUP BY 1
 ORDER BY 1;
