-- Ключ имени: регистр не важен, ё сводится к е, знаки и лишние пробелы
-- выброшены, слова отсортированы. Поэтому «Джумабаев Азамат» и
-- «Азамат Джумабаев» дают ОДИН ключ — порядок слов в форме гуляет.
форма_к AS (
  SELECT ф.*, (SELECT string_agg(w, ' ' ORDER BY w)
            FROM unnest(string_to_array(
                   regexp_replace(lower(translate(ф.фио, 'ёЁ', 'ее')),
                                  '[^[:alnum:]]+', ' ', 'g'), ' ')) AS t(w)
           WHERE w <> '') AS ключ FROM форма ф
),
игроки_к AS (
  SELECT p.id, p.name, p.gender, p.category_id,
         p.ntrp_singles, p.ntrp_doubles,
         (SELECT string_agg(w, ' ' ORDER BY w)
            FROM unnest(string_to_array(
                   regexp_replace(lower(translate(p.name, 'ёЁ', 'ее')),
                                  '[^[:alnum:]]+', ' ', 'g'), ' ')) AS t(w)
           WHERE w <> '') AS ключ
    FROM players p
)
-- 8. ПОЛ: турнир мужской, значит обе карточки пары должны быть men.
--    Женская карточка в мужской паре — ошибка сверки, а не данных.
--    Ждём ПУСТО.
SELECT ф.блок, ф.ном, ф.роль, ф.фио, и.id, и.gender AS пол
  FROM форма_к ф
  JOIN игроки_к и ON и.ключ = ф.ключ
 WHERE и.gender IS DISTINCT FROM 'men'
 ORDER BY ф.блок DESC, ф.ном;
