-- 1. ТУРНИР: куда класть. id у турниров текстовый — его надо увидеть
--    глазами, а не угадать по названию. Турнир один, но мужских
--    парных в базе может быть несколько — выбираем нужный по дате.
SELECT t.id, t.title,
       t.category_id       AS разряд,
       t.format            AS формат,
       t.gender            AS пол,
       t.status            AS состояние,
       t.date_start::text  AS начало,
       t.max_participants  AS мест,
       t.reserved_spots    AS бронь,
       t.draw_size         AS сетка,
       t.bracket_type      AS вид_сетки,
       t.ntrp_combined_max::text AS сумма_ntrp_макс
  FROM tournaments t
 WHERE t.format IN ('doubles', 'mixed_doubles')
 ORDER BY t.date_start DESC NULLS LAST
 LIMIT 20;


-- 2. ЧТО В ПАРНЫХ УЖЕ ЛЕЖИТ. Не ноль — заливка их молча не трёт,
--    решаем вместе.
SELECT t.id, t.title, r.status AS состояние, count(*) AS заявок
  FROM tournament_registrations r
  JOIN tournaments t ON t.id = r.tournament_id
 WHERE t.format IN ('doubles', 'mixed_doubles')
 GROUP BY 1, 2, 3
 ORDER BY 2, 3;


