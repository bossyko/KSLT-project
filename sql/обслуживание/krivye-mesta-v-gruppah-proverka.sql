-- ============================================================
-- Ручные места в группах — ПРОВЕРКА
-- ============================================================
--
-- Только читает. Показывает каждую раскладку ручных мест: сколько в ней
-- записей, сколько разных мест и какое место наибольшее.
--
-- Здоровая раскладка: разных мест столько же, сколько записей, и
-- наибольшее место не больше числа участников. Иначе это след старой
-- ошибки в обмене местами — лечится файлом
-- krivye-mesta-v-gruppah-pravka.sql

SELECT t.title                  AS турнир,
       г.ключ                   AS группа,
       г.раскладка,
       count(*)                 AS записей,
       count(DISTINCT м.место)  AS разных_мест,
       max(м.место)             AS наибольшее,
       CASE WHEN count(DISTINCT м.место) < count(*) OR max(м.место) > count(*)
            THEN 'кривая' ELSE 'в порядке' END AS состояние
  FROM public.tournaments t
 CROSS JOIN LATERAL jsonb_each(COALESCE(t.manual_group_places, '{}'::jsonb)) AS г(ключ, раскладка)
 CROSS JOIN LATERAL jsonb_each_text(г.раскладка) AS з(игрок, место_текст)
 CROSS JOIN LATERAL (SELECT з.место_текст::int AS место) AS м
 GROUP BY t.title, г.ключ, г.раскладка
 ORDER BY состояние, t.title, г.ключ;
