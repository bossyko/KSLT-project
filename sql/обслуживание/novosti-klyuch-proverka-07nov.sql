-- ПОРЯДОК: сначала развернуть обе функции в панели Edge Functions,
-- потом этот запрос. До деплоя он покажет прежние 401 — и это не
-- новость, а прошлое.
--
-- РЕЗУЛЬТАТ ЗАПРОСА ПРОВЕРЯЕТСЯ ЧТЕНИЕМ БАЗЫ, А НЕ ОТВЕТОМ «SUCCESS»:
-- журнал заданий ставит «успешно» сразу, потому что `net.http_post`
-- асинхронный. Настоящий ответ лежит только здесь.
--
-- АДРЕСА В ТАБЛИЦЕ ОТВЕТОВ НЕТ (замерено составом столбцов 07.11),
-- поэтому функция узнаётся по телу ответа и заголовкам.
--
-- КАК ЧИТАТЬ:
--   нет строк за время после деплоя  → ночной вызов ещё не наступал;
--       либо подождать расписания, либо позвать вручную (ниже, но это
--       ЗАПИСЬ в базу — новости добавятся; без твоего слова не зову)
--   401 «Unauthorized — service role or cron secret only»
--                                    → деплой не доехал: в панели лежит
--       прежний код. Сверить, что вставлено целиком из файла на Маке
--   200                              → ключ принят, беда закрыта

SELECT  r.created                                  AS kogda,
        r.status_code,
        left(coalesce(r.content, ''), 300)         AS telo_otveta,
        left(coalesce(r.error_msg, ''), 150)       AS oshibka,
        r.headers ->> 'sb-request-id'              AS nomer_zaprosa,
        r.timed_out
FROM    net._http_response r
WHERE   r.created > now() - interval '24 hours'
ORDER BY r.created DESC
LIMIT   30;

