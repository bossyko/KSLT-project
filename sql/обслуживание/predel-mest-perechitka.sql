-- последнюю выдачу.
--
-- «Success. No rows returned» НИЧЕГО НЕ ДОКАЗЫВАЕТ. Миграция
-- `sql/схема/predel-mest-urovnya.sql` кончается `COMMIT;` и ничего не
-- возвращает по устройству — такой ответ приходит и когда всё легло верно, и
-- когда `ADD COLUMN IF NOT EXISTS` промолчал о том, что колонка уже была с
-- другим значением. РЕЗУЛЬТАТ ЗАПРОСА ПРОВЕРЯЕТСЯ ЧТЕНИЕМ БАЗЫ.
--
-- ЖДЁМ по боевой:
--   · четыре категории — max_place 64, платятся 64, за пределом 0;
--   · итоговый турнир — max_place 8, платятся 8, за пределом 56,
--     и ОЧКОВ ЗА ПРЕДЕЛОМ 179.
--
-- 179 — ПОСЧИТАНО из колонки «Четвёртая» мест 9–34
-- (`sql/схема/kategorii-i-ochki.sql:109–134`) и затем получено прогоном на
-- черновой базе с теми же числами. Если боевая даст другое — значит числа
-- правили после наполнения, и это НАХОДКА, а не сбой запроса.
--
-- В тестовой число за пределом может быть своим: её наполняли
-- `testovaya-odnim-zahodom.sql`, а не тем же файлом, что боевую. Там важны
-- только max_place и «платятся».

SELECT у.sort_order                                       AS порядок,
       у.name                                             AS уровень,
       у.on_ladder                                        AS на_лестнице,
       у.max_place                                        AS предел,
       count(п.place)                                      AS строк_всего,
       count(п.place) FILTER (WHERE п.place <= у.max_place) AS платятся,
       count(п.place) FILTER (WHERE п.place >  у.max_place) AS за_пределом,
       sum(п.points)  FILTER (WHERE п.place >  у.max_place) AS очков_за_пределом
  FROM public.tournament_levels у
  LEFT JOIN public.points_by_place п ON п.level_id = у.id
 GROUP BY у.sort_order, у.name, у.on_ladder, у.max_place
 ORDER BY у.sort_order DESC;
