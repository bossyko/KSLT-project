-- ============================================
-- Кэширование картинок в хранилище
-- Запустить в Supabase SQL Editor целиком.
-- ============================================
--
-- Картинки новостей отдавались с заголовком «cache-control: no-cache» —
-- браузеру запрещено их запоминать. При каждом открытии страницы новостей
-- все фотографии скачивались заново: восемь картинок, около двух мегабайт
-- за просмотр, и столько же при каждом возврате.
--
-- Отсюда перерасход: 80 МБ файлов в хранилище против 27 ГБ отданного
-- трафика при бесплатном лимите в 5 ГБ. Файлы качались по кругу.
--
-- Заголовок берётся из метаданных объекта, поэтому перезаливать ничего не
-- нужно — достаточно поправить значение.

-- --- Что сейчас ---------------------------------------------------------
SELECT bucket_id,
       metadata->>'cacheControl' AS срок_кэша,
       count(*) AS файлов,
       pg_size_pretty(sum((metadata->>'size')::bigint)) AS объём
FROM storage.objects
GROUP BY bucket_id, metadata->>'cacheControl'
ORDER BY bucket_id;

-- --- Новости ------------------------------------------------------------
-- Имена файлов случайные и никогда не переиспользуются: по одному адресу
-- всегда лежит одна и та же картинка. Значит кэшировать можно надолго —
-- год. Меняется картинка — меняется и адрес.

UPDATE storage.objects
SET metadata = jsonb_set(metadata, '{cacheControl}', '"max-age=31536000, immutable"')
WHERE bucket_id = 'news';

-- --- Аватары ------------------------------------------------------------
-- Здесь осторожнее: аватар лежит по адресу avatars/<id>.jpg, и при смене
-- фотографии адрес остаётся прежним. С годовым кэшем человек менял бы
-- аватар и продолжал видеть старый. Даём сутки — этого хватает, чтобы снять
-- нагрузку, и обновление доходит за разумное время.
--
-- Новые загрузки получают имя со случайной частью (js/dashboard.js,
-- mobile/www/js/screens/profile.js), так что со временем и они перейдут
-- на длинный кэш.

UPDATE storage.objects
SET metadata = jsonb_set(metadata, '{cacheControl}', '"max-age=86400"')
WHERE bucket_id = 'avatars';

-- --- Остальные бакеты ---------------------------------------------------
-- Логотипы спонсоров, фотографии кортов и тренеров меняются редко.

UPDATE storage.objects
SET metadata = jsonb_set(metadata, '{cacheControl}', '"max-age=604800"')
WHERE bucket_id NOT IN ('news', 'avatars')
  AND coalesce(metadata->>'cacheControl', 'no-cache') IN ('no-cache', '3600', 'max-age=3600');

-- --- Проверка -----------------------------------------------------------
SELECT bucket_id,
       metadata->>'cacheControl' AS срок_кэша,
       count(*) AS файлов
FROM storage.objects
GROUP BY bucket_id, metadata->>'cacheControl'
ORDER BY bucket_id;
