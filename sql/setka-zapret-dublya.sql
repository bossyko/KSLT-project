-- ============================================================
-- Запрет на две сетки в одном турнире
-- ============================================================
--
-- Жеребьёвка дважды складывала две раскладки в один турнир: кнопка оставалась
-- живой, пока шёл запрос, и второе нажатие уходило вторым прогоном. В админке
-- это закрыто — кнопка гаснет и стоит защёлка. Но интерфейс всегда можно
-- обойти, а цена ошибки высокая: пары оказываются сразу в двух группах, и
-- заметно это не сразу.
--
-- Ставим запрет там, где его не обойти. В сетке у каждой игры своё место:
-- турнир, группа, круг и номер по порядку. Двух игр на одном месте быть не
-- может — так и записываем.
--
-- Группа у плей-офф пустая, а пустое значение в Postgres не равно другому
-- пустому, и запрет бы не сработал. Поэтому берём COALESCE: нет группы —
-- считаем нулём.
--
-- Проверено перед установкой: в базе 882 матча, ни одной клетки с двумя
-- играми, ни одного участника в двух группах.
--
-- Запускать можно повторно.

CREATE UNIQUE INDEX IF NOT EXISTS matches_odna_igra_na_mesto
    ON public.matches (
        tournament_id,
        COALESCE(group_number, 0),
        round,
        round_number,
        match_order
    );

COMMENT ON INDEX public.matches_odna_igra_na_mesto IS
    'Одно место в сетке — одна игра. Защита от повторного запуска жеребьёвки';

-- ---- Проверка ----

SELECT indexname AS запрет, indexdef AS определение
  FROM pg_indexes
 WHERE schemaname = 'public' AND tablename = 'matches'
   AND indexname = 'matches_odna_igra_na_mesto';
