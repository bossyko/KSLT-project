-- ЖИВ ЛИ СЛУЖЕБНЫЙ КЛЮЧ В РАСПИСАНИИ — ТОЛЬКО ЧТЕНИЕ
-- ============================================================
--
-- ПОВОД. 27.10 в задании `season-reset-yearly` нашёлся служебный ключ
-- Supabase, записанный прямо в текст команды: `Authorization: Bearer
-- sb_secret_...`. Его видит любой, кто может читать `cron.job`, и он
-- попал в переписку. Тогда было решено ключ отозвать и переписать
-- задание так, чтобы ключ брался из `vault`.
--
-- ЭТОТ ФАЙЛ НИЧЕГО НЕ МЕНЯЕТ И НЕ ПОКАЗЫВАЕТ САМ КЛЮЧ — только
-- признаки. Печатать ключ второй раз значит повторить ту же ошибку.
--
-- КАК ЧИТАТЬ ОТВЕТ:
--   kluch_v_tekste = true  → ключ (или другой секрет) по-прежнему лежит
--                            строкой в расписании. Отозван он или нет,
--                            строку надо убрать: задание переписывается
--                            на чтение из vault
--   kluch_v_tekste = false → в расписании секретов нет, этот путь чист
--
-- ОТОЗВАН ЛИ КЛЮЧ — ЭТО ДРУГОЙ ВОПРОС, и ответ на него даёт ВТОРОЙ
-- запрос: если задание ходит по сети и получает 401, ключ мёртв; если
-- 200 — ключ ЖИВОЙ и работает прямо сейчас.

-- ---- 1. Есть ли секреты в тексте заданий ----
SELECT  jobid,
        jobname,
        schedule,
        active,
        (command ILIKE '%sb_secret%'
         OR command ILIKE '%service_role%'
         OR command ILIKE '%Bearer %'
         OR command ILIKE '%apikey%')                      AS kluch_v_tekste,
        length(command)                                    AS dlina_komandy,
        (command ILIKE '%vault%')                          AS beret_iz_vault
FROM    cron.job
ORDER BY jobid;

-- ---- 2. Что отвечает сеть на эти задания ----
-- `net.http_post` АСИНХРОННЫЙ: «1 row» в журнале заданий значит лишь,
-- что запрос поставлен в очередь. Настоящий ответ лежит здесь.
--   status_code 200/2xx → ключ принят, то есть ЖИВОЙ
--   status_code 401     → ключ отозван или сменён
SELECT  id,
        created                                            AS kogda,
        status_code,
        left(coalesce(error_msg, ''), 120)                 AS oshibka
FROM    net._http_response
ORDER BY created DESC
LIMIT   10;
