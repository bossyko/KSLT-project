-- УМОЛЧАНИЕ УВЕДОМЛЕНИЙ — СОГЛАСИЕ ЖИВЁТ В ДАННЫХ (07.11.2026)
--
-- ЧТО ТРЕБУЮТ ДОКУМЕНТЫ. Политика конфиденциальности, таблица оснований,
-- строка «Служебные уведомления о турнирах, заявках, матчах, изменении
-- документов»: «Исполнение соглашения (п. 1 ч. 1); ДЛЯ НАПРАВЛЕНИЯ
-- УВЕДОМЛЕНИЙ НА КОНТАКТНЫЕ ДАННЫЕ — СОГЛАСИЕ ПОЛЬЗОВАТЕЛЯ (ст. 44)».
-- Текст Согласия, цель 1: «Без согласия уведомления показываются только в
-- Приложении и личном кабинете на Сайте», переключатели по умолчанию
-- выключены. Цель 4 (новости и предложения) — отдельное согласие.
--
-- ЧТО БЫЛО В КОДЕ. Правило `shouldNotify` живёт в 16 копиях в серверных
-- функциях, и во всех оно говорило: НЕТ НАСТРОЕК — СЛАТЬ. То есть человек,
-- не давший ни одного согласия, получал письма и сообщения в телеграм.
--
-- ПОЧЕМУ ПРАВИМ ДАННЫЕ, А НЕ 56 ЗОВОВ. Зовов правила 56, копий правила 16,
-- и ни одна из них не видит столбцов согласия — им передают только
-- `notify_preferences`. Передать согласие в каждый зов — это 72 места, где
-- его потом забудут. УМОЛЧАНИЕ — СВОЙСТВО ДАННЫХ, А НЕ РАЗМЕТКИ: согласие
-- проставляет значения в `notify_preferences` триггером базы, а правило
-- меняет умолчание на «молчать» — и дальше оно работает само.
--
-- ЧЕГО ЭТОТ ФАЙЛ НЕ ТРОГАЕТ И ПОЧЕМУ:
--   • канал `site` (колокольчик в приложении и кабинете) — по документу он
--     работает и БЕЗ согласия, это и есть «показываются только в
--     Приложении»;
--   • раздел `security` (вход с нового устройства) — основание иное:
--     политика, строка «Безопасность учётной записи» → «Законный интерес
--     КСЛТ и пользователя в защите аккаунта (п. 5 ч. 1)». Согласия не
--     требует;
--   • коды входа (`send-otp`) — «Регистрация, вход, ведение учётной
--     записи» → исполнение соглашения (п. 1 ч. 1);
--   • push-уведомления — канала `push` в правиле нет вовсе: push приходит
--     В ПРИЛОЖЕНИЕ, а не на контактные данные. ЗДЕСЬ РАСХОЖДЕНИЕ ДВУХ
--     НАШИХ ДОКУМЕНТОВ, и оно к юристу, а не к коду: политика относит
--     токен push к служебным уведомлениям, а текст Согласия перечисляет
--     его только в цели 4;
--   • извещения персоналу (`score-dispute-notify`, `news-offer`) —
--     ЗАМЕРЕНО ЧТЕНИЕМ: оба выбирают получателей по `role IN
--     ('admin','manager')`, то есть это служебная почта администраторов, а
--     не уведомления игроку. Моё прежнее предположение, что спор по счёту
--     идёт игроку, замер опроверг;
--   • `auto-unban` и `admin-manage-user` — сообщения о бане и разбане,
--     основание «Рассмотрение обращений, жалоб и споров» → обязанность по
--     ст. 119 (п. 2 ч. 1).
--
-- ЧЕМ ПЛАТИМ. Тонкая настройка внутри согласия (человек дал согласие, но
-- выключил, скажем, только «матчи») сбрасывается при отзыве и повторной
-- выдаче согласия: вернётся «все четыре включены». Названо заранее.
--
-- ЗАПРОС ТРОГАЕТ ДАННЫЕ: в конце есть разовое приведение
-- `notify_preferences` у ВСЕХ профилей. Согласие Кости получено 07.11.


-- ----------------------------------------------------------------------
-- 1. ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ
--
-- Как согласие ложится в настройки — сказано ЗДЕСЬ и только здесь. Его
-- зовут и триггер, и разовое приведение ниже: иначе беда родилась бы ровно
-- на шве между ними.
-- ----------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public."согласие_в_настройки"(
    н       jsonb,
    дано_1  boolean,
    дано_4  boolean
) RETURNS jsonb
LANGUAGE sql
IMMUTABLE
AS $$
    SELECT coalesce(н, '{}'::jsonb)
        || jsonb_build_object(
               'tg',    coalesce(coalesce(н, '{}'::jsonb) -> 'tg',    '{}'::jsonb) || б.блок,
               'email', coalesce(coalesce(н, '{}'::jsonb) -> 'email', '{}'::jsonb) || б.блок
           )
      FROM (
          SELECT jsonb_build_object(
                     /* цель 1 — служебные уведомления на контактные данные */
                     'challenges',  coalesce(дано_1, false),
                     'tournaments', coalesce(дано_1, false),
                     'membership',  coalesce(дано_1, false),
                     'matches',     coalesce(дано_1, false),
                     /* цель 4 — новости и предложения (рассылка broadcast) */
                     'general',     coalesce(дано_4, false)
                 ) AS блок
      ) AS б;
$$;

COMMENT ON FUNCTION public."согласие_в_настройки"(jsonb, boolean, boolean) IS
'Кладёт согласия целей 1 и 4 в notify_preferences для каналов tg и email. Разделы security и канал site не трогает: у них иное основание обработки.';


-- ----------------------------------------------------------------------
-- 2. СТОРОЖ НА СТЫКЕ: СОГЛАСИЕ МЕНЯЕТСЯ — МЕНЯЮТСЯ НАСТРОЙКИ
--
-- BEFORE, потому что меняем NEW. `UPDATE OF` — чтобы не трогать настройки
-- при любой другой правке профиля: человек, выключивший отдельный раздел
-- внутри данного согласия, свой выбор сохраняет.
-- ----------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public."согласие_меняет_настройки"()
RETURNS trigger
LANGUAGE plpgsql
SET search_path TO 'public'
AS $$
BEGIN
    NEW.notify_preferences := public."согласие_в_настройки"(
        NEW.notify_preferences, NEW.consent_notify, NEW.consent_news);
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS profiles_soglasie_v_nastroyki ON public.profiles;
CREATE TRIGGER profiles_soglasie_v_nastroyki
    BEFORE INSERT OR UPDATE OF consent_notify, consent_news
    ON public.profiles
    FOR EACH ROW
    EXECUTE FUNCTION public."согласие_меняет_настройки"();


-- ----------------------------------------------------------------------
-- 3. РАЗОВОЕ ПРИВЕДЕНИЕ — БЕЗ НЕГО ОСТАЁТСЯ ДЫРА
--
-- У части профилей в `notify_preferences` уже лежат явные `true`,
-- проставленные экраном уведомлений ДО того, как появились согласия. Новое
-- правило читает явное `true` как «слать» — и такой профиль получал бы
-- письма без согласия. Поэтому настройки приводятся к согласию у всех.
--
-- Этот UPDATE не перечисляет столбцы consent_*, поэтому триггер выше на нём
-- НЕ срабатывает (там `UPDATE OF`) и журнал согласий `consents` ложных
-- записей не получит: `записать_согласие()` пишет только при РАЗНИЦЕ
-- значений согласия, а они здесь не меняются.
-- ----------------------------------------------------------------------
UPDATE public.profiles
   SET notify_preferences = public."согласие_в_настройки"(
           notify_preferences, consent_notify, consent_news)
 WHERE notify_preferences IS DISTINCT FROM public."согласие_в_настройки"(
           notify_preferences, consent_notify, consent_news);


-- ----------------------------------------------------------------------
-- 4. ПРОВЕРКА — ЧИТАЕТСЯ ИЗ БАЗЫ, А НЕ ИЗ ОТВЕТА «Success»
--
-- Ждём: ровно столько профилей, сколько их всего, и у каждого пять
-- разделов проставлены явно; «молчим» — у кого согласия нет.
-- ----------------------------------------------------------------------
SELECT
    count(*)                                                        AS vsego_profiley,
    count(*) FILTER (WHERE notify_preferences #> '{tg,challenges}'  IS NOT NULL
                       AND notify_preferences #> '{email,general}'  IS NOT NULL) AS nastroyki_yavnye,
    count(*) FILTER (WHERE coalesce(consent_notify, false))         AS dali_cel_1,
    count(*) FILTER (WHERE coalesce(consent_news, false))           AS dali_cel_4,
    count(*) FILTER (WHERE (notify_preferences #>> '{email,matches}') = 'false') AS molchim_po_pochte,
    count(*) FILTER (WHERE (notify_preferences #>> '{tg,matches}')   = 'true')   AS pishem_v_tg
  FROM public.profiles;
