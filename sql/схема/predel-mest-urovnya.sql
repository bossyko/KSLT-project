-- ЗАЧЕМ. Слово Кости 02.10: «итоговый — это просто восьмёрка, как у АТР и в
-- женском»; 03.10: «да, только 8 строк, там больше и не может быть».
--
-- А в базе у итогового турнира ВСЕ 64 места (замер, шаг 2), и места с 9-го
-- по 34-е оплачены: 18 · 16 · 13 · 13 · 11 … 2. Эти 26 чисел не может
-- заработать никто — восьмёрка кончается на восьмом месте. Но если сетку на
-- 16 на этом уровне кто-нибудь заведёт, они заплатятся, и заплатятся неверно.
--
-- ЧТО ДЕЛАЕМ. У уровня появляется ПРЕДЕЛ — наибольшее место, которое он
-- платит. Четырём категориям 64, итоговому 8.
--
-- ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. Предел живёт ОДНОЙ колонкой рядом с
-- `on_ladder`, и его спрашивает чтение таблицы мест (`bracket.js`,
-- `местаУровня`). Экран очков спросит его же.
--
-- ПРЕДЕЛ И `on_ladder` — РАЗНЫЕ ФАКТЫ, И СВОДИТЬ ИХ НЕЛЬЗЯ. `on_ladder`
-- говорит, входит ли уровень в лестницу категорий; предел — сколько мест он
-- платит. Сегодня у итогового выключено и то и другое, но завтра может
-- появиться уровень на лестнице с пределом 16, и тогда склейка родила бы
-- беду ровно на шве.
--
-- СТРОКИ 9–64 ИТОГОВОГО НЕ УДАЛЯЮТСЯ. Удаление — отдельный шаг, он не
-- начинается без слова Кости и без слепка.
-- ЦЕНА, НАЗВАННАЯ ВСЛУХ: в базе остаются 56 строк на уровень, невидимые и
-- неоплачиваемые. Зато правка обратима одним `UPDATE` предела.

BEGIN;

-- ---- Шаг 1. Колонка ----

ALTER TABLE public.tournament_levels
    ADD COLUMN IF NOT EXISTS max_place integer NOT NULL DEFAULT 64;

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_constraint
                    WHERE conname = 'tournament_levels_max_place_check') THEN
        ALTER TABLE public.tournament_levels
            ADD CONSTRAINT tournament_levels_max_place_check
            CHECK (max_place BETWEEN 1 AND 64);
    END IF;
END $$;

COMMENT ON COLUMN public.tournament_levels.max_place IS
    'Наибольшее место, которое уровень платит. Четырём категориям 64, итоговому 8. Не то же, что on_ladder';

-- ---- Шаг 2. Порог: ровно один уровень вне лестницы ----
--
-- ПРИВЯЗКА ПО `sort_order`, А НЕ ПО ИМЕНИ. Имена уровней переименовывались
-- 30.09 и 02.10, и файл `kategorii-i-ochki.sql:179`, привязанный к именам,
-- после переименования не положил бы ни строки.
--
-- Порог отдельный, потому что `sort_order = 1` — это договорённость, а не
-- закон: если итоговый окажется не первым или их станет двое, правка должна
-- ОТКАЗАТЬСЯ, а не угадать.

DO $$
DECLARE
    итоговых integer;
BEGIN
    SELECT count(*) INTO итоговых
      FROM public.tournament_levels
     WHERE sort_order = 1;

    IF итоговых <> 1 THEN
        RAISE EXCEPTION
            'Уровней с sort_order = 1 найдено %, а не один — правка отказывается',
            итоговых;
    END IF;
END $$;

-- ---- Шаг 3. Восьмёрка ----

UPDATE public.tournament_levels
   SET max_place = 8
 WHERE sort_order = 1;

-- ---- Шаг 4. Перечитка ВНУТРИ транзакции ----
--
-- «UPDATE 1» говорит, сколько строк тронуто, а не что в них лежит.
-- РЕЗУЛЬТАТ ЗАПРОСА ПРОВЕРЯЕТСЯ ЧТЕНИЕМ, а не ответом «Success».

DO $$
DECLARE
    восьмёрок integer;
    шестьдесятчетвёрок integer;
BEGIN
    SELECT count(*) INTO восьмёрок
      FROM public.tournament_levels WHERE max_place = 8;
    SELECT count(*) INTO шестьдесятчетвёрок
      FROM public.tournament_levels WHERE max_place = 64;

    IF восьмёрок <> 1 THEN
        RAISE EXCEPTION 'После правки уровней с пределом 8 стало %, а не один', восьмёрок;
    END IF;
    IF шестьдесятчетвёрок <> 4 THEN
        RAISE EXCEPTION 'После правки уровней с пределом 64 стало %, а не четыре', шестьдесятчетвёрок;
    END IF;
END $$;

COMMIT;

