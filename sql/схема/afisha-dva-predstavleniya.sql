-- ЗАЧЕМ. Сегодня афиша хранится ОДНА и обрезается прямо при загрузке под
-- 16:9 (js/admin/sections/tournaments.js:1368 -> A.cropCover). Оригинал
-- выбрасывается, поэтому вертикальные афиши на карточках выглядят
-- срезанными: режет не показ, а загрузка.
--
-- Костя: «на карточке отображается полная афиша миниатюрой, а на самой
-- странице турнира вверху — обрезанная кропом, что выберет админ».
--
-- ЧТО ДОБАВЛЯЕМ И ПОЧЕМУ ИМЕННО ТАК:
--
--   image       — НЕ ТРОГАЕМ. Это по-прежнему обложка страницы, кадр 16:9.
--                 Все 43 существующие афиши остаются на месте, переносить
--                 строки не нужно.
--   image_full  — полная афиша без обрезки. Её показывает карточка.
--                 Пусто — карточка берёт image, как сегодня.
--                 УМОЛЧАНИЕ — СВОЙСТВО ДАННЫХ, А НЕ РАЗМЕТКИ.
--   image_crop  — прямоугольник кадра в долях исходной картинки
--                 {"x":0.0,"y":0.12,"w":1.0,"h":0.56}. Нужен, чтобы
--                 перекадрировать БЕЗ перезаливки файла.
--
-- МЕСТО. Замерено 28.09: 20 афиш занимают 3.2 МБ, вся корзина news —
-- 75 файлов и 15.0 МБ. Второе представление добавит около 1.3 МБ.
-- Место — не наша беда; беда — трафик: в короб 120 x 160 на обзоре
-- турниров тянется файл шириной 1200.

ALTER TABLE tournaments ADD COLUMN IF NOT EXISTS image_full TEXT;
ALTER TABLE tournaments ADD COLUMN IF NOT EXISTS image_crop JSONB;

COMMENT ON COLUMN tournaments.image IS
    'Обложка страницы турнира: кадр 16:9, готовится при загрузке';
COMMENT ON COLUMN tournaments.image_full IS
    'Полная афиша без обрезки — для миниатюры в карточке. Пусто: берём image';
COMMENT ON COLUMN tournaments.image_crop IS
    'Кадр в долях исходной картинки: x, y, w, h. Нужен для перекадрирования';

-- Проверка: сколько турниров с афишей, сколько уже с полной
SELECT
    count(*)                                        AS всего,
    count(*) FILTER (WHERE image IS NOT NULL)       AS с_обложкой,
    count(*) FILTER (WHERE image_full IS NOT NULL)  AS с_полной,
    count(*) FILTER (WHERE image_crop IS NOT NULL)  AS с_кадром
FROM tournaments;
