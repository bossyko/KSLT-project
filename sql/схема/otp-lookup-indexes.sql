-- ============================================
-- Поиск аккаунта при восстановлении доступа
-- Запустить в Supabase SQL Editor целиком.
-- ============================================
--
-- Восстановление пароля начинается с поиска: есть ли аккаунт с такой почтой
-- или таким телефоном. До сих пор функция вместо поиска выкачивала список
-- пользователей и перебирала его в памяти — и видела только первую страницу
-- в 50 записей, то есть полсотни самых старых аккаунтов из трёхсот.
--
-- Здесь два индекса под этот поиск и решение застарелой проблемы с телефоном.

-- --- Почта -------------------------------------------------------------
-- profiles.email заполняется триггером из auth.users, там адрес уже в нижнем
-- регистре. Старые записи могли попасть иначе — приводим к одному виду,
-- иначе поиск будет промахиваться.

UPDATE profiles
SET email = lower(email)
WHERE email IS NOT NULL AND email <> lower(email);

CREATE INDEX IF NOT EXISTS idx_profiles_email ON profiles (email);

-- --- Телефон -----------------------------------------------------------
-- Телефон попадает в профиль в том виде, в каком его набрал человек:
-- «+996 555 12 34 56», «0555123456», «996555 123456». А код восстановления
-- ищет по нормализованному номеру. Сравнивать такое напрямую бессмысленно.
--
-- Считаем последние девять цифр — это номер без кода страны. Тогда все три
-- записи выше совпадут между собой. Колонку считает сама база, поэтому
-- забыть обновить её нельзя ни из кабинета, ни из админки, ни из импорта.

ALTER TABLE profiles
    ADD COLUMN IF NOT EXISTS phone_tail TEXT
    GENERATED ALWAYS AS (
        right(regexp_replace(coalesce(phone, ''), '[^0-9]', '', 'g'), 9)
    ) STORED;

CREATE INDEX IF NOT EXISTS idx_profiles_phone_tail ON profiles (phone_tail)
    WHERE phone_tail <> '';

COMMENT ON COLUMN profiles.phone_tail IS
    'Последние 9 цифр телефона — номер без кода страны. Для поиска при восстановлении доступа';

-- --- Проверка ----------------------------------------------------------

SELECT count(*) AS всего,
       count(email) AS с_почтой,
       count(*) FILTER (WHERE phone_tail <> '') AS с_телефоном
FROM profiles;

-- Совпадают ли номера, записанные по-разному
SELECT phone, phone_tail
FROM profiles
WHERE phone IS NOT NULL AND phone <> ''
ORDER BY phone
LIMIT 10;
