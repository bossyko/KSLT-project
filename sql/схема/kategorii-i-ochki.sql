    разложено AS (
        SELECT у.id AS level_id, т.место,
               CASE у.name
                   WHEN 'Высшая'    THEN т."Высшая"
                   WHEN 'Первая'    THEN т."Первая"
                   WHEN 'Вторая'    THEN т."Вторая"
                   WHEN 'Третья'    THEN т."Третья"
                   WHEN 'Четвёртая' THEN т."Четвёртая"
               END AS очки
          FROM public.tournament_levels у
          CROSS JOIN таблица т
         WHERE у.name IN ('Высшая', 'Первая', 'Вторая', 'Третья', 'Четвёртая')
    )
