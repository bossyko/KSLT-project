    -- ATP на своём итоговом: очки идут за победы, а не за факт участия.
    --
    -- Решение Costa 17.09.2026: у нас турнир любительский, и попавшим в
    -- восьмёрку победы в группе засчитываем, чтобы не пропадали.

    WITH восьмёрка(место, очки) AS (
      VALUES (1, 400), (2, 250), (3, 150), (4, 100),
             (5, 0), (6, 0), (7, 0), (8, 0)
    )
    INSERT INTO public.points_by_place (level_id, place, points)
    SELECT у.id, в.место, в.очки
      FROM public.tournament_levels у
      CROSS JOIN восьмёрка в
     WHERE у.name = 'Итоговый турнир'
        ON CONFLICT (level_id, place) DO UPDATE SET points = EXCLUDED.points;

    COMMIT;
