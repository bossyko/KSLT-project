    SELECT level_id, место, очки FROM разложено
        ON CONFLICT (level_id, place) DO UPDATE SET points = EXCLUDED.points;

    -- ---- Итоговый турнир года ----
    --
    -- Восемь лучших по итогам сезона: группы, потом плей-офф на вылет, и за
