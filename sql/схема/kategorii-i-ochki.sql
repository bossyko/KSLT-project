    -- ============================================================
    -- Категории турниров и очки за место — ПРАВКА
    -- ============================================================
    --
    -- До сих пор очки начислялись по стадии: выиграл турнир — столько,
    -- дошёл до полуфинала — столько. В Положении клуба иначе: очки даёт
    -- занятое место, с первого по шестьдесят четвёртое. Третье и четвёртое
    -- там различаются, пятое и шестое тоже, а по стадиям оба полуфиналиста
    -- одинаковы.
    --
    -- Источник: Приложение 2 к Положению КСЛТ, г. Бишкек, 2021, стр. 10–11.
    -- Файл лежит в docs/. Часть значений исправлена от руки: жёлтым новое,
    -- зачёркнуто старое — берём жёлтое. Проверено на убывание: в каждой
    -- категории очки сверху вниз не растут, со старыми это не сходилось.
    --
    -- Строка таблицы — занятое место, колонка — категория турнира. За победу
    -- дают 1000 в Высшей, 600 в Первой, 360 во Второй, 215 в Третьей,
    -- 130 в Четвёртой.
    --
    -- ---- Названия ----
    --
    -- В базе уровни звались «Категория 1…4» и «Grand (ТБШ)», причём первая
    -- была самой слабой — обратный счёт к Положению. Менеджер выбирает
    -- уровень при создании турнира и читает там не то, что в документе.
    -- Переименовываем по Положению, порядок силы не меняем: привязка
    -- турниров к уровням остаётся прежней, меняется только подпись.
    --
    -- Четвёртую заводим тоже, хотя турниров по ней пока нет: список должен
    -- совпадать с Положением.
    --
    -- Итоговый турнир года считается отдельно (Положение, п. 9.8): восемь
    -- лучших, 50 за матч в группе, 100 за полуфинал, 150 за финал, потолок
    -- 400. Очков за место у него нет, поэтому строк в таблице ему не даём —
    -- его считает своё правило в коде.
    --
    -- ---- Сноска Положения (стр. 11) ----
    --
    -- Если места в двойке, четвёрке, восьмёрке не разыгрывались, всем
    -- игрокам этой группы начисляется одинаково — на уровне очков за
    -- последнее место группы. То есть без матча за третье место оба
    -- полуфиналиста получают как за четвёртое. Это считает код при
    -- завершении турнира, в таблице такого правила нет.
    --
    -- Таблица пока справочная: начисление её ещё не читает, ничего не
    -- пересчитывается.
    --
    -- Файл меняет базу. Проверка — kategorii-i-ochki-proverka.sql.
    -- Запускать можно повторно.

    BEGIN;

    -- ---- Названия категорий по Положению ----

    UPDATE public.tournament_levels SET name = 'Высшая',    name_en = 'Top'    WHERE sort_order = 5;
    UPDATE public.tournament_levels SET name = 'Первая',    name_en = 'First'  WHERE sort_order = 4;
    UPDATE public.tournament_levels SET name = 'Вторая',    name_en = 'Second' WHERE sort_order = 3;
    UPDATE public.tournament_levels SET name = 'Третья',    name_en = 'Third'  WHERE sort_order = 2;
    UPDATE public.tournament_levels SET name = 'Четвёртая', name_en = 'Fourth' WHERE sort_order = 1;

    -- Итоговый турнир года: восемь лучших, свои очки
    INSERT INTO public.tournament_levels (name, name_en, sort_order)
    SELECT 'Итоговый турнир', 'Year-End Finals', 6
     WHERE NOT EXISTS (SELECT 1 FROM public.tournament_levels WHERE sort_order = 6);

    -- ---- Таблица очков за место ----

    CREATE TABLE IF NOT EXISTS public.points_by_place (
        id       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
        level_id uuid NOT NULL REFERENCES public.tournament_levels(id) ON DELETE CASCADE,
        place    integer NOT NULL CHECK (place BETWEEN 1 AND 64),
        points   integer NOT NULL DEFAULT 0,
        UNIQUE (level_id, place)
    );

    COMMENT ON TABLE public.points_by_place IS
        'Очки за место в турнире по категориям. Приложение 2 к Положению КСЛТ 2021';
    COMMENT ON COLUMN public.points_by_place.place IS
        'Место с 1 по 64. Мест больше, чем стадий: третье и четвёртое различаются';

    ALTER TABLE public.points_by_place ENABLE ROW LEVEL SECURITY;

    -- Читают все: очки за место — открытая часть правил
    DROP POLICY IF EXISTS points_by_place_read ON public.points_by_place;
    CREATE POLICY points_by_place_read ON public.points_by_place
        FOR SELECT USING (true);

    -- Пишут только сотрудники клуба
    DROP POLICY IF EXISTS points_by_place_staff ON public.points_by_place;
    CREATE POLICY points_by_place_staff ON public.points_by_place
        FOR ALL
        USING (EXISTS (SELECT 1 FROM public.profiles p
                        WHERE p.id = auth.uid() AND p.role IN ('admin', 'manager')))
        WITH CHECK (EXISTS (SELECT 1 FROM public.profiles p
                             WHERE p.id = auth.uid() AND p.role IN ('admin', 'manager')));

    -- ---- Значения ----
