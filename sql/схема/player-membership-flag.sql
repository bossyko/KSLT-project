-- ============================================
-- Отметка члена клуба у карточки игрока
-- ============================================
--
-- В `players` 292 карточки, и почти все — перенос списков NTRP: человека
-- на платформе нет, членство никто не оплачивал. При этом в рейтинге они
-- стоят наравне с настоящими членами клуба, и на карточке любого из них
-- работает кнопка «Вызвать на матч» — вызвать некого.
--
-- Членом клуба игрок считается в двух случаях:
--
--   1. Его карточка связана с учётной записью, а у той есть действующее
--      членство. Это обычный путь: зарегистрировался, нашёлся, оплатил.
--
--   2. Стоит отметка `is_member`, которую администратор проставил вручную.
--      Нужна для тех, кто платит наличными и на сайте не регистрировался.
--
-- Очки и NTRP на членство не влияют. Это важно: исторические очки клуб
-- отдаёт в сентябре, и залить их собираются всем 292. Если считать
-- признаком наличие очков, все фоновые окажутся в клубе, не заплатив.

BEGIN;

ALTER TABLE players ADD COLUMN IF NOT EXISTS is_member BOOLEAN NOT NULL DEFAULT false;

COMMENT ON COLUMN players.is_member IS
    'Отметка администратора: игрок оплатил членство мимо сайта. Второй путь — действующее членство у привязанной учётной записи';

-- Отбор членов идёт по этому полю на каждой загрузке рейтинга
CREATE INDEX IF NOT EXISTS idx_players_is_member
    ON players (is_member) WHERE is_member;

-- ============================================
-- Кто уже член: проставляем отметку тем, у кого членство действует
-- ============================================
-- Дальше отметка живёт сама: её ставит и снимает администратор, а для
-- зарегистрированных членство проверяется на лету.

UPDATE players p
   SET is_member = true
  FROM profiles pr
  JOIN memberships m ON m.profile_id = pr.id
 WHERE pr.player_id = p.id
   AND m.status = 'active'
   AND m.expires_at >= CURRENT_DATE;

COMMIT;

