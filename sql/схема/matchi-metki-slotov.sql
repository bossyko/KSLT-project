-- ============================================================
-- Матч плей-офф знает, кого ждёт в каждом слоте
-- ============================================================
--
-- Сетка плей-офф теперь создаётся сразу после жеребьёвки групп, когда имён
-- ещё нет: известно только, что сюда придёт победитель группы A, а сюда —
-- второе место группы B. Эти метки и храним.
--
-- Как только группа доиграна, её места окончательны, и система сама ставит
-- игроков в ожидающие слоты — не дожидаясь остальных групп.
--
--   A1, B2, C3 — место в своей группе
--   IG1, IG2   — победитель дополнительного матча номер N
--
-- Пусто — слот заполнен по ходу сетки: сюда приходит победитель предыдущего
-- круга, и ждать нечего.
--
-- Запускать можно повторно.

BEGIN;

ALTER TABLE public.matches
    ADD COLUMN IF NOT EXISTS slot1_label text,
    ADD COLUMN IF NOT EXISTS slot2_label text;

COMMENT ON COLUMN public.matches.slot1_label IS
    'Кого ждёт первый слот: A1, B2 — место в группе, IG1 — победитель доп. матча';
COMMENT ON COLUMN public.matches.slot2_label IS
    'Кого ждёт второй слот: A1, B2 — место в группе, IG1 — победитель доп. матча';

COMMIT;

NOTIFY pgrst, 'reload schema';

-- ---- Проверка ----

SELECT count(*) AS всего_матчей,
       count(*) FILTER (WHERE slot1_label IS NOT NULL
                           OR slot2_label IS NOT NULL) AS с_метками
  FROM public.matches;
-- Ожидаем: колонки появились, меток пока нет — они проставятся при
-- следующей жеребьёвке.
