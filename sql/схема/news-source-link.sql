-- ============================================================
-- Мировая новость ведёт прямо к статье
-- ============================================================
--
-- Первая же опубликованная новость показала промах замысла. Карточка вела
-- на нашу страницу, а на ней — тот же заголовок и ссылка «Читать целиком».
-- Человек нажимает, ждёт статью, получает указатель на статью и нажимает
-- второй раз. Смысл теряется.
--
-- Наполнить эту страницу нечем: чужой текст мы не перепечатываем
-- принципиально, за это и прилетает. Значит своей страницы у мировой
-- новости быть не должно — карточка уводит сразу к источнику.
--
-- Для этого ссылка нужна отдельным полем. Раньше она лежала внутри готовой
-- разметки текста, и достать её оттуда можно было только разбором.
--
-- Поля общие для всех новостей, не только мировых: у клубной новости они
-- останутся пустыми, и вести она будет к себе, как и вела.
--
-- Файл меняет базу. Читающие запросы — в world-news-feed-check.sql.

BEGIN;

ALTER TABLE public.news
    ADD COLUMN IF NOT EXISTS source_url  text,
    ADD COLUMN IF NOT EXISTS source_name text;

COMMENT ON COLUMN public.news.source_url IS
    'Ссылка на первоисточник. Если заполнена — карточка ведёт туда, а не на нашу страницу.';

COMMENT ON COLUMN public.news.source_name IS
    'Название первоисточника: показываем рядом со ссылкой, чтобы человек знал, куда уходит.';

-- ---- Уже опубликованным достаём ссылку из текста ----
-- Их пока единицы, но пусть ведут себя как остальные.

UPDATE public.news
   SET source_url = substring(content from 'href="([^"]+)"')
 WHERE category = 'world'
   AND source_url IS NULL
   AND content LIKE '%href=%';

UPDATE public.news
   SET source_name = trim(replace(excerpt, 'Источник:', ''))
 WHERE category = 'world'
   AND source_name IS NULL
   AND excerpt LIKE 'Источник:%';

COMMIT;
