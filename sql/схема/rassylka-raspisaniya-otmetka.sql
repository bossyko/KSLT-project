-- ============================================================
-- Рассылка расписания: помним, когда отправляли
-- ============================================================
--
-- Кнопка «Уведомить игроков» шлёт всем участникам расписание запусков.
-- Гасла она только на экране: обновил страницу — и снова как новая, а
-- отправляли уже или нет, не понять.
--
-- Заводим в турнире отметку времени последней рассылки. Запрещать повтор
-- не будем: расписание меняется — запуски двигают стрелками, меняют корт,
-- добавляют пару, — и новое письмо как раз нужно. Но перед повтором админка
-- скажет, когда отправляли в прошлый раз.
--
-- Запускать можно повторно.

BEGIN;

ALTER TABLE public.tournaments
    ADD COLUMN IF NOT EXISTS schedule_notified_at timestamptz;

COMMENT ON COLUMN public.tournaments.schedule_notified_at IS 'Когда последний раз рассылали расписание запусков участникам';

COMMIT;

-- ---- Проверка ----

SELECT column_name AS поле, data_type AS тип
  FROM information_schema.columns
 WHERE table_schema = 'public' AND table_name = 'tournaments'
   AND column_name = 'schedule_notified_at';
-- Ожидаем одну строку.
