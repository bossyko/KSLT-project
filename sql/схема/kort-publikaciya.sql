-- КСЛТ — публикация корта.
--
-- Зачем: корт теперь можно завести прямо из формы турнира, тремя полями —
-- название, адрес, город. Такой корт ещё не готов для сайта: у него нет ни
-- фотографии, ни покрытий, ни цен, ни расписания. Показывать его людям
-- нельзя, пока его не дозаполнили в разделе «Корты».
--
-- Поле названо published_at, а не is_published: ровно так уже устроены
-- турниры (tournaments.published_at). Одно определение на одно понятие —
-- у публикации на КСЛТ одна форма, а не две.
--
-- ВАЖНО: всем существующим кортам дата проставляется здесь. Иначе после
-- включения фильтра тридцать один корт разом пропадёт с сайта.

ALTER TABLE courts ADD COLUMN IF NOT EXISTS published_at TIMESTAMPTZ;

COMMENT ON COLUMN courts.published_at IS 'Когда корт открыли людям. Пусто — черновик: виден только в админке';

UPDATE courts SET published_at = COALESCE(created_at, now()) WHERE published_at IS NULL;

-- Проверка: черновиков не осталось, все существующие корты опубликованы
SELECT count(*) AS всего,
       count(published_at) AS опубликовано,
       count(*) FILTER (WHERE published_at IS NULL) AS черновиков
FROM courts;
