-- ============================================
-- Оригинал обложки новости
-- Запустить в Supabase SQL Editor целиком.
-- ============================================
--
-- Менеджер грузит афишу как есть — она бывает вертикальной, квадратной, любой.
-- В карточках списка нужна одна пропорция, иначе сетка разъезжается, поэтому
-- при загрузке он кадрирует снимок в рамке 16:9, и результат ложится в `image`.
--
-- Но афишу рисовали, чтобы её прочитали: даты, состав, телеграм-канал. Поэтому
-- исходник сохраняем отдельно и показываем целиком в шапке самой новости.
--
-- У старых новостей колонка останется пустой — там в шапке покажется обложка,
-- как и раньше.

ALTER TABLE news ADD COLUMN IF NOT EXISTS image_original TEXT;

COMMENT ON COLUMN news.image IS 'Обложка для карточек: кадрирована 16:9 при загрузке';
COMMENT ON COLUMN news.image_original IS 'Исходная афиша без обрезки — показывается в шапке новости';

SELECT count(*) AS всего,
       count(image) AS с_обложкой,
       count(image_original) AS с_оригиналом
FROM news;
