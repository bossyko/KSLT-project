-- ============================================================
-- Зерно жеребьёвки у турнира
-- ============================================================
--
-- Внутри группы сеяных (скажем, кто из 5-8 встанет на линию 16, а кто на 17)
-- решает жребий. Но тянуть его надо один раз: пока он тянулся при каждой
-- сборке сетки, пересборка давала другую расстановку, и люди видели, что
-- сетка меняется сама собой.
--
-- Теперь зерно хранится вместе с турниром. Одно зерно — одна и та же сетка,
-- сколько бы раз её ни строили заново.
--
-- Поле добавляется, ничего не переименовывается: у прежних турниров оно
-- останется пустым, и для них жеребьёвка ведёт себя как раньше.

BEGIN;

ALTER TABLE public.tournaments
    ADD COLUMN IF NOT EXISTS draw_seed integer;

COMMENT ON COLUMN public.tournaments.draw_seed IS
    'Зерно жеребьёвки. Одно зерно даёт одну и ту же расстановку: пересборка сетки не меняет её.';

COMMIT;
