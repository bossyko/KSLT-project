BEGIN;

ALTER TABLE public.tournaments
    ADD COLUMN IF NOT EXISTS schedule_saved_at timestamptz;

COMMENT ON COLUMN public.tournaments.schedule_saved_at IS 'Когда последний раз сохраняли расписание запусков';

COMMIT;

NOTIFY pgrst, 'reload schema';

-- ---- Проверка ----

SELECT t.title AS турнир,
       t.schedule_saved_at    AS сохраняли,
       t.schedule_notified_at AS рассылали
  FROM public.tournaments t
 WHERE t.id IN ('b8a6de7b-a146-4168-aaea-b56fb5dbd135',
                '7094e2bd-02e6-476b-9e0c-efc7bffc8418');
