-- Этот запрос показывает, из чего таблица состоит, — дальше запрос про
-- упавшие задания строится по ней, а не по памяти.

SELECT  ordinal_position AS nomer,
        column_name      AS stolbec,
        data_type        AS tip
FROM    information_schema.columns
WHERE   table_schema = 'net'
    AND table_name   = '_http_response'
ORDER BY ordinal_position;
