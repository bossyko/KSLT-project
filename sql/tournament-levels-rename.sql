-- Уровни турнира — названия по Положению КСЛТ 2021
-- ================================================
--
-- В базе уровни назывались «Категория 1…4», причём «Категория 1» была самой
-- слабой: 25 очков за победу против 200 у «Категории 4». В Положении наоборот —
-- первая категория идёт сразу за высшей. Организатор, читавший Положение,
-- выбрал бы «Категория 1» и начислил человеку 25 очков вместо максимума.
--
-- Названия берём из Положения (п. 9.2–9.6): высшая, первая, вторая, третья.
-- В таблице очков есть ещё «Четвертая», но Положение её не описывает, и
-- заводить её мы не стали — документ всё равно будет редактироваться.
-- Итоговый турнир года ТБШ стоит отдельно, у него своя шкала (п. 9.8).
--
-- Сопоставление — по нынешним очкам, от дорогой категории к дешёвой.
--
-- ВАЖНО: сами числа очков этим запросом не трогаются и остаются неверными —
-- в базе за победу 25/50/100/200, у клиента за 1-е место 1000/600/360/215/130.
-- Шкалу пересобираем отдельно, когда дойдём до начисления очков в админке.

BEGIN;

UPDATE tournament_levels SET name = 'Высшая',    name_en = 'Top Category',    sort_order = 1 WHERE name = 'Категория 4';
UPDATE tournament_levels SET name = 'Первая',    name_en = 'First Category',  sort_order = 2 WHERE name = 'Категория 3';
UPDATE tournament_levels SET name = 'Вторая',    name_en = 'Second Category', sort_order = 3 WHERE name = 'Категория 2';
UPDATE tournament_levels SET name = 'Третья',    name_en = 'Third Category',  sort_order = 4 WHERE name = 'Категория 1';
UPDATE tournament_levels SET name = 'Итоговый турнир года (ТБШ)', name_en = 'Year-End Finals', sort_order = 5 WHERE name = 'Grand (ТБШ)';

-- Проверка: пять уровней от высшей к третьей, ТБШ последним
SELECT sort_order, name, name_en FROM tournament_levels ORDER BY sort_order;

COMMIT;
