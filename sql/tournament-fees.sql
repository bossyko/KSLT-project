-- ============================================
-- Взносы за участие в турнире
-- ============================================
--
-- Две суммы на турнир: для членов КСЛТ и для всех остальных. Заполняет
-- админ или менеджер при заведении турнира. Не заполнил — на сайте ничего
-- не показываем, как и с призовым фондом.
--
-- Для парных и смешанных турниров сумма считается с пары, а не с игрока —
-- поэтому подпись на карточке зависит от формата турнира.
--
-- Оплату пока не заводим: до подключения платёжного шлюза сумма только
-- показывается, транзакции создаются вручную в разделе «Финансы».

ALTER TABLE tournaments
    ADD COLUMN IF NOT EXISTS fee_member numeric,
    ADD COLUMN IF NOT EXISTS fee_guest  numeric;

COMMENT ON COLUMN tournaments.fee_member IS
    'Взнос для членов КСЛТ, сом. Для парных и смешанных — с пары. NULL — не показываем';
COMMENT ON COLUMN tournaments.fee_guest IS
    'Взнос для не членов КСЛТ, сом. Для парных и смешанных — с пары. NULL — не показываем';

-- Проверка
SELECT column_name, data_type, is_nullable
FROM information_schema.columns
WHERE table_name = 'tournaments'
  AND column_name IN ('fee_member', 'fee_guest');
