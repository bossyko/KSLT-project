-- ============================================
-- Право удалять скидки
-- ============================================
--
-- В админке появилась кнопка удаления — для отменённых и истёкших
-- ваучеров. Без правила Supabase на удаление не отдаёт ошибку: он молча
-- возвращает пустой ответ, и удаление выглядит выполненным, хотя запись
-- на месте. Так уже было с файлами хранилища.
--
-- Разрешаем только администраторам и менеджерам. Действующие ваучеры
-- удалить всё равно нельзя: это проверяет сама кнопка — выданная скидка
-- обязательство перед человеком, её сначала отменяют.

DROP POLICY IF EXISTS "Админ и менеджер удаляют скидки" ON discount_vouchers;

CREATE POLICY "Админ и менеджер удаляют скидки"
    ON discount_vouchers
    FOR DELETE
    TO authenticated
    USING (
        EXISTS (
            SELECT 1 FROM profiles
             WHERE id = auth.uid()
               AND role IN ('admin', 'manager')
        )
    );

-- Проверка: какие правила стоят на скидках
SELECT cmd AS операция, policyname AS правило, roles AS роли
FROM pg_policies
WHERE tablename = 'discount_vouchers'
ORDER BY cmd, policyname;
