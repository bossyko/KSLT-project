-- файле — ЛАТИНИЦЕЙ. В базе имена русские, и латинское `azat` с русским
-- `азат` не совпадает ни одной буквой для машины. ПРИБОР, ИЩУЩИЙ В ОДНОМ
-- АЛФАВИТЕ, НЕ НАХОДИТ В ДРУГОМ — и молчание того запроса про Азата
-- ничего не доказывало.
-- Слово Кости 04.11: это «Азат Кубанычбек уулу».
--
-- Двое других уже искались по-русски и не нашлись; здесь они повторно, по
-- КАЖДОМУ слову отдельно, чтобы «не нашлось» значило «не нашлось».

WITH искомые(кто, слово) AS (VALUES
    ('Азат Кубанычбек уулу', 'азат'),
    ('Азат Кубанычбек уулу', 'кубанычбек'),
    ('Даниил Орлов',         'даниил'),
    ('Даниил Орлов',         'орлов'),
    ('Самат Кожобаев',       'самат'),
    ('Самат Кожобаев',       'кожобаев')
),
слова_базы AS (
    SELECT p.id, p.name, p.gender, p.category_id, p.ntrp_singles, p.is_guest,
           с AS слово
      FROM public.players p,
           unnest(regexp_split_to_array(
               translate(lower(regexp_replace(btrim(p.name), '[^[:alnum:]]+', ' ', 'g')),
                         'ё', 'е'),
               ' ')) AS с
     WHERE length(с) >= 4
)
SELECT и.кто               AS kogo_ishchem,
       и.слово             AS po_slovu,
       б.id                AS kandidat,
       б.name              AS imya_v_baze,
       б.gender            AS pol,
       б.category_id       AS razryad,
       б.ntrp_singles      AS ntrp,
       б.is_guest          AS gost
  FROM искомые и
  LEFT JOIN слова_базы б ON б.слово = и.слово
 ORDER BY и.кто, и.слово, б.name;
