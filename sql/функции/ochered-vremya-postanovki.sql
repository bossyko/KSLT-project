-- ============================================================
-- Порядок очереди — по времени постановки в неё, а не подачи
-- ============================================================
--
-- ЧТО СЛОМАНО. Прогон 01.10 на турнире ec46a732 (8 мест, 8 в основе,
-- 4 в очереди). Менеджер жмёт «Снять» у S03. Окно обещает: «Место
-- освободится и достанется первому в очереди». После нажатия в базе
-- НЕ МЕНЯЕТСЯ НИЧЕГО: 8 approved / 4 waitlist, S03 на месте, W1 как
-- ждал, так и ждёт. Ни ошибки, ни следа.
--
-- ПОЧЕМУ. «Снять» ставит `waitlist` (bracket.js:1057) и тут же зовёт
-- `поднятьИзОчереди` (bracket.js:1060). Та берёт из очереди первого по
-- `registered_at` (bracket.js:818). У снятого время подачи 16:54:26, у
-- первого ждуна W1 — 16:54:50. Снятый оказывается первым в очереди и
-- возвращается в основу.
--
-- Снятый обгоняет очередь ВСЕГДА: он подавал заявку раньше тех, кто в
-- основу не попал. Беда срабатывает каждый раз.
--
-- «Отклонить» при этом работает верно: статус `rejected` в очередь не
-- попадает, и подъём берёт настоящего первого. Проверено на S04 —
-- поднялся W1. Механизм подъёма исправен, беда ровно в «Снять».
--
-- КАК ПРАВИЛЬНО. ITF/ATP: список альтернатов упорядочен тем, кто раньше
-- в нём оказался. Игрок, освободивший место в основе, возвращается в
-- альтернаты — но НЕ впереди тех, кто всё это время ждал: своё место он
-- уже получал. Значит снятый встаёт в КОНЕЦ очереди.
--
-- ЧЕМ ЧИНИМ. `registered_at` — факт подачи заявки, его переписывать
-- нельзя. `withdrawn_at` — время самоснятия игроком, другое понятие;
-- совать туда второй смысл значит завести шов, на котором родится
-- следующая беда.
--
-- Поэтому два столбца:
--   `waitlisted_at` — когда заявка попала в очередь. Пусто у тех, кто
--                     в очереди с самой подачи.
--   `queue_at`      — ОДНО ОПРЕДЕЛЕНИЕ ПОРЯДКА ОЧЕРЕДИ, считается базой:
--                     `COALESCE(waitlisted_at, registered_at)`.
--
-- Порядок очереди больше нельзя выразить двумя способами: кто бы ни
-- сортировал — админка, сервер заявок, приложение — он сортирует по
-- `queue_at`, и второго правила не заводит.
--
-- СТАРЫЕ ОЧЕРЕДИ НЕ ТРОГАЕМ. У всех существующих заявок `waitlisted_at`
-- пуст, значит `queue_at` равен `registered_at` — нынешний порядок
-- сохраняется до байта. Ничей порядок не переставляется задним числом.
--
-- Файл меняет базу. Проверка — в `ochered-vremya-postanovki-proverka.sql`.
-- Запускать можно повторно.

BEGIN;

-- 1. Когда заявка встала в очередь
ALTER TABLE public.tournament_registrations
    ADD COLUMN IF NOT EXISTS waitlisted_at timestamptz;

COMMENT ON COLUMN public.tournament_registrations.waitlisted_at IS
    'Когда заявка попала в лист ожидания. Пусто у тех, кто в очереди с подачи. Снятый с основы получает его на момент снятия и встаёт в конец.';

-- 2. Порядок очереди — считает база, а не каждый, кто сортирует
ALTER TABLE public.tournament_registrations
    ADD COLUMN IF NOT EXISTS queue_at timestamptz
    GENERATED ALWAYS AS (COALESCE(waitlisted_at, registered_at)) STORED;

COMMENT ON COLUMN public.tournament_registrations.queue_at IS
    'Порядок в листе ожидания: время постановки в очередь, а где его нет — время подачи. Считается базой. Сортировать очередь ТОЛЬКО по нему.';

-- 3. Очередь читают при каждом снятии и отказе — индекс по тому, как её и спрашивают
CREATE INDEX IF NOT EXISTS tournament_registrations_queue_idx
    ON public.tournament_registrations (tournament_id, seat_pool, queue_at)
    WHERE status = 'waitlist';

COMMIT;
