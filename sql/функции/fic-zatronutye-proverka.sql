-- ============================================================
-- Зависимые матчи — ПРОВЕРКА
-- ============================================================
--
-- Только читает. Берём первый сыгранный матч сетки микст-турнира и
-- смотрим, что функция считает зависимым от него.
--
-- Ожидаем: только клетки сетки дальше по ходу (четвертьфинал, полуфинал,
-- финал). Групповых встреч и доп. матчей в выдаче быть не должно.

WITH исходный AS (
    SELECT id, round, match_order
      FROM public.matches
     WHERE tournament_id = 'c0a30bae-30ee-4a38-a26a-4c6b339bd695'
       AND group_number IS NULL
       AND round = 'R1'
     ORDER BY match_order
     LIMIT 1
)
SELECT и.round || '-' || и.match_order   AS правим,
       з.круг || '-' || з.номер          AS зависит,
       з.игрок_1 || ' — ' || з.игрок_2   AS пара,
       COALESCE(з.счёт, '—')             AS счёт,
       m.round                           AS вид
  FROM исходный и
  CROSS JOIN LATERAL public.fic_затронутые(и.id) з
  JOIN public.matches m ON m.id = з.id
 ORDER BY з.круг, з.номер;
