-- ============================================================
-- Старые сборки приложения снова могут сохранять профиль
-- ============================================================
--
-- Мы свели словарь пола к двум словам — men и women — и поставили в базе
-- запрет на прочие значения. Сайт и свежее приложение с тех пор шлют
-- правильные слова.
--
-- Но установленное приложение живёт своей жизнью: у человека на телефоне
-- сборка от августа, и она шлёт male и female, как было раньше. Запрет её
-- отбивает, и профиль просто не сохраняется. Человек видит «не удалось» и
-- не понимает, что делать — обновиться ему никто не предлагал.
--
-- Заставлять всех обновиться нельзя: приложение ставится файлом, и часть
-- людей так и останется на старом. Поэтому база сама переводит старые
-- слова в новые — молча, до проверки запрета.
--
-- Файл меняет базу. Читающие запросы — в gender-accept-old-words-check.sql.

BEGIN;

CREATE OR REPLACE FUNCTION public.перевести_пол()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.gender = 'male'   THEN NEW.gender := 'men';   END IF;
    IF NEW.gender = 'female' THEN NEW.gender := 'women'; END IF;
    -- Пустую строку старые сборки шлют, когда пол не выбран
    IF NEW.gender = ''       THEN NEW.gender := NULL;    END IF;
    RETURN NEW;
END;
$$;

COMMENT ON FUNCTION public.перевести_пол() IS
    'Старые сборки приложения шлют male/female. Переводим в men/women до проверки запрета, иначе у них не сохраняется профиль.';

DROP TRIGGER IF EXISTS trg_перевести_пол ON public.profiles;
CREATE TRIGGER trg_перевести_пол
    BEFORE INSERT OR UPDATE OF gender ON public.profiles
    FOR EACH ROW
    EXECUTE FUNCTION public.перевести_пол();

COMMIT;
