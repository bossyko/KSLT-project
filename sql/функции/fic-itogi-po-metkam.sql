-- ============================================================
-- Клетка, которая ждёт человека по метке, — не проход без игры
-- ============================================================
--
-- Плей-офф теперь собирается пустым сразу после жеребьёвки групп: в клетках
-- стоят метки — «A1» победитель группы A, «IG2» победитель второго доп.
-- матча. Люди приезжают позже, по мере того как группы доигрывают.
--
-- А счёт клеток остался прежним: он смотрел только на вписанных игроков.
-- Пока соседняя группа в игре, в клетке стоит один человек — и функция
-- считала её проходом без игры, закрывала матч и уводила победителя дальше.
-- Когда группа доигрывала, второй участник вписывался в уже закрытый матч:
-- в сетке стояла живая пара со счётом BYE и победителем, который не играл.
--
-- На микст-Futures 19.09 так закрылись шесть матчей 1/8 из восьми.
--
-- Лечение: клетка с меткой считается ожидающей человека. Настоящие проходы
-- метку не имеют вовсе — их так и создают, пустыми, поэтому они закроются
-- как прежде.
--
-- Тот же счёт делает браузер в js/bracket-draw.js — там поправлено заодно.
--
-- Запускать можно повторно.

BEGIN;

CREATE OR REPLACE FUNCTION public.fic_итоги(p_турнир text)
RETURNS TABLE(круг integer, номер integer, итог integer)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_сетка  integer;
    v_кругов integer;
    v_вкруге integer;
    v_круг   integer;
    v_ном    integer;
    v_куда   integer;
    v_итог   integer[];
    м        record;
BEGIN
    -- Сколько человек окажется в каждой клетке. Один счёт на всю сетку, из
    -- которого выводится всё: есть ли клетка вообще (итог 0), проход это
    -- (итог 1) или настоящая пара (итог 2).
    --
    -- Считаем от первого круга вперёд. В первом круге — сколько вписано
    -- жребием и сколько ещё приедет по меткам. Дальше победитель приедет из
    -- любой клетки, где в итоге будет хоть один, а проигравший — только из
    -- той, где будет двое: у прохода без игры проигравшего не бывает.
    --
    -- Считаем в памяти, без временных таблиц: функция зовётся сама из себя
    -- через триггер, а временная таблица одна на сеанс — вторая попытка её
    -- создать падала с ошибкой.

    SELECT count(*) * 2 INTO v_сетка FROM matches
     WHERE tournament_id = p_турнир AND round_number = 1;
    IF v_сетка IS NULL OR v_сетка < 2 THEN RETURN; END IF;
    v_кругов := log(2, v_сетка::numeric)::int;
    v_вкруге := v_сетка / 2;

    v_итог := array_fill(0, ARRAY[v_кругов, v_вкруге]);

    FOR м IN SELECT match_order, player1_id, player2_id, slot1_label, slot2_label
               FROM matches
              WHERE tournament_id = p_турнир AND round_number = 1
    LOOP
        -- Метка — обещание человека: он приедет, когда доиграет его группа
        -- или доп. матч. Такая клетка ждёт, а не закрывается проходом
        v_итог[1][м.match_order] :=
            (CASE WHEN м.player1_id IS NOT NULL OR м.slot1_label IS NOT NULL THEN 1 ELSE 0 END)
          + (CASE WHEN м.player2_id IS NOT NULL OR м.slot2_label IS NOT NULL THEN 1 ELSE 0 END);
    END LOOP;

    FOR v_круг IN 2..v_кругов LOOP
        FOR v_ном IN 1..v_вкруге LOOP
            IF v_итог[v_круг - 1][v_ном] >= 1 THEN
                v_куда := public.fic_адрес(v_сетка, v_круг - 1, v_ном, true);
                IF v_куда IS NOT NULL THEN
                    v_итог[v_круг][v_куда] := v_итог[v_круг][v_куда] + 1;
                END IF;
            END IF;
            IF v_итог[v_круг - 1][v_ном] >= 2 THEN
                v_куда := public.fic_адрес(v_сетка, v_круг - 1, v_ном, false);
                IF v_куда IS NOT NULL THEN
                    v_итог[v_круг][v_куда] := v_итог[v_круг][v_куда] + 1;
                END IF;
            END IF;
        END LOOP;
    END LOOP;

    FOR v_круг IN 1..v_кругов LOOP
        FOR v_ном IN 1..v_вкруге LOOP
            круг := v_круг; номер := v_ном; итог := v_итог[v_круг][v_ном];
            RETURN NEXT;
        END LOOP;
    END LOOP;
END;
$$;

COMMENT ON FUNCTION public.fic_итоги(text) IS
    'Сколько человек окажется в каждой клетке: 0 — клетки нет, 1 — проход, 2 — пара. Метка в слоте считается за человека: он приедет позже. Единственный счёт, по которому решают и закрытие проходов, и пересборка.';

COMMIT;

-- ---- Проверка ----
--
-- Ложные проходы: живая пара со счётом BYE. После пересборки сетки таких
-- быть не должно.

SELECT t.title AS турнир,
       count(*) AS ложных_проходов
  FROM public.matches m
  JOIN public.tournaments t ON t.id = m.tournament_id
 WHERE m.score = 'BYE'
   AND m.player1_id IS NOT NULL
   AND m.player2_id IS NOT NULL
 GROUP BY t.title
 ORDER BY 2 DESC;
