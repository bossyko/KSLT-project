const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ПРАВИЛА  = чит('js/kslt-rules.js');
const ПРАВч    = безКом(ПРАВИЛА);
const ПРАВМОБ  = чит('mobile/www/js/kslt-rules.js');
const СЕТКА    = чит('js/admin/sections/bracket.js');
const СЕТч     = безКом(СЕТКА);
const ЗАГЛУШКА = чит('maket/progon-zaglushka.js');
const ЗАГч     = безКом(ЗАГЛУШКА);
const ДВИЖОК   = чит('maket/progon-dvizhok.js');
const ДВИЖч    = безКом(ДВИЖОК);
const СТЕНДПР  = чит('maket/progon-cepochki.html');
const СТРАНИЦА = чит('pages/admin.html');
const ПОДПИСИ  = чит('js/admin/core/constants.js');
const ПОДч     = безКом(ПОДПИСИ);

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

function тело(текст, имя) {
    const i = текст.indexOf('function ' + имя + '(');
    if (i === -1) return '';
    let гл = 0, j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}
const телоПрисвоения = (текст, имя) => {
    const i = текст.indexOf(имя + ' = function');
    if (i === -1) return '';
    let гл = 0, j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
};

/* ─────────── ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ ─────────── */

правило('список букв групп объявлен ровно один раз, и он в правилах',
    (ПРАВч.match(/R\.БУКВЫ_ГРУПП\s*=\s*\[/g) || []).length === 1,
    'алфавит групп снова объявлен не единожды — беда родится ровно на шве, как она и родилась');

правило('в сетке не осталось собственного списка букв',
    !/\[\s*'A',\s*'B',\s*'C'/.test(СЕТч) && !/var\s+букв\s*=/.test(СЕТч),
    'в bracket.js вернулась своя копия алфавита — четыре копии уже расходились запасными вариантами');

/* СПОСОБ ПОЛУЧИТЬ БУКВУ ЕСТЬ ОДИН. Считать вхождения бессмысленно: мест
   становится больше, и порог из числа стареет. Стережём ОТНОШЕНИЕ — что
   букву не строят никаким другим способом. */
var СВОИ_СПОСОБЫ = [
    /fromCharCode\(\s*64\s*\+/,            // 'A' + номер
    /charCodeAt\(0\)\s*-\s*64/,             // буква → номер
    /'ABCDEFGH/, /"ABCDEFGH/,                // строковый алфавит
    /\[\s*'A',\s*'B',\s*'C'/               // массив букв
];
var живыеФайлы = [СЕТч, безКом(чит('js/tournament-detail.js')),
                  безКом(чит('js/tournament-generator.js')),
                  безКом(чит('mobile/www/js/screens/home.js'))];

правило('букву никто не строит сам — только общей таблицей',
    живыеФайлы.every(function(т) { return СВОИ_СПОСОБЫ.every(function(р) { return !р.test(т); }); }) &&
    /KSLT_RULES\.букваГруппы\(/.test(СЕТч),
    'где-то снова строят букву своим способом — алфавит разъедется с таблицей, ' +
    'а занятые I и Q вернутся в метки');

/* ─────────── ЗАНЯТЫЕ БУКВЫ ─────────── */

правило('в алфавите групп нет I — она занята доп. матчем',
    !/'I'/.test(ПРАВч.slice(ПРАВч.indexOf('R.БУКВЫ_ГРУПП'), ПРАВч.indexOf('R.букваГруппы'))),
    'буква I вернулась в алфавит групп, а метка доп. матча начинается с IG — метки станут неразличимы');

правило('в алфавите групп нет Q — она занята добором',
    !/'Q'/.test(ПРАВч.slice(ПРАВч.indexOf('R.БУКВЫ_ГРУПП'), ПРАВч.indexOf('R.букваГруппы'))),
    'буква Q вернулась в алфавит групп, а Q1 это добор — группа 17 отберёт метку у претендента');

/* ─────────── ЗАПАСНОГО ВАРИАНТА НЕТ ─────────── */

правило('буква вне таблицы — это отказ, а не число',
    /return null;/.test(телоПрисвоения(ПРАВч, 'R.букваГруппы')) &&
    !/\|\|\s*номер/.test(телоПрисвоения(ПРАВч, 'R.букваГруппы')),
    'у перевода номера в букву появился запасной вариант — молчаливое число и было бедой');

правило('обратный перевод идёт по той же таблице, а не по коду буквы',
    /indexOf\(/.test(телоПрисвоения(ПРАВч, 'R.группаПоБукве')) &&
    !/charCodeAt/.test(телоПрисвоения(ПРАВч, 'R.группаПоБукве')),
    'обратный перевод снова считает код буквы — после выкидывания I и Q он разойдётся с номером группы');

правило('в сетке не осталось перевода буквы через код',
    !/charCodeAt\(0\)\s*-\s*64/.test(СЕТч),
    'в bracket.js вернулся charCodeAt(0) - 64 — это верно только для сплошного алфавита');

/* ─────────── СУДЬЯ ЗНАЕТ ПРО ГРАНИЦУ ─────────── */

правило('судья настроек ограничивает число групп длиной алфавита',
    /г\s*>\s*R\.БУКВЫ_ГРУПП\.length/.test(телоПрисвоения(ПРАВч, 'R.бедаНастройкиГрупп')),
    'верхняя граница числа групп пропала — на двадцать пятой группе метка снова станет «null1»');

правило('у отказа «групп много» есть слова, а не код',
    /'групп_много':/.test(безКом(чит('js/admin/core/constants.js')) + СЕТч) ||
    /'групп_много':/.test(СЕТч),
    'код групп_много вернётся менеджеру как есть, без объяснения');

правило('граница названа числом из таблицы в ОБОИХ языках',
    (СЕТч.match(/KSLT_RULES\.БУКВЫ_ГРУПП\.length/g) || []).length >= 2,
    'в сообщении зашито число вместо длины таблицы — разойдутся при первой же правке алфавита');

/* ─────────── ДВЕ КОПИИ ПРАВИЛ СОВПАДАЮТ ─────────── */

правило('копии kslt-rules.js в js/ и mobile/www/js/ совпадают',
    ПРАВИЛА === ПРАВМОБ,
    'копии правил разошлись — приложение и сайт станут считать по-разному');

/* ─────────── ПРОГОН: ПРИБОР НЕ УГАДЫВАЕТ ─────────── */

правило('заглушка базы падает на непредусмотренной форме запроса',
    /throw new Error/.test(тело(ЗАГч, 'обёртка')) &&
    (тело(ЗАГч, 'обёртка').match(/return о;/g) || []).length === 1 &&
    /заглушка базы не умеет/.test(ЗАГЛУШКА),
    'сторож заглушки обойдён ранним возвратом или снят — прогон начнёт проверять выдумку вместо продукта');

правило('обещание заглушка не оборачивает',
    /instanceof Promise\) return о;/.test(ЗАГч),
    'Proxy вернулся на Promise — then перестанет работать, и прогон замолчит целиком');

правило('прогон зовёт настоящие функции этапов',
    /A\.прогон\s*=\s*\{/.test(СЕТч) &&
    /жеребьёвкаГрупп:\s*generateGroupDraw/.test(СЕТч) &&
    /пересчитать:\s*пересчитатьСоставСетки/.test(СЕТч) &&
    /дубли:\s*дублиВСетке/.test(СЕТч),
    'прогон отвязался от настоящих функций — он будет проверять пересказ');

правило('прогон берёт номер группы у продукта, а не своей шкалой',
    /KSLT_RULES\.группаПоБукве/.test(ДВИЖч) && !/\[A-H\]/.test(ДВИЖч),
    'в движке прогона вернулась своя буквенная шкала — она уже один раз обвинила продукт в том, чего не было');

правило('годные настройки перечисляет судья продукта',
    /KSLT_RULES\.бедаНастройкиГрупп/.test(ДВИЖч),
    'прогон снова перечисляет настройки сам — проверит свой список, а не продуктовый');

правило('жребий прогона засеян',
    /Math\.random\s*=\s*function/.test(ЗАГч) && /зерно/.test(ЗАГч),
    'жребий расзасеян — падение перестанет повторяться, и разбирать его будет нечем');

правило('прогон проверяет все четыре пункта',
    /пара встречается дважды/.test(ДВИЖОК) &&
    /стоит дважды в одном туре/.test(ДВИЖОК) &&
    /получила имя раньше своей группы/.test(ДВИЖОК) &&
    /после ручной перестановки появился дубль/.test(ДВИЖОК),
    'из прогона выпала одна из четырёх проверок — а спрашивали именно про них');

правило('дубль в сетке проверяется на КАЖДОМ шаге, а не в конце',
    /for \(var k = 0; k < групповые\.length/.test(ДВИЖч) &&
    /A\.прогон\.дубли\(все\)/.test(ДВИЖч),
    'проверка дубля уехала из цикла — беду увидят только в конце, если увидят');

/* ─────────── УЧАСТНИК БЕЗ ЛИЧНОСТИ НЕ УЧАСТВУЕТ ─────────── */

правило('сторож «нет карточки игрока» стоит в двери менеджера',
    /var безКарточки = approved\.filter\(/.test(тело(СЕТч, 'генерироватьСетку')),
    'сторож гостей ушёл из `генерироватьСетку` — вся цепочка ключуется по player_id, ' +
    'и все гости станут для продукта одним человеком');

правило('отказ громкий и до жеребьёвки, а не тихий расчёт после',
    /if \(безКарточки\.length\) \{[\s\S]{0,400}?A\.showNotice[\s\S]{0,400}?return;/.test(тело(СЕТч, 'генерироватьСетку')),
    'отказ перестал останавливать жеребьёвку — беда снова станет молчаливой');

правило('отказ назван словами на обоих языках',
    (ПОДч.match(/drawNoCardTitle:/g) || []).length === 2 &&
    (ПОДч.match(/drawNoCardHint:/g) || []).length === 2,
    'подписи отказа пропали или остались на одном языке');

правило('прогон ходит в дверь менеджера, а не мимо неё',
    /сеткуЦеликом:\s*генерироватьСетку/.test(СЕТч) &&
    /A\.прогон\.сеткуЦеликом\(/.test(ДВИЖч),
    'прогон снова зовёт `generateGroupDraw` напрямую — он пройдёт мимо всех проверок, ' +
    'что стоят ДО жеребьёвки, и проверит не тот путь');

/* ─────────── ВЕРСИИ ─────────── */

правило('версии подняты — иначе правка не доедет до того, у кого файл в кеше',
    /kslt-rules\.js\?v=(2[3-9]|[3-9]\d)/.test(СТРАНИЦА) &&
    /sections\/bracket\.js\?v=(21[3-9]|2[2-9]\d|[3-9]\d\d)/.test(СТРАНИЦА) &&
    /sections\/bracket\.js\?v=(21[3-9]|2[2-9]\d|[3-9]\d\d)/.test(СТЕНДПР),
    'версия kslt-rules.js или bracket.js не поднята после правки');

