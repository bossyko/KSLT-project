/**
 * ЗАМОРОЗКА «ССЫЛКИ ВМЕСТО DIV» (кусок 69, 13.10.2026).
 *
 * Карточка, которая ведёт на страницу, обязана БЫТЬ ссылкой. Померено 13.10:
 * на поиске игрока девять карточек были `div` с обработчиком, фокусируемых
 * внутри ОДИН (кнопка «Пригласить»), ссылок ноль — ни новой вкладки, ни
 * клавиатуры, ни диктора, ни поисковика.
 *
 * ПРИЁМ НЕ НОВЫЙ И ЗДЕСЬ НЕ ПЕРЕОТКРЫВАЕТСЯ. Решение 04.10: слой-ссылка
 * прямым ребёнком карточки, растянутый на неё. Обёртка невозможна — внутри
 * карточек живут свои кнопки, а кнопка внутри ссылки недопустима.
 *
 * ГЛАВНОЕ ЗДЕСЬ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • слой лежит ВЫШЕ содержимого, иначе содержимое его съедает;
 *   • своё действие лежит ВЫШЕ слоя, иначе слой съедает его;
 *   • переход у карточки РОВНО ОДИН: либо слой, либо видимая ссылка;
 *   • обработчик больше не уводит оттуда, где есть слой;
 *   • слой собирает ОДИН общий сборщик, и рукописных копий счётное число.
 *
 *   node tools/check-ssylki-kartochek.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СБОРЩИК = безКом(чит('js/kslt-sloy.js'));
const ПОИСК   = безКом(чит('js/partners.js'));
const ОБЗБ    = безКом(чит('js/battles-overview.js'));
const КАРТБ   = безКом(чит('js/battle-cards.js'));
const КРУПТ   = безКом(чит('js/tournament-featured.js'));

const CSS_П = безКом(чит('css/partners.css'));
const CSS_Б = безКом(чит('css/battles-overview.css'));
const CSS_К = безКом(чит('css/battle-cards.css'));
const CSS_Т = безКом(чит('css/tournaments-overview.css'));
const CSS_У = безКом(чит('css/services.css'));

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };
const скобка = (текст, сел) => {
    const м = текст.match(new RegExp('(?:^|\\n)' + сел.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{'));
    if (!м) return '';
    const i = м.index + 1;
    return текст.slice(i, текст.indexOf('}', i));
};
const сколько = (текст, ре) => (текст.match(ре) || []).length;
const z = блок => { const м = блок.match(/z-index:\s*(\d+)/); return м ? Number(м[1]) : null; };

/* ══ ОДИН СБОРЩИК НА ВЕСЬ САЙТ ══════════════════════════════════════════ */

правило('общий сборщик слоя существует и отдаёт ссылку с именем',
    /window\.KSLT_SLOY\s*=/.test(СБОРЩИК) &&
    /function слой\(класс, href, имя\)/.test(СБОРЩИК) &&
    /<a class="/.test(СБОРЩИК) && /aria-label="/.test(СБОРЩИК),
    'пустая ссылка диктору не говорит ничего: имя карточки уходит в\n' +
    'aria-label, а видимый заголовок остаётся заголовком');

правило('сборщик экранирует всё, что в него кладут',
    /function экр\(/.test(СБОРЩИК) && /экр\(класс\)/.test(СБОРЩИК) &&
    /экр\(href\)/.test(СБОРЩИК) && /экр\(имя\)/.test(СБОРЩИК),
    'в aria-label уходит имя игрока из базы, в href — адрес с номером');

правило('четыре семьи карточек зовут общий сборщик',
    /KSLT_SLOY\.слой\('pt-card-cover'/.test(ПОИСК) &&
    /KSLT_SLOY\.слой\('bo-featured-cover'/.test(ОБЗБ) &&
    /KSLT_SLOY\.слой\('bc-card-cover'/.test(КАРТБ) &&
    /KSLT_SLOY\.слой\('to-featured-cover'/.test(КРУПТ),
    'слой пишется в одном месте, а не заново в каждом файле');

/* СТОРОЖ НА РУКОПИСНУЮ КОПИЮ. ХРАПОВИК ОПУЩЕН 21.10 С ДВУХ ДО ОДНОЙ:
   копия в `tournament-featured.js` сведена на дом `KSLT_SLOY.слой` — она
   повторяла его побайтово и несла СВОЁ экранирование, не гасившее
   одинарную кавычку. Осталась одна, в «Услугах», и её держит заморозка
   закрытого куска. Вторая такая — повод позвать сборщик, а не писать
   строку заново.
   Правило упало от моей же правки и было ПРАВО: снижение обязано опускать
   потолок вместе с собой, иначе храповик перестаёт держать достигнутое. */
const рукописных =
    sum('js/services.js') + sum('js/tournament-featured.js') +
    sum('js/partners.js') + sum('js/battles-overview.js') +
    sum('js/battle-cards.js') + sum('js/tournaments-overview.js') +
    sum('js/home-partners.js') + sum('js/players.js') + sum('js/tournament-blocks.js');

function sum(ф) { return сколько(безКом(чит(ф)), /<a class="[a-z-]*cover"/g); }

правило('рукописный сборщик слоя ровно один, и он старше общего',
    рукописных === 1,
    'сейчас найдено: ' + рукописных + ' (потолок 1). Второй — это второе\n' +
    'определение одного понятия, и беда родится ровно на шве. Если стало\n' +
    'МЕНЬШЕ — опусти потолок вместе со снижением.');

/* ══ ПОРЯДОК СЛОЁВ — ОТНОШЕНИЕМ, А НЕ ЧИСЛОМ ═══════════════════════════ */

const семьи = [
    ['поиск игрока',        CSS_П, '.pt-card-link > *',        '.pt-card-link > .pt-card-cover',       '.pt-card .pt-invite-btn'],
    /* У крупного баттла содержимое — это ФОН: короб `.bo-featured-content`
       нарочно БЕЗ z-index (см. правило о слое наложения ниже), иначе своё
       действие внутри него не всплывает над слоем. 17.10. */
    ['крупный баттл',       CSS_Б, '.bo-featured > .bo-featured-bg', '.bo-featured > .bo-featured-cover', '.bo-featured .bo-meta-venue'],
    ['карточка баттла',     CSS_К, '.bc-card > .bc-card-inner,\n.bc-card > .bc-banner',                '.bc-card > .bc-card-cover',            null],
    ['крупный турнир',      CSS_Т, '.to-featured > .to-featured-bg,\n.to-featured > .to-featured-overlay,\n.to-featured > .to-featured-content', '.to-featured > .to-featured-cover', null],
    ['игрок на «Услугах»',  CSS_У, '.sv-player > *',           '.sv-player > .sv-player-cover',        '.sv-player > .sv-player-btn']
];

семьи.forEach(([имя, css, содержимое, слой, действие]) => {
    const бС = скобка(css, содержимое), бСл = скобка(css, слой);
    правило('слой лежит ВЫШЕ содержимого: ' + имя,
        z(бСл) !== null && z(бС) !== null && z(бСл) > z(бС),
        'СОДЕРЖИМОЕ СЪЕДАЕТ СЛОЙ, ЕСЛИ СЛОЙ ПОД НИМ. Правило выведено 04.10\n' +
        'на полосе турнира и подтверждено замером 13.10 на «Услугах», где\n' +
        'слой стоял z-index 0: нажатие на фотографию попадало в IMG, на имя —\n' +
        'в DIV, и ссылка срабатывала только на пустых полях карточки');

    правило('слой растянут на карточку, а не на своё содержимое: ' + имя,
        /position:\s*absolute/.test(бСл) && /inset:\s*0/.test(бСл),
        'слой без inset лежит в углу и накрывает несколько пикселей');

    правило('у слоя виден фокус с клавиатуры: ' + имя,
        new RegExp(слой.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + ':focus-visible')
            .test(css.replace(/\n/g, '\n')),
        'слой — единственное, что берёт фокус в карточке. Без кольца человек\n' +
        'не видит, что выбрал');

    if (действие) {
        правило('своё действие лежит ВЫШЕ слоя: ' + имя,
            z(скобка(css, действие)) > z(бСл),
            'иначе слой съедает кнопку: нажатие на «Пригласить» уводило бы\n' +
            'на страницу игрока');
    }
});

/* ══ КОРОБ СОДЕРЖИМОГО НЕ ЗАВОДИТ СВОЕГО СЛОЯ НАЛОЖЕНИЯ ═════════════════
   НАЙДЕНО ПРОБОЙ 17.10, И ЭТО БЫЛА НАСТОЯЩАЯ БЕДА: у крупного баттла
   `.bo-featured-content` был объявлен ДВАЖДЫ — с z-index 1 и с z-index 2,
   — побеждало то, что точнее, и короб заводил свой слой наложения.
   Внутри него `z-index: 3` у места и кнопки голоса считался СРЕДИ СВОИХ:
   они стояли третьими в коробе, а весь короб лежал под слоем-ссылкой.
   Место перестало нажиматься, окно карты не открывалось вовсе.
   След прогона сказал прямо: «<a class="bo-featured-cover"> intercepts
   pointer events».
   ОТНОШЕНИЕ, КОТОРОЕ ЗАМОРОЖЕНО: если внутри короба живёт СВОЁ ДЕЙСТВИЕ,
   короб обязан оставаться без z-index — иначе действие заперто в нём. */
const коробаСДействием = [
    ['крупный баттл', CSS_Б, '.bo-featured-content']
];
коробаСДействием.forEach(([имя, css, короб]) => {
    const все = css.split('\n').join('\n');
    const куски = [];
    const ре = new RegExp('(^|\\})\\s*[^{}]*' + короб.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') +
                          '\\s*\\{([^{}]*)\\}', 'g');
    let м;
    while ((м = ре.exec(все))) куски.push(м[2]);
    правило('короб содержимого не заводит своего слоя наложения: ' + имя,
        куски.length > 0 && куски.every(к => !/z-index:/.test(к)),
        'Найдено объявлений короба: ' + куски.length + ', с z-index: ' +
        куски.filter(к => /z-index:/.test(к)).length + '.\n' +
        'Короб с z-index запирает в себе своё действие: `z-index: 3` у места\n' +
        'считается среди соседей по коробу, а короб целиком уходит под слой.');
});

/* ══ ПЕРЕХОД РОВНО ОДИН ═════════════════════════════════════════════════ */

правило('у крупной карточки баттла переход один: надпись, а не вторая ссылка',
    /<span class="bo-featured-link"/.test(ОБЗБ) &&
    !/<a class="bo-featured-link" href="/.test(ОБЗБ),
    'две ссылки на один адрес внутри одной карточки диктор читает дважды');

правило('у карточки баттла переход один: надпись, а не вторая ссылка',
    /<span class="bc-details-link"/.test(КАРТБ) &&
    !/<a href="' \+ detailUrl\(battle\.id\) \+ '" class="bc-details-link"/.test(КАРТБ),
    'то же самое на второй карточке баттла');

правило('обработчик больше не уводит с крупной карточки баттла',
    !/window\.location\.href = card\.dataset\.href/.test(ОБЗБ),
    'переход несёт слой-ссылка; обработчику остались свои действия карточки');

правило('крупная карточка турнира не несёт адреса атрибутом',
    !/data-href="' \+ esc\(t\.href\)/.test(КРУПТ),
    'адрес в data-href — это переход, которого не видит ни клавиатура, ни\n' +
    'поисковик: его делал общий bindLinks');

правило('обработчик карточки баттла уводит только без общего сборщика',
    /if \(!window\.KSLT_SLOY\) window\.location\.href = detailUrl/.test(КАРТБ),
    'страховка на случай, когда модуль не подключён, — но не второй способ\n' +
    'перехода при подключённом');

правило('инлайнового cursor в разметке поиска не осталось',
    !/style="cursor:pointer;"/.test(ПОИСК) &&
    /cursor:\s*pointer/.test(скобка(CSS_П, '.pt-card')),
    'оформление живёт в файле стилей, а не в атрибуте');

/* ══ ГОСТЬ ══════════════════════════════════════════════════════════════ */

правило('гостю слоя не дают: карточка открывает окно, а не профиль',
    /_accessLevel !== 'guest' && window\.KSLT_SLOY/.test(ПОИСК) &&
    /_accessLevel === 'guest' && window\.KSLT_INVITE/.test(ПОИСК),
    'на странице профиля гостя ждёт только замок, а вернувшись, он теряет\n' +
    'место в списке. Ссылки, которая никуда не ведёт, на экране не бывает');

правило('класс слоя вешается только вместе со слоем',
    /\(слой \? ' pt-card-link' : ''\)/.test(ПОИСК) &&
    /\.pt-card-link > \./.test(CSS_П),
    'правила порядка слоёв висят на .pt-card-link, а не на .pt-card: у\n' +
    'гостевой карточки слоя нет, и поднимать ей нечего');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      ссылки вместо div: 26 правил, шесть семей карточек');
    console.log('          слой выше содержимого   ·   действие выше слоя');
    console.log('          переход ровно один   ·   рукописных сборщиков ' + рукописных);
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  ссылки вместо div — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
