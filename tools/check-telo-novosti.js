/**
 * ТЕЛО НОВОСТИ — ОДНО ОПРЕДЕЛЕНИЕ НА ТРИ ЭКРАНА. Круг 11 ветки D, 18.10.
 *
 * ЧТО БЫЛО. Тело статьи определено ТРИЖДЫ: `.news-html` (читатель),
 * `.ad-news-preview-body` (предпросмотр админки), `.ad-editor-area`
 * (редактор). Предпросмотр — экран, назначение которого показать правду, —
 * ВРАЛ автору. Замерено стендом `maket/telo-novosti-zamer.html`: десять
 * свойств расходились с читателем, и среди них заголовок в тексте —
 * у читателя 21px белый, в предпросмотре 16px лаймовый. Автор верстал
 * новость по ложной картинке.
 *
 * ЭТАЛОН УЖЕ БЫЛ В КОДЕ: `css/news.css` подключён в `pages/admin.html`, и
 * элемент носит ОБА класса (`news-html ad-news-preview-body`). Правда
 * приходила и перебивалась. Блок предпросмотра снесён целиком; разметка не
 * тронута — класс `news-html` уже стоял.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ, А НЕ ЧИСЛА. Не «заголовок 21px», а:
 * предпросмотр НЕ объявляет уровни текста заново, и элемент предпросмотра
 * НЕСЁТ класс читателя. Числа решает `news.css`; правило требует, чтобы
 * предпросмотр их не перебивал.
 *
 *   node tools/check-telo-novosti.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чисто = п => fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

const admin = чисто('css/admin.css');
const news = чисто('css/news.css');
const newsJs = fs.readFileSync(path.join(КОРЕНЬ, 'js/admin/sections/news.js'), 'utf8');
const adminHtml = fs.readFileSync(path.join(КОРЕНЬ, 'pages/admin.html'), 'utf8');

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

/* ПРАВИЛО 1. Предпросмотр не объявляет уровни текста заново.
   УРОВНИ — то, что держит лестницу: кегль, межстрочный, вес, цвет,
   отступы. Один `max-height` у окна правилом не считается: его можно
   задать контейнеру. Поэтому ищем ровно эти свойства. */
const УРОВНИ = ['font-size', 'line-height', 'font-weight', 'color',
                'margin', 'margin-top', 'margin-bottom', 'padding-left'];
const свои = [];
{
    const р = /\.ad-news-preview-body[^{]*\{([^}]*)\}/g;
    let м;
    while ((м = р.exec(admin))) {
        const стр = admin.slice(0, м.index).split('\n').length;
        УРОВНИ.forEach(св => {
            if (new RegExp('(^|;)\\s*' + св + '\\s*:').test(м[1])) {
                свои.push(св + ' на строке ' + стр);
            }
        });
    }
}
правило('предпросмотр не объявляет уровни текста заново',
    свои.length === 0,
    'Предпросмотр снова задаёт лестницу сам: ' + свои.join(', ') + '.\n' +
    'ЭКРАН, НАЗНАЧЕНИЕ КОТОРОГО ПОКАЗАТЬ ПРАВДУ, НЕ ИМЕЕТ ПРАВА НА СВОИ\n' +
    'ЧИСЛА. Тело статьи определено один раз — в `css/news.css`. Нужна\n' +
    'поправка для окна админки — она задаётся КОНТЕЙНЕРУ окна (высота,\n' +
    'прокрутка), а не уровням текста внутри.');

/* ПРАВИЛО 2. Элемент предпросмотра несёт класс читателя.
   Без него правило 1 сторожило бы пустоту: предпросмотр перестал бы
   перебивать эталон, но и не получал бы его. */
правило('предпросмотр рисуется классом читателя',
    /class="[^"]*\bnews-html\b/.test(newsJs),
    'В `js/admin/sections/news.js` тело предпросмотра больше не несёт\n' +
    'класс `news-html`. Тогда правда до автора не доходит вовсе, и\n' +
    'предпросмотр показывает голый html без лестницы.');

/* ПРАВИЛО 3. Лестница читателя приходит в админку.
   Третий шов: класс стоит, правило молчит, а файла на странице нет. */
правило('news.css подключён к странице админки',
    /news\.css\?v=\d+/.test(adminHtml),
    '`css/news.css` не подключён в `pages/admin.html` — предпросмотр\n' +
    'останется без лестницы читателя, хотя класс на элементе стоит.');

/* ПРАВИЛО 4. Лестница читателя объявлена ТАМ, а не растворилась.
   Если уровни ушли из `news.css`, предпросмотру нечего наследовать. */
/* ГРАНИЦА КЛАССА ОБЯЗАТЕЛЬНА, и это показал прувер: без `(?![\w-])`
   регексп считал `.news-html-net` за `.news-html` — откат переименовывал
   класс, лестница у читателя исчезала, а правило молчало. Класс в css
   кончается на не-[\w-]. */
const ЧИТАТЕЛЬ = '\\.news-html(?![\\w-])';
const уровнейУчитателя = УРОВНИ.filter(св =>
    new RegExp(ЧИТАТЕЛЬ + '[^{]*\\{[^}]*(^|;)\\s*' + св + '\\s*:', 'm').test(news) ||
    new RegExp(ЧИТАТЕЛЬ + '\\s+\\w+[^{]*\\{[^}]*' + св + '\\s*:').test(news));
правило('лестница тела статьи объявлена у читателя',
    уровнejПроверка(уровнейУчитателя),
    'В `css/news.css` у `.news-html` почти не осталось уровней текста\n' +
    '(найдено ' + уровнейУчитателя.length + ' из ' + УРОВНИ.length + ').\n' +
    'Тело статьи определяется ТАМ — и предпросмотр наследует оттуда.');
function уровнejПроверка(н) { return н.length >= 4; }

/* ПРАВИЛО 5. Отступ маркера списка — на ступени шкалы, а не числом.
   Было 22px в двух местах (предпросмотр и редактор) против 24 у читателя:
   автор набирал список с одним отступом, а выходил другой. */
const маркерЧислом = [];
{
    const р = /padding-left\s*:\s*(\d+)px/g;
    let м;
    while ((м = р.exec(admin))) {
        if (+м[1] % 8 !== 0) {
            маркерЧислом.push(м[1] + 'px на строке ' + admin.slice(0, м.index).split('\n').length);
        }
    }
}
правило('отступы слева в админке стоят на шкале восьмёрки',
    маркерЧислом.length === 0,
    'Отступ слева числом мимо восьмёрки: ' + маркерЧислом.join(', ') + '.\n' +
    'Шкала отступов — 8 · 12 · 16 · 20 · 24 · 32 · 40. Маркер списка у\n' +
    'читателя стоит на 24 (--space-6); 22 — это ни ступень, ни правда.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      тело новости: 5 правил');
    console.log('          предпросмотр своих уровней текста не задаёт');
    console.log('          класс читателя на элементе, news.css на странице');
    console.log('          уровней у читателя: ' + уровнейУчитателя.length + ' из ' + УРОВНИ.length);
    console.log('          отступов слева мимо восьмёрки: 0');
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  тело новости — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
