'use strict';
const path = require('path');

let acorn = null;
try {
    acorn = require(path.join(__dirname, '..', 'node_modules', 'acorn'));
} catch (e) {
    acorn = null;
}

/**
 * Запасной проход: знает строки, но не знает регулярных выражений.
 * Нужен только там, где парсер не справился.
 */
function проходом(т) {
    let из = '';
    let i = 0;
    const н = т.length;
    let кавычка = null;
    while (i < н) {
        const с = т[i], сл = т[i + 1];
        if (кавычка) {
            из += с;
            if (с === '\\') { из += (сл === undefined ? '' : сл); i += 2; continue; }
            if (с === кавычка) кавычка = null;
            i++;
            continue;
        }
        if (с === '"' || с === "'" || с === '`') { кавычка = с; из += с; i++; continue; }
        if (с === '/' && сл === '/') {
            while (i < н && т[i] !== '\n') { из += ' '; i++; }
            continue;
        }
        if (с === '/' && сл === '*') {
            из += '  '; i += 2;
            while (i < н && !(т[i] === '*' && т[i + 1] === '/')) {
                из += (т[i] === '\n' ? '\n' : ' ');
                i++;
            }
            if (i < н) { из += '  '; i += 2; }
            continue;
        }
        из += с;
        i++;
    }
    return из;
}

/**
 * @param {string} текст — исходник js
 * @returns {string} тот же текст, где комментарии забиты пробелами
 */
function безКомментариев(текст) {
    const т = String(текст == null ? '' : текст);
    if (!acorn) return проходом(т);

    const куски = [];
    const запомнить = (блочный, содержимое, от, до) => куски.push([от, до]);
    let разобрано = false;
    for (const вид of ['module', 'script']) {
        try {
            acorn.parse(т, {
                ecmaVersion: 'latest',
                sourceType: вид,
                allowReturnOutsideFunction: true,
                allowAwaitOutsideFunction: true,
                allowHashBang: true,
                onComment: запомнить
            });
            разобрано = true;
            break;
        } catch (e) {
            куски.length = 0;
        }
    }
    if (!разобрано) return проходом(т);

    /* ЗАБИВАЕМ С КОНЦА: иначе каждая правка сдвигала бы границы
       следующих, и прибор резал бы по чужим местам. */
    const знаки = т.split('');
    куски.sort((a, b) => b[0] - a[0]).forEach(([от, до]) => {
        for (let i = от; i < до && i < знаки.length; i++) {
            if (знаки[i] !== '\n') знаки[i] = ' ';
        }
    });
    return знаки.join('');
}

module.exports = { безКомментариев, проходом };
