#!/usr/bin/env node
/**
 * ТАЙ-БРЕЙК ВПИСЫВАЕТ ИГРОК (29.10, слово Кости).
 *
 * ЧТО БЫЛО, ИЗМЕРЕНО ЧТЕНИЕМ СЕРВЕРА, А НЕ ДОГАДКОЙ. Серверная функция
 * `submit_match_score` принимала тай-брейк С САМОГО НАЧАЛА:
 * `sql/функции/match-score-notify.sql:140` разбирает сет по
 * `^(\d{1,2})/(\d{1,2})(?:\(\d{1,2}-\d{1,2}\))?$`, и в комментарии на
 * `:133` так и написано — «допускаем тай-брейк в скобках». В базе таких
 * строк уже 105 (замер 28.10). Не умел только ВВОД: `buildScore`
 * отбрасывал скобку, а в окне игрока было два поля на сет вместо
 * четырёх.
 *
 * И НА ЭТОМ ЖЕ ЗАМЕРЕ ВСКРЫЛОСЬ ТРИ КОПИИ ПЕРЕВОРОТА СЧЁТА. Счёт глазами
 * соперника считался в трёх местах, и все три давали РАЗНОЕ на строке с
 * тай-брейком: свод — `6(11-9)/7` (скобка уехала к левой стороне, числа
 * не поменялись), два экрана приложения — `6/7(11-9)` (скобка осталась у
 * того, кто сет выиграл). Скобка держит очки В ПОРЯДКЕ СТОРОН, значит
 * меняются стороны — меняются и числа. Копии сняты, правило одно.
 *
 * ПОЧЕМУ ЭТО ВСПЛЫЛО ИМЕННО СЕЙЧАС: пока тай-брейк вписывал только
 * организатор, таких строк было 105. Игроки сделают их обычными.
 *
 * Запуск: node tools/check-tay-breyk.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));

const СВОД = 'js/kslt-rules.js';
const ДОМ = 'js/kslt-schyot-matcha.js';
const СЕРВЕР = 'sql/функции/match-score-notify.sql';
const ОКНА = [['js/match-score.js', 'сайта', 'ms'],
              ['mobile/www/js/match-score.js', 'приложения', 'msa']];

console.log('\n  ТАЙ-БРЕЙК ВПИСЫВАЕТ ИГРОК\n');

const свод = безКом(чит(СВОД));

правило('сервер принимает тай-брейк — и это читается в его коде',
    /\(\?:\\\(\\d\{1,2\}-\\d\{1,2\}\\\)\)\?/.test(чит(СЕРВЕР)),
    'Если серверная регулярка перестанет принимать скобку, окно будет\n' +
    'слать то, что база отвергнет. ПРАВИЛО СТОИТ ПЕРВЫМ: вся работа\n' +
    'кусочка опирается на этот договор, и он не наш.');

правило('форма, которую собирает свод, совпадает с серверной',
    /скобка = '\(' \+ т1 \+ '-' \+ т2 \+ '\)'/.test(свод) &&
    /сеты\.push\(a \+ '\/' \+ b \+ скобка\)/.test(свод),
    'Сервер ждёт `геймы/геймы(очки-очки)`. Любая другая форма — отказ\n' +
    '`bad_score`, и человек не поймёт, за что.');

правило('свод проверяет половину тай-брейка',
    /error: 'tb_half'/.test(свод),
    'Заполнено одно поле из двух — писать в скобку нечего, и молча\n' +
    'отбрасывать введённое нельзя.');

/* ПРАВИЛО СМОТРИТ НА САМУ ПРОВЕРКУ, А НЕ НА СЛОВА РЯДОМ: `tb_bad`
   возвращается и при равных очках, а `^\d{1,2}$` живёт ещё и в
   `сетСТайБрейком`, — поэтому первая редакция не упала от снятия
   проверки. Промах поймал прувер. */
правило('свод проверяет сами цифры',
    /!\/\^\\d\{1,2\}\$\/\.test\(т1\)/.test(свод) &&
    /!\/\^\\d\{1,2\}\$\/\.test\(т2\)/.test(свод) &&
    /if \(т1 === т2\) return \{ ok: false, error: 'tb_bad' \}/.test(свод),
    'Больше двух знаков сервер не примет — отказ пришёл бы от него.\n' +
    'Равные очки в тай-брейке тоже беда: победителя из них не вывести.');

правило('свод ловит тай-брейк, доставшийся не тому',
    /error: 'tb_side'/.test(свод) &&
    /сетВзялПервый !== тбВзялПервый/.test(свод),
    'САМАЯ ЧАСТАЯ ОПИСКА: цифры переставлены местами. Сет база считает по\n' +
    'геймам и расхождения внутри одной записи НЕ ЗАМЕТИТ — счёт ляжет\n' +
    'противоречивый.');

правило('когда показывать поле — одно правило на оба продукта',
    /R\.сетСТайБрейком = /.test(свод) &&
    /Math\.max\(п, в\) === 7 && Math\.abs\(п - в\) === 1/.test(свод),
    'Тай-брейк бывает при 7:6 и 6:7. Разойдись правило — один продукт\n' +
    'открывал бы поле там, где другой его прячет, и один матч записался\n' +
    'бы по-разному.');

правило('дом собирает четыре поля на сет',
    /'tb1s'/.test(безКом(чит(ДОМ))) && /'tb2s'/.test(безКом(чит(ДОМ))),
    'Два поля — это счёт без тай-брейка. Четыре — как в админке и как\n' +
    'лежит в базе.');

правило('отказ сборки разнесён по ключам, а не свален в один',
    /API\.ключСборки = /.test(безКом(чит(ДОМ))) &&
    /errTbHalf/.test(безКом(чит(ДОМ))) && /errTbSide/.test(безКом(чит(ДОМ))),
    'Человеку надо знать, ЧТО поправить. Один `errBad` на четыре разные\n' +
    'причины — это «не удалось сохранить счёт», из-за которого кусок\n' +
    'A3.7г и делался.');

ОКНА.forEach(function (пара) {
    const ф = пара[0], имя = пара[1], п = пара[2];
    const т = безКом(чит(ф));

    /* ПРИЗНАК БЕЗ КАВЫЧЕК: имя поля собирается склейкой, и у сайта оно
       нигде не стоит целой строкой в одинарных кавычках — оно
       `id="mstb1s' + i + '"`. Правило, искавшее `'mstb1s'`, падало на
       верном коде, а у приложения проходило случайно: там то же имя есть
       и в `getElementById('msatb1s' + i)`. ПРИБОР НЕ ВИДИТ СКЛЕЙКУ. */
    /* СМОТРИМ НА РАЗМЕТКУ ПОЛЯ, А НЕ НА ЛЮБОЕ УПОМИНАНИЕ ИМЕНИ: у
       приложения то же имя встречается и в `getElementById`, и правило
       держалось, когда поле из разметки убрали. Второй промах того же
       рода за этот кусок. */
    правило('у ' + имя + ' в окне есть поля тай-брейка',
        new RegExp('id="' + п + 'tb1s').test(т) &&
        new RegExp('id="' + п + 'tb2s').test(т) &&
        /data-tb-set=/.test(т),
        'Четыре поля на сет, иначе вписывать некуда.');

    правило('у ' + имя + ' поле прячется по правилу свода',
        /сетСТайБрейком\(/.test(т) && /hidden = !видно/.test(т),
        'Своё условие показа здесь — второе определение одного понятия.');

    правило('у ' + имя + ' закрытое поле очищается',
        /п1\.value = '';/.test(т) && /п2\.value = '';/.test(т),
        'Иначе в счёт уедет тай-брейк от сета, который человек уже\n' +
        'переписал: поле спрятано, а значение в нём осталось.');

    правило('у ' + имя + ' есть слова на все три отказа тай-брейка',
        ['errTbHalf', 'errTbBad', 'errTbSide'].every(к =>
            new RegExp(к).test(чит(ф)) ||
            new RegExp(к).test(чит(ф.indexOf('mobile') === 0
                ? 'mobile/www/js/match-score-texts.js' : 'js/match-score-texts.js'))),
        'Ключ без слова — пустое окно вместо объяснения.');
});

правило('слова тай-брейка есть на всех трёх языках',
    ['errTbHalf', 'errTbBad', 'errTbSide', 'tb'].every(к =>
        (чит('js/match-score-texts.js').match(new RegExp(к + ':', 'g')) || []).length === 3),
    'Словарей три. Нет слова в одном — человек на этом языке увидит\n' +
    'пустоту вместо подсказки.');

правило('переворот счёта меняет и стороны, и числа в скобке',
    /п\[2\] \+ '\/' \+ п\[1\] \+ '\(' \+ п\[4\] \+ '-' \+ п\[3\] \+ '\)'/.test(свод),
    'Скобка держит очки В ПОРЯДКЕ СТОРОН. Было две неверные редакции:\n' +
    'первая оставляла скобку у победителя сета, вторая уводила её к левой\n' +
    'стороне, не меняя чисел.');

правило('переворот объявлен один раз — в своде',
    (function () {
        const копии = ['mobile/www/js/screens/profile.js',
                       'mobile/www/js/screens/player-detail.js'];
        return копии.every(ф => {
            const т = безКом(чит(ф));
            return /KSLT_RULES\.перевернутьСчёт/.test(т) &&
                   !/replace\(\/\(\\d\+\)\\\/\(\\d\+\)\/g, '\$2\/\$1'\)/.test(т);
        });
    })(),
    'Копий было ТРИ, и все три давали разное на строке с тай-брейком.\n' +
    'Два экрана приложения держали свою, со старой ошибкой, которую сайт\n' +
    'уже починил и описал в комментарии.');

правило('у клетки тай-брейка есть вид в обоих продуктах',
    /\.ms-tb-cell/.test(чит('css/match-score.css')) &&
    /\.msa-tb-cell/.test(чит('mobile/www/css/app.css')),
    'Без вида два поля слипнутся в одну клетку шириной 60 точек.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else { console.log('  ок      тай-брейк: все ' + держится + ' правил держатся\n'); }
