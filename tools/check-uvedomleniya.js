#!/usr/bin/env node
/**
 * НАСТРОЙКИ УВЕДОМЛЕНИЙ — ЭКРАН НЕ РАСХОДИТСЯ С СЕРВЕРОМ (шаг A2.3, 29.10).
 *
 * ЗАЧЕМ. Настройки живут в `profiles.notify_preferences`, и читают их
 * ШЕСТНАДЦАТЬ серверных функций правилом `shouldNotify(prefs, ch, cat)`.
 * А экраны расходились с этим договором по трём местам, и каждое — свой
 * род беды:
 *
 *   1. САЙТ рисовал канал `site`, которого НЕ СПРАШИВАЕТ НИ ОДНА
 *      функция: человек выключал — и ничего не менялось;
 *   2. РАЗДЕЛОВ на экране было ЧЕТЫРЕ против шести серверных: `security`
 *      и `general` выключить было нечем;
 *   3. ПРИЛОЖЕНИЕ писало в таблицу `notification_preferences`, КОТОРОЙ В
 *      БАЗЕ НЕТ ВОВСЕ, своими именами каналов и разделов.
 *
 * ГЛАВНОЕ, ЧТО ДЕРЖИТ СТОРОЖ: имена каналов и разделов в доме сверяются
 * С ЖИВЫМ СЕРВЕРНЫМ КОДОМ, а не со списком, записанным руками. Добавят
 * на сервере новый раздел — правило упадёт и скажет, какой. СПИСОК,
 * КОТОРЫЙ ДЕРЖИТСЯ РУКАМИ, ОТСТАЁТ.
 *
 * Запуск: node tools/check-uvedomleniya.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));
const безКомCss = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

const ДОМ = 'js/kslt-uvedomleniya.js';
const ДОМ_П = 'mobile/www/js/kslt-uvedomleniya.js';
const САЙТ = 'js/dashboard.js';
const ПРИЛ = 'mobile/www/js/screens/profile.js';

/* ЧЕГО СЕРВЕР СПРАШИВАЕТ НА САМОМ ДЕЛЕ — читается из его кода. */
const СЕРВЕР = (function () {
    const каналы = new Map(), разделы = new Map();
    let функций = 0;
    const обойти = (отн) => {
        const п = path.join(КОРЕНЬ, отн);
        if (!fs.existsSync(п)) return;
        for (const э of fs.readdirSync(п, { withFileTypes: true })) {
            const вложен = отн + '/' + э.name;
            if (э.isDirectory()) { обойти(вложен); continue; }
            if (!/\.(ts|js)$/.test(э.name)) continue;
            const т = fs.readFileSync(path.join(КОРЕНЬ, вложен), 'utf8');
            let нашлось = false;
            const re = /shouldNotify\([^,)]+,\s*'([a-z_]+)'\s*,\s*'([a-z_]+)'\s*\)/g;
            let м;
            while ((м = re.exec(т)) !== null) {
                каналы.set(м[1], (каналы.get(м[1]) || 0) + 1);
                разделы.set(м[2], (разделы.get(м[2]) || 0) + 1);
                нашлось = true;
            }
            if (нашлось) функций++;
        }
    };
    обойти('supabase/functions');
    return { каналы, разделы, функций };
})();

/* Что объявил дом — читается из его текста, а не исполняется. */
function список(имя) {
    const м = безКом(чит(ДОМ)).match(new RegExp('API\\.' + имя + '\\s*=\\s*\\[([^\\]]*)\\]'));
    if (!м) return null;
    return (м[1].match(/'([^']+)'/g) || []).map(с => с.replace(/'/g, ''));
}

console.log('\n  УВЕДОМЛЕНИЯ — ЭКРАН НЕ РАСХОДИТСЯ С СЕРВЕРОМ\n');

const дом = безКом(чит(ДОМ));
const каналыДома = список('КАНАЛЫ');
const разделыДома = список('РАЗДЕЛЫ');

правило('дом объявлен и отдаёт все шесть понятий',
    /KSLT_UVEDOMLENIYA\b/.test(дом) && caналыЕсть(),
    'Нужны: КАНАЛЫ, РАЗДЕЛЫ, прочитать, включено, переключить,\n' +
    'каналДоступен.');
function caналыЕсть() {
    return /API\.КАНАЛЫ\s*=/.test(дом) && /API\.РАЗДЕЛЫ\s*=/.test(дом) &&
        ['прочитать', 'включено', 'переключить', 'каналДоступен']
            .every(и => new RegExp('API\\.' + и + '\\s*=').test(дом));
}

правило('копии дома побайтово равны',
    чит(ДОМ) === чит(ДОМ_П),
    'Разошлись — значит имена каналов снова живут двумя жизнями.');

правило('сервер вообще найден и спрашивает настройки',
    СЕРВЕР.функций >= 10 && СЕРВЕР.каналы.size > 0,
    'Обход `supabase/functions` нашёл ' + СЕРВЕР.функций + ' функций с\n' +
    '`shouldNotify`. Если ноль — сломался ПРИБОР, а не продукт, и все\n' +
    'сверки ниже стали бы пустыми. Правило стоит ПЕРЕД ними нарочно.');

правило('КАНАЛЫ дома — ровно те, что спрашивает сервер',
    caналыСовпали(),
    'Сервер спрашивает: ' + [...СЕРВЕР.каналы.keys()].sort().join(', ') + '\n' +
    'Дом объявил:      ' + (каналыДома || []).slice().sort().join(', ') + '\n' +
    'ОРГАН УПРАВЛЕНИЯ, КОТОРЫЙ ДЕЛАЕТ НЕ ТО, ЧТО ОБЕЩАЕТ, ХУЖЕ\n' +
    'ОТСУТСТВУЮЩЕГО: ровно так на сайте жил канал `site`, которого не\n' +
    'спрашивал никто.');
function caналыСовпали() {
    if (!каналыДома) return false;
    const a = [...СЕРВЕР.каналы.keys()].sort().join(',');
    return a === каналыДома.slice().sort().join(',');
}

правило('РАЗДЕЛЫ дома — ровно те, что спрашивает сервер',
    (function () {
        if (!разделыДома) return false;
        const a = [...СЕРВЕР.разделы.keys()].sort().join(',');
        return a === разделыДома.slice().sort().join(',');
    })(),
    'Сервер спрашивает: ' + [...СЕРВЕР.разделы.keys()].sort().join(', ') + '\n' +
    'Дом объявил:      ' + (разделыДома || []).slice().sort().join(', ') + '\n' +
    'Раздел, которого нет на экране, НЕЛЬЗЯ ВЫКЛЮЧИТЬ — а мы в анкетах\n' +
    'магазинов заявляем, что человек управляет рассылками. Так и жили\n' +
    '`security` и `general`.');

правило('правило «включено ли» повторяет серверное знак в знак',
    /if\s*\(!настройки\)\s*return true/.test(дом) &&
    /if\s*\(!ч\)\s*return true/.test(дом) &&
    /ч\[раздел\]\s*!==\s*false/.test(дом),
    'У сервера: нет настроек — отправляем, нет канала — отправляем,\n' +
    'иначе `!== false`. Разойдись правило — экран показывал бы одно, а\n' +
    'сервер делал другое, и прав всегда сервер.\n' +
    'УМОЛЧАНИЕ — СВОЙСТВО ДАННЫХ, А НЕ РАЗМЕТКИ.');

правило('`переключить` не трогает прежний слепок',
    /API\.переключить/.test(дом) && !/настройки\[канал\]\[раздел\]\s*=/.test(дом),
    'Оба продукта правили настройки НА МЕСТЕ и при неудаче возвращали\n' +
    'значение обратно. Возвращать проще, когда прежний слепок цел.');

[[САЙТ, 'сайта'], [ПРИЛ, 'приложения']].forEach(([ф, имя]) => {
    const т = безКом(чит(ф));

    /* ПРИЗНАК СУЖЕН ДО СПИСКОВ ЭКРАНА НАСТРОЕК: первая редакция
       запрещала подстроку `'tournament',` во всём файле и упала на
       `js/dashboard.js:4134` — там список фильтров КОЛОКОЛЬЧИКА
       (`['all','unread','challenge','tournament','match','membership']`),
       а это другое понятие и другой словарь. Промах поймал прувер.
       И он же подтвердил находку: у колокольчика разделы зовутся
       `challenge`/`tournament`/`match`, а у настроек —
       `challenges`/`tournaments`/`matches`. Два написания одного
       понятия; записано в трекер отдельным куском. */
    правило('у ' + имя + ' нет своих списков каналов и разделов',
        !/NOTIF_CATS\s*=\s*\[/.test(т) && !/NOTIF_CHANNELS\s*=\s*\[/.test(т) &&
        !/key:\s*'(?:tournament|payment|system|marketing)'/.test(т),
        'Имена живут в доме и сверяются с сервером. Свой список здесь —\n' +
        'это второе определение, которое однажды отстанет.');

    правило('у ' + имя + ' нет своего правила «включено ли»',
        !/\[channel\]\[cat\]\s*!==\s*false|\[ch\]\[cat\]\s*!==\s*false|prefs\[key\]\s*!==\s*false/.test(т),
        'Правило одно, и оно обязано совпадать с серверным.');

    правило('у ' + имя + ' дом зовётся',
        /KSLT_UVEDOMLENIYA/.test(т) && /\.включено\(/.test(т) &&
        /\.переключить\(/.test(т) && /\.каналДоступен\(/.test(т),
        'Без зова работа не сделана.');

    правило('у ' + имя + ' настройки пишутся в profiles.notify_preferences',
        /notify_preferences/.test(т) && /from\('profiles'\)/.test(т),
        'Это единственное место, которое читает сервер.');

    правило('у ' + имя + ' нет зова к несуществующей таблице',
        !/notification_preferences/.test(т),
        'Таблицы нет в базе ни в одной схеме — проверено запросом 29.10.');
});

правило('канала `site` не осталось ни в доме, ни на экранах',
    !/'site'/.test(дом) && !/'site'/.test(безКом(чит(САЙТ))) &&
    !/notifSite/.test(чит(САЙТ)),
    'Его не спрашивает ни одна серверная функция. Научить сервер его\n' +
    'спрашивать — это 13 мест записи в колокольчик и словарь\n' +
    '`notification_log.type`, где уже два написания одного понятия\n' +
    '(`challenge`/`challenges`, `match`/`matches`). Это свой кусок.');

правило('ни одна серверная функция не трогает несуществующую таблицу',
    (function () {
        let нашлось = 0;
        const обойти = (отн) => {
            const п = path.join(КОРЕНЬ, отн);
            if (!fs.existsSync(п)) return;
            for (const э of fs.readdirSync(п, { withFileTypes: true })) {
                const в = отн + '/' + э.name;
                if (э.isDirectory()) { обойти(в); continue; }
                if (!/\.(ts|js)$/.test(э.name)) continue;
                if (/from\('notification_preferences'\)/.test(
                        безКом(fs.readFileSync(path.join(КОРЕНЬ, в), 'utf8')))) нашлось++;
            }
        };
        обойти('supabase/functions');
        return нашлось === 0;
    })(),
    '`delete-account` и `purge-deleted-accounts` удаляли строки из\n' +
    'таблицы, которой нет. В `purge` результат зова даже не проверялся —\n' +
    'ТИХОЕ РАСХОЖДЕНИЕ.');

правило('в приложении разрешение на пуши просят ПОСЛЕ успешной записи',
    (function () {
        const т = безКом(чит(ПРИЛ));
        const з = т.indexOf('.update({ notify_preferences');
        const р = т.indexOf('KSLT_PUSH.спросить');
        return з !== -1 && р !== -1 && з < р;
    })(),
    'Прежде спрашивали ДО записи, запись падала (таблицы нет), и человек\n' +
    'отдавал системное разрешение ни за что. Взяли разрешение —\n' +
    'исполните обещание.');

правило('у каждого раздела есть слово на всех трёх языках',
    (function () {
        if (!разделыДома) return false;
        const имена = { tournaments: 'notifTournaments', challenges: 'notifChallenges',
            membership: 'notifMembership', matches: 'notifMatches',
            security: 'notifSecurity', general: 'notifGeneral' };
        const с = чит(САЙТ), п = чит('mobile/www/js/i18n.js');
        return разделыДома.every(р => {
            const к = имена[р];
            if (!к) return false;
            if ((с.match(new RegExp(к + ':\\s*\'[^\']+\'', 'g')) || []).length !== 3) return false;
            const м = п.match(new RegExp("'profile\\." + к + "':\\s*\\{([^}]*)\\}"));
            if (!м) return false;
            return ['ru', 'en', 'kg'].every(я => new RegExp(я + ":\\s*'[^']+'").test(м[1]));
        });
    })(),
    'Раздел без слова — пустая строка в таблице. У сайта три словаря, у\n' +
    'приложения по три языка на ключ; проверяются оба.');

правило('дом подключён и грузится ДО того, кто его зовёт',
    ['mobile/www/index.html', 'pages/dashboard.html', 'pages/dashboard-en.html',
     'pages/dashboard-kg.html'].every(ф => {
        const t = чит(ф);
        const д = t.indexOf('kslt-uvedomleniya.js');
        const з = Math.min.apply(null,
            ['js/dashboard.js?', 'js/screens/profile.js?']
                .map(с => t.indexOf(с)).filter(и => и !== -1).concat([Infinity]));
        return д !== -1 && з !== Infinity && д < з;
    }),
    'Страница грузит экран настроек без дома — ползунки упадут на\n' +
    '`undefined` при первом открытии.');

правило('гашение канала без бота есть у обоих продуктов',
    /db-notif-off/.test(чит(САЙТ)) && /prof-notif-off/.test(чит(ПРИЛ)) &&
    /\.prof-notif-off/.test(безКомCss(чит('mobile/www/css/app.css'))),
    'Без привязанного бота столбец телеграма бесполезен: человек включал\n' +
    'ползунок и ждал сообщений, которым неоткуда взяться. Правило было\n' +
    'только у сайта.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else {
    console.log('  ок      уведомления: все ' + держится + ' правил держатся');
    console.log('          сервер спрашивает каналы [' + [...СЕРВЕР.каналы.keys()].sort().join(', ') +
                '] и разделы [' + [...СЕРВЕР.разделы.keys()].sort().join(', ') + '] в ' +
                СЕРВЕР.функций + ' функциях\n');
}
