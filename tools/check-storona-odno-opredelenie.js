const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

function гасить(s) {
    const из = s.split('');
    s.replace(/\/\*[\s\S]*?\*\//g, (м, i) => {
        for (let k = i; k < i + м.length; k++) if (из[k] !== '\n') из[k] = ' ';
        return м;
    });
    return из.join('');
}

function блоки(текст, селектор) {
    const из = [];
    let i = 0;
    while ((i = текст.indexOf(селектор, i)) !== -1) {
        const след = текст[i + селектор.length] || '';
        i += селектор.length;
        if (/[\w-]/.test(след)) continue;
        const о = текст.indexOf('{', i), з = текст.indexOf('}', i);
        if (о === -1 || (з !== -1 && з < о)) continue;
        let гл = 1, j = о + 1;
        while (j < текст.length && гл) { if (текст[j] === '{') гл++; else if (текст[j] === '}') гл--; j++; }
        из.push(текст.slice(о + 1, j - 1));
    }
    return из;
}

/** Тон краски в градусах. Серые тона не имеют — для них null. */
function тон(hex) {
    const h = String(hex).replace('#', '');
    if (!/^[0-9a-f]{6}$/i.test(h)) return null;
    const r = parseInt(h.slice(0, 2), 16) / 255,
          g = parseInt(h.slice(2, 4), 16) / 255,
          b = parseInt(h.slice(4, 6), 16) / 255;
    const mx = Math.max(r, g, b), mn = Math.min(r, g, b);
    if (mx - mn < 0.12) return null;
    const d = mx - mn;
    let H = mx === r ? ((g - b) / d + (g < b ? 6 : 0)) : mx === g ? ((b - r) / d + 2) : ((r - g) / d + 4);
    return Math.round(H * 60);
}
const расстояние = (a, b) => { const d = Math.abs(a - b) % 360; return d > 180 ? 360 - d : d; };

