/** Содержимое блока по его якорю. Якорь держится на содержимом, не на строке. */
const блок = (текст, якорь) => {
    const i = текст.indexOf(якорь);
    if (i === -1) return '';
    let j = текст.indexOf('{', i), г = 0;
    const с = j;
    for (; j < текст.length; j++) {
        if (текст[j] === '{') г++;
        else if (текст[j] === '}') { г--; if (г === 0) return текст.slice(с + 1, j); }
    }
    return '';
};

