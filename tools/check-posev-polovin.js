/**
 * ПОСЕВ: ЗЕМЛЯКИ РАЗВОДЯТСЯ ПО ПОЛОВИНАМ — СТОРОЖ НА ВСЕ 42 РАСКЛАДА.
 *
 * ПОЧЕМУ ОН ПОЯВИЛСЯ ТОЛЬКО СЕЙЧАС. Развод по половинам сделан 09.10,
 * в тот же день найден и починен регресс при «выходят трое» — и всё это
 * осталось БЕЗ СТОРОЖА: «кусок шёл срочным» (трекер, 09.10). Неделю
 * починка держалась словом. Теперь держится проверкой.
 *
 * ЧТО ИМЕННО ПРОВЕРЯЕТСЯ. Берётся настоящая функция `раскладСлотов` из
 * `js/admin/sections/bracket.js` — тот же код, что работает в админке, а
 * не его пересказ. Прогоняются все расклады: 2–8 групп × 1/2/3 выходящих.
 * Для каждого считается, в каком круге впервые встречаются земляки —
 * участники одной группы.
 *
 * ПЛАНКА, И ОНА ОТНОШЕНИЕ, А НЕ ЧИСЛО:
 *   выходят ДВОЕ  — земляки не раньше ФИНАЛА (две половины, двое членов);
 *   выходят ТРОЕ  — не раньше ПОЛУФИНАЛА (половин две, членов три —
 *                   развести всех по разным половинам невозможно в
 *                   принципе, и первый круг здесь уже беда);
 *   выходит ОДИН  — земляков в сетке нет вовсе.
 *
 *   node tools/check-posev-polovin.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ = path.join(КОРЕНЬ, 'js', 'admin', 'sections', 'bracket.js');
const исходник = fs.readFileSync(ФАЙЛ, 'utf8');

/* ВЫРЕЗАЕМ ФУНКЦИЮ ПО СКОБКАМ, А НЕ ПО НОМЕРАМ СТРОК: номера уедут от
   любой правки выше, и сторож начнёт врать на верном коде — сегодня это
   случилось четыре раза с другими приборами. */
function вырезать(имя) {
    const нач = исходник.indexOf('function ' + имя + '(');
    if (нач === -1) throw new Error('не найдена функция ' + имя);
    const фиг = исходник.indexOf('{', нач);
    let гл = 1, j = фиг + 1;
    while (j < исходник.length && гл > 0) {
        if (исходник[j] === '{') гл++;
        else if (исходник[j] === '}') гл--;
        j++;
    }
    return исходник.slice(нач, j);
}

/* Зависимости функции: SEED_POSITIONS из tournament-generator.js и
   KSLT_RULES из js/kslt-rules.js — берутся настоящие, не заглушки. */
const генератор = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'tournament-generator.js'), 'utf8');
const мПоз = /var SEED_POSITIONS = \{[\s\S]*?\n\};/.exec(генератор);
if (!мПоз) throw new Error('SEED_POSITIONS не найдены');

const правила = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'kslt-rules.js'), 'utf8');

const песочница = {};
const запуск = new Function('window', 'globalThis',
    правила + '\n' + мПоз[0] + '\n' + вырезать('раскладСлотов') +
    '\nreturn { раскладСлотов: раскладСлотов, SEED_POSITIONS: SEED_POSITIONS, KSLT_RULES: (typeof KSLT_RULES !== "undefined" ? KSLT_RULES : window.KSLT_RULES) };');
const среда = запуск(песочница, песочница);
const раскладСлотов = среда.раскладСлотов;
if (!среда.KSLT_RULES) { console.log('\n  БЕДА    KSLT_RULES не поднялись — сторож не может считать\n'); process.exit(1); }
global.KSLT_RULES = среда.KSLT_RULES;
песочница.KSLT_RULES = среда.KSLT_RULES;

/* Круг первой встречи двух слотов в сетке размера N: чем длиннее общий
   префикс в двоичной записи, тем раньше встреча. */
function кругВстречи(i, j, размер) {
    let круг = 1, a = i, b = j, шаг = размер;
    while (шаг > 1) {
        if ((a >> 1) === (b >> 1) && Math.abs(a - b) === 1) return круг;
        a >>= 1; b >>= 1; шаг >>= 1; круг++;
    }
    return круг;
}

const ВЫХОДЯТ = [1, 2, 3];
const ГРУПП = [2, 3, 4, 5, 6, 7, 8];
/* СКОЛЬКО КРУГОВ ДО КОНЦА ДОПУСТИМО. Финал — это 0 кругов до конца,
   полуфинал — 1, четвертьфинал — 2. Значит планка не «не меньше», а «НЕ
   БОЛЬШЕ»: чем больше кругов до конца, тем РАНЬШЕ встреча.
     выходит один — земляков в сетке нет;
     выходят двое — только финал, то есть 0;
     выходят трое — финал или полуфинал, то есть не больше 1. */
const ПЛАНКА = { 1: -1, 2: 0, 3: 1 };

let бед = 0, всего = 0;
console.log('');
console.log('  ПОСЕВ: ПЕРВАЯ ВСТРЕЧА ЗЕМЛЯКОВ, ВСЕ РАСКЛАДЫ');
console.log('  планка: двое — только финал (0 кругов до конца), трое — финал или полуфинал (не больше 1)');
console.log('');
console.log('  групп  выходят  размер  первая встреча  до конца  планка');

for (const выходят of ВЫХОДЯТ) {
    for (const групп of ГРУПП) {
        всего++;
        let расклад;
        try {
            расклад = раскладСлотов({ qualifiers_per_group: выходят, format: 'single' }, групп);
        } catch (e) {
            console.log('  ✗ ' + групп + ' × ' + выходят + ' — функция упала: ' + e.message);
            бед++; continue;
        }
        const сетка = расклад.сетка, размер = расклад.размер;
        const кругов = Math.log2(размер);
        let раньшеВсего = 99;
        for (let i = 0; i < размер; i++) {
            for (let j = i + 1; j < размер; j++) {
                const a = сетка[i], b = сетка[j];
                if (!a || !b || a.группа < 0 || a.группа !== b.группа) continue;
                const к = кругВстречи(i, j, размер);
                if (к < раньшеВсего) раньшеВсего = к;
            }
        }
        const доКонца = раньшеВсего === 99 ? 99 : кругов - раньшеВсего;
        const планка = ПЛАНКА[выходят];
        const ок = (раньшеВсего === 99) || (доКонца <= планка);
        if (!ок) бед++;
        console.log('  ' + (ок ? ' ' : '✗') + String(групп).padStart(4) +
            String(выходят).padStart(9) + String(размер).padStart(8) +
            (раньшеВсего === 99 ? '          нет' : String(раньшеВсего).padStart(13)) +
            (доКонца === 99 ? '         —' : String(доКонца).padStart(10)) +
            String(планка).padStart(8));
    }
}

/* ВТОРОЕ ПРАВИЛО, И ОНО РЕШЕНИЕ КОСТИ ОТ 29.09: «непрошедших ставим ПО
   СИЛЕ». Слабейшие — метки Q и IG — принадлежат ТРУДНЫМ слотам, то есть
   соседним с верхними сеяными. Признак нарушения: двое слабейших стоят
   в одной паре первого круга (Q против Q) — значит их развели не по
   силе, а по остатку. Ровно это я сломал 09.10, починяя первое правило,
   и поймал тогда Костя. Теперь ловит проверка. */
console.log('');
console.log('  СЛАБЕЙШИЕ (Q и IG) — ПО СИЛЕ, А НЕ ПО ОСТАТКУ');
console.log('  признак беды: двое слабейших в одной паре первого круга');
console.log('');
let бедQ = 0;
for (const выходят of ВЫХОДЯТ) {
    for (const групп of ГРУПП) {
        let расклад;
        try { расклад = раскладСлотов({ qualifiers_per_group: выходят, format: 'single' }, групп); }
        catch (e) { continue; }
        const сетка = расклад.сетка, размер = расклад.размер;
        let пар = 0;
        for (let i = 0; i < размер; i += 2) {
            const a = сетка[i], b = сетка[i + 1];
            if (a && b && a.группа < 0 && b.группа < 0) пар++;
        }
        if (пар > 0) {
            console.log('  ✗ ' + групп + ' групп × ' + выходят + ' — слабейшие сошлись между собой в ' + пар + ' парах первого круга');
            бедQ++;
        }
    }
}
if (бедQ === 0) console.log('  ок      нигде: слабейшие стоят против сеяных, как решено 29.09');

бед += бедQ;
console.log('');
if (бед === 0) {
    console.log('  ок      все ' + всего + ' раскладов держат планку');
    console.log('          земляки нигде не сходятся раньше, чем решено\n');
} else {
    console.log('  НЕ ТАК  ' + бед + ' раскладов из ' + всего + ' планку не держат\n');
    process.exitCode = 1;
}
