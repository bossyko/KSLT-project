const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ = path.join(КОРЕНЬ, 'js', 'admin', 'sections', 'bracket.js');
const исходник = fs.readFileSync(ФАЙЛ, 'utf8');

/* ВЫРЕЗАЕМ ФУНКЦИЮ ПО СКОБКАМ, А НЕ ПО НОМЕРАМ СТРОК: номера уедут от
   любой правки выше, и сторож начнёт врать на верном коде — сегодня это
   случилось четыре раза с другими приборами. */
function вырезать(имя) {
    const нач = исходник.indexOf('function ' + имя + '(');
    if (нач === -1) throw new Error('не найдена функция ' + имя);
    const фиг = исходник.indexOf('{', нач);
    let гл = 1, j = фиг + 1;
    while (j < исходник.length && гл > 0) {
        if (исходник[j] === '{') гл++;
        else if (исходник[j] === '}') гл--;
        j++;
    }
    return исходник.slice(нач, j);
}

/* Зависимости функции: SEED_POSITIONS из tournament-generator.js и
   KSLT_RULES из js/kslt-rules.js — берутся настоящие, не заглушки. */
const генератор = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'tournament-generator.js'), 'utf8');
const мПоз = /var SEED_POSITIONS = \{[\s\S]*?\n\};/.exec(генератор);
if (!мПоз) throw new Error('SEED_POSITIONS не найдены');

const правила = fs.readFileSync(path.join(КОРЕНЬ, 'js', 'kslt-rules.js'), 'utf8');

const песочница = {};
const запуск = new Function('window', 'globalThis',
    правила + '\n' + мПоз[0] + '\n' + вырезать('раскладСлотов') +
    '\nreturn { раскладСлотов: раскладСлотов, SEED_POSITIONS: SEED_POSITIONS, KSLT_RULES: (typeof KSLT_RULES !== "undefined" ? KSLT_RULES : window.KSLT_RULES) };');
const среда = запуск(песочница, песочница);
const раскладСлотов = среда.раскладСлотов;
if (!среда.KSLT_RULES) { console.log('\n  БЕДА    KSLT_RULES не поднялись — сторож не может считать\n'); process.exit(1); }
global.KSLT_RULES = среда.KSLT_RULES;
песочница.KSLT_RULES = среда.KSLT_RULES;

/* Круг первой встречи двух слотов в сетке размера N: чем длиннее общий
   префикс в двоичной записи, тем раньше встреча. */
function кругВстречи(i, j, размер) {
    let круг = 1, a = i, b = j, шаг = размер;
    while (шаг > 1) {
        if ((a >> 1) === (b >> 1) && Math.abs(a - b) === 1) return круг;
        a >>= 1; b >>= 1; шаг >>= 1; круг++;
    }
    return круг;
}

const ВЫХОДЯТ = [1, 2, 3];
const ГРУПП = [2, 3, 4, 5, 6, 7, 8];
/* ДВА ФОРМАТА СВОБОДНЫХ МЕСТ, и имя поля настоящее — `playoff_format`,
   то, которое читает `раскладСлотов`:
     'ig'     — свободные места разыгрываются доп. матчами (умолчание);
     'direct' — не разыгрываются вовсе, у сеяных стоит BYE
                (`kslt-rules.js:628`, решение Кости 29.09).
   Второй формат труднее первого: клеток под BYE больше, свободных слотов
   меньше, и разводить земляков негде. Его и не мерили. */
const ФОРМАТЫ = [
    { имя: 'доп. матчи', playoff_format: 'ig' },
    { имя: 'без игры  ', playoff_format: 'direct' },
];
/* СКОЛЬКО КРУГОВ ДО КОНЦА ДОПУСТИМО. Финал — это 0 кругов до конца,
   полуфинал — 1, четвертьфинал — 2. Значит планка не «не меньше», а «НЕ
   БОЛЬШЕ»: чем больше кругов до конца, тем РАНЬШЕ встреча.
     выходит один — земляков в сетке нет;
     выходят двое — только финал, то есть 0;
     выходят трое — финал или полуфинал, то есть не больше 1. */
const ПЛАНКА = { 1: -1, 2: 0, 3: 1 };

let бед = 0, всего = 0;
console.log('');
console.log('  ПОСЕВ: ПЕРВАЯ ВСТРЕЧА ЗЕМЛЯКОВ, ВСЕ РАСКЛАДЫ');
console.log('  планка: двое — только финал (0 кругов до конца), трое — финал или полуфинал (не больше 1)');
console.log('');
console.log('  формат      групп  выходят  размер  первая встреча  до конца  планка');

for (const формат of ФОРМАТЫ) {
  for (const выходят of ВЫХОДЯТ) {
    for (const групп of ГРУПП) {
        всего++;
        let расклад;
        try {
            расклад = раскладСлотов({ qualifiers_per_group: выходят, playoff_format: формат.playoff_format }, групп);
        } catch (e) {
            console.log('  ✗ ' + формат.имя + ' ' + групп + ' × ' + выходят + ' — функция упала: ' + e.message);
            бед++; continue;
        }
        const сетка = расклад.сетка, размер = расклад.размер;
        const кругов = Math.log2(размер);
        let раньшеВсего = 99;
        for (let i = 0; i < размер; i++) {
            for (let j = i + 1; j < размер; j++) {
                const a = сетка[i], b = сетка[j];
                if (!a || !b || a.группа < 0 || a.группа !== b.группа) continue;
                const к = кругВстречи(i, j, размер);
                if (к < раньшеВсего) раньшеВсего = к;
            }
        }
        const доКонца = раньшеВсего === 99 ? 99 : кругов - раньшеВсего;
        const планка = ПЛАНКА[выходят];
        const ок = (раньшеВсего === 99) || (доКонца <= планка);
        if (!ок) бед++;
        console.log('  ' + (ок ? ' ' : '✗') + формат.имя + String(групп).padStart(5) +
            String(выходят).padStart(9) + String(размер).padStart(8) +
            (раньшеВсего === 99 ? '          нет' : String(раньшеВсего).padStart(13)) +
            (доКонца === 99 ? '         —' : String(доКонца).padStart(10)) +
            String(планка).padStart(8));
    }
  }
}

/* ВТОРОЕ ПРАВИЛО, И ОНО РЕШЕНИЕ КОСТИ ОТ 29.09: «непрошедших ставим ПО
   СИЛЕ». Слабейшие — метки Q и IG — принадлежат ТРУДНЫМ слотам, то есть
   соседним с верхними сеяными. Признак нарушения: двое слабейших стоят
   в одной паре первого круга (Q против Q) — значит их развели не по
   силе, а по остатку. Ровно это я сломал 09.10, починяя первое правило,
   и поймал тогда Костя. Теперь ловит проверка. */
console.log('');
console.log('  СЛАБЕЙШИЕ (Q и IG) — ПО СИЛЕ, А НЕ ПО ОСТАТКУ');
console.log('  признак беды: двое слабейших в одной паре первого круга');
console.log('');
let бедQ = 0;
for (const формат of ФОРМАТЫ) {
  for (const выходят of ВЫХОДЯТ) {
    for (const групп of ГРУПП) {
        let расклад;
        try { расклад = раскладСлотов({ qualifiers_per_group: выходят, playoff_format: формат.playoff_format }, групп); }
        catch (e) { continue; }
        const сетка = расклад.сетка, размер = расклад.размер;
        let пар = 0;
        for (let i = 0; i < размер; i += 2) {
            const a = сетка[i], b = сетка[i + 1];
            if (a && b && a.группа < 0 && b.группа < 0) пар++;
        }
        if (пар > 0) {
            console.log('  ✗ ' + формат.имя + ' ' + групп + ' групп × ' + выходят + ' — слабейшие сошлись между собой в ' + пар + ' парах первого круга');
            бедQ++;
        }
    }
  }
}
/* ЧЕСТНО О ПОКРЫТИИ: при формате «без игры» меток Q и IG нет ВОВСЕ —
   свободные места не разыгрываются, у сеяных стоит BYE. Значит второе
   правило мерит только половину раскладов, и сторож говорит это сам, а не
   делает вид, что проверил все 42. */
let сМетками = 0;
for (const формат of ФОРМАТЫ) {
  for (const выходят of ВЫХОДЯТ) {
    for (const групп of ГРУПП) {
        let р;
        try { р = раскладСлотов({ qualifiers_per_group: выходят, playoff_format: формат.playoff_format }, групп); }
        catch (e) { continue; }
        if (р.сетка.some(function (к) { return к && к.группа < 0; })) сМетками++;
    }
  }
}
if (бедQ === 0) {
    console.log('  ок      нигде: слабейшие стоят против сеяных, как решено 29.09');
    console.log('          правило мерит ' + сМетками + ' раскладов из ' + всего +
                ' — в остальных слабейших нет вовсе («без игры»: BYE вместо доп. матчей)');
}

/* ══ ТРЕТЬЯ ПЛАНКА: СЕЯНЫЕ И BYE СТОЯТ ТАМ, ГДЕ РЕШЕНО ════════════════
   ПОЧЕМУ ОНА ПОЯВИЛАСЬ. Первые две планки мерил прувер четырьмя откатами
   сверх своих пяти, и ТРИ ИЗ ЧЕТЫРЁХ правило не уронили: «двигать обменами
   и сеяных», «не занимать слоты под BYE», «не сортировать слоты от трудных
   к лёгким» — всё проходило. Значит две планки мерили НЕ ВСЁ решение: обмен
   мог увезти сеяного с его позиции посева, а BYE — достаться не тому, и
   сторож бы молчал. Померено, а не предположено.

   ЧТО ПРОВЕРЯЕТСЯ:
     1) первые места стоят РОВНО на `SEED_POSITIONS[размер]`, по порядку —
        сеяный №1 на первой позиции списка, №2 на второй и так далее;
     2) пустые клетки (BYE) стоят В ПАРАХ верхних сеяных — проход без игры
        принадлежит сильнейшим, решение Кости 29.09, а не достаётся кому
        попало после обменов. */
console.log('');
console.log('  СЕЯНЫЕ И BYE — НА СВОИХ МЕСТАХ');
console.log('  признак беды: сеяный уехал с позиции посева или BYE достался не верхнему сеяному');
console.log('');
let бедС = 0;
for (const формат of ФОРМАТЫ) {
  for (const выходят of ВЫХОДЯТ) {
    for (const групп of ГРУПП) {
        let р;
        try { р = раскладСлотов({ qualifiers_per_group: выходят, playoff_format: формат.playoff_format }, групп); }
        catch (e) { continue; }
        const сетка = р.сетка, размер = р.размер;
        /* ПОКРЫТИЕ ПОЛНОЕ С 16.10. Раньше здесь стоял пропуск: сетки 2 и 4
           жили запасными списками внутри `bracket.js`, и планка мерила 34
           расклада из 42. Списки сведены в `SEED_POSITIONS`, пропуск снят —
           нет списка, значит беда, а не «не наш размер». */
        const позиции = среда.SEED_POSITIONS[размер];
        if (!позиции) {
            console.log('  ✗ ' + формат.имя + ' ' + групп + ' × ' + выходят +
                        ' — для сетки ' + размер + ' нет позиций в SEED_POSITIONS');
            бедС++; continue;
        }

        /* 1. Сеяные по порядку на своих позициях */
        let сеяных = 0;
        for (let п = 0; п < размер; п++) if (сетка[п] && сетка[п].посев) сеяных++;
        let сбой = '';
        for (let н2 = 1; н2 <= сеяных; н2++) {
            const ждём = позиции[н2 - 1] - 1;
            const кто = сетка[ждём];
            if (!кто || кто.посев !== н2) {
                сбой = 'сеяный №' + н2 + ' не на позиции ' + позиции[н2 - 1] +
                       ' (там ' + (кто ? (кто.метка + ', посев ' + кто.посев) : 'пусто') + ')';
                break;
            }
        }

        /* 2. BYE ДОСТАЁТСЯ СЕЯНЫМ — И ЭТО ОТНОШЕНИЕ, А НЕ ЧИСЛО.
           Первая редакция требовала, чтобы КАЖДАЯ пустая клетка стояла в
           паре сеяного, и упала на двух раскладах — «без игры» 6×3 и 7×3,
           где пустых 14 при шести сеяных. Планка была невыполнима в
           принципе: пар у сеяных ровно столько, сколько сеяных. Это та же
           ошибка, что с «тремя по двум половинам», и поймал её прогон.

           Верное отношение: пустых клеток в парах сеяных не меньше, чем
           min(пустых, сеяных) — проход без игры достаётся сильнейшим, пока
           сильнейшие есть. Померено по всем раскладам: держится везде. */
        if (!сбой) {
            const пустые = [];
            for (let п = 0; п < размер; п++) if (!сетка[п]) пустые.push(п);
            let сеяныхВсего = 0;
            for (let п2 = 0; п2 < размер; п2++) if (сетка[п2] && сетка[п2].посев) сеяныхВсего++;
            const вПарах = пустые.filter(function (п3) {
                const сосед = сетка[(п3 % 2 === 0) ? п3 + 1 : п3 - 1];
                return сосед && сосед.посев;
            }).length;
            const ждём = Math.min(пустые.length, сеяныхВсего);
            if (вПарах < ждём) {
                сбой = 'проход без игры достался сеяным ' + вПарах + ' раз из ' + ждём +
                       ' возможных (пустых ' + пустые.length + ', сеяных ' + сеяныхВсего + ')';
            }
        }

        if (сбой) {
            console.log('  ✗ ' + формат.имя + ' ' + групп + ' групп × ' + выходят + ' — ' + сбой);
            бедС++;
        }
    }
  }
}
if (бедС === 0) console.log('  ок      все ' + всего + ' раскладов: сеяные на позициях посева, BYE у верхних сеяных');

/* ══ ЧЕТВЁРТАЯ ПЛАНКА: НИ ОДИН УЧАСТНИК НЕ ТЕРЯЕТСЯ ══════════════════
   САМАЯ ТЯЖЁЛАЯ БЕДА КУСКА, И НАЙДЕНА ОНА ТОЛЬКО ТЕМ, ЧТО ТРЕТЬЯ ПЛАНКА
   ЗАСТАВИЛА СРАВНИТЬ СЕТКУ СО СПИСКОМ ЛЮДЕЙ. Позиций посева ровно половина
   сетки, и при «выходит один» с пятью и более группами первых мест больше,
   чем позиций: лишние не попадали ни в сеяных, ни в `остальные`. При восьми
   группах в сетку вставали ЧЕТЫРЕ победителя из восьми.

   Проверка простая и не зависит от расклада: сколько прямых мест
   разыгрывается (групп × выходящих), столько метко�� с группой и должно
   стоять в сетке. Ни одной меньше. */
console.log('');
console.log('  НИ ОДИН УЧАСТНИК НЕ ТЕРЯЕТСЯ');
console.log('  признак беды: прямых мест разыгрывается больше, чем стоит в сетке');
console.log('');
let бедП = 0, потеряноВсего = 0;
for (const формат of ФОРМАТЫ) {
  for (const выходят of ВЫХОДЯТ) {
    for (const групп of ГРУПП) {
        let р;
        try { р = раскладСлотов({ qualifiers_per_group: выходят, playoff_format: формат.playoff_format }, групп); }
        catch (e) { continue; }
        const надо = групп * выходят;
        const стоит = р.сетка.filter(function (к) { return к && к.группа >= 0; }).length;
        if (стоит < надо) {
            const есть = {};
            р.сетка.forEach(function (к) { if (к && к.группа >= 0) есть[к.метка] = 1; });
            const нет = [];
            for (let м = 1; м <= выходят; м++) {
                for (let г = 0; г < групп; г++) {
                    const метка = KSLT_RULES.букваГруппы(г + 1) + м;
                    if (!есть[метка]) нет.push(метка);
                }
            }
            console.log('  ✗ ' + формат.имя + ' ' + групп + ' групп × ' + выходят +
                        ' — потеряно ' + (надо - стоит) + ': ' + нет.join(' '));
            бедП++; потеряноВсего += надо - стоит;
        }
    }
  }
}
if (бедП === 0) console.log('  ок      все ' + всего + ' раскладов: в сетке стоят все, кто вышел из групп');
else console.log('\n          всего потеряно участников: ' + потеряноВсего);

бед += бедQ + бедС + бедП;
console.log('');
if (бед === 0) {
    console.log('  ок      все ' + всего + ' раскладов держат планку');
    console.log('          земляки нигде не сходятся раньше, чем решено\n');
} else {
    console.log('  НЕ ТАК  ' + бед + ' раскладов из ' + всего + ' планку не держат\n');
    process.exitCode = 1;
}
