#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ПРАВИЛО ПАРОЛЯ ОДНО» (02.11).
 *
 * ЗАМЕР, С КОТОРОГО ВСЁ НАЧАЛОСЬ. Правило жило в ЧЕТЫРЁХ местах и в
 * ДВУХ видах: сайт при регистрации и две смены пароля в приложении
 * требовали восемь знаков, заглавную, цифру и знак препинания, а смена
 * пароля В КАБИНЕТЕ — шесть знаков и ничего больше.
 *
 * СЛАБЕЕ ОКАЗАЛОСЬ ТО МЕСТО, КОТОРЫМ ПОЛЬЗУЮТСЯ ЧАЩЕ. Человек,
 * сменивший пароль в кабинете, получал «123456» там, где при
 * регистрации у него потребовали бы восемь со знаком препинания. Дверь
 * заперта, а окно открыто — и заметить это можно было только сравнив
 * два экрана подряд.
 *
 * ПОДПИСЬ ВРАЛА ЗАОДНО С КОДОМ: в словаре стояло «Минимум 6 символов»,
 * и она честно описывала слабую проверку. Сведение правила без правки
 * подписи оставило бы человека с требованием, которого он не видит.
 *
 * ЧТО СТЕРЕЖЁТСЯ: что правило не написано заново ни в одном экране и
 * что длина не опускается ниже восьми.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ. Прибор читает код. Насколько пароль хорош на самом
 * деле, он не знает: это вопрос к тому, кто правило придумывал.
 *
 *   node tools/check-pravilo-parolya.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ДОМ = 'js/kslt-parol.js';
const ПРИЛОЖЕНИЕ = 'mobile/www/js';

function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function безКом(т) {
    return (т || '').replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');
}
function файлы(д, вых) {
    вых = вых || [];
    const п = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(п)) return вых;
    for (const э of fs.readdirSync(п, { withFileTypes: true })) {
        const о = д + '/' + э.name;
        if (э.isDirectory()) { if (э.name !== 'vendor') файлы(о, вых); }
        else if (э.name.endsWith('.js')) вых.push(о);
    }
    return вых;
}

/**
 * СВОЯ ПРОВЕРКА ПАРОЛЯ — строка, где длина сравнивается с числом РЯДОМ
 * с проверкой на заглавную или на знак препинания. Одна голая длина
 * (`code.length < 6` у кода из письма) — не правило пароля, и считать
 * её бедой значит кричать волками.
 */
function свои(т) {
    return безКом(т).split('\n').filter(с =>
        /\.length\s*[<>]=?\s*\d/.test(с) &&
        /\[A-Z|A-ZА-Я|0-9\]|!@#\$/.test(с)
    ).length;
}

const все = файлы(ПРИЛОЖЕНИЕ).concat(['js/auth.js']);
const свои_места = [];
for (const ф of все) {
    if (ф === ДОМ || ф === ПРИЛОЖЕНИЕ + '/kslt-parol.js') continue;
    const н = свои(чит(ф));
    if (н) свои_места.push({ ф, н });
}

const дом = безКом(чит(ДОМ));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('правило пароля не написано заново',
    свои_места.length === 0,
    'Своя проверка пароля: ' +
    свои_места.map(о => '\n  ' + о.ф + ' — ' + о.н + ' мест').join('') +
    '\nПравило живёт в `' + ДОМ + '`. Написанное заново, оно разойдётся\n' +
    'молча — так в кабинете и оказалась планка вдвое ниже, чем на\n' +
    'регистрации.');

правило('длина не опускается ниже восьми',
    /P\.ДЛИНА\s*=\s*8\s*;/.test(дом),
    'В доме изменилась `P.ДЛИНА`. Восемь — решение продукта: столько\n' +
    'требует регистрация с сентября, и опускать планку нельзя — часть\n' +
    'паролей заведена по ней.');

правило('дом отвечает, ЧЕГО не хватает, а не только да/нет',
    /* ГРАНИЦА СЛОВА `\b` НЕ РАБОТАЕТ С КИРИЛЛИЦЕЙ: она определена по
       `[A-Za-z0-9_]`, и `\bгодится\b` не совпадает ни с чем. Правило
       упало на верном коде при первом же прогоне — поймано 02.11. */
    /* ИЩЕМ ОБЪЯВЛЕНИЕ, А НЕ УПОМИНАНИЕ: имя встречается и внутри
       `P.годится`, которая его зовёт, — и откат, снявший саму функцию,
       правило не ронял. Поймано своим же прувером 02.11. */
    /P\.чегоНеХватает\s*=/.test(дом) && /P\.годится\s*=/.test(дом),
    'В доме пропала `чегоНеХватает`. Короткий ответ «не годится»\n' +
    'заставляет человека править пароль вслепую: он не знает, мало ли\n' +
    'знаков или нет цифры.');

правило('подпись в словаре говорит то же, что проверяет код',
    (function () {
        const т = чит(ПРИЛОЖЕНИЕ + '/i18n.js');
        if (!т) return false;
        const м = т.match(/'profile\.passRule':\s*\{[^}]*\}/);
        if (!м) return false;
        /* Подпись обязана называть восемь, а не шесть: до 02.11 она
           честно описывала слабую проверку, и обе были неверны вместе. */
        return /8/.test(м[0]) && !/\b6\b/.test(м[0]);
    })(),
    'Подпись `profile.passRule` снова обещает не то, что проверяет код.\n' +
    'До 02.11 там стояло «Минимум 6 символов» — и проверка правда\n' +
    'пускала шесть. Правило и подпись меняются вместе.');

правило('прибор отличает правило пароля от проверки длины кода',
    (function () {
        /* ОБРАЗЕЦ ВНУТРЬ ПРИБОРА: голая длина (код из письма) — не
           правило пароля; длина вместе с видом знаков — правило. */
        const о = "if (code.length < 6) return;\n" +
                  "if (pw.length < 8 || !/[A-Z]/.test(pw)) return;\n" +
                  "/* pw.length < 8 || !/[A-Z]/ в подписи */\n";
        return свои(о) === 1;
    })(),
    'Образец внутри прибора: проверка длины кода из письма, настоящее\n' +
    'правило пароля и правило в подписи. Ждём РОВНО одно место. Считает\n' +
    'иначе — значит падает на проверке кода или молчит на беде.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      правило пароля: все ' + всего + ' правил держатся');
    console.log('          своих проверок 0, длина 8, подпись сверена');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  правило пароля — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
