/**
 * ЗАМОРОЗКА РОВНЫХ РЯДОВ (кусок 71, 13.10.2026).
 *
 * Пункт назывался «мелкие переливы публичной части», и перелива не нашлось
 * НИ ОДНОГО: 14 публичных страниц на 390 и 844 — ноль. Три записи пункта из
 * четырёх не подтвердились и закрыты числами. Подтвердилась одна — ряд
 * таблицы рейтинга, — и рядом нашлось то, чего в записи не было.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ:
 *   • ряды одной таблицы равны между собой на каждом виде;
 *   • высоту ряда держит СВОЙСТВО, а разделитель места не занимает;
 *   • значок стоит в одну строку — иначе он тянет ряд вверх;
 *   • дорожки бенто равны, и карточка РАСТЯГИВАЕТСЯ на свою дорожку;
 *   • оговорка о высоте накрывает ВСЕ карточки списка, а не первые три.
 *
 *   node tools/check-rovnye-ryady.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '');

const РЕЙТ = безКом(чит('css/players.css'));
const НОВ  = безКом(чит('css/news.css'));

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };
const скобка = (текст, сел) => {
    const м = текст.match(new RegExp('(?:^|\\n)' + сел.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{'));
    if (!м) return '';
    const i = м.index + 1;
    return текст.slice(i, текст.indexOf('}', i));
};

/* ══ РЯД ТАБЛИЦЫ РЕЙТИНГА ══════════════════════════════════════════════ */

const РЯД = скобка(РЕЙТ, '.pl-row');

правило('высоту ряда держит свойство, а не сумма полей',
    /min-height:\s*var\(--btn-h-lg\)/.test(РЯД),
    'правило дома, куплено на админке 08.10. Без свойства ряд собирается из\n' +
    'полей и содержимого и гуляет на пиксель от строки к строке');

правило('разделитель ряда не занимает места в потоке',
    /box-shadow:\s*inset 0 -1px 0 var\(--border-subtle\)/.test(РЯД) &&
    !/border-bottom:\s*(?:1px|var\(--bw-hair\))/.test(РЯД),
    'померено 13.10: содержимое 40 плюс поля 12 — это ровно 52, а лишний\n' +
    'пиксель давал border-bottom. У последнего ряда его не было, и ряды в\n' +
    'ОДНОЙ таблице выходили 53 и 52');

правило('последний ряд снимает тот же разделитель, которым он нарисован',
    /box-shadow:\s*none/.test(скобка(РЕЙТ, '.pl-row:last-child')),
    'если линия — тень, а снимают border, снимается не то');

правило('значок NTRP стоит в одну строку',
    /white-space:\s*nowrap/.test(скобка(РЕЙТ, '.pl-col-ntrp')),
    'померено 13.10 на 768 и 844: парное «4.5 / 4.0» переносилось, ячейка\n' +
    'выходила 48 вместо 24, и ряд — 68 при 56 у соседей. Badge 27:53 говорит\n' +
    'высоту 24 и ОДНУ строку; ту же беду ловили в админке 08.10');

/* ══ БЕНТО НОВОСТЕЙ ════════════════════════════════════════════════════ */

правило('дорожки бенто равны между собой',
    /grid-auto-rows:\s*1fr/.test(скобка(НОВ, '.news-grid.news-grid')),
    'нижний ряд жил своей жизнью: на 1024 верхние 254, нижние 278;\n' +
    'на 1512 наоборот — 265 и 254');

правило('отношение «крупная = два ряда боковых» не тронуто',
    /grid-column:\s*span 6/.test(скобка(НОВ, '.news-grid.news-grid > .tc:nth-child(1)')) &&
    /grid-row:\s*span 2/.test(скобка(НОВ, '.news-grid.news-grid > .tc:nth-child(1)')),
    'отношение заморожено 08.10 и здесь НЕ переоткрывается — оно только\n' +
    'стало накрывать все восемь карточек вместо двух');

правило('оговорка о высоте накрывает ВСЕ карточки списка',
    /\.news-grid\.tournaments-grid > \.tc \{[^}]*height:\s*auto/.test(НОВ) &&
    !/\.news-grid\.tournaments-grid > \.tc:nth-child\(-n\+3\)/.test(НОВ),
    'стояло :nth-child(-n+3) — только первые три. Замер на 844: дорожки\n' +
    'РАВНЫЕ по 303, а карточки 4–7 стояли 270, то есть не растягивались на\n' +
    'свою дорожку. Это и есть «клетка-ребёнок грида не растягивается»');

/* ══ СТОРОЖ: ОТСЕЧКА ПО НОМЕРУ РЕБЁНКА ═════════════════════════════════ */

/* Оговорка, снимающая чужую высоту, не должна считать детей: завтра карточек
   станет больше, и правило молча перестанет их накрывать — ровно так и вышло
   с первыми тремя. */
const поНомеру = (НОВ.match(/\.tc:nth-child\(-n\+\d+\)\s*\{[^}]*height/g) || []).length;
правило('высота не снимается у первых N карточек по счёту',
    поНомеру === 0,
    'найдено таких правил: ' + поНомеру + '. Правило, которое считает штуки,\n' +
    'перестаёт работать от добавления лишней — это уже ловили 09.10');

/* ══ СТОРОЖ: ПРОБНАЯ ВИТРИНА НОВОСТЕЙ — ОДНОЙ КОПИЕЙ ════════════════════ */

/* Карточки новостей в прогоне доливаются разметкой, повторяющей
   `js/news.js` → renderGrid. Таких разметок в прогоне должно быть РОВНО
   ОДНА: две копии разойдутся с отрисовкой по очереди, и беда родится ровно
   на шве. 13.10 копия была одна, но вторая проба уже собиралась её
   списать — модуль `tests/podstava-novostey.js` завёлся именно поэтому. */
const собратьТесты = (кат, список) => {
    fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(д => {
        const п = кат + '/' + д.name;
        if (д.isDirectory()) собратьТесты(п, список);
        else if (/\.js$/.test(д.name)) список.push(п);
    });
    return список;
};
const КОПИЙ_ВИТРИНЫ = собратьТесты('tests', [])
    .reduce((с, ф) => с + (чит(ф).split("a.className = 'tc проба'").length - 1), 0);
правило('пробная витрина новостей существует одной копией',
    КОПИЙ_ВИТРИНЫ === 1,
    'найдено копий: ' + КОПИЙ_ВИТРИНЫ + '. Разметка пробной карточки обязана\n' +
    'жить в tests/podstava-novostey.js и браться оттуда: ОДНО ОПРЕДЕЛЕНИЕ НА\n' +
    'ОДНО ПОНЯТИЕ. Копия, разошедшаяся с renderGrid, доказывает не то');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      ровные ряды: 9 правил');
    console.log('          высота свойством   ·   разделитель без места');
    console.log('          значок в одну строку   ·   карточка растягивается на дорожку');
    console.log('          пробная витрина новостей — одной копией');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  ровные ряды — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
