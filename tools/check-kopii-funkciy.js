const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = о => fs.readFileSync(path.join(КОРЕНЬ, о), 'utf8');

/* Комментарии гасим, СОХРАНЯЯ переводы строк. */
const чисто = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '));

/* ЗАМЕРЕНО 19.10 после сведения. Экранирование считается отдельно: у него
   своё решение, и его копии законны. */
const ПОТОЛОК_ИМЁН = 25;
const ПОТОЛОК_СТРОК = 196;

function всеJS(дир, итог) {
    итог = итог || [];
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        const п = path.join(дир, э.name);
        if (э.isDirectory()) всеJS(п, итог);
        else if (э.name.endsWith('.js')) итог.push(п);
    }
    return итог;
}

function всеHTML() {
    const итог = [];
    (function обойти(дир) {
        for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
            if (э.name.startsWith('.')) continue;
            const п = path.join(дир, э.name);
            if (э.isDirectory()) {
                if (['node_modules','test-results','mobile','lib','playwright-report','tests','tools'].indexOf(э.name) !== -1) continue;
                обойти(п);
            } else if (э.name.endsWith('.html')) итог.push(п);
        }
    })(КОРЕНЬ);
    return итог;
}

/* Функции вырезаются по балансу скобок, СЧИТАЯ С ОТКРЫВАЮЩЕЙ. */
function функции(текст) {
    const обр = /(?:^|\n)[ \t]*(?:function\s+([A-Za-zА-Яа-я_$][\w$А-Яа-я]*)\s*\([^)]*\)|(?:var|let|const)\s+([A-Za-zА-Яа-я_$][\w$А-Яа-я]*)\s*=\s*function\s*\([^)]*\))\s*\{/g;
    const итог = [];
    let м;
    while ((м = обр.exec(текст))) {
        const имя = м[1] || м[2];
        let о = текст.indexOf('{', м.index + м[0].length - 1);
        if (о === -1) continue;
        let гл = 0, конец = -1;
        for (let i = о; i < текст.length && i < о + 80000; i++) {
            if (текст[i] === '{') гл++;
            else if (текст[i] === '}') { гл--; if (гл === 0) { конец = i; break; } }
        }
        if (конец === -1) continue;
        const тело = текст.slice(о, конец + 1);
        итог.push({ имя, строк: тело.split('\n').length, норм: тело.replace(/\s+/g, ' ').trim() });
    }
    return итог;
}

const файлыJS = всеJS(path.join(КОРЕНЬ, 'js'));

/* ПРИЗНАК КОПИИ — ТЕЛО, А НЕ ИМЯ. Сначала правило группировало по имени,
   и прувер нашёл дыру: две побайтово одинаковые функции под РАЗНЫМИ
   именами проходили мимо. Это третий раз за один кусок, когда прибор
   искал имя вместо признака — и первые два раза он врал так же:
   пропустил седьмую копию уведомления (`toast` вместо `showToast`) и
   принял `admin/sections/courts.js` за `courts.js`.
   Теперь копии считаются по хешу тела, а имя идёт в подсказку. */
const поТелу = {};
for (const п of файлыJS) {
    for (const ф of функции(чисто(fs.readFileSync(п, 'utf8')))) {
        (поТелу[ф.норм] = поТелу[ф.норм] || []).push({ имя: ф.имя, строк: ф.строк, файл: п });
    }
}

/* ЭКРАНИРОВАНИЕ ИСКЛЮЧЕНО ПО ТЕЛУ, А НЕ ПО СПИСКУ ИМЁН. Список имён
   пришлось бы вести руками, и он уже был неполон: кроме `esc` и
   `escHtml` в продукте живут `escH`, `escUsrHtml`, `dbEsc` — то же
   тело под другим именем. Признак — тело: если функция гасит пять
   html-сущностей, это экранирование, и её копии законны по решению
   куска 103. */
const этоЭкранирование = тело =>
    /&amp;/.test(тело) && /&lt;/.test(тело) && /&gt;/.test(тело) &&
    /&quot;/.test(тело) && /&#39;/.test(тело);

let имён = 0, лишних = 0;
const список = [];
for (const тело in поТелу) {
    const с = поТелу[тело];
    if (с.length < 2) continue;
    if (этоЭкранирование(тело)) continue;
    /* Функция в одну строку — это не копия понятия, а совпадение записи:
       `function () { return null; }` встречается у всего продукта. */
    if (с[0].строк < 3) continue;
    имён++;
    лишних += (с.length - 1) * с[0].строк;
    const имена = {};
    с.forEach(x => { имена[x.имя] = 1; });
    список.push(Object.keys(имена).join('=') + '×' + с.length);
}

const ошибки = [];
let держится = 0;
function правило(имя, годно, подсказка) {
    if (годно) { держится++; console.log('  ✓ ' + имя); }
    else ошибки.push({ имя, подсказка });
}

/* ── 1. время расписания: одно определение ── */
const bracket = чисто(чит('js/admin/sections/bracket.js'));
const nTime = (bracket.match(/function timeToMin\s*\(/g) || []).length;
const nMin = (bracket.match(/function minToTime\s*\(/g) || []).length;
правило(
    'время расписания определено один раз, и устойчиво к числу',
    nTime === 1 && nMin === 1 && /function timeToMin\(t\) \{\s*var parts = String\(t\)/.test(bracket),
    'timeToMin: ' + nTime + ', minToTime: ' + nMin + '.\n' +
    'Стояло 4 и 3 копии — по одной внутри каждой функции расписания.\n' +
    'Три копии timeToMin писали `t.split`, одна `String(t).split` и не\n' +
    'падала на числе. Взята устойчивая: одна починена, три нет — это не\n' +
    'одинаковые копии, это РАСХОЖДЕНИЕ, где слабых большинство.');

/* ── 2. группы в половине сетки: рамка, а не середина ── */
const nHalf = (bracket.match(/function getGroupsInHalf\s*\(/g) || []).length;
правило(
    'группы в половине сетки: одно определение, сетка параметром',
    nHalf === 1 && /function getGroupsInHalf\(halfIdx, draw, halfSize\)/.test(bracket),
    'Определений: ' + nHalf + '.\n' +
    'Две копии замыкались на `draw` и `halfSize` своей функции. Поэтому\n' +
    'СВОДИТСЯ РАМКА, А НЕ СЕРЕДИНА: сетка и размер половины приходят\n' +
    'параметрами, замыкание не переезжает вместе с телом.');

/* ── 3. карта: одно определение, и оно в доме ── */
const своиКарты = файлыJS.filter(п => /function getMapEmbed\s*\(/.test(чисто(fs.readFileSync(п, 'utf8'))));
правило(
    'карта определена только в доме kslt-karta.js',
    своиКарты.length === 0 && /K\.встроить = function/.test(чит('js/kslt-karta.js')),
    'Свои определения карты остались в: ' + своиКарты.join(', ') + '.\n' +
    'Было четыре копии, и они разошлись: богатая строила карту по адресу,\n' +
    'а копия в courts.js на короткой ссылке подставляла САМУ ССЫЛКУ\n' +
    'поисковым запросом и показывала карту неизвестно чего.');

/* ── 4. дом карты подключён там, где его зовут ── */
/* СРАВНИВАЕМ ПУТЬ, А НЕ ИМЯ. По имени `courts.js` правило поймало
   `js/admin/sections/courts.js` — другой файл, который карту не зовёт.
   Это та же беда, что ловила прибор куска 102, и я завёл её снова через
   полчаса после того, как её чинил. ПУТЬ, А НЕ ИМЯ — и в приборе тоже. */
const зовутКарту = файлыJS
    .filter(п => /KSLT_KARTA\.встроить/.test(чисто(fs.readFileSync(п, 'utf8'))))
    .map(п => path.relative(КОРЕНЬ, п).split(path.sep).join('/'));
/* ПОДКЛЮЧЕНИЕ — ЭТО ТЕГ `<script src>`, А НЕ УПОМИНАНИЕ. Три стенда
   пишут «разметка та же, что собирает js/tournament-detail.js» в
   комментарии, и правило приняло это за подключение. Десятый раз за
   сессию прибор считал написание вместо признака. */
const подключённые = т => {
    const обр = /<script[^>]*\ssrc="([^"]+)"/g;
    const итог = [];
    let м;
    while ((м = обр.exec(т))) итог.push(м[1].split('?')[0].replace(/^(\.\.\/)+/, ''));
    return итог;
};
const безДомаКарты = всеHTML().filter(п => {
    const т = fs.readFileSync(п, 'utf8');
    const свои = подключённые(т);
    const зовёт = зовутКарту.some(путь => свои.indexOf(путь) !== -1);
    return зовёт && свои.indexOf('js/kslt-karta.js') === -1;
}).map(п => path.relative(КОРЕНЬ, п));
правило(
    'дом карты подключён на каждой странице, где его зовут',
    безДомаКарты.length === 0,
    'Страницы без дома: ' + безДомаКарты.join(', ') + '.\n' +
    'Дом без подключения — это не одно определение, а тихая поломка: зов\n' +
    'упадёт на той единственной странице, куда дом не донесли. Ровно это\n' +
    'закрыл сторож куска 104 в находке 96ж.');

/* ── 5. уведомление: ярлык один, потребители своего не держат ── */
const ПОТРЕБИТЕЛИ_ТОСТА = ['js/courts.js', 'js/coaches.js', 'js/invite-player.js',
    'js/battles-overview.js', 'js/battle-cards.js', 'js/match-score.js',
    'js/admin/core/utils.js'];
const своиТосты = ПОТРЕБИТЕЛИ_ТОСТА.filter(ф =>
    /function\s+(showToast|toast)\s*\([^)]*\)\s*\{[\s\S]{0,400}?(document\.createElement|KSLT_TOAST\.показать)/.test(чисто(чит(ф))));
правило(
    'уведомление: ярлык в доме, у потребителей своего определения нет',
    своиТосты.length === 0 && /window\.showToast = T\.ярлык/.test(чит('js/kslt-toast.js')),
    'Своё определение держат: ' + своиТосты.join(', ') + '.\n' +
    'Копий было СЕМЬ одной пятистрочной обёртки, и седьмую нашёл не мой\n' +
    'замер, а чужой сторож: в match-score.js она зовётся `toast`, а мой\n' +
    'прибор искал имя `showToast`.');

/* ── 6. храповик на остаток ── */
правило(
    'побайтовых копий не больше замеренного',
    имён <= ПОТОЛОК_ИМЁН && лишних <= ПОТОЛОК_СТРОК,
    'Сейчас имён ' + имён + ' (потолок ' + ПОТОЛОК_ИМЁН + '), лишних строк ' +
    лишних + ' (потолок ' + ПОТОЛОК_СТРОК + ').\n' +
    'Снижение опускает потолок вместе с собой. Экранирование не считается:\n' +
    'его копии законны по решению куска 103.\n' +
    'Сейчас: ' + список.sort().join(', '));

console.log('');
if (!ошибки.length) {
    console.log('  ок      копии функций: ' + держится + ' правил');
    console.log('          время расписания 4+3 → 1+1, группы 2 → 1, карта 4 → 1, уведомление 7 → 1');
    console.log('          остаток под храповиком: имён ' + имён + ', лишних строк ' + лишних);
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  копии функций — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
