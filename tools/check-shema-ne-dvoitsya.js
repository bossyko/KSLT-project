/**
 * ЗАМОРОЗКА СХЕМЫ ОТ ДВОЕНИЯ (кусок 197, 27.10.2026).
 *
 * ЗАМЕР: 329 файлов `sql/` (без архива и разборов), 570 объявлений
 * столбцов и 39 пар «таблица + столбец» под CHECK-списком. Расходились:
 *   • ПО ТИПУ — один столбец: `tournaments.draw_seed` объявлен `integer`
 *     в `tournament-draw-seed.sql` и `bigint` в `zerno-zhrebiya.sql`;
 *   • ПО СПИСКУ CHECK — четыре пары.
 *
 * ТРИ ИЗ ЧЕТЫРЁХ ОКАЗАЛИСЬ НЕ БЕДОЙ, А ИСТОРИЕЙ: поздняя миграция
 * снимает раннюю через `DROP CONSTRAINT`, и в снимке базы стоит именно
 * она. МЁРТВЫМ КОД НАЗЫВАЕТСЯ ПОСЛЕ ПРОВЕРКИ — то же про двоение.
 *
 * ОСТАЛИСЬ ДВЕ НАСТОЯЩИЕ, и обе — про ПОРЯДОК ПРИМЕНЕНИЯ:
 *   • `news_reactions.reaction_type`: файл-СОЗДАТЕЛЬ таблицы держал три
 *     значения, расширение до десяти лежало в другом файле. На боевой
 *     победило расширение, а на ЧИСТОЙ базе первым отработал бы
 *     создатель — и семь кнопок реакций из десяти упали бы на вставке;
 *   • `tournaments.draw_seed`: `IF NOT EXISTS` на боевой не отработал
 *     (столбец уже был `integer`), и файл с `bigint` молча не сделал
 *     того, что обещает. На чистой базе вышел бы bigint.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ:
 *   • один столбец — один тип во всех файлах схемы;
 *   • одна пара «таблица + столбец» — один список CHECK, ЕСЛИ поздний
 *     файл не снимает ранний через DROP CONSTRAINT;
 *   • файл, СОЗДАЮЩИЙ таблицу, держит тот же список, что расширение:
 *     иначе чистая база получает устаревшую схему;
 *   • тип `draw_seed` сходится с диапазоном, который пишет код.
 *
 *   node tools/check-shema-ne-dvoitsya.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* АРХИВ, РАЗБОРЫ И ДИАГНОСТИКА НЕ СЧИТАЮТСЯ: это записи о прошлом и
   читающие запросы, а не схема. */
const пропуск = ['архив', 'разбор', 'диагностика'];
const собрать = (кат, спис) => {
    fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(д => {
        const п = кат + '/' + д.name;
        if (д.isDirectory()) { if (!пропуск.includes(д.name)) собрать(п, спис); }
        else if (д.name.endsWith('.sql')) спис.push(п);
    });
    return спис;
};
const SQL = собрать('sql', []);
const СНИМОК = 'sql/схема/schema-snapshot.sql';

const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/--[^\n]*/g, '');

const ТИПЫ = '(?:timestamptz|timestamp(?:\\s+with(?:out)?\\s+time\\s+zone)?|text|varchar\\s*\\([0-9]+\\)|varchar|uuid|boolean|bool|integer|int4|int8|int|bigint|smallint|numeric\\s*\\([0-9, ]+\\)|numeric|decimal\\s*\\([0-9, ]+\\)|real|double\\s+precision|date|jsonb|json|serial|bigserial)';
const норма = s => s.replace(/\s+/g, '').toLowerCase().replace('int4', 'integer').replace(/^bool$/, 'boolean');

const типы = new Map();   // "таблица.столбец" -> [{тип, файл, строка}]
const чеки = new Map();   // "таблица.столбец" -> [{значения, файл, строка, снимает}]
const создатели = new Map(); // "таблица.столбец" -> [{значения, файл}] только из CREATE TABLE

const добавить = (карта, ключ, знач) => {
    if (!карта.has(ключ)) карта.set(ключ, []);
    карта.get(ключ).push(знач);
};

SQL.filter(ф => ф !== СНИМОК).forEach(ф => {
    const т = безКом(чит(ф));
    const строка = и => т.slice(0, и).split('\n').length;
    const снимает = /DROP\s+CONSTRAINT/i.test(т);

    let м;
    const пАльтер = new RegExp('ALTER\\s+TABLE\\s+(?:public\\.)?"?([a-z_]+)"?\\s+ADD\\s+COLUMN\\s+(?:IF\\s+NOT\\s+EXISTS\\s+)?"?([a-z_]+)"?\\s+(' + ТИПЫ + ')', 'gi');
    while ((м = пАльтер.exec(т)) !== null) {
        добавить(типы, м[1].toLowerCase() + '.' + м[2].toLowerCase(),
            { тип: норма(м[3]), ф, с: строка(м.index) });
    }

    const пСоздать = /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(?:public\.)?"?([a-z_]+)"?\s*\(([\s\S]*?)\n\s*\);/gi;
    while ((м = пСоздать.exec(т)) !== null) {
        const таб = м[1].toLowerCase(), тело = м[2], нач = строка(м.index);
        тело.split('\n').forEach(стр => {
            const s = стр.trim().replace(/,$/, '');
            if (!s || /^(?:CONSTRAINT|PRIMARY|UNIQUE|FOREIGN|CHECK|EXCLUDE)\b/i.test(s)) return;
            const mm = new RegExp('^"?([a-z_]+)"?\\s+(' + ТИПЫ + ')\\b', 'i').exec(s);
            if (mm) добавить(типы, таб + '.' + mm[1].toLowerCase(), { тип: норма(mm[2]), ф, с: нач });
        });
        const пЧек = /CHECK\s*\(\s*"?([a-z_]+)"?\s+IN\s*\(([^)]*)\)/gi;
        let c;
        while ((c = пЧек.exec(тело)) !== null) {
            const зн = c[2].split(',').map(x => x.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean).sort().join(',');
            добавить(чеки, таб + '.' + c[1].toLowerCase(), { зн, ф, с: нач, снимает });
            добавить(создатели, таб + '.' + c[1].toLowerCase(), { зн, ф });
        }
    }

    [new RegExp('ALTER\\s+TABLE\\s+(?:public\\.)?"?([a-z_]+)"?\\s+ADD\\s+CONSTRAINT[\\s\\S]{0,120}?CHECK\\s*\\(\\s*"?([a-z_]+)"?\\s+IN\\s*\\(([^)]*)\\)', 'gi'),
     new RegExp('ALTER\\s+TABLE\\s+(?:public\\.)?"?([a-z_]+)"?\\s+ADD\\s+COLUMN[\\s\\S]{0,160}?CHECK\\s*\\(\\s*"?([a-z_]+)"?\\s+IN\\s*\\(([^)]*)\\)', 'gi')]
        .forEach(п => {
            let m2;
            while ((m2 = п.exec(т)) !== null) {
                const зн = m2[3].split(',').map(x => x.trim().replace(/^['"]|['"]$/g, '')).filter(Boolean).sort().join(',');
                добавить(чеки, m2[1].toLowerCase() + '.' + m2[2].toLowerCase(),
                    { зн, ф, с: строка(m2.index), снимает });
            }
        });
});

/* ══ 1. ОДИН СТОЛБЕЦ — ОДИН ТИП ════════════════════════════════════════ */

const разныеТипы = [];
типы.forEach((v, k) => {
    const набор = [...new Set(v.map(x => x.тип))];
    if (набор.length > 1) разныеТипы.push(k + ' → ' + набор.join(' / ') + ' (' +
        v.map(x => x.ф.split('/').pop() + ':' + x.с).join(', ') + ')');
});

правило('один столбец — один тип во всех файлах схемы',
    разныеТипы.length === 0,
    'столбцов с разным типом: ' + разныеТипы.length + '\n' +
    разныеТипы.slice(0, 3).join('\n') + '\n' +
    'Какой тип выйдет — зависит от порядка применения файлов');

/* ══ 2. ОДНА ПАРА — ОДИН СПИСОК CHECK, ЕСЛИ НИКТО НЕ СНИМАЕТ ═══════════ */

/* ПОЗДНЯЯ МИГРАЦИЯ, СНИМАЮЩАЯ РАННЮЮ, — НЕ ДВОЕНИЕ, А ИСТОРИЯ. Три из
   четырёх расхождений оказались именно такими, и правило, не знающее про
   `DROP CONSTRAINT`, обвинило бы правильные файлы. */
const разныеЧеки = [];
чеки.forEach((v, k) => {
    const набор = [...new Set(v.map(x => x.зн))];
    if (набор.length < 2) return;
    if (v.some(x => x.снимает)) return;
    разныеЧеки.push(k + ' (' + v.map(x => x.ф.split('/').pop() + ':' + x.с).join(', ') + ')');
});

правило('расходящихся списков CHECK без снятия прежнего нет',
    разныеЧеки.length === 0,
    'пар с разными списками и без DROP CONSTRAINT: ' + разныеЧеки.length + '\n' +
    разныеЧеки.slice(0, 3).join('\n') + '\n' +
    'Какой список выйдет — зависит от порядка применения файлов');

/* ══ 3. СОЗДАТЕЛЬ ТАБЛИЦЫ НЕ ОТСТАЁТ ОТ РАСШИРЕНИЯ ═════════════════════ */

/* ГЛАВНОЕ ПРАВИЛО КУСКА. Боевая база уже расширена, и расхождение на ней
   не видно вовсе — оно вылезает на ЧИСТОЙ, где создатель отрабатывает
   первым. Так и было с реакциями: создатель держал три значения из
   десяти, и на новом проекте семь кнопок упали бы на вставке. */
const отстали = [];
создатели.forEach((v, k) => {
    const все = чеки.get(k) || [];
    const самыйПолный = все.reduce((a, b) => (b.зн.split(',').length > a.зн.split(',').length ? b : a), все[0]);
    v.forEach(с => {
        if (с.зн !== самыйПолный.зн && с.зн.split(',').length < самыйПолный.зн.split(',').length) {
            отстали.push(k + ': создатель ' + с.ф.split('/').pop() + ' держит ' +
                с.зн.split(',').length + ' значений, расширение ' +
                самыйПолный.ф.split('/').pop() + ' — ' + самыйПолный.зн.split(',').length);
        }
    });
});

правило('файл, создающий таблицу, не отстаёт от расширения списка',
    отстали.length === 0,
    'отставших создателей: ' + отстали.length + '\n' + отстали.slice(0, 3).join('\n') + '\n' +
    'На ЧИСТОЙ базе создатель отработает первым, и схема выйдет устаревшей');

/* ══ 4. ТИП ЗЕРНА СХОДИТСЯ С ДИАПАЗОНОМ КОДА ═══════════════════════════ */

/* ЧИСЛО В СХЕМЕ И ЧИСЛО В КОДЕ — ОДНО ПОНЯТИЕ. Зерно пишется кодом в
   диапазоне до 2147483000 и делится по модулю 2147483647: это предел
   `integer`. Поднимут тип или диапазон врозь — правило упадёт. */
const БРАКЕТ = безКом(fs.readFileSync(path.join(КОРЕНЬ, 'js/admin/sections/bracket.js'), 'utf8'));
const ЖРЕБИЙ = безКом(fs.readFileSync(path.join(КОРЕНЬ, 'js/bracket-draw.js'), 'utf8'));
const зерноТипы = (типы.get('tournaments.draw_seed') || []).map(x => x.тип);

правило('тип зерна жребия сходится с диапазоном, который пишет код',
    зерноТипы.length > 0 && зерноТипы.every(т => т === 'integer') &&
    /Math\.random\(\) \* 2147483000/.test(БРАКЕТ) && /% 2147483647/.test(ЖРЕБИЙ),
    'тип зерна ' + [...new Set(зерноТипы)].join('/') + ', а код пишет в предел integer.\n' +
    'Либо тип, либо диапазон поехал — и повторяемость жребия с ним');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      схема не двоится: 4 правила');
    console.log('          ' + SQL.length + ' файлов, ' + типы.size + ' столбцов, ' +
                чеки.size + ' пар под CHECK');
    console.log('          один столбец — один тип   ·   создатель не отстаёт');
    console.log('          снятие прежнего CHECK — история, а не двоение');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  схема двоится — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
