#!/usr/bin/env node
/**
 * ПРОЦЕНТ ПОБЕД — ОДНО ОПРЕДЕЛЕНИЕ (шаг A3.1, 29.10).
 *
 * ЗАМЕР 29.10: считался в ДЕСЯТИ местах своими руками, и расходилось не
 * число (всюду `Math.round(w / played * 100)`), а ТО, ЧТО ПОКАЗЫВАЮТ ПРИ
 * НУЛЕ ИГР: `js/dashboard.js` ставил прочерк, четыре места — `0%`.
 * «0%» значит «играл и не выиграл ни разу», «не играл» — другое
 * утверждение. Поэтому дом отдаёт `null`, а печать — прочерк.
 *
 * ЧЕТВЁРТАЯ ПЛИТКА КАБИНЕТА. Сайт показывал `rank_change`, приложение —
 * процент. Замер: `rank_change` НЕ ПЕРЕСЧИТЫВАЕТ НИКТО — ни одна
 * edge-функция его не пишет, он правится руками в админке
 * (`js/admin/sections/players.js`). Плитка, почти всегда показывающая 0,
 * — тот же вид беды, что мёртвый ползунок. Взят процент: он считается из
 * матчей, то есть из того, что заполняется само. Столбец не выброшен —
 * в карточке игрока админки он остаётся.
 *
 * ОРИЕНТИР — САЙТ (слово Кости 29.10). Здесь я от сайта ОТОШЁЛ, и это
 * названо выше числом: поле, которого никто не пишет, не данные.
 *
 * Запуск: node tools/check-procent-pobed.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
const { безКомментариев } = require('./bez-kommentariev.js');
/* СНЯТИЕ КОММЕНТАРИЕВ — ОБЩИЙ ДОМ (30.10). Своё `безКом` здесь было
   слепым: строка с `accept="image` и открывашкой блочного комментария
   внутри открывала для регулярки «комментарий» до следующей настоящей
   закрывашки, и прибор не видел кода до конца файла. Имя `безКом`
   оставлено — его зовут правила ниже. */
const безКом = безКомментариев;

const ПРАВИЛА_САЙТ = 'js/kslt-rules.js';
const ПРАВИЛА_ПРИЛ = 'mobile/www/js/kslt-rules.js';

/* Десять мест, где процент считался своими руками — замер 29.10 */
const ЗОВУЩИЕ = [
    'js/dashboard.js', 'js/player.js', 'js/admin/sections/players.js',
    'mobile/www/js/screens/profile.js', 'mobile/www/js/screens/player-detail.js',
    'mobile/www/js/app.js'
];

console.log('\n  ПРОЦЕНТ ПОБЕД — ОДНО ОПРЕДЕЛЕНИЕ\n');

правило('дом объявлен в правилах',
    /R\.процентПобед\s*=/.test(чит(ПРАВИЛА_САЙТ)) &&
    /R\.процентПобедТекст\s*=/.test(чит(ПРАВИЛА_САЙТ)),
    'В `js/kslt-rules.js` нужны оба: `процентПобед` (число или null) и\n' +
    '`процентПобедТекст` (строка с процентом или прочерк).');

правило('копии правил побайтово равны',
    чит(ПРАВИЛА_САЙТ) === чит(ПРАВИЛА_ПРИЛ),
    'Правила лежат копией в приложении. Разошлись — значит процент\n' +
    'снова считается двумя способами.');

правило('при нуле игр процента НЕТ, а не ноль',
    /if\s*\(!игр\)\s*return null;/.test(чит(ПРАВИЛА_САЙТ)),
    'Дом обязан отдавать `null` при нуле игр. «0%» — это «играл и не\n' +
    'выиграл ни разу», а не «не играл»: врать числом нельзя.');

/* ПРАВИЛО СМОТРИТ В ТЕЛО ФУНКЦИИ, А НЕ В ФАЙЛ. Первая редакция искала
   `\u2014` по всему `kslt-rules.js` — а он там встречается ДВАЖДЫ (на
   :963 и :1182, второй у чужого правила). Поэтому откат, снёсший
   прочерк из `процентПобедТекст`, правило не уронил: оно нашло чужой.
   Прувер это и показал. */
правило('печать прочерка — в доме, а не у зовущих',
    /процентПобедТекст\s*=\s*function[\s\S]{0,200}?\\u2014/.test(чит(ПРАВИЛА_САЙТ)),
    'Прочерк при нуле игр — часть понятия, а не украшение экрана.\n' +
    'Иначе один продукт напишет «—», другой «0%», как и было.');

const свои = [];
ЗОВУЩИЕ.forEach(ф => {
    const т = безКом(чит(ф));
    /* ПРИЗНАК ЛОВИЛ ТОЛЬКО ТРИ ИМЕНИ ЗНАМЕНАТЕЛЯ (`played`, `totalM`,
       `totalMatches`) — и 29.10 прувер показал, чего это стоит: откат,
       вернувший свой счёт с делением на `(wins + losses)`, правило НЕ
       УРОНИЛ. Беда не в том, КАК НАЗВАН знаменатель, а в том, что
       процент считают на месте. Признак берёт деление ПОБЕД на что
       угодно с умножением на сто; знаменатель не называется. */
    const м = т.match(/Math\.round\(\s*[^)]*(wins|\bw\b)[^)]*\/[\s\S]{0,60}?\*\s*100\s*\)/g);
    if (м) свои.push(ф + ' (' + м.length + ')');
});
правило('своих считалок процента не осталось',
    свои.length === 0,
    'Процент считается руками вне дома — ' + свои.length + ':\n' +
    свои.map(с => '  · ' + с).join('\n'));

правило('четвёртая плитка кабинета — процент, а не изменение места',
    /процентПобедТекст\(wins,\s*losses\)/.test(чит('js/dashboard.js')) &&
    !/rank_change\s*\|\|\s*0\)\s*\+\s*'<\/div><div class="db-stat-label"/.test(чит('js/dashboard.js')),
    '`rank_change` никто не пересчитывает — он правится руками в\n' +
    'админке. Плитка показывала 0 почти всем.');

правило('подпись плитки есть в трёх словарях сайта',
    (чит('js/dashboard.js').match(/winRate:\s*'/g) || []).length === 3,
    'Плитка подписывается `L.winRate` — ключ нужен в английском,\n' +
    'кыргызском и русском словарях, иначе подпись станет `undefined`.');

правило('приложение печатает процент через дом',
    /KSLT_RULES\.процентПобедТекст/.test(чит('mobile/www/js/screens/profile.js')) &&
    /KSLT_RULES\.процентПобедТекст/.test(чит('mobile/www/js/screens/player-detail.js')),
    'Приложение показывало `0%` при нуле игр. Теперь прочерк из дома.');

/* ПРИЗНАК ЛОВИТ ЛЮБУЮ ПРИПИСКУ, А НЕ ОДНУ ЗАПИСЬ. Первая редакция
   искала ровно `winRate + '%'` — а откат написал `winRate + '%</div>`,
   и правило промолчало. БЕДА ОДНА, ФОРМ У НЕЁ МНОГО: ищем знак
   процента сразу после переменной, чем бы он ни продолжался. */
/* Разметку плитки теперь даёт дом (шаг A3.5), поэтому признак ловит
   приписку в ЗОВЕ дома, а не в склейке: беда та же, место другое. */
правило('знака процента руками в плитке нет',
    !/winRate\s*\+\s*'%/.test(чит('mobile/www/js/screens/profile.js')) &&
    !/winRate\s*\+\s*'%/.test(чит('mobile/www/js/screens/player-detail.js')) &&
    !/плитка\(\s*winRate\s*\+/.test(чит('mobile/www/js/screens/profile.js')),
    'Процент печатает дом целиком — со знаком. Приписка `+ \'%\'`\n' +
    'снаружи превратила бы прочерк в «—%».');

const css = чит('mobile/www/css/app.css');

/* ПОНЯТИЕ ПЕРЕЕХАЛО — ПРАВИЛО ПЕРЕЕХАЛО ЗА НИМ (шаг A3.5, 29.10).
   Здесь стояло `.stats-grid`; после переезда плиток в общий дом сетка
   зовётся `.kst-grid`. Правило УПАЛО при переименовании, и это верно:
   ПРАВИЛО, ПОТЕРЯВШЕЕ МЕСТО, НЕ ПАДАЕТ — ОНО МОЛЧИТ, и это хуже. */
правило('сетка плиток объявлена один раз',
    (css.match(/^\.kst-grid \{/gm) || []).length === 1,
    'Объявлений было ДВА: первое (три колонки, зазор 12) полностью\n' +
    'перебивалось вторым (auto-fit, зазор 8). Замер в браузере дал\n' +
    'колонки 83.5 × 4, то есть ЧЕТЫРЕ. Мёртвым назвали после замера.');

правило('боковой отступ плитки 8, чтобы «100%» влезало',
    /padding: 16px 8px;/.test(css),
    'Замер на 390: карточка 84, место под цифру 58, «100%» при кегле 21\n' +
    'требует 60 — не влезало и ломалось. Семь вариантов мерены одним\n' +
    'прогоном: кегль 18 тоже решал, но менял высоту с 80 на 77.\n' +
    'Отступ 8 держит высоту прежней, и 8 — ступень шкалы.');

правило('подпись плитки не торчит за край',
    /letter-spacing: 0;\s*\n\s*overflow-wrap: anywhere;/.test(css),
    'Прописные и разрядка и были причиной: «ПОРАЖЕНИЯ» требовала 75 при\n' +
    'месте 66, кыргызское «ЖЕҢИЛҮҮЛӨР» — 85. Одно слово короче\n' +
    'контейнера не становится, ломаться ему нечем — оно торчало.');

/* ЧИСЛОВОЙ ЗОВ ОБЯЗАН СТОЯТЬ ПОД ПРОВЕРКОЙ. `процентПобед` отдаёт
   `null` при нуле игр, и четыре места клеят к нему знак процента в
   составе фразы («63% побед», «63%» в плашке). Все четыре защищены
   `if (!played) return ...` ВЫШЕ зова — проверено чтением 29.10.
   ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ, А НЕ ЧИСЛО: не «зовов четыре», а «у
   каждого числового зова есть проверка над ним». */
const безПроверки = [];
ЗОВУЩИЕ.forEach(ф => {
    const строки = безКом(чит(ф)).split('\n');
    строки.forEach((с, i) => {
        if (!/KSLT_RULES\.процентПобед\s*\(/.test(с)) return;
        if (/процентПобедТекст/.test(с)) return;          // текст безопасен сам
        const выше = строки.slice(Math.max(0, i - 12), i).join('\n');
        if (/if\s*\(!played\)/.test(выше)) return;
        безПроверки.push(ф + ':' + (i + 1));
    });
});
правило('у каждого числового зова есть проверка на нуль игр',
    безПроверки.length === 0,
    'Числовой `процентПобед` без `if (!played)` выше — ' +
    безПроверки.length + ':\n' + безПроверки.map(с => '  · ' + с).join('\n') +
    '\nОн отдаёт `null`, и знак процента рядом даст «null%».\n' +
    'Либо проверка выше, либо зовите `процентПобедТекст`.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      процент побед: все ' + держится + ' правил держатся\n');
}
