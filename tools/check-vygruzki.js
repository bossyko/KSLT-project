const fs = require('fs');
const path = require('path');

const корень = path.resolve(__dirname, '..');
const разделы = path.join(корень, 'js/admin/sections');
const без = т => т.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
const ошибки = [];

/* РАЗДЕЛЫ, У КОТОРЫХ ЕСТЬ ВЫГРУЗКА. Имя отбора — то, что читают и файл,
   и лист печати. У игроков отбор уходит в базу, и его имя — дом
   фильтров, через который обязаны пройти оба запроса. */
const СПИСОК = [
    { файл: 'users.js',    отбор: 'usrОтобрано',    кнопки: ['adUsrPdfBtn', 'adUsrExcelBtn'],       места: ['exportUsrExcel', 'openUsrPdfReport'] },
    { файл: 'finances.js', отбор: 'finОтобрано',    кнопки: ['adFinPdfBtn', 'adFinExcelBtn'],       места: ['exportFinExcel', 'openFinPdfReport'] },
    { файл: 'vouchers.js', отбор: 'vchFilteredData', кнопки: ['adVchExportPdf', 'adVchExcelBtn'],   места: ['exportVchExcel', 'openPdfReport'] },
    { файл: 'players.js',  отбор: 'плрФильтры',      кнопки: ['adPlrExportBtn'],                     места: ['exportPlayersExcel'] },
];

/** Тело функции по имени — балансировкой фигурных скобок. */
function тело(текст, имя) {
    const м = текст.match(new RegExp('function\\s+' + имя + '\\s*\\('));
    if (!м) return null;
    let i = текст.indexOf('{', м.index);
    if (i < 0) return null;
    let гл = 0;
    for (let j = i; j < текст.length; j++) {
        if (текст[j] === '{') гл++;
        else if (текст[j] === '}') { гл--; if (!гл) return текст.slice(i, j + 1); }
    }
    return null;
}

let кнопок = 0, мест = 0;
for (const р of СПИСОК) {
    const путь = path.join(разделы, р.файл);
    if (!fs.existsSync(путь)) { ошибки.push(`${р.файл}: раздела нет — правило стало мёртвым`); continue; }
    const т = без(fs.readFileSync(путь, 'utf8'));

    /* 1. НАДПИСЬ НАЗЫВАЕТ ТО, ЧТО ДЕЛАЕТ. */
    const зовётCsv = /A\.exportCsv\(/.test(т);
    for (const м of т.matchAll(/<button[^>]*>([^<]*Excel[^<]*)<\/button>/g)) {
        if (зовётCsv) ошибки.push(`${р.файл}: кнопка «${м[1].trim()}» подписана Excel, а файл отдаётся csv (A.exportCsv)`);
    }
    const тольКоПечать = /печатныйЛист|window\.print\(\)/.test(т) && !/\.pdf['"]/.test(т);
    for (const м of т.matchAll(/<button[^>]*>([^<]*PDF[^<]*)<\/button>/g)) {
        if (тольКоПечать) ошибки.push(`${р.файл}: кнопка «${м[1].trim()}» обещает PDF, а открывает лист для печати`);
    }

    /* 2 и 3. ВЫГРУЗКА ЧИТАЕТ ОТБОР И НЕ ЗАВОДИТ СВОЕГО. */
    for (const имя of р.места) {
        const т2 = тело(т, имя);
        if (!т2) { ошибки.push(`${р.файл}: функции ${имя} нет — выгрузка переехала, правило ослепло`); continue; }
        мест++;
        if (т2.indexOf(р.отбор) === -1) {
            ошибки.push(`${р.файл}:${имя} не читает отбор раздела «${р.отбор}» — файл разойдётся с таблицей`);
        }
        if (/\.filter\(/.test(т2)) {
            ошибки.push(`${р.файл}:${имя} отбирает сама (.filter) — это вторая копия фильтра, она отстанет от первой`);
        }
        if (/\.from\(/.test(т2) && !new RegExp(р.отбор + '\\(').test(т2)) {
            ошибки.push(`${р.файл}:${имя} делает свой запрос в базу мимо «${р.отбор}»`);
        }
    }

    /* 4. ЧИСЛО НА КНОПКЕ: у каждой кнопки есть свой зов подписи. */
    for (const id of р.кнопки) {
        кнопок++;
        if (т.indexOf("id=\"" + id + "\"") === -1 && т.indexOf("id='" + id + "'") === -1) {
            ошибки.push(`${р.файл}: кнопки ${id} больше нет — правило сторожит пустоту`);
            continue;
        }
        const естьПодпись = new RegExp("подписьВыгрузки\\((?:[^)]*)'" + id + "'").test(т);
        if (!естьПодпись) {
            ошибки.push(`${р.файл}: кнопка ${id} не получает числа строк (нет зова A.подписьВыгрузки) — человек снова не знает, что скачает`);
        }
    }
}

/* ДОМ ПОДПИСИ ОДИН И ГАСИТ НОЛЬ. */
const утилиты = без(fs.readFileSync(path.join(корень, 'js/admin/core/utils.js'), 'utf8'));
if (!/function\s+подписьВыгрузки\s*\(/.test(утилиты)) {
    ошибки.push('js/admin/core/utils.js: дома подписи выгрузки нет');
} else {
    const т2 = тело(утилиты, 'подписьВыгрузки');
    if (!/\.disabled\s*=\s*!/.test(т2 || '')) {
        ошибки.push('подписьВыгрузки больше не гасит кнопку на нуле — она зовёт скачать пустой файл');
    }
}

if (ошибки.length) {
    console.error('ВЫГРУЗКИ — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
console.log(`выгрузки: ${СПИСОК.length} раздела, ${мест} мест выгрузки читают отбор раздела, ${кнопок} кнопок несут число`);
