/**
 * ЗАМОРОЗКА «ОТСЧЁТ — ОЖИДАНИЕ, А НЕ ТРЕВОГА» (ветка B, заход B3, круг 2,
 * подкруг 2г, 15.10.2026).
 *
 * ЗАМЕР. Три беды, и в каждой эталон уже был в коде.
 *
 * 1. ОТСЧЁТ ОПРЕДЕЛЁН ДВАЖДЫ. На карточках (`.to-cd` в двух файлах,
 *    `.bo-cd`, `.tc-countdown`) — красная плашка с белым текстом. На
 *    странице турнира (`.td-cd-box` + `.td-cd-num`) — нейтральная плашка,
 *    акцентные цифры, красный ТОЛЬКО для срочного.
 *    Померено: карточки давали обычный 5.69, срочный 4.09 — НИЖЕ нормы
 *    AA 4.5, разница между ними 1.39. То есть САМОЕ СРОЧНОЕ читалось хуже
 *    обычного, а градация не работала вовсе. Страница турнира: 14.19 и
 *    4.99, разница 2.84.
 *    Плюс красный отсчёт стоял в 1.70 от эфира — ровно то схлопывание,
 *    которое Костя отверг по снимку в 2б.
 *    У красной плашки было обоснование в коде: «белым он терялся среди
 *    прочего текста». Довод верный, вывод неверен: нейтральная плашка с
 *    акцентными цифрами теряется ЕЩЁ МЕНЬШЕ — 14.19 против 5.69.
 *    Замерено живьём после правки: обычный 14.19, срочный 5.13.
 *
 * 2. СКИДКА ОПРЕДЕЛЕНА ДВАЖДЫ: красная плашка на трёх обложках против
 *    лаймовой в шести местах — списки, карточка тренера, ваучер. Выгода
 *    не должна выглядеть тревогой, и красный к тому времени был занят
 *    отказом и эфиром.
 *
 * 3. ПРЕДУПРЕЖДЕНИЕ О РЕГИСТРАЦИИ красилось `#ffaa00` при живой роли
 *    `--warning: #FF9F43`.
 *
 * ПОСЛЕ 2г КРАСНЫЙ ЗНАЧИТ ТОЛЬКО ОТКАЗ И ЭФИР, и ничего больше.
 *
 * ПОПУТНО ЗАКРЫТО УПУЩЕНИЕ 2б: свечение значка эфира жило в
 * `@keyframes pulse-glow` со старым красным, и правило эфира его не
 * видело — `@keyframes` не селектор. Правило дополнено: оно читает кадры
 * анимаций, которые зовёт блок роли.
 *
 *   node tools/check-otschet-ozhidanie.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

function гасить(s) {
    const из = s.split('');
    s.replace(/\/\*[\s\S]*?\*\//g, (м, i) => {
        for (let k = i; k < i + м.length; k++) if (из[k] !== '\n') из[k] = ' ';
        return м;
    });
    return из.join('');
}
function блоки(текст, селектор) {
    const из = [];
    let i = 0;
    while ((i = текст.indexOf(селектор, i)) !== -1) {
        const след = текст[i + селектор.length] || '';
        i += селектор.length;
        if (/[\w-]/.test(след)) continue;
        const о = текст.indexOf('{', i), з = текст.indexOf('}', i);
        if (о === -1 || (з !== -1 && з < о)) continue;
        let гл = 1, j = о + 1;
        while (j < текст.length && гл) { if (текст[j] === '{') гл++; else if (текст[j] === '}') гл--; j++; }
        из.push(текст.slice(о + 1, j - 1));
    }
    return из;
}

/* ───────── обычный отсчёт — нейтральная плашка, акцентные цифры ───────── */

const ОБЫЧНЫЙ = [
    ['css/tournaments.css',          '.to-cd'],
    ['css/tournaments-overview.css', '.to-cd'],
    ['css/battles-overview.css',     '.bo-cd'],
    ['css/style.css',                '.tc-countdown']
];
const СРОЧНЫЙ = [
    ['css/tournaments.css',          '.to-cd-urgent'],
    ['css/tournaments-overview.css', '.to-cd-urgent'],
    ['css/battles-overview.css',     '.bo-cd-urgent'],
    ['css/style.css',                '.tc-cd-urgent']
];

const файлы = {};
[...new Set([...ОБЫЧНЫЙ, ...СРОЧНЫЙ].map(([ф]) => ф))].forEach(ф => { файлы[ф] = гасить(чит(ф)); });

const тревожные = [];
ОБЫЧНЫЙ.forEach(([ф, сел]) => {
    const т = (блоки(файлы[ф], сел)[0] || '');
    if (!т) { тревожные.push(ф + '  ' + сел + ' — блок пропал'); return; }
    if (!/background:\s*var\(--alpha-white-08\)/.test(т)) тревожные.push(ф + '  ' + сел + ' — заливка не нейтральная');
    if (!/color:\s*var\(--accent\)/.test(т))               тревожные.push(ф + '  ' + сел + ' — цифры не акцентные');
    if (/linear-gradient/.test(т))                         тревожные.push(ф + '  ' + сел + ' — вернулся градиент');
    [/220,\s*38,\s*38/, /185,\s*28,\s*28/, /#dc2626/i, /#b91c1c/i].forEach(р => {
        if (р.test(т)) тревожные.push(ф + '  ' + сел + ' — вернулась красная краска');
    });
});

правило('обычный отсчёт — ожидание, а не тревога',
    тревожные.length === 0,
    'Отсчёт снова красится тревогой: ' + тревожные.length + '.\n' + тревожные.join('\n') + '\n\n' +
    '«ДО НАЧАЛА 2 ДНЯ» — ЭТО НЕ ОПАСНОСТЬ. Красная плашка давала обычному\n' +
    '5.69, срочному 4.09 (НИЖЕ нормы 4.5), а разницу между ними 1.39 — то\n' +
    'есть самое срочное читалось хуже обычного, а градации не было вовсе.\n' +
    'Приём взят у страницы турнира, где он был с самого начала. Замерено\n' +
    'живьём после правки: 14.19 и 5.13.\n' +
    'Прежний довод «белым он терялся среди прочего текста» верен, но вывод\n' +
    'из него был неверен: нейтральная плашка с акцентными цифрами теряется\n' +
    'ЕЩЁ меньше.');

const бессрочные = [];
СРОЧНЫЙ.forEach(([ф, сел]) => {
    const т = (блоки(файлы[ф], сел)[0] || '');
    if (!т) { бессрочные.push(ф + '  ' + сел + ' — блок пропал'); return; }
    if (!/var\(--danger/.test(т)) бессрочные.push(ф + '  ' + сел + ' — срочное перестало быть тревогой');
    if (/linear-gradient/.test(т)) бессрочные.push(ф + '  ' + сел + ' — вернулся градиент');
});

правило('срочный отсчёт — единственная тревога на карточке',
    бессрочные.length === 0,
    'Срочный отсчёт не говорит `--danger`: ' + бессрочные.length + '.\n' + бессрочные.join('\n') + '\n\n' +
    'Градация держится на ДВУХ состояниях: ожидание акцентом, тревога\n' +
    'красным. Уберёшь красный у срочного — и останется одно состояние,\n' +
    'ради которого вся пара и затевалась.');

/* ───────── скидка говорит лаймом ───────── */

const СКИДКА = [
    ['css/courts.css',   '.ct-discount-overlay'],
    ['css/services.css', '.sv-discount-overlay'],
    ['css/services.css', '.sv-discount-overlay-sm']
];
const краснаяСкидка = [];
СКИДКА.forEach(([ф, сел]) => {
    const т = (блоки(гасить(чит(ф)), сел)[0] || '');
    if (!т) { краснаяСкидка.push(ф + '  ' + сел + ' — блок пропал'); return; }
    if (!/background:\s*var\(--accent\)/.test(т)) краснаяСкидка.push(ф + '  ' + сел + ' — скидка не лаймовая');
    if (/220,\s*38,\s*38|#dc2626|var\(--danger/i.test(т)) краснаяСкидка.push(ф + '  ' + сел + ' — скидка снова красная');
});

правило('скидка говорит лаймом, а не тревогой',
    краснаяСкидка.length === 0,
    'Скидка снова красная: ' + краснаяСкидка.length + '.\n' + краснаяСкидка.join('\n') + '\n\n' +
    'ВЫГОДА НЕ ДОЛЖНА ВЫГЛЯДЕТЬ ТРЕВОГОЙ. Красной скидка была только на\n' +
    'трёх обложках, а лаймовой — в шести местах: списки, карточка тренера,\n' +
    'ваучер. Это было второе определение одного понятия, и красный к тому\n' +
    'же занят отказом и эфиром.');

/* ───────── предупреждение берёт свою роль ───────── */

const TD = гасить(чит('css/tournament-detail.css'));
правило('предупреждение о регистрации берёт роль, а не своё число',
    !/#ffaa00/i.test(TD) &&
    /\.td-cd-reg-warning[\s\S]{0,200}color:\s*var\(--warning\)/.test(TD),
    'Предупреждение снова красится своим числом.\n' +
    '`#ffaa00` стоял при живой роли `--warning: #FF9F43` — второе имя на\n' +
    'одно понятие, и менять его пришлось бы в двух местах вместо одного.');

/* ───────── красный больше не значит «время» ───────── */

const ВСЕ = ['css/tournaments.css', 'css/tournaments-overview.css', 'css/battles-overview.css', 'css/style.css'];
const остатки = [];
ВСЕ.forEach(ф => {
    const т = гасить(чит(ф));
    [...ОБЫЧНЫЙ, ...СРОЧНЫЙ].filter(([x]) => x === ф).forEach(([, сел]) => {
        блоки(т, сел).forEach(б => {
            const зовёт = б.match(/animation(?:-name)?\s*:\s*([^;]+)/g) || [];
            зовёт.forEach(стр => {
                (стр.match(/[a-zA-Z][\w-]*/g) || []).forEach(имя => {
                    блоки(т, '@keyframes ' + имя).forEach(тк => {
                        if (/220,\s*38,\s*38|239,\s*68,\s*68|185,\s*28,\s*28/.test(тк))
                            остатки.push(ф + '  ' + сел + ' → @keyframes ' + имя);
                    });
                });
            });
        });
    });
});

правило('кадры анимаций отсчёта тоже без чужого красного',
    остатки.length === 0,
    'Чужой красный остался в кадрах анимации: ' + остатки.length + '.\n' + остатки.join('\n') + '\n\n' +
    'КРАСКА, СПРЯТАННАЯ В `@keyframes`, КРАСИТ РОВНО ТОТ ЖЕ ЭЛЕМЕНТ, а\n' +
    'правило, которое читает только блоки по селекторам, её не видит.\n' +
    'Именно так старый красный дожил в `pulse-glow` у значка эфира от\n' +
    'подкруга 2б до 2г.');

/* ───────── вывод ───────── */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      отсчёт и скидка: 5 правил');
    console.log('          отсчёт ожидание, срочное тревога, скидка лайм');
    console.log('          кадры анимаций проверены вместе с блоками');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  отсчёт и скидка — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          x ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
