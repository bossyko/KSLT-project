#!/usr/bin/env node
/**
 * СЛОВАРЬ ПРИЛОЖЕНИЯ — ЗАМОРОЗКА КУСКА 214 (28.10).
 *
 * ГЛАВНАЯ НАХОДКА: `I18N.currentLang` — ИМЕНИ, КОТОРОГО В `js/i18n.js`
 * НЕТ ВОВСЕ. Язык лежит в `I18N.lang`. Восемь мест читали `currentLang`,
 * всегда получали `undefined`, считали язык русским — и переводы, которые
 * админ заполнял в базе соседними столбцами (`name_en`, `name_kg`,
 * `schedule_en`, `service_name_en`), НЕ ПОКАЗЫВАЛИСЬ НИКОГДА:
 *   названия ачивок и описания — 24 строки на одном экране,
 *   названия разрядов в рейтинге,
 *   расписание и услуги кортов,
 *   содержимое страниц из `site-content` (в приложении — весь первый
 *   экран: девиз, подзаголовок, кнопка).
 * Проверено в браузере: при языке `en` `I18N.lang` = 'en', а
 * `I18N.currentLang` = undefined.
 *
 * `site-content.js` — файл, общий с сайтом. На сайте условие было просто
 * ложным (там нет `KSLT_I18N`) и язык определялся по адресу страницы;
 * в приложении адрес один на все три языка, поэтому всегда выходил
 * русский. Правка внесена в ОБЕ копии.
 *
 * ПЛЮС ЧЕТЫРЕ ГРУППЫ ЗАШИТОГО РУССКОГО, которые словарь уже умел
 * переводить: покрытия кортов (`SURFACE_MAP` — четыре слова, и в фильтре,
 * и на карточке), формат турнира (одиночный · парный · микст), окно гостя
 * на двух экранах (корты и поиск игрока).
 *
 * ПОСЛЕ, замерено в браузере с загрузкой сразу на нужном языке: на
 * английском из кода не осталось НИ ОДНОЙ русской строки — только данные
 * базы (города, названия кортов, имена игроков). На киргизском то же.
 *
 * Запуск: node tools/check-slovar-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
function безСлов(отн) {
    return чит(отн).replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const словарь = чит('mobile/www/js/i18n.js');

/* ── 1. ИМЯ ЯЗЫКА ОДНО ── */
(function имяЯзыка() {
    const иголка = 'current' + 'Lang';
    const папки = ['mobile/www/js', 'js'];
    const зовут = [];
    const обойти = дир => {
        const п = path.join(КОРЕНЬ, дир);
        if (!fs.existsSync(п)) return;
        for (const э of fs.readdirSync(п, { withFileTypes: true })) {
            const отн = дир + '/' + э.name;
            if (э.isDirectory()) { обойти(отн); continue; }
            if (!э.name.endsWith('.js')) continue;
            const т = безСлов(отн);
            if (new RegExp('I18N\\.' + иголка).test(т)) зовут.push(отн);
        }
    };
    папки.forEach(обойти);
    правило(
        'язык читается одним именем',
        зовут.length === 0,
        'Язык лежит в `I18N.lang`. Имени `I18N.' + иголка + '` в словаре\n' +
        'НЕТ ВОВСЕ — читающий всегда получает `undefined` и считает язык\n' +
        'русским. Так восемь мест годами показывали русский текст на всех\n' +
        'трёх языках, хотя переводы в базе были заполнены.\n' +
        'Зовут: ' + зовут.join(', '));
})();

/* ── 2. ВЫБОР ЯЗЫКОВОГО ПОЛЯ — ОДИН ДОМ ── */
правило(
    'дом языкового поля объявлен',
    /I18N\.поле\s*=\s*function/.test(словарь),
    '`I18N.поле(строка, основа)` — один выбор на весь продукт: берёт\n' +
    '`основа_<язык>`, а при пустом переводе — русское поле.');

(function свойВыбор() {
    const свои = [];
    const обойти = дир => {
        const п = path.join(КОРЕНЬ, дир);
        if (!fs.existsSync(п)) return;
        for (const э of fs.readdirSync(п, { withFileTypes: true })) {
            const отн = дир + '/' + э.name;
            if (э.isDirectory()) { обойти(отн); continue; }
            if (!э.name.endsWith('.js') || э.name === 'i18n.js') continue;
            const т = безСлов(отн);
            /* свой выбор: читают поле `*_en` или `*_kg` руками */
            if (/\[\s*base\s*\+\s*'_en'\s*\]|\.name_en\s*\)|&&\s*\w+\.schedule_en/.test(т)) свои.push(отн);
        }
    };
    обойти('mobile/www/js');
    правило(
        'языковое поле нигде не выбирается руками',
        свои.length === 0,
        'Выбор `_en` / `_kg` обязан идти через `I18N.поле`. Свой выбор —\n' +
        'это второе определение, и ровно на нём восемь мест разошлись с\n' +
        'именем языка.\nСвой выбор в: ' + свои.join(', '));
})();

/* ── 3. ЧЕТЫРЕ ГРУППЫ, КОТОРЫЕ БЫЛИ ЗАШИТЫ ── */
[['surface.hard', 'покрытия кортов'],
 ['format.singles', 'формат турнира'],
 ['guest.courtsTitle', 'окно гостя на кортах'],
 ['guest.partnersTitle', 'окно гостя в поиске игрока']].forEach(function (п) {
    const м = словарь.match(new RegExp("'" + п[0].replace('.', '\\.') + "':\\s*\\{([\\s\\S]{0,260}?)\\}"));
    правило(
        'ключ заведён на трёх языках: ' + п[1],
        !!м && /ru:/.test(м[1]) && /en:/.test(м[1]) && /kg:/.test(м[1]),
        'Ключ `' + п[0] + '` обязан быть на трёх языках сразу: ключ в\n' +
        'одном языке — это ключ, которого нет.');
});

(function зашито() {
    const проверки = [
        ['mobile/www/js/screens/courts.js', ["'Хард'", "'Грунт'", "'Трава'", "'Ковёр'"], 'покрытия кортов'],
        ['mobile/www/js/screens/tournaments.js', ["'Одиночный'", "'Парный'", "'Микст'"], 'формат турнира'],
        ['mobile/www/js/screens/courts.js', ['Все корты доступны', 'Войдите, чтобы увидеть'], 'окно гостя на кортах'],
        ['mobile/www/js/screens/partners.js', ['Все партнёры доступны'], 'окно гостя в поиске игрока']
    ];
    проверки.forEach(function (п) {
        const т = безСлов(п[0]);
        const нашлось = п[1].filter(и => т.indexOf(и) >= 0);
        правило(
            'не зашито по-русски: ' + п[2],
            нашлось.length === 0,
            'Эти слова обязаны идти из словаря, а не из кода.\n' +
            'Найдено зашитым: ' + нашлось.join(', '));
    });
})();

/* ── 4. ОБЩИЙ ФАЙЛ ПРАВЛЕН В ОБЕИХ КОПИЯХ ── */
правило(
    'общий `site-content.js` читает язык одинаково в обеих копиях',
    чит('js/site-content.js') === чит('mobile/www/js/site-content.js') &&
    /KSLT_I18N\.lang/.test(чит('js/site-content.js')),
    'Файл общий и сверяется до байта. На сайте условие было просто\n' +
    'ложным, в приложении — всегда русским: один адрес на три языка.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      словарь приложения: все ' + держится + ' правил держатся');
    console.log('          одно имя языка, один дом языкового поля\n');
}
