'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');

function обойти(д, годится, вых) {
    вых = вых || [];
    const полный = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(полный)) return вых;
    fs.readdirSync(полный, { withFileTypes: true }).forEach(э => {
        const п = д ? д + '/' + э.name : э.name;
        if (э.isDirectory()) {
            if (!/^(node_modules|\.git|android|ios|build|test-results|playwright-report|slepki|_figma)$/
                .test(э.name) && !э.name.startsWith('.')) обойти(п, годится, вых);
        } else if (годится(э.name)) вых.push(п);
    });
    return вых;
}

/* ПРОДУКТ — ЭТО РАЗМЕТКА И JS, ВКЛЮЧАЯ СТЕНДЫ И ПРИЛОЖЕНИЕ. Стенды
   считаются: пробы ходят и на них. */
const продукт = []
    .concat(обойти('', и => и.endsWith('.html')))
    .concat(обойти('js', и => и.endsWith('.js')))
    .concat(обойти('mobile/www', и => и.endsWith('.js') || и.endsWith('.html')))
    .concat(обойти('maket', и => и.endsWith('.html')));

const текстПродукта = [...new Set(продукт)]
    .map(ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8')).join('\n');

const пробы = обойти('tests', и => и.endsWith('.spec.js'));

/* `#id` И `.класс` ИЗ СЕЛЕКТОРОВ ПРОБЫ.
   КЛАССЫ ДОБАВЛЕНЫ 31.10, И ПОВОД ИЗМЕРЕН: пробы 79 и 80 искали
   `.db-stat-value`, а 29.10 (шаг A3.5) плитка числа с подписью переехала
   в дом `js/kslt-plitki.js` с приставкой `kst-`, и старого имени в
   продукте не осталось НИ ОДНОГО. Проба 80 падала «плитки статистики
   нет», а 79 — и вовсе чужими словами: `getComputedStyle` звали сразу на
   найденном узле, и падало «parameter 1 is not of type Element».
   А ВОТ КЛАССЫ ПРИБОР НЕ СМОТРИТ, И ЭТО РЕШЕНО ЗАМЕРОМ — см. подпись у
   признака `мертва` ниже: на классах он дал 15 тревог и ни одной живой
   беды. */
const ИМЯ = /#([A-Za-z][\w-]{2,})/g;

/* СЕЛЕКТОР БЕРЁТСЯ ЦЕЛИКОМ И РАЗБИРАЕТСЯ ПО ЗАПЯТЫМ — ПОПРАВКА 31.10.
   Первая редакция смотрела имена ПООДИНОЧКЕ и дала 24 ложные тревоги:
   пробы часто пишут список через запятую — `'#dbSidebar, .db-sidebar'`,
   `'#scroll-top, .back-to-top'`, — где одна ветвь живая, а вторая
   осталась от прежнего имени. Такой список работает, и беды в нём нет.
   Беда — когда МЕРТВЫ ВСЕ ВЕТВИ: тогда селектор не найдёт ничего
   никогда. Считаем так. */
const найдено = new Map();
const СЕЛЕКТОР = /(?:locator|querySelector|querySelectorAll|getElementById|\$\$?)\(\s*(['"`])([^'"`]+)\1/g;

пробы.forEach(ф => {
    const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
    const строки = т.split('\n');
    строки.forEach((с, i) => {
        let m; СЕЛЕКТОР.lastIndex = 0;
        while ((m = СЕЛЕКТОР.exec(с))) {
            const весь = m[2];
            /* `getElementById` зовут без решётки — добавим её для разбора. */
            const ветви = (/getElementById/.test(m[0]) ? '#' + весь : весь)
                .split(',').map(в => в.trim()).filter(Boolean);
            if (!ветви.length) continue;

            /* Ветвь ЖИВА, если каждое её имя (`#id`, `.класс`) есть в
               продукте. Имя одним словом, без дефиса, не считаем: оно
               слишком часто не селектор (слепое пятно названо). */
            /* ТОЛЬКО `#id`, И КЛАССЫ ОТМЕНЕНЫ ЗАМЕРОМ, А НЕ ОСТОРОЖНОСТЬЮ.
               31.10 прибор расширили на `.класс` — вышло 34 тревоги, из
               них после двух отсечек осталось 15, и ЧТЕНИЕ КАЖДОЙ
               показало: это имена, собранные в коде по частям
               (`'lm-row-' + n` в `js/live-match.js:556`,
               `'adS' + setNum + 'TB1Wrap'` в админке) либо проверки
               отсутствия, написанные без слов `toBe(0)`. Ни одной живой
               беды. Классов в продукте вдвое больше, чем `id`, и
               собирают их по частям гораздо чаще — значит на классах
               прибор даёт шум, а шумным прибором не пользуются.
               ЧТО ДЕЙСТВИТЕЛЬНО БЫЛО СРЕДИ КЛАССОВ: `.db-stat-value`,
               которого не стало после переезда плитки в дом 29.10, —
               его нашёл ПРОГОН (пробы 79 и 80), и починен он там же. */
            const мертва = в => {
                const имена = [...в.matchAll(/#([A-Za-z][\w-]{2,})/g)].map(x => x[1]);
                if (!имена.length) return false;      /* сверять нечем */
                return имена.some(и => текстПродукта.indexOf(и) === -1);
            };
            if (!ветви.every(мертва)) continue;

            /* ПРОВЕРКА ОТСУТСТВИЯ — НЕ НАХОДКА, А ПРЕДМЕТ ПРОБЫ. Пробы
               нарочно требуют, чтобы узла НЕ БЫЛО: «дубля предупреждения
               нет», «правил в строке js не осталось». Мёртвое имя там —
               ровно то, что нужно. Смотрим четыре строки вперёд: именно
               там стоит утверждение. */
            const окно = строки.slice(i, i + 4).join(' ');
            if (/toHaveCount\(0\)|toBe\(0\)|toBeNull\(\)|not\.toBeVisible|toHaveLength\(0\)|length\s*===?\s*0/
                .test(окно)) continue;

            const ключ = весь;
            if (!найдено.has(ключ)) найдено.set(ключ, []);
            найдено.get(ключ).push(ф.replace(/^tests\/e2e\//, '') + ':' + (i + 1));
        }
    });
});

console.log('');
console.log('  проб прочитано: ' + пробы.length +
            ', файлов продукта: ' + new Set(продукт).size);
if (!найдено.size) {
    console.log('  ок      ни одна проба не ищет id, которого нет в продукте вовсе\n');
    process.exit(0);
}
console.log('  СЕЛЕКТОРОВ, У КОТОРЫХ МЕРТВЫ ВСЕ ВЕТВИ: ' + найдено.size + '\n');
[...найдено.entries()]
    .sort((a, b) => b[1].length - a[1].length)
    .forEach(([имя, места]) => {
        console.log('  ' + имя + '  (' + места.length + ')');
        места.slice(0, 4).forEach(м => console.log('      ' + м));
        if (места.length > 4) console.log('      …');
    });
console.log('');
