'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');

function обойти(д, годится, вых) {
    вых = вых || [];
    const полный = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(полный)) return вых;
    fs.readdirSync(полный, { withFileTypes: true }).forEach(э => {
        const п = д ? д + '/' + э.name : э.name;
        if (э.isDirectory()) {
            if (!/^(node_modules|\.git|android|ios|build|test-results|playwright-report|slepki|_figma)$/
                .test(э.name) && !э.name.startsWith('.')) обойти(п, годится, вых);
        } else if (годится(э.name)) вых.push(п);
    });
    return вых;
}

/* ПРОДУКТ — ЭТО РАЗМЕТКА И JS, ВКЛЮЧАЯ СТЕНДЫ И ПРИЛОЖЕНИЕ. Стенды
   считаются: пробы ходят и на них. */
const продукт = []
    .concat(обойти('', и => и.endsWith('.html')))
    .concat(обойти('js', и => и.endsWith('.js')))
    .concat(обойти('mobile/www', и => и.endsWith('.js') || и.endsWith('.html')))
    .concat(обойти('maket', и => и.endsWith('.html')));

const текстПродукта = [...new Set(продукт)]
    .map(ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8')).join('\n');

const пробы = обойти('tests', и => и.endsWith('.spec.js'));

/* `#id` ИЗ СЕЛЕКТОРОВ ПРОБЫ. Берём только простые имена: составные
   селекторы (`#a .b`, `#a[x]`) дают своё имя первым, его и ловим. */
const ИМЯ = /#([A-Za-z][\w-]{2,})/g;

const найдено = new Map();
пробы.forEach(ф => {
    const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
    /* Смотрим только строки, где есть locator/querySelector/getElementById:
       `#` в комментарии или в адресе — не селектор. */
    т.split('\n').forEach((с, i) => {
        if (!/locator\(|querySelector|getElementById|\$\$?\(/.test(с)) return;
        let m; ИМЯ.lastIndex = 0;
        while ((m = ИМЯ.exec(с))) {
            const имя = m[1];
            if (текстПродукта.indexOf(имя) !== -1) continue;
            if (!найдено.has(имя)) найдено.set(имя, []);
            найдено.get(имя).push(ф.replace(/^tests\/e2e\//, '') + ':' + (i + 1));
        }
    });
});

console.log('');
console.log('  проб прочитано: ' + пробы.length +
            ', файлов продукта: ' + new Set(продукт).size);
if (!найдено.size) {
    console.log('  ок      ни одна проба не ищет id, которого нет в продукте вовсе\n');
    process.exit(0);
}
console.log('  МЁРТВЫХ ИМЁН: ' + найдено.size + '\n');
[...найдено.entries()]
    .sort((a, b) => b[1].length - a[1].length)
    .forEach(([имя, места]) => {
        console.log('  #' + имя + '  (' + места.length + ')');
        места.slice(0, 4).forEach(м => console.log('      ' + м));
        if (места.length > 4) console.log('      …');
    });
console.log('');
