#!/usr/bin/env node
/**
 * ПРИЛОЖЕНИЕ САМОДОСТАТОЧНО (кусок 04.11).
 *
 * ЗАМЕР 04.11: установленное приложение тянуло из интернета ДВЕ вещи, без
 * которых оно либо не работало, либо выглядело не так:
 *   · `supabase.js` с `unpkg.com` — без него нет ни входа, ни данных.
 *     Не «часть не работает», а БЕЛЫЙ ЭКРАН;
 *   · шрифт Inter с `fonts.googleapis.com` — нет сети, и вся лестница
 *     текста едет на системный шрифт другой ширины. Плюс запрос к Google
 *     с IP человека при КАЖДОМ запуске.
 * Третьим был `placehold.co` на подиуме рейтинга — он уносил ИМЯ ИГРОКА
 * в адресе ссылки на чужой сервер.
 *
 * ПРАВИЛО APPLE 2.5.2 ДОСЛОВНО: «Apps should be self-contained in their
 * bundles… nor may they download, install, or execute code».
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ: «всё, что приложение грузит САМО, лежит внутри».
 * Ссылка, по которой человек нажимает сам (телеграм клуба, видео матча),
 * правилом не трогается — это содержимое, а не часть приложения.
 *
 * ПОРЯДОК ПОДКЛЮЧЕНИЯ — ОТДЕЛЬНОЕ ПРАВИЛО: `supabase-config.js` читает
 * то, что положил `supabase.js`. Поменяй местами — и беда МОЛЧАЛИВАЯ:
 * ни ошибки, ни пустого экрана, просто `supabase` не определён в миг зова.
 *
 * КЫРГЫЗСКИЕ БУКВЫ СТОРОЖАТСЯ ОТДЕЛЬНО. Ң, Ө и Ү живут в наборе
 * `cyrillic-ext`, а не в `cyrillic` — это ЗАМЕРЕНО по таблице знаков
 * woff2, а не взято по памяти. Выкинь набор ради веса — и кыргызский
 * поедет на системный шрифт, что заметит только кыргызскоязычный.
 *
 *   node tools/check-prilozhenie-samo-sebe.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const П = (...ч) => path.join(КОРЕНЬ, ...ч);
const чит = ф => fs.readFileSync(П(ф), 'utf8');
const есть = ф => fs.existsSync(П(ф));

const ПРИЛ = 'mobile/www';
const СТРАНИЦА = ПРИЛ + '/index.html';
const ШРИФТЫ = ПРИЛ + '/css/fonts.css';
const БАЗА = ПРИЛ + '/js/vendor/supabase.js';

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const стр = есть(СТРАНИЦА) ? чит(СТРАНИЦА) : '';

/* ── 1. ничего исполняемого и оформляющего не грузится извне ─────────── */
const ВНЕШНИЕ = [];
const ТЯНЕТ = /<(script|link)\b[^>]*?(?:src|href)\s*=\s*"(https?:)?\/\/[^"]*"[^>]*>/gi;
let м;
while ((м = ТЯНЕТ.exec(стр)) !== null) ВНЕШНИЕ.push(м[0].slice(0, 90));

правило('страница приложения не тянет чужой код и оформление',
    ВНЕШНИЕ.length === 0,
    'внешние подключения: ' + ВНЕШНИЕ.join(' | '));

/* ── 2. дом базы лежит внутри, подключён и с версией ─────────────────── */
правило('дом базы лежит внутри приложения', есть(БАЗА), БАЗА + ' не найден');

правило('дом базы — настоящая библиотека, а не заглушка',
    есть(БАЗА) && /createClient/.test(чит(БАЗА)),
    'в ' + БАЗА + ' нет createClient');

правило('у подключения дома базы есть версия',
    /js\/vendor\/supabase\.js\?v=\d+/.test(стр),
    'js/vendor/supabase.js подключается без ?v= — в кеше останется старый');

const гдеДом = стр.indexOf('js/vendor/supabase.js');
const гдеКонфиг = стр.indexOf('js/supabase-config.js');
правило('дом базы подключён раньше своего конфига',
    гдеДом !== -1 && гдеКонфиг !== -1 && гдеДом < гдеКонфиг,
    'supabase.js подключён после supabase-config.js — в миг зова его ещё нет');

/* ── 3. шрифт свой ───────────────────────────────────────────────────── */
правило('шрифт подключается своим файлом',
    /css\/fonts\.css\?v=\d+/.test(стр),
    'css/fonts.css не подключён или без версии');

правило('файл шрифтов на месте', есть(ШРИФТЫ), ШРИФТЫ + ' не найден');

const шр = есть(ШРИФТЫ) ? чит(ШРИФТЫ) : '';
/* СЧИТАЮТСЯ ОБЪЯВЛЕНИЯ, А НЕ ВХОЖДЕНИЯ СЛОВА. Прувер показал: откат,
   переименовавший `@font-face` в `@font-face-ВЫКИНУТ`, оставлял счёт
   прежним — подстрока-то на месте. ПРАВИЛО, СЧИТАЮЩЕЕ ПОДСТРОКУ, НЕ
   СЧИТАЕТ ОБЪЯВЛЕНИЙ: нужна открывающая скобка, иначе это просто текст. */
const объявлено = (шр.match(/@font-face\s*\{/g) || []).length;
правило('объявлены все веса всех трёх наборов',
    объявлено === 18,
    'в fonts.css ' + объявлено + ' объявлений вместо 18 (3 набора × 6 весов)');

/* каждый объявленный файл обязан лежать на диске */
const нетФайла = [];
const ФАЙЛ = /url\('\.\.\/fonts\/([^']+)'\)/g;
while ((м = ФАЙЛ.exec(шр)) !== null) {
    if (!есть(ПРИЛ + '/fonts/' + м[1])) нетФайла.push(м[1]);
}
правило('каждый объявленный файл шрифта лежит на диске',
    нетФайла.length === 0,
    'объявлены, но не найдены: ' + нетФайла.join(', '));

/* ── 4. кыргызские буквы покрыты ─────────────────────────────────────── */
function вДиапазонах(текст, знак) {
    const блоки = текст.match(/unicode-range:[^;]+;/g) || [];
    return блоки.some(б => (б.match(/U\+([0-9A-Fa-f]+)(?:-([0-9A-Fa-f]+))?/g) || []).some(д => {
        const ч = д.slice(2).split('-');
        const а = parseInt(ч[0], 16);
        const бб = ч[1] ? parseInt(ч[1], 16) : а;
        return знак >= а && знак <= бб;
    }));
}
/* ПОКРЫТИЕ МЕРЯЕТСЯ У КАЖДОГО ВЕСА ОТДЕЛЬНО, А НЕ ПО ВСЕМУ ФАЙЛУ.
   Прувер показал беду: откат вынул кыргызские буквы из веса 400, а
   правило смолчало — те же знаки нашлись у веса 700, и поиск по всему
   тексту был доволен. ПРАВИЛО, ИЩУЩЕЕ ПО ВСЕМУ ФАЙЛУ, НЕ ЗАМЕЧАЕТ
   ПОТЕРИ В ОДНОЙ ЕГО ЧАСТИ. А беда настоящая: обычный текст поехал бы
   на системный шрифт, жирный остался бы Inter, и на одном экране
   оказались бы две гарнитуры. */
const ВЕСА = [400, 500, 600, 700, 800, 900];
const блокиПоВесу = {};
(шр.split('@font-face').slice(1)).forEach(б => {
    const в = (б.match(/font-weight:\s*(\d{3})/) || [])[1];
    if (в) (блокиПоВесу[в] = блокиПоВесу[в] || []).push(б);
});
[['Ң', 0x04A3], ['Ө', 0x04E9], ['Ү', 0x04AF], ['А', 0x0410], ['A', 0x0041]].forEach(([имя, код]) => {
    const безЗнака = ВЕСА.filter(в => {
        const блоки = блокиПоВесу[String(в)] || [];
        return !блоки.some(б => вДиапазонах(б, код));
    });
    правило('шрифт покрывает знак ' + имя + ' на каждом весе',
        безЗнака.length === 0,
        'U+' + код.toString(16).toUpperCase() + ' не покрыт у весов: ' + безЗнака.join(', '));
});

/* ── 5. наборы не перекрываются ──────────────────────────────────────── */
const латинскаяAвКириллице = (() => {
    const куски = шр.split('@font-face');
    return куски.some(к => /cyrillic/.test(к) && вДиапазонах(к, 0x0041));
})();
правило('наборы шрифта не перекрываются',
    !латинскаяAвКириллице,
    'латинская A объявлена в кириллическом наборе — браузер потянет лишний файл');

/* ── 6. чужих рисовалок картинок нет в живом коде ────────────────────── */
const { безКомментариев } = require('./bez-kommentariev.js');
const ЧУЖИЕ = /placehold\.co|placeholder\.com|dummyimage\.com|ui-avatars\.com/i;
const сЧужими = [];
(function обойти(д) {
    const полный = П(д);
    if (!fs.existsSync(полный)) return;
    fs.readdirSync(полный, { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) { if (э.name !== 'vendor') обойти(п); return; }
        if (!/\.(js|css|html)$/.test(э.name)) return;
        const живой = э.name.endsWith('.js') ? безКомментариев(чит(п)) : чит(п);
        if (ЧУЖИЕ.test(живой)) сЧужими.push(п);
    });
})(ПРИЛ);
правило('картинки не берутся с чужих серверов',
    сЧужими.length === 0,
    'чужая рисовалка картинок в: ' + сЧужими.join(', '));

/* ── вывод ───────────────────────────────────────────────────────────── */
const ВСЕГО = 14;
console.log('\n  ПРИЛОЖЕНИЕ САМОДОСТАТОЧНО\n');
if (ошибки.length === 0) {
    console.log('  ок      все ' + ВСЕГО + ' правил держат\n');
    process.exit(0);
}
ошибки.forEach(о => {
    console.log('  НЕ ТАК  ' + о.имя);
    console.log('          ' + о.подсказка);
});
console.log('\n  НЕ ТАК  ' + ошибки.length + ' из ' + ВСЕГО + '\n');
process.exit(1);
