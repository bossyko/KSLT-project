const fs = require('fs');
const path = require('path');

/* БАЗОВЫЙ ПРОПУСК — то, что не является кодом продукта НИКОГДА:
   чужие библиотеки, служебные каталоги, отчёты и артефакты прогонов. */
const ПРОПУСК = /^(?:node_modules|\.git|\.github|dist|build|backups|archive|coverage|test-results|playwright-report|tests[\\/]reports|\.playwright.*)$/;

/**
 * Список файлов дерева, относительными путями от корня.
 *
 * @param {string} корень   абсолютный путь
 * @param {object} [опции]
 *   расширение — '.html' по умолчанию, '' — все файлы
 *   кроме      — дополнительные имена каталогов, которые это правило
 *                не считает своими
 */
function дерево(корень, опции) {
    const о = опции || {};
    const расш = о.расширение === undefined ? '.html' : о.расширение;
    const ещё = (о.кроме || []).map(String);
    const итог = [];
    (function обойти(отн) {
        const полный = отн ? path.join(корень, отн) : корень;
        fs.readdirSync(полный, { withFileTypes: true }).forEach(э => {
            const п = отн ? отн + '/' + э.name : э.name;
            if (э.isDirectory()) {
                if (ПРОПУСК.test(э.name) || э.name.startsWith('.')) return;
                if (ещё.indexOf(э.name) !== -1) return;
                обойти(п);
            } else if (!расш || э.name.endsWith(расш)) итог.push(п);
        });
    })('');
    return итог;
}

module.exports = { дерево, ПРОПУСК };
