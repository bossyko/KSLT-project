#!/usr/bin/env node
/**
 * ЗАМОРОЗКА ИМЕНИ ИГРОКА В ТРАНСЛЯЦИИ — КАРТОЧКА СТАРШЕ СНИМКА.
 *
 * ЗАМЕР 13.11 (кусок f21), чтением, с файлами и строками. В таблице
 * `live_matches` рядом со ссылкой на игрока лежит строка `player1_name` —
 * СНИМОК имени, который админка пишет при создании трансляции. Снимок
 * нужен: его читает экран судьи (ходит по ключу, карточек не видит) и
 * любой случай, когда у человека карточки нет вовсе.
 *
 * Беда была не в снимке, а в СТАРШИНСТВЕ. Пять читателей ставили его
 * по-разному, и трое — выше живой карточки:
 *
 *     live-match.js   карточка на языке → карточка → снимок   ВЕРНО
 *     index.html      снимок → карточка
 *     index-en.html   снимок → name_en   английское имя не показывалось
 *                                        на английской главной НИ РАЗУ
 *     scoreboard.js   снимок → карточка
 *     umpire.js       только снимок      (так и оставлено: судья русский,
 *                                         языки туда не подключаются)
 *
 * А так как в режимах «турнир» и «вызов» админка пишет снимок ВСЕГДА,
 * он всегда и побеждал: переименовали человека в карточке — на главной
 * и на табло осталось старое.
 *
 * ЧТО СТЕРЕЖЁТСЯ — ПРАВИЛО, А НЕ ЗНАЧЕНИЕ:
 *
 *     снимок имени никогда не стоит первым;
 *     имя собирает дом, а не страница;
 *     дом подключён там, где его зовут, — иначе экран падает молча.
 *
 * Запуск:  node tools/check-imya-igroka.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
const ок = [];
function проверить(имя, условие, почему) {
    if (условие) ок.push(имя); else ошибки.push({ имя, почему });
}
const читать = (ф) => {
    try { return fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'); } catch (e) { return null; }
};

/* ПРИБОР НЕ УМИРАЕТ ОТ ОТСУТСТВИЯ ФАЙЛА, А ГОВОРИТ ОБ ЭТОМ. Падение
   прибора прячет беду за своим падением — урок 12.11. */
const нет = [];

// ---------- 1. дом знает про снимок и ставит его последним ----------
(function () {
    const дом = читать('js/kslt-lico.js');
    if (дом === null) { нет.push('js/kslt-lico.js'); return; }

    /* ТЕЛО БЕРЁТСЯ ПОСЛЕ СИГНАТУРЫ: слово «снимок» стоит и в самой
       строке объявления, и если считать его частью тела, то снимок
       всегда «раньше» карточки и правило зелёное всегда. Поймано на
       себе же при первом запуске. */
    const нач = дом.indexOf('function имяНаЯзыке');
    const откр = нач === -1 ? -1 : дом.indexOf('{', нач);
    const тело = откр === -1 ? '' : дом.slice(откр + 1, дом.indexOf('\n    }', откр));

    /* ТРЕТИЙ ДОВОД — ЗАГЛУШКА ЭКРАНА, и правило обязано её допускать:
       'TBD' на главных и «Игрок 1» на табло поставлены не случайно, дом
       их не решает. Проверяется ПОРЯДОК первых двух, а не длина списка. */
    проверить('дом имени принимает снимок вторым доводом',
        /function имяНаЯзыке\s*\(\s*игрок\s*,\s*снимок\s*[,)]/.test(дом),
        'Нужна подпись имяНаЯзыке(игрок, снимок). Без второго довода ' +
        'зовущие снова начнут собирать запасной ход у себя, и старшинство ' +
        'разойдётся там же, где расходилось до 13.11.');

    /* ПОРЯДОК ПРОВЕРЯЕТСЯ ПОЛОЖЕНИЕМ ВНУТРИ ТЕЛА, А НЕ НАЛИЧИЕМ СЛОВ:
       «снимок упомянут» ничего не говорит о том, кто первый. */
    const гдеКарточка = тело.indexOf('игрок.name');
    const гдеСнимок = тело.indexOf('снимок');
    проверить('в доме карточка идёт раньше снимка',
        гдеКарточка !== -1 && гдеСнимок !== -1 && гдеКарточка < гдеСнимок,
        'Снимок обязан стоять ПОСЛЕ всех полей карточки. Снимок — имя на ' +
        'момент создания трансляции, карточка — живое имя человека. Снимок ' +
        'старше живого не бывает: переименование обязано доезжать до экрана.');

    проверить('дом спрашивает язык страницы, а не путь',
        /window\.KSLT_YAZYK/.test(тело),
        'Язык берётся из дома KSLT_YAZYK. Своё вычисление языка здесь — ' +
        'второе определение одного понятия, их уже сводили куском 155.');
})();

// ---------- 2. ни один читатель не ставит снимок первым ----------
(function () {
    /* ЧИТАТЕЛИ ПЕРЕЧИСЛЕНЫ ПОИМЁННО, А НЕ НАЙДЕНЫ ОБХОДОМ: новый файл,
       забытый в этом списке, должен ловиться правилом ниже, а не тихо
       выпадать из проверки. */
    const ЧИТАТЕЛИ = ['index.html', 'index-en.html', 'index-kg.html',
                      'js/scoreboard.js', 'js/live-match.js'];

    ЧИТАТЕЛИ.forEach(function (ф) {
        const т = читать(ф);
        if (т === null) { нет.push(ф); return; }

        /* Ищем выражение «снимок ИЛИ что-то» — ровно ту запись, которой
           снимок ставился первым. В комментариях она тоже запрещена:
           пример в комментарии — такой же код, как остальной (урок 12.11),
           и следующий правщик скопирует именно его. */
        const снимокПервым = /player[12]_name\s*\|\|/.test(т);
        проверить('снимок не стоит первым: ' + ф,
            !снимокПервым,
            'В ' + ф + ' найдено выражение вида `player1_name || …`. Так ' +
            'снимок побеждает живую карточку. Имя собирает дом: ' +
            'KSLT_LICO.имяНаЯзыке(карточка, снимок).');
    });
})();

// ---------- 3. имя собирает дом, а не страница ----------
(function () {
    const ЗОВУЩИЕ = ['index.html', 'index-en.html', 'index-kg.html',
                     'js/scoreboard.js', 'js/live-match.js'];
    ЗОВУЩИЕ.forEach(function (ф) {
        const т = читать(ф);
        if (т === null) { нет.push(ф); return; }
        проверить('имя собирает дом: ' + ф,
            /KSLT_LICO\.имяНаЯзыке\(/.test(т),
            ф + ' обязан звать KSLT_LICO.имяНаЯзыке. Своя сборка имени — ' +
            'шестое определение одного понятия; их было именно столько до ' +
            '13.11, и два из них расходились между собой.');
    });

    /* СВОЯ ФУНКЦИЯ ИМЕНИ НЕ ВОЗВРАЩАЕТСЯ. Та, что жила в live-match.js,
       была верной — и именно поэтому уехала в дом целиком. Появление
       локальной копии снова разведёт поверхности. */
    const лм = читать('js/live-match.js');
    if (лм === null) нет.push('js/live-match.js');
    else проверить('в странице матча нет своей функции имени',
        !/function getPlayerName/.test(лм),
        'В js/live-match.js снова объявлена getPlayerName. Эта функция ' +
        'снята 13.11 и перенесена в дом, а не скопирована. Две сборки ' +
        'имени разойдутся на первой же правке одной из них.');
})();

// ---------- 4. дом подключён везде, где его зовут ----------
(function () {
    /* ЭКРАН, ЗОВУЩИЙ ДОМ БЕЗ ПОДКЛЮЧЕНИЯ, ПАДАЕТ МОЛЧА. Стенд табло
       поймался ровно так: он тянет тот же scoreboard.js, что и боевое
       табло, и остался бы с пустым экраном. */
    const страницы = [];
    const обход = (кат) => {
        fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(э => {
            if (э.isFile() && э.name.endsWith('.html')) страницы.push(path.join(кат, э.name));
        });
    };
    ['.', 'pages', 'maket'].forEach(к => { try { обход(к); } catch (e) { нет.push(к + '/'); } });

    const зовутДом = ['js/scoreboard.js', 'js/live-match.js'];
    const безДома = [];
    страницы.forEach(function (ф) {
        const т = читать(ф);
        if (т === null) return;
        const зовёт = зовутДом.some(j => т.indexOf(j.replace('js/', '')) !== -1)
                   || /KSLT_LICO\./.test(т);
        if (зовёт && !/kslt-lico\.js/.test(т)) безДома.push(ф);
    });
    проверить('дом подключён на каждой странице, которая его зовёт',
        безДома.length === 0,
        'Эти страницы зовут дом, но не подключают его — экран упадёт на ' +
        'первом же имени: ' + безДома.join(', '));
})();

// ---------- 5. версия дома поднята везде одинаково ----------
(function () {
    /* ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ — И ДЛЯ ВЕРСИИ ТОЖЕ. Половина
       страниц со старым номером означает старый дом из кеша: он не знает
       про снимок, и гость без карточки получит знак вопроса вместо имени.
       Это не украшение, а молчаливая потеря данных на экране. */
    const версии = new Set();
    const обойти = (кат) => {
        fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(э => {
            if (!э.isFile() || !э.name.endsWith('.html')) return;
            const т = читать(path.join(кат, э.name));
            if (т === null) return;
            const м = т.match(/kslt-lico\.js\?v=(\d+)/g) || [];
            м.forEach(x => версии.add(x));
        });
    };
    ['.', 'pages', 'maket'].forEach(к => { try { обойти(к); } catch (e) {} });
    проверить('версия дома имени одна на весь сайт',
        версии.size <= 1,
        'Страницы просят РАЗНЫЕ версии kslt-lico.js: ' +
        Array.from(версии).join(' · ') + '. Часть экранов возьмёт из кеша ' +
        'старый дом, который не знает про снимок, и покажет «?» там, где ' +
        'у человека нет карточки.');
})();

// ---------- догадка не выдаётся за уверенность (13.11) ----------
//
// Сервер различает два совпадения: точный ключ имени и совпадение по
// фамилии. Второе — догадка: так «Рома» находит «Романа», но так же
// однофамилец находит чужие 560 очков. Поэтому сервер НИЧЕГО не
// привязывает сам, а экран обязан спросить по-разному.
//
// ЧЕЛОВЕК НЕ ЧИТАЕТ ОКНО, КОТОРОЕ ВЫГЛЯДИТ КАК ПРЕЖНЕЕ. «Кажется, это
// ваша карточка» с одной кнопкой «да, это я» нажимают не глядя. Если за
// этим стоит догадка по фамилии, человек возьмёт чужой рейтинг и
// заметит нескоро, а вернуть его можно будет только запросом в базу.
(function () {
    const сервер = читать('supabase/functions/ensure-player-card/index.ts');
    if (сервер === null) { нет.push('supabase/functions/ensure-player-card/index.ts'); return; }

    проверить('сервер помечает, каким совпадением нашёл карточку',
        /match:\s*'exact'/.test(сервер) && /match:\s*'surname'/.test(сервер),
        'В ответе `candidate` обязано стоять поле match: exact или ' +
        'surname. Без него экран не отличит уверенное совпадение от ' +
        'догадки по фамилии и спросит одинаково в обоих случаях.');

    проверить('поиск по фамилии не присваивает карточку сам',
        !/match:\s*'surname'[\s\S]{0,400}?profiles[\s\S]{0,80}?update/i.test(сервер),
        'Рядом с ответом surname не должно быть записи в profiles. ' +
        'Совпадение части имени — повод спросить, а не присвоить: цена ' +
        'ошибки иначе не лишний вопрос, а чужой рейтинг в чужих руках.');

    проверить('части имени короче пяти букв в поиск не идут',
        /length\s*>\s*4/.test(сервер),
        'Нужен порог длины части строго больше четырёх. «Ким», «Хан», ' +
        '«Пак» — пол-клуба, а «уулу» и «кызы» ровно четырёхбуквенные: ' +
        'по ним в кандидаты попадёт каждый второй.');

    const каб = читать('js/dashboard.js');
    if (каб === null) { нет.push('js/dashboard.js'); return; }

    проверить('кабинет спрашивает про догадку иначе, чем про точное совпадение',
        /совпадение\s*===\s*'surname'/.test(каб) &&
        /cardMaybeTitle/.test(каб) && /cardMaybeNone/.test(каб),
        'Кабинет обязан читать match и при surname показывать другой ' +
        'заголовок, список кандидатов и ответ «ни одна не моя». Один ' +
        'вопрос на оба случая человек нажмёт не глядя.');

    проверить('кабинет показывает весь список кандидатов, а не первого',
        /кандидаты\s*&&\s*кандидаты\.length/.test(каб),
        'Сервер отдаёт до пяти кандидатов в поле candidates. Показать ' +
        'одного — значит выбрать за человека там, где уверенности нет.');

    /* СЛОВА ОКНА ЖИВУТ В СЛОВАРЕ НА ТРЁХ ЯЗЫКАХ. Пропущенный язык даёт
       не ошибку, а пустое место в окне — и человек не поймёт, о чём
       его спрашивают, ровно в тот момент, когда решает судьбу рейтинга. */
    for (const ключ of ['cardMaybeTitle', 'cardMaybeText', 'cardMaybeNone']) {
        const сколько = (каб.match(new RegExp(ключ + ':', 'g')) || []).length;
        проверить('слово окна есть на трёх языках: ' + ключ,
            сколько >= 3,
            'Ключ ' + ключ + ' найден ' + сколько + ' раз вместо трёх. ' +
            'В js/dashboard.js три словаря — русский, английский и ' +
            'кыргызский, и пустое место в окне подтверждения хуже, чем ' +
            'отсутствие окна.');
    }
})();

// ---------- смена карточки в админке (13.11) ----------
//
// Привязать карточку админка умела только тому, у кого её нет вовсе.
// Беда же обратная: карточку ЗАВЕЛИ пустую, пока настоящая лежала
// рядом. За один день 13.11 так свели девятнадцать человек — запросами
// в базу, потому что кнопки не было.
(function () {
    const адм = читать('js/admin/sections/users.js');
    if (адм === null) { нет.push('js/admin/sections/users.js'); return; }

    проверить('кнопка смены карточки есть и только у того, у кого карточка есть',
        /user\.player_id\s*&&\s*!A\.сотрудник\(user\.role\)/.test(адм) &&
        /adUsrSmenitKartu/.test(адм),
        'Нужна кнопка смены карточки под условием user.player_id и не ' +
        'сотрудник. Без неё перепривязка делается запросом в базу, а ' +
        'сотруднику карточка не заводится вовсе.');

    проверить('смена ищет карточку общим домом, а не своим поиском',
        /сменитьКарточку[\s\S]{0,1200}?KSLT_KARTOCHKA\.искать/.test(адм),
        'Поиск кандидатов обязан идти через KSLT_KARTOCHKA.искать. Свой ' +
        'поиск здесь — третье написание одного понятия, и он разойдётся ' +
        'с сервером на первой же правке ключа имени.');

    /* ГЛАВНОЕ ПРАВИЛО ЭТОГО КУСКА. Удаление карточки уводит каскадом
       результаты, историю рейтинга, значки и заявки — молча, без
       ошибки. Карточка с нулём очков вполне может держать заявку на
       турнир: так было у Атаханова 13.11, и заявку спасли только тем,
       что считали её отдельно. Проверка «points = 0» этого не видит. */
    проверить('перед удалением считаются заявки, а не только очки',
        /предложитьУбратьПустую[\s\S]{0,2000}?tournament_registrations[\s\S]{0,400}?partner_id/.test(адм),
        'Перед предложением удалить карточку обязаны считаться заявки ' +
        'игрока И заявки, где он партнёр. Ноль очков не значит «пусто»: ' +
        'на такой карточке может висеть заявка на турнир, и она уйдёт ' +
        'каскадом молча.');

    проверить('карточка с чужим хозяином не предлагается к удалению',
        /предложитьУбратьПустую[\s\S]{0,1200}?from\('profiles'\)[\s\S]{0,200}?player_id/.test(адм),
        'Перед удалением надо убедиться, что на карточку больше никто ' +
        'не ссылается: у неё мог быть второй профиль.');

    проверить('при смене не предлагается завести ещё одну карточку',
        /режим === 'smena' \? '' :/.test(адм),
        'В окне смены кнопки «всё равно новую» быть не должно: карточка ' +
        'у человека уже есть, и вторая — ровно та беда, которую эта ' +
        'кнопка разбирает.');
})();

// ---------- заглушка не становится данными (f24, 13.11) ----------
//
// У матча из сетки соперник может быть ещё не определён: полуфинал
// составлен, а кто в нём играет, решится завтра. Админка показывала в
// списке «TBD» — и та же строка уходила в базу при сохранении, потому
// что список и запись брали одно поле `_p1Name`.
//
// ЗАГЛУШКА РАЗМЕТКИ, СТАВШАЯ ДАННЫМИ, НЕ ОТЛИЧИМА ОТ ИМЕНИ. Строку
// `player1_name` читают главная, табло, страница матча и экран судьи;
// «TBD» выглядел там настоящим именем человека, и убрать его можно было
// только запросом в базу. Найдено в живой записи a38e8f0d.
(function () {
    const адм = читать('js/admin/sections/live.js');
    if (адм === null) { нет.push('js/admin/sections/live.js'); return; }

    проверить('в кэш кладётся правда, а не заглушка',
        !/_p[12]Name\s*=\s*p[12]\s*\?\s*\(?p[12]\.name\)?\s*:\s*'[^']+'/.test(адм),
        'В `m._p1Name` и `b._p1Name` не должно быть строковой заглушки: ' +
        'это же поле уходит в базу при сохранении. Пусто — значит ' +
        'карточка есть и имя берут из неё.');

    /* ПРОВЕРЯЮТСЯ ВСЕ МЕСТА, А НЕ ЛЮБОЕ ИЗ НИХ. Первая редакция искала
       одно совпадение, и откат, портивший одну строку из двух, правило
       не ронял: вторая строка отвечала за обе. Тот же урок, что 12.11. */
    const записи = (адм.match(/row\.player[12]_name\s*=\s*[^\n;]+/g) || []);
    /* «NULL УПОМЯНУТ» — ВЕРНЫЙ ПОРОГ, А НЕ «|| NULL». В свободном режиме
       стоит `p1Id ? null : p1Name`: имя пишется только когда карточки
       нет, и это тоже правильная запись. Требовать именно `|| null`
       значило бы требовать один способ там, где их два. */
    проверить('в базу не пишется заглушка вместо null',
        записи.length >= 4 && записи.every((з) => /null/.test(з)),
        'Каждая запись имени в live_matches обязана приводиться к null. ' +
        'Найдено записей: ' + записи.length + ', из них без `|| null`: ' +
        записи.filter((з) => !/null/.test(з)).length + '. Иначе на ' +
        'месте снимка окажется заглушка и будет выглядеть именем.');

    проверить('заглушка для показа объявлена одним местом',
        /function дляПоказа/.test(адм),
        'Нужна одна функция показа. Заглушка, расставленная по шести ' +
        'местам руками, разойдётся на первом же новом списке.');
})();

// ---------- раздел Live не тянет всех игроков (f18, 13.11) ----------
//
// `loadData` выбирала ВСЕХ игроков без границы при каждом входе в
// раздел — на 13.11 это 290 строк. Нужны они были ради двух вещей:
// подставить имя по id в двух списках и искать игрока в свободном
// режиме. Обе обходятся точечными запросами.
(function () {
    const жив = читать('js/admin/sections/live.js');
    if (жив === null) { нет.push('js/admin/sections/live.js'); return; }

    проверить('раздел Live не выбирает игроков без границы',
        !/from\('players'\)\s*\.select\([^)]*\)\s*\.order\('name'\)\s*\n/.test(жив) &&
        !/from\('players'\)\.select\('id, name, name_en, photo'\)\.order/.test(жив),
        'Выборка всех игроков без .in() и без .limit() вернулась. Это ' +
        'весь клуб на каждый вход в раздел ради восьми строк подсказки.');

    const выборки = (жив.match(/from\('players'\)[\s\S]{0,200}?(?=\n\s*(?:\.then|\}|;|\)))/g) || []);
    проверить('каждая выборка игроков ограничена: по id или по числу',
        выборки.length > 0 && выборки.every((в) => /\.in\(/.test(в) || /\.limit\(/.test(в)),
        'Каждый запрос к players в разделе Live обязан иметь .in() по ' +
        'нужным id или .limit(). Найдено выборок: ' + выборки.length +
        ', без границы: ' + выборки.filter((в) => !/\.in\(/.test(в) && !/\.limit\(/.test(в)).length);

    /* НАБРАННОЕ ЧЕЛОВЕКОМ УХОДИТ В СТРОКУ ФИЛЬТРА PostgREST, где запятая
       разделяет условия, скобки задают вложенность, а проценты и
       подчёркивания в ilike значат «любой текст» и «любой знак».
       Подставить туда ввод как есть — значит дать ему менять запрос. */
    проверить('набранное чистится перед подстановкой в фильтр',
        /replace\(\/\[,\(\)"%_/.test(жив) && /ilike\.%' \+ чисто/.test(жив),
        'Перед подстановкой в .or(...) из ввода обязаны выбрасываться ' +
        'запятая, скобки, кавычка, процент, подчёркивание и обратная ' +
        'косая. Иначе «Иванов, Петров» развалит запрос, а процент молча ' +
        'изменит смысл поиска.');
})();

