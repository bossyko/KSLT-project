/**
 * ЗАМОРОЗКА ДВУХ НАХОДОК ЛИНТЕРА И ПРОБЫ (кусок 200, 27.10.2026).
 *
 * 1. ФОКУС ТЕРЯЛСЯ ВМЕСТЕ С УЗЛОМ. Окно H2H на странице игрока
 *    открывается с «загрузкой», фокус ставится на кнопку закрытия — а
 *    когда приходят данные, `modal.innerHTML` перезаписывает содержимое
 *    ВМЕСТЕ С ЭТОЙ КНОПКОЙ. Узел с фокусом удалён, браузер отдаёт фокус
 *    `<body>`, и обратно внутрь его никто не возвращал: с клавиатуры
 *    человек выпадал из модального окна.
 *    Поймала проба 76 — и поймала ЧЕРЕЗ РАЗ: успела перерисовка до
 *    нажатия Tab или нет. В прогоне 27.10 она числилась flaky, и flaky
 *    здесь означало живую беду доступности, а не каприз прибора.
 *    ПЕРЕРИСОВКА ОКНА — ЭТО УДАЛЕНИЕ УЗЛА, НА КОТОРОМ СТОИТ ФОКУС.
 *
 * 2. ОТКАЗ ПО ЗАЯВКАМ ЗОВАЛИ ДВА РАЗДЕЛА. `removeRegistrations`
 *    объявлена внутри IIFE `sections/bracket.js` и наружу не выдавалась,
 *    а `sections/tournaments.js` звал её прямым именем: кнопки «Удалить
 *    выбранные» в разделе турниров после подтверждения падали
 *    `ReferenceError`, и заявки НЕ отказывались. Нашлось линтером,
 *    разобрано чтением — кнопка, пишущая в базу, не нажималась.
 *
 *   node tools/check-fokus-posle-pererisovki.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const ИГРОК = безКом(чит('js/player.js'));
const СЕТКА = безКом(чит('js/admin/sections/bracket.js'));
const ТУРНИРЫ = безКом(чит('js/admin/sections/tournaments.js'));
const ПРОБА = чит('tests/e2e/design-system/76-stranica-igroka.spec.js');

/* ══ 1. ФОКУС ВОЗВРАЩАЕТСЯ ПОСЛЕ ПЕРЕРИСОВКИ ═══════════════════════════ */

правило('кнопка закрытия после перерисовки забирает фокус назад',
    /if \(!overlay\.contains\(document\.activeElement\)\) \{[\s\S]{0,80}btn\.focus\(\)/.test(ИГРОК),
    'после перерисовки окна фокус остаётся на <body>, и с клавиатуры\n' +
    'человек выпадает из модального окна');

/* ФОКУС ЗАБИРАЕТСЯ ТОЛЬКО ЕСЛИ ОН УШЁЛ. Если человек успел встать на
   что-то внутри окна сам, отнимать у него фокус нельзя — это второй
   способ сломать то же место. */
правило('фокус не отбирается у того, кто уже внутри окна',
    /!overlay\.contains\(document\.activeElement\)/.test(ИГРОК),
    'условие снято: окно будет дёргать фокус на кнопку закрытия при\n' +
    'каждой перерисовке, даже если человек стоит на ссылке внутри');

/* ОБА ПУТИ ПЕРЕРИСОВКИ ЗОВУТ ОДНУ ФУНКЦИЮ. Пустое окно и окно с данными
   перерисовываются по-разному, а теряют фокус одинаково. */
/* ПРИЗНАК СЧИТАЕТ ЗОВЫ, А НЕ ОБЪЯВЛЕНИЕ. Первая редакция брала просто
   `attachH2HCloseBtn(overlay)` — и попадала в саму `function
   attachH2HCloseBtn(overlay)`: совпадений выходило три, и откат, снявший
   ОДИН зов, правило не ронял. Поймал прувер. */
правило('оба пути перерисовки идут через одну кнопку закрытия',
    (ИГРОК.match(/(?<!function\s)attachH2HCloseBtn\(overlay\);/g) || []).length >= 2,
    'путей перерисовки два — с данными и пустое. Если один перестанет\n' +
    'звать общую функцию, фокус на нём снова потеряется');

правило('проба ждёт признак, а не удачу',
    /!d\.querySelector\('\.h2h-loading'\) && d\.contains\(document\.activeElement\)/.test(ПРОБА),
    'правило снова жмёт Tab сразу после появления окна и станет flaky:\n' +
    'падение будет гонкой с перерисовкой, а не проверкой');

/* ══ 2. ОТКАЗ ПО ЗАЯВКАМ — ОДИН НА ДВА РАЗДЕЛА ═════════════════════════ */

правило('отказ по заявкам выдан наружу домом раздела',
    /A\.removeRegistrations = removeRegistrations;/.test(СЕТКА),
    'функция снова заперта в своём IIFE, а зовут её из чужого — кнопка\n' +
    '«Удалить выбранные» в разделе турниров упадёт ReferenceError');

правило('раздел турниров зовёт отказ через дом, а не прямым именем',
    /await A\.removeRegistrations\(/.test(ТУРНИРЫ) &&
    !/await removeRegistrations\(/.test(ТУРНИРЫ),
    'прямой зов имени из чужого IIFE не находится в области видимости');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      фокус после перерисовки: 6 правил');
    console.log('          окно возвращает фокус и не отбирает его у человека');
    console.log('          оба пути перерисовки — через одну кнопку');
    console.log('          отказ по заявкам — один на два раздела');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  фокус после перерисовки — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
