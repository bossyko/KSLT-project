const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}
function безКом(т) {
    return т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));
}

/* ШКАЛА БЕРЁТСЯ ИЗ ТОКЕНОВ, А НЕ ИЗ СВОЕГО СПИСКА. 17.10 выяснилось,
   что прибор и система разошлись: в `tokens.css` ступень 20 объявлена
   (`--space-5`, на ней же стоит `--btn-px-md`), а сторож её не знал — и
   26 законных мест числились нарушением. ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО
   ПОНЯТИЕ: шкала живёт в токенах, правило её читает. */
const ШКАЛА = new Set(['0', '0px']);
(function шкалаИзТокенов() {
    const ток = fs.readFileSync(path.join(КОРЕНЬ, 'css/tokens.css'), 'utf8');
    let м;
    const re = /--space-[\w-]+\s*:\s*([\d.]+)rem/g;
    while ((м = re.exec(ток))) ШКАЛА.add(Math.round(Number(м[1]) * 16) + 'px');
})();
/* `border-radius` ОТСЮДА УБРАН 17.10. Прибор считал радиус отступом, и
   38 из «261 отступа мимо шкалы» оказались радиусами — у них своя шкала
   (2 · 4 · 8 · 12 · 16 · 24 · 32 и полное), и мерить радиус шкалой
   отступов всё равно что мерить кегль отступом: число совпадёт, смысл
   нет. Радиусы сторожит `check-radiusy.js` на весь продукт. */
const ОТСТУПЫ = new Set(['padding', 'margin', 'margin-top', 'margin-bottom',
    'margin-left', 'margin-right', 'gap', 'row-gap', 'column-gap']);
const КРАСКИ = new Set(['color', 'background', 'background-color', 'border',
    'border-bottom', 'border-top', 'border-left', 'border-right', 'box-shadow',
    'fill', 'outline']);

/* ---- css админки ---- */
const CSS = безКом(fs.readFileSync(path.join(КОРЕНЬ, 'css/admin.css'), 'utf8'));
let краскиCSS = 0, мимоCSS = 0;
const написания = {};
let м;
const ОБЪЯВ = /([a-z-]+)\s*:\s*([^;{}]+)[;}]/g;
while ((м = ОБЪЯВ.exec(CSS))) {
    const к = м[1], v = м[2].trim();
    if (КРАСКИ.has(к)) {
        const цв = v.match(/#[0-9a-fA-F]{3,8}\b/g) || [];
        цв.forEach(ц => { краскиCSS++; написания[ц.toLowerCase()] = true; });
        /* ПРИБОР БЫЛ СЛЕП К `rgba(...)` — ПОЛОВИНА БЕДЫ ПРЯТАЛАСЬ ТАМ.
           Первая редакция считала только hex, а в `admin.css` живут ещё
           99 объявлений `rgba(...)`, из них 60 написаний ЦВЕТНЫЕ:
           rgba(244,67,54,0.15) ×9, rgba(76,175,80,0.15) ×5,
           rgba(255,152,0,0.15) ×4 — та же краска числом, просто другой
           записью. Не закрой мы это, чистка hex просто перетекла бы в
           rgba, и храповик бы молчал.
           Белые и чёрные прозрачности не считаются: это лестница
           прозрачности (`--alpha-white-*`), своё понятие и своя ветка. */
        (v.match(/rgba?\([^)]*\)/g) || []).forEach(ц => {
            const сж = ц.replace(/\s+/g, '');
            if (/^rgba?\(255,255,255/.test(сж) || /^rgba?\(0,0,0/.test(сж)) return;
            краскиCSS++; написания[сж] = true;
        });
    }
    if (ОТСТУПЫ.has(к)) {
        v.split(/\s+/).forEach(ч => {
            if (/^\d+(\.\d+)?px$/.test(ч) && !ШКАЛА.has(ч)) мимоCSS++;
        });
    }
}

/* ---- js админки ---- */
const JSФ = [];
(function обойти(д) {
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) обойти(п);
        else if (э.name.endsWith('.js')) JSФ.push(п);
    });
})('js/admin');

let инлайнов = 0, краскиJS = 0;
JSФ.forEach(ф => {
    const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
    const найдены = т.match(/style="[^"]*"/gs) || [];
    инлайнов += найдены.length;
    найдены.forEach(тег => {
        тег.split(';').forEach(об => {
            const и = об.indexOf(':');
            if (и === -1) return;
            const к = об.slice(0, и).replace(/.*"/, '').trim();
            if (КРАСКИ.has(к) && /#[0-9a-fA-F]{3,8}\b/.test(об)) краскиJS++;
        });
    });
});

/* ---- КЕГЛИ ЧИСЛОМ В js АДМИНКИ ----
   Добавлено тем же днём, следом за первой редакцией: она кегли не
   считала вовсе, а они-то и есть главная беда слоя. В `css/admin.css`
   кеглей числом НОЛЬ (все 297 на токенах) — зато в `js/admin` их 229 в
   27 написаниях, и мимо шкалы 11 · 12 · 14 · 16 · 18 · 21 · 26 · 32 · 40
   стоят `0.8rem` (12.8) 44 раза, `0.85rem` (13.6) 42, `0.9rem` (14.4) 10,
   `0.7rem` (11.2) 10. Замер 14.10 называл ровно эти числа — и они живы. */
const ШКАЛА_КЕГЛЕЙ = new Set(['11px', '12px', '14px', '16px', '18px', '21px',
    '26px', '32px', '40px', '0.6875rem', '0.75rem', '0.875rem', '1rem',
    '1.125rem', '1.3125rem', '1.625rem', '2rem', '2.5rem']);
let кеглейЧислом = 0, кеглейМимо = 0;
JSФ.forEach(ф => {
    const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
    /* ДВА НАЗВАННЫХ ИСКЛЮЧЕНИЯ, И ОБА НАЙДЕНЫ ЗАМЕРОМ, А НЕ ПРИДУМАНЫ.
       Первый проход круга 2 чуть не посадил на экранную шкалу печатный
       отчёт и эмодзи.
         • ПЕЧАТЬ — `.report-header`, `.stat-box`, `@media print`: у листа
           бумаги своя мера, экранная шкала к ней не относится (9 мест:
           users, vouchers, finances);
         • ЭМОДЗИ — размер картинки, а не текста (7 мест).
       Строки с ними не считаются вовсе; всё остальное считается. */
    т.split('\n').forEach(стр => {
        const печать = /\.report-|\.stat-box|@media print|@page/.test(стр);
        const эмодзи = /[\u{1F300}-\u{1FAFF}\u2600-\u27BF]/u.test(стр) || /emoji/.test(стр);
        if (печать || эмодзи) return;
        (стр.match(/font-size:\s*[0-9.]+(?:rem|px|em)/g) || []).forEach(зн => {
            кеглейЧислом++;
            const ч = зн.replace(/font-size:\s*/, '');
            if (!ШКАЛА_КЕГЛЕЙ.has(ч)) кеглейМимо++;
        });
    });
});

