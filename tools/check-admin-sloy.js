/**
 * АДМИНКА — СТОРОЖ-ХРАПОВИК НА ВЕСЬ СЛОЙ (ветка D, круг 1, 17.10).
 *
 * ПОЧЕМУ ЕГО НЕ БЫЛО. `css/admin.css` исключён НАМЕРЕННО из четырнадцати
 * сторожей — «админка ждёт своей ветки» (`check-cvet-imenem.js:63`,
 * `check-tochki-ostanova.js:25` и далее). Решение было верным: чистить
 * 8643 строки вместе с публичной частью значило бы не закрыть ни ту, ни
 * другую. Но пока исключение стоит, слой не сторожится НИЧЕМ, и за месяц
 * в нём прибыло.
 *
 * ЗАМЕР 17.10:
 *   css/admin.css — 171 объявление с голой краской, 49 написаний:
 *     серый 14, голубой 13, КРАСНЫЙ 9, оранжевый 6, зелёный 5, жёлтый 1,
 *     розовый 1. Отступов мимо шкалы 261: 10px(68), 6px(58), 2px(29),
 *     20px(26), 14px(20), 3px(19), 5px(12), 18px(7).
 *   js/admin — 1034 инлайна, в них 47 голых красок (18 написаний).
 *
 * ЧТО ЗАМОРОЖЕНО — ХРАПОВИК, А НЕ ЧИСТОТА. Вычистить слой одним куском
 * нельзя, и врать, что он вычищен, тоже. Потолки — сегодняшние числа:
 * рост роняет правило, снижение опускает потолок вместе с собой. Круги
 * чистки ветки D опускают их до нуля.
 *
 *   node tools/check-admin-sloy.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}
function безКом(т) {
    return т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));
}

/* ШКАЛЫ — решение Кости, те же, что у публичной части */
const ШКАЛА = new Set(['0', '0px', '4px', '8px', '12px', '16px', '24px', '32px', '40px']);
const ОТСТУПЫ = new Set(['padding', 'margin', 'margin-top', 'margin-bottom',
    'margin-left', 'margin-right', 'gap', 'row-gap', 'column-gap', 'border-radius']);
const КРАСКИ = new Set(['color', 'background', 'background-color', 'border',
    'border-bottom', 'border-top', 'border-left', 'border-right', 'box-shadow',
    'fill', 'outline']);

/* ---- css админки ---- */
const CSS = безКом(fs.readFileSync(path.join(КОРЕНЬ, 'css/admin.css'), 'utf8'));
let краскиCSS = 0, мимоCSS = 0;
const написания = {};
let м;
const ОБЪЯВ = /([a-z-]+)\s*:\s*([^;{}]+)[;}]/g;
while ((м = ОБЪЯВ.exec(CSS))) {
    const к = м[1], v = м[2].trim();
    if (КРАСКИ.has(к)) {
        const цв = v.match(/#[0-9a-fA-F]{3,8}\b/g) || [];
        цв.forEach(ц => { краскиCSS++; написания[ц.toLowerCase()] = true; });
    }
    if (ОТСТУПЫ.has(к)) {
        v.split(/\s+/).forEach(ч => {
            if (/^\d+(\.\d+)?px$/.test(ч) && !ШКАЛА.has(ч)) мимоCSS++;
        });
    }
}

/* ---- js админки ---- */
const JSФ = [];
(function обойти(д) {
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) обойти(п);
        else if (э.name.endsWith('.js')) JSФ.push(п);
    });
})('js/admin');

let инлайнов = 0, краскиJS = 0;
JSФ.forEach(ф => {
    const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
    const найдены = т.match(/style="[^"]*"/gs) || [];
    инлайнов += найдены.length;
    найдены.forEach(тег => {
        тег.split(';').forEach(об => {
            const и = об.indexOf(':');
            if (и === -1) return;
            const к = об.slice(0, и).replace(/.*"/, '').trim();
            if (КРАСКИ.has(к) && /#[0-9a-fA-F]{3,8}\b/.test(об)) краскиJS++;
        });
    });
});

/* ---- КЕГЛИ ЧИСЛОМ В js АДМИНКИ ----
   Добавлено тем же днём, следом за первой редакцией: она кегли не
   считала вовсе, а они-то и есть главная беда слоя. В `css/admin.css`
   кеглей числом НОЛЬ (все 297 на токенах) — зато в `js/admin` их 229 в
   27 написаниях, и мимо шкалы 11 · 12 · 14 · 16 · 18 · 21 · 26 · 32 · 40
   стоят `0.8rem` (12.8) 44 раза, `0.85rem` (13.6) 42, `0.9rem` (14.4) 10,
   `0.7rem` (11.2) 10. Замер 14.10 называл ровно эти числа — и они живы. */
const ШКАЛА_КЕГЛЕЙ = new Set(['11px', '12px', '14px', '16px', '18px', '21px',
    '26px', '32px', '40px', '0.6875rem', '0.75rem', '0.875rem', '1rem',
    '1.125rem', '1.3125rem', '1.625rem', '2rem', '2.5rem']);
let кеглейЧислом = 0, кеглейМимо = 0;
JSФ.forEach(ф => {
    const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
    /* ДВА НАЗВАННЫХ ИСКЛЮЧЕНИЯ, И ОБА НАЙДЕНЫ ЗАМЕРОМ, А НЕ ПРИДУМАНЫ.
       Первый проход круга 2 чуть не посадил на экранную шкалу печатный
       отчёт и эмодзи.
         • ПЕЧАТЬ — `.report-header`, `.stat-box`, `@media print`: у листа
           бумаги своя мера, экранная шкала к ней не относится (9 мест:
           users, vouchers, finances);
         • ЭМОДЗИ — размер картинки, а не текста (7 мест).
       Строки с ними не считаются вовсе; всё остальное считается. */
    т.split('\n').forEach(стр => {
        const печать = /\.report-|\.stat-box|@media print|@page/.test(стр);
        const эмодзи = /[\u{1F300}-\u{1FAFF}\u2600-\u27BF]/u.test(стр) || /emoji/.test(стр);
        if (печать || эмодзи) return;
        (стр.match(/font-size:\s*[0-9.]+(?:rem|px|em)/g) || []).forEach(зн => {
            кеглейЧислом++;
            const ч = зн.replace(/font-size:\s*/, '');
            if (!ШКАЛА_КЕГЛЕЙ.has(ч)) кеглейМимо++;
        });
    });
});

/* ПОТОЛКИ ЗАМЕРЕНЫ 17.10 ЭТИМ ЖЕ ПРИБОРОМ. Только вниз. */
const П = {
    краскиCSS: 171, написаний: 49, мимоCSS: 261,
    инлайнов: 1034, краскиJS: 47,
    /* ОПУЩЕНЫ ПОСЛЕ КРУГА 2: 204 кегля сели на токены `--fs-*`. Осталось
       25, из них 16 оказались НЕ ЭКРАННЫМ ТЕКСТОМ — печатный отчёт и
       эмодзи, — и получили названное исключение; оставшиеся 9 сели на
       ступени: PIN-поле и буква в кружке 19.2 -> 18, пояснения 13 и 15 ->
       14, метка исхода 9.6 -> 11 (ниже 11 текст перестаёт читаться).
       Было 229 и 151; 151 я сперва посчитал сам и разошёлся с прибором
       на шесть — ЧИСЛО БЕРЁТСЯ У ПРИБОРА. Теперь ноль: правило держит
       пустоту, и любой новый кегль числом роняет его сразу. */
    кеглейЧислом: 0, кеглейМимо: 0
};

правило('голых красок в admin.css не больше потолка',
    краскиCSS <= П.краскиCSS,
    'Голых красок: ' + краскиCSS + ', потолок ' + П.краскиCSS + '.\n' +
    'Краска живёт именами в `css/tokens.css`. В админке их 49 написаний —\n' +
    'красный девятью способами, голубой тринадцатью; это и чинят круги\n' +
    'ветки D. Новое написание сюда не добавляется.');

правило('написаний краски в admin.css не больше замеренного',
    Object.keys(написания).length <= П.написаний,
    'Написаний краски: ' + Object.keys(написания).length + ', было ' + П.написаний + '.\n' +
    'Каждое написание — копия понятия. Число только убывает.');

правило('отступов мимо шкалы в admin.css не больше потолка',
    мимоCSS <= П.мимоCSS,
    'Отступов мимо шкалы: ' + мимоCSS + ', потолок ' + П.мимоCSS + '.\n' +
    'Шкала — 8 · 12 · 16 · 24 · 32 · 40. В админке 261 место мимо неё:\n' +
    '10px, 6px, 2px, 20px, 14px, 3px. Нужен новый размер — он заводится\n' +
    'в компоненте, а не придумывается в правиле.');

правило('инлайнов в js/admin не больше потолка',
    инлайнов <= П.инлайнов,
    'Инлайнов: ' + инлайнов + ', потолок ' + П.инлайнов + '.\n' +
    'Оформление живёт в css классами. Инлайн в строке разметки сильнее\n' +
    'любого правила и невидим для сторожей css.');

правило('кеглей числом в js/admin не больше потолка',
    кеглейЧислом <= П.кеглейЧислом,
    'Кеглей числом: ' + кеглейЧислом + ', потолок ' + П.кеглейЧислом + '.\n' +
    'Кегль живёт токеном `--fs-*`. Число в строке мимо лестницы и мимо\n' +
    'сторожей: в `css/admin.css` кеглей числом ноль, а в js их сотни.');

правило('кеглей МИМО ШКАЛЫ в js/admin не больше потолка',
    кеглейМимо <= П.кеглейМимо,
    'Кеглей мимо шкалы: ' + кеглейМимо + ', потолок ' + П.кеглейМимо + '.\n' +
    'Шкала — 11 · 12 · 14 · 16 · 18 · 21 · 26 · 32 · 40. Мимо неё стоят\n' +
    '0.8rem (12.8), 0.85rem (13.6), 0.9rem (14.4), 0.7rem (11.2).');

правило('голых красок в инлайнах js/admin не больше потолка',
    краскиJS <= П.краскиJS,
    'Голых красок в инлайнах: ' + краскиJS + ', потолок ' + П.краскиJS + '.');

if (!ошибки.length) {
    console.log('');
    console.log('  ок      слой админки: 7 правил (храповик)');
    console.log('          admin.css: красок ' + краскиCSS + '/' + П.краскиCSS +
                ', написаний ' + Object.keys(написания).length + '/' + П.написаний +
                ', мимо шкалы ' + мимоCSS + '/' + П.мимоCSS);
    console.log('          js/admin: инлайнов ' + инлайнов + '/' + П.инлайнов +
                ', красок в них ' + краскиJS + '/' + П.краскиJS);
    console.log('          js/admin: кеглей числом ' + кеглейЧислом + '/' + П.кеглейЧислом +
                ', из них мимо шкалы ' + кеглейМимо + '/' + П.кеглейМимо);
    console.log('          потолки только вниз — круги ветки D опускают их');
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  слой админки — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
