/**
 * ЗАМОРОЗКА ОБОЛОЧКИ ОКНА АДМИНКИ — 04.10.
 *
 * Было двенадцать мест, создающих окно: три сборщика в `utils.js` и девять
 * рукодельных в разделах. Замер 04.10: `role="dialog"` и фокус были ровно у
 * одного из двенадцати, Esc — у двух, ловушки фокуса и возврата фокуса не
 * было ни у одного, включая сборщик.
 *
 * ЧТО ДЕРЖАТ ЭТИ ПРАВИЛА: оболочка одна, зовут её все, второе семейство
 * окон (`ad-modal`) в неё НЕ затянуто, и числа окна стоят на шкале.
 * Чего они не держат: как это выглядит и работает в браузере — это замер
 * и прогон.
 *
 *   node tools/check-okno-obolochka.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const УТИЛ    = безКом(чит('js/admin/core/utils.js'));
const ТУРНИРЫ = безКом(чит('js/admin/sections/tournaments.js'));
const СЕТКА   = безКом(чит('js/admin/sections/bracket.js'));
const ЮЗЕРЫ   = безКом(чит('js/admin/sections/users.js'));
const ИГРОКИ  = безКом(чит('js/admin/sections/players.js'));
const АДч     = безКом(чит('css/admin.css'));
const СТРАНИЦА = чит('pages/admin.html');
const РАЗДЕЛЫ = [СЕТКА, ЮЗЕРЫ, ИГРОКИ];

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ─────────── ОДНА ОБОЛОЧКА ─────────── */

правило('оболочка объявлена одна и отдана разделам',
    /function оболочкаОкна\(о\) \{/.test(УТИЛ) && /A\.оболочкаОкна = оболочкаОкна;/.test(УТИЛ),
    'функции `оболочкаОкна` в utils.js нет либо её перестали отдавать разделам');

/* СЧИТАЕМ, ЧТО НЕТ НИ ОДНОГО РУКОДЕЛЬНОГО, а не что оболочка есть:
   правило на присутствие оставалось бы зелёным при девяти своих окнах. */
правило('ни одно окно в разделах не строит подложку само',
    РАЗДЕЛЫ.every(р => !/className = 'ad-confirm-overlay'/.test(р)),
    'в разделе снова заводят `ad-confirm-overlay` руками — окно останется ' +
    'без role, фокуса, ловушки и Esc, как было у девяти до 04.10');

правило('все девять окон разделов зовут оболочку',
    РАЗДЕЛЫ.reduce((н, р) => н + (р.match(/A\.оболочкаОкна\(/g) || []).length, 0) >= 9,
    'окон, зовущих оболочку, стало меньше девяти — одно из них снова само по себе');

/* ВТОРОЕ СЕМЕЙСТВО НЕ ТРОГАЕМ. Пакетная правка 04.10 затащила окно
   `ad-modal` в оболочку окна подтверждения — подложка подменилась бы.
   Поймано чтением своего же diff; сторож, чтобы не повторилось. */
правило('семейство `ad-modal` строит подложку по-своему',
    /overlay\.className = 'ad-modal-overlay';/.test(СЕТКА) &&
    !/A\.оболочкаОкна\(\{ сырое:\s*\n\s*'<div class="ad-modal"/.test(СЕТКА),
    'окно семейства `ad-modal` затянуто в оболочку окна подтверждения: ' +
    'у него своя подложка, шапка, тело и подвал, и оно поедет в чужой рамке');

/* ─────────── ЧТО ДАЁТ ОБОЛОЧКА ─────────── */

правило('окно называет себя диктору',
    /role="dialog"/.test(УТИЛ) && /aria-modal="true"/.test(УТИЛ) &&
    /aria-labelledby/.test(УТИЛ),
    'из оболочки убрали role/aria-modal/aria-labelledby — диктор окно не объявит');

правило('готовой разметке доставляется то, чего в ней нет',
    /окно\.setAttribute\('role', 'dialog'\);/.test(УТИЛ) &&
    /свойЗаголовок\.id = номерОкна;/.test(УТИЛ),
    'девять окон передают готовую разметку: без доставки role и подписи ' +
    'они снова останутся немыми');

правило('фокус уходит в окно, а не на кнопку',
    /var окно = overlay\.querySelector\('\.ad-confirm-modal'\);/.test(УТИЛ) &&
    /if \(окно && окно\.focus\) окно\.focus\(\);/.test(УТИЛ),
    'фокус перестал уходить в окно либо его поставили на кнопку: первой ' +
    'стоит «Отмена», а за ней бывают необратимые действия');

правило('ловушка фокуса держит Tab внутри окна',
    /if \(e\.key !== 'Tab'\) return;/.test(УТИЛ) &&
    /e\.shiftKey && document\.activeElement === первый/.test(УТИЛ),
    'ловушка фокуса снята: из открытого окна клавиатурой уходят на кнопки ' +
    'страницы под ним, а они меняют данные');

правило('Esc закрывает окно',
    /if \(e\.key === 'Escape'\) \{ закрыть\(\); return; \}/.test(УТИЛ),
    'Esc перестал закрывать окно');

/* ВИДИМОСТЬ ПРОВЕРЯЕТСЯ ЗАМЕРОМ, А НЕ ПРИСУТСТВИЕМ В РАЗМЕТКЕ: кнопка из
   закрытого меню остаётся в DOM, и `focus()` на ней не делает ничего. */
правило('фокус возвращается только живому и видимому',
    /звал\.getBoundingClientRect\(\)\.height > 0/.test(УТИЛ),
    'возврат фокуса снова смотрит только на присутствие в разметке — ' +
    'фокус уедет на body, и обход страницы начнётся с начала');

правило('запасной путь фокуса — видимый заголовок раздела',
    /querySelectorAll\('\.ad-section-title'\)/.test(УТИЛ) &&
    /getBoundingClientRect\(\)\.height > 0/.test(УТИЛ),
    'запасной путь ищет заголовок раздела селектором по стилю: разделы ' +
    'прячутся КЛАССОМ, и находится скрытый');

правило('подпись окна уникальна',
    /var счётчикОкон = 0;/.test(УТИЛ) && /\+\+счётчикОкон\)/.test(УТИЛ),
    'aria-labelledby снова указывает на постоянный id: второе окно ' +
    'сошлётся на заголовок первого');

/* ─────────── ТРИ СБОРЩИКА НА ОДНОЙ ОБОЛОЧКЕ ─────────── */

правило('все три сборщика зовут оболочку',
    (УТИЛ.match(/оболочкаОкна\(\{/g) || []).length >= 3,
    'сборщик окна снова строит подложку сам: `showNotice` и `showPromptAsync` ' +
    'жили так до 04.10 — без role, фокуса и Esc');

правило('в окне ввода фокус уезжает в поле, а не в окно',
    /if \(input\) input\.focus\(\);/.test(УТИЛ),
    'в окне ввода фокус остался на окне: первое нажатие клавиши не попадёт в поле');

/* ─────────── ЧИСЛА ОКНА ─────────── */

/* ПРАВИЛО СМОТРИТ В СВОЙ БЛОК. Голое `max-height: 90vh` есть и у второго
   семейства окон — с ним правило не падало, когда предел убирали у
   нашего. Поймал прувер: «упало — ничего». */
правило('окно не рвёт экран: предел высоты и прокрутка тела',
    /\.ad-confirm-modal \{[^}]*max-height: 90vh;/.test(АДч) &&
    /\.ad-confirm-text \{[\s\S]*?overflow-y: auto;[\s\S]*?min-height: 0;/.test(АДч),
    'у окна снова нет предела высоты либо прокручивается само окно, а не ' +
    'тело: заголовок и кнопки уедут за край');

правило('заголовок окна стоит на ступени заголовка',
    /\.ad-confirm-title \{[\s\S]*?line-height: var\(--lh-snug\);/.test(АДч),
    'заголовок окна вернулся на межстрочный абзаца (1.5): замер 04.10 дал ' +
    '18 / 27 — ступень текста, а не заголовка');

правило('ширина окна со списком — классом, а не числом',
    /\.ad-confirm-modal-wide \{ max-width: 540px; \}/.test(АДч),
    'ширина окна со списком снова инлайном: 540 — ширина второго семейства, ' +
    'и жить она должна в одном месте');

правило('выход уходит вниз уже при трёх кнопках',
    /\.ad-confirm-actions:has\(> :nth-child\(3\)\)/.test(АДч) &&
    !/\.ad-confirm-actions:has\(> :nth-child\(4\)\)/.test(АДч),
    'порог вернулся на четыре кнопки: на трёх ряд переносится как попало, ' +
    'и красное действие падает вниз по центру. Решение Кости 04.10');

/* ─────────── ПОЛОСА ВКЛАДОК ТУРНИРА ─────────── */

/* ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. Полоса вкладок была написана дважды —
   в форме (`tournaments.js`) и в сетке (`bracket.js`), — и у формы вкладки
   «Новости» не было ВОВСЕ: открыв турнир кликом из списка, её не видел
   никто. Замер 04.10: из списка пять вкладок, по прямой ссылке шесть.
   СЧИТАЕМ, ЧТО КОПИЯ ОДНА, а не что функция есть. */
правило('полоса вкладок турнира объявлена один раз',
    /A\.полосаВкладокТурнира = function/.test(УТИЛ) &&
    (УТИЛ.match(/data-trn-nav="/g) || []).length === 1,
    'разметка вкладок снова пишется не в одном месте');

правило('ни один раздел не рисует вкладки сам',
    !/data-trn-nav="/.test(СЕТКА) && !/data-trn-nav="/.test(ТУРНИРЫ),
    'в разделе снова своя полоса вкладок — состав разойдётся с другим путём, ' +
    'как разошлась «Новости» до 04.10');

правило('состав вкладок выводится из турнира, а не из маршрута',
    /завершён = естьЗапись && t_поле\(т, 'status'\) === 'completed'/.test(УТИЛ) &&
    /завершён \? вкладка\('news'/.test(УТИЛ),
    'вкладка «Новости» снова зависит не от состояния турнира');

/* ─────────── ВЕРСИИ ─────────── */

правило('версии подняты — иначе браузер отдаст старое из кеша',
    /admin\.css\?v=(20[4-9]|2[1-9]\d|[3-9]\d\d)/.test(СТРАНИЦА) &&
    /core\/utils\.js\?v=(3[5-9]|[4-9]\d)/.test(СТРАНИЦА),
    'версия admin.css или core/utils.js не поднята после правки');

/* ─────────── ВЫВОД ─────────── */

const всего = 21;
if (ошибки.length) {
    console.log('\n  ✗ оболочка окна — ' + ошибки.length + ' из ' + всего + ':\n');
    ошибки.forEach(о => console.log('    · ' + о.имя + '\n      ' + о.подсказка));
    console.log('');
    process.exit(1);
}
console.log('ок оболочка окна админки: ' + всего + ' правил');
