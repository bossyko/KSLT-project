/* ПРИЗНАК НАУЧЕН ИДТИ ПО ЗОВУ — ОДИН УРОВЕНЬ ВГЛУБЬ (26.10, кусок 180).
   Прежний смотрел ТОЛЬКО тело той функции, где создана подложка, и потому
   три окна висели «под вопросом» с 24.10:
     `showChallengeAlert` и `showChallengeModal` (`js/player.js`) запирают
     соседней `attachChalClose`, которую зовут последней строкой;
     поздравление (`js/badge-celebration.js`) строит подложку в `build()`, а
     оснащает в `next()` — и это НАМЕРЕНО, с пояснением в коде: окно одно на
     очередь, а запирание на каждый бейдж запомнило бы кнопку «Дальше»
     вместо того места, откуда человек пришёл.
   Прочитано по одному, все три ЗАПЕРТЫ. Теперь это видит и прибор.
   ЗАПИРАНИЕ ЧЕРЕЗ ЗОВ — ТАКОЕ ЖЕ ЗАПИРАНИЕ; ПРИЗНАК, СМОТРЯЩИЙ ТОЛЬКО В
   СВОЁ ТЕЛО, НАЗОВЁТ ЗАПЕРТОЕ НЕЗАПЕРТЫМ. */
function заперлаСама(т, ф) {
    return ЗАПИРАНИЕ.test(т.slice(ф.начало, ф.конец));
}
function заперлаЧерезЗов(т, ф, функции) {
    const тело = т.slice(ф.начало, ф.конец);
    /* имена функций того же файла, которые зовут из этого тела */
    return функции.some(др => {
        if (!др.имя || др === ф) return false;
        if (др.начало >= ф.начало && др.конец <= ф.конец) return false; // своя вложенная уже учтена
        const зовут = new RegExp('(^|[^\\w.])' + др.имя + '\\s*\\(').test(тело);
        return зовут && ЗАПИРАНИЕ.test(т.slice(др.начало, др.конец));
    });
}

