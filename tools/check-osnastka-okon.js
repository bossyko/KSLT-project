/* И СУЖЕНО ДО ТЕЛА СВОЕГО ОКНА: в `news.js` функций `закрыть` ДВЕ — вторая
   у смотрелки снимков, которую запер кусок 153. Правило, искавшее первую по
   файлу, падало на чистом коде. ОБЛАСТЬ СЧИТАЕТСЯ ОТ ОКНА, А НЕ ОТ ФАЙЛА. */
function телоПо(т, началоИмени) {
    let гл = 0;
    const о = т.indexOf('{', началоИмени);
    for (let i = о; i < т.length; i++) {
        if (т[i] === '{') гл++;
        else if (т[i] === '}') { гл--; if (гл === 0) return т.slice(началоИмени, i + 1); }
    }
    return null;
}
function внеЗакрытия(ф, имяОкна, имяЗакрытия) {
    const весь = чисто(чит(ф));
    const началоОкна = весь.indexOf('function ' + имяОкна);
    if (началоОкна === -1) return 'окна `' + имяОкна + '` нет вовсе';
    const окноТело = телоПо(весь, началоОкна);
    if (!окноТело) return 'тело окна `' + имяОкна + '` не разобралось';
    const началоЗакр = окноТело.indexOf('function ' + имяЗакрытия);
    if (началоЗакр === -1) return 'внутри `' + имяОкна + '` нет `' + имяЗакрытия + '`';
    const закрТело = телоПо(окноТело, началоЗакр);
    const остаток = окноТело.replace(закрТело, '');
    const n = (остаток.match(/overlay\.remove\(\)/g) || []).length;
    return n === 0 ? null : 'удалений вне `' + имяЗакрытия + '`: ' + n;
}
