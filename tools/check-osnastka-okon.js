function телоПо(т, началоИмени) {
    let гл = 0;
    const о = т.indexOf('{', началоИмени);
    for (let i = о; i < т.length; i++) {
        if (т[i] === '{') гл++;
        else if (т[i] === '}') { гл--; if (гл === 0) return т.slice(началоИмени, i + 1); }
    }
    return null;
}
