/* ── ОКНА ПРОДУКТА: ПРИЗНАК — МЕСТО СОЗДАНИЯ ПОДЛОЖКИ ── */
const ПОДЛОЖКА = /(?:className\s*=\s*|classList\.add\(\s*)['"]([a-zA-Zа-яА-Я0-9_-]*(?:overlay|modal|подложк)[a-zA-Zа-яА-Я0-9_ -]*)['"]/g;
