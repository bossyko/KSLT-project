#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «НИЗКИЙ ГОРИЗОНТАЛЬНЫЙ ВИД ПРИЛОЖЕНИЯ» (05.11).
 *
 * ЗАЧЕМ ОН ЕСТЬ — СЛУЧАЙ, А НЕ ОПАСЕНИЕ. Костя увидел глазами в
 * Android Studio: приложение лёжа разъезжается. Замер пяти видов
 * загрузкой назвал причину числами. Лёжа (844×390) — единственный вид,
 * где `body` не ограничено 600: предел снят намеренно куском 212, чтобы
 * не было чёрных полей. Поэтому всё, чья высота считается ОТ ШИРИНЫ,
 * выросло вдвое, а экран стал вдвое ниже:
 *
 *     афиша новости  4/3  →  812×609 при экране 390 — 156 % высоты
 *     видео новости 16/9  →  844×475 — 122 %
 *     карта баттла  (304) →  78 %
 *     график        (192) →  49 %
 *
 * При этом правил `orientation: landscape` в `app.css` было РОВНО НОЛЬ,
 * а на сайте это правило живёт в 13 файлах.
 *
 * ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ, А НЕ ЧИСЛО:
 *   · у афиши и карты — потолок ВЫСОТЫ (их кадр можно обрезать);
 *   · у видео — предел ШИРИНЫ, выраженный пропорцией 16/9 (видео
 *     обрезать нельзя, пропорция обязана уцелеть);
 *   · граница низкого горизонтального — ОДНА на сайт и приложение.
 *
 * ДВЕ ЛОВУШКИ, НА КОТОРЫХ УЖЕ СПОТКНУЛСЯ ПЕРВЫЙ ЗАХОД, И ПОТОМУ ОНИ
 * ЗАПЕРТЫ ПРАВИЛАМИ:
 *   · потолок высоты при живом `aspect-ratio` сжимает и ШИРИНУ — замер
 *     дал 240×180, полосу у левого края вместо афиши. Пропорцию надо
 *     СНЯТЬ (`aspect-ratio: auto`), а не придавить;
 *   · один `max-width` без `width: 100%` в колоночном родителе сжал
 *     кадр трансляции до содержимого — 111×63 вместо 416×234. ПРЕДЕЛ
 *     ШИРИНЫ ОГРАНИЧИВАЕТ, А НЕ ЗАДАЁТ.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ, И ЭТО НАЗВАНО. Прибор читает ФАЙЛ КАК ТЕКСТ: он не
 * знает, что увидит глаз, и не заменяет ни пробу, ни Костю. Правило,
 * написанное внутри другого `@media`, или одежда, пришедшая инлайном из
 * js, ему не видны.
 *
 *   node tools/check-gorizontalnyy-vid.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ОДЕЖДА_ПРИЛОЖЕНИЯ = 'mobile/www/css/app.css';
const ТОКЕНЫ_ПРИЛОЖЕНИЯ = 'mobile/www/css/tokens.css';
const ТОКЕНЫ_САЙТА = 'css/tokens.css';

function читать(о) {
    const п = path.join(КОРЕНЬ, о);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}

/**
 * БЛОКИ НИЗКОГО ГОРИЗОНТАЛЬНОГО в тексте css.
 *
 * ЛОВУШКА, РАДИ КОТОРОЙ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ: тело `@media` содержит
 * ВЛОЖЕННЫЕ скобки правил, поэтому «до первой закрывающей» читать
 * нельзя — так прибор увидел бы одно правило из пяти. Скобки считаются.
 *
 * Якорь держится на СОДЕРЖИМОМ условия — на повороте и пороге высоты, —
 * а не на положении в файле и не на соседнем правиле, которое уедет.
 */
function блокиГоризонтали(т) {
    const вых = [];
    const re = /@media[^{]*?\(\s*max-height\s*:\s*(\d+)px\s*\)[^{]*?\(\s*orientation\s*:\s*landscape\s*\)[^{]*\{/g;
    let м;
    while ((м = re.exec(т))) {
        let глубина = 1;
        let i = м.index + м[0].length;
        while (i < т.length && глубина > 0) {
            if (т[i] === '{') глубина++;
            else if (т[i] === '}') глубина--;
            i++;
        }
        вых.push({
            порог: Number(м[1]),
            тело: т.slice(м.index + м[0].length, i - 1),
            строка: т.slice(0, м.index).split('\n').length
        });
    }
    return вых;
}

/* ПРАВИЛО ПО СЕЛЕКТОРУ внутри тела блока: возвращает текст объявлений.
   Селектор ищется как отдельное слово в списке через запятую, иначе
   `.rc-svg` нашёлся бы внутри `.rc-svg-podpis`. */
function объявления(тело, селектор) {
    /* КОММЕНТАРИИ СНИМАЮТСЯ ПЕРВЫМИ, И ЭТО НЕ МЕЛОЧЬ: без этого текст
       пояснения прилипает к селектору слева, список через запятую
       перестаёт совпадать по слову, и прибор говорит «правила нет» там,
       где оно есть. Первый прогон 05.11 упал ровно на этом. */
    тело = тело.replace(/\/\*[\s\S]*?\*\//g, ' ');
    const re = /([^{}]+)\{([^{}]*)\}/g;
    let м;
    const вых = [];
    while ((м = re.exec(тело))) {
        const список = м[1].split(',').map(s => s.trim());
        if (список.some(s => s === селектор)) вых.push(м[2]);
    }
    return вых.join(' ');
}

const одежда = читать(ОДЕЖДА_ПРИЛОЖЕНИЯ);
const токеныПрил = читать(ТОКЕНЫ_ПРИЛОЖЕНИЯ);
const токеныСайта = читать(ТОКЕНЫ_САЙТА);

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

const блоки = одежда ? блокиГоризонтали(одежда) : [];
const блок = блоки.length ? блоки[0] : null;
/* ТЕЛО БЕРЁТСЯ ОТ ВСЕХ БЛОКОВ СРАЗУ, И ЭТО НАРОЧНО. Иначе второй такой
   же блок уронил бы заодно все правила о содержимом, и прувер не смог
   бы доказать, ЧТО ИМЕННО сломалось: падение одной беды не должно
   тянуть за собой чужие правила. */
const тело = блоки.map(б => б.тело).join('\n');

правило('низкий горизонтальный в одежде приложения описан один раз',
    блоки.length === 1,
    блоки.length === 0
        ? 'В ' + ОДЕЖДА_ПРИЛОЖЕНИЯ + ' нет ни одного блока\n' +
          '`@media (max-height: …px) and (orientation: landscape)`.\n' +
          'Телефон лёжа — это вид, у которого высота вдвое меньше ширины,\n' +
          'и без этого блока афиша встаёт в 156 % экрана. Замер 05.11.'
        : 'Блоков низкого горизонтального ' + блоки.length + ': строки ' +
          блоки.map(б => б.строка).join(', ') + '.\n' +
          'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ — беда родится ровно на шве:\n' +
          'правка доедет до одного блока и не доедет до второго.');

правило('граница низкого горизонтального — 500, как у сайта',
    блоки.length > 0 && блоки.every(б => б.порог === 500),
    !блок ? 'Блока низкого горизонтального нет вовсе — порог мерить нечем.'
        : 'Порог высоты у приложения ' + блоки.map(б => б.порог).join(', ') + ', а не 500.\n' +
          'Это число — не подгонка под устройство, а общая граница двух\n' +
          'продуктов. Менять её можно только вместе с сайтом.');

правило('афиша снимает пропорцию, а не придавливает её',
    (function () {
        const д = объявления(тело, '.nd-hero-img');
        return /aspect-ratio\s*:\s*auto/.test(д) &&
               /height\s*:\s*var\(\s*--oblozhka-potolok/.test(д);
    })(),
    'В блоке низкого горизонтального правило `.nd-hero-img` должно\n' +
    'снимать пропорцию (`aspect-ratio: auto`) и брать высоту из\n' +
    '`var(--oblozhka-potolok)`.\n' +
    'ПОЧЕМУ ИМЕННО ТАК — ЗАМЕР, А НЕ ВКУС: при живом `aspect-ratio: 4/3`\n' +
    'один потолок высоты сжимает и ширину, и афиша становится полосой\n' +
    '240×180 у левого края. А число вместо переменной разводит два\n' +
    'определения одного понятия: потолок уже задан в tokens.css.');

правило('видео держится пределом ШИРИНЫ, выраженным пропорцией',
    (function () {
        const д = объявления(тело, '.live-full-video');
        return /width\s*:\s*100%/.test(д) &&
               /max-width\s*:\s*calc\([^)]*16\s*\/\s*9[^)]*\)/.test(д) &&
               !/max-height/.test(д);
    })(),
    'В блоке низкого горизонтального у `.live-full-video` ждём три вещи:\n' +
    '`width: 100%`, `max-width: calc(… * 16 / 9)` и НИ ОДНОГО\n' +
    '`max-height`.\n' +
    'Видео обрезать нельзя — пропорция 16/9 обязана уцелеть, поэтому\n' +
    'ограничивается ширина, а высота следует сама. А `width: 100%` тут\n' +
    'не украшение: без него предел ширины в колоночном родителе сжал\n' +
    'кадр до содержимого — замер дал 111×63 вместо 416×234.');

правило('карта и график держатся долей экрана, а не пикселями',
    (function () {
        const карта = объявления(тело, '.bd-map iframe');
        const график = объявления(тело, '.rc-svg');
        const высотаВДоле = д => /height\s*:\s*\d+(\.\d+)?vh/.test(д) &&
                                 !/height\s*:\s*\d+(\.\d+)?px/.test(д);
        return высотаВДоле(карта) && высотаВДоле(график);
    })(),
    'Карте (`.bd-map iframe`) и графику (`.rc-svg`) в этом виде высота\n' +
    'задаётся долей экрана (vh), а не числом в пикселях. Жёсткие 304 и\n' +
    '192 занимали лёжа 78 % и 49 % экрана высотой 390 — замер 05.11.');

правило('у читателя есть определение: потолок обложки задан в том же виде',
    (function () {
        if (!токеныПрил) return false;
        const б = блокиГоризонтали(токеныПрил);
        return б.length === 1 && /--oblozhka-potolok\s*:/.test(б[0].тело);
    })(),
    'В ' + ТОКЕНЫ_ПРИЛОЖЕНИЯ + ' внутри блока низкого горизонтального\n' +
    'должна задаваться `--oblozhka-potolok`. Иначе читатель в app.css\n' +
    'остаётся без значения, и правило молча ничего не делает.\n' +
    'ДО 05.11 ЭТА ПЕРЕМЕННАЯ БЫЛА ЖИВА, А ЧИТАТЕЛЕЙ У НЕЁ НЕ БЫЛО\n' +
    'ВОВСЕ — ровно та беда, от которой этот прибор и поставлен.');

правило('порог низкого горизонтального у двух продуктов один',
    (function () {
        if (!блок || !токеныСайта) return false;
        const б = блокиГоризонтали(токеныСайта);
        return б.length > 0 && б.every(x => x.порог === блок.порог);
    })(),
    'Порог высоты у приложения и у ' + ТОКЕНЫ_САЙТА + ' разошёлся.\n' +
    'Низкий горизонтальный — ОДНО понятие на два продукта. Разные\n' +
    'пороги означают, что телефон лёжа на сайте и в приложении —\n' +
    'разные виды, и правка одного не доедет до другого.');

правило('прибор считает вложенные скобки и различает условия',
    (function () {
        /* ОБРАЗЕЦ ВНУТРЬ ПРИБОРА. Он обязан: взять тело ЦЕЛИКОМ, а не до
           первой закрывающей скобки; не принять чужой @media за свой. */
        const о = '@media (max-width: 640px) { .a { height: 1px; } }\n' +
                  '@media (max-height: 500px) and (orientation: landscape) {\n' +
                  '  .b { height: 2px; }\n  .c, .d { width: 3px; }\n}\n' +
                  '@media (orientation: landscape) { .e { height: 4px; } }\n';
        const б = блокиГоризонтали(о);
        if (б.length !== 1 || б[0].порог !== 500) return false;
        if (!/\.c, \.d/.test(б[0].тело)) return false;
        if (объявления(б[0].тело, '.d').indexOf('width: 3px') === -1) return false;
        /* и не путает слово с его началом */
        return объявления('.bb { height: 9px; }', '.b') === '';
    })(),
    'Образец внутри прибора: чужой @media по ширине, свой блок с двумя\n' +
    'правилами и @media без порога высоты. Прибор обязан увидеть РОВНО\n' +
    'один свой блок, прочитать его тело целиком и не считать `.bb` за\n' +
    '`.b`. Не так — он скажет «всё держится» на половине правил.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      низкий горизонтальный: все ' + всего + ' правил держатся');
    console.log('          порог ' + блок.порог + ', блок один, строка ' + блок.строка +
                ' в ' + ОДЕЖДА_ПРИЛОЖЕНИЯ);
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  низкий горизонтальный — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
