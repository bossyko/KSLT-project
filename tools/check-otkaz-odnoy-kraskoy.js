/** ВСЕ тела блоков, в чьём селекторе искомое имя стоит ЦЕЛИКОМ.
    Поиск голой подстрокой не годится, и это поймал прувер: блок
    `.pl-change-down-ЗАГЛУШКА` встаёт раньше настоящего `.pl-change-down`,
    правило проверяет самозванца, а настоящий блок не смотрит вовсе.
    Граница нужна ровно одна — СЛЕДУЮЩИЙ символ не может быть частью
    имени. Перед именем граница не нужна: все имена роли начинаются с
    точки, а она сама разделяет (`.pw-rule.pw-rule-error` — это блок
    `.pw-rule-error`, и он должен найтись). */
function блоки(текст, селектор) {
    const из = [];
    let i = 0;
    while ((i = текст.indexOf(селектор, i)) !== -1) {
        const след = текст[i + селектор.length] || '';
        i += селектор.length;
        if (/[\w-]/.test(след)) continue;              // самозванец с суффиксом
        const о = текст.indexOf('{', i);
        const з = текст.indexOf('}', i);
        if (о === -1 || (з !== -1 && з < о)) continue;  // имя не в селекторе блока
        let гл = 1, j = о + 1;
        while (j < текст.length && гл) { if (текст[j] === '{') гл++; else if (текст[j] === '}') гл--; j++; }
        из.push(текст.slice(о + 1, j - 1));
    }
    return из;
}

