/** Комментарии гасим пробелами ТОЙ ЖЕ ДЛИНЫ: вырезание ломает позиции и
    даёт объявлению сожрать текст после `*\/` (поймано в круге 1). */
function гасить(s) {
    const из = s.split('');
    s.replace(/\/\*[\s\S]*?\*\//g, (м, i) => {
        for (let k = i; k < i + м.length; k++) if (из[k] !== '\n') из[k] = ' ';
        return м;
    });
    return из.join('');
}

