function перечень(заголовок, список) {
    if (!список.length) return '  • ' + заголовок + ': нет';
    const тело = [];
    let строка = '    ';
    for (const х of список) {
        if (строка.length + х.length + 2 > 72) { тело.push(строка); строка = '    '; }
        строка += х + ', ';
    }
    тело.push(строка.replace(/, $/, ''));
    return '  • ' + заголовок + ' (' + список.length + '):\n' + тело.join('\n');
}

// --- запуск -------------------------------------------------------
function главное() {
    const арг = process.argv.slice(2);
    const вход = арг.find(а => !а.startsWith('--'));
    if (!вход) {
        console.error('Нужен файл выгрузки: node tools/sobrat-snimok-shemy.js <файл>');
        process.exit(2);
    }
    const i = арг.indexOf('--vyvod');
    const вывод = i >= 0 ? арг[i + 1]
        : path.join(path.dirname(path.dirname(path.resolve(__filename))), 'sql', 'схема', 'schema-snapshot.sql');

    const ряды = читатьВыгрузку(вход);
    if (!ряды.length) {
        console.error('В выгрузке не нашлось ни одной строки — проверьте, что это вывод snyat-shemu.sql.');
        process.exit(1);
    }

    const пропуски = проверитьНумерацию(ряды);
    const прежний = прочитатьПрежний(вывод);
    const текст = собрать(ряды, прежний);
    fs.writeFileSync(вывод, текст, 'utf8');

    const по = {};
    for (const р of ряды) по[р.razdel] = (по[р.razdel] || 0) + 1;
    console.log('Собран ' + вывод);
    console.log('строк выгрузки: ' + ряды.length);
    for (const раздел of РАЗДЕЛЫ) if (по[раздел.ключ]) console.log('  ' + раздел.ключ + ': ' + по[раздел.ключ]);
    if (пропуски.length) {
        console.log('ВЫГРУЗКА НЕПОЛНАЯ — пропущены номера: ' + пропуски.slice(0, 20).join(', ')
            + (пропуски.length > 20 ? ' … всего ' + пропуски.length : ''));
        process.exitCode = 1;
    } else {
        console.log('нумерация без пропусков: 1..' + ряды.length);
    }
}

// Выгрузка нумерована самим запросом. Пропуск номера — признак того, что
// копия оборвана или панель отдала часть строк. ОБОРВАННАЯ ВЫГРУЗКА, СОБРАННАЯ
// МОЛЧА, — ЭТО СНИМОК, КОТОРЫЙ ВРЁТ НЕДОГОВАРИВАЯ.
function проверитьНумерацию(ряды) {
    const есть = new Set(ряды.map(р => р.n));
    const макс = Math.max(...есть);
    const пропуски = [];
    for (let i = 1; i <= макс; i++) if (!есть.has(i)) пропуски.push(i);
    return пропуски;
}

