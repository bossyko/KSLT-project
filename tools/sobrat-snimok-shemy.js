// СОБРАТЬ СНИМОК СХЕМЫ ИЗ ВЫГРУЗКИ
//
// ЗАЧЕМ. sql/схема/snyat-shemu.sql читает каталог постгреса и отдаёт четыре
// столбца: n, razdel, imya, stroka. Прежде я собирал из этого вывода файл
// руками — и значит снимок пересобирался только когда у меня хватало на это
// места в разговоре. ПРИБОР, КОТОРОГО НЕТ, НЕ ПРОГОНЯЕТСЯ: сборщик пишется
// один раз и зовётся одной строкой.
//
// КАК ЗВАТЬ:
//   node tools/sobrat-snimok-shemy.js <выгрузка> [--vyvod sql/схема/schema-snapshot.sql]
//
// Выгрузка принимается в двух видах, вид определяется чтением первой строки,
// а не расширением: CSV («Download CSV» в панели) и markdown-таблица
// (кнопка копирования в панели — она отдаёт `| n | razdel | imya | stroka |`
// и заменяет переводы строк внутри поля на <br>).
//
// ЧТО ДЕЛАЕТ СВЕРХ СБОРКИ: сравнивает новую выгрузку с прежним снимком по
// трём измеримым множествам — таблицы, столбцы (таблица.столбец) и подписи
// функций — и печатает, что появилось и что исчезло. Это ЗАМЕР расхождения,
// а не «кажется, снимок отстал».

const fs = require('fs');
const path = require('path');

const РАЗДЕЛЫ = [
    { ключ: 'TABLICY',        имя: 'ТАБЛИЦЫ И СТОЛБЦЫ — имя, тип, пустота, умолчание', групп: true },
    { ключ: 'OGRANICHENIYA',  имя: 'ОГРАНИЧЕНИЯ — ключи, уникальность, проверки' },
    { ключ: 'UKAZATELI',      имя: 'УКАЗАТЕЛИ' },
    { ключ: 'PERECHISLENIYA', имя: 'ПЕРЕЧИСЛЕНИЯ' },
    { ключ: 'PREDSTAVLENIYA', имя: 'ПРЕДСТАВЛЕНИЯ' },
    { ключ: 'FUNKCII',        имя: 'ФУНКЦИИ — полные тела, ровно как в базе', телами: true },
    { ключ: 'STOROZHA',       имя: 'СТОРОЖА (триггеры)' },
    { ключ: 'DOSTUP',         имя: 'ПРАВИЛА ДОСТУПА (RLS)' }
];

// Слепок — резервная копия, снятая перед правкой данных, а не часть
// продукта. Отнесение ПО ВИДУ ИМЕНИ, поэтому имена перечислены в снимке:
// если что-то попало сюда ошибочно — это видно глазами.
const ВИД_СЛЕПКА = /^(slepok|metki_)/;

function читатьВыгрузку(путь) {
    const текст = fs.readFileSync(путь, 'utf8');
    const строки = текст.split('\n');
    let первая = 0;
    while (первая < строки.length && строки[первая].trim() === '') первая++;
    const шапка = строки[первая] || '';

    if (/^\s*\|/.test(шапка)) return разобратьMarkdown(строки, первая);
    return разобратьCsv(текст);
}

// --- markdown-таблица ---------------------------------------------
function разобратьMarkdown(строки, первая) {
    const ряды = [];
    for (let i = первая + 1; i < строки.length; i++) {
        const с = строки[i].replace(/\s+$/, '');
        if (с.trim() === '') continue;
        const м = с.match(/^\s*\|(.*)\|$/);
        if (!м) continue;
        const внутри = м[1];
        if (/^[\s|:-]*$/.test(внутри)) continue;       // строка-разделитель
        const части = внутри.split('|');
        if (части.length < 4) continue;
        const n = части[0].trim();
        const razdel = части[1].trim();
        const imya = части[2].trim();
        const stroka = части.slice(3).join('|');       // в содержимом бывает ||
        if (!/^\d+$/.test(n)) continue;
        ряды.push({ n: +n, razdel, imya, stroka: изBr(stroka) });
    }
    return ряды;
}

// Панель заменяет перевод строки внутри поля на <br>. Обратная замена —
// единственный способ вернуть телам функций их настоящий вид.
function изBr(т) {
    return т.replace(/<br\s*\/?>/g, '\n');
}

// --- CSV ----------------------------------------------------------
function разобратьCsv(текст) {
    const поля = [];
    let поле = '';
    let ряд = [];
    let вКавычках = false;
    for (let i = 0; i < текст.length; i++) {
        const з = текст[i];
        if (вКавычках) {
            if (з === '"') {
                if (текст[i + 1] === '"') { поле += '"'; i++; }
                else вКавычках = false;
            } else поле += з;
            continue;
        }
        if (з === '"') { вКавычках = true; continue; }
        if (з === ',') { ряд.push(поле); поле = ''; continue; }
        if (з === '\r') continue;
        if (з === '\n') { ряд.push(поле); поля.push(ряд); ряд = []; поле = ''; continue; }
        поле += з;
    }
    if (поле !== '' || ряд.length) { ряд.push(поле); поля.push(ряд); }

    const ряды = [];
    for (let i = 1; i < поля.length; i++) {           // первая строка — заголовки
        const р = поля[i];
        if (!р || р.length < 4) continue;
        if (!/^\d+$/.test(String(р[0]).trim())) continue;
        ряды.push({ n: +р[0], razdel: р[1].trim(), imya: р[2].trim(), stroka: р[3] });
    }
    return ряды;
}

// --- сборка файла -------------------------------------------------
function вКомментарий(т) {
    return т.split('\n')
        .map(с => ('-- ' + с.replace(/\s+$/, '')).replace(/\s+$/, ''))
        .join('\n');
}

// Ячейка markdown-таблицы отбита пробелами с обоих концов, и у тела функции
// этот отбой садится на первую строку, а хвостовой — пустой строкой в конце.
// Внутренние отступы тела трогать НЕЛЬЗЯ: это код, как он лежит в базе.
function телоФункции(т) {
    const строки = т.split('\n');
    while (строки.length && строки[0].trim() === '') строки.shift();
    while (строки.length && строки[строки.length - 1].trim() === '') строки.pop();
    if (строки.length) строки[0] = строки[0].replace(/^[ \t]+/, '');
    return строки.join('\n');
}

function рамка(т) {
    const черта = '-- ' + '='.repeat(70);
    return черта + '\n-- ' + т + '\n' + черта;
}

function собрать(ряды, прежний) {
    const по = {};
    for (const р of ряды) (по[р.razdel] = по[р.razdel] || []).push(р);

    const столбцы = ряды.filter(р => р.razdel === 'TABLICY');
    const таблицы = [...new Set(столбцы.map(р => р.imya.split('.')[0]))].sort();
    const слепки = таблицы.filter(т => ВИД_СЛЕПКА.test(т));
    const рабочие = таблицы.filter(т => !ВИД_СЛЕПКА.test(т));

    const подписи = (по.FUNKCII || []).map(р => р.imya).sort();

    const куски = [];

    куски.push(шапкаФайла({ ряды, по, таблицы, рабочие, слепки, подписи, прежний }));

    for (const раздел of РАЗДЕЛЫ) {
        const свои = (по[раздел.ключ] || []).slice().sort((а, б) => а.imya < б.imya ? -1 : а.imya > б.imya ? 1 : 0);
        if (!свои.length) continue;

        if (раздел.ключ === 'TABLICY') {
            куски.push(рамка(раздел.имя));
            куски.push(разделТаблиц(свои, рабочие));
            continue;
        }

        куски.push(рамка(раздел.имя));
        if (раздел.телами) {
            const тела = свои.map(р => '-- --- ' + р.imya + ' ' + '-'.repeat(Math.max(3, 60 - р.imya.length)) + '\n' + вКомментарий(телоФункции(р.stroka)));
            куски.push(тела.join('\n\n'));
        } else {
            куски.push(свои.map(р => вКомментарий(р.stroka.trim())).join('\n'));
        }
    }

    if (слепки.length) {
        куски.push(рамка('СЛЕПКИ И МЕТКИ — резервные копии, не продукт'));
        куски.push(вКомментарий(
            'Отнесено ПО ВИДУ ИМЕНИ (' + ВИД_СЛЕПКА.source + '), поэтому имена\n' +
            'перечислены: ошибочное отнесение видно глазами. Решение об удалении\n' +
            'за Костей — само оно не уйдёт.\n'));
        куски.push(разделТаблиц(столбцы, слепки));
    }

    return куски.join('\n\n\n') + '\n';
}

function разделТаблиц(свои, имена) {
    const набор = new Set(имена);
    const по = {};
    for (const р of свои) {
        const т = р.imya.split('.')[0];
        if (!набор.has(т)) continue;
        (по[т] = по[т] || []).push(р);
    }
    const куски = [];
    for (const т of имена) {
        const строки = (по[т] || []).slice().sort((а, б) => а.imya < б.imya ? -1 : 1);
        куски.push('-- --- ' + т + ' ' + '-'.repeat(Math.max(3, 60 - т.length)) + '\n'
            + строки.map(р => вКомментарий(р.stroka.trim())).join('\n'));
    }
    return куски.join('\n\n');
}

// --- сравнение с прежним снимком ----------------------------------
// Из прежнего снимка вынимаются ровно те же три множества. Берётся то, что
// в файле РАЗМЕЧЕНО видом строки, а не то, что я помню о прежнем файле.
function прочитатьПрежний(путь) {
    if (!fs.existsSync(путь)) return null;
    const текст = fs.readFileSync(путь, 'utf8');
    const столбцы = new Set();
    const подписи = new Set();
    for (const с of текст.split('\n')) {
        const тело = с.replace(/^--\s?/, '');
        const стл = тело.match(/^([a-z_][a-z0-9_]*\.[a-z_][a-z0-9_]*) : /);
        if (стл) { столбцы.add(стл[1]); continue; }
        const фн = тело.match(/^CREATE OR REPLACE FUNCTION public\.([a-z_][a-z0-9_]*)\((.*)\)\s*$/i);
        if (фн) подписи.add(приводитьПодпись(фн[1] + '(' + фн[2] + ')'));
    }
    const таблицы = new Set([...столбцы].map(с => с.split('.')[0]));
    return { столбцы, подписи, таблицы };
}

// Подпись функции в прежнем снимке взята из строки CREATE OR REPLACE
// FUNCTION — там аргументы ПОЛНЫЕ: с DEFAULT и с OUT. В выгрузке подпись
// даёт `pg_get_function_identity_arguments` — там ни того, ни другого.
// ДВА РАЗНЫХ ВИДА ОДНОЙ ПОДПИСИ СРАВНИВАТЬ НЕЛЬЗЯ: сверка показала бы
// 51 «появилась» и 19 «исчезла» на функциях, которые не трогали. Поэтому
// подпись приводится к одному виду: имя + только входные аргументы, без
// умолчаний.
function приводитьПодпись(п) {
    const i = п.indexOf('(');
    if (i < 0) return п;
    const имя = п.slice(0, i);
    const внутри = п.slice(i + 1, п.lastIndexOf(')'));
    const части = поЗапятымВерхнегоУровня(внутри)
        .map(а => а.trim())
        .filter(а => а !== '')
        .filter(а => !/^OUT\s/i.test(а))
        .map(а => а.replace(/^(IN|INOUT)\s+/i, ''))
        .map(а => а.replace(/\s+DEFAULT\s[\s\S]*$/i, ''))
        .map(а => а.replace(/"/g, '').replace(/\s+/g, ' ').trim());
    return имя + '(' + части.join(', ') + ')';
}

function поЗапятымВерхнегоУровня(т) {
    const части = [];
    let глубина = 0;
    let вКавычках = false;
    let текущая = '';
    for (const з of т) {
        if (з === "'") вКавычках = !вКавычках;
        if (!вКавычках && (з === '(' || з === '[')) глубина++;
        if (!вКавычках && (з === ')' || з === ']')) глубина--;
        if (!вКавычках && глубина === 0 && з === ',') { части.push(текущая); текущая = ''; continue; }
        текущая += з;
    }
    части.push(текущая);
    return части;
}

function разница(было, стало) {
    const появилось = [...стало].filter(х => !было.has(х)).sort();
    const исчезло = [...было].filter(х => !стало.has(х)).sort();
    return { появилось, исчезло };
}

