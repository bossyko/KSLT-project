const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СПО = безКом(чит('css/sponsors.css'));
const УСЛ = безКом(чит('css/services.css'));
const ДЖС = безКом(чит('js/sponsors-page.js'));
const СТРАНИЦЫ = ['pages/sponsors.html', 'pages/sponsors-en.html', 'pages/sponsors-kg.html'].map(чит);

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

function блок(текст, сел) {
    const кл = сел.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const м = текст.match(new RegExp('(?:^|\\n)' + кл + '(?:[,\\s][^{]*)?\\{'));
    if (!м) return '';
    const i = м.index + (текст[м.index] === '\n' ? 1 : 0);
    return текст.slice(i, текст.indexOf('}', i));
}
const всеВхождения = (т, рег) => (т.match(рег) || []).length;

/* ══ ЛЕСТНИЦА СЖИМАЕТСЯ НА ТЕЛЕФОНЕ ═════════════════════════════════════ */

правило('на телефоне заголовок раздела мельче заголовка обложки',
    /\.sn-h2\s*\{\s*font-size: var\(--fs-xl\)/.test(СПО.slice(СПО.indexOf('@media (max-width: 992px)'))),
    'замер 13.10: на 390 заголовок раздела стоял 32 — РОВНО как заголовок\n' +
    'обложки, — и два уровня спорили за первый взгляд. Лестница обязана\n' +
    'сжиматься: 32 обложка, 26 раздел');

правило('на телефоне цифра аудитории не крупнее заголовка обложки',
    /\.sn-num-val\s*\{\s*font-size: var\(--fs-2xl\)/.test(СПО.slice(СПО.indexOf('@media (max-width: 992px)'))),
    'замер 13.10: цифра стояла 40 при заголовке обложки 32 — крупнее всего\n' +
    'на экране была не мысль, а число. Костя выбрал пробу с 32');

/* ══ АБЗАЦ И МЕЖСТРОЧНЫЕ ════════════════════════════════════════════════ */

правило('у лида страницы есть мера абзаца и ступень межстрочного',
    /line-height: var\(--lh-relaxed\)/.test(блок(СПО, '.sn-lead')) &&
    /max-width: 62ch/.test(блок(СПО, '.sn-lead')),
    'было 1.75 мимо лестницы и 720px потолка — строка выходила в 85 знаков\n' +
    'при норме 45–75. 62ch подобрано замером на странице корта 13.10');

правило('межстрочных числом в файле спонсоров не осталось',
    всеВхождения(СПО, /line-height:\s*[\d.]+\s*;/g) === 0,
    'ступени лестницы живут токенами --lh-*; число в файле — это возврат к\n' +
    'тому, с чего начинали');

/* ══ КНОПКА ═════════════════════════════════════════════════════════════ */

правило('кнопка страницы держит высоту свойством',
    /min-height: var\(--btn-h-md\)/.test(блок(СПО, '.sn-btn')) &&
    /line-height: var\(--lh-none\)/.test(блок(СПО, '.sn-btn')) &&
    !/padding:\s*\d+px \d+px/.test(блок(СПО, '.sn-btn')),
    '`Button 17:82`: «Height is set by the height property, never by vertical\n' +
    'padding». Замер 13.10: 50 у кнопки обложки и 56 у контактных — ни одна\n' +
    'не ступень шкалы (28 · 36 · 44 · 52), а на телефоне ДВЕ КНОПКИ ОДНОГО\n' +
    'РЯДА выходили разной высоты: 50 и 56');

правило('у кнопки обзорной «Услуги» задан межстрочный',
    /line-height: var\(--lh-none\)/.test(блок(УСЛ, '.sv-player-btn')),
    '`normal` зависит от шрифта и съезжает вместе с ним. Замер 13.10 поймал\n' +
    'два таких места — здесь и у кнопки страницы спонсоров');

/* ══ КОНТРАСТ ═══════════════════════════════════════════════════════════ */

правило('подписи контактов красятся text-muted, а не text-dim',
    /color: var\(--text-muted\)/.test(блок(СПО, '.sn-final-contact')) &&
    /color: var\(--text-muted\)/.test(блок(СПО, '.snm-note')),
    'замер 13.10: 3.14 при норме 4.5 — единственный провал страницы. Та же\n' +
    'поправка, что у шапки таблицы кортов и в описании `Section stat strip\n' +
    '135:170`: text/dim 0.35 → text/muted 0.50');

/* ══ ГРАНИЦЫ ════════════════════════════════════════════════════════════ */

правило('в файле спонсоров только домашние границы',
    СПО.indexOf('max-width: 820px') === -1 &&
    СПО.indexOf('max-width: 1000px') === -1 &&
    СПО.indexOf('max-width: 720px') === -1,
    'было три числа — 820, 1000 и 720, — и ни одного из домашней пары\n' +
    '640 / 992. Внутри них жило 11 правил (посчитано 13.10)');

правило('блок ≤992 в «Услугах» объявлен один раз',
    всеВхождения(УСЛ, /@media \(max-width: 992px\)/g) === 1,
    'их было два подряд, без единого объявления между, — то есть второй\n' +
    'ничего не перебивал. ДВА БЛОКА ≤640 НИЖЕ НЕ СВОДЯТСЯ, и это проверено\n' +
    'чтением: между ними лежат объявления компонента `.sv-player-*`, и\n' +
    'правило из середины файла проигрывало бы им молча (замер 07.10)');

/* ══ ОФОРМЛЕНИЕ ЖИВЁТ В ФАЙЛЕ СТИЛЕЙ ════════════════════════════════════ */

правило('в разметке страницы спонсоров нет атрибута style',
    СТРАНИЦЫ.every(с => с.indexOf('style="') === -1),
    'было четыре: два отступа и распорка под липкую полосу. Оформление в\n' +
    'атрибуте не видит ни файл стилей, ни один сторож');

/* ══ ОКНО КОНТАКТОВ ═════════════════════════════════════════════════════ */

правило('окно контактов называет себя окном',
    СТРАНИЦЫ.every(с =>
        /id="snModal" role="dialog" aria-modal="true" aria-labelledby="snModalTitle"/.test(с) &&
        /<h2 class="snm-title" id="snModalTitle">/.test(с)),
    'роли не было, имени не было, заголовок был `div` — диктор не знал ни\n' +
    'что это окно, ни как оно называется. На всех трёх языках');

правило('окно держит фокус и возвращает его',
    /function фокусируемые/.test(ДЖС) &&
    /e\.key !== 'Tab'/.test(ДЖС) &&
    /ктоОткрыл/.test(ДЖС),
    'Tab уходил на страницу под окном, а закрытие бросало фокус в никуда.\n' +
    'Правило куплено на окне обмена баллов в кабинете 12.10');

/* ══ ДОСТУПНОСТЬ ════════════════════════════════════════════════════════ */

правило('у страницы спонсоров есть видимый фокус',
    /\.sn-btn:focus-visible/.test(СПО) && /\.snm-row:focus-visible/.test(СПО),
    'замер 13.10: слова `focus-visible` в файле не было ни разу, при том что\n' +
    '`Button 17:82` требует кольцо прямо');

правило('движение страницы спонсоров спрашивает разрешения',
    /@media \(prefers-reduced-motion: reduce\)/.test(СПО),
    'в файле четыре перехода `transform` и `box-shadow`, а блока не было\n' +
    'вовсе');

if (ошибки.length === 0) {
    console.log('  ок      страница «Спонсорам» и обзорная «Услуги»: 14 правил');
    console.log('          лестница сжимается   ·   кнопки одного ряда одной высоты');
    console.log('          оформление в файле стилей   ·   окно держит фокус');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  спонсоры и услуги — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
