/**
 * ЗАМОРОЗКА ПУНКТА «СТАТЬ СПОНСОРОМ» В МЕНЮ «ИНФО» (кусок 66, 13.10.2026).
 *
 * Страница спонсоров жила сиротой: попасть на неё можно было только из
 * подвала, и то лишь по-русски — в подвалах en и kg ссылки на неё не было
 * вовсе, а в быстром меню её не было ни на одном языке (замер 13.10:
 * `grep` по 146 файлам, вхождений `sponsors` в блоках меню — ноль).
 *
 * Правка сделана не по файлам, а по ОБРАЗЦУ: шапка и подвал собираются
 * скриптом tools/build-partials.js из partials/<кусок>-<язык>.html. Поэтому
 * и стережём образец, а совпадение страниц с ним — отдельным правилом,
 * чтобы правка руками в одной странице не прошла молча.
 *
 * ГЛАВНОЕ ЗДЕСЬ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • пункт есть в обоих меню на всех трёх языках;
 *   • он стоит ПЕРЕД «скачать приложение», а не на номере 9;
 *   • наборы пунктов «Инфо» на трёх языках равной длины;
 *   • предел мобильной панели вмещает её список целиком;
 *   • подвал ведёт на спонсоров на всех трёх языках;
 *   • путь в образце — через {{P}}, а не зашитый.
 *
 * Замеры 13.10 (iframe на точной ширине, переходы сняты):
 *   десктоп 1512 / 1024 — 9 пунктов, панель 314, в окно влезает с запасом
 *   мобильное 390×844 и 768×1024 — список 410 при пределе 500
 *   мобильное 844×390        — список 450 при пределе 500, ряд 45
 *   лестница пункта: 14 / 400 / 21 на десктопе, 14 / 500 / 21 в мобильном —
 *   ровно как у соседей, нового уровня текста не завелось
 *
 *   node tools/check-menyu-sponsory.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ЯЗЫКИ = ['ru', 'en', 'kg'];
const ХВОСТ = { ru: '', en: '-en', kg: '-kg' };

const ШАПКА = {}, ПОДВАЛ = {};
ЯЗЫКИ.forEach(я => { ШАПКА[я] = чит('partials/header-' + я + '.html');
                     ПОДВАЛ[я] = чит('partials/footer-' + я + '.html'); });
const СБОРКА = чит('tools/build-partials.js');
const СТИЛИ = чит('css/style.css');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/** Содержимое выпадающей панели «Инфо» в образце: от её открытия до закрытия. */
function панельИнфо(т) {
    const с = т.lastIndexOf('<div class="nav-dropdown-menu">');
    if (с === -1) return '';
    return т.slice(с, т.indexOf('</div>', с));
}
/** Содержимое мобильного списка «Инфо» в образце. */
function списокИнфо(т) {
    const с = т.lastIndexOf('<ul class="mobile-dropdown-menu">');
    if (с === -1) return '';
    return т.slice(с, т.indexOf('</ul>', с));
}
const пунктов = блок => (блок.match(/<a /g) || []).length;

/* ══ ПУНКТ ЕСТЬ В ОБОИХ МЕНЮ НА ТРЁХ ЯЗЫКАХ ══════════════════════════════ */

ЯЗЫКИ.forEach(я => {
    const цель = 'sponsors' + ХВОСТ[я] + '.html';
    правило('в десктопной панели «Инфо» (' + я + ') есть пункт спонсоров',
        панельИнфо(ШАПКА[я]).indexOf(цель) !== -1,
        'замер 13.10: в быстром меню страницы спонсоров не было ни на одном\n' +
        'языке — на неё попадали только из подвала, и только по-русски');

    правило('в мобильном списке «Инфо» (' + я + ') есть пункт спонсоров',
        списокИнфо(ШАПКА[я]).indexOf(цель) !== -1,
        'мобильное меню — единственный путь на телефоне: десктопной панели\n' +
        'там нет вовсе (display:none ниже 993)');

    правило('подвал (' + я + ') ведёт на страницу спонсоров',
        ПОДВАЛ[я].indexOf(цель) !== -1,
        'до 13.10 ссылка стояла только в русском подвале: на en и kg\n' +
        'страница была недостижима из разметки ни одним путём');
});

/* ══ ПОРЯДОК — ОТНОШЕНИЕМ, А НЕ НОМЕРОМ ═════════════════════════════════ */

ЯЗЫКИ.forEach(я => {
    const п = панельИнфо(ШАПКА[я]), м = списокИнфо(ШАПКА[я]);
    const сп = 'sponsors' + ХВОСТ[я] + '.html', ск = 'download' + ХВОСТ[я] + '.html';
    правило('пункт спонсоров стоит перед «скачать» в панели (' + я + ')',
        п.indexOf(сп) !== -1 && п.indexOf(ск) !== -1 && п.indexOf(сп) < п.indexOf(ск),
        '«скачать приложение» — единственный пункт со значком и замыкает\n' +
        'список. Содержательный пункт после него читается как часть хвоста');
    правило('пункт спонсоров стоит перед «скачать» в мобильном списке (' + я + ')',
        м.indexOf(сп) !== -1 && м.indexOf(ск) !== -1 && м.indexOf(сп) < м.indexOf(ск),
        'тот же порядок, что в панели: одно меню — один порядок');
});

/* ══ ТРИ ЯЗЫКА НЕСУТ ОДИН НАБОР ═════════════════════════════════════════ */

правило('наборы пунктов «Инфо» на трёх языках равной длины',
    new Set(ЯЗЫКИ.map(я => пунктов(панельИнфо(ШАПКА[я])))).size === 1 &&
    new Set(ЯЗЫКИ.map(я => пунктов(списокИнфо(ШАПКА[я])))).size === 1,
    'расхождение языков — та самая беда, от которой заведён сам образец:\n' +
    'на сайте уже оказывалось три разных подвала, а ссылка Live с русской\n' +
    'страницы вела на английскую главную');

/* ══ ПРЕДЕЛ ПАНЕЛИ ВМЕЩАЕТ СПИСОК ═══════════════════════════════════════ */

const предел = (СТИЛИ.match(/\.mobile-nav-dropdown\.active \.mobile-dropdown-menu \{\s*max-height: (\d+)px/) || [])[1];
const РЯД = 45;   // замерено 13.10 на 844×390: поля 12 + 12, межстрочный 21
правило('предел мобильной панели вмещает список «Инфо» целиком',
    предел !== undefined &&
    ЯЗЫКИ.every(я => пунктов(списокИнфо(ШАПКА[я])) * РЯД <= Number(предел)),
    'замер 13.10: на 844×390 список занял 450 при пределе 500 — запас\n' +
    'ровно в один ряд. Одиннадцатый пункт «Инфо» обрежется, и обрежется\n' +
    'молча: у панели overflow-y:auto, то есть внутри открытого меню\n' +
    'появится ВТОРАЯ полоса прокрутки. Правило держит отношение: предел ' +
    'не меньше, чем ряд на число пунктов');

/* ══ ПУТЬ В ОБРАЗЦЕ — ЧЕРЕЗ ПОДСТАНОВКУ ═════════════════════════════════ */

правило('путь к спонсорам в образцах идёт через {{P}}',
    ЯЗЫКИ.every(я => !/href="(?:pages\/|\.\.\/)[^"]*sponsors/.test(ШАПКА[я] + ПОДВАЛ[я])) &&
    ЯЗЫКИ.every(я => (ШАПКА[я] + ПОДВАЛ[я]).indexOf('{{P}}sponsors') !== -1),
    'зашитый путь верен ровно на одном уровне вложенности: `sponsors.html`\n' +
    'сломается на index, `pages/sponsors.html` — на всех страницах в pages');

/* ══ СТРАНИЦА СПОНСОРОВ ПОДСВЕЧИВАЕТ «ИНФО» ═════════════════════════════ */

правило('карта разделов знает страницу спонсоров',
    /'sponsors':\s*'info'/.test(СБОРКА),
    'пункт живёт в «Инфо», значит на самой странице «Инфо» обязано быть\n' +
    'подсвечено: иначе человек стоит в разделе, который меню не признаёт');

/* ══ ЦЕЛЬ СУЩЕСТВУЕТ ════════════════════════════════════════════════════ */

правило('страница спонсоров есть на всех трёх языках',
    ЯЗЫКИ.every(я => fs.existsSync(path.join(КОРЕНЬ, 'pages', 'sponsors' + ХВОСТ[я] + '.html'))),
    'ссылка на несуществующий файл — 404 из меню на каждой странице сайта');

/* ══ СТРАНИЦЫ НЕ РАЗОШЛИСЬ С ОБРАЗЦОМ ═══════════════════════════════════ */

const стр = [];
(function обойти(д) {
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д ? д + '/' + э.name : э.name;
        if (э.isDirectory()) {
            if (['node_modules', 'maket', '_sync', 'mobile', 'tests', '.git', 'partials'].indexOf(э.name) === -1) обойти(п);
        } else if (э.name.endsWith('.html')) стр.push(п);
    });
})('');

const сПанелью = стр.filter(ф => /download(-en|-kg)?\.html" class="nav-dropdown-item"/.test(чит(ф)));
const сПунктом = сПанелью.filter(ф => /sponsors(-en|-kg)?\.html" class="nav-dropdown-item"/.test(чит(ф)));
const сСписком = стр.filter(ф => /<li><a href="(?:pages\/)?download(-en|-kg)?\.html"/.test(чит(ф)));
const вСписке  = сСписком.filter(ф => /<li><a href="(?:pages\/)?sponsors(-en|-kg)?\.html">/.test(чит(ф)));

правило('ни одна страница с панелью «Инфо» не осталась без пункта',
    сПанелью.length > 0 && сПунктом.length === сПанелью.length,
    'страниц с панелью — ' + сПанелью.length + ', с пунктом — ' + сПунктом.length + '.\n' +
    'Четыре страницы (admin и три кабинета) живут со своей шапкой и мимо\n' +
    'сборки: именно они и отстают, когда правишь только образец');

правило('ни одна страница с мобильным «Инфо» не осталась без пункта',
    сСписком.length > 0 && вСписке.length === сСписком.length,
    'страниц со списком — ' + сСписком.length + ', с пунктом — ' + вСписке.length);

if (ошибки.length === 0) {
    console.log('  ок      пункт «Стать спонсором» в меню «Инфо»: ' + (6 + 6 + 1 + 1 + 1 + 1 + 1 + 2) + ' правил');
    console.log('          оба меню на трёх языках   ·   порядок отношением');
    console.log('          предел панели вмещает список   ·   страницы не отстали');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  меню «Инфо» — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
