#!/usr/bin/env node
/**
 * ПОЛНОТА ПРОГОНА: СТОРОЖ, КОТОРОГО НЕ ГОНЯЮТ, НЕ СТОРОЖИТ НИЧЕГО
 * (кусок «полнота прогона», 07.11.2026).
 *
 * ЗАЧЕМ. Эта беда УЖЕ ПРИХОДИЛА ДВАЖДЫ, и оба раза её находили случайно:
 *   · 29.10 — «БЕГУНОК, КОТОРЫЙ НЕ ЗАПУСКАЮТ, МОЛЧА ГНИЁТ»: когда полный
 *     прогон наконец сделали, 42 прувера из 201 оказались сгнившими
 *     (`tools/check-vse-srezom.js` заведён ровно поэтому);
 *   · 27.10 — `tools/check-rules.js` своими же словами пишет: «этот
 *     сторож НЕ ВХОДИЛ в check-vse.js, то есть его падение никто не
 *     видел», и внутри него тогда жила проверка версий, падавшая НА
 *     ПРАВИЛЬНОМ КОДЕ.
 *
 * ЗАМЕР 07.11 (найдено по хвостам): из 250 сторожей ТРОЕ не входили в
 * общий прогон и ни у одного из них не было прувера — `check-shkala.js`
 * (шкала кеглей сайта), `check-rules.js` (правила клуба и копии для
 * приложения) и `check-vse-srezom.js`, который не сторож, а второй
 * бегунок. То есть хвост «у сайта нет сторожа размеров» был не про
 * отсутствие файла: файл есть, его просто никто не запускал.
 *
 * ЧТО ДЕРЖИТ СТОРОЖ:
 *   • каждый сторож внесён в `check-vse.js`;
 *   • у каждого сторожа есть прувер — «у меня зелёное» ничего не
 *     доказывает, доказывает упавший откат;
 *   • каждый прувер внесён в прогон вместе со своим сторожем;
 *   • бегунки исключены ПОИМЁННО: ИСКЛЮЧЕНИЕ НАЗЫВАЕТСЯ ИМЕНЕМ, А НЕ
 *     УГАДЫВАЕТСЯ ПО ВИДУ;
 *   • бегунок срезом читает список пар ИЗ `check-vse.js`, а не держит
 *     второй — два списка разошлись бы на первой правке;
 *   • число пар в прогоне не опускается (храповик).
 *
 * ЧЕГО СТОРОЖ НЕ МОЖЕТ: он не запускает сторожей и не знает, зелёные ли
 * они. Это работа `check-vse.js`; здесь проверяется только то, что ему
 * вообще отдали всех.
 *
 * Запуск: node tools/check-polnota-progona.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const ПАПКА = path.join(КОРЕНЬ, 'tools');
const ПРОГОН = 'tools/check-vse.js';
const СРЕЗОМ = 'check-vse-srezom.js';

/* БЕГУНКИ — НЕ СТОРОЖА, И ОНИ НАЗВАНЫ ПОИМЁННО. Угадывать их по имени
   («если в имени есть vse») — значит завести правило, которое само себя
   обойдёт при следующем файле. */
const БЕГУНКИ = ['check-vse.js', СРЕЗОМ];

const текстПрогона = fs.existsSync(path.join(КОРЕНЬ, ПРОГОН))
    ? fs.readFileSync(path.join(КОРЕНЬ, ПРОГОН), 'utf8') : '';

const всеФайлы = fs.existsSync(ПАПКА)
    ? fs.readdirSync(ПАПКА).filter(и => /^check-.*\.js$/.test(и)) : [];
const сторожа = всеФайлы.filter(и => !/-otkat\.js$/.test(и) && БЕГУНКИ.indexOf(и) === -1);
const пруверы = всеФайлы.filter(и => /-otkat\.js$/.test(и));

console.log('\n  ПОЛНОТА ПРОГОНА\n');

правило('общий бегунок на месте',
    текстПрогона.length > 0,
    'Файла ' + ПРОГОН + ' нет или он пуст — проверять полноту нечего.');

/* ── 1. КАЖДЫЙ СТОРОЖ ВНЕСЁН В ПРОГОН ──────────────────────────────── */
const внеПрогона = сторожа.filter(и => текстПрогона.indexOf("'" + и + "'") === -1);
правило('каждый сторож внесён в общий прогон',
    внеПрогона.length === 0,
    'Вне прогона: ' + (внеПрогона.join(', ') || '—') + '.\n' +
    'НЕПРОГНАННЫЙ СТОРОЖ — НЕ СТОРОЖ: его правила не держат ничего, а\n' +
    'падение не видит никто. Внесите пару в `check-vse.js`.');

/* ── 2. У КАЖДОГО СТОРОЖА ЕСТЬ ПРУВЕР ──────────────────────────────── */
const безПрувера = сторожа.filter(и =>
    !fs.existsSync(path.join(ПАПКА, и.replace(/\.js$/, '-otkat.js'))));
правило('у каждого сторожа есть прувер',
    безПрувера.length === 0,
    'Без прувера: ' + (безПрувера.join(', ') || '—') + '.\n' +
    '«У МЕНЯ ЗЕЛЁНОЕ» НИЧЕГО НЕ ДОКАЗЫВАЕТ. Доказывает откат, который\n' +
    'уронил ИМЕННО то правило, что за это отвечает: иначе правило может\n' +
    'держать форму кода, а не смысл, и молчать на настоящей беде.');

/* ── 3. КАЖДЫЙ ПРУВЕР ВНЕСЁН В ПРОГОН ──────────────────────────────── */
const пруверыВне = пруверы.filter(и => текстПрогона.indexOf("'" + и + "'") === -1);
правило('каждый прувер внесён в общий прогон',
    пруверыВне.length === 0,
    'Вне прогона: ' + (пруверыВне.join(', ') || '—') + '.\n' +
    'Прувер, которого не запускают, гниёт молча: 29.10 таких нашлось 42\n' +
    'из 201 — все якоря разъехались с кодом, и ни один не был виден.');

/* ── 4. У КАЖДОГО ПРУВЕРА ЕСТЬ СВОЙ СТОРОЖ ─────────────────────────── */
const сиротыПруверы = пруверы.filter(и =>
    !fs.existsSync(path.join(ПАПКА, и.replace(/-otkat\.js$/, '.js'))));
правило('у каждого прувера есть свой сторож',
    сиротыПруверы.length === 0,
    'Пруверы без сторожа: ' + (сиротыПруверы.join(', ') || '—') + '.\n' +
    'Такой прувер поднимает файл, которого нет, и падает не по делу —\n' +
    'либо остался от снятого куска и его надо убрать вместе с ним.');

/* ── 5. БЕГУНКИ НАЗВАНЫ ПОИМЁННО И СУЩЕСТВУЮТ ──────────────────────── */
const бегункиНет = БЕГУНКИ.filter(и => !fs.existsSync(path.join(ПАПКА, и)));
правило('исключённые бегунки существуют',
    бегункиНет.length === 0,
    'Названы, но отсутствуют: ' + (бегункиНет.join(', ') || '—') + '.\n' +
    'Список исключений — это утверждение о продукте. Исключение, которого\n' +
    'нет, прячет от правила настоящий файл с тем же именем в будущем.');

/* ── 6. БЕГУНОК СРЕЗОМ НЕ ДЕРЖИТ ВТОРОЙ СПИСОК ПАР ─────────────────── */
const срезом = fs.existsSync(path.join(ПАПКА, СРЕЗОМ))
    ? fs.readFileSync(path.join(ПАПКА, СРЕЗОМ), 'utf8') : '';
правило('бегунок срезом читает список пар из общего бегунка',
    /check-vse\.js/.test(срезом) && /readFileSync/.test(срезом),
    'В ' + СРЕЗОМ + ' нет чтения `check-vse.js`.\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: два списка пар разошлись бы на\n' +
    'первой же правке, и срезом гонялось бы не то, что полным прогоном.');

/* ── 7. ХРАПОВИК ЧИСЛА ПАР ─────────────────────────────────────────── */
/* ЗАМЕР 07.11 после внесения `check-shkala.js` и `check-rules.js`:
   сторожей 250, пруверов 250. Храповик ходит ВВЕРХ свободно, вниз —
   только с причиной, названной здесь же: снятый кусок уносит свою пару,
   и тогда число опускают вместе с записью в трекере. */
const ПОЛ_СТОРОЖЕЙ = 250;
правило('сторожей не стало меньше замеренного',
    сторожа.length >= ПОЛ_СТОРОЖЕЙ,
    'Сторожей ' + сторожа.length + ', замерено ' + ПОЛ_СТОРОЖЕЙ + '.\n' +
    'Вниз — значит пара исчезла. Если кусок снят намеренно, опустите\n' +
    'число здесь и напишите в трекере, какой именно и почему.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else {
    console.log('  ок      полнота прогона: все ' + держится + ' правил держатся');
    console.log('          сторожей ' + сторожа.length + ', пруверов ' + пруверы.length +
                ', вне прогона ноль, без прувера ноль\n');
}
