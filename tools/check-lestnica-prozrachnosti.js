/**
 * ЗАМОРОЗКА ЛЕСТНИЦЫ ПРОЗРАЧНОСТИ (круг B3, 15.10.2026).
 *
 * ЗАМЕР 15.10: 632 прозрачных места в публичном css вне tokens.css, и
 * 43 разные альфы при шести ступенях на белый и шести на чёрный. Белую
 * границу звали пятнадцатью разными числами на 83 места, чёрную подложку —
 * девятнадцатью. Лайм при семи ступенях не звали числом НИ РАЗУ: шкала
 * работает ровно там, где ступени есть.
 *
 * ЗАМОРОЖЕНЫ ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *
 *   • белая и чёрная прозрачность записывается ИМЕНЕМ, а не числом;
 *   • лестница РАЗНАЯ ПО РОЛИ — одна шкала на все роли не работает:
 *       граница    0.08 · 0.12 · 0.20
 *       подложка   0.04 · 0.08 · 0.12
 *       текст      0.35 · 0.50 · 0.72
 *       затемнение 0.50 · 0.65 · 0.85   (чёрный)
 *       тень       0.30 · 0.50 · 0.90   (чёрный)
 *   • прозрачный текст держит AA (4.5 на фоне страницы) везде, кроме
 *     поимённого списка неактивного — его ведёт check-tihiy-tekst;
 *   • ГРАНИЦА ЭЛЕМЕНТА УПРАВЛЕНИЯ в лестницу НЕ ВХОДИТ: её планка —
 *     WCAG 1.4.11 (3:1), это отдельный заход. Здесь она только не
 *     подтягивается к ступеням лестницы границ;
 *   • одно значение шкалы — одно имя.
 *
 * ПОСЧИТАНО (WCAG 2.1, белый с альфой на --bg-primary #0A0A0A):
 *   0.25 -> 2.14   0.35 -> 3.14   0.45 -> 4.50   0.60 -> 7.30
 *   0.30 -> 2.59   0.40 -> 3.77   0.50 -> 5.33   0.72 -> 10.25
 *
 *   node tools/check-lestnica-prozrachnosti.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ПАПКА = path.join(КОРЕНЬ, 'css');
const ФАЙЛЫ = fs.readdirSync(ПАПКА).filter(ф => ф.endsWith('.css'));

/* Гашение комментариев СОХРАНЯЕТ ПЕРЕВОДЫ СТРОК: иначе номера строк
   уезжают вниз на число строк во всех комментариях выше, и находка
   указывает не туда. */
const гасить = s => s.replace(/\/\*[\s\S]*?\*\//g, m => m.replace(/[^\n]/g, ' '));

/* СТУПЕНИ ВЗЯТЫ ИЗ ЗАМЕРА, А НЕ ПРИДУМАНЫ. Первая редакция дала по три
   ступени на роль и тут же разошлась с кодом: замер считал ЧИСЛА и не видел
   имён, уже стоявших мимо — волосяную границу --alpha-white-04 и лёгкое
   затемнение --alpha-black-30. Они в лестнице, потому что работают.
   Ступени 0.60 и 0.65 держать обе нельзя — это не лестница, а дребезг:
   0.65 завелась этим кругом, 0.60 старше и зовётся именем, 26 мест сведены
   на неё. */
const ЛЕСТНИЦА = {
    'белый|граница':    [0.04, 0.08, 0.12, 0.20],
    'белый|подложка':   [0.04, 0.08, 0.12],
    'белый|текст':      [0.35, 0.50, 0.72],
    'белый|тень':       [0.04, 0.12, 0.28],
    'чёрный|подложка':  [0.20, 0.50, 0.60, 0.85],
    'чёрный|тень':      [0.30, 0.50, 0.90]
};

/* ДОЛГ СЛЕДУЮЩЕГО ЗАХОДА, А НЕ ПРОЩЕНИЕ. Граница элемента управления живёт
   по WCAG 1.4.11 (3:1), а не по этой лестнице, и ни одно из девяти мест
   ниже порога не проходит: 0.05 даёт 1.1, 0.15 — 1.5, 0.30 — 2.1. Трогать
   их этим кругом нельзя — это другой разбор и другие глаза. Список закрыт:
   новое место сюда не добавится молча. */
const ДОЛГ_КОНТРОЛОВ = [
    ['.ad-col-dd-check input[type="checkbox"]', 0.3],
    ['.ad-col-dd-check-all input[type="checkbox"]', 0.3],
    ['.ad-pts-in:hover', 0.16],
    ['.bo-vote-btn', 0.15],
    ['.ch-vote-btn', 0.15],
    ['.co-picker-option', 0.06],
    ['.ct-picker-option', 0.06],
    ['.db-field-input.is-saved', 0.05],
    ['.rat-rule-input', 0.15]
];
const РОЛЬ = {
    background: 'подложка', 'background-color': 'подложка', 'background-image': 'подложка',
    border: 'граница', 'border-color': 'граница', 'border-top': 'граница',
    'border-bottom': 'граница', 'border-left': 'граница', 'border-right': 'граница',
    'border-top-color': 'граница', 'border-bottom-color': 'граница',
    outline: 'граница', 'outline-color': 'граница',
    color: 'текст', 'caret-color': 'текст',
    'box-shadow': 'тень', 'text-shadow': 'тень'
};
const ОСНОВЫ = { '255,255,255': 'белый', '0,0,0': 'чёрный' };

/* Контрол узнаётся ПО БЛОКУ, а не по имени: `.ad-crt-amenity` — настоящий
   чекбокс (appearance:none, 16x16), слова «input» в имени у него нет. */
const КОНТР_СЕЛ = /input|checkbox|radio|\bswitch\b|toggle|select|\bslider\b|\[type=/i;
const КОНТР_ТЕЛО = /appearance\s*:|accent-color\s*:/i;

/* ── разбор css на блоки стеком ──────────────────────────────────────── */

/* РАЗБОР КЭШИРУЕТСЯ. Первая редакция читала и разбирала все css по разу на
   каждую проверку — три полных прохода, 5 секунд на прогон и 43 на прувер,
   который гоняет правило десять раз. */
const кэш = {};
function разбор(ф) {
    if (!(ф in кэш)) {
        const т = гасить(fs.readFileSync(path.join(ПАПКА, ф), 'utf8'));
        кэш[ф] = { текст: т, бл: блоки(т) };
    }
    return кэш[ф];
}

function блоки(текст) {
    const из = [], стек = [];
    let i = 0, пред = 0;
    while (i < текст.length) {
        const c = текст[i];
        if (c === '{') {
            const сел = текст.slice(пред, i).trim().split('\n').pop().trim();
            стек.push([сел, i, текст.slice(0, i).split('\n').length]);
            пред = i + 1;
        } else if (c === '}') {
            const в = стек.pop();
            if (в) из.push({ сел: в[0], тело: текст.slice(в[1] + 1, i), стр: в[2] });
            пред = i + 1;
        } else if (c === ';') пред = i + 1;
        i++;
    }
    return из;
}

function разбратьЦвет(s) {
    const m = /^rgba?\(([^)]*)\)$/.exec(s.trim().toLowerCase());
    if (!m) return null;
    const ч = m[1].split(/[,\s/]+/).filter(Boolean).map(Number);
    if (ч.some(n => !Number.isFinite(n))) return null;
    if (ч.length === 3) ч.push(1);
    return ч.length === 4 ? ч : null;
}

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ══ 1. ЧИСЛОМ НЕ ПИШЕМ ════════════════════════════════════════════════ */

const числом = [];
const контролов = [];
ФАЙЛЫ.forEach(ф => {
    if (ф === 'tokens.css') return;
    const бл = разбор(ф).бл;
    /* имя класса, который хоть раз объявлен как контрол, остаётся контролом
       и в `.x:checked`, и в `.x:focus` */
    const именаКонтролов = new Set();
    бл.forEach(b => {
        if (КОНТР_СЕЛ.test(b.сел) || КОНТР_ТЕЛО.test(b.тело))
            (b.сел.match(/\.[\w-]+/g) || []).forEach(к => именаКонтролов.add(к));
    });
    бл.forEach(b => {
        const контрол = КОНТР_СЕЛ.test(b.сел) || КОНТР_ТЕЛО.test(b.тело)
            || (b.сел.match(/\.[\w-]+/g) || []).some(к => именаКонтролов.has(к));
        const прямое = b.тело.replace(/\{[^{}]*\}/g, m => m.replace(/[^\n]/g, ' '));
        const об = /(?:^|[;\s])([-a-zA-Z]+)\s*:\s*([^;}]*)/g;
        let d;
        while ((d = об.exec(прямое)) !== null) {
            const рл = РОЛЬ[d[1].toLowerCase()];
            if (!рл) continue;
            const цв = /rgba?\([^()]*\)/g;
            let m;
            while ((m = цв.exec(d[2])) !== null) {
                const ч = разбратьЦвет(m[0]);
                if (!ч || ч[3] >= 1 || ч[3] === 0) continue;
                const осн = ОСНОВЫ[ч.slice(0, 3).join(',')];
                if (!осн) continue;
                if (рл === 'граница' && контрол) { контролов.push({ файл: ф, стр: b.стр, сел: b.сел.trim(), альфа: ч[3] }); continue; }
                числом.push(ф + ':' + b.стр + '  ' + b.сел.slice(0, 40) + '  ' + m[0] + '  (' + осн + ' ' + рл + ')');
            }
        }
    });
});

правило('белая и чёрная прозрачность записана именем',
    числом.length === 0,
    'мест числом: ' + числом.length + '\n            ' + числом.slice(0, 8).join('\n            ') +
    '\n            Имя — это ОДНО определение. Число рядом с именем — второе,\n' +
    '            и правка токена пройдёт мимо него.');

/* ══ 2. ЛЕСТНИЦА ПО РОЛИ ═══════════════════════════════════════════════ */

const ТОКЕНЫ = {};
{
    const т = гасить(fs.readFileSync(path.join(ПАПКА, 'tokens.css'), 'utf8'));
    const об = /(--[\w-]+)\s*:\s*([^;]+);/g;
    let m;
    while ((m = об.exec(т)) !== null) if (!(m[1] in ТОКЕНЫ)) ТОКЕНЫ[m[1]] = m[2].trim();
}
function значение(имя, гл) {
    if ((гл || 0) > 10 || !(имя in ТОКЕНЫ)) return null;
    const v = ТОКЕНЫ[имя].trim();
    const m = /^var\(\s*(--[\w-]+)\s*(?:,[\s\S]*)?\)$/.exec(v);
    return m ? значение(m[1], (гл || 0) + 1) : разбратьЦвет(v);
}

const мимо = [];
ФАЙЛЫ.forEach(ф => {
    if (ф === 'tokens.css') return;
    разбор(ф).бл.forEach(b => {
        const контрол = КОНТР_СЕЛ.test(b.сел) || КОНТР_ТЕЛО.test(b.тело);
        const прямое = b.тело.replace(/\{[^{}]*\}/g, m => m.replace(/[^\n]/g, ' '));
        const об = /(?:^|[;\s])([-a-zA-Z]+)\s*:\s*([^;}]*)/g;
        let d;
        while ((d = об.exec(прямое)) !== null) {
            const рл = РОЛЬ[d[1].toLowerCase()];
            if (!рл) continue;
            const зов = /var\(\s*(--alpha-(?:white|black)-\d+)\s*\)/g;
            let m;
            while ((m = зов.exec(d[2])) !== null) {
                const ч = значение(m[1]);
                if (!ч) continue;
                const осн = ОСНОВЫ[ч.slice(0, 3).join(',')];
                if (!осн) continue;
                if (рл === 'граница' && контрол) continue;
                const ст = ЛЕСТНИЦА[осн + '|' + рл];
                if (!ст) continue;
                if (!ст.some(x => Math.abs(x - ч[3]) < 1e-6))
                    мимо.push(ф + ':' + b.стр + '  ' + b.сел.slice(0, 36) + '  ' + m[1] +
                              ' (' + ч[3] + ') мимо ступеней ' + ст.join(' · ') + ' для «' + рл + '»');
            }
        }
    });
});

правило('ступень берётся по РОЛИ, а не одна на всё',
    мимо.length === 0,
    'мест мимо лестницы своей роли: ' + мимо.length + '\n            ' + мимо.slice(0, 8).join('\n            ') +
    '\n            Граница, подложка и текст живут на РАЗНЫХ ступенях: у них\n' +
    '            разная работа и разная планка контраста.');

/* ══ 3. ПРОЗРАЧНЫЙ ТЕКСТ ДЕРЖИТ AA ═════════════════════════════════════ */

/* Поимённо — те же, что ведёт check-tihiy-tekst, плюс декор, который
   текстом не является: разделитель в подвале и значок карточки «Инфо». */
const ОСВОБОЖДЕНЫ = [
    '.ad-pts-in.ad-pts-zero', '.ad-pts-off',
    '.pl-row-guest .pl-col-rank', '.pl-guest-mark',
    '.ad-brk-schedule', '.ad-brk-player.loser .ad-brk-name',
    '.co-vh-status-used', '.ct-vh-status-used',
    '.site-notif-item-time',
    '.io-card .io-card-icon', '.io-card:hover .io-card-icon',
    '.footer-bottom-links li + li a::before'
];
const ФОН = [10, 10, 10];
const яркость = (r, g, b) => {
    const к = c => { c /= 255; return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4); };
    return 0.2126 * к(r) + 0.7152 * к(g) + 0.0722 * к(b);
};
function контраст(ч) {
    const c = [0, 1, 2].map(i => ч[i] * ч[3] + ФОН[i] * (1 - ч[3]));
    const a = яркость(c[0], c[1], c[2]), b = яркость(ФОН[0], ФОН[1], ФОН[2]);
    return (Math.max(a, b) + 0.05) / (Math.min(a, b) + 0.05);
}

const слепые = [];
ФАЙЛЫ.forEach(ф => {
    if (ф === 'tokens.css') return;
    разбор(ф).бл.forEach(b => {
        if (ОСВОБОЖДЕНЫ.indexOf(b.сел.trim()) !== -1) return;
        const прямое = b.тело.replace(/\{[^{}]*\}/g, m => m.replace(/[^\n]/g, ' '));
        const d = /(?:^|[;\s])color\s*:\s*([^;}]+)/.exec(прямое);
        if (!d) return;
        const v = d[1].trim();
        const m = /^var\(\s*(--[\w-]+)/.exec(v);
        const ч = m ? значение(m[1]) : разбратьЦвет(v);
        if (!ч || ч[3] >= 1) return;
        if (!ОСНОВЫ[ч.slice(0, 3).join(',')]) return;
        const к = контраст(ч);
        if (к < 4.5) слепые.push(ф + ':' + b.стр + '  ' + b.сел.slice(0, 40) + '  альфа ' + ч[3] + ' -> ' + к.toFixed(2));
    });
});

правило('прозрачный текст не падает ниже AA',
    слепые.length === 0,
    'мест ниже 4.5: ' + слепые.length + '\n            ' + слепые.slice(0, 8).join('\n            ') +
    '\n            Освобождение даёт только НЕАКТИВНОЕ (WCAG 1.4.3) и декор —\n' +
    '            поимённо, в списке ОСВОБОЖДЕНЫ этого файла.');

/* ══ 4. ОДНО ЗНАЧЕНИЕ — ОДНО ИМЯ ═══════════════════════════════════════ */

const поЗначению = {};
Object.keys(ТОКЕНЫ).forEach(имя => {
    if (!/^--alpha-(white|black)-/.test(имя)) return;
    const ч = значение(имя);
    if (!ч) return;
    const к = ч.join(',');
    (поЗначению[к] = поЗначению[к] || []).push(имя);
});
const двойные = Object.keys(поЗначению).filter(к => поЗначению[к].length > 1);

правило('у ступени шкалы одно имя',
    двойные.length === 0,
    'ступеней с двумя именами: ' + двойные.length + '\n            ' +
    двойные.map(к => 'rgba(' + к + ') -> ' + поЗначению[к].join(', ')).join('\n            '));

/* ══ 5. ГРАНИЦА КОНТРОЛА ОСТАЛАСЬ СВОИМ ЗАХОДОМ ════════════════════════ */

const ждали = ДОЛГ_КОНТРОЛОВ.map(п => п[0]);
const новые = контролов.filter(к => ждали.indexOf(к.сел) === -1);

правило('долг по границам контролов не растёт молча',
    новые.length === 0,
    'границ контролов числом сверх списка: ' + новые.length + '\n            ' +
    новые.slice(0, 6).map(к => к.файл + ':' + к.стр + '  ' + к.сел + '  альфа ' + к.альфа).join('\n            ') +
    '\n            Граница контрола держит планку WCAG 1.4.11 (3:1), а не эту\n' +
    '            лестницу. Новое такое место заводится СПИСКОМ ДОЛГ_КОНТРОЛОВ\n' +
    '            этого файла — вместе с решением, когда его закрывают.');

правило('долг по границам контролов не растёт в значении',
    контролов.every(к => {
        const п = ДОЛГ_КОНТРОЛОВ.find(x => x[0] === к.сел);
        return !п || Math.abs(п[1] - к.альфа) < 1e-6;
    }),
    'у места из списка долга поменялась альфа: список назван числами,\n' +
    '            и правка мимо разбора пройдёт незамеченной.');

/* ══ ВЫВОД ═════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('\n  ок      лестница прозрачности: 5 правил');
    console.log('          белый и чёрный записаны именем, ступень берётся по роли');
    console.log('          прозрачный текст держит AA, у ступени одно имя');
    console.log('          граница контрола оставлена своему заходу\n');
} else {
    console.log('\n  НЕ ТАК  лестница прозрачности — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(о => {
        console.log('          x ' + о.имя);
        console.log('            ' + о.подсказка + '\n');
    });
    process.exitCode = 1;
}
