#!/usr/bin/env node
/**
 * Заморозка экрана входа — проверка по исходникам, без браузера и базы.
 *
 * ЗАЧЕМ. Экран входа закрыт 21.09.2026: две колонки на низком и широком
 * экране, три способа одной высоты, все цели нажатия 44, Apple заведён и
 * спрятан флагом. Заморозка защищает это от МЕНЯ на следующих прогонах —
 * не от постороннего.
 *
 * Она стережёт ПРАВИЛА, а не картинку:
 *
 *   1. раскладка переключается по ВЫСОТЕ экрана, а не по ширине и не по
 *      устройству;
 *   2. правило держит только вход и не трогает остальные экраны карточки;
 *   3. две колонки — две независимые стопки, а не общая сетка строк;
 *   4. нарисованный размер и область нажатия — разные числа;
 *   5. мёртвых кнопок не бывает: Apple показывается только под флагом.
 *
 * Замеры, на которых всё построено (21.09.2026, 5 видов x 3 языка):
 *   844x390 — способы входа были за сгибом на 158, стало 0
 *   целей меньше 44 на экране входа: было 5 на вид, стало 0 из 15
 *   вкладки: дорожка 44, цель 44, пилюля 147x38
 *
 * Запуск:  node tools/check-auth.js   (он же npm run check:auth)
 * Код возврата 1, если хоть один пункт не сошёлся.
 *
 * Корень можно подменить через KSLT_ROOT — этим пользуется прибор отката
 * tools/check-auth-otkat.js.
 */

const fs = require('fs');
const path = require('path');

const ROOT = process.env.KSLT_ROOT || path.join(__dirname, '..');
const читать = (...ч) => fs.readFileSync(path.join(ROOT, ...ч), 'utf8');

const ошибки = [];
const ок = [];
function проверить(имя, условие, почему) {
    if (условие) ок.push(имя); else ошибки.push({ имя, почему });
}

/* КОММЕНТАРИИ СНИМАЕМ ДО ЛЮБОЙ ПРОВЕРКИ.
 *
 * Поймано откатом 21.09: правило про пилюлю вкладки искало
 * background-clip: padding-box и находило его в МОЁМ ЖЕ пояснении над
 * кодом. Откат менял объявление на border-box — проверка оставалась
 * зелёной, потому что читала комментарий.
 *
 * Это та же болезнь, что была на шапке: проверка сверяется с
 * документацией вместо кода. Правило, которое читает комментарий, —
 * это пожелание. */
const безКомментариев = т => т.replace(/\/\*[\s\S]*?\*\//g, '');

const стиль = безКомментариев(читать('css', 'style.css'));
const конфиг = безКомментариев(читать('js', 'supabase-config.js')).replace(/\/\/[^\n]*/g, '');
const авторизация = безКомментариев(читать('js', 'auth.js')).replace(/\/\/[^\n]*/g, '');
const СТРАНИЦЫ = ['auth.html', 'auth-en.html', 'auth-kg.html'];
const страницы = СТРАНИЦЫ.map(и => ({ имя: и, текст: читать('pages', и) }));

/** Тело медиаблока про низкий и широкий экран — считаем скобки, а не
 *  регуляркой: регулярка перешагивает закрывающую скобку вложенного
 *  правила. На шапке это уже дало четыре ложных срабатывания. */
function телоБлока(текст, началоRe) {
    const м = началоRe.exec(текст);
    if (!м) return '';
    let i = м.index + м[0].length, глубина = 1;
    while (i < текст.length && глубина) {
        if (текст[i] === '{') глубина++;
        else if (текст[i] === '}') глубина--;
        i++;
    }
    return текст.slice(м.index + м[0].length, i - 1);
}

const ландшафт = телоБлока(стиль,
    /@media\s*\(max-height:\s*680px\)\s*and\s*\(min-width:\s*600px\)\s*\{/g);

// ---------- 1. условие раскладки ----------
проверить('раскладка переключается по высоте экрана, а не по ширине',
    ландшафт !== '',
    'Не найден блок @media (max-height: 680px) and (min-width: 600px). ' +
    'Телефон боком 844x390 и неразвёрнутое окно ноутбука — одна и та же ' +
    'задача: мало высоты, много ширины. Условие по ширине или по устройству ' +
    'ловит не то. Замер 21.09: на 844x390 способы входа были за сгибом на 158px.');

// ---------- 2. правило держит ТОЛЬКО вход ----------
проверить('две колонки включаются только на экране входа',
    (ландшафт.match(/:has\(#signinForm\.active\)/g) || []).length >= 2,
    'В блоке нет :has(#signinForm.active). У регистрации своя длина и свой ' +
    'разговор: без этой оговорки две колонки применятся ко всем девяти ' +
    'экранам карточки, и на регистрации правая колонка окажется пустой.');

// ---------- 3. две независимые стопки ----------
проверить('колонки — две обёртки, а не общая сетка строк',
    /\.auth-col-fields/.test(стиль) && /\.auth-col-methods/.test(стиль) &&
    /#signinForm\s*>\s*\.auth-col-fields/.test(ландшафт) &&
    /#signinForm\s*>\s*\.auth-col-methods/.test(ландшафт),
    'Пропали обёртки колонок. Без них дети формы раскладываются по общей ' +
    'сетке карточки, строки становятся ОБЩИМИ для обеих колонок, и ритм ' +
    'одной протекает в другую. Замер 21.09 в таком виде дал зазоры 12, 16, ' +
    '33 и 37 на одном экране — ни одного из шкалы.');

проверить('обёртки колонок есть на всех трёх языках',
    страницы.every(с => /class="auth-col-fields"/.test(с.текст) &&
                        /class="auth-col-methods"/.test(с.текст)),
    'Обёртка колонки есть не на всех трёх страницах входа. Раскладка ' +
    'обязана быть одинаковой на ru, en и kg.');

проверить('форма входа раскрывается в ячейки сетки карточки',
    /#signinForm\.active\s*\{[^}]*display:\s*contents/.test(ландшафт),
    'Нет display: contents у #signinForm.active. Без него форма остаётся ' +
    'одной ячейкой сетки и занимает одну колонку из двух.');

проверить('излишек высоты забирает вторая строка, а не обе',
    /grid-template-rows:\s*auto\s+1fr/.test(ландшафт),
    'Нет grid-template-rows: auto 1fr. С auto излишек, который приносит ' +
    'колонка полей, растекается по обеим строкам, и вкладки уезжают от ' +
    'способов входа.');

проверить('ячейки не растягиваются на высоту строки',
    /align-items:\s*start/.test(ландшафт),
    'Нет align-items: start. Без него ячейки тянутся на высоту строки, ' +
    'которую задают поля справа. Замер 21.09: вкладки 69 и Google 69 при ' +
    'Telegram 40 — ряд, который читается как собранный из кусков.');

// ---------- 4. способы входа — одна семья ----------
(function способыОднойВысоты() {
    const семья = /\.auth-col-methods\s+\.auth-social-btn,\s*\n\.auth-col-methods\s+\.auth-tg-app-btn,\s*\n\.auth-col-methods\s+\.auth-apple-btn\s*\{([^}]*)\}/
        .exec(стиль);
    проверить('Google, Telegram и Apple — одна семья кнопок, 52',
        семья !== null && /min-height:\s*52px/.test(семья[1]),
        'Три способа входа должны описываться одним правилом и иметь 52. ' +
        'До 21.09 это были две несвязанные кнопки: .auth-social-btn ' +
        '(паддинг 12, радиус --radius-md, текст --text-secondary) и ' +
        '.auth-tg-app-btn (паддинг 10/16, радиус 8 числом, текст ' +
        '--text-primary). Замер дал 44 и 40 — соседние кнопки в одном ' +
        'столбце разной высоты, и Telegram ниже 44.');
})();

// ---------- 5. цели нажатия ----------
(function цели() {
    const глаз = телоБлока(стиль, /\n\.auth-eye\s*\{/g);
    проверить('глаз показа пароля — цель 44x44',
        /width:\s*44px/.test(глаз) && /height:\s*44px/.test(глаз),
        'Было 28x28: значок 20 плюс паддинг 4. WCAG 2.5.5 требует 44. ' +
        'right: 4 вместо 12 подобран так, чтобы значок остался ровно там, ' +
        'где стоял — его центр был на 26 от края поля.');

    const забыли = телоБлока(стиль, /\n\.auth-forgot\s*\{/g);
    проверить('«Забыли пароль?» — цель 44 по высоте',
        /min-height:\s*44px/.test(забыли),
        'Была 19 — высота строки текста. Отрицательное поле справа держит ' +
        'текст прижатым к краю колонки, а не сдвинутым внутрь на паддинг цели.');
})();

// ---------- 6. вкладки: рисунок и палец — разные числа ----------
(function вкладки() {
    const дорожка = телоБлока(стиль, /\n\.auth-tabs\s*\{/g);
    const вкладка = телоБлока(стиль, /\n\.auth-tab\s*\{/g);

    проверить('дорожка вкладок не добавляет своего паддинга',
        /padding:\s*0\s*;/.test(дорожка),
        'У .auth-tabs вернулся паддинг. Высоту дорожки задаёт сама вкладка ' +
        '(44). Паддинг дорожки делает её 52 и разводит с доской.');

    проверить('вкладка ловит палец на 44',
        /min-height:\s*44px/.test(вкладка),
        'Было 36 — нарушение WCAG 2.5.5 на всех пяти видах и трёх языках.');

    проверить('пилюля рисуется внутрь рамки, а не растягивается до 44',
        /border:\s*3px\s+solid\s+transparent/.test(вкладка) &&
        /background-clip:\s*padding-box/.test(вкладка),
        'Пилюля по макету 38, а палец требует 44 — это РАЗНЫЕ числа, и они ' +
        'намеренно не равны. Apple HIG и Material обе рисуют сегментированный ' +
        'контрол низким, а палец ловят шире его границ. Приём: прозрачная ' +
        'рамка 3 плюс background-clip: padding-box — фон красится внутрь ' +
        'рамки ровно на 3 со всех сторон. content-box так не умеет: он режет ' +
        'по паддингу, а паддинг здесь разный по осям, и пилюля ужимается по ' +
        'бокам на 16 вместо 3.');
})();

// ---------- 7. hidden обязан прятать ----------
проверить('атрибут hidden сильнее display в классе',
    /\[hidden\]\s*\{\s*display:\s*none\s*!important/.test(стиль),
    'Пропало правило [hidden] { display: none !important }. Браузер прячет ' +
    '[hidden] своей таблицей, но любое НАШЕ правило с display его перебивает. ' +
    'Замер 21.09: спрятанный слот Apple внутри .auth-social (display: flex) ' +
    'занимал 64px в колонке способов входа.');

// ---------- 8. мёртвых кнопок не бывает ----------
проверить('Apple по умолчанию выключен и флаг можно переопределить',
    /window\.KSLT_APPLE\s*=\s*window\.KSLT_APPLE\s*\|\|\s*false/.test(конфиг),
    'В js/supabase-config.js флаг Apple должен быть window.KSLT_APPLE = ' +
    'window.KSLT_APPLE || false. Просто = false затирает значение, ' +
    'выставленное снаружи, и кнопку нельзя показать ни тестом, ни средой.');

проверить('кнопка Apple появляется только под флагом',
    /if\s*\(window\.KSLT_APPLE\)\s*\{[\s\S]{0,400}\[data-apple\]/.test(авторизация),
    'Обработчик Apple обязан жить внутри if (window.KSLT_APPLE). Мёртвая ' +
    'кнопка хуже отсутствующей: человек жмёт и получает ошибку провайдера.');

проверить('в разметке спрятаны и кнопка Apple, и её обёртка',
    страницы.every(с => /data-apple-slot hidden/.test(с.текст) &&
                        /data-apple hidden/.test(с.текст)),
    'Кнопка Apple или её обёртка не спрятаны в разметке. Обёртку надо ' +
    'прятать отдельно: у .auth-social задан display: flex, и спрятанная ' +
    'кнопка внутри видимой обёртки всё равно занимает место.');

проверить('логотип Apple — слот под официальный файл, а не глиф',
    страницы.every(с => с.текст.indexOf('') === -1 &&
                        /images\/apple-logo\.svg/.test(с.текст)),
    'В разметке символ U+F8FF вместо слота под файл. Этот глиф рисуется ' +
    'только на устройствах Apple, на Windows и Android это пустой ' +
    'прямоугольник. Фирменный знак берётся официальным файлом и кладётся ' +
    'в images/apple-logo.svg.');

проверить('порядок способов входа Google — Apple — Telegram',
    страницы.every(с => {
        const г = с.текст.indexOf('auth-social-btn');
        const a = с.текст.indexOf('auth-apple-btn');
        const t = с.текст.indexOf('auth-tg-app-btn');
        return г !== -1 && a !== -1 && t !== -1 && г < a && a < t;
    }),
    'Порядок способов входа в разметке изменился. Утверждён Костей 21.09: ' +
    'Google — Apple — Telegram, одинаково на входе и на выборе способа ' +
    'регистрации, на всех трёх языках.');

// ---------- 9. кеш ----------
(function версии() {
    const все = fs.readdirSync(path.join(ROOT, 'pages'))
        .filter(f => f.endsWith('.html'))
        .map(f => читать('pages', f))
        .concat(fs.readdirSync(ROOT).filter(f => f.endsWith('.html')).map(f => читать(f)));
    [['style.css', /style\.css\?v=(\d+)/g],
     ['auth.js', /\/auth\.js\?v=(\d+)/g],
     ['supabase-config.js', /supabase-config\.js\?v=(\d+)/g]].forEach(([имя, re]) => {
        const набор = new Set();
        все.forEach(т => { let м; const r = new RegExp(re.source, 'g');
            while ((м = r.exec(т)) !== null) набор.add(м[1]); });
        проверить('версия ' + имя + ' одна на все страницы',
            набор.size === 1,
            'У ' + имя + ' на страницах разные ?v=: ' +
            Array.from(набор).join(', ') + '. Правило, которое живёт только в ' +
            'документации, — это пожелание. Браузер отдаёт старый файл, и ' +
            'правка не доезжает до людей.');
    });
})();

// ---------- вывод ----------
console.log('');
for (const и of ок) console.log('  ок      ' + и);
for (const е of ошибки) {
    console.log('  НЕ ТАК  ' + е.имя);
    console.log('          ' + е.почему.replace(/\n/g, '\n          '));
}
console.log('');
console.log('Вход: сошлось ' + ок.length + ' из ' + (ок.length + ошибки.length));
console.log('');
process.exit(ошибки.length ? 1 : 0);
