#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «БЕЗОПАСНАЯ ЗОНА — ОДНО ОПРЕДЕЛЕНИЕ, И ОНА НЕ ЕДЕТ» (02.11).
 *
 * ДВА СЛУЧАЯ, ОБА УВИДЕНЫ ГЛАЗАМИ, И ОБА — ОДНА БЕДА С ДВУХ СТОРОН.
 *
 * ПЕРВЫЙ. «Уведомление наезжает на время, и тяжело нажать и выйти» —
 * панель уведомлений начиналась от самого верха экрана, и её шапка с
 * кнопкой возврата оказывалась ПОД часами и значками Android: заголовок
 * читался поверх времени, по кнопке было не попасть.
 *
 * ВТОРОЙ. «Что за повтор почты сверху отображается после скрола» —
 * повтора не было. У бокового меню `overflow-y: auto` стоял на самом
 * окне, и его `padding-top` с безопасной зоной прокручивался ВМЕСТЕ с
 * содержимым: строки меню заезжали в зону статусной строки и там
 * оставались видимыми. ОТСТУП, КОТОРЫЙ ЕДЕТ ВМЕСТЕ С СОДЕРЖИМЫМ, НЕ
 * ОТСТУП.
 *
 * ЗАМЕР 02.11: величина безопасной зоны была записана ТРЕМЯ способами —
 * токеном `--safe-top`, голым `env(safe-area-inset-top)` (пять мест) и
 * никак (одиннадцать окон из двенадцати). ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО
 * ПОНЯТИЕ: теперь величина живёт только в `tokens.css`.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ, И ЭТО НАЗВАНО. Прибор читает css как текст и видит
 * ПРАВИЛО, а не живой экран. Окно, которое залезет под часы по другой
 * причине — отрицательным отступом, своей шапкой `position: fixed`, —
 * он не поймает. Это проверяется глазами и пробой.
 *
 *   node tools/check-bezopasnaya-zona.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const APP = 'mobile/www/css/app.css';
const ТОКЕНЫ = 'mobile/www/css/tokens.css';

function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function безКом(т) {
    return (т || '').replace(/\/\*[\s\S]*?\*\//g, ' ');
}

/** Тело правила по имени селектора: от `.имя {` до ближайшей `}`. */
function тело(css, селектор) {
    const i = css.indexOf('\n' + селектор);
    if (i === -1) return null;
    const о = css.indexOf('{', i);
    const з = css.indexOf('}', о);
    if (о === -1 || з === -1) return null;
    return css.slice(о + 1, з);
}

const app = безКом(чит(APP));
const токены = безКом(чит(ТОКЕНЫ));

/* Сколько раз величина посчитана мимо токена. `@supports` не в счёт:
   он спрашивает БРАУЗЕР, понимает ли тот `env()` вовсе, и такой вопрос
   нельзя задать иначе. */
const сырые = (app.match(/env\(safe-area-inset-top/g) || []).length;
const вSupports = (app.match(/@supports[^{]*env\(safe-area-inset-top/g) || []).length;

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('величина безопасной зоны определена один раз',
    токены !== null && /--safe-top:\s*env\(safe-area-inset-top/.test(токены),
    'В `' + ТОКЕНЫ + '` нет `--safe-top`. Величина обязана жить в ОДНОМ\n' +
    'месте: иначе половина окон считает её по-своему, а половина не\n' +
    'считает вовсе — так и вышло до 02.11.');

правило('в одежде приложения нет своего счёта безопасной зоны',
    сырые - вSupports === 0,
    'Голый `env(safe-area-inset-top)` в `' + APP + '`: ' +
    (сырые - вSupports) + ' мест вне `@supports`.\n' +
    'Это второе определение того же понятия. Бери `var(--safe-top)`.');

правило('панель уведомлений держит безопасную зону',
    /padding-top:\s*var\(--safe-top\)/.test(тело(app, '.notif-overlay') || ''),
    'У `.notif-overlay` нет `padding-top: var(--safe-top)`. Окно\n' +
    'начнётся от самого верха экрана, и его шапка с кнопкой возврата\n' +
    'уйдёт под часы и значки Android — заголовок поверх времени, по\n' +
    'кнопке не попасть. Увидено глазами 02.11.');

правило('боковое меню прокручивает внутренний блок, а не себя',
    (function () {
        const окно = тело(app, '.side-menu') || '';
        const внутри = тело(app, '.menu-scroll') || '';
        /* У ОКНА отступ и НЕТ своей прокрутки; прокрутка у внутреннего. */
        return /padding-top:\s*calc\([^)]*var\(--safe-top\)/.test(окно) &&
               !/overflow-y:\s*auto/.test(окно) &&
               /overflow-y:\s*auto/.test(внутри);
    })(),
    'Либо `.side-menu` снова прокручивается сам, либо у него пропал\n' +
    'отступ, либо `.menu-scroll` перестал прокручиваться.\n' +
    'ОТСТУП, КОТОРЫЙ ЕДЕТ ВМЕСТЕ С СОДЕРЖИМЫМ, НЕ ОТСТУП: `padding-top`\n' +
    'на прокручиваемом окне уезжает вверх вместе с пунктами, и они\n' +
    'остаются видимыми в зоне статусной строки. Костя принял это за\n' +
    '«повтор почты сверху после скрола».');

правило('кнопка возврата из уведомлений — цель нажатия 44',
    (function () {
        const к = тело(app, '.notif-back') || '';
        return /min-height:\s*44px/.test(к) && /min-width:\s*44px/.test(к);
    })(),
    'У `.notif-back` нет цели нажатия 44 на обе стороны. Было 37 — кегль\n' +
    '21 плюс отступ 8, — и кнопка стояла под статусной строкой у самого\n' +
    'края. Слово Кости: «тяжело нажать и выйти».');

правило('прибор читает правило, а не подпись к нему',
    (function () {
        /* ОБРАЗЕЦ ВНУТРЬ ПРИБОРА. На подписях приборы КСЛТ попадались
           трижды: имя в комментарии принималось за живой код. */
        const о = '/* тут был env(safe-area-inset-top) */\n' +
                  '.a { padding-top: env(safe-area-inset-top); }\n';
        const ч = безКом(о);
        return (ч.match(/env\(safe-area-inset-top/g) || []).length === 1;
    })(),
    'Образец внутри прибора: одно упоминание в комментарии и одно в\n' +
    'коде. Прибор обязан насчитать РОВНО одно. Считает иначе — значит\n' +
    'падает на подписях и зеленеет на беде.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      безопасная зона: все ' + всего + ' правил держатся');
    console.log('          величина одна, своих счётов 0, окна держат отступ');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  безопасная зона — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
