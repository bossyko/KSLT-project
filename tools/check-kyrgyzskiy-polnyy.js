function словаМеню(ф) {
  const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
  return (т.match(/\n\s{20,}([^<>\n]{3,30})\n/g) || [])
    .map(с => с.trim()).filter(с => /^[А-Яа-яЁёA-Za-zӨөҮүҢң]/.test(с));
}
