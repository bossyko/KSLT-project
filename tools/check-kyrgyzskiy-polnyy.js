/**
 * ЗАМОРОЗКА КУСКА 138 — КЫРГЫЗСКИЙ НАЗЫВАЕТСЯ ВСЛУХ, А НЕ ПАДАЕТ В РУССКИЙ.
 *
 * ЧТО БЫЛО: 87 пар `isEn ? … : …`. У 29 из них кыргызский стоял ОДНИМ
 * УРОВНЕМ ВЫШЕ (`isKg ? … : (…)`) — и это я померил неверно, посмотрев на
 * узел и не посмотрев на РОДИТЕЛЯ: словари кабинета, входа, ваучера и
 * сравнения игроков были полны (361, 48, 27 и 8 ключей, ни одного
 * пропуска). СМОТРИ НА РОДИТЕЛЯ, А НЕ ТОЛЬКО НА УЗЕЛ.
 *
 * НАСТОЯЩИХ ДЫР БЫЛО 58, и они закрыты:
 *   · 12 кодов локали отдавали кыргызу `ru-RU` — теперь `ky-KG`;
 *   · 10 мест записывали заново `KSLT_YAZYK.код`, и четыре из них отдавали
 *     `'ru'` в `KSLT_RULES`, где кыргызский есть;
 *   · 4 адреса уводили с кыргызской страницы на РУССКУЮ (`dashboard.html`,
 *     `pricing.html`) — человек терял язык одним нажатием;
 *   · 22 текста переведены; `ntrpСтрока` знала два языка из трёх и
 *     показывала кыргызу «одиночка / пара»;
 *   · 9 выборов формы (сокращения месяцев, порядок даты) СКАЗАНЫ ВСЛУХ:
 *     кыргызская ветвь совпадает с русской, и это видно, а не угадывается;
 *   · 3 места, где у базы ЕСТЬ кыргызская колонка, её не спрашивали.
 *
 * ОСТАЛОСЬ 10 ПАР, И У КАЖДОЙ НАЗВАННАЯ ПРИЧИНА — список ниже.
 *
 *   node tools/check-kyrgyzskiy-polnyy.js
 */
const fs = require('fs');
const path = require('path');
const acorn = require('acorn');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

/* ПАРЫ, КОТОРЫМ КЫРГЫЗСКИЙ НЕ НУЖЕН — ПО ОДНОЙ ПРИЧИНЕ НА КАЖДУЮ.
   Имя файла и строка не годятся в якорь: строки едут. Якорь — САМ ТЕКСТ
   пары, то, что живёт в ней постоянно. */
const РАЗРЕШЁННЫЕ = [
  /* админка одноязычная русская — решение Кости 29.09; английская ветвь
     старше того решения и остаётся как есть */
  "isEn ? [",
  /* ИМЯ ЧЕЛОВЕКА НЕ ПЕРЕВОДИТСЯ. Колонки `name_kg` у игроков в базе нет
     вовсе (замерено: `name_kg` стоит у кортов, услуг и категорий, у
     игроков — нет), и кыргызская запись русского имени — то же имя. */
  "p.name_en || p.name",
  "reg.partner.name_en || reg.partner.name",
  "reg.capitan.name_en || reg.capitan.name",
  "кто.name_en || кто.name",
  "a.name_en || a.name",
  "b.name_en || b.name",
  "соперник.name_en || соперник.name"
];

const файлы = [];
(function обход(д) {
  fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
    const п = path.join(д, э.name);
    if (э.isDirectory()) { if (!/^node_modules$/.test(э.name)) обход(п); }
    else if (э.name.endsWith('.js')) файлы.push(п);
  });
})('js');

function обойти(у, дело) {
  if (!у || typeof у.type !== 'string') return;
  дело(у);
  for (const к of Object.keys(у)) {
    if (к === 'type' || к === 'start' || к === 'end' || к === 'loc') continue;
    const v = у[к];
    if (Array.isArray(v)) v.forEach(x => x && typeof x.type === 'string' && обойти(x, дело));
    else if (v && typeof v.type === 'string') обойти(v, дело);
  }
}

let неразобран = 0, зовы = 0, скЛокали = 0, равные = 0, вложенных = 0;
const пары = [], локалиПары = [], кодЯзыкаПары = [], адресаПары = [], равныеГде = [];
const словари = [];

файлы.forEach(ф => {
  const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
  let д;
  try { д = acorn.parse(т, { ecmaVersion: 2020, locations: true }); }
  catch (e) { неразобран++; return; }
  обойти(д, у => {
    if (у.type === 'ConditionalExpression') {
      const усл = т.slice(у.test.start, у.test.end).trim();
      const цел = т.slice(у.start, у.end);
      if (усл === 'isEn' && у.alternate.type !== 'ConditionalExpression') {
        const где = path.basename(ф) + ':' + у.loc.start.line;
        if (!РАЗРЕШЁННЫЕ.some(я => цел.indexOf(я) !== -1)) пары.push(где + '  ' + цел.replace(/\n\s*/g, ' ').slice(0, 70));
        const en = у.consequent, ru = у.alternate;
        if (en.type === 'Literal' && ru.type === 'Literal') {
          if (ru.value === 'ru-RU') локалиПары.push(где);
          if (ru.value === 'ru') кодЯзыкаПары.push(где);
          if (typeof ru.value === 'string' && /\.html/.test(ru.value)) адресаПары.push(где + '  ' + ru.value);
        }
      }
      /* ДВА УСЛОВИЯ ВМЕСТО ОДНОГО ЗОВА: `isKg ? … : (isEn ? … : …)` или
         `isKg ? … : выбрать(…)`. Второе — моя же беда 23.10: кыргызская
         ветвь зова оказывалась НЕДОСТИЖИМОЙ, второе определение понятия. */
      if (усл === 'isKg' && у.alternate && (
            у.alternate.type === 'ConditionalExpression' ||
            (у.alternate.type === 'CallExpression' && у.alternate.callee &&
             т.slice(у.alternate.callee.start, у.alternate.callee.end) === 'KSLT_YAZYK.выбрать'))) {
        вложенных++;
      }
      return;
    }
    if (у.type !== 'CallExpression' || !у.callee) return;
    if (т.slice(у.callee.start, у.callee.end) !== 'KSLT_YAZYK.выбрать') return;
    зовы++;
    if (у.arguments.length !== 3) return;
    const [, kg, ru] = у.arguments;
    if (kg.type === 'Literal' && kg.value === 'ky-KG') скЛокали++;
    if (kg.type === 'Literal' && ru.type === 'Literal' &&
        typeof kg.value === 'string' && kg.value === ru.value && kg.value.trim() !== '') {
      равные++;
      равныеГде.push(path.basename(ф) + ':' + у.loc.start.line + ' ' + JSON.stringify(kg.value));
    }
    /* большие словари: состав ключей обязан совпасть по всем трём ветвям */
    if (у.arguments.every(a => a.type === 'ObjectExpression') &&
        у.arguments[0].properties.length >= 8) {
      const кл = o => o.properties.map(p => p.key.name || p.key.value);
      const [en, кг, рус] = у.arguments.map(кл);
      const нЕn = new Set(en), нКг = new Set(кг);
      const нет = рус.filter(к => !нКг.has(к) || !нЕn.has(к));
      словари.push({ где: path.basename(ф) + ':' + у.loc.start.line, ключей: рус.length, нет: нет });
    }
  });
});

