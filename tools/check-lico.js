/**
 * ЗАМОРОЗКА ЛИЦА БЕЗ ФОТОГРАФИИ (кусок 75, 13.10.2026).
 *
 * ЗАМЕР: инициалы считались ВОСЕМЬЮ функциями в восьми файлах, и вели они
 * себя ПЯТЬЮ разными способами — две буквы или одна, с верхним регистром
 * или без, при пустом имени «?» или ПУСТОЙ кружок. Одно имя давало разные
 * кружки на разных экранах.
 *
 * Плюс два живых адреса `placehold.co`: нет фотографии — запрос на чужой
 * сайт за серым «?», по одному на каждую карточку.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ:
 *   • инициалы считает ОДНА функция на продукт;
 *   • своих реализаций в файлах не осталось — только вызовы общей;
 *   • заглушки с чужого сайта нет нигде;
 *   • страница, зовущая лицо, подключает модуль — иначе кружок не
 *     нарисуется вовсе;
 *   • заглушка носит ТОТ ЖЕ класс, что фотография: размер и скругление у
 *     них общие, второго объявления не заводится.
 *
 *   node tools/check-lico.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const собрать = (кат, спис) => {
    fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(д => {
        const п = кат + '/' + д.name;
        if (д.isDirectory()) собрать(п, спис);
        else if (д.name.endsWith('.js')) спис.push(п);
    });
    return спис;
};
const JS = собрать('js', []);
const ДОМ = 'js/kslt-lico.js';

/* ══ 1. ОДНА ФУНКЦИЯ НА ПРОДУКТ ════════════════════════════════════════ */

правило('модуль лица объявлен ровно один раз',
    JS.reduce((с, ф) => с + (безКом(чит(ф)).match(/window\.KSLT_LICO\s*=/g) || []).length, 0) === 1,
    'объявлений window.KSLT_LICO не одно. Два модуля разойдутся на первой\n' +
    'же правке — ровно та болезнь, ради которой кусок и делался');

/* ГДЕ БЫЛ СВОЙ ПОДСЧЁТ — ТАМ ТЕПЕРЬ ВЫЗОВ ОБЩЕГО. Файлы названы ПОИМЁННО.
   Первая редакция этого правила искала функцию по ИМЕНИ («…ини…») и по
   подстроке в теле — и поймала `влатиницу` в dashboard.js, где `п[0])` от
   таблицы замен. Это 26-й случай подстроки у нас, и он мой собственный:
   правило, ищущее по куску имени, однажды поймает чужое. */
const БЫВШИЕ = [
    'js/services.js', 'js/partners.js', 'js/match-score.js', 'js/battle-cards.js',
    'js/home-partners.js', 'js/player.js', 'js/players.js', 'js/home-rankings.js',
    /* Девятая нашлась не замером, а ЧУЖИМ ПРАВИЛОМ: сторож страницы игрока
       требовал, чтобы её формула совпадала с формулой кабинета, и упал,
       когда первая переехала в модуль. Кабинет считал инициалы сам. */
    'js/dashboard.js',
    /* ЕЩЁ ШЕСТЬ НАШЛИСЬ КУСКОМ 194, И НЕ ЗАМЕРОМ ПО КЛАССУ, А ПРИЗНАКОМ
       ПО ПОДСЧЁТУ. Прежний замер искал класс `avatar-initials` и видел
       девять файлов; эти шесть звали свои буквы через переменную
       `initials` и свой класс, поэтому в счёт не попали. ЗАМЕР ПО ВИДУ
       РАЗМЕТКИ НЕ НАХОДИТ ТОГО, ЧТО НАПИСАНО ДРУГИМИ СЛОВАМИ. */
    'js/auth-nav.js', 'js/live-match.js',
    'js/admin/core/layout.js', 'js/admin/sections/users.js'
];
/* ЗОВУТ ДОМ ТРЕМЯ ДВЕРЯМИ, А НЕ ОДНОЙ. Кусок 194 перевёл три файла с
   `инициалы` на `кружок`: они рисовали свой `<span>` при живом доме,
   отдающем `<div>`, — два тега на одно понятие. Правило требовало
   ИМЕННО `инициалы` и упало бы на правильном коде. Признак теперь —
   любая дверь дома, рисующая кружок. */
const ДВЕРЬ = /window\.KSLT_LICO\.(инициалы|кружок|лицо)\s*\(/;
const свои = БЫВШИЕ.filter(function (ф) {
    return !ДВЕРЬ.test(безКом(чит(ф)));
});

правило('своих подсчётов инициалов не осталось',
    свои.length === 0,
    'файлов, где подсчёт не переведён на общий: ' + свои.length + ' — ' +
    свои.join(', ') + '.\n' +
    'Их было ВОСЕМЬ, и вели они себя пятью разными способами');

/* СВОЙ ПОДСЧЁТ НЕ ИЩЕТСЯ ПОИМЁННО — ОН ИЩЕТСЯ ПО ПРИЗНАКУ, ВО ВСЁМ js.
   Поимённый список держит только то, что уже нашли: кусок 194 нашёл шесть
   мест, которых в списке не было, и список бы молчал и дальше. Два
   написания было два, но ВТОРОЕ НЕ ОТЛИЧИМО ПРИЗНАКОМ: `charAt(0)` с
   поднятым регистром — это ещё и «заглавная буква слова» (17 мест:
   категории, подписи, статусы) и «фамилия сокращённо» в `live-match.js`.
   ПРИЗНАК, КОТОРЫЙ НЕ РАЗЛИЧАЕТ ПОНЯТИЙ, НЕ ПРАВИЛО, А ШУМ: сторож
   держит ту форму, которой писались все пятнадцать мест, —
   первые буквы ВСЕХ слов. Одна буква держится поимённым списком. */
const своиПодсчёты = JS.filter(ф => ф !== ДОМ)
    .filter(ф => /charAt\(0\)\s*;?\s*\}\s*\)\s*\.join\(''\)/.test(безКом(чит(ф))))
    .map(ф => ф.split('/').pop());

правило('своего подсчёта инициалов нет ни в одном файле',
    своиПодсчёты.length === 0,
    'файлов со своим подсчётом: ' + своиПодсчёты.length + ' — ' +
    своиПодсчёты.slice(0, 5).join(', ') + '.\n' +
    'Так писались все ПЯТНАДЦАТЬ прежних мест');

/* ИНИЦИАЛЫ НАРУЖУ НЕ ЗОВУТ. Пока `инициалы` была открытой дверью, зовущий
   получал буквы и рисовал вокруг них свою разметку — так и жили
   восемнадцать кружков. Буквы выдаются только внутри кружка. */
const зовутБуквы = JS.filter(ф => ф !== ДОМ && /KSLT_LICO\.инициалы\s*\(/.test(безКом(чит(ф))))
    .map(ф => ф.split('/').pop());

правило('буквы наружу не выдаются — только внутри кружка',
    зовутБуквы.length === 0,
    'файлов, зовущих инициалы напрямую: ' + зовутБуквы.length + ' — ' +
    зовутБуквы.slice(0, 5).join(', ') + '.\n' +
    'Вокруг букв вырастет своя разметка, и кружков снова станет много');

/* ══ 2. ЧУЖОГО CDN НЕТ ═════════════════════════════════════════════════ */

/* ПОСЕВ ВХОДИТ В ОБЛАСТЬ ПРОВЕРКИ (31.10). Правило смотрело только `js/`
   и `css/` — и молчало, пока `tests/seed.js:1456` клал в тестовую базу
   фото с `placehold.co`. Продукт честно показывал, что ему дали, а проба
   31 падала: «страница ходит за картинками наружу». Сторож при этом был
   зелёный: ПРИБОР, СМОТРЯЩИЙ ЧАСТЬ, НЕ СТОРОЖИТ НИЧЕГО.
   ПОСЕВ — ЭТО ТОЖЕ ПРОДУКТ ДЛЯ ПРОБЫ: что он положит, то она и померит.
   Сами пробы в область НЕ входят: там `placehold` упоминается законно —
   как то, что они ищут и запрещают. */
const сCDN = JS.concat(fs.readdirSync(path.join(КОРЕНЬ, 'css'))
        .filter(ф => ф.endsWith('.css')).map(ф => 'css/' + ф))
    .concat(['tests/seed.js'])
    .map(ф => ({ ф, n: (безКом(чит(ф)).match(/placehold\.co/g) || []).length }))
    .filter(x => x.n > 0);

правило('заглушки с чужого сайта нет',
    сCDN.length === 0,
    'файлов с placehold.co: ' + сCDN.length + ' — ' +
    сCDN.slice(0, 4).map(x => x.ф).join(', ') + '.\n' +
    'Нет фотографии — рисуем инициалы, а не просим картинку снаружи');

/* ══ 3. МОДУЛЬ ДОЕЗЖАЕТ ДО СТРАНИЦЫ ════════════════════════════════════ */

/* Правило стоит столько, сколько страниц его видят — то же, на чём подвёл
   шрифт управлений в тот же день. */
const ЗОВУТ = JS.filter(ф => ф !== ДОМ && /KSLT_LICO\./.test(безКом(чит(ф))))
    .map(ф => ф.split('/').pop());
/* СТЕНДЫ СЧИТАЮТСЯ СТРАНИЦАМИ. Кусок 194 перевёл на дом админские файлы,
   и СЕМЬ стендов в `maket/` остались звать дом, которого на них нет:
   правило смотрело только `pages/` и `index*`, и молчало бы. */
const СТРАНИЦЫ = fs.readdirSync(path.join(КОРЕНЬ, 'pages'))
    .filter(ф => ф.endsWith('.html')).map(ф => 'pages/' + ф)
    .concat(fs.readdirSync(path.join(КОРЕНЬ, 'maket'))
        .filter(ф => ф.endsWith('.html')).map(ф => 'maket/' + ф))
    .concat(fs.readdirSync(КОРЕНЬ).filter(ф => /^index.*\.html$/.test(ф)));
const безМодуля = СТРАНИЦЫ.filter(с => {
    const т = чит(с);
    return ЗОВУТ.some(ф => т.indexOf('/' + ф + '?v=') !== -1) && т.indexOf('kslt-lico.js') === -1;
});

правило('модуль подключают все страницы, которым он нужен',
    безМодуля.length === 0,
    'страниц без модуля: ' + безМодуля.length + ' — ' + безМодуля.slice(0, 4).join(', ') +
    '.\nБез него кружок не нарисуется вовсе');

/* ПОДКЛЮЧЁН — НЕ ЗНАЧИТ РАНЬШЕ. На ТРИДЦАТИ страницах дом стоял ПОЗЖЕ
   своих зовущих: держалось это только тем, что кружок рисуется не при
   разборе файла, а после ответа входа. Порядок, который работает
   случайно, однажды перестанет: достаточно зовущему посчитать кружок
   сразу. Дом стоит раньше всех зовущих и позже экранирования, которое
   зовёт сам. */
const скрипты = с => (чит(с).match(/<script src="[^"]+"/g) || [])
    .map(т => т.slice(13, -1).split('?')[0].split('/').pop());
const порядок = СТРАНИЦЫ.filter(с => {
    const и = скрипты(с);
    const л = и.indexOf('kslt-lico.js');
    if (л === -1) return false;
    const э = и.indexOf('kslt-ekranirovanie.js');
    return (э === -1 || э > л) || и.some((н, i) => ЗОВУТ.indexOf(н) !== -1 && i < л);
});

правило('дом стоит раньше своих зовущих и позже экранирования',
    порядок.length === 0,
    'страниц с порядком наоборот: ' + порядок.length + ' — ' +
    порядок.slice(0, 4).join(', ') + '.\n' +
    'Порядок, который держится случайно, однажды перестанет держаться');

/* ══ 4. ЗАГЛУШКА НОСИТ КЛАСС ФОТОГРАФИИ ════════════════════════════════ */

const ЛИЦО = безКом(чит(ДОМ));
правило('заглушка берёт класс фотографии и общий класс кружка',
    /return кружок\(имя, \(класс \? класс \+ ' ' : ''\) \+ 'avatar-initials', тег\);/.test(ЛИЦО),
    'размер и скругление заглушки обязаны приходить от класса фотографии,\n' +
    'иначе на каждый размер заведётся своё объявление (Avatar 29:82)');

/* ОБЩИЙ КЛАСС НАВЕШИВАЕТ ЗОВУЩИЙ, А НЕ ДОМ. `.avatar-initials` задаёт
   краску, вес, регистр и `inline-flex`; у двенадцати кружков из
   восемнадцати свой вид — акцентные кружки админки, кабинет, табло live.
   Навесив общий класс всем, дом правил бы ВИД под видом сведения кода.
   Пустой класс не даёт и самого атрибута. */
правило('общий класс кружка приходит доводом, а не от дома',
    /var к = класс \? ' class="' \+ экр\(класс\) \+ '"' : '';/.test(ЛИЦО) &&
    !/\+ 'avatar-initials'/.test(ЛИЦО.slice(ЛИЦО.indexOf('function кружок'), ЛИЦО.indexOf('function лицо'))),
    'дом навешивает общий класс сам — это правка вида, а не сведение кода');

/* ТЕГ — ДОВОД, А НЕ ЗАШИТОЕ СЛОВО. Пока дом умел один `<div>`, три файла
   рисовали свой `<span>` сами, и починить разметку в одном месте было
   нельзя. Умолчание остаётся `div` — на нём стоят два прежних зовущих. */
/* ИД — ТОЖЕ ДОВОД. Кружок в кабинете стоит на `#avatarPreview`, и без
   довода это место обязано было рисовать разметку само. */
правило('имя узла называет зовущий',
    /var и = ид \? ' id="' \+ экр\(ид\) \+ '"' : '';/.test(ЛИЦО) && /\+ и \+/.test(ЛИЦО),
    'без довода `ид` место с `#avatarPreview` рисует кружок само');

правило('тег кружка называет зовущий, умолчание — div',
    /var т = тег \|\| 'div';/.test(ЛИЦО) && /'<' \+ т \+ к \+ и \+/.test(ЛИЦО),
    'без довода тег зашит, и зовущему с другим тегом остаётся\n' +
    'рисовать разметку самому — ровно то, что кусок 194 и убрал');

правило('кружок скрыт от диктора',
    /aria-hidden="true"/.test(ЛИЦО),
    'имя стоит рядом текстом; буквы в кружке диктору читать незачем');

/* ══ 5. РАЗМЕТКУ КРУЖКА РИСУЕТ ТОЛЬКО ДОМ ══════════════════════════════ */

/* Замер куска 194: `avatar-initials` писали ЧЕТЫРЕ файла — дом и три
   списка. Дом отдавал `<div>`, списки — `<span>`, и у одного понятия
   оказалось два тега. Сторож падает на появлении пятого: разметка
   кружка живёт в одном файле, а не повторяется строкой. */
/* ПРИЗНАК — ОТКРЫВАЮЩИЙ ТЕГ РЯДОМ С КЛАССОМ ЗАГЛУШКИ, А НЕ САМО ИМЯ
   КЛАССА: с куска 194 общий класс приходит доводом, и строка
   `'avatar-initials'` в файле — это ЗОВ дома, а не своя разметка.
   Своя разметка узнаётся по тому, что класс стоит внутри тега. */
const своёВТеге = /<[a-z]+ class="[^"]*(?:avatar-initials|-avatar-placeholder|-player-initials|-photo-ph|-avatar-ph|-noface|avatar-ph)/;
const свояРазметка = JS.filter(ф => ф !== ДОМ && своёВТеге.test(безКом(чит(ф))))
    .map(ф => ф.split('/').pop());

правило('разметку кружка рисует только дом',
    свояРазметка.length === 0,
    'файлов со своей разметкой кружка: ' + свояРазметка.length + ' — ' +
    свояРазметка.slice(0, 4).join(', ') + '.\n' +
    'Их было ВОСЕМНАДЦАТЬ, и тегов у одного понятия было четыре');

/* ══ 6. ПОВЕДЕНИЕ ЕДИНО ════════════════════════════════════════════════ */

правило('пустое имя даёт знак вопроса, а не пустой кружок',
    /if \(слова\.length === 0\) return '\?';/.test(ЛИЦО),
    'у трёх из восьми прежних реализаций пустое имя давало ПУСТОЙ кружок');

правило('инициалы берутся от первого и ПОСЛЕДНЕГО слова',
    /слова\[слова\.length - 1\]\.charAt\(0\)/.test(ЛИЦО),
    'человека узнают по имени и фамилии, а не по первым двум словам —\n' +
    'так у Apple в Контактах и у Linear');

правило('регистр поднимается',
    /toUpperCase\(\)/.test(ЛИЦО),
    'три из восьми прежних реализаций регистр не поднимали');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      лицо без фотографии: 15 правил');
    console.log('          одна функция на продукт   ·   чужого CDN нет');
    console.log('          модуль доезжает до страниц и стендов, и раньше зовущих');
    console.log('          разметку кружка рисует только дом   ·   тег и ид — доводы');
    console.log('          своего подсчёта нет нигде   ·   буквы наружу не выдаются');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  лицо без фотографии — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
