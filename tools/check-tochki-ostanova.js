/**
 * ТОЧКИ ОСТАНОВА — ОДИН СТОРОЖ НА ВЕСЬ ПРОДУКТ.
 *
 * ПОЧЕМУ ОН ПОЯВИЛСЯ ТОЛЬКО 16.10. У каждого куска был свой сторож, и
 * каждый читал ТОЛЬКО свой css: `check-turniry.js:153` честно говорил
 * «точек останова ровно две», проверяя `tournaments-overview.css`, — а
 * рядом в общем `style.css` лежали 42 блока на 768, которые красят те же
 * страницы. Из-за этого к одним и тем же страницам возвращались четыре
 * раза. Это та же беда, что с версиями файлов в заходе B5: ПРАВИЛО,
 * СМОТРЯЩЕЕ ЧАСТЬ ПРОДУКТА, НЕ СТОРОЖИТ НИЧЕГО.
 *
 * Разрешены 640 и 992 плюс их зеркала 641 и 993. Всё остальное — либо
 * ошибка, либо НАЗВАННОЕ исключение из списка ниже: у каждого есть файл,
 * строка решения и причина. Список закрыт: новая чужая ширина роняет
 * правило, и её нельзя просто дописать — сначала решение.
 *
 *   node tools/check-tochki-ostanova.js
 */
const fs = require('fs');
const path = require('path');

const ПАПКА = path.join(__dirname, '..', 'css');
const ДОМ = new Set(['640', '992', '641', '993']);

/* Админка — пункт 80 ветки D, свой кусок: ей телефон не нужен вовсе.
   Исключается целиком и намеренно. */
const ВНЕ = new Set(['admin.css']);

/* НАЗВАННЫЕ ИСКЛЮЧЕНИЯ. Ключ — ширина, значение — чем обосновано.
   Число рядом — сколько блоков разрешено на этой ширине. */
const ИСКЛЮЧЕНИЯ = {
    '768': [13, 'типографическая связка (заголовок раздела, перебивка, подзаголовок, ' +
                'спонсорский блок) плюс первый экран, live и подвал: ' +
                'tools/check-sponsor.js:86 — «768 остаётся НАМЕРЕННО»'],
    '769': [1,  'зеркало 768 у окна оплаты: шире телефона окно дышит свободнее'],
    '599': [1,  'граница compact/medium из Material Design, tokens.css — ' +
                'менять её значит менять стандарт, на который сослались'],
    '600': [3,  'подписи подвала и окно уведомлений: полные подписи не влезают ' +
                'примерно до 489, граница с запасом'],
    '900': [2,  'решение Кости 23.09, доска 347:9 — две колонки новостей, ' +
                'полоса 769–900 никем не рисовалась'],
    '901': [1,  'зеркало 900 из того же решения'],
    '1023': [1, 'сетка плей-офф: уже этого листается вбок, ужимать нечего'],
    '1024': [1, 'зеркало 1023 из того же решения'],
    '1200': [1, 'две лиги в ряд не помещаются уже'],
    '1300': [1, 'кнопка «назад» наезжала бы на содержимое'],
    '480': [2,  'каскадная подпорка players-grid и зеркало --sheet-w'],
    '375': [1,  'блок iPhone SE: 18 объявлений, ни одного столкновения с 640'],
};

const считано = {};
let всего = 0;
for (const ф of fs.readdirSync(ПАПКА).filter(x => x.endsWith('.css'))) {
    if (ВНЕ.has(ф)) continue;
    const текст = fs.readFileSync(path.join(ПАПКА, ф), 'utf8')
        .replace(/\/\*[\s\S]*?\*\//g, '');          /* комментарии не считаются */
    const м = текст.match(/@media[^{]*\{/g) || [];
    for (const у of м) {
        const ширины = [...у.matchAll(/(?:max|min)-width\s*:\s*(\d+)px/g)].map(x => x[1]);
        const чужие = ширины.filter(ш => !ДОМ.has(ш));
        if (!чужие.length) continue;
        всего++;
        for (const ш of new Set(чужие)) {
            считано[ш] = считано[ш] || { сколько: 0, файлы: new Set() };
            считано[ш].сколько++;
            считано[ш].файлы.add(ф);
        }
    }
}

let бед = 0;
console.log('');
console.log('  ТОЧКИ ОСТАНОВА ПО ВСЕМУ ПРОДУКТУ (без admin.css)');
console.log('  домашние: 640 и 992, зеркала 641 и 993');
console.log('');

for (const ш of Object.keys(считано).sort((a, b) => считано[b].сколько - считано[a].сколько)) {
    const { сколько, файлы } = считано[ш];
    const искл = ИСКЛЮЧЕНИЯ[ш];
    if (!искл) {
        console.log(`  ✗ ${ш} — ${сколько} блоков, НЕ НАЗВАНО исключением (${[...файлы].join(', ')})`);
        бед++;
    } else if (сколько > искл[0]) {
        console.log(`  ✗ ${ш} — блоков ${сколько}, разрешено ${искл[0]} (${[...файлы].join(', ')})`);
        бед++;
    } else {
        console.log(`  ок ${ш.padEnd(5)} ${String(сколько).padStart(2)} из ${искл[0]} — ${искл[1].slice(0, 62)}`);
    }
}

for (const ш of Object.keys(ИСКЛЮЧЕНИЯ)) {
    if (!считано[ш]) console.log(`  ! ${ш} — исключение больше не нужно, строку можно снять`);
}

console.log('');
if (бед === 0) {
    console.log(`  ок      чужих блоков ${всего}, и каждый назван решением`);
    console.log('          новая чужая ширина уронит это правило\n');
} else {
    console.log(`  НЕ ТАК  ${бед} ширин без решения\n`);
    process.exitCode = 1;
}
