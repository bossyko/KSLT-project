/**
 * ДОКАЗАТЕЛЬСТВО ПРОВЕРКИ ЖЕРЕБЬЁВКИ И СЕТОК ЗА МЕСТА ОТКАТОМ.
 *
 * ПОЧЕМУ ОН ПОЯВИЛСЯ ТОЛЬКО 09.10. `check-draw.js` написан при закрытии
 * куска и был зелёным — но зелёное правило без прувера не значит ничего:
 * оно может быть зелёным потому, что ничего не проверяет. Прувера не было,
 * и в общий прогон файл не был включён. Нашёл Костя вопросом.
 *
 * ЧЕМ ЭТОТ ПРУВЕР ОТЛИЧАЕТСЯ ОТ ОСТАЛЬНЫХ. Прочие читают файлы как ТЕКСТ,
 * и откат меняет строку. `check-draw.js` гоняет ЖИВЫЕ ФУНКЦИИ — значит и
 * ломать надо код, а проверять поведение. Откат портит одну строку в копии
 * js/ и требует, чтобы упала ИМЕННО названная проверка.
 *
 * ПРОВЕРКА ПОВТОРЯЕТСЯ НА РАЗНЫХ РАЗМЕРАХ, и один откат роняет её на всех
 * сразу — это нормально. Нельзя другое: чтобы заодно упало что-то ЧУЖОЕ.
 * Поэтому сверяется МНОЖЕСТВО упавших имён с ожидаемым, а не их число.
 *
 *   node tools/check-draw-otkat.js
 */
const fs = require('fs');
const path = require('path');
const os = require('os');
const { spawnSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const ВРЕМ = fs.mkdtempSync(path.join(os.tmpdir(), 'kslt-draw-'));
['js', 'tools'].forEach(д =>
    fs.cpSync(path.join(КОРЕНЬ, д), path.join(ВРЕМ, д), { recursive: true }));

const DRAW  = 'js/bracket-draw.js';
const RULES = 'js/kslt-rules.js';

/* ИМЯ ПРОВЕРКИ БЕЗ ЧИСЕЛ И БЕЗ АДРЕСА. Один и тот же вопрос задаётся на
   сетках 8, 16, 32 и 64, и текст несёт в себе размер: «места с 1 по 32» и
   «места с 1 по 64» — это ОДНА проверка. Так же и маршрут: «проигравший
   круга 1 → 17-20 место» печатает не только вопрос, но и ответ, который у
   каждой сетки свой. Числа приводим к N, хвост после стрелки срезаем. */
const безЧисел = s => s.replace(/\d+/g, 'N').replace(/\s*→.*$/, '');

const ОТКАТЫ = [

  /* ─── линии сеяных: таблица, а не выдумка ─── */

  [DRAW, `32: { 1: [1], 2: [32], 3: [9, 24], 5: [8, 16, 17, 25],`,
         `32: { 1: [2], 2: [32], 3: [9, 24], 5: [8, 16, 17, 25],`,
   ['сеяный N на первой линии']],

  [DRAW, `64: { 1: [1], 2: [64], 3: [17, 48], 5: [16, 32, 33, 49],`,
         `64: { 1: [1], 2: [63], 3: [17, 48], 5: [16, 32, 33, 49],`,
   ['сеяный N на последней линии']],

  /* ЛОМАТЬ НАДО ТУ СЕТКУ, ГДЕ НЕТ ПРОХОДОВ. Третьего и четвёртого сводим в
     одну половину на сетке 64 — она гоняется с полным составом. На сетке 32
     с 22 участниками любая переставленная линия сеяного заодно уводит бронь
     соседней линии, и падает ещё и проверка проходов: чужая проверка. */
  [DRAW, `3: [17, 48], 5: [16, 32, 33, 49],`,
         `3: [17, 18], 5: [16, 32, 33, 49],`,
   ['сеяные N и N в разных половинах']],

  /* ПОДМЕНА ДОЛЖНА МЕНЯТЬ ЧЕТВЕРТЬ, А НЕ ЛИНИЮ. Первый замах был 16 → 15:
     проверка осталась зелёной, потому что 15 и 16 лежат в ОДНОЙ четверти, и
     набор четвертей не изменился. Уводим 16 → 34, в третью четверть, где
     уже стоит 33. */
  [DRAW, `3: [17, 48], 5: [16, 32, 33, 49],`,
         `3: [17, 48], 5: [34, 32, 33, 49],`,
   ['сеяные N-N по одному в каждой четверти']],

  /* Девятый и десятый в одну восьмую: 10 и 9 обе во второй. */
  [DRAW, `9: [8, 9, 24, 25, 40, 41, 56, 57],`,
         `9: [10, 9, 24, 25, 40, 41, 56, 57],`,
   ['сеяные N-N по одному в каждой восьмой части']],

  /* ─── расстановка несеяных ─── */

  /* Один участник не доезжает до сетки. Падают ТРИ проверки, и все три
     честные: состав считают двое с разных сторон, а освободившаяся линия
     добавляет одиннадцатый проход там, где их должно быть десять. */
  [DRAW, `        var прочие = участники.slice(сеяных);`,
         `        var прочие = участники.slice(сеяных + 1);`,
   ['все участники на сетке', 'никто не стоит дважды',
    'проходов N, столько и есть']],

  /* ДУБЛЬ БЕЗ ПОТЕРИ ЧИСЛА И БЕЗ ПОБОЧНЫХ ПАДЕНИЙ. Сперва дважды ставился
     первый участник — и падала заодно проверка «сеяный 1 на первой линии»:
     карта `где` помнит ПОСЛЕДНЮЮ линию, и первый сеяный съезжал с единицы.
     Дублируем последнего несеяного: его линия никого больше не волнует. */
  [DRAW, `            if (i < порядок.length) линии[порядок[i] - 1] = у;`,
         `            if (i < порядок.length) линии[порядок[i] - 1] = (i === 0 ? прочие[прочие.length - 1] : у);`,
   ['никто не стоит дважды']],

  /* ─── проходы без игры ─── */

  /* ПРОХОДОВ ПО-ПРЕЖНЕМУ ДЕСЯТЬ, НО НЕ У ТЕХ. Снятая бронь освобождает
     линию, на неё встаёт несеяный, и проход переезжает с десятого сеяного
     на него — число сходится, список нет. Поэтому ждём ровно одну. */
  [DRAW, `        var сколько = размер - участников;`,
         `        var сколько = размер - участников - 1;`,
   ['проходы у сеяных с N по N и ни у кого больше']],

  /* Проходы достаются не верхним сеяным, а через одного. */
  [DRAW, `        for (var i = 1; i <= сколько; i++) кому.push(i);`,
         `        for (var i = 1; i <= сколько; i++) кому.push(i + 1);`,
   ['проходы у сеяных с N по N и ни у кого больше']],

  /* ─── жребий ─── */

  /* Жребий перестал быть воспроизводимым. */
  [DRAW, `            s = (s * 16807) % 2147483647;`,
         `            s = Math.floor(Math.random() * 2147483646) + 1;`,
   ['та же сетка при повторной раскладке']],

  /* Жребий перестал слушать зерно. */
  [DRAW, `        var s = (зерно || 1) % 2147483647;`,
         `        var s = 1;`,
   ['другое зерно даёт другую сетку']],

  /* ─── адрес клетки: куда едут победитель и проигравший ─── */

  /* Победитель и проигравший меняются половинами блока. Клетка всё так же
     принимает двоих — меняется только, кто в неё едет. */
  [DRAW, `return (победил ? (2 * b - 2) : (2 * b - 1)) * (S / 2) + Math.ceil(p / 2);`,
         `return (победил ? (2 * b - 1) : (2 * b - 2)) * (S / 2) + Math.ceil(p / 2);`,
   ['победитель никогда не уходит из своей ветки', 'проигравший круга N']],

  /* Сдвиг внутри блока: пары съезжают, и в клетку приезжает не двое. */
  [DRAW, `* (S / 2) + Math.ceil(p / 2);`,
         `* (S / 2) + Math.floor(p / 2) + 1;`,
   ['победитель никогда не уходит из своей ветки',
    'каждая клетка следующего круга принимает ровно двоих']],

  /* ─── таблица блоков за места ─── */

  /* Блок отдаёт на одну клетку меньше — в сетке остаются неразмеченные. */
  [RULES, `return [индекс * наБлок + 1, (индекс + 1) * наБлок];`,
          `return [индекс * наБлок + 1, (индекс + 1) * наБлок - 1];`,
   ['размечены все N клеток']],

  /* Блок залезает на соседний. Падают обе проверки разметки, и честно:
     клетка достаётся двум блокам, а всего клеток становится больше, чем
     матчей в сетке. */
  [RULES, `return [индекс * наБлок + 1, (индекс + 1) * наБлок];`,
          `return [индекс * наБлок + 1, (индекс + 1) * наБлок + 1];`,
   ['размечены все N клеток', 'ни одна клетка не размечена дважды']],

  /* Отрезок мест делится не пополам — ветки перестают идти подряд. */
  [RULES, `for (var i = 0; i < путь.length; i++) { w /= 2; if (путь[i] === 'L') a += w; }`,
          `for (var i = 0; i < путь.length; i++) { w /= 2; if (путь[i] === 'L') a += w / 2; }`,
   ['победитель никогда не уходит из своей ветки',
    'места с N по N идут подряд, без пропусков и повторов',
    'проигравший круга N']],
];

let упало = 0;
ОТКАТЫ.forEach(([файл, было, стало, ожидаем], i) => {
    const путь = path.join(ВРЕМ, файл);
    const цел = fs.readFileSync(путь, 'utf8');
    const сколько = цел.split(было).length - 1;
    if (сколько !== 1) {
        console.log(`  ✗ ${i + 1}  якорь встречается ${сколько} раз: ${ожидаем[0]}`);
        упало++;
        return;
    }
    fs.writeFileSync(путь, цел.replace(было, стало));
    /* ПРОВАЛЫ ЖИВУТ В ПОТОКЕ ОШИБОК, И ЧИТАТЬ НАДО ОБА ПОТОКА. `check-draw.js`
       печатает ✓ через console.log, а ✗ через console.error. execFileSync
       отдаёт наружу ТОЛЬКО stdout: при успешном коде выхода stderr просто
       выбрасывается, при ошибке лежит в исключении. Прувер видел вывод без
       единого ✗ и на каждом откате говорил «не упало НИЧЕГО». Поэтому здесь
       spawnSync — он отдаёт оба потока всегда, независимо от кода выхода. */
    const прогон = spawnSync('node', [path.join(ВРЕМ, 'tools/check-draw.js')],
                             { encoding: 'utf8' });
    const вывод = (прогон.stdout || '') + (прогон.stderr || '');
    fs.writeFileSync(путь, цел);

    const упавшие = new Set((вывод.match(/^  ✗ .+$/gm) || [])
        .map(с => безЧисел(с.replace(/^  ✗ /, '').trim())));
    const ждём = new Set(ожидаем);
    const лишние = [...упавшие].filter(и => !ждём.has(и));
    const нету  = [...ждём].filter(и => !упавшие.has(и));

    if (!лишние.length && !нету.length && упавшие.size) {
        console.log(`  ок  ${i + 1}  ${ожидаем.join(' + ')}`);
    } else {
        console.log(`  ✗ ${i + 1}  ${ожидаем.join(' + ')}`);
        if (нету.length)   console.log(`          не упало: ${нету.join(' · ')}`);
        if (лишние.length) console.log(`          упало лишнее: ${лишние.join(' · ')}`);
        if (!упавшие.size) console.log('          не упало НИЧЕГО — правило ничего не держит');
        упало++;
    }
});

/* НЕПОКРЫТОЕ НАЗЫВАЕТСЯ ВСЛУХ. Прувер, который доказал свои откаты и
   молчит об остальном, оставляет ту же самую беду: проверка есть, прувера у
   неё нет, и красной её никто никогда не видел. Поэтому берём чистый
   прогон, собираем ИМЕНА ВСЕХ проверок и вычитаем те, у которых откат есть.
   ИСКЛЮЧЕНИЕ ОДНО, И ОНО НАЗВАНО: «матчей в турнире» сверяет арифметику
   самого check-draw.js (кругов × размер/2) с зашитым числом и не трогает
   js/ вовсе — откатом кода её не уронить. */
const БЕЗ_ОТКАТА = ['матчей в турнире: N'];
const чистый = spawnSync('node', [path.join(ВРЕМ, 'tools/check-draw.js')],
                         { encoding: 'utf8' });
const всеИмена = new Set((((чистый.stdout || '') + (чистый.stderr || ''))
    .match(/^  [✓✗] .+$/gm) || []).map(с => безЧисел(с.slice(4).trim())));
const покрыто = new Set([].concat(...ОТКАТЫ.map(о => о[3])));
const голые = [...всеИмена].filter(и => !покрыто.has(и) && !БЕЗ_ОТКАТА.includes(и));
if (голые.length) {
    console.log(`\n  ✗  проверок без отката: ${голые.length}`);
    голые.forEach(и => console.log(`          ${и}`));
    упало++;
} else {
    console.log(`\n  ок  все ${всеИмена.size} проверок покрыты откатами`
              + ` (кроме названных: ${БЕЗ_ОТКАТА.join(', ')})`);
}

fs.rmSync(ВРЕМ, { recursive: true, force: true });
if (упало === 0) {
    console.log(`\n  ок      все ${ОТКАТЫ.length} откатов доказали свои правила`);
    console.log('          оригиналы не изменялись — работа шла на копии\n');
    process.exit(0);
}
console.log(`\n  НЕ ТАК  откатов ${ОТКАТЫ.length}, не доказали ${упало}\n`);
process.exit(1);
