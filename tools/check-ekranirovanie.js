const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
/* ЭТАЛОН ПЕРЕЕХАЛ В ДОМ — кусок 141, 23.10. Был `js/kslt-lenta.js`:
   файл, С КОТОРОГО СПИСЫВАЛИ 35 объявлений сайта. Списывать больше
   неоткуда и незачем — экранирование объявлено ОДИН раз, и образец есть
   сам работающий код. */
const ЭТАЛОН = 'js/kslt-ekranirovanie.js';

/* ХРАПОВИК ПРИЛОЖЕНИЯ: замерено 19.10. Опускать можно, поднимать нельзя. */
const ПОТОЛОК_ПРИЛОЖЕНИЯ = 15;
/* Тесты edge-функций проверяют СВОЮ копию экранирования из функции на
   сервере — она своя и живёт не в браузере. Замерено 19.10. */
const ПОТОЛОК_ТЕСТОВ = 2;

const чисто = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

function всеJs(д, вых) {
    вых = вых || [];
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) {
            if (/^(node_modules|android|test-results|playwright-report|build)$/.test(э.name)) return;
            всеJs(п, вых);
        } else if (э.name.endsWith('.js')) вых.push(п);
    });
    return вых;
}

/** Тело функции от объявления до парной скобке. */
function тело(т, от) {
    let i = т.indexOf('{', от);
    if (i === -1) return '';
    let гл = 0, j = i;
    while (j < т.length) {
        if (т[j] === '{') гл++;
        else if (т[j] === '}') { гл--; if (гл === 0) break; }
        j++;
    }
    return т.slice(от, j + 1);
}

/* Экранирование для СЕЛЕКТОРА css — другое понятие: там гасят не кавычки,
   а знаки селектора. Такие функции правилом не ловятся. */
const селектор = т => /querySelector|CSS\.escape|\$&/.test(т);

const файлы = ['js', 'mobile/www/js', 'tests'].reduce((в, д) => {
    try { return в.concat(всеJs(д)); } catch (e) { return в; }
}, []);

const находки = { сайт: [], приложение: [], тесты: [] };
let всего = 0;
файлы.forEach(п => {
    const т = чисто(fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8'));
    /* КАНДИДАТЫ ИЩУТСЯ ПО ПРИЗНАКУ ТЕЛА, А НЕ ПО ИМЕНИ (21.10).
       Правило хвалилось, что спрашивает признак, — и всё равно отбирало
       кандидатов по НАПИСАНИЮ ИМЕНИ (`esc|Esc|экран|Escape`). Две функции
       `экр` в `kslt-sloy.js` и `tournament-featured.js` не содержат ни
       одного из этих корней, и правило их НЕ ВИДЕЛО ВОВСЕ: докладывало
       «на сайте слабых НОЛЬ», когда их было две.
       Признак экранирования — ТЕЛО: гасит `&` в `&amp;` и `<` в `&lt;`.
       Имя при этом может быть любым, в том числе кириллическим. */
    /* ОБЪЕДИНЕНИЕ, А НЕ ЗАМЕНА. Первая правка 21.10 заменила отбор по
       имени отбором по телу — и признак вышел УЖЕ прежнего: функция,
       гасящая только кавычки и НЕ гасящая `&`, перестала считаться
       экранированием вовсе, и потолок приложения упал с 15 до 1 не
       потому, что что-то починили. НОВЫЙ ПРИЗНАК ОБЯЗАН ВИДЕТЬ ВСЁ, ЧТО
       ВИДЕЛ СТАРЫЙ, ИНАЧЕ ЭТО НЕ РАСШИРЕНИЕ, А ПОДМЕНА. */
    const корни = /(?:esc|Esc|экран|Escape)/;
    const р = /function\s+([\wЀ-ӿ$]+)\s*\(/g;
    let м;
    while ((м = р.exec(т))) {
        const тл = тело(т, м.index);
        const этоHtml = /replace|textContent|innerHTML|createTextNode/.test(тл);
        /* кандидат: имя говорит об экранировании ИЛИ тело гасит `&` и `<` */
        const кандидат = корни.test(м[1]) || (/&amp;/.test(тл) && /&lt;/.test(тл));
        if (!этоHtml || !кандидат || селектор(тл)) continue;
        всего++;
        const двойная = /&quot;|&#34;/.test(тл);
        const одинарная = /&#39;|&apos;|&#x27;/.test(тл);
        if (двойная && одинарная) continue;
        const где = п.startsWith('mobile/') ? 'приложение'
                  : (п.startsWith('tests/') ? 'тесты' : 'сайт');
        находки[где].push(п + ':' + (т.slice(0, м.index).split('\n').length) + ' ← ' + м[1]);
    }
});

/* ---- 1. на сайте ни одного слабого ---- */
правило('экранирование на сайте гасит обе кавычки',
    находки.сайт.length === 0,
    'Не гасят обе кавычки:\n  ' + находки.сайт.join('\n  ') + '\n' +
    'Это ЗАЩИТА, а не оформление. Результат идёт внутрь атрибута\n' +
    '(`title=`, `src=`, `alt=`), а данные там из базы — их вводит\n' +
    'человек через админку. Эталон: ' + ЭТАЛОН + '.');

/* ---- 2. эталон на месте ---- */
const эталон = чисто(fs.readFileSync(path.join(КОРЕНЬ, ЭТАЛОН), 'utf8'));
правило('эталон экранирования на месте',
    /&quot;/.test(эталон) && /&#39;/.test(эталон),
    'В ' + ЭТАЛОН + ' экранирование перестало гасить обе кавычки.\n' +
    'Это ЕДИНСТВЕННОЕ объявление на продукт: его зовут 506 мест на сайте\n' +
    'и дом админки. Испортить его — значит испортить все 506 сразу, и\n' +
    'ровно поэтому оно стоит под правилом.');

/* ---- 2б. ОДНО ОБЪЯВЛЕНИЕ НА ПРОДУКТ — кусок 141 ---- */
/* ЧИТАЕТСЯ ДЕРЕВО: имя `esc` живёт и внутри чужих слов (`escape`), и в
   строках. Считаются ОБЪЯВЛЕНИЯ функции с таким именем, а не вхождения
   текста. */
const acorn = require('acorn');
const свои = [];
(function обход(д) {
  fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
    const п = path.join(д, э.name);
    if (э.isDirectory()) { if (!/^node_modules$/.test(э.name)) обход(п); return; }
    if (!э.name.endsWith('.js')) return;
    if (/kslt-ekranirovanie\.js$/.test(п)) return;
    const т = fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8');
    let дер;
    try { дер = acorn.parse(т, { ecmaVersion: 2020, locations: true }); } catch (e) { return; }
    (function о(у) {
      if (!у || typeof у.type !== 'string') return;
      if ((у.type === 'FunctionDeclaration' || у.type === 'FunctionExpression') &&
          у.id && /^(esc|escHtml|escapeHtml)$/.test(у.id.name)) {
        const тело = т.slice(у.body.start, у.body.end);
        /* зов дома — не объявление понятия, а имя, привычное админке */
        if (тело.indexOf('KSLT_экранировать') === -1) свои.push(п + ':' + у.loc.start.line);
      }
      for (const к of Object.keys(у)) {
        if (к === 'type' || к === 'start' || к === 'end' || к === 'loc') continue;
        const v = у[к];
        if (Array.isArray(v)) v.forEach(x => x && typeof x.type === 'string' && о(x));
        else if (v && typeof v.type === 'string') о(v);
      }
    })(дер);
  });
})('js');

правило('экранирование объявлено один раз на весь продукт',
    свои.length === 0,
    'Своих объявлений экранирования: ' + свои.length + '\n' +
    свои.slice(0, 8).map(с => '  ' + с).join('\n') + '\n' +
    'Их было ТРИДЦАТЬ ОДНО, и все тела — побайтово одинаковы. Цена не в\n' +
    'сегодняшнем расхождении, а в завтрашнем: добавить сюда обратный\n' +
    'апостроф придётся в тридцати одном месте, и хватит пропустить одно.');

/* ---- 3. храповик приложения ---- */
правило('в приложении слабых экранирований не прибавилось',
    находки.приложение.length <= ПОТОЛОК_ПРИЛОЖЕНИЯ,
    'Было ' + ПОТОЛОК_ПРИЛОЖЕНИЯ + ', стало ' + находки.приложение.length + '.\n' +
    'Приложение ждёт своей ветки (слово Кости 13.10: оно не начинается,\n' +
    'пока не закрыта ветка B), но беда там не должна расти.\n' +
    'Снизил число — опусти потолок в этом файле.');
правило('потолок приложения не завышен',
    находки.приложение.length >= ПОТОЛОК_ПРИЛОЖЕНИЯ,
    'Слабых в приложении ' + находки.приложение.length + ' при потолке ' +
    ПОТОЛОК_ПРИЛОЖЕНИЯ + '.\nХРАПОВИК ОПУСКАЕТСЯ: поправь ПОТОЛОК_ПРИЛОЖЕНИЯ на ' +
    находки.приложение.length + ', иначе правило перестанет держать достигнутое.');

/* ---- 4. храповик тестов ---- */
правило('в тестах слабых экранирований не прибавилось',
    находки.тесты.length <= ПОТОЛОК_ТЕСТОВ,
    'Было ' + ПОТОЛОК_ТЕСТОВ + ', стало ' + находки.тесты.length + '.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      экранирование html: ' +
        (fs.readFileSync(__filename, 'utf8').match(/правило\('/g) || []).length + ' правил');
    console.log('          ' + всего + ' экранирований в продукте, на сайте слабых НОЛЬ');
    console.log('          правило смотрит на ПРИЗНАК — гасит ли обе кавычки, —');
    console.log('          а не на написание: слабых написаний было ТРИ');
    console.log('          приложение под храповиком: ' + находки.приложение.length +
                ', тесты: ' + находки.тесты.length);
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  экранирование html — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
