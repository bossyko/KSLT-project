#!/usr/bin/env node
/**
 * ЗАМОРОЗКА ОБЗОРНОЙ «ИНФО» — кусок 53-й, 09.10.
 *
 * Здесь заморожены ОТНОШЕНИЯ, а не числа: «обложка живёт общими крутилками
 * раздела», «кегли берутся из крутилок обложки», «границ две», «поля — из
 * компонента», «лестница не переворачивается на узком виде».
 *
 * ЧТО БЫЛО ДО ПРАВКИ (замер 09.10, пять видов загрузкой на нужной ширине,
 * три языка): обложка занимала 33% · 118% · 27% · 60% · 51% экрана — на
 * телефоне лёжа она была ВЫШЕ окна; заголовок шёл 22.62 · 37.14 · 27.2 ·
 * 45.06 · 49.6, ни одного числа со шкалы; межстрочных было восемь разных
 * (1.2 · 1.25 · 1.35 · 1.4 · 1.45 · 1.55 · 1.6 и 1.5); точек останова
 * четыре (768 · 480 · 375 · 640) при двух разрешённых; кнопка 152 × 41;
 * поля карточек 40 и 14; `:focus-visible` ноль при 55 правилах;
 * `prefers-reduced-motion` ноль при тринадцати движущихся.
 *
 *   node tools/check-info-obzor.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '');

const CSS  = чит('css/info-overview.css');
const CSSч = безКом(CSS);
const СТР  = чит('pages/info.html');
const СТРen = чит('pages/info-en.html');
const СТРkg = чит('pages/info-kg.html');
const JS   = чит('js/info-overview.js');

const ошибки = [];
let всегоПравил = 0;
const правило = (имя, условие, подсказка) => {
    всегоПравил++;
    if (!условие) ошибки.push({ имя, подсказка });
};

/* Блок правила по селектору, со счётом скобок: правило смотрит в СВОЙ блок,
   а не ищет значение где угодно в файле. */
function блок(текст, селектор) {
    const i = текст.indexOf(селектор);
    if (i === -1) return '';
    const о = текст.indexOf('{', i);
    if (о === -1) return '';
    let гл = 0;
    for (let j = о; j < текст.length; j++) {
        if (текст[j] === '{') гл++;
        else if (текст[j] === '}') { гл--; if (!гл) return текст.slice(о, j + 1); }
    }
    return '';
}

/* ─────────── ОБЛОЖКА РАЗДЕЛА ─────────── */

правило('высота обложки — общая крутилка, а не своё число',
    /min-height:\s*var\(--oblozhka-pol\)/.test(блок(CSSч, '.io-hero {')),
    'в обложку вернулось своё число высоты: раздел разойдётся с восемью соседними');

правило('воздух обложки — общие крутилки',
    /padding:\s*var\(--oblozhka-vozduh\)\s+var\(--pad-x\)\s+var\(--oblozhka-vozduh-niz\)/
        .test(блок(CSSч, '.io-hero {')),
    'воздух обложки снова задан своим `--section-y`: он крупнее общего на ступень');

/* ПРАВИЛО СМОТРИТ В СВОЙ БЛОК. Первая редакция ловила `min-height` у любого
   селектора с `io-` и краснела от крупной карточки (300) и её узких ступеней
   (260 и 240) — это её собственные высоты, к обложке они отношения не имеют. */
правило('своих высот обложки в узких блоках не осталось',
    !(CSSч.match(/\.io-hero[^,{]*\{[^}]*\}/g) || [])
        .some(б => /min-height:\s*\d+px/.test(б)),
    'в узком блоке опять объявлена своя высота обложки — крутилка перестала решать');

правило('на низком горизонтальном экране пола нет',
    /@media \(max-height: 500px\) and \(orientation: landscape\)[\s\S]{0,300}min-height:\s*0/.test(CSSч),
    'снято правило телефона лёжа: обложка снова займёт весь экран (было 118%)');

правило('кегли на низком горизонтальном не трогаются',
    !/@media \(max-height: 500px\) and \(orientation: landscape\)[\s\S]{0,400}font-size/.test(CSSч),
    'в правило телефона лёжа добавлен кегль: лестница одна на все виды, меняется только воздух');

/* ─────────── ЛЕСТНИЦА ТЕКСТА ─────────── */

правило('заголовок обложки — крутилка --fs-hero',
    /font-size:\s*var\(--fs-hero\)/.test(блок(CSSч, '.io-hero h1 {')),
    'заголовок снова считается своим clamp: он давал пять чисел мимо шкалы');

правило('название КСЛТ — крутилка подзаголовка обложки',
    /font-size:\s*var\(--fs-hero-sub\)/.test(блок(CSSч, '.io-hero-full {')),
    'название организации ушло со ступени подзаголовка обложки');

правило('ни одного clamp для кегля во всём файле',
    !/font-size:\s*clamp\(/.test(CSSч),
    'вернулся clamp: кегль перестал быть ступенью и будет плавать между видами');

правило('межстрочные — только ступени лестницы',
    (CSSч.match(/line-height:\s*([0-9.]+)/g) || [])
        .map(с => parseFloat(с.split(':')[1]))
        .every(з => [1, 1.1, 1.3, 1.5, 1.65].includes(з)),
    'в файле снова межстрочный мимо лестницы 1 · 1.1 · 1.3 · 1.5 · 1.65');

правило('метка группы не крупнее на узком виде, чем на широком',
    !/\.io-group-title\s*\{[^}]*font-size:\s*var\(--fs-sm\)/.test(
        CSSч.slice(CSSч.indexOf('@media (max-width: 992px)'))),
    'метка группы снова поднята до 14 на узких при 12 на десктопе — лестница перевёрнута');

/* ─────────── ГРАНИЦЫ ─────────── */

правило('границ ровно две — 640 и 992',
    (CSSч.match(/@media \(max-width: (\d+)px\)/g) || [])
        .map(с => с.match(/(\d+)px/)[1])
        .every(ш => ш === '640' || ш === '992'),
    'в файл вернулась третья точка останова: разрешены только 640 и 992');

/* ─────────── КОМПОНЕНТЫ ─────────── */

правило('поля карточки — ступень Regular 24',
    /padding:\s*var\(--space-md\)/.test(блок(CSSч, '/* Compact card */\n.io-card {')) ||
    /padding:\s*var\(--space-md\)/.test(блок(CSSч, '.io-card {')),
    'поля карточки снова не со шкалы: `Card 29:65` знает 16 и 24, а стояло 40');

правило('цель нажатия кнопки — ступень 44, а не сумма полей',
    /min-height:\s*44px/.test(блок(CSSч, '.io-featured-link {')),
    'высоту кнопки снова дают поля: замер давал 41 при ступени 44');

правило('ни одного отступа мимо шкалы',
    !(CSSч.match(/(?:padding|margin|gap)[a-z-]*:\s*[^;]*\b(?:2|3|5|6|7|9|10|11|13|14|15|17|18|19|20|21|22|23|25|26|28|30|34|36|38|42|44|46|48|50|52|54|56)px/g) || [])
        .some(с => !/44px/.test(с)),
    'вернулся отступ мимо шкалы 8 · 12 · 16 · 24 · 32 · 40');

/* ─────────── ДОСТУПНОСТЬ ─────────── */

правило('фокус с клавиатуры виден',
    (CSSч.match(/:focus-visible/g) || []).length >= 4,
    'пропал :focus-visible: ходящий по странице с клавиатуры снова не видит, где он');

правило('движение спрашивает системную настройку',
    /@media \(prefers-reduced-motion: reduce\)/.test(CSSч),
    'снято уважение к «меньше движения» при тринадцати движущихся правилах');

/* ─────────── ТРИ ЯЗЫКА ─────────── */

правило('версия стиля поднята и одинакова на трёх языках',
    /info-overview\.css\?v=(3[9]|[4-9]\d)/.test(СТР) &&
    СТР.match(/info-overview\.css\?v=\d+/)[0] === СТРen.match(/info-overview\.css\?v=\d+/)[0] &&
    СТР.match(/info-overview\.css\?v=\d+/)[0] === СТРkg.match(/info-overview\.css\?v=\d+/)[0],
    'версия стиля не поднята или разошлась между языками — один язык получит старое из кеша');

/* СТРОКА РОЖДАЕТСЯ В JS, А НЕ В РАЗМЕТКЕ. Первая редакция искала её в
   html — там её нет ни на одном языке: страницу рисует js/info-overview.js,
   и строка появляется только если у языка задан `heroSub`. */
правило('четвёртая строка обложки — только у английского словаря',
    /L\.heroSub \? '<div class="io-hero-sub">'/.test(JS) &&
    (JS.match(/heroSub:/g) || []).length === 1,
    'строка-расшифровка завелась ещё у одного языка или пропала у английского: ' +
    'решение 09.10 — она нужна только английской версии, где аббревиатура ничего не говорит');

const всего = всегоПравил;
if (ошибки.length) {
    console.log('\n  ✗ обзорная «Инфо» — ' + ошибки.length + ' из ' + всего + ':\n');
    ошибки.forEach(о => console.log('    · ' + о.имя + '\n      ' + о.подсказка));
    console.log('');
    process.exit(1);
}
console.log('ок обзорная «Инфо»: ' + всего + ' правил');
