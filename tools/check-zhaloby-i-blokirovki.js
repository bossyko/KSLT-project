#!/usr/bin/env node
/**
 * ЖАЛОБЫ, БЛОКИРОВКИ И ЗАСЛОН (Apple 1.2, кусок 04.11).
 *
 * ЗАЧЕМ. Правило App Store 1.2 требует от приложения с пользовательским
 * содержимым четырёх вещей; у КСЛТ была одна — опубликованные контакты.
 * Это не замечание на ревью, а отказ. Здесь заморожено то, без чего
 * кнопки превращаются в обещание: заслон в базе, тихая отмена, честный
 * текст окна и язык, на котором всё это написано.
 *
 * ЗАМОРОЖЕНЫ ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   · заслон живёт ТРИГГЕРОМ, а не проверкой в приложении — запись идёт
 *     не только через нашу функцию;
 *   · блокировка ТИХАЯ: клубу push не уходит, и в тексте уведомления нет
 *     слова «заблокировал»;
 *   · парные баттлы НЕ отменяются — матч четверых не снимают двое;
 *   · окно обещает ровно то, что делает код;
 *   · три языка идут ВМЕСТЕ: экран, где человек защищается, — худшее
 *     место для непонятных слов;
 *   · `anon` не зовёт ни одной нашей функции;
 *   · связь `profiles`↔`players` в кабинете названа ПОИМЁННО.
 *
 * ПОСЛЕДНЕЕ ПРАВИЛО КУПЛЕНО ДОРОГО, 04.11: колонка `players.banned_by`
 * стала ВТОРОЙ связью между теми же таблицами, PostgREST перестал
 * угадывать нужную, и кабинет приложения умер с «more than one
 * relationship was found». Сторож ловит возврат этой беды.
 *
 *   node tools/check-zhaloby-i-blokirovki.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');

const СХЕМА = 'sql/схема/';
const функции  = чит(СХЕМА + 'apple-1-2-funkcii.sql');
const заслон   = чит(СХЕМА + 'apple-1-2-zaslon.sql');
const права    = чит(СХЕМА + 'apple-1-2-prava.sql');
const баны     = чит(СХЕМА + 'apple-1-2-bany-vse.sql');
const карточка = безКомментариев(чит('mobile/www/js/screens/player-detail.js'));
const кабинет  = безКомментариев(чит('mobile/www/js/screens/profile.js'));
const вход     = безКомментариев(чит('mobile/www/js/auth.js'));
const словарь  = чит('mobile/www/js/i18n.js');
const страница = безКомментариев(чит('js/player.js'));
const кабСайта = безКомментариев(чит('js/dashboard.js'));
const админка  = безКомментариев(чит('js/admin/sections/safety.js'));
const одежда   = чит('mobile/www/css/app.css');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/** Тело функции базы по имени — чтобы правило мерило ИМЕННО её, а не файл.
    ОДНО ИМЯ В ДВУХ ОБЪЯВЛЕНИЯХ — ЭТО ДВА РАЗНЫХ ПРАВИЛА. */
function тело(sql, имя) {
    const н = sql.indexOf('FUNCTION public.' + имя + '(');
    if (н === -1) return '';
    const к = sql.indexOf('$function$;', н);
    return к === -1 ? sql.slice(н) : sql.slice(н, к);
}
/** SQL без построчных комментариев: комментарий, объясняющий, что чего-то
    НЕТ, не должен доказывать, что оно есть (поймано 04.11 на `push_log`). */
const безСлов = s => s.replace(/--[^\n]*/g, '');

/* ── 1. ЗАСЛОН ЖИВЁТ В БАЗЕ ──────────────────────────────────────────── */
правило('заслон стоит триггером на вызовах',
    /CREATE TRIGGER challenges_block_trg\s+BEFORE INSERT ON public\.challenges/.test(заслон),
    'триггер на challenges пропал — заблокированный снова отправит вызов');

правило('заслон стоит триггером на приглашениях',
    /CREATE TRIGGER game_invites_block_trg\s+BEFORE INSERT ON public\.game_invites/.test(заслон),
    'триггер на game_invites пропал — приглашения пойдут мимо блокировки');

правило('заслон действует в обе стороны',
    /blocker_profile_id = a AND blocked_profile_id = b\s*\)?\s*OR\s*\(?\s*blocker_profile_id = b AND blocked_profile_id = a/
        .test(безСлов(тело(заслон, 'kslt_est_blokirovka'))),
    'проверка смотрит в одну сторону: заблокировавший сам сможет звать');

/* ── 2. БЛОКИРОВКА ТИХАЯ ─────────────────────────────────────────────── */
/* ИЩЕМ ЗАПИСЬ, А НЕ СЛОВО. 04.11 проверка нашла `push_log` в комментарии,
   который объяснял, что записи туда нет, и объявила беду. ПРАВИЛО,
   СЧИТАЮЩЕЕ ПОДСТРОКУ, НЕ СЧИТАЕТ ОБЪЯВЛЕНИЙ. */
правило('блокировка не трубит клубу',
    !/INSERT\s+INTO\s+push_log/i.test(безСлов(тело(функции, 'kslt_zablokirovat'))),
    'блокировка пишет в push_log — весь клуб узнает о чужой ссоре');

правило('уведомление не называет блокировку',
    !/заблокир/i.test(безСлов(тело(функции, 'kslt_zablokirovat')).split('notification_log')[1] || ''),
    'в тексте уведомления появилось слово «заблокировал» — блокировка перестала быть тихой');

/* ── 3. ПАРНЫЕ НЕ ОТМЕНЯЮТСЯ ─────────────────────────────────────────── */
правило('отменяются только одиночные баттлы',
    /coalesce\(format, 'singles'\) = 'singles'/.test(безСлов(тело(функции, 'kslt_zablokirovat'))),
    'условие про singles пропало — ссора двоих снимает матч четверых');

правило('парные считаются отдельно и называются вслух',
    /'parnyh', v_par/.test(безСлов(тело(функции, 'kslt_zablokirovat'))) &&
    /parnyh/.test(карточка),
    'число парных не возвращается или приложение его не показывает');

/* ── 4. ПРАВА: anon НЕ ЗОВЁТ ─────────────────────────────────────────── */
правило('права снимаются у anon, а не только у PUBLIC',
    /REVOKE ALL ON FUNCTION %s FROM anon/.test(права),
    'снятие прав у роли anon пропало — в Supabase её грант ставит DEFAULT PRIVILEGES');

правило('права снимаются и у authenticated перед возвратом',
    /REVOKE ALL ON FUNCTION %s FROM authenticated/.test(права),
    'без этого внутренние функции остаются зовомыми вошедшим');

правило('внутренние функции не возвращаются никому',
    !/GRANT EXECUTE ON FUNCTION public\.kslt_est_blokirovka/.test(права),
    'kslt_est_blokirovka снова открыта: она отвечает про ЛЮБУЮ пару людей');

/* ── 5. СВЯЗЬ НАЗВАНА ПОИМЁННО ───────────────────────────────────────── */
правило('кабинет приложения называет связь поимённо',
    !/\.select\('\*, players\(/.test(вход) &&
    /players!profiles_player_id_fkey\(/.test(вход),
    'embed без имени связи — кабинет умрёт на «more than one relationship was found»');

/* ── 6. ОКНО ОБЕЩАЕТ ТО, ЧТО ДЕЛАЕТ КОД ──────────────────────────────── */
правило('окно блокировки перечисляет шесть последствий',
    ['blk.w1','blk.w2','blk.w3','blk.w4','blk.w5','blk.w6'].every(к => карточка.includes(к)),
    'из окна пропал пункт — человек узнает о последствии после нажатия');

правило('окно обещает сохранность турнирных результатов',
    /blk\.keepTitle/.test(карточка) && /blk\.keepText/.test(карточка),
    'плашка про турнирные результаты исчезла');

правило('окно не обещает того, чего код не делает',
    !/списк|поиск/i.test(словарь.split("'blk.w1'")[1].split("'blk.keepTitle'")[0] || ''),
    'вернулось обещание «исчезнет из списков» — фильтрации списков в коде нет');

/* ── 7. ТРИ ЯЗЫКА ИДУТ ВМЕСТЕ ────────────────────────────────────────── */
const ТРЕБУЮТСЯ = ['sft.report','sft.block','rep.title','rep.send','blk.title',
                   'blk.do','blk.keepText','blk.listTitle','blk.unblock','blk.listEmpty'];
ТРЕБУЮТСЯ.forEach(ключ => {
    const м = словарь.match(new RegExp("'" + ключ.replace('.', '\\.') + "':\\s*\\{([^}]*)\\}"));
    правило('ключ ' + ключ + ' есть на трёх языках',
        !!м && /ru:\s*'[^']+'/.test(м[1]) && /en:\s*'[^']+'/.test(м[1]) && /kg:\s*'[^']+'/.test(м[1]),
        'ключ потерян или один из языков пуст — кыргызский теряется первым');
});

/* ── 8. СНЯТИЕ ЕСТЬ ТАМ, ГДЕ БЛОКИРУЮТ ───────────────────────────────── */
правило('кабинет приложения показывает заблокированных',
    /rpc\('kslt_moi_blokirovki'\)/.test(кабинет) && /blk\.listTitle/.test(кабинет),
    'экран «Заблокированные» пропал — блокировка стала дорогой в один конец');

правило('кабинет сайта показывает заблокированных',
    /rpc\('kslt_moi_blokirovki'\)/.test(кабСайта) && /blkListTitle/.test(кабСайта),
    'в кабинете сайта снять блокировку нечем');

правило('список перечитывается, а не правится на месте',
    /рисоватьБлокировки\(overlay\)/.test(кабинет) || /рисоватьБлокировки\(\)/.test(кабСайта),
    'строку убирают руками — снятие могло не дойти, и список соврёт');

/* ── 9. САЙТ И ПРИЛОЖЕНИЕ ГОВОРЯТ ОДНО ───────────────────────────────── */
['kslt_pozhalovatsya', 'kslt_zablokirovat', 'kslt_razblokirovat'].forEach(зов => {
    правило('сайт зовёт ' + зов,
        new RegExp("rpc\\('" + зов + "'").test(страница),
        'страница игрока на сайте разошлась с приложением');
    правило('приложение зовёт ' + зов,
        new RegExp("rpc\\('" + зов + "'").test(карточка),
        'карточка игрока в приложении разошлась с сайтом');
});

правило('кнопка, которая откажет, не рисуется',
    /var _zablokirovan\s*=/.test(карточка) && /var _заблокирован\s*=/.test(страница),
    'состояние блокировки не читается — кнопка «Вызвать» станет ловушкой');

/* ── 10. АДМИНКА ВИДИТ ОБА БАНА ──────────────────────────────────────── */
правило('вкладка банов читает оба вида',
    /kslt_bany_vse/.test(админка) && !/from\('players'\)\s*\n?\s*\.select\('id, name, banned_until/.test(админка),
    'вкладка снова читает только players — бан учётной записи не покажется');

правило('снятие бана выбирает действие по виду',
    /unban_user/.test(админка) && /unban_player/.test(админка) &&
    /getAttribute\('data-vid'\)/.test(админка),
    'снятие зовёт одно действие на оба бана — человек останется без входа');

правило('чужую блокировку админ не снимает',
    !/rpc\('kslt_razblokirovat'/.test(админка),
    'в админке появилось снятие чужой блокировки — это выбор человека, а не наш');

правило('общий список банов закрыт для anon',
    /REVOKE ALL ON FUNCTION public\.kslt_bany_vse\(\) FROM anon/.test(баны),
    'kslt_bany_vse открыта анониму — список наказаний утечёт наружу');

/* ── 11. ЦЕЛЬ НАЖАТИЯ ────────────────────────────────────────────────── */
правило('кнопки безопасности держат 44',
    /\.pd-safety-btn\s*\{[^}]*min-height:\s*44px/.test(одежда),
    'цель нажатия ушла ниже 44 — минимум Apple HIG');

правило('причина жалобы несёт галочку, а не только подсветку',
    /^\.pd-rep-tick\s*\{/m.test(одежда) && /pd-rep-tick/.test(карточка),
    'выбор причины различается только цветом — его не увидит тот, кто не делит два серых');

/* ── ПОСЛЕ БЛОКИРОВКИ СТРАНИЦА ПЕРЕРИСОВЫВАЕТСЯ, А НЕ ПЕРЕЗАГРУЖАЕТСЯ ──
   04.11, НАЙДЕНО ЧТЕНИЕМ, А НЕ ОПАСЕНИЕМ. На сайте стояло
   `location.reload()` сразу за тостом, и тост о числе отменённых матчей
   жил доли секунды до ухода страницы: человек НЕ УСПЕВАЛ прочитать то
   самое сообщение, ради которого всё затевалось. В приложении этой беды
   не было — там `PD.open(_playerId)`, перерисовка.
   ОДНО ПОНЯТИЕ — ОДИН СПОСОБ, и беда родилась ровно на шве.
   ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ: «обе стороны перерисовывают, ни одна не
   перезагружает», а не имя функции. */
правило('сайт после блокировки перерисовывает, а не перезагружает',
    (страница.match(/location\.reload\s*\(/g) || []).length === 0 &&
    /сказать\(слово,\s*'ok'\);\s*renderProfile\(data\);/.test(страница),
    'в js/player.js снова стоит location.reload() за тостом — тост о числе ' +
    'отменённых матчей не доживёт до глаз');

правило('снятие блокировки на сайте тоже перерисовывает',
    /сказать\(L\.blkUnblockDone,\s*'ok'\);\s*renderProfile\(data\);/.test(страница),
    'в js/player.js снятие блокировки не перерисовывает страницу — ' +
    'кнопка останется «Разблокировать», а контакты скрытыми');

правило('приложение после блокировки перерисовывает тем же способом',
    /toast\(слово\);\s*PD\.open\(/.test(карточка) &&
    (карточка.match(/location\.reload\s*\(/g) || []).length === 0,
    'в mobile/www/js/screens/player-detail.js перерисовки за тостом нет ' +
    'или появилась перезагрузка — два способа на одно понятие');

const ВСЕГО = 27 + ТРЕБУЮТСЯ.length;
console.log('\n  ЖАЛОБЫ, БЛОКИРОВКИ И ЗАСЛОН\n');
if (ошибки.length === 0) {
    console.log('  ок      все ' + ВСЕГО + ' правил держат\n');
    process.exit(0);
}
ошибки.forEach(о => {
    console.log('  НЕ ТАК  ' + о.имя);
    console.log('          ' + о.подсказка);
});
console.log('\n  НЕ ТАК  ' + ошибки.length + ' из ' + ВСЕГО + '\n');
process.exit(1);
