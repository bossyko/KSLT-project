/**
 * ЗАМОРОЗКА: ПРОХОД БЕЗ ИГРЫ НЕ ЗАПИРАЕТ КЛЕТКУ.
 *
 * Беда, пойманная прогоном 01.10 на турнире d8b39287. Сетка 16 на 14
 * вышедших — два BYE. Правка счёта в доигранной группе поменяла места:
 * Исматов из первого стал вторым, О31 — первым. Пересчёт почистил
 * незапертую клетку `A2` и поставил туда нового второго, а запертую `A1`
 * с BYE не тронул — там остался бывший первый. Один человек оказался в
 * первом круге ДВАЖДЫ, а законный первый номер группы не попал в сетку
 * вовсе: его слот занят. В первом круге 13 человек вместо 14.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ, А НЕ ЧИСЛО: «клетка со счётом BYE пересчитывается
 * наравне с несыгранной», и «сыгранность определена в файле один раз».
 * Право на проход без игры даёт РАСЧЁТ мест, а не прошлый расклад.
 *
 *   node tools/check-bye-ne-zapiraet.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СЕТКА = чит('js/admin/sections/bracket.js');
const СЕТч = безКом(СЕТКА);

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* Тело функции по имени, со счётом скобок: регуляркой «до закрывающей»
   тело утекает до конца файла на первой же вложенной скобке */
function тело(текст, имя) {
    const i = текст.indexOf('function ' + имя + '(');
    if (i === -1) return '';
    let гл = 0, j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}

const ЗАПЕРТА = тело(СЕТч, 'клеткаЗаперта');

/* ── 1. Сама функция есть и её тело читается ───────────────────────── */
правило('клеткаЗаперта на месте',
    ЗАПЕРТА.length > 0,
    'функция `клеткаЗаперта` не найдена в js/admin/sections/bracket.js — ' +
    'если её переименовали, правило нужно перенацелить, а не удалять');

/* ── 2. Отбой по BYE есть ───────────────────────────────────────────
   Якорь на СОДЕРЖИМОМ: сравнение счёта с 'BYE' и возврат «не заперта».
   Не на номере строки и не на соседях — те могут уехать. */
правило('проход без игры не запирает клетку',
    /score\s*===\s*'BYE'\s*\)\s*return\s+false/.test(ЗАПЕРТА),
    'в `клеткаЗаперта` пропал отбой `if (m.score === \'BYE\') return false`. ' +
    'Без него пересчёт состава сетки обходит клетку с проходом без игры, ' +
    'и при смене мест в группе один человек встаёт в сетку дважды, ' +
    'а законный первый номер группы выпадает из турнира');

/* ── 3. Отбой стоит ПЕРВЫМ ──────────────────────────────────────────
   Клетка BYE имеет и `completed`, и `winner_id`, и `score`. Любая из
   трёх проверок, вставшая раньше, вернёт «заперта» и беда вернётся,
   хотя строка про BYE в файле останется и правило 2 будет зелёным. */
const иBYE = ЗАПЕРТА.search(/score\s*===\s*'BYE'/);
const иПрочие = [
    ЗАПЕРТА.search(/status\s*===\s*'completed'/),
    ЗАПЕРТА.search(/winner_id\s*\)\s*return\s+true/),
    ЗАПЕРТА.search(/if\s*\(\s*m\.score\s*\)\s*return\s+true/)
].filter(и => и !== -1);
правило('отбой по BYE проверяется раньше прочих',
    иBYE !== -1 && иПрочие.length > 0 && иПрочие.every(и => иBYE < и),
    'проверка `score === \'BYE\'` должна стоять ПЕРВОЙ в `клеткаЗаперта`. ' +
    'У клетки с проходом без игры выставлены и `status: completed`, и ' +
    '`winner_id`, и `score` — любая из этих проверок, оказавшись раньше, ' +
    'снова объявит её запертой');

/* ── 4. Пересчёт спрашивает общую функцию, а не свою копию ──────────
   Пятое определение сыгранности — ровно тот шов, на котором беда и
   родилась. Пересчёт обязан звать `клеткаЗаперта`. */
const ПЕРЕСЧЁТ = тело(СЕТч, 'пересчитатьСоставСетки');
/* ЗАПЕРТОСТЬ В ПЕРЕСЧЁТЕ СПРАШИВАЕТСЯ В ДВУХ МЕСТАХ, И ОБА ОБЯЗАНЫ
   ЗВАТЬ ОБЩУЮ ФУНКЦИЮ: обход клеток первого круга и фильтр клеток
   кругов 2+. Правило держалось на НАЛИЧИИ `клеткаЗаперта` в теле — и
   перестало держать, как только мест стало два: откат подменял одно, а
   второе оставалось, и правило молчало. Теперь держим оба места и
   запрещаем самодельный критерий сыгранности внутри тела. */
правило('пересчёт сетки спрашивает клеткаЗаперта',
    /if \(клеткаЗаперта\(m\)\) return;/.test(ПЕРЕСЧЁТ) &&
    /!клеткаЗаперта\(m\)/.test(ПЕРЕСЧЁТ) &&
    !/===\s*'completed'/.test(ПЕРЕСЧЁТ),
    '`пересчитатьСоставСетки` перестала звать `клеткаЗаперта`. Если она ' +
    'решает сама, чем заперта клетка, определений становится два, и они ' +
    'разойдутся — беда 01.10 родилась ровно на таком шве');

/* ── 5. Сыгранность по всему файлу исключает BYE ────────────────────
   `сторонаСыграла` — судья «эта сторона уже играла, менять нельзя».
   Если он перестанет отличать BYE, человек, прошедший без игры, станет
   незаменимым, хотя на корт не выходил. */
const СЫГРАЛА = тело(СЕТч, 'сторонаСыграла');
правило('сыгранность стороны исключает проход без игры',
    /score\s*!==\s*'BYE'/.test(СЫГРАЛА),
    'в `сторонаСыграла` пропало `score !== \'BYE\'`. Проход без игры стал ' +
    'бы считаться игрой, и заменить такого человека было бы нельзя, ' +
    'хотя он не выходил на корт');

/* ── 6. Это определение не одиноко ──────────────────────────────────
   По файлу «сыгран» значит `score && score !== 'BYE'` — так устроены
   сторона сыграла, подсчёт очков, таблица группы, расписание. Правило
   держит, что таких мест осталось много: если их станет единицы,
   значит понятие начали переписывать по-своему. */
const вхождений = (СЕТч.match(/!==\s*'BYE'/g) || []).length;
правило('BYE исключается из сыгранного по всему файлу',
    вхождений >= 6,
    'мест, где счёт сравнивается с BYE как с «не игрой», стало ' +
    вхождений + ' — было не меньше шести. Понятие «матч сыгран» ' +
    'начали определять заново, и копии разойдутся');

/* ── вывод ──────────────────────────────────────────────────────────── */
if (ошибки.length) {
    console.log('✗ Проход без игры: ' + ошибки.length + ' правил упало\n');
    ошибки.forEach(о => console.log('  • ' + о.имя + '\n    ' + о.подсказка + '\n'));
    process.exit(1);
}
console.log('✓ Проход без игры не запирает клетку — все правила держат');
