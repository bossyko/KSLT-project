const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ПОТОЛОК_ПРИЛОЖЕНИЯ = 6;

/* СТОРОЖ ЧИТАЕТ КОД, А НЕ СЛОВА О КОДЕ. И гасит html-сущности: `&#127934;`
   — это символ, а не краска. Прибор ловился на них ТРИЖДЫ за одну сессию,
   поэтому гашение стоит и здесь. */
const чисто = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '))
    .replace(/&#?[0-9a-zA-Z]+;/g, м => ' '.repeat(м.length));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

function всеJs(д, вых) {
    вых = вых || [];
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) {
            if (/^(node_modules|android|test-results|playwright-report|build)$/.test(э.name)) return;
            всеJs(п, вых);
        } else if (э.name.endsWith('.js')) вых.push(п);
    });
    return вых;
}

const КРАСКА = /#[0-9a-fA-F]{3}\b|#[0-9a-fA-F]{6}\b|rgba?\(\s*\d+\s*,[^)]*\)/g;
/* РОЛЬ ЧИТАЕТСЯ ИЗ СТРОКИ: имя состояния рядом с краской. Это не «любое
   число», а число ИМЕННО в роли — то же разделение, что у css-сторожа. */
const РОЛЬ = /danger|success|status|blocked|banned|approved|rejected|is-error|de-bad|ошибк|error|\bbad\b/i;
/* Текст поверх акцентной заливки: у него своё имя `--accent-on`. */
const НА_АКЦЕНТЕ = /var\(--accent\)/;

const находки = { сайт: [], приложение: [] };
const наАкценте = { сайт: [], приложение: [] };
const файлы = ['js', 'mobile/www/js'].reduce((в, д) => {
    try { return в.concat(всеJs(д)); } catch (e) { return в; }
}, []);

файлы.forEach(п => {
    const т = чисто(fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8'));
    const где = п.startsWith('mobile/') ? 'приложение' : 'сайт';
    т.split('\n').forEach((s, i) => {
        if (!КРАСКА.test(s)) { КРАСКА.lastIndex = 0; return; }
        КРАСКА.lastIndex = 0;
        if (НА_АКЦЕНТЕ.test(s) && /color:\s*#/.test(s)) {
            наАкценте[где].push(п + ':' + (i + 1));
        } else if (РОЛЬ.test(s)) {
            const найдено = s.match(КРАСКА) || [];
            КРАСКА.lastIndex = 0;
            найдено.forEach(c => находки[где].push(п + ':' + (i + 1) + ' ← ' + c));
        }
    });
});

/* ---- 1. на сайте роль не пишется числом ---- */
правило('на сайте роль в инлайнах js не пишется числом',
    находки.сайт.length === 0,
    'Краска роли числом:\n  ' + находки.сайт.join('\n  ') + '\n' +
    'Пять разных красных уже жили в продукте, и один из них давал\n' +
    'контраст 3.55 при пороге 4.5. Бери роль: var(--danger),\n' +
    'var(--success), var(--danger-subtle), var(--danger-on).');

/* ---- 2. текст поверх акцента берёт своё имя ---- */
правило('текст поверх акцента берёт --accent-on, а не число',
    наАкценте.сайт.length === 0,
    'Текст на акцентной заливке числом:\n  ' + наАкценте.сайт.join('\n  ') + '\n' +
    '`#000` и `--accent-on` — РАЗНЫЕ цвета: ΔE 2.7, то есть различимы.\n' +
    'Имя у этого цвета есть с самого начала.');

/* ---- 3. храповик приложения ---- */
const вПриложении = находки.приложение.length + наАкценте.приложение.length;
правило('в приложении краски роли числом не прибавилось',
    вПриложении <= ПОТОЛОК_ПРИЛОЖЕНИЯ,
    'Было ' + ПОТОЛОК_ПРИЛОЖЕНИЯ + ', стало ' + вПриложении + '.\n' +
    'Приложение ждёт своей ветки (слово Кости 13.10), но беда там не\n' +
    'должна расти.');
правило('потолок приложения не завышен',
    вПриложении >= ПОТОЛОК_ПРИЛОЖЕНИЯ,
    'В приложении ' + вПриложении + ' при потолке ' + ПОТОЛОК_ПРИЛОЖЕНИЯ + '.\n' +
    'ХРАПОВИК ОПУСКАЕТСЯ: поправь ПОТОЛОК_ПРИЛОЖЕНИЯ на ' + вПриложении + '.');

/* ---- 4. роли и их пары объявлены ---- */
const токены = чисто(fs.readFileSync(path.join(КОРЕНЬ, 'css/tokens.css'), 'utf8'));
const НУЖНЫ = ['--danger', '--danger-subtle', '--danger-on', '--success', '--accent-on'];
const нет = НУЖНЫ.filter(и => !new RegExp('^\\s*' + и + '\\s*:', 'm').test(токены));
правило('роли и их пары объявлены в токенах',
    нет.length === 0,
    'Нет в css/tokens.css: ' + нет.join(', ') + '\n' +
    'Без имени инлайн снова напишет число.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      роль в инлайнах js: 5 правил');
    console.log('          на сайте краски роли числом НОЛЬ');
    console.log('          текст на акценте берёт --accent-on');
    console.log('          приложение под храповиком: ' + вПриложении);
    console.log('          css-сторож отказа не тронут: он про селекторы, этот про строки js');
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  роль в инлайнах js — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
