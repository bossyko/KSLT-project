'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ИМЯ = /KSLT_[A-ZА-Я][A-ZА-Я_]*/g;

function всеHtml(д, вых) {
    вых = вых || [];
    fs.readdirSync(path.join(КОРЕНЬ, д || '.'), { withFileTypes: true }).forEach(э => {
        const п = д ? д + '/' + э.name : э.name;
        if (э.isDirectory()) {
            if (!/^(node_modules|\.git|android|ios|build|test-results|playwright-report|slepki|_figma|_bazovy)$/
                .test(э.name) && !э.name.startsWith('.')) всеHtml(п, вых);
        } else if (э.name.endsWith('.html')) вых.push(п);
    });
    return вых;
}

const кеш = new Map();
function файл(п) {
    if (!кеш.has(п)) {
        try { кеш.set(п, fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8')); }
        catch (e) { кеш.set(п, null); }
    }
    return кеш.get(п);
}

/** Пути своих скриптов разметки, приведённые к корню репозитория. */
function скрипты(страница) {
    const т = файл(страница);
    if (т == null) return [];
    const д = path.posix.dirname(страница);
    return [...т.matchAll(/<script[^>]+src="([^"]+?\.js)(?:\?[^"]*)?"/g)]
        .map(m => m[1])
        .filter(с => с.indexOf('//') === -1)          /* чужие адреса не наши */
        .map(с => path.posix.normalize((д === '.' ? '' : д + '/') + с));
}

const находки = [];
всеHtml('').forEach(страница => {
    const свои = скрипты(страница);
    if (!свои.length) return;

    const объявлены = new Set();
    const зовы = new Map();      /* имя → файл, где зовут */
    const подОхраной = new Set();

    свои.forEach(п => {
        const т = файл(п);
        if (т == null) return;
        /* ОБЪЯВЛЕНИЕ: присваивание в глобальное имя. */
        [...т.matchAll(/(?:window|global)\.(KSLT_[A-ZА-Я][A-ZА-Я_]*)\s*=/g)]
            .forEach(m => объявлены.add(m[1]));
        /* ОХРАНА: автор о случае думал. */
        [...т.matchAll(/typeof\s+(KSLT_[A-ZА-Я][A-ZА-Я_]*)|(?:window\.|global\.|\(\s*)(KSLT_[A-ZА-Я][A-ZА-Я_]*)\s*(?:&&|\?|\|\|)/g)]
            .forEach(m => подОхраной.add(m[1] || m[2]));
        /* ЗОВ: имя с точкой — то есть у дома что-то берут. */
        [...т.matchAll(/(KSLT_[A-ZА-Я][A-ZА-Я_]*)\s*\./g)]
            .forEach(m => { if (!зовы.has(m[1])) зовы.set(m[1], п); });
    });

    [...зовы.entries()].forEach(([имя, где]) => {
        if (объявлены.has(имя) || подОхраной.has(имя)) return;
        находки.push({ страница, имя, где });
    });
});

console.log('');
console.log('  разметок прочитано: ' + всеHtml('').length);
if (!находки.length) {
    console.log('  ок      ни одна разметка не зовёт дом, которого на ней нет\n');
    process.exit(0);
}

const поСтранице = {};
находки.forEach(н => {
    поСтранице[н.страница] = поСтранице[н.страница] || [];
    поСтранице[н.страница].push(н.имя + '  ← ' + н.где);
});
console.log('  БЕСПРИЗОРНЫХ ЗОВОВ: ' + находки.length +
            ' на ' + Object.keys(поСтранице).length + ' разметках\n');
Object.entries(поСтранице)
    .sort((a, b) => b[1].length - a[1].length)
    .forEach(([с, список]) => {
        console.log('  ' + с);
        [...new Set(список)].forEach(и => console.log('      ' + и));
    });
console.log('');
