#!/usr/bin/env node
/**
 * РАЗМЕР СЕТКИ ПЛЕЙ-ОФФ — СКОЛЬКО ЕГО ОПРЕДЕЛЕНИЙ И ГДЕ ОНИ.
 *
 * ОДНО ПОНЯТИЕ ОПРЕДЕЛЕНО ТРЕМЯ СПОСОБАМИ, и беда 13.11 родилась ровно
 * на шве между ними. Турнир «Дружеский парный MASTERS»: в админке сетка
 * рисовалась верно — четвертьфинал, полуфинал, финал, — а на публичной
 * странице кругов было два, четвертьфиналы назывались «полуфиналом», и
 * финал не показывался вовсе. Данные были одни и те же.
 *
 * Три способа, замер 13.11:
 *
 *   tournament.draw_size || 16          14 мест (11 в админке, 3 на сайте)
 *   первыйКруг * 2                       1 место — bracket.js:6258, и там
 *                                        прямо написано «в групповом
 *                                        турнире draw_size не задают»
 *   groupCount * qualifiers_per_group    1 место — tournament-detail.js:1679,
 *                                        и ИМЕННО ОНО рисует публичную
 *                                        сетку группового турнира
 *
 * Отсюда и беда: у группового турнира `draw_size` не заполняют, админка
 * считает по матчам, а сайт — по настройкам групп. Настройки говорили
 * «из группы выходит один»: 4 × 1 = 4, два круга вместо трёх.
 *
 * ЭТОТ ПРИБОР НЕ СВОДИТ ИХ ВОЕДИНО — на это нужно слово Кости, правка
 * трогает четыре страницы. Он ДЕРЖИТ ЧИСЛО: пока способов три и мест
 * столько же, он молчит. Появится четвёртый способ или новое место —
 * упадёт, и разбираться будут сразу, а не через полгода на живом
 * турнире.
 *
 * ДУБЛИКАТ ЛОВИТ ПРОВЕРКА, А НЕ ПАМЯТЬ.
 *
 * Запуск:  node tools/check-razmer-setki.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
const ок = [];
function проверить(имя, условие, почему) {
    if (условие) ок.push(имя); else ошибки.push({ имя, почему });
}
const читать = (ф) => {
    try { return fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'); } catch (e) { return null; }
};

const ФАЙЛЫ = ['js/admin/sections/bracket.js', 'js/tournament-detail.js'];
const нет = ФАЙЛЫ.filter((ф) => читать(ф) === null);
const текст = {};
ФАЙЛЫ.forEach((ф) => { const т = читать(ф); if (т !== null) текст[ф] = т; });

/* СЧИТАЕТСЯ КОД, А НЕ КОММЕНТАРИИ. Пример в пояснении — такой же текст
   для регулярки, как настоящая строка, и 13.11 я на этом уже попалась:
   прибор насчитал лишнюю запись, которой в коде не было. */
const безПояснений = (т) => т
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^\s*\/\/[^\n]*$/gm, '');

// ---------- 1. способов ровно три, и они те же самые ----------
(function () {
    if (нет.length) return;

    const всё = ФАЙЛЫ.map((ф) => безПояснений(текст[ф])).join('\n');

    const поПолю = (всё.match(/(?:tournament|t)\.draw_size\s*\|\|\s*16/g) || []).length;
    const поМатчам = (всё.match(/первыйКруг\s*\?\s*первыйКруг\s*\*\s*2/g) || []).length;
    const поГруппам = (всё.match(/groupCount\s*\*\s*qualifiers/g) || []).length;

    /* ХРАПОВИК ИДЁТ ЗА ЗАМЕРОМ И ВНИЗ ТОЖЕ. Станет мест меньше — значит
       кто-то начал сводить их воедино, и число надо опустить здесь же,
       иначе сторож перестанет ловить рост. */
    проверить('счёт по полю draw_size не расползается: ровно 14 мест',
        поПолю === 14,
        'Мест со счётом `draw_size || 16` стало ' + поПолю + ' вместо 14. ' +
        'Выросло — завели ещё одно определение размера сетки; стало ' +
        'меньше — их сводят, и число надо поправить здесь же.');

    проверить('счёт по матчам первого круга — ровно одно место',
        поМатчам === 1,
        'Счёт размера по матчам первого круга найден ' + поМатчам +
        ' раз вместо одного (bracket.js, «в групповом турнире draw_size ' +
        'не задают»).');

    /* ДВА МЕСТА, А НЕ ОДНО — ПРИБОР ПОПРАВИЛ МОЙ ЗАМЕР. Я насчитала
       одно и ошиблась: `groupCount * qualifiers` стоит ещё и в
       bracket.js:10220 под именем `directCount` — сколько пар выходит
       из групп НАПРЯМУЮ. Считают они одно и то же число разными
       словами, и в этом вся беда: на сайте оно становится размером
       сетки целиком, а в админке — только прямыми местами, к которым
       потом добавляются доп. матчи. 13.11 это и разошлось. */
    проверить('счёт по группам и выходящим — ровно два места',
        поГруппам === 2,
        'Счёт `groupCount * qualifiers` найден ' + поГруппам + ' раз ' +
        'вместо двух (tournament-detail.js:1679 — размер публичной ' +
        'сетки, bracket.js:10220 — число прямых мест). Это одно и то же ' +
        'число под разными именами, и именно оно разошлось 13.11.');

    проверить('четвёртого способа счёта не появилось',
        поПолю + поМатчам + поГруппам === 17,
        'Всего мест счёта размера сетки: ' + (поПолю + поМатчам + поГруппам) +
        ' вместо 17. Одно понятие уже определено тремя способами; ' +
        'четвёртый сделает расхождение неразличимым.');
})();

// ---------- 2. публичная сетка группового турнира ----------
(function () {
    if (нет.length) return;
    const сайт = безПояснений(текст['js/tournament-detail.js']);

    /* ЭТО ПРАВИЛО — НЕ ПРО КРАСОТУ, А ПРО ТО МЕСТО, ГДЕ УЖЕ ОБОЖГЛИСЬ.
       Публичная сетка группового турнира считает круги по настройкам
       групп. Значит настройка `qualifiers_per_group` — не справочное
       поле, а то, что РИСУЕТ сетку зрителю: поставили 1 при восьми
       участниках плей-офф — и финал пропал со страницы. */
    проверить('публичная сетка группового турнира считает круги по настройкам групп',
        /plDrawSize\s*=\s*groupCount\s*\*\s*qualifiers/.test(сайт) &&
        /while\s*\(d\s*<\s*plDrawSize\)/.test(сайт),
        'В tournament-detail.js пропал счёт plDrawSize = groupCount * ' +
        'qualifiers с округлением вверх до степени двойки. Если счёт ' +
        'сменили — проверьте публичную страницу группового турнира ' +
        'глазами: 13.11 она показывала два круга вместо трёх.');

    проверить('число кругов берётся логарифмом, а не на глаз',
        /plTotalRounds\s*=\s*Math\.log2\(plDrawSize\)/.test(сайт),
        'Круги обязаны считаться как log2 размера. Любое другое ' +
        'выражение разойдётся с админкой, которая считает так же.');
})();

// ---------- вывод ----------
console.log('');
for (const и of ок) console.log('  ·       ' + и);
for (const е of ошибки) {
    console.log('  НЕ ТАК  ' + е.имя);
    console.log('          ' + е.почему.replace(/\n/g, '\n          '));
}
if (нет.length) console.log('  НЕ ТАК  прибор не нашёл файлы: ' + нет.join(', '));
console.log('');
if (!ошибки.length && !нет.length) {
    console.log('  ок      размер сетки плей-офф: ' + ок.length + ' правил');
    console.log('          три способа счёта, 17 мест   ·   публичная считает по группам');
} else {
    console.log('  НЕ ТАК  размер сетки — ' + (ошибки.length + (нет.length ? 1 : 0)) + ' правил не держится');
}
console.log('');
process.exit((ошибки.length || нет.length) ? 1 : 0);
