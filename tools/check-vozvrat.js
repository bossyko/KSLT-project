#!/usr/bin/env node
/**
 * ВОЗВРАТ УДАЛЁННОЙ УЧЁТНОЙ ЗАПИСИ — ОДИН ДОМ (шаг A3.7в, 29.10).
 *
 * ЗАЧЕМ. Зов функции возврата расходился ОПАСНО: сайт звал
 * `client.functions.invoke`, приложение собирало `fetch` руками — свой
 * адрес, свой `Authorization`, свой `apikey`, свой разбор ответа.
 * Поменяйся формат заголовков — приложение замолчит, а срок удаления
 * будет идти своим чередом, и вернуть станет нечего.
 *
 * Замер 29.10: во всём продукте `functions.invoke` стоял ОДИН раз, а
 * `fetch` руками — 47. Дом зовёт `invoke`, когда клиент его умеет, и
 * откатывается на `fetch`; остальные 46 мест — отдельная работа,
 * записанная в трекер числом.
 *
 * Запуск: node tools/check-vozvrat.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));

const ДОМ = 'js/kslt-vozvrat.js';
const ДОМ_П = 'mobile/www/js/kslt-vozvrat.js';

console.log('\n  ВОЗВРАТ УЧЁТНОЙ ЗАПИСИ — ОДИН ДОМ\n');

правило('дом объявлен',
    /KSLT_VOZVRAT/.test(чит(ДОМ)) && /API\.метка\s*=/.test(чит(ДОМ)) &&
    /API\.вернуть\s*=/.test(чит(ДОМ)),
    'Нужны `метка` (помечена ли запись) и `вернуть` (зов функции).');

правило('копии дома побайтово равны',
    чит(ДОМ) === чит(ДОМ_П),
    'Разошлись — значит зов возврата снова живёт двумя жизнями.');

правило('дом зовёт через invoke, когда клиент умеет',
    /client\.functions\.invoke/.test(безКом(чит(ДОМ))),
    '`invoke` сам ставит заголовки и сам разбирает ответ — ровно то\n' +
    'место, где приложение расходилось, собирая их руками.');

правило('у дома есть откат на fetch',
    /functions\/v1\/delete-account/.test(безКом(чит(ДОМ))),
    'Клиент без `functions` должен работать тоже, иначе дом хуже того,\n' +
    'что заменил.');

правило('адрес базы дом берёт у настроек, а не вписывает',
    /global\.SUPABASE_URL/.test(безКом(чит(ДОМ))) &&
    !/https:\/\/[a-z0-9]+\.supabase\.co/.test(безКом(чит(ДОМ))),
    'Вписанный адрес здесь был бы ВТОРЫМ местом, где живёт адрес базы.');

правило('дом отдаёт исход, а не бросает',
    /ок:\s*false/.test(чит(ДОМ)) && /беда:/.test(чит(ДОМ)),
    'Сайт показывает надпись в окне, приложение — тост. Что показать,\n' +
    'решает продукт, поэтому дом отдаёт `{ ок, беда }`, а не бросает.');

[['js/account-restore.js', 'сайта'],
 ['mobile/www/js/account-restore.js', 'приложения']].forEach(([ф, имя]) => {
    const т = безКом(чит(ф));
    правило('у ' + имя + ' нет своего зова функции',
        !/functions\.invoke|functions\/v1\/delete-account/.test(т),
        'Зов переехал в дом. Остался на месте — два способа звать одно.');
    правило('у ' + имя + ' дом зовётся',
        /KSLT_VOZVRAT\.вернуть/.test(т),
        'Без зова работа не сделана.');
});

правило('у сайта нет своего чтения метки',
    !/from\('profiles'\)[\s\S]{0,80}deleted_at/.test(безКом(чит('js/account-restore.js'))),
    'Проверка метки тоже переехала: она одна и та же — прочитать\n' +
    '`profiles.deleted_at` по своей сессии.');

правило('срок возврата по-прежнему из дома правил',
    /ДНЕЙ_НА_ВОЗВРАТ|датаУдаления/.test(чит('js/account-restore.js')) ||
    /датаУдаления/.test(чит('mobile/www/js/account-restore.js')),
    'Шаг A3.7а свёл срок в `kslt-rules.js`. Этот сторож проверяет, что\n' +
    'он там и остался: два куска про один файл не должны расходиться.');

правило('дом подключён во всех разметках',
    ['mobile/www/index.html', 'pages/dashboard.html'].every(ф =>
        !/account-restore\.js/.test(чит(ф)) || /kslt-vozvrat\.js/.test(чит(ф))),
    'Страница грузит возврат без дома — окно не сможет вернуть запись.');

правило('дом грузится ДО того, кто его зовёт',
    (function () {
        const t = чит('mobile/www/index.html');
        const д = t.indexOf('kslt-vozvrat.js'), з = t.indexOf('account-restore.js');
        return д !== -1 && з !== -1 && д < з;
    })(),
    'Порядок ставится явно, а не на удачу тайминга.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else { console.log('  ок      возврат учётной записи: все ' + держится + ' правил держатся\n'); }
