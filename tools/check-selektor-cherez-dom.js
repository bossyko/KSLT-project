/**
 * ЗАМОРОЗКА СЕЛЕКТОРА С ПОДСТАНОВКОЙ (кусок 195, 27.10.2026).
 *
 * ЗАМЕР: значение атрибута подставлялось в селектор строкой в ДВАДЦАТИ
 * ДЕВЯТИ местах двенадцати файлов. Кавычка там не даёт чужого
 * обработчика — она РОНЯЕТ ЗОВ исключением `SyntaxError`, и дальше по
 * функции не идёт ничего: ни отрисовка, ни обработчики.
 *
 * ПРОВЕРЕНО В БРАУЗЕРЕ: `[data-t="a"b"]` падает `SyntaxError`, через дом
 * тот же узел находится.
 *
 * СЕГОДНЯ КАВЫЧКА НЕ ПРОЙДЁТ НИ В ОДНО МЕСТО — и это главное, что здесь
 * заморожено. Значения либо из кода (индекс, номер группы, ключ
 * правила), либо под CHECK в базе (`gender`, `entity_type`,
 * `reaction_type`), либо uuid. КОД ДЕРЖИТСЯ НЕ СОБОЙ, А БАЗОЙ, и база
 * уже подвела: у `reaction_type` CHECK объявлен ДВАЖДЫ и по-разному —
 * десять значений в снимке схемы, три в
 * `sql/схема/news-reactions-poll-votes.sql`. УМОЛЧАНИЕ — СВОЙСТВО
 * ДАННЫХ, БЕЗОПАСНОСТЬ — СВОЙСТВО КОДА.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ:
 *   • дом селектора объявлен ОДИН раз;
 *   • обратная косая закрывается ПЕРВОЙ, иначе она испортит кавычку;
 *   • `null` даёт пусто, а не слово «null» в селекторе;
 *   • ни одна подстановка значения атрибута не идёт мимо дома;
 *   • `KSLT_экранировать` в селектор не зовут: `&quot;` внутри селектора
 *     это шесть знаков, а не кавычка, и узел не найдётся;
 *   • страница, зовущая дом, подключает его — и раньше зовущих.
 *
 *   node tools/check-selektor-cherez-dom.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const собрать = (кат, спис) => {
    fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(д => {
        const п = кат + '/' + д.name;
        if (д.isDirectory()) собрать(п, спис);
        else if (д.name.endsWith('.js')) спис.push(п);
    });
    return спис;
};
const JS = собрать('js', []);
const ДОМ = 'js/kslt-ekranirovanie.js';
const ТЕЛО = безКом(чит(ДОМ));

/* ══ 1. ДОМ ОДИН И ЗАКРЫВАЕТ ЧТО НАДО ══════════════════════════════════ */

правило('дом селектора объявлен ровно один раз',
    JS.reduce((с, ф) => с + (безКом(чит(ф)).match(/window\.KSLT_селектор\s*=/g) || []).length, 0) === 1,
    'объявлений не одно. Два дома разойдутся на первой же правке');

/* ОБРАТНАЯ КОСАЯ ПЕРВОЙ. Закрой сперва кавычку — и косая, подставленная
   следом, съест её же экран. Тот же порядок, что у `&` в разметке. */
const ТЕЛО_СЕЛ = ТЕЛО.slice(ТЕЛО.indexOf('KSLT_селектор ='));
const иКосая = ТЕЛО_СЕЛ.indexOf('.replace(/\\\\/g');
const иКавычка = ТЕЛО_СЕЛ.indexOf('.replace(/"/g');
const порядок = иКосая !== -1 && иКавычка !== -1 && иКосая < иКавычка;
правило('обратная косая закрывается ПЕРВОЙ, кавычка следом',
    порядок,
    'порядок замен обратный: косая съест экран кавычки, и зов снова упадёт');

правило('пустое значение даёт пусто, а не слово',
    /значение == null \? '' : значение/.test(ТЕЛО.slice(ТЕЛО.indexOf('KSLT_селектор'))),
    'в селектор уедет слово «null», и узел не найдётся молча');

/* ══ 2. НИ ОДНОЙ ПОДСТАНОВКИ МИМО ДОМА ═════════════════════════════════ */

/* ПРИЗНАК БЕРЁТ ЗОВ ЦЕЛИКОМ, А НЕ СТРОКУ. Селектор переносят по строкам,
   и признак, читающий строку, пропустит перенесённый. */
const зов = /querySelector(?:All)?\(\s*('(?:[^'\\]|\\.)*'[\s\S]{0,200}?)\)/g;
const мимо = [];
JS.filter(ф => ф !== ДОМ).forEach(ф => {
    const т = безКом(чит(ф));
    let м;
    const р = new RegExp(зов.source, 'g');
    while ((м = р.exec(т)) !== null) {
        const арг = м[1];
        if (!/="'\s*\+/.test(арг.replace(/\s+/g, ' ')) && !/="'\s*\n?\s*\+/.test(арг)) continue;
        if (/KSLT_селектор\s*\(/.test(арг)) continue;
        мимо.push(ф.split('/').pop() + ':' + (т.slice(0, м.index).split('\n').length));
    }
});

правило('подстановок значения атрибута мимо дома нет',
    мимо.length === 0,
    'мест мимо дома: ' + мимо.length + ' — ' + мимо.slice(0, 5).join(', ') + '.\n' +
    'Кавычка там не даёт обработчика — она роняет зов SyntaxError');

/* СКОЛЬКО ИХ ВСЕГО — ЗАМЕРЕНО, А НЕ ВСПОМНЕНО. Правило стоит столько,
   сколько мест оно видит: признак, нашедший ноль, ничего не сторожит. */
let черезДом = 0;
JS.filter(ф => ф !== ДОМ).forEach(ф => {
    черезДом += (безКом(чит(ф)).match(/KSLT_селектор\s*\(/g) || []).length;
});
/* ПОЛ ПОДНЯТ 29.10: 30 → 31. Прибавило одно место — клетка тай-брейка в
   `js/match-score.js`: подстановка номера сета в `[data-tb-set="…"]`
   шла мимо дома, и это показал ПРИЗНАК ВЫШЕ, а не замер. Пол идёт за
   замером: оставь 30 — и следующий возврат к строке пройдёт молча. */
/* ПОДНЯТ ДО ЗАМЕРЕННОГО 04.11: 31 → 32, и число взято У ПРИБОРА, а не
   грепом: прибор считает подстановки В СЕЛЕКТОРАХ, а не любое упоминание
   имени, — греп давал 35. ЧИСЛО БЕРЁТСЯ ИЗ ПРИБОРА, УСТНЫЙ СЧЁТ
   ЗАПРЕЩЁН. Люфт в один зов пропускал снятие молча. */
/* ОПУЩЕН 07.11: 32 → 31, И ЭТО НЕ ВОЗВРАТ К СТРОКЕ, А УБОРКА.
   Коммит «Правила пароля — один дом; семь мёртвых чтений из auth.js
   сняты» удалил место, которое звало дом: `.pw-rule[data-rule=…]`
   переехало в дом правил пароля вместе со своим кодом. Померено
   по файлам: `auth.js` 3 → 2, `bracket.js` 2 → 3, итог 31.
   ПОЛ, СЧИТАЮЩИЙ ЗОВЫ, ПАДАЕТ И ОТ УДАЛЕНИЯ МЁРТВОГО КОДА — поэтому
   при снижении сначала смотрят, КУДА делось место, и лишь потом
   трогают число. Здесь места нет вовсе, и строки вместо него тоже нет. */
правило('зовов дома не меньше замеренных 31',
    черезДом >= 31,
    'зовов дома ' + черезДом + ', замерено 07.11 ровно 31 (мест 30: у\n' +
    '`stats.js` в одном селекторе две подстановки).\n' +
    'Стало меньше — значит место вернулось к строке, а признак выше это\n' +
    'пропустил: тогда беда в признаке, а не в числе');

/* ══ 3. ЧУЖОЙ ДОМ В СЕЛЕКТОР НЕ ЗОВУТ ══════════════════════════════════ */

const ЧУЖИМ = [];
JS.filter(ф => ф !== ДОМ).forEach(ф => {
    const т = безКом(чит(ф));
    const р = new RegExp(зов.source, 'g');
    let м;
    while ((м = р.exec(т)) !== null) {
        if (/KSLT_экранировать\s*\(|A\.esc\s*\(/.test(м[1])) ЧУЖИМ.push(ф.split('/').pop());
    }
});
правило('экранирование разметки в селектор не зовут',
    ЧУЖИМ.length === 0,
    'файлов с чужим домом в селекторе: ' + ЧУЖИМ.length + ' — ' +
    [...new Set(ЧУЖИМ)].slice(0, 4).join(', ') + '.\n' +
    '`&quot;` внутри селектора — шесть знаков, а не кавычка: узел не найдётся');

/* ══ 4. ДОМ ДОЕЗЖАЕТ ДО СТРАНИЦЫ И СТОИТ РАНЬШЕ ════════════════════════ */

const ЗОВУТ = JS.filter(ф => ф !== ДОМ && /KSLT_селектор\s*\(/.test(безКом(чит(ф))))
    .map(ф => ф.split('/').pop());
const СТРАНИЦЫ = fs.readdirSync(path.join(КОРЕНЬ, 'pages'))
    .filter(ф => ф.endsWith('.html')).map(ф => 'pages/' + ф)
    .concat(fs.readdirSync(path.join(КОРЕНЬ, 'maket'))
        .filter(ф => ф.endsWith('.html')).map(ф => 'maket/' + ф))
    .concat(fs.readdirSync(КОРЕНЬ).filter(ф => /^index.*\.html$/.test(ф)));

const скрипты = с => (чит(с).match(/<script src="[^"]+"/g) || [])
    .map(т => т.slice(13, -1).split('?')[0].split('/').pop());

const безДома = [];
const позже = [];
СТРАНИЦЫ.forEach(с => {
    const и = скрипты(с);
    const свои = и.map((н, i) => ({ н, i })).filter(x => ЗОВУТ.indexOf(x.н) !== -1);
    if (!свои.length) return;
    const д = и.indexOf('kslt-ekranirovanie.js');
    if (д === -1) { безДома.push(с); return; }
    if (д > свои[0].i) позже.push(с + ' (дом ' + д + ', зовущий ' + свои[0].i + ')');
});

правило('дом подключают все страницы, которым он нужен',
    безДома.length === 0,
    'страниц без дома: ' + безДома.length + ' — ' + безДома.slice(0, 4).join(', ') +
    '.\nБез него зов упадёт на первом же селекторе с подстановкой');

правило('дом стоит раньше своих зовущих',
    позже.length === 0,
    'страниц с порядком наоборот: ' + позже.length + ' — ' + позже.slice(0, 4).join(', ') +
    '.\nСкрипты продукта обычные: поздний дом — это падение, а не задержка');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      селектор через дом: 8 правил');
    console.log('          подстановок через дом ' + черезДом + ', мимо дома ноль');
    console.log('          косая закрывается первой   ·   чужой дом не зовут');
    console.log('          дом доезжает до страниц и стоит раньше зовущих');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  селектор через дом — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
