/**
 * ЗАМОРОЗКА «ВОЗРАСТ ОДИН НА ВЕСЬ ПРОДУКТ» (ветка Ю, кусок 189, 27.10.2026).
 *
 * ЗАМЕР 27.10. Запись Ю11 говорила: «в оферте 18+, в Условиях 14+».
 * ЗАМЕР НАШЁЛ ТРИ ЧИСЛА И ДВА МОЛЧАНИЯ:
 *
 *   документ    ru        en        kg
 *   Условия     14        13        13
 *   Оферта      18        18        молчит (пункта 4.5.2 в ней нет вовсе)
 *   Политика    молчит    молчит    молчит
 *   Приложение  молчит    молчит    молчит
 *
 * Прежний признак этого не увидел: он искал «число + лет/years/жаш», а
 * английское «aged 13 and older» и кыргызское «13 жаштан жогорку» пишут
 * число и слово иначе. ПРИЗНАК, ПОДОГНАННЫЙ ПОД ОДИН ЯЗЫК, МОЛЧИТ НА ДВУХ
 * ОСТАЛЬНЫХ.
 *
 * РЕШЕНИЕ КОСТИ 27.10: «правильно будет 18 — если будет оплата в
 * дальнейшем установлена». Условия сведены на 18 на трёх языках.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ, А НЕ ЧИСЛО: не «возраст равен 18», а «во всех
 * документах, где возраст назван, он ОДИН И ТОТ ЖЕ». Поменяется решение —
 * поменяется число в одном месте здесь, и правило поймает любой документ,
 * который за ним не пошёл.
 *
 *   node tools/check-vozrast-odin.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => { try { return fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'); } catch (e) { return null; } };
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ПЕРЕПИСАНО 06.11. ВОЗРАСТОВ ДВА, И ЭТО НЕ ОШИБКА.
   Политика, утверждённая приказом № 1 от 3 ноября, говорит: Сервис
   предназначен для лиц ОТ 14 ЛЕТ, и с 14 до 18 человек сам даёт
   согласие на обработку своих данных (ч. 3 ст. 81 Цифрового кодекса).
   Оферта говорит про УЧАСТИЕ В ТУРНИРАХ — там 18, потому что там
   деньги и ответственность.

   Прежнее правило требовало ОДНО число во всех документах. Это было
   верно 27.10, когда числа разъехались случайно (13, 14, 18), и стало
   неверно, когда появились два НАЗНАЧЕНИЯ возраста.

   ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ: внутри одного назначения число одно на все
   языки, а возраст пользования не больше возраста участия. Поменяется
   решение — меняются ДВЕ строки ниже, и правило ловит каждый документ,
   который за ними не пошёл. */
const МЕСТА = [
    /* Пользование Сервисом.
       ЯКОРЯ ПЕРЕПИСАНЫ 06.11: Условия заменены Пользовательским
       соглашением, утверждённым приказом № 1, и фразы о возрасте в нём
       другие. Прежние якоря ослепли молча — поймал этот же сторож,
       когда начал искать возраст и в политике. */
    ['pages/terms.html',            /Сервис доступен лицам от (\d{1,2}) лет/,                         'пользование'],
    ['pages/terms-en.html',         /the Service is available to persons aged (\d{1,2}) and over/,    'пользование'],
    ['pages/terms-kg.html',         /Кызмат (\d{1,2}) жаштан жогорку адамдарга жеткиликтүү/,          'пользование'],
    ['pages/privacy-policy.html',   /Сервис предназначен для лиц от (\d{1,2}) лет/,                   'пользование'],
    ['pages/privacy-policy-en.html',/The Service is intended for persons aged (\d{1,2}) and over/,    'пользование'],
    ['pages/privacy-policy-kg.html',/Кызмат (\d{1,2}) жаштан жогорку адамдарга арналган/,             'пользование'],
    /* Участие в турнирах */
    ['pages/offer.html',            /участник должен быть достигшим возраста (\d{1,2}) лет/,          'участие'],
    ['pages/offer-en.html',         /the Participant must be at least (\d{1,2}) years of age/,        'участие']
];

const найдено = [], пропали = [];
МЕСТА.forEach(([ф, при, назначение]) => {
    const т = чит(ф);
    if (т === null) { пропали.push(ф + ' — файла нет'); return; }
    const м = т.match(при);
    if (!м) { пропали.push(ф + ' — фраза о возрасте исчезла'); return; }
    найдено.push({ ф, число: м[1], назначение });
});

правило('фраза о возрасте на месте во всех названных документах',
    пропали.length === 0,
    'Возраст пропал из: ' + пропали.join('; ') + '.\n' +
    'Якорь держится на САМОЙ ФРАЗЕ. Переписали её — правило перестало бы\n' +
    'сторожить документ МОЛЧА, и числа разъехались бы снова, как они и\n' +
    'разъехались на три: 13, 14 и 18.');

/* ── Внутри одного назначения число одно на все языки ───────────── */
['пользование', 'участие'].forEach(назначение => {
    const свои = найдено.filter(н => н.назначение === назначение);
    const числа = [...new Set(свои.map(н => н.число))];
    правило('возраст «' + назначение + '» одинаков во всех документах и на всех языках',
        числа.length <= 1,
        'Названо разных чисел: ' + числа.join(', ') + '.\n' +
        свои.map(н => '  ' + н.ф + ': ' + н.число).join('\n') + '\n\n' +
        'Один и тот же возраст, написанный по-разному на двух страницах, —\n' +
        'это два разных обещания. В Play Console и App Store подаётся одно\n' +
        'число, и анкета Data Safety строится от него.');
});

/* Решения. Меняются ОНИ — и правило ловит каждый документ, который за
   ними не пошёл. Пользование 14 — политика, утверждённая приказом № 1
   от 3 ноября 2026 (ч. 3 ст. 81). Участие 18 — слово Кости 27.10:
   «правильно будет 18 — если будет оплата в дальнейшем установлена». */
const РЕШЕНО = { 'пользование': '14', 'участие': '18' };
const мимо = найдено.filter(н => н.число !== РЕШЕНО[н.назначение]);
правило('возраст совпадает с решением по своему назначению',
    мимо.length === 0,
    'Решено: пользование ' + РЕШЕНО['пользование'] + ', участие ' + РЕШЕНО['участие'] + '.\n' +
    'Не совпадает:\n' +
    мимо.map(н => '  ' + н.ф + ' (' + н.назначение + '): ' + н.число).join('\n') + '\n\n' +
    'ЭТО ЖДЁТ ДОКУМЕНТОВ ОТ ЮРИСТА (06.11). Политика от 3 ноября говорит\n' +
    '«Сервис предназначен для лиц от 14 лет», а Условия на сайте — ещё\n' +
    'наш прежний текст со словом «18». Условия и Оферту юрист переписал,\n' +
    'Костя их пришлёт; до тех пор правило честно показывает расхождение,\n' +
    'а не закрашивает его.');

/* Пользоваться можно раньше, чем играть в турнирах, но не наоборот. */
const возр = н => parseInt(н.число, 10);
const польз = найдено.filter(н => н.назначение === 'пользование').map(возр);
const участ = найдено.filter(н => н.назначение === 'участие').map(возр);
правило('возраст пользования не больше возраста участия в турнирах',
    польз.length === 0 || участ.length === 0 || Math.max(...польз) <= Math.min(...участ),
    'Пользование: ' + польз.join(', ') + '; участие: ' + участ.join(', ') + '.\n' +
    'Если пользоваться можно позже, чем играть, то между документами\n' +
    'образуется возраст, в котором человек может заявиться на турнир, но\n' +
    'не может завести учётную запись.');

/* Приложение возраст не называет — и это нормально ровно до тех пор, пока
   оно не начнёт называть его САМО, мимо документов. */
const МОБ = [];
(function идти(д) {
    let сп = [];
    try { сп = fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }); } catch (e) { return; }
    сп.forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) идти(п); else if (/\.(js|html)$/.test(э.name)) МОБ.push(п);
    });
})('mobile/www');
const своё = МОБ.filter(ф => {
    const т = чит(ф) || '';
    /* БЕЗ \b ПОСЛЕ КИРИЛЛИЦЫ. `\b` в JS считает словом только ASCII, и
       между «лет» и «<» границы нет — признак молчал на «16 лет</p>».
       Поймал это собственный прувер: откат не уронил правило. */
    return /\d{1,2}\s*(?:жаштан|лет(?![а-яё])|years old|and older)/i.test(т);
});
правило('приложение не называет возраст само',
    своё.length === 0,
    'Приложение называет возраст само: ' + своё.join(', ') + '.\n' +
    'Тогда он обязан быть в этом же списке — иначе третья копия понятия\n' +
    'заживёт своей жизнью, как уже случилось с Условиями на трёх языках.');

const ВСЕГО = 6;
if (ошибки.length) {
    console.log('\n  ВОЗРАСТ — ПРАВИЛО УПАЛО (' + ошибки.length + ' из ' + ВСЕГО + ')\n');
    ошибки.forEach(о => { console.log('  x ' + о.имя); console.log('    ' + о.подсказка.split('\n').join('\n    ') + '\n'); });
    process.exit(1);
}
console.log('  v возраст по назначению: ' + ВСЕГО + ' правил, документов ' + найдено.length +
            ', пользование ' + РЕШЕНО['пользование'] + ', участие ' + РЕШЕНО['участие']);
