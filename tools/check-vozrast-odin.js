/**
 * ЗАМОРОЗКА «ВОЗРАСТ ОДИН НА ВЕСЬ ПРОДУКТ» (ветка Ю, кусок 189, 27.10.2026).
 *
 * ЗАМЕР 27.10. Запись Ю11 говорила: «в оферте 18+, в Условиях 14+».
 * ЗАМЕР НАШЁЛ ТРИ ЧИСЛА И ДВА МОЛЧАНИЯ:
 *
 *   документ    ru        en        kg
 *   Условия     14        13        13
 *   Оферта      18        18        молчит (пункта 4.5.2 в ней нет вовсе)
 *   Политика    молчит    молчит    молчит
 *   Приложение  молчит    молчит    молчит
 *
 * Прежний признак этого не увидел: он искал «число + лет/years/жаш», а
 * английское «aged 13 and older» и кыргызское «13 жаштан жогорку» пишут
 * число и слово иначе. ПРИЗНАК, ПОДОГНАННЫЙ ПОД ОДИН ЯЗЫК, МОЛЧИТ НА ДВУХ
 * ОСТАЛЬНЫХ.
 *
 * РЕШЕНИЕ КОСТИ 27.10: «правильно будет 18 — если будет оплата в
 * дальнейшем установлена». Условия сведены на 18 на трёх языках.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ, А НЕ ЧИСЛО: не «возраст равен 18», а «во всех
 * документах, где возраст назван, он ОДИН И ТОТ ЖЕ». Поменяется решение —
 * поменяется число в одном месте здесь, и правило поймает любой документ,
 * который за ним не пошёл.
 *
 *   node tools/check-vozrast-odin.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => { try { return fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'); } catch (e) { return null; } };
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* Где возраст назван и КАК он там написан — по одному якорю на язык.
   Якорь держится на СОДЕРЖИМОМ фразы, а не на номере строки. */
const МЕСТА = [
    ['pages/terms.html',    /Платформа доступна лицам, достигшим (\d{1,2}) лет/],
    ['pages/terms-en.html', /The platform is available to persons aged (\d{1,2}) and older/],
    ['pages/terms-kg.html', /Платформа (\d{1,2}) жаштан жогорку адамдар/],
    ['pages/offer.html',    /участник должен быть достигшим возраста (\d{1,2}) лет/],
    ['pages/offer-en.html', /the Participant must be at least (\d{1,2}) years of age/]
];

const найдено = [], пропали = [];
МЕСТА.forEach(([ф, при]) => {
    const т = чит(ф);
    if (т === null) { пропали.push(ф + ' — файла нет'); return; }
    const м = т.match(при);
    if (!м) { пропали.push(ф + ' — фраза о возрасте исчезла'); return; }
    найдено.push({ ф, число: м[1] });
});

правило('фраза о возрасте на месте во всех названных документах',
    пропали.length === 0,
    'Возраст пропал из: ' + пропали.join('; ') + '.\n' +
    'Якорь держится на САМОЙ ФРАЗЕ. Переписали её — правило перестало бы\n' +
    'сторожить документ МОЛЧА, и числа разъехались бы снова, как они и\n' +
    'разъехались на три: 13, 14 и 18.');

const числа = [...new Set(найдено.map(н => н.число))];
правило('во всех документах возраст ОДИН И ТОТ ЖЕ',
    числа.length <= 1,
    'Названо разных чисел: ' + числа.length + ' — ' + числа.join(', ') + '.\n' +
    найдено.map(н => '  ' + н.ф + ': ' + н.число).join('\n') + '\n\n' +
    'В Play Console и App Store подаётся ОДНО число, и анкета Data Safety\n' +
    'строится от него. Два числа в документах — это два разных обещания.');

/* Решение Кости 27.10. Меняется решение — меняется ЭТА строка, и правило
   ловит каждый документ, который за ней не пошёл. */
const РЕШЕНО = '18';
правило('возраст совпадает с решением',
    найдено.every(н => н.число === РЕШЕНО),
    'Решено ' + РЕШЕНО + ', а в документах: ' +
    найдено.map(н => н.ф.split('/').pop() + ' ' + н.число).join(', ') + '.');

/* Приложение возраст не называет — и это нормально ровно до тех пор, пока
   оно не начнёт называть его САМО, мимо документов. */
const МОБ = [];
(function идти(д) {
    let сп = [];
    try { сп = fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }); } catch (e) { return; }
    сп.forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) идти(п); else if (/\.(js|html)$/.test(э.name)) МОБ.push(п);
    });
})('mobile/www');
const своё = МОБ.filter(ф => {
    const т = чит(ф) || '';
    /* БЕЗ \b ПОСЛЕ КИРИЛЛИЦЫ. `\b` в JS считает словом только ASCII, и
       между «лет» и «<» границы нет — признак молчал на «16 лет</p>».
       Поймал это собственный прувер: откат не уронил правило. */
    return /\d{1,2}\s*(?:жаштан|лет(?![а-яё])|years old|and older)/i.test(т);
});
правило('приложение не называет возраст само',
    своё.length === 0,
    'Приложение называет возраст само: ' + своё.join(', ') + '.\n' +
    'Тогда он обязан быть в этом же списке — иначе третья копия понятия\n' +
    'заживёт своей жизнью, как уже случилось с Условиями на трёх языках.');

const ВСЕГО = 4;
if (ошибки.length) {
    console.log('\n  ВОЗРАСТ — ПРАВИЛО УПАЛО (' + ошибки.length + ' из ' + ВСЕГО + ')\n');
    ошибки.forEach(о => { console.log('  x ' + о.имя); console.log('    ' + о.подсказка.split('\n').join('\n    ') + '\n'); });
    process.exit(1);
}
console.log('  v возраст один: ' + ВСЕГО + ' правила, документов с возрастом ' +
            найдено.length + ', число ' + (числа[0] || '—'));
