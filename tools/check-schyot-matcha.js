#!/usr/bin/env node
/**
 * СЧЁТ МАТЧА: ВПИСАТЬ И ПОДТВЕРДИТЬ — ОДИН ДОМ (шаг A3.7г, 29.10).
 *
 * ЗАЧЕМ. `js/match-score.js` (366 строк) и `mobile/www/js/match-score.js`
 * (321) носили одно имя `KSLT_MATCH_SCORE` и жили двумя телами. Правила
 * счёта давно были общими (`buildScore`, `matchScoreState` в
 * `kslt-rules.js`), а вокруг них было написано дважды: сколько сетов
 * спрашивать, сбор пар из полей, зов `submit_match_score`, зовы
 * `confirm_match_score`/`dispute_match_score` и разбор кода ошибки.
 *
 * И НА ШВЕ УЖЕ РОДИЛАСЬ БЕДА: ветка `tied_set`/`bad_score`/`empty_score`
 * была только у сайта. В приложении человек с равными геймами в сете
 * видел общее «не удалось сохранить счёт» и не понимал, что исправить.
 * Этот сторож держит ветку в доме — одну на оба продукта.
 *
 * ЧТО ОСТАЁТСЯ ПРОДУКТУ: имена полей (`ms*` у сайта, `msa*` у
 * приложения), разметка окна, способ показать сообщение и сами слова.
 * Дом отдаёт КЛЮЧ, слово по ключу находит продукт.
 *
 * Запуск: node tools/check-schyot-matcha.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));
/* В css нет `//`, а запись о снятом классе ЖИВЁТ В КОММЕНТАРИИ: правило,
   искавшее слово `msa-toast` во всём файле, падало на моей же записи о
   том, что класс снят. ПРАВИЛО, СЧИТАЮЩЕЕ ТЕКСТ, ЛОВИТ СЛОВА, А НЕ БЕДУ. */
const безКомCss = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

const ДОМ = 'js/kslt-schyot-matcha.js';
const ДОМ_П = 'mobile/www/js/kslt-schyot-matcha.js';
const САЙТ = 'js/match-score.js';
const ПРИЛ = 'mobile/www/js/match-score.js';

console.log('\n  СЧЁТ МАТЧА — ОДИН ДОМ\n');

const дом = безКом(чит(ДОМ));

правило('дом объявлен и отдаёт все пять действий',
    /KSLT_SCHYOT_MATCHA/.test(дом) &&
    /API\.сетов\s*=/.test(дом) && /API\.собрать\s*=/.test(дом) &&
    /API\.ключОшибки\s*=/.test(дом) && /API\.вписать\s*=/.test(дом) &&
    /API\.ответить\s*=/.test(дом),
    'Нужны: `сетов`, `собрать`, `ключОшибки`, `вписать`, `ответить`.\n' +
    'Пропал кто-то один — продукт завёл его себе обратно.');

правило('копии дома побайтово равны',
    чит(ДОМ) === чит(ДОМ_П),
    'Разошлись — значит счёт матча снова живёт двумя жизнями.');

правило('число сетов знает только дом',
    /set_format\s*===\s*'short'/.test(дом),
    'Короткий формат — два сета, обычный — три. Разойдись это число,\n' +
    'один продукт собрал бы три сета, другой два, и счёт ОДНОГО матча\n' +
    'вышел бы разным.');

правило('ветка равных геймов живёт в доме',
    /tied_set/.test(дом) && /bad_score/.test(дом) && /empty_score/.test(дом) &&
    /errBad/.test(дом),
    'Это та самая беда, которая уже случилась: ветка была у сайта и не\n' +
    'было её в приложении.');

правило('дом отдаёт КЛЮЧ, а не слово',
    !/Не удалось сохранить|геймы в сете/.test(дом) && /ключ:/.test(дом),
    'Словарь у сайта свой (три языка), у приложения свой. Попади слово\n' +
    'в дом — перевод разошёлся бы с продуктом.');

правило('дом не знает имён полей разметки',
    !/'ms1s|'msa1s|msDate|msaDate/.test(дом),
    'Приставку даёт продукт: у сайта `ms`, у приложения `msa`. Имена\n' +
    'полей — забота разметки, а не правила.');

правило('дом не собирает счёт сам',
    /R\.buildScore\(/.test(дом) && !/replace\(\/\\\/\/g/.test(дом),
    'Сборка строки счёта — дом правил `kslt-rules.js`. Своя арифметика\n' +
    'здесь была бы ВТОРЫМ определением одного понятия.');

/* ПРАВИЛО ДЕРЖИТСЯ НА ЗОВЕ, А НЕ НА СЛОВЕ `console.error`: сторож,
   искавший слово, не упал от отката — слово осталось в условии строкой
   выше (`if (global.console && console.error)`). Промах поймал прувер. */
правило('без дома правил дом не пишет в базу и говорит вслух',
    /console\.error\(\s*'KSLT_SCHYOT_MATCHA/.test(дом) &&
    /!R\s*\|\|\s*!R\.buildScore/.test(дом),
    'Тихий отказ выглядел бы как «база не ответила». Дом обязан сказать,\n' +
    'что счёт НЕ ОТПРАВЛЕН и почему.');

[[САЙТ, 'сайта', 'ms'], [ПРИЛ, 'приложения', 'msa']].forEach(([ф, имя, приставка]) => {
    const т = безКом(чит(ф));

    правило('у ' + имя + ' нет своего числа сетов',
        !/set_format\s*===\s*'short'/.test(т),
        'Число переехало в дом. Осталось на месте — два определения.');

    правило('у ' + имя + ' нет своего зова базы',
        !/rpc\(\s*'submit_match_score'/.test(т) &&
        !/'confirm_match_score'/.test(т) && !/'dispute_match_score'/.test(т),
        'Зовы переехали в дом. Это КНОПКИ, КОТОРЫЕ ПИШУТ В БАЗУ: два\n' +
        'способа звать одно — два места, где может разойтись формат.');

    правило('у ' + имя + ' нет своего зова сборки счёта',
        !/buildScore\(/.test(т),
        '`buildScore` зовёт дом — иначе проверка «геймы не равны» стоит\n' +
        'в продукте, и один продукт может её потерять, как и было.');

    правило('у ' + имя + ' нет своего разбора кода ошибки',
        !/own_score|already_final|not_a_player|no_winner/.test(т),
        'Коды базы разбирает дом. Продукт знает только КЛЮЧИ.');

    /* ЗОВ ИЩЕТСЯ ПО ДЕЙСТВИЮ, А НЕ ПО ПОЛНОМУ ИМЕНИ: оба продукта берут
       дом в короткое `SM`, и правило, искавшее `KSLT_SCHYOT_MATCHA.собрать`,
       не нашло `SM.собрать` — промах сторожа, поймал прувер. */
    правило('у ' + имя + ' дом зовётся на все четыре',
        /KSLT_SCHYOT_MATCHA/.test(т) &&
        /\.сетов\(/.test(т) && /\.собрать\(/.test(т) &&
        /\.вписать\(/.test(т) && /\.ответить\(/.test(т),
        'Без зова работа не сделана.');

    /* ПРАВИЛО СУЖЕНО ДО ЗОВА СБОРКИ (29.10): приставка `'ms'` встречается
       теперь и в зове показа полей тай-брейка, поэтому «есть ли такая
       строка в файле» перестало что-либо доказывать — откат его не
       уронил. Проверяем, что приставка приходит ИМЕННО в сборку пар. */
    правило('у ' + имя + ' своя приставка полей осталась',
        new RegExp("\\.собрать\\(поле, '" + приставка + "',").test(т),
        'Приставку даёт продукт — у сайта `ms`, у приложения `msa`.\n' +
        'Пропала — поля собираются не те, и счёт уйдёт пустым.');

    правило('у ' + имя + ' слово берётся ПО КЛЮЧУ из дома',
        /слово\(\s*итог\.ключ\s*\)/.test(т) && /function\s+слово\s*\(/.test(т),
        'Дом отдаёт ключ. Продукт обязан искать слово ИМЕННО по нему, а не\n' +
        'подставлять одно общее сообщение на все беды.');
});

/* У САЙТА СЛОВА ЖИВУТ В СВОЁМ ФАЙЛЕ, У ПРИЛОЖЕНИЯ — В СВОЁМ: правило,
   искавшее `errBad` в теле `js/match-score.js`, падало впустую — слова
   сайта лежат в `js/match-score-texts.js`, по словарю на каждый язык. */
правило('у сайта слово errBad есть на всех трёх языках',
    (чит('js/match-score-texts.js').match(/errBad:/g) || []).length === 3,
    'Словарей три — русский, английский, кыргызский. Нет слова в одном —\n' +
    'человек на этом языке увидит пустоту вместо подсказки.');

правило('у приложения слова ошибок перечислены полным списком',
    (function () {
        const т = безКом(чит(ПРИЛ));
        return ['errOwn', 'errFinal', 'errNotPlayer', 'errNoWinner', 'errBad', 'err']
            .every(к => new RegExp('\\b' + к + ':').test(т));
    })(),
    'Пропущенный ключ отдаст запасное «не удалось сохранить счёт» — ровно\n' +
    'та дыра, из-за которой этот кусок и делался.');

/* ОДНО УВЕДОМЛЕНИЕ НА ПРОДУКТ — требование компонента Toast 30:59:
   «four separate notification mechanisms… should all render this one
   component». В окне счёта приложения стояла ВТОРАЯ полоска (`msa-toast`),
   мёртвая по проверке и уже отъехавшая кеглем и z-index. */
правило('у приложения полоску сообщения рисует одно место',
    !/msa-toast/.test(безКом(чит(ПРИЛ))) &&
    /KSLT_APP\.toast/.test(безКом(чит(ПРИЛ))) &&
    !/msa-toast/.test(безКомCss(чит('mobile/www/css/app.css'))),
    'Вторая копия уведомления в окне счёта — и она уже один раз тихо\n' +
    'разошлась с первой по кеглю, радиусу и z-index.');

правило('дом подключён во всех разметках, где подключён счёт',
    ['mobile/www/index.html', 'pages/dashboard.html', 'pages/dashboard-en.html',
     'pages/dashboard-kg.html', 'pages/tournament.html', 'pages/tournament-en.html',
     'pages/tournament-kg.html'].every(ф =>
        !/match-score\.js/.test(чит(ф)) || /kslt-schyot-matcha\.js/.test(чит(ф))),
    'Страница грузит окно счёта без дома — кнопка «Отправить счёт» упадёт\n' +
    'на `undefined`, и счёт не уйдёт никуда.');

правило('дом грузится ДО того, кто его зовёт',
    ['mobile/www/index.html', 'pages/dashboard.html', 'pages/tournament.html']
        .every(ф => {
            const t = чит(ф);
            const д = t.indexOf('kslt-schyot-matcha.js');
            const з = t.indexOf('match-score.js?');
            return д !== -1 && з !== -1 && д < з;
        }),
    'Порядок ставится явно, а не на удачу тайминга.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else { console.log('  ок      счёт матча: все ' + держится + ' правил держатся\n'); }
