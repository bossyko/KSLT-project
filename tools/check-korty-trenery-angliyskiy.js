/**
 * ЗАМОРОЗКА АНГЛИЙСКОЙ ВЕТКИ КОРТОВ И ТРЕНЕРОВ. 12.10, кусок 63-й.
 *
 * ЧТО БЫЛО. `js/courts.js` и `js/coaches.js` — ДВА последних файла
 * продукта, строивших словарь как `window.xLabels || (isKg ? {kg} : {ru})`:
 * ветки `isEn` не было вовсе, и английская страница отдавала РУССКИЙ
 * словарь при `<html lang="en">`. Замер 12.10 на 390: 58 русских узлов из
 * 110 видимых плюс 28 русских атрибутов.
 *
 * ЧТО ЗАМОРАЖИВАЕТСЯ — ОТНОШЕНИЯ, А НЕ СТРОКИ:
 *   • у словаря ТРИ ветки, и состав ключей во всех трёх ОДИНАКОВ —
 *     перевод, забытый в одной ветке, роняет правило;
 *   • в английской ветке нет кириллицы ВООБЩЕ;
 *   • покрытие названо ОДИН раз: карта, выбранная по языку. Было дважды —
 *     картами SURFACE_MAP* и ключами filterHard/filterClay в словаре;
 *   • подпись опыта на карточке и на странице — РАЗНЫЕ ключи: полная не
 *     влезает в карточку (замер: 53.4 против 103.3);
 *   • раскрывашка говорит диктору, что она раскрывашка и открыта ли она;
 *   • выбранный пункт меню отличается не только краской — `Menu item 32:44`;
 *   • фокус виден: правило есть в общем файле, и оно покрывает чипы,
 *     карточки и ОБЩУЮ полосу страниц;
 *   • версия файла одна на весь продукт — админка отставала на две.
 *
 *   node tools/check-korty-trenery-angliyskiy.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const acorn = require('acorn');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const КОРТЫ = безКом(чит('js/courts.js'));
const ТРЕНЕРЫ = безКом(чит('js/coaches.js'));
const ОБЩИЙ = безКом(чит('css/style.css'));
const CSS_К = безКом(чит('css/courts.css'));

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };

/** Три ветки словаря: en · kg · ru. Возвращает списки ключей.
 *
 * ЧИТАЕТСЯ ДЕРЕВО, А НЕ СКОБКИ. До 23.10 ветки искались подстроками
 * `var L = isEn ? {`, `} : (isKg ? {`, `} : {`. Кусок 137 свёл тройку к
 * одному зову `KSLT_YAZYK.выбрать(en, kg, ru)` — и разбор возвращал
 * `null`, то есть «английской ветки нет». Правило упало на словаре,
 * который на месте и цел: ЯКОРЬ НА ФОРМУ ЖИВЁТ РОВНО ДО СМЕНЫ ФОРМЫ.
 * Парсер отдаёт три довода зова как три объекта, и порядок доводов
 * (английский, кыргызский, русский) ему известен из дома языка. */
function ветки(текст, перем) {
    let д;
    try { д = acorn.parse(текст, { ecmaVersion: 2020 }); } catch (e) { return null; }
    let найдено = null;
    (function обход(у) {
        if (!у || typeof у.type !== 'string' || найдено) return;
        if (у.type === 'VariableDeclarator' && у.id && у.id.name === перем &&
            у.init && у.init.type === 'CallExpression' && у.init.callee &&
            текст.slice(у.init.callee.start, у.init.callee.end) === 'KSLT_YAZYK.выбрать' &&
            у.init.arguments.length === 3 &&
            у.init.arguments.every(a => a.type === 'ObjectExpression')) {
            найдено = у.init.arguments;
            return;
        }
        for (const к of Object.keys(у)) {
            if (к === 'type' || к === 'start' || к === 'end' || к === 'loc') continue;
            const v = у[к];
            if (Array.isArray(v)) v.forEach(x => x && typeof x.type === 'string' && обход(x));
            else if (v && typeof v.type === 'string') обход(v);
        }
    })(д);
    if (!найдено) return null;
    const ключи = о => о.properties.map(с => с.key && (с.key.name || с.key.value)).filter(Boolean);
    return {
        en: ключи(найдено[0]),
        kg: ключи(найдено[1]),
        ru: ключи(найдено[2]),
        телоEn: текст.slice(найдено[0].start, найдено[0].end)
    };
}

/* ══ 1. ТРИ ВЕТКИ, ОДИН СОСТАВ ═════════════════════════════════════════ */

[['корты', КОРТЫ, 'L_labels'], ['тренеры', ТРЕНЕРЫ, 'L']].forEach(([имя, текст, перем]) => {
    const в = ветки(текст, перем);
    правило('у словаря «' + имя + '» есть английская ветка',
        в !== null,
        'словарь снова строится как `isKg ? {kg} : {ru}` — английская страница\n' +
        '          получит РУССКИЙ словарь при lang="en". Так было до 12.10');
    if (!в) return;

    const наборEn = new Set(в.en), наборKg = new Set(в.kg), наборRu = new Set(в.ru);
    const нетВEn = в.ru.filter(к => !наборEn.has(к));
    const нетВKg = в.ru.filter(к => !наборKg.has(к));
    const лишнее = в.en.filter(к => !наборRu.has(к));

    правило('состав ключей «' + имя + '» одинаков во всех трёх ветках',
        нетВEn.length === 0 && нетВKg.length === 0 && лишнее.length === 0,
        'ветки разъехались. Нет в en: ' + (нетВEn.join(', ') || '—') +
        '; нет в kg: ' + (нетВKg.join(', ') || '—') +
        '; лишнее в en: ' + (лишнее.join(', ') || '—'));

    const строкиСкириллицей = в.телоEn.split('\n').filter(с => /[А-Яа-яЁё]/.test(с));
    правило('в английской ветке «' + имя + '» нет кириллицы',
        строкиСкириллицей.length === 0,
        'кириллица в английском словаре: ' + строкиСкириллицей.slice(0, 2).map(с => с.trim()).join(' | '));
});

/* ══ 2. ОДНО ОПРЕДЕЛЕНИЕ ПОКРЫТИЯ ══════════════════════════════════════ */

/* ЯКОРЬ НА СОДЕРЖИМОЕ: карта называется по именам всех трёх карт в
   одном зове — так же, как прежде называлась в тернарнике. */
правило('покрытие выбирается по языку ОДНОЙ картой',
    /var ПОКРЫТИЯ = KSLT_YAZYK\.выбрать\(SURFACE_MAP_EN, SURFACE_MAP_KG, SURFACE_MAP\)/.test(КОРТЫ),
    'карта ПОКРЫТИЯ снята. Покрытие снова будет названо дважды — картами\n' +
    '          SURFACE_MAP* и ключами filterHard/filterClay словаря');

правило('выбор языка покрытия не повторяется по файлу',
    (КОРТЫ.match(/isEn \? \(SURFACE_MAP_EN/g) || []).length === 0 &&
    (КОРТЫ.match(/выбрать\(SURFACE_MAP_EN/g) || []).length === 1,
    'вернулся поштучный выбор `isEn ? SURFACE_MAP_EN[...] : ...`. Таких мест\n' +
    '          было четыре, и они расходились бы при правке по одному');

/* ══ 3. ПОДПИСЬ ОПЫТА — РАЗНАЯ ПО МЕСТУ ════════════════════════════════ */

/* Спрашиваем ключ В АНГЛИЙСКОЙ ВЕТКЕ, а не «где-нибудь в файле»: именно
   там он и нужен, и именно там его легче всего забыть. Прувер показал
   разницу — откат, убравший ключ только из английской ветки, прежнее
   правило не ронял вовсе. */
const веткиТренеров = ветки(ТРЕНЕРЫ, 'L');
правило('у подписи опыта есть короткая и полная запись в английской ветке',
    веткиТренеров !== null &&
    /experience:\s*"years"/.test(веткиТренеров.телоEn) &&
    /experienceFull:\s*"years of experience"/.test(веткиТренеров.телоEn),
    'ключ experienceFull снят или совпал с коротким. На карточке самое узкое\n' +
    '          место: замер 12.10 дал «лет опыта» 53.4 против\n' +
    '          «years of experience» 103.3 — почти вдвое');

правило('карточка берёт короткую подпись, страница — полную',
    /co-card-stat-label">' \+ L\.experience \+/.test(ТРЕНЕРЫ) &&
    /co-detail-stat-label">' \+ L\.experienceFull \+/.test(ТРЕНЕРЫ),
    'карточка и страница снова берут одну подпись — та, что влезает в\n' +
    '          страницу, не влезает в карточку');

/* ══ 4. ЧТО ЧИТАЕТ ДИКТОР ══════════════════════════════════════════════ */

правило('раскрывашка называет себя раскрывашкой',
    /aria-haspopup="listbox" aria-expanded="false"/.test(КОРТЫ),
    'без aria-haspopup и aria-expanded это просто кнопка с непонятным словом');

правило('aria-expanded переключается при открытии И при закрытии',
    /toggle\.setAttribute\('aria-expanded', String\(!wasOpen\)\)/.test(КОРТЫ) &&
    /к\.setAttribute\('aria-expanded', 'false'\)/.test(КОРТЫ),
    'состояние обновляется не везде: диктор и экран разойдутся на первом же\n' +
    '          закрытии «кликом мимо» или выбором пункта');

правило('у выбранного пункта меню есть галочка, а не только краска',
    /ct-dd-tick/.test(КОРТЫ) && /aria-current="true"/.test(КОРТЫ),
    'Menu item 32:44: «never rely on the tint alone, it is invisible to\n' +
    '          anyone who cannot separate the two greys»');

/* ══ 5. ФОКУС ВИДЕН, И ПРАВИЛО ЖИВЁТ В ОБЩЕМ ФАЙЛЕ ═════════════════════ */

правило('фокус виден у чипов, карточек и ОБЩЕЙ полосы страниц',
    /\.ct-dd-toggle:focus-visible/.test(ОБЩИЙ) &&
    /\.pl-page-btn:focus-visible/.test(ОБЩИЙ) &&
    /\.ct-card:focus-visible/.test(ОБЩИЙ) &&
    /\.co-card:focus-visible/.test(ОБЩИЙ),
    'до 12.10 слова focus-visible не было ни в courts.css, ни в coaches.css,\n' +
    '          и фокус не показывался вовсе. Полоса ОБЩАЯ: правило чинит и\n' +
    '          рейтинг, и новости, и кабинет');

/* ══ 6. МЕЖСТРОЧНЫЕ НА СТУПЕНЯХ ════════════════════════════════════════ */

const ЛЕСТНИЦА = ['1', '1.1', '1.3', '1.5', '1.65'];

/* Правило спрашивает КАРТОЧКУ, а не весь файл. Мимо лестницы в courts.css
   осталось ещё три места — `.ct-membership-modal p` 1.6, `.ct-about-text`
   1.8/1.55 и `.ct-cta p` 1.35: это окно членства и страница отдельного
   корта, они в куске 63 не мерены и вслепую не трогались. Записаны
   находкой. Сторож на весь файл поставил бы меня перед выбором «тронуть
   непромеренное или ослабить правило», а это и есть то, чего делать
   нельзя. */
const тело = сел => {
    const i = CSS_К.indexOf(сел + ' {');
    if (i === -1) return '';
    const j = CSS_К.indexOf('}', i);
    return j === -1 ? '' : CSS_К.slice(i, j);
};
const межстрочныйУ = сел => {
    const m = тело(сел).match(/line-height:\s*([\d.]+);/);
    return m ? m[1] : null;
};

[['.ct-card-name', '1.3'], ['.ct-card-type', '1.5'], ['.ct-card-price', '1.5']].forEach(([сел, ждём]) => {
    const з = межстрочныйУ(сел);
    правило('межстрочный ' + сел + ' стоит на ступени лестницы',
        з !== null && ЛЕСТНИЦА.includes(з),
        'у ' + сел + ' межстрочный ' + з + ', а ступеней всего пять:\n' +
        '          1 · 1.1 · 1.3 · 1.5 · 1.65. До 12.10 здесь стояли 1.25 и 1.4');
});

/* ══ 7. ВЕРСИИ — ОДНА НА ВЕСЬ ПРОДУКТ, ВКЛЮЧАЯ АДМИНКУ ═════════════════ */

const СТРАНИЦЫ = fs.readdirSync(path.join(КОРЕНЬ, 'pages'))
    .filter(ф => ф.endsWith('.html'))
    .map(ф => ({ имя: ф, текст: чит('pages/' + ф) }));

/* ПРАВИЛО СЧИТАЛО ПО ПОДСТРОКЕ, И ЭТО 23-й СЛУЧАЙ. `courts.js?v=` ловит и
   `js/courts.js`, и `js/admin/sections/courts.js` — РАЗНЫЕ файлы. Пока обе
   версии случайно совпадали (28 и 28), правило было зелёным; 13.10 публичный
   файл уехал на 29, и оно упало на честном коде. Считаем по ПОЛНОМУ адресу:
   у каждого файла своя версия, одна на все страницы. Намерение то же —
   «админка не грузит старый код», — а подстрочной склейки больше нет. */
['courts.js', 'coaches.js', 'courts.css', 'coaches.css'].forEach(файл => {
    const поАдресу = new Map();
    СТРАНИЦЫ.forEach(с => {
        const re = new RegExp('(?:\\.\\./)?((?:[\\w./-]*?)' + файл.replace('.', '\\.') + ')\\?v=(\\d+)', 'g');
        let m;
        while ((m = re.exec(с.текст))) {
            const адрес = m[1].replace(/^\.\.\//, '');
            if (!поАдресу.has(адрес)) поАдресу.set(адрес, new Set());
            поАдресу.get(адрес).add(m[2]);
        }
    });
    поАдресу.forEach((версии, адрес) => {
        правило('версия ' + адрес + ' одна на все страницы, включая админку',
            версии.size === 1,
            'разные версии: ' + [...версии].join(', ') + '. 12.10 админка грузила\n' +
            '          courts.js v24 при v26 на страницах — работала по старому коду');
    });
});

if (ошибки.length === 0) {
    console.log(`\n  ок      английская ветка кортов и тренеров: ${ВСЕГО} правил\n`);
    process.exit(0);
}
console.log(`\n  НЕ ТАК  английская ветка кортов и тренеров: ${ВСЕГО} правил, упало ${ошибки.length}.\n`);
ошибки.forEach(о => {
    console.log(`  ✗ ${о.имя}`);
    if (о.подсказка) console.log(`          ${о.подсказка}`);
    console.log('');
});
process.exit(1);
