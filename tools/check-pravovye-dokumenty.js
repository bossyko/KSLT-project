function мера(т, якорь) {
    return {
        разделов:    (т.match(/<details/g) || []).length,
        пунктов:     (т.match(/<strong>\d{1,2}\.\d{1,2}\.<\/strong>/g) || []).length,
        строкТаблиц: (т.match(/<tr/g) || []).length,
        ячеек:       (т.match(/<td/g) || []).length,
        списка:      (т.match(/<li/g) || []).length,
        якорей:      (т.match(new RegExp('id="' + якорь + '-\\d+"', 'g')) || []).length
    };
}

function телоСтраницы(ф) {
    const т = чит(ф);
    if (т === null) return null;
    const от = т.indexOf('data-document');
    const до = т.indexOf('</main>', от);
    if (от === -1 || до === -1) return null;
    return т.slice(от, до);
}

