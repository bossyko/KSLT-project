#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ШТОРКА ПРИЛОЖЕНИЯ — ОДИН ДОМ, ОДНА ПОВЕРХНОСТЬ» (06.11).
 *
 * ЗАЧЕМ ОН ЕСТЬ — СЛУЧАЙ, А НЕ ОПАСЕНИЕ. Окно с классом `pd-h2h-modal`
 * собиралось ТРЕМЯ руками (`screens/player-detail.js` дважды и
 * `screens/profile.js` один раз), и к 06.11 они разошлись:
 *   · роль `dialog` и `aria-modal` ставила руками ОДНА из трёх — и это
 *     был дубль, их ставит `kslt-okno.js` по классу `open`;
 *   · `type="button"` и `aria-label` у кнопки закрытия были у ОДНОЙ;
 *   · заголовок «Head-to-Head» был зашит по-английски ПРИ ЖИВОМ КЛЮЧЕ
 *     словаря `pd.h2h` — «Личные встречи».
 *
 * И ПОВЕРХНОСТЬ ОКНА БЫЛА ОПРЕДЕЛЕНА ТРИЖДЫ. Замер 06.11: шторка
 * 10,10,10 (`--bg`, тот же цвет, что страница под ней), окно возврата
 * 17,17,17, онбординг 30,30,30. При этом в `tokens.css` у
 * `--bg-elevated` стоит пояснение «модалка, дропдаун, поповер» —
 * ОПРЕДЕЛЕНИЕ БЫЛО, А ЧИТАЛО ЕГО ОДНО ОКНО ИЗ ТРЁХ.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ, И ЭТО НАЗВАНО. Прибор читает ФАЙЛ КАК ТЕКСТ: он не
 * видит, что выйдет на экране. Это работа пробы
 * `tests/e2e/features/41-shtorka.spec.js`.
 *
 *   node tools/check-shtorka.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ПАПКА = 'mobile/www/js';
const ДОМ = 'mobile/www/js/kslt-shtorka.js';
const ОДЕЖДА = 'mobile/www/css/app.css';

function читать(о) {
    const п = path.join(КОРЕНЬ, о);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function безКомментариев(т) {
    return т.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1 ');
}
function файлы(д, вых) {
    вых = вых || [];
    const п = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(п)) return вых;
    for (const э of fs.readdirSync(п, { withFileTypes: true })) {
        const о = д + '/' + э.name;
        if (э.isDirectory()) { if (э.name !== 'vendor') файлы(о, вых); }
        else if (э.name.endsWith('.js')) вых.push(о);
    }
    return вых;
}
/* Объявления класса в одежде, с комментариями, снятыми заранее. */
function объявления(т, селектор) {
    const без = т.replace(/\/\*[\s\S]*?\*\//g, ' ');
    const re = /([^{}]+)\{([^{}]*)\}/g;
    let м; const вых = [];
    while ((м = re.exec(без))) {
        if (м[1].split(',').some(s => s.trim() === селектор)) вых.push(м[2]);
    }
    return вых.join(' ');
}

const домТекст = безКомментариев(читать(ДОМ) || '');
const одежда = читать(ОДЕЖДА) || '';

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

/* ── 1. шторку собирает один дом ── */
const собирают = файлы(ПАПКА).filter(ф =>
    /className\s*=\s*['"]pd-h2h-modal['"]/.test(безКомментариев(читать(ф) || '')));
правило('шторку собирает один дом',
    собирают.length === 1 && собирают[0] === ДОМ,
    'Класс `pd-h2h-modal` присваивается в ' + собирают.length + ' местах:' +
    собирают.map(ф => '\n  ' + ф).join('') +
    '\nОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. Три руки уже расходились по\n' +
    'роли, по подписи кнопки и по языку заголовка — беда рождалась ровно\n' +
    'на шве, и до неё оставался один новый вызов.');

/* ── 2. роль ставит дом окон, а не разметка шторки ── */
правило('роль диалога ставит дом окон, а не шторка',
    !/role\s*=\s*["']dialog["']|aria-modal/.test(домТекст),
    'В ' + ДОМ + ' разметка сама ставит роль или `aria-modal`. Их ставит\n' +
    '`kslt-okno.js` по классу `open` — вместе с подписью, уводом фокуса,\n' +
    'Tab и Esc. Два диалога друг в друге диктор читает как вложенные.');

/* ── 3. открывается по часам, а не по кадру ── */
правило('класс открытия вешается по часам, а не по кадру',
    !/requestAnimationFrame[\s\S]{0,120}classList\.add\(\s*'open'\s*\)/.test(домТекст),
    'Класс `open` вешается из `requestAnimationFrame`. СВЁРНУТОЕ\n' +
    'ПРИЛОЖЕНИЕ КАДРОВ НЕ РИСУЕТ, и кадр может не прийти вовсе — окно\n' +
    'останется прозрачным. Правило выведено на окне возврата учётной\n' +
    'записи и применяется здесь без нового разбора.');

/* ── 4. прежнее окно снимает класс перед удалением ── */
function удаляютБезСнятия(т) {
    const вых = [];
    const re = /([A-Za-zА-Яа-яЁё_$][\wА-Яа-яЁё$]*)\.remove\(\)/g;
    let м;
    while ((м = re.exec(т))) {
        const узел = м[1];
        const до = т.slice(Math.max(0, м.index - 200), м.index);
        if (!new RegExp(узел + "\\.classList\\.remove\\(\\s*'open'\\s*\\)").test(до)) вых.push(узел);
    }
    return вых;
}
правило('прежняя шторка снимает класс open перед удалением',
    удаляютБезСнятия(домТекст).length === 0,
    'Узел удаляется из дерева, не сняв класс `open`. Дом окон ведёт\n' +
    'стопку открытых и чистит её по снятию класса — выдернутый узел\n' +
    'остаётся в ней навсегда, и Esc потом закрывает мёртвое окно.');

/* ── 5. поверхность окна — один токен на все окна ── */
const ПОВЕРХНОСТИ = ['.pd-h2h-content', '.ar-modal', '.onb-card'];
const мимоТокена = ПОВЕРХНОСТИ.filter(с =>
    !/background\s*:\s*var\(\s*--bg-elevated\s*\)/.test(объявления(одежда, с)));
правило('поверхность окна — токен, который сам себя подписывает',
    мимоТокена.length === 0,
    'Мимо `--bg-elevated` стоят: ' + мимоТокена.join(', ') + '.\n' +
    'В `tokens.css` у этого токена написано «модалка, дропдаун,\n' +
    'поповер». Замер 06.11 нашёл три разных фона у трёх окон, и один из\n' +
    'них совпадал с фоном страницы под окном.');

/* ── 6. цели нажатия в окнах ── */
const цели = [['.pd-h2h-close', /(width|min-height|height)\s*:\s*44px/],
              ['.onb-skip', /min-height\s*:\s*44px/]];
const мелкие = цели.filter(([с, re]) => !re.test(объявления(одежда, с))).map(([с]) => с);
правило('кнопки в окнах не мельче ступени 44',
    мелкие.length === 0,
    'Мельче 44: ' + мелкие.join(', ') + '.\n' +
    'Замер 06.11: кнопка закрытия шторки 28x28, «Пропустить» в\n' +
    'онбординге 33 — и ниже нижней ступени, и мимо шкалы кнопок\n' +
    '(28 · 36 · 44 · 52). Высота там не задавалась, а получалась.');

/* ── 7. заголовок из словаря, а не зашит ── */
/* СЛОВАРЬ ИЗ ПОИСКА ИСКЛЮЧЁН, И ЭТО НЕ ПОБЛАЖКА: `js/i18n.js` — ЕДИНСТВЕННОЕ
   МЕСТО, ГДЕ АНГЛИЙСКАЯ НАДПИСЬ ЗАКОННА, там она и лежит как перевод
   ключа `pd.h2h`. Прибор без этого исключения падал на самом словаре —
   то есть требовал убрать перевод вместо того, чтобы требовать его
   использовать. */
const СЛОВАРЬ = ПАПКА + '/i18n.js';
const зашитые = файлы(ПАПКА)
    .filter(ф => ф !== СЛОВАРЬ)
    .filter(ф => /Head-to-Head|Head to Head/.test(безКомментариев(читать(ф) || '')));
правило('заголовок личных встреч берётся из словаря',
    зашитые.length === 0,
    'Английская надпись зашита в ' + зашитые.join(', ') + '.\n' +
    'Приложение одноязычное, и ключ `pd.h2h` («Личные встречи») жив с\n' +
    'самого начала. НАДПИСЬ МИМО СЛОВАРЯ ПРИ ЖИВОМ КЛЮЧЕ — ЭТО ВТОРОЕ\n' +
    'определение одного понятия, и расходятся они молча.');

/* ── 8. самопроверка ── */
правило('прибор не принимает комментарий за код',
    (function () {
        const о = '/* тут про className = "pd-h2h-modal" и про Head-to-Head */\n' +
                  '// и про role="dialog"\n' +
                  'var a = 1;\n';
        const б = безКомментариев(о);
        return !/pd-h2h-modal/.test(б) && !/Head-to-Head/.test(б) && !/role/.test(б);
    })(),
    'Образец внутри прибора: все сторожимые слова, но в комментариях.\n' +
    'В этих самых файлах объяснено, почему так сделано, — прибор,\n' +
    'читающий объяснение как улику, красен на верном коде.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      шторка: все ' + всего + ' правил держатся');
    console.log('          дом один — ' + ДОМ);
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  шторка — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
