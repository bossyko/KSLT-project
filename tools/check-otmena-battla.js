/**
 * ЗАМОРОЗКА «ОТМЕНА — СОСТОЯНИЕ, А НЕ ОСОБЫЙ СЛУЧАЙ» (06.11).
 *
 * ЗАЧЕМ ОН ЕСТЬ — СЛУЧАЙ, А НЕ ОПАСЕНИЕ. Найдено 30.10, взято 06.11:
 *   · `cast_battle_vote` не проверяла статус — голос за ОТМЕНЁННЫЙ
 *     баттл принимался и ложился в `challenge_predictions` навсегда.
 *     ЭКРАН — НЕ ЗАПРЕТ: запрос можно послать и мимо экрана;
 *   · три списка (`js/battles-overview.js`, `mobile/.../home.js`,
 *     `mobile/.../battles.js`) брали всё опубликованное, а слова
 *     `cancelled` в отрисовке карточек не было ни в одном: человек
 *     видел живую с виду карточку, нажимал — и попадал на «Баттл
 *     отменён»;
 *   · ПРИЧИНА БЫЛА ГЛУБЖЕ ТРЁХ СПИСКОВ. Дом состояния `BF.state` знал
 *     ТРИ состояния — upcoming, live, done, — и отмены среди них не
 *     было, при том что в продукте этот статус проверяется 24 раза.
 *     А в приложении дома состояния не было ВООБЩЕ.
 *
 * ЧТО ЗАМОРОЖЕНО. Не «на карточке есть метка» — это следствие, — а то,
 * из чего оно следует: отмена есть в доме, дом один на два продукта,
 * экраны спрашивают дом, а не сравнивают строки, и запрет стоит в базе.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ, И ЭТО НАЗВАНО. Прибор читает ФАЙЛЫ КАК ТЕКСТ: он не
 * знает, что в базе функция и вправду заменена (это показал прогон
 * Кости: `zapret_stoit = true`), и не видит, как метка встала на экране
 * — это работа пробы `tests/e2e/features/42-otmenyonnyy-battl.spec.js`.
 *
 *   node tools/check-otmena-battla.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ДОМ_САЙТА = 'js/battle-format.js';
const ДОМ_ПРИЛОЖЕНИЯ = 'mobile/www/js/battle-format.js';
const ФУНКЦИЯ = 'sql/функции/battle-vote-rpc.sql';
/* СПИСКИ БАТТЛОВ. `home.js` сюда не входит нарочно: в нём живут и
   МАТЧИ турнира, у которых свой `m.status === 'cancelled'` — другое
   понятие с тем же словом. Прибор, запретивший слово целиком, назвал бы
   бедой верный код сетки плей-офф; поэтому экран баттла в `home.js`
   проверяется отдельным правилом — по тому, что он СПРАШИВАЕТ ДОМ. */
const ЭКРАНЫ = [
    'js/battles-overview.js',
    'mobile/www/js/screens/battles.js'
];
const ГЛАВНАЯ = 'mobile/www/js/screens/home.js';

function читать(о) {
    const п = path.join(КОРЕНЬ, о);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function безКомментариев(т) {
    return т.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1 ');
}

const домСайта = читать(ДОМ_САЙТА);
const домПрил = читать(ДОМ_ПРИЛОЖЕНИЯ);
const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('отмена — состояние в доме, а не случай на экране',
    !!домСайта && /return\s+'cancelled'/.test(безКомментариев(домСайта)) &&
    /isCancelled/.test(безКомментариев(домСайта)),
    'В ' + ДОМ_САЙТА + ' состояние `cancelled` не возвращается или нет\n' +
    '`BF.isCancelled`. Пока отмена не состояние, каждый экран решает про\n' +
    'неё сам — а их три, и сравнение со строкой в трёх местах это три\n' +
    'места, где можно опечататься и где правка доедет не до всех.');

правило('отмена стоит в доме РАНЬШЕ завершения',
    (function () {
        const т = безКомментариев(домСайта || '');
        const о = т.indexOf("'cancelled'");
        const з = т.indexOf("=== 'completed'");
        return о > -1 && з > -1 && о < з;
    })(),
    'Проверка `cancelled` стоит ПОСЛЕ проверки `completed`.\n' +
    'ОТМЕНЁННЫЙ БАТТЛ НЕ СТАНОВИТСЯ СЫГРАННЫМ ОТТОГО, ЧТО ЕГО ВРЕМЯ\n' +
    'ПРОШЛО. Порядок здесь — это правило, а не вкус.');

правило('дом состояния один на два продукта',
    !!домСайта && !!домПрил && домСайта === домПрил,
    !домПрил
        ? 'В приложении нет ' + ДОМ_ПРИЛОЖЕНИЯ + '. До 06.11 правила\n' +
          'состояния там не было вовсе: карточка отменённого баттла\n' +
          'выглядела как живая, потому что статус никто не спрашивал.'
        : 'Дом состояния в сайте и приложении РАЗОШЁЛСЯ. Одно понятие —\n' +
          'одно определение: пока файлы равны побайтово, правка доезжает\n' +
          'до обоих продуктов разом.');

правило('экраны спрашивают дом, а не сравнивают строки',
    (function () {
        return ЭКРАНЫ.every(ф => {
            const т = безКомментариев(читать(ф) || '');
            return !/status\s*===?\s*['"]cancelled['"]/.test(т);
        });
    })(),
    'Экран сравнивает статус со строкой сам:' +
    ЭКРАНЫ.filter(ф => /status\s*===?\s*['"]cancelled['"]/
        .test(безКомментариев(читать(ф) || ''))).map(ф => '\n  ' + ф).join('') +
    '\nСостояние считает дом `battle-format`. Своё сравнение — это второе\n' +
    'определение одного понятия, и расходятся они молча.');

правило('главная спрашивает дом, а не сравнивает строку',
    (function () {
        const т = безКомментариев(читать(ГЛАВНАЯ) || '');
        /* У баттла состояние спрашивается у дома. Матчи турнира со
           своим `m.status === 'cancelled'` остаются как есть: это
           другое понятие, и дом баттлов о нём ничего не знает. */
        return /isCancelled\s*\(/.test(т) &&
               !/_battleData\.status\s*===?\s*['"]cancelled['"]/.test(т);
    })(),
    'Экран баттла на главной сам сравнивает статус со строкой вместо\n' +
    'того, чтобы спросить дом. Это второе определение одного понятия.');

правило('карточка говорит об отмене в обоих продуктах',
    /bo-strip-cancelled/.test(читать('js/battles-overview.js') || '') &&
    /battle-badge-cancelled/.test(читать('mobile/www/js/screens/battles.js') || ''),
    'Метки отмены нет на карточке сайта или приложения. ОТМЕНА\n' +
    'ГОВОРИТСЯ, А НЕ ПРЯЧЕТСЯ: спрятанная карточка не объясняет ничего,\n' +
    'и человек решит, что потерял баттл сам.');

правило('запрет голоса за отменённый стоит в базе',
    (function () {
        const т = читать(ФУНКЦИЯ) || '';
        const без = т.replace(/--[^\n]*/g, ' ');
        return /status\s*=\s*'cancelled'/.test(без) && /SELECT[\s\S]{0,200}status/.test(без);
    })(),
    'В ' + ФУНКЦИЯ + ' нет проверки статуса — или статус не попал в\n' +
    'выборку, и проверка сравнивает пустоту. ЭКРАН — НЕ ЗАПРЕТ: запрос\n' +
    'можно послать мимо экрана, и голос ляжет в базу навсегда.\n' +
    'Прогон Кости 06.11 показал чтением базы: запрет стоит, отменённых\n' +
    'баттлов 0, голосов за них 0.');

правило('прибор не принимает комментарий за код',
    (function () {
        const о = "/* тут про return 'cancelled' и про status === 'cancelled' */\n" +
                  '// и про isCancelled\n' +
                  'var a = 1;\n';
        const б = безКомментариев(о);
        return !/cancelled/.test(б) && !/isCancelled/.test(б);
    })(),
    'Образец внутри прибора: сторожимые слова в комментариях. В этих\n' +
    'самых файлах объяснено, почему так сделано, — прибор, читающий\n' +
    'объяснение как улику, красен на верном коде.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      отмена баттла: все ' + всего + ' правил держатся');
    console.log('          дом один на два продукта, запрет в базе стоит');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  отмена баттла — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
