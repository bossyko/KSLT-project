const файлыJs = [];
function собратьJs(относительный) {
    const п = path.join(КОРЕНЬ, относительный);
    if (!fs.existsSync(п)) return;
    for (const и of fs.readdirSync(п, { withFileTypes: true })) {
        if (и.isDirectory()) {
            if (и.name !== 'vendor') собратьJs(относительный + '/' + и.name);
        } else if (и.name.endsWith('.js')) {
            файлыJs.push(относительный + '/' + и.name);
        }
    }
}
собратьJs('js');
let зашито = 0;
