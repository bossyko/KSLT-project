#!/usr/bin/env node
/**
 * ПОЗДРАВЛЕНИЕ С ДОСТИЖЕНИЕМ — ОДИН ДОМ (шаг A3.7б, 29.10).
 *
 * ЗАЧЕМ. `badge-celebration.js` жил двумя телами под одним именем.
 * Логика совпадала по смыслу целиком, а расходилось БЕДОЙ одно:
 * **сайт экранировал значок, приложение вставляло его СЫРЫМ.**
 * `icon` — текстовый столбец базы.
 *
 * ПОЧЕМУ ДЫРА ЖИЛА. Сторож `check-dannye-v-razmetku` запер
 * `js/badge-celebration.js` ещё куском 166 — но его признак обходит
 * ТОЛЬКО `js/` (`tools/priznak-dannye-v-razmetke.js:179`), и
 * `mobile/www/js` не видит вовсе. ДЫРА ЖИЛА РОВНО В СЛЕПОМ ПЯТНЕ
 * СТОРОЖА. Это записано отдельным куском: признак надо расширить на
 * приложение, и тогда он покажет остальные.
 *
 * Запуск: node tools/check-pozdravlenie.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
function безКом(т) {
    return т
        .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
        .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));
}

const ДОМ_САЙТ = 'js/kslt-pozdravlenie.js';
const ДОМ_ПРИЛ = 'mobile/www/js/kslt-pozdravlenie.js';

console.log('\n  ПОЗДРАВЛЕНИЕ С ДОСТИЖЕНИЕМ — ОДИН ДОМ\n');

правило('дом объявлен',
    /* ПРИЗНАК ТРЕБУЕТ ПРИСВОЕНИЯ, А НЕ УПОМИНАНИЯ. Первая редакция
       искала `API.карточка` — и не упала, когда зов переименовали в
       `API.карточкаОткл`: имя `API.карточка` осталось в шапке и в
       соседних строках. ПРАВИЛО, СЧИТАЮЩЕЕ ТЕКСТ, ЛОВИТ СЛОВА, А НЕ
       БЕДУ — четвёртый раз за день. */
    ['KSLT_POZDRAVLENIE', 'API\\.очередь\\s*=', 'API\\.пометить\\s*=',
     'API\\.карточка\\s*=', 'API\\.назвать\\s*=', 'API\\.оболочка\\s*=']
        .every(п => new RegExp(п).test(безКом(чит(ДОМ_САЙТ)))),
    'Нужны: `очередь`, `пометить`, `карточка`, `назвать`, `оболочка`.');

правило('копии дома побайтово равны',
    чит(ДОМ_САЙТ) === чит(ДОМ_ПРИЛ),
    'Разошлись — значит экранирование значка снова живёт двумя жизнями.');

правило('ЗНАЧОК ЭКРАНИРОВАН В ДОМЕ',
    /экр\(значок\.icon/.test(чит(ДОМ_САЙТ)),
    'Это та самая дыра: `icon` — текстовый столбец базы, и в приложении\n' +
    'он шёл сырым. Экранирование обязано стоять в доме, один раз на\n' +
    'оба продукта.');

правило('очередь отбирает непоказанные и сортирует',
    /is\('seen_at', null\)/.test(чит(ДОМ_САЙТ)) &&
    /sort_order/.test(чит(ДОМ_САЙТ)),
    'Отбор по `seen_at = null` и порядок по `sort_order` — это и есть\n' +
    'логика, которая была написана дважды.');

правило('отметка ставится сразу, а не после просмотра',
    /mark_badges_seen/.test(чит(ДОМ_САЙТ)),
    'Человек может закрыть вкладку на середине — иначе его встречало бы\n' +
    'то же поздравление при каждом входе.');

правило('ошибку чтения дом не глотает',
    /console\.error\('\[KSLT\] достижения не проверены/.test(чит(ДОМ_САЙТ)),
    'Молча пропустить нельзя: человек не узнает, что заработал, а мы не\n' +
    'узнаем, что поздравление не работает.');

правило('число шариков — одно на оба продукта',
    /API\.ШАРИКОВ\s*=\s*\d+/.test(чит(ДОМ_САЙТ)),
    'Расходилось молча: 26 у сайта против 22 у приложения.');

[['js/badge-celebration.js', 'сайта'],
 ['mobile/www/js/badge-celebration.js', 'приложения']].forEach(([ф, имя]) => {
    const т = безКом(чит(ф));
    правило('у ' + имя + ' нет своего чтения достижений',
        !/from\('player_badges'\)/.test(т),
        'Чтение переехало в дом. Осталось на месте — два определения.');
    правило('у ' + имя + ' нет своей отметки о показе',
        !/mark_badges_seen/.test(т),
        'Отметка переехала в дом.');
    правило('у ' + имя + ' нет своей разметки карточки',
        !/ach-emoji/.test(т),
        'Разметку даёт дом — вместе с экранированием значка.');
    правило('у ' + имя + ' дом зовётся',
        /KSLT_POZDRAVLENIE/.test(т),
        'Без зова работа не сделана.');
});

правило('дом подключён во всех разметках',
    ['mobile/www/index.html', 'pages/dashboard.html'].every(ф =>
        !/badge-celebration\.js/.test(чит(ф)) || /kslt-pozdravlenie\.js/.test(чит(ф))),
    'Страница грузит поздравление без дома — оно просто не нарисуется.');

правило('дом грузится ДО того, кто его зовёт',
    (function () {
        const t = чит('mobile/www/index.html');
        const д = t.indexOf('kslt-pozdravlenie.js');
        const з = t.indexOf('badge-celebration.js');
        return д !== -1 && з !== -1 && д < з;
    })(),
    'Дом зовётся при показе, а не при загрузке, но порядок всё равно\n' +
    'ставится явно: надеяться на тайминг — та же беда, что в A3.3.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      поздравление: все ' + держится + ' правил держатся\n');
}
