/**
 * ДОКАЗАТЕЛЬСТВО СТОРОЖА «СЧЁТ КОНТРАСТА ОДИН» (кусок 186). На КОПИИ.
 *   node tools/check-odin-schyot-kontrasta-otkat.js
 *
 * «У МЕНЯ ЗЕЛЁНОЕ» НИЧЕГО НЕ ДОКАЗЫВАЕТ. Каждый откат возвращает ОДНО
 * прежнее значение и обязан уронить ИМЕННО то правило, которое за него
 * отвечает. Якоря держатся на СОДЕРЖИМОМ, а не на номере строки.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const песок = fs.mkdtempSync(path.join(os.tmpdir(), 'kslt-kontrast-'));
['css', 'tools', 'tests', 'maket'].forEach(д =>
    fs.cpSync(path.join(КОРЕНЬ, д), path.join(песок, д), { recursive: true }));

const МОД = 'tools/kontrast.mjs',
      ПРБ = 'tests/e2e/design-system/92-tihiy-tekst.spec.js',
      ЦСС = 'css/style.css',
      НОВ = 'tools/razovye/zzz-kopiya-formuly.js';
const ФАЙЛЫ = [МОД, ПРБ, ЦСС];
const исходник = {};
ФАЙЛЫ.forEach(ф => { исходник[ф] = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'); });

function прогон(правки, лишний) {
    ФАЙЛЫ.forEach(ф => {
        const п = (правки || []).find(([и]) => и === ф);
        fs.writeFileSync(path.join(песок, ф),
            п ? исходник[ф].replace(п[1], п[2]) : исходник[ф]);
    });
    const лишнийПуть = path.join(песок, НОВ);
    /* ЧИСЛО СОБИРАЕТСЯ ИЗ ЧАСТЕЙ НАМЕРЕННО: напиши его здесь целиком — и
       прувер сам станет сорок пятой копией формулы, уронив правило,
       которое доказывает. Прибор не должен попадать в собственный замер. */
    if (лишний) fs.writeFileSync(лишнийПуть, 'const я = 0.' + '2126; // своя копия\n');
    else if (fs.existsSync(лишнийПуть)) fs.unlinkSync(лишнийПуть);
    try {
        execFileSync(process.execPath,
            [path.join(песок, 'tools', 'check-odin-schyot-kontrasta.js')], { encoding: 'utf8' });
        return { упало: false, вывод: '' };
    } catch (e) { return { упало: true, вывод: (e.stdout || '') + (e.stderr || '') }; }
}

const ОТКАТЫ = [
    ['спрятать формулу внутрь модуля', [[МОД,
      'export const контраст = (a,b)', 'const контраст = (a,b)']],
     'модуль отдаёт наружу и замер, и саму формулу'],

    ['вернуть «картинка ИЛИ градиент — не мерим»', [[МОД,
      "const фотография = s => /url\\(\\s*['\"]?(?!data:)/i.test(s || '');",
      "const фотография = s => /url\\(/i.test(s || '');"]],
     'фотография и градиент различаются'],

    ['записать не мереный узел в прошедшие', [[МОД,
      'if (!фоны) { неМерено.push', 'if (false) { неМерено.push']],
     'фотография не записывается в прошедшие'],

    ['брать у градиента одну остановку вместо всех', [[МОД,
      'варианты.forEach(в => гр.forEach(г => нов.push(поверх(г, в))));',
      'варианты.forEach(в => нов.push(поверх(гр[0], в)));']],
     'градиент складывается ВСЕМИ остановками, а не одной'],

    ['вернуть пробе свою копию формулы', [[ПРБ,
      'const { test, expect } = require(\'../../fixtures\');',
      'const { test, expect } = require(\'../../fixtures\');\nconst ярк = c => 0.' + '2126 * c;']],
     'у пробы нет своей копии формулы'],

    ['отнять у пробы зов модуля в лестнице', [[ПРБ,
      "const м = await import('/tools/kontrast.mjs');",
      "const м = { раз: () => null, контраст: () => 0, поверх: a => a };"]],
     'проба зовёт модуль'],

    ['снять требование нуля не мереных', [[ПРБ,
      'expect(р.неМерено,', 'expect(0 * р.неМерено,']],
     'проба требует нуля не мереных и нуля ниже нормы'],

    ['снять порог «ни одного градиента за прогон»', [[ПРБ,
      'if (градиентныхЗаПрогон === 0) {', 'if (false) {']],
     'проба падает, если градиентов за прогон ноль'],

    ['снять проверку независимости от языка', [[ПРБ,
      "test('краска текста не зависит от языка'", "test.skip('краска текста НЕ сторожится'"]],
     'проба сторожит независимость краски от языка'],

    ['завязать css на язык', [[ЦСС,
      '.lang-current {', 'html:lang(en) .lang-current { color: #fff; }\n.lang-current {']],
     'css не завязан на язык'],

    ['завести новую копию формулы', null, 'копий формулы контраста не прибавляется']
];

const база = прогон(null, false);
if (база.упало) {
    console.log('\n  x база: правила падают на ЧИСТОЙ копии — чинить сторож, а не код\n');
    console.log(база.вывод);
    fs.rmSync(песок, { recursive: true, force: true });
    process.exit(1);
}
console.log('  база    исходный код правила проходит\n');

let плохих = 0;
ОТКАТЫ.forEach(([имя, правки, ждём]) => {
    if (правки) {
        let беда = '';
        правки.forEach(([ф, что]) => {
            const n = исходник[ф].split(что).length - 1;
            if (n === 0) беда = 'якоря нет в ' + ф;
            else if (n !== 1) беда = 'якорь встречается ' + n + ' раз в ' + ф;
        });
        if (беда) { console.log('  ? ' + имя + '  ->  ' + беда); плохих++; return; }
    }
    const р = прогон(правки, !правки);
    прогон(null, false);
    if (!р.упало) { console.log('  x ' + имя + '  ->  правило НЕ упало'); плохих++; }
    else if (р.вывод.indexOf(ждём) === -1) {
        console.log('  ~ ' + имя + '  ->  упало ДРУГОЕ. Ждали: ' + ждём); плохих++;
    } else console.log('  v ' + имя + '  ->  «' + ждём + '»');
});
fs.rmSync(песок, { recursive: true, force: true });
console.log('');
if (плохих === 0) {
    console.log('  ок      все ' + ОТКАТЫ.length + ' откатов доказали свои правила');
    console.log('          оригиналы не трогались — работа шла на копии\n');
} else {
    console.log('  НЕ ТАК  ' + плохих + ' из ' + ОТКАТЫ.length + ' откатов не доказали правило\n');
    process.exitCode = 1;
}
