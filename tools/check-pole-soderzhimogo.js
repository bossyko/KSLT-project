/**
 * БОКОВОЕ ПОЛЕ СОДЕРЖИМОГО АДМИНКИ — ОДНО ОПРЕДЕЛЕНИЕ НА ДВА МЕСТА.
 * Круг 12 ветки D, 18.10.
 *
 * ЧТО БЫЛО. Обёртка таблицы уходит в МИНУСОВОЕ поле, чтобы таблица
 * доходила до края экрана, — приём законный. Но поле содержимого задавалось
 * числом в пяти медиа-блоках, а минус — числом `-16px` в шестом. На виде,
 * где поле 16, они сходились; на телефоне поле 12, и страница переливалась
 * по горизонтали.
 *
 * ЗАПИСЬ ТРЕКЕРА ГОВОРИЛА «на 768 шире окна на 6 пикселей». ПРИБОР СКАЗАЛ
 * ДРУГОЕ: на 768 перелива НЕТ (поле 16 = минус 16), а на 390 перелив
 * РОВНО 4 — по 4 пикселя в каждую сторону. Ни ширина, ни число не
 * совпали с записью. Замерено стендом `maket/pereliv-admin-zamer.html`
 * ЗАГРУЗКОЙ на каждой ширине.
 *
 * ПЕРВАЯ РЕДАКЦИЯ СТЕНДА СОВРАЛА НА 8 ПИКСЕЛЕЙ: она взяла только
 * `tokens.css` и `admin.css`, без `style.css`, — и браузерное поле `body`
 * (8px) съело ровно то расхождение, которое мерим. ВИД МЕРЯЕТСЯ ТЕМ ЖЕ
 * НАБОРОМ ФАЙЛОВ, ЧТО В ПРОДУКТЕ, а не частью его.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ, А НЕ ЧИСЛО. Не «поле 12» и не «минус 16»,
 * а: поле объявлено переменной, и минус обёртки берётся у ТОЙ ЖЕ
 * переменной. Какими числами задано поле на каком виде — решает замер;
 * правило требует, чтобы эти два места не могли разойтись.
 *
 *   node tools/check-pole-soderzhimogo.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const сырой = fs.readFileSync(path.join(КОРЕНЬ, 'css/admin.css'), 'utf8');
const текст = сырой.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));
const строка = поз => текст.slice(0, поз).split('\n').length;

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

/* ---- блоки `.ad-content` — свои, без списков через запятую ---- */
const блокиContent = [];
{
    /* ЗАГЛЯД НАЗАД ДОПУСКАЕТ И `{`: блок `.ad-content` внутри медиа стоит
       ПЕРВЫМ, и перед ним открывающая скобка медиа, а не `}` соседа.
       Первая редакция видела 2 блока из 5 — третий раз за сутки одна и
       та же дыра в моём собственном якоре. */
    const р = /(?<=^|\}|\{)\s*\.ad-content\s*\{([^}]*)\}/g;
    let м;
    while ((м = р.exec(текст))) блокиContent.push({ тело: м[1], стр: строка(м.index) });
}

/* ПРАВИЛО 1. Поле объявлено ПЕРЕМЕННОЙ, а не только числом. */
const сПеременной = блокиContent.filter(б => /--ad-content-pad\s*:/.test(б.тело));
правило('боковое поле содержимого объявлено переменной',
    сПеременной.length >= 2,
    'Блоков `.ad-content` с `--ad-content-pad`: ' + сПеременной.length + ' из ' +
    блокиContent.length + '.\n' +
    'Поле должно жить ПЕРЕМЕННОЙ: от него зависит минусовое поле обёртки\n' +
    'таблицы, и пока оба — числа в разных местах, они разойдутся.');

/* ПРАВИЛО 2. Боковой padding берётся ИЗ переменной, а не числом рядом.
   Иначе переменная объявлена, а поле задано мимо неё — и минус соврёт. */
const мимоПеременной = [];
блокиContent.forEach(б => {
    /* Короткая запись `padding: X` и боковые `padding-left/right`. */
    const бок = б.тело.match(/(?:^|;)\s*padding(-left|-right|-inline)?\s*:\s*([^;]+)/g) || [];
    бок.forEach(п => {
        const зн = п.split(':').slice(1).join(':');
        if (/padding-top\s*:/.test(п)) return;
        if (!/var\(--ad-content-pad\)/.test(зн)) {
            мимоПеременной.push(п.trim().slice(0, 44) + ' (строка ' + б.стр + ')');
        }
    });
});
правило('боковой отступ содержимого берётся у переменной',
    мимоПеременной.length === 0,
    'Поле задано мимо переменной: ' + мимоПеременной.join('; ') + '.\n' +
    'Переменная объявлена, но отступ написан рядом числом — минус обёртки\n' +
    'возьмёт переменную, отступ останется своим, и они разойдутся снова.');

/* ПРАВИЛО 3. Минус обёртки таблицы берётся у ТОЙ ЖЕ переменной.
   Это и есть замороженное отношение. */
const обёртки = [];
{
    const р = /\.ad-table-wrap[^{,]*\{([^}]*)\}/g;
    let м;
    while ((м = р.exec(текст))) {
        const тело = м[1];
        if (!/margin/.test(тело)) continue;
        обёртки.push({ тело, стр: строка(м.index) });
    }
}
const минусЧислом = обёртки.filter(о =>
    /margin[^:]*:\s*[^;]*-\d+px/.test(о.тело) ||
    (/margin/.test(о.тело) && !/var\(--ad-content-pad\)/.test(о.тело)));
правило('минусовое поле обёртки таблицы равно полю содержимого',
    обёртки.length > 0 && минусЧислом.length === 0,
    обёртки.length === 0
        ? 'Правил `.ad-table-wrap` с полем не найдено — приём «таблица до края\n' +
          'экрана» пропал, либо селектор переименован.'
        : 'Минус задан числом, а не полем: строки ' +
          минусЧислом.map(о => о.стр).join(', ') + '.\n' +
          'Обёртка уходит в минус РОВНО на боковое поле содержимого:\n' +
          '`margin-inline: calc(-1 * var(--ad-content-pad))`. Число здесь\n' +
          'сходится лишь на одном виде, а на остальных даёт перелив.');

/* ПРАВИЛО 4. Отступ обёртки возвращает содержимое внутрь — тем же полем.
   Без него текст таблицы прилипнет к краю экрана. */
const безОтступа = обёртки.filter(о =>
    /margin-inline|margin\s*:/.test(о.тело) && !/padding[^:]*:\s*[^;]*var\(--ad-content-pad\)/.test(о.тело));
правило('обёртка возвращает содержимое внутрь тем же полем',
    безОтступа.length === 0,
    'Обёртка ушла в минус, но не вернула содержимое: строки ' +
    безОтступа.map(о => о.стр).join(', ') + '.\n' +
    'Минус и отступ — пара: `margin-inline: calc(-1 * var(--ad-content-pad))`\n' +
    'плюс `padding-inline: var(--ad-content-pad)`. Иначе первая ячейка\n' +
    'таблицы прилипнет к краю экрана.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      поле содержимого: 4 правила');
    console.log('          блоков .ad-content: ' + блокиContent.length +
                ', из них задают поле переменной: ' + сПеременной.length);
    console.log('          боковых отступов мимо переменной: 0');
    console.log('          обёрток таблицы с полем: ' + обёртки.length + ', минус у всех равен полю');
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  поле содержимого — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
