// ---------- 11. язык переключается в одном месте ----------
//
// Решение Кости 20.09: в полосе 769–992 язык остаётся в шапке, ниже 768
// уезжает в бургер. Это ВЫБОР, а не случайность, и он держится на том, что
// обе половины переключаются на ОДНОЙ границе. Если их развести — найдётся
// ширина, где языка нет нигде, или где он есть дважды.
(function языкВОдномМесте() {
    const блоки = [...style.matchAll(/@media\s*\(max-width:\s*(\d+)px\)\s*\{/g)];
    let прячут = null, показывают = null;
    for (const м of блоки) {
        let i = style.indexOf('{', м.index), г = 0, к = i;
        for (; i < style.length; i++) {
            if (style[i] === '{') г++;
            else if (style[i] === '}') { г--; if (г === 0) { к = i; break; } }
        }
        const тело = style.slice(м.index, к + 1);
        if (/\.lang-dropdown\s*\{[^{}]*display:\s*none/.test(тело)) прячут = Number(м[1]);
        if (/\.mobile-lang-list\s*\{[^{}]*display:\s*flex/.test(тело)) показывают = Number(м[1]);
    }
    проверить('язык прячется из шапки и появляется в бургере на одной границе',
        прячут !== null && прячут === показывают,
        'Десктопный переключатель прячется на ' + прячут + ', а список в ' +
        'бургере появляется на ' + показывают + '. Границы обязаны совпадать, ' +
        'иначе найдётся ширина, где языка нет вовсе или он есть дважды.');
})();


// ---------- 12. класс .open вешает скрипт, и судит он по пальцу ----------
//
// Правило 10 стережёт CSS: есть правило .nav-dropdown.open под (pointer:
// coarse). Но CSS сам класс не вешает — его вешает js/script.js. Проверка
// только по стилям сказала бы «сделано» на странице, где панель не
// открывается ничем: ровно так сегодня заморозка показала 13 из 13 на
// сломанном бургере.
(function скриптПанелей() {
    let скрипт = '';
    try {
        скрипт = fs.readFileSync(path.join(ROOT, 'js', 'script.js'), 'utf8')
                   .replace(/\/\*[\s\S]*?\*\//g, '')
                   .replace(/^\s*\/\/.*$/gm, '');
    } catch (e) { /* файла нет — упадёт ниже */ }

    проверить('класс .open вешает скрипт, а не только описан в стилях',
        /classList\.add\(['"]open['"]\)/.test(скрипт) &&
        /\.floating-header \.nav-dropdown/.test(скрипт),
        'В js/script.js нет обработчика, который вешает .open на ' +
        '.floating-header .nav-dropdown. Стили без него описывают состояние, ' +
        'в которое страница никогда не попадает.');

    // ОСТОРОЖНО: искать matchMedia ПО ВСЕМУ ФАЙЛУ нельзя. В js/script.js он
    // встречается трижды — в чужих местах тоже. Первая версия этой проверки
    // так и делала: я подменил условие в обработчике на innerWidth, а она
    // осталась зелёной, потому что нашла matchMedia в другой функции.
    // Смотрим ТОЛЬКО внутрь самого обработчика.
    const н = скрипт.indexOf('навПанели');
    // И ЕЩЁ РАЗ ТУДА ЖЕ: границу куска нельзя ставить по КОММЕНТАРИЮ —
    // комментарии вырезаны выше, и indexOf вернул −1, кусок вышел пустым,
    // проверка упала на верном коде. Граница обязана быть по коду.
    const к = скрипт.indexOf('const sections');
    const кусок = (н !== -1 && к > н) ? скрипт.slice(н, к) : '';
    проверить('обработчик панелей судит по способу ввода, а не по ширине',
        /matchMedia\(['"]\(pointer: coarse\)['"]\)/.test(кусок) &&
        !/innerWidth/.test(кусок),
        'Условие обязано спрашивать matchMedia(\'(pointer: coarse)\'). ' +
        'Проверка по innerWidth здесь не работает: 1024 шире любого ' +
        'мобильного порога, а палец там есть. На этой подмене обожглись ' +
        'дважды — h270 и h274.');
})();


// ---------- 13. обводка фокуса одна на всю шапку ----------
//
// Костя 20.09: «сверь, что обводка одинакового размера у названий и у
// кнопок». Одинаковой она может быть только одним способом — если её
// задаёт ОДНО правило на все элементы шапки. Два правила с одинаковыми
// числами сегодня одинаковы, а завтра одно поправят.
//
// И отдельно: в правиле фокуса не должно быть border-radius. Он меняет
// форму самого элемента в момент фокуса — у логотипа из-за этого обводка
// шла овалом и срезала знак. Форму элемент приносит свою, правило фокуса
// задаёт только обводку. Исключение — .logo:focus-visible, которому радиус
// и увеличенный отступ заданы НАМЕРЕННО, отдельным правилом, с объяснением.
(function обводкаФокуса() {
    const правила = [...style.matchAll(/([^{}]*:focus-visible[^{}]*)\{([^{}]*)\}/g)]
        .filter(м => /nav-item|btn-auth|lang-toggle|\.logo|burger-menu|nav-dropdown-item/.test(м[1]));
    const сОбводкой = правила.filter(м => /outline:\s*\d/.test(м[2]));
    проверить('обводка фокуса в шапке задана одним правилом',
        сОбводкой.length === 1,
        'Правил с outline для элементов шапки: ' + сОбводкой.length + '. ' +
        'Должно быть одно на всех, иначе толщина и отступ разъедутся. ' +
        'Отличия по форме задаются отдельным правилом БЕЗ outline.');

    const сРадиусом = сОбводкой.filter(м => /border-radius/.test(м[2]));
    проверить('в общем правиле фокуса нет border-radius',
        сРадиусом.length === 0,
        'border-radius в :focus-visible меняет форму САМОГО элемента на ' +
        'время фокуса. У логотипа своего скругления нет, и он превращался ' +
        'в таблетку — обводка шла овалом и срезала знак (найдено Костей ' +
        'глазами 20.09). Правило фокуса задаёт только обводку.');
})();


// ---------- 14. клавиатура: панель открывается и закрывается сама ----------
//
// Написано ДО правки. Найдено Костей 20.09 клавишей Tab:
//   1) список языков он открыл, пошёл дальше по Tab — и список остался
//      висеть. Закрытие было описано ТОЛЬКО для щелчка мимо
//      (document click), а уход фокуса никто не слушал;
//   2) панели разделов с клавиатуры не открываются вовсе: они висят на
//      :hover и на классе .open, который вешает нажатие пальцем. У
//      клавиатуры нет ни того, ни другого — значит пять вложенных ссылок
//      в каждом разделе недостижимы и с клавиатуры тоже.
//
// :focus-within решает обе задачи одним приёмом: панель открыта, пока
// фокус внутри неё, и закрывается сама, когда фокус ушёл. Ни таймеров,
// ни обработчиков закрытия.
проверить('панель раздела открывается фокусом с клавиатуры',
    /\.nav-dropdown:focus-within\s+\.nav-dropdown-menu/.test(style),
    'Нужно правило .nav-dropdown:focus-within .nav-dropdown-menu. Без него ' +
    'вложенные ссылки разделов недостижимы с клавиатуры: :hover у клавиатуры ' +
    'нет, а .open вешает только нажатие пальцем.');

(function языкЗакрывается() {
    let скрипт = '';
    try {
        скрипт = fs.readFileSync(path.join(ROOT, 'js', 'script.js'), 'utf8')
                   .replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
    } catch (e) {}
    проверить('список языков закрывается, когда фокус ушёл',
        /focusout/.test(скрипт),
        'В js/script.js нет обработчика focusout для .lang-dropdown. ' +
        'Закрытие описано только для щелчка мимо — при ходьбе по Tab список ' +
        'остаётся висеть поверх страницы (найдено Костей 20.09).');
})();


// ---------- 15. панель висит от края шапки, а не под кнопкой ----------
//
// Написано ДО правки. Решение Кости 20.09 по макету 222:145, после двух
// отвергнутых попыток — и обе отверг он, глядя на целое:
//   1) панель с зазором под кнопкой — «как будто отвалилась». Зазор был
//      структурный: пилюля пункта кончается на 50, а панель начинается на
//      64 (низ шапки). Четырнадцать пикселей шапки между ними;
//   2) язычок, дорастающий до низа шапки, — «сапог». Узкий язычок с
//      широкой панелью под ним рисует букву Г при любой ширине меню.
//      Подрезать ступеньку бессмысленно, дело в самой форме.
//
// Принято: панели нет ни зазора, ни язычка. Она висит прямо от края
// шапки, верхние углы прямые, нижние скруглены. Открытый раздел отмечает
// лаймовая черта под подписью — приём в проекте уже есть.
//
// ОСТОРОЖНО, ГЛАВНОЕ МЕСТО ОШИБКИ: у открытого пункта НЕ ДОЛЖНО быть
// подложки-пилюли. Если она вернётся, вернётся и зазор: коробка кончится
// на 50, панель начнётся на 64, и «отвалилось» будет снова.
