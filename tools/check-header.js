// ---------- 10. панель открывается пальцем ----------
//
// Написано ДО правки. Все пять панелей висели ТОЛЬКО на :hover, а на 1024
// десктопная шапка отдаётся сенсорному экрану. У пальца наведения нет —
// значит пять вложенных ссылок в каждом разделе были недостижимы вовсе.
