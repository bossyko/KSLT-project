#!/usr/bin/env node
/**
 * Заморозка шапки — быстрая проверка по исходникам, без браузера.
 *
 * Написана ДО переезда на токен, а не после. На подвале я сделал наоборот:
 * сначала правка, потом проверка — и она промолчала о девятнадцати правилах,
 * которых не знала (h274). Проверка, написанная заранее, обязана упасть
 * ровно столько раз, сколько мест ещё не переехало. Если упадёт меньше —
 * значит она чего-то не видит, и чинить надо её, а не код.
 *
 * Что она стережёт — ПРАВИЛО, а не значения:
 *
 *     высота шапки живёт в одном месте — токене --header-h.
 *     Ни один файл не повторяет её числом.
 *
 * Замеры, на которых всё построено (21.09.2026, прибор
 * tests/e2e/design-system/20-header-offsets.spec.js, 60 снимков):
 *     шапка 65 на 768/844/1024/1280 и 57 на 375
 *     лишний пиксель — прозрачная рамка (h80)
 *     42 липкие панели липнут на 64 — ни одна не совпадает с низом шапки
 *     зазор до содержимого 23…45 и не по порядку (h273)
 *
 * Запуск:  node tools/check-header.js
 * Код возврата 1, если хоть один пункт не сошёлся.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const CSS = path.join(ROOT, 'css');

const ошибки = [];
const ок = [];
function проверить(имя, условие, почему) {
    if (условие) ок.push(имя); else ошибки.push({ имя, почему });
}

const файлы = fs.readdirSync(CSS)
    .filter(f => f.endsWith('.css') && f.indexOf('backup') === -1)
    .map(f => ({ имя: f, текст: fs.readFileSync(path.join(CSS, f), 'utf8') }));

const токены = файлы.filter(f => f.имя === 'tokens.css')[0].текст;

// ---------- 1. токен говорит правду ----------
//
// ОСТОРОЖНО, ЗДЕСЬ ЛЕГКО ОШИБИТЬСЯ. Токен --header-h существовал и раньше,
// но держал clamp(72px, 6vw, 100px) при настоящей высоте 64. Его звали три
// места, и все три отбивали содержимое от шапки — то есть «лишний воздух»
// рос с шириной окна: 8 пикселей на телефоне, 36 на 1920. Это и был «сайт
// плывёт» в одной строке. Значение должно быть ЧИСЛОМ, не формулой: высота
// шапки от ширины окна не зависит, она меняется только ступенькой.
проверить('токен --header-h держит число, а не формулу',
    /--header-h:\s*\d+px\s*;/.test(токены) && !/--header-h:\s*clamp/.test(токены),
    'Токен обязан держать настоящую высоту шапки числом. Формула clamp() ' +
    'здесь означает, что отбивка под шапкой плавает с шириной окна, а сама ' +
    'шапка — нет. Замерено 21.09: зазор до содержимого 23 / 31 / 31 / 33.6 / ' +
    '45.1 на 375 / 768 / 844 / 1024 / 1280.');

проверить('у шапки есть вторая, узкая высота',
    /--header-h:\s*56px\s*;/.test(токены),
    'Ниже узкой границы шапка ниже — это стандарт Material Design (56 dp ' +
    'compact, 64 medium+) и решение Кости от 21.09. Без второго значения ' +
    'токен описывает только половину правды.');

// ---------- 2. высота шапки не повторяется числом ----------
//
// ОСТОРОЖНО. Число 56/64/65 встречается в проекте 70 раз, и только 28 из них
// про шапку. Остальные 42 — аватарки, колонки таблиц, поля ввода, столбики
// пьедестала, отступы между секциями. Связать их с токеном значит сломать их
// при первой же смене высоты шапки. Поэтому ловим НЕ число, а число в
// ПОЗИЦИИ, которая может значить только «отсчитываюсь от шапки»:
//     top: Npx            — липкая панель под шапкой
//     padding-top: Npx    — отбивка содержимого
//     calc(100vh - Npx)   — боковое меню на остаток экрана
// Число 72 из образцов убрано 21.09: оно было минимумом старого clamp и
// значило высоту шапки, пока токен врал. Теперь 72 встречается один раз —
// в админке, и отбивает полосу вкладок, а не шапку. Ловить его значит
// звать чинить то, что не сломано.
// Аватарка 64×64 под эти образцы не попадает и остаётся в покое.
const ОБРАЗЦЫ = [
    { имя: 'top',          re: /(^|[;{\s])top:\s*(56|64|65|120)px/g },
    { имя: 'padding-top',  re: /padding-top:\s*(56|64|65)px/g },
    { имя: 'calc(100vh)',  re: /calc\(\s*100vh\s*-\s*(56|64|65)px\s*\)/g },
    { имя: 'scroll-margin',re: /scroll-margin-top:\s*(56|64|65|120)px/g }
];

const виноватые = [];
for (const ф of файлы) {
    const строки = ф.текст.split('\n');
    for (let i = 0; i < строки.length; i++) {
        const с = строки[i];
        if (/^\s*(\/\*|\*)/.test(с)) continue;          // комментарий — не код
        for (const о of ОБРАЗЦЫ) {
            о.re.lastIndex = 0;
            if (о.re.test(с)) {
                виноватые.push(ф.имя + ':' + (i + 1) + '  ' + с.trim().slice(0, 56));
                break;
            }
        }
    }
}

const поФайлам = {};
for (const в of виноватые) {
    const ф = в.split(':')[0];
    поФайлам[ф] = (поФайлам[ф] || 0) + 1;
}

проверить('высота шапки нигде не повторяется числом',
    виноватые.length === 0,
    'Найдено ' + виноватые.length + ' мест, где высота шапки зашита числом ' +
    'вместо var(--header-h).\n    По файлам: ' +
    Object.keys(поФайлам).sort().map(k => k + ' ' + поФайлам[k]).join(' · ') +
    '\n    Пока они зашиты, смена высоты шапки не доходит до них: 21.09 ' +
    'замерено, что все липкие панели липнут на 64 при шапке 65 — на четырёх ' +
    'ширинах пиксель под шапкой, а на 375 при шапке 57 дыра в семь пикселей. ' +
    'Ноль из сорока двух стоят верно.\n    Поимённо:\n      ' +
    виноватые.join('\n      '));

// ---------- 3. правило шапки не бьёт по чужим <nav> ----------
//
// ОСТОРОЖНО, ЗДЕСЬ УЖЕ ОБЖИГАЛИСЬ ДВАЖДЫ. Селектор был голый — `nav` — и
// ловил каждый <nav> на сайте: навигация подвала выросла с 44 до 64 и
// утянула плашку со 118 до 139, а полоса вкладок турнира до сих пор носит
// строку «Override global nav styles». Оба места оборонялись вручную.
// Голых <nav> в проекте 80, и все 80 лежат внутри .floating-header — то есть
// правило и так работало только по шапке, просто заодно било по чужим.
(function голыйNav() {
    const текст = файлы.map(f => f.текст.replace(/\/\*[\s\S]*?\*\//g, '')).join('\n');
    const найдено = (текст.match(/(^|\}|\{)\s*nav\s*\{/gm) || []).length;
    проверить('селектор шапки не ловит чужие <nav>',
        найдено === 0,
        'Голый селектор nav снова появился в CSS (' + найдено + ' шт.). Он ' +
        'написан для шапки, но достаётся каждому <nav> на сайте, и следующий ' +
        'же придётся оборонять вручную, как .footer-legal-nav и .td-tabs-bar. ' +
        'Писать .floating-header nav.');
})();

// ---------- 3. зазор до первой строки задаётся одним способом ----------
//
// ЧЕСТНО: эта проверка написана ПОСЛЕ правки, в отличие от трёх выше. Так
// вышло, потому что правило родилось из замера, а не наоборот. Доказана
// откатом отдельно.
//
// ОСТОРОЖНО, ЗДЕСЬ ЛЕГКО ОШИБИТЬСЯ. До 21.09 зазор получался ДВУМЯ разными
// способами: до 768 его задавало правило первой секции, выше 768 он выходил
// побочно — из вертикального отступа секции (--section-y), который плавает с
// шириной окна. Отсюда разнобой 23 / 31 / 31 / 33.6 / 45.1 при неподвижной
// шапке. Способ должен остаться один.
проверить('зазор под шапкой живёт в токене --header-gap',
    /--header-gap:\s*24px\s*;/.test(токены) && /--header-gap:\s*32px\s*;/.test(токены),
    'Зазор между низом шапки и первой строкой страницы задаётся токеном ' +
    '--header-gap: 24 под пальцем, 32 от 993 (решение Кости 21.09, вариант А). ' +
    'Обе величины — ступени шкалы отступов, а не выдуманные числа.');

проверить('первая секция берёт зазор из токена, а не считает его сама',
    /main\s*>\s*section:first-child:not\(\.hero\)\s*\{[^{}]*padding-top:\s*var\(--header-gap\)/
        .test(файлы.filter(f => f.имя === 'style.css')[0].текст.replace(/\/\*[\s\S]*?\*\//g, '')),
    'Первая секция страницы должна брать зазор готовым из токена. Если здесь ' +
    'снова появится calc() с высотой шапки или --section-y, зазор начнёт ' +
    'складываться из двух источников и поедет с шириной окна, как до 21.09.');

// ---------- 3. шапка занимает ровно столько, сколько обещает ----------
//
// ОСТОРОЖНО. Прозрачная рамка снизу шапки не видна, но занимает пиксель:
// шапка 64 отрисовывается как 65 (h80). Из-за неё каждое top: 64 уезжает
// под шапку. Рамку убираем, линию рисует ::after — он там уже есть.
// ПРОВЕРКУ САМУ ТОЖЕ НАДО ПРОВЕРЯТЬ. Первый прогон 21.09 упал на пустом
// месте: рамку из кода убрали, но в комментарии рядом осталось объяснение,
// ПОЧЕМУ её убрали, — и регулярка нашла текст в комментарии. Поэтому здесь
// комментарии вырезаются до поиска. То же самое было на подвале 20.09.
const style = файлы.filter(f => f.имя === 'style.css')[0].текст
    .replace(/\/\*[\s\S]*?\*\//g, '');
проверить('у шапки нет невидимой рамки, съедающей пиксель',
    !/\.floating-header[^{}]*\{[^{}]*border-bottom:\s*1px\s+solid\s+transparent/.test(style),
    'Замерено 21.09: шапка 65 при height 64 и 57 при height 56. Лишний ' +
    'пиксель — border-bottom: 1px solid transparent. Он невидим, но входит ' +
    'в высоту, и из-за него ВСЕ липкие панели на 64 уходят под шапку. ' +
    'Линию под шапкой рисует ::after, рамка не нужна.');


// ---------- 4. цели под палец не меньше 44 ----------
//
// ОСТОРОЖНО, ЗДЕСЬ ЛЕГКО ОШИБИТЬСЯ ТРЕМЯ СПОСОБАМИ — все три уже случались.
//
// 1) УСЛОВИЕ. Блок обязан висеть на (pointer: coarse), а не на ширине.
//    Замер 21.09: на 844 (айфон боком) и 1024 (айпад боком) бургер вообще
//    не показывается — сенсорному устройству отдаётся ДЕСКТОПНАЯ шапка, и
//    все девять её элементов были ниже 44 (пункты 37 и 41, язык 33,
//    «Войти» 39, знак 34). Ширина про это не знает. Ровно эта подмена
//    стоила нам h270 и h274 в подвале.
// 2) INLINE. У строчного <a> min-height не работает вовсе. Вложенным
//    ссылкам бургера нужен display: flex рядом с min-height, иначе правило
//    есть, а высота прежняя — и проверка по одному min-height промолчит.
// 3) ПРОВЕРКА ПО КОММЕНТАРИЮ. Этот файл уже падал на тексте объяснения
//    вместо кода. Комментарии вырезаны выше, в переменной style.
//
// Стережём ПРАВИЛО: под пальцем каждая цель в шапке — не меньше 44.
// Источник числа: WCAG 2.5.5 (AAA, 44x44) и Apple HIG (44pt). Это не
// выдуманная величина и не вкус.
(function целиПодПалец() {
    // ОСТОРОЖНО: блоков (pointer: coarse) в style.css НЕ ОДИН — на 21.09 их
    // девять, и наш — последний. Первая версия этой проверки брала первый
    // попавшийся и падала на верном коде. Берём ВСЕ и ищем по их объединению.
    const все = [];
    const ре = /@media\s*\(pointer:\s*coarse\)\s*\{/g;
    let сп;
    while ((сп = ре.exec(style)) !== null) {
        let j = style.indexOf("{", сп.index), г = 0, к = j;
        for (; j < style.length; j++) {
            if (style[j] === "{") г++;
            else if (style[j] === "}") { г--; if (г === 0) { к = j; break; } }
        }
        все.push(style.slice(сп.index, к + 1));
    }
    if (все.length === 0) {
        проверить('цели под палец защищены блоком (pointer: coarse)', false,
            'В style.css нет блока @media (pointer: coarse). Без него шапка ' +
            'отдаёт сенсорному устройству цели ниже 44: замерено 21.09 — ' +
            'пункты 37 и 41, язык 33, «Войти» 39, знак 34, вложенные ссылки ' +
            'бургера 41.1, чипы языка 38.8. На 844 и 1024 бургера нет вовсе, ' +
            'поэтому условие по ширине эту дыру не закрывает.');
        return;
    }
    const блок = все.join("\n");

    const обязаны = [
        ['.floating-header .logo',        'знак (замерен 34 в высоту)'],
        ['.floating-header .nav-item',    'пункты меню (37 и 41)'],
        ['.floating-header .btn-auth',    '«Войти» (39)'],
        ['.floating-header .lang-toggle', 'переключатель языка (33)'],
        ['.mobile-dropdown-menu li a',    'вложенные ссылки бургера (41.1, тридцать две штуки)'],
        ['.mobile-lang-option',           'чипы языка в бургере (38.8)']
    ];
    const без = обязаны.filter(([сел]) => {
        const где = блок.indexOf(сел);
        if (где === -1) return true;
        // от селектора до ближайшей закрывающей скобки правила
        const правило = блок.slice(где, блок.indexOf('}', где));
        return !/min-height:\s*44px/.test(правило);
    });
    проверить('под пальцем каждая цель в шапке не меньше 44',
        без.length === 0,
        'Не закрыты min-height: 44px внутри (pointer: coarse): ' +
        без.map(([с, ч]) => с + ' — ' + ч).join(' · ') +
        '\n    Замер 21.09, прибор tests/e2e/design-system/21-header-tap-targets.spec.js. ' +
        'Порог 44 — WCAG 2.5.5 (AAA) и Apple HIG (44pt).');

    // отдельным пунктом — flex у строчной ссылки
    const ссылки = блок.slice(блок.indexOf('.mobile-dropdown-menu li a'));
    проверить('вложенной ссылке бургера дан display: flex, иначе 44 не работает',
        блок.indexOf('.mobile-dropdown-menu li a') !== -1 &&
        /display:\s*flex/.test(ссылки.slice(0, ссылки.indexOf('}'))),
        'У строчного <a> min-height не действует вовсе — правило будет ' +
        'написано, а высота останется 41.1, и проверка по одному min-height ' +
        'этого не заметит. Рядом с min-height обязан стоять display: flex.');
})();

// ---------- вывод ----------
console.log('');
for (const и of ок) console.log('  ок      ' + и);
for (const е of ошибки) {
    console.log('  НЕ ТАК  ' + е.имя);
    console.log('          ' + е.почему.replace(/\n/g, '\n          '));
}
console.log('');
console.log('Шапка: сошлось ' + ок.length + ' из ' + (ок.length + ошибки.length));
console.log('');
process.exit(ошибки.length ? 1 : 0);
