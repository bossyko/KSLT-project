// ---------- 16. панель — настоящее стекло, а не половина ----------
//
// Написано ДО правки. Решение Кости 20.09 по доске 230:145.
// Было rgba(20,20,20,0.95) + blur(20). При 95% сквозь панель почти ничего
// не видно — значит размытие не делает НИЧЕГО; но те 5%, что проходят, —
// это тёплое фото корта на главной, и оно красит панель в коричневый.
// Костя: «ни туда ни сюда». Он прав буквально: половина стекла и половина
// плоскости дают худшее от обоих.
//
// ОСТОРОЖНО, ПОЧЕМУ ЭТО ДОЖИЛО ДО СЕГОДНЯ: на плоском чёрном такая панель
// выглядит нормально, а все мои замеры делались на чёрном. Проверять
// поверхности надо НАД СОДЕРЖИМЫМ, а не над пустым фоном.
(function стекло() {
    const m = style.match(/\.nav-dropdown-menu\s*\{([^{}]*)\}/);
    const тело = m ? m[1] : '';
    const альфа = тело.match(/background:\s*rgba\([^)]*,\s*([\d.]+)\s*\)/);
    const блюр = style.match(/\.nav-dropdown:hover \.nav-dropdown-menu\s*\{[^{}]*backdrop-filter:\s*blur\((\d+)px\)/);
    const a = альфа ? Number(альфа[1]) : null;
    const b = блюр ? Number(блюр[1]) : null;
    // ПРАВИЛО САМО БЫЛО НЕВЕРНЫМ, И ЭТО ВАЖНО.
    // Я написал в нём «либо стекло, либо плоскость», а проверял только
    // стекло: a <= 0.7 && b >= 24. Сплошная панель — та, на которую мы
    // в итоге и перешли, — провалила бы его. Текст правила расходился
    // с его кодом, и заметил я это только когда понадобился второй путь.
    // Теперь путей действительно два, и запрещена ровно середина.
    // ПРАВИЛО ПЕРЕПИСАНО ВТОРОЙ РАЗ, И ВТОРАЯ ПРИЧИНА ВАЖНЕЕ ПЕРВОЙ.
    // Сначала оно проверяло только стекло, хотя описывало два пути. Это я
    // починил. Но и ось была выбрана неверно: я мерил «стекло или
    // плоскость», а провалились обе попытки по ДРУГОЙ причине — цвет.
    // Полупрозрачная панель подкрасилась фотографией; сплошная серая
    // #1E1E1E выбилась из палитры. Прозрачность тут ни при чём — важно,
    // откуда взят цвет.
    // Поэтому теперь проверяется: цвет панели приходит ТОКЕНОМ палитры,
    // а не одноразовым числом. Токен нельзя «не попасть в палитру».
    const изТокена = /background:\s*var\(--/.test(тело);
    const стекло = a !== null && a <= 0.7 && b !== null && b >= 24;
    const плоскость = a === null || a >= 1;
    проверить('цвет панели взят из палитры токеном, а не числом',
        изТокена,
        'Фон панели должен быть var(--…) из палитры. Два одноразовых ' +
        'значения уже провалились на живой странице: rgba(20,20,20,0.95) ' +
        'подкрасилось фотографией героя, #1E1E1E выбился серым пятном над ' +
        'тёплой обложкой. Число, выбранное на глаз, не обязано ужиться ' +
        'с остальным сайтом; токен обязан.');

    проверить('панель либо стекло целиком, либо плоскость — но не середина',
        стекло || плоскость,
        'Сейчас прозрачность ' + a + ' и размытие ' + b + '. Решено 20.09: ' +
        'либо стекло целиком (прозрачность не выше 0.7 и размытие от 24), ' +
        'либо плоскость без прозрачности вовсе. 0.95 с размытием 20 — это ' +
        'ни то ни другое: пропускает ровно столько, чтобы подкраситься фоном, ' +
        'и недостаточно, чтобы это читалось как стекло.');
})();

