const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = о => fs.readFileSync(path.join(КОРЕНЬ, о), 'utf8');
const чисто = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '));

const ПОТОЛОК_СВОЕГО_ДВИЖЕНИЯ = 0;   /* ЗАМЕРЕНО 19.10: Web Animations API нигде */

/* Блок вырезается по балансу скобок, СЧИТАЯ С ОТКРЫВАЮЩЕЙ. */
function блок(текст, зачин) {
    const н = текст.indexOf(зачин);
    if (н === -1) return '';
    const о = текст.indexOf('{', н);
    if (о === -1) return '';
    let гл = 0;
    for (let i = о; i < текст.length; i++) {
        if (текст[i] === '{') гл++;
        else if (текст[i] === '}') { гл--; if (гл === 0) return текст.slice(н, i + 1); }
    }
    return текст.slice(н);
}

function всеHTML() {
    const итог = [];
    (function обойти(дир) {
        for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
            if (э.name.startsWith('.')) continue;
            const п = path.join(дир, э.name);
            if (э.isDirectory()) {
                if (['node_modules','test-results','mobile','lib','playwright-report','tests','tools'].indexOf(э.name) !== -1) continue;
                обойти(п);
            } else if (э.name.endsWith('.html')) итог.push(п);
        }
    })(КОРЕНЬ);
    return итог;
}

const ошибки = [];
let держится = 0;
function правило(имя, годно, подсказка) {
    if (годно) { держится++; console.log('  ✓ ' + имя); }
    else ошибки.push({ имя, подсказка });
}

/* ── 1. общий блок отказа существует и накрывает ВСЁ ── */
const tokens = чисто(чит('css/tokens.css'));
const общий = блок(tokens, '@media (prefers-reduced-motion: reduce)');
правило(
    'общий блок отказа накрывает все элементы и их псевдоэлементы',
    /\*\s*,\s*\*::before\s*,\s*\*::after/.test(общий.replace(/\s+/g, ' ').replace(/ ,/g, ',')),
    'Блок в tokens.css должен перечислять `*`, `*::before`, `*::after`.\n' +
    'Накрой он только `*` — псевдоэлементы продолжат крутиться, а именно\n' +
    'ими рисуются искры, точки и бегущие полосы.\n' +
    'Сейчас: ' + (общий ? общий.slice(0, 120).replace(/\s+/g, ' ') : 'БЛОКА НЕТ ВОВСЕ'));

правило(
    'в общем блоке все четыре свойства и все с важностью',
    ['animation-duration', 'animation-iteration-count', 'transition-duration', 'scroll-behavior']
        .every(св => new RegExp(св + ':[^;]*!important').test(общий)),
    'Нужны четыре с `!important`: animation-duration, animation-iteration-count,\n' +
    'transition-duration, scroll-behavior. Без важности любое правило с\n' +
    'анимацией победит отказ — у него специфичность выше, чем у `*`.\n' +
    'Это единственное место продукта, где важность ОБЯЗАТЕЛЬНА (кусок 107).');

/* ── 2. отказ никто не перебивает ── */
const перебой = [];
for (const ф of fs.readdirSync(path.join(КОРЕНЬ, 'css')).sort()) {
    if (!ф.endsWith('.css')) continue;
    const т = чисто(чит('css/' + ф));
    const стрки = т.split('\n');
    let стек = [], гл = 0;
    for (let i = 0; i < стрки.length; i++) {
        const с = стрки[i];
        const мм = с.match(/\s*(@media[^{]*)\{/);
        if (мм) стек.push([гл, мм[1]]);
        гл += (с.split('{').length - 1) - (с.split('}').length - 1);
        while (стек.length && гл <= стек[стек.length - 1][0]) стек.pop();
        const медиа = стек.map(x => x[1]).join(' ');
        if (/animation[^:]*:[^;]*!important/.test(с) && медиа.indexOf('prefers-reduced-motion') === -1) {
            перебой.push(ф + ':' + (i + 1));
        }
    }
}
правило(
    'важностью на анимации отказ никто не перебивает',
    перебой.length === 0,
    'Перебивают: ' + перебой.join(', ') + '.\n' +
    '`animation` с важностью ВНЕ блока отказа бьёт общий блок на равных и\n' +
    'выигрывает по порядку в файле. Такое правило отменяет отказ молча.');

/* ── 3. tokens.css подключён на каждой странице С СОДЕРЖИМЫМ ── */
/* ПРИЗНАК: БЕРЁШЬ ВИД ПРОДУКТА — БЕРИ И ЕГО ОТКАЗ ОТ ДВИЖЕНИЯ.
   Спрашивать «есть ли tokens.css» у каждого html нельзя: прибор дважды
   соврал на этом. Сперва назвал дырой `pages/admin-en.html` — это
   ПЕРЕНАПРАВЛЕНИЕ в 25 строк с location.replace. Потом
   `maket/progon-cepochki.html` — стенд с пишущей заглушкой, в котором
   прямо написано: «ничего не рисует, видом здесь проверять нечего,
   поэтому и вида нет». Он подключает один `kslt-toast.css` и свой
   инлайновый стиль — вида продукта не берёт вовсе.
   Поэтому правило смотрит на тех, кто ПОДКЛЮЧАЕТ ВИД ПРОДУКТА. */
const ВИД_ПРОДУКТА = ['style.css', 'admin.css', 'dashboard.css', 'news.css',
    'tournament-detail.css', 'tournaments-overview.css', 'players.css',
    'courts.css', 'services.css', 'partners.css', 'live-match.css',
    'podium.css', 'player.css', 'umpire.css', 'battle-cards.css'];
const безТокенов = всеHTML().filter(п => {
    const т = fs.readFileSync(п, 'utf8');
    if (т.indexOf('tokens.css') !== -1) return false;
    const беретВид = ВИД_ПРОДУКТА.some(ф => new RegExp('css/' + ф.replace('.', '\\.') + '(\\?|")').test(т));
    return беретВид;
}).map(п => path.relative(КОРЕНЬ, п));
правило(
    'общий блок отказа доходит до каждой страницы с содержимым',
    безТокенов.length === 0,
    'Берут вид продукта без tokens.css: ' + безТокенов.join(', ') + '.\n' +
    'Блок отказа живёт в tokens.css. Страница, взявшая вид продукта без\n' +
    'него, не получает ни токенов, ни отказа — и крутит всё, что умеет.\n' +
    'Перенаправления и стенды без вида сюда НЕ входят: у них вида нет.');

/* ── 4. своё движение из js: потолок и правило эталона ── */
const своё = [];
(function обойти(дир) {
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        const п = path.join(дир, э.name);
        if (э.isDirectory()) обойти(п);
        else if (э.name.endsWith('.js')) {
            const т = чисто(fs.readFileSync(п, 'utf8'));
            /* Web Animations API: движение рисует js, и css его не достанет */
            if (/\.animate\s*\(\s*\[/.test(т) && т.indexOf('prefers-reduced-motion') === -1) {
                своё.push(path.relative(КОРЕНЬ, п));
            }
        }
    }
})(path.join(КОРЕНЬ, 'js'));
правило(
    'js не рисует движение сам, минуя отказ',
    своё.length <= ПОТОЛОК_СВОЕГО_ДВИЖЕНИЯ,
    'Рисуют сами и отказ не спрашивают: ' + своё.join(', ') + '.\n' +
    'Общий блок css сюда не достаёт вовсе. Эталон — js/home-rankings.js:\n' +
    'спрашивает matchMedia(\'(prefers-reduced-motion: reduce)\'), и там\n' +
    'названа причина: «то же проверяет css, но искры создаёт js, поэтому\n' +
    'спросить надо в обоих местах».');

правило(
    'эталон вопроса об отказе в js на месте',
    /matchMedia\s*\(\s*'\(prefers-reduced-motion: reduce\)'\s*\)/.test(чисто(чит('js/home-rankings.js'))),
    'js/home-rankings.js должен спрашивать отказ сам: он создаёт въезд\n' +
    'карточек наблюдателем, а не css-анимацией. Исчезнет вопрос —\n' +
    'исчезнет и образец, по которому пишут следующий такой экран.');

/* ── 5. приложение: свой блок отказа, чужая ветка под храповиком ── */
