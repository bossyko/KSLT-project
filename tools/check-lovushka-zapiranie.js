/* ---- 6. шесть зовущих, и у каждого снятие зовётся ---- */
const зовущие = {};
const безСнятия = [];
ФАЙЛЫ.forEach(ф => {
    if (ф === ДОМ) return;
    let т;
    try { т = дерево(чит(ф)); } catch (e) { return; }
    const имена = [];
    обойти(т, у => {
        if (у.type !== 'VariableDeclarator' || !у.init) return;
        const и = у.init;
        if (и.type !== 'CallExpression' || !и.callee || и.callee.type !== 'MemberExpression') return;
        if (и.callee.property && и.callee.property.name === 'запереть' &&
            и.callee.object && и.callee.object.type === 'MemberExpression' &&
            и.callee.object.property && и.callee.object.property.name === 'KSLT_FOKUS') {
            имена.push({ имя: у.id.name, строка: у.loc.start.line });
        }
    });
    if (!имена.length) return;
    зовущие[ф] = имена.length;
    /* СНЯТИЕ ОБЯЗАНО БЫТЬ ПОЗВАНО. Не «присвоено» — позвано: иначе цена
       переноса не уплачена, и слушатель переживёт окно. */
    имена.forEach(({ имя, строка }) => {
        let зовут = 0;
        обойти(т, у => {
            if (у.type === 'CallExpression' && у.callee && у.callee.type === 'Identifier' &&
                у.callee.name === имя) зовут++;
        });
        if (!зовут) безСнятия.push(ф + ':' + строка + ' (' + имя + ')');
    });
});
