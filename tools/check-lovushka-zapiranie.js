/* ---- 9б. дом не зовётся на загрузке, и потому порядок тегов не важен ---- */
/* ПРАВИЛО ПЕРЕПИСАНО В ТОТ ЖЕ ЧАС, И ПЕРЕПИСАЛ ЕГО ЗАМЕР. Сперва я завёл
   здесь ПОРЯДОК ТЕГОВ — «дом подключён раньше потребителя», купив правило
   на куске 133. Оно упало на СЕМИ страницах, где дом стоит с 21.10:
   `sponsors-loader.js` там подключён раньше дома. Я померил, прежде чем
   называть это бедой, — и беды нет: ни один зов дома не лежит на ВЕРХНЕМ
   уровне файла, все одиннадцать живут внутри функций открытия окна и
   случаются по нажатию, когда загружено уже всё.
   ЗНАЧИТ ДЕРЖАТЬ НАДО ПРИЧИНУ, А НЕ СЛЕДСТВИЕ: порядок тегов не важен
   ровно до тех пор, пока дом не позвали на загрузке. Позовут — это правило
   упадёт и скажет, что теперь порядок стал важен. ПРАВИЛО, ЗАПРЕЩАЮЩЕЕ
   БЕЗВРЕДНОЕ, УЧИТ ОБХОДИТЬ СЕБЯ. */
const ПОТРЕБИТЕЛИ_ДОМА = ['js/sponsors-loader.js', 'js/news.js', 'js/sponsors-page.js',
                          'js/battles-overview.js', 'js/dashboard.js', 'js/player.js',
                          'js/admin/core/utils.js'];
const зовыНаЗагрузке = [];
ПОТРЕБИТЕЛИ_ДОМА.forEach(ф => {
    let т;
    try { т = дерево(чит(ф)); } catch (e) { return; }
    /* НЕМЕДЛЕННО ВЫЗВАННАЯ ФУНКЦИЯ ПРОЗРАЧНА, И ЭТО ПОЙМАЛ ПРУВЕР. Первая
       версия считала «в функции» любое тело — а ВЕСЬ код продукта обёрнут в
       IIFE, значит правило не упало бы никогда: откат это и показал. Тело
       IIFE выполняется синхронно при загрузке файла, поэтому зов в нём —
       зов НА ЗАГРУЗКЕ. Обработчик события (аргумент `addEventListener`) —
       настоящая функция, и зов в нём случается позже. */
    (function ход(у, вФункции, родитель) {
        if (!у || typeof у !== 'object') return;
        if (у.type === 'CallExpression' && у.callee && у.callee.type === 'MemberExpression' &&
            у.callee.object && у.callee.object.type === 'MemberExpression' &&
            у.callee.object.property && у.callee.object.property.name === 'KSLT_FOKUS' && !вФункции) {
            зовыНаЗагрузке.push(ф + ':' + у.loc.start.line);
        }
        const немедленная = /Function/.test(у.type) && родитель &&
            родитель.type === 'CallExpression' && родитель.callee === у;
        const этоФункция = /Function/.test(у.type) && !немедленная;
        for (const к in у) {
            if (к === 'loc') continue;
            const з = у[к];
            if (Array.isArray(з)) з.forEach(д => ход(д, вФункции || этоФункция, у));
            else if (з && typeof з === 'object' && з.type) ход(з, вФункции || этоФункция, у);
        }
    })(т, false, null);
});
правило('дом не зовётся на загрузке — иначе порядок тегов станет важен',
    зовыНаЗагрузке.length === 0,
    'Зовут дом на верхнем уровне файла: ' + зовыНаЗагрузке.join(', ') + '.\n' +
    'Все скрипты продукта обычные и стоят в `<body>`, ни одного `defer` или\n' +
    '`async`: зов на загрузке означает, что дом ОБЯЗАН стоять раньше этого\n' +
    'файла на каждой из 81 страницы, иначе `KSLT_FOKUS is undefined`.\n' +
    'Сегодня все одиннадцать зовов живут внутри функций открытия окна.');

