/**
 * ЗАМОРОЗКА КУСКА 142 — СОТРУДНИК КЛУБА НЕ ЧЛЕН КЛУБА.
 *
 * ЧТО БЫЛО. Одно понятие — «сотрудник под рабочей почтой не играет» —
 * было определено в коде ТРИЖДЫ и в разные стороны:
 *   · `js/dashboard.js` не предлагал сотруднику привязать карточку игрока
 *     («под рабочей почтой они не играют») — это и есть решение;
 *   · `js/membership.js` с 03.03 (коммит 0663822) отдавал роли `admin` и
 *     `manager` `{active: true, paid: true, staff_bypass: true}`, не
 *     глядя в базу, — то есть делал сотрудника членом клуба;
 *   · `js/tournament-detail.js` выдавал роли членство И оплату напрямую
 *     (`membershipOk = isStaff`), минуя зов.
 *
 * ПОМЕРЕНО ПЕРЕД ПРАВКОЙ, А НЕ ПОСЛЕ:
 *   · без `player_id` кнопка записи на турнир не рисуется вовсе, а
 *     сотруднику карточку не привязывают — значит ветвь роли в заявке
 *     работала только у сотрудника С карточкой;
 *   · кабинет без действующего членства ЗАПИРАЕТ «Турниры» и «Статистику»
 *     замком с предложением оплатить. Поэтому снятие обхода без второй
 *     правки заперло бы кабинет самому админу: он не «не заплатил», он НЕ
 *     ИГРАЕТ. Отсюда ветвь в кабинете, а не «забыли».
 *
 * РОЛЬ ДАЁТ ДОСТУП В АДМИНКУ, А НЕ ЧЛЕНСТВО И НЕ ИГРУ.
 *
 * ПРЕДИКАТ РОЛИ БЫЛ НАПИСАН В КОДЕ САЙТА ШЕСТЬ РАЗ. Три копии кабинета
 * сведены в дом; три оставшиеся — `auth-guard.js`, `auth-nav.js`,
 * `auth.js` — стоят на 80 страницах, где дома нет, и держатся ХРАПОВИКОМ:
 * потолок равен замеренному, рост роняет правило.
 *
 *   node tools/check-sotrudnik-ne-chlen.js
 */
const fs = require('fs');
const path = require('path');
const acorn = require('acorn');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const ПОТОЛОК_КОПИЙ = 3;   /* auth-guard.js, auth-nav.js, auth.js */
const КАБИНЕТЫ = ['pages/dashboard.html', 'pages/dashboard-en.html', 'pages/dashboard-kg.html'];

/* обход дерева с родителями: правило держится на дереве, а не на тексте —
   иначе падает на собственном комментарии (восьмой раз за ветку). */
function обойти(узел, дело, род) {
    if (!узел || typeof узел.type !== 'string') return;
    дело(узел, род);
    for (const к of Object.keys(узел)) {
        if (к === 'type' || к === 'start' || к === 'end' || к === 'loc') continue;
        const v = узел[к];
        if (Array.isArray(v)) v.forEach(x => x && typeof x.type === 'string' && обойти(x, дело, узел));
        else if (v && typeof v.type === 'string') обойти(v, дело, узел);
    }
}
function дерево(т) { return acorn.parse(т, { ecmaVersion: 2020, locations: true }); }

/* сравнение роли со строкой сотрудника — ровно тот предикат, о котором
   кусок: `х === 'admin'` или `х === 'manager'` где угодно в коде. */
function копииПредиката(т) {
    /* СЧИТАЮТСЯ МЕСТА, А НЕ СРАВНЕНИЯ. Первая запись правила считала
       `role === 'admin' || role === 'manager'` ДВУМЯ копиями — потолок 3
       показал 5 на трёх файлах. Одно место — одна строка. */
    const строки = new Set();
    обойти(дерево(т), у => {
        if (у.type === 'BinaryExpression' && у.operator === '===' &&
            у.right && у.right.type === 'Literal' &&
            (у.right.value === 'admin' || у.right.value === 'manager')) {
            строки.add(у.loc.start.line);
        }
        /* список ролей массивом — то же понятие другим написанием */
        if (у.type === 'ArrayExpression' && у.elements.length === 2 &&
            у.elements.every(э => э && э.type === 'Literal') &&
            у.elements.map(э => э.value).sort().join(',') === 'admin,manager') {
            строки.add(у.loc.start.line);
        }
    });
    return [...строки];
}

/* ---- 1. членство не выдаётся по роли ---- */
const ЧЛЕНСТВО = чит('js/membership.js');
правило('членство не выдаётся по роли',
    копииПредиката(ЧЛЕНСТВО).length === 0,
    'В `js/membership.js` снова сравнивают роль с «admin»/«manager»:\n' +
    '  строки ' + копииПредиката(ЧЛЕНСТВО).join(', ') + '\n' +
    'Обход по роли и есть беда куска: он делал сотрудника членом клуба,\n' +
    'противореча решению кабинета «под рабочей почтой они не играют».');

/* `staff_bypass` жил не только в членстве: три страницы цен прятали по\n   нему состояние. Поле снято — его следов быть не должно нигде. */
const следы = [];
(function обход(д) {
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = path.join(д, э.name);
        if (э.isDirectory()) { if (!/^(node_modules|\.git|mobile|test-results|playwright-report|archive|slepki)$/.test(э.name)) обход(п); return; }
        if (!/\.(js|html)$/.test(э.name)) return;
        if (п === path.join('tools', 'check-sotrudnik-ne-chlen.js')) return;
        if (/check-sotrudnik-ne-chlen-otkat\.js$/.test(п)) return;
        /* ПРОБА КУСКА НАЗЫВАЕТ ПРИЗНАК, ЧТОБЫ ПОТРЕБОВАТЬ ЕГО ОТСУТСТВИЯ —
           это не след обхода, а его сторож с другой стороны. Правило
           поймало её на первом же прогоне, и это честно: имя признака
           действительно встречается. Исключение названо ОДНИМ файлом, а не
           папкой `tests`, иначе в тестах признак сможет ожить. */
        if (/142-sotrudnik\.spec\.js$/.test(п)) return;
        const т = fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8');
        /* дерево здесь не поможет: половина мест — html; но имя поля
           придумано нами и в прозе не встречается, кроме этого файла */
        т.split('\n').forEach((л, i) => { if (л.indexOf('staff_bypass') !== -1) следы.push(п + ':' + (i + 1)); });
    });
})('.');
правило('следов обхода по роли не осталось',
    следы.length === 0,
    'Поле `staff_bypass` снова встречается:\n' + следы.slice(0, 8).map(с => '  ' + с).join('\n') + '\n' +
    'Оно было признаком обхода, и после куска 142 признака нет — значит\n' +
    'и проверок на него быть не должно: МЁРТВАЯ ПРОВЕРКА ХУЖЕ ОТСУТСТВИЯ.');

/* ---- 2. турнирная заявка не смотрит на роль ---- */
const ТУРНИР = чит('js/tournament-detail.js');
let членствоСРоли = null;
обойти(дерево(ТУРНИР), у => {
    if (у.type === 'VariableDeclarator' && у.id && у.id.name === 'membershipOk') {
        членствоСРоли = у.init ? ТУРНИР.slice(у.init.start, у.init.end) : null;
    }
});
правило('турнирная заявка начинает с «членства нет»',
    членствоСРоли === 'false',
    'Было `var membershipOk = ' + членствоСРоли + '`.\n' +
    'Роль не даёт ни членства, ни оплаты: заявка спрашивает базу, как у\n' +
    'всех. Померено: без `player_id` кнопка записи не рисуется вовсе.');

правило('в турнирной заявке нет своего предиката роли',
    копииПредиката(ТУРНИР).length === 0,
    'В `js/tournament-detail.js` снова сравнивают роль: строки ' +
    копииПредиката(ТУРНИР).join(', ') + '.');

/* ---- 3. предикат живёт в доме ---- */
const ДОСТУП = чит('js/kslt-dostup.js');
let предикатВДоме = false;
обойти(дерево(ДОСТУП), (у, род) => {
    if (у.type === 'FunctionExpression' && род && род.type === 'AssignmentExpression' &&
        ДОСТУП.slice(род.left.start, род.left.end) === 'Д.сотрудникПоРоли') предикатВДоме = true;
});
правило('предикат сотрудника объявлен в доме доступа',
    предикатВДоме,
    'В `js/kslt-dostup.js` нет `Д.сотрудникПоРоли`. Понятие «сотрудник —\n' +
    'это роль» должно быть объявлено один раз, иначе кабинет снова\n' +
    'напишет его себе сам, и копий станет семь.');

/* ---- 4. кабинет зовёт дом, а не пишет предикат сам ---- */
const КАБИНЕТ = чит('js/dashboard.js');
let зововПредиката = 0;
обойти(дерево(КАБИНЕТ), у => {
    if (у.type === 'CallExpression' &&
        КАБИНЕТ.slice(у.callee.start, у.callee.end) === 'KSLT_DOSTUP.сотрудникПоРоли') зововПредиката++;
});
правило('кабинет зовёт предикат дома',
    зововПредиката === 4,
    'Зовов `KSLT_DOSTUP.сотрудникПоРоли` в кабинете: ' + зововПредиката + ', замерено 4\n' +
    '(подсказка карточки игрока, бейдж роли, разделы «Игры», членство).');

правило('кабинет не пишет предикат роли сам',
    копииПредиката(КАБИНЕТ).length === 0,
    'В `js/dashboard.js` снова сравнивают роль со строкой: строки ' +
    копииПредиката(КАБИНЕТ).join(', ') + '.\n' +
    'Это понятие живёт в доме; своя копия — вторая правда о сотруднике.');

/* ---- 5. кабинет не предлагает членства сотруднику ---- */
let членствоПодУсловием = false;
{
    /* РОДИТЕЛИ БЕРУТСЯ ИЗ ТОГО ЖЕ РАЗБОРА. Первая запись строила карту по
       одному дереву, а искала по второму — узлы разные объекты, и путь
       вверх обрывался на первом шаге: правило врало в «не держится». */
    const дер = дерево(КАБИНЕТ);
    const родители = new Map();
    обойти(дер, (у, род) => { родители.set(у, род); });
    обойти(дер, у => {
        if (у.type === 'CallExpression' &&
            КАБИНЕТ.slice(у.callee.start, у.callee.end) === 'renderMembershipCard') {
            let p = родители.get(у);
            while (p) {
                if (p.type === 'IfStatement' && p.test &&
                    КАБИНЕТ.slice(p.test.start, p.test.end).indexOf('сотрудникПоРоли') !== -1) {
                    членствоПодУсловием = true; break;
                }
                p = родители.get(p);
            }
        }
    });
}
правило('кабинет не предлагает членство сотруднику',
    членствоПодУсловием,
    'Зов `renderMembershipCard()` больше не укрыт условием о роли.\n' +
    'БЕЗ ЭТОГО УСЛОВИЯ КАБИНЕТ АДМИНА ЗАПИРАЕТ «Турниры» и «Статистику»\n' +
    'замком «оплатите членство» — замерено: `applyMembershipRestrictions`\n' +
    'ставит замок всем, у кого членства нет.');

/* ---- 6. храповик копий предиката по сайту ---- */
const копии = [];
(function обход(д) {
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = path.join(д, э.name);
        if (э.isDirectory()) { if (!/^(node_modules|admin)$/.test(э.name)) обход(п); return; }
        if (!э.name.endsWith('.js')) return;
        if (/kslt-dostup\.js$/.test(п)) return;
        let т;
        try { т = fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8'); } catch (e) { return; }
        let строки;
        try { строки = копииПредиката(т); } catch (e) { return; }
        строки.forEach(л => копии.push(п + ':' + л));
    });
})('js');
правило('копий предиката роли по сайту не прибавилось',
    копии.length <= ПОТОЛОК_КОПИЙ,
    'Копий предиката «сотрудник» вне дома: ' + копии.length + ', потолок ' + ПОТОЛОК_КОПИЙ + '\n' +
    копии.map(с => '  ' + с).join('\n') + '\n' +
    'Три законные — `auth-guard.js`, `auth-nav.js`, `auth.js`: они стоят на\n' +
    '80 страницах, где дома нет, и ждут своего куска.');
правило('потолок копий не завышен',
    копии.length >= ПОТОЛОК_КОПИЙ,
    'Копий ' + копии.length + ' при потолке ' + ПОТОЛОК_КОПИЙ + ' — ХРАПОВИК ОПУСКАЕТСЯ:\n' +
    'поправь ПОТОЛОК_КОПИЙ на ' + копии.length + '.');

/* ---- 7. дом подключён в кабинете раньше своего потребителя ---- */
const поздние = [];
КАБИНЕТЫ.forEach(с => {
    const т = чит(с);
    const дом = т.indexOf('kslt-dostup.js');
    const каб = т.indexOf('dashboard.js');
    if (дом === -1 || каб === -1 || дом > каб) поздние.push(с);
});
правило('дом доступа стоит в кабинете раньше dashboard.js',
    поздние.length === 0,
    'Страницы, где дома нет или он позже потребителя:\n' +
    поздние.map(с => '  ' + с).join('\n') + '\n' +
    'Все скрипты продукта обычные и в `<body>`: поздний дом — это падение\n' +
    'на первом же зове предиката, а не задержка.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      сотрудник не член клуба: ' +
        (fs.readFileSync(__filename, 'utf8').match(/правило\('/g) || []).length + ' правил');
    console.log('          роль даёт доступ в админку, а не членство и не игру');
    console.log('          копий предиката вне дома: ' + копии.length + ' из ' + ПОТОЛОК_КОПИЙ +
                ' (auth-guard, auth-nav, auth)');
    console.log('');
} else {
    console.log('');
    console.log('  НЕ ТАК  сотрудник не член клуба — ' + ошибки.length + ' правил не держится');
    console.log('');
    ошибки.forEach(([и, п]) => {
        console.log('          x ' + и);
        п.split('\n').forEach(л => console.log('            ' + л));
        console.log('');
    });
    process.exit(1);
}
