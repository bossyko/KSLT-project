#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ИМЯ ЛИГИ — ОДНО ОПРЕДЕЛЕНИЕ» (06.11).
 *
 * СЛОВО КОСТИ 06.11: по-русски и по-кыргызски имя пишется кириллицей
 * («КСЛТ»), по-английски латиницей («KSLT»).
 *
 * ЧТО БЫЛО ПОМЕРЕНО ДО ПРАВКИ. На 95 страницах заголовок расходился с
 * этим правилом в 29 местах, причём ВНУТРИ одного языка: кыргызские
 * `sponsors-kg`, `pricing-kg`, `faq-kg`, `delete-account-kg` несли
 * кириллицу, а остальные кыргызские — латиницу. В коде заголовок
 * собирался в ОДИННАДЦАТИ местах пятью разными способами:
 * `courts.js`, `coaches.js`, `news.js` писали латиницу всегда,
 * `tournament-detail.js` считал кыргызский латинским, а `player.js`
 * ставил имя в конец. Одно понятие, шесть определений.
 *
 * ЧТО СТЕРЕЖЁТ.
 *   · имя лиги задаётся ровно один раз — `Я.имя` в доме языка;
 *   · ни один файл сайта не собирает заголовок вкладки из литерала;
 *   · заголовок каждой страницы несёт имя, положенное её языку.
 *
 * НАЗВАНИЕ ПРИЛОЖЕНИЯ «KSLT Tennis» — ДРУГОЕ ПОНЯТИЕ. Это имя продукта
 * в магазинах, оно латинское на всех языках, и страницы `download*`
 * законно несут его как есть.
 *
 *   node tools/check-imya-ligi.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ДОМ = 'js/kslt-yazyk.js';
const ПРИЛОЖЕНИЕ = 'KSLT Tennis';

function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function страницы() {
    const из = [];
    for (const д of ['.', 'pages']) {
        const п = path.join(КОРЕНЬ, д);
        if (!fs.existsSync(п)) continue;
        for (const и of fs.readdirSync(п)) {
            if (!и.endsWith('.html') || и === '_preview-mobile.html') continue;
            из.push(д === '.' ? и : д + '/' + и);
        }
    }
    return из;
}
function скрипты() {
    const п = path.join(КОРЕНЬ, 'js');
    if (!fs.existsSync(п)) return [];
    return fs.readdirSync(п).filter(и => и.endsWith('.js')).map(и => 'js/' + и);
}
function язык(ф) {
    const б = path.basename(ф);
    if (б.indexOf('-en.') !== -1) return 'en';
    if (б.indexOf('-kg.') !== -1) return 'kg';
    return 'ru';
}

const дом = чит(ДОМ) || '';
const домОпр = (дом.match(/Я\.имя\s*=/g) || []).length;

/* Литерал имени лиги в коде — любое «KSLT»/«КСЛТ» в кавычках. В доме
   языка он законен: там он и определён. */
const литералы = [];
for (const ф of скрипты()) {
    if (ф === ДОМ) continue;
    const т = чит(ф) || '';
    const стр = т.split('\n');
    for (let i = 0; i < стр.length; i++) {
        const с = стр[i];
        if (с.indexOf(ПРИЛОЖЕНИЕ) !== -1) continue;
        /* ТОЛЬКО ЗАГОЛОВОК ВКЛАДКИ. Прежняя проверка ловила `title =`
           где угодно и поймала семнадцать мест, где имя лиги стоит в
           подписи ссылки, в alt картинки и в письме — это другое
           понятие, и к заголовку вкладки отношения не имеет.
           ПРАВИЛО, КОТОРОЕ ЛОВИТ СЛОВО ГДЕ УГОДНО, НЕ ЛОВИТ НИЧЕГО. */
        if (/['"][^'"]*(?:KSLT|КСЛТ)[^'"]*['"]/.test(с) && /document\.title\s*=/.test(с)) {
            литералы.push(ф + ':' + (i + 1));
        }
    }
}

const расходятся = [];
const безИмени = [];
for (const ф of страницы()) {
    const т = чит(ф) || '';
    const м = т.match(/<title>([\s\S]*?)<\/title>/);
    if (!м) { безИмени.push(ф + ' (нет <title>)'); continue; }
    const t = м[1].trim();
    if (t.indexOf(ПРИЛОЖЕНИЕ) !== -1) continue;
    const я = язык(ф);
    const чужое = я === 'en' ? 'КСЛТ' : 'KSLT';
    if (t.indexOf(чужое) !== -1) расходятся.push(ф + ' | ' + t);
}

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя: имя, подсказка: подсказка });
}

правило('имя лиги определено один раз и в доме языка',
    домОпр === 1,
    'В `' + ДОМ + '` найдено определений `Я.имя`: ' + домОпр + '.\n' +
    'Имя лиги — одно понятие. Два определения разойдутся молча, и\n' +
    'разойдутся они по языкам, то есть там, где их реже всего смотрят.');

правило('заголовок вкладки не собирается из литерала',
    литералы.length === 0,
    'Имя лиги вписано прямо в код: ' + литералы.map(м => '\n  ' + м).join('') +
    '\nЗаголовок вкладки собирает `KSLT_YAZYK.заголовок(хвост)`, а имя\n' +
    'берётся из `KSLT_YAZYK.имя`. Литерал в коде — это второе\n' +
    'определение понятия, и именно так кыргызский оказался латинским в\n' +
    '`tournament-detail.js`, а в `courts.js` латиница стояла всегда.');

правило('имя в заголовке страницы отвечает её языку',
    расходятся.length === 0,
    'Заголовок несёт чужое написание имени: ' +
    расходятся.map(с => '\n  ' + с).join('') +
    '\nПо-русски и по-кыргызски — «КСЛТ», по-английски — «KSLT»\n' +
    '(слово Кости 06.11). Название приложения «KSLT Tennis» это\n' +
    'правило не трогает: оно латинское на всех языках.');

правило('у каждой страницы есть заголовок',
    безИмени.length === 0,
    'Страницы без `<title>`: ' + безИмени.map(с => '\n  ' + с).join(''));

if (ошибки.length) {
    console.log('НЕ ТАК  имя лиги: ' + ошибки.length + ' из 4 правил упало\n');
    for (const о of ошибки) console.log('  ✗ ' + о.имя + '\n    ' + о.подсказка.replace(/\n/g, '\n    ') + '\n');
    process.exit(1);
}
console.log('ок      имя лиги: 4 правила, ' + страницы().length + ' страниц');
