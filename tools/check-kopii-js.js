const РАВНЫХ_НЕ_МЕНЬШЕ = 40;
const РАЗНЫХ_НЕ_БОЛЬШЕ = 7;

function файлы(каталог) {
    const п = path.join(КОРЕНЬ, каталог);
    if (!fs.existsSync(п)) return [];
    return fs.readdirSync(п).filter(f => f.endsWith('.js'));
}

const сайт = файлы('js');
const прил = файлы('mobile/www/js');
const общие = сайт.filter(f => прил.indexOf(f) !== -1).sort();

const равны = [], разные = [];
общие.forEach(f => {
    const a = fs.readFileSync(path.join(КОРЕНЬ, 'js', f));
    const b = fs.readFileSync(path.join(КОРЕНЬ, 'mobile/www/js', f));
    (a.equals(b) ? равны : разные).push(f);
});

