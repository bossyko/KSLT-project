const JSФ = [];
(function обойтиJS(д) {
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) {
            if (/node_modules|\.git|tests|mobile|_sync|dist|build|tools|maket/.test(э.name)) return;
            обойтиJS(п);
        } else if (э.name.endsWith('.js')) JSФ.push(п.replace(/^\.\//, ''));
    });
})('.');
const JS = {};
JSФ.forEach(ф => { JS[ф] = чит(ф); });

