const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const есть = ф => fs.existsSync(path.join(КОРЕНЬ, ф));
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, '');
/* ДЛИНА СОХРАНЯЕТСЯ — иначе номер строки врёт. Комментарий гасится
   пробелами по месту, а переводы строк остаются: только так найденное
   в очищенном тексте можно показать номером строки исходного. */
const безКомРовно = s => s.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));
/* подключение скриптом, а не упоминание в тексте страницы */
const подключён = (html, ф) =>
    new RegExp('<script[^>]+src=["\'][^"\']*' + ф.replace(/[/.]/g, '\\$&') + '[^"\']*["\']').test(html);

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ---- что читаем ---- */
const CSSФ = fs.readdirSync(path.join(КОРЕНЬ, 'css')).filter(ф => ф.endsWith('.css'));
const CSS = {};
CSSФ.forEach(ф => { CSS['css/' + ф] = чит('css/' + ф); });

const HTMLФ = [];
(function обойти(д) {
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) {
            if (/node_modules|\.git|tests|mobile|_sync|dist|build/.test(э.name)) return;
            обойти(п);
        } else if (э.name.endsWith('.html')) HTMLФ.push(п.replace(/^\.\//, ''));
    });
})('.');
const HTML = {};
HTMLФ.forEach(ф => { HTML[ф] = чит(ф); });

const ТОКЕНЫ = чит('css/tokens.css');
