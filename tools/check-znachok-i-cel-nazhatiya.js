/**
 * ЗАМОРОЗКА КУСКА 124 — ЗНАЧКОВАЯ КНОПКА АДМИНКИ.
 *
 * `.ad-btn-icon` был определён в admin.css ДВАЖДЫ — на :2626 и на :5907,
 * и `:hover` тоже дважды. Браузер брал свойства ВПЕРЕМЕШКУ из обоих:
 * размер, flex и цвет из первого, отсутствие рамки, кегль, отступ и
 * переход из второго. Мёртвыми лежали `border: 1px solid`, `font-size:
 * --fs-md`, `transition: all` и при наведении `border-color` — рисовать
 * нечего, рамки нет. Комментарий у `.ad-reg-act` ссылался на первое
 * правило, будто второго не существует. Ровно та же беда, что с
 * `.ad-btn-sm` 28.09, и шов на том же месте.
 *
 * Замерено в браузере 22.10 ДО свёртки, на трёх видах админки: 32×32
 * (одна 28–30 — её жал flex), кегль 16, отступ 4, рамки нет, цвет
 * --text-muted, контраст к фону 5.33, наведение — фон --alpha-white-08
 * и цвет --danger. Свёрнуто в одно правило ЭТИМ замером.
 *
 * 32 не было ни одной ступенью шкалы кнопок (28 · 36 · 44 · 52,
 * tokens.css:501). Цель нажатия 44 не выполнялась ни у одной из 22
 * кнопок, прозрачного слоя не было ни у одной.
 *
 * Вариантов было померено четыре, ДО правки файла, одним прогоном
 * (maket/znachok-varianty.html). Слой 44 при кнопке 32, стоящей
 * СТОЛБИКОМ, съедал три точки из девяти у соседней кнопки: «Отозвать»
 * перекрывал «Удалить рассылку». Поэтому значок 36, значки в ряд с
 * зазором 8, слой 44 — зона ровно 44×44 и ни одного перекрытия на всех
 * трёх видах.
 *
 * СТОЛБИК БЫЛ НЕ ЗАДУМАН. Значок — flex-контейнер, то есть блок, и два
 * значка в одной ячейке встают один под другим. `text-align: right` и
 * `white-space: nowrap`, которые в тех ячейках стояли, на блоки не
 * действуют — автор ждал ряд и его не получил. Замерено: сдвиг вниз 32.
 *
 *   node tools/check-znachok-i-cel-nazhatiya.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const AD = чит('css/admin.css');
const NT = чит('js/admin/sections/notifications.js');
const PL = чит('js/admin/sections/players.js');
const VC = чит('js/admin/sections/vouchers.js');

/* ── 1. ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ ──────────────────────────────── */
/* Якорь на начало строки: `.ad-btn-icon {` внутри `.a, .ad-btn-icon {`
   был бы другим понятием — групповым правилом, а не определением. */
const определений = (AD.match(/^\.ad-btn-icon \{/gm) || []).length;
правило('`.ad-btn-icon` определён ровно один раз',
    определений === 1,
    'Определений `.ad-btn-icon { … }` в admin.css: ' + определений + ', а должно быть одно.\n' +
    'Их было два, и браузер брал свойства из обоих вперемешку — именно так\n' +
    'лежали мёртвыми рамка, кегль и переход. ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ.');

const наведений = (AD.match(/^\.ad-btn-icon:hover \{/gm) || []).length;
правило('`.ad-btn-icon:hover` объявлен ровно один раз',
    наведений === 1,
    'Правил `.ad-btn-icon:hover { … }`: ' + наведений + ', а должно быть одно.\n' +
    'Их было два: одно давало фон, другое цвет и мёртвый `border-color`.\n' +
    'Оба срабатывали, и ни одно не было видно целиком.');

/* ── 2. БЛОК НА МЕСТЕ И СТОИТ НА ШКАЛЕ ────────────────────────────────── */
const блок = (function () {
    const i = AD.search(/^\.ad-btn-icon \{/m);
    return i === -1 ? '' : AD.slice(i, AD.indexOf('}', i) + 1);
})();
правило('блок значковой кнопки найден',
    блок.length > 0,
    'Не нашёл `.ad-btn-icon { … }` в admin.css — правила ниже искали бы\n' +
    'в пустоте. ПРОВЕРКА, КОТОРАЯ ИЩЕТ В ПУСТОМ, ЗЕЛЕНЕЕТ ВСЕГДА.');

правило('размер значка — ступень шкалы, а не число',
    /width:\s*var\(--btn-h-sm\)/.test(блок) && /height:\s*var\(--btn-h-sm\)/.test(блок) &&
    !/\d+px/.test(блок),
    'Размер значка ушёл со ступени. Было 32px — его нет в шкале кнопок\n' +
    '(28 · 36 · 44 · 52, tokens.css:501); стоит --btn-h-sm = 36.\n' +
    'Зашитых пикселей в блоке быть не должно ни одного.');

правило('значок держит ширину в тесной строке формы',
    /flex-shrink:\s*0/.test(блок),
    'Снят `flex-shrink: 0`. Без него flex жмёт значок в строке формы:\n' +
    'замерено до правки — 30px на 1440, 29.1 на 1024, 28 на 768, то есть\n' +
    'заданная ширина не держалась ни на одном виде.');

правило('значок — опора для своего слоя нажатия',
    /position:\s*relative/.test(блок),
    'Снят `position: relative`. Прозрачный слой `::before` позиционируется\n' +
    'ОТ НЕГО; без опоры слой уедет к ближайшему позиционированному предку\n' +
    'или к странице, и цель нажатия окажется не над кнопкой.');

/* ── 3. ЦЕЛЬ НАЖАТИЯ 44 ───────────────────────────────────────────────── */
const слой = (function () {
    const i = AD.indexOf('.ad-btn-icon::before {');
    return i === -1 ? '' : AD.slice(i, AD.indexOf('}', i) + 1);
})();
правило('у значка есть прозрачный слой нажатия',
    слой.length > 0,
    'Нет `.ad-btn-icon::before` — цель нажатия вернулась к размеру значка,\n' +
    'то есть к 36 против нормы 44. Эталон слоя — `.ad-bulk-item::before`\n' +
    '(решение 04.10).');

правило('слой нажатия ровно 44 на 44, ступенью, а не числом',
    /width:\s*var\(--btn-h-md\)/.test(слой) && /height:\s*var\(--btn-h-md\)/.test(слой),
    'Слой перестал быть 44×44 (--btn-h-md). Замерено 22.10 на трёх видах:\n' +
    'зона нажатия 44×44 у всех десяти кнопок стенда и ни одного перекрытия\n' +
    'с соседней кнопкой или полем.');

правило('слой вынут из потока и не толкает значок',
    /position:\s*absolute/.test(слой) &&
    /transform:\s*translate\(-50%,\s*-50%\)/.test(слой),
    'Слой перестал быть `absolute` с переносом на половину. Значок — flex-\n' +
    'контейнер: слой в потоке стал бы его flex-элементом и сдвинул бы знак\n' +
    'в сторону. Вне потока он не влияет на раскладку вовсе.');

/* ── 4. ЗНАЧКИ СТОЯТ В РЯД ────────────────────────────────────────────── */
const ряд = (function () {
    const i = AD.indexOf('.ad-icon-row {');
    return i === -1 ? '' : AD.slice(i, AD.indexOf('}', i) + 1);
})();
правило('обёртка ряда значков есть и даёт зазор',
    /display:\s*flex/.test(ряд) && /gap:\s*var\(--space-2\)/.test(ряд),
    'Обёртка `.ad-icon-row` пропала или потеряла зазор. На зазоре 8 держится\n' +
    'цель 44: без него слои соседних значков наезжают друг на друга, и\n' +
    'замер показал три точки перекрытия из девяти.');

/* ПРОВЕРЯЕМ ВСЕ ТРИ МЕСТА, А НЕ ОДНО. Ячеек с двумя значками ровно три, и
   правило, которому хватает одной, сторожит треть. */
правило('все три ячейки с двумя значками обёрнуты в ряд',
    /class="ad-icon-row">' \+ actions \+ '<\/div><\/td>'/.test(NT) &&
    /class="ad-icon-row">' \+\n/.test(PL) &&
    /class="ad-icon-row">' \+ actionHtml \+ '<\/div><\/td>'/.test(VC),
    'Одна из трёх ячеек потеряла обёртку: журнал рассылок (notifications.js),\n' +
    'история рейтинга (players.js) или список ваучеров (vouchers.js).\n' +
    'Без обёртки значки встают СТОЛБИКОМ — замерено, сдвиг вниз 32, — и ни\n' +
    '`text-align: right`, ни `white-space: nowrap` этого не меняют.');

/* ПРИЗНАК БЕРЁТ ВСЮ ЯЧЕЙКУ, А НЕ СТЫК. Первая версия искала `nowrap;">'
   + actions` — то есть требовала, чтобы мусор стоял ВПЛОТНУЮ к значкам.
   Прувер показал: `nowrap` возвращается вместе с обёрткой, между ними
   встаёт `<div class="ad-icon-row">`, и правило молчит. */
const ячейкаЗначков = (файл, имяПеременной) => {
    const i = файл.indexOf("' + " + имяПеременной + " + '</div></td>'");
    if (i === -1) return '';
    return файл.slice(файл.lastIndexOf("'<td", i), i);
};
правило('`white-space: nowrap` не вернулся туда, где он ничего не держал',
    !/nowrap/.test(ячейкаЗначков(NT, 'actions')) &&
    !/nowrap/.test(ячейкаЗначков(VC, 'actionHtml')),
    'В ячейку значков вернулся `white-space: nowrap`. На блочные значки он\n' +
    'не действовал и до правки — это и было замерено; ряд их держит\n' +
    'обёрткой, а не переносом строк.');

/* ── 5. У КАЖДОГО ЗНАЧКА ЕСТЬ ДОСТУПНОЕ ИМЯ ───────────────────────────── */
/* Значок сам по себе не говорит диктору ничего: «×», «↩», «👁». Замерено
   22.10: из 22 кнопок админки `aria-label` не было НИ У ОДНОЙ, а `title`
   — у одиннадцати. Среди безымянных — удаление строки формы, среди
   названных одним `title` — «Удалить рассылку». */
const РАЗДЕЛЫ = ['coaches', 'courts', 'notifications', 'players', 'settings', 'vouchers']
    .map(и => ['js/admin/sections/' + и + '.js', чит('js/admin/sections/' + и + '.js')]);
const значки = [];
РАЗДЕЛЫ.forEach(([имя, текст]) => {
    /* ТЕГ СКЛЕИВАЕТСЯ В ОДНУ СТРОКУ ДО РАЗБОРА. В двух местах разметка
       разорвана переносом ради ширины колонки, и признак, читающий текст
       как есть, принял обрывок `' +` за подпись — правило упало на коде,
       где всё верно. Прибор обязан видеть тег целиком, а не его кусок. */
    (текст.match(/<button[^>]*ad-btn-icon[^>]*>/g) || [])
        .forEach(т => значки.push([имя, т.replace(/\s+/g, ' ')]));
});

правило('значковые кнопки найдены, и их 22',
    значки.length === 22,
    'Значковых кнопок в разделах админки: ' + значки.length + ', а замерено 22.\n' +
    'Меньше — часть исчезла или сменила класс; больше — завелась новая, и её\n' +
    'подпись никто не мерил. ПРОВЕРКА, КОТОРАЯ ИЩЕТ В ПУСТОМ, ЗЕЛЕНЕЕТ ВСЕГДА.');

const безПодписи = значки.filter(([, т]) => т.indexOf('aria-label') === -1);
правило('у каждой значковой кнопки есть доступное имя',
    безПодписи.length === 0,
    'Без `aria-label` осталось ' + безПодписи.length + ':\n' +
    безПодписи.map(([и, т]) => '  ' + и + ': ' + т.slice(0, 90)).join('\n') + '\n' +
    'Диктор прочитает сам знак — «×» или «↩», — и человек не узнает, что\n' +
    'одна из этих кнопок удаляет рассылку.');

/* ОДИН ТЕКСТ НА КНОПКУ. `title` и `aria-label` обязаны брать его из
   ОДНОГО выражения, иначе это два определения одного понятия и они
   разойдутся на первой же правке слов. */
const вразнобой = значки.filter(([, т]) => {
    const t = т.match(/title="([^"]*)"/), a = т.match(/aria-label="([^"]*)"/);
    return t && a && t[1] !== a[1];
});
правило('подпись и подсказка значка — один текст, а не два',
    вразнобой.length === 0,
    'Разошлись у ' + вразнобой.length + ':\n' +
    вразнобой.map(([и, т]) => '  ' + и + ': ' + т.slice(0, 110)).join('\n') + '\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: оба атрибута берут один ключ словаря.');

/* ПОДПИСЬ ЖИВЁТ В СЛОВАРЕ, А НЕ В РАЗМЕТКЕ. Четыре подписи значков были
   зашиты литералом — `('Изменить')`, `('Просмотр')`, `('Убрать')`,
   `('Удалить')`, остаток свёртки английской ветки (кусок 118). */
const зашитые = значки.filter(([, т]) => /aria-label="[^"'+]*[А-Яа-яЁё]/.test(т));
правило('подписи значков берутся из словаря, а не зашиты в разметке',
    зашитые.length === 0,
    'Зашито прямо в разметке ' + зашитые.length + ':\n' +
    зашитые.map(([и, т]) => '  ' + и + ': ' + т.slice(0, 110)).join('\n') + '\n' +
    'Слова админки живут в `constants.js` одним списком — иначе правка слова\n' +
    'идёт по шести файлам и забывает один.');

/* ── вывод ───────────────────────────────────────────────────────────── */
console.log('');
if (ошибки.length) {
    console.log('  НЕ ТАК  значок и цель нажатия — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(([и, п]) => console.log('          ✗ ' + и + '\n            ' + п.replace(/\n/g, '\n            ') + '\n'));
    process.exit(1);
}
console.log('  ок      значок и цель нажатия: 15 правил');
console.log('          одно определение вместо двух, одно наведение вместо двух');
console.log('          значок 36 ступенью, слой 44, ряд с зазором 8 в трёх местах');
console.log('          все 22 значка подписаны, подпись и подсказка — один текст');
console.log('');
