/**
 * ЗАМОРОЗКА: ПОЛОСА ПРОГНОЗА ВЫКЛЮЧЕНА, И ВЫКЛЮЧАТЕЛЬ ОДИН.
 *
 * Решение Кости 02.10: до декабря прогноз не показываем. Причина — не
 * формула, а вход: `players.points` это очки за МЕСТА, и обыграть первую
 * ракетку стоит столько же, сколько обыграть новичка.
 *
 * ЧИСЛА, ПО КОТОРЫМ ПРИНЯТО (чтение боевой базы, отбор «одиночные
 * рейтинговые»): 130 матчей, 3 турнира, 64 игрока, 4 матча на человека,
 * десять и больше — у ОДНОГО, двадцать — ни у кого, история 14 дней,
 * архива нет. Проценты рядом с именами читаются как знание; на четырёх
 * матчах это знание выдуманное.
 *
 * ЧТО СТЕРЕЖЁМ. Выключатель должен быть ОДИН: экранов с полосой два —
 * страница турнира и страница вызова, — и выключенная на одном полоса
 * вернулась бы на другом. Плюс сам код НЕ УДАЛЁН: в декабре он основа
 * для Glicko-2, и правило следит, чтобы его не вынесли «как мёртвый».
 *
 *   node tools/check-prognoz-vyklyuchen.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const МОДУЛЬ = безКом(чит('js/match-prediction.js'));
const ТУРНИР = безКом(чит('js/tournament-detail.js'));
const ВЫЗОВ  = безКом(чит('js/challenge-detail.js'));

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ── 1. ВЫКЛЮЧАТЕЛЬ ЕСТЬ И ВЫКЛЮЧЕН ─────────────────────────────────── */
/* ЯКОРЬ ОТЛИЧАЕТ ПРИСВАИВАНИЕ ОТ СРАВНЕНИЯ. `P.ВКЛЮЧЁН === true` стоит
   внутри `показывать`, и `\s*=` ловило первый знак из `===`: правило
   оставалось зелёным, когда выключатель переставал быть общим. Поймал
   прувер 02.10 — четвёртый слабый якорь за вечер, и все одной семьи. */
правило('выключатель живёт в общем модуле',
    /P\.ВКЛЮЧЁН\s*=(?!=)/.test(МОДУЛЬ) && /P\.показывать\s*=\s*function/.test(МОДУЛЬ),
    'js/match-prediction.js больше не отдаёт выключатель. Каждый экран ' +
    'начнёт решать сам, и полоса вернётся на одном из двух');

правило('полоса выключена',
    /P\.ВКЛЮЧЁН\s*=\s*false\s*;/.test(МОДУЛЬ),
    'прогноз снова включён. Решение Кости 02.10: до декабря не показываем, ' +
    'пока у игроков не наберётся по двадцать матчей. Включать надо не это, ' +
    'а Glicko-2 — он сам молчит там, где данных мало');

/* ── 2. ОБА ЭКРАНА СПРАШИВАЮТ ЕГО, А НЕ СВОЁ ────────────────────────── */
правило('страница турнира спрашивает общий выключатель',
    /KSLT_PREDICTION\.показывать\(\)/.test(ТУРНИР) &&
    /\(isDbl \|\| !предсказаниеВидно\)\s*\?\s*null/.test(ТУРНИР),
    'страница турнира перестала спрашивать выключатель. Полоса вернётся в ' +
    'сетку, хотя на четырёх матчах её проценты ничем не обеспечены');

правило('страница вызова спрашивает общий выключатель',
    /if \(!window\.KSLT_PREDICTION\.показывать\(\)\) return '';/.test(ВЫЗОВ),
    'страница вызова перестала спрашивать выключатель. Один экран молчит, ' +
    'второй показывает — хуже, чем если бы показывали оба');

/* ── 3. РАСЧЁТ НЕ ВЫНЕСЕН «КАК МЁРТВЫЙ» ──────────────────────────────
   Выключенный код выглядит мёртвым ровно до декабря. Правило держит то,
   ради чего он оставлен: формулу, которая станет основой Glicko-2. */
правило('формула осталась на месте',
    /function\s+streak/.test(МОДУЛЬ) && /P\.calculate\s*=|calculate:/.test(МОДУЛЬ),
    'расчёт прогноза вынесен из js/match-prediction.js. Он выключен, а не ' +
    'мёртв: в декабре это основа Glicko-2, и переписанное заново теряет ' +
    'выверенное');

/* ── 4. ПАРНЫЕ ОСТАЮТСЯ ОТКЛЮЧЁННЫМИ ОТДЕЛЬНО ──────────────────────
   Это решение старше и переживёт включение полосы в декабре: формула
   берёт силу ОДНОГО человека, а на корт выходят двое. */
правило('в парных прогноз выключен своей причиной',
    /isDbl \|\|/.test(ТУРНИР) &&
    /b\.format && b\.format !== 'singles'/.test(ВЫЗОВ),
    'из отбора пропала проверка на парный разряд. Она не про объём данных, ' +
    'а про смысл: рейтинг у КСЛТ личный, в паре не разобрать, чья заслуга');

/* ── вывод ───────────────────────────────────────────────────────────── */
if (ошибки.length) {
    console.log('✗ Прогноз выключен: ' + ошибки.length + ' правил упало\n');
    ошибки.forEach(о => console.log('  • ' + о.имя + '\n    ' + о.подсказка + '\n'));
    process.exit(1);
}
console.log('✓ Прогноз выключен до декабря, выключатель один: все правила держат');
