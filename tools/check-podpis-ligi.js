console.log('\nдержится правил: ' + держится + ', упало: ' + упало);
if (швы.length < ПОТОЛОК_БЕЗЗАЩИТНЫХ) {
    console.log('  · беззащитных классов на h3: ' + швы.length +
                ' (потолок ' + ПОТОЛОК_БЕЗЗАЩИТНЫХ + ' — можно опустить)');
}
process.exit(упало ? 1 : 0);
