/* ── 6. ЛЕСТНИЦА ТЕКСТА: ОТНОШЕНИЕ, А НЕ ЧИСЛО ──────────────────── */

const ШКАЛА = { '--fs-2xs': 11, '--fs-xs': 12, '--fs-sm': 14, '--fs-base': 16,
                '--fs-md': 18, '--fs-lg': 21, '--fs-xl': 26, '--fs-2xl': 32, '--fs-3xl': 40 };
/* ПРИБОР ЧИТАЕТ ПРАВИЛО ПО ЕГО СЕЛЕКТОРУ, А НЕ ПО СКЛЕЕННОЙ РЕГУЛЯРКЕ.
   Сперва здесь стояло двойное экранирование — селектор приходил уже
   экранированным и экранировался ещё раз, отчего правило не находилось
   НИКОГДА и кегль выходил пустым. ПОЧТИ ТОЧНЫЙ ПРИБОР — НЕТОЧНЫЙ ПРИБОР:
   такой «сторож» молчал бы на любой лестнице. Теперь селекторы
   сравниваются как строки, знак в знак. */
function кегль(селектор) {
    const правила = [...cssЧистый.matchAll(/([^{}]+)\{([^{}]*)\}/g)]
        .map(м => ({ сел: м[1].trim().replace(/\s+/g, ' '), тело: м[2] }))
        .filter(р => р.сел.split(',').some(s => s.trim() === селектор));
    for (const р of правила) {
        const ф = р.тело.match(/font-size:\s*var\((--fs-[\w-]+)\)/);
        if (ф) return ШКАЛА[ф[1]];
    }
    return null;
}
