#!/usr/bin/env node
/**
 * ОДИН ЯЗЫК, ПОКА ЯЗЫКИ УБРАНЫ (слово Кости 29.10).
 *
 * «Языки пока оставим и уберём — оставим только на русском, и
 * переключатели скроем».
 *
 * ПОЧЕМУ ЭТО СТОРОЖ, А НЕ ПРОСТО ПРАВКА. Переключателей языка было ДВА:
 * в профиле (`screens/profile.js`) и в боковом меню
 * (`index.html#menuLangControl`), и работали они ПО-РАЗНОМУ — тот из
 * меню ронял кэш экранов и перерисовывал всё, а тот из профиля
 * перерисовывал только профиль. Спрячешь один — второй останется, и
 * останется именно тот, который врёт. Поэтому счёт держит проверка, а
 * не память.
 *
 * ЗАПОР ЖИВЁТ В ОДНОМ МЕСТЕ — `I18N.ОДИН_ЯЗЫК` в `js/i18n.js`. Если
 * запереть в переключателе, у того, кто УЖЕ выбрал `en`, в
 * `localStorage` останется чужой язык, а вернуть его будет нечем: органа
 * управления больше нет. Замер 29.10: 152 места в экранах и 116 в
 * разметке идут мимо словаря, то есть он увидел бы половину приложения
 * по-русски и половину по-английски.
 *
 * СЛОВАРЬ НЕ ТРОГАЕТСЯ: 709 ключей — сделанная работа, она вернётся.
 * Сторож это и держит: убрать переключатели можно, выбросить словарь нет.
 *
 * Запуск: node tools/check-odin-yazyk.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
/* Разметка без комментариев: ряды языка оставлены в `index.html`
   закомментированными — вернуть их должно быть просто, а сторож обязан
   считать РАБОЧУЮ разметку, а не слова. */
function безКомHTML(т) { return т.replace(/<!--[\s\S]*?-->/g, ''); }
function безКомJS(т) {
    return т
        .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
        .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));
}

const I18N = чит('mobile/www/js/i18n.js');
const РАЗМЕТКА = безКомHTML(чит('mobile/www/index.html'));
const ПРОФИЛЬ = безКомJS(чит('mobile/www/js/screens/profile.js'));

console.log('\n  ОДИН ЯЗЫК, ПОКА ЯЗЫКИ УБРАНЫ\n');

правило('выключатель объявлен в доме языка',
    /I18N\.ОДИН_ЯЗЫК\s*=\s*'ru'/.test(I18N),
    'В `mobile/www/js/i18n.js` должен стоять `I18N.ОДИН_ЯЗЫК = \'ru\'`.\n' +
    'Это единственное место, где язык запирается: его спрашивают десять\n' +
    'экранов, и помнить про каждый нельзя.');

правило('язык берётся через выключатель, а не прямо из памяти',
    /_lang\s*=\s*I18N\.ОДИН_ЯЗЫК\s*\|\|/.test(I18N),
    '`_lang` обязан начинаться с `I18N.ОДИН_ЯЗЫК || ...`. Иначе у того,\n' +
    'кто уже выбрал `en`, язык останется английским, а переключателя,\n' +
    'чтобы вернуть, больше нет.');

правило('setLang не применяет язык, пока заперто',
    /if\s*\(\s*I18N\.ОДИН_ЯЗЫК\s*\)\s*return;/.test(I18N),
    '`setLang` обязан выходить, пока язык заперт. Применить молча —\n' +
    'значит показать человеку половину приложения на другом языке.');

правило('выбор человека ЗАПОМИНАЕТСЯ, а не стирается',
    /localStorage\.setItem\('kslt_lang'/.test(I18N) &&
    I18N.indexOf("localStorage.setItem('kslt_lang'") <
    I18N.indexOf('if (I18N.ОДИН_ЯЗЫК) return;'),
    'Запись выбора обязана стоять ДО выхода: вернут языки — вернётся и\n' +
    'то, что человек выбрал. Стирать чужой выбор мы не просили.');

const вРазметке = (РАЗМЕТКА.match(/data-lang=/g) || []).length;
правило('переключателя языка в рабочей разметке нет',
    вРазметке === 0,
    'Кнопок языка в `mobile/www/index.html` — ' + вРазметке + ', а должно\n' +
    'быть 0. Ряд убран РАЗМЕТКОЙ, а не `display: none`: скрытый ряд всё\n' +
    'равно читает диктор и ловит Tab.');

правило('ряд языка в профиле не рисуется, пока заперто',
    /if\s*\(!I18N\.ОДИН_ЯЗЫК\)\s*\{/.test(ПРОФИЛЬ),
    'В `screens/profile.js` ряд языка обязан стоять под\n' +
    '`if (!I18N.ОДИН_ЯЗЫК)`. Это ВТОРОЙ переключатель — спрятав только\n' +
    'тот, что в меню, мы оставили бы этот.');

правило('тему не задели',
    /data-theme=/.test(РАЗМЕТКА),
    'Переключатель темы убирать не просили — он обязан остаться.\n' +
    'Правило стоит здесь, чтобы «убрать языки» не стало «убрать\n' +
    'переключатели вообще».');

const ключей = (I18N.match(/ru:\s*'/g) || []).length;
правило('словарь на месте: ключей не меньше 700',
    ключей >= 700,
    'Ключей в словаре: ' + ключей + ', было 709. Языки УБРАНЫ, а не\n' +
    'выброшены: словарь — сделанная работа, и она вернётся. Убрать\n' +
    'переключатели можно, выбросить переводы нет.');

правило('версия i18n поднята',
    (function () {
        const m = чит('mobile/www/index.html').match(/js\/i18n\.js\?v=(\d+)/);
        return !!m && Number(m[1]) >= 11;
    })(),
    'Запор заведён в `i18n.js` — версия в разметке обязана быть не ниже\n' +
    '11, иначе у человека останется старый файл, язык не запрётся, а\n' +
    'переключателей уже нет.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      один язык: все ' + держится + ' правил держатся');
    console.log('          словарь сохранён: ключей ' + ключей + '\n');
}
