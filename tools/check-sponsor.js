/**
 * ЗАМОРОЗКА БЛОКА «СТАНЬТЕ СПОНСОРОМ КСЛТ» `.sp-offer` НА ГЛАВНОЙ.
 *
 * Доска 437:9, решения Кости 24.09: блок говорит голосом раздела, числа
 * стоят ступенью ниже заголовка, блок появляется на всех трёх языках,
 * третье число приходит из базы.
 *
 * ЗАМОРАЖИВАЮТСЯ ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • заголовок блока = заголовок раздела, число строго МЕЛЬЧЕ заголовка;
 *   • вступление никогда не мельче пункта списка;
 *   • заголовок блока и заголовки разделов объявлены ОДНИМ правилом —
 *     пара, которая читается парой, едет одной границей;
 *   • коробка-предложение существует ровно в двух местах и они согласны;
 *   • высота кнопки — свойством, и не ниже минимальной цели нажатия.
 *
 *   node tools/check-sponsor.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СТИ = безКом(чит('css/style.css'));
const СПОН = безКом(чит('css/sponsors.css'));
const СТАТ = чит('js/stats.js');
const СТР = { ru: чит('index.html'), en: чит('index-en.html'), kg: чит('index-kg.html') };

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };
const сколько = (т, р) => (т.match(р) || []).length;

/* ЛЕСТНИЦА КЕГЛЕЙ. Правило сравнивает СТУПЕНИ, а не пиксели: когда шкала
   поедет, правило поедет вместе с ней и не соврёт. */
const СТУПЕНИ = ['--fs-2xs', '--fs-xs', '--fs-sm', '--fs-base', '--fs-md', '--fs-lg', '--fs-xl', '--fs-2xl', '--fs-3xl'];
const ступень = т => { const м = т && т.match(/--fs-[a-z0-9]+/); return м ? СТУПЕНИ.indexOf(м[0]) : -1; };
const свойство = (блок, сел, имя) => {
    const i = блок.indexOf(сел + ' {');
    if (i < 0) return null;
    const тело = блок.slice(i, блок.indexOf('}', i));
    const м = тело.match(new RegExp(имя + ':\\s*([^;]+);'));
    return м ? м[1].trim() : null;
};

/* ══ ГДЕ ЖИВЁТ БЛОК ══════════════════════════════════════════════════════ */

const нач = СТИ.indexOf('.sp-offer-wrap {');
/* ПОПРАВКА 24.09, ночь: якорь ловил ПОДСТРОКУ. Секция спонсоров завела
   правило .sponsors-cloud .spon-static, и indexOf находил его — а оно
   лежит ВЫШЕ блока, так что конец оказывался раньше начала и блок
   выходил пустым. Держимся за начало строки. */
const кон = СТИ.indexOf('\n.spon-static {');
правило('блок лежит одним куском, а не рассыпан по файлу',
    нач > 0 && кон > нач,
    'Не нашёл границы блока: от .sp-offer-wrap до .spon-static.');
const БЛОК = нач > 0 && кон > нач ? СТИ.slice(нач, кон) : '';

function слои(текст) {
    const вых = [];
    const рег = /@media[^{]*\{/g;
    let м;
    while ((м = рег.exec(текст)) !== null) {
        let i = рег.lastIndex, d = 1;
        while (d && i < текст.length) { if (текст[i] === '{') d++; else if (текст[i] === '}') d--; i++; }
        вых.push({ текст: текст.slice(м.index, i), усл: текст.slice(м.index, текст.indexOf('{', м.index)).trim() });
    }
    return вых;
}
const СЛОИ = слои(БЛОК);
const слой = усл => СЛОИ.find(с => new RegExp(усл).test(с.усл)) || null;
/* База — блок БЕЗ медиазапросов: иначе правило про базу ловит одноимённое
   объявление из узкого слоя, и держит оно чужое. */
const БАЗА = СЛОИ.reduce((т, с) => т.replace(с.текст, ''), БЛОК);

/* ══ СЛОИ И ГРАНИЦЫ ══════════════════════════════════════════════════════ */

const ширины = [...new Set((БЛОК.match(/max-width:\s*(\d+)px/g) || []).map(s => s.match(/\d+/)[0]))];

правило('в блоке нет ни одной ширины, кроме 768 и 640',
    ширины.every(ш => ш === '768' || ш === '640'),
    'Найдено: ' + ширины.join(' · ') + '\n' +
    '          До 24.09 блок стоял на 900 и 768 — 900 не из лестницы вовсе.\n' +
    '          768 остаётся намеренно: на нём переключается заголовок РАЗДЕЛА,\n' +
    '          а заголовок блока обязан ехать вместе с ним.');

правило('слоёв ровно четыре: ≤768, ≤640, поворот и движение',
    СЛОИ.length === 4,
    'Сейчас ' + СЛОИ.length + ': ' + СЛОИ.map(с => с.усл).join(' | '));

правило('тесный по высоте вид отделён поворотом, а не шириной',
    !!слой('orientation: landscape') && /max-height:\s*500px/.test(слой('orientation: landscape').усл),
    'Телефон боком 844 × 390 — это не узкий экран, это низкий.');

/* ══ ЛЕСТНИЦА: ОТНОШЕНИЯ, А НЕ ЧИСЛА ═════════════════════════════════════ */

правило('заголовок блока объявлен ТЕМ ЖЕ правилом, что заголовки разделов',
    /\.section-header h2,[\s\S]{0,400}\.sp-offer h2,[\s\S]{0,40}section > h2 \{/.test(СТИ),
    'Мобильная ступень заголовка раздела должна быть определена ОДИН раз.\n' +
    '          До 24.09 у блока было своё правило с clamp(1.15rem, 5vw, 1.32rem):\n' +
    '          19.5 и 21.12 — оба мимо шкалы.');

const h2баз = ступень(свойство(БАЗА, '.sp-offer h2', 'font-size'));
const числоБаз = ступень(свойство(БАЗА, '.sp-num-val', 'font-size'));
правило('на широком число СТРОГО мельче заголовка блока',
    h2баз > 0 && числоБаз > 0 && числоБаз < h2баз,
    'Заголовок ' + (СТУПЕНИ[h2баз] || '?') + ', число ' + (СТУПЕНИ[числоБаз] || '?') + '.\n' +
    '          До 24.09 было наоборот: заголовок 21, число 26 — и первым в блоке\n' +
    '          про спонсорство читалась цифра 350.');

const узкий = слой('max-width: 768px');
const числоУзк = узкий ? ступень(свойство(узкий.текст, '.sp-num-val', 'font-size')) : -1;
правило('на узком число тоже строго мельче заголовка',
    числоУзк > 0 && числоУзк < ступень('--fs-lg'),
    'Заголовок раздела на узком — --fs-lg. Число должно стоять ниже него.\n' +
    '          Было --fs-lg против --fs-lg при весе 800 против 700: число крупнее\n' +
    '          заголовка и по кеглю, и по весу.');

const liБаз = ступень(свойство(БАЗА, '.sp-gives li', 'font-size'));
const ledБаз = ступень(свойство(БАЗА, '.sp-offer-lead', 'font-size'));
const ledУзк = узкий ? ступень(свойство(узкий.текст, '.sp-offer-lead', 'font-size')) : -1;
правило('вступление никогда не мельче пункта списка',
    ledБаз >= liБаз && ledУзк >= liБаз,
    'Широкий: вступление ' + (СТУПЕНИ[ledБаз] || '?') + ', пункт ' + (СТУПЕНИ[liБаз] || '?') + '.\n' +
    '          Узкий: вступление ' + (СТУПЕНИ[ledУзк] || '?') + '.\n' +
    '          На 768 и 390 вступление стояло в 12 при списке в 14: первая фраза\n' +
    '          блока была самым мелким текстом в нём.');

правило('вступление — это body, а не ступень lead',
    ledБаз === ступень('--fs-base'),
    'Ступень lead (21 / 16) заведена для абзаца ПОД заголовком раздела.\n' +
    '          Внутри коробки это обычный текст, иначе 26 → 21 → 21 схлопнет\n' +
    '          заголовок, вступление и число в один уровень.');

правило('h3 из блока ушёл, уровень не пропущен',
    !/\.sp-offer h3/.test(СТИ),
    'Было .sp-offer h3 — и в структуре документа он стоял ПОСЛЕ шести h3\n' +
    '          раздела «О проекте», без h2 между ними.');

/* ══ ШИРИНА И ЛЕВЫЙ КРАЙ ═════════════════════════════════════════════════ */

правило('у коробки нет своей ширины — её задаёт обёртка, как всем секциям',
    !/\.sp-offer \{[^}]*max-width/.test(БЛОК),
    'Было max-width: var(--container-narrow) — 1100 при контейнере 1400.\n' +
    '          На 1280 содержимое блока начиналось на 125 пикселе против 28\n' +
    '          у соседних секций: третий левый край на одной странице.');

/* ══ КНОПКА — Button 17:82 ═══════════════════════════════════════════════ */

правило('высота кнопки — свойством, и это минимальная цель нажатия',
    /\.sp-cta-btn \{[\s\S]{0,400}height: var\(--btn-h-md\)/.test(БЛОК) &&
    !/\.sp-cta-btn \{[\s\S]{0,400}padding:\s*\d+px\s+\d+px/.test(БЛОК),
    'Было padding 12/26 и 11/20 — высота выходила 48 и 40, и 40 ниже порога 44.\n' +
    '          Button 17:82: «Height is set by the height property, never by\n' +
    '          vertical padding — otherwise it drifts with the line-height».');

правило('у кнопки есть кольцо фокуса',
    /\.sp-cta-btn:focus-visible \{[^}]*outline:\s*3px/.test(БЛОК),
    'Единственная ссылка блока была недостижима глазом с клавиатуры. WCAG 2.4.7.');

правило('текст на лайме берётся токеном, а не литералом',
    /\.sp-cta-btn \{[\s\S]{0,400}color: var\(--accent-on\)/.test(БЛОК) && !/#0a0a0a/i.test(БЛОК),
    'Было color: #0a0a0a — то же значение, что --accent-on, но мимо системы.');

правило('движение гасится по просьбе системы',
    /@media \(prefers-reduced-motion: reduce\) \{[\s\S]{0,200}\.sp-cta-btn:hover \{[^}]*transform: none/.test(БЛОК),
    'Гасить надо и переход, и сам сдвиг.');

/* ══ ШКАЛА ═══════════════════════════════════════════════════════════════ */

/* В блоке остаются ровно три группы сырых пикселей, и каждая — рисунок,
   а не отступ: свечение в углу, ширина колонки текста и галочка-маркер. */
const сырые = (БЛОК.match(/(padding|margin|gap|row-gap|column-gap)(-top|-right|-bottom|-left)?:\s*[^;]+;/g) || [])
    .filter(д => /\d+px/.test(д));
правило('отступов мимо шкалы в блоке нет',
    сырые.length === 0,
    'Найдено: ' + сырые.join(' · ') + '\n' +
    '          Было 30/34 · 26/22 · 16/14 · 20 · 22 · 24 · 9/32 · 6 · 8/10 · 10.');

/* ══ СТОРОЖ: КОРОБКА-ПРЕДЛОЖЕНИЕ ═════════════════════════════════════════ */

const коробки = [];
[['css/style.css', СТИ], ['css/sponsors.css', СПОН]].forEach(([имя, текст]) => {
    const рег = /\.([a-z0-9-]+)\s*\{[^}]*background:\s*var\(--surface-glass\)[^}]*border:\s*1px solid rgba\(204,\s*255,\s*0/g;
    let м; while ((м = рег.exec(текст)) !== null) коробки.push(имя + ' → .' + м[1]);
});

правило('коробка-предложение существует ровно в двух местах',
    коробки.length === 2 &&
    коробки.some(к => /\.sp-offer$/.test(к)) && коробки.some(к => /\.sn-final$/.test(к)),
    'Найдено ' + коробки.length + ': ' + коробки.join(' · ') + '\n' +
    '          Стеклянная коробка с лаймовой рамкой и свечением из угла — это\n' +
    '          .sp-offer здесь и .sn-final на странице спонсоров. Третья копия\n' +
    '          значит, что понятие пора выносить в компонент, а не копировать.');

правило('обе коробки согласны по радиусу и свечению',
    /\.sp-offer \{[\s\S]{0,300}border-radius: var\(--radius-xl\)/.test(БЛОК) &&
    /\.sn-final[\s\S]{0,300}border-radius: var\(--radius-xl\)/.test(СПОН) &&
    /\.sp-offer::after \{[\s\S]{0,400}radial-gradient\(circle, rgba\(204, 255, 0/.test(БЛОК) &&
    /\.sn-final::after[\s\S]{0,400}radial-gradient\(circle, rgba\(204,\s*255,\s*0/.test(СПОН),
    'Расхождение между двумя копиями — это и есть болезнь, ради которой\n' +
    '          сторож стоит. Эталон — .sp-offer.');

/* ══ ОДИН СЧЁТЧИК НА ОБА МЕСТА ═══════════════════════════════════════════ */

правило('число турниров считает ОДИН счётчик, а не два',
    /querySelectorAll\('#' \+ id \+ ', \[data-stat="' \+ id \+ '"\]'\)/.test(СТАТ) &&
    !/getElementById\(id\)/.test(СТАТ),
    'Одно и то же число стоит теперь и в шапке, и в блоке спонсорам.\n' +
    '          Два счётчика на одно понятие однажды разойдутся — это в файле\n' +
    '          написано первой же строкой.');

/* ══ РАЗМЕТКА, ТРИ ЯЗЫКА ═════════════════════════════════════════════════ */

for (const [яз, html] of Object.entries(СТР)) {
    const суф = яз === 'ru' ? '' : '-' + яз;
    const i = html.indexOf('<section class="sp-offer-wrap">');
    const кусок = i < 0 ? '' : html.slice(i, html.indexOf('</section>', i));

    правило('блок есть на языке · ' + яз,
        кусок.length > 0,
        'До 24.09 приглашение спонсорам жило только на русской главной.');

    правило('заголовок блока — h2 · ' + яз,
        /<h2>/.test(кусок) && !/<h3>/.test(кусок),
        'Это раздел, а не перебивка внутри раздела.');

    правило('четыре числа и четыре обещания · ' + яз,
        сколько(кусок, /class="sp-num-val"/g) === 4 && сколько(кусок, /<li>/g) === 4,
        'Числа: ' + сколько(кусок, /class="sp-num-val"/g) + ', обещания: ' + сколько(кусок, /<li>/g));

    правило('обещания — список, а не четыре дива · ' + яз,
        /<ul class="sp-gives">/.test(кусок),
        'Диктор должен сказать «список из четырёх».');

    правило('третье число приходит из базы · ' + яз,
        /data-stat="statTournaments"/.test(кусок) && !/120\+/.test(кусок),
        'Было «120+ рейтинговых турниров» — цифра из письма за август и\n' +
        '          деление по виду турнира, которого нет больше нигде на сайте.\n' +
        '          Стало число завершённых турниров: архив клуба плюс база.');

    правило('в блоке одна ссылка, и она ведёт на страницу СВОЕГО языка · ' + яз,
        сколько(кусок, /<a /g) === 1 &&
        new RegExp('href="pages/sponsors' + суф + '\\.html"').test(кусок),
        'Одно действие на блок — и лайм принадлежит ему одному.\n' +
        '          До 24.09 кнопка на всех трёх языках вела на русскую страницу,\n' +
        '          потому что переведённых не существовало. Теперь они есть.');
}

правило('версии подняты',
    Number((СТР.ru.match(/style\.css\?v=(\d+)/) || [0, 0])[1]) >= 367 &&
    Number((СТР.ru.match(/stats\.js\?v=(\d+)/) || [0, 0])[1]) >= 4,
    'Не поднял версию — смотришь старый сайт и думаешь, что правка не сработала.');

/* ══ ВЫВОД ═══════════════════════════════════════════════════════════════ */

console.log('');
if (ошибки.length === 0) {
    console.log('  ок      блок «Станьте спонсором»: ' + ВСЕГО + ' правил');
    console.log('          число мельче заголовка   ·   вступление не мельче списка');
    console.log('          кнопка 44 свойством   ·   три языка   ·   коробка ровно в двух местах');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  «Станьте спонсором» — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s+/g, '\n            '));
    console.log('');
});
process.exit(1);
