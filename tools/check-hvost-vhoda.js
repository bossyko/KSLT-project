/**
 * ХВОСТ ВХОДА — СТОРОЖ (11.11.2026).
 *
 * ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ: НИ ОДИН ЭКРАН КАРТОЧКИ НЕ ОСТАЁТСЯ БЕЗ
 * РАСКЛАДКИ НА НИЗКОМ ЭКРАНЕ, и цели нажатия берут высоту со шкалы.
 *
 * ЗАМЕР 11.11, телефон боком 844x390, карточка за сгибом:
 *   signupForm 468 · otpNewPasswordForm 293 · tgRegisterForm 212 ·
 *   resetForm 169. Правило двух колонок стояло у трёх экранов из
 *   девяти, остальные шесть никто не раскладывал.
 * После правки: 91 · 76 · 87 · 0 — короткая прокрутка вместо экрана с
 * половиной формы за краем.
 *
 * ЧТО В ЗАПИСИ УСТАРЕЛО И ПРОВЕРЕНО ЗАНОВО: кегли вне шкалы — ноль на
 * всех девяти экранах; клетки кода 47x52, а не 42x50; цель согласия —
 * ярлык 426x44, а не квадратик 16x16. ТЕКСТ ЗАДАЧИ — НЕ ДОКАЗАТЕЛЬСТВО.
 *
 * ПРО ССЫЛКИ ВНУТРИ ПРЕДЛОЖЕНИЯ (otpResend, ссылки согласия): WCAG
 * 2.5.8 прямо исключает inline-цели в потоке текста, и растягивать их
 * до 44 значит разорвать абзац. Правило их не трогает — ПРАВИЛО,
 * ЦЕЛЯЩЕЕ ШИРЕ СВОЕГО ПРЕДМЕТА, ЛОВИТ НЕВИНОВНЫХ.
 *
 * ШЕСТОЕ ПРАВИЛО — ПРО ЛИШНЮЮ СКОБКУ. Сегодня одна лишняя `}` в
 * style.css молча отключила следующее правило: обёртка колонки
 * осталась без flex, ритм пропал, и замер показывал «нормально».
 * Браузер об этом не говорит ни слова.
 */
const fs = require('fs');
const path = require('path');

const корень = path.resolve(__dirname, '..');
const стиль = fs.readFileSync(path.join(корень, 'css/style.css'), 'utf8');
const безК = т => т.replace(/\/\*[\s\S]*?\*\//g, '');
const чистый = безК(стиль);
const ошибки = [];

/* 1. СКОБКИ СХОДЯТСЯ. */
const открыт = (чистый.match(/\{/g) || []).length;
const закрыт = (чистый.match(/\}/g) || []).length;
if (открыт !== закрыт) {
    ошибки.push(`css/style.css: скобок { ${открыт}, } ${закрыт} — лишняя молча отключает следующее правило`);
}

/* 2. У КАЖДОГО ЭКРАНА ЕСТЬ РАСКЛАДКА НА НИЗКОМ ЭКРАНЕ.
   Короткие экраны-итоги помещаются и без неё — они названы поимённо,
   а не «все остальные»: список обязан падать при появлении десятого. */
const ЭКРАНЫ = ['signinForm', 'tgRegisterForm', 'forgotStep1', 'otpCodeForm',
                'otpNewPasswordForm', 'signupForm', 'resetForm', 'resetSuccess', 'signupSuccess'];
const КОРОТКИЕ = ['resetSuccess', 'signupSuccess'];

const блок = (() => {
    const i = чистый.indexOf('@media (max-height: 680px) and (min-width: 640px)');
    if (i < 0) return null;
    let гл = 0;
    for (let j = чистый.indexOf('{', i); j < чистый.length; j++) {
        if (чистый[j] === '{') гл++;
        else if (чистый[j] === '}') { гл--; if (!гл) return чистый.slice(i, j + 1); }
    }
    return null;
})();

if (!блок) {
    ошибки.push('css/style.css: блока раскладки на низком экране нет — девять экранов снова без правил');
} else {
    /* РАСКЛАДКА — ЭТО СЕТКА, А НЕ УПОМИНАНИЕ ИМЕНИ. Первая редакция
       искала `#id.active` где угодно в блоке и засчитывала любое
       совпадение — прувер её не уронил: имя экрана встречается и в
       правилах его детей. Теперь спрашиваем то, что решает дело:
       карточка с этим экраном становится сеткой в две колонки. */
    for (const id of ЭКРАНЫ) {
        if (КОРОТКИЕ.includes(id)) continue;
        const м = блок.match(new RegExp('([^{}]*\\.auth-card:has\\(#' + id + '\\.active\\)[^{}]*)\\{([^}]*)\\}'));
        if (!м) {
            ошибки.push(`экран #${id} остался без раскладки на низком экране — карточка уйдёт за сгиб`);
            continue;
        }
        if (!/display:\s*grid/.test(м[2]) || !/grid-template-columns/.test(м[2])) {
            ошибки.push(`экран #${id}: правило есть, а сетки в нём нет — раскладка не состоится`);
        }
    }
}

/* Разметка девяти экранов не изменилась под ногами у правила. */
for (const файл of ['pages/auth.html', 'pages/auth-en.html', 'pages/auth-kg.html']) {
    const т = fs.readFileSync(path.join(корень, файл), 'utf8');
    for (const id of ЭКРАНЫ) {
        if (т.indexOf('id="' + id + '"') === -1) ошибки.push(`${файл}: экрана #${id} нет — правило сторожит пустоту`);
    }
    /* 3. ОБЁРТКА ГЛАВНОЙ КОЛОНКИ СТОИТ ВО ВСЕХ ТРЁХ ЯЗЫКАХ. Без неё
       шапка занимает собственную строку сетки, и карточка вырастает
       на 79 — замерено 11.11 на otpNewPasswordForm (543 против 464). */
    const n = (т.match(/auth-col-glavnoe/g) || []).length;
    if (n !== 3) ошибки.push(`${файл}: обёрток .auth-col-glavnoe ${n}, а экранов с шапкой три`);
}

/* 4. ОБЁРТКА — ТАКАЯ ЖЕ СТОПКА, ЧТО И ФОРМА. */
/* ЯКОРЬ БЕРЁТ ОБЪЯВЛЕНИЕ, А НЕ ПЕРВОЕ УПОМИНАНИЕ: тот же класс стоит
   в селекторе внутри медиа-блока (`... > .auth-col-glavnoe`), и поиск
   «где-нибудь» находил его, а не сам класс. */
const обёртка = чистый.match(/(?:^|\n)\s*\.auth-col-glavnoe\s*\{([^}]*)\}/);
if (!обёртка) {
    ошибки.push('css: .auth-col-glavnoe не объявлена — дети колонки сядут по своему тексту');
} else {
    if (!/display:\s*flex/.test(обёртка[1]) || !/flex-direction:\s*column/.test(обёртка[1]))
        ошибки.push('.auth-col-glavnoe перестала быть колонкой — ритм и ширина разойдутся');
    if (!/gap:\s*var\(--space-\d+\)/.test(обёртка[1]))
        ошибки.push('.auth-col-glavnoe задаёт ритм числом мимо шкалы');
}

/* 5. ЦЕЛЬ НАЖАТИЯ ВЫБОРА ПОЛА — СО ШКАЛЫ КНОПОК, А НЕ ИЗ СЛАГАЕМЫХ.
   Было 43: строка 21 + отступы 20 + рамка 2. Промах на пиксель. */
const пол = чистый.match(/\.auth-gender-option\s*\{([^}]*)\}/);
if (!пол) {
    ошибки.push('css: .auth-gender-option не объявлен');
} else if (!/min-height:\s*var\(--btn-h-md\)/.test(пол[1])) {
    ошибки.push('.auth-gender-option больше не берёт высоту со шкалы кнопок — вернутся 43 вместо 44');
}

/* 6. КЛЕТКИ КОДА: ЧИСЛО ВВОДИТСЯ ЦИФРОВОЙ КЛАВИАТУРОЙ, А КОД
   ПОДСТАВЛЯЕТСЯ САМ. Apple ставит autocomplete="one-time-code" на
   ПЕРВУЮ клетку — Safari сам разносит цифры по остальным. */
for (const файл of ['pages/auth.html', 'pages/auth-en.html', 'pages/auth-kg.html']) {
    const т = fs.readFileSync(path.join(корень, файл), 'utf8');
    const клетки = т.match(/<input[^>]*class="otp-digit"[^>]*>/g) || [];
    if (клетки.length !== 6) { ошибки.push(`${файл}: клеток кода ${клетки.length}, а не шесть`); continue; }
    if (клетки.some(к => !/inputmode="numeric"/.test(к)))
        ошибки.push(`${файл}: не у всех клеток кода inputmode="numeric" — на телефоне откроется буквенная клавиатура`);
    if (!/autocomplete="one-time-code"/.test(клетки[0]))
        ошибки.push(`${файл}: первая клетка кода без autocomplete="one-time-code" — код не подставится сам`);
}

if (ошибки.length) {
    console.error('ХВОСТ ВХОДА — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
console.log(`хвост входа: девять экранов, семь с раскладкой на низком экране, обёртки в трёх языках, цели со шкалы`);
