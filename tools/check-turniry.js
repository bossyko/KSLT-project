function мёртвыеВМедиа(css) {
    /* Однострочное правило «.sel { prop: v; }» разбирается так же, как
       многострочное: иначе сторож пропустит перебивку, записанную в строку.
       Поймано прувером 28.09 — откат был именно такой. */
    const без = css.replace(/\/\*[\s\S]*?\*\//g, '')
                   .replace(/\{/g, '{\n').replace(/;/g, ';\n').replace(/\}/g, '\n}\n');
    const строки = без.split('\n');
    let d = 0, медиа = null;
    const правила = [];
    строки.forEach((l, i) => {
        const т = l.trim();
        if (т.startsWith('@media')) медиа = d;
        const m = т.match(/^([.#][^{}/]+?)\s*\{$/);
        if (m) {
            const свойства = [];
            for (let j = i + 1; j < строки.length && строки[j].indexOf('}') === -1; j++) {
                const p = строки[j].trim().match(/^([a-z-]+)\s*:/);
                if (p) свойства.push(p[1]);
            }
            правила.push({ сел: m[1].replace(/\s+/g, ' ').trim(), стр: i + 1,
                           вМедиа: медиа !== null && d > медиа, свойства });
        }
        d += (l.match(/\{/g) || []).length - (l.match(/\}/g) || []).length;
        if (медиа !== null && d <= медиа) медиа = null;
    });
    const беды = [];
    правила.filter(р => р.вМедиа).forEach(р => {
        правила.filter(б => !б.вМедиа && б.сел === р.сел && б.стр > р.стр).forEach(б => {
            const общие = р.свойства.filter(x => б.свойства.indexOf(x) !== -1);
            if (общие.length) беды.push(р.сел + ' стр.' + р.стр + ' → ' + б.стр + ' · ' + общие.join(', '));
        });
    });
    return беды;
}
