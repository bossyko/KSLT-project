#!/usr/bin/env node
/**
 * КАРТОЧКА СТАТИСТИКИ АДМИНКИ — ОДИН ПОРЯДОК НА ВСЕ РАЗДЕЛЫ (12.11.2026).
 *
 * ОТКУДА. Запись h159 говорила «у Тренеров карточки перевёрнуты». Замер
 * показал, что перевёрнуты не они одни: из 13 карточек статистики в
 * админке 7 шли ЧИСЛО → подпись и 6 подпись → ЧИСЛО, причём ОДИН И ТОТ
 * ЖЕ класс .ad-stat-card встречался в обоих видах (loyalty против
 * bracket). ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ — а тут одно понятие
 * читалось двумя способами в соседних разделах.
 *
 * РЕШЕНИЕ: ЧИСЛО СВЕРХУ, ПОДПИСЬ СНИЗУ. Это большинство (7 из 13) и это
 * то, как устроены сводки везде: главное — значение, подпись лишь
 * называет его. Меньшинство приведено к большинству, а не наоборот.
 *
 * ЧТО СТОРОЖИТСЯ — ОТНОШЕНИЕ, А НЕ СПИСОК ФАЙЛОВ: прибор сам обходит
 * js/admin, находит КАЖДУЮ карточку статистики и требует, чтобы число
 * стояло раньше подписи. Новый раздел с перевёрнутой карточкой уронит
 * правило, даже если про него тут никто не писал.
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const файлы = [];
(function обход(д) {
    for (const ф of fs.readdirSync(д, { withFileTypes: true })) {
        const п = path.join(д, ф.name);
        if (ф.isDirectory()) обход(п);
        else if (ф.name.endsWith('.js')) файлы.push(п);
    }
})(path.join(КОРЕНЬ, 'js/admin'));

const перевёрнутые = [];
let всего = 0;
for (const ф of файлы) {
    const т = fs.readFileSync(ф, 'utf8');
    const рег = /class="([a-z-]*stat-card[a-z0-9- ]*)"/g;
    let м;
    while ((м = рег.exec(т))) {
        /* Окно в 450 знаков — это сама карточка: класс, значок, число,
           подпись. Больше брать нельзя: заедем в соседнюю карточку. */
        const окно = т.slice(м.index, м.index + 450);
        const iП = окно.search(/stat-label|stat-sub/);
        const iЧ = окно.search(/stat-value|stat-top-score|stat-big/);
        if (iП < 0 || iЧ < 0) continue;
        всего++;
        if (iП < iЧ) {
            const строка = т.slice(0, м.index).split('\n').length;
            перевёрнутые.push(path.relative(КОРЕНЬ, ф) + ':' + строка + ' (' + м[1].trim().split(' ')[0] + ')');
        }
    }
}

/* ═══ ГЕОМЕТРИЯ — ОДНА НА ВСЕ КАРТОЧКИ СВОДКИ (h146/h208, 12.11) ═══
   До правки у одного понятия было СЕМЬ коробок: 8/4, 12/16, 16, 20,
   16/20 и два радиуса. Теперь отступ и радиус берутся из двух имён, и
   правило требует именно их: своё число или своя ступень в любой из
   этих карточек — снова семь геометрий через месяц. */
const css = fs.readFileSync(path.join(КОРЕНЬ, 'css/admin.css'), 'utf8');
const КАРТОЧКИ = ['ad-stat-card', 'ad-vch-stat', 'ad-news-stat-card', 'ad-pay-stat-card',
    'anl-card', 'ad-cch-stat-card', 'ad-crt-stat-card', 'ad-usr-card'];
const своиГеометрии = [];
for (const к of КАРТОЧКИ) {
    const м = css.match(new RegExp('\\n\\.' + к + '\\s*\\{([^}]*)\\}'));
    if (!м) { своиГеометрии.push(к + ' — правила нет вовсе'); continue; }
    const тело = м[1];
    const отступ = (тело.match(/padding:\s*([^;]+);/) || [])[1];
    const радиус = (тело.match(/border-radius:\s*([^;]+);/) || [])[1];
    if (отступ && отступ.indexOf('--ad-stat-pad') === -1) своиГеометрии.push(к + ': свой отступ ' + отступ);
    if (радиус && радиус.indexOf('--ad-stat-radius') === -1) своиГеометрии.push(к + ': свой радиус ' + радиус);
}
if (!/--ad-stat-pad:/.test(css) || !/--ad-stat-radius:/.test(css)) {
    своиГеометрии.push('в admin.css нет имён --ad-stat-pad / --ad-stat-radius — геометрию снова задают на местах');
}
if (/\.ad-usr-card--sm\s*\{/.test(css)) {
    своиГеометрии.push('.ad-usr-card--sm вернулся: вторая высота одного и того же понятия (h124)');
}
if (своиГеометрии.length) {
    console.error('КАРТОЧКИ СТАТИСТИКИ — НАРУШЕНО:');
    for (const о of своиГеометрии) console.error('  · ' + о);
    console.error('    Решение 12.11: отступ и радиус — только --ad-stat-pad и --ad-stat-radius.');
    process.exit(1);
}

if (всего < 10) {
    console.error('КАРТОЧКИ СТАТИСТИКИ — НАРУШЕНО:');
    console.error('  · найдено всего ' + всего + ' карточек при замере 13 — прибор ослеп либо раздел снесли');
    process.exit(1);
}
if (перевёрнутые.length) {
    console.error('КАРТОЧКИ СТАТИСТИКИ — НАРУШЕНО:');
    console.error('  · подпись стоит НАД числом в ' + перевёрнутые.length + ' карточке(ах): ' + перевёрнутые.join(' · '));
    console.error('    Решение 12.11: число сверху, подпись снизу — один порядок на все разделы.');
    process.exit(1);
}
console.log('карточки статистики: ' + всего + ' карточек, во всех число стоит перед подписью');
