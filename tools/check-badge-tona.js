/**
 * БЕЙДЖ АДМИНКИ — ИМЯ ТОНА, А НЕ ИМЯ ЦВЕТА. 19.10.
 *
 * ЧЕТЫРЕ БЕДЫ НАШЛИСЬ В ОДНОМ СЕМЕЙСТВЕ, И ТРИ ИЗ НИХ БЫЛИ НА ЭКРАНЕ.
 *
 * 1. ОДНО ИМЯ НА ДВА ПОНЯТИЯ. `.ad-badge-out` был объявлен ДВАЖДЫ в
 *    `admin.css`: на 940 — счётчик у заголовков «Снятые / Не допущены»
 *    (красный `--danger-subtle`), на 8446 — подпись «в зачёт не берётся»
 *    (прозрачная, приглушённая, ПУНКТИРОМ). Второе идёт позже и перебивало
 *    первое: замер показал счётчик снятых белым 0.5 с пунктиром — рядом с
 *    красным заголовком `.ad-reg-title-out`. Беда родилась ровно на шве.
 *
 * 2. ЗОВ В ПУСТОТУ. `bracket.js` звал `.ad-badge-success`, которого НЕ
 *    СУЩЕСТВОВАЛО: статус «сыгран» в расписании рисовался базовым серым,
 *    хотя рядом лежал `.ad-badge-green` ровно с нужными красками. Класс
 *    назвали по тону, а объявили по цвету — и зов промахнулся.
 *    Переименование в тон починило это само.
 *
 * 3. ПОРЯДОК ПРАВИЛ В ФАЙЛЕ РЕШАЕТ. Когда имена развели, оба счётчика
 *    остались СТОЯТЬ ВЫШЕ базового `.ad-badge`, и он при равной силе
 *    селектора перебивал им фон: краска проходила, фон оставался серым.
 *    Перенесены вниз, к остальным тонам.
 *
 * 4. И ЧЕТВЁРТУЮ Я ЗАВЁЛ САМ, пока чинил первые три. Разводя `-out`/`-blk`
 *    в `-danger`/`-warning`, я не заметил, что рядом уже лежат `-red` и
 *    `-yellow` с теми же красками. Вышло ЧЕТЫРЕ имени на ДВА тона. Поймал
 *    замер: краски совпали до байта. ОДИН ТОН — ОДНО ИМЯ.
 *
 * ЦВЕТ НЕ ГОВОРИТ, ЧТО ЗНАЧИТ. `-green` — это успех, подтверждение или
 * «идёт»? Имя тона отвечает, имя цвета нет. Компонент `Badge` 27:53 в
 * Фигме называет именно тоны, и его описание поправлено 19.10.
 *
 * ЧТО НЕ ТРОНУТО, И ЭТО ПРОВЕРЕНО ЧТЕНИЕМ: `-del` и `-sm` — не тоны.
 * Первый КРЮЧОК для обработчика на кнопке удаления (вид ей даёт
 * `ad-btn-icon`), второй — размер. `-ig` и `-out` — состояния матча со
 * своей формой, а не тоны: у них рамка и свой кегль.
 *
 *   node tools/check-badge-tona.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чисто = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '));

const css = чисто(fs.readFileSync(path.join(КОРЕНЬ, 'css/admin.css'), 'utf8'));
const строки = css.split('\n');

/* ИМЕНА ЦВЕТОВ ЗАПРЕЩЕНЫ. Список — не прихоть: ровно эти четыре и стояли. */
const ЦВЕТА = ['green', 'yellow', 'blue', 'red', 'orange', 'violet', 'lime', 'grey', 'gray'];
/* НЕ ТОНЫ, И ЭТО НАЗВАНО: крючок, размер и две формы состояния. */
const НЕ_ТОНЫ = ['del', 'sm', 'ig', 'out', 'accent'];

function всеJS(дир, итог) {
    итог = итог || [];
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        const п = path.join(дир, э.name);
        if (э.isDirectory()) всеJS(п, итог);
        else if (э.name.endsWith('.js')) итог.push(п);
    }
    return итог;
}

const ошибки = [];
let держится = 0;
function правило(имя, годно, подсказка) {
    if (годно) { держится++; console.log('  ✓ ' + имя); }
    else ошибки.push({ имя, подсказка });
}

/* ── 1. ни одного имени по цвету ── */
const поЦвету = [];
строки.forEach((с, i) => {
    const м = с.match(/\.ad-badge-([a-z]+)/);
    if (м && ЦВЕТА.indexOf(м[1]) !== -1) поЦвету.push('admin.css:' + (i + 1) + ' .ad-badge-' + м[1]);
});
const зовыПоЦвету = [];
for (const п of всеJS(path.join(КОРЕНЬ, 'js'))) {
    const т = чисто(fs.readFileSync(п, 'utf8'));
    for (const ц of ЦВЕТА) {
        if (new RegExp('ad-badge-' + ц + '(?![\\w-])').test(т)) {
            зовыПоЦвету.push(path.relative(КОРЕНЬ, п) + ' .ad-badge-' + ц);
        }
    }
}
правило(
    'ни один бейдж не назван по цвету',
    поЦвету.length === 0 && зовыПоЦвету.length === 0,
    'По цвету: ' + поЦвету.concat(зовыПоЦвету).join(', ') + '.\n' +
    'ЦВЕТ НЕ ГОВОРИТ, ЧТО ЗНАЧИТ: `-green` это успех, подтверждение или\n' +
    '«идёт»? Имя тона отвечает, имя цвета нет. И цена не только в чтении:\n' +
    '`bracket.js` звал `.ad-badge-success`, которого не существовало, —\n' +
    'статус «сыгран» рисовался серым.');

/* ── 2. один тон — одно имя ── */
/* ТЕЛО ВЫРЕЗАЕТСЯ ПО БАЛАНСУ СКОБОК, А НЕ ПОСТРОЧНЫМ ОБРАЗЦОМ.
   Сперва правило искало `.ad-badge-X { ... }` в ОДНОЙ строке — и потому
   сравнивало краски только у однострочных определений, а многострочные не
   видело вовсе. Прувер это нашёл: он завёл второе имя на тот же тон
   многострочным блоком, и правило осталось зелёным.
   ПРАВИЛО, ВИДЯЩЕЕ ЧАСТЬ ОБЪЯВЛЕНИЙ, СТОРОЖИТ ЧАСТЬ ПРОДУКТА. */
const краски = {};
const обрИмя = /\.ad-badge-([a-z]+)\s*\{/g;
let мИмя;
while ((мИмя = обрИмя.exec(css))) {
    const имя = мИмя[1];
    if (НЕ_ТОНЫ.indexOf(имя) !== -1) continue;
    const о = css.indexOf('{', мИмя.index);
    let гл = 0, конец = -1;
    for (let i = о; i < css.length; i++) {
        if (css[i] === '{') гл++;
        else if (css[i] === '}') { гл--; if (гл === 0) { конец = i; break; } }
    }
    if (конец === -1) continue;
    const тело = css.slice(о + 1, конец);
    const цв = (тело.match(/(?:^|[;\s])(?:background|color):\s*var\(([^)]+)\)/g) || [])
        .map(s => s.trim()).sort().join('|');
    if (цв) (краски[цв] = краски[цв] || []).push(имя);
}
const повторы = Object.keys(краски).filter(к => краски[к].length > 1)
    .map(к => краски[к].join(' = ') + ' (' + к + ')');
правило(
    'один тон — одно имя',
    повторы.length === 0,
    'Один тон под разными именами: ' + повторы.join('; ') + '.\n' +
    'Эту беду я завёл САМ, разводя столкнувшиеся имена: рядом уже лежали\n' +
    'те же краски под именами цветов, и вышло четыре имени на два тона.\n' +
    'Поймал замер — краски совпали до байта.');

/* ── 3. ни одного зова в пустоту ── */
const объявлены = new Set();
(css.match(/\.ad-badge(-[a-z]+)?/g) || []).forEach(к => объявлены.add(к.slice(1)));
const вПустоту = [];
for (const п of всеJS(path.join(КОРЕНЬ, 'js'))) {
    const т = чисто(fs.readFileSync(п, 'utf8'));
    (т.match(/ad-badge-[a-z]+/g) || []).forEach(к => {
        const хвост = к.replace('ad-badge-', '');
        if (!объявлены.has(к) && НЕ_ТОНЫ.indexOf(хвост) === -1) {
            вПустоту.push(path.relative(КОРЕНЬ, п) + ' .' + к);
        }
    });
}
правило(
    'ни один зовущийся бейдж не бьёт в пустоту',
    вПустоту.length === 0,
    'Зовут несуществующее: ' + Array.from(new Set(вПустоту)).join(', ') + '.\n' +
    'Такой бейдж рисуется БАЗОВЫМ СЕРЫМ, и на экране это выглядит как\n' +
    'решение, а не как промах. Крючки обработчиков (`-del`) и размер\n' +
    '(`-sm`) из правила исключены НАЗВАННО: они не тоны.');

/* ── 4. ВСЕ модификаторы объявлены НИЖЕ базового класса ── */
/* ПРАВИЛО, ИСКЛЮЧИВШЕЕ ЧАСТЬ СЕМЕЙСТВА, ПРОПУСТИЛО РОВНО ЕЁ. Сперва оно
   смотрело только тоны, а `-sm` было вычеркнуто как «не тон». Там беда и
   сидела: `.ad-badge-sm` стоял на 1105, выше базового на 4045, и базовый
   возвращал кегль обратно — номер посева `[1]` выходил 12 вместо 11 при
   четырёх живых зовах. Нашёл ЗАМЕР, не чтение. Теперь смотрятся ВСЕ.
   Исключение осталось одно и названное: `-del` — крючок обработчика, в
   css его нет вовсе. */
const базовый = строки.findIndex(с => /^\.ad-badge\s*\{/.test(с));
const выше = [];
строки.forEach((с, i) => {
    const м = с.match(/^\.ad-badge-([a-z]+)/);
    if (м && м[1] !== 'del' && i < базовый) {
        выше.push('admin.css:' + (i + 1) + ' .ad-badge-' + м[1]);
    }
});
правило(
    'все модификаторы объявлены ниже базового класса',
    базовый !== -1 && выше.length === 0,
    'Выше базового: ' + выше.join(', ') + ' (базовый на строке ' + (базовый + 1) + ').\n' +
    'ПОРЯДОК ПРАВИЛ В ФАЙЛЕ РЕШАЕТ: при равной силе селектора побеждает\n' +
    'тот, что ниже. Модификатор выше базового МЁРТВ — тон теряет фон и\n' +
    'оставляет краску, размер не меняется вовсе. На экране это выглядит\n' +
    'как решение, а не как промах, и зовы при этом живые.');

/* ── 4б. ни одного повтора базового кегля вложенным селектором ── */
/* `.ad-reg-section-title .ad-badge { font-size: var(--fs-xs) }` повторял
   то, что базовый класс уже задаёт: на сегодняшних бейджах не менял
   ничего, но удельный вес у него ВЫШЕ, чем у `-sm`, и первый же мелкий
   бейдж в заголовке раздела молча вернулся бы к обычному кеглю. Снят.
   ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. */
const вложенные = [];
строки.forEach((с, i) => {
    if (/^\S[^{]*\s\.ad-badge\s*\{/.test(с)) {
        вложенные.push('admin.css:' + (i + 1) + ' ' + с.trim());
    }
});
правило(
    'базовый кегль не повторяется вложенным селектором',
    вложенные.length === 0,
    'Вложенный повтор: ' + вложенные.join(', ') + '.\n' +
    'Такой селектор тяжелее модификатора `-sm` и молча его перебьёт.\n' +
    'Повтор того же значения не меняет вида СЕГОДНЯ — и ровно поэтому\n' +
    'ловушка незаметна.');

/* ── 5. у каждого имени ровно одно определение ── */
const счёт = {};
строки.forEach(с => {
    const м = с.match(/^\.ad-badge(-[a-z]+)?\s*[\{,]/);
    if (м) { const к = 'ad-badge' + (м[1] || ''); счёт[к] = (счёт[к] || 0) + 1; }
});
const дважды = Object.keys(счёт).filter(к => счёт[к] > 1).map(к => '.' + к + ' ×' + счёт[к]);
правило(
    'у каждого имени бейджа ровно одно определение',
    дважды.length === 0,
    'Объявлено дважды: ' + дважды.join(', ') + '.\n' +
    'Так и была первая беда: `.ad-badge-out` значил и счётчик снятых, и\n' +
    'подпись «в зачёт не берётся». Второе определение перебивало первое, и\n' +
    'счётчик рисовался пунктиром рядом с красным заголовком.');

/* ── 6. лестница базового бейджа — решение Кости 21.10 ── */
/* ЗАМОРАЖИВАЕТСЯ ЗАМЕРЕННОЕ, А НЕ ЗАДУМАННОЕ. Эталонный компонент `Badge`
   27:53 стоит на 11px / Medium / высоте 24; базовый `.ad-badge` админки
   замерен стендом как 12px / вес 400 / высота 22 на 29 зовах.
   КОСТЯ 21.10 РЕШИЛ ОСТАВИТЬ КАК ЕСТЬ — расхождение с компонентом
   НАМЕРЕННОЕ, и сторож держит ровно это состояние: кегль ступенью
   `--fs-xs`, радиус пилюлей `--radius-full`, вес НЕ ЗАДАН (наследуется 400).
   Если кегль однажды поедет — поедет по решению, а не молча. */
const тБаз = (() => {
    const м = /\.ad-badge\s*\{([^}]*)\}/.exec(css);
    return м ? м[1] : '';
})();
const лестница = [];
if (!/font-size:\s*var\(--fs-xs\)/.test(тБаз)) лестница.push('кегль не на ступени --fs-xs');
if (!/border-radius:\s*var\(--radius-full\)/.test(тБаз)) лестница.push('радиус не пилюля --radius-full');
if (/font-weight/.test(тБаз)) лестница.push('вес задан — он должен наследоваться');
правило(
    'лестница базового бейджа стоит на ступенях',
    тБаз !== '' && лестница.length === 0,
    'Разошлось: ' + лестница.join('; ') + '.\n' +
    'Компонент `Badge` 27:53 держит 11px / Medium / 24. Базовый бейдж\n' +
    'админки замерен 12px / 400 / 22, и КОСТЯ 21.10 РЕШИЛ ОСТАВИТЬ ТАК —\n' +
    'расхождение намеренное, 29 зовов не трогаем. Сторож держит именно\n' +
    'замеренное состояние: кегль ступенью, радиус пилюлей, вес не задан.');

console.log('');
if (!ошибки.length) {
    console.log('  ок      бейдж админки: ' + держится + ' правил');
    console.log('          имена по тону; один тон — одно имя; зовов в пустоту нет');
    console.log('          тоны ниже базового; у каждого имени одно определение');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  бейдж админки — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
