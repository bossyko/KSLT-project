/**
 * ЗАМОРОЗКА: ПОРЯДОК ОЧЕРЕДИ — ВРЕМЯ ПОСТАНОВКИ В НЕЁ, А НЕ ПОДАЧИ.
 *
 * Беда, пойманная прогоном 01.10 на турнире ec46a732 (8 мест, 8 в
 * основе, 4 в очереди). Менеджер жмёт «Снять» у S03, окно обещает «Место
 * освободится и достанется первому в очереди», а в базе НЕ МЕНЯЕТСЯ
 * НИЧЕГО: 8 approved / 4 waitlist до и после, и ни слова в ответ.
 *
 * Причина: «Снять» ставит `waitlist` и тут же зовёт подъём, а подъём брал
 * первого по `registered_at`. У снятого время подачи 16:54:26, у первого
 * ждуна 16:54:50 — снятый оказывался первым в очереди и возвращался в
 * основу. Он обгоняет очередь ВСЕГДА: он подавал заявку раньше тех, кто
 * в основу не попал.
 *
 * ПО ITF/ATP список альтернатов упорядочен тем, кто раньше в нём
 * оказался. Освободивший место возвращается в альтернаты, но не впереди
 * тех, кто ждал: своё место он уже получал.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ: «кто встал в очередь позже — тот и ниже в ней»,
 * и «снятый не может занять место, которое сам только что освободил».
 *
 * ПОРЯДОК СЧИТАЕТ БАЗА. `queue_at` = COALESCE(waitlisted_at,
 * registered_at), колонка генерируемая — записать её руками нельзя, и
 * второго определения порядка не завести.
 *
 *   node tools/check-ochered-poryadok.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СЕТКА = чит('js/admin/sections/bracket.js');
const СЕТч = безКом(СЕТКА);
const СЕРВЕР = безКом(чит('supabase/functions/tournament-register/index.ts'));
const SQL = чит('sql/функции/ochered-vremya-postanovki.sql');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

function тело(текст, имя) {
    const i = текст.indexOf('function ' + имя + '(');
    if (i === -1) return '';
    let гл = 0, j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}

/* ── 1. Подъём читает очередь по queue_at ────────────────────────────── */
const ПОДЪЁМ = тело(СЕТч, 'поднятьИзОчереди');
правило('подъём сортирует очередь по queue_at',
    ПОДЪЁМ.length > 0 && /order\s*\(\s*'queue_at'/.test(ПОДЪЁМ),
    '`поднятьИзОчереди` сортирует очередь не по `queue_at`. По ' +
    '`registered_at` снятый с основы обгоняет всех, кто ждал, и ' +
    'возвращается в основу сам — «Снять» перестаёт снимать');

правило('подъём не сортирует по времени подачи',
    ПОДЪЁМ.length > 0 && !/order\s*\(\s*'registered_at'/.test(ПОДЪЁМ),
    'в `поднятьИзОчереди` вернулась сортировка по `registered_at`. ' +
    'Порядок очереди определён один раз — колонкой `queue_at`');

/* ── 2. ВСЕ ДВЕРИ В ОЧЕРЕДЬ СТАВЯТ ОТМЕТКУ ───────────────────────────
   Дверей оказалось три, и правка одной не чинила остальные: окно «три
   исхода», кнопка в меню строки, вытеснение на сервере. Пропущенная
   дверь — та, через которую беда вернётся. */
const ДВЕРИ = [
    ['админка: окно «три исхода» и меню строки', СЕТч],
    ['сервер: вытеснение игроком своей категории', СЕРВЕР]
];
ДВЕРИ.forEach(([имя, текст]) => {
    const переводы = (текст.match(/update\s*\(\s*\{\s*status:\s*'waitlist'/g) || []).length;
    const сОтметкой = (текст.match(/update\s*\(\s*\{\s*status:\s*'waitlist',\s*waitlisted_at:/g) || []).length;
    правило('дверь «' + имя + '»: отметка времени постановки',
        переводы > 0 && переводы === сОтметкой,
        'переводов в очередь ' + переводы + ', из них с `waitlisted_at` — ' +
        сОтметкой + '. Дверь без отметки возвращает снятого в основу сам: ' +
        'его `queue_at` остаётся временем подачи, и он обгоняет очередь');
});

/* ── 3. Показываем очередь в том же порядке, в каком её читает подъём ── */
правило('очередь на экране в порядке подъёма',
    /status === 'waitlist'[\s\S]{0,260}queue_at/.test(СЕТч),
    'список очереди в разделе «Заявки» сортируется не по `queue_at`. ' +
    'Менеджер должен видеть на экране того, кто займёт место — иначе ' +
    'экран и расчёт расходятся');

правило('окно замены показывает очередь в том же порядке',
    (СЕТч.match(/queue_at\s*\|\|\s*[ab]?\.?registered_at/g) || []).length >= 2 ||
    (СЕТч.match(/queue_at/g) || []).length >= 4,
    'окно замены сортирует очередь по своему. Порядок очереди один на ' +
    'продукт: кто первый по `queue_at`, тот первый и в списке, и в окне, ' +
    'и в подъёме');

/* ── 4. Порядок считает база, а не код ───────────────────────────────── */
правило('queue_at заведён генерируемым',
    /GENERATED\s+ALWAYS\s+AS\s*\(\s*COALESCE\s*\(\s*waitlisted_at\s*,\s*registered_at\s*\)\s*\)\s*STORED/i.test(SQL),
    'в sql/функции/ochered-vremya-postanovki.sql `queue_at` перестал быть ' +
    'генерируемым столбцом. Обычный столбец кто-нибудь однажды заполнит ' +
    'руками, и порядок очереди снова станет мнением, а не правилом');

правило('время подачи не переписывается',
    !/UPDATE[\s\S]{0,200}SET[\s\S]{0,120}registered_at\s*=/i.test(SQL),
    'в миграции появилась запись в `registered_at`. Это факт подачи ' +
    'заявки, его переписывать нельзя — для очереди есть `waitlisted_at`');

/* ── 7. Пара из одного человека ──────────────────────────────────────
   Вопрос Кости 02.10: «если будет заменяться капитан, что будет
   перетираться?». Замер показал дыру рядом: `ктоЗанятВТурнире` пропускает
   заменяемую заявку ЦЕЛИКОМ, и вместе с заменяемым из списка занятых
   выпадал его НАПАРНИК — поиск предлагал поставить капитаном того, кто уже
   стоит напарником в этой же паре. Вышла бы пара из одного человека. */
const ОКНО_ЗАМЕНЫ = тело(СЕТч, 'openReplaceModal');

правило('обе стороны заменяемой заявки недоступны для выбора',
    ОКНО_ЗАМЕНЫ.length > 0 &&
    /\[reg\.player_id, reg\.partner_id\][\s\S]{0,160}занятость\.занятые\[/.test(ОКНО_ЗАМЕНЫ),
    'из списка занятых снова выпал напарник заменяемой пары: поиск предложит ' +
    'поставить капитаном того, кто уже стоит напарником, и выйдет пара из ' +
    'одного человека');

правило('сторож «разные игроки» стоит и на записи, а не только в списке',
    /другаяСторона = target === 'partner' \? reg\.player_id : reg\.partner_id/.test(ОКНО_ЗАМЕНЫ) &&
    /selectedId === другаяСторона[\s\S]{0,120}return;/.test(ОКНО_ЗАМЕНЫ),
    'проверку «в паре разные игроки» убрали с записи. Список обойти можно: ' +
    'выбор из очереди кладётся в то же поле мимо поиска');

/* ── 8. Сетка не остаётся с прежним игроком молча ────────────────────
   `заменитьВМатчах` пропускала матч, где новый игрок уже стоит, — чтобы не
   поставить одного человека по обе стороны клетки. Заявка при этом уже
   переписана, и по матчу её не найти: на публичной вместо пары встаёт одно
   имя без напарника. Пропуск стал отказом, а дверь замены до него не
   доводит — отказывает ДО всякой записи. */
const В_МАТЧАХ = тело(СЕТч, 'заменитьВМатчах');

правило('матч с новым игроком не пропускается молча',
    В_МАТЧАХ.length > 0 &&
    /м\.player1_id === новый \|\| м\.player2_id === новый\)\s*\{[\s\S]{0,400}return/.test(В_МАТЧАХ) &&
    !/м\.player2_id === новый\) continue;/.test(В_МАТЧАХ),
    'пропуск снова молчит: матч остаётся с прежним игроком, заявка уже ' +
    'переписана, и на публичной вместо пары встанет одно имя');

правило('замена отказывает ДО записи, если новый уже стоит в сетке',
    /ужеСтоит[\s\S]{0,200}L\.regReplaceInDraw[\s\S]{0,60}return;/.test(ОКНО_ЗАМЕНЫ),
    'отказ «уже стоит в сетке» пропал или уехал после записи. Он обязан ' +
    'стоять до снятия из очереди и до правки заявки: иначе человек выпадет ' +
    'из очереди, а замена не состоится');

/* ── вывод ───────────────────────────────────────────────────────────── */
if (ошибки.length) {
    console.log('✗ Порядок очереди: ' + ошибки.length + ' правил упало\n');
    ошибки.forEach(о => console.log('  • ' + о.имя + '\n    ' + о.подсказка + '\n'));
    process.exit(1);
}
console.log('✓ Порядок очереди — по времени постановки: все правила держат');
