#!/usr/bin/env python3
"""
Разбор турнирных сеток ТБШ из Excel.

Сетка нарисована по-бумажному: столбец на круг. Имя победителя пары
появляется в следующем столбце ровно посередине между соперниками, а под
именем — счёт. Сеяные первый круг не играют: их имя сразу стоит во втором
столбце, счёта под ним нет.

Отсюда два правила:
  • есть счёт под именем — значит был матч, соперников ищем в предыдущем
    столбце: ближайшего сверху и ближайшего снизу;
  • нет счёта и нет соперников — значит это вход в сетку (посев или бай).

Номер посева стоит на одну клетку левее имени.

Имена в файле набраны как попало: лишние пробелы, разрывы внутри фамилии.
Здесь чиним только пробелы — сверка с базой отдельным шагом.

Запуск: python3 tools/parse-brackets.py <файл.xlsx> [лист]
"""
import sys, re, json
import openpyxl

СЧЁТ = re.compile(r'^\s*\d+[/:]\d+')


def чистое(v):
    return re.sub(r'\s+', ' ', str(v)).strip() if v not in (None, '') else ''


def это_имя(s):
    if not s or СЧЁТ.match(s) or re.match(r'^[\d\s/:,.-]+$', s):
        return False
    низ = s.lower()
    return not ('круг' in низ or 'финал' in низ or 'тбш' in низ
                or низ in ('№', 'bye', 'место', 'wo', 'w/o'))


def разобрать(ws):
    подписи = {c: чистое(ws.cell(2, c).value) for c in range(2, ws.max_column + 1)}
    столбцы = {}
    for c in range(2, ws.max_column + 1):
        клетки = []
        for r in range(3, ws.max_row + 1):
            s = чистое(ws.cell(r, c).value)
            if это_имя(s):
                под = чистое(ws.cell(r + 1, c).value)
                низ = под.lower()
                счёт = под if (СЧЁТ.match(под) or низ in ('bye', 'wo', 'w/o')) else None
                клетки.append({'строка': r, 'имя': s, 'счёт': счёт,
                               'снятие': низ in ('bye', 'wo', 'w/o')})
        if клетки:
            столбцы[c] = клетки

    матчи, входы = [], []
    колонки = sorted(столбцы)

    # Участник — тот, у кого слева стоит номер посева. Отдельным проходом,
    # не оглядываясь на пары: у клетки сеяного пара может найтись случайно,
    # и он терялся.
    for c in колонки:
        for клетка in столбцы[c]:
            посев = чистое(ws.cell(клетка['строка'], c - 1).value)
            if посев.isdigit():
                входы.append({
                    'имя': клетка['имя'],
                    'посев': int(посев),
                    'вошёл_в_круг': c - 1,
                })
    for c in колонки:
        пред = столбцы.get(c - 1, [])
        for клетка in столбцы[c]:
            # Победитель стоит ровно посередине между соперниками: сумма их
            # строк вдвое больше его собственной. Условие точное — по нему
            # и отличаем настоящую пару от соседей из чужой части сетки.
            # Берём самую тесную симметричную пару. Просто «первая
            # подходящая» не годится: на листе несколько сеток одна под
            # другой, и строки далёких игроков случайно дают ту же сумму —
            # Сейитову доставался соперник с другого конца листа.
            середина = 2 * клетка['строка']
            пара = None
            лучшее = None
            for i, a in enumerate(пред):
                if a['строка'] >= клетка['строка']:
                    break
                for b in пред[i + 1:]:
                    if a['строка'] + b['строка'] == середина:
                        разброс = b['строка'] - a['строка']
                        if лучшее is None or разброс < лучшее:
                            лучшее, пара = разброс, (a, b)
            есть_пара = пара is not None

            if есть_пара and клетка['счёт']:
                a, b = пара
                победитель = клетка['имя']
                проигравший = b['имя'] if a['имя'] == победитель else a['имя']
                матчи.append({
                    'круг': подписи.get(c - 1) or f'круг {c - 1}',
                    'номер_круга': c - 1,
                    'строка': клетка['строка'],
                    'победитель': победитель,
                    'проигравший': проигравший,
                    # Снятие: матч назначили, но игры не было. В нашей админке
                    # это исход W/O, снявшимся считается проигравший.
                    'счёт': None if клетка['снятие'] else клетка['счёт'],
                    'исход': 'W/O' if клетка['снятие'] else None,
                })

    return входы, матчи


def main(путь, только=None):
    wb = openpyxl.load_workbook(путь, data_only=True)
    итог = {}
    for лист in wb.sheetnames:
        if '2026' not in лист or (только and лист != только):
            continue
        ws = wb[лист]
        входы, матчи = разобрать(ws)
        итог[лист] = {
            'заголовок': чистое(ws.cell(1, 1).value),
            'участники': входы,
            'матчи': матчи,
        }
    print(json.dumps(итог, ensure_ascii=False, indent=1))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else None)
