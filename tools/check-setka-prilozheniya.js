#!/usr/bin/env node
/**
 * СЕТКА ПЛЕЙ-ОФФ В ПРИЛОЖЕНИИ — ЗАМОРОЗКА КУСКА 217 (28.10).
 *
 * ЗАМЕР ДО. Плей-офф показывался таблетками кругов: виден ОДИН круг за
 * раз, и путь пары из четвертьфинала в финал проследить нельзя. Костя
 * сказал: «мне не нравится, хочется видеть СЕ сетку». Мой довод был про
 * боковой ход, и он снят его же глазами: на сайте сетка на 375
 * двигается вбок (654 при видимых 343), обрезок там 0, и этот вид он
 * принял.
 *
 * ЕЩЁ ОДИН ДУБЛИКАТ ВНУТРИ САЙТА. Разметка «круг — столбец линий —
 * круг» стояла в `js/tournament-detail.js` ЧЕТЫРЕЖДЫ: у одиночной
 * сетки, у лиги, у кругового плей-офф и у сетки «все места». Клетку
 * матча рисовал `renderMatch` — 132 строки вместе с полосой
 * предсказания. Всё это переехало в общий дом `js/kslt-setka.js`;
 * предсказание осталось у сайта отдельной функцией и приходит в дом
 * подстановкой `подвал`, потому что в приложении его нет.
 *
 * ЗАМЕР ПОСЛЕ. Сайт: сетка 343/654, кругов 4, матчей 15, имён 30,
 * счётов 30, победителей 15, вкладка 2431 — ВСЕ ЧИСЛА СОВПАЛИ С
 * ЗАМЕРОМ ДО. Проверен и незавершённый турнир: 16 матчей, 16 TBD, 16
 * меток групп, высота 3110 — тоже совпало, сравнением с прежним файлом
 * из git, а не по памяти.
 * Приложение на 375×812: кругов 4, матчей 15, подписи слева направо
 * «Раунд 1 · Четвертьфинал · Полуфинал · Финал», сетка 311/776,
 * вкладка 1.35 экрана, обрезок 0.
 *
 * ПОПУТНО. Строка прошедшего из группы была залита целиком, и текст на
 * ней терялся: `--accent-dim` в приложении переопределён ТОЛЬКО под
 * светлую тему (`app.css:157`), а в тёмной из `tokens.css` приходит
 * СПЛОШНОЙ лайм. Предупреждение об этом стоит прямо в `tokens.css` —
 * и я на него напоролся. Подложки переведены на `--accent-subtle`, а
 * у прошедшего выделяется имя, а не полоса (слово Кости).
 *
 * Запуск: node tools/check-setka-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
function безСлов(отн) {
    return чит(отн).replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const дом = безСлов('js/kslt-setka.js');
const главная = безСлов('mobile/www/js/screens/home.js');
const сайт = безСлов('js/tournament-detail.js');
const css = чит('mobile/www/css/app.css');

/* ── 1. ДОМ РИСУЕТ И КЛЕТКУ, И СЕТКУ ── */
правило(
    'дом рисует клетку матча',
    /S\.матч = function/.test(дом),
    'Клетку рисовал `renderMatch` сайта — 132 строки, и в приложении\n' +
    'её не было вовсе.');

правило(
    'дом рисует сетку столбцами',
    /S\.сетка = function/.test(дом) && /td-connector-column/.test(дом),
    'Разметка «круг — столбец линий — круг» стояла в коде сайта\n' +
    'ЧЕТЫРЕЖДЫ. Одно понятие, четыре копии.');

правило(
    'дом не тянет за собой предсказание сайта',
    !/calculatePrediction/.test(дом) && !/td-pred-bar/.test(дом),
    'Полоса предсказания — довесок САЙТА: в приложении её нет.\n' +
    'Она приходит в дом подстановкой `подвал`.');

/* ── 2. ОБА ПРОДУКТА ЗОВУТ ДОМ ── */
правило(
    'сайт рисует клетку домом',
    /KSLT_SETKA\.матч\(/.test(сайт) && !/<div class="td-match-player /.test(сайт),
    'Разметка клетки обязана идти из дома целиком.');

правило(
    'полоса предсказания осталась у сайта отдельной функцией',
    /function полосаПредсказания\(/.test(сайт) && /td-pred-bar/.test(сайт),
    'Её нельзя было уводить в дом и нельзя было терять.');

правило(
    'приложение рисует плей-офф сеткой из дома',
    /KSLT_SETKA\.сетка\(/.test(главная) && /function сеткаПлейофф/.test(главная),
    'Было: таблетки кругов — виден один круг за раз.');

правило(
    'таблетки кругов в плей-офф снесены',
    главная.indexOf('function renderPlayoffWithPills') < 0,
    'Мёртвым код назван ПОСЛЕ ПРОВЕРКИ: зовов не осталось ни одного,\n' +
    'все шесть переведены на `сеткаПлейофф`.');

/* ── 3. ПОРЯДОК КРУГОВ: СЛЕВА РАННИЕ, СПРАВА ФИНАЛ ── */
правило(
    'круги идут слева направо к финалу',
    /номера\.sort\(function \(a, b\) \{ return a - b; \}\)/.test(главная),
    'ПОСЧИТАНО замером, а не угадано: подписи дали «Финал» у\n' +
    'НАИБОЛЬШЕГО номера круга. Сортировка по убыванию ставила финал\n' +
    'первым слева — и сетка читалась задом наперёд.');

/* ── 4. ПОДЛОЖКА — ВЕРНЫМ ТОКЕНОМ ── */
(function () {
    /* Комментарии снимаем ПЕРЕД проверкой: иначе сторож ловит
       собственное объяснение, где это имя и упомянуто. */
    const чистый = безСлов('mobile/www/css/app.css');
    const куски = чистый.split('.td-bracket-scroll {');
    const наш = куски.length > 1 ? куски[1].split('.td-more-btn')[0] : '';
    правило(
        'подложки сетки взяты `--accent-subtle`, а не `--accent-dim`',
        наш.indexOf('var(--accent-dim)') < 0 && /accent-subtle/.test(наш),
        'Имя `--accent-dim` значит разное в двух базах: на сайте это\n' +
        'СПЛОШНОЙ цвет, в приложении полупрозрачная подложка — и\n' +
        'переопределено оно только под светлую тему. В тёмной приходит\n' +
        'сплошной лайм, и заливка им съедает текст.');

    правило(
        'у прошедшего из группы выделено имя, а не полоса',
        /\.td-gt-qualified \.td-gt-name/.test(css) &&
        !/\.td-gt-qualified \{ background/.test(css),
        'Строка была залита целиком, и текст на ней терялся.\n' +
        'Костя увидел это глазами: «надо было только текст имени».');
})();

/* ── 5. ИМЯ В КЛЕТКЕ НЕ ОБРЕЗАЕТСЯ ── */
правило(
    'имя в клетке сетки переносится, а не обрезается',
    /\.td-player-name \{[^}]*min-width: 0/.test(css) &&
    !/\.td-player-name \{[^}]*text-overflow: ellipsis/.test(css),
    'Правило куска 216: обрезать фамилию многоточием нельзя,\n' +
    'пара переносится по игроку.');

/* ── 6. КОПИЯ ДОМА СВЕРЯЕТСЯ ── */
правило(
    'копия общего дома совпадает до байта',
    чит('js/kslt-setka.js') !== '' &&
    чит('js/kslt-setka.js') === чит('mobile/www/js/kslt-setka.js'),
    'Разойдутся — беда родится ровно на шве.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      сетка приложения: все ' + держится + ' правил держатся');
    console.log('          клетка и сетка из дома, круги слева направо\n');
}
