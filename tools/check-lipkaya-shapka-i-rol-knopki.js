/**
 * ЗАМОРОЗКА КУСКА 123 — ЛИПКАЯ ШАПКА ТАБЛИЦЫ ОЧКОВ И РОЛИ КНОПОК СТРОКИ.
 *
 * Обе находки — с ОБХОДА БОЕВОЙ АДМИНКИ, а не из чтения.
 *
 * 1. Шапка таблицы очков объявлена `position: sticky` и НЕ ЛИПЛА: на
 *    последней из 65 строк её ячейка уходила вверх на −1200px. Обёртку
 *    `.ad-pts-scroll` уже опустошили ровно по этой причине — и беда
 *    осталась, потому что `overflow-x: auto` стоит ЭТАЖОМ ВЫШЕ.
 *    ЛЕЧИЛИ ТУ ОБЁРТКУ, КОТОРУЮ ЗАМЕТИЛИ, А МЕШАЛА СЛЕДУЮЩАЯ.
 *    Проверено в браузере ДО отправки: с переполнением −1200, без него 64.
 *
 * 2. «Сетка», «Опубликовать» и «Снять» были одного тона `secondary`:
 *    первая открывает экран, две другие одним нажатием меняют видимость
 *    турнира на сайте. ДЕЙСТВИЕ С ПОСЛЕДСТВИЯМИ НЕОТЛИЧИМО ПО ВИДУ ОТ
 *    БЕЗОБИДНОГО.
 *
 *   node tools/check-lipkaya-shapka-i-rol-knopki.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const AD = чит('css/admin.css');
const НАСТР = чит('js/admin/sections/settings.js');
const ТУРН = чит('js/admin/sections/tournaments.js');

/* ── 1. ЛИПКОСТЬ ──────────────────────────────────────────────────────── */
правило('шапка таблицы очков объявлена липкой и липнет к шапке сайта',
    /\.ad-pts th\s*\{[^}]*position:\s*sticky[^}]*top:\s*var\(--header-h\)/s.test(AD),
    'Шапка перестала быть липкой или липнет к своему числу вместо\n' +
    '`--header-h`. Одно определение высоты шапки на весь продукт — тем же\n' +
    'числом липнут полосы фильтров.');

правило('карточка таблицы очков помечена своим классом',
    /ad-table-card ad-table-card-pts/.test(НАСТР),
    'Таблица очков снова лежит в обычной `.ad-table-card`. У той\n' +
    '`overflow-x: auto`, и она становится ПРОКРУЧИВАЕМЫМ ПРЕДКОМ: шапка\n' +
    'липнет к её краю, а край ниже экрана на две с половиной тысячи\n' +
    'пикселов. ЛИПКОСТЬ ПРИЛИПАЕТ К БЛИЖАЙШЕМУ ПРОКРУЧИВАЕМОМУ ПРЕДКУ,\n' +
    'А НЕ К ЭКРАНУ.');

правило('у карточки таблицы очков переполнения нет',
    /\.ad-table-card-pts\s*\{[^}]*overflow:\s*visible/s.test(AD),
    'Переполнение вернулось — значит липкость снова мертва. Боковая\n' +
    'прокрутка этой таблице не нужна: замер 22.10 — таблица 1114 при\n' +
    'карточке 1162, и пять колонок укладываются в 820 (планшет стоя).');

правило('обёртка `.ad-pts-scroll` осталась пустой',
    /\.ad-pts-scroll\s*\{\s*\/\*[^}]*\*\/\s*\}/.test(AD),
    'В `.ad-pts-scroll` снова что-то объявили. Её опустошили НАМЕРЕННО:\n' +
    'любое переполнение здесь убивает липкость тем же способом.');

/* ── 2. РОЛИ КНОПОК СТРОКИ ТУРНИРА ───────────────────────────────────── */
правило('кнопка публикации берёт роль по состоянию, а не один тон на оба',
    /\(t\.published_at \? 'ad-btn-warning' : 'ad-btn-primary'\)/.test(ТУРН),
    'Кнопка снова одного тона на оба состояния. Роли берутся из лестницы:\n' +
    '`primary` — утверждающее (турнир открывается людям), `warning` —\n' +
    'осторожное и ОБРАТИМОЕ (убираем с сайта, ничего не удаляя).\n' +
    'Цвет заодно говорит СОСТОЯНИЕ с одного взгляда.');

правило('кнопка публикации не носит нейтральный тон',
    !/ad-btn-sm ad-btn-secondary ad-pub-btn/.test(ТУРН),
    'Кнопка публикации снова `secondary` — тот же тон, что у «Сетки»,\n' +
    'которая просто открывает экран.');

правило('кнопка публикации не носит разрушительный тон',
    /* ПРИЗНАК НЕ УПИРАЕТСЯ В КАВЫЧКУ: первая версия искала `[^']*` между
       тоном и классом кнопки, а между ними стоят и кавычки, и плюсы —
       правило не падало, и прувер это показал. */
    !/ad-btn-danger[\s\S]{0,120}ad-pub-btn|ad-pub-btn[\s\S]{0,120}ad-btn-danger/.test(ТУРН),
    '`danger` оставлен разрушительному. Снятие с публикации ничего не\n' +
    'удаляет и отменяется тем же нажатием — решение Кости 22.10:\n' +
    '«один клик», без подтверждения.');

правило('«Сетка» осталась нейтральной',
    /ad-btn-sm ad-btn-secondary ad-brk-btn/.test(ТУРН),
    'Кнопка сетки сменила тон. Она НАВИГАЦИЯ, и если её покрасить, три\n' +
    'кнопки строки снова сольются — беда вернётся с другой стороны.');

/* ── 3. ПОЛОСА ФИЛЬТРОВ: ОДНО ПОНЯТИЕ — ОДНО ИМЯ (кусок 125, 22.10) ──── */
/* Найдено обходом «Финансов». Полос фильтров по админке ДВЕНАДЦАТЬ, а имён
   у липкости было ТРИ: шесть носили `ad-filter-sticky`, ДВЕ — голое
   `sticky`, под которое правила в admin.css нет вовсе, и четыре стоят без
   модификатора. Замерено на боевой: у носивших мёртвое имя
   `position: static`, фон прозрачный, границы нет, отступы 0 — автор
   написал слово и не получил ничего. ИМЯ БЕЗ ПРАВИЛА ВЫГЛЯДИТ КАК РЕШЕНИЕ. */
const РАЗДЕЛЫ_ФИЛЬТРОВ = ['coaches', 'courts', 'finances', 'loyalty', 'news',
    'players', 'settings', 'tournaments', 'users', 'vouchers']
    .map(и => ['js/admin/sections/' + и + '.js', чит('js/admin/sections/' + и + '.js')]);

const полосы = [];
РАЗДЕЛЫ_ФИЛЬТРОВ.forEach(([имя, текст]) => {
    (текст.match(/class="[^"]*ad-filter-row[^"]*"/g) || []).forEach(т => полосы.push([имя, т]));
});

правило('полосы фильтров найдены, и их 12',
    полосы.length === 12,
    'Полос фильтров в разделах админки: ' + полосы.length + ', а замерено 12.\n' +
    'ПРОВЕРКА, КОТОРАЯ ИЩЕТ В ПУСТОМ, ЗЕЛЕНЕЕТ ВСЕГДА.');

const мёртвоеИмя = полосы.filter(([, т]) => /\bsticky"/.test(т) && !/ad-filter-sticky/.test(т));
правило('ни одна полоса фильтров не носит имени, под которым нет правила',
    мёртвоеИмя.length === 0,
    'Полос с голым `sticky`: ' + мёртвоеИмя.length + '\n' +
    мёртвоеИмя.map(([и, т]) => '  ' + и + ': ' + т).join('\n') + '\n' +
    'Правила `.sticky` в admin.css нет. Класс стоит, липкости не будет, и\n' +
    'отличить это от решения «здесь не липнет» нельзя ничем, кроме замера.');

правило('правила `.sticky` в admin.css по-прежнему нет',
    !/^\.sticky[\s,{]/m.test(AD),
    'В admin.css завелось правило `.sticky`. Тогда прежние две полосы начали бы\n' +
    'липнуть ВТОРЫМ именем — и понятие снова получило бы два определения.\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: липкость полосы зовётся `ad-filter-sticky`.');

const липких = полосы.filter(([, т]) => /ad-filter-sticky/.test(т)).length;
правило('липнут ВСЕ двенадцать полос фильтров',
    липких === 12,
    'Липких полос: ' + липких + ' из 12. Слово Кости 22.10: липнуть должны все.\n' +
    'Шесть липли и прежде, две носили мёртвое имя `sticky`, четыре стояли без\n' +
    'модификатора — переведены все. ПОЛОСА, КОТОРАЯ ВЕДЁТ СЕБЯ ИНАЧЕ ОСТАЛЬНЫХ,\n' +
    'заставляет гадать, уедут фильтры или нет.\n' +
    'Проверено, что липкости есть к чему прилипнуть: у полос «Игроков» и\n' +
    '«Пользователей» прокручиваемого предка нет — замерено на боевой 22.10;\n' +
    'ЛИПКОСТЬ ПРИЛИПАЕТ К БЛИЖАЙШЕМУ ПРОКРУЧИВАЕМОМУ ПРЕДКУ, А НЕ К ЭКРАНУ.');

/* ── вывод ───────────────────────────────────────────────────────────── */
console.log('');
if (ошибки.length) {
    console.log('  НЕ ТАК  липкая шапка и роли кнопок — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(([и, п]) => console.log('          ✗ ' + и + '\n            ' + п.replace(/\n/g, '\n            ') + '\n'));
    process.exit(1);
}
console.log('  ок      липкая шапка и роли кнопок: 12 правил');
console.log('          шапка очков липнет к --header-h, переполнения у карточки нет');
console.log('          публикация: primary / warning, «Сетка» осталась secondary');
console.log('          полос фильтров 12, липких 12, мёртвых имён 0');
console.log('');
