const acorn = require('acorn');
function дерево(т) { return acorn.parse(т, { ecmaVersion: 2020, locations: true }); }
function поДереву(у, дело) {
    if (!у || typeof у.type !== 'string') return;
    дело(у);
    for (const к of Object.keys(у)) {
        if (к === 'type' || к === 'start' || к === 'end' || к === 'loc') continue;
        const v = у[к];
        if (Array.isArray(v)) v.forEach(x => x && typeof x.type === 'string' && поДереву(x, дело));
        else if (v && typeof v.type === 'string') поДереву(v, дело);
    }
}

