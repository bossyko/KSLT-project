#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «СТРОКИ КАТЕГОРИЙ ИГРОКА В КАБИНЕТЕ — ОДНО ОПРЕДЕЛЕНИЕ» (30.10).
 *
 * ЗАМЕР ДО ПРАВКИ, ЧТЕНИЕМ. Один и тот же запрос с одним и тем же
 * разбором стоял в `js/dashboard.js` ДВАЖДЫ: карточка в «Моём профиле»
 * (:1448) и боковая колонка (:1527). Оба читали `player_categories` по
 * игроку, оба выбрасывали `friendly`, оба тянули справочник категорий и
 * оба считали место зовом `KSLT_RULES.местоВКатегории`. Разнилась только
 * РАЗМЕТКА.
 *
 * И НА ШВЕ УЖЕ РАЗОШЛОСЬ. Справочник оба брали как `select('id, name')` —
 * только РУССКОЕ имя: в английском и кыргызском кабинете категория
 * показывалась по-русски. На публичной странице игрока тот же справочник
 * берётся с `name_en, name_kg` и выбирается по языку. Один человек, два
 * экрана, два разных имени одной категории. ДУБЛИКАТ ЛОВИТ ПРОВЕРКА, А
 * НЕ ПАМЯТЬ — поэтому сторож, а не «я запомнил».
 *
 * ЧЕГО ЗДЕСЬ НЕТ НАМЕРЕННО. Третье писание живёт в `js/player.js`,
 * четвёртое — в доме `js/kslt-kategorii.js`. Свести все четыре — свой
 * кусок: у них РАЗНЫЕ правила (страница игрока прячет закрытые и
 * сортирует по ступени лестницы, кабинет показывает их приглушёнными и
 * сортирует по очкам), и это решение про ВИД, а не про код. Правило,
 * которое потребовало бы их равенства сегодня, было бы ложью.
 *
 *   node tools/check-stroki-kategoriy.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = т => безКомментариев(т);

const КАБИНЕТ = 'js/dashboard.js';
const СТРАНИЦА = 'js/player.js';
const каб = безКом(чит(КАБИНЕТ));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

const сколько = (т, п) => (т.match(п) || []).length;

/* ══ 1. ОДИН ЗАПРОС, ОДИН РАЗБОР ════════════════════════════════════════ */

правило('кабинет читает категории игрока ровно одним местом',
    сколько(каб, /from\('player_categories'\)/g) === 1,
    'Мест: ' + сколько(каб, /from\('player_categories'\)/g) + ', а должно быть одно.\n' +
    'Их было два, и на шве уже разошлось имя категории. Второй запрос —\n' +
    'это второе определение понятия, а не экономия строк.');

правило('это место называется строкиКатегорий и его зовут оба экрана',
    /async function строкиКатегорий\(client, игрок\)/.test(каб) &&
    сколько(каб, /await строкиКатегорий\(client,/g) === 2,
    'Зовов: ' + сколько(каб, /await строкиКатегорий\(client,/g) + ', а экранов два —\n' +
    'карточка в «Моём профиле» и боковая колонка. Если зовёт один, второй\n' +
    'снова собрал себе свои строки.');

правило('`friendly` выбрасывается в кабинете одним местом',
    сколько(каб, /!== 'friendly'/g) === 1,
    'Мест: ' + сколько(каб, /!== 'friendly'/g) + '.\n' +
    'Правило «friendly в рейтинге не участвует» — одно на продукт.\n' +
    'Повторённое, оно разойдётся ровно там, где его забудут повторить.');

/* ══ 2. ИМЯ КАТЕГОРИИ — ПО ЯЗЫКУ СТРАНИЦЫ ═══════════════════════════════ */

правило('справочник категорий кабинет читает со всеми тремя именами',
    /from\('categories'\)\.select\('id, name, name_en, name_kg'\)/.test(каб),
    'Было `select(\'id, name\')` — то есть русское имя на всех трёх\n' +
    'языках. Это не «некрасиво»: человек в английском кабинете видел\n' +
    'категорию по-русски, а на публичной странице — по-английски.');

правило('имя категории выбирается по языку, а не берётся первым попавшимся',
    /имена\[c\.id\] = KSLT_YAZYK\.выбрать\(c\.name_en \|\| c\.name,/.test(каб),
    'Три имени в запросе и выбор мимо языка — это те же три имени, из\n' +
    'которых показывается не то. Выбор делает дом языка.');

правило('страница игрока читает справочник так же — по трём именам',
    /select\('id, name, name_en, name_kg, sort_order'\)/.test(безКом(чит(СТРАНИЦА))),
    'Писание здесь СВОЁ (ступень лестницы, закрытые скрыты) — и это\n' +
    'названо в трекере находкой. Но имена обязаны быть на трёх языках в\n' +
    'обоих: это не разные правила, это одно.');

/* ══ 3. МЕСТО СЧИТАЕТ ОДИН ДОМ ══════════════════════════════════════════ */

правило('место в категории кабинет не считает сам',
    /KSLT_RULES\.местоВКатегории\(client, р\.category_id,/.test(каб) &&
    сколько(каб, /KSLT_RULES\.местоВКатегории\(/g) === 1,
    'Зовов дома: ' + сколько(каб, /KSLT_RULES\.местоВКатегории\(/g) + '.\n' +
    'Место — отношение между игроками, и считать его двумя способами\n' +
    'значит показать человеку «#4» на одном экране и «#6» на другом.');

/* ══ 4. ЛИШНИЙ ЗАПРОС ПОЛА СНЯТ ═════════════════════════════════════════ */

правило('пол игрока боковая колонка берёт тем же запросом, а не отдельным',
    !/from\('players'\)\.select\('gender'\)/.test(каб) &&
    /select\('points, category_id, ntrp_singles, ntrp_doubles, gender'\)/.test(каб),
    'Отдельный запрос за одним полем шёл рядом с тем, который и так\n' +
    'читает ту же запись. Это не скорость, это второе место, где\n' +
    'решают, откуда берётся пол.');

/* ───────── вывод ───────── */
console.log('');
if (!ошибки.length) {
    console.log('  ок      строки категорий в кабинете: все ' +
        (fs.readFileSync(__filename, 'utf8').match(/правило\('/g) || []).length +
        ' правил держатся');
    console.log('          запрос категорий в кабинете: 1 место, зовут его 2 экрана');
    console.log('          имя категории: по языку страницы, в обоих продуктах сайта');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  строки категорий в кабинете — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
