#!/usr/bin/env node
/**
 * ВИД ГРАФИКА — ОДИН ДОМ (12.11.2026).
 *
 * ОТКУДА. Костя про аналитику: «не понятно и не читабельно, всё
 * сливается». Замер по коду: графики рисуются в ЧЕТЫРЁХ местах, и
 * каждое задавало свои краски, сетку и толщину полос.
 * Что сливалось: barThickness 40 без зазора, две краски в одной полосе
 * стопкой, сетка 6% белого и НИ ОДНОГО ЧИСЛА на полосах — значение
 * читалось только мышью.
 *
 * ЧТО СТОРОЖИТСЯ:
 *   1. дом объявлен и отдаёт все пять частей вида;
 *   2. дом подключён ДО того, кто его зовёт;
 *   3. аналитика берёт вид у дома, а не задаёт краски на месте;
 *   4. числа на полосах рисуются (плагин подписей передан графику);
 *   5. полосы стоят РЯДОМ, а не стопкой: в стопке подпись первого
 *      набора ложится на сегмент второго — поймано снимком 12.11.
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, ' ');

const ошибки = [];
const правило = (имя, условие, почему) => { if (!условие) ошибки.push(имя + ' — ' + почему); };

const дом = безКом(чит('js/kslt-grafik-vid.js'));
const анл = безКом(чит('js/admin/sections/analytics.js'));
const стр = чит('pages/admin.html');
const токены = чит('css/tokens.css');

правило('дом вида объявлен и полон',
    /KSLT_GRAFIK_VID/.test(дом) &&
    ['подписиЗначений', 'ось', 'легенда', 'подсказка', 'набор']
        .every(и => new RegExp('API\\.' + и + '\\s*=').test(дом)),
    'в доме нет одной из частей вида — значит её снова задают на местах');

правило('толщина полосы — имя, а не число на месте',
    /API\.ПОЛОСА\s*=\s*\d+/.test(дом) && /barThickness:\s*о\.тонкая/.test(дом),
    'толщина вернулась числом в наборы — полосы опять встанут вплотную');

const iДом = стр.indexOf('kslt-grafik-vid.js');
const iАнл = стр.indexOf('sections/analytics.js');
правило('дом подключён ДО аналитики',
    iДом !== -1 && iАнл !== -1 && iДом < iАнл,
    'дом грузится позже зовущего — график останется без вида (admin.html)');

правило('аналитика берёт вид у дома',
    /window\.KSLT_GRAFIK_VID/.test(анл) &&
    (анл.match(/В\.набор\(/g) || []).length >= 4 &&
    (анл.match(/В\.ось\(/g) || []).length >= 4,
    'аналитика снова собирает вид сама');

правило('краски графиков не задаются в аналитике на месте',
    !/KSLT_KRASKA/.test(анл),
    'в аналитике опять свои краски — это второе определение вида');

правило('числа на полосах рисуются',
    (анл.match(/plugins:\s*\[В\.подписиЗначений\]/g) || []).length >= 2,
    'плагин подписей не передан графику: значение снова читается только мышью,\n' +
    'а на снимке и на планшете мыши нет');

/* ═══ АКЦЕНТ КЛУБА НЕ КРАСИТ ПОЛОВИНУ ГРАФИКА (12.11) ═══
   Слово Кости: «поменяй лаймовый на пастельный, не так бросалось».
   Посчитано: контраст лайма к подложке карточки 14.19 против 7.48 у
   песка — акцент создан выделять ОДНО, а в графике красил половину
   площади. Ряды берут --chart-ryad-1/2 (песок и розовый, оба тёплые,
   ΔE 54.8). Роли (--warning и прочие) в график не берутся: график
   заговорил бы языком предупреждения. */
/* ПРИЗНАК СМОТРИТ В ТЕЛО НАБОРА, А НЕ ВО ВЕСЬ ФАЙЛ: акцент законно
   остаётся заголовком подсказки, и первая редакция правила упала на
   нём — показала беду там, где её нет. */
const телоНабора = (дом.match(/API\.набор\s*=\s*function[\s\S]*?\n    \};/) || [''])[0];
правило('ряды графика красятся своими именами, а не акцентом клуба',
    /--chart-ryad-1/.test(телоНабора) && /--chart-ryad-2/.test(телоНабора) &&
    !/--accent/.test(телоНабора),
    'в краску полосы вернулся акцент клуба — лайм снова будет бить в глаза');

/* ПРАВИЛО, НАПИСАННОЕ ЧЕРЕЗ ЧИСЛО, СТАРЕЕТ ВМЕСТЕ С ЧИСЛОМ: первая
   редакция требовала буквально cat-2 и cat-3 и упала бы при любой
   смене краски. Сторожится ОТНОШЕНИЕ: оба имени есть, ведут к разным
   краскам палитры, не к роли, и пара различима глазом. */
const р1 = (токены.match(/--chart-ryad-1:\s*var\(\s*(--[\w-]+)\s*\)/) || [])[1];
const р2 = (токены.match(/--chart-ryad-2:\s*var\(\s*(--[\w-]+)\s*\)/) || [])[1];
правило('имена рядов объявлены в справочнике',
    !!р1 && !!р2 && р1 !== р2 && /^--cat-\d+$/.test(р1) && /^--cat-\d+$/.test(р2),
    'имена рядов пропали из tokens.css, сошлись в одну краску или стали ролью');

/* ═══ ВЫСОТА ГРАФИКА — ОТ ЧИСЛА СТРОК (12.11, вторая жалоба) ═══
   Слово Кости: «вот тут наложение идёт». Замер: обёртка 180, область
   112, строк 5 — шаг 22.3 на пару полос в 32, полосы налезали на 9.7.
   В большом графике шаг 31.9 на 32 — ЗАПАС В ОДНУ ТОЧКУ НЕ ЗАПАС.
   Сторожится отношение: строка вмещает пару полос с воздухом, и
   высоту ставит дом, а не зашитое число в css. */
правило('строка вмещает пару полос с воздухом',
    /API\.СТРОКА\s*=\s*(\d+)/.test(дом) && /API\.ПОЛОСА_МАЛАЯ\s*=\s*(\d+)/.test(дом) &&
    Number(дом.match(/API\.СТРОКА\s*=\s*(\d+)/)[1]) >
        2 * Number(дом.match(/API\.ПОЛОСА_МАЛАЯ\s*=\s*(\d+)/)[1]),
    'строка графика уже двух полос — полосы снова налезут друг на друга');

правило('высоту обёртки ставит дом, а не зашитое число',
    /API\.высота\s*=\s*function/.test(дом) &&
    /строк\s*\*\s*API\.СТРОКА\s*\+\s*API\.СЛУЖЕБНОЕ/.test(дом) &&
    (анл.match(/В\.высота\(/g) || []).length >= 2,
    'высота графика снова живёт зашитым числом в css: при пятой строке полосы налезут');

правило('полосы стоят рядом, а не стопкой',
    !/стопкой:\s*true/.test(анл),
    'вернулась стопка: подпись первого набора ляжет на сегмент второго');

/* ═══ РЯДЫ РАЗЛИЧИМЫ — СЧЁТ БЕРЁТСЯ У ЕДИНСТВЕННОГО ДОМА ═══
   КОНТРАСТ ОДИН РАЗЛИЧИМОСТЬ НЕ ДОКАЗЫВАЕТ: пара серых имела контраст
   11.19 и 5.15 — оба видны, а друг от друга отличались на ΔE 25.5, и
   Костя сказал «оттенки не очень видны». Планка 3 — WCAG для
   НЕтекстового: полоса графика не буква.
   Формула не копируется сюда: сторож «счёт контраста один» поймал
   44-ю копию, когда она тут была. Дом — tools/kontrast.mjs. */
function доЦвета(имя) {
    let т = имя, шагов = 0;
    while (/^--/.test(т) && шагов++ < 6) {
        const м = токены.match(new RegExp('\\' + '-\\-' + т.slice(2) + ':\\s*([^;]+);'));
        if (!м) return null;
        т = м[1].trim();
        const v = т.match(/^var\(\s*(--[\w-]+)\s*\)$/);
        т = v ? v[1] : т;
    }
    return /^#[0-9a-fA-F]{6}$/.test(т) ? т : null;
}
const вЧисла = hex => [1, 3, 5].map(i => parseInt(hex.substr(i, 2), 16));
/* ПОДЛОЖКА КАРТОЧКИ ЗАМЕРЕНА В БРАУЗЕРЕ 12.11, а не взята из головы. */
const ПОДЛОЖКА = '#1E1E1E';
const ПЛАНКА_ВИДИМОСТИ = 3;
const ПЛАНКА_РАЗЛИЧИЯ = 30;

import('./kontrast.mjs').then(К => {
    const ц1 = р1 && доЦвета(р1), ц2 = р2 && доЦвета(р2);
    const к = h => К.контраст(вЧисла(h).concat(1), вЧисла(ПОДЛОЖКА).concat(1));
    const раз = ц1 && ц2 ? К.дельтаE(вЧисла(ц1), вЧисла(ц2)) : 0;
    правило('ряды различимы между собой и видны на подложке',
        !!ц1 && !!ц2 && раз >= ПЛАНКА_РАЗЛИЧИЯ &&
        к(ц1) >= ПЛАНКА_ВИДИМОСТИ && к(ц2) >= ПЛАНКА_ВИДИМОСТИ,
        'ряды сливаются (ΔE < ' + ПЛАНКА_РАЗЛИЧИЯ + ') или тонут на подложке (контраст < ' +
        ПЛАНКА_ВИДИМОСТИ + '): ряд1 ' + ц1 + ' контраст ' + (ц1 ? к(ц1).toFixed(2) : '—') +
        ', ряд2 ' + ц2 + ' контраст ' + (ц2 ? к(ц2).toFixed(2) : '—') +
        ', ΔE между ними ' + раз.toFixed(1));

    if (ошибки.length) {
        console.error('ВИД ГРАФИКА — НАРУШЕНО:');
        for (const о of ошибки) console.error('  · ' + о);
        process.exit(1);
    }
    console.log('вид графика: 10 правил держатся');
});
