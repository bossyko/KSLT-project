#!/usr/bin/env node
/**
 * ВИД ГРАФИКА — ОДИН ДОМ (12.11.2026).
 *
 * ОТКУДА. Костя про аналитику: «не понятно и не читабельно, всё
 * сливается». Замер по коду: графики рисуются в ЧЕТЫРЁХ местах, и
 * каждое задавало свои краски, сетку и толщину полос.
 * Что сливалось: barThickness 40 без зазора, две краски в одной полосе
 * стопкой, сетка 6% белого и НИ ОДНОГО ЧИСЛА на полосах — значение
 * читалось только мышью.
 *
 * ЧТО СТОРОЖИТСЯ:
 *   1. дом объявлен и отдаёт все пять частей вида;
 *   2. дом подключён ДО того, кто его зовёт;
 *   3. аналитика берёт вид у дома, а не задаёт краски на месте;
 *   4. числа на полосах рисуются (плагин подписей передан графику);
 *   5. полосы стоят РЯДОМ, а не стопкой: в стопке подпись первого
 *      набора ложится на сегмент второго — поймано снимком 12.11.
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, ' ');

const ошибки = [];
const правило = (имя, условие, почему) => { if (!условие) ошибки.push(имя + ' — ' + почему); };

const дом = безКом(чит('js/kslt-grafik-vid.js'));
const анл = безКом(чит('js/admin/sections/analytics.js'));
const стр = чит('pages/admin.html');

правило('дом вида объявлен и полон',
    /KSLT_GRAFIK_VID/.test(дом) &&
    ['подписиЗначений', 'ось', 'легенда', 'подсказка', 'набор']
        .every(и => new RegExp('API\\.' + и + '\\s*=').test(дом)),
    'в доме нет одной из частей вида — значит её снова задают на местах');

правило('толщина полосы — имя, а не число на месте',
    /API\.ПОЛОСА\s*=\s*\d+/.test(дом) && /barThickness:\s*о\.тонкая/.test(дом),
    'толщина вернулась числом в наборы — полосы опять встанут вплотную');

const iДом = стр.indexOf('kslt-grafik-vid.js');
const iАнл = стр.indexOf('sections/analytics.js');
правило('дом подключён ДО аналитики',
    iДом !== -1 && iАнл !== -1 && iДом < iАнл,
    'дом грузится позже зовущего — график останется без вида (admin.html)');

правило('аналитика берёт вид у дома',
    /window\.KSLT_GRAFIK_VID/.test(анл) &&
    (анл.match(/В\.набор\(/g) || []).length >= 4 &&
    (анл.match(/В\.ось\(/g) || []).length >= 4,
    'аналитика снова собирает вид сама');

правило('краски графиков не задаются в аналитике на месте',
    !/KSLT_KRASKA/.test(анл),
    'в аналитике опять свои краски — это второе определение вида');

правило('числа на полосах рисуются',
    (анл.match(/plugins:\s*\[В\.подписиЗначений\]/g) || []).length >= 2,
    'плагин подписей не передан графику: значение снова читается только мышью,\n' +
    'а на снимке и на планшете мыши нет');

правило('полосы стоят рядом, а не стопкой',
    !/стопкой:\s*true/.test(анл),
    'вернулась стопка: подпись первого набора ляжет на сегмент второго');

if (ошибки.length) {
    console.error('ВИД ГРАФИКА — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
console.log('вид графика: 7 правил держатся');
