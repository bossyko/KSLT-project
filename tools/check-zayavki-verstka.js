const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СЕТКА   = чит('js/admin/sections/bracket.js');
const СЕТч    = безКом(СЕТКА);
const АДМИН   = чит('css/admin.css');
const АДч     = безКом(АДМИН);
const УТИЛ    = безКом(чит('js/admin/core/utils.js'));
const СТРАНИЦА = чит('pages/admin.html');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

function блок(текст, селектор) {
    const i = текст.indexOf(селектор + ' {');
    if (i === -1) return '';
    let гл = 0, j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}

/* Строка заявки целиком — от сборщика до возврата разметки. Якорь на
   содержимом функции, а не на номерах строк. */
const СТРОКА = (() => {
    const i = СЕТч.indexOf('function renderRegRow');
    const j = СЕТч.indexOf('function renderSchedulePanel');
    return i === -1 ? '' : СЕТч.slice(i, j === -1 ? СЕТч.length : j);
})();

/* ─────────── ЗНАЧКИ ─────────── */

правило('значки строки заявки — классом, а не инлайном',
    /class="ad-reg-mark ad-reg-mark-dolg"/.test(СТРОКА) &&
    /class="ad-reg-mark ad-reg-mark-ext"/.test(СТРОКА) &&
    /class="ad-reg-mark ad-reg-mark-seed"/.test(СТРОКА),
    'значок долга, EXT или посева вернулся в инлайн-стиль: это кегль мимо ' +
    'шкалы и зашитая краска, ровно то, против чего заводился Badge 27:53');

правило('в строке заявки нет кеглей 0.65rem',
    !/font-size:0\.65rem/.test(СТРОКА),
    'в строку вернулся кегль 10.4 — ниже самой мелкой ступени 11');

правило('значок стоит на ступени чипа и шкале кеглей',
    /min-height:\s*var\(--chip-h\)/.test(блок(АДч, '.ad-reg-mark')) &&
    /font-size:\s*var\(--fs-2xs\)/.test(блок(АДч, '.ad-reg-mark')),
    'значку задали высоту или кегль числом: 24 и 11 — это компонент, а не вкус');

/* ─────────── ПОДПИСЬ ПОД ИМЕНЕМ ─────────── */

правило('подпись под именем — одно определение',
    /\.ad-table-sub \{/.test(АДч) &&
    !/\.ad-table-user-email/.test(АДч),
    'вернулся `.ad-table-user-email` либо завелась вторая подпись: одно ' +
    'определение на одно понятие');

правило('подпись не на --text-dim',
    !/--text-dim/.test(блок(АДч, '.ad-table-sub')),
    'подписи вернули --text-dim: на фоне карточки это 3.21, мимо WCAG AA');

правило('подпись рисуется всегда, а показывается медиа-правилом',
    /class="ad-table-sub ad-reg-sub-inline"/.test(СТРОКА) &&
    /\.ad-reg-sub-inline \{\s*display:\s*none/.test(АДч),
    'подпись стали рисовать по условию в js: тогда разметка зависит от ' +
    'ширины, а ширину знает только css');

правило('на узком виде прячутся ровно категория и дата',
    /@media \(max-width: 992px\) \{[\s\S]{0,200}\.ad-col-cat,\s*\n\s*\.ad-col-dt \{ display: none; \}/.test(АДч) &&
    /class="ad-col-cat ad-table-sub"/.test(СТРОКА) &&
    /class="ad-col-dt ad-table-sub"/.test(СТРОКА),
    'медиа-правило или классы колонок разошлись: прячется не то, что помечено');

правило('граница одна и своя — 992',
    !/@media[^{]*max-width:\s*(?!992)(?!768)(?!640)\d+px[^{]*\{[^}]*ad-col-(cat|dt)/.test(АДч),
    'у колонок заявок завелась своя точка останова: у проекта их две — 640 и 992');

/* ─────────── ЧИСЛА СО ШКАЛЫ ─────────── */

правило('номер строки без инлайн-отступа',
    !/padding:4px 6px/.test(СТРОКА) && /class="ad-reg-num"/.test(СТРОКА),
    'номеру вернули инлайн padding 4px 6px — ни 4, ни 6 на шкале отступов нет');

правило('шапка таблиц админки читается',
    !/--text-dim/.test(блок(АДч, '.ad-table th')),
    'шапке таблиц вернули --text-dim: 3.21 при кегле 11, мимо WCAG AA');

/* ─────────── ЦЕЛЬ НАЖАТИЯ ─────────── */

правило('галочка и «Отмена» в списке слоя цели',
    /\.ad-reg-check-wrap,\s*\n\.ad-confirm-cancel \{\s*\n\s*position: relative;/.test(АДч) &&
    /\.ad-reg-check-wrap::after,\s*\n\.ad-confirm-cancel::after \{/.test(АДч),
    'галочка или «Отмена» выпали из слоя цели 44: у input своих ' +
    'псевдоэлементов нет, слой живёт на обёртке');

/* СЧИТАЕМ НЕ «ЕСТЬ ЛИ ОДНА», А «НЕТ ЛИ ГОЛОЙ». У сборщика две ветки,
   одиночная и парная; правило на присутствие оставалось зелёным, когда
   обёртку снимали с одной из них. Поймал прувер. */
правило('ни одной галочки строки без обёртки',
    (СТРОКА.match(/<input type="checkbox" class="ad-reg-check"/g) || []).length ===
    (СТРОКА.match(/ad-reg-check-wrap"><input type="checkbox" class="ad-reg-check"/g) || []).length,
    'галочка строки осталась без обёртки — слою цели не на чем стоять. ' +
    'Веток у сборщика две: одиночная и парная');

/* ─────────── ОКНО ПОДТВЕРЖДЕНИЯ ─────────── */

правило('окно подтверждения называет себя диктору',
    /role="dialog"/.test(УТИЛ) && /aria-modal="true"/.test(УТИЛ) &&
    /aria-labelledby="/.test(УТИЛ),
    'из окна подтверждения убрали role/aria-modal/aria-labelledby — ' +
    'диктор его не объявит');

правило('окно берёт фокус на себя, а не на кнопку',
    /\.ad-confirm-modal'\);\s*\n\s*if \(окно && окно\.focus\) окно\.focus\(\);/.test(УТИЛ),
    'фокус перестал уходить в окно либо его поставили на кнопку: первой ' +
    'стоит «Отмена», а за ней бывают необратимые действия');

/* `/счётчикОкон/` совпадало и с `счётчикОконБыло` — подстрока ловит
   переименование как успех. Держим объявление И применение. */
правило('подпись окна уникальна',
    /var счётчикОкон = 0;/.test(УТИЛ) && /\+\+счётчикОкон\)/.test(УТИЛ),
    'aria-labelledby снова указывает на постоянный id: второе окно сошлётся ' +
    'на заголовок первого');

/* ─────────── ВЕРСИИ ─────────── */

правило('версии подняты — иначе браузер отдаст старое из кеша',
    /admin\.css\?v=(19[7-9]|[2-9]\d\d)/.test(СТРАНИЦА) &&
    /bracket\.js\?v=(25[6-9]|2[6-9]\d|[3-9]\d\d)/.test(СТРАНИЦА) &&
    /core\/utils\.js\?v=(3[1-9]|[4-9]\d)/.test(СТРАНИЦА),
    'версия admin.css, bracket.js или utils.js не поднята после правки');

