function блок(текст, селектор) {
    const i = текст.indexOf(селектор + ' {');
    if (i === -1) return '';
    let гл = 0, j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}

/* Строка заявки целиком — от сборщика до возврата разметки. Якорь на
   содержимом функции, а не на номерах строк. */
const СТРОКА = (() => {
    const i = СЕТч.indexOf('function renderRegRow');
    const j = СЕТч.indexOf('function renderSchedulePanel');
    const тело = i === -1 ? '' : СЕТч.slice(i, j === -1 ? СЕТч.length : j);
    /* ЯЧЕЙКУ РИСУЕТ И ПОМОЩНИК, А НЕ ТОЛЬКО САМ СБОРЩИК.
       `ячейкаNtrpПары` объявлена выше по файлу и рисует колонку парного
       рейтинга — то есть часть строки. Прувер показал, что окно правила
       её не видит: откат вернул инлайн-кегль ИМЕННО туда, и правило
       промолчало. ОКНО ПРАВИЛА НАКРЫВАЕТ ВСЁ, ЧТО РИСУЕТ ЭТУ СТРОКУ. */
    const п = СЕТч.indexOf('function ячейкаNtrpПары');
    const к = п === -1 ? '' : СЕТч.slice(п, СЕТч.indexOf('\n    }', п) + 6);
    return тело + '\n' + к;
})();

