#!/usr/bin/env node
/**
 * ВАУЧЕР РИСУЕТСЯ В ТЕЛЕФОНЕ, А НЕ НА ЧУЖОМ СЕРВЕРЕ (кусок 03.11).
 *
 * ЗАМЕР 03.11: окно ваучера показывало картинку с чужой машины —
 * `api.qrserver.com/v1/create-qr-code/?data=<код>`. КОД ВАУЧЕРА УХОДИЛ В
 * АДРЕСЕ ССЫЛКИ, то есть в журналы чужого сервиса. Упал бы сервис —
 * исчезли бы ВСЕ ваучеры разом, запасного пути не было ни одного. Для
 * анкеты Data safety в Play это, сверх того, передача данных третьей
 * стороне, которую пришлось бы объявлять.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ, А НЕ НОМЕР: «ваучер рисуется своим домом, и
 * наружу при этом не уходит ничего» — а не «в строке 1238 стоит div».
 *
 * ПОЧЕМУ ПОРЯДОК ПОДКЛЮЧЕНИЯ — ОТДЕЛЬНОЕ ПРАВИЛО: дом кладёт себя в
 * `window.qrcode`. Подключи его ПОСЛЕ потребителя — и в миг зова его ещё
 * нет; окно уйдёт в запасной путь и покажет код словами вместо картинки.
 * Беда при этом МОЛЧАЛИВАЯ: ни ошибки, ни пустого места, просто не то.
 *
 * ЗАПАСНОЙ ПУТЬ СТОРОЖИТСЯ НАРАВНЕ С ГЛАВНЫМ. Пустое белое окно вместо
 * ваучера человек читает как поломку и зовёт в клуб; код словами он
 * прочитает вслух, и скидку всё равно получит.
 *
 *   node tools/check-qr-svoy.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const П = (...ч) => path.join(КОРЕНЬ, ...ч);
const чит = ф => fs.readFileSync(П(ф), 'utf8');
const есть = ф => fs.existsSync(П(ф));

const ПРИЛОЖЕНИЕ = 'mobile/www';
const ДОМ = ПРИЛОЖЕНИЕ + '/js/vendor/qrcode.js';
const ОКНО = ПРИЛОЖЕНИЕ + '/js/screens/profile.js';
const СТРАНИЦА = ПРИЛОЖЕНИЕ + '/index.html';

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ── 1. чужих рисовалок QR нет ни в одном живом коде приложения ──────── */
const ЧУЖИЕ = /qrserver\.com|chart\.googleapis\.com\/chart|quickchart\.io\/qr|goqr\.me|api\.qrcode/i;
const найдено = [];
(function обойти(д) {
    const полный = П(д);
    if (!fs.existsSync(полный)) return;
    fs.readdirSync(полный, { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) { if (э.name !== 'vendor') обойти(п); return; }
        if (!/\.(js|html)$/.test(э.name)) return;
        const живой = э.name.endsWith('.js') ? безКомментариев(чит(п)) : чит(п);
        if (ЧУЖИЕ.test(живой)) найдено.push(п);
    });
})(ПРИЛОЖЕНИЕ);

правило('ваучер не рисуется на чужом сервере',
    найдено.length === 0,
    'живой код зовёт чужую рисовалку QR: ' + найдено.join(', '));

/* ── 2. свой дом на месте и это настоящий кодировщик ─────────────────── */
правило('дом QR лежит в приложении', есть(ДОМ), ДОМ + ' не найден');

const домТекст = есть(ДОМ) ? чит(ДОМ) : '';
правило('дом QR — настоящий кодировщик, а не заглушка',
    /createSvgTag/.test(домТекст) && /addData/.test(домТекст),
    'в ' + ДОМ + ' нет createSvgTag или addData');

/* ── 3. дом подключён, и подключён РАНЬШЕ своего потребителя ─────────── */
const стр = есть(СТРАНИЦА) ? чит(СТРАНИЦА) : '';
const гдеДом = стр.indexOf('js/vendor/qrcode.js');
const гдеОкно = stрИндекс();
function stрИндекс() { return стр.indexOf('js/screens/profile.js'); }

правило('дом QR подключён на странице приложения',
    гдеДом !== -1,
    'в ' + СТРАНИЦА + ' нет подключения js/vendor/qrcode.js');

правило('у подключения дома QR есть версия',
    /js\/vendor\/qrcode\.js\?v=\d+/.test(стр),
    'подключение js/vendor/qrcode.js идёт без ?v= — в кеше останется старый');

правило('дом QR подключён раньше окна ваучера',
    гдеДом !== -1 && гдеОкно !== -1 && гдеДом < гдеОкно,
    'qrcode.js подключён после screens/profile.js — в миг зова дома ещё нет');

/* ── 4. окно ваучера зовёт свою отрисовку ────────────────────────────── */
const окно = есть(ОКНО) ? безКомментариев(чит(ОКНО)) : '';

правило('отрисовка QR определена в окне ваучера',
    /function\s+рисоватьQR\s*\(/.test(окно),
    'в ' + ОКНО + ' нет самой функции рисоватьQR');

/* ── 5. отрисовка строит код из кода ваучера, а не из адреса ─────────── */
const телоОтрисовки = (окно.match(/function\s+рисоватьQR\s*\([\s\S]*?\n  \}/) || [''])[0];

/* ЗОВ ИЩЕТСЯ ВНЕ САМОГО ДОМА, И ЭТО НЕ ПРИДИРКА: прувер показал, что
   правило `/рисоватьQR\(/` по всему файлу ловит ОБЪЯВЛЕНИЕ функции и
   молчит, когда зов убран, а объявление осталось. ПРАВИЛО, КОТОРОЕ
   ЛОВИТ И ЗОВ, И ОБЪЯВЛЕНИЕ, НЕ ОТЛИЧАЕТ ОДНОГО ОТ ДРУГОГО. */
const окноБезДома = телоОтрисовки ? окно.replace(телоОтрисовки, ' ') : окно;

правило('окно ваучера зовёт свою отрисовку',
    /рисоватьQR\s*\(/.test(окноБезДома),
    'в ' + ОКНО + ' нет зова рисоватьQR вне самой функции');

правило('QR строится из кода ваучера',
    /addData\s*\(/.test(телоОтрисовки) && /createSvgTag\s*\(/.test(телоОтрисовки),
    'рисоватьQR не зовёт addData/createSvgTag — рисует не ваучер');

правило('отрисовка QR не ходит в сеть',
    !/fetch\s*\(|XMLHttpRequest|https?:\/\//.test(телоОтрисовки),
    'в рисоватьQR есть сетевой зов — код ваучера снова уходит наружу');

/* ── 6. запасной путь: дома нет — человек видит код словами ──────────── */
правило('у отрисовки есть запасной путь без дома',
    /typeof\s+window\.qrcode\s*!==\s*'function'/.test(телоОтрисовки),
    'рисоватьQR не проверяет, загрузился ли дом');

правило('запасной путь показывает сам код',
    /textContent\s*=\s*String\(\s*код\s*\)/.test(телоОтрисовки),
    'запасной путь не показывает код словами — окно будет выглядеть пустым');

/* ── вывод ───────────────────────────────────────────────────────────── */
console.log('\n  ВАУЧЕР: СВОЙ QR\n');
if (ошибки.length === 0) {
    console.log('  ок      все 11 правил держат\n');
    process.exit(0);
}
ошибки.forEach(о => {
    console.log('  НЕ ТАК  ' + о.имя);
    console.log('          ' + о.подсказка);
});
console.log('\n  НЕ ТАК  ' + ошибки.length + ' из 11\n');
process.exit(1);
