#!/usr/bin/env node
/**
 * ВХОД — ОБЩИЕ ПРАВИЛА И ЗОВЫ В ОДНОМ ДОМЕ (шаг A3.7е, 29.10).
 *
 * ЗАЧЕМ. `js/auth.js` (2162) и `mobile/www/js/auth.js` (1089) были САМЫМ
 * КРУПНЫМ расхождением продукта и ПОСЛЕДНИМ ДОЛГОМ переписи копий.
 * Экраны входа законно разные — страница с вкладками против накладки. А
 * девять понятий были написаны дважды и трижды, и на швах разошлось:
 *
 *   · ЗАДЕРЖКА ПОВТОРА: у сайта ЛЕСТНИЦА 30·60·120·300, выведенная из
 *     серверного предела «пять запросов в час», у приложения ПЛОСКИЕ 60
 *     в двух местах. Человек, не получивший письма, жал повтор каждую
 *     минуту, упирался в предел на пятом разе и получал блокировку на
 *     четверть часа — наказание за медленное письмо;
 *   · `send-otp` БЕЗ ЯЗЫКА: сервер не знал, на каком языке писать, а при
 *     регистрации профиля ещё нет, спросить ему некого;
 *   · СЛЕПОЙ `r.json()`: упади функция — человек получал SyntaxError
 *     вместо причины, и в консоли не оставалось и того;
 *   · ЗАШИТЫЙ АДРЕС БАЗЫ в ТРЁХ местах приложения, и ключ пуст по
 *     умолчанию — пустой ключ даёт молчаливый отказ сервера.
 *
 * ЧТО ДЕРЖИТ СТОРОЖ: ни один файл продукта не зовёт серверную функцию
 * руками, ни в одном не зашит адрес базы, лестница одна, язык уходит
 * всегда, не-JSON ответ разбирается вслух.
 *
 * ЧЕГО ЭТОТ КУСОК НЕ ТРОГАЛ: вход через Apple. У сайта он есть, у
 * приложения нет — это шаг E3, и правило ниже следит, что он у сайта на
 * месте и не снесён попутной правкой.
 *
 * Запуск: node tools/check-vhod.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));

const ДОМ = 'js/kslt-vhod.js';
const ДОМ_П = 'mobile/www/js/kslt-vhod.js';
/* Файлы, из которых понятия переехали. Список — замер 29.10. */
const ЗОВУЩИЕ = [
    ['js/auth.js', 'сайта'],
    ['mobile/www/js/auth.js', 'приложения'],
    ['js/tournament-register.js', 'заявки'],
    ['js/dashboard.js', 'кабинета']
];

/* Разметки, где подключён хоть один из зовущих. Список не держится
   руками: собирается обходом. */
const РАЗМЕТКИ = (function () {
    const найдено = [];
    const пропуск = /^(node_modules|\.git|android|ios|build|assets|test-results|reports)$/;
    const обойти = (отн) => {
        const п = path.join(КОРЕНЬ, отн);
        if (!fs.existsSync(п)) return;
        for (const э of fs.readdirSync(п, { withFileTypes: true })) {
            const вложен = отн ? отн + '/' + э.name : э.name;
            if (э.isDirectory()) { if (!пропуск.test(э.name)) обойти(вложен); continue; }
            if (!э.name.endsWith('.html')) continue;
            if (/\/(build|assets)\//.test(вложен)) continue;
            const т = fs.readFileSync(path.join(КОРЕНЬ, вложен), 'utf8');
            if (/(?:^|[/"])(?:auth|dashboard|tournament-register)\.js\?/m.test(т)) найдено.push(вложен);
        }
    };
    обойти('');
    return найдено;
})();

console.log('\n  ВХОД — ОДИН ДОМ\n');

const дом = безКом(чит(ДОМ));

правило('дом объявлен и отдаёт все одиннадцать понятий',
    /KSLT_VHOD\b/.test(дом) &&
    ['почтой', 'хеш', 'отпечаток', 'запомнитьУстройство', 'задержкаПовтора',
     'сбросПовтора', 'зовФункции', 'отправитьКод', 'проверитьКод',
     'карточкаИгрока', 'завестиКарточку', 'письмоБезопасности']
        .every(и => new RegExp('API\\.' + и + '\\s*=').test(дом)),
    'Нужны все: почта, хеш, отпечаток, запомнитьУстройство,\n' +
    'письмоБезопасности, задержкаПовтора, сбросПовтора, зовФункции,\n' +
    'отправитьКод, проверитьКод, карточкаИгрока, завестиКарточку.');

правило('копии дома побайтово равны',
    чит(ДОМ) === чит(ДОМ_П),
    'Разошлись — значит вход снова живёт двумя жизнями.');

правило('дом берёт адрес базы у настроек, а не вписывает',
    /global\.SUPABASE_URL/.test(дом) && /global\.SUPABASE_ANON_KEY/.test(дом) &&
    !/[a-z0-9]{15,}\.supabase\.co/.test(дом) &&
    /* ПРИЗНАК СУЖЕН ДО САМОГО КЛЮЧА: первая редакция запрещала любое
       `|| ''` и падала на `адрес || ''`, `userAgent || ''` и
       `(д && д.status) || ''` — все три законны. Промах поймал прувер. */
    !/SUPABASE_(?:URL|ANON_KEY)\s*\|\|/.test(дом),
    'Вписанный адрес — второе место, где живёт адрес базы (шаг A3.4).\n' +
    'Пустой ключ по умолчанию ещё хуже: сервер отказывает МОЛЧА.');

правило('лестница повтора одна и ровно та, что замерена',
    /ЛЕСТНИЦА_ПОВТОРА\s*=\s*\[30,\s*60,\s*120,\s*300\]/.test(дом),
    'Ступени выведены из серверного предела пяти запросов в час\n' +
    '(`send-otp`, RATE_LIMIT_MAX). Первая 30, а не 60: за полминуты\n' +
    'письмо либо дошло, либо не дойдёт, и 60 заставляло ждать зря.');

правило('дом разбирает ответ, пришедший не в JSON',
    /resp\.text\(\)/.test(дом) && /console\.error/.test(дом) &&
    /throw new Error\(\s*имя \+ ': HTTP '/.test(дом),
    'Слепой `r.json()` на теле вроде `<html>502` бросает SyntaxError, и\n' +
    'человек видит пустоту. Дом говорит в консоль, ЧТО ответило, и\n' +
    'бросает внятное «<функция>: HTTP <код>».');

правило('язык уходит в send-otp всегда',
    /lang:\s*о\.язык\s*\|\|\s*'ru'/.test(дом),
    'При регистрации профиля ещё нет, и сервер не знает, на каком языке\n' +
    'писать. У приложения язык не уходил вовсе.');

/* ФУНКЦИИ, КОТОРЫЕ ВЕДЁТ ЭТОТ КУСОК. В `js/dashboard.js` есть и другие
   голые зовы — `respond-game-invite`, `challenge-notify`,
   `delete-account`. Это не беда сведения входа, а общий уклад продукта:
   46 мест зовут функции руками, и свести их — СВОЙ кусок, названный
   числом в трекере. Правило смотрит только своё. */
const СВОИ_ФУНКЦИИ = /functions\/v1\/(send-otp|verify-otp|telegram-auth|rate-limit|ensure-player-card|security-notify)/;

ЗОВУЩИЕ.forEach(([ф, имя]) => {
    const т = безКом(чит(ф));

    правило('у ' + имя + ' нет ни одного зова своей функции руками',
        !СВОИ_ФУНКЦИИ.test(т),
        'Заголовки собирались в ОДИННАДЦАТИ местах: `send-otp` 2,\n' +
        '`verify-otp` 6, `telegram-auth` 2, `rate-limit` 3,\n' +
        '`ensure-player-card` 5, `security-notify` 4. Теперь зов один.');

    правило('у ' + имя + ' не зашит адрес базы',
        !/[a-z0-9]{15,}\.supabase\.co/.test(т),
        'Адрес базы живёт в настройках. Строкой здесь он был ВТОРЫМ\n' +
        'определением одного понятия (шаг A3.4).');

    правило('у ' + имя + ' дом зовётся',
        !/KSLT_VHOD/.test(чит(ф)) === false,
        'Без зова работа не сделана.');
});

правило('правило почты объявлено один раз — в доме',
    (function () {
        const тел = /function\s+почтой|\/\^\[A-Za-z0-9\._%\+-\]\+@/;
        return тел.test(дом) &&
            ЗОВУЩИЕ.every(([ф]) => !/\[A-Za-z0-9\._%\+-\]\+@/.test(безКом(чит(ф))));
    })(),
    'Было два объявления, сегодня знак в знак — поправь одно, второе\n' +
    'промолчит.');

правило('простой хеш объявлен один раз — в доме',
    /h = \(\(h << 5\) - h\)/.test(дом) &&
    ЗОВУЩИЕ.every(([ф]) => !/<< 5\)\s*-\s*(?:hash|h)\)/.test(безКом(чит(ф)))),
    'Хеш устройства считался в ТРЁХ файлах, и в третьей копии\n' +
    '(`js/dashboard.js`, список устройств) в подписи стояло «считаем в\n' +
    'точности как при входе» — автор ЗНАЛ, что это копия. Разойдись она —\n' +
    '«это устройство» не совпало бы ни с одной строкой в списке, и\n' +
    'человек решил бы, что в его запись зашёл чужой.');

правило('письмо безопасности отправляется одним местом',
    /API\.письмоБезопасности\s*=/.test(дом) &&
    ЗОВУЩИЕ.every(([ф]) => !/event_type:/.test(безКом(чит(ф)))),
    'Зов стоял в ЧЕТЫРЁХ местах — новое устройство у сайта и у\n' +
    'приложения, смена телефона и смена пароля в кабинете, — и каждое\n' +
    'само добывало токен и само собирало заголовки.');

правило('у приложения нет плоской задержки повтора',
    (function () {
        const т = безКом(чит('mobile/www/js/auth.js'));
        return !/startResendCooldown\(\s*60\s*\)/.test(т) &&
               /задержкаПовтора\(\)/.test(т) && /сбросПовтора\(\)/.test(т);
    })(),
    'ЭТО ТА САМАЯ БЕДА: плоские 60 в двух местах. Пять нажатий — и\n' +
    'блокировка на четверть часа. Шаг обязан СБРАСЫВАТЬСЯ при входе на\n' +
    'экран кода, иначе вернувшийся к форме получит ожидание с прошлого\n' +
    'раза.');

правило('вход через Apple у сайта на месте',
    /window\.KSLT_APPLE/.test(безКом(чит('js/auth.js'))) &&
    /provider:\s*'apple'/.test(безКом(чит('js/auth.js'))),
    'Этот кусок Apple не трогал. У приложения входа с Apple НЕТ, и без\n' +
    'него правило 4.8 даёт прямой отказ в App Store — это шаг E3.\n' +
    'Правило следит, что у сайта он не снесён попутной правкой.');

правило('дом подключён во всех разметках, где подключён вход',
    РАЗМЕТКИ.length >= 20 && РАЗМЕТКИ.every(ф => /kslt-vhod\.js/.test(чит(ф))),
    'Разметок со входом ' + РАЗМЕТКИ.length + ', и каждая обязана грузить\n' +
    'дом: иначе вход упадёт на `undefined` при первом же нажатии.\n' +
    'Без дома: ' + РАЗМЕТКИ.filter(ф => !/kslt-vhod\.js/.test(чит(ф))).join(', '));

правило('дом грузится ДО того, кто его зовёт',
    РАЗМЕТКИ.every(ф => {
        const т = чит(ф);
        const д = т.indexOf('kslt-vhod.js');
        const все = (т.match(/[^"]*(?:auth|dashboard|tournament-register)\.js\?v=\d+/g) || [])
            .map(с => т.indexOf(с)).filter(и => и !== -1);
        return д !== -1 && все.length > 0 && д < Math.min.apply(null, все);
    }),
    'Порядок ставится явно, а не на удачу тайминга.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else { console.log('  ок      вход: все ' + держится + ' правил держатся · разметок ' + РАЗМЕТКИ.length + '\n'); }
