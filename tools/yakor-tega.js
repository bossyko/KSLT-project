'use strict';
const fs = require('fs');
const path = require('path');

/** Строки файла разметки. */
function строки(корень, файл) {
    return fs.readFileSync(path.join(корень, файл), 'utf8').split('\n');
}

/**
 * Строка тега скрипта по имени файла — КАК ОНА СЕЙЧАС НАПИСАНА, вместе со
 * своим `?v=`. Отступ сохраняется: он часть замены.
 *
 * @returns {string|null} null, если тега нет — тогда прувер честно скажет,
 *          что ему нечего возвращать, вместо того чтобы латать мимо.
 */
function тег(корень, файл, имяJs) {
    const с = строки(корень, файл);
    const i = с.findIndex(л => л.indexOf('<script') !== -1 &&
                               л.indexOf('/' + имяJs) !== -1);
    return i === -1 ? null : с[i];
}

/** Тег вместе с переводом строки — для откатов, снимающих его целиком. */
function тегСтрокой(корень, файл, имяJs) {
    const т = тег(корень, файл, имяJs);
    return т === null ? null : т + '\n';
}

/**
 * Кусок разметки от тега ДОМА до тега ЧИТАТЕЛЯ и тот же кусок с домом,
 * уехавшим в конец. Берётся непрерывный кусок, поэтому между ними может
 * стоять что угодно — это и спасает якорь от соседей, которые уезжают.
 *
 * @returns {{было: string, станет: string}|null}
 */
function переставить(корень, файл, имяДома, имяЧитателя) {
    const с = строки(корень, файл);
    const д = с.findIndex(л => л.indexOf('<script') !== -1 &&
                               л.indexOf('/' + имяДома) !== -1);
    if (д === -1) return null;
    const ч = с.findIndex((л, i) => i > д && л.indexOf('<script') !== -1 &&
                                    л.indexOf('/' + имяЧитателя) !== -1);
    if (ч === -1) return null;
    const кусок = с.slice(д, ч + 1);
    return {
        было: кусок.join('\n'),
        станет: кусок.slice(1).concat(кусок[0]).join('\n')
    };
}

/** Подменить имя файла в теге, оставив версию как есть (откат «дома нет»). */
function переименовать(корень, файл, имяJs, новоеИмя) {
    const т = тег(корень, файл, имяJs);
    return т === null ? null : { было: т, станет: т.replace(имяJs, новоеИмя) };
}

module.exports = { тег, тегСтрокой, переставить, переименовать };
