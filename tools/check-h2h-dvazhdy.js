/* ── 7. ОКНО РИСУЮТ РОВНО ДВА ДОМА В JS ──────────────────────────────── */
function всеJs(д) {
    const из = [];
    (function идти(п) {
        fs.readdirSync(path.join(КОРЕНЬ, п), { withFileTypes: true }).forEach(э => {
            const ф = п + '/' + э.name;
            if (э.isDirectory()) идти(ф); else if (э.name.endsWith('.js')) из.push(ф);
        });
    })(д);
    return из;
}
const рисуют = всеJs('js').filter(ф => /className\s*=\s*['"]h2h-overlay['"]|class="h2h-overlay/.test(безКом(чит(ф))));
