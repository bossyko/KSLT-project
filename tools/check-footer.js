#!/usr/bin/env node
/**
 * Заморозка подвала — быстрая проверка без браузера.
 *
 * Тест tests/e2e/ux/19-footer-tap-targets.spec.js проверяет ОТРИСОВКУ и ловит
 * больше, но требует Playwright и поднятого сервера. Эта проверка идёт по
 * исходникам, запускается за долю секунды и ловит главное: что правила и
 * разметка, добытые замерами, никто не удалил и не переписал мимоходом.
 *
 * Числа под каждым пунктом — замеры по живой странице 19-20.09.2026.
 *
 * Запуск:  node tools/check-footer.js
 * Код возврата 1, если хоть один пункт не сошёлся.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const читать = п => fs.readFileSync(path.join(ROOT, п), 'utf8');
const сжать = т => т.replace(/\s+/g, ' ');

const ошибки = [];
const ок = [];

function проверить(имя, условие, почему) {
    if (условие) ок.push(имя);
    else ошибки.push({ имя, почему });
}

// ---------- скрипт ----------
const script = читать('js/script.js');

проверить('гармошка включается до 768',
    /var\s+УЗКО\s*=\s*768\s*;/.test(script),
    'Было 640, а стили .footer-acc написаны под @media (max-width: 768px). ' +
    'Полоса 641…768 — это iPad вертикально — оставалась без правил: ' +
    '14 ссылок высотой 15 при норме 44.');

проверить('кнопка «наверх» уходит от подвала',
    /footerEl[\s\S]{0,400}innerHeight\s*-\s*20/.test(script),
    'Без этого условия кнопка ложится на подвал и перехватывает нажатие ' +
    'на правые 44px заголовков гармошки — всю зону стрелки, у всех четырёх.');

проверить('role/tabindex снимаются там, где гармошки нет',
    /removeAttribute\('role'\)/.test(script) &&
    /removeAttribute\('tabindex'\)/.test(script) &&
    /removeAttribute\('aria-expanded'\)/.test(script),
    'Находка h271. Атрибуты ставились один раз при инициализации и не ' +
    'снимались никогда. На десктопе читалка объявляла «Навигация, кнопка, ' +
    'свёрнуто» при раскрытом и видимом списке (174px, display:flex), а ' +
    'нажатие ничего не делало: переключить() выходит по первой строке. ' +
    'WCAG 4.1.2 плюс четыре мёртвые остановки Tab — в подвале было 24 ' +
    'фокусируемых элемента вместо 20.');

проверить('role/tabindex ставятся там, где гармошка есть',
    /if\s*\(узко\)\s*\{[\s\S]{0,400}setAttribute\('role',\s*'button'\)/.test(script),
    'Обратная половина h271: если снять атрибуты и не ставить их обратно ' +
    'на телефоне, гармошка станет недоступна с клавиатуры и читалка ' +
    'не объявит её состояние.');

проверить('год в копирайте подставляется',
    /getFullYear[\s\S]{0,300}footer-year/.test(script) ||
    /footer-year[\s\S]{0,300}getFullYear/.test(script),
    'Иначе «© 2026» снова станет текстом на 76 страницах и протухнет в январе.');

// ---------- полнота переноса на способ ввода (h274) ----------
//
// Эта проверка стережёт не значение, а ПОЛНОТУ.
//
// 20.09 гармошка подвала переехала на (pointer: coarse), но её оформление
// осталось на ширине: 17 правил в блоках с 768 и ещё два в блоке с 992.
// На планшете и телефоне боком выходил гибрид — структура мобильная,
// вид десктопный. Замерено на 1024 (iPad Mini) и 844 (iPhone 12 Pro):
//   выравнивание start вместо center
//   лишние 24px перед «Контактами» — блоки шли 45 · 45 · 45 · 69
//   нижняя плашка в строку, поля 24/22.5 вместо 12/0/14
//   соцсети у левого края при центрированном тексте
//
// Заморозка тогда промолчала, и это её честный предел: она стерегла то,
// что написано, а не то, что забыто. Поэтому здесь проверяется ПРАВИЛО:
// оформление подвала не живёт в медиаблоке, который смотрит только на
// ширину и не спрашивает про палец.
//
// Исключение одно и осознанное: блок на 600. Там короткие подписи вместо
// полных — это про то, сколько места на строке, а не про то, чем тыкают.
(function проверитьПолнотуПереноса() {
    const текст = fs.readFileSync(path.join(ROOT, 'css/style.css'), 'utf8');
    const виноватые = [];
    const re = /@media([^{]*)\{/g;
    let m;
    while ((m = re.exec(текст)) !== null) {
        const условие = m[1].replace(/\s+/g, ' ').trim();
        let глубина = 1, j = re.lastIndex;
        while (j < текст.length && глубина > 0) {
            if (текст[j] === '{') глубина++;
            else if (текст[j] === '}') глубина--;
            j++;
        }
        const тело = текст.slice(re.lastIndex, j - 1);
        re.lastIndex = m.index + m[0].length;

        if (/pointer/.test(условие)) continue;

        // самая узкая max-width в условии
        const ширины = (условие.match(/max-width:\s*(\d+)px/g) || [])
            .map(s => parseInt(s.replace(/\D/g, ''), 10));
        if (!ширины.length) continue;
        const узкая = Math.min.apply(null, ширины);
        if (узкая > 992) continue;        // десктопные подстройки — не наше дело
        if (узкая === 600) continue;      // осознанное исключение: длина подписей

        const rr = /([^{}]+)\{[^{}]*\}/g;
        let r2;
        while ((r2 = rr.exec(тело)) !== null) {
            const сел = r2[1].replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').trim();
            if (/\.footer-/.test(сел)) виноватые.push(узкая + 'px: ' + сел.slice(0, 45));
        }
    }
    проверить('перенос подвала на способ ввода доведён до конца',
        виноватые.length === 0,
        'Оформление подвала снова оказалось в медиаблоке, который смотрит ' +
        'только на ширину. Значит на планшете и на телефоне боком эти правила ' +
        'не применятся, и вернётся гибрид: гармошка есть, а выравнивания, ' +
        'отступов и полей нет. Найдено ' + виноватые.length + ': ' +
        виноватые.slice(0, 4).join(' | ') + '. ' +
        'Правило h274: оформление подвала живёт только в блоках с pointer, ' +
        'кроме блока на 600 — там про длину подписей, а не про палец.');
})();

// ---------- стили ----------
const css = сжать(читать('css/style.css'));

проверить('правовые ссылки: строка 44 на мобильном',
    /\.footer-bottom-links a \{[^}]*min-height: 44px/.test(css),
    'Ссылки были 17 в высоту: зона попадания 8 вверх и 8 вниз, ' +
    'промах уводил в пустоту или в соседний документ.');

проверить('ссылки внутри раскрытого раздела: 44',
    /\.открыт \.footer-links a[^{]*\{[^}]*min-height: 44px/.test(css),
    'Гармошка даёт 44 заголовку, а внутри ссылки оставались 15.');

проверить('цель 44 задана по УКАЗАТЕЛЮ, а не только по ширине',
    /@media \(pointer: coarse\)/.test(css) &&
    /@media \(pointer: coarse\) \{[^@]*\.footer-bottom-links a \{[^}]*min-height: 44px/.test(css),
    'Ширина окна ничего не говорит о том, чем тыкают. Замерено: iPad Pro ' +
    '1024 и телефон боком 844 шире 768, но оба сенсорные — браузер ' +
    'отвечает (pointer: coarse) ДА. Пока условие было только по ширине, ' +
    'подвал отдавал им 17 целей высотой 15-18.');

проверить('гармошка тоже включается по указателю',
    /@media \(pointer: coarse\), \(max-width: 768px\)/.test(css),
    'Стили .footer-acc обязаны действовать везде, где скрипт ставит класс. ' +
    'Условие читается как «или»: сенсорный экран любой ширины либо узкое ' +
    'окно. Разойдутся — класс встанет без оформления.');

проверить('скрипт и стили используют ОДНО условие',
    /pointer: coarse/.test(script) && /matchMedia/.test(script),
    'js/script.js должен спрашивать указатель тем же запросом, что и CSS. ' +
    'Иначе класс footer-acc и стили под него разъедутся.');

проверить('своя навигация подвала не наследует высоту шапки',
    /\.footer-legal-nav \{[^}]*height: auto/.test(css),
    'В проекте есть голый селектор nav { height: 64px } для шапки. ' +
    'Без своего правила навигация подвала вырастает с 44 до 64.');

проверить('видимый фокус с клавиатуры',
    /\.footer-bottom-links a:focus-visible \{[^}]*outline: 2px/.test(css),
    'Иначе ссылки выпадают из системы: у .mobile-nav-links и .trn-chip ' +
    'фокус описан, а у подвала работало бы только умолчание браузера.');

проверить('переключатель длинных и коротких названий',
    /\.footer-legal-short \{ display: none/.test(css) &&
    /\.footer-legal-full \{ display: none/.test(css),
    'ОСОЗНАННЫЙ ДУБЛЬ: полные названия занимают 457 при доступных 358 и ' +
    'переносятся во второй ряд, короткие дают 333 в один ряд.');

проверить('короткие подписи включаются на 600, а не на 768',
    /@media \(max-width: 600px\) \{[^}]*\.footer-legal-full \{ display: none/.test(css),
    'Граница подписи не должна совпадать с границей раскладки. Полные ' +
    'названия занимают 457: на 390 доступно 358 — не влезают, на 768 ' +
    'доступно 736 — влезают с запасом 280. Сокращать на планшете нечего.');

проверить('объяснение дубля не удалено из стилей',
    /ОСОЗНАННЫЙ ДУБЛЬ/.test(читать('css/style.css')),
    'Без комментария следующий читатель примет дубль за копипасту ' +
    'и схлопнет его обратно.');

// ---------- разметка ----------
for (const язык of ['ru', 'kg', 'en']) {
    const файл = `partials/footer-${язык}.html`;
    const html = читать(файл);
    const s = сжать(html);

    проверить(`${язык}: ссылки в nav со списком`,
        /<nav class="footer-legal-nav" aria-label="[^"]+">/.test(s) &&
        /<ul class="footer-bottom-links">/.test(s) &&
        (s.match(/<li><a href/g) || []).length >= 3,
        'Читалке нужен ориентир и группа, иначе это три одиночные ссылки.');

    проверить(`${язык}: год отдельным элементом`,
        /<span class="footer-year">/.test(s),
        'Иначе год снова окажется текстом и протухнет.');

    проверить(`${язык}: эмодзи скрыты от читалки`,
        /footer-made[\s\S]{0,300}aria-hidden="true"/.test(s),
        'Строка читается как «сделано с красное сердце».');
}

const ru = читать('partials/footer-ru.html');
проверить('ru: обе подписи на месте',
    /footer-legal-full/.test(ru) && /footer-legal-short/.test(ru),
    'Дубль нужен только русскому: kg 324 и en 241 влезают полными в 358.');

проверить('ru: объяснение дубля не удалено из разметки',
    /ОСОЗНАННЫЙ ДУБЛЬ/.test(ru),
    'Комментарий — часть решения, без него дубль выглядит ошибкой.');

// ---------- итог ----------
console.log(`Подвал: сошлось ${ок.length} из ${ок.length + ошибки.length}`);
if (ошибки.length) {
    console.log('');
    for (const о of ошибки) {
        console.log(`  НЕ СОШЛОСЬ: ${о.имя}`);
        console.log(`              ${о.почему}`);
    }
    console.log('');
    console.log('Полная проверка отрисовки: npx playwright test tests/e2e/ux/19-footer-tap-targets.spec.js');
    process.exit(1);
}
