/**
 * ГРАНИЦЫ РАСКЛАДКИ — СТОРОЖ (11.11.2026).
 *
 * ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ, А НЕ ЧИСЛО: ширинами делятся только телефон и
 * планшет, границ ровно две — 640 и 992, плюс их пары 641 и 993. Всё
 * остальное делится высотой и поворотом.
 *
 * ЗАМЕР ДО (11.11): в css/ было 304 медиазапроса и ВОСЕМНАДЦАТЬ разных
 * границ, 47 мест мимо шкалы. Главная — max-width: 768 в 22 местах: она
 * ловит телефон и планшет вертикально, но пропускает телефон боком (844),
 * и тот оставался с десктопной раскладкой. Слепок пробы 49 показал это
 * числом: на 844 корты шли в ЧЕТЫРЕ колонки и сетки турниров и новостей
 * схлопывались в высоту 4px, тогда как на 768 — три колонки и нормальные
 * сетки. ГРАНИЦА, ПОСТАВЛЕННАЯ РОВНО ПО ШИРИНЕ УСТРОЙСТВА, ОСТАВЛЯЕТ
 * СОСЕДА СНАРУЖИ.
 *
 * ОДНО ОТСТУПЛЕНИЕ РАЗРЕШЕНО И НАЗВАНО ПОИМЁННО — max-width: 1300 в
 * player.css. Оно не про раскладку: 1300 посчитано из содержимого
 * (карточка 1100 плюс по 100 на плавающую кнопку с боков). Сторож знает
 * о нём и требует, чтобы рядом стояло слово НАМЕРЕНО: отступление без
 * объяснения завтра станет правилом.
 *
 * КОММЕНТАРИИ ВЫРЕЗАЮТСЯ ПЕРЕД ПРОВЕРКОЙ. ЯКОРЬ, КОТОРЫЙ НАХОДИТ СЕБЯ В
 * КОММЕНТАРИИ, НИЧЕГО НЕ СТОРОЖИТ: в этом самом куске счётчик сперва
 * насчитал три нарушения, и два из них были строками из моего же
 * пояснения про clamp.
 */
const fs = require('fs');
const path = require('path');

const корень = path.resolve(__dirname, '..');
const дир = path.join(корень, 'css');
const РАЗРЕШЕНО = new Set([640, 641, 992, 993]);

/* Отступления: файл → граница → чем обосновано. Расширять этот список
   можно только вместе с расчётом в самом файле. */
const ОТСТУПЛЕНИЯ = [{ файл: 'player.css', ширина: 1300 }];

const ошибки = [];
const без = т => т.replace(/\/\*[\s\S]*?\*\//g, '');

if (!fs.existsSync(дир)) {
    ошибки.push('папка css/ не найдена — проверять нечего');
} else {
    let запросов = 0, границ = 0;
    for (const имя of fs.readdirSync(дир).filter(ф => ф.endsWith('.css'))) {
        const текст = без(fs.readFileSync(path.join(дир, имя), 'utf8'));
        const сырой = fs.readFileSync(path.join(дир, имя), 'utf8');
        for (const зап of текст.match(/@media[^{]+/g) || []) {
            запросов++;
            for (const м of зап.matchAll(/(max|min)-width:\s*([\d.]+)px/g)) {
                границ++;
                const w = parseFloat(м[2]);
                if (РАЗРЕШЕНО.has(w)) continue;
                const поблажка = ОТСТУПЛЕНИЯ.find(о => о.файл === имя && о.ширина === w);
                if (!поблажка) {
                    ошибки.push(`${имя}: ширина ${w}px мимо шкалы (разрешены 640, 641, 992, 993)`);
                } else if (!/НАМЕРЕНО/.test(сырой)) {
                    ошибки.push(`${имя}: отступление ${w}px есть, а слова НАМЕРЕНО с расчётом рядом нет`);
                }
            }
        }
    }
    if (!границ) ошибки.push('в css/ не найдено ни одной ширины в @media — правило стало мёртвым');

    /* ПАРА БЕЗ СВОЕЙ ПОЛОВИНЫ ОСТАВЛЯЕТ ЩЕЛЬ. 641 имеет смысл только при
       640, 993 — только при 992. */
    const весь = fs.readdirSync(дир).filter(ф => ф.endsWith('.css'))
        .map(ф => без(fs.readFileSync(path.join(дир, ф), 'utf8'))).join('\n');
    const есть = w => new RegExp(`(max|min)-width:\\s*${w}px`).test(весь);
    if (есть(641) && !есть(640)) ошибки.push('min-width 641 без max-width 640 — между ними щель');
    if (есть(993) && !есть(992)) ошибки.push('min-width 993 без max-width 992 — между ними щель');

    /* СПРАВОЧНИК НЕ ДОЛЖЕН ВРАТЬ. Раздел 9 в tokens.css объявлял пять
       границ, которых в коде не было ни одной — ровно отсюда и выросли
       восемнадцать самодельных. */
    const токены = fs.readFileSync(path.join(дир, 'tokens.css'), 'utf8');
    const раздел = (токены.match(/9\.\s*БРЕЙКПОИНТЫ[\s\S]*?={20,}\s*\*\//) || [])[0] || '';
    if (!раздел) ошибки.push('tokens.css: раздел 9 «БРЕЙКПОИНТЫ» пропал — границы объявлять негде');
    else {
        for (const w of [640, 992]) {
            if (!раздел.includes(`${w}px`)) ошибки.push(`tokens.css: справочник не называет границу ${w}px`);
        }
        /* ЯКОРЬ ИЩЕТ ОБЪЯВЛЕНИЕ, А НЕ УПОМИНАНИЕ. Первый заход искал само
           число — и упал на этом же справочнике, где старые границы
           названы в пояснении «здесь были объявлены пять границ».
           ПРАВИЛО, ЦЕЛЯЩЕЕ ШИРЕ СВОЕГО ПРЕДМЕТА, ЛОВИТ НЕВИНОВНЫХ. */
        for (const w of ['479.98', '767.98', '1023.98', '1279.98']) {
            const объявление = new RegExp(`@media\\s*\\((?:max|min)-width:\\s*${w.replace('.', '\\.')}px`);
            if (объявление.test(раздел)) {
                ошибки.push(`tokens.css: справочник снова объявляет ${w}px, которой нет в коде`);
            }
        }
    }
    /* ШОВ МЕЖДУ CSS И JS СТОРОЖИТСЯ ОТДЕЛЬНО, ПОТОМУ ЧТО ИМЕННО ОН И РВЁТСЯ.
       Гармошка подвала описана дважды: стили у .footer-acc в style.css и
       порог УЗКО в js/script.js. Задача h264 (20.09) чинила ровно это
       расхождение — тогда стили стояли на 768, а JS на 640, и полоса
       641…768 не получала ни того, ни другого. 11.11 я повторил ту же
       ошибку в другую сторону: поднял CSS до 992 и забыл JS.
       ДВА ОПРЕДЕЛЕНИЯ ОДНОГО ПОНЯТИЯ РАСХОДЯТСЯ РОВНО НА ШВЕ. */
    const скрипт = path.join(корень, 'js/script.js');
    if (fs.existsSync(скрипт)) {
        const текстJS = без(fs.readFileSync(скрипт, 'utf8'));
        const м = текстJS.match(/УЗКО\s*=\s*(\d+)/);
        if (!м) {
            ошибки.push('js/script.js: порог УЗКО для гармошки подвала не найден');
        } else {
            const узко = parseInt(м[1], 10);
            if (!РАЗРЕШЕНО.has(узко)) {
                ошибки.push(`js/script.js: УЗКО = ${узко} мимо шкалы (разрешены 640, 641, 992, 993)`);
            }
            const стиль = без(fs.readFileSync(path.join(дир, 'style.css'), 'utf8'));
            /* ПРОВЕРЯЮТСЯ ВСЕ БЛОКИ «ПАЛЕЦ ИЛИ ШИРИНА», А НЕ ПЕРВЫЙ ПОХОЖИЙ.
               Первая редакция искала один блок — тот, за которым идёт
               .footer-acc, — и прувер её не уронил: таких блоков в файле
               четыре, откат бил в один, а сторож смотрел в другой.
               ПРАВИЛО, ПРОВЕРЯЮЩЕЕ ОДНО МЕСТО ИЗ ЧЕТЫРЁХ, СТОРОЖИТ ЧЕТВЕРТЬ.
               Условие «палец или узко» — одно понятие на весь продукт, и
               число в нём должно быть одно и то же, равное УЗКО в скрипте. */
            const пальцем = [...стиль.matchAll(/@media\s*\(any-pointer:\s*coarse\)\s*,\s*\(max-width:\s*(\d+)px\)/g)]
                .map(м => parseInt(м[1], 10));
            if (!пальцем.length) {
                ошибки.push('style.css: условие (any-pointer: coarse), (max-width: …) не найдено ни разу');
            } else {
                const чужие = [...new Set(пальцем.filter(w => w !== узко))];
                if (чужие.length) {
                    ошибки.push(
                        `условие «палец или узко» описано разными числами: в css ${[...new Set(пальцем)].join(', ')}, ` +
                        `в js УЗКО = ${узко}. Между ними полоса, где стили есть, а поведения нет — ровно h264.`
                    );
                }
            }
        }
    }

    if (!ошибки.length) {
        console.log(`границы раскладки: ${запросов} медиазапросов, ${границ} границ, все на шкале 640/992 (одно названное отступление)`);
    }
}

if (ошибки.length) {
    console.error('ГРАНИЦЫ РАСКЛАДКИ — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
