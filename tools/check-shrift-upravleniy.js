/**
 * ЗАМОРОЗКА ШРИФТА УПРАВЛЕНИЙ И КАРТОЧКИ ПРОФИЛЯ. 12.10, кусок 62-й.
 *
 * ОТКУДА ВЗЯЛОСЬ. Кусок начинался с другого: трекер говорил, что кнопки
 * QR нет на телефоне. Замер показал, что она есть (`js/dashboard.js`,
 * `#dbProfileQr` в карточке профиля), и находка оказалась моей ошибкой
 * учёта. Зато замер того же места нашёл настоящее:
 *
 *   • `button`, `input`, `select` и `textarea` НЕ НАСЛЕДУЮТ семейство
 *     шрифта от body — браузер ставит им свой системный. В продукте это
 *     лечилось поштучно, `font-family: inherit` написан 82 раза в 24
 *     файлах css, и там, где забыли, элемент выпадал в Arial. Замер на
 *     390: в кабинете мимо Inter 12 видимых управлений из 26, на каждой
 *     публичной странице 5 — колокольчик, меню пользователя, выход,
 *     бургер и «наверх», то есть ОБЩАЯ ШАПКА всех страниц;
 *   • `.db-btn` носят и `button`, и `a`, а подчёркивание у ссылки своё.
 *     В ряду карточки «QR код» выходил кнопкой, «Моя страница» ссылкой
 *     при одинаковой рамке и высоте. Увидено глазами на снимке;
 *   • имя в карточке на узких видах было опущено до ступени СТРОК той
 *     же карточки — пара схлопывалась, хотя на широких отстояла.
 *
 * ЧТО ЗАМОРАЖИВАЕТСЯ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • шрифт управлений наследуется ОДНИМ определением, а не копиями;
 *   • копии не плодятся: их счёт сторожится, рост роняет правило;
 *   • кнопка гасит подчёркивание ТАМ, ГДЕ ЗАВЕДЕНА, а не в каждом месте
 *     применения;
 *   • имя карточки СТРОГО крупнее её строк на КАЖДОМ виде;
 *   • подпись кнопки — ступень компонента, высоту держит свойство.
 *
 *   node tools/check-shrift-upravleniy.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const CSS = безКом(чит('css/dashboard.css'));
const ОБЩИЙ = безКом(чит('css/style.css'));
const СТРАНИЦЫ = ['pages/dashboard.html', 'pages/dashboard-en.html', 'pages/dashboard-kg.html'].map(чит);

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };
const тело = (текст, сел) => {
    const i = текст.indexOf(сел + ' {');
    if (i === -1) return '';
    const j = текст.indexOf('}', i);
    return j === -1 ? '' : текст.slice(i, j + 1);
};

/* ══ 1. ШРИФТ УПРАВЛЕНИЙ — ОДНО ОПРЕДЕЛЕНИЕ ════════════════════════════ */

const общиеБлоки = ОБЩИЙ.split('input, button, select, textarea {').slice(1)
    .map(ч => ч.slice(0, ч.indexOf('}')));

правило('шрифт управлений наследуется общим правилом',
    общиеБлоки.some(б => /font-family:\s*inherit/.test(б)),
    'button/input/select/textarea не наследуют семейство от body: браузер\n' +
    '          ставит системное. Без общего правила каждый забытый элемент\n' +
    '          выпадает в Arial — замер 12.10 нашёл 12 таких из 26 в кабинете');

правило('общее правило шрифта объявлено ровно один раз',
    общиеБлоки.filter(б => /font-family:\s*inherit/.test(б)).length === 1,
    'одно определение на одно понятие: два общих правила шрифта — это шов,\n' +
    '          на котором родится расхождение');

/* Дубликат ловит проверка, а не память: поштучные копии замораживаются
   счётом. 82 — то, что осталось от лечения по одному месту; каждая новая
   копия роняет это правило и просит снять её вместе с соседями */
const копий = fs.readdirSync(path.join(КОРЕНЬ, 'css'))
    .filter(ф => ф.endsWith('.css'))
    .reduce((s, ф) => s + (чит('css/' + ф).match(/font-family:\s*inherit/g) || []).length, 0);

/* 13.10: копий стало 81. Одну снял кусок баттлов — в `.bo-more` стояла
   сокращённая запись `font: 600 0.9rem inherit` и рядом дубль
   `font-family: inherit`; при переводе кнопки на высоту свойством обе ушли.
   Число опускается вместе с долгом: сторож ловит НОВУЮ копию, а не помнит
   старое число. */
правило('поштучные копии наследования не плодятся',
    копий <= 81,
    'копий font-family: inherit стало ' + копий + ' при 81 на 13.10. Общее\n' +
    '          правило уже есть — новая копия не нужна. Долг: снять все 81');

/* ══ 2. КНОПКА ГАСИТ ПОДЧЁРКИВАНИЕ У СЕБЯ ══════════════════════════════ */

правило('кнопка кабинета гасит подчёркивание в своём объявлении',
    /text-decoration:\s*none/.test(тело(CSS, '.db-btn')),
    '.db-btn носят и button, и a: у ссылки подчёркивание браузерное.\n' +
    '          В карточке профиля «Моя страница» шла подчёркнутой рядом с\n' +
    '          «QR код» при одинаковой рамке — увидено глазами 12.10');

/* ══ 3. ЛЕСТНИЦА КАРТОЧКИ — ОТНОШЕНИЕ, А НЕ ЧИСЛО ══════════════════════ */

const ШКАЛА = { '--fs-xs': 12, '--fs-sm': 14, '--fs-base': 16, '--fs-md': 18, '--fs-lg': 21, '--fs-xl': 26 };
const кегль = тлo => {
    const m = тлo.match(/font-size:\s*var\((--fs-[a-z]+)\)/);
    return m ? ШКАЛА[m[1]] : null;
};

/* Базовые объявления */
const имяБаза = кегль(тело(CSS, '.db-profile-card-name'));
const строкаБаза = кегль(тело(CSS, '.db-profile-card-row'));

правило('имя карточки крупнее её строк на широких видах',
    имяБаза !== null && строкаБаза !== null && имяБаза > строкаБаза,
    'пара «имя + строки» читается как пара и обязана отстоять на ступень:\n' +
    '          имя ' + имяБаза + ', строки ' + строкаБаза);

/* На узких видах — то же отношение. Медиа-блок на <=992 правит имя;
   берём ПОСЛЕДНЕЕ объявление, оно и побеждает */
const всеИмена = [...CSS.matchAll(/\.db-profile-card-name \{[^}]*\}/g)].map(m => кегль(m[0])).filter(к => к);
const всеСтроки = [...CSS.matchAll(/\.db-profile-card-row \{[^}]*\}/g)].map(m => кегль(m[0])).filter(к => к);

правило('имя карточки крупнее строк НА КАЖДОМ виде, а не только на широком',
    всеИмена.length > 0 && Math.min(...всеИмена) > Math.max(...всеСтроки),
    'на узких имя опускалось до --fs-sm, и строки карточки тоже --fs-sm:\n' +
    '          пара схлопывалась в одну ступень. Имена: ' + всеИмена.join(', ') +
    ', строки: ' + всеСтроки.join(', '));

/* ══ 4. ПОДПИСЬ КНОПКИ И ЕЁ ВЫСОТА ═════════════════════════════════════ */

/* Объявлений два: базовое (flex: 1) и в медиа на <=992, где кегль. Берём
   ВСЕ и спрашиваем кегль у того, кто его задаёт — искать первое вхождение
   значит мерить не того, кто побеждает */
const кнопкиКарточки = [...CSS.matchAll(/\.db-profile-card-actions \.db-btn \{[^}]*\}/g)].map(m => m[0]);
const кнопкаКарточки = кнопкиКарточки.find(т => /font-size/.test(т)) || '';

правило('подпись кнопки карточки — ступень компонента Button 17:82',
    кегль(кнопкаКарточки) === 14,
    'кнопка высотой 44 носила подпись мелкой ступени 12. Замер 12.10 на\n' +
    '          390: кыргызская «Менин баракчам» при 14 занимает 119.3 из 146');

правило('высоту кнопки карточки не задаёт вертикальное поле',
    !/padding:\s*\d+px\s+\d+px/.test(кнопкаКарточки),
    'Button 17:82: «height is set by the height property, never by vertical\n' +
    '          padding». Было padding: 8px 8px при min-height 44');

/* ══ 5. ОДНО НАПРАВЛЕНИЕ РЯДА — ОДНО ОБЪЯВЛЕНИЕ ════════════════════════ */

const направления = [...CSS.matchAll(/\.db-profile-card-actions \{[^}]*flex-direction:\s*(\w+)/g)].map(m => m[1]);

правило('направление ряда действий объявлено один раз',
    направления.length <= 1,
    'было два: column на <=640 и row на <=992 ниже по файлу. При равном\n' +
    '          весе побеждает последний — правило на <=640 было мёртвым, и\n' +
    '          замер на 390 давал row. Направлений сейчас: ' + направления.join(', '));

/* ══ 6. КНОПКА QR ДОСТИЖИМА ТАМ, ГДЕ БОКОВОЕ МЕНЮ СКРЫТО ═══════════════ */

const JS = безКом(чит('js/dashboard.js'));

правило('кнопка QR есть в карточке профиля, а не только в боковом меню',
    /id="dbProfileQr"/.test(JS) && /dbProfileQr'\)/.test(JS),
    'боковое меню скрыто на <=992 (.db-sidebar display:none), а телефон\n' +
    '          как раз и достают, чтобы показать код с экрана. Вторая кнопка\n' +
    '          живёт в карточке профиля и зовёт то же окно');

правило('обе кнопки QR зовут одно и то же окно',
    (JS.match(/showQrModal\(/g) || []).length >= 3,
    'окно QR должно быть одно на оба входа: определение плюс два вызова');

/* ══ 7. ИМЯ НЕ ОБЪЯВЛЯЕТСЯ ДВАЖДЫ В ОДНОЙ ФУНКЦИИ ═══════════════════════ */

/* `var` живёт во ВСЕЙ функции, а не в блоке. В карточке профиля `место`
   было и контейнером, и местом игрока в категории: второе объявление
   затирало первое, и `место.innerHTML` после цикла присваивался ЧИСЛУ —
   молча, без ошибки. Карточка не рисовалась НИ У КОГО, у кого есть хоть
   одна категория. Замер в браузере этого показать не мог: у аккаунта,
   которым я мерил, категорий нет. Нашёл прогон 12.10 — 60 из 75 */
const карточкаФ = (() => {
    const i = JS.indexOf('async function карточкаВПрофиле');
    if (i === -1) return '';
    const j = JS.indexOf('\n    }', i);
    return j === -1 ? JS.slice(i) : JS.slice(i, j);
})();

const объявления = (карточкаФ.match(/\bvar\s+([А-Яа-яЁёA-Za-z_$][\wА-Яа-яЁё$]*)/g) || [])
    .map(с => с.replace(/^var\s+/, ''));
const повторы = объявления.filter((и, к) => объявления.indexOf(и) !== к);

правило('в карточке профиля ни одно имя не объявлено дважды',
    карточкаФ !== '' && повторы.length === 0,
    'var живёт во всей функции: второе объявление затирает первое, и\n' +
    '          присваивание уходит не тому. Повторы: ' + повторы.join(', '));

/* ══ 8. ВЕРСИИ ═════════════════════════════════════════════════════════ */

const версии = имя => {
    const найдено = new Set();
    СТРАНИЦЫ.forEach(s => {
        const re = new RegExp('/' + имя.replace('.', '\\.') + '\\?v=(\\d+)', 'g');
        let m; while ((m = re.exec(s))) найдено.add(m[1]);
    });
    return [...найдено];
};
[['dashboard.css'], ['dashboard.js'], ['style.css']].forEach(([ф]) => {
    const в = версии(ф);
    правило('версия ' + ф + ' одна на все три языка',
        в.length === 1,
        ф + ' подключён разными версиями: ' + в.join(', '));
});

if (ошибки.length === 0) {
    console.log(`\n  ок      шрифт управлений и карточка профиля: ${ВСЕГО} правил\n`);
    process.exit(0);
}
console.log(`\n  НЕ ТАК  шрифт управлений и карточка профиля: ${ВСЕГО} правил, упало ${ошибки.length}.\n`);
ошибки.forEach(о => {
    console.log(`  ✗ ${о.имя}`);
    if (о.подсказка) console.log(`          ${о.подсказка}`);
    console.log('');
});
process.exit(1);
