/**
 * ЗАМОРОЗКА ЦВЕТА СТАТУСОВ ТУРНИРА.
 *
 * 22.09 бейджи турнира и дата уведены с лайма на статусные тона. Решение
 * Кости: «мне нравится все тут», тон подобран замером и им же проверен
 * глазами на localhost:8080.
 *
 * ЧТО ИМЕННО ЗАМОРАЖИВАЕМ И ПОЧЕМУ КАЖДОЕ:
 *
 * 1. Контраст СЧИТАЕТСЯ, а не сверяется со строкой. Правила ниже достают
 *    значения из tokens.css, складывают полупрозрачный текст с подложкой и
 *    считают WCAG-отношение. Подпись бейджа 11px — мелкий текст, порог 4.5
 *    (1.4.3). Сравнение строк поймало бы только переименование; счёт ловит
 *    ЛЮБУЮ подмену тона, в том числе «чуть притушить красный».
 * 2. Подложки бейджа НЕПРОЗРАЧНЫЕ. Бейдж лежит на афише турнира: сквозь 15%
 *    проступает фотография, и контраст перестаёт быть числом — он зависит от
 *    того, какую картинку загрузил организатор. Поэтому -surface, а не -subtle.
 * 3. Белый на --danger запрещён. 3.34 — не проходит. Это та же пара, что уже
 *    жила в .live-badge.is-live, поэтому правило смотрит ОБА раздела.
 * 4. Лайма в бейджах и дате нет. Правило 109:370: лайм принадлежит одному
 *    главному действию в поле зрения — кнопке записи.
 * 5. Высоту бейджа держит компонент: край даём inset-тенью, а не рамкой.
 *    Рамка добавила бы 2px к высоте 24.
 * 6. .tc-badge-cancelled существует. До 22.09 его не было вовсе, хотя
 *    js/tournament-card.js его выдаёт — отменённый турнир рисовался голым
 *    текстом без подложки.
 *
 *   node tools/check-turniry-cvet.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
/* Комментарии срезаем ПОСТРОЧНО и блочно: в них процитирован прежний код —
   там и «#fff», и «rgba(204, 255, 0, 0.15)». 22.09 проверка раздела #live уже
   спотыкалась о собственный комментарий, второй раз не наступаем. */
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ТОК = безКом(чит('css/tokens.css'));
const СТИ = безКом(чит('css/style.css'));

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ── значения токенов ────────────────────────────────────────────────────── */
function токен(имя) {
    const м = ТОК.match(new RegExp('(?:^|\\n)\\s*' + имя.replace(/[-]/g, '\\-') + ':\\s*([^;]+);'));
    return м ? м[1].trim() : null;
}
/* var(--x) разворачиваем до значения, глубина ограничена — цикл не повесит */
function значение(v, глубина) {
    глубина = глубина || 0;
    if (!v || глубина > 8) return v;
    const м = v.match(/^var\((--[a-z0-9-]+)\)$/i);
    return м ? значение(токен(м[1]), глубина + 1) : v;
}

/* ── цвет: разбор, складывание, контраст ─────────────────────────────────── */
function цвет(s) {
    s = (s || '').trim();
    let м = s.match(/^#([0-9a-f]{6})$/i);
    if (м) return [parseInt(м[1].slice(0,2),16), parseInt(м[1].slice(2,4),16), parseInt(м[1].slice(4,6),16), 1];
    м = s.match(/^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:[,/\s]+([\d.]+))?\s*\)$/i);
    if (м) return [+м[1], +м[2], +м[3], м[4] === undefined ? 1 : +м[4]];
    return null;
}
/* полупрозрачный поверх непрозрачного — иначе контраст текста 72% белого
   посчитается как у чистого белого, и правило пропустит тусклую подпись */
function поверх(верх, низ) {
    const a = цвет(верх), b = цвет(низ);
    if (!a || !b) return null;
    return [0,1,2].map(i => Math.round(a[i] * a[3] + b[i] * (1 - a[3]))).concat(1);
}
function яркость(c) {
    const l = c.slice(0,3).map(v => { v /= 255; return v <= 0.03928 ? v/12.92 : Math.pow((v+0.055)/1.055, 2.4); });
    return 0.2126*l[0] + 0.7152*l[1] + 0.0722*l[2];
}
function контраст(текст, фон) {
    const ф = цвет(фон), т = поверх(текст, фон);
    if (!ф || !т) return null;
    const a = яркость(т), b = яркость(ф);
    return (Math.max(a,b) + 0.05) / (Math.min(a,b) + 0.05);
}

/* ── тело правила ────────────────────────────────────────────────────────── */
function тело(текст, селектор) {
    const i = текст.indexOf(селектор + ' {');
    if (i === -1) return null;
    const j = текст.indexOf('}', i);
    return j === -1 ? null : текст.slice(i, j);
}
function свойство(тело_, имя) {
    if (!тело_) return null;
    const м = тело_.match(new RegExp('(?:^|\\n)\\s*' + имя + ':\\s*([^;]+);'));
    return м ? м[1].trim() : null;
}

/* ── 1. токены существуют и читаются как цвет ────────────────────────────── */
/* ЗАЧЕМ ИМЕННО ТАК. Первая версия этого файла прибивала точные шестнадцатеричные
   значения: --danger = #FF4757 и так далее. Это заморозка не того: Костя прямо
   сказал «если надо поднять или уменьшить тон цвета делай». Прибитое значение
   запрещает и безобидную правку тона, и при этом НЕ ловит настоящую поломку —
   подмену пары текст/подложка. Поэтому здесь замораживается СВОЙСТВО —
   читаемость, — а не пиксель: тон меняй сколько хочешь, пока контраст держится. */
const ЦВЕТА = ['--danger', '--danger-on', '--success', '--info',
               '--success-surface', '--info-surface', '--neutral-surface',
               '--danger-surface', '--text-secondary'];
ЦВЕТА.forEach(имя => {
    const v = значение(токен(имя));
    правило('токен ' + имя + ' объявлен и читается как цвет',
        !!цвет(v),
        'Сейчас: ' + (v === null ? 'токена нет вовсе' : v));
});

/* Подложка -subtle обязана быть из того же тона, что и текст. Когда синий
   подняли на ступень, rgba осталась от прежнего #3B82F6 — подложка уехала бы
   в другой оттенок, и никто бы этого не заметил. Сверяем не строку, а числа. */
(function () {
    const т = цвет(значение(токен('--info')));
    const п = цвет(значение(токен('--alpha-blue-15')));
    правило('--alpha-blue-15 собран из того же тона, что --info',
        !!т && !!п && т[0] === п[0] && т[1] === п[1] && т[2] === п[2],
        'Текст: ' + значение(токен('--info')) + ' · подложка: ' + значение(токен('--alpha-blue-15')));
})();

/* ── 2. считаем контраст каждой пары ─────────────────────────────────────── */
const ПОРОГ = 4.5;   /* WCAG 1.4.3, подпись бейджа 11px — мелкий текст */
const ПАРЫ = [
    ['бейдж «идёт сейчас»',        '--danger-on',     '--danger'],
    ['бейдж «регистрация открыта»','--success',       '--success-surface'],
    ['бейдж «скоро»',              '--info',          '--info-surface'],
    ['бейдж «закрыта / завершён»', '--text-secondary','--neutral-surface'],
    ['бейдж «отменён»',            '--danger',        '--danger-surface'],
    ['подпись матча live',         '--danger-on',     '--danger']
];
ПАРЫ.forEach(([имя, т, ф]) => {
    const k = контраст(значение(токен(т)), значение(токен(ф)));
    правило('контраст: ' + имя + ' ≥ ' + ПОРОГ,
        k !== null && k >= ПОРОГ,
        'Посчитал: ' + (k === null ? 'не смог разобрать цвета' : k.toFixed(2)) + '\n' +
        '          ' + т + ' на ' + ф + '. Порог 4.5 — подпись 11px, это мелкий текст (WCAG 1.4.3).');
});

/* Подложки бейджа НЕПРОЗРАЧНЫЕ. Считаем альфу, а не ищем слово -subtle:
   прозрачность могли бы вернуть и через rgba, и через новый токен. */
['--success-surface', '--info-surface', '--neutral-surface', '--danger-surface'].forEach(имя => {
    const c = цвет(значение(токен(имя)));
    правило('подложка ' + имя + ' непрозрачная',
        !!c && c[3] === 1,
        'Альфа: ' + (c ? c[3] : '?') + '\n' +
        '          Бейдж лежит на АФИШЕ. Сквозь прозрачную подложку проступает фотография,' +
        ' и контраст перестаёт быть числом — он зависит от того, что загрузил организатор.');
});

/* ── 3. тона бейджа турнира ──────────────────────────────────────────────── */
const ТОНА = {
    '.tc-badge-live':      { фон: 'var(--danger)',           текст: 'var(--danger-on)',      край: false },
    '.tc-badge-open':      { фон: 'var(--success-surface)',  текст: 'var(--success)',        край: true  },
    '.tc-badge-soon':      { фон: 'var(--info-surface)',     текст: 'var(--info)',           край: true  },
    '.tc-badge-cancelled': { фон: 'var(--danger-surface)',   текст: 'var(--danger)',         край: true  }
};
Object.keys(ТОНА).forEach(сел => {
    const б = тело(СТИ, сел);
    правило('тон ' + сел + ' объявлен', !!б,
        сел + ' в style.css не найден. У отменённого турнира его не было до 22.09 —' +
        ' бейдж рисовался голым текстом без подложки.');
    if (!б) return;
    const ж = ТОНА[сел];
    if (ж.фон) правило('тон ' + сел + ' берёт подложку ' + ж.фон,
        свойство(б, 'background') === ж.фон,
        'Сейчас: ' + свойство(б, 'background') + '\n' +
        '          Бейдж лежит на афише. Прозрачная подложка = контраст зависит от чужой фотографии.');
    правило('тон ' + сел + ' берёт текст ' + ж.текст,
        свойство(б, 'color') === ж.текст,
        'Сейчас: ' + свойство(б, 'color'));
    правило('тон ' + сел + ' не рисует рамку',
        !/(?:^|\n)\s*border:/.test(б),
        'Рамка добавляет 2px к высоте, а высоту 24 задаёт компонент Badge 27:53 одним числом. Край — inset-тенью.');
    if (ж.край) правило('тон ' + сел + ' даёт край inset-тенью',
        /box-shadow:\s*inset 0 0 0 1px var\(--border-light\)/.test(б),
        'Тёмная подложка на тёмной афише сливается с ней (1.44 к чёрному) — бейдж читается как текст в воздухе.');
});

const закрыт = тело(СТИ, '.tc-badge-done');
правило('«закрыта» и «завершён» — один тон',
    !!закрыт && /\.tc-badge-closed,\s*\n\.tc-badge-done/.test(СТИ),
    'Оба состояния означают «записаться уже нельзя» и обязаны выглядеть одинаково.');

/* ── 4. лайма нет ни в бейджах, ни в дате ────────────────────────────────── */
const лайм = /204\s*,\s*255\s*,\s*0|#CCFF00|var\(--accent(-hover|-dim|-subtle|-glow)?\)/i;
Object.keys(ТОНА).concat(['.tc-badge-closed', '.tc-date']).forEach(сел => {
    const б = тело(СТИ, сел);
    if (!б) return;
    правило('в ' + сел + ' нет лайма',
        !лайм.test(б),
        'Правило 109:370: лайм принадлежит ОДНОМУ главному действию в поле зрения —' +
        ' кнопке записи. В секции было 13 лаймовых пятен, осталось 7.');
});
/* Правило «дата белая» жило здесь с 22.09 и 23.09 отменено: белая дата дала
   вторую стопроцентную ступень рядом с названием, и всё слилось. Что теперь
   с датой — сказано ниже, в лестнице цвета. */

/* ── 5. белый на красном не вернулся ─────────────────────────────────────── */
const живой = тело(СТИ, '.live-badge.is-live');
правило('.live-badge.is-live не белым по красному',
    !!живой && свойство(живой, 'color') === 'var(--danger-on)',
    'Сейчас: ' + свойство(живой, 'color') + '\n' +
    '          Белый на #FF4757 — 3.34. Заливку не трогаем, этот бейдж обязан доминировать.');

/* ── 6. версия поднята везде ─────────────────────────────────────────────── */
const страницы = [];
(function обход(дир) {
    fs.readdirSync(path.join(КОРЕНЬ, дир), { withFileTypes: true }).forEach(э => {
        if (э.name === 'node_modules' || э.name === 'mobile' || э.name.startsWith('.')) return;
        if (э.isDirectory()) обход(path.join(дир, э.name));
        else if (э.name.endsWith('.html')) страницы.push(path.join(дир, э.name));
    });
})('.');
const отстали = страницы.filter(ф => {
    const s = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
    return /tokens\.css\?v=(\d+)/.test(s) && +RegExp.$1 < 19;
});
правило('tokens.css на всех страницах не ниже v=19',
    отстали.length === 0,
    'Отстали: ' + отстали.slice(0, 6).join(', ') + (отстали.length > 6 ? ' и ещё ' + (отстали.length - 6) : '') + '\n' +
    '          Старые токены + новый style.css = цвет отваливается: var(--danger-on) не объявлен.');

/* ── лестница цвета внутри карточки ──────────────────────────────────────── */
/* Решение Кости 23.09, доска 345:9. Ступеней РОВНО ТРИ:
     100% — что это (название)
      72% — про что это (дата и описание)
      50% — подробности (места)
   Дату и описание разводит форма, а не цвет: 12 капсом с разрядкой и весом
   600 против обычных 14. Четвёртой ступени не заводим — именно из-за второй
   стопроцентной 23.09 у Кости всё слилось: «дата название описание все
   одного белого цвета».

   Подложка карточки — --surface-glass (4% белого) поверх --bg-base. Считаем
   контраст над её непрозрачным двойником #131313: замерено в браузере. */
const КАРТА = '#131313';
/* Блок берём с якорем НА НАЧАЛО СТРОКИ. indexOf('.tc-desc {') находит сначала
   '.tc-featured .tc-desc {' — правило смотрело не на тот блок и возвращало
   null. Третий раз на этих граблях за два дня: .avatar-initials, .tc-more,
   теперь .tc-desc. Селектор без якоря — это подстрока, а не селектор. */
function блок(сел) {
    const м = СТИ.match(new RegExp('(?:^|\\n)' + сел.replace('.', '\\.') + '\\s*\\{[^}]*\\}'));
    return м ? м[0] : null;
}

const СТУПЕНИ = [
    ['название', '.tc-title', 'var(--text-primary)'],
    ['дата',     '.tc-date',  'var(--text-secondary)'],
    ['описание', '.tc-desc',  'var(--text-secondary)'],
    ['места',    '.tc-meta',  'var(--text-muted)']
];
СТУПЕНИ.forEach(([имя, сел, ждём]) => {
    const б = блок(сел);
    правило('ступень цвета: ' + имя + ' — ' + ждём,
        б && свойство(б, 'color') === ждём,
        'Сейчас: ' + (б ? свойство(б, 'color') : 'блока нет') + '\n' +
        '          Три ступени: 100 — что это, 72 — про что это, 50 — подробности.');
});

/* Контраст каждой ступени считаем отдельно: 35% белого, на которых жили
   «места» до 23.09, дают 3.22 — ниже порога 4.5 для кегля 14. Глазами такое
   не ловится: текст «читается», просто плохо. */
[['--text-primary', 4.5], ['--text-secondary', 4.5], ['--text-muted', 4.5]].forEach(([т, порог]) => {
    const k = контраст(значение(токен(т)), КАРТА);
    правило('контраст ступени ' + т + ' ≥ ' + порог,
        k !== null && k >= порог,
        'Посчитал: ' + (k === null ? 'не разобрал' : k.toFixed(2)) + ' на подложке карточки.');
});
правило('«места» больше не на --text-dim',
    !/\.tc-meta\s*\{[^}]*color:\s*var\(--text-dim\)/.test(СТИ),
    '--text-dim это 35% белого — 3.22 при кегле 14, порог 4.5.');

/* ── вывод ───────────────────────────────────────────────────────────────── */
console.log('');
if (ошибки.length === 0) {
    console.log('  ок      цвет статусов турнира: ' + (ЦВЕТА.length + ПАРЫ.length + 22) + '+ правил');
    console.log('          контраст посчитан, не сверен со строкой   ·   подложки непрозрачные   ·   лайм остался кнопке');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  цвет статусов турнира — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s+/g, '\n            '));
    console.log('');
});
process.exit(1);
