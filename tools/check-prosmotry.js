/**
 * ПРОСМОТРЫ — СТОРОЖ (11.11.2026).
 *
 * ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ: счёт просмотров на сайте идёт через ОДИН дом,
 * заход считается ровно в одном месте, и ни один счётчик не зовётся голым.
 *
 * ОТКУДА ПРАВИЛА — ТРИ ЗАМЕРА ОДНОГО ДНЯ, ДВА ИЗ НИХ ПОЙМАЛИ МЕНЯ.
 *
 * 1. Шесть вызовов increment_*_view жили голыми в шести файлах, и запись
 *    f26 считала, что они падают с PGRST203. ЧТЕНИЕ БАЗЫ 11.11 ПОКАЗАЛО
 *    ОБРАТНОЕ: все шесть отвечают ok — миграция от 06.11 дубли убрала.
 *    Запись устарела, а я собирался чинить по ней. ТЕКСТ ЗАДАЧИ — НЕ
 *    ДОКАЗАТЕЛЬСТВО, ПРОВЕРЯЕТСЯ БАЗА.
 *
 * 2. Заход на сайт считался в js/sponsors-loader.js — там, где рисуются
 *    логотипы. В таблице page_views строка site_visit стояла на нуле, а
 *    её updated_at показывал 31 ИЮЛЯ: счётчик был мёртв три с половиной
 *    месяца.
 *
 * 3. Перенеся заход в js/script.js, я на час оставил старый зов «чтобы не
 *    потерять» — и замер сразу поймал: за ОДНУ загрузку главной счётчик
 *    вырос с 1 до 3. ДВА ОПРЕДЕЛЕНИЯ ОДНОГО ПОНЯТИЯ СЧИТАЮТ ДВАЖДЫ, А НЕ
 *    НАДЁЖНЕЕ. Отметка сеанса тут не спасает: оба зова уходят раньше, чем
 *    первый успевает ответить.
 */
const fs = require('fs');
const path = require('path');

const корень = path.resolve(__dirname, '..');
const без = т => т.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
const ошибки = [];

const дом = path.join(корень, 'js/kslt-prosmotry.js');
if (!fs.existsSync(дом)) {
    ошибки.push('js/kslt-prosmotry.js не найден — дом просмотров исчез');
} else {
    const т = без(fs.readFileSync(дом, 'utf8'));
    if (!/p_source\s*=\s*'site'|ИСТОЧНИК\s*=\s*'site'/.test(т))
        ошибки.push('дом просмотров не называет источник site');
    /* ЯКОРЬ ИЩЕТ ПРОВЕРКУ, А НЕ СЛОВО. Первая редакция искала просто
       `.error` и не упала, когда проверку выключили: в файле рядом живёт
       console.error, и его хватало, чтобы правило считало себя сытым.
       Нужна именно проверка ответа базы, и обе — в счёте и в заходе. */
    const проверок = (т.match(/if\s*\(\s*ответ\s*&&\s*ответ\.error\s*\)/g) || []).length;
    if (проверок < 2)
        ошибки.push(`дом просмотров проверяет ответ базы ${проверок} раз из двух (счёт и заход) — поломка снова проживёт месяцы`);
}

/* ГОЛЫХ ВЫЗОВОВ БЫТЬ НЕ ДОЛЖНО: источник задаётся в доме, а не на месте. */
const папка = path.join(корень, 'js');
const файлы = fs.readdirSync(папка).filter(ф => ф.endsWith('.js') && ф !== 'kslt-prosmotry.js');
for (const ф of файлы) {
    const т = без(fs.readFileSync(path.join(папка, ф), 'utf8'));
    /* ПРАВИЛО, ЦЕЛЯЩЕЕ ШИРЕ СВОЕГО ПРЕДМЕТА, ЛОВИТ НЕВИНОВНЫХ.
       Первая редакция ловила increment_\w*_view и обвинила три файла с
       increment_page_view — а это другой счётчик: он в базе в
       единственном числе, перегрузки у него нет, источник ему не нужен и
       он исправно работает. Предмет этого правила — шесть счётчиков
       ОБЪЕКТОВ, у которых две перегрузки; их и называем поимённо. */
    for (const м of т.matchAll(/\.rpc\(\s*'(increment_(?:court|coach|player|news|tournament|sponsor)_view)'/g)) {
        ошибки.push(`${ф}: голый вызов ${м[1]} мимо дома js/kslt-prosmotry.js`);
    }
}

/* ЗАХОД СЧИТАЕТСЯ РОВНО В ОДНОМ МЕСТЕ. */
const зовы = [];
for (const ф of файлы) {
    const т = без(fs.readFileSync(path.join(папка, ф), 'utf8'));
    const n = (т.match(/KSLT_PROSMOTRY\s*\.\s*заход\s*\(/g) || []).length;
    if (n) зовы.push(ф + (n > 1 ? ` ×${n}` : ''));
    for (const м of т.matchAll(/increment_page_view'\s*,\s*\{\s*p_page_name:\s*'(site_visit|app_visit)'/g)) {
        ошибки.push(`${ф}: заход '${м[1]}' считается напрямую, мимо дома`);
    }
}
if (зовы.length === 0) ошибки.push('заход на сайт не считается нигде — счётчик снова мёртв');
else if (зовы.length > 1) ошибки.push(`заход считается в ДВУХ местах (${зовы.join(', ')}) — счётчик вырастет вдвое за одну загрузку`);
else if (зовы[0] !== 'script.js') ошибки.push(`заход считается в ${зовы[0]}, а должен в script.js — он подключён на всех страницах`);

/* ДОМ ДОЛЖЕН БЫТЬ ПОДКЛЮЧЁН ВЕЗДЕ, ГДЕ ЕСТЬ ЕГО ЕДОКИ. */
const страницы = [
    ...fs.readdirSync(корень).filter(ф => ф.endsWith('.html')).map(ф => ф),
    ...fs.readdirSync(path.join(корень, 'pages')).filter(ф => ф.endsWith('.html')).map(ф => 'pages/' + ф),
];
const без_дома = страницы.filter(ф => {
    const т = fs.readFileSync(path.join(корень, ф), 'utf8');
    return /sponsors-loader\.js/.test(т) && !/kslt-prosmotry\.js/.test(т);
});
if (без_дома.length) {
    ошибки.push(`страниц без дома просмотров: ${без_дома.length} (${без_дома.slice(0, 3).join(', ')}…)`);
}

if (ошибки.length) {
    console.error('ПРОСМОТРЫ — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
console.log(`просмотры: дом один, голых вызовов 0, заход считается в ${зовы[0]}, дом подключён на ${страницы.length - без_дома.length} страницах`);
