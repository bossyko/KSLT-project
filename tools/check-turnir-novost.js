/**
 * ЗАМОРОЗКА ВКЛАДКИ «НОВОСТИ» ВНУТРИ ТУРНИРА.
 *
 * До 08.10 у этой вкладки не было НИ ОДНОГО правила и ни одной пробы —
 * при том что кусок «админка турнира» закрыт 04.10. Заморозка не видит
 * того, чего не назвали, и вкладка четыре дня жила без присмотра.
 *
 * ЧТО ЗАМОРАЖИВАЕТСЯ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • вкладка зовёт ТУ ЖЕ форму, что раздел «Новости», а не свою копию;
 *   • своих полей `adTrnNews*` у неё не осталось вовсе;
 *   • своего у неё ровно три: заготовка с победителями, «Фото с турнира»
 *     и «Рассылка в ТГ» — то, чего в разделе нет и быть не должно;
 *   • статья помнит свой турнир (`news.tournament_id`);
 *   • ОЧКИ НЕ ПИШУТСЯ В ТЕКСТ СТАТЬИ (слово Кости 08.10), но генератор
 *     по-прежнему ТОЛЬКО ЧИТАЕТ начисления — рейтинга он не касается;
 *   • состояние кнопки рассылки берётся из ПЕРЕЧИТАННОЙ статьи, а не из
 *     снимков формы в переменных: сторож, а не память;
 *   • стенд рисует настоящую панель, а не её пересказ.
 *
 *   node tools/check-turnir-novost.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const BRK = безКом(чит('js/admin/sections/bracket.js'));
const NJS = безКом(чит('js/admin/sections/news.js'));
const СТЕНД = чит('maket/stend-admin-turnir-novost.html');

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };

правило('вкладка зовёт ТУ ЖЕ форму, что раздел «Новости»',
    /A\.renderNewsForm\(статья, \{/.test(BRK) && /A\.renderNewsForm = renderNewsForm;/.test(NJS),
    'До 08.10 здесь жила обеднённая КОПИЯ формы: голая `textarea` вместо\n' +
    '          редактора, без обложки и предела подзаголовка. ДВА КОМПОНЕНТА\n' +
    '          НА ОДНО ПОНЯТИЕ РАСХОДЯТСЯ НА ВТОРОЙ ПРАВКЕ — и разошлись.');

правило('своих полей `adTrnNews*` у вкладки не осталось',
    !/adTrnNewsTitle|adTrnNewsContent|adTrnNewsExcerpt|adTrnNewsSave|adTrnNewsPublish/.test(BRK),
    'Четырнадцать полей с ДРУГИМИ именами для того же самого. Имя поля —\n' +
    '          это и есть шов, по которому расходятся две копии.');

правило('«Рассылка в ТГ» осталась своей — её в разделе нет',
    /adTrnNewsTg/.test(BRK) && !/adTrnNewsTg/.test(NJS),
    'Форма о рассылке не знает и знать не должна.');

правило('«Фото с турнира» осталось своим и дописывается в запись входом',
    /adTrnPhotoGrid/.test(BRK) && /своиПоля/.test(BRK) && /gallery: галерея/.test(BRK),
    'Галереи в разделе нет вовсе. Вход дописывает своё поле, а запись в\n' +
    '          базу — ОДНА: иначе сохранений станет два и они разойдутся.');

правило('статья помнит свой турнир',
    /tournament_id: newsFormOpts\.tournamentId \|\| null/.test(NJS) &&
    /tournamentId: tournament\.id/.test(BRK),
    'Связь `news.tournament_id` в схеме есть с рождения. Без неё статья,\n' +
    '          заведённая из турнира, турнира не помнит.');

правило('ОЧКИ НЕ ПИШУТСЯ В ТЕКСТ СТАТЬИ',
    !/points_earned \|\| 0\) \+ \(lang === 'en' \? ' pts'/.test(BRK) &&
    !/рейтинговых очков/.test(BRK),
    'Слово Кости 08.10: убрать распределённые и начисленные очки.\n' +
    '          Три призовых места и итоговая фраза.');

правило('но начисления генератор по-прежнему ТОЛЬКО ЧИТАЕТ',
    /points_earned/.test(BRK),
    'Рейтинга текст статьи не касается: `rating_history` и\n' +
    '          `player_categories` генератор не трогал и не трогает.\n' +
    '          Если это правило упало — снесли лишнее.');

правило('состояние кнопки рассылки — из перечитанной статьи, а не из памяти',
    /initNewsPanel\.перерисовать = function\(\)/.test(BRK) &&
    !/publishedSnapshot|sentSnapshot/.test(BRK),
    'Сторожили двумя снимками формы в переменных. Снимок — это память,\n' +
    '          а память расходится с базой. СТОРОЖ, А НЕ ПАМЯТЬ.');

правило('у вкладки нет своей шапки раздела',
    /безШапки: true/.test(BRK),
    'Она живёт внутри экрана турнира, у которого заголовок уже есть.');

правило('стенд рисует НАСТОЯЩУЮ панель, а не её пересказ',
    /A\.renderNewsPanel\(/.test(СТЕНД) && !/<input|<textarea/.test(СТЕНД.replace(/<input type="file"[^>]*>/g, '')),
    'Скопированный стенд остаётся зелёным после того, как админку\n' +
    '          поменяли, и доказывает только сам себя.');

правило('стенд зажигает `body` сам',
    /body \{ opacity: 1 !important; \}/.test(СТЕНД),
    '`style.css` гасит его в ноль и зажигает скриптом загрузки страницы,\n' +
    '          которого у стенда нет: замеры верные, а снимок чёрный.');

if (ошибки.length === 0) {
    console.log(`\n  ок      вкладка «Новости» турнира: ${ВСЕГО} правил\n`);
    process.exit(0);
}
console.log(`\n  НЕ ТАК  вкладка «Новости» турнира: ${ВСЕГО} правил, упало ${ошибки.length}.\n`);
ошибки.forEach(о => {
    console.log(`  ✗ ${о.имя}`);
    if (о.подсказка) console.log(`          ${о.подсказка}`);
});
console.log('');
process.exit(1);
