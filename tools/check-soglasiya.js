/* ФАЙЛЫ БАЗЫ ИЩУТСЯ ПО ВИДУ ИМЕНИ, А НЕ ПО ТОЧНОМУ. Дата в имени
   меняется при каждой пересборке куска, и сторож, прибитый к `07nov`,
   упал бы на следующей же. Поймано на правовых документах 07.11. */
function файлПапки(папка, вид) {
    const д = path.join(КОРЕНЬ, папка);
    if (!fs.existsSync(д)) return '';
    const имя = fs.readdirSync(д).filter(и => вид.test(и)).sort().pop();
    return имя ? fs.readFileSync(path.join(д, имя), 'utf8') : '';
}
const файлБазы = вид => файлПапки('sql/схема', вид);
const SQL_ЖУРНАЛ    = файлБазы(/^soglasiya-zhurnal-.*\.sql$/);
const SQL_ДАННЫЕ    = файлБазы(/^moi-dannye-.*\.sql$/);
const SQL_УМОЛЧАНИЕ = файлБазы(/^soglasie-umolchanie-.*\.sql$/);

/* ЧТО ОБЪЯВИЛ ДОМ — ЧИТАЕТСЯ ИЗ ТЕКСТА, А НЕ ИСПОЛНЯЕТСЯ. */
function список(файл, имя) {
    const м = безКом(чит(файл)).match(new RegExp('API\\.' + имя + '\\s*=\\s*\\[([^\\]]*)\\]'));
    if (!м) return null;
    return (м[1].match(/'([^']+)'|(\d+)/g) || []).map(с => с.replace(/'/g, ''));
}

/* СЕРВЕРНОЕ ПРАВИЛО — СОБИРАЕТСЯ ИЗ ЖИВОГО КОДА. Тело берётся по
   глубине скобок, а не регуляркой: регулярка на `}` ломается о первый же
   вложенный блок. */
const ПРАВИЛА_СЕРВЕРА = (function () {
    const д = path.join(КОРЕНЬ, 'supabase/functions');
    const найдено = [];
    if (!fs.existsSync(д)) return найдено;
    for (const ф of fs.readdirSync(д)) {
        const п = path.join(д, ф, 'index.ts');
        if (!fs.existsSync(п)) continue;
        const т = fs.readFileSync(п, 'utf8');
        const и = т.indexOf('function shouldNotify');
        if (и < 0) continue;
        let г = 0, к = т.indexOf('{', и);
        for (; к < т.length; к++) { if (т[к] === '{') г++; if (т[к] === '}') { г--; if (!г) break; } }
        найдено.push({ функция: ф, тело: т.slice(и, к + 1) });
    }
    return найдено;
})();
