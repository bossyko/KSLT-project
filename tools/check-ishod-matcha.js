#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ИСХОД МАТЧА — ОДНО ОПРЕДЕЛЕНИЕ» (03.11).
 *
 * ЦИФРА, С КОТОРОЙ ВСЁ НАЧАЛОСЬ. Замер базы 03.11: `W/O` выбран НОЛЬ
 * раз, `DEF` — НОЛЬ, `N/A` — ДВАДЦАТЬ СЕМЬ. Менеджер видел четыре
 * сокращения без единого слова о том, что они значат, не знал, что
 * такое `W/O`, и брал `N/A` как «что-то случилось». Из шестнадцати
 * рейтинговых `N/A` пятнадцать записаны ОДНИМ СЕТОМ ВСУХУЮ — то есть
 * это и были неявки.
 *
 * НЕПОНЯТНАЯ ПОДПИСЬ НЕ ПРОСТО НЕУДОБНА: ОНА МЕНЯЕТ ДАННЫЕ. Это главное,
 * что стережёт этот прибор, — не буквы, а то, что у каждой буквы есть
 * расшифровка и она доезжает до человека.
 *
 * ЧТО ЕЩЁ ЗАМОРОЖЕНО: список исходов стоял ЧЕТЫРЕЖДЫ, и ответ на вопрос
 * «идёт ли матч в зачёт» давался ДВАЖДЫ по-разному — таблица группы
 * неявку выкидывала, подсчёт побед для очков считал её наравне со всеми.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ. Прибор читает код: он не видит, понял ли менеджер
 * подсказку. Это покажет только новый замер базы — если `W/O` начнёт
 * появляться, а `N/A` перестанет.
 *
 *   node tools/check-ishod-matcha.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ДОМ = 'js/kslt-rules.js';
const ЗОВУЩИЕ = [
    'js/group-standings.js',
    'js/kslt-setka.js',
    'js/tournament-detail.js',
    'js/admin/sections/bracket.js'
];
const ОЧКИ = 'js/rating-points.js';

function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function безКом(т) {
    return (т || '').replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');
}

const дом = безКом(чит(ДОМ));
const очки = безКом(чит(ОЧКИ));

/** Свой список исходов — набор из тех же четырёх букв, записанный руками. */
function свойСписок(т) {
    return (безКом(т).match(/\[\s*'RET'\s*,\s*'W\/O'/g) || []).length;
}

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('список исходов объявлен ровно один раз — в доме',
    свойСписок(дом) === 1 &&
    ЗОВУЩИЕ.every(ф => свойСписок(чит(ф)) === 0),
    'Список исходов записан руками не только в доме. Он стоял ЧЕТЫРЕЖДЫ:\n' +
    'group-standings, kslt-setka, tournament-detail, bracket. Пятая копия\n' +
    'заводится на первой же задаче, и расходятся они молча: буквы у всех\n' +
    'одинаковые, а поведение у каждого своё.');

правило('у каждого исхода есть расшифровка словами',
    (function () {
        /* КУСОК РЕЖЕТСЯ ПО КОНЦУ СВОЕГО ОБЪЕКТА, А НЕ ПО ДЛИНЕ.
           Прувер поймал: при длине 700 кусок захватывал СЛЕДУЮЩИЙ исход,
           и пропажа расшифровки у одного пряталась за расшифровкой
           соседа — правило зеленело на беде. */
        const коды = ["''", "'RET'", "'W/O'", "'DEF'", "'NA'"];
        return коды.every(к => {
            const метка = (к === "''" ? "''" : к) + ': {';
            const и = дом.indexOf(метка);
            if (и === -1) return false;
            const конец = дом.indexOf('\n        }', и);
            const кусок = дом.slice(и, конец === -1 ? и + 700 : конец);
            const м = кусок.match(/что:\s*'([^']{30,})/);
            return !!м;
        });
    })(),
    'У исхода пропала расшифровка `что` или она короче тридцати знаков.\n' +
    'ЗАМЕР 03.11 ПОКАЗАЛ, ЧЕМ ЭТО КОНЧАЕТСЯ: без расшифровок `W/O` не\n' +
    'выбрали НИ РАЗУ, а `N/A` выбрали 27 раз, и пятнадцать из них были\n' +
    'неявками. Подпись без объяснения меняет данные.');

правило('подсказка доходит и до мыши, и до диктора',
    (function () {
        const б = безКом(чит('js/admin/sections/bracket.js'));
        return /title="'\s*\+\s*A\.esc\(и\.подпись\s*\+\s*' — '\s*\+\s*и\.что\)/.test(б) &&
               /aria-label="'\s*\+\s*A\.esc\(и\.подпись\s*\+\s*'\. '\s*\+\s*и\.что\)/.test(б);
    })(),
    'У чипа исхода пропал `title` или `aria-label`. Одного мало: `title`\n' +
    'не читает диктор, `aria-label` не показывает мышь. Менеджер бывает и\n' +
    'незрячим, и подсказка для него — единственный способ узнать разницу\n' +
    'между `W/O` и `RET`.');

правило('чипы строятся из дома, а не перечисляются руками',
    (function () {
        const б = безКом(чит('js/admin/sections/bracket.js'));
        return /исходыДляВвода\(\)/.test(б) &&
               (б.match(/data-outcome="RET"|data-outcome="W\/O"|data-outcome="DEF"/g) || []).length === 0;
    })(),
    'Кнопки исходов снова перечислены руками в разметке. Тогда новый\n' +
    'исход появится в одном месте и не появится в другом, а снятый\n' +
    'останется на кнопке — ровно так `N/A` и дожил до 27 записей.');

правило('N/A убран из ввода, но остался в разборе',
    (function () {
        const м = дом.match(/'NA':\s*\{[\s\S]{0,700}?\}/);
        return !!м && /предлагается:\s*false/.test(м[0]) &&
               /'NA'/.test(дом.match(/R\.ИСХОДЫ\s*=\s*\[[^\]]*\]/)[0]);
    })(),
    'Либо `N/A` вернулся в кнопки, либо его выкинули из списка разбора.\n' +
    'ВТОРОЕ ХУЖЕ: счёт хранится строкой «6/3 4/6 NA», разбор отделяет\n' +
    'последнее слово по списку. Нет `NA` в списке — у ДВАДЦАТИ СЕМИ\n' +
    'старых матчей буквы уедут в сеты и покажут мусор вместо счёта.\n' +
    'МЁРТВЫМ КОД НАЗЫВАЕТСЯ ПОСЛЕ ПРОВЕРКИ: проверка нашла 27 живых.');

правило('«идёт ли матч в зачёт» спрашивается у дома в обоих местах',
    /исходВЗачёт/.test(безКом(чит('js/group-standings.js'))) &&
    /исходВЗачёт/.test(очки),
    'Вопрос «считается ли этот матч» снова задаётся на месте. Он задавался\n' +
    'ДВАЖДЫ и получал РАЗНЫЕ ответы: таблица группы неявку выкидывала\n' +
    '(`group-standings`), а подсчёт побед для очков считал её наравне со\n' +
    'всеми (`rating-points`). Один матч считался и не считался разом.');

правило('дом правил спрашивается лениво, а не при загрузке',
    (function () {
        return ЗОВУЩИЕ.concat([ОЧКИ]).every(ф => {
            const т = безКом(чит(ф));
            /* Зов на уровне модуля — присваивание переменной при загрузке. */
            /* ИМЯ ПЕРЕМЕННОЙ БЫВАЕТ КИРИЛЛИЧЕСКИМ, А `\w` — ЭТО ЛАТИНИЦА.
               Второй раз за два дня: `\b` не сработал с кириллицей на
               правиле пароля. ПРИБОР, НАПИСАННЫЙ ЛАТИНИЦЕЙ, НЕ ВИДИТ
               КОДА, НАПИСАННОГО КИРИЛЛИЦЕЙ. */
            /* ЛОВИМ ИМЕННО СПИСОК ИСХОДОВ, А НЕ ЛЮБОЙ ЗОВ ДОМА.
               Первая редакция падала на законных строках вида
               `var а = window.KSLT_RULES.ntrpДопуска(…)` ВНУТРИ функций —
               а они ленивы по определению. ПРИБОР, КРИЧАЩИЙ ВОЛКАМИ,
               СНИМАЮТ ЦЕЛИКОМ: сужено до того, ради чего заведён. */
            return !/\bvar\s+[\wА-Яа-яЁё]+\s*=\s*(?:window|global)\.KSLT_RULES\.ИСХОДЫ\s*;/.test(т);
        });
    })(),
    'Дом спрашивается при загрузке файла. В приложении\n' +
    '`js/group-standings.js` подключён РАНЬШЕ дома, и такой зов падает.\n' +
    'ПОРЯДОК ПОДКЛЮЧЕНИЯ — ХРУПКАЯ ОПОРА: он держится на строке в html,\n' +
    'которую двигают, не думая о зависимостях.');

правило('подсчёт очков не падает без дома',
    /var П = КСЛТ_ПРАВИЛА\(\);\s*\n\s*if \(П && /.test(очки),
    'Подсчёт побед зовёт дом без проверки. Файл подключают на страницах,\n' +
    'где дома может не быть, и тогда вместо прежнего поведения выйдет\n' +
    'падение. Нет дома — считаем как раньше, все матчи в зачёт.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    const кодов = (дом.match(/^\s*'(?:|RET|W\/O|DEF|NA)':\s*\{/gm) || []).length;
    console.log('  ок      исход матча: все ' + всего + ' правил держатся');
    console.log('          список один, исходов ' + кодов + ', у каждого расшифровка');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  исход матча — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
