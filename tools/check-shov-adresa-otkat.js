/**
 * ДОКАЗАТЕЛЬСТВО СТОРОЖА ШВА ОТКАТОМ.
 *
 * Каждое правило check-shov-adresa.js проверяем обратным ходом — возвращаем
 * прежнее значение, и ИМЕННО ТО правило обязано упасть. Работаем на КОПИИ.
 *
 * ЯКОРЬ ДЕРЖИТСЯ НА СОДЕРЖИМОМ И ОБЯЗАН БЫТЬ ЕДИНСТВЕННЫМ НЕ ТОЛЬКО ПО
 * ТЕКСТУ, НО И ПО СМЫСЛУ: вторая копия той же строки держит правило вместо
 * испорченной. Поймано прувером 09.10 на голосах вызова.
 *
 *   node tools/check-shov-adresa-otkat.js
 */
const fs = require('fs');
const path = require('path');
const os = require('os');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const ВРЕМ = fs.mkdtempSync(path.join(os.tmpdir(), 'kslt-shov-'));
['js', 'tools', 'sql'].forEach(д =>
    fs.cpSync(path.join(КОРЕНЬ, д), path.join(ВРЕМ, д), { recursive: true }));

const JS_ = 'js/bracket-draw.js';
const СН  = 'sql/схема/schema-snapshot.sql';

const ОТКАТЫ = [

  /* СНИМКА НЕТ ВОВСЕ — сторожить нечем, и правило обязано это сказать. */
  /* БЛОКА НЕТ ВОВСЕ. Первая редакция переименовывала заголовок в
     `fic_адрес_снят` — и правило устояло: регулярка ищет `fic_адрес` и
     находила его как начало нового имени. Прувер поймал. */
  [СН, `-- --- fic_адрес(`, `-- --- adres_snyat(`,
   'тело `fic_адрес` есть в снимке схемы'],

  /* ФОРМУЛУ В БАЗЕ ПОПРАВИЛИ, А В САЙТЕ НЕТ. */
  [СН, `--     b := ceil(p_номер::numeric / S)::int;`,
       `--     b := floor(p_номер::numeric / S)::int;`,
   'формула базы не менялась в одиночку'],

  /* ТО ЖЕ С ДРУГОЙ СТОРОНЫ ШВА. */
  /* ТЕКСТ ДРУГОЙ, СЧЁТ ТОТ ЖЕ. Первая редакция меняла ceil на floor — и
     падали ДВА правила сразу: и о тексте, и о совпадении с базой.
     Доказательство, которое валит два правила, не доказывает ни одного. */
  [JS_, `        var b = Math.ceil(номер / S);`,
        `        var b = Math.ceil((номер) / S);`,
   'формула сайта не менялась в одиночку'],

  /* ВОЗВРАЩАЕМ ДЫРКУ: на последнем круге формула снова отдаёт дробь. */
  [JS_, `        if (S < 2) return null;`,
        `        if (S < 1) return null;`,
   'адрес никогда не дробный'],

  /* АДРЕС ПЛЕЙ-ОФФА УЕХАЛ ОТ БАЗЫ. Правим множитель победителя: формулы
     сайта и базы при этом расходятся И по тексту, но правило о тексте
     сторожит ТРИ строки, а ломаем мы четвёртую — ту, что считает. */
  [JS_, `        return (победил ? (2 * b - 2) : (2 * b - 1)) * (S / 2) + Math.ceil(p / 2);`,
        `        return (победил ? (2 * b - 2) : (2 * b - 1)) * (S / 2) + Math.ceil(p / 2) + (круг === 1 ? 1 : 0);`,
   'в плей-оффе адрес сайта равен адресу базы'],

  /* ТРИГГЕР ПЕРЕСТАЛ ОСТАНАВЛИВАТЬСЯ НА ПОСЛЕДНЕМ КРУГЕ. */
  [СН, `--         IF m.round_number >= v_кругов THEN`,
       `--         IF false THEN`,
   'триггер не идёт дальше последнего круга'],
];

let упало = 0;
ОТКАТЫ.forEach(([файл, было, стало, правило], i) => {
    const путь = path.join(ВРЕМ, файл);
    const цел = fs.readFileSync(путь, 'utf8');
    const сколько = цел.split(было).length - 1;
    if (сколько !== 1) {
        console.log(`  ✗ ${i + 1}  якорь встречается ${сколько} раз: ${правило}`);
        упало++;
        return;
    }
    fs.writeFileSync(путь, цел.replace(было, стало));
    let вывод = '';
    try {
        вывод = execFileSync('node', [path.join(ВРЕМ, 'tools/check-shov-adresa.js')], { encoding: 'utf8' });
    } catch (e) { вывод = (e.stdout || '') + (e.stderr || ''); }
    fs.writeFileSync(путь, цел);

    const своё = вывод.includes(`✗ ${правило}`);
    const сколькоУпало = (вывод.match(/^  ✗ /gm) || []).length;
    if (своё && сколькоУпало === 1) {
        console.log(`  ок  ${i + 1}  ${правило}`);
    } else {
        console.log(`  ✗ ${i + 1}  ${правило} — упало ${сколькоУпало}, своё: ${своё}`);
        упало++;
    }
});

fs.rmSync(ВРЕМ, { recursive: true, force: true });
if (упало === 0) {
    console.log(`\n  ок      все ${ОТКАТЫ.length} откатов доказали свои правила`);
    console.log('          оригиналы не изменялись — работа шла на копии\n');
    process.exit(0);
}
console.log(`\n  НЕ ТАК  откатов ${ОТКАТЫ.length}, не доказали ${упало}\n`);
process.exit(1);
