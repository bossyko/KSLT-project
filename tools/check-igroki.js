/**
 * ЗАМОРОЗКА РАЗДЕЛА «ДАВАЙ СЫГРАЕМ» `#players` НА ГЛАВНОЙ.
 *
 * Решения Кости 24.09, доска 406:9 и три снимка вечером:
 *   пять карточек на широком; подпись стала подзаголовком, а не частью
 *   заголовка; карточки одного размера с кортами и тренерами;
 *   И ГЛАВНОЕ — ТОЛЬКО ЦЕЛЫЕ РЯДЫ: ряд с дырой на месте недостающей
 *   карточки читается как поломка, а не как «игроков пока мало».
 *
 * ГЛАВНОЕ ЗДЕСЬ — ОТНОШЕНИЯ И ЕДИНСТВЕННОСТЬ, а не числа:
 *   • потолок каждого вида КРАТЕН числу его колонок;
 *   • хвост считается ОТ КОНЦА — правило не знает, сколько игроков в базе;
 *   • слой хвоста НЕ ПЕРЕСЕКАЕТСЯ с соседними: правила с двумя
 *     псевдоклассами перебьют любой «возврат в поток» из соседнего слоя;
 *   • у понятия одно определение: размеры карточки живут в style.css,
 *     partners.css отвечает только за свою страницу;
 *   • метка NTRP не лежит на портрете ни на одном виде;
 *   • кружок с фотографией и кружок с инициалами ведут себя одинаково.
 *
 *   node tools/check-igroki.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СТИ = безКом(чит('css/style.css'));
const ПАР = безКом(чит('css/partners.css'));
const ДЖС = безКом(чит('js/home-partners.js'));
const ГЛАВНАЯ = чит('index.html');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

function блок(текст, сел, маркер) {
    const рег = new RegExp('(?:^|\\n)[ \\t]*' + сел.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{[^}]*\\}', 'g');
    let м;
    while ((м = рег.exec(текст)) !== null) {
        if (!маркер || м[0].indexOf(маркер) !== -1) return м[0];
    }
    return null;
}
const свойство = (т, имя) => {
    if (!т) return null;
    const м = т.match(new RegExp('(?:^|\\n|\\{)\\s*' + имя + ':\\s*([^;]+);'));
    return м ? м[1].trim() : null;
};
const сколько = (текст, рег) => (текст.match(рег) || []).length;

/* Слой @media целиком, со счётом скобок: вложенные правила регуляркой не
   огораживаются, и «слой» без счёта утекал до конца файла. */
function слои(текст) {
    const вых = [];
    const рег = /@media[^{]*\{/g;
    let м;
    while ((м = рег.exec(текст)) !== null) {
        let i = рег.lastIndex, d = 1;
        while (d && i < текст.length) { if (текст[i] === '{') d++; else if (текст[i] === '}') d--; i++; }
        вых.push(текст.slice(м.index, i));
    }
    return вых;
}
const ВСЕ_СЛОИ = слои(текст_стилей());
function текст_стилей() { return СТИ; }
function слой(текст, маркер) {
    const список = текст === СТИ ? ВСЕ_СЛОИ : слои(текст);
    for (const с of список) if (с.indexOf(маркер) !== -1) return с;
    return null;
}

