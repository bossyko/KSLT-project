/**
 * ДОКАЗАТЕЛЬСТВО СТОРОЖА ИНЛАЙН-СТИЛЕЙ. На КОПИИ.
 *
 * Каждый откат возвращает ровно то, от чего правило бережёт, — и требует,
 * чтобы упало ИМЕННО оно. Якоря держатся на содержимом файла-цели, а не
 * на положении строки.
 *
 *   node tools/check-inlayn-stili-otkat.js
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const песок = fs.mkdtempSync(path.join(os.tmpdir(), 'kslt-inlayn-'));
['js', 'tools'].forEach(д => fs.cpSync(path.join(КОРЕНЬ, д), path.join(песок, д), { recursive: true }));

const ЦЕЛЬ = 'js/tournament-detail.js';
const чистый = fs.readFileSync(path.join(КОРЕНЬ, ЦЕЛЬ), 'utf8');

/* ВТОРАЯ ЦЕЛЬ — ФАЙЛ АДМИНКИ. Правило о дереве тегов считает ТОЛЬКО
   `js/admin`, и откат, положенный в `tournament-detail.js`, его не
   тронет: прувер показывал бы зелёное, ничего не доказав. */
const ЦЕЛЬ_АД = 'js/admin/sections/tournaments.js';
const чистыйАд = fs.readFileSync(path.join(КОРЕНЬ, ЦЕЛЬ_АД), 'utf8');

/* ТРЕТЬЯ ЦЕЛЬ — ВЫЧИЩЕННЫЙ ФАЙЛ (кусок 175). Пятое правило сторожа
   проснулось: `bracket.js` вычищен от инлайнов целиком, и вернувшийся
   инлайн с краской должен ронять правило СРАЗУ, а не через потолок.
   Откат, положенный в другой файл, этого не докажет. */
const ЦЕЛЬ_ЧИСТ = 'js/admin/sections/bracket.js';
const чистыйЧист = fs.readFileSync(path.join(КОРЕНЬ, ЦЕЛЬ_ЧИСТ), 'utf8');

function прогон(текст, текстАд, текстЧист) {
    fs.writeFileSync(path.join(песок, ЦЕЛЬ_АД), текстАд ? текстАд : чистыйАд);
    fs.writeFileSync(path.join(песок, ЦЕЛЬ_ЧИСТ), текстЧист ? текстЧист : чистыйЧист);
    fs.writeFileSync(path.join(песок, ЦЕЛЬ), текст === null ? чистый : текст);
    try {
        execFileSync(process.execPath, [path.join(песок, 'tools', 'check-inlayn-stili.js')], { encoding: 'utf8' });
        return { упало: false, вывод: '' };
    } catch (e) { return { упало: true, вывод: (e.stdout || '') + (e.stderr || '') }; }
}

/* ЯКОРЬ — ОБЪЯВЛЕНИЕ ФУНКЦИИ, живущее в файле постоянно, а не строка
   разметки: разметка переписывается кругами 2 и 3 ветки C, и откат,
   прибитый к ней, перестанет находить своё место молча. Проверяем, что
   якорь встречается РОВНО один раз: подменять наугад нельзя. */
const ЯКОРЬ = 'function renderRegistrationButton(';
const разЯкорь = чистый.split(ЯКОРЬ).length - 1;
const естьЯкорь = разЯкорь === 1;
/* ПОРЧА кладётся строкой js перед телом функции — прибор читает текст
   файла, и ему всё равно, исполнится эта строка или нет. */
/* ОБРАМЛЯЕМ ОДИНАРНЫМИ, а не через JSON.stringify: тот экранирует
   двойные кавычки, и `style=\"...\"` перестаёт быть инлайном для
   прибора — три отката из четырёх молчали именно поэтому. */
const порча = код => т => т.replace(ЯКОРЬ, "var _порча = '" + код + "';\n" + ЯКОРЬ);

const ОТКАТЫ = [
    ['завести лишний инлайн с голой краской — потолок',
     порча('<i style="color:#ff3b30"></i>'),
     'инлайнов с голой краской не больше потолка'],

    ['завести лишний отступ мимо шкалы — потолок',
     порча('<i style="padding:7px"></i>'),
     'инлайнов с числом мимо шкалы отступов не больше потолка'],

    ['завести НОВОЕ написание краски — закрытый список',
     /* ЯКОРЬ ПЕРЕСТАВЛЕН 16.10: держался за `style="color:#ff3b30` —
        строку, которую круг 2 как раз и снял. Откат, прибитый к тому,
        что мы сами чистим, перестаёт находить своё место молча. */
     порча('<i style="color:#e81123"></i>'),
     'новых написаний краски в инлайнах не завелось'],

    ['поставить ВТОРОЙ атрибут class в тег, где он уже есть',
     порча('<i class="td-gt-num" class="td-gt-name"></i>'),
     'двух атрибутов class в одном теге не завелось'],

    ['развести роль ещё одним написанием — храповик по ролям',
     порча('<i style="color:#ff5a4f"></i>'),
     'написаний краски в каждой роли не больше замеренного'],
];

/* ОТКАТЫ НА ДЕРЕВО ТЕГОВ. Правят ФАЙЛ АДМИНКИ: правило смотрит только
   `js/admin`, и откат в `tournament-detail.js` его не тронул бы. Якорь —
   объявление функции, живущее в файле постоянно; счётом проверено, что
   встречается один раз. */
const ЯКОРЬ_АД = 'async function renderTournamentsSection()';
const разЯкорьАд = чистыйАд.split(ЯКОРЬ_АД).length - 1;
const порчаАд = код => т => т.replace(ЯКОРЬ_АД, "var _порча = '" + код + "';\n    " + ЯКОРЬ_АД);
const ОТКАТЫ_АД = [
    ['добавить в разметку админки лишний тег — дерево поехало вверх',
     порчаАд('<span>лишний</span>'),
     'дерево тегов админки не поехало вслед за инлайнам'],

    ['вернуть снятый инлайн в админку — храповик круга 9',
     порчаАд('<i style="display:none"></i>'),
     'инлайнов в админке не больше потолка'],

    ['потерять тег при правке строки — дерево поехало вниз',
     т => т.replace("'<div class=\"ad-field-row ad-field-row-4\">' +", "'' +"),
     'дерево тегов админки не поехало вслед за инлайнам'],
];

/* ── ОТКАТЫ ПО ВЫЧИЩЕННОМУ ФАЙЛУ (кусок 175) ────────────────────────
   Пятое правило сторожа проснулось: `bracket.js` вычищен от инлайнов
   целиком. Откат в другом файле этого не докажет — правило смотрит
   ИМЕННО список вычищенных. ЯКОРЬ — объявление функции окна счёта: оно
   живёт постоянно, а разметку кусок 175 как раз и переписал. */
const ЯКОРЬ_ЧИСТ = '    function openScoreModal(';
const разЯкорьЧист = чистыйЧист.split(ЯКОРЬ_ЧИСТ).length - 1;
const порчаЧист = код => т => т.replace(ЯКОРЬ_ЧИСТ,
    "    var _порча = '" + код + "';\n" + ЯКОРЬ_ЧИСТ);
const ОТКАТЫ_ЧИСТ = [
    ['вернуть инлайн с краской в вычищенный файл — пятое правило',
     порчаЧист('<i style="color:#aaa"></i>'),
     'вычищенные файлы остались чистыми'],

    ['вернуть инлайн с отступом мимо шкалы в вычищенный файл',
     порчаЧист('<i style="padding:10px"></i>'),
     'вычищенные файлы остались чистыми'],
];

console.log('');
if (!естьЯкорь) {
    console.log('  БЕДА    якорь «' + ЯКОРЬ + '» встречается ' + разЯкорь +
                ' раз в ' + ЦЕЛЬ + ' — откаты бессмысленны\n');
    fs.rmSync(песок, { recursive: true, force: true });
    process.exitCode = 1;
} else if (прогон(null).упало) {
    console.log('  БЕДА    исходный код правила НЕ проходит — откаты бессмысленны\n');
    fs.rmSync(песок, { recursive: true, force: true });
    process.exitCode = 1;
} else {
    console.log('  база    исходный код правила проходит\n');
    let плохих = 0;
    ОТКАТЫ.forEach(([имя, порча, ждём]) => {
        const испорчен = порча(чистый);
        if (испорчен === чистый) {
            console.log('  ? ' + имя + '  ->  якорь не сработал, откат не сделан'); плохих++;
            return;
        }
        const р = прогон(испорчен);
        прогон(null);
        if (!р.упало) { console.log('  ✗ ' + имя + '  ->  правило НЕ упало'); плохих++; }
        else if (р.вывод.indexOf(ждём) === -1) {
            console.log('  ~ ' + имя + '  ->  упало ДРУГОЕ. Ждали: ' + ждём); плохих++;
        } else console.log('  v ' + имя + '  ->  «' + ждём + '»');
    });
    if (разЯкорьАд !== 1) {
        console.log('  БЕДА    якорь «' + ЯКОРЬ_АД + '» встречается ' + разЯкорьАд +
                    ' раз в ' + ЦЕЛЬ_АД + ' — откаты дерева тегов бессмысленны');
        плохих += ОТКАТЫ_АД.length;
    } else ОТКАТЫ_АД.forEach(([имя, порча, ждём]) => {
        const испорчен = порча(чистыйАд);
        if (испорчен === чистыйАд) {
            console.log('  ? ' + имя + '  ->  якорь не сработал, откат не сделан'); плохих++;
            return;
        }
        const р = прогон(null, испорчен);
        прогон(null, null);
        if (!р.упало) { console.log('  ✗ ' + имя + '  ->  правило НЕ упало'); плохих++; }
        else if (р.вывод.indexOf(ждём) === -1) {
            console.log('  ~ ' + имя + '  ->  упало ДРУГОЕ. Ждали: ' + ждём); плохих++;
        } else console.log('  v ' + имя + '  ->  «' + ждём + '»');
    });
    if (разЯкорьЧист !== 1) {
        console.log('  БЕДА    якорь «' + ЯКОРЬ_ЧИСТ.trim() + '» встречается ' + разЯкорьЧист +
                    ' раз в ' + ЦЕЛЬ_ЧИСТ + ' — откаты вычищенного файла бессмысленны');
        плохих += ОТКАТЫ_ЧИСТ.length;
    } else ОТКАТЫ_ЧИСТ.forEach(([имя, порча, ждём]) => {
        const испорчен = порча(чистыйЧист);
        if (испорчен === чистыйЧист) {
            console.log('  ? ' + имя + '  ->  якорь не сработал, откат не сделан'); плохих++;
            return;
        }
        const р = прогон(null, null, испорчен);
        прогон(null, null, null);
        if (!р.упало) { console.log('  ✗ ' + имя + '  ->  правило НЕ упало'); плохих++; }
        else if (р.вывод.indexOf(ждём) === -1) {
            console.log('  ~ ' + имя + '  ->  упало ДРУГОЕ. Ждали: ' + ждём); плохих++;
        } else console.log('  v ' + имя + '  ->  «' + ждём + '»');
    });
    fs.rmSync(песок, { recursive: true, force: true });
    console.log('');
    const ВСЕГО_ОТКАТОВ = ОТКАТЫ.length + ОТКАТЫ_АД.length + ОТКАТЫ_ЧИСТ.length;
    if (плохих === 0) {
        console.log('  ок      все ' + ВСЕГО_ОТКАТОВ + ' откатов доказали свои правила');
        console.log('          оригиналы не трогались — работа шла на копии\n');
    } else {
        console.log('  НЕ ТАК  ' + плохих + ' из ' + ВСЕГО_ОТКАТОВ + ' откатов не доказали правило\n');
        process.exitCode = 1;
    }
}
