/**
 * ЗАМОРОЗКА ЦИФР ОБЛОЖКИ РАЗДЕЛА ТУРНИРОВ.
 *
 * Обложку с цифрами несут ТРИ экрана: обзорная «Турниры», страница разряда
 * и страница турнира, — плюс баттлы и лендинг теми же классами. Правит их
 * `css/style.css` (общий стандарт), `css/tournaments.css` (разряд) и
 * `css/tournaments-overview.css` (обзорная), а наполняют два файла js.
 *
 * ЧТО ЗАМОРАЖИВАЕТСЯ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • ноль УБИРАЕТ показатель из дерева, а не прячет его видом: колонки
 *     сетки считает селектор по ДЕТЯМ, и спрятанный слот он всё равно
 *     считает;
 *   • пара показателей стоит по центру обложки, а не по её половинам;
 *   • зазор пары и зазор «заголовок → цифры» берутся со шкалы;
 *   • заголовок и цифры — ОДНА группа, а не два края;
 *   • лендинг под правило пары не попадает.
 *
 *   node tools/check-cifry-oblozhki.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СТИЛЬ = безКом(чит('css/style.css'));
const ТУРН  = безКом(чит('css/tournaments.css'));
const ОБЗОР = безКом(чит('css/tournaments-overview.css'));
const JSРАЗ = безКом(чит('js/tournaments-overlay.js'));
const JSОБЗ = безКом(чит('js/tournaments-overview.js'));
const ЛЕНД  = чит('index.html');

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };

/* Окно правила — свой блок, а не весь файл */
const блок = (текст, якорь) => {
    const i = текст.indexOf(якорь);
    if (i === -1) return '';
    let j = текст.indexOf('{', i), г = 0, с = j;
    for (; j < текст.length; j++) {
        if (текст[j] === '{') г++;
        else if (текст[j] === '}') { г--; if (г === 0) return текст.slice(с + 1, j); }
    }
    return '';
};

/* ══ 1. НОЛЬ УБИРАЕТ, А НЕ ПРЯЧЕТ ══════════════════════════════════════ */

правило('на странице разряда нулевой показатель УБИРАЕТСЯ из дерева',
    /ячейка\.remove\(\);/.test(JSРАЗ),
    'Колонки сетки считает `:has(> :nth-child(N):last-child)` — он смотрит\n' +
    '          на ДЕТЕЙ, а не на видимых. Спрятанный видом слот остаётся в счёте:\n' +
    '          три дорожки под два числа, и пара садится в первые две.');

правило('на обзорной нулевой показатель УБИРАЕТСЯ из дерева',
    /ячейка\.remove\(\);/.test(JSОБЗ),
    'Та же беда на обзорной: четыре дорожки под три числа, и группа уезжает\n' +
    '          влево на 44 пикселя при экране 390.');

правило('ни один из двух файлов больше не прячет показатель видом',
    !/ячейка\.style\.display\s*=\s*'none'/.test(JSРАЗ) &&
    !/ячейка\.style\.display\s*=\s*'none'/.test(JSОБЗ),
    'Если вернётся `display: none`, слот снова останется в дереве — и счёт\n' +
    '          колонок снова соврёт, а правило `remove` рядом будет зелёным.');

правило('счёт колонок по-прежнему идёт ПО ДЕТЯМ — иначе убирать нечего',
    /\.tournament-hero \.tournament-hero-stats:has\(> :nth-child\(3\):last-child\)/.test(СТИЛЬ) &&
    /\.to-hero \.tournament-hero-stats:has\(> :nth-child\(4\):last-child\)/.test(СТИЛЬ),
    'Правило «убрать из дерева» существует ради этого счёта. Если счёт\n' +
    '          уйдёт, останется уборка без причины — и наоборот.');

/* ══ 2. ПАРА СТОИТ ПО ЦЕНТРУ ═══════════════════════════════════════════ */

const ПАРА = блок(СТИЛЬ, '.bo-hero .bo-hero-stats:has(> :nth-child(2):last-child)');

правило('у пары показателей есть своё правило',
    ПАРА !== '',
    'Без него работает база `1fr 1fr`: два числа разводятся к краям обложки,\n' +
    '          на 667 между ними встаёт 212 пикселей.');

правило('дорожки пары — ПО СОДЕРЖИМОМУ, а не равными долями',
    /grid-template-columns:\s*repeat\(2,\s*auto\)/.test(ПАРА),
    'Равные дорожки делят обложку пополам: числа разной ширины встают\n' +
    '          каждое в центр своей половины, и центр пары мажет мимо центра\n' +
    '          обложки на 12 пикселей при любой ширине.');

правило('пара выравнивается по центру обложки',
    /justify-content:\s*center/.test(ПАРА),
    'Дорожки по содержимому без выравнивания прижмутся к левому краю.');

правило('зазор пары — ступень шкалы, а не число',
    /column-gap:\s*var\(--space-/.test(ПАРА) && !/column-gap:\s*\d/.test(ПАРА),
    'Число мимо шкалы отступов (8 · 12 · 16 · 24 · 32 · 40) заводит\n' +
    '          шестую ступень, которой нет ни в одной мере сайта.');

правило('лендинг под правило пары не попадает — показателей у него не два',
    (ЛЕНД.match(/<div class="stat">/g) || []).length !== 2,
    'Правило пары ловит второго ребёнка, который ПОСЛЕДНИЙ. Пока у лендинга\n' +
    '          пять показателей, оно его не видит. Если их станет два, лендинг\n' +
    '          поедет — а он принят Костей и не правится без его слова.');

/* ══ 3. ЗАГОЛОВОК И ЦИФРЫ — ОДНА ГРУППА ════════════════════════════════ */

const РАЗРЯД768 = блок(ТУРН, '@media (max-width: 768px)');
const ОБЗОР640 = блок(ОБЗОР, '@media (max-width: 640px)');

правило('на странице разряда заголовок и цифры собраны в одну группу',
    /\.tournament-hero-content\s*\{[^}]*justify-content:\s*center/.test(РАЗРЯД768),
    '`space-between` разводит их по краям обложки: при поле 275 между\n' +
    '          названием и числами встаёт 175 пикселей пустоты, при 360 — 240.');

правило('на обзорной заголовок, подпись и цифры собраны так же',
    /\.to-hero-content\s*\{[^}]*justify-content:\s*center/.test(ОБЗОР640),
    'Правило выведено на странице разряда и применяется к обзорной без\n' +
    '          нового разбора: на 390 между названием и числами стояло 167.');

правило('ни на одном из двух экранов не вернулся развод по краям',
    !/\.tournament-hero-content\s*\{[^}]*justify-content:\s*space-between/.test(РАЗРЯД768) &&
    !/\.to-hero-content\s*\{[^}]*justify-content:\s*space-between/.test(ОБЗОР640),
    'Правило центра и правило краёв могут лежать в файле ОБА и не\n' +
    '          пересекаться: решит то, что ниже. Сторож смотрит на оба.');

правило('зазор «заголовок → цифры» — ступень шкалы, а не число',
    /\.trn-hero-sub:empty \+ \.tournament-hero-stats\s*\{\s*margin-top:\s*var\(--space-/.test(РАЗРЯД768),
    'Было 22 — ступени, которой нет на шкале. Со ступенью 24 зазор выходит\n' +
    '          40 вместе с отбивкой заголовка — тот же, что на десктопе.');

правило('пол обложки раздела не тронут — он держит одну высоту у шести разрядов',
    /min-height:\s*var\(--oblozhka-pol\)/.test(ТУРН),
    'Хвост под цифрами — следствие пола. Убрать его, понизив пол, значит\n' +
    '          развести высоты шести разрядов: при переходе обложка запрыгает.');

if (ошибки.length === 0) {
    console.log(`\n  ок      цифры обложки: ${ВСЕГО} правил\n`);
    process.exit(0);
}
console.log(`\n  НЕ ТАК  цифры обложки: ${ВСЕГО} правил, упало ${ошибки.length}.\n`);
ошибки.forEach(о => {
    console.log(`  ✗ ${о.имя}`);
    if (о.подсказка) console.log(`          ${о.подсказка}`);
    console.log('');
});
process.exit(1);
