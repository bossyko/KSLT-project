/**
 * ЗАМОРОЗКА КУСКА 147 — ПО ЯЗЫКАМ, А НЕ ВПЕРЕМЕШКУ.
 *
 * СЛОВО КОСТИ: «англ надо будет заменить на кырг и сделать согласно
 * языкам, а не вперемешку».
 *
 * ЗАМЕР. Вперемешку было ДВУМЯ способами, и первый не виден в текстах:
 *   · ЛОКАЛЬ. Одиннадцать мест спрашивали `ky-KG` у браузера, а её там
 *     НЕТ: `supportedLocalesOf(['ky-KG','ky'])` отдаёт пусто, локаль
 *     разрешается в `en-US`. Кыргызская страница печатала английские
 *     месяцы, английский порядок даты и английский разделитель чисел.
 *     Понятие сведено в дом языка: `KSLT_YAZYK.локаль` — одна строка,
 *     кыргызскому даётся РУССКАЯ раскладка (замер куска 138: сокращения
 *     месяцев и порядок даты в кыргызском те же, что в русском).
 *   · ТЕКСТЫ. Прибор `tools/razovye/147-kg-po-angliyski.js` сравнил
 *     кыргызскую ветвь каждого зова `выбрать` с английской: нашлось ДЕСЯТЬ
 *     ключей, где кыргызу давали английское. Девять — имена собственные
 *     (Telegram, Email, Instagram, NTRP, FAQ, KSLT), они законны и
 *     названы здесь поимённо. Десятый был настоящей бедой: `live: 'Live'`
 *     в расписании турнира, пока русскому стояло «Идёт». Слово взято У
 *     ДОМА СТАТУСОВ, а не придумано.
 *
 * ПОПУТНО СНЕСЕНО МЁРТВОЕ, И ЭТО ВАЖНЕЕ, ЧЕМ ЕГО МЁРТВОСТЬ: в
 * `tournament-detail.js` лежали две ни разу не зовомые функции, а внутри
 * них — ВТОРАЯ И ТРЕТЬЯ карты подписей статуса турнира, по-русски и с
 * ключом `live`, которого у понятия нет (в доме он `ongoing`).
 *
 *   node tools/check-yazyk-bez-peremeshki.js
 */
const fs = require('fs');
const path = require('path');
const acorn = require('acorn');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
let правил = 0;
const правило = (имя, держится, почему) => { правил++; if (!держится) ошибки.push([имя, почему]); };

/* ЗАМЕРЕНО 23.10, прибором, а не вспомнено. */
const ПОТРЕБИТЕЛЕЙ_ЛОКАЛИ = 11;
const ИМЁН_СОБСТВЕННЫХ = 9;   /* Telegram, Email, Instagram ×2, NTRP, FAQ, KSLT… */

function обойти(у, дело, род) {
    if (!у || typeof у.type !== 'string') return;
    дело(у, род);
    for (const к of Object.keys(у)) {
        if (к === 'type' || к === 'start' || к === 'end' || к === 'loc') continue;
        const v = у[к];
        if (Array.isArray(v)) v.forEach(x => x && typeof x.type === 'string' && обойти(x, дело, у));
        else if (v && typeof v.type === 'string') обойти(v, дело, у);
    }
}
const дерево = т => acorn.parse(т, { ecmaVersion: 2020, locations: true });

const файлы = [];
(function о(д) {
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = path.join(д, э.name);
        if (э.isDirectory()) { if (!/node_modules/.test(э.name)) о(п); return; }
        if (э.name.endsWith('.js')) файлы.push(п);
    });
})('js');

/* ---- 1. локаль объявлена в доме языка один раз ---- */
const ДОМ = чит('js/kslt-yazyk.js');
let локальВДоме = 0;
обойти(дерево(ДОМ), (у, род) => {
    if (у.type === 'AssignmentExpression' &&
        ДОМ.slice(у.left.start, у.left.end) === 'Я.локаль') локальВДоме++;
});
правило('локаль страницы объявлена в доме языка один раз',
    локальВДоме === 1,
    'Объявлений `Я.локаль` в доме: ' + локальВДоме + ', нужно одно.\n' +
    'Два объявления — беда родится ровно на шве.');

/* ---- 2. литерала `ky-KG` в продукте нет вовсе. ЧИТАЕТСЯ ДЕРЕВО: имя
          локали СТОИТ в пояснениях дома и этого сторожа, и текстовый
          поиск поймал бы их, а не код. ---- */
const гдеKyKG = [];
файлы.forEach(ф => {
    let дер;
    try { дер = дерево(чит(ф)); } catch (e) { return; }
    обойти(дер, у => {
        if (у.type === 'Literal' && у.value === 'ky-KG') гдеKyKG.push(ф + ':' + у.loc.start.line);
    });
});
правило('локали `ky-KG` в коде продукта нет',
    гдеKyKG.length === 0,
    'Литерал `ky-KG` снова в коде:\n' + гдеKyKG.map(с => '  ' + с).join('\n') + '\n' +
    'ЕЁ НЕТ В БРАУЗЕРЕ, и она молча становится английской: кыргыз увидит\n' +
    '«Oct 15» вместо «15 окт.» и «1,234.5» вместо «1 234,5».');

/* ---- 3. потребители локали берут её у дома ---- */
let зововЛокали = 0;
файлы.forEach(ф => {
    const т = чит(ф);
    зововЛокали += (т.match(/KSLT_YAZYK\.локаль/g) || []).length;
});
правило('потребителей локали ровно столько, сколько замерено',
    зововЛокали === ПОТРЕБИТЕЛЕЙ_ЛОКАЛИ,
    'Зовов `KSLT_YAZYK.локаль`: ' + зововЛокали + ', замерено ' + ПОТРЕБИТЕЛЕЙ_ЛОКАЛИ + '.\n' +
    'Вниз — кто-то снова считает локаль сам (и, скорее всего, через\n' +
    '`ky-KG`); вверх — появился новый потребитель, и это хорошо, но число\n' +
    'живёт здесь: поправь его вместе с причиной.');

/* ---- 4. кыргызу дают английское только в именах собственных ---- */
const кгПоАнглийски = [];
файлы.forEach(ф => {
    const т = чит(ф);
    let дер;
    try { дер = дерево(т); } catch (e) { return; }
    обойти(дер, у => {
        if (у.type !== 'CallExpression' || !у.callee) return;
        if (т.slice(у.callee.start, у.callee.end) !== 'KSLT_YAZYK.выбрать') return;
        if (у.arguments.length !== 3) return;
        const [en, kg] = у.arguments;
        if (en.type === 'Literal' && kg.type === 'Literal' &&
            typeof en.value === 'string' && en.value === kg.value && /[A-Za-z]{3}/.test(en.value)) {
            кгПоАнглийски.push(ф + ':' + у.loc.start.line + ' «' + String(en.value).slice(0, 40) + '»');
        }
        if (en.type === 'ObjectExpression' && kg.type === 'ObjectExpression') {
            const карта = н => {
                const о = {};
                н.properties.forEach(с => {
                    if (!с.key || !с.value || с.value.type !== 'Literal') return;
                    о[с.key.name || с.key.value] = с.value.value;
                });
                return о;
            };
            const e = карта(en), k = карта(kg);
            Object.keys(e).forEach(ключ => {
                if (typeof e[ключ] === 'string' && e[ключ] === k[ключ] && /[A-Za-z]{3}/.test(e[ключ])) {
                    кгПоАнглийски.push(ф + ':' + у.loc.start.line + ' ' + ключ + ' = «' + e[ключ] + '»');
                }
            });
        }
    });
});
правило('кыргызу дают английское не больше, чем в именах собственных',
    кгПоАнглийски.length <= ИМЁН_СОБСТВЕННЫХ,
    'Мест, где кыргызская ветвь равна английской: ' + кгПоАнглийски.length +
    ', потолок ' + ИМЁН_СОБСТВЕННЫХ + '\n' +
    кгПоАнглийски.map(с => '  ' + с).join('\n') + '\n' +
    'Законные — только имена собственные и аббревиатуры: Telegram, Email,\n' +
    'Instagram, NTRP, FAQ, KSLT. Новое такое место — это забытый перевод,\n' +
    'как было с `live: \'Live\'` в расписании турнира.');
правило('потолок английского у кыргыза не завышен',
    кгПоАнглийски.length >= ИМЁН_СОБСТВЕННЫХ,
    'Мест ' + кгПоАнглийски.length + ' при потолке ' + ИМЁН_СОБСТВЕННЫХ +
    ' — ХРАПОВИК ОПУСКАЕТСЯ: поправь ИМЁН_СОБСТВЕННЫХ на ' + кгПоАнглийски.length + '.');

/* ---- 5. второй карты подписей статуса нет ---- */
const ТУРНИР = чит('js/tournament-detail.js');
const свояКарта = [];
обойти(дерево(ТУРНИР), у => {
    if (у.type === 'FunctionDeclaration' && у.id &&
        /^(getStatusLabel|renderHero)$/.test(у.id.name)) свояКарта.push(у.id.name + ':' + у.loc.start.line);
    if (у.type === 'MemberExpression' &&
        ТУРНИР.slice(у.start, у.end) === 'window.heroLabels') свояКарта.push('window.heroLabels:' + у.loc.start.line);
    if (у.type === 'MemberExpression' &&
        ТУРНИР.slice(у.start, у.end) === 'window.statusLabels') свояКарта.push('window.statusLabels:' + у.loc.start.line);
});
правило('своей карты подписей статуса в странице турнира нет',
    свояКарта.length === 0,
    'Вернулось своё: ' + свояКарта.join(', ') + '\n' +
    'Подписи статуса знает ДОМ `js/tournament-status.js` на трёх языках.\n' +
    'Прежние карты лежали в мёртвых функциях — по-русски и с ключом `live`,\n' +
    'которого у понятия нет вовсе.');
правило('страница турнира берёт подписи статуса у дома',
    /KSLT_STATUS\.подписи\(/.test(ТУРНИР),
    'Зов `KSLT_STATUS.подписи` исчез — значит подписи снова свои.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      по языкам, а не вперемешку: ' + правил + ' правил');
    console.log('          локаль одна на продукт, зовут её ' + зововЛокали + ' мест');
    console.log('          `ky-KG` в коде ноль; английского у кыргыза ' + кгПоАнглийски.length +
                ' — только имена собственные');
    console.log('');
} else {
    console.log('');
    console.log('  НЕ ТАК  по языкам, а не вперемешку — ' + ошибки.length + ' правил не держится');
    console.log('');
    ошибки.forEach(([и, п]) => {
        console.log('          x ' + и);
        п.split('\n').forEach(л => console.log('            ' + л));
        console.log('');
    });
    process.exit(1);
}
