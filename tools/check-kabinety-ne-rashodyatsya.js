'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const САЙТ = 'js/dashboard.js';
const ПРИЛОЖЕНИЕ = 'mobile/www/js/screens/profile.js';

/* Якорь — столбец, который пишут оба кабинета. По нему находится нужный
   `update`, а не любой из полутора десятков в файле. */
const ЯКОРЬ = /\bgender\s*:/;

const ТОЛЬКО_У_САЙТА = {
    first_name: 'имя и фамилия на сайте разнесены по двум полям, в приложении это одно `full_name`',
    last_name:  'то же: половина имени — поле сайта, приложение пишет `full_name` целиком',
    full_name:  'на сайте собирается из имени и фамилии в другом месте'
};
const ТОЛЬКО_У_ПРИЛОЖЕНИЯ = {
    full_name: 'в приложении имя одним полем; на сайте те же данные пишутся как first_name и last_name'
};

function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}

/** Столбцы из объекта `.update({...})`, в котором встречается якорь. */
function столбцы(текст, файл) {
    const из = new Set();
    const ре = /\.update\s*\(\s*\{/g;
    let м;
    while ((м = ре.exec(текст)) !== null) {
        let баланс = 0, конец = -1;
        for (let i = м.index + м[0].length - 1; i < текст.length; i++) {
            if (текст[i] === '{') баланс++;
            else if (текст[i] === '}') { баланс--; if (баланс === 0) { конец = i; break; } }
        }
        if (конец === -1) continue;
        const тело = текст.slice(м.index, конец);
        if (!ЯКОРЬ.test(тело)) continue;              // не тот update
        const без = тело.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');
        for (const к of без.match(/^\s*([a-z_][a-z0-9_]*)\s*:/gm) || []) {
            из.add(к.trim().replace(':', ''));
        }
    }
    return { набор: из, файл: файл };
}

const тс = чит(САЙТ), тп = чит(ПРИЛОЖЕНИЕ);
const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя: имя, подсказка: подсказка });
}

правило('оба кабинета на месте', тс !== null && тп !== null,
    'Нет файла: ' + [тс === null ? САЙТ : null, тп === null ? ПРИЛОЖЕНИЕ : null].filter(Boolean).join(', '));

if (тс && тп) {
    const с = столбцы(тс, САЙТ).набор;
    const п = столбцы(тп, ПРИЛОЖЕНИЕ).набор;

    правило('запись профиля найдена в обоих кабинетах', с.size > 0 && п.size > 0,
        'Не нашёлся `update` с полем `gender`: ' +
        (с.size === 0 ? САЙТ : ПРИЛОЖЕНИЕ) + '. Либо запись переехала, либо\n' +
        'якорь устарел — поправь прибор, а не обходи его.');

    const нетВПриложении = [...с].filter(к => !п.has(к) && !ТОЛЬКО_У_САЙТА[к]);
    const нетНаСайте = [...п].filter(к => !с.has(к) && !ТОЛЬКО_У_ПРИЛОЖЕНИЯ[к]);

    правило('приложение пишет всё, что пишет сайт', нетВПриложении.length === 0,
        'Эти столбцы пишет кабинет сайта, а кабинет приложения — нет:' +
        нетВПриложении.map(к => '\n  ' + к).join('') +
        '\nОдна база, два кабинета: поле, заполненное на сайте и не спрошенное\n' +
        'в приложении, расходится молча — человек не знает, что у него пусто.\n' +
        'Либо добавь поле в приложение, либо назови исключение С ПРИЧИНОЙ.');

    правило('сайт пишет всё, что пишет приложение', нетНаСайте.length === 0,
        'Эти столбцы пишет кабинет приложения, а кабинет сайта — нет:' +
        нетНаСайте.map(к => '\n  ' + к).join('') +
        '\nОриентир по функционалу — сайт (слово Кости 29.10). Если поле\n' +
        'нужно, оно нужно обоим.');

    правило('у каждого исключения названа причина',
        Object.values(ТОЛЬКО_У_САЙТА).concat(Object.values(ТОЛЬКО_У_ПРИЛОЖЕНИЯ))
            .every(п => typeof п === 'string' && п.trim().length > 25),
        'Исключение без внятной причины — это список, а не правило.');

    if (!ошибки.length) {
        console.log('ок      два кабинета пишут одно и то же: ' + с.size + ' столбцов на сайте, ' +
            п.size + ' в приложении, расхождений нет');
        process.exit(0);
    }
}

console.log('НЕ ТАК  кабинеты разошлись: ' + ошибки.length + ' правил упало\n');
for (const о of ошибки) console.log('  ✗ ' + о.имя + '\n    ' + о.подсказка.replace(/\n/g, '\n    ') + '\n');
process.exit(1);
