/**
 * ОФОРМЛЕНИЕ ИМЕНЕМ, СОСТОЯНИЕ КЛАССОМ. Кусок 175, 26.10. Круг 4 ветки C.
 *
 * ЧТО БЫЛО. В `js/admin/sections/bracket.js` — самом крупном файле
 * продукта (14 200 строк) — стояло 136 инлайн-стилей, и это был ПОСЛЕДНИЙ
 * круг ветки C после кругов 2 и 3. Разбор прибором: раскладка и отступы
 * 61, смешанные 41, типографика 30, чистое состояние 4, и ДЕСЯТЬ мест,
 * где значение считал js.
 *
 * ГЛАВНОЕ БЫЛО НЕ В ЧИСЛЕ ИНЛАЙНОВ:
 *   ПЯТЬ ПАНЕЛЕЙ ВКЛАДОК ДЕРЖАЛИ СОСТОЯНИЕ В РАЗМЕТКЕ: `display:none`
 *   собирался условием при сборке строки, а переключение писало инлайн
 *   ещё пятью строками по id. Состояние жило в двух местах и в десяти
 *   записях — теперь это одна карта «ключ → панель» и класс.
 *   ВЕРХНИЙ ОТСТУП ПАНЕЛИ стоял инлайном у ТРЁХ панелей из пяти: замер на
 *   стенде показал 8px у заявок и сетки и 0 у расписания — одно понятие
 *   держало два значения.
 *   `ad-input` ОКАЗАЛСЯ МЁРТВЫМ ИМЕНЕМ: правила под него нет ни в одном
 *   css, и select крестовых слотов рисовался браузерным — белый фон,
 *   чёрный текст, 13.33px на тёмной админке. Замерено вставкой образца.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ:
 *   в файле нет ни одного инлайна и ни одной записи `style.display`;
 *   состояние панели — класс, и переключение идёт одной картой;
 *   отступ панели живёт в css;
 *   новые утилиты объявлены удвоенным именем, как велит приём 17.10;
 *   мёртвое имя `ad-input` не возвращается;
 *   состояние тай-брейка — отдельный селектор, а не второе определение
 *   класса (я чуть не завёл дубль и поймал его замером).
 *
 *   node tools/check-oformlenie-imenem.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const читать = п => fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8');
/* КОД БЕЗ ПОЯСНЕНИЙ: иначе правило падает на собственном комментарии —
   на этом я попадался трижды за октябрь. */
const безПояснений = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));

const ФАЙЛ = 'js/admin/sections/bracket.js';
const js = безПояснений(читать(ФАЙЛ));
const admin = безПояснений(читать('css/admin.css'));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

/* ── 1. НИ ОДНОГО ИНЛАЙНА В ФАЙЛЕ ──────────────────────────────────── */
const инлайны = (js.match(/style\s*=\s*"/g) || []).length
              + (js.match(/style\s*=\s*'/g) || []).length
              + (js.match(/style\.cssText/g) || []).length;
правило('в файле сетки не осталось инлайн-стилей',
    инлайны === 0,
    'Инлайнов в ' + ФАЙЛ + ': ' + инлайны + ', было 136, решено ноль.\n' +
    'ОФОРМЛЕНИЕ ИМЕНЕМ: инлайн сильнее любого правила и невидим сторожам\n' +
    'css — ни краска, ни отступ в нём не сторожатся. Файл внесён в список\n' +
    'ВЫЧИЩЕННЫХ в `check-inlayn-stili.js`, и там это держит пятое правило.');

/* ── 2. СОСТОЯНИЕ НЕ ПИШЕТСЯ ИНЛАЙНОМ ──────────────────────────────── */
const записиDisplay = (js.match(/\.style\.display\s*=/g) || []).length;
правило('состояние не пишется через style.display',
    записиDisplay === 0,
    'Записей `.style.display =`: ' + записиDisplay + ', было 20, решено ноль.\n' +
    'СОСТОЯНИЕ — КЛАСС: `display` в инлайне перебивает любое правило css и\n' +
    'остаётся в разметке после переключения. Утилита `.ad-skryt` заведена\n' +
    'кругом 17.10 с удвоенным именем вместо !important.');

/* ── 3. ПАНЕЛИ ВКЛАДОК: ОДНА КАРТА, А НЕ ПЯТЬ СТРОК ПО ID ──────────── */
правило('панели вкладок переключаются одной картой',
    /var ПАНЕЛИ = \{[^}]*registrations:[^}]*bracket:[^}]*schedule:[^}]*results:[^}]*news:[^}]*\}/.test(js) &&
    /Object\.keys\(ПАНЕЛИ\)\.forEach/.test(js),
    'Карта «ключ → панель» и проход по ней не найдены. Было пять записей\n' +
    '`document.getElementById(\'adBrk…Panel\').style.display = …`, и две из\n' +
    'них не проверяли, существует ли панель: у незавершённого турнира\n' +
    'панелей результатов и новостей в разметке нет вовсе.');

const вРазметке = (js.match(/'<div class="ad-brk-panel/g) || []).length;
правило('состояние панели ставится классом при сборке разметки',
    вРазметке >= 5 && !/ad-brk-panel[^']*style="/.test(js),
    'Панелей в разметке ' + вРазметке + ', и ни одна не должна несть инлайн.\n' +
    'Скрытая панель помечается `ad-skryt`, а не `style="display:none"`.');

/* ── 4. ОТСТУП ПАНЕЛИ ЖИВЁТ В CSS ──────────────────────────────────── */
правило('верхний отступ панели вкладки задан в css',
    /\.ad-brk-panel\s*\{[^}]*padding-top:\s*var\(--space-2\)/.test(admin),
    'Правило `.ad-brk-panel { padding-top }` в `css/admin.css` не найдено.\n' +
    'Отступ стоял инлайном у ТРЁХ панелей из пяти: замер на стенде дал 8px\n' +
    'у заявок и сетки и 0 у расписания — ОДНО ПОНЯТИЕ ДЕРЖАЛО ДВА ЗНАЧЕНИЯ.');

/* ── 5. НОВЫЕ УТИЛИТЫ — УДВОЕННЫМ ИМЕНЕМ ───────────────────────────── */
const УТИЛИТЫ = ['ad-bez-polya', 'ad-vlevo', 'ad-accent', 'ad-ryad', 'ad-ryad-sverhu',
                 'ad-podpis-sm', 'ad-kursiv', 'ad-abzac-snizu', 'ad-abzac-sverhu',
                 'ad-uzhe-zapisan', 'ad-conf-actions-gap'];
const безУдвоения = УТИЛИТЫ.filter(у =>
    !new RegExp('\\.' + у + '\\.' + у + '[\\s{]').test(admin));
правило('новые утилиты объявлены удвоенным именем',
    безУдвоения.length === 0,
    'Объявлены одним именем: ' + безУдвоения.join(', ') + '\n' +
    'ПРИЁМ КРУГА 17.10: удвоение имени поднимает утилиту до двух классов и\n' +
    'перебивает составные селекторы вроде `.ad-table td`, не прибегая к\n' +
    '`!important`, который в этом файле считается бедой.');

/* ── 6. МЁРТВОЕ ИМЯ НЕ ВОЗВРАЩАЕТСЯ ────────────────────────────────── */
правило('мёртвое имя `ad-input` не вернулось в разметку',
    !/class="ad-input[\s"]/.test(js),
    'В разметке снова `class="ad-input"`. Правила под него нет НИ В ОДНОМ\n' +
    'css — проверено 26.10, — и select рисовался браузерным: белый фон,\n' +
    'чёрный текст, 13.33px на тёмной админке. Системное поле —\n' +
    '`.ad-field-input`.');

/* ── 7. СОСТОЯНИЕ ТАЙ-БРЕЙКА — ОТДЕЛЬНЫЙ СЕЛЕКТОР ─────────────────── */
const правилаTb = (admin.match(/(?:^|\n)\.ad-tb-wrap\s*\{/g) || []).length;
правило('у тай-брейка одно определение раскладки',
    правилаTb === 1 && /\.ad-tb-wrap:not\(\.ad-vidno\)\s*\{\s*display:\s*none/.test(admin),
    'Правил `.ad-tb-wrap {` в css: ' + правилаTb + ', нужно одно, плюс\n' +
    'отдельный селектор `:not(.ad-vidno)` на скрытие.\n' +
    'Я ЗАВЁЛ ВТОРОЕ ОПРЕДЕЛЕНИЕ И ПОЙМАЛ ЕГО ЗАМЕРОМ: раскладка стояла\n' +
    'ниже в файле и перебивала мой `display:none`, тай-брейк перестал\n' +
    'скрываться при счёте 6:4. ВИДЕЛ ЭТО БРАУЗЕР, А НЕ ЧТЕНИЕ.');

/* ── 8. КЛЮЧЕВЫЕ КЛАССЫ ОКНА СЧЁТА ЕСТЬ В CSS ─────────────────────── */
const НУЖНЫ = ['ad-score-head', 'ad-score-player', 'ad-score-vs', 'ad-score-setbtns',
               'ad-score-minibtn', 'ad-score-chips', 'ad-score-retired', 'ad-score-btn-col',
               'ad-score-winner', 'ad-score-winner-display', 'ad-modal-score'];
const нет = НУЖНЫ.filter(к => !new RegExp('\\.' + к + '[\\s,{:]').test(admin));
правило('классы окна ввода счёта объявлены в css',
    нет.length === 0,
    'Нет правил под: ' + нет.join(', ') + '\n' +
    'Класс в разметке без правила в css — то же мёртвое имя, что `ad-input`:\n' +
    'вид молча уезжает к браузерному.');

/* ── 9. КЛАСС В РАЗМЕТКЕ НЕ ОСТАЁТСЯ БЕЗ ПРАВИЛА ──────────────────── */
const вРазметкеКлассы = new Set();
(js.match(/class="[^"]*"/g) || []).forEach(с => {
    с.replace(/class="|"/g, '').split(/\s+/).forEach(к => {
        if (/^ad-[a-z0-9-]+$/.test(к)) вРазметкеКлассы.add(к);
    });
});
const ВЕСЬ_CSS = fs.readdirSync(path.join(КОРЕНЬ, 'css'))
    .filter(ф => ф.endsWith('.css'))
    .map(ф => читать('css/' + ф)).join('\n');
/* КЛАСС БЫВАЕТ КРЮЧКОМ ДЛЯ JS, А НЕ ОФОРМЛЕНИЕМ, и тогда правила в css
   у него нет законно: `ad-set-game` ищут `querySelectorAll`, `ad-btn-approve`
   ловит делегированное нажатие. ПЕРВАЯ РЕДАКЦИЯ ПРАВИЛА НАЗВАЛА МЁРТВЫМИ
   ДВЕНАДЦАТЬ ТАКИХ ИМЁН — поймал прогон, а не чтение. Мёртвым имя
   называется, только если его не знает НИ css, НИ js как крючок. */
const ВЕСЬ_JS = fs.readdirSync(path.join(КОРЕНЬ, 'js'), { recursive: true })
    .filter(ф => typeof ф === 'string' && ф.endsWith('.js'))
    .map(ф => { try { return читать('js/' + ф); } catch (e) { return ''; } }).join('\n');
const крючок = к => new RegExp('[.\\[\'"`]' + к + '[\'"`\\]\\s),.]').test(ВЕСЬ_JS.replace(/class="[^"]*"/g, ''));
const мёртвые = [...вРазметкеКлассы].filter(к =>
    !new RegExp('\\.' + к + '[\\s,{:.]').test(ВЕСЬ_CSS) && !крючок(к));
/* ЧЕТЫРЕ ИМЕНИ БЕЗ ПРАВИЛА НАЙДЕНЫ ЭТИМ ЖЕ ПРОГОНОМ И НЕ ЧИНЯТСЯ ЗДЕСЬ —
   НАХОДКИ НЕ УВОДЯТ С МАРШРУТА. Все четыре жили в файле до куска 175:
   `ad-alert-info` и `ad-league-bracket` не знает ни один css, а
   `ad-qual-block` и `ad-dual-league` существуют в css ТОЛЬКО составными
   (`-top`, `-row`) — само имя не красит ничего. Они под храповиком:
   пятое такое имя уронит правило. */
const ИЗВЕСТНЫЕ_БЕЗ_ПРАВИЛА = ['ad-alert-info', 'ad-qual-block',
                               'ad-dual-league', 'ad-league-bracket'];
const новыеМёртвые = мёртвые.filter(к => ИЗВЕСТНЫЕ_БЕЗ_ПРАВИЛА.indexOf(к) === -1);
правило('новых классов без правила и без крючка не завелось',
    новыеМёртвые.length === 0 && мёртвые.length <= ИЗВЕСТНЫЕ_БЕЗ_ПРАВИЛА.length,
    'Новые классы, которых не знает ни css, ни js: ' + новыеМёртвые.join(', ') + '\n' +
    'Всего таких имён ' + мёртвые.length + ', известных ' + ИЗВЕСТНЫЕ_БЕЗ_ПРАВИЛА.length + '.\n' +
    'МЁРТВЫМ ИМЯ НАЗЫВАЕТСЯ ПОСЛЕ ПРОВЕРКИ, и проверка здесь двойная:\n' +
    'правило в css ИЛИ поиск по этому имени в js. Класс без того и другого\n' +
    'не делает ничего, а в коде читается как решение.');

/* ── 10. ХРАПОВИК НА КЛАССЫ: ОФОРМЛЕНИЕ НЕ ПОЛЗЁТ ОБРАТНО ─────────── */
правило('классов в разметке файла не меньше замеренного',
    вРазметкеКлассы.size >= 120,
    'Имён классов в разметке ' + вРазметкеКлассы.size + ', замерено 26.10 — 128.\n' +
    'Резкое падение значит, что оформление вернулось в инлайны или в строки.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      оформление именем: 10 правил');
    console.log('          инлайнов в файле сетки 0 (было 136), записей style.display 0 (было 20)');
    console.log('          панели вкладок: одна карта вместо пяти строк по id');
    console.log('          имён классов в разметке ' + вРазметкеКлассы.size +
                ', без правила ' + мёртвые.length + ' (все четыре названы и под храповиком)');
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  оформление именем — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          x ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
