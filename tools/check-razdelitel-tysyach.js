/**
 * ЗАМОРОЗКА «РАЗДЕЛИТЕЛЬ ТЫСЯЧ — ОДИН НА ПРОДУКТ»
 * (ветка D, кусок 192, 27.10.2026).
 *
 * ЗАМЕР 27.10. Правило «ставить пробел каждые три цифры» жило в ШЕСТИ
 * местах и в ДВУХ ВИДАХ: три `money(n)` ставили НЕРАЗРЫВНЫЙ пробел,
 * а три места — ОБЫЧНЫЙ. Разница не бумажная: обычный переносится на
 * новую строку, и «1 200» рвётся пополам в узкой колонке. Один и тот же
 * приз выглядел по-разному в афише и в таблице.
 *
 * Запись ветки D говорила «money объявлен дважды, девять мест не зовут
 * его вовсе». Замер: объявлений **три**, своих копий разделителя —
 * **шесть**. ЧИСЛО ЗАПИСИ НЕ СОВПАЛО НИ С ОДНИМ ИЗ ДВУХ.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ: не «пробел неразрывный», а «разделитель назван
 * ОДИН РАЗ, и зовут его все». Поменяется вид пробела — поменяется одна
 * строка в доме, и ни одно место не отстанет.
 *
 *   node tools/check-razdelitel-tysyach.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };
const гасить = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/^([ \t]*)\/\/[^\n]*$/gm, (м, о) => о);

const ДОМ = 'js/kslt-chisla.js';
const есть = ф => fs.existsSync(path.join(КОРЕНЬ, ф));
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');

function всеJs(д, из) {
    из = из || [];
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) всеJs(п, из); else if (э.name.endsWith('.js')) из.push(п);
    });
    return из;
}

правило('дом чисел есть и отдаёт два приёма',
    есть(ДОМ) && /Ч\.тысячи = function/.test(чит(ДОМ)) && /Ч\.деньги = function/.test(чит(ДОМ)),
    'Нет `' + ДОМ + '` или он не отдаёт `тысячи` и `деньги`.\n' +
    'Якорь держится на СОДЕРЖИМОМ дома, а не на его имени в списке.');

/* ── РАЗДЕЛИТЕЛЬ НАЗВАН ТОЛЬКО В ДОМЕ ────────────────────────────────── */
const ПРИЗНАК = /\(\?=\(\\d\{3\}\)\+\(\?!\\d\)\)/;
const свои = всеJs('js').filter(ф => ф !== ДОМ && ПРИЗНАК.test(гасить(чит(ф))));
правило('разделитель тысяч назван только в доме',
    свои.length === 0,
    'Своя копия разделителя в: ' + свои.join(', ') + '.\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. Было шесть копий в двух видах\n' +
    'пробела, и один приз выглядел по-разному в афише и в таблице.');

/* ── ПУСТОТА НЕ СТАНОВИТСЯ НУЛЁМ ─────────────────────────────────────── */
правило('пустота остаётся пустотой',
    /Ч\.деньги = function \(n\) \{\s*if \(n === null \|\| n === undefined \|\| n === ''\) return '';/.test(чит(ДОМ)),
    'В `деньги` нет отказа на пустом значении. `Number(\'\')` даёт 0, и\n' +
    'пустое поле цены показало бы «0». Поймано на первом же прогоне дома.');

/* ── ПРОБЕЛ НЕРАЗРЫВНЫЙ ──────────────────────────────────────────────── */
правило('разделитель — неразрывный пробел',
    /РАЗДЕЛИТЕЛЬ = String\.fromCharCode\(0xA0\)/.test(чит(ДОМ)),
    'Разделитель не неразрывный ИЛИ записан самим знаком.\n' +
    'Обычный пробел переносится на новую строку, и число рвётся пополам\n' +
    'в узкой колонке. А сам знак в файле глазами неотличим от обычного —\n' +
    'ЗНАК, КОТОРОГО НЕ ВИДНО, НЕ ДОЛЖЕН РЕШАТЬ. Нужен `String.fromCharCode(0xA0)`.');

/* ── ДОМ ПОДКЛЮЧЁН ВЕЗДЕ, ГДЕ ЕГО ЗОВУТ, И РАНЬШЕ ЗОВУЩИХ ────────────── */
const зовущие = всеJs('js')
    .filter(ф => ф !== ДОМ && /\bKSLT_CHISLA\b/.test(гасить(чит(ф))))
    .map(ф => ф.replace(/^js\//, '').replace(/\.js$/, ''));
const реЗовущих = new RegExp('<script src="[^"]*js/(?:' +
    зовущие.map(и => и.replace(/[/.]/g, с => '\\' + с)).join('|') + ')\\.js\\?');
function страницы() {
    const из = [];
    ['pages', 'maket'].forEach(д => fs.readdirSync(path.join(КОРЕНЬ, д))
        .filter(и => и.endsWith('.html')).forEach(и => из.push(д + '/' + и)));
    fs.readdirSync(КОРЕНЬ).filter(и => /^index.*\.html$/.test(и)).forEach(и => из.push(и));
    return из;
}
const без = [], поздно = [];
страницы().forEach(ф => {
    const т = чит(ф);
    const м = т.match(реЗовущих);
    if (!м) return;
    const дом = т.indexOf('kslt-chisla.js');
    if (дом === -1) { без.push(ф); return; }
    if (м.index < дом) поздно.push(ф);
});
правило('дом чисел подключён на каждой странице, где его зовут',
    без.length === 0,
    'Без дома: ' + без.join(', ') + '.\n' +
    'Без него `KSLT_CHISLA` не существует, и страница падает на первом же\n' +
    'числе — молча, если вызов стоит в ветке, которая случается не всегда.');
правило('дом чисел подключён РАНЬШЕ тех, кто его зовёт',
    поздно.length === 0,
    'Поздно: ' + поздно.join(', ') + '.\n' +
    'Скрипт, стоящий выше, выполняется раньше: читатель не найдёт дом.\n' +
    'Дом ни от чего не зависит — его место первым безопасно.');

const ВСЕГО = 6;
if (ошибки.length) {
    console.log('\n  РАЗДЕЛИТЕЛЬ ТЫСЯЧ — ПРАВИЛО УПАЛО (' + ошибки.length + ' из ' + ВСЕГО + ')\n');
    ошибки.forEach(о => { console.log('  x ' + о.имя); console.log('    ' + о.подсказка.split('\n').join('\n    ') + '\n'); });
    process.exit(1);
}
console.log('  v разделитель тысяч: ' + ВСЕГО + ' правил, зовущих дом ' + зовущие.length +
            ', своих копий 0');
