function всеПробы(дир, итог) {
    итог = итог || [];
    if (!fs.existsSync(дир)) return итог;
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        const п = path.join(дир, э.name);
        if (э.isDirectory()) всеПробы(п, итог);
        else if (э.name.endsWith('.spec.js')) итог.push(path.relative(КОРЕНЬ, п).split(path.sep).join('/'));
    }
    return итог;
}
