function правило(имя, годно, подсказка) {
    if (годно) { держится++; console.log('  ✓ ' + имя); }
    else ошибки.push({ имя, подсказка });
}

/* Дом подключён везде, где его зовут. Одно правило на пять домов: дыра в
   любом из них — одна и та же тихая поломка. */
function домВездеГдеЗовут(дом, зовущие, имяПравила) {
    const без = страницы.filter(с =>
        зовущие.some(з => с.свои.indexOf(з) !== -1) && с.свои.indexOf(дом) === -1
    ).map(с => с.путь);
    правило(имяПравила,
        без.length === 0,
        'Страницы без дома `' + дом + '`: ' + без.join(', ') + '.\n' +
        'Дом без подключения — не одно определение, а тихая поломка: зов\n' +
        'упадёт на той единственной странице, куда дом не донесли, и\n' +
        'узнает об этом только человек, который туда зашёл.');
}

