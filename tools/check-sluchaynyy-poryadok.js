const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = о => fs.readFileSync(path.join(КОРЕНЬ, о), 'utf8');

/* Комментарии гасим, СОХРАНЯЯ переводы строк: храповик, считающий
   пояснения, считает слова о коде — семь раз за ветку. */
const чисто = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '));

function всеJS(дир, итог) {
    итог = итог || [];
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        const п = path.join(дир, э.name);
        if (э.isDirectory()) всеJS(п, итог);
        else if (э.name.endsWith('.js')) итог.push(п);
    }
    return итог;
}
const файлыJS = всеJS(path.join(КОРЕНЬ, 'js'))
    .map(п => path.relative(КОРЕНЬ, п).split(path.sep).join('/'));

function всеHTML() {
    const итог = [];
    (function обойти(дир) {
        for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
            if (э.name.startsWith('.')) continue;
            const п = path.join(дир, э.name);
            if (э.isDirectory()) {
                if (['node_modules','test-results','mobile','lib','playwright-report','tests','tools'].indexOf(э.name) !== -1) continue;
                обойти(п);
            } else if (э.name.endsWith('.html')) итог.push(path.relative(КОРЕНЬ, п).split(path.sep).join('/'));
        }
    })(КОРЕНЬ);
    return итог;
}
/* ПОДКЛЮЧЕНИЕ — ЭТО ТЕГ, А НЕ УПОМИНАНИЕ (урок куска 104). */
const подключённые = т => {
    const обр = /<script[^>]*\ssrc="([^"]+)"/g;
    const итог = [];
    let м;
    while ((м = обр.exec(т))) итог.push(м[1].split('?')[0].replace(/^(\.\.\/)+/, ''));
    return итог;
};
const страницы = всеHTML().map(п => ({ путь: п, свои: подключённые(чит(п)) }));

const ошибки = [];
