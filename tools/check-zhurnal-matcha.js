function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function безКом(т) {
    return (т || '').replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');
}

/**
 * ИМЕНА, КОТОРЫЕ ЧИТАЕТ ДОМ: `о.подписи.X` и `п.X` (дом сокращает
 * довод в `var п = о.подписи`). Граница слова `\b` здесь не годится:
 * в JS она считается по латинице, и `\bп` не совпадает ни с чем —
 * проверено на своей же шкуре. Отсекаем взглядом назад.
 */
function читаетДом(т) {
    const имена = new Set();
    const re = /(?:о\.подписи|(?<![\wА-Яа-яЁё.$])п)\.([A-Za-z_]\w*)/g;
    let м;
    while ((м = re.exec(т))) имена.add(м[1]);
    return [...имена];
}

/** Тело объекта от `{` после якоря до парной `}`. */
function блок(т, якорь) {
    const i = т.indexOf(якорь);
    if (i === -1) return null;
    let j = т.indexOf('{', i);
    if (j === -1) return null;
    let глуб = 0;
    for (let k = j; k < т.length; k++) {
        if (т[k] === '{') глуб++;
        else if (т[k] === '}') {
            глуб--;
            if (!глуб) return т.slice(j + 1, k);
        }
    }
    return null;
}

/** Имена полей объекта: `имя:` в начале строки. */
function поляОбъекта(тело) {
    const имена = new Set();
    const re = /(?:^|[,{])\s*([A-Za-z_]\w*)\s*:/g;
    let м;
    while ((м = re.exec(тело))) имена.add(м[1]);
    return имена;
}

