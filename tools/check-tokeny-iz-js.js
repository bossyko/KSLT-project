#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ТОКЕН, КОТОРЫЙ БЕРУТ ИЗ JS ПО ИМЕНИ, ОБЪЯВЛЕН В CSS» (30.10).
 *
 * ЗАЧЕМ ОН ЕСТЬ — СЛУЧАЙ, А НЕ ОПАСЕНИЕ. 26.10 кусок 179 снял 28
 * «мёртвых токенов-мостов» и записал: «ни один не зовётся нигде —
 * проверено двойным поиском, и вид не мог измениться ни на пиксель».
 * Поиск искал `var(--имя)` в css. А дом печатной карточки берёт токен
 * ИЗ JS ПО ИМЕНИ СТРОКОЙ: `краска('--vch-card-top')`
 * (`js/kslt-vaucher-kartochka.js:77`) — холст `var()` не понимает вовсе.
 * Четыре дня верх фирменного перехода был пустой строкой, холст бросал
 * `addColorStop … ('')`, и КАРТОЧКА ВАУЧЕРА НЕ РИСОВАЛАСЬ ВООБЩЕ.
 * Нашла это проба 108 в полном прогоне 30.10 — то есть беда дожила до
 * первого прогона всего набора.
 *
 * ПРАВИЛО ОТСЮДА: ТОКЕН, КОТОРЫЙ БЕРУТ ИЗ JS ПО ИМЕНИ, НЕ ВИДЕН ПОИСКОМ
 * ПО `var(`. МЁРТВЫМ КОД НАЗЫВАЕТСЯ ПОСЛЕ ПРОВЕРКИ — а проверка обязана
 * смотреть ОБА способа зова.
 *
 * ЧТО СТЕРЕЖЁТ. Каждое имя токена, которое js передаёт СТРОКОЙ, обязано
 * быть объявлено в css. Признак точный, без слепого пятна: строковый
 * литерал — это литерал, его не надо угадывать. Обратная сторона (токен
 * объявлен, но никем не зовётся) здесь НЕ стережётся: это другое
 * понятие, и у него другая цена ошибки.
 *
 *   node tools/check-tokeny-iz-js.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');

function обойти(д, годится, вых) {
    вых = вых || [];
    const полный = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(полный)) return вых;
    fs.readdirSync(полный, { withFileTypes: true }).forEach(э => {
        const п = д ? д + '/' + э.name : э.name;
        if (э.isDirectory()) {
            if (!/^(node_modules|\.git|android|ios|build|test-results|playwright-report|slepki|_figma|_bazovy)$/
                .test(э.name) && !э.name.startsWith('.')) обойти(п, годится, вых);
        } else if (годится(э.name)) вых.push(п);
    });
    return вых;
}

const JS = []
    .concat(обойти('js', и => и.endsWith('.js')))
    .concat(обойти('mobile/www/js', и => и.endsWith('.js')));
const CSS = []
    .concat(обойти('css', и => и.endsWith('.css')))
    .concat(обойти('mobile/www/css', и => и.endsWith('.css')));

const объявлено = new Set();
CSS.forEach(ф => {
    const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
    [...т.matchAll(/(--[a-z0-9-]+)\s*:/g)].forEach(m => объявлено.add(m[1]));
});

/* ИМЯ ТОКЕНА СТРОКОЙ: '--что-то' или "--что-то". Комментарии сняты домом
   `bez-kommentariev.js`: имя, названное в подписи («был --vch-card-top»),
   — это объяснение, а не зов. */
const ЛИТЕРАЛ = /['"](--[a-z0-9-]+)['"]/g;

/* ЧТЕНИЕ И ЗАПИСЬ — РАЗНЫЕ ВЕЩИ, И ПРИБОР ПОПРАВЛЕН НА ПЕРВОМ ЖЕ ПРОГОНЕ.
   Первая редакция назвала беспризорным `--iskra` в
   `js/home-rankings.js:205`. А там `э.style.setProperty('--iskra', цвет)`
   — js САМ ОБЪЯВЛЯЕТ токен на узле, а css читает его с запасом:
   `var(--iskra, rgba(233,184,36,.95))` (`css/podium.css:566`). Беды нет,
   есть законное место. ПОЧТИ ТОЧНЫЙ ПРИБОР — ЭТО НЕТОЧНЫЙ ПРИБОР:
   поэтому имя в первом доводе `setProperty` зовом НЕ считается. */
const ЗАПИСЬ = /setProperty\(\s*['"](--[a-z0-9-]+)['"]/g;

const беспризорные = [];
JS.forEach(ф => {
    const т = безКомментариев(fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'));
    т.split('\n').forEach((с, i) => {
        const пишут = new Set();
        let z; ЗАПИСЬ.lastIndex = 0;
        while ((z = ЗАПИСЬ.exec(с))) пишут.add(z[1]);
        let m; ЛИТЕРАЛ.lastIndex = 0;
        while ((m = ЛИТЕРАЛ.exec(с))) {
            if (объявлено.has(m[1]) || пишут.has(m[1])) continue;
            беспризорные.push(ф + ':' + (i + 1) + '  ' + m[1]);
        }
    });
});

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('каждый токен, названный из js строкой, объявлен в css',
    беспризорные.length === 0,
    'Беспризорных: ' + беспризорные.length + '\n' +
    беспризорные.slice(0, 12).map(с => '  ' + с).join('\n') + '\n' +
    'Такой токен даёт ПУСТУЮ СТРОКУ, а не красную краску: на холсте это\n' +
    '`addColorStop` с пустой краской — исключение, а в разметке\n' +
    'прозрачное место.\n' +
    'Либо токен объявить, либо зов убрать.');

/* ЖИВОЙ СЛУЧАЙ ПОД ПРИСМОТРОМ ИМЕНЕМ, А НЕ ТОЛЬКО ЧИСЛОМ: именно он
   стоил четырёх дней неработающей карточки. */
правило('верх перехода печатной карточки объявлен',
    объявлено.has('--vch-card-top') && объявлено.has('--vch-card-bottom'),
    'Карточка ваучера рисует фон переходом из двух токенов. Нет одного —\n' +
    'холст бросает, и карточка не рисуется ВОВСЕ, а не «чуть иначе».');

console.log('');
if (!ошибки.length) {
    console.log('  ок      токены из js: все ' +
        (fs.readFileSync(__filename, 'utf8').match(/правило\('/g) || []).length +
        ' правил держатся');
    console.log('          объявлено токенов: ' + объявлено.size +
                ', беспризорных зовов из js: 0');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  токены из js — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
