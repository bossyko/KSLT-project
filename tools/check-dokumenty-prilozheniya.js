#!/usr/bin/env node
/**
 * ДОКУМЕНТЫ ДОСТИЖИМЫ ИЗ ПРИЛОЖЕНИЯ (29.10).
 *
 * ЗАЧЕМ. Замер грепом по всему `mobile/www`: ссылок на политику
 * конфиденциальности, оферту, правила и соглашение в приложении было
 * **НОЛЬ**. В меню профиля стояли настройки, уведомления, платежи,
 * ваучеры, удаление записи, язык, тема и выход — документов не было
 * вовсе.
 *
 * ЭТО СТЕНА ДЛЯ ПЛОЩАДОК, А НЕ УДОБСТВО: Play требует политику и в
 * карточке приложения, и внутри него для всего, что собирает личные
 * данные, Apple требует того же. Мы собираем ФИО, почту, телефон, дату
 * рождения и отпечаток устройства.
 *
 * НА САЙТЕ ОНИ БЫЛИ ВСЕГДА — в подвале (`partials/footer-ru.html:81-83`),
 * и строит их разметка. Поэтому дом сделан только для приложения, у
 * которого подвала нет: копия на сайте была бы мёртвым файлом.
 *
 * И ЗДЕСЬ ЖЕ СНЯТ ТРЕТИЙ АДРЕС САЙТА: `auth.js` вписывал
 * `https://bossyko.github.io/KSLT-project` и вёл на
 * `pages/reset-password.html`, которой в репозитории нет вовсе.
 *
 * Запуск: node tools/check-dokumenty-prilozheniya.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));

const ДОМ = 'mobile/www/js/kslt-dokumenty.js';
const ПРОФИЛЬ = 'mobile/www/js/screens/profile.js';
const РАЗМЕТКА = 'mobile/www/index.html';
const СЛОВАРЬ = 'mobile/www/js/i18n.js';

/* Список документов читается ИЗ ДОМА, а не держится здесь руками. */
const СТРАНИЦЫ = (function () {
    const м = безКом(чит(ДОМ)).match(/API\.СПИСОК = \[([\s\S]*?)\];/);
    if (!м) return null;
    return (м[1].match(/страница:\s*'([^']+)'/g) || [])
        .map(с => с.replace(/.*'([^']+)'.*/, '$1'));
})();

console.log('\n  ДОКУМЕНТЫ ДОСТИЖИМЫ ИЗ ПРИЛОЖЕНИЯ\n');

правило('дом документов объявлен',
    /KSLT_DOKUMENTY/.test(чит(ДОМ)) && /API\.СПИСОК/.test(чит(ДОМ)) &&
    /API\.адрес\s*=/.test(чит(ДОМ)) && /API\.все\s*=/.test(чит(ДОМ)),
    'Нужны `СПИСОК`, `адрес` и `все`.');

правило('список документов прочитан из дома',
    СТРАНИЦЫ && СТРАНИЦЫ.length >= 4,
    'Прочитано: ' + (СТРАНИЦЫ ? СТРАНИЦЫ.join(', ') : 'НИЧЕГО') + '.\n' +
    'Если список не читается — сломался ПРИБОР, и сверки ниже пусты.\n' +
    'Правило стоит ПЕРЕД ними нарочно.');

правило('каждый документ есть на сайте на всех трёх языках',
    СТРАНИЦЫ.every(с => ['', '-en', '-kg'].every(я =>
        fs.existsSync(path.join(КОРЕНЬ, 'pages', с + я + '.html')))),
    'Ссылка на страницу, которой нет, — это то, что уже случилось с\n' +
    '`pages/reset-password.html`: приложение вело человека в никуда.\n' +
    'Нет файла:\n' + СТРАНИЦЫ.filter(с => !['', '-en', '-kg'].every(я =>
        fs.existsSync(path.join(КОРЕНЬ, 'pages', с + я + '.html'))))
        .map(с => '  · ' + с).join('\n'));

правило('политика конфиденциальности в списке есть',
    СТРАНИЦЫ.indexOf('privacy-policy') !== -1,
    'Именно её спрашивают обе площадки. Остальное можно обсуждать,\n' +
    'политику — нет.');

правило('адрес сайта дом берёт у настроек, а не вписывает',
    /global\.KSLT_SAYT/.test(безКом(чит(ДОМ))) &&
    !/[a-z0-9-]+\.(?:netlify\.app|github\.io|kg)\b/.test(безКом(чит(ДОМ))),
    'Одно определение адреса завёл шаг A3.4. Вписанный здесь стал бы\n' +
    'ЧЕТВЁРТЫМ: в приложении уже жили `kslt.netlify.app` в доме и\n' +
    '`bossyko.github.io` в `auth.js`.');

/* ПРАВИЛО ДЕРЖИТСЯ НА ЗОВЕ, А НЕ НА СЛОВЕ `console.error`: слово
   остаётся в условии строкой выше (`if (global.console && console.error)`).
   ТОТ ЖЕ ПРОМАХ Я УЖЕ ДЕЛАЛ В КУСКЕ A3.7г и повторил здесь — правило,
   считающее текст, ловит слова, а не беду. */
правило('без дома адреса ссылки не угадываются',
    /console\.error\(\s*'KSLT_DOKUMENTY/.test(безКом(чит(ДОМ))) &&
    /return '';/.test(безКом(чит(ДОМ))),
    'Нет настроек — дом говорит вслух и отдаёт пусто, а не подставляет\n' +
    'свой адрес. Тихая подстановка и есть второе определение.');

правило('язык выбирает продукт, а не дом',
    /'-' \+ язык/.test(безКом(чит(ДОМ))) && /I\.lang/.test(безКом(чит(ПРОФИЛЬ))),
    'У страниц есть `-en` и `-kg`. Человек должен попадать на документ на\n' +
    'своём языке, а не на русский.');

правило('в меню профиля есть строка документов',
    /profDocsRow/.test(безКом(чит(ПРОФИЛЬ))) &&
    /profile\.documents/.test(безКом(чит(ПРОФИЛЬ))) &&
    /bindRowClick\('profDocsRow'/.test(безКом(чит(ПРОФИЛЬ))),
    'Строка без обработчика — мёртвый орган управления: нажал, ничего не\n' +
    'произошло.');

правило('окно документов строит ссылки через дом',
    /KSLT_DOKUMENTY/.test(безКом(чит(ПРОФИЛЬ))) && /\.все\(/.test(безКом(чит(ПРОФИЛЬ))) &&
    !/pages\/privacy-policy/.test(безКом(чит(ПРОФИЛЬ))),
    'Адреса собирает дом. Своя склейка здесь — второе определение.');

/* ПРИЗНАК НЕ ПЕРЕШАГИВАЛ СКОБКУ ВНУТРИ ЗОВА: `[^)]*` обрывался на `)`
   от `getAttribute('data-doc')`, и правило падало на верном коде.
   Промах поймал сам сторож на первом прогоне. */
правило('документ открывается системным браузером',
    /window\.open\([\s\S]{0,140}?'_system'\s*\)/.test(безКом(чит(ПРОФИЛЬ))),
    'Документ длинный: его читают, копируют и показывают юристу. Держать\n' +
    'его в накладке без адресной строки хуже.');

правило('у каждого документа есть название на всех трёх языках',
    (function () {
        const ключи = ['docPrivacy', 'docOffer', 'docRules', 'docTerms', 'documents', 'docOpens'];
        const с = чит(СЛОВАРЬ);
        return ключи.every(к => {
            const м = с.match(new RegExp("'profile\\." + к + "':\\s*\\{([^}]*)\\}"));
            if (!м) return false;
            return ['ru', 'en', 'kg'].every(я => new RegExp(я + ":\\s*'[^']+'").test(м[1]));
        });
    })(),
    'Документ без названия — пустая строка в списке.');

правило('дом подключён и грузится ДО профиля',
    (function () {
        const t = чит(РАЗМЕТКА);
        const д = t.indexOf('kslt-dokumenty.js');
        const п = t.indexOf('js/screens/profile.js?');
        return д !== -1 && п !== -1 && д < п;
    })(),
    'Без дома строка документов упадёт на `undefined` при первом нажатии.');

правило('третьего адреса сайта в приложении больше нет',
    !/github\.io/.test(безКом(чит('mobile/www/js/auth.js'))) &&
    !/reset-password\.html/.test(безКом(чит('mobile/www/js/auth.js'))),
    'В `auth.js` жил `https://bossyko.github.io/KSLT-project`, и вёл он на\n' +
    '`pages/reset-password.html`, которой в репозитории НЕТ ВОВСЕ. Зовов у\n' +
    'той функции было ноль: пароль меняют кодом. ЗАПАСНОЙ ХОД, ВЕДУЩИЙ В\n' +
    'НИКУДА, ХУЖЕ ОТСУТСТВУЮЩЕГО.');

правило('на сайте копии дома нет — и это намеренно',
    !fs.existsSync(path.join(КОРЕНЬ, 'js/kslt-dokumenty.js')) &&
    /footer-ru\.html/.test(чит(ДОМ)) &&
    /offer\.html/.test(чит('partials/footer-ru.html')),
    'На сайте документы достижимы из подвала, и строит их разметка.\n' +
    'Копия, которую никто не зовёт, — мёртвый файл, а не сведение.\n' +
    'Правило парное: уберут ссылки из подвала — оно упадёт.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else { console.log('  ок      документы: все ' + держится + ' правил держатся · документов ' + СТРАНИЦЫ.length + '\n'); }
