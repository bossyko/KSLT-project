/**
 * ЗАМОРОЗКА УЗКИХ ВИДОВ: ПОЛОСА ФИЛЬТРОВ РЕЙТИНГА И КАРТОЧКА РАЗРЯДА.
 *
 * Два экрана, одна болезнь: правило, написанное для ДРУГОГО места,
 * доставало сюда и ломало то, чего не имело в виду.
 *   • полоса фильтров рейтинга на телефоне ЛЁЖА брала базовые размеры,
 *     потому что ступень ≤640 отключается по ШИРИНЕ, а не по повороту;
 *   • блок «Предстоящие» на странице разряда ловил правила ВИТРИНЫ
 *     категорий обзорной — плитки по две в ряд и высоту 200.
 *
 * ЧТО ЗАМОРАЖИВАЕТСЯ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • узкий вид по высоте и повороту, а не новой шириной: границ две — 640 и 992;
 *   • кнопка меньше 44 законна только вместе со слоем цели 44;
 *   • воздух полосы — ступени шкалы;
 *   • исключение названо АДРЕСНО, а правило витрины остаётся витрине;
 *   • место под афишу считается из ширины самой афиши, а не числом;
 *   • порядок правил в файле решает: блок узкого вида стоит ПОСЛЕ ≤640.
 *
 *   node tools/check-telefon-razdela.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const РЕЙТ  = безКом(чит('css/players.css'));
const ОБЗОР = безКом(чит('css/tournaments-overview.css'));
const ТУРН  = безКом(чит('css/tournaments.css'));

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };

/* Окно правила — свой блок, а не весь файл */
const блок = (текст, якорь, откуда) => {
    const i = текст.indexOf(якорь, откуда || 0);
    if (i === -1) return '';
    let j = текст.indexOf('{', i), г = 0, с = j;
    for (; j < текст.length; j++) {
        if (текст[j] === '{') г++;
        else if (текст[j] === '}') { г--; if (г === 0) return текст.slice(с + 1, j); }
    }
    return '';
};

const ЛЁЖА = '@media (max-height: 500px) and (orientation: landscape)';

/* ══ 1. ПОЛОСА ФИЛЬТРОВ РЕЙТИНГА НА ТЕЛЕФОНЕ ЛЁЖА ══════════════════════ */

const ЛЁЖА_РЕЙТ = блок(РЕЙТ, ЛЁЖА);

правило('узкий вид рейтинга задан высотой и поворотом, а не новой шириной',
    ЛЁЖА_РЕЙТ !== '',
    'Ширины в медиа только 640 и 992, остальное делится высотой и поворотом.\n' +
    '          Без этого блока на 667 отключается ступень ≤640 и возвращаются\n' +
    '          базовые размеры: полоса занимала 173 из 375 — 46% экрана.');

правило('в рейтинге не завелось третьей границы по ширине',
    !/@media \(max-width: (?!640px|992px)\d+px\)/.test(РЕЙТ),
    'Две границы на весь сайт. Третья разводит правила по видам, которых\n' +
    '          нет ни в одной другой мере.');

правило('чип пола сходит на ступень ниже ТОЛЬКО вместе со слоем цели 44',
    /\.pl-gender-tab\s*\{[^}]*min-height:\s*var\(--btn-h-sm\)/.test(ЛЁЖА_РЕЙТ) &&
    /\.pl-gender-tab::after\s*\{[^}]*height:\s*var\(--btn-h-md\)/.test(ЛЁЖА_РЕЙТ),
    'Правило выведено на пилюле разряда: КНОПКА 36 ЗАКОННА, ЕСЛИ У НЕЁ ЕСТЬ\n' +
    '          СЛОЙ ЦЕЛИ 44. Ступень без слоя — это цель нажатия меньше нормы\n' +
    '          WCAG 2.5.5 на том самом виде, где целятся пальцем.');

правило('слой цели у чипа умеет лежать поверх — у чипа есть точка отсчёта',
    /\.pl-gender-tab\s*\{[^}]*position:\s*relative/.test(ЛЁЖА_РЕЙТ),
    'Без точки отсчёта слой растянется по ближайшему предку, а не по чипу,\n' +
    '          и цель уедет с кнопки.');

правило('воздух полосы в узком виде — ступени шкалы, а не числа',
    /\.pl-filters-section\s*\{\s*padding-block:\s*var\(--space-[a-z0-9]+\) var\(--space-[a-z0-9]+\)/.test(ЛЁЖА_РЕЙТ) &&
    /\.pl-gender-tabs\s*\{\s*margin-bottom:\s*var\(--space-/.test(ЛЁЖА_РЕЙТ),
    'Полоса липкая: её доля экрана держится всю прокрутку. Воздух тут\n' +
    '          стоит дороже, чем где-либо, и считается ступенями, а не на глаз.');

правило('пилюли и «Показать всех» стоят ОДНОЙ строкой',
    /\.pl-category-row\s*\{[^}]*grid-template-columns:\s*minmax\(0, auto\) auto/.test(ЛЁЖА_РЕЙТ) &&
    /\.pl-view-all\s*\{[^}]*grid-row:\s*1/.test(ЛЁЖА_РЕЙТ),
    'Второй строкой ссылка добавляет 29 пикселей к липкой полосе на виде,\n' +
    '          где высота экрана 375.');

правило('место каждого элемента названо колонкой, а не порядком',
    /\.pl-category-pills\s*\{[^}]*grid-column:\s*1/.test(ЛЁЖА_РЕЙТ) &&
    /\.pl-view-all\s*\{[^}]*grid-column:\s*2/.test(ЛЁЖА_РЕЙТ),
    'Состав строки меняется — в поиске пилюли уходят. Если место брать\n' +
    '          первым свободным, ссылка переедет на их клетку.');

правило('режим поиска под правило узкого вида не попадает',
    /\.pl-filters-searching \.pl-category-row\s*\{/.test(РЕЙТ),
    'У поиска свой селектор весом выше (0,2,0 против 0,1,0): он и решает,\n' +
    '          пока существует. Если его снять, поле поиска встанет в колонку\n' +
    '          пилюль, которых в этом режиме нет.');

правило('блок узкого вида стоит ПОСЛЕ правил ≤640 — порядок решает',
    РЕЙТ.lastIndexOf('@media (max-width: 640px)') < РЕЙТ.indexOf(ЛЁЖА),
    'Вес у них одинаковый, и при равном весе побеждает тот, что ниже.\n' +
    '          Эту же беду я уже ловил 06.10 на обложке: ландшафтное правило\n' +
    '          стояло выше базового и не действовало вовсе.');

правило('на странице разряда рейтинга «назад», поиск и название — одной строкой',
    /\.pl-cat-mode \.pl-category-row\s*\{[^}]*grid-template-columns:\s*minmax\(0, 1fr\) auto minmax\(0, 1fr\)/.test(ЛЁЖА_РЕЙТ) &&
    /\.pl-cat-mode \.pl-category-row \.trn-search-wrap\s*\{[^}]*grid-row:\s*1/.test(ЛЁЖА_РЕЙТ),
    'Поиск второй строкой держал полосу разряда на 181 из 375 — 48% экрана.');

/* ══ 2. СТРАНИЦА РАЗРЯДА НА ТЕЛЕФОНЕ: КАРТОЧКА, А НЕ ПЛИТКА ════════════ */

/* Окно — ТОТ медиаблок, внутри которого лежит исключение, а не первый
   попавшийся: правил ≤640 в файле несколько */
const РАЗРЯД640 = (() => {
    const где = ОБЗОР.indexOf('.trn-block .to-card-grid');
    if (где === -1) return '';
    const н = ОБЗОР.lastIndexOf('@media (max-width: 640px)', где);
    return н === -1 ? '' : блок(ОБЗОР.slice(н), '@media (max-width: 640px)');
})();

правило('исключение названо АДРЕСНО — блоком раздела, а не всем подряд',
    /\.trn-block \.to-card-grid\s*\{[^}]*grid-template-columns:\s*1fr/.test(РАЗРЯД640),
    'Правила витрины писались для категорий обзорной и для баттлов. Снимать\n' +
    '          их целиком нельзя — поедет страница баттлов; называем адресно.');

правило('правило витрины осталось витрине — его не сняли заодно',
    /^\s*\.to-card-grid\s*\{\s*grid-template-columns:\s*1fr 1fr;/m.test(ОБЗОР),
    'Плитками по две в ряд пользуется страница баттлов\n' +
    '          (js/battles-overview.js:445). Если правило исчезнет, поедет она.');

правило('карточка раздела берёт высоту от содержимого, а не от ступени плитки',
    /\.trn-block \.to-featured,\s*\.trn-block \.to-featured-side\s*\{[^}]*height:\s*auto/.test(РАЗРЯД640),
    'Внутри `.to-featured-side` стоит та же карточка `.tc`, что в ленте\n' +
    '          обзорной. Ступень 200 обрезала ей низ вместе с кнопкой записи.');

правило('полоса второго турнира ВИДНА на странице разряда',
    /\.trn-block \.to-side-stack \.to-compact-thumb\s*\{\s*display:\s*grid/.test(РАЗРЯД640),
    'На витрине строчная раскладка не нужна и снята целиком. Здесь полоса —\n' +
    '          ЕДИНСТВЕННЫЙ вид второго турнира: он пропадал с экрана.');

правило('место под афишу считается ИЗ ЕЁ ШИРИНЫ, а не повторяет число',
    /\.trn-block \.to-side-stack \.to-compact-thumb\s*\{[^}]*padding-left:\s*calc\(var\(--to-thumb\)/.test(РАЗРЯД640),
    'Афиша лежит слоем `::before` и места под себя не занимает. Если поле\n' +
    '          задать отдельным числом, они разъедутся на первой же правке —\n' +
    '          ровно это и случилось: текст лёг на афишу.');

правило('ширина афиши на телефоне — ступень шкалы',
    /\.trn-block \.to-side-stack \.to-compact-thumb\s*\{[^}]*--to-thumb:\s*96px/.test(РАЗРЯД640),
    '96 — это 8 × 12. При 120 строке оставалось 187, и кнопка записи 170\n' +
    '          вставала впритык к краю.');

правило('на телефоне карточка идёт ОДНОЙ колонкой',
    /\.trn-block \.to-side-stack \.to-compact-thumb\s*\{[^}]*grid-template-columns:\s*minmax\(0, 1fr\)/.test(РАЗРЯД640),
    'Столб объявляет `auto minmax(0, 1fr)` — раскладку широкого вида, где\n' +
    '          слева столбец меты. На телефоне мета это РЯД, и колонка `auto`\n' +
    '          забирала всю строку: название получало ширину НОЛЬ.');

правило('колонка меты на телефоне не держит ширину широкого вида',
    /\.trn-block \.to-side-stack \.to-compact-thumb \.to-compact-left\s*\{[^}]*width:\s*auto/.test(РАЗРЯД640),
    'Ширина 104 оставлена для столбца; ряду из трёх плашек её мало, и он\n' +
    '          ломается на три строки.');

/* ══ 3. ПОЛОСА ПОИСКА ПОД ЦИФРАМИ ══════════════════════════════════════ */

const РАЗРЯД768 = блок(ТУРН, '@media (max-width: 768px)');

правило('воздух между обложкой и полосой — ступень шкалы, а не ноль',
    /\.tournament-hero\s*\{\s*margin-bottom:\s*var\(--space-/.test(РАЗРЯД768),
    'Ноль не годится: без отбивки поиск липнет к фотографии. Нужна ступень,\n' +
    '          а не число и не её отсутствие.');

правило('поле полосы фильтров поднято у ТОЙ полосы, что стоит под обложкой',
    /\.trn-sticky-sentinel \+ \.trn-filters\s*\{\s*padding-top:\s*var\(--space-/.test(РАЗРЯД768),
    'Полоса общая для нескольких страниц. Названа через соседа, потому что\n' +
    '          поднять надо ту, у которой сверху обложка.');

правило('ссылка «назад» подняла текст, не тронув цель нажатия',
    /\.trn-filters \.trn-back\s*\{\s*padding-top:\s*0/.test(РАЗРЯД768) &&
    /min-height:\s*var\(--btn-h-md\)/.test(ТУРН),
    'Высоту коробки держит `min-height`, поле сверху только опускало текст\n' +
    '          внутри неё. Если высоту начнёт давать поле, цель нажатия уедет.');

if (ошибки.length === 0) {
    console.log(`\n  ок      телефон раздела: ${ВСЕГО} правил\n`);
    process.exit(0);
}
console.log(`\n  НЕ ТАК  телефон раздела: ${ВСЕГО} правил, упало ${ошибки.length}.\n`);
ошибки.forEach(о => {
    console.log(`  ✗ ${о.имя}`);
    if (о.подсказка) console.log(`          ${о.подсказка}`);
    console.log('');
});
process.exit(1);
