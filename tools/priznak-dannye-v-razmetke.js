function всеJS(дир, итог) {
    итог = итог || [];
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        const п = path.join(дир, э.name);
        if (э.isDirectory()) всеJS(п, итог);
        else if (э.name.endsWith('.js')) итог.push(path.relative(КОРЕНЬ, п).split(path.sep).join('/'));
    }
    return итог;
}

/** Столбцы, которые пишет человек — ЧИТАЮТСЯ ИЗ СХЕМЫ. */
function столбцыЧеловека() {
    const дир = path.join(КОРЕНЬ, 'supabase', 'migrations');
    let схема = fs.readdirSync(дир).filter(и => и.endsWith('.sql'))
        .map(и => fs.readFileSync(path.join(дир, и), 'utf8')).join('\n');
    схема += fs.readFileSync(path.join(КОРЕНЬ, 'supabase', 'schema.sql'), 'utf8');
    for (const д of [path.join(КОРЕНЬ, 'sql', 'схема'), path.join(КОРЕНЬ, 'sql', 'архив')]) {
        if (!fs.existsSync(д)) continue;
        схема += '\n' + fs.readdirSync(д).filter(и => и.endsWith('.sql'))
            .map(и => fs.readFileSync(path.join(д, и), 'utf8')).join('\n');
    }
    const набор = new Set();
    const сПодчерком = [];
    /* ОПРЕДЕЛЕНИЕ СТОЛБЦА ЖИВЁТ НЕ В ОДНОЙ СТРОКЕ, И CHECK ЧАСТО СТОИТ НА
       СЛЕДУЮЩЕЙ: `ADD COLUMN pause_reason text` + перевод строки +
       `CHECK (pause_reason IN (...))`. Построчное чтение видело столбец и не
       видело его CHECK — и перечисление попадало в «пишет человек».
       Поэтому схема сперва СКЛЕИВАЕТСЯ В ОПРЕДЕЛЕНИЯ: каждое определение
       столбца — от его имени до запятой на нулевой глубине или до `;`. */
    const определения = [];
    {
        /* Комментарии `-- …` вырезаются: они тоже называют столбцы словами.
           Запятая РЕЖЕТ на нулевой И на первой глубине: тело CREATE TABLE
           целиком лежит внутри одной пары скобок, и на нулевой глубине
           запятых между столбцами нет вовсе. */
        const чисто = схема.replace(/--[^\n]*/g, ' ');
        let тек = '', глубина = 0;
        for (const з of чисто) {
            if (з === '(') глубина++;
            else if (з === ')') глубина--;
            if ((з === ',' && глубина <= 1) || з === ';') { определения.push(тек); тек = ''; continue; }
            тек += з;
        }
        if (тек.trim()) определения.push(тек);
    }
    определения.forEach(о => {
        /* ПЕРВЫЙ СТОЛБЕЦ ТАБЛИЦЫ ЛЕЖИТ В ОДНОМ КУСКЕ С `CREATE TABLE`:
           запятых перед ним нет, и без снятия этой головы он не находился
           вовсе — у каждой таблицы терялся первый текстовый столбец.
           Поймал прувер: откат с таблицей `_проба` перестал ронять правило. */
        const с = о.replace(/\s+/g, ' ').trim()
            /* `\w` НЕ ЗНАЕТ КИРИЛЛИЦЫ — правило трекера, и прувер поймал меня
               на нём ещё раз: имя таблицы в откате было `_проба`, голова не
               снималась, и столбец с подчерка не находился. */
            .replace(/^.*?\bcreate\s+table\s+(?:if\s+not\s+exists\s+)?["']?[^\s(]+["']?\s*\(\s*/i, '');
        const м = /^["']?([a-z_][a-z0-9_]*)["']?\s+["']?(?:text|character varying|varchar|citext)["']?/i.exec(с)
            || /\badd\s+column\s+(?:if\s+not\s+exists\s+)?["']?([a-z_][a-z0-9_]*)["']?\s+["']?(?:text|character varying|varchar|citext)["']?/i.exec(с);
        if (!м) return;
        const имя = м[1];
        if (имя.charAt(0) === '_') сПодчерком.push(имя);
        if (/\bCHECK\b/i.test(с)) return;
        if (имя === 'id' || /_id$/.test(имя) || /uuid/i.test(с)) return;
        набор.add(имя);
    });
    return { набор: набор, сПодчерком: сПодчерком };
}

function имяЗова(у) {
    if (!у.callee) return null;
    if (у.callee.type === 'Identifier') return у.callee.name;
    if (у.callee.type === 'MemberExpression') {
        const об = у.callee.object, св = у.callee.property;
        const и = об.type === 'Identifier' ? об.name
            : (об.type === 'MemberExpression' && об.property.type === 'Identifier' ? об.property.name : null);
        return (и ? и + '.' : '') + (св.type === 'Identifier' ? св.name : '');
    }
    return null;
}
function корень(x) {
    while (x && (x.type === 'MemberExpression' || x.type === 'CallExpression')) x = x.object || x.callee;
    const имя = x && x.type === 'Identifier' ? x.name : null;
    return имя;
}
/** Корень БЕЗ `window`: `window.KSLT_SLOY.слой` — это дом, а не `window`. */
function корень2(x) {
    const путь = [];
    let н = x;
    while (н && (н.type === 'MemberExpression' || н.type === 'CallExpression')) {
        if (н.type === 'MemberExpression' && н.property && н.property.type === 'Identifier') путь.unshift(н.property.name);
        н = н.object || н.callee;
    }
    if (н && н.type === 'Identifier') путь.unshift(н.name);
    while (путь.length > 1 && (путь[0] === 'window' || путь[0] === 'globalThis')) путь.shift();
    return путь[0] || null;
}
function обход(у, дело) {
    if (!у || typeof у !== 'object') return;
    if (Array.isArray(у)) return у.forEach(н => обход(н, дело));
    дело(у);
    for (const к in у) if (к !== 'loc' && к !== 'start' && к !== 'end') обход(у[к], дело);
}
function свои(у, дело) {           /* обход тела функции БЕЗ вложенных функций */
    (function х(н) {
        if (!н || typeof н !== 'object') return;
        if (Array.isArray(н)) return н.forEach(х);
        if (н !== у && ФУНК.indexOf(н.type) !== -1) return;
        дело(н);
        for (const к in н) if (к !== 'loc' && к !== 'start' && к !== 'end') х(н[к]);
    })(у.body);
}
function части(у, и) {
    и = и || [];
    if (у.type === 'BinaryExpression' && у.operator === '+') { части(у.left, и); части(у.right, и); }
    else и.push(у);
    return и;
}
function естьРазметка(с) {
    return с.some(ч => (ч.type === 'Literal' && typeof ч.value === 'string' && РАЗМЕТКА.test(ч.value)) ||
        (ч.type === 'TemplateLiteral' && ч.quasis.some(q => РАЗМЕТКА.test(q.value.raw))));
}

function разобрать(файлы) {
    const деревья = {};
    (файлы || всеJS(path.join(КОРЕНЬ, 'js'))).forEach(ф => {
        const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
        try { деревья[ф] = { т: т, д: acorn.parse(т, { ecmaVersion: 2020, locations: true }) }; }
        catch (e) { /* файл не разбирается — его считает другой сторож */ }
    });
    return деревья;
}

/**
 * Словари файла. Три вида, и все три ЧИТАЮТСЯ:
 *  - переменная, которой присвоен объект-литерал или `KSLT_YAZYK.выбрать(...)`;
 *  - перечисление-литерал (массив объектов) — его пункты тоже свои;
 *  - ДОВОД ОБХОДЧИКА такого перечисления: `ПУНКТЫ.forEach(function (s) {…})`
 *    даёт `s`, у которого данных базы нет. Без этого правила «ярлык из своего
 *    перечисления» признак считал полем человека: имена `label`, `icon`,
 *    `title` есть и в базе.
 */
function словариФайла(д) {
    const н = new Set();
    const свои_перечисления = new Set();
    /* СЮДА Я ЗАВЁЛ БЫЛО ПЯТОЕ ЗНАНИЕ — «имя, которому присвоили объект-литерал
       вторым оператором, тоже словарь» (`var Т = window.X;` … `Т = {…}`) — И
       СНЯЛ ЕГО ПОСЛЕ ПРОВЕРКИ: дыр с ним 45 и без него 45, а прувер не смог
       уронить им ни одного правила. МЁРТВЫМ КОД НАЗЫВАЕТСЯ ПОСЛЕ ПРОВЕРКИ, И
       ЭТО КАСАЕТСЯ МОИХ СОБСТВЕННЫХ ПРАВОК ТОЖЕ: причину паузы уже закрывает
       прослеживание местных переменных. */
    обход(д, у => {
        if (у.type !== 'VariableDeclarator' || у.id.type !== 'Identifier' || !у.init) return;
        const и = у.init;
        if (и.type === 'ObjectExpression') н.add(у.id.name);
        else if (и.type === 'ArrayExpression') свои_перечисления.add(у.id.name);
        else if (и.type === 'ConditionalExpression' &&
                 и.consequent.type === 'ArrayExpression' && и.alternate.type === 'ArrayExpression')
            свои_перечисления.add(у.id.name);
        /* `var L = A.L` — СЛОВАРЬ, ВЗЯТЫЙ У ДОМА, ОСТАЁТСЯ СЛОВАРЁМ. Админка
           держит свои подписи в `A.L`, и каждый её файл берёт их этой
           строкой; признак же видел здесь «иное» и считал `L[key]` полем
           человека (кусок 167). Доверие идёт от ДОМА, а не от имени `L`. */
        else if (и.type === 'MemberExpression' && !и.computed &&
                 ДОМА.indexOf(корень2(и)) !== -1) н.add(у.id.name);
        else if (и.type === 'CallExpression') {
            const зов = имяЗова(и) || '';
            if (зов.indexOf('выбрать') !== -1 || /^get[A-Z]|[Ll]abels$/.test(зов)) н.add(у.id.name);
            /* `[{…}].concat(что-то)` перечислением своим НЕ становится:
               данные приходят вторым слагаемым. Проверено на новостях. */
        }
        /* `var L = window.playerProfileLabels || KSLT_YAZYK.выбрать({…})` —
           словарь с запасным ходом на свой же словарь. Признак видел здесь
           «иное» и считал `L.message` полем человека. */
        else if (и.type === 'LogicalExpression' || и.type === 'ConditionalExpression') {
            const ветки = и.type === 'LogicalExpression' ? [и.left, и.right] : [и.consequent, и.alternate];
            const словарная = в => !!в && (в.type === 'ObjectExpression' ||
                (в.type === 'CallExpression' && ((имяЗова(в) || '').indexOf('выбрать') !== -1 ||
                                                 /^get[A-Z]|[Ll]abels$/.test(имяЗова(в) || ''))));
            if (ветки.some(словарная)) н.add(у.id.name);
        }
    });
    /* ФУНКЦИЯ, ОТДАЮЩАЯ ТОЛЬКО ЛИТЕРАЛЫ, — ТОЖЕ СЛОВАРЬ (кусок 169).
       `ddГруппы()` возвращает массив литералов с подписями из словаря языка,
       а `var группы = ddГруппы()` признак словарём не считал: он смотрел ИМЯ
       зова (`get…`, `…Labels`), а не ТЕЛО. ИМЯ ВРЁТ, ТЕЛО НЕТ.
       Условие строгое: каждая выдача — объект-литерал или массив, в котором
       каждый элемент объект-литерал или литерал. Один `return данныеБазы` —
       и функция словарём не считается. */
    const функцииСловари = new Set();
    обход(д, у => {
        if (ФУНК.indexOf(у.type) === -1 || !у.id || у.id.type !== 'Identifier') return;
        const выдачи = [];
        свои(у, н => { if (н.type === 'ReturnStatement' && н.argument) выдачи.push(н.argument); });
        if (!выдачи.length) return;
        const литерален = в => в.type === 'ObjectExpression' ||
            (в.type === 'ArrayExpression' && в.elements.every(э =>
                э && (э.type === 'ObjectExpression' || э.type === 'Literal' || э.type === 'ArrayExpression')));
        if (выдачи.every(литерален)) функцииСловари.add(у.id.name);
    });
    обход(д, у => {
        if (у.type !== 'VariableDeclarator' || у.id.type !== 'Identifier' || !у.init) return;
        if (у.init.type !== 'CallExpression') return;
        const зов = имяЗова(у.init) || '';
        if (функцииСловари.has(зов)) { н.add(у.id.name); свои_перечисления.add(у.id.name); }
    });

    /* доводы обходчиков своих перечислений */
    обход(д, у => {
        if (у.type !== 'CallExpression' || !у.callee || у.callee.type !== 'MemberExpression') return;
        const метод = у.callee.property && у.callee.property.type === 'Identifier' ? у.callee.property.name : '';
        if (['forEach', 'map', 'filter', 'some', 'every', 'find'].indexOf(метод) === -1) return;
        const корешок = у.callee.object;
        const имяПеречисления = корешок && корешок.type === 'Identifier' ? корешок.name : null;
        if (!имяПеречисления || !свои_перечисления.has(имяПеречисления)) return;
        const тело = у.arguments[0];
        if (!тело || ФУНК.indexOf(тело.type) === -1) return;
        тело.params.forEach(п => { if (п.type === 'Identifier') н.add(п.name); });
    });
    свои_перечисления.forEach(и => н.add(и));
    return н;
}

/**
 * Для каждой функции файла — НАБОР НОМЕРОВ доводов, экранированных на каждом
 * пути выдачи. Замыкание: функция, зовущая другую с экранированным доводом,
 * сама становится экраном для своего.
 */
function экраныФайла(д, словарь) {
    /* MAP, А НЕ ОБЪЕКТ: у объекта есть `toString` из прототипа, и признак
       принимал зов `toString` за экран — падал на `набор.has`.
       СПИСОК ПО ИМЕНИ ЖИВЁТ В MAP, ИНАЧЕ В НЁМ УЖЕ ЕСТЬ ЧУЖИЕ ИМЕНА. */
    const экраны = new Map();          /* имя -> 'все' | Set номеров доводов */
    БАЗОВЫЕ_ЭКРАНЫ.forEach(и => экраны.set(и, 'все'));
    const функции = [];
    обход(д, у => { if (у.type === 'FunctionDeclaration' && у.id) функции.push(у); });

    /* БЕЗОПАСНЫЕ ПОЛОЖЕНИЯ ДОВОДА (кусок 169). Довод может стоять в выдаче и
       НЕ дойти до разметки текстом — тогда функция чиста по этому доводу, хотя
       экранирования в ней нет вовсе:
         · КЛЮЧ СЛОВАРЯ — `СЛОВА[род]`: в разметку идёт значение словаря;
         · СРАВНЕНИЕ — `род === 'men'`: отдаёт «да» или «нет»;
         · АРИФМЕТИКА — `Math.round(цена * доля / 100)`: отдаёт число;
         · ЧИСТИЛКА ЦИФР — `телефон.replace(/\D/g, '')`: от текста остаются
           только цифры, и кавычке взяться негде;
         · ГРУППА РЕГУЛЯРКИ — `(адрес.match(/([\w-]{11})/) || [])[1]`;
         · ДЛИНА — `список.length`.
       Каждое из них ЧИТАЕТСЯ ПО УЗЛУ, а не по имени функции: имя врёт, узел
       нет. Это те самые двенадцать мест, которые кусок 168 намерил как
       «значение прошло через местную функцию». */
    const АРИФМЕТИКА = ['*', '/', '-', '%', '**'];
    const ЧИСЛОВЫЕ_ЗОВЫ = ['Math.round', 'Math.floor', 'Math.ceil', 'Math.abs',
                           'Math.min', 'Math.max', 'Number', 'parseInt', 'parseFloat'];
    function цифрыТолько(н) {
        /* `.replace(/\D/g, '')` — и любая цепочка, кончающаяся этим. */
        if (!н || н.type !== 'CallExpression' || !н.callee || н.callee.type !== 'MemberExpression') return false;
        if ((н.callee.property.name || '') !== 'replace') return false;
        const р = н.arguments[0];
        if (!р || р.type !== 'Literal' || !р.regex) return false;
        return /\\D/.test(р.regex.pattern);
    }
    function группаРегулярки(н) {
        /* `строка.match(/…/)` — в разметку идёт то, что разрешила регулярка. */
        return !!(н && н.type === 'CallExpression' && н.callee && н.callee.type === 'MemberExpression' &&
                  ['match', 'exec'].indexOf(н.callee.property.name || '') !== -1);
    }

    /* БЕЗОПАСНОЕ ПОЛОЖЕНИЕ ПОГЛОЩАЕТ ДОВОД, А НЕ СКРЫВАЕТ ЕГО. Если довод
       стоит внутри сравнения, ключа словаря, арифметики или чистилки, он ВИДЕН
       (функция им пользуется) и при этом ЧИСТ. Без этой пометки функция
       считалась «довода не видит» и экраном не становилась — именно так
       `extractYoutubeId` оставался для признака непрозрачным. */
    function естьДовод(н, довод) {
        let есть = false;
        (function х(у) {
            if (есть || !у || typeof у !== 'object') return;
            if (Array.isArray(у)) return у.forEach(х);
            if (у.type === 'Identifier' && у.name === довод) { есть = true; return; }
            for (const к in у) if (к !== 'loc' && к !== 'start' && к !== 'end') х(у[к]);
        })(н);
        return есть;
    }

    function подЭкраном(выдача, довод, карта) {
        let обёрнут = true, встретился = false;
        const развёрнуто = new Set();
        const поглотить = н => { if (естьДовод(н, довод)) встретился = true; };
        (function х(н, под) {
            if (!н || typeof н !== 'object') return;
            if (Array.isArray(н)) return н.forEach(э => х(э, под));
            /* СРАВНЕНИЕ — НЕ ПОДСТАНОВКА. */
            if (н.type === 'BinaryExpression' &&
                ['===', '!==', '==', '!=', '<', '>', '<=', '>=', 'in', 'instanceof'].indexOf(н.operator) !== -1) { поглотить(н); return; }
            /* АРИФМЕТИКА ОТДАЁТ ЧИСЛО. */
            if (н.type === 'BinaryExpression' && АРИФМЕТИКА.indexOf(н.operator) !== -1) { поглотить(н); return; }
            if (н.type === 'CallExpression' && ЧИСЛОВЫЕ_ЗОВЫ.indexOf(имяЗова(н) || '') !== -1) { поглотить(н); return; }
            /* ЧИСТИЛКА ЦИФР И ГРУППА РЕГУЛЯРКИ. */
            if (цифрыТолько(н) || группаРегулярки(н)) { поглотить(н); return; }
            /* КЛЮЧ СЛОВАРЯ: `СЛОВА[род]` — ключ до разметки не доходит. */
            if (н.type === 'MemberExpression' && н.computed) {
                const к = корень2(н.object);
                if (к && (словарь.has(к) || ДОМА.indexOf(к) !== -1)) { поглотить(н); return; }
            }
            /* ДЛИНА — НЕ ЗНАЧЕНИЕ. */
            if (н.type === 'MemberExpression' && н.property && н.property.type === 'Identifier' &&
                н.property.name === 'length') { поглотить(н); return; }
            /* МЕСТНАЯ ПЕРЕМЕННАЯ РАЗВЁРТЫВАЕТСЯ: экранирование часто стоит не в
               `return`, а в строке выше — `var рамка = … A.esc(opts.photo) …`,
               и выдача лишь склеивает `рамка`. Без этого шага `extrasRow` и
               ему подобные экранами не считались. Круг обрывается набором. */
            if (н.type === 'Identifier' && н.name !== довод && карта && карта.has(н.name) &&
                !развёрнуто.has(н.name)) {
                развёрнуто.add(н.name);
                карта.get(н.name).forEach(и => { if (и && и.type !== 'ДОВОД') х(и, под); });
                return;
            }
            /* ПРОВЕРКА НА ПУСТОТУ — НЕ ПОДСТАНОВКА, и при выводе экранов тоже:
               `фото ? '<img src=' + экр(фото) : …` — довод обёрнут, хотя в
               условии он стоит как есть. Без этого шесть переходников,
               экранирующих своё, экранами не считались. */
            if (н.type === 'ConditionalExpression') { х(н.consequent, под); х(н.alternate, под); return; }
            if (н.type === 'LogicalExpression' && н.operator === '&&') { х(н.right, под); return; }
            let п = под;
            if (н.type === 'CallExpression') {
                const зов = имяЗова(н) || '';
                const хвост = зов.indexOf('.') !== -1 ? зов.split('.')[1] : зов;
                const набор = экраны.get(зов) || экраны.get(хвост);
                if (набор === 'все' || ДОМА.indexOf(корень2(н)) !== -1) п = true;
                else if (набор) {
                    /* экран только для своих номеров: остальные доводы идут как есть */
                    н.arguments.forEach((а, и) => х(а, под || набор.has(и)));
                    х(н.callee, под);
                    return;
                }
            }
            if (н.type === 'Identifier' && н.name === довод) {
                встретился = true;
                if (!п) обёрнут = false;
            }
            for (const к in н) if (к !== 'loc' && к !== 'start' && к !== 'end') х(н[к], п);
        })(выдача, false);
        return { обёрнут: обёрнут, встретился: встретился };
    }

    let росло = true, круг = 0;
    while (росло && круг < 8) {
        росло = false; круг++;
        функции.forEach(ф => {
            const имя = ф.id.name;
            if (экраны.get(имя) === 'все') return;
            const выдачи = [];
            свои(ф, н => { if (н.type === 'ReturnStatement' && н.argument) выдачи.push(н.argument); });
            if (!выдачи.length) return;
            const набор = экраны.get(имя) ? new Set(экраны.get(имя)) : new Set();
            const карта = источникиФункции(ф);
            /* ВСЁ, ЧЕМ ФУНКЦИЯ МОЖЕТ ОТДАТЬ РАЗМЕТКУ: выдачи, накопление через
               `+=` и запись в `innerHTML`. Нужно, чтобы отличить довод, который
               ДО РАЗМЕТКИ НЕ ДОХОДИТ ВОВСЕ, от довода, который до неё доходит
               неэкранированным. */
            const отдачи = выдачи.slice();
            свои(ф, н => {
                if (н.type === 'AssignmentExpression' && н.operator === '+=') отдачи.push(н.right);
                if (н.type === 'AssignmentExpression' && н.left.type === 'MemberExpression' &&
                    н.left.property.type === 'Identifier' &&
                    ['innerHTML', 'outerHTML'].indexOf(н.left.property.name) !== -1) отдачи.push(н.right);
            });
            ф.params.forEach((п, и) => {
                if (п.type !== 'Identifier' || набор.has(и)) return;
                let виден = false, чисто = true;
                выдачи.forEach(в => {
                    const р = подЭкраном(в, п.name, карта);
                    if (р.встретился) { виден = true; if (!р.обёрнут) чисто = false; }
                });
                /* ДОВОД, КОТОРЫЙ НЕ ДОХОДИТ НИ ДО ОДНОЙ ОТДАЧИ, ДО РАЗМЕТКИ НЕ
                   ДОХОДИТ ВОВСЕ. `отсчёт(дата, время, статус)` сравнивает статус
                   (`статус === 'past'`) и больше нигде его не поминает — функция
                   чиста по этому доводу, хотя экранирования в ней нет. Проверка
                   идёт по ОТДАЧАМ, а не по телу целиком: довод, положенный в
                   переменную, доходит до разметки через неё, и это ловит
                   прослеживание выше. */
                if (!виден) {
                    const дошёл = отдачи.some(о => подЭкраном(о, п.name, карта).встретился);
                    if (!дошёл) { набор.add(и); росло = true; return; }
                }
                if (виден && чисто) { набор.add(и); росло = true; }
            });
            if (набор.size) экраны.set(имя, набор);
        });
    }
    void словарь;
    return экраны;
}

/**
 * ИСТОЧНИКИ ПЕРЕМЕННЫХ ОДНОЙ ФУНКЦИИ (кусок 159).
 *
 * Признак 158 видел `t.image`, но не видел `var постер = t.image`, и ровно
 * так адрес афиши турнира попал в `style="…url(…)"` мимо экранирования.
 * Здесь для каждой функции собирается карта «имя -> что в него положили»:
 * объявления, присваивания и `+=`. Доводы помечаются особо — за них отвечает
 * зовущий, и их проверяет другое правило.
 *
 * ПРОСЛЕЖИВАНИЕ ИДЁТ ТОЛЬКО ВНУТРИ ОДНОЙ ФУНКЦИИ. Дальше начинается чужая
 * область, где то же имя значит другое, и признак начнёт врать в обе стороны.
 */
function источникиФункции(фн) {
    const карта = new Map();
    const добавить = (имя, выр) => {
        if (!карта.has(имя)) карта.set(имя, []);
        карта.get(имя).push(выр);
    };
    свои(фн, н => {
        if (н.type === 'VariableDeclarator' && н.id.type === 'Identifier' && н.init)
            добавить(н.id.name, н.init);
        if (н.type === 'AssignmentExpression' && н.left.type === 'Identifier' &&
            (н.operator === '=' || н.operator === '+=')) добавить(н.left.name, н.right);
    });
    фн.params.forEach(п => { if (п.type === 'Identifier') добавить(п.name, { type: 'ДОВОД' }); });
    return карта;
}

/**
 * ЗОВЫ ИМЕНОВАННЫХ ФУНКЦИЙ ФАЙЛА (кусок 160).
 *
 * Признак 159 останавливался на ДОВОДЕ: за довод отвечает зовущий, а зовущий
 * был за границей прослеживания. Таких доводов замерено 263. Здесь строятся
 * две карты по файлу — имя функции к её узлу и имя функции к её зовам, — и
 * признак идёт из тела в довод зовущего.
 *
 * ГРАНИЦА ТА ЖЕ — ОДИН ФАЙЛ. Зов из другого файла признаку не виден: там
 * другая область и другие имена. Функций, чьи доводы идут в разметку, 72;
 * зовов у них в своих файлах 228, и у четырёх зовов в файле нет вовсе —
 * их зовут снаружи. Это число держит правило.
 */
function зовыФайла(д) {
    const функции = new Map();
    const зовы = new Map();
    обход(д, у => { if (у.type === 'FunctionDeclaration' && у.id) функции.set(у.id.name, у); });
    обход(д, у => {
        if (у.type !== 'CallExpression' || !у.callee || у.callee.type !== 'Identifier') return;
        const имя = у.callee.name;
        if (!функции.has(имя)) return;
        if (!зовы.has(имя)) зовы.set(имя, []);
        зовы.get(имя).push(у);
    });
    return { функции: функции, зовы: зовы };
}

/**
 * Находки файла. Возвращает { дыры, вАтрибуте, зовы, отдают, копят, склеек }.
 * Дыра — чтение столбца, который пишет человек, попавшее в строку с разметкой
 * не под экраном и не из словаря.
 */
function находкиФайла(ф, т, д, ПИШЕТ) {
    const словарь = словариФайла(д);
    const экраны = экраныФайла(д, словарь);
    const дыры = [], вАтрибуте = [], безопасные = [];
    let зовы = 0, отдают = 0, копят = 0, склеек = 0, переменных = 0;

    обход(д, у => {
        if (ФУНК.indexOf(у.type) === -1) return;
        let отдаёт = false, копит = false;
        свои(у, н => {
            if (н.type === 'ReturnStatement' && н.argument && естьРазметка(части(н.argument))) отдаёт = true;
            if (н.type === 'AssignmentExpression' && н.operator === '+=' && естьРазметка(части(н.right))) копит = true;
        });
        if (отдаёт) отдают++;
        else if (копит) копят++;
    });

    /* карта функций: заполняется тем же проходом, что ищет склейки */
    const картаФункций = new Map();
    let мояКарта = new Map();
    let мояФункция = null;
    const вПути = new Set();
    const { зовы: зовыФункций } = зовыФайла(д);
    const вЗовах = new Set();
    let безЗовов = 0;

    /* кто объемлет узел: нужен, чтобы у зовущего взять его карту переменных */
    const родители = new Map();
    обход(д, у => {
        for (const к in у) {
            if (к === 'loc' || к === 'start' || к === 'end') continue;
            const з = у[к];
            if (Array.isArray(з)) з.forEach(н => { if (н && typeof н === 'object' && н.type) родители.set(н, у); });
            else if (з && typeof з === 'object' && з.type) родители.set(з, у);
        }
    });
    function чьяЭтоФункция(узел) {
        let н = родители.get(узел);
        while (н) { if (ФУНК.indexOf(н.type) !== -1) return н; н = родители.get(н); }
        return null;
    }

    function чужое(у, итог) {
        if (!у || typeof у !== 'object') return итог;
        if (Array.isArray(у)) { у.forEach(н => чужое(н, итог)); return итог; }
        /* ПЕРЕМЕННАЯ РАЗВОРАЧИВАЕТСЯ ДО ТОГО, ЧТО В НЕЁ ПОЛОЖИЛИ (кусок 159).
           Круг по именам обрывается набором `вПути`: `h += h + …` иначе
           уводит признак в бесконечность. */
        if (у.type === 'Identifier') {
            if (вПути.has(у.name)) return итог;
            const ист = мояКарта.get(у.name);
            if (!ист || !ист.length) return итог;
            вПути.add(у.name);
            /* МЕСТО НАЗЫВАЕТСЯ ПО ПОДСТАНОВКЕ, А НЕ ПО ПРИСВАИВАНИЮ: править
               надо там, где переменная входит в разметку. Одна и та же
               переменная может идти и в `input.value`, где экранирование
               только испортит текст. Источник приписывается рядом. */
            /* ПАРА «УЗЕЛ И МЕСТО», А НЕ ПОМЕТКА НА УЗЛЕ: один и тот же узел
               находится разными путями, и пометка на нём получала ПОСЛЕДНЕЕ
               место — отчёт звал править не ту строку. */
            const своё = [];
            ист.forEach(и => {
                if (и && и.type !== 'ДОВОД') { чужое(и, своё); return; }
                /* ДОВОД — ИДЁМ К ЗОВУЩЕМУ (кусок 160). Граница — один файл:
                   зов из другого файла признаку не виден. */
                if (!мояФункция || !мояФункция.id) return;
                const имяФ = мояФункция.id.name;
                if (вЗовах.has(имяФ)) return;
                const номер = мояФункция.params.findIndex(п => п.type === 'Identifier' && п.name === у.name);
                if (номер === -1) return;
                const мои = зовыФункций.get(имяФ);
                if (!мои || !мои.length) { безЗовов++; return; }
                вЗовах.add(имяФ);
                const сохрК = мояКарта, сохрФ = мояФункция;
                мои.forEach(зов => {
                    const довод = зов.arguments[номер];
                    if (!довод) return;
                    const объемл = чьяЭтоФункция(зов);
                    if (объемл && !картаФункций.has(объемл)) картаФункций.set(объемл, источникиФункции(объемл));
                    мояФункция = объемл;
                    мояКарта = объемл ? картаФункций.get(объемл) : new Map();
                    чужое(довод, своё);
                });
                мояКарта = сохрК; мояФункция = сохрФ;
                вЗовах.delete(имяФ);
            });
            вПути.delete(у.name);
            своё.forEach(п => итог.push({ узел: п.узел || п, место: у }));
            return итог;
        }
        /* СРАВНЕНИЕ — НЕ ПОДСТАНОВКА: `t.format === 'doubles'` отдаёт «да»
           или «нет», а не поле. Признак считал такие места дырами, пока
           прослеживание переменных не привело его к ним (кусок 159). */
        if (у.type === 'BinaryExpression' &&
            ['===', '!==', '==', '!=', '<', '>', '<=', '>=', 'in', 'instanceof'].indexOf(у.operator) !== -1)
            return итог;
        /* проверка на пустоту — не подстановка */
        if (у.type === 'ConditionalExpression') { чужое(у.consequent, итог); чужое(у.alternate, итог); return итог; }
        if (у.type === 'LogicalExpression' && у.operator === '&&') { чужое(у.right, итог); return итог; }
        if (у.type === 'CallExpression') {
            const зов = имяЗова(у) || '';
            const хвост = зов.indexOf('.') !== -1 ? зов.split('.')[1] : зов;
            const набор = экраны.get(зов) || экраны.get(хвост);
            if (набор === 'все' || ДОМА.indexOf(корень2(у)) !== -1) return итог;
            if (набор) {
                у.arguments.forEach((а, и) => { if (!набор.has(и)) чужое(а, итог); });
                return итог;
            }
            /* ЗОВ НЕ ЧИТАЕТ ДАННЫЕ СВОИМ ИМЕНЕМ: `Math.round(x)` — это не
               чтение столбца `round`. Смотрим доводы, имя зова пропускаем. */
            у.arguments.forEach(а => чужое(а, итог));
            return итог;
        }
        /* ЗНАЧЕНИЕ, ВЗЯТОЕ ИЗ СЛОВАРЯ ПО КЛЮЧУ, — СЛОВО СЛОВАРЯ, А НЕ ПОЛЕ.
           `A.COURT_TYPES[t0.type]`, `audienceLabels[r.audience]`, `L[key]`:
           в разметку идёт ЗНАЧЕНИЕ словаря — его собственный литерал, — а
           поле стоит КЛЮЧОМ и до разметки не доходит вовсе. Признак же шёл в
           ключ и называл дырой его: двенадцать мест в шести файлах.
           Условие узкое: словарём считается только объект, чей КОРЕНЬ —
           известный словарь этого файла или дом. `article.reactions[type]`
           под него не попадает: корень там `article`, то есть данные, и
           значение по ключу — тоже данные. */
        if (у.type === 'MemberExpression' && у.computed) {
            const к = корень2(у.object);
            if (к && (словарь.has(к) || ДОМА.indexOf(к) !== -1)) return итог;
        }
        /* `item.bio.length` — это число, а не текст поля. ДЛИНА — НЕ ЗНАЧЕНИЕ. */
        if (у.type === 'MemberExpression' && у.property && у.property.type === 'Identifier' &&
            у.property.name === 'length') { чужое(у.object.object || {}, итог); return итог; }
        if (у.type === 'MemberExpression' && у.property && у.property.type === 'Identifier' &&
            ПИШЕТ.has(у.property.name)) {
            const к = корень2(у);
            if (!(к && (словарь.has(к) || ДОМА.indexOf(к) !== -1))) итог.push({ узел: у, место: null });
        }
        /* ИМЯ СВОЙСТВА — НЕ ПЕРЕМЕННАЯ. `ICON.phone` признак разворачивал в
           местную переменную `phone` и показывал дыру там, где стоит словарь
           значков. Ключи объекта — тоже не переменные.
           ОБЪЕКТ, У КОТОРОГО ЧИТАЮТ ОДНО ПОЛЕ, САМ В РАЗМЕТКУ НЕ ИДЁТ:
           `match.player1Id` — это чтение одного поля, а не подстановка всего
           `match`. Пока признак шёл в объект и разворачивал его как
           переменную, он уходил к зовущим и перебирал ВСЕ поля объекта —
           дыр становилось 180 вместо 118, и шестьдесят из них были одним и
           тем же местом, названным шестью полями. В цепочку (`a.b.c`)
           признак идёт по-прежнему: там слева настоящее чтение. */
        for (const к in у) {
            if (к === 'loc' || к === 'start' || к === 'end') continue;
            if (у.type === 'MemberExpression' && к === 'property' && !у.computed) continue;
            if (у.type === 'Property' && к === 'key' && !у.computed) continue;
            if (у.type === 'MemberExpression' && к === 'object' && у.object.type === 'Identifier') continue;
            чужое(у[к], итог);
        }
        return итог;
    }

    (function х(у, р, фн) {
        if (!у || typeof у !== 'object') return;
        if (Array.isArray(у)) return у.forEach(н => х(н, р, фн));
        /* СКЛЕЙКА ОТНОСИТСЯ К БЛИЖАЙШЕЙ ОБЪЕМЛЮЩЕЙ ФУНКЦИИ, И ТОЛЬКО К НЕЙ:
           разовый прибор, считавший её в каждой объемлющей, дал 22966 вместо
           1554 — в пятнадцать раз больше. */
        if (ФУНК.indexOf(у.type) !== -1) {
            if (!картаФункций.has(у)) картаФункций.set(у, источникиФункции(у));
            фн = у;
        }
        мояКарта = фн ? картаФункций.get(фн) : new Map();
        мояФункция = фн;
        if (у.type === 'BinaryExpression' && у.operator === '+' &&
            !(р && р.type === 'BinaryExpression' && р.operator === '+')) {
            const сп = части(у);
            if (естьРазметка(сп)) {
                склеек++;
                сп.forEach((ч, и) => {
                    /* ПЕРЕМЕННАЯ, В КОТОРУЮ ПОЛОЖИЛИ ПОЛЕ, ДЛЯ ПРИЗНАКА
                       НЕВИДИМА. Так в `tournament-blocks.js` адрес афиши
                       попал в `style="…url(` мимо экранирования: поле
                       положили в `постер`. Число — мера этой слепоты. */
                    if (ч.type === 'Identifier') переменных++;
                    if (ч.type === 'CallExpression') {
                        const зов = имяЗова(ч) || '';
                        const хвост = зов.indexOf('.') !== -1 ? зов.split('.')[1] : зов;
                        if (!(экраны.get(зов) || экраны.get(хвост)) && ДОМА.indexOf(корень2(ч)) === -1) зовы++;
                    }
                    const метка = п => {
                        const узел = п.узел, место = п.место;
                        const где = место || узел;
                        const что = т.slice(узел.start, узел.end).replace(/\s+/g, ' ').slice(0, 42);
                        return ф + ':' + где.loc.start.line + '  ' +
                            (место ? (место.name + ' [' + что + ']') : что);
                    };
                    const свои_ = чужое(ч, []);
                    /* ЧТО ПРИЗНАК СЧЁЛ БЕЗОПАСНЫМ — ТОЖЕ ВИДНО. Запирание файла
                       опирается на эти решения, значит их надо уметь ПРОЧИТАТЬ
                       глазами, а не только довериться счёту: правило доски 158
                       «что нашло чтение, чего не нашёл прибор». */
                    if (!свои_.length) безопасные.push(ф + ':' + ч.loc.start.line + '  ' +
                        т.slice(ч.start, ч.end).replace(/\s+/g, ' ').slice(0, 72));
                    свои_.forEach(н => дыры.push(метка(н)));
                    const слева = сп[и - 1];
                    const хвостЛит = слева && слева.type === 'Literal' && typeof слева.value === 'string'
                        ? слева.value
                        : (слева && слева.type === 'TemplateLiteral'
                            ? слева.quasis[слева.quasis.length - 1].value.raw : null);
                    if (хвостЛит && В_АТРИБУТЕ.test(хвостЛит)) чужое(ч, []).forEach(н => вАтрибуте.push(метка(н)));
                });
            }
        }
        for (const к in у) if (к !== 'loc' && к !== 'start' && к !== 'end') х(у[к], у, фн);
    })(д, null, null);

    return { дыры: дыры, вАтрибуте: вАтрибуте, безопасные: безопасные, зовы: зовы,
             отдают: отдают, копят: копят, склеек: склеек, переменных: переменных,
             безЗовов: безЗовов };
}

function собрать() {
    const { набор, сПодчерком } = столбцыЧеловека();
    const деревья = разобрать();
    const итог = { дыры: [], вАтрибуте: [], зовы: 0, отдают: 0, копят: 0, склеек: 0,
                   переменных: 0, безЗовов: 0, столбцов: набор.size, сПодчерком: сПодчерком };
    for (const ф in деревья) {
        const н = находкиФайла(ф, деревья[ф].т, деревья[ф].д, набор);
        итог.дыры = итог.дыры.concat(н.дыры);
        итог.вАтрибуте = итог.вАтрибуте.concat(н.вАтрибуте);
        итог.зовы += н.зовы; итог.отдают += н.отдают; итог.копят += н.копят;
        итог.склеек += н.склеек; итог.переменных += н.переменных;
        итог.безЗовов += н.безЗовов;
    }
    итог.дыры = [...new Set(итог.дыры)];
    итог.вАтрибуте = [...new Set(итог.вАтрибуте)];
    return итог;
}

/* ПО ФАЙЛАМ — ТОТ ЖЕ ПРИЗНАК, ДРУГАЯ РАЗБИВКА, А НЕ ВТОРОЙ ПРИЗНАК. Второй,
   упрощённый признак уже соврал в куске 161 («пять чистых файлов» против
   тридцати семи), поэтому счёт по файлам берётся отсюда же, из ОДНОГО
   определения, и просто не складывается в общую сумму. */
function поФайлам() {
    const { набор } = столбцыЧеловека();
    const деревья = разобрать();
    const о = {};
    for (const ф in деревья) {
        const н = находкиФайла(ф, деревья[ф].т, деревья[ф].д, набор);
        /* ОДИН УЗЕЛ, НАЙДЕННЫЙ ДВУМЯ ПУТЯМИ, — ОДНО МЕСТО. Без этого счёт по
           файлам даёт 113 там, где общий счёт даёт 92: беда куска 159,
           только другой стороной. */
        const дыры = [...new Set(н.дыры)];
        о[ф] = { дыр: дыры.length, вАтрибуте: [...new Set(н.вАтрибуте)].length,
                 склеек: н.склеек, переменных: н.переменных, дыры: дыры,
                 безопасные: [...new Set(н.безопасные)] };
    }
    return о;
}

/* ПРИБОР ПРОВЕРЯЕТСЯ ОБРАЗЦОМ, А НЕ ВЕРОЙ (кусок 170).
 *
 * У строгости признака нет своего правила: отними её — и ни один сторож не
 * пикнет, потому что дыр станет МЕНЬШЕ, а не больше. Ровно так в куске 170
 * выяснилось, что прослеживание местных переменных (кусок 169) уже ничего не
 * держит на сегодняшнем коде — хотя именно оно нашло сырой инициал игрока.
 * СНИМАТЬ ЕГО ИЗ-ЗА ЭТОГО НЕЛЬЗЯ: завтра такая же дыра вернётся и признак её
 * не увидит. Поэтому строгость закрепляется ОБРАЗЦОМ: правило кормит признак
 * коротким куском кода, в котором дыра ЕСТЬ, и требует, чтобы он её нашёл.
 * Образец разбирается тем же парсером и тем же `находкиФайла` — второго
 * признака здесь нет.
 */
function дырыОбразца(текст) {
    const { набор } = столбцыЧеловека();
    const д = acorn.parse(текст, { ecmaVersion: 2020, locations: true });
    const н = находкиФайла('образец', текст, д, набор);
    return { дыры: [...new Set(н.дыры)], вАтрибуте: [...new Set(н.вАтрибуте)] };
}

/* ЧТО ПРИЗНАК СЧИТАЕТ ЭКРАНОМ В ОДНОМ ФАЙЛЕ — ВИДНО СНАРУЖИ. Нужно, чтобы
   разбирать его слепоту числами, а не догадками (кусок 169). */
function экраныДляФайла(ф) {
    const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
    const д = acorn.parse(т, { ecmaVersion: 2020, locations: true });
    const словарь = словариФайла(д);
    const э = экраныФайла(д, словарь);
    const о = {};
    э.forEach((v, k) => { о[k] = v === 'все' ? 'все' : [...v]; });
    return { экраны: о, словари: [...словарь] };
}

