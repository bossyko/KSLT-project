const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const ПЛАТФ   = 'mobile/www/js/kslt-platforma.js';
const ПАРТН   = 'mobile/www/js/screens/partners.js';
const КАРТ    = 'mobile/www/js/screens/player-detail.js';
const ЯЗЫКИ   = 'mobile/www/js/i18n.js';
const ДОМ     = 'mobile/www/index.html';

const платф = чит(ПЛАТФ), партн = чит(ПАРТН), карт = чит(КАРТ),
      языки = чит(ЯЗЫКИ), дом = чит(ДОМ);

/* ЯКОРЬ, КОТОРЫЙ НАХОДИТ СЕБЯ В КОММЕНТАРИИ, НИЧЕГО НЕ СТОРОЖИТ.
   Поймано собственным прувером 10.11: два правила остались ЗЕЛЁНЫМИ после
   отката, потому что искомые слова — `ценуПоказываем`, `Capacitor` — я сам
   написал в пояснении рядом. Откат убрал код, пояснение осталось, правило
   отчиталось «всё на месте».
   Код этих файлов читается БЕЗ комментариев там, где правило сторожит
   именно работу, а не рассказ о ней. */
const безПояснений = т => т
    .replace(/\/\*[\s\S]*?\*\//g, ' ')
    .replace(/(^|[^:])\/\/[^\n]*/g, '$1 ');
const платфКод = безПояснений(платф), партнКод = безПояснений(партн);

/* ── ПРИЗНАК ПЛАТФОРМЫ: ОДНО ОПРЕДЕЛЕНИЕ ─────────────────────────────── */

правило('признак платформы объявлен одним местом',
    /KSLT_PLATFORMA\s*=/.test(платф),
    ПЛАТФ + ': пропало объявление KSLT_PLATFORMA.');

правило('платформа берётся у Capacitor, а не угадывается',
    /Capacitor/.test(платфКод) && /getPlatform/.test(платфКод),
    ПЛАТФ + ': платформа больше не спрашивается у Capacitor.\n' +
    'Угадывать её по User-Agent или по адресу нельзя: мост знает точно.');

const свои = ['mobile/www/js/screens/partners.js','mobile/www/js/screens/player-detail.js',
              'mobile/www/js/screens/profile.js','mobile/www/js/screens/home.js',
              'mobile/www/js/screens/tournaments.js','mobile/www/js/app.js'];
const вторые = свои.filter(ф => /getPlatform\s*\(/.test(чит(ф)));
правило('второго определения платформы не заводится',
    вторые.length === 0,
    'getPlatform зовётся мимо дома в: ' + вторые.join(', ') + '.\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: спрашивать надо KSLT_PLATFORMA.');

правило('признак платформы подключён раньше экранов',
    дом.indexOf('js/kslt-platforma.js') !== -1 &&
    дом.indexOf('js/kslt-platforma.js') < дом.indexOf('js/screens/partners.js'),
    ДОМ + ': kslt-platforma.js подключён после экранов или не подключён.\n' +
    'Опоздавший признак читается как «браузер» на живом устройстве.');

/* ── НИ ОДНА КНОПКА ПРИЛОЖЕНИЯ НЕ СТОИТ ЗА ВЗНОСОМ ───────────────────── */

правило('приглашение партнёра открыто всем вошедшим',
    /if \(!isGuest\) \{\s*\n\s*html \+= '<button class="partner-invite-btn"/.test(партн),
    ПАРТН + ': кнопка приглашения снова за взносом.\n' +
    'ЗАМОК НА ФУНКЦИИ ПРИЛОЖЕНИЯ ДЕЛАЕТ УСЛУГУ ЦИФРОВОЙ, КАК БЫ МЫ ЕЁ НИ\n' +
    'НАЗЫВАЛИ, и тогда правило 3.1.1 требует встроенной покупки и доли.');

правило('вызов и приглашение в карточке открыты всем вошедшим',
    /if \(access !== 'guest' && естьЧеловек && !_zablokirovan\)/.test(карт),
    КАРТ + ': кнопки вызова и приглашения снова за взносом (3.1.1).');

правило('обработчик кнопок вешается тому же кругу, что и кнопки',
    /if \(access !== 'guest'\) \{\s*\n\s*var chalBtn/.test(карт),
    КАРТ + ': кнопки рисуются всем вошедшим, а обработчик — только членам.\n' +
    'Кнопка без обработчика не жалуется, как и обработчик без кнопки.');

правило('на месте снятого замка не стоит призыв к оплате',
    карт.indexOf('pd.memberCta') === -1 && языки.indexOf('pd.memberCta') === -1,
    'Вернулся текст «для вызовов нужно членство».\n' +
    'ПРИЗЫВ К ОПЛАТЕ, СТОЯЩИЙ НА МЕСТЕ СНЯТОГО ЗАМКА, — ЭТО ТОТ ЖЕ ЗАМОК,\n' +
    'ТОЛЬКО СЛОВАМИ.');

/* ── СПОСОБА ОПЛАТЫ В ПРИЛОЖЕНИИ НЕТ ─────────────────────────────────── */

правило('в окне взноса нет ссылки на оплату',
    !/t\.me\/kslt_admin/.test(партнКод),
    ПАРТН + ': в окне взноса снова стоит ссылка на оплату.\n' +
    'Правило 3.1.3 запрещает внутри приложения кнопки, внешние ссылки И\n' +
    'ЛЮБЫЕ ПРИЗЫВЫ к способу оплаты помимо встроенной покупки — везде,\n' +
    'кроме витрины США. Кыргызстан не США.');

правило('строка «как оплатить» не показывается в окне взноса',
    !/pricing\.howToPay/.test(партнКод),
    ПАРТН + ': вернулась строка «для оплаты свяжитесь с нами».\n' +
    'ЗАГЛУШКА, КОТОРАЯ ЗОВЁТ ПЛАТИТЬ, — ЭТО ПРИЗЫВ, А НЕ ЗАГЛУШКА.');

правило('вместо способа оплаты сказано, где оформляется взнос',
    /pricing\.atClub/.test(партн) && /'pricing\.atClub'/.test(языки),
    'Пропала строка «оформляется в клубе» — человек остался без ответа\n' +
    'на вопрос «а как же вступить».');

/* ── ЦЕНА НЕ ПОКАЗЫВАЕТСЯ НА ВИТРИНЕ APPLE ───────────────────────────── */

правило('цена спрашивает правило, а не имя платформы',
    /ценуПоказываем/.test(платфКод) && /ценуПоказываем\(\)/.test(партнКод),
    'Цена снова завязана на имя платформы вместо `ценуПоказываем()`.\n' +
    'ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ, А НЕ ПЛАТФОРМА: решишь иначе — поменяешь\n' +
    'одно место, а не семь по файлам.');

правило('цена скрыта именно на витрине Apple',
    /ценуПоказываем: function \(\) \{ return ПЛАТФОРМА !== 'ios'; \}/.test(платфКод),
    ПЛАТФ + ': правило показа цены изменено.\n' +
    'Скрывать цену надо на iOS: 3.1.1 и 3.1.3 — это правила App Store.\n' +
    'Android живёт по своим, и сводить их в одну проверку — беда на шве.');

/* ── ВЫГОДЫ ОБЕЩАЮТ ТО, ЧТО ДАЁТ КОД ─────────────────────────────────── */

/* ЯКОРЬ ЦЕЛИТ В САМИ ВЫГОДЫ, А НЕ ВО ВЕСЬ СЛОВАРЬ. Первая редакция искала
   слова по всему i18n.js и поймала `rating.guestTitle` — заголовок окна
   «Полный рейтинг» для гостя, который зовёт ВОЙТИ, а не заплатить.
   ПРАВИЛО, ЦЕЛЯЩЕЕ ШИРЕ СВОЕГО ПРЕДМЕТА, ЛОВИТ НЕВИНОВНЫХ, и его потом
   отключают целиком — вместе с тем, ради чего заводили. */
const выгоды = (языки.match(/'pricing\.feat\d+':[^\n]*\n/g) || []).join('');
правило('выгод взноса в словаре по-прежнему шесть',
    (выгоды.match(/pricing\.feat/g) || []).length === 6,
    ЯЗЫКИ + ': выгод взноса не шесть — список читается не целиком, и\n' +
    'проверки ниже молчат не потому, что чисто.');

const цифровые = [
  ['рейтинг', 'рейтинг открыт всем вошедшим, его не продают'],
  ['вызов', 'вызовы открыты всем вошедшим'],
  ['лояльност', 'баллы ничем не закрыты'],
  ['статистик', 'статистика открыта всем вошедшим'],
];
цифровые.forEach(([строка, почему]) => {
  правило('в выгодах взноса нет обещания «' + строка + '»',
    выгоды.toLowerCase().indexOf(строка) === -1,
    ЯЗЫКИ + ': в списке выгод взноса снова обещано «' + строка + '» — ' + почему + '.\n' +
    'РЕВЬЮЕР СУДИТ ПО ТЕКСТУ НА ЭКРАНЕ, А НЕ ПО НАШИМ НАМЕРЕНИЯМ: обещание\n' +
    'цифровой функции за деньги — это заявка на правило 3.1.1 своими руками.');
});

правило('кабинет не обещает доступ ко всем функциям за взнос',
    языки.indexOf('доступа ко всем функциям') === -1 &&
    языки.indexOf('access to all features') === -1,
    ЯЗЫКИ + ': `profile.getMembership` снова обещает «доступ ко всем\n' +
    'функциям». Это прямая заявка на 3.1.1.');

правило('взнос назван взносом, а не подпиской',
    /'menu\.pricing':\s*\{ ru: 'Клубный взнос'/.test(языки),
    ЯЗЫКИ + ': пункт меню снова называется «Членство».\n' +
    'Слово «членство» читается как подписка и само тянет к 3.1.1;\n' +
    'взнос — это плата за участие, а не за доступ к приложению.');

правило('FAQ не отсылает оформлять взнос внутри приложения',
    !/оформите членство через раздел/.test(партнКод),
    ПАРТН + ': FAQ снова указывает путь к оплате внутри приложения.');

/* ── ПРИЁМ РАСЧИСТКИ ПУТИ ЖИВЁТ ОДНИМ МЕСТОМ ─────────────────────────── */

/* ДУБЛИКАТ ЛОВИТ ПРОВЕРКА, А НЕ ПАМЯТЬ. 10.11 проба 46 легла всеми 25
   прогонами об экран входа — ту же помеху, что проба 45 разбирала
   накануне: я написал для 46 свой заход вместо готового.
   ПРОЦЕДУРА, НАПИСАННАЯ ЗАНОВО ВМЕСТО ГОТОВОЙ, ПОВТОРЯЕТ ЕЁ ОШИБКИ. */
const ПОМОЩНИК = 'tests/e2e/pomoshniki/nazhatie.js';
const всеПробы = (function собрать(д, итог) {
    итог = итог || [];
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) собрать(п, итог);
        else if (/\.spec\.js$/.test(э.name)) итог.push(п);
    });
    return итог;
})('tests/e2e', []);

/* ЯКОРЬ ЦЕЛИТ В САМ ПРИЁМ, А НЕ В ОДНУ ЕГО СТРОКУ. Первая редакция искала
   `elementFromPoint` по всем пробам и назвала беглецами ДВАДЦАТЬ ДВЕ — те
   меряют им свои цели нажатия и перекрытия, и это их законное дело.
   ПРАВИЛО, ЦЕЛЯЩЕЕ ШИРЕ СВОЕГО ПРЕДМЕТА, ЛОВИТ НЕВИНОВНЫХ, и его потом
   отключают целиком — вместе с тем, ради чего заводили. Второй раз за день.
   Копия приёма — это СВОЁ ОБЪЯВЛЕНИЕ `нажатьСквозьПомехи` в пробе. */
const своиКопии = всеПробы.filter(ф =>
    /(function|const|var|let)\s+нажатьСквозьПомехи/.test(чит(ф)));
правило('приём расчистки пути не копируется по пробам',
    своиКопии.length === 0,
    'Своё объявление `нажатьСквозьПомехи` завели в: ' + своиКопии.join(', ') + '.\n' +
    'Приём живёт в ' + ПОМОЩНИК + ' — звать надо его.\n' +
    'ПРОЦЕДУРА, НАПИСАННАЯ ЗАНОВО ВМЕСТО ГОТОВОЙ, ПОВТОРЯЕТ ЕЁ ОШИБКИ.');

правило('помощник расчистки пути на месте',
    fs.existsSync(path.join(КОРЕНЬ, ПОМОЩНИК)) &&
    /elementFromPoint/.test(чит(ПОМОЩНИК)),
    ПОМОЩНИК + ': пропал общий помощник — пробы снова будут гадать,\n' +
    'что перекрыло нажатие, по одной догадке за прогон.');

правило('проба взноса зовёт общий помощник',
    /require\('\.\.\/\.\.\/pomoshniki\/nazhatie'\)/.test(чит('tests/e2e/features/46-klubnyy-vznos.spec.js')),
    'tests/e2e/features/46-klubnyy-vznos.spec.js: проба перестала звать\n' +
    'общий помощник. Экран входа стоит поверх, пока база не ответила, и\n' +
    'без расчистки проба ляжет в тайм-аут на первом же нажатии.');

/* ── САМОПРОВЕРКА: ПРИБОР НЕ ДОЛЖЕН ВРАТЬ О СЕБЕ ─────────────────────── */
правило('снятие пояснений действительно работает',
    безПояснений('/* ценуПоказываем */ var a = 1;').indexOf('ценуПоказываем') === -1 &&
    безПояснений('// Capacitor\nvar b = 2;').indexOf('Capacitor') === -1 &&
    безПояснений("var u = 'https://t.me/x';").indexOf('t.me') !== -1,
    'Снятие пояснений сломано: оно либо не убирает комментарии, либо\n' +
    'съедает код вместе с ними (адрес с «//» внутри строки).\n' +
    'ПРИБОР, КОТОРЫЙ НЕ ПРОВЕРЯЕТ СЕБЯ, ОТЧИТЫВАЕТСЯ О ЧУЖОЙ РАБОТЕ.');

