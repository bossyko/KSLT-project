/**
 * ЗАМОРОЗКА ЛЕНТЫ ФИЛЬТРОВ — `.trn-filters`.
 *
 * Лента общая: её несут ШЕСТЬ страниц — турниры и баттлы на трёх языках, —
 * а правит её четыре файла css. Главное определение живёт в
 * `css/style.css`; самой ленты на лендинге нет (0 вхождений в index.html,
 * проверено счётом), поэтому правка под этими селекторами лендинга
 * коснуться не может.
 *
 * ЧТО ЗАМОРАЖИВАЕТСЯ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • две группы фильтров — это ДВЕ группы, и у каждой ровно один выбор;
 *   • цель нажатия — ступень кнопки, и задана ВЫСОТОЙ, а не слоем;
 *   • кегль и межстрочный чипа одни на все виды;
 *   • на низком горизонтальном лента не липнет;
 *   • левый край ленты считается той же формулой, что содержимое страницы.
 *
 *   node tools/check-lenta-filtrov.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const CSS  = безКом(чит('css/style.css'));
const JS   = безКом(чит('js/tournaments-overlay.js'));
const RU   = чит('pages/tournaments.html');
const EN   = чит('pages/tournaments-en.html');
const KG   = чит('pages/tournaments-kg.html');
const ЛЕНД = чит('index.html');

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };

/* Окно правила — свой блок, а не весь файл */
const блокCSS = сел => {
    const i = CSS.indexOf(сел + ' {');
    if (i === -1) return '';
    const j = CSS.indexOf('}', i);
    return j === -1 ? '' : CSS.slice(i, j);
};
const медиа = условие => {
    const н = CSS.indexOf('@media ' + условие);
    if (н === -1) return '';
    let i = CSS.indexOf('{', н), г = 0, с = i;
    for (; i < CSS.length; i++) {
        if (CSS[i] === '{') г++;
        else if (CSS[i] === '}') { г--; if (г === 0) return CSS.slice(с + 1, i); }
    }
    return '';
};

/* ══ 1. ДВЕ ГРУППЫ — ЭТО ДВЕ ГРУППЫ ════════════════════════════════════ */

правило('лента есть на всех трёх языках и нигде не на лендинге',
    [RU, EN, KG].every(т => т.indexOf('class="trn-filters"') !== -1) &&
    ЛЕНД.indexOf('trn-filters') === -1,
    'Если лента заведётся на лендинге, правка под этими селекторами начнёт\n' +
    '          его трогать, а лендинг принят Костей и не правится без его слова.');

правило('фильтры собраны в ДВЕ группы с ролью, на каждом языке',
    [RU, EN, KG].every(т =>
        (т.match(/class="trn-chip-group" role="radiogroup"/g) || []).length === 2),
    'До 05.10 семь чипов ДВУХ разных смыслов лежали одной лентой: в ряду\n' +
    '          горели две лаймовые «Все», и разметка утверждала, что это один\n' +
    '          набор с двумя выбранными.');

правило('у каждой группы есть подпись для диктора, и она переведена',
    [RU, EN, KG].every(т => (т.match(/role="radiogroup" aria-label="[^"]{3,}"/g) || []).length === 2) &&
    (RU.match(/aria-label="Статус турнира"/) ? true : false) &&
    (EN.match(/aria-label="Tournament status"/) ? true : false) &&
    (KG.match(/aria-label="Мелдештин абалы"/) ? true : false),
    'Группа без подписи — это просто семь кнопок подряд: диктор не скажет\n' +
    '          ни «статус», ни «пол», ни «выбрано одно из четырёх».');

правило('каждый чип несёт роль и состояние',
    [RU, EN, KG].every(т => {
        const чипов = (т.match(/class="trn-chip[ "]/g) || []).length;
        const сРолью = (т.match(/role="radio" aria-checked="(true|false)"/g) || []).length;
        return чипов > 0 && сРолью >= чипов;
    }),
    'Класс active красит чип, а диктору про выбор говорит только\n' +
    '          aria-checked.');

правило('состояние едет вместе с видом, а не отдельно',
    /classList\.remove\('active'\)[\s\S]{0,120}?setAttribute\('aria-checked', 'false'\)/.test(JS) &&
    /classList\.add\('active'\)[\s\S]{0,120}?setAttribute\('aria-checked', 'true'\)/.test(JS),
    'Если класс и состояние расходятся, экран говорит одно, а диктор другое —\n' +
    '          и беда родится ровно на этом шве.');

правило('чип, который ничего не найдёт, гаснет',
    /чип\.disabled = !v/.test(JS) || /\.disabled = !v/.test(JS),
    'Было: ноль прятался в пустую строку, и «Предстоящие» без числа нельзя\n' +
    '          было отличить от «числа не знаем».');

/* ══ 2. ЦЕЛЬ НАЖАТИЯ ═══════════════════════════════════════════════════ */

правило('цель нажатия чипа — ступень кнопки, и задана ВЫСОТОЙ',
    /min-height:\s*var\(--btn-h-md\)/.test(блокCSS('.trn-chip')),
    'Слой 44 на ::after я ставил первым, и замер поймал: он срабатывал у\n' +
    '          первого и последнего чипа в группе и НЕ срабатывал у средних.\n' +
    '          НАСТОЯЩУЮ ВЫСОТУ ПЕРЕКРАСИТЬ НЕЧЕМ.');

правило('чип не вернулся в общий блок мелких кнопок',
    CSS.indexOf('.trn-chip.trn-chip') === -1,
    'Ступень «мелкая» даёт 32 — ниже цели нажатия 44 по WCAG 2.5.5. Чип\n' +
    '          вынут оттуда 05.10 по заведённому там же порядку.');

правило('поле поиска — ступень кнопки, а не 39',
    /min-height:\s*var\(--btn-h-md\)/.test(блокCSS('.trn-search-input')),
    'В поле надо попадать курсором, а не слоем над ним, — поэтому высота,\n' +
    '          а не ::after.');

/* ══ 3. ЛЕСТНИЦА ══════════════════════════════════════════════════════ */

правило('кегль чипа один на все виды',
    /font-size:\s*var\(--fs-xs\)/.test(блокCSS('.trn-chip')) &&
    !/\.trn-chip\s*\{[^}]*font-size/.test(медиа('(max-width: 768px)')) &&
    !/\.trn-chip\s*\{[^}]*font-size/.test(медиа('(max-width: 480px)')),
    'Замер 05.10: один и тот же чип выходил 12 на 375 и 768 и 14 на 844,\n' +
    '          1024 и 1280 — при одной и той же роли.');

правило('межстрочный чипа — ступень, а не число',
    /line-height:\s*var\(--lh-/.test(блокCSS('.trn-chip')) &&
    !/line-height:\s*[0-9]/.test(блокCSS('.trn-chip')),
    'Было 1.15 — 13.8 при кегле 12 и 16.1 при 14; такой ступени на лестнице\n' +
    '          нет вовсе.');

/* ══ 4. МЕСТО НА ЭКРАНЕ ═══════════════════════════════════════════════ */

правило('на низком горизонтальном лента НЕ липнет',
    /\.trn-filters\s*\{[^}]*position:\s*static/.test(
        медиа('(max-height: 500px) and (orientation: landscape)')),
    'Замер 05.10: при экране 844×390 липкая полоса занимала 156 — сорок\n' +
    '          процентов высоты окна, и столько же отнимала у списка, ради\n' +
    '          которого человек сюда пришёл.');

правило('левый край ленты считается ТОЙ ЖЕ формулой, что содержимое',
    /padding:\s*0 var\(--pad-x\)/.test(блокCSS('.trn-filters-inner')) &&
    !/max-width/.test(блокCSS('.trn-filters-inner')),
    'Полоса считала свой отступ --gutter, а содержимое страницы --pad-x. На\n' +
    '          1280, 768 и 375 они дают одно и то же, и расхождения не видно; на\n' +
    '          1512 полоса начиналась на 88, а лаймовая полоска заголовка — на 56.');

/* ══ ИТОГ ═════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log(`\n  ок      лента фильтров: ${ВСЕГО} правил\n`);
    process.exit(0);
}
console.log(`\n  НЕ ТАК  лента фильтров: ${ВСЕГО} правил, упало ${ошибки.length}.\n`);
ошибки.forEach(о => {
    console.log(`  ✗ ${о.имя}`);
    if (о.подсказка) console.log(`          ${о.подсказка}`);
    console.log('');
});
process.exit(1);
