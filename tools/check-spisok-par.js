#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «СПИСОК ПАР ПОЛОН» (04.11).
 *
 * ЗАЧЕМ ОН ЕСТЬ — СЛУЧАЙ, А НЕ ОПАСЕНИЕ. 04.11 прогон показал: на диске
 * лежало 229 пруверов, а в списке `КУСКИ` у `check-vse.js` стояло 210
 * пар. ДВАДЦАТЬ ПАР ОБЩИЙ БЕГУНОК НЕ ГОНЯЛ НИ РАЗУ — среди них `вход с
 * Apple`, `правило пароля`, `бекап заперт` и свежие `жалобы и
 * блокировки`. Ровно та беда, про которую написано в заголовке
 * `check-vse-srezom.js`: БЕГУНОК, КОТОРЫЙ НЕ ЗАПУСКАЮТ, МОЛЧА ГНИЁТ.
 * Там же нашлась и вторая: пара `check-znachki` стояла в списке ДВАЖДЫ,
 * под двумя разными именами.
 *
 * ПОЧЕМУ ПАМЯТИ ЗДЕСЬ НЕ ХВАТАЕТ. Полнота списка — это не решение, которое
 * можно записать один раз: она расходится сама, при каждой новой паре.
 * ДУБЛИКАТ И ПРОПУСК ЛОВИТ ПРОВЕРКА, А НЕ ПАМЯТЬ.
 *
 * ЧТО СТЕРЕЖЁТ: каждый прувер с диска стоит в списке, и ровно один раз;
 * каждый сторож, у которого есть прувер, — тоже; у каждой пары оба файла
 * существуют; сторожей без прувера ровно столько, сколько замерено, и это
 * поимённый список.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ, И ЭТО НАЗВАНО: что прувер внутри пары проверяет
 * ИМЕННО своего сторожа. Это читается глазами при заведении пары.
 *
 *   node tools/check-spisok-par.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ПАПКА = path.join(КОРЕНЬ, 'tools');

/* СПИСОК ЧИТАЕТСЯ ИЗ `check-vse.js` ТЕКСТОМ — тем же приёмом, что у
   `check-vse-srezom.js`. Второго списка пар здесь не заводится: он бы
   разошёлся с первым на первой же правке. */
const текстБегунка = fs.existsSync(path.join(ПАПКА, 'check-vse.js'))
    ? fs.readFileSync(path.join(ПАПКА, 'check-vse.js'), 'utf8') : '';
const найдено = текстБегунка.match(/const КУСКИ = (\[[\s\S]*?\n\];)/);
const КУСКИ = найдено ? eval(найдено[1].replace(/;$/, '')) : null;

/* СТОРОЖА БЕЗ ПРУВЕРА — ПОИМЁННО, А НЕ ЧИСЛОМ.
   `check-vse.js` и `check-vse-srezom.js` — сами бегунки, им пара не нужна.
   `check-rules.js` и `check-shkala.js` остались без прувера с прежних
   веток: это ДОЛГ, он записан в трекер, а не разрешение. Новое имя здесь
   уронит правило — так и задумано. */
const БЕЗ_ПРУВЕРА = [
    'check-vse.js',
    'check-vse-srezom.js',
    'check-rules.js',
    'check-shkala.js'
];

const наДиске = fs.existsSync(ПАПКА)
    ? fs.readdirSync(ПАПКА).filter(ф => /^check-.*\.js$/.test(ф)) : [];
const пруверыДиск = наДиске.filter(ф => /-otkat\.js$/.test(ф)).sort();
const сторожаДиск = наДиске.filter(ф => !/-otkat\.js$/.test(ф)).sort();

const вСписке = КУСКИ ? КУСКИ.map(к => к[1]) : [];
const пруверыСписка = КУСКИ ? КУСКИ.map(к => к[2]) : [];

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('список пар читается из бегунка',
    Array.isArray(КУСКИ) && КУСКИ.length > 0,
    'В `tools/check-vse.js` не нашёлся список `КУСКИ` — значит сломался\n' +
    'ПРИБОР, и все сверки ниже пусты. Правило стоит ПЕРЕД ними нарочно.\n' +
    'ПУСТОЕ ПРАВИЛО ХУЖЕ ОТСУТСТВУЮЩЕГО.');

const пропущены = пруверыДиск.filter(ф => пруверыСписка.indexOf(ф) === -1);
правило('каждый прувер с диска стоит в списке',
    !!КУСКИ && пропущены.length === 0,
    'Этих пруверов общий бегунок не гоняет:\n  ' + пропущены.join('\n  ') + '\n' +
    'Прувер вне списка не гоняется НИКОГДА и гниёт молча: 04.11 так\n' +
    'оказались вне прогона двадцать пар. Пара заводится в `КУСКИ`\n' +
    'у `check-vse.js` в тот же день, что и сам прувер.');

const сиротыСторожа = сторожаДиск.filter(
    ф => вСписке.indexOf(ф) === -1 && БЕЗ_ПРУВЕРА.indexOf(ф) === -1);
правило('у каждого сторожа есть пара, кроме названных',
    !!КУСКИ && сиротыСторожа.length === 0,
    'Эти сторожа ни в списке пар, ни в поимённом списке без прувера:\n  ' +
    сиротыСторожа.join('\n  ') + '\n' +
    'Сторож без прувера ничего не доказывает: «у меня зелёное» не\n' +
    'доказательство. Либо завести прувер и пару, либо — если долг\n' +
    'осознанный — внести имя в `БЕЗ_ПРУВЕРА` здесь и в трекер.');

const дубСторожа = вСписке.filter((ф, i) => вСписке.indexOf(ф) !== i);
const дубПрувера = пруверыСписка.filter((ф, i) => пруверыСписка.indexOf(ф) !== i);
правило('в списке нет двух записей на один кусок',
    !!КУСКИ && дубСторожа.length === 0 && дубПрувера.length === 0,
    'Встречается дважды:\n  ' + дубСторожа.concat(дубПрувера).join('\n  ') + '\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. Два имени на одну пару — это две\n' +
    'записи, которые разойдутся: правку внесут в одну.');

const безФайла = !КУСКИ ? [] : КУСКИ.filter(
    к => !fs.existsSync(path.join(ПАПКА, к[1])) || !fs.existsSync(path.join(ПАПКА, к[2])));
правило('у каждой пары оба файла на диске',
    !!КУСКИ && безФайла.length === 0,
    'У этих пар файла нет:\n  ' +
    безФайла.map(к => к[0] + ' → ' + к[1] + ' + ' + к[2]).join('\n  ') + '\n' +
    'Пара, ссылающаяся в пустоту, валит общий прогон и прячет настоящие\n' +
    'падения за своим.');

const лишние = БЕЗ_ПРУВЕРА.filter(ф => сторожаДиск.indexOf(ф) === -1);
правило('поимённый список без прувера не отстал от диска',
    лишние.length === 0,
    'В `БЕЗ_ПРУВЕРА` названы файлы, которых на диске нет:\n  ' +
    лишние.join('\n  ') + '\n' +
    'Список-разрешение, переживший свой файл, завтра разрешит чужому\n' +
    'сторожу остаться без прувера под тем же именем.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      список пар: все ' + всего + ' правил держатся');
    console.log('          пар в списке ' + КУСКИ.length +
                ', пруверов на диске ' + пруверыДиск.length +
                ', сторожей ' + сторожаДиск.length +
                ' (без прувера ' + БЕЗ_ПРУВЕРА.length + ')');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  список пар — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
