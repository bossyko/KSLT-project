const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СТИ = безКом(чит('css/style.css'));
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* содержимое медиазапроса — до СЛЕДУЮЩЕГО @media */
/* СЛОЙ ИЩЕТСЯ ПО УСЛОВИЮ И ПО СОДЕРЖИМОМУ. 23.09 у новостей появилась такая же
   лента с тем же условием из трёх частей, и indexOf стал приводить в чужой
   блок: правила турниров падали на исправном коде. Берём тот блок, внутри
   которого есть нужный селектор. */
function слой(условие, маркер) {
    let i = -1;
    while ((i = СТИ.indexOf('@media ' + условие, i + 1)) !== -1) {
        const j = СТИ.indexOf('@media ', i + 7);
        const кусок = СТИ.slice(i, j === -1 ? СТИ.length : j);
        if (!маркер || кусок.indexOf(маркер) !== -1) return кусок;
    }
    return null;
}
function тело(текст, селектор) {
    if (!текст) return null;
    const i = текст.indexOf(селектор + ' {');
    if (i === -1) return null;
    const j = текст.indexOf('}', i);
    return j === -1 ? null : текст.slice(i, j);
}

const ТЕЛЕФОН = '(max-width: 640px)';
const ПЛАНШЕТ = '(max-width: 992px)';
const ЛЕНТА   = '(max-width: 992px) and (orientation: landscape) and (max-height: 500px)';
const ВЫСОТА  = '(min-width: 641px) and (max-width: 992px) and (orientation: portrait)';

/* ── телефон вертикально ─────────────────────────────────────────────────── */
const тел = слой(ТЕЛЕФОН, '.tournaments-grid');
правило('слой телефона на месте', !!тел, 'Блок @media ' + ТЕЛЕФОН + ' не найден.');
правило('на телефоне главная карточка на всю ширину',
    тел && /\.tournaments-grid > \.tc:nth-child\(1\)\s*\{\s*grid-column: span 12/.test(тел),
    'Решение Кости 23.09, доска 341:9: одна широкая сверху, две под ней.\n' +
    '          Было четыре одинаковых плитки, и главную нельзя было отличить.');
правило('на телефоне остальные карточки в половину ряда',
    тел && /\.tournaments-grid > \.tc:nth-child\(n\+2\)\s*\{\s*grid-column: span 6/.test(тел),
    'Вторая и третья идут парой под главной.');
правило('на телефоне видно ровно три карточки',
    тел && /\.tournaments-grid > \.tc:nth-child\(n\+4\)\s*\{\s*display: none/.test(тел),
    'Четвёртая повисла бы одна в ряду. Витрина показывает столько,\n' +
    '          сколько заполняет ряды целиком.');
правило('в раскладке телефона нет !important',
    тел && !/grid-column:[^;]*!important/.test(тел),
    'Раньше !important перебивал слой планшета. Теперь правила равной\n' +
    '          цепкости, и побеждает порядок — этого достаточно.');

/* ── планшет ─────────────────────────────────────────────────────────────── */
const пл = слой(ПЛАНШЕТ, '.tournaments-grid');
правило('на планшете видно пять карточек',
    пл && /\.tournaments-grid > \.tc:nth-child\(n\+6\)\s*\{\s*display: none/.test(пл),
    'Решение Кости 23.09, доска 341:52: 1 + 2 + 2. Шестая висела одна\n' +
    '          в последнем ряду — это и был дефект, а не само число шесть.');

const выс = слой(ВЫСОТА, '.tournaments-grid');
правило('высота обычной карточки планшета объявлена в СВОИХ границах',
    выс && /nth-child\(-n\+3\):not\(:nth-child\(1\)\)\s*\{\s*height: 322px/.test(выс),
    'Правило (0,4,1) перебивает и «height: auto» телефона, и высоту ленты.\n' +
    '          23.09 оно стояло просто в слое 992 и протекло в оба вида:\n' +
    '          телефон получил 322 вместо 273, лента — 322 вместо 270.\n' +
    '          Правило, которое нельзя перебить снизу, обязано знать свои границы.');
правило('границы у этого правила именно портретные и от 641',
    выс !== null,
    'Условие @media ' + ВЫСОТА + ' не найдено дословно.');

/* ── лента ───────────────────────────────────────────────────────────────── */
const лен = слой(ЛЕНТА, '.tournaments-grid');
правило('лента объявлена условием из трёх частей', !!лен,
    'Нужно ровно @media ' + ЛЕНТА + '.\n' +
    '          Без max-width под правило попадёт низкое окно браузера на ноутбуке.');
const сетка = тело(лен, '.tournaments-grid');
правило('в ленте сетка становится полосой',
    сетка && /display: flex/.test(сетка) && /overflow-x: auto/.test(сетка)
          && /scroll-snap-type: x mandatory/.test(сетка) && /gap: 12px/.test(сетка),
    'flex + overflow-x + снап по оси x + зазор 12.');
const карточка = тело(лен, '.tournaments-grid > .tc:nth-child(n)');
правило('в ленте карточка 340 × 270 и прилипает',
    карточка && /flex: 0 0 340px/.test(карточка) && /width: 340px/.test(карточка)
             && /height: 270px/.test(карточка) && /scroll-snap-align: start/.test(карточка),
    'Две целые в кадре: 340 + 12 + 340 + 12 + остаток. Остаток — та самая\n' +
    '          выглядывающая карточка, без неё полоса читается как законченный ряд.');
правило('в ленте показаны ВСЕ карточки',
    лен && /\.tournaments-grid > \.tc:nth-child\(n\+4\)\s*\{\s*display: flex/.test(лен),
    'Прятать нечего: вниз полоса не растёт.');
правило('в ленте главная теряет разметку «афиша слева»',
    лен && /\.tc-featured\s*\{\s*grid-template-columns: 1fr/.test(лен),
    'При 340 в ширину делить нечего. Роль главной несёт порядок — она первая.');
правило('в ленте кегли телефонные',
    лен && /\.tournaments-grid \.tc \.tc-title,[\s\S]{0,80}font-size: var\(--fs-sm\)/.test(лен)
        && /\.tournaments-grid > \.tc:nth-child\(1\) \.tc-title\s*\{\s*font-size: var\(--fs-base\)/.test(лен),
    'Карточка 340 в ширину — ступени широкого экрана ей велики.\n' +
    '          Ступень card title лестницы 86:10: 16 у главной, 14 у обычной.');

/* ── высота первого ряда и воздух шапки ──────────────────────────────────── */
/* Решение Кости 23.09, доска 345:9. 320 — не вкусовое число: при 380 у боковых
   карточек тело 228 при содержимом 128, полях 24 и промежутках 18, то есть
   дыра 58; при 320 тело 170 и занято ровно, в ноль. Сжать боковые отдельно
   нельзя — они стоят с главной в одном ряду сетки. */
const рядБлок = (СТИ.match(/(?:^|\n)\.tournaments-grid > \.tc:nth-child\(-n\+3\)\s*\{[^}]*\}/) || [null])[0];
правило('высота первого ряда 320',
    рядБлок && /height:\s*320px/.test(рядБлок),
    'Сейчас: ' + (рядБлок ? рядБлок.replace(/\s+/g, ' ').slice(0, 80) : 'блока нет'));

const шапка = (СТИ.match(/(?:^|\n)\.section-header\s*\{[^}]*\}/) || [null])[0];
правило('шапка раздела одной высоты во всех секциях',
    шапка && /min-height:\s*44px/.test(шапка),
    'Заголовок турниров стоял на 3px ниже, чем у live. Причина не в шкале:\n' +
    '          у «Все турниры» цель нажатия 44, у live ссылки нет, и шапка\n' +
    '          выходила 44 против 39 — заголовок по центру съезжал. Цель\n' +
    '          нажатия трогать нельзя, поэтому высоту получают ВСЕ шапки.');

/* ── плитка «Все турниры» ────────────────────────────────────────────────── */
/* Якорь с переводом строки: '.tc-more {' встречается и внутри ленты,
   как '> .tc-more {', и indexOf находил сначала ЕЁ — правило смотрело не
   на тот блок и было зелёным всегда. Тот же промах, что с .avatar-initials. */
const плитка = (СТИ.match(/\n\.tc-more\s*\{[^}]*\}/) || [null])[0];
правило('плитка «Все турниры» по умолчанию скрыта',
    плитка && /display: none/.test(плитка),
    'В сетке её роль исполняет ссылка в шапке раздела.');
правило('плитка показана только в ленте',
    лен && /\.tournaments-grid > \.tc-more\s*\{\s*display: flex/.test(лен),
    'У полосы должен быть конец, иначе непонятно, докуда листать.');

/* ── типографика карточки ────────────────────────────────────────────────── */
const блокиКарточки = (СТИ.match(/[^{}]*\.tc[-a-z ]*\{[^}]*\}/g) || [])
    .filter(б => /\.tc-(badge|title|date|desc|meta|slots|btn|countdown|cd-label|more)/.test(б.split('{')[0]));
const сЧислом = блокиКарточки.filter(б => /font-weight:\s*\d/.test(б));
правило('веса внутри карточки — токенами, не числами',
    сЧислом.length === 0,
    'Нашёл: ' + сЧислом.map(б => б.split('{')[0].trim().slice(0, 40)).join(' · ') + '\n' +
    '          Число рисует то же самое, но система про него не знает:\n' +
    '          поменяем ступень веса в tokens.css — карточка не сдвинется.');

правило('мета на телефоне объявлена селектором с родителем',
    тел && /\.tournaments-grid \.tc \.tc-meta,\s*\n\s*\.tournaments-grid \.tc-featured \.tc-meta\s*\{[^}]*font-size: var\(--fs-2xs\)/.test(тел),
    'Одиночный .tc-meta (0,1,0) проигрывает правилу .tc-featured .tc-meta (0,2,0)\n' +
    '          из базы. Замер 23.09: мета была 14 при заголовке 14 — подпись\n' +
    '          того же кегля, что заголовок.');
правило('на телефоне главная карточка крупнее обычной',
    тел && /\.tournaments-grid > \.tc:nth-child\(1\) \.tc-title\s*\{\s*font-size: var\(--fs-base\)/.test(тел)
        && /\.tournaments-grid > \.tc:nth-child\(1\) \.tc-image\s*\{[^}]*height: 150px/.test(тел),
    'Ступень card title лестницы 86:10 и афиша 150 против 120.');
['телефон', 'лента'].forEach((имя, i) => {
    const б = i === 0 ? тел : лен;
    правило('цель нажатия кнопки 44 — ' + имя,
        б && /min-height: 44px/.test(б),
        'Палец один и тот же, экран просто повёрнут. С padding 8 и кеглем 12\n' +
        '          выходило около 33.');
});

/* ── плитка в разметке: адрес совпадает со ссылкой раздела ───────────────── */
const js = безКом(чит('js/home-tournaments.js'));
