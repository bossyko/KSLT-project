/**
 * ЗАМОРОЗКА КУСКА 150 — ПЕЧАТНЫЙ ЛИСТ ОТЧЁТА ОДИН НА ПРОДУКТ.
 *
 * ЧТО БЫЛО. Лист печатного отчёта существовал ТРИЖДЫ — «Пользователи»,
 * «Ваучеры», «Финансы», — и копией был не css, а ВЕСЬ ЛИСТ: открытие
 * окна, скелет документа, шапка с заголовком и периодом, полоса плашек,
 * таблица, подвал и зов печати из `onload`. Замер по правилам: 13 из 17
 * совпадали знак в знак, тела `vouchers`/`finances` — 0.99.
 *
 * ЧЕТЫРЁХ РАСХОЖДЕНИЙ БЫЛО ТРИ ЗАКОННЫХ И ОДНО МЁРТВОЕ: `.breakdown`
 * нужен только «Пользователям» (в их разметке он есть), плотные плашки —
 * тоже их свойство, а `.no-print` не носит ни один элемент продукта.
 *
 * Правила держат отношение: лист один, зовут его три раздела, у каждого
 * свои доводы, мёртвое правило не вернулось, а текст, который дом
 * получает ТЕКСТОМ, он сам и гасит.
 */
const fs = require('fs');
const path = require('path');
const acorn = require(path.join(__dirname, '..', 'node_modules', 'acorn'));

const КОРЕНЬ = path.join(__dirname, '..');
const чит = (ф) => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ДОМ = 'js/admin/core/export.js';
const РАЗДЕЛЫ = ['js/admin/sections/users.js', 'js/admin/sections/vouchers.js',
                 'js/admin/sections/finances.js'];

let плохо = 0, правил = 0;
function правило(имя, ок, беда) {
    правил++;
    if (ок) return;
    плохо++;
    console.log('\n  НЕ ТАК  ' + имя + '\n          ' + String(беда).split('\n').join('\n          '));
}
const дерево = (т) => acorn.parse(т, { ecmaVersion: 2022, locations: true });
function обойти(узел, дело, род) {
    if (!узел || typeof узел !== 'object') return;
    if (узел.type) дело(узел, род);
    for (const к in узел) {
        if (к === 'loc') continue;
        const з = узел[к];
        if (Array.isArray(з)) з.forEach(д => обойти(д, дело, узел));
        else if (з && typeof з === 'object' && з.type) обойти(з, дело, узел);
    }
}
const домТекст = чит(ДОМ);

/* ---- 1. лист собирается только в доме ---- */
const своиЛисты = [];
function обходJs(д) {
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) return обходJs(п);
        if (!/\.js$/.test(э.name)) return;
        const т = чит(п);
        if (/\.report-header\s*\{/.test(т) && п !== ДОМ) своиЛисты.push(п);
    });
}
обходJs('js');
правило('лист отчёта описан только в доме',
    своиЛисты.length === 0,
    'Свой лист вернулся в: ' + своиЛисты.join(', ') + '.\n' +
    'Лист был описан трижды, и копией был не css, а весь лист целиком.');

/* ---- 2. окно отчёта открывает только дом ---- */
const свойОткрыв = [];
РАЗДЕЛЫ.concat(['js/admin/core/layout.js']).forEach(ф => {
    const т = чит(ф);
    обойти(дерево(т), у => {
        if (у.type !== 'CallExpression') return;
        if (т.slice(у.callee.start, у.callee.end) !== 'window.open') return;
        свойОткрыв.push(ф + ':' + у.loc.start.line);
    });
});
правило('окно отчёта открывает дом, а не раздел',
    свойОткрыв.length === 0,
    'Разделы снова открывают окно сами: ' + свойОткрыв.join(', ') + '.\n' +
    'У ваучеров окно открывалось ДО сборки строк, и при пустом отчёте\n' +
    'оставалась пустая вкладка. Теперь окно появляется вместе с листом.');

/* ---- 3. у дома есть понятие ---- */
правило('дом отдаёт понятие `печатныйЛист`',
    /A\.печатныйЛист\s*=\s*печатныйЛист/.test(домТекст) &&
    /function печатныйЛист\s*\(о\)/.test(домТекст),
    'В `' + ДОМ + '` нет понятия `печатныйЛист`. Разделы зовут его по\n' +
    'имени, и без него кнопка печати перестанет работать МОЛЧА.');

/* ---- 4. три зова, и у каждого обязательные доводы ---- */
const зовы = [];
РАЗДЕЛЫ.forEach(ф => {
    const т = чит(ф);
    обойти(дерево(т), у => {
        if (у.type !== 'CallExpression') return;
        if (!/печатныйЛист$/.test(т.slice(у.callee.start, у.callee.end))) return;
        const д = у.arguments[0];
        зовы.push({
            файл: ф, строка: у.loc.start.line,
            поля: (д && д.type === 'ObjectExpression')
                ? д.properties.map(п => п.key && (п.key.name || п.key.value)) : []
        });
    });
});
правило('дом зовут три раздела — замерено',
    зовы.length === 3,
    'Зовов `печатныйЛист`: ' + зовы.length + ', замерено 3 (пользователи,\n' +
    'ваучеры, финансы). Найдено:\n' + зовы.map(з => '  ' + з.файл + ':' + з.строка).join('\n'));
const ОБЯЗАТЕЛЬНЫЕ = ['заголовок', 'периодПодпись', 'период', 'плашки', 'колонки',
                      'строки', 'подвалСлева', 'подвалСправа'];
const неполные = зовы.filter(з => !ОБЯЗАТЕЛЬНЫЕ.every(п => з.поля.indexOf(п) !== -1));
правило('у каждого зова на месте все обязательные доводы',
    неполные.length === 0,
    'Не хватает доводов:\n' + неполные.map(з => '  ' + з.файл + ':' + з.строка +
        ' — нет ' + ОБЯЗАТЕЛЬНЫЕ.filter(п => з.поля.indexOf(п) === -1).join(', ')).join('\n') +
    '\nПустое место в листе читается как ошибка данных, а не как пропуск\n' +
    'довода, поэтому доводы названы поимённо.');

/* ---- 5. плотный лист и разбивка — свойства одного отчёта ---- */
const плотные = зовы.filter(з => з.поля.indexOf('плотный') !== -1);
правило('плотный лист назван доводом ровно у одного отчёта',
    плотные.length === 1 && /users\.js$/.test(плотные[0].файл),
    'Довод `плотный` стоит у ' + плотные.length + ' зовов: ' +
    плотные.map(з => з.файл).join(', ') + '.\n' +
    'Плашки 100 вместо 120 и полоса 16 вместо 24 — свойство отчёта о\n' +
    'пользователях, а не дома. ВИД РАБОТЫ НЕ МЕНЯЕТСЯ.');
const сРазбивкой = зовы.filter(з => з.поля.indexOf('разбивка') !== -1);
правило('разбивка названа доводом ровно у одного отчёта',
    сРазбивкой.length === 1 && /users\.js$/.test(сРазбивкой[0].файл),
    'Довод `разбивка` стоит у ' + сРазбивкой.length + ' зовов.\n' +
    'Строка разбивки по ролям есть только в отчёте о пользователях.');

/* ---- 6. правила разбивки не лежат мёртвыми ---- */
правило('правила разбивки выдаются только под своим доводом',
    /о\.разбивка\s*\n?\s*\?\s*'\.breakdown/.test(домТекст.replace(/\r/g, '')) ||
    /\(о\.разбивка[\s\S]{0,120}\.breakdown \{/.test(домТекст),
    'Правила `.breakdown` выдаются всегда. У двух отчётов из трёх\n' +
    'разбивки нет вовсе, и правила лежали бы МЁРТВЫМИ — а мёртвый css\n' +
    'стоит под заморозкой, а не под обещанием.');

/* ---- 7. мёртвое правило не вернулось, живое на месте ---- */
/* ПРАВИЛО ЧИТАЕТ ЛИТЕРАЛЫ, А НЕ ТЕКСТ ФАЙЛА. Первая запись искала
   `.no-print {` по всему файлу — и упала на МОЁМ ЖЕ ПОЯСНЕНИИ к дому, где
   это правило названо как снятое. Ловушка одной формы встречается в этом
   проекте девятый раз: МОИ СЛОВА О КОДЕ ВЫГЛЯДЯТ КАК КОД. Теперь правило
   смотрит только строковые литералы, которых в комментариях не бывает. */
const литералыДома = [];
обойти(дерево(домТекст), у => {
    if (у.type === 'Literal' && typeof у.value === 'string') литералыДома.push(у.value);
});
правило('мёртвое правило `.no-print` не вернулось в лист',
    !литералыДома.some(с => /(^|[^-\w])\.no-print\s*\{/.test(с)),
    'В листе снова `.no-print { display: none }`. ЗАМЕРЕНО: класс\n' +
    '`no-print` не носит ни один элемент продукта. Живое понятие зовётся\n' +
    '`ad-no-print`, и его ставит печать панели в этом же файле.');
/* ГРАНИЦА СЛОВА У ИМЕНИ КЛАССА. Первая запись искала `.ad-no-print` без
   границы, и откат «переименовать класс в `.ad-no-print-snyato`» её НЕ
   ронял: имя класса — приставка нового имени. ИМЯ КЛАССА БЕЗ ГРАНИЦЫ
   СЛОВА НАХОДИТ СВОЁ ПРОДОЛЖЕНИЕ. */
правило('живое `ad-no-print` имеет правило в css админки',
    /\.ad-no-print(?![-\w])/.test(чит('css/admin.css')) &&
    /ad-no-print(?![-\w])/.test(домТекст),
    'Правило `ad-no-print` пропало из `css/admin.css` или его перестал\n' +
    'ставить `export.js`. Тогда служебные колонки уедут на бумагу.');

/* ---- 8. граница экранирования: текст гасит дом ---- */
/* ПРОВЕРЯЕТСЯ ОТСУТСТВИЕ СЫРОГО ВСТАВЛЕНИЯ, А НЕ НАЛИЧИЕ ОДНОГО ЗОВА.
   Первая запись требовала `гасить(о.заголовок)` — и откат, снявший гашение
   в `<title>`, её не ронял: тот же зов есть во втором месте, в `<h1>`.
   НАЛИЧИЕ ОДНОГО ЗОВА НЕ ГОВОРИТ О ВТОРОМ (правило куска 146, и вот оно
   снова). Теперь из тела вырезаются все `гасить(...)`, и в остатке не
   должно остаться ни одного текстового довода. */
let гаситЛист = false, сырые = [];
обойти(дерево(домТекст), (у, род) => {
    if (!(у.type === 'FunctionDeclaration' && у.id && у.id.name === 'печатныйЛист')) return;
    const тело = домТекст.slice(у.start, у.end);
    /* ОДИН УРОВЕНЬ ВЛОЖЕННОСТИ ВНУТРИ ЗОВА: в доме стоит
       `гасить(String(п.значение))`, и выкус «без скобок внутри» его не
       видел — правило доложило о сыром вставлении, которого нет.
       ПРИБОР, НЕ ЗНАЮЩИЙ ВЛОЖЕННОСТИ, ВИДИТ ЧАСТЬ ЗОВА. */
    const остаток = тело.replace(/гасить\((?:[^()]|\([^()]*\))*\)/g, 'ГАШЕНО');
    ['о.заголовок', 'о.период', 'о.периодПодпись', 'о.подвалСлева', 'о.подвалСправа',
     'п.значение', 'п.подпись'].forEach(д => {
        if (остаток.indexOf(д) !== -1) сырые.push(д);
    });
    гаситЛист = /var гасить = A\.esc/.test(тело) && сырые.length === 0;
});
правило('текст, пришедший текстом, дом гасит сам',
    гаситЛист,
    'Вставлено без гашения: ' + (сырые.join(', ') || 'нет, но пропал сам `гасить`') + '.\n' +
    'Дом обязан гасить `заголовок`, `период`, подписи плашек и колонок:\n' +
    'он получает их ТЕКСТОМ. `строки` и `разбивка` приходят готовой\n' +
    'разметкой, и за данные внутри отвечает раздел — это шов, и он\n' +
    'назван вслух в пояснении дома.');

/* ---- 9. печать зовётся из onload нового окна ---- */
правило('печать зовётся из onload нового окна',
    /window\.onload=function\(\)\{window\.print\(\);\}/.test(домТекст),
    'Зов печати ушёл из `onload`. Если печатать раньше отрисовки, на\n' +
    'бумагу уходит пустая страница — так было во всех трёх копиях, и\n' +
    'перенесено как есть.');

/* ---- вывод ---- */
console.log('');
if (плохо === 0) {
    console.log('  ок      печатный лист: ' + правил + ' правил');
    console.log('          лист один, зовов ' + зовы.length + ', плотный и разбивка — доводы');
    console.log('          мёртвое `.no-print` не вернулось, живое `ad-no-print` на месте');
} else {
    console.log('  НЕ ТАК  ' + плохо + ' из ' + правил + ' правил');
    process.exitCode = 1;
}
console.log('');
