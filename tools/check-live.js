/* ОТМЕНЕНО 24.09 РЕШЕНИЕМ КОСТИ, доска 437:9. Здесь стояло обратное:
   «.sp-offer h3 вынесен из правила заголовка раздела». Причина отмены —
   замер: «Станьте спонсором» это не перебивка внутри раздела, а раздел со
   своей секцией, своими отступами и своей поверхностью. Он получил h2 и
   встал в общее правило намеренно — иначе пара «этот заголовок и заголовок
   соседнего раздела» поедет по двум разным границам. */
/* ОДИН ЛЕВЫЙ КРАЙ НА СТРАНИЦЕ — 24.09. Поле от края экрана на узком задавала
   строка padding-inline: 26px для всех section. Померено на 768: семь секций
   стояли на 26, а #venues и блок спонсорам — на системном --pad-x, 16.89,
   потому что их слои переписаны и берут формулу. Два края на одной странице.
   26 не ступень шкалы и ниоткуда не выведено; доска 86:9 говорит «поле 16,
   содержимое 358» — ровно то, что даёт --pad-x. Теперь определение одно. */
правило('поле от края экрана задаёт --pad-x, и только оно',
    /@media \(max-width: 768px\) \{\s*section \{[^}]*padding-inline: var\(--pad-x\)/.test(тЧ) &&
    !/section \{[^}]*padding-inline:\s*\d+px/.test(тЧ),
    'Было padding-inline: 26px — второй левый край страницы. На 390 содержимое\n' +
    '          выходило 338 вместо 358, обещанных доской 86:9.');

правило('заголовок блока спонсорам стоит в том же правиле, а не в своём',
    /\.sp-offer h2,/.test(тЧ) && !/\.sp-offer h3/.test(тЧ),
    'Мобильная ступень заголовка раздела определена один раз, и блок\n' +
    '          «Станьте спонсором» берёт её оттуда же, что и все разделы.');

/* ── ряд карточек ────────────────────────────────────────────────────────── */
