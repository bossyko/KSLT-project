#!/usr/bin/env node
/**
 * ИМЕНА В КОДЕ — ЗАМОРОЗКА КУСКА 206 (27.10).
 *
 * ПОЧЕМУ ОНА ЕСТЬ. Проверка имён в продукте была, линтер настроен, но
 * внутри `tools/check-rules.js` стоял храповик `ДОЛГ_ЛИНТЕРА = 53`.
 * Проверка каждый раз писала «новых ошибок нет (старый долг 53)» — и ровно
 * эти 53 находки прятала. Среди них лежали ДВА ЖИВЫХ ПАДЕНИЯ экранов
 * приложения:
 *   `mobile/www/js/screens/rating.js:173` — `AUTH` не определён вовсе,
 *   экран рейтинга падал на первом зове и оставался пустым;
 *   `mobile/www/js/screens/profile.js` — `renderProfile()` в двух местах,
 *   имя, которого в файле нет (отрисовка зовётся `P.load`).
 * Плюс 16 мёртвых дублей ключей (побеждает последний, ранние не доходят до
 * человека) и 30 слепых мест в самих настройках линтера.
 *
 * ХРАПОВИК С ЗАПАСОМ ПРЯЧЕТ ЖИВОЕ ПАДЕНИЕ. Правила ниже держат не число
 * находок, а ОТНОШЕНИЕ: долг равен нулю, линтер читает весь корень, список
 * домов считается из кода обеих половин продукта, и проверка входит в
 * общий прогон.
 *
 * Запуск: node tools/check-imena-v-kode.js
 * Корень можно подменить: KSLT_KOREN=<путь> — этим пользуется прувер.
 */

const fs = require('fs');
const path = require('path');
const { spawnSync } = require('child_process');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0;
let держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}

function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const настройки = чит('eslint.config.mjs');
const правилаКлуба = чит('tools/check-rules.js');
const общийПрогон = чит('tools/check-vse.js');

/* ── 1. ХРАПОВИК ДОЛГА СТОИТ НА НУЛЕ ── */
правило(
    'долг линтера равен нулю',
    /const\s+ДОЛГ_ЛИНТЕРА\s*=\s*0\s*;/.test(правилаКлуба),
    'В `tools/check-rules.js` храповик `ДОЛГ_ЛИНТЕРА` обязан стоять на\n' +
    'нуле. Любое другое число — это разрешение прятать находки, и именно\n' +
    'так дожили до 27.10 два пустых экрана приложения.');

/* ── 2. ЛИНТЕР ЧИТАЕТ ВЕСЬ КОРЕНЬ, А НЕ СПИСОК ПАПОК ── */
правило(
    'проверка имён гоняет весь корень',
    /spawnSync\(линтер,\s*\['\.'\]/.test(правилаКлуба),
    'Запуск обязан быть по `.`, а не по списку папок: `tests/` в прежний\n' +
    'список не входили, и глушитель линтера лежал там незамеченным.');

/* ── 3. ДОМА СЧИТАЮТСЯ ИЗ КОДА ОБЕИХ ПОЛОВИН ПРОДУКТА ── */
правило(
    'список домов считается из кода',
    /matchAll\(\/window\\\.\(KSLT_/.test(настройки),
    'Имена домов берутся из кода признаком `window.KSLT_ИМЯ =`, а не\n' +
    'держатся руками: список, который держится руками, отстаёт (кусок 197).');

правило(
    'обход идёт и по приложению',
    /обойти\('js'\)/.test(настройки) && /обойти\('mobile\/www\/js'\)/.test(настройки),
    'Обход обязан пройти ОБЕ половины продукта: `js` и `mobile/www/js`.\n' +
    'Пока шёл только по `js`, дом `KSLT_NEWS_MEDIA` из приложения давал\n' +
    'три находки на живом коде и прятал настоящие беды в общем шуме.');

правило(
    'глобальная функция без отступа тоже считается домом',
    /matchAll\(\/\^function/.test(настройки),
    'Второй признак: `function имя(` в начале строки. Внутри IIFE все\n' +
    'объявления с отступом, поэтому без отступа остаются только настоящие\n' +
    'глобали — так узнаётся `initSupabase`.');

/* ── 4. ПРАВИЛА ЛИНТЕРА ВКЛЮЧЕНЫ В ОБА БЛОКА НАСТРОЕК ── */
const блоковНеопределённых = (настройки.match(/'no-undef':\s*'error'/g) || []).length;
const блоковДублей = (настройки.match(/'no-dupe-keys':\s*'error'/g) || []).length;
правило(
    'оба блока настроек ловят неопределённые имена и дубли ключей',
    блоковНеопределённых >= 2 && блоковДублей >= 2,
    'Блоков настроек два — продукт и инструменты. `no-undef` и\n' +
    '`no-dupe-keys` обязаны стоять `error` в каждом, иначе половина кода\n' +
    'проверяется, а половина нет. Сейчас: no-undef в ' + блоковНеопределённых +
    ', no-dupe-keys в ' + блоковДублей + '.');

/* ── 5. ИНСТРУМЕНТЫ ЧИТАЮТСЯ КАК МОДУЛИ NODE ── */
правило(
    'инструменты читаются как commonjs',
    /files:\s*\['tools\/\*\*\/\*\.js'\][\s\S]{0,400}sourceType:\s*'commonjs'/.test(настройки),
    'У блока `tools/**/*.js` обязан стоять `sourceType: \'commonjs\'`.\n' +
    'Со `script` линтер звал законный `return` верхнего уровня\n' +
    'синтаксической ошибкой и ВООБЩЕ НЕ ЧИТАЛ прувер версий.');

/* ── 6. ДВА ПОЧИНЕННЫХ ЭКРАНА ПРИЛОЖЕНИЯ ── */
const рейтинг = чит('mobile/www/js/screens/rating.js');
правило(
    'экран рейтинга приложения знает дом входа',
    !/\bAUTH\s*\./.test(рейтинг) || /var\s+AUTH\s*=\s*window\.KSLT_AUTH/.test(рейтинг),
    '`mobile/www/js/screens/rating.js` зовёт `AUTH.…`, значит обязан взять\n' +
    'дом входа: `var AUTH = window.KSLT_AUTH;`. Без этой строки экран\n' +
    'рейтинга падал `ReferenceError` и оставался пустым.');

const профиль = чит('mobile/www/js/screens/profile.js');
правило(
    'профиль приложения зовёт отрисовку своим именем',
    !/renderProfile\s*\(/.test(профиль),
    '`mobile/www/js/screens/profile.js` обязан звать отрисовку тем именем,\n' +
    'которое в нём объявлено (`P.load`). Имени `renderProfile` в файле нет\n' +
    'вовсе — два зова падали `ReferenceError`.');

/* ── 7. ОДНО ОПРЕДЕЛЕНИЕ НА КЛЮЧ СЛОВАРЯ ── */
правило(
    'ключ «место проведения» объявлен один раз',
    (чит('mobile/www/js/i18n.js').match(/'td\.venue'/g) || []).length === 1,
    'В словаре приложения `td.venue` был объявлен дважды: «Место» и\n' +
    '«Место проведения». Побеждает последний, первый не доходит до\n' +
    'человека. ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ.');

правило(
    'ключ «онлайн» объявлен один раз на язык',
    (чит('js/services.js').match(/\bonline:/g) || []).length === 3,
    'В `js/services.js` ключ `online` был объявлен дважды в каждом из трёх\n' +
    'языков: «недавно заходил» и «Онлайн». Ранний был мёртв. Ожидается\n' +
    'ровно три объявления — по одному на язык.');

/* ── 8. ПРОВЕРКА ИМЁН ВХОДИТ В ОБЩИЙ ПРОГОН ── */
правило(
    'заморозка имён входит в общий прогон',
    /check-imena-v-kode\.js/.test(общийПрогон),
    'СТОРОЖ, КОТОРОГО НЕ ГОНЯЮТ, НЕ СТОРОЖ. `check-imena-v-kode.js`\n' +
    'обязан стоять в списке `tools/check-vse.js`.');

/* ── 9. ЛИНТЕР ПО ВСЕМУ КОРНЮ НЕ ДАЁТ НИ ОДНОЙ НАХОДКИ ── */
(function прогонЛинтера() {
    const линтер = path.join(КОРЕНЬ, 'node_modules', '.bin', 'eslint');
    if (!fs.existsSync(линтер)) {
        console.log('  ? линтер не установлен — npm i -D eslint');
        return;
    }
    const з = spawnSync(линтер, ['.'], { cwd: КОРЕНЬ, encoding: 'utf8' });
    const вывод = (з.stdout || '') + (з.stderr || '');
    const итог = вывод.match(/✖ (\d+) problems?/);
    const сколько = итог ? parseInt(итог[1], 10) : (з.status === 0 ? 0 : -1);
    правило(
        'линтер по всему корню чист',
        з.status === 0 && сколько === 0,
        'Находок: ' + (сколько < 0 ? 'линтер не отработал' : сколько) + '.\n' +
        'Ни одной быть не должно: ноль — это и есть разобранный долг.\n' +
        вывод.split('\n').filter(с => /error|warning|Oops/.test(с)).slice(0, 8).join('\n'));
})();

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      имена в коде: все ' + держится + ' правил держатся');
    console.log('          линтер по всему корню чист, долг храповика ноль\n');
}
