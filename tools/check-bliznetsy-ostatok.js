function обойти(у, дело, род) {
    if (!у || typeof у.type !== 'string') return;
    дело(у, род);
    for (const к of Object.keys(у)) {
        if (к === 'type' || к === 'start' || к === 'end' || к === 'loc') continue;
        const v = у[к];
        if (Array.isArray(v)) v.forEach(x => x && typeof x.type === 'string' && обойти(x, дело, у));
        else if (v && typeof v.type === 'string') обойти(v, дело, у);
    }
}
