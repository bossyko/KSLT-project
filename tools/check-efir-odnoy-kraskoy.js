/* Оранжевый добавлен 18.10: именно он стоял в админке на роли эфира.
   Запрещена НЕ КРАСКА, А КРАСКА В ЭТОЙ РОЛИ — `--warning` остаётся
   законным у «скоро», «черновика» и «регистрация закрыта». */
const ЧУЖИЕ = ['#ff3b30', '#ef4444', '#ff6961', '#4ade80', '#22c55e',
               'var(--warning)', 'var(--warning-faint)', 'var(--warning-subtle)',
               'var(--warning-border)', 'var(--role-manager)', 'var(--accent)',
               '255, 59, 48', '255,59,48', '239, 68, 68', '239,68,68',
               '74,222,128', '74, 222, 128', '22,163,74', '22, 163, 74',
               '21,128,61', '21, 128, 61'];

const файлы = {};
[...new Set(РОЛЬ.map(([ф]) => ф))].forEach(ф => { файлы[ф] = гасить(чит(ф)); });

const грязные = [], пропавшие = [];
РОЛЬ.forEach(([ф, сел]) => {
    const тела = блоки(файлы[ф], сел);
    if (!тела.length) { пропавшие.push(ф + '  ' + сел); return; }
    тела.forEach(т => {
        ЧУЖИЕ.forEach(ч => {
            if (т.toLowerCase().includes(ч.toLowerCase())) грязные.push(ф + '  ' + сел + '  ←  ' + ч);
        });
        /* И КАДРЫ АНИМАЦИЙ, КОТОРЫЕ ЗОВЁТ ЭТОТ БЛОК. Первая редакция
           правила их не читала: `@keyframes` не селектор, и старый красный
           спокойно дожил в `pulse-glow` у значка эфира до следующего
           куска. Краска, спрятанная в кадре, красит ровно тот же элемент. */
        const зовёт = т.match(/animation(?:-name)?\s*:\s*([^;]+)/g) || [];
        зовёт.forEach(стр => {
            (стр.match(/[a-zA-Z][\w-]*/g) || []).forEach(имя => {
                const к = блоки(файлы[ф], '@keyframes ' + имя);
                к.forEach(тк => ЧУЖИЕ.forEach(ч => {
                    if (тк.toLowerCase().includes(ч.toLowerCase()))
                        грязные.push(ф + '  ' + сел + ' → @keyframes ' + имя + '  ←  ' + ч);
                }));
            });
        });
    });
});

