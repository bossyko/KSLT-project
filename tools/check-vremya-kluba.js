/**
 * ВРЕМЯ КЛУБА — СТОРОЖ НА ВЕСЬ ПРОДУКТ (ветка D, круг 8, 17.10).
 *
 * РЕШЕНИЕ КОСТИ, ПОВТОРЁННОЕ 17.10: «время надо поставить Кыргызстан, там
 * работает приложение и сайт и турниры». То есть день турнира, срок
 * заявки, членство и отсчёты считаются по БИШКЕКУ — не по Гринвичу и не
 * по часовому поясу того, кто смотрит страницу.
 *
 * ЧТО НАШЁЛ ЗАМЕР 17.10. «Сегодня» бралось как
 * `new Date().toISOString().slice(0, 10)` — это день по ГРИНВИЧУ — в 33
 * местах: 30 в админке, 3 в публичной части. Бишкек идёт на шесть часов
 * впереди: с полуночи до 6 утра по Бишкеку код считал ещё вчерашний
 * день — заявка, закрытая сегодня, оставалась открытой, а членство,
 * истекающее сегодня, ещё живым. У Кости в Чикаго ошибка зеркальная: его
 * вечер — уже завтрашний день в клубе.
 *
 * ДВА ДОМА ОДНОГО ПОНЯТИЯ. `js/kslt-vremya.js` считал день зашитым
 * смещением «+6 часов», а `js/admin/core/utils.js` — по ИМЕНИ зоны
 * (`toLocaleDateString('sv-SE', { timeZone: 'Asia/Bishkek' })`). База
 * считает по имени (`AT TIME ZONE 'Asia/Bishkek'`). Победило имя:
 * смещение числом верно ровно до того дня, когда часы тронут. Дом один,
 * `A.сегодняБишкек` оставлен обёрткой над ним.
 *
 *   node tools/check-vremya-kluba.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}
function безКом(т) {
    return т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
            .replace(/^[ \t]*\/\/[^\n]*$/gm, '');
}
function файлы(каталог, расш, собранное) {
    собранное = собранное || [];
    fs.readdirSync(path.join(КОРЕНЬ, каталог), { withFileTypes: true }).forEach(э => {
        const п = каталог + '/' + э.name;
        if (э.isDirectory()) файлы(п, расш, собранное);
        else if (расш.some(р => э.name.endsWith(р))) собранное.push(п);
    });
    return собранное;
}

const ДОМ = 'js/kslt-vremya.js';
const ТЕКСТ_ДОМА = fs.readFileSync(path.join(КОРЕНЬ, ДОМ), 'utf8');

/* ---- 1. ДОМ ЕСТЬ И СЧИТАЕТ ПО ИМЕНИ ЗОНЫ ---- */
правило('дом времени считает день ПО ИМЕНИ ЗОНЫ, а не зашитым смещением',
    /timeZone:\s*ЗОНА|timeZone:\s*'Asia\/Bishkek'/.test(ТЕКСТ_ДОМА) &&
    /Asia\/Bishkek/.test(ТЕКСТ_ДОМА) &&
    !/СМЕЩЕНИЕ_МИНУТ|\*\s*60\s*\*\s*60000/.test(безКом(ТЕКСТ_ДОМА)),
    'Смещение числом верно ровно до того дня, когда часы тронут, а база\n' +
    'считает AT TIME ZONE \'Asia/Bishkek\' — по имени. Два определения\n' +
    'одного понятия разойдутся ровно на шве.');

правило('дом отдаёт и «сегодня», и день любого момента',
    /В\.сегодня\s*=/.test(ТЕКСТ_ДОМА) && /В\.деньПоБишкеку\s*=/.test(ТЕКСТ_ДОМА),
    'Читателям нужно и то и другое: «сегодня» для сроков и день\n' +
    'конкретной отметки для записей в базе.');

/* ---- 2. ДЕНЬ НИГДЕ НЕ СЧИТАЕТСЯ ПО ГРИНВИЧУ ---- */
const ДЕНЬ_ПО_ГРИНВИЧУ =
    /toISOString\(\)\s*\.\s*(?:slice\(\s*0\s*,\s*10\s*\)|split\(\s*'T'\s*\)\s*\[\s*0\s*\])|getUTCDate\(|getUTCFullYear\(|getUTCMonth\(/;
const места = [];
файлы('js', ['.js']).filter(ф => ф !== ДОМ).forEach(ф => {
    безКом(fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8')).split('\n').forEach((с, i) => {
        if (ДЕНЬ_ПО_ГРИНВИЧУ.test(с)) места.push(ф + ':' + (i + 1) + '  ' + с.trim().slice(0, 70));
    });
});
правило('день нигде не берётся по Гринвичу',
    места.length === 0,
    'Мест: ' + места.length + '\n' + места.slice(0, 10).join('\n') + '\n' +
    'День клуба берётся у дома: KSLT_VREMYA.сегодня() или\n' +
    'KSLT_VREMYA.деньПоБишкеку(момент). `toISOString().slice(0, 10)` — это\n' +
    'день по Гринвичу, и он расходится с днём клуба шесть часов в сутки.');

/* ---- 3. ОДНО ОПРЕДЕЛЕНИЕ: ЗОНА НАЗВАНА В ОДНОМ МЕСТЕ ---- */
const зоны = [];
файлы('js', ['.js']).forEach(ф => {
    const т = безКом(fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'));
    const сколько = (т.match(/Asia\/Bishkek/g) || []).length;
    if (сколько) зоны.push({ ф, сколько });
});
правило('имя зоны живёт в одном файле — в доме времени',
    зоны.length === 1 && зоны[0].ф === ДОМ,
    'Зона названа в: ' + зоны.map(з => з.ф + ' ×' + з.сколько).join(', ') + '\n' +
    'Второе место, где написано \'Asia/Bishkek\', — это второй дом\n' +
    'времени, и он разойдётся с первым.');

/* ---- 4. ДОМ ПОДКЛЮЧЁН ВЕЗДЕ, ГДЕ ЕГО ЗОВУТ ---- */
const страницы = ['index.html', 'index-en.html', 'index-kg.html']
    .concat(файлы('pages', ['.html']))
    .concat(файлы('maket', ['.html']));
const потребители = /src="[^"]*(?:player\.js|membership\.js|dashboard\.js|admin\/core\/utils\.js)\?/;
const без = страницы.filter(ф => {
    const п = path.join(КОРЕНЬ, ф);
    if (!fs.existsSync(п)) return false;
    const т = fs.readFileSync(п, 'utf8');
    return потребители.test(т) && т.indexOf('kslt-vremya.js') === -1;
});
правило('дом времени подключён на каждой странице, где его зовут',
    без.length === 0,
    'Без дома: ' + без.length + '\n' + без.slice(0, 8).join('\n') + '\n' +
    'Без него KSLT_VREMYA не существует, и страница падает на первом же\n' +
    'сроке — молча, если вызов стоит в ветке, которая случается не всегда.');

/* ---- 5. ДОМ СТОИТ РАНЬШЕ СВОИХ ЧИТАТЕЛЕЙ ---- */
const поздно = [];
страницы.forEach(ф => {
    const п = path.join(КОРЕНЬ, ф);
    if (!fs.existsSync(п)) return;
    const т = fs.readFileSync(п, 'utf8');
    const дом = т.indexOf('kslt-vremya.js');
    if (дом === -1) return;
    const m = т.match(potребительРе());
    if (m && m.index < дом) поздно.push(ф);
});
function potребительРе() {
    return /src="[^"]*(?:player\.js|membership\.js|dashboard\.js|admin\/core\/utils\.js)\?/;
}
правило('дом подключён РАНЬШЕ тех, кто его зовёт',
    поздно.length === 0,
    'Поздно: ' + поздно.join(', ') + '\n' +
    'Скрипт, стоящий выше, выполняется раньше: читатель не найдёт дом.');

if (!ошибки.length) {
    console.log('\n  ок      время клуба: 5 правил');
    console.log('          день считается по имени зоны Asia/Bishkek, дом один');
    console.log('          мест с днём по Гринвичу: 0');
    console.log('          страниц с домом: ' + страницы.filter(ф => {
        const п = path.join(КОРЕНЬ, ф);
        return fs.existsSync(п) && fs.readFileSync(п, 'utf8').indexOf('kslt-vremya.js') !== -1;
    }).length + '\n');
    process.exit(0);
}
console.log('\n  УПАЛО: ' + ошибки.length + '\n');
ошибки.forEach(о => console.log('  x  ' + о.имя + '\n     ' + о.подсказка.replace(/\n/g, '\n     ') + '\n'));
process.exit(1);
