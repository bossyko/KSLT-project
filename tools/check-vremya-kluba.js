const fs = require('fs');
const path = require('path');

/* ОБХОД js/ ЦЕЛИКОМ: кусок может лежать в нескольких файлах, и прибор
   обязан читать все. */
function собратьФайлы(папка) {
    var итог = [];
    if (!fs.existsSync(папка)) return итог;
    fs.readdirSync(папка, { withFileTypes: true }).forEach(function (и) {
        var п = path.join(папка, и.name);
        if (и.isDirectory()) { итог = итог.concat(собратьФайлы(п)); return; }
        if (/\.js$/.test(и.name)) итог.push(п);
    });
    return итог;
}

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}
function безКом(т) {
    return т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
            .replace(/^[ \t]*\/\/[^\n]*$/gm, '');
}
function файлы(каталог, расш, собранное) {
    собранное = собранное || [];
    fs.readdirSync(path.join(КОРЕНЬ, каталог), { withFileTypes: true }).forEach(э => {
        const п = каталог + '/' + э.name;
        if (э.isDirectory()) файлы(п, расш, собранное);
        else if (расш.some(р => э.name.endsWith(р))) собранное.push(п);
    });
    return собранное;
}

const ДОМ = 'js/kslt-vremya.js';
const ТЕКСТ_ДОМА = fs.readFileSync(path.join(КОРЕНЬ, ДОМ), 'utf8');

/* ---- 1. ДОМ ЕСТЬ И СЧИТАЕТ ПО ИМЕНИ ЗОНЫ ---- */
правило('дом времени считает день ПО ИМЕНИ ЗОНЫ, а не зашитым смещением',
    /timeZone:\s*ЗОНА|timeZone:\s*'Asia\/Bishkek'/.test(ТЕКСТ_ДОМА) &&
    /Asia\/Bishkek/.test(ТЕКСТ_ДОМА) &&
    !/СМЕЩЕНИЕ_МИНУТ|\*\s*60\s*\*\s*60000/.test(безКом(ТЕКСТ_ДОМА)),
    'Смещение числом верно ровно до того дня, когда часы тронут, а база\n' +
    'считает AT TIME ZONE \'Asia/Bishkek\' — по имени. Два определения\n' +
    'одного понятия разойдутся ровно на шве.');

правило('дом отдаёт и «сегодня», и день любого момента',
    /В\.сегодня\s*=/.test(ТЕКСТ_ДОМА) && /В\.деньПоБишкеку\s*=/.test(ТЕКСТ_ДОМА),
    'Читателям нужно и то и другое: «сегодня» для сроков и день\n' +
    'конкретной отметки для записей в базе.');

/* ---- 2. ДЕНЬ НИГДЕ НЕ СЧИТАЕТСЯ ПО ГРИНВИЧУ ---- */
/* ПРИЗНАК ЗНАЛ ДВЕ ФОРМЫ ИЗ ТРЁХ. 27.10: `substring(0, 10)` делает ровно
   то же, что `slice(0, 10)`, и два места в `js/tournaments-overview.js`
   жили с днём по Гринвичу, пока сторож показывал ноль.
   ПРИЗНАК, ЗНАЮЩИЙ ОДНО НАПИСАНИЕ, НЕ СТОРОЖИТ ПОНЯТИЕ. */
const ДЕНЬ_ПО_ГРИНВИЧУ =
    /toISOString\(\)\s*\.\s*(?:slice\(\s*0\s*,\s*10\s*\)|substring\(\s*0\s*,\s*10\s*\)|substr\(\s*0\s*,\s*10\s*\)|split\(\s*'T'\s*\)\s*\[\s*0\s*\])|getUTCDate\(|getUTCFullYear\(|getUTCMonth\(/;
const места = [];
файлы('js', ['.js']).filter(ф => ф !== ДОМ).forEach(ф => {
    безКом(fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8')).split('\n').forEach((с, i) => {
        if (ДЕНЬ_ПО_ГРИНВИЧУ.test(с)) места.push(ф + ':' + (i + 1) + '  ' + с.trim().slice(0, 70));
    });
});
/* ── МОМЕНТ, А НЕ ТОЛЬКО ДЕНЬ ───────────────────────────────────────
   08.11, НАЙДЕНО КОСТЕЙ НА БОЕВОЙ. Этот сторож держал ДЕНЬ по Бишкеку и
   был зелёным — а карточка турнира писала «старт через 07ч 41м» у
   турнира, который в Бишкеке уже шёл. Разница ровно двенадцать часов:
   Костя смотрел из Чикаго.
   Причина: момент строился как `new Date(день + 'T' + время + ':00')`
   — строка без пояса читается браузером как ЕГО местное время. Понятие
   «момент по часам клуба» было новым, и правило про день его не знало.
   ЗАПИСЬ СТАРЕЕТ БЫСТРЕЕ КОДА: решение «время клуба — Бишкек» записано
   09.10, а два пути к тому же понятию о нём не знали.
   ВРЕМЯ СТАРТА — СВОЙСТВО ТУРНИРА, А НЕ ЗРИТЕЛЯ. */

правило('дом отдаёт момент по часам Бишкека, а не только день',
    /В\.моментПоБишкеку\s*=\s*function/.test(ТЕКСТ_ДОМА) &&
    /timeZone:\s*ЗОНА/.test(ТЕКСТ_ДОМА),
    'В доме времени нет `моментПоБишкеку`. Без него каждый, кому нужен\n' +
    'момент старта, соберёт его сам — и соберёт по часам зрителя.');

(function () {
    /* ЯКОРЬ НА СОДЕРЖИМОМ: ловим склейку дня и времени в `new Date`.
       Пояс внутри строки ('Z', '+06:00') считается указанным — такая
       запись хотя бы не зависит от зрителя, хотя смещение числом это
       отдельный долг, он ниже. */
    var найдено = [];
    собратьФайлы(path.join(КОРЕНЬ, 'js')).forEach(function (ф) {
        if (/kslt-vremya\.js$/.test(ф)) return;
        var т = fs.readFileSync(ф, 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
        var re = /new Date\(\s*[\w.\[\]]+\s*\+\s*'T'/g;
        var м;
        while ((м = re.exec(т))) {
            var хвост = т.slice(м.index, м.index + 160);
            if (/Z'|\+0\d:00'/.test(хвост)) continue;
            найдено.push(path.relative(КОРЕНЬ, ф));
        }
    });
    правило('момент из дня и времени собирает только дом',
        найдено.length === 0,
        'Момент строится склейкой `new Date(день + "T" + время)` в ' +
        найдено.length + ' месте(ах): ' + найдено.join(', ') + '.\n' +
        'Такая строка без пояса читается как местное время ТОГО, КТО\n' +
        'СМОТРИТ: из Чикаго старт уезжает на двенадцать часов.\n' +
        'Зовите `KSLT_VREMYA.моментПоБишкеку(день, время)`.');
})();

правило('день нигде не берётся по Гринвичу',
    места.length === 0,
    'Мест: ' + места.length + '\n' + места.slice(0, 10).join('\n') + '\n' +
    'День клуба берётся у дома: KSLT_VREMYA.сегодня() или\n' +
    'KSLT_VREMYA.деньПоБишкеку(момент). `toISOString().slice(0, 10)` — это\n' +
    'день по Гринвичу, и он расходится с днём клуба шесть часов в сутки.');

/* ---- 2б. ДЕНЬ НЕ БЕРЁТСЯ ПО ЧАСАМ СМОТРЯЩЕГО ----

   ПОЧЕМУ ПРАВИЛА НЕ ХВАТАЛО. Правило выше ловит день по Гринвичу
   (`toISOString`). А беда 13.11 пришла с другой стороны: «сегодня»
   бралось как `new Date().getDate()` — день по часам ТОГО, КТО СМОТРИТ.
   Костя открыл аналитику вечером 12-го из Чикаго, в Гринвиче шло уже
   13-е, и график выбросил всех, кто зарегистрировался «тринадцатого»:
   прирост 1 при 37 новых за месяц на соседней карточке.

   ОДНО ПОНЯТИЕ «СЕГОДНЯ» БЫЛО ОПРЕДЕЛЕНО ДВАЖДЫ — локальным временем
   смотрящего и строкой из базы, — и беда родилась ровно на шве.

   ПОЧЕМУ ХРАПОВИК, А НЕ ЗАПРЕТ. Таких мест в продукте 37, и не все они
   беда: год в подвале, дата в имени выгружаемого файла, срок от «сейчас»
   плюс неделя. Запрет уронил бы верный код, а разбирать все 37 — это
   другой кусок (записан в трекер). Храповик держит то, что держать
   можно: НОВЫХ НЕ ПОЯВЛЯЕТСЯ. Появилось — разбирай, сравнивается ли оно
   с датой из базы; если да, зови дом. */
const ПОТОЛОК_МЕСТНЫХ = 25;
const местные = [];
файлы('js', ['.js']).forEach(ф => {
    const т = безКом(fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'));
    const имена = new Set();
    let м;
    const объявления = /(?:var|let|const)\s+([A-Za-zА-Яа-я_$][\wА-Яа-я$]*)\s*=\s*new Date\(\s*\)/g;
    while ((м = объявления.exec(т))) имена.add(м[1]);
    т.split('\n').forEach((строка, i) => {
        let нашлось = /new Date\(\s*\)\.(getDate|getMonth|getFullYear)\(\)/.test(строка);
        if (!нашлось) {
            for (const имя of имена) {
                const р = new RegExp('\\b' + имя.replace(/[$]/g, '\\$&') + '\\.(getDate|getMonth|getFullYear)\\(\\)');
                if (р.test(строка)) { нашлось = true; break; }
            }
        }
        if (нашлось) местные.push(ф + ':' + (i + 1));
    });
});
правило('мест, где день берётся по часам смотрящего, не больше ' + ПОТОЛОК_МЕСТНЫХ,
    местные.length <= ПОТОЛОК_МЕСТНЫХ,
    'Стало ' + местные.length + ' при потолке ' + ПОТОЛОК_МЕСТНЫХ + '.\n' +
    'Новые: смотри ' + местные.slice(-5).join(', ') + '\n' +
    'Если новое место СРАВНИВАЕТ день с датой из базы — это та самая\n' +
    'беда 13.11: зовите KSLT_VREMYA.сегодня() и KSLT_VREMYA.деньПоБишкеку().\n' +
    'Если это показ года в подвале или имя файла — опустите потолок\n' +
    'числом и напишите, почему место безвредно.');

/* ---- 2в. ГРАФИК ДИНАМИКИ СЧИТАЕТ ДЕНЬ ВРЕМЕНЕМ КЛУБА ---- */
