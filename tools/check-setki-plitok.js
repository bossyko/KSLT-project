/**
 * СЕТКИ ПЛИТОК СТАТИСТИКИ — ОДНО ОПРЕДЕЛЕНИЕ НА ОДИННАДЦАТЬ СЕТОК.
 * Круг 10 ветки D, 18.10.
 *
 * ЧТО БЫЛО. Одиннадцать сеток плиток, 28 объявлений, ЧЕТЫРЕ написания
 * одного понятия («N колонок»: repeat(3,1fr), 1fr 1fr 1fr, repeat(2,1fr),
 * 1fr 1fr) и ПЯТЬ границ — 992, 900, 768, 600, 480, из них на шкале одна.
 * Беда родилась ровно на швах: на планшете вертикально СЕМЬ сеток из
 * девяти стояли в одну колонку шириной 752px, и плитка «Активных: 14»
 * растягивалась на весь экран. Замерено загрузкой на каждой ширине:
 * высота девяти сеток там была 1628px, стала 712 — экран короче на 916.
 *
 * ВТОРАЯ БЕДА — СЕТКА ВРАЛА О СВОЁМ РАЗМЕРЕ. `auto-fit` без потолка
 * разводил четыре плитки `.ad-pay-stats-grid` на ВОСЕМЬ колонок на
 * десктопе (шесть на планшете), а пять плиток `.anl-cards` — на шесть.
 * Половина сетки была пустыми местами справа.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ, А НЕ ЧИСЛО. Не «колонок три», а: число
 * колонок берётся у компонента, раздел задаёт только потолок параметром,
 * и ни одна из этих сеток не упоминается в медиа-запросе. Как именно
 * записана раскладка, решает замер; правило держит то, что беда не
 * вернётся молча.
 *
 *   node tools/check-setki-plitok.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ФАЙЛ = 'css/admin.css';
const сырой = fs.readFileSync(path.join(КОРЕНЬ, ФАЙЛ), 'utf8');
/* МАСКА КОММЕНТАРИЕВ СОХРАНЯЕТ ПЕРЕВОДЫ СТРОК: замена всего блока на
   пробелы схлопывала строки, и номера в подсказках врали (поймано 17.10
   на радиусах — первая правка ушла не туда). */
const текст = сырой.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}
const строка = поз => текст.slice(0, поз).split('\n').length;

/* ---- одиннадцать сеток одного понятия ---- */
const СЕТКИ = [
    'ad-stats-grid', 'ad-trn-stats-grid', 'ad-crt-stats-grid',
    'ad-cch-stats-grid', 'ad-pay-stats-grid', 'ad-vch-stats-big',
    'ad-vch-stats-small', 'ad-usr-cards', 'ad-ig-matches-grid',
    'anl-cards', 'anl-top-grid'
];

/* ПРАВИЛО 1. Раскладка объявлена ОДИН раз — в компоненте.
   Держится на отношении «сколько объявлений», а не на их тексте. */
const объявленийКолонок = (текст.match(/grid-template-columns\s*:/g) || []).length;
const вКомпоненте = /--ad-plitok[\s\S]{0,400}?grid-template-columns:\s*repeat\(auto-fit/.test(текст);
правило('раскладка плиток объявлена в компоненте, а не в каждой сетке',
    вКомпоненте,
    'Компонент сеток плиток не найден: ожидается одно правило, которое\n' +
    'берёт --ad-plitok и --ad-plitka-min и считает колонки через\n' +
    'repeat(auto-fit, minmax(max(...))). Без него раздел снова начнёт\n' +
    'писать свою раскладку, и четыре написания вернутся.');

/* ПРАВИЛО 2. Ни одна из этих сеток не упомянута в медиа-запросе.
   ИМЕННО ЭТО и была беда: раскладка жила на пяти границах. */
const медиа = [];
{
    let i = 0;
    while (i < текст.length) {
        const н = текст.indexOf('@media', i);
        if (н === -1) break;
        const о = текст.indexOf('{', н);
        if (о === -1) break;
        let глуб = 1, j = о + 1;
        while (j < текст.length && глуб > 0) {
            if (текст[j] === '{') глуб++;
            else if (текст[j] === '}') глуб--;
            j++;
        }
        медиа.push({ начало: н, тело: текст.slice(о, j), усл: текст.slice(н, о) });
        i = j;
    }
}
const вМедиа = [];
СЕТКИ.forEach(кл => {
    медиа.forEach(б => {
        if (new RegExp('\\.' + кл + '\\b').test(б.тело)) {
            вМедиа.push(кл + ' в @media на строке ' + строка(б.начало));
        }
    });
});
правило('сетки плиток не упоминаются в медиа-запросах',
    вМедиа.length === 0,
    'Раскладка плиток вернулась в точку останова: ' + вМедиа.join('; ') + '.\n' +
    'ЧИСЛО КОЛОНОК — СВОЙСТВО ШИРИНЫ, А НЕ ГРАНИЦЫ. Нужно другое число\n' +
    'колонок — меняется --ad-plitok, а не заводится @media: именно пять\n' +
    'границ на одно понятие и дали семь сеток в одну колонку на планшете.');

/* ПРАВИЛО 3. У каждой сетки есть СВОЙ потолок колонок параметром.
   ПЕРВАЯ РЕДАКЦИЯ БЫЛА ДЫРЯВОЙ, и это показал прувер: регексп ловил
   блок КОМПОНЕНТА (там класс стоит в списке через запятую, и --ad-plitok
   в нём есть всегда) — потеря своего потолка проходила молча, а вид бы
   поехал: сетка кортов получила бы общие три колонки вместо двух.
   Смотрим ТОЛЬКО одиночный блок класса. */
const одиночные = {};
{
    /* ЗАГЛЯД НАЗАД, А НЕ ПОЕДАНИЕ: первая редакция съедала закрывающую
       `}` предыдущего блока, и СЛЕДУЮЩИЙ блок терял свой якорь — пять
       сеток из одиннадцати пропадали из виду. Поймано прувером. */
    const р = /(?<=^|\})\s*(\.[A-Za-z0-9_-]+)\s*\{([^}]*)\}/g;
    let м;
    while ((м = р.exec(текст))) {
        const кл = м[1].slice(1);
        одиночные[кл] = (одиночные[кл] || '') + м[2];
    }
}
const безПотолка = СЕТКИ.filter(кл =>
    !(одиночные[кл] && /--ad-plitok\s*:/.test(одиночные[кл])));
правило('у каждой сетки плиток потолок колонок задан параметром',
    безПотолка.length === 0,
    'Сетки без --ad-plitok: ' + безПотолка.join(', ') + '.\n' +
    'Без потолка auto-fit разводит плитки на всю ширину — так четыре\n' +
    'плитки стояли в восьми колонках, а пять в шести.');

/* ПРАВИЛО 4. `auto-fit` НИГДЕ не заводится без потолка.
   Сторож на весь файл, а не на наши одиннадцать: следующая сетка не
   должна повторить беду молча. */
const голыйAutofit = [];
{
    const р = /repeat\(\s*auto-fit\s*,\s*minmax\(\s*(?!max\()/g;
    let м;
    while ((м = р.exec(текст))) голыйAutofit.push('строка ' + строка(м.index));
}
правило('auto-fit нигде не заведён без потолка колонок',
    голыйAutofit.length === 0,
    'auto-fit без потолка: ' + голыйAutofit.join(', ') + '.\n' +
    '`repeat(auto-fit, minmax(ЧИСЛО, 1fr))` разводит плитки на столько\n' +
    'колонок, сколько поместится, и сетка врёт о своём размере: лишние\n' +
    'треки стоят пустыми справа. Потолок пишется так:\n' +
    'minmax(max(--min, (100% - (n - 1) * gap) / n), 1fr).');

/* ПРАВИЛО 5. ХРАПОВИК ГРАНИЦ. Ширины в медиа — только 640 и 992;
   остальное делится высотой и поворотом. Вычистить все сразу нельзя,
   поэтому правило держит ПОТОЛОК: рост роняет, снижение опускает
   потолок вместе с собой. ЗАМЕРЕНО ЭТИМ ЖЕ ПРИБОРОМ 18.10 после круга:
   было 14 запросов мимо шкалы, стало 11 (768×6, плюс 1280, 1600, 480,
   600, 900 по одному). */
const ПОТОЛОК_МИМО_ШКАЛЫ = 11;
const ШКАЛА = new Set(['640', '992']);
const мимоШкалы = [];
медиа.forEach(б => {
    const ш = б.усл.match(/max-width:\s*(\d+)px/);
    if (ш && !ШКАЛА.has(ш[1])) мимоШкалы.push(ш[1] + ' (строка ' + строка(б.начало) + ')');
});
правило('точек останова мимо шкалы не больше потолка',
    мимоШкалы.length <= ПОТОЛОК_МИМО_ШКАЛЫ,
    'Медиа-запросов мимо 640/992: ' + мимоШкалы.length + ', потолок ' +
    ПОТОЛОК_МИМО_ШКАЛЫ + '.\n' + мимоШкалы.join(', ') + '\n' +
    'Ширины в медиа — только 640 и 992; остальное делится высотой и\n' +
    'поворотом. Нужна новая ступень — она заводится в компоненте.');

/* ПРАВИЛО 6. Порог переноса объявлен ступенью, а не случайным числом:
   кратен восьми. Отношение, а не значение — 160 можно сменить на 168
   или 320, но не на 150. */
const пороги = [];
{
    const р = /--ad-plitka-min\s*:\s*(\d+)px/g;
    let м;
    while ((м = р.exec(текст))) пороги.push({ знач: +м[1], стр: строка(м.index) });
}
const мимоВосьмёрки = пороги.filter(п => п.знач % 8 !== 0);
правило('порог переноса плитки стоит на шкале восьмёрки',
    пороги.length > 0 && мимоВосьмёрки.length === 0,
    пороги.length === 0
        ? 'Порог переноса --ad-plitka-min не объявлен вовсе.'
        : 'Порог мимо восьмёрки: ' +
          мимоВосьмёрки.map(п => п.знач + 'px на строке ' + п.стр).join(', ') + '.\n' +
          'Ступени ширины админки кратны восьми (.ad-pole-uzkoe 160,\n' +
          '.ad-pole-shirokoe 360). Порог — такая же ступень, а не на глаз.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      сетки плиток: 6 правил');
    console.log('          одиннадцать сеток, одно определение; объявлений');
    console.log('          grid-template-columns во всём файле: ' + объявленийКолонок);
    console.log('          в медиа этих сеток нет ни одной');
    console.log('          auto-fit без потолка: 0');
    console.log('          точек останова мимо шкалы ' + мимоШкалы.length +
                ' (потолок ' + ПОТОЛОК_МИМО_ШКАЛЫ + ')');
    console.log('          порогов переноса ' + пороги.length + ', все кратны восьми');
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  сетки плиток — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
