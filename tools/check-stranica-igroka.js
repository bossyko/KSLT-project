/** Тело правила по его селектору — скобка в скобку. */
const блок = (текст, якорь) => {
    // ЯКОРЬ — С НАЧАЛА СТРОКИ И С ТЕЛОМ НА СЛЕДУЮЩЕЙ. indexOf ловил
    // «.pp-container {» внутри однострочного группового
    // «.pp-hero,\n.pp-container { --pp-gutter: 24px; }» и возвращал чужое
    // тело — правило падало на верном файле.
    const i = текст.indexOf('\n' + якорь + '\n');
    if (i === -1) return '';
    let j = текст.indexOf('{', i), г = 0;
    const с = j;
    for (; j < текст.length; j++) {
        if (текст[j] === '{') г++;
        else if (текст[j] === '}') { г--; if (г === 0) return текст.slice(с + 1, j); }
    }
    return '';
};

