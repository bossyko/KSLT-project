/**
 * ЗАМОРОЗКА ПУБЛИЧНОЙ СТРАНИЦЫ ИГРОКА — `pages/player.html` и два языка.
 *
 * ЧТО ЗАМОРАЖИВАЕТСЯ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • боковое поле страницы — ОДНО определение, и шапка с телом берут его
 *     оттуда, а не каждая своё;
 *   • воздух над первым заголовком — ОДИН, а не сумма двух;
 *   • «Pro-Masters» и «Микст» — один уровень лестницы, одно объявление;
 *   • цифра показателя на телефоне строго мельче, чем на широких видах,
 *     и всегда строго крупнее своей подписи;
 *   • отсечка длинного списка — общий механизм, своего у страницы нет;
 *   • строка матча — один шаблон колонок, а не шесть похожих;
 *   • имя игрока — заголовок первого уровня, а не раскрашенный div;
 *   • окно H2H называет себя окном и возвращает фокус туда, откуда позвали;
 *   • портрет не берёт ни акцент, ни цвет статуса.
 *
 *   node tools/check-stranica-igroka.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const CSS = безКом(чит('css/player.css'));
const JS  = безКом(чит('js/player.js'));
const ОТС = безКом(чит('js/kslt-otsechka.js'));
const RU = чит('pages/player.html');
const EN = чит('pages/player-en.html');
const KG = чит('pages/player-kg.html');
const СТРАНИЦЫ = [RU, EN, KG];

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };

/** Тело правила по его селектору — скобка в скобку. */
const блок = (текст, якорь) => {
    // ЯКОРЬ — С НАЧАЛА СТРОКИ И С ТЕЛОМ НА СЛЕДУЮЩЕЙ. indexOf ловил
    // «.pp-container {» внутри однострочного группового
    // «.pp-hero,\n.pp-container { --pp-gutter: 24px; }» и возвращал чужое
    // тело — правило падало на верном файле.
    const i = текст.indexOf('\n' + якорь + '\n');
    if (i === -1) return '';
    let j = текст.indexOf('{', i), г = 0;
    const с = j;
    for (; j < текст.length; j++) {
        if (текст[j] === '{') г++;
        else if (текст[j] === '}') { г--; if (г === 0) return текст.slice(с + 1, j); }
    }
    return '';
};

/* ══ 1. ОДНА МЕРА СТРАНИЦЫ ══════════════════════════════════════════════
   Шапка лежит в .pp-hero-content, тело — в .pp-container. Пока поле было
   задано у каждой своё, шапка стояла левее тела на 24 на широких видах и
   правее на 4 на узких. */

правило('боковое поле страницы — одно определение на обе коробки',
    (CSS.match(/--pp-gutter:\s*\d+px;/g) || []).length === 3 &&
    /\.pp-hero,\s*\n\.pp-container \{ --pp-gutter:/.test(CSS),
    'поле снова разъехалось по коробкам: у шапки своё число, у тела своё.\n' +
    '          Ждём ровно три объявления --pp-gutter — по одному на каждый\n' +
    '          диапазон, и все в общем селекторе .pp-hero, .pp-container');

правило('шапка и тело держат поле ВНУТРИ своих 900',
    /padding:\s*0 var\(--pp-gutter\)/.test(блок(CSS, '.pp-hero-content {')) &&
    /padding:\s*\d+px var\(--pp-gutter\) \d+px/.test(блок(CSS, '.pp-container {')) &&
    !/padding:\s*\d+px \d+px \d+px;/.test(блок(CSS, '.pp-hero {')) &&
    /padding:\s*\d+px 0 \d+px;/.test(блок(CSS, '.pp-hero {')),
    'одна из коробок снова держит поле СНАРУЖИ предела ширины: тогда левая\n' +
    '          граница шапки и тела расходятся ровно на величину поля');

/* ══ 2. ВОЗДУХ НАД ПЕРВЫМ ЗАГОЛОВКОМ — ОДИН ════════════════════════════ */

правило('межсекционный воздух стоит на ступени шкалы',
    /margin-top:\s*var\(--space-10\)/.test(блок(CSS, '.pp-section-title {')) &&
    // ОДИН КЛАСС — ОДИН БЛОК: два объявления .pp-section-title в разных
    // концах файла и были тем швом, на котором родился двойной воздух
    (CSS.match(/^\.pp-section-title \{/gm) || []).length === 1,
    'воздух между секциями ушёл со ступени 40, задан числом либо класс снова\n' +
    '          объявлен двумя блоками');

правило('у первого заголовка воздух не удваивается',
    /\.pp-container > \.pp-section-title:first-child \{\s*margin-top:\s*0;\s*\}/.test(CSS),
    'сброс снят: над первым заголовком снова складываются padding контейнера\n' +
    '          и межсекционный margin — 80 вместо 40 на узких видах');

/* ══ 3. ОДИН УРОВЕНЬ — ОДНО ОБЪЯВЛЕНИЕ ═════════════════════════════════
   Сторож на дубликат: «Pro-Masters» и «Микст» одинаковы НЕ по случайности. */

правило('название блока внутри раздела объявлено один раз на два класса',
    /\.pp-pair-title,\s*\n\.pp-cat-name \{/.test(CSS) &&
    // ровно один селектор на каждое имя — и оба в одной группе
    (CSS.match(/^\.pp-cat-name[ ,{]/gm) || []).length === 1 &&
    (CSS.match(/^\.pp-pair-title[ ,{]/gm) || []).length === 1,
    '«Pro-Masters» и «Микст» снова объявлены врозь. Они — один уровень\n' +
    '          лестницы; порознь они одинаковы лишь до первой правки');

/* ══ 4. ЦИФРА ПОКАЗАТЕЛЯ — ОТНОШЕНИЕ, А НЕ ЧИСЛО ══════════════════════ */

правило('цифра показателя на телефоне строго мельче, чем на широких видах',
    /font-size:\s*var\(--fs-lg\)/.test(блок(CSS, '.pp-stat-num {')) &&
    /\.pp-stat-num \{ font-size: var\(--fs-md\); \}/.test(CSS),
    'цифра перестала опускаться на ступень под 640: пара «цифра + подпись»\n' +
    '          снова расходится на три ступени, и ряд читается как четыре\n' +
    '          отдельных числа, а не как один блок');

правило('цифра показателя строго крупнее своей подписи',
    /font-size:\s*var\(--fs-lg\)/.test(блок(CSS, '.pp-stat-num {')) &&
    /font-size:\s*var\(--fs-xs\)/.test(блок(CSS, '.pp-stat-label {')),
    'цифра и подпись сравнялись по кеглю — пара перестала читаться парой');

правило('подпись показателя не красится краской ниже порога AA',
    /color:\s*var\(--text-muted\)/.test(блок(CSS, '.pp-stat-label {')),
    'подпись вернулась на --text-dim: контраст 3.14 при норме AA 4.5');

/* ══ 5. ЛЕСТНИЦА ЗАГОЛОВКОВ ═══════════════════════════════════════════ */

правило('имя игрока строго крупнее заголовка раздела',
    /font-size:\s*var\(--fs-2xl\)/.test(блок(CSS, '.pp-name {')) &&
    /font-size:\s*var\(--fs-lg\)/.test(блок(CSS, '.pp-section-title {')),
    'имя игрока и заголовок раздела сошлись на одной ступени');

правило('межстрочный заголовков — ступень, а не общие 1.5',
    /line-height:\s*1\.1/.test(блок(CSS, '.pp-name {')) &&
    /line-height:\s*1\.3/.test(блок(CSS, '.pp-section-title {')),
    'заголовок вернулся к наследованию 1.5: 32 x 1.5 даёт строку в 48');

правило('вес берётся из системы 400·500·600·700',
    !/font-weight:\s*(800|900|300|200|100)\b/.test(CSS),
    'в файл вернулся вес, которого нет в системе');

/* ══ 6. ИМЯ ИГРОКА — ЗАГОЛОВОК, А НЕ DIV ══════════════════════════════ */

правило('имя игрока — заголовок первого уровня',
    /<h1 class="pp-name">/.test(JS),
    'имя снова рисуется div: у страницы пропадает h1, и диктор не называет,\n' +
    '          чья это страница');

/* ══ 7. ПОЛОСА «НАЗАД» — ОДНА ПОДЛОЖКА ════════════════════════════════ */

правило('полоса «Назад» на этой странице не рисует вторую подложку',
    /\.kslt-back-wrap\.pp-back-float::before \{\s*content: none;\s*\}/.test(CSS),
    'подложка полосы вернулась: над обложкой она ложится вторым слоем и\n' +
    '          закрашивает снимок — ровно то, что Костя увидел 09.10');

/* ══ 8. ОТСЕЧКА — ОБЩИЙ МЕХАНИЗМ ══════════════════════════════════════ */

правило('страница зовёт общую отсечку, а не заводит свою',
    /window\.KSLT_OTSECHKA\.класс\(/.test(JS) &&
    /window\.KSLT_OTSECHKA\.кнопка\(/.test(JS) &&
    /window\.KSLT_OTSECHKA\.включить\(/.test(JS) &&
    !/СТРОК_СРАЗУ\s*=/.test(JS) &&
    !/function классОтсечки\(/.test(JS),
    'у страницы игрока снова своя отсечка. Одно понятие — одно определение,\n' +
    '          а у строки матча и строки таблицы разный display: вторая копия\n' +
    '          разойдётся с первой на первой же правке');

правило('общий механизм подключён на всех трёх языках',
    СТРАНИЦЫ.every(h => /js\/kslt-otsechka\.js/.test(h) && /css\/kslt-otsechka\.css/.test(h)),
    'один из трёх языков остался без общего файла: там отсечка просто\n' +
    '          не сработает, а ошибки в консоли никто не увидит');

правило('кнопка отсечки берёт язык страницы, а не русский по умолчанию',
    // ОБА вызова — с языком. Проверка «хотя бы один» пропускала бы случай,
    // когда язык потеряли у турниров, а у матчей оставили
    (JS.match(/KSLT_OTSECHKA\.кнопка\([^)]*, lang\)/g) || []).length === 2 &&
    (JS.match(/KSLT_OTSECHKA\.кнопка\(/g) || []).length === 2,
    'кнопка снова зовётся без языка либо зовётся не из обоих списков —\n' +
    '          матчей и турниров');

/* ══ 9. СТРОКА МАТЧА — ОДИН ШАБЛОН ════════════════════════════════════ */

правило('строка матча — один шаблон колонок на все состояния',
    (CSS.match(/grid-template-columns:\s*80px 190px minmax\(0, 1fr\) 96px 44px 48px;/g) || []).length === 1,
    'шаблон строки матча снова размножен: пары, одиночка и микст разъедутся\n' +
    '          по колонкам ровно на шве между копиями');

/* ══ 10. ЦЕЛЬ НАЖАТИЯ, ФОКУС, ДВИЖЕНИЕ ════════════════════════════════ */

правило('мелкие кнопки добирают цель нажатия 44 прозрачным слоем',
    /\.pp-match-h2h::after,/.test(CSS) &&
    /min-height:\s*44px/.test(блок(CSS, '.pp-tournament-link::after {')),
    'слой цели нажатия снят: H2H снова 23 в высоту, и таких на странице\n' +
    '          десять');

правило('видимый фокус есть, и не у одного элемента',
    (CSS.match(/:focus-visible/g) || []).length >= 8,
    'с клавиатуры по странице снова не пройти: фокус невидим');

правило('переходы перечислены поимённо, а не «all»',
    !/transition:\s*all\b/.test(CSS),
    'вернулся «transition: all». Замер 09.10 на кнопке H2H: :focus-visible — да,\n' +
    '          цвет контура лаймовый, стиль solid, ширина 0px. «all» анимирует и\n' +
    '          outline-width, и контур у клавиатурного пользователя наезжает от\n' +
    '          нуля вместо того, чтобы появиться сразу');

правило('у страницы есть отказ от движения',
    /@media \(prefers-reduced-motion: reduce\)/.test(CSS),
    'страница снова двигается у того, кто движение выключил');

/* ══ 11. ОКНО H2H — НАСТОЯЩЕЕ ОКНО ════════════════════════════════════ */

правило('окно H2H называет себя окном',
    /setAttribute\('role', 'dialog'\)/.test(JS) &&
    /setAttribute\('aria-modal', 'true'\)/.test(JS) &&
    /setAttribute\('aria-label'/.test(JS),
    'окно снова безымянный div: диктор не скажет, что открылось окно');

правило('окно держит Tab внутри и возвращает фокус туда, откуда позвали',
    /var фокусДоОкна = document\.activeElement/.test(JS) &&
    /addEventListener\('keydown', ловушка\)/.test(JS) &&
    /dispatchEvent\(new CustomEvent\('h2h-closed'\)\)/.test(JS),
    'ловушка Tab или возврат фокуса сняты: с клавиатуры окно либо не\n' +
    '          удержать, либо после закрытия некуда вернуться');

/* ══ 12. ПОРТРЕТ — НЕ ДЕЙСТВИЕ ════════════════════════════════════════ */

правило('портрет не берёт ни акцент, ни цвет статуса',
    /border:\s*3px solid rgba\(255, 255, 255, 0\.08\)/.test(CSS) &&
    !/border:\s*4px solid var\(--accent\)/.test(CSS),
    'портрету вернули лаймовое кольцо: лайм принадлежит одному главному\n' +
    '          действию на экране, а портрет не действие');

/* ══ 13. МЁРТВОГО НЕ ДЕРЖИМ ═══════════════════════════════════════════ */

правило('мёртвой кнопки отсечки в файле нет',
    !/\.pp-show-all-btn/.test(CSS) && !/pp-show-all-btn/.test(JS),
    '.pp-show-all-btn вернулся: отсечка живёт на общем .kslt-more, и вторая\n' +
    '          кнопка — это второе определение одного понятия');

/* ══ 14. ВЕРСИЯ ОДНА НА ВСЕ ТРИ ЯЗЫКА ═════════════════════════════════ */

const версии = имя => {
    const найдено = new Set();
    СТРАНИЦЫ.forEach(s => {
        // ЯКОРЬ НА ПУТЬ, А НЕ НА ХВОСТ ИМЕНИ: «player.js» иначе ловит
        // «invite-player.js», и правило падает на ровном месте
        const re = new RegExp('/' + имя.replace('.', '\\.') + '\\?v=(\\d+)', 'g');
        let m; while ((m = re.exec(s))) найдено.add(m[1]);
    });
    return [...найдено];
};
[['player.css'], ['player.js'], ['kslt-otsechka.css'], ['kslt-otsechka.js']].forEach(([ф]) => {
    const в = версии(ф);
    правило('версия ' + ф + ' одна на все три языка',
        в.length === 1,
        ф + ' подключён разными версиями: ' + в.join(', ') + '. У кого страница\n' +
        '          в кеше, тот увидит старый файл на одном языке и новый на другом');
});

if (ошибки.length === 0) {
    console.log(`\n  ок      страница игрока: ${ВСЕГО} правил\n`);
    process.exit(0);
}
console.log(`\n  НЕ ТАК  страница игрока: ${ВСЕГО} правил, упало ${ошибки.length}.\n`);
ошибки.forEach(о => {
    console.log(`  ✗ ${о.имя}`);
    if (о.подсказка) console.log(`          ${о.подсказка}`);
    console.log('');
});
process.exit(1);
