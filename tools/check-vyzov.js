#!/usr/bin/env node
/**
 * ВЫЗОВ НА БАТТЛ — ОДИН ДОМ (29.10, по слову Кости).
 *
 * ЭТО БЫЛА ПОЛОМКА, А НЕ НЕХВАТКА БЛОКА, И ДОКАЗЫВАЕТ ЕЁ ОГРАНИЧЕНИЕ
 * САМОЙ БАЗЫ. `challenges_status_check` допускает только `active`,
 * `negotiating`, `countered`, `accepted`, `declined`, `expired`,
 * `completed`, `cancelled`. А приложение писало в таблицу НАПРЯМУЮ со
 * статусом **`pending`**, которого там нет: база отклоняла вставку, и
 * человек получал ошибку при каждом нажатии «Вызвать».
 *
 * И вставка шла МИМО серверной функции `create-challenge`, которую
 * зовёт сайт, — то есть мимо восьми её проверок (вошёл, есть карточка,
 * не себя, член клуба, соперник найден, не слишком много висящих, нет
 * такого вызова, нет назначенного матча) и мимо уведомлений сопернику.
 *
 * И ПРОВЕРКА «ВЫЗОВ УЖЕ ЕСТЬ» РАСХОДИЛАСЬ: сайт смотрел в ОБЕ стороны
 * по `active`/`accepted`, приложение — в одну и по `pending`, то есть не
 * находило НИЧЕГО НИКОГДА.
 *
 * Запуск: node tools/check-vyzov.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));

const ДОМ = 'js/kslt-vyzov.js';
const ДОМ_П = 'mobile/www/js/kslt-vyzov.js';
const САЙТ = 'js/player.js';
const ПРИЛ = 'mobile/www/js/screens/player-detail.js';
/* ОПИСАНИЕ СХЕМЫ ЧИТАЕТСЯ ИЗ СНИМКА, А НЕ ИЗ СЛЕПКА (13.11, h306).
   Здесь стоял `supabase/migrations/…_baseline.sql` — слепок от 10.08,
   отставший на три месяца. Статусы вызова в нём случайно совпали с
   боевыми, и прибор три месяца давал ВЕЗЕНИЕ, а не уверенность. */
const БАЗА = 'sql/схема/schema-snapshot.sql';
const ФУНКЦИЯ = 'supabase/functions/create-challenge/index.ts';

/* Допустимые статусы читаются ИЗ ОГРАНИЧЕНИЯ БАЗЫ, а не держатся
   списком: список, который держится руками, отстаёт. */
const СТАТУСЫ = (function () {
    /* Снимок — чтение каталога, и ограничение записано в нём одной
       строкой без кавычек у имён столбцов. */
    const м = чит(БАЗА).match(/challenges_status_check : CHECK \(\(status = ANY \(ARRAY\[([^\]]*)\]/);
    if (!м) return null;
    return (м[1].match(/'([a-z_]+)'/g) || []).map(с => с.replace(/'/g, ''));
})();

const дом = безКом(чит(ДОМ));

console.log('\n  ВЫЗОВ НА БАТТЛ — ОДИН ДОМ\n');

правило('ограничение статусов прочитано из базы',
    СТАТУСЫ && СТАТУСЫ.length >= 8,
    'Прочитано: ' + (СТАТУСЫ ? СТАТУСЫ.join(', ') : 'НИЧЕГО') + '.\n' +
    'Не прочиталось — сломался ПРИБОР, и сверки ниже пусты. Правило\n' +
    'стоит ПЕРЕД ними нарочно.');

правило('статуса `pending` в базе действительно нет',
    !!СТАТУСЫ && СТАТУСЫ.indexOf('pending') === -1,
    'ПРАВИЛО ПАРНОЕ: если `pending` однажды добавят в ограничение, оно\n' +
    'упадёт — и тогда решать заново, осознанно, а не наткнуться через\n' +
    'полгода. Пока его нет, вставка с ним отклоняется базой.');

правило('дом объявлен и отдаёт все четыре понятия',
    /KSLT_VYZOV/.test(дом) && /API\.ФУНКЦИЯ/.test(дом) && /API\.ЖИВЫЕ/.test(дом) &&
    /API\.ключОтказа\s*=/.test(дом) && /API\.создать\s*=/.test(дом) &&
    /API\.занят\s*=/.test(дом),
    'Нужны: имя функции, живые статусы, разбор кодов, создание, проверка.');

правило('копии дома побайтово равны',
    чит(ДОМ) === чит(ДОМ_П),
    'Разошлись — значит вызов снова живёт двумя жизнями.');

правило('живые статусы дома ЕСТЬ в ограничении базы',
    (function () {
        const м = дом.match(/API\.ЖИВЫЕ = \[([^\]]*)\]/);
        if (!м) return false;
        const свои = (м[1].match(/'([a-z_]+)'/g) || []).map(с => с.replace(/'/g, ''));
        return !!СТАТУСЫ && свои.length > 0 && свои.every(с => СТАТУСЫ.indexOf(с) !== -1);
    })(),
    'Статус, которого нет в ограничении, не найдётся НИКОГДА — ровно это\n' +
    'и делало проверку в приложении пустой.');

правило('дом зовёт серверную функцию, а не пишет в таблицу',
    /API\.ФУНКЦИЯ = 'create-challenge'/.test(дом) &&
    /зовОтИмени\(/.test(дом) && !/from\('challenges'\)[\s\S]{0,60}insert/.test(дом),
    'Восемь проверок знает только функция. Писать в таблицу мимо неё —\n' +
    'значит обойти их все и не отправить уведомление сопернику.');

правило('зов идёт ОТ ИМЕНИ человека',
    /зовОтИмени\(client/.test(дом) &&
    /auth\.getUser\(\)/.test(чит(ФУНКЦИЯ)),
    'Функция спрашивает `auth.getUser()` — значит ей нужен токен, а не\n' +
    'только ключ. С одним ключом она ответит `Unauthorized`.');

правило('дом разбирает все восемь кодов отказа функции',
    (function () {
        const коды = ['not_logged_in', 'no_player', 'opponent_not_found', 'self_challenge',
                      'not_member', 'too_many_pending', 'already_pending', 'match_pending'];
        return коды.every(к => new RegExp(к + ':').test(дом));
    })(),
    'Каждый код — своя причина, и человеку надо знать, почему нельзя.\n' +
    'Лестница `else if` по этим кодам жила на сайте и не жила в\n' +
    'приложении вовсе.');

правило('дом смотрит вызов В ОБЕ СТОРОНЫ',
    /challenger_player_id\.eq\.' \+ мойId/.test(дом) &&
    /challenger_player_id\.eq\.' \+ егоId/.test(дом),
    'Приложение смотрело только «я его». Человек, которого УЖЕ вызвали,\n' +
    'мог вызвать встречно и завести второй вызов на ту же пару.');

правило('без дома входа вызов не отправляется и говорит вслух',
    /console\.error\(\s*'KSLT_VYZOV/.test(дом) && /!V\.зовОтИмени/.test(дом),
    'Тихий отказ выглядел бы как «сервер не ответил».');

[[САЙТ, 'сайта'], [ПРИЛ, 'приложения']].forEach(function (пара) {
    const ф = пара[0], имя = пара[1];
    const т = безКом(чит(ф));

    правило('у ' + имя + ' нет прямой записи вызова в таблицу',
        !/from\('challenges'\)[\s\S]{0,120}insert/.test(т) && !/status: 'pending'/.test(т),
        'ЭТО И БЫЛА ПОЛОМКА: вставка со статусом, которого нет в\n' +
        'ограничении базы, да ещё мимо восьми проверок функции.');

    правило('у ' + имя + ' нет своего разбора кодов базы',
        !/too_many_pending|match_pending|already_pending|not_member/.test(т),
        'Коды разбирает дом, продукт знает только КЛЮЧИ.');

    правило('у ' + имя + ' нет своего запроса «вызов уже есть»',
        !/challenger_player_id\.eq/.test(т),
        'Запрос один, и он смотрит в обе стороны по статусам из базы.');

    правило('у ' + имя + ' дом зовётся',
        /KSLT_VYZOV/.test(т) && /\.создать\(/.test(т),
        'Без зова работа не сделана.');

    правило('у ' + имя + ' есть слово на каждый ключ дома',
        (function () {
            const м = дом.match(/API\.КЛЮЧИ = [\s\S]*?\}\)\(\);/);
            const ключи = ['chalLogin', 'chalNoPlayer', 'chalSelf', 'chalNotMember',
                           'chalLimit', 'chalExists', 'chalMatchSet', 'chalError'];
            return м && ключи.every(к => new RegExp(к + ':').test(т));
        })(),
        'Ключ без слова — пустой тост вместо причины.');
});

правило('на страницах игрока подключены оба дома, и в нужном порядке',
    ['pages/player.html', 'pages/player-en.html', 'pages/player-kg.html',
     'mobile/www/index.html'].every(ф => {
        const t = чит(ф);
        const вх = t.indexOf('kslt-vhod.js');
        const вз = t.indexOf('kslt-vyzov.js');
        const зов = Math.min.apply(null,
            ['js/player.js?', 'player-detail.js?'].map(с => t.indexOf(с))
                .filter(и => и !== -1).concat([Infinity]));
        return вх !== -1 && вз !== -1 && вх < вз && вз < зов;
    }),
    'Дом вызова опирается на дом входа (`зовОтИмени`), значит порядок:\n' +
    'вход → вызов → тот, кто их зовёт. Иначе кнопка упадёт на\n' +
    '`undefined` при первом нажатии.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else { console.log('  ок      вызов на баттл: все ' + держится + ' правил держатся · статусов в базе ' + СТАТУСЫ.length + '\n'); }
