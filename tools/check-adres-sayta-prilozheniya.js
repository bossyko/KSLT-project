#!/usr/bin/env node
/**
 * АДРЕС САЙТА В ПРИЛОЖЕНИИ — ОДНО ОПРЕДЕЛЕНИЕ (шаг A3.4, 29.10).
 *
 * ЧТО БЫЛО. В `mobile/www/js/screens/home-blocks.js:73` стояло
 * `window.KSLT_SITE_URL || 'https://kslt.netlify.app'`, а `KSLT_SITE_URL`
 * не был объявлен НИГДЕ — это было его единственное упоминание во всём
 * приложении. Значит `||` срабатывал всегда, адрес был зашит намертво,
 * но ВЫГЛЯДЕЛ настройкой.
 *
 * НАСТРОЙКА, КОТОРУЮ НИКТО НЕ СТАВИТ, ХУЖЕ ЗАШИТОГО ЧИСЛА: зашитое
 * видно глазами, а эта врёт читающему. Тот же вид беды, что мёртвые
 * ползунки уведомлений (шаг A2).
 *
 * ЗАЧЕМ СТОРОЖ. Переезд на `www.tennis.kg` (шаг C1) обязан быть правкой
 * ОДНОЙ строки. Второй зашитый адрес молчит: ссылка ведёт на старый
 * домен и работает, пока старый домен жив, — и беда вылезет через месяц
 * после переезда, когда netlify отключат.
 *
 * ГРАНИЦА С ЧУЖИМ СТОРОЖЕМ. `check-adres-sayta.js` утверждает, что
 * адреса НЕТ там, где его быть не должно, — по всему дереву, включая
 * `mobile/www`, с одним исключением: дом приложения. Этот сторож
 * утверждает обратное: что дом ЕСТЬ, отдаёт оба поля, его ЗОВУТ, и
 * внутри него адрес написан ровно два раза. Два разных утверждения —
 * не дубликат.
 *
 * Якорь держится на СОДЕРЖИМОМ, а не на номере строки: номера уедут.
 *
 * Запуск: node tools/check-adres-sayta-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

/* Все файлы приложения, которые могут нести адрес */
function файлыПриложения() {
    const корень = path.join(КОРЕНЬ, 'mobile/www');
    const список = [];
    (function обход(каталог) {
        if (!fs.existsSync(каталог)) return;
        for (const имя of fs.readdirSync(каталог)) {
            const п = path.join(каталог, имя);
            const с = fs.statSync(п);
            if (с.isDirectory()) { обход(п); continue; }
            if (/\.(js|html|css)$/.test(имя)) список.push(п);
        }
    })(корень);
    return список;
}

const ДОМ = path.join(КОРЕНЬ, 'mobile/www/js/supabase-config.js');
const домТекст = fs.existsSync(ДОМ) ? fs.readFileSync(ДОМ, 'utf8') : '';

/* Строка комментария не считается: сторож ищет РАБОЧИЙ адрес */
function безКомментариев(текст) {
    return текст
        .replace(/\/\*[\s\S]*?\*\//g, '')
        .split('\n')
        .filter(с => !/^\s*(\/\/|\*)/.test(с))
        .join('\n');
}

console.log('\n  АДРЕС САЙТА В ПРИЛОЖЕНИИ — ОДНО ОПРЕДЕЛЕНИЕ\n');

правило('дом адреса заведён',
    /window\.KSLT_SAYT\s*=\s*window\.KSLT_SAYT\s*\|\|/.test(домТекст),
    'В `mobile/www/js/supabase-config.js` должен стоять\n' +
    '`window.KSLT_SAYT = window.KSLT_SAYT || { адрес, подпись }`.\n' +
    'Без дома адрес расползётся по экранам снова.');

правило('у дома есть и адрес, и подпись',
    /адрес\s*:/.test(домТекст) && /подпись\s*:/.test(домТекст),
    'Сайт отдаёт оба поля (`js/supabase-config.js`): `адрес` для ссылки,\n' +
    '`подпись` для печати на картинке ваучера. Приложение обязано\n' +
    'отдавать те же два, иначе зовущий код разойдётся.');

/* ЗАШИТЫЙ АДРЕС ВНЕ ДОМА ДЕРЖИТ ЧУЖОЙ СТОРОЖ `check-adres-sayta.js` —
   он обходит всё дерево, включая `mobile/www`, и исключает только дом
   приложения. Второго такого правила здесь НЕ ЗАВОДИТСЯ: одно
   определение на одно понятие.

   НО ПОСЛАБЛЕНИЕ, КОТОРОЕ Я ЕМУ СДЕЛАЛ, САМО ПО СЕБЕ ДЫРА: раз дом
   приложения исключён целиком, в него можно вписать десять адресов, и
   чужой сторож промолчит. Поэтому храповик держит ЧИСЛО: ровно два
   рабочих упоминания — `адрес` и `подпись`, и ни одного больше. */
const ПОЛ_ДОМА = 2;
const вДоме = (безКомментариев(домТекст).match(/kslt\.netlify\.app|tennis\.kg/g) || []).length;
правило('в доме адрес написан ровно ' + ПОЛ_ДОМА + ' раза',
    вДоме === ПОЛ_ДОМА,
    'Рабочих упоминаний адреса в доме: ' + вДоме + ', а должно быть ' +
    ПОЛ_ДОМА + ' — `адрес` и `подпись`.\n' +
    'Чужой сторож `check-adres-sayta.js` этот файл не смотрит вовсе\n' +
    '(послабление от 29.10), поэтому счёт держится здесь. Больше двух —\n' +
    'значит адрес снова расползается, только уже внутри дома.\n' +
    'Переезд на свой домен (шаг C1) правит ровно эти две строки.');

const мёртвые = [];
for (const п of файлыПриложения()) {
    const отн = path.relative(КОРЕНЬ, п);
    const текст = безКомментариев(fs.readFileSync(п, 'utf8'));
    const зовы = (текст.match(/window\.KSLT_SITE_URL/g) || []).length;
    if (зовы > 0) мёртвые.push(отн + ' (' + зовы + ')');
}
правило('мёртвой настройки KSLT_SITE_URL не осталось',
    мёртвые.length === 0,
    '`KSLT_SITE_URL` не объявлен нигде в приложении — всякий его зов\n' +
    'всегда уходит в `||`, то есть это зашитый адрес с видом настройки:\n' +
    мёртвые.map(с => '  · ' + с).join('\n'));

правило('дом зовут по имени, а не мимо',
    (function () {
        const g = path.join(КОРЕНЬ, 'mobile/www/js/screens/home-blocks.js');
        if (!fs.existsSync(g)) return false;
        return /window\.KSLT_SAYT\.адрес/.test(fs.readFileSync(g, 'utf8'));
    })(),
    'Обложка главного экрана достраивает короткий путь картинки до\n' +
    'полного адреса (`home-blocks.js`). Она обязана брать его у дома.');

правило('версия supabase-config поднята',
    (function () {
        const i = path.join(КОРЕНЬ, 'mobile/www/index.html');
        if (!fs.existsSync(i)) return false;
        const m = fs.readFileSync(i, 'utf8')
            .match(/js\/supabase-config\.js\?v=(\d+)/);
        return !!m && Number(m[1]) >= 4;
    })(),
    'Дом адреса заведён в `supabase-config.js` — версия в\n' +
    '`mobile/www/index.html` обязана быть не ниже 4, иначе у человека\n' +
    'останется старый файл без дома, и обложка упадёт на `undefined`.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      адрес сайта в приложении: все ' + держится + ' правил держатся\n');
}
