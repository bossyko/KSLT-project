/* ── 11. ЧЕТЫРЕ НАХОДКИ КОСТИ НА ЖИВОМ ТУРНИРЕ, 05.11 ────────────────
   Турнир на 18 пар, шесть групп по три — первый прогон ручного выбора.

   ГЛАВНАЯ: «в сетках у кого есть TBD — почему-то автоматически не
   проходят дальше, и получается, мы застреваем тут». Олимпийка
   собирается сразу с людьми и помечает проход в тот же миг; сетки лиг
   собираются ПУСТЫМИ с метками, людей ставит `заполнитьСлоты` — и
   пометку не ставил никто, а продвижение ищет именно её.
   ДВЕ ВЕТКИ ОДНОГО ПОНЯТИЯ РАЗОШЛИСЬ НА ТОМ, ЧТО ОДНА СОБИРАЕТСЯ СРАЗУ,
   А ДРУГАЯ ПО ЧАСТЯМ.

   ОСТАЛЬНЫЕ ТРИ — про то, что видно глазами: подсчёт в таблице лиг не
   показывался вовсе, а переключатель рисовался системным видом и не
   назывался нажимаемым. */
/* ВТОРАЯ РЕДАКЦИЯ 05.11: пометка переехала из `заполнитьСлоты` в общий
   ход панели, и ждать её надо там же. Правило следит за САМИМ
   определением; где её зовут — держит правило ниже. */
