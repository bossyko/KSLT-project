#!/usr/bin/env node
/**
 * СЕТКИ ЛИГ СТОЯТ С ПЕРВОГО ДНЯ (кусок 04.11, слово Кости).
 *
 * «Чтобы видно было, какое место в группе выходит на какое место с другой
 * группы — как у нас сейчас в групповых».
 *
 * ЗАМЕР 04.11: плей-офф собирался сразу после жеребьёвки (`создатьПустой‐
 * Плейофф`, с метками A1/B2), а лиги — только по кнопке и только после
 * последней группы. До того на их месте не было ничего.
 *
 * ПОЧЕМУ ЭТО ВОЗМОЖНО, И ЭТО ЗАМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО: игроки
 * раскладываются по группам СЕРПАНТИНОМ ПО РЕЙТИНГУ
 * (`js/tournament-generator.js:432`) — первый сеяный в группу A, второй в
 * B. Значит буква группы это ПОСЕВ, а не алфавит, и расклад лиг известен
 * из настроек так же, как расклад плей-оффа.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ: «все три сетки — плей-офф и обе лиги — считает
 * ОДИН расклад». Свой ход у лиг (`buildLeagueSEBracket`, посев по силе
 * выступления) из продукта убран: два определения одного понятия давали
 * турниру, собранному кнопкой, иной расклад, чем турниру, собранному
 * самому, и беда родилась бы ровно на шве.
 *
 * РАЗМЕР ГРУППЫ СЧИТАЕТСЯ ПО ЛЮДЯМ, А НЕ БЕРЁТСЯ ИЗ НАСТРОЕК: группы
 * бывают разной величины, и у утешительной лиги нижняя граница мест у
 * разных групп РАЗНАЯ. Настройка этого не знает, матчи знают.
 *
 *   node tools/check-ligi-s-pervogo-dnya.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');

const СЕТКА = 'js/admin/sections/bracket.js';
const ГЕН = 'js/tournament-generator.js';

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const полный = чит(СЕТКА);
const код = безКомментариев(полный);
const ген = безКомментариев(чит(ГЕН));

/* ── 1. основание: серпантин по рейтингу ─────────────────────────────── */
правило('игроки раскладываются по группам по рейтингу',
    /row % 2 === 0[\s\S]{0,120}groupCount - 1 - \(idx % groupCount\)/.test(ген),
    'серпантин по рейтингу в tournament-generator.js пропал — буква группы ' +
    'больше не посев, и весь расклад лиг с первого дня теряет основание');

/* ── 2. сборка лиг есть и зовётся при отрисовке ──────────────────────── */
правило('пустые лиги собираются своим ходом',
    /async function создатьПустыеЛиги\s*\(/.test(код),
    'нет функции создатьПустыеЛиги');

const ветка = (код.match(/естьГруппы && !естьСетка[\s\S]{0,700}/) || [''])[0];
правило('лиги собираются там же, где плей-офф',
    /group_league/.test(ветка) && /создатьПустыеЛиги\s*\(/.test(ветка) &&
    /создатьПустойПлейофф\s*\(/.test(ветка),
    'ветка сборки при отрисовке не знает про group_league');

/* ── 3. СУТЬ: один расклад на три сетки ──────────────────────────────── */
const телоЛиг = (код.match(/async function создатьПустыеЛиги[\s\S]*?\n    \}/) || [''])[0];

правило('лиги считает общий расклад, а не свой',
    /раскладСлотов\s*\(/.test(телоЛиг),
    'создатьПустыеЛиги не зовёт раскладСлотов — у лиг снова свой ход');

правило('свой ход лиг убран из продукта',
    !/buildLeagueSEBracket\s*\([^)]*tournament/.test(код.replace(/function buildLeagueSEBracket[^\n]*/, '')),
    'buildLeagueSEBracket снова зовётся — два расклада на одно понятие');

/* ── 4. слои мест: высшая сверху, утешительная под ней ───────────────── */
правило('высшая лига берёт места с первого',
    /префикс:\s*'PL'[^}]*от:\s*1/.test(телоЛиг),
    'высшая лига берёт не с первого места');

правило('утешительная берёт места сразу под проходными',
    /префикс:\s*'CL'[^}]*от:\s*qualifiers \+ 1/.test(телоЛиг),
    'утешительная лига начинается не с qualifiers+1 — слои мест разошлись');

/* ── 5. размер группы считается, а не берётся из настроек ────────────── */
правило('размер группы считается по людям в матчах',
    /размерГруппы\[г - 1\] = Object\.keys\(люди\)\.length/.test(телоЛиг),
    'размер группы не считается из матчей — у неравных групп утешительная ' +
    'получит метки на места, которых нет');

правило('расклад знает про размеры групп',
    /размерГруппы:\s*размерГруппы/.test(телоЛиг),
    'размеры групп не передаются в расклад');

const телоРасклада = (код.match(/function раскладСлотов[\s\S]*?\n        if \(прямые\.length < 2\) return null;/) || [''])[0];
правило('расклад пропускает места, которых в группе нет',
    /if \(размерГруппы && м > \(размерГруппы\[г\] \|\| 0\)\) continue;/.test(телоРасклада),
    'расклад ставит метку на место, которого в группе не существует');

/* ── 6. доп. матчей в лигах нет ──────────────────────────────────────── */
правило('лигам доп. матчи не разыгрываются',
    /безДопМатчей:\s*true/.test(телоЛиг),
    'лиги просят доп. матчи — их в лигах не бывает');

правило('выключатель доп. матчей действует',
    /опции\.безДопМатчей \? 'direct' : tournament\.playoff_format/.test(телоРасклада.length ? код : ''),
    'безДопМатчей не влияет на формат — выключатель мёртвый');

/* ── 7. метки и круги ────────────────────────────────────────────────── */
правило('метки кладутся в слоты, а не игроки',
    /slot1_label:\s*лев \? лев\.метка : null/.test(телоЛиг) &&
    /player1_id:\s*null/.test(телоЛиг),
    'в клетки лиг кладутся игроки вместо меток');

правило('круги лиг именуются своим префиксом',
    /л\.префикс \+ '-R1'/.test(телоЛиг) && /л\.префикс \+ '-F'/.test(телоЛиг) &&
    /л\.префикс \+ '-3RD'/.test(телоЛиг),
    'круги лиг именуются не через префикс PL/CL');

/* ── вывод ───────────────────────────────────────────────────────────── */
const ВСЕГО = 13;
console.log('\n  ЛИГИ СТОЯТ С ПЕРВОГО ДНЯ\n');
if (ошибки.length === 0) {
    console.log('  ок      все ' + ВСЕГО + ' правил держат\n');
    process.exit(0);
}
ошибки.forEach(о => {
    console.log('  НЕ ТАК  ' + о.имя);
    console.log('          ' + о.подсказка);
});
console.log('\n  НЕ ТАК  ' + ошибки.length + ' из ' + ВСЕГО + '\n');
process.exit(1);
