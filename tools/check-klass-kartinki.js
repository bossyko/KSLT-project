#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «КЛАСС, СДЕЛАННЫЙ ДЛЯ КАРТИНКИ, НЕ НОСИТ ТЕКСТ» (01.11).
 *
 * ЗАЧЕМ ОН ЕСТЬ — СЛУЧАЙ, А НЕ ОПАСЕНИЕ. У спонсора без логотипа
 * `js/sponsors-loader.js` ставил на `<span>` с названием класс
 * `.sponsor-logo-img`, у которого в css `height: 24px`, `max-width: 120px`
 * и `object-fit: contain`. Картинке это рамка — она в неё впишется сама.
 * ТЕКСТУ ЭТО ЛОВУШКА: он в рамку не вписывается, а вылезает из неё.
 *
 * ЗАМЕР НА ЖИВОЙ СТРАНИЦЕ, А НЕ ОПАСЕНИЕ: `clientHeight` 24 при
 * `scrollHeight` **48** — «Ала-Тоо Спорт» встал ДВУМЯ строками, и вторая
 * при `overflow: visible` отрисовалась НИЖЕ бокса, до 85.5 при боксе
 * 37.5→61.5. Эта невидимая строка накрывала ссылку «назад» под шапкой и
 * забирала её нажатия: профиль попадания показал, что до 84 всё
 * достаётся логотипу, а собственная цель ссылки начинается с 88.
 * Семь прогонов одной пробы ушло на то, чтобы это назвать.
 *
 * ПОЧЕМУ ПРИЗНАК — `object-fit`. Это свойство имеет смысл ТОЛЬКО для
 * замещаемых элементов: картинка, видео, `object`. Класс, в котором он
 * стоит, объявлен для картинки — и на текстовом узле он всегда ошибка,
 * даже если сегодня текст случайно влез в одну строку.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ, И ЭТО НАЗВАНО. Прибор читает ЛИТЕРАЛЫ разметки в js:
 * класс, собранный склейкой из переменных, он не видит — ПРИБОР НЕ ВИДИТ
 * СКЛЕЙКУ, и это уже четвёртый раз за ветку. Разметку в .html он тоже не
 * читает: там классы на текстовых узлах ставят руками и осознанно, а
 * беда родилась ровно на шве «данных нет — подставим текст».
 *
 *   node tools/check-klass-kartinki.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');

/* ПРИБОР ЧИТАЕТ CSS, А НЕ ПОДПИСИ К НЕМУ. Поймано прувером на себе —
   второй раз за сессию и теперь в css: в подписи к новому классу я
   процитировал имя старого, прибор нашёл цитату и взял за ней ЧУЖОЙ
   блок — тот самый, где стоит `overflow: hidden`, — и решил, что ловушка
   обезврежена. Главный откат из-за этого не падал.
   ЯКОРЬ ВНУТРИ КОММЕНТАРИЯ — ЭТО ЯКОРЬ, КОТОРОГО ПРИБОР ВИДЕТЬ НЕ
   ДОЛЖЕН. */
function cssБезКомментариев(текст) {
    return текст.replace(/\/\*[\s\S]*?\*\//g, с => с.replace(/[^\n]/g, ' '));
}

function читатьCss(файл) {
    return cssБезКомментариев(fs.readFileSync(файл, 'utf8'));
}

/* ЗАМЕРЕНО 01.11: таких мест НОЛЬ. Храповик вниз не нужен — понятие
   простое, и новое место здесь всегда беда, а не долг. */
function файлы(д, вых) {
    вых = вых || [];
    const п = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(п)) return вых;
    for (const э of fs.readdirSync(п, { withFileTypes: true })) {
        const о = д + '/' + э.name;
        if (э.isDirectory()) файлы(о, вых);
        else if (э.name.endsWith('.js')) вых.push(о);
    }
    return вых;
}

/**
 * Классы, у которых в css стоит `object-fit` — то есть «это для картинки».
 *
 * РАЗБОР ИДЁТ ОТ СВОЙСТВА НАЗАД, А НЕ ОТ СЕЛЕКТОРА ВПЕРЁД, И ЭТО НЕ
 * ВКУС. Первая редакция шла по css выражением `([^{}]+)\{([^}]*)\}` — и
 * ломалась на `@media`: для него `[^{}]+` забирает условие, `[^}]*`
 * закрывается на ПЕРВОЙ внутренней скобке, и дальше разбор едет по
 * половинкам чужих правил. Прувер это и поймал: главный откат —
 * «вернуть надписи класс картинки» — НЕ УПАЛ, потому что прибор не нашёл
 * `object-fit` у `.sponsor-logo-img`, лежащего на верхнем уровне.
 * От свойства назад до ближайшей `{`, оттуда назад до конца предыдущего
 * правила — и вложенность не мешает.
 */
function классыКартинокИз(текст) {
    const из = new Set();
    {
        const re = /object-fit\s*:/g;
        let м;
        while ((м = re.exec(текст))) {
            const о = текст.lastIndexOf('{', м.index);
            if (о === -1) continue;
            const начало = Math.max(
                текст.lastIndexOf('}', о), текст.lastIndexOf('{', о - 1),
                текст.lastIndexOf(';', о));
            const селектор = текст.slice(начало + 1, о);
            for (const с of селектор.split(',')) {
                const части = с.trim().split(/\s+|>/).filter(Boolean);
                const хвост = части[части.length - 1] || '';
                const кл = хвост.match(/\.([A-Za-z0-9_-]+)/g);
                if (кл) кл.forEach(k => из.add(k.slice(1)));
            }
        }
    }
    return из;
}

function классыКартинок() {
    const из = new Set();
    const д = path.join(КОРЕНЬ, 'css');
    if (!fs.existsSync(д)) return из;
    for (const имя of fs.readdirSync(д)) {
        if (!имя.endsWith('.css')) continue;
        классыКартинокИз(читатьCss(path.join(д, имя))).forEach(к => из.add(к));
    }
    return из;
}

/**
 * Все объявления, какие css даёт этому классу — одной строкой.
 * Тем же приёмом от свойства назад: ищем сам класс и берём блок, в
 * котором он объявлен, по парным скобкам.
 */
function правилаКлассаИз(текст, имя) {
    let из = '';
    const признак = new RegExp('\\.' + имя + '(?![A-Za-z0-9_-])', 'g');
    {
        признак.lastIndex = 0;
        let м;
        while ((м = признак.exec(текст))) {
            const о = текст.indexOf('{', м.index);
            if (о === -1) continue;
            /* Между именем и скобкой не должно быть другой скобки —
               иначе это не его блок, а упоминание в селекторе соседа. */
            if (/[{};]/.test(текст.slice(м.index, о).replace(/[\s,>+~a-zA-Z0-9_.:#()\[\]="'-]/g, ''))) continue;
            let гл = 0;
            for (let j = о; j < текст.length; j++) {
                if (текст[j] === '{') гл++;
                else if (текст[j] === '}') { гл--; if (!гл) { из += текст.slice(о + 1, j) + ';'; break; } }
            }
        }
    }
    return из;
}

function правилаКласса(имя) {
    let из = '';
    const д = path.join(КОРЕНЬ, 'css');
    if (!fs.existsSync(д)) return из;
    for (const файл of fs.readdirSync(д)) {
        if (!файл.endsWith('.css')) continue;
        из += правилаКлассаИз(читатьCss(path.join(д, файл)), имя);
    }
    return из;
}

const КАРТИНОЧНЫЕ = классыКартинок();
const беды = [];

/* Текстовые узлы в литералах разметки: span, div, p, h1..h6, a, li, td. */
const ТЕКСТОВЫЕ = /<(span|div|p|h[1-6]|a|li|td|strong|em|small)\b([^>]*)>/gi;

/* БЕДА — НЕ ЛЮБОЙ ТЕКСТ, А ТЕКСТ НЕИЗВЕСТНОЙ ДЛИНЫ.
   Первая редакция правила падала на пяти местах, и ВСЕ ПЯТЬ оказались
   законными: `<div class="ad-table-thumb"></div>` пуст вовсе, а
   `<div class="pp-tournament-photo pp-tournament-photo-empty">🎾</div>`
   держит один знак, который в 48×48 влезает заведомо, да ещё и выровнен
   своим вторым классом.
   Ловушка срабатывает там, где внутрь подставляются ДАННЫЕ: их длину
   никто не знает заранее, и рамка картинки её не удержит. Ровно так и
   было у спонсора: `>' + KSLT_экранировать(hero.name) + '<`.
   ПРИЗНАК, НАЗЫВАЮЩИЙ БЕДОЙ ЗАКОННОЕ, БУДЕТ СНЯТ ЦЕЛИКОМ — и вместе с
   ним уйдёт настоящая проверка. */
function данныеСразуПосле(текст, конецТега) {
    const хвост = текст.slice(конецТега, конецТега + 60);
    return /^\s*['"]?\s*\+/.test(хвост);
}

for (const ф of файлы('js').concat(файлы('mobile/www/js'))) {
    const текст = безКомментариев(fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'), ф);
    let м;
    ТЕКСТОВЫЕ.lastIndex = 0;
    while ((м = ТЕКСТОВЫЕ.exec(текст))) {
        const кл = м[2].match(/class\s*=\s*["']([^"']*)["']/);
        if (!кл) continue;
        if (!данныеСразуПосле(текст, м.index + м[0].length)) continue;
        /* УДЕРЖАННОЕ СОДЕРЖИМОЕ — НЕ ЛОВУШКА. Вторая редакция правила
           падала на карточке игрока в админке, и падала зря: там внутрь
           идёт флаг-эмодзи, а узел тут же выровнен инлайном
           `display:flex; align-items:center; justify-content:center` —
           содержимое центрируется в рамке и наружу не выходит.
           Ловушка — это рамка БЕЗ удержания: ни flex, ни grid, ни
           `overflow: hidden`. Ровно так и стоял класс у спонсора:
           `display: block`, `overflow: visible`. */
        const удержано = /display\s*:\s*(flex|grid|inline-flex)/.test(м[2]) ||
                         /overflow\s*:\s*hidden/.test(м[2]);
        if (удержано) continue;
        for (const имя of кл[1].split(/\s+/).filter(Boolean)) {
            if (!КАРТИНОЧНЫЕ.has(имя)) continue;
            /* И ТО ЖЕ САМОЕ, ЗАДАННОЕ КЛАССОМ, А НЕ ИНЛАЙНОМ. */
            const изCss = правилаКласса(имя);
            if (/display\s*:\s*(flex|grid|inline-flex)/.test(изCss) ||
                /overflow\s*:\s*hidden/.test(изCss)) continue;
            const строка = текст.slice(0, м.index).split('\n').length;
            беды.push(ф + ':' + строка + '  <' + м[1] + ' class="' + имя + '"> + данные');
        }
    }
}

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('класс картинки не носит данные',
    беды.length === 0,
    'Так стоит:\n  ' + беды.join('\n  ') + '\n' +
    'У этого класса в css есть `object-fit`, то есть он объявлен для\n' +
    'КАРТИНКИ: `height` и `max-width` там рамка, в которую картинка\n' +
    'впишется сама. Текст в неё не впишется — он вылезет наружу при\n' +
    '`overflow: visible` и будет невидимо забирать нажатия у того, что\n' +
    'лежит ниже. Текстовому случаю нужен СВОЙ класс: та же ступень\n' +
    'высоты, но одна строка и многоточие.');

/* ОБРАЗЕЦ ВНУТРИ ПРИБОРА: он обязан РАЗЛИЧАТЬ, иначе «ноль мест» не
   значит ничего. В образце — ровно та ловушка, на которую я наступил:
   имя класса картинки процитировано В КОММЕНТАРИИ перед ЧУЖИМ блоком, у
   которого стоит `overflow: hidden`. Прибор, читающий комментарии,
   припишет это удержание картиночному классу и замолчит. */
правило('разбор css не путает блоки и не читает подписи',
    (function () {
        const о = '.ramka { height: 24px; object-fit: contain; }\n' +
                  '/* было: класс .ramka стоял на тексте */\n' +
                  '.nadpis { display: block; overflow: hidden; }\n';
        const чисто = cssБезКомментариев(о);
        const картиночные = классыКартинокИз(чисто);
        if (!картиночные.has('ramka') || картиночные.has('nadpis')) return false;
        const свои = правилаКлассаИз(чисто, 'ramka');
        /* У `.ramka` НЕТ удержания — значит прибор не должен его увидеть. */
        return /object-fit/.test(свои) && !/overflow\s*:\s*hidden/.test(свои);
    })(),
    'Образец внутри прибора: класс картинки, за ним ПОДПИСЬ с его именем,\n' +
    'за подписью чужой блок с `overflow: hidden`. Прибор обязан отдать\n' +
    'у картиночного класса только его собственные объявления. Не отдаёт —\n' +
    'значит он снова читает комментарии или берёт соседний блок, и тогда\n' +
    'главное правило молчит на настоящей беде.');

правило('классы картинок вообще нашлись',
    КАРТИНОЧНЫЕ.size > 0,
    'Ни одного класса с `object-fit` в css не найдено — значит признак\n' +
    'сломан, и правило выше молчит не потому, что всё хорошо.\n' +
    'ПУСТОЕ ПРАВИЛО ХУЖЕ ОТСУТСТВУЮЩЕГО.');

правило('у надписи спонсора своя одна строка',
    (function () {
        const о = читатьCss(path.join(КОРЕНЬ, 'css/style.css'));
        const i = о.indexOf('.sponsor-logo-text');
        if (i === -1) return false;
        const блок = о.slice(i, о.indexOf('}', i));
        return /overflow:\s*hidden/.test(блок) &&
               /white-space:\s*nowrap/.test(блок) &&
               /text-overflow:\s*ellipsis/.test(блок);
    })(),
    'Надпись вместо логотипа держится тремя свойствами разом: `overflow:\n' +
    'hidden`, `white-space: nowrap`, `text-overflow: ellipsis`. Пропало\n' +
    'любое — и длинное название снова вылезет из бокса и начнёт забирать\n' +
    'чужие нажатия. Это ровно та беда, из-за которой класс и заведён.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      класс картинки на тексте: все ' + всего + ' правил держатся');
    console.log('          классов с object-fit ' + КАРТИНОЧНЫЕ.size + ', текстовых мест с ними 0');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  класс картинки на тексте — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
