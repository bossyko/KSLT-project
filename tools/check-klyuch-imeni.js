#!/usr/bin/env node
/**
 * КЛЮЧ ИМЕНИ — ПРОБА НА НАБОРЕ НАПИСАНИЙ, А НЕ ВЕРА В ТАБЛИЦУ.
 *
 * ЗАЧЕМ. Карточку игрока заводит `ensure-player-card`: ищет свободную
 * карточку с тем же «ключом имени» и, не найдя, создаёт новую. Имена в
 * базе кириллицей, а человек входит через Google латиницей — ключ и
 * сводит их вместе. Разошёлся ключ — родился дубль.
 *
 * ТАК РОДИЛИСЬ ОБА ДУБЛЯ 12–13.11:
 *   «Данияр Атаханов»  ↔ «Daniyar Atakhanov» — х пишут h и kh
 *   «Азамат Джумабаев» ↔ «Azamat Jumabaev»   — ж пишут zh, j и dzh
 * Разбирать их пришлось руками в SQL, с риском потерять заявку на турнир.
 *
 * ПОЧЕМУ ПРОБА, А НЕ ЧТЕНИЕ СПИСКА ЗАМЕН. Список замен в коде можно
 * прочитать и сказать «выглядит правильно» — это ничего не доказывает.
 * Прибор берёт НАСТОЯЩИЙ код функции из `index.ts`, выполняет его и
 * гоняет таблицу написаний. Правило держит ОТНОШЕНИЕ: эти пары обязаны
 * давать один ключ, а разные люди — разные.
 *
 * Запуск: node tools/check-klyuch-imeni.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_ROOT || path.join(__dirname, '..');
const ФАЙЛ = 'supabase/functions/ensure-player-card/index.ts';

const ошибки = [];
const ок = [];
function правило(имя, держится, почему) {
    if (держится) ок.push(имя); else ошибки.push({ имя, почему });
}

/* КОД БЕРЁТСЯ ИЗ ПРОДУКТА, А НЕ ПЕРЕПИСЫВАЕТСЯ СЮДА. Копия жила бы
   своей жизнью и доказывала бы саму себя. Типы Deno снимаются — они
   нужны компилятору, а не поведению. */
const исходник = fs.readFileSync(path.join(КОРЕНЬ, ФАЙЛ), 'utf8');

function вырезать(имя) {
    const начало = исходник.indexOf('function ' + имя + '(');
    if (начало < 0) return null;
    let i = исходник.indexOf('{', начало), глубина = 0, конец = -1;
    for (let j = i; j < исходник.length; j++) {
        if (исходник[j] === '{') глубина++;
        else if (исходник[j] === '}') { глубина--; if (!глубина) { конец = j + 1; break; } }
    }
    return конец < 0 ? null : исходник.slice(начало, конец);
}

const тТранслит = вырезать('транслит');
const тКлюч = вырезать('ключ');

правило('обе части ключа имени нашлись в продукте',
    !!тТранслит && !!тКлюч,
    'Не удалось вырезать функции `транслит` и `ключ` из ' + ФАЙЛ + '.\n' +
    'Либо их переименовали, либо унесли в другой файл: прибор обязан\n' +
    'читать настоящий код, иначе он доказывает копию.');

let ключ = null;
if (тТранслит && тКлюч) {
    const безТипов = (т) => т
        .replace(/:\s*Record<[^>]+>/g, '')
        .replace(/\(\s*имя\s*:\s*string\s*\)\s*:\s*string/g, '(имя)')
        .replace(/\(\s*с\s*:\s*string\s*\)/g, '(с)')
        .replace(/:\s*string/g, '');
    try {
        ключ = new Function(безТипов(тТранслит) + '\n' + безТипов(тКлюч) + '\nreturn ключ;')();
    } catch (e) {
        правило('код ключа выполняется', false, 'Не выполнился: ' + e.message);
    }
}

/* ТАБЛИЦА НАПИСАНИЙ. Левое и правое — ОДИН человек, и ключ обязан
   совпасть. Случаи не выдуманы: первые два разбирались руками в базе. */
const ОДИН_ЧЕЛОВЕК = [
    ['Данияр Атаханов',  'Daniyar Atakhanov'],
    ['Данияр Атаханов',  'Daniyar Atahanov'],
    ['Константин Хан',   'Konstantin Khan'],
    ['Константин Хан',   'Konstantin Han'],
    ['Азамат Джумабаев', 'Azamat Jumabaev'],
    ['Азамат Джумабаев', 'Azamat Dzhumabaev'],
    ['Эрлан Шекербеков', 'Erlan Shekerbekov'],
    ['Айсулуу Токтосун', 'Aisuluu Toktosun'],
    ['Айсулуу Токтосун', 'Aysuluu Toktosun'],
    ['Нурбек Цой',       'Nurbek Tsoy'],
    ['Нурбек Цой',       'Nurbek Coy'],
    ['Александр Ким',    'Alexandr Kim'],
    ['Александр Ким',    'Aleksandr Kim'],
    ['Жанна Орозова',    'Janna Orozova'],
    ['Хан Константин',   'Konstantin Han']
];

/* РАЗНЫЕ ЛЮДИ ОБЯЗАНЫ ОСТАТЬСЯ РАЗНЫМИ. Схлопывание можно довести до
   того, что ключ совпадёт у половины клуба, и тогда человеку предложат
   чужую карточку. Это вторая половина правила, без неё первая опасна. */
const РАЗНЫЕ = [
    ['Иванов Иван',   'Petrov Petr'],
    ['Ахмат Алиев',   'Ahmedov Alim'],
    ['Ким Сергей',    'Kan Sergey'],
    ['Нурбек Цой',    'Nurbek Choi'],
    ['Эрлан Шекербеков', 'Erlan Shakirov']
];

if (ключ) {
    const разошлись = ОДИН_ЧЕЛОВЕК
        .filter(([а, б]) => ключ(а) !== ключ(б))
        .map(([а, б]) => а + ' → ' + ключ(а) + '  ≠  ' + б + ' → ' + ключ(б));
    правило('одно имя в разных написаниях даёт один ключ',
        разошлись.length === 0,
        'Разошлись ' + разошлись.length + ' пар(ы) из ' + ОДИН_ЧЕЛОВЕК.length + ':\n  ' +
        разошлись.join('\n  ') + '\n' +
        'Каждая такая пара — будущий дубль карточки: функция не найдёт\n' +
        'человека в базе и заведёт ему вторую, с нулём очков.');

    const слились = РАЗНЫЕ
        .filter(([а, б]) => ключ(а) === ключ(б))
        .map(([а, б]) => а + ' и ' + б + ' → ' + ключ(а));
    правило('разные люди не получают один ключ',
        слились.length === 0,
        'Слились ' + слились.length + ':\n  ' + слились.join('\n  ') + '\n' +
        'Схлопывание зашло слишком далеко: человеку предложат чужую\n' +
        'карточку со словами «кажется, это вы».');

    правило('ключ не зависит от порядка слов и регистра',
        ключ('Константин Хан') === ключ('ХАН константин'),
        'Ключ стал зависеть от порядка слов или регистра — а люди пишут\n' +
        'и «Фамилия Имя», и «Имя Фамилия».');
}

console.log('');
ок.forEach(и => console.log('  ок      ' + и));
ошибки.forEach(о => { console.log('\n  НЕ ТАК  ' + о.имя + '\n          ' + о.почему.split('\n').join('\n          ')); });
console.log('');
if (ошибки.length) { console.log('  Ключ имени: не сошлось ' + ошибки.length + '\n'); process.exit(1); }
console.log('  ок      ключ имени: ' + ок.length + ' правила, пар в таблице ' +
            (ОДИН_ЧЕЛОВЕК.length + РАЗНЫЕ.length) + '\n');
