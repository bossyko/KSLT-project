#!/usr/bin/env node
/**
 * НОВОСТИ ПРИЛОЖЕНИЯ: ВРЕЗКА И ЛИСТАНИЕ — ЗАМОРОЗКА КУСКА 219 (28.10).
 *
 * ДВЕ БЕДЫ, НАЗВАННЫЕ КОСТЕЙ: «в новостях кошмар с фото и инстаграм.
 * Первое — инста, там скрол почему? Второе — когда фото лента, не
 * получается листать фото в увеличенном и в миниатюре».
 *
 * 1. ВРЕЗКА INSTAGRAM СО СВОЕЙ ПРОКРУТКОЙ ВНУТРИ. Кадру в теле новости
 *    стояло `aspect-ratio: 16/9` — при ширине 343 это 193 пикселя.
 *    Инстаграм рисует вертикальный ролик 9:16 ПЛЮС свою шапку с именем
 *    аккаунта и низ с лайками; в 193 это не влезает, и внутри кадра
 *    появляется своя полоса прокрутки.
 *    НА САЙТЕ ЭТУ ЖЕ БЕДУ ЧИНИЛИ 08.10 — тем же глазом Кости. Там для
 *    неё есть общий дом `js/kslt-video.js` («одно определение на одно
 *    понятие»), который проставляет кадрам классы: в базе они лежат
 *    ГОЛЫМИ, их классы срезала чистка при сохранении. В приложении дома
 *    не было вовсе, и правило вертикального кадра не применялось.
 *    Замер после: кадр 723 пикселя вместо 193, короб 429×343 — видна
 *    ровно вертикальная часть, без чужой шапки и низа.
 *
 * 2. ФОТО НЕ ЛИСТАЛИСЬ. Листание было сделано ТОЛЬКО свайпом, а нажатие
 *    по снимку в просмотре ЗАКРЫВАЛО окно. На компьютере свайпа нет
 *    вовсе; на телефоне неточный свайп читался как нажатие — и вместо
 *    следующего кадра окно пропадало. Поставлены кнопки «назад/вперёд»
 *    и в карусели, и в просмотре, добавлены стрелки с клавиатуры, а
 *    закрытие по снимку снято: закрывает только фон и крестик.
 *    Замер после: карусель 1/5 → кнопка → 2/5 → миниатюра → 3/5;
 *    просмотр открылся на 3/5, кнопка → 4/5, нажатие по снимку окно НЕ
 *    закрывает.
 *
 * ПОПУТНО: посев переставлен ПЕРЕД именем в круговой таблице — слово
 * Кости, и так же он стоит в клетке сетки, теперь оба места читаются
 * одинаково.
 *
 * Запуск: node tools/check-novosti-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
function безСлов(отн) {
    return чит(отн).replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const разметка = безСлов('mobile/www/index.html');
const главная = безСлов('mobile/www/js/screens/home.js');
const медиа = безСлов('mobile/www/js/news-media.js');
const css = безСлов('mobile/www/css/app.css');

/* ── 1. ВРЕЗКА: ДОМ КАДРОВ ── */
правило(
    'дом внешнего видео лежит в приложении и подключён',
    чит('mobile/www/js/kslt-video.js') !== '' &&
    /js\/kslt-video\.js\?v=/.test(разметка),
    'На сайте он есть с 08.10, в приложении не было вовсе.');

правило(
    'копия дома кадров совпадает до байта',
    чит('js/kslt-video.js') !== '' &&
    чит('js/kslt-video.js') === чит('mobile/www/js/kslt-video.js'),
    'Разойдутся — беда родится ровно на шве.');

правило(
    'кадры чинятся при отрисовке новости',
    /KSLT_VIDEO\.починитьКадры\(detail\)/.test(главная),
    'В базе кадры лежат ГОЛЫМИ: классы срезала чистка при сохранении\n' +
    '(находка 08.10). Разметку чиним при отрисовке, а не в данных.');

правило(
    'вертикальная врезка описана отношением, а не высотой',
    /--ig-shapka: 54px/.test(css) && /--ig-niz: 240px/.test(css) &&
    /--ig-kadr: 4 \/ 5/.test(css) &&
    /\.nd-body figure \.news-video-ig/.test(css),
    'Кадру стояло 16/9 — при ширине 343 это 193 пикселя, и внутри него\n' +
    'появлялась СВОЯ полоса прокрутки. Числа 54 и 240 сняты замером\n' +
    'живого встраивания и НАМЕРЕННО не со шкалы: они описывают чужой\n' +
    'кадр, а не наш макет.');

/* ── 2. ЛИСТАНИЕ ── */
правило(
    'в просмотре есть кнопки листания',
    /nm-viewer-nav nm-prev/.test(медиа) && /nm-viewer-nav nm-next/.test(медиа),
    'Листание было ТОЛЬКО свайпом, а на компьютере его нет вовсе.');

правило(
    'в ленте есть кнопки листания',
    /news-carousel-nav news-carousel-prev/.test(безСлов('js/kslt-lenta.js')) &&
    /news-carousel-nav news-carousel-next/.test(безСлов('js/kslt-lenta.js')),
    'Миниатюры работали, а крупный кадр листался только свайпом.\n' +
    'ПРАВИЛО ПЕРЕПИСАНО КУСКОМ 220: кнопки я сперва написал своими\n' +
    'руками в `news-media.js`, а потом оказалось, что в общем доме\n' +
    '`js/kslt-lenta.js` они были с самого начала. Своя сборка снесена,\n' +
    'и правило смотрит туда, где эти кнопки теперь живут.');

правило(
    'нажатие по снимку больше не закрывает просмотр',
    /if \(e\.target === overlay\) close\(\)/.test(медиа) &&
    !/e\.target === overlay \|\| e\.target === img/.test(медиа),
    'Неточный свайп читался как нажатие — и вместо следующего кадра\n' +
    'окно пропадало.');

правило(
    'листать можно и с клавиатуры',
    /ArrowLeft/.test(медиа) && /ArrowRight/.test(медиа),
    'На планшете с клавиатурой и в окне разработчика свайпа нет.');

правило(
    'свайп остался',
    /onSwipe\(overlay/.test(медиа) && /onSwipe\(wrap\.querySelector/.test(медиа),
    'Кнопки добавлены В ДОПОЛНЕНИЕ к свайпу, а не вместо него.');

правило(
    'у кнопок листания цель нажатия со шкалы',
    /\.nm-viewer-nav, \.nm-nav \{[^}]*width: 44px; height: 44px/.test(css),
    'Ступени кнопок: 28 · 36 · 44 · 52.');

/* ── 3. ПОСЕВ ПЕРЕД ИМЕНЕМ ── */
правило(
    'посев стоит перед именем',
    /\(st\.seed \? '<span class="td-gt-seed">\[' \+ st\.seed \+ '\]<\/span> ' : ''\) \+\s*\n\s*имя\(st\.playerId\)/.test(безСлов('js/kslt-setka.js')),
    'Слово Кости: «номер сеяного наверно лучше поставить перед ФИО».\n' +
    'В клетке сетки он и так был первым — теперь оба места читаются\n' +
    'одинаково.');

/* ── 4. ВЕРСИИ ── */
(function () {
    const ВЕРСИИ = [['css/app.css', 30], ['js/news-media.js', 5],
                    ['js/screens/home.js', 14], ['js/kslt-video.js', 1],
                    ['js/kslt-lenta.js', 1], ['js/kslt-ekranirovanie.js', 1]];
    const отстали = [];
    ВЕРСИИ.forEach(function (в) {
        const м = разметка.match(new RegExp(в[0].replace(/[./]/g, '\\$&') + '\\?v=(\\d+)'));
        if (!м || Number(м[1]) < в[1]) отстали.push(в[0] + ' = ' + (м ? м[1] : 'нет'));
    });
    правило('версии правленых файлов подняты', отстали.length === 0,
        'Правка без подъёма версии невидима.\nОтстали: ' + отстали.join(', '));
})();

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      новости приложения: все ' + держится + ' правил держатся');
    console.log('          врезка отношением, листание кнопками и свайпом\n');
}
