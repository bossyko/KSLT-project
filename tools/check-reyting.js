/* Блок по селектору с якорем на начало строки: '.rk-row {' встречается и как
   '.rankings-panel .rk-row {'. */
function блок(текст, сел, маркер) {
    const рег = new RegExp('(?:^|\\n)' + сел.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{[^}]*\\}', 'g');
    let м;
    while ((м = рег.exec(текст)) !== null) {
        if (!маркер || м[0].indexOf(маркер) !== -1) return м[0];
    }
    return null;
}
const свойство = (т, имя) => {
    if (!т) return null;
    const м = т.match(new RegExp('(?:^|\\n)\\s*' + имя + ':\\s*([^;]+);'));
    return м ? м[1].trim() : null;
};
const сколько = (текст, рег) => (текст.match(рег) || []).length;

