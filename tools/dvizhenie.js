/**
 * ДВИЖЕНИЕ ВЫКЛЮЧАЕТСЯ ОДНИМ МЕСТОМ — ОБЩЕЕ ОПРЕДЕЛЕНИЕ ДЛЯ ЗАМОРОЗОК.
 *
 * До 15.10 шестнадцать правил в шестнадцати кусках сторожили НАЛИЧИЕ
 * блока `prefers-reduced-motion` в СВОЁМ css, а некоторые — ещё и
 * конкретный селектор внутри него. Это сторож МЕСТА, а не отношения: при
 * сведении блоков в один общий все шестнадцать упали бы, хотя движение
 * стало гаситься строже, чем раньше.
 *
 * ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ: «движение выключается у того, кто попросил
 * систему его не показывать». Где именно стоит блок — не предмет заморозки.
 *
 * Модуль один, зовут его все: ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ.
 */
const fs = require('fs');
const path = require('path');

const ТОКЕНЫ = path.join(__dirname, '..', 'css', 'tokens.css');

/** Общий блок: звёздочка плюс длительность, а не перечень имён. */
function общееГашение(текстТокенов) {
    const т = текстТокенов !== undefined ? текстТокенов : fs.readFileSync(ТОКЕНЫ, 'utf8');
    const м = /@media\s*\(\s*prefers-reduced-motion:\s*reduce\s*\)\s*\{([\s\S]*?)\n\}/.exec(т);
    if (!м) return false;
    const тело = м[1];
    /* Звёздочка обязательна: перечень имён стареет вместе с кодом — ровно
       так и жили 26 непогашенных анимаций из 38. */
    if (!/\*\s*,[\s\S]{0,80}\*::after|\*\s*\{/.test(тело)) return false;
    /* `none` оставил бы элемент в начальном кадре: всё, что появляется
       через opacity 0 → 1, осталось бы невидимым навсегда. */
    if (!/animation-duration\s*:\s*0\.01ms/.test(тело)) return false;
    if (!/animation-iteration-count\s*:\s*1/.test(тело)) return false;
    if (!/transition-duration\s*:\s*0\.01ms/.test(тело)) return false;
    return true;
}

/**
 * Движение куска гасится: общим блоком либо своим — для тех двух лент,
 * что везут содержимое и получают взамен прокрутку пальцем.
 */
function гасится(cssКуска) {
    if (общееГашение()) return true;
    return /@media\s*\(\s*prefers-reduced-motion:\s*reduce\s*\)/.test(cssКуска || '');
}

const ПОДСКАЗКА =
    'движение не выключается у того, кто попросил систему его не показывать.\n' +
    '          Общий блок живёт в css/tokens.css и гасит ВСЁ через звёздочку;\n' +
    '          до 15.10 на его месте было 27 поимённых блоков, и 26 бесконечных\n' +
    '          анимаций из 38 не гасились вовсе. WCAG 2.3.3.';

module.exports = { общееГашение, гасится, ПОДСКАЗКА };
