/**
 * ЗАМОРОЗКА КУСКА 128 — ИМЯ КЛАССА, ПОД КОТОРЫМ НЕТ ПРАВИЛА.
 *
 * Третий случай одной болезни за день. Сперва полоса фильтров звала
 * `sticky` (кусок 125), потом «Лояльность» — `ad-btn--sm`,
 * `ad-btn--danger` и `ad-page-btn`. Правил под них нет ни в одном css.
 *
 * ИМЯ БЕЗ ПРАВИЛА ВЫГЛЯДИТ КАК РЕШЕНИЕ: в коде написано «мелкая» и
 * «опасная», а на экране — обычная.
 *
 * ЗАМЕРЕНО НА БОЕВОЙ 22.10, раздел «Лояльность»: «Ред.» 81×44 и «✕»
 * 61×44 — обе обычного размера и одного фона #1E1E1E. Кнопка УДАЛЕНИЯ
 * ПРАВИЛА неотличима по виду от «Ред.». Пагинация «Транзакций» звала
 * несуществующее имя и рисовалась голой кнопкой браузера: 22×22, фон
 * #EFEFEF, чёрный текст на тёмной странице.
 *
 * После перевода на живые имена (замер на стенде): «Ред.» 65×36, «✕»
 * 45×36 с красным фоном и краской --danger, пагинация 32×30.
 *
 *   node tools/check-imena-klassov-zhivye.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const ВЕСЬ_CSS = fs.readdirSync(path.join(КОРЕНЬ, 'css'))
    .filter(н => н.endsWith('.css')).map(н => чит('css/' + н)).join('\n');

function всеJs(дир, сп) {
    fs.readdirSync(path.join(КОРЕНЬ, дир), { withFileTypes: true }).forEach(э => {
        if (э.isDirectory()) всеJs(path.join(дир, э.name), сп);
        else if (э.name.endsWith('.js')) сп.push([path.join(дир, э.name), чит(path.join(дир, э.name))]);
    });
    return сп;
}
const JS = всеJs('js', []);

/* ── 1. ДВОЙНОГО ТИРЕ НЕТ НИГДЕ ──────────────────────────────────────── */
/* Признак берётся по ПРИЗНАКУ, а не по списку известных: любое имя вида
   `ad-что-то--что-то` ловится само, даже если его ещё не существовало. */
const двойные = [];
JS.forEach(([имя, текст]) => {
    (текст.match(/\bad-[a-z]+--[a-z-]+/g) || []).forEach(к => двойные.push(имя + ': ' + к));
});
правило('ни одно имя класса в js не пишется через двойное тире',
    двойные.length === 0,
    'Найдено: ' + двойные.join(', ') + '.\n' +
    'В продукте все имена через ОДНО тире, и правил под двойное нет ни в одном\n' +
    'css. Такое имя ничего не делает, а в коде читается как решение.');

/* ── 2. ТРИ ПРЕЖНИХ ИМЕНИ МЕРТВЫ, И ЭТО ПРОВЕРЕНО, А НЕ ПОМНИТСЯ ─────── */
[['ad-btn--sm', 'мелкая кнопка'], ['ad-btn--danger', 'разрушительная кнопка'],
 ['ad-page-btn', 'кнопка страницы']].forEach(([к, что]) => {
    правило('правила `.' + к + '` в css по-прежнему нет',
        !new RegExp('\\.' + к + '[\\s,{:]').test(ВЕСЬ_CSS),
        'Под `.' + к + '` (' + что + ') завелось правило. Тогда у понятия снова\n' +
        'два имени, и беда родится на шве: часть мест зовёт одно, часть другое.');
});

/* ── 3. ЖИВЫЕ ИМЕНА НА МЕСТЕ И ЗОВУТСЯ ───────────────────────────────── */
const ЛОЯ = чит('js/admin/sections/loyalty.js');
правило('кнопки «Лояльности» зовут живые имена',
    (ЛОЯ.match(/ad-btn ad-btn-sm/g) || []).length === 4 &&
    (ЛОЯ.match(/ad-btn-sm ad-btn-danger/g) || []).length === 2 &&
    /class="ad-crt-page-btn/.test(ЛОЯ),
    'Имена кнопок «Лояльности» уехали. Замерено: четыре мелких, из них две\n' +
    'разрушительные, и пагинация на общем имени `ad-crt-page-btn` (26 зовов\n' +
    'по продукту, 3 правила в css).');

/* ПРОВЕРЯЕТСЯ НЕ НАЛИЧИЕ СЕЛЕКТОРА, А ТО, ЧТО ОН ДАЁТ. Прувер показал:
   `.ad-btn-sm` объявлен ДВАЖДЫ — на :1477 высота, на :5977 только
   скругление (так решено 28.09), — и откат, уносивший первое, правило
   не ронял: селектор-то оставался. ПРАВИЛО, СПРАШИВАЮЩЕЕ «ЕСТЬ ЛИ ИМЯ»,
   НЕ ВИДИТ, ЧТО ИМЯ БОЛЬШЕ НИЧЕГО НЕ ДЕЛАЕТ. */
[['ad-btn-sm', '--ad-btn-h:\\s*var\\(--btn-h-sm\\)', 'высоту мелкой кнопки'],
 ['ad-btn-danger', 'ad-btn-danger[\\s,{][^}]*color', 'краску разрушительной кнопки'],
 ['ad-crt-page-btn', 'ad-crt-page-btn[\\s,{][^}]*(background|border)', 'вид кнопки страницы']
].forEach(([к, признак, что]) => {
    /* ПРИЗНАК ИЩЕТСЯ В БЛОКАХ ЭТОГО СЕЛЕКТОРА, А НЕ ПО ВСЕМУ ФАЙЛУ:
       прувер переименовал правило, а содержимое осталось лежать в css —
       и проверка «есть ли такая строка где-нибудь» прошла. */
    const блоки = (ВЕСЬ_CSS.match(new RegExp('\\.' + к + '[^{}]*\\{[^}]*\\}', 'g')) || []).join('\n');
    правило('`.' + к + '` не просто существует, а задаёт ' + что,
        new RegExp(признак).test(блоки),
        'Правило `.' + к + '` опустело или пропало: имя, на которое кусок 128\n' +
        'перевёл кнопки, стало таким же мёртвым, как прежнее.');
});

/* ── вывод ───────────────────────────────────────────────────────────── */
console.log('');
if (ошибки.length) {
    console.log('  НЕ ТАК  имена классов — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(([и, п]) => console.log('          ✗ ' + и + '\n            ' + п.replace(/\n/g, '\n            ') + '\n'));
    process.exit(1);
}
