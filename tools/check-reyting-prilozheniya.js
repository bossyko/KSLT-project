#!/usr/bin/env node
/**
 * РАЗДЕЛ РЕЙТИНГА ПРИЛОЖЕНИЯ — ЗАМОРОЗКА КУСКА 208 (27.10).
 *
 * ЧТО БЫЛО. Раздел держался на ЧЕТЫРЁХ границах ширины — 340 · 414 · 430 ·
 * 500, — и один и тот же текстовый уровень определялся в них три-четыре
 * раза разными числами: имя 11 / 13 / 14, очки 11 / 13 / 14, аватар
 * 28 / 32 / 36, фото на пьедестале 44 / 52 / 56 / 60, карточка
 * 74 / 90 / 100 / 110, отступ строки 8-10 / 10-14 / 12-16. На шкале
 * проекта границ между 340 и 500 нет вовсе: только 640 и 992.
 * Мимо шкалы кеглей стояли 9, 10, 13, 17, 20, 22; мимо шкалы отступов —
 * 4, 6, 10, 14, 20. Столбец очков был определён ДВАЖДЫ и уже разошёлся:
 * шапка 48, строка 50 — заголовок и число под ним стояли на разных
 * вертикалях. Целей нажатия меньше 44 было четыре из пятнадцати.
 * Аria-атрибутов на всём экране — НОЛЬ.
 *
 * ПОЧЕМУ ТЯНУЩИЙСЯ КЕГЕЛЬ НЕ РЕШЕНИЕ. Первый заход поставил `clamp` по
 * ширине вида — и на 375 кегли вышли 12.2, 15.6, 19.2. Ни одно не
 * ступень: тянущийся кегель беду не лечит, а прячет. Поэтому типографика
 * от ширины НЕ зависит, а по ширине меняется только то, сколько текста
 * видно: имя обрезается многоточием, карточки пьедестала делят полосу.
 *
 * ПОСЛЕ: одна лестница на всех видах (замерено на 340, 375 и 844 —
 * 11 · 12 · 14 · 16 · 21 везде), столбцы 24 · 44 · 44 · 44, целей меньше
 * 44 ни одной, aria-атрибутов 73, перелива нет.
 *
 * Запуск: node tools/check-reyting-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

const ШКАЛА_КЕГЕЛЬ = [11, 12, 14, 16, 18, 21, 26, 32, 40];
/* Отступ допустим, если он на шкале или кратен восьми: подтяжки
   градиента и прочие крупные смещения живут на той же сетке.
   2 — оптическая правка, заведена в компоненте. */
const ШКАЛА_ОТСТУП = [0, 2, 8, 12, 16, 24, 32, 40];
function отступНаСетке(v) { return ШКАЛА_ОТСТУП.includes(v) || v % 8 === 0; }
/* РАЗМЕР ДОПУСТИМ, ЕСЛИ ОН СТОИТ НА СЕТКЕ, А НЕ ЕСЛИ ОН ЕСТЬ В СПИСКЕ.
   Список пришлось бы дописывать на каждое декоративное пятно, а список,
   который держится руками, отстаёт. Сетка: ступень кнопок (28·36·44·52),
   ступень кеглей — так живут иконки, — или кратное восьми. */
const ШКАЛА_КНОПКА = [28, 36, 44, 52];
function размерНаСетке(v) {
    return ШКАЛА_КНОПКА.includes(v) || ШКАЛА_КЕГЕЛЬ.includes(v) || (v % 8 === 0);
}

let упало = 0, держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}

function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const стили = чит('mobile/www/css/app.css');
const экран = чит('mobile/www/js/screens/rating.js');
const словарь = чит('mobile/www/js/i18n.js');

/* Селекторы раздела */
const РАЗДЕЛ = /^\s*\.(rating-|rp-|rf-|rr-|rt-col-)/;

/* ── 1. НИ ОДНОЙ ГРАНИЦЫ ШИРИНЫ НА РАЗДЕЛ ── */
(function границы() {
    const строки = стили.split('\n');
    let глубина = 0, вМедиа = false, граница = '';
    const найдено = [];
    строки.forEach(function (с, i) {
        const м = с.match(/@media \((?:min|max)-width:\s*(\d+)px\)/);
        if (м) { вМедиа = true; граница = м[1]; глубина = 0; }
        if (вМедиа) {
            for (const ч of с) { if (ч === '{') глубина++; if (ч === '}') глубина--; }
            if (РАЗДЕЛ.test(с) && граница !== '640' && граница !== '992') {
                найдено.push((i + 1) + ' (граница ' + граница + '): ' + с.trim());
            }
            if (глубина === 0) вМедиа = false;
        }
    });
    правило(
        'раздел рейтинга не стоит ни на одной границе ширины',
        найдено.length === 0,
        'На шкале проекта границ две — 640 и 992. Раздел держался на\n' +
        'четырёх (340 · 414 · 430 · 500), и каждая задавала свой набор\n' +
        'чисел. Найдено сейчас: ' + найдено.length + '\n' + найдено.slice(0, 6).join('\n'));
})();

/* ── 2. КЕГЕЛЬ СТОИТ НА СТУПЕНИ, А НЕ ТЯНЕТСЯ ── */
(function кегли() {
    /* блоки раздела: от селектора до закрывающей скобки */
    const блоки = [];
    const рег = /(^|\n)([^\n{}]*\.(?:rating-|rp-|rf-|rr-|rt-col-)[^\n{}]*)\{([^}]*)\}/g;
    let м;
    while ((м = рег.exec(стили)) !== null) блоки.push({ селектор: м[2].trim(), тело: м[3] });

    const тянутся = [], мимо = [];
    блоки.forEach(function (б) {
        const кег = б.тело.match(/font-size:\s*([^;]+);/g) || [];
        кег.forEach(function (з) {
            if (/clamp\(/.test(з)) { тянутся.push(б.селектор + ' → ' + з.trim()); return; }
            if (/var\(--fs-/.test(з)) return;            /* токен шкалы */
            const пикс = (з.match(/(\d+(?:\.\d+)?)px/g) || []).map(parseFloat);
            пикс.forEach(function (v) {
                if (!ШКАЛА_КЕГЕЛЬ.includes(v)) мимо.push(б.селектор + ' → ' + v);
            });
        });
    });
    правило(
        'кегель раздела не тянется по ширине',
        тянутся.length === 0,
        'ТЯНУЩИЙСЯ КЕГЕЛЬ — ЭТО КЕГЕЛЬ МИМО ШКАЛЫ: на промежуточной ширине\n' +
        '`clamp` даёт дробь (на 375 выходило 12.2, 15.6, 19.2).\n' +
        'Найдено: ' + тянутся.slice(0, 5).join('; '));
    правило(
        'каждый кегель раздела — ступень шкалы',
        мимо.length === 0,
        'Шкала кеглей: ' + ШКАЛА_КЕГЕЛЬ.join(' · ') + '.\n' +
        'Мимо неё: ' + мимо.slice(0, 8).join('; '));
})();

/* ── 3. ОТСТУПЫ И РАЗМЕРЫ РАЗДЕЛА — СО ШКАЛЫ ── */
(function otstupy() {
    const блоки = [];
    const рег = /(^|\n)([^\n{}]*\.(?:rating-|rp-|rf-|rr-|rt-col-)[^\n{}]*)\{([^}]*)\}/g;
    let м;
    while ((м = рег.exec(стили)) !== null) блоки.push({ селектор: м[2].trim(), тело: м[3] });

    const мимоОтступ = [], мимоРазмер = [];
    блоки.forEach(function (б) {
        (б.тело.match(/(?:^|\n)\s*(?:margin|padding|gap|row-gap|column-gap)(?:-(?:top|right|bottom|left))?:\s*([^;]+);/g) || [])
            .forEach(function (з) {
                if (/var\(--space-/.test(з) || /calc\(/.test(з)) return;
                (з.match(/(\d+(?:\.\d+)?)px/g) || []).map(parseFloat).forEach(function (v) {
                    if (!отступНаСетке(v)) мимоОтступ.push(б.селектор + ' → ' + v);
                });
            });
        (б.тело.match(/(?:^|\n)\s*(?:width|height|min-height|max-width):\s*([^;]+);/g) || [])
            .forEach(function (з) {
                if (/var\(--|%|calc\(|auto|100/.test(з)) return;
                (з.match(/(\d+(?:\.\d+)?)px/g) || []).map(parseFloat).forEach(function (v) {
                    if (!размерНаСетке(v)) мимоРазмер.push(б.селектор + ' → ' + v);
                });
            });
    });
    правило(
        'каждый отступ раздела — ступень шкалы',
        мимоОтступ.length === 0,
        'Шкала отступов: 8 · 12 · 16 · 24 · 32 · 40 (через `--space-*`).\n' +
        'Мимо неё: ' + мимоОтступ.slice(0, 8).join('; '));
    правило(
        'каждый размер раздела — ступень шкалы',
        мимоРазмер.length === 0,
        'Размер обязан стоять на сетке: ступень кнопок 28 · 36 · 44 · 52,\n' +
        'ступень кеглей (иконки) или кратное восьми.\n' +
        'Мимо неё: ' + мимоРазмер.slice(0, 8).join('; '));
})();

/* ── 4. ШИРИНА СТОЛБЦА ОПРЕДЕЛЕНА ОДИН РАЗ ── */
правило(
    'столбцы таблицы объявлены переменными на одном узле',
    /\.rating-table\s*\{[\s\S]{0,600}?--rt-mesto:[\s\S]{0,200}?--rt-ochki:[\s\S]{0,200}?--rt-ntrp:[\s\S]{0,200}?--rt-wl:/.test(стили),
    'Ширины столбцов обязаны жить переменными на `.rating-table`.');

['mesto', 'ochki', 'ntrp', 'wl'].forEach(function (имя) {
    const зовы = (стили.match(new RegExp('width:\\s*var\\(--rt-' + имя + '\\)', 'g')) || []).length;
    правило(
        'столбец «' + имя + '» берётся из одного определения шапкой и строкой',
        зовы === 2,
        'Шапка и строка обязаны звать `var(--rt-' + имя + ')` — ровно два\n' +
        'зова. Сейчас: ' + зовы + '. Столбец очков уже один раз разошёлся:\n' +
        'шапка 48, строка 50, и заголовок стоял не над числом.');
});

/* ── 5. ЦЕЛИ НАЖАТИЯ И ФОКУС ── */
[['.rf-select', 'выпадашка'], ['.rating-toggle-btn', 'переключатель'],
 ['.rr-more-btn', 'кнопка «ещё»'], ['.rr-guest-btn', 'кнопка гостя']].forEach(function (п) {
    const сел = п[0].replace('.', '\\.');
    const блок = стили.match(new RegExp(сел + '\\s*\\{[^}]*\\}'));
    правило(
        'цель нажатия: ' + п[1] + ' не ниже 44',
        !!блок && /min-height:\s*44px/.test(блок[0]),
        'У `' + п[0] + '` обязан стоять `min-height: 44px`. Было 33 у\n' +
        'выпадашки и 41 у остальных трёх.');
    правило(
        'видимый фокус: ' + п[1],
        new RegExp(сел + ':focus-visible').test(стили),
        'У `' + п[0] + '` обязан быть `:focus-visible` — с клавиатуры\n' +
        'и с голосового управления иначе не видно, где стоишь.');
});

/* ── 6. ИМЯ ОБРЕЗАЕТСЯ, А НЕ МЕЛЬЧАЕТ ── */
правило(
    'имя в таблице обрезается многоточием',
    /\.rr-name\s*\{[\s\S]{0,400}?text-overflow:\s*ellipsis/.test(стили) &&
    /\.rr-name\s*\{[\s\S]{0,400}?overflow:\s*hidden/.test(стили),
    'Раз кегель не мельчает на узком виде, имя обязано обрезаться:\n' +
    '`overflow: hidden` и `text-overflow: ellipsis`. Иначе оно наезжает\n' +
    'на столбец очков.');

правило(
    'ячейка игрока умеет сжиматься',
    /\.rr-player\s*\{[\s\S]{0,300}?min-width:\s*0/.test(стили),
    'Без `min-width: 0` у `.rr-player` обрезка не срабатывает вовсе:\n' +
    'flex-ячейка не даёт себя сузить ниже содержимого.');

/* ── 7. ПЬЕДЕСТАЛ ДЕЛИТ ПОЛОСУ, А НЕ МЕНЯЕТ ШИРИНУ ПО ГРАНИЦАМ ── */
правило(
    'карточки пьедестала делят полосу',
    /\.rp-card\s*\{[\s\S]{0,400}?flex:\s*1 1 0/.test(стили),
    'Было четыре фиксированные ширины под четыре границы. Карточки\n' +
    'обязаны делить полосу (`flex: 1 1 0`) с пределом сверху.');

правило(
    'фото первого больше остальных на одну ступень',
    /\.rp-photo-wrap\s*\{[\s\S]{0,300}?width:\s*52px/.test(стили) &&
    /\.rp-first \.rp-photo-wrap\s*\{[\s\S]{0,400}?width:\s*64px/.test(стили),
    'ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ: фото первого = фото остальных плюс одна\n' +
    'ступень отступов (52 + 12 = 64), а не два отдельных числа.');

/* ── 7б. ПЕРЕКЛЮЧАТЕЛЬ ПОЛА ТИШЕ ВЫПАДАШКИ РАЗРЯДА ──
   МОЁ ПРЕЖНЕЕ ПРАВИЛО ЗДЕСЬ БЫЛО НЕВЕРНЫМ, и его отменил Костя, глядя
   на экран: «они большие, и глаза сразу идут туда — это не самое
   главное на странице». Я свёл выпадашку и переключатель как ПАРУ —
   одна ступень, одна полоса. Они не пара: разряд это главный фильтр,
   пол — уточнение к нему. Равный вес у неравных по смыслу полос и
   уводил глаз: залитая лаймом полоса весила 171×44 сплошного акцента.
   ЦИФРЫ МОГУТ СОЙТИСЬ, А ИЕРАРХИЯ БЫТЬ НЕВЕРНОЙ. */
(function tishe() {
    const выб = (стили.match(/\.rf-select\s*\{[^}]*\}/) || [''])[0];
    const пер = (стили.match(/\.rating-toggle-btn\s*\{[^}]*\}/) || [''])[0];
    const безСлов = с => с.replace(/\/\*[\s\S]*?\*\//g, '');
    function кегль(б) {
        const м = безСлов(б).match(/font-size:\s*([^;]+);/);
        if (!м) return 0;
        const з = м[1].trim();
        if (/--fs-2xs/.test(з)) return 11;
        if (/--fs-xs/.test(з)) return 12;
        const п = з.match(/(\d+(?:\.\d+)?)px/);
        return п ? parseFloat(п[1]) : 0;
    }
    правило(
        'переключатель пола мельче выпадашки разряда',
        кегль(пер) > 0 && кегль(выб) > 0 && кегль(пер) < кегль(выб),
        'Разряд — главный фильтр, пол — уточнение к нему. Кегль уточнения\n' +
        'обязан стоять НИЖЕ ступенью. Сейчас: выпадашка ' + кегль(выб) +
        ', переключатель ' + кегль(пер) + '.');
    правило(
        'переключатель пола не занимает всю полосу',
        /flex:\s*0 0 auto/.test(безСлов(пер)) && !/flex:\s*1[;\s]/.test(безСлов(пер)),
        'Переключатель сжимается по содержимому и стоит по центру\n' +
        '(`flex: 0 0 auto`). Во всю полосу он весил 343×44 и забирал глаз\n' +
        'у пьедестала и таблицы — того, ради чего страницу и открывают.');
    правило(
        'тише — значит уже и мельче, а не ниже ростом',
        /min-height:\s*44px/.test(безСлов(пер)),
        'Приглушение не трогает цель нажатия: высота остаётся 44.');
})();

/* ── 7в. НИ ОДНОГО ЗАШИТОГО СТИЛЯ В РАЗМЕТКЕ РАЗДЕЛА ── */
(function razmetka() {
    const разметка = чит('mobile/www/index.html');
    const найдено = (разметка.match(/class="(?:rf-row|rf-col|rf-label|rating-[a-z-]+|rp-[a-z-]+|rr-[a-z-]+)[^"]*"\s+style="/g) || []);
    правило(
        'в разметке раздела нет зашитых стилей',
        найдено.length === 0,
        'Ширина колонки фильтра стояла зашитым `style="max-width:280px"` в\n' +
        '`mobile/www/index.html`: число мимо шкалы, мимо файла стилей и\n' +
        'мимо всякой проверки. Из-за него выпадашка была уже переключателя.\n' +
        'Найдено: ' + найдено.slice(0, 4).join(' | '));
})();

/* ── 8. ДОСТУПНОСТЬ ── */
правило(
    'таблица представляется диктору таблицей',
    /role="table"/.test(экран) && /role="columnheader"/.test(экран) &&
    /role="row"/.test(экран) && /role="cell"/.test(экран),
    'Таблица собрана на div-ах: без ролей диктор читает пять столбцов\n' +
    'одной строкой без имён. Было ноль aria-атрибутов на весь экран.');

правило(
    'пьедестал представляется диктору списком',
    /role="list"/.test(экран) && /role="listitem"/.test(экран),
    'Пьедестал обязан быть списком с подписью у каждого места.');

правило(
    'медаль и аватар от диктора скрыты',
    /class="rp-medal" aria-hidden="true"/.test(экран) &&
    /class="rr-avatar" aria-hidden="true"/.test(экран),
    'Значок места и кружок инициалов — картинки смысла, который уже\n' +
    'сказан словами. Диктору они не читаются.');

правило(
    'подписи для диктора заведены на трёх языках',
    ['rating.tableLabel', 'rating.podiumLabel', 'rating.wlLabel'].every(function (к) {
        const м = словарь.match(new RegExp("'" + к.replace('.', '\\.') + "':\\s*\\{([^}]*)\\}"));
        return !!м && /ru:/.test(м[1]) && /en:/.test(м[1]) && /kg:/.test(м[1]);
    }),
    'Столбцы «#» и «В/П» прочитать вслух нельзя, таблица и пьедестал без\n' +
    'имени читаются как сплошной текст. Все три подписи обязаны быть на\n' +
    'трёх языках сразу: ключ в одном языке — это ключ, которого нет.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      раздел рейтинга приложения: все ' + держится + ' правил держатся');
    console.log('          одна лестница на всех видах, ни одной границы ширины\n');
}
