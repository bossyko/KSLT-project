/**
 * ЗАМОРОЗКА КУСКА 126 — ВСЕ ОКНА АДМИНКИ ЖИВУТ В ОДНОЙ ОБОЛОЧКЕ.
 *
 * Общая оболочка есть с 04.10, и вход `сырое` сделан ровно для
 * рукодельных окон. Но её признак знал ОДНО имя окна —
 * `.ad-confirm-modal`, — а рукодельные зовут своё `.ad-modal`, окно
 * кадрирования — `.ad-crop-modal`. Оболочка их не находила вовсе:
 * `role`, подпись диктору и фокус до них не доезжали.
 * ПРИЗНАК, ЗНАЮЩИЙ ОДНО ИМЯ, СТОРОЖИТ ОДНО СЕМЕЙСТВО.
 *
 * Замерено на боевой 22.10, окно «Детали скидки»: `role` нет,
 * `aria-modal` нет, фокус остаётся на `body`, Esc не закрывает, фокус
 * звавшему не возвращается, закрывашка 20×26 при норме цели 44 и без
 * подписи — диктор читает «✕». Закрывашек таких ДВЕНАДЦАТЬ.
 *
 * После перевода (замерено на стенде той же разметкой): role=dialog,
 * aria-modal=true, подпись на своём заголовке, фокус внутрь, Esc
 * закрывает, фокус вернулся звавшей кнопке, слой нажатия 44×44.
 * Вид не изменился ни на пиксель: закрывашка те же 20×26.
 *
 *   node tools/check-okna-odna-obolochka.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const УТИЛ = чит('js/admin/core/utils.js');
const AD = чит('css/admin.css');

function файлыАдминки(дир, сп) {
    fs.readdirSync(path.join(КОРЕНЬ, дир), { withFileTypes: true }).forEach(э => {
        if (э.isDirectory()) файлыАдминки(path.join(дир, э.name), сп);
        else if (э.name.endsWith('.js')) сп.push([path.join(дир, э.name), чит(path.join(дир, э.name))]);
    });
    return сп;
}
const ФАЙЛЫ = файлыАдминки('js/admin', []);

/* ── 1. НИ ОДНО ОКНО НЕ ВСТАЁТ В СТРАНИЦУ МИМО ОБОЛОЧКИ ───────────────── */
const мимо = [];
ФАЙЛЫ.forEach(([имя, текст]) => {
    if (имя.indexOf('utils.js') !== -1) return;   // сама оболочка и вставляет
    const n = (текст.match(/document\.body\.(appendChild\(overlay\)|insertAdjacentHTML)/g) || []).length;
    if (n) мимо.push(имя + ' — ' + n);
});
правило('ни одно окно админки не встаёт в страницу мимо оболочки',
    мимо.length === 0,
    'Окна вставляют себя сами: ' + мимо.join(', ') + '.\n' +
    'Такое окно не получает ни `role`, ни фокуса, ни ловушки Tab, ни Esc, ни\n' +
    'возврата фокуса звавшему — и отличить это от решения нельзя ничем,\n' +
    'кроме замера. Оболочка принимает готовый узел входом `узел`.');

/* ── 2. ПРИЗНАК ОКНА ЗНАЕТ ВСЕ ТРИ СЕМЕЙСТВА ──────────────────────────── */
правило('оболочка узнаёт окно всех трёх семейств',
    /querySelector\('\.ad-confirm-modal, \.ad-modal, \.ad-crop-modal'\)/.test(УТИЛ),
    'Признак окна сузился. Семейств в админке три: `.ad-confirm-modal` у самой\n' +
    'оболочки, `.ad-modal` у четырнадцати рукодельных, `.ad-crop-modal` у\n' +
    'кадрирования обложки. Выпавшее семейство перестанет получать `role`,\n' +
    'подпись и фокус — молча, как и было до 22.10.');

правило('оболочка сносит подложку любого семейства — одно окно за раз',
    /querySelectorAll\('\.ad-confirm-overlay, \.ad-modal-overlay'\)/.test(УТИЛ),
    'Снос чужой подложки убран. Пока сносилось только своё семейство,\n' +
    'рукодельное окно оставалось стоять ПОД новым: закрываешь верхнее, а под\n' +
    'ним такое же.');

правило('готовый узел принимается, а его класс добавляется, а не заменяет',
    /var overlay = о\.узел \|\| document\.createElement\('div'\);/.test(УТИЛ) &&
    /overlay\.classList\.add\('ad-confirm-overlay'\)/.test(УТИЛ),
    'Вход `узел` пропал или класс снова ставится присвоением. На\n' +
    '`.ad-modal-overlay` держится ВСЯ вёрстка рукодельных окон: заменить\n' +
    'класс значит раздеть окно.');

правило('слушатель клавиш снимает себя, если окно закрыли мимо оболочки',
    /if \(!overlay\.isConnected\)/.test(УТИЛ),
    'Снята защита от закрытия мимо оболочки. Рукодельные окна закрывают себя\n' +
    'своим же `overlay.remove()`, оболочка об этом не узнаёт — и её слушатель\n' +
    'остался бы на `document` навсегда, перехватывая Esc у следующего окна.');

/* ── 3. ЗАКРЫВАШКА: ЦЕЛЬ НАЖАТИЯ И ПОДПИСЬ ───────────────────────────── */
const закрывашки = [];
ФАЙЛЫ.forEach(([имя, текст]) => {
    (текст.match(/<button[^>]*ad-modal-close[^>]*>/g) || []).forEach(т => закрывашки.push([имя, т]));
});
правило('закрывашки окон найдены, и их 12',
    закрывашки.length === 12,
    'Закрывашек `.ad-modal-close`: ' + закрывашки.length + ', а замерено 12.\n' +
    'ПРОВЕРКА, КОТОРАЯ ИЩЕТ В ПУСТОМ, ЗЕЛЕНЕЕТ ВСЕГДА.');

const безПодписи = закрывашки.filter(([, т]) => т.indexOf('aria-label') === -1);
правило('у каждой закрывашки окна есть доступное имя',
    безПодписи.length === 0,
    'Без подписи осталось ' + безПодписи.length + ':\n' +
    безПодписи.map(([и, т]) => '  ' + и + ': ' + т.slice(0, 80)).join('\n') + '\n' +
    'Диктор прочитает знак «✕» и ничего больше.');

const блокЗакр = (function () {
    const i = AD.indexOf('.ad-modal-close::before {');
    return i === -1 ? '' : AD.slice(i, AD.indexOf('}', i) + 1);
})();
правило('у закрывашки окна есть прозрачный слой нажатия 44',
    /width:\s*var\(--btn-h-md\)/.test(блокЗакр) && /height:\s*var\(--btn-h-md\)/.test(блокЗакр) &&
    /position:\s*absolute/.test(блокЗакр),
    'Слой нажатия закрывашки пропал или сменил размер. Своего размера у неё\n' +
    'нет вовсе — прямоугольник равен кеглю текста, замерено 20×26 при норме\n' +
    '44. Эталон слоя — `.ad-bulk-item::before`, решение 04.10.');

правило('закрывашка осталась опорой для своего слоя',
    /\.ad-modal-close \{[^}]*position:\s*relative/.test(AD),
    'У `.ad-modal-close` снят `position: relative` — слой уедет к ближайшему\n' +
    'позиционированному предку, и цель нажатия окажется не над кнопкой.');

/* ── вывод ───────────────────────────────────────────────────────────── */
console.log('');
if (ошибки.length) {
    console.log('  НЕ ТАК  окна в одной оболочке — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(([и, п]) => console.log('          ✗ ' + и + '\n            ' + п.replace(/\n/g, '\n            ') + '\n'));
    process.exit(1);
}
console.log('  ок      окна в одной оболочке: 9 правил');
console.log('          мимо оболочки не встаёт ни одно, признак знает три семейства');
console.log('          12 закрывашек подписаны, цель нажатия 44 слоем');
console.log('');
