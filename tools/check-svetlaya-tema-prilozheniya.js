#!/usr/bin/env node
/**
 * СВЕТЛАЯ ТЕМА ПРИЛОЖЕНИЯ — ЗАМОРОЗКА КУСКА 207 (27.10).
 *
 * ЧТО БЫЛО. Замер контраста по всем одиннадцати экранам в светлой теме:
 * 98 мест ниже планки WCAG из 539 проверенных узлов, на девяти экранах.
 * Корней три, и все три — «одно понятие определено дважды»:
 *
 *   1. `--text-primary` НЕ переопределялся в блоке светлой темы и оставался
 *      белым из `css/tokens.css` — 20 мест стоят на нём, и это был белый
 *      текст на белой карточке. Замерено: `.rr-ntrp` 1.00, `.hb-badge-name`
 *      1.00. `--text` и `--text-primary` — одно понятие под двумя именами.
 *   2. Акцент как ЗАЛИВКА и акцент как ЦВЕТ ТЕКСТА были одним именем.
 *      Лайм `#4A8C00` как текст даёт 4.16 на белой карточке и 3.58 на фоне
 *      экрана — ниже 4.5; таких мест 99.
 *   3. Переопределение `[data-theme="light"] … { color: #fff }` ставило
 *      белый текст на лаймовую кнопку: 4.16. Чёрный на том же лайме даёт
 *      5.04. ПРАВКА, ВНЕСЁННАЯ РАДИ СВЕТЛОЙ ТЕМЫ, И БЫЛА ЕЁ БЕДОЙ.
 *   Плюс светлая тема ослабляла плашку бейджа с 0.6 (`--alpha-black-60` в
 *   tokens) до 0.5 — ровно на этом бейдж на картинке и перестал читаться.
 *
 * ПОСЛЕ: светлая тема 98 → 0, тёмная 0 → 0 (вид тёмной не изменился).
 *
 * ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ, А НЕ ЧИСЛО: акцентный текст в светлой теме
 * ТЕМНЕЕ заливочного акцента, а не «равен #3D7500».
 *
 * Запуск: node tools/check-svetlaya-tema-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}

function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const стили = чит('mobile/www/css/app.css');
const токены = чит('mobile/www/css/tokens.css');
const баттлы = чит('mobile/www/js/screens/battles.js');

/* Блок светлой темы — от объявления до закрывающей скобки */
const светлаяОт = стили.indexOf('[data-theme="light"] {');
const светлая = светлаяОт >= 0
    ? стили.slice(светлаяОт, стили.indexOf('\n}', светлаяОт) + 2)
    : '';

/* ── 1. У СВЕТЛОЙ ТЕМЫ ЕСТЬ СВОЙ ОСНОВНОЙ ЦВЕТ ТЕКСТА ── */
правило(
    'светлая тема задаёт свой основной цвет текста',
    /--text-primary:\s*[^;]+;/.test(светлая),
    'Блок `[data-theme="light"]` в `mobile/www/css/app.css` обязан задать\n' +
    '`--text-primary`. Без этого он берётся из `tokens.css` белым, и всё,\n' +
    'что на нём стоит, в светлой теме становится белым на белом.');

правило(
    'основной цвет текста светлой темы не белый',
    !/--text-primary:\s*(#fff(f{3})?|#FFF(F{3})?|white|var\(--neutral-white\)|rgb\(255,\s*255,\s*255\))\s*;/.test(светлая),
    '`--text-primary` в светлой теме не может быть белым: фон карточек в ней\n' +
    'тоже белый (`--bg-card: #FFFFFF`).');

/* ── 2. АКЦЕНТ-ТЕКСТ И АКЦЕНТ-ЗАЛИВКА РАЗВЕДЕНЫ ── */
правило(
    'акцентный текст имеет своё имя',
    /--accent-text:\s*var\(--accent\)\s*;/.test(токены),
    'По умолчанию (тёмная тема) `--accent-text` равен `--accent`: лайм на\n' +
    'чёрном читается. Имя обязано быть объявлено в `tokens.css` — туда оно\n' +
    'переехало 02.11, потому что его зовут общие компоненты обоих\n' +
    'продуктов (`.kslt-cc`, `.kslt-dd`), а на сайте оно было пустым.');

правило(
    'в светлой теме акцентный текст НЕ равен заливочному акценту',
    /--accent-text:\s*[^;]+;/.test(светлая) &&
    !/--accent-text:\s*var\(--accent\)\s*;/.test(светлая),
    'Светлая тема обязана задать `--accent-text` СВОИМ значением, темнее\n' +
    'заливочного акцента. Если он равен `var(--accent)`, возвращается\n' +
    'ровно та беда, из которой кусок и вырос.');

правило(
    'цвет текста нигде не идёт через заливочный акцент',
    !/(?<![-\w])color:\s*var\(--accent\)\s*[;}]/.test(стили),
    'Ни одно объявление `color` не может ссылаться на `--accent` — только\n' +
    'на `--accent-text`. Заливки (`background`, `border-color`) на\n' +
    '`--accent` остаются: там он верен.');

/* ── 3. СВЕТЛАЯ ТЕМА НЕ СТАВИТ БЕЛЫЙ ТЕКСТ НА АКЦЕНТНУЮ ЗАЛИВКУ ── */
правило(
    'светлая тема не перекрашивает заполненные кнопки в белый',
    !/\[data-theme="light"\][^{]*\.btn-accent[\s\S]{0,400}?color:\s*#fff/.test(стили),
    'Переопределение `[data-theme="light"] .btn-accent … { color: #fff }`\n' +
    'опускало контраст до 4.16. Чёрный на том же лайме даёт 5.04 —\n' +
    'заполненная кнопка носит в светлой теме тот же чёрный текст, что и в\n' +
    'тёмной.');

/* ── 4. СВЕТЛАЯ ТЕМА НЕ ОСЛАБЛЯЕТ ЗАТЕМНЯЮЩУЮ ПЛАШКУ ── */
правило(
    'плашка бейджа определена один раз — в токенах',
    /--badge-overlay:/.test(токены) && !/--badge-overlay:/.test(стили),
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: плашка живёт в `tokens.css`\n' +
    '(`--alpha-black-60`). Светлая тема ослабляла её до 0.5, и бейдж на\n' +
    'картинке перестал читаться: при самой светлой картинке под плашкой\n' +
    '0.5 ярко-лаймовый текст даёт 3.38, под 0.6 — 4.89.');

правило(
    'текст бейджа на картинке не зависит от темы',
    /\.tcv-badge\s*\{[\s\S]{0,300}?color:\s*var\(--lime-500\)/.test(стили),
    'Бейдж лежит на СВОЕЙ затемняющей плашке поверх картинки, а не на фоне\n' +
    'темы, поэтому цвет его текста от темы не зависит и берётся прямо из\n' +
    'шкалы лайма (`--lime-500`). Тёмно-зелёный акцентный текст давал там\n' +
    '1.38.');

/* ── 5. ДВА МЕСТА, ГДЕ БЕЛЫЙ БЫЛ ЗАШИТ ПО ОШИБКЕ ── */
правило(
    'имя на пьедестале идёт через токен',
    /\.rp-name\s*\{[\s\S]{0,200}?color:\s*var\(--text-primary\)/.test(стили),
    '`.rp-name` носил зашитый `color: #fff` — в светлой теме контраст 1.16.');

правило(
    'выпадашка рейтинга идёт через токен',
    !/background:\s*var\(--glass\);\s*\n\s*color:\s*#fff/.test(стили),
    '`.rf-select` стоит на `var(--glass)`, который в светлой теме почти\n' +
    'белый; зашитый белый текст давал 1.27.');

/* ── 6. ЗАПРОС БАТТЛОВ НЕ ТЯНЕТ СВЯЗЕЙ, КОТОРЫХ В БАЗЕ НЕТ ── */
правило(
    'запрос баттлов не тянет связи на партнёров',
    /* Признак берёт ЗОВ, а не упоминание: имя связи встречается и в
       объяснении внутри файла. Иголка собрана из частей, чтобы правило
       не ловило ни себя, ни чужой комментарий. */
    !new RegExp('players' + '!' + 'challenges_(challenger|opponent)_partner_id_fkey').test(баттлы),
    'Экран баттлов приложения просил `challenges_challenger_partner_id_fkey`\n' +
    'и `challenges_opponent_partner_id_fkey`. Таких внешних ключей в базе\n' +
    'НЕТ — проверено чтением базы по одной связи. Весь запрос падал 400, а\n' +
    '`catch` молча показывал пустой список: экран не работал никогда.\n' +
    'Имя, фото и страна партнёра лежат в самой таблице плоскими полями.');

правило(
    'отрисовка баттлов берёт плоские поля партнёра',
    /challenger_partner_name/.test(баттлы) && /opponent_partner_name/.test(баттлы),
    'Раз связей нет, отрисовка обязана читать плоские поля\n' +
    '`challenger_partner_name` и `opponent_partner_name` из самой таблицы.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      светлая тема приложения: все ' + держится + ' правил держатся');
    console.log('          98 мест ниже планки WCAG сведены к нулю, тёмная тема не задета\n');
}
