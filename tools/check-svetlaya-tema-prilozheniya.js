#!/usr/bin/env node
/**
 * СВЕТЛАЯ ТЕМА ПРИЛОЖЕНИЯ — ЗАМОРОЗКА КУСКА 207 (27.10).
 *
 * ЧТО БЫЛО. Замер контраста по всем одиннадцати экранам в светлой теме:
 * 98 мест ниже планки WCAG из 539 проверенных узлов, на девяти экранах.
 * Корней три, и все три — «одно понятие определено дважды»:
 *
 *   1. `--text-primary` НЕ переопределялся в блоке светлой темы и оставался
 *      белым из `css/tokens.css` — 20 мест стоят на нём, и это был белый
 *      текст на белой карточке. Замерено: `.rr-ntrp` 1.00, `.hb-badge-name`
 *      1.00. `--text` и `--text-primary` — одно понятие под двумя именами.
 *   2. Акцент как ЗАЛИВКА и акцент как ЦВЕТ ТЕКСТА были одним именем.
 *      Лайм `#4A8C00` как текст даёт 4.16 на белой карточке и 3.58 на фоне
 *      экрана — ниже 4.5; таких мест 99.
 *   3. Переопределение `[data-theme="light"] … { color: #fff }` ставило
 *      белый текст на лаймовую кнопку: 4.16. Чёрный на том же лайме даёт
 *      5.04. ПРАВКА, ВНЕСЁННАЯ РАДИ СВЕТЛОЙ ТЕМЫ, И БЫЛА ЕЁ БЕДОЙ.
 *   Плюс светлая тема ослабляла плашку бейджа с 0.6 (`--alpha-black-60` в
 *   tokens) до 0.5 — ровно на этом бейдж на картинке и перестал читаться.
 *
 * ПОСЛЕ: светлая тема 98 → 0, тёмная 0 → 0 (вид тёмной не изменился).
 *
 * ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ, А НЕ ЧИСЛО: акцентный текст в светлой теме
 * ТЕМНЕЕ заливочного акцента, а не «равен #3D7500».
 *
 * Запуск: node tools/check-svetlaya-tema-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}

function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const стили = чит('mobile/www/css/app.css');
const токены = чит('mobile/www/css/tokens.css');
const баттлы = чит('mobile/www/js/screens/battles.js');

/* БЛОК СВЕТЛОЙ ТЕМЫ ПЕРЕЕХАЛ В ТОКЕНЫ (08.11, кусок «светлая тема
   приложения»). Он переопределяет РОЛИ, а роли живут в `tokens.css`:
   ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ — и само понятие, и его вид в каждой
   теме стоят рядом, а не в разных файлах. Прежде блок жил в `app.css`,
   и сторож искал его там; ищем в обоих, чтобы правило держало СМЫСЛ, а
   не место.
   ПРАВИЛО, ПРИВЯЗАННОЕ К ФАЙЛУ, ПАДАЕТ ПРИ ПЕРЕЕЗДЕ — и это падение
   ничего не доказывает. */
function блокТемы(текст) {
    const от = текст.indexOf('[data-theme="light"] {');
    if (от < 0) return '';
    const до = текст.indexOf('\n}', от);
    return до < 0 ? текст.slice(от) : текст.slice(от, до + 2);
}
const светлая = блокТемы(токены) || блокТемы(стили);

/* ── 1. У СВЕТЛОЙ ТЕМЫ ЕСТЬ СВОЙ ОСНОВНОЙ ЦВЕТ ТЕКСТА ── */
правило(
    'светлая тема задаёт свой основной цвет текста',
    /--text-primary:\s*[^;]+;/.test(светлая),
    'Блок `[data-theme="light"]` (с 08.11 живёт в `mobile/www/css/tokens.css`)\n' +
    'обязан задать\n' +
    '`--text-primary`. Без этого он берётся из `tokens.css` белым, и всё,\n' +
    'что на нём стоит, в светлой теме становится белым на белом.');

правило(
    'основной цвет текста светлой темы не белый',
    !/--text-primary:\s*(#fff(f{3})?|#FFF(F{3})?|white|var\(--neutral-white\)|rgb\(255,\s*255,\s*255\))\s*;/.test(светлая),
    '`--text-primary` в светлой теме не может быть белым: фон карточек в ней\n' +
    'тоже белый (`--bg-card: #FFFFFF`).');

/* ── 2. АКЦЕНТ-ТЕКСТ И АКЦЕНТ-ЗАЛИВКА РАЗВЕДЕНЫ ── */
правило(
    'акцентный текст имеет своё имя',
    /--accent-text:\s*var\(--accent\)\s*;/.test(токены),
    'По умолчанию (тёмная тема) `--accent-text` равен `--accent`: лайм на\n' +
    'чёрном читается. Имя обязано быть объявлено в `tokens.css` — туда оно\n' +
    'переехало 02.11, потому что его зовут общие компоненты обоих\n' +
    'продуктов (`.kslt-cc`, `.kslt-dd`), а на сайте оно было пустым.');

правило(
    'в светлой теме акцентный текст НЕ равен заливочному акценту',
    /--accent-text:\s*[^;]+;/.test(светлая) &&
    !/--accent-text:\s*var\(--accent\)\s*;/.test(светлая),
    'Светлая тема обязана задать `--accent-text` СВОИМ значением, темнее\n' +
    'заливочного акцента. Если он равен `var(--accent)`, возвращается\n' +
    'ровно та беда, из которой кусок и вырос.');

правило(
    'цвет текста нигде не идёт через заливочный акцент',
    !/(?<![-\w])color:\s*var\(--accent\)\s*[;}]/.test(стили),
    'Ни одно объявление `color` не может ссылаться на `--accent` — только\n' +
    'на `--accent-text`. Заливки (`background`, `border-color`) на\n' +
    '`--accent` остаются: там он верен.');

/* ── 3. СВЕТЛАЯ ТЕМА НЕ СТАВИТ БЕЛЫЙ ТЕКСТ НА АКЦЕНТНУЮ ЗАЛИВКУ ── */
правило(
    'светлая тема не перекрашивает заполненные кнопки в белый',
    !/\[data-theme="light"\][^{]*\.btn-accent[\s\S]{0,400}?color:\s*#fff/.test(стили),
    'Переопределение `[data-theme="light"] .btn-accent … { color: #fff }`\n' +
    'опускало контраст до 4.16. Чёрный на том же лайме даёт 5.04 —\n' +
    'заполненная кнопка носит в светлой теме тот же чёрный текст, что и в\n' +
    'тёмной.');

/* ── 4. СВЕТЛАЯ ТЕМА НЕ ОСЛАБЛЯЕТ ЗАТЕМНЯЮЩУЮ ПЛАШКУ ── */
правило(
    'плашка бейджа определена один раз — в токенах',
    /--badge-overlay:/.test(токены) && !/--badge-overlay:/.test(стили),
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: плашка живёт в `tokens.css`\n' +
    '(`--alpha-black-60`). Светлая тема ослабляла её до 0.5, и бейдж на\n' +
    'картинке перестал читаться: при самой светлой картинке под плашкой\n' +
    '0.5 ярко-лаймовый текст даёт 3.38, под 0.6 — 4.89.');

правило(
    'текст бейджа на картинке не зависит от темы',
    /\.tcv-badge\s*\{[\s\S]{0,300}?color:\s*var\(--lime-500\)/.test(стили),
    'Бейдж лежит на СВОЕЙ затемняющей плашке поверх картинки, а не на фоне\n' +
    'темы, поэтому цвет его текста от темы не зависит и берётся прямо из\n' +
    'шкалы лайма (`--lime-500`). Тёмно-зелёный акцентный текст давал там\n' +
    '1.38.');

/* ── 5. ДВА МЕСТА, ГДЕ БЕЛЫЙ БЫЛ ЗАШИТ ПО ОШИБКЕ ── */
правило(
    'имя на пьедестале идёт через токен',
    /\.rp-name\s*\{[\s\S]{0,200}?color:\s*var\(--text-primary\)/.test(стили),
    '`.rp-name` носил зашитый `color: #fff` — в светлой теме контраст 1.16.');

правило(
    'выпадашка рейтинга идёт через токен',
    !/background:\s*var\(--glass\);\s*\n\s*color:\s*#fff/.test(стили),
    '`.rf-select` стоит на `var(--glass)`, который в светлой теме почти\n' +
    'белый; зашитый белый текст давал 1.27.');

/* ══ 7. ПРАВИЛА КУСКА «СВЕТЛАЯ ТЕМА ПРИЛОЖЕНИЯ» (08.11) ══════════════
   Кусок вернул светлую тему после снятия 07.11 и заплатил за это
   четырьмя бедами, каждая из которых ниже держится правилом. */

/* 7.1 КРАСКА ПАЛИТРЫ — НЕ РОЛЬ.
   Первая редакция блока переопределяла `--neutral-white`, и
   `--on-image: var(--neutral-white)` превратился в чернила: белые
   подписи поверх фотографии корта стали чёрными на чёрном. Ровно та
   беда, от которой `--on-image-*` и заведены.
   ПЕРЕОПРЕДЕЛИВ КРАСКУ, ПЕРЕОПРЕДЕЛЯЕШЬ ВСЕХ, КТО НА НЕЙ СТОИТ. */
правило(
    'светлая тема не переопределяет краски палитры',
    !/--neutral-(white|black|\d{3})\s*:/.test(светлая) &&
    !/--alpha-white-\d+\s*:/.test(светлая),
    'В блоке светлой темы нашлась краска палитры (`--neutral-*` или\n' +
    '`--alpha-white-*`). Тема говорит с РОЛЯМИ: краску на себе держат и\n' +
    'те, кому тема не указ — слой поверх фотографии. Переопределив\n' +
    '`--neutral-white`, кусок 08.11 уронил весь заглавный экран.\n' +
    'Исключение одно и названо в самом блоке: шкала `--alpha-lime-*`.');

/* 7.2 СЛОЙ ПОВЕРХ ФОТОГРАФИИ И ПОДЛОЖКИ ОКОН ТЕМЫ НЕ ЗНАЮТ.
   ВУАЛЬ И ПОДЛОЖКА ВЫГЛЯДЯТ ОДИНАКОВО, А ВЕДУТ СЕБЯ ПРОТИВОПОЛОЖНО:
   первая обязана перевернуться, вторая обязана остаться тёмной. */
правило(
    'светлая тема не трогает слой поверх фото и подложки окон',
    !/--on-image[\w-]*\s*:/.test(светлая) &&
    !/--(scrim-dialog|overlay-bg|overlay-modal|onb-bg|modal-bg[\w-]*)\s*:/.test(светлая),
    'В блоке светлой темы нашлась роль слоя поверх фотографии\n' +
    '(`--on-image-*`) или подложки окна (`--scrim-dialog`, `--overlay-bg`,\n' +
    '`--onb-bg`, `--modal-bg*`). Подложка лежит МЕЖДУ экраном и окном и\n' +
    'затемняет светлый экран ровно так же, как тёмный; слой поверх фото\n' +
    'имеет свою подложку — фотографию. Обоим тема не указ.');

/* 7.3 ЛАЙМ КАК ЛИНИЯ — ЭТО `--accent-text`, А НЕ `--accent`.
   Замер 08.11: 65 мест писали лаймом обводку, штрих или буквы, и среди
   них 25 обводок фокуса. На белом лайм даёт 1.18 — человек с
   клавиатурой не видел бы, где стоит. */
правило(
    'лайм не пишется линией и буквами мимо акцентного текста',
    (() => {
        const ЛИНИЯ = /\b(color|border|border-color|border-top-color|border-bottom-color|border-left-color|border-right-color|outline|outline-color|fill|stroke)(\s*:\s*[^;{}]*?)var\(--accent\)/g;
        const погашен = стили.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));
        let б, лишних = 0;
        const БЛОК = /\{[^{}]*\}/g;
        while ((б = БЛОК.exec(погашен)) !== null) {
            /* Линия ПО лаймовой заливке остаётся лаймовой — законно. */
            if (/background(-color)?:\s*[^;]*var\(--accent\)/.test(б[0])) continue;
            ЛИНИЯ.lastIndex = 0;
            while (ЛИНИЯ.exec(б[0]) !== null) лишних++;
        }
        return лишних === 0;
    })(),
    'Лайм (`--accent`) стоит обводкой, штрихом или цветом букв там, где\n' +
    'под ним НЕТ лаймовой заливки. В светлой теме это 1.18 на белом —\n' +
    'невидимо. Такие места пишутся `--accent-text` (#446000, 7.19).\n' +
    'Линия ПО лаймовой заливке — исключение и остаётся лаймом.');

/* 7.4 КРАСКА, СПРЯТАННАЯ В КАРТИНКЕ, ТЕМЕ НЕ ПОДЧИНЯЕТСЯ.
   Логотип — `.svg` с зашитыми `fill`, и ни один прибор, читающий css,
   его не видел: беду поймали глаза на первом снимке. */
правило(
    'у логотипа есть светлая редакция, и она отличается ровно красками',
    (() => {
        const тёмный = чит('mobile/www/img/kslt-logo.svg');
        const светлый = чит('mobile/www/img/kslt-logo-light.svg');
        if (!тёмный || !светлый) return false;
        /* ОДНО ПОНЯТИЕ В ДВУХ ПРЕДСТАВЛЕНИЯХ: светлая редакция обязана
           быть тёмной с заменой ровно двух красок — иначе знаки
           разойдутся рисунком, и этого никто не заметит. */
        /* ЗНАК ОСТАЁТСЯ ЗНАКОМ. Слово Кости 08.11: «цвет логотипа
           человечка не лаймовый, а тёмно-зелёный какой-то». И он прав
           не только на глаз: WCAG 1.4.3 прямо выводит логотипы и
           названия брендов из-под требования контраста — знак узнают,
           а не читают. Темнеют только БУКВЫ, которые читают; фигурка
           игрока остаётся фирменным лаймом в обеих редакциях.
           ПЛАНКА ЧИТАЕМОСТИ — ДЛЯ ТОГО, ЧТО ЧИТАЮТ. */
        const из = тёмный.replace(/fill="white"/g, 'fill="#111111"');
        return из === светлый && /fill="#CCFF00"/.test(светлый);
    })(),
    'Светлая редакция логотипа (`img/kslt-logo-light.svg`) отсутствует или\n' +
    'разошлась с тёмной не только красками. Она обязана получаться из\n' +
    '`img/kslt-logo.svg` заменой ОДНОЙ краски: `fill="white"` на чернила\n' +
    '`#111111`. Фигурка игрока остаётся лаймовой — это знак, а не текст,\n' +
    'и WCAG выводит логотипы из-под требования контраста.\n' +
    'Иначе два знака разъедутся рисунком, и заметит это не сторож, а\n' +
    'человек на экране.');

правило(
    'светлая тема подменяет логотип и снимает его свечение',
    /\[data-theme="light"\][^{]*\.header-logo-img[\s\S]{0,240}?content:\s*url\([^)]*kslt-logo-light\.svg/.test(стили) &&
    /\[data-theme="light"\][\s\S]{0,300}?logo-img[\s\S]{0,160}?filter:\s*none/.test(стили),
    'Светлая тема обязана подменять логотип на светлую редакцию через\n' +
    '`content: url(...)` — одним узлом, а не вторым `<img>`: иначе диктор\n' +
    'читает знак дважды, а Tab останавливается на невидимом. И обязана\n' +
    'снимать лаймовое свечение: на белом оно читается грязным пятном.');

/* 7.5 ВЫБОР ТЕМЫ — СВОЙСТВО ЧЕЛОВЕКА, А НЕ ЭКРАНА. */
правило(
    'у темы три положения, и по умолчанию — система',
    (() => {
        const дом = чит('mobile/www/js/app.js');
        return /ТЕМЫ\s*=\s*\['light',\s*'dark',\s*'system'\]/.test(дом) &&
               /prefers-color-scheme/.test(дом) &&
               /ТЕМЫ\.indexOf\(в\)\s*!==\s*-1\s*\?\s*в\s*:\s*'system'/.test(дом);
    })(),
    'Положений обязано быть три: `light`, `dark` и `system`, и третье —\n' +
    'по умолчанию. Человек ставит ночной режим в телефоне один раз и\n' +
    'ждёт, что приложения ему подчинятся; так устроены Appearance у Apple\n' +
    'и MODE_NIGHT_FOLLOW_SYSTEM у Google.\n' +
    'ХРАНИМ ВЫБОР, А НЕ ИТОГ: записанное `system` обязано остаться\n' +
    '`system`, иначе завтра приложение не пойдёт за телефоном.');

правило(
    'приложение слушает смену системной темы на ходу',
    (() => {
        const дом = чит('mobile/www/js/app.js');
        return /addEventListener\('change'/.test(дом) &&
               /выборТемы\(\)\s*===\s*'system'/.test(дом);
    })(),
    'Человек тянет шторку, включает ночной режим и возвращается в\n' +
    'приложение. Без подписки на `change` оно осталось бы в прежней теме\n' +
    'до перезапуска. Слушать обязано только при выборе `system`: иначе\n' +
    'системный выбор перебивал бы ручной.');

/* ── 6. ЗАПРОС БАТТЛОВ НЕ ТЯНЕТ СВЯЗЕЙ, КОТОРЫХ В БАЗЕ НЕТ ── */
правило(
    'запрос баттлов не тянет связи на партнёров',
    /* Признак берёт ЗОВ, а не упоминание: имя связи встречается и в
       объяснении внутри файла. Иголка собрана из частей, чтобы правило
       не ловило ни себя, ни чужой комментарий. */
    !new RegExp('players' + '!' + 'challenges_(challenger|opponent)_partner_id_fkey').test(баттлы),
    'Экран баттлов приложения просил `challenges_challenger_partner_id_fkey`\n' +
    'и `challenges_opponent_partner_id_fkey`. Таких внешних ключей в базе\n' +
    'НЕТ — проверено чтением базы по одной связи. Весь запрос падал 400, а\n' +
    '`catch` молча показывал пустой список: экран не работал никогда.\n' +
    'Имя, фото и страна партнёра лежат в самой таблице плоскими полями.');

правило(
    'отрисовка баттлов берёт плоские поля партнёра',
    /challenger_partner_name/.test(баттлы) && /opponent_partner_name/.test(баттлы),
    'Раз связей нет, отрисовка обязана читать плоские поля\n' +
    '`challenger_partner_name` и `opponent_partner_name` из самой таблицы.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      светлая тема приложения: все ' + держится + ' правил держатся');
    console.log('          98 мест ниже планки WCAG сведены к нулю, тёмная тема не задета\n');
}
