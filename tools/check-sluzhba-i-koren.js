/**
 * ЗАМОРОЗКА КУСКА 134 — ОФЛАЙН-СЛУЖБА ПОДНИМАЕТСЯ И ЗНАЕТ СВОЙ КОРЕНЬ.
 *
 * ЗАМЕР НА БОЕВОЙ 22.10: служб зарегистрировано НОЛЬ, кэшей НОЛЬ. Офлайн
 * не работал ни разу с момента выкладки, и об этом не знал даже трекер —
 * службу завели и ни разу не разобрали.
 *
 * Две поломки подряд, каждой хватало в одиночку:
 *   1. `js/script.js` просил службу от КОРНЯ ДОМЕНА (`/sw.js`) — на
 *      боевой 404. Ошибку глушил пустой `.catch()`.
 *   2. Семь путей `PRE_CACHE` тоже шли от корня домена. `cache.addAll`
 *      АТОМАРЕН — ПРОВЕРЕНО В БРАУЗЕРЕ, а не взято на веру: один мёртвый
 *      адрес отклоняет весь набор, в кэш не попадает ничего, даже живое.
 *      Значит починка первой поломки в одиночку не дала бы НИЧЕГО.
 *
 * КОРЕНЬ ПРОЕКТА НЕ ВЫЧИСЛЯЕТСЯ ЗАНОВО. На странице его уже объявляет
 * `<link rel="manifest">` (кусок 132, под сторожем); внутри службы он
 * известен из её собственного адреса — она лежит в корне проекта.
 *
 *   node tools/check-sluzhba-i-koren.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const СЛУЖБА = чит('sw.js');
const СКРИПТ = чит('js/script.js');

/* 1-3. РЕГИСТРАЦИЯ ИДЁТ ОТ КОРНЯ ПРОЕКТА */
правило('служба не просится от корня домена',
    !/register\(\s*['"]\//.test(СКРИПТ),
    'Вернулось `register("/sw.js")`. На боевой это `bossyko.github.io/sw.js`\n' +
    'и 404: проект живёт под `/KSLT-project/`. Служба не поднимется, и\n' +
    'ОШИБКУ ПРОГЛОТИТ `.catch()` — как глотал до 22.10.');

правило('адрес службы считается от объявленного корня проекта',
    /link\[rel="manifest"\]/.test(СКРИПТ) &&
    /new URL\('sw\.js', корень\)/.test(СКРИПТ),
    'Адрес службы должен строиться от `<link rel="manifest">` — это\n' +
    'ЕДИНСТВЕННОЕ объявление корня проекта на странице, и оно уже под\n' +
    'сторожем куска 132. Замерено: все 80 страниц, грузящих `script.js`,\n' +
    'манифест имеют.');

правило('служба не просится просто по имени',
    !/register\(\s*['"]sw\.js['"]/.test(СКРИПТ),
    'Простое `register("sw.js")` неверно: со страницы в `pages/` оно даёт\n' +
    '`pages/sw.js`. Область службы — это папка, где она лежит, а GitHub\n' +
    'Pages заголовка `Service-Worker-Allowed` не отдаёт, так что такая\n' +
    'регистрация не покрыла бы сайт даже если бы файл там был.');

/* 4-5. СПИСОК ПРЕДЗАГРУЗКИ И ЕГО ЧИСЛО */
const предзагрузка = (СЛУЖБА.match(/PRE_CACHE\s*=\s*\[([^\]]*)\]/) || [])[1] || '';
const пути = предзагрузка.match(/['"][^'"]+['"]/g) || [];
правило('в списке предзагрузки семь путей, и все относительные',
    пути.length === 7 && !пути.some(п => /^['"]\//.test(п)),
    'Путей в PRE_CACHE: ' + пути.length + ' (замерено 7), абсолютных: ' +
    пути.filter(п => /^['"]\//.test(п)).length + '.\n' +
    '`addAll` АТОМАРЕН: один мёртвый адрес роняет весь набор. Число под\n' +
    'присмотром не ради числа — каждый новый путь это новый способ\n' +
    'уронить установку целиком.');

const файловНет = пути
    .map(п => п.slice(1, -1).split('?')[0])
    .filter(п => !fs.existsSync(path.join(КОРЕНЬ, п)));
правило('каждый путь предзагрузки указывает на существующий файл',
    файловНет.length === 0,
    'Файлов нет: ' + файловНет.join(', ') + '\n' +
    'Это не придирка к опрятности: несуществующий путь в `addAll` роняет\n' +
    'УСТАНОВКУ СЛУЖБЫ ЦЕЛИКОМ, и офлайн перестаёт работать весь.');

/* 6-7. СЛУЖБА ЗНАЕТ СВОЙ КОРЕНЬ И МЕРИТ ПУТИ ОТНОСИТЕЛЬНО НЕГО */
правило('служба берёт корень из своего адреса',
    /new URL\('\.\/', self\.location\.href\)\.pathname/.test(СЛУЖБА),
    'Служба лежит В КОРНЕ ПРОЕКТА — это единственное место, где корень\n' +
    'известен без вычислений и без чужих объявлений. Потеряв его, она\n' +
    'снова начнёт мерить пути от корня домена.');

правило('админка отсекается по пути ОТНОСИТЕЛЬНО корня проекта',
    /url\.pathname\.indexOf\(КОРЕНЬ\) === 0/.test(СЛУЖБА) &&
    /\(\?:\^\|\\\/\)admin/.test(СЛУЖБА),
    'Прежняя проверка искала `/admin` в ПОЛНОМ пути и на боевой\n' +
    'срабатывала случайно — подпапка проекта стоит перед ним. Замерено:\n' +
    'прежняя и новая отсекают ОДНИ И ТЕ ЖЕ 28 файлов, и ни одна не ловит\n' +
    'стенды вида `otstupy-admin-zamer.html`.');

/* 8. ВЕРСИЯ КЭША ПОДНЯТА ВМЕСТЕ С ПРАВКОЙ */
const версияКэша = (СЛУЖБА.match(/CACHE_NAME = 'kslt-v(\d+)'/) || [])[1];
правило('версия кэша не ниже 7',
    версияКэша && Number(версияКэша) >= 7,
    'Версия кэша: ' + версияКэша + ', а при правке службы она поднята до 7.\n' +
    'Старое имя означает, что у тех, у кого кэш уже есть, останется\n' +
    'прежний набор — с путями, которых больше нет.');

/* 9. НИ ОДИН ПУТЬ СЛУЖБЫ НЕ АБСОЛЮТЕН — НО СПРАШИВАЕМ У КОДА, НЕ У ТЕКСТА.
   Первая попытка этого правила упала на СОБСТВЕННЫХ КОММЕНТАРИЯХ: в них
   названы и '/', и '/KSLT-project/', и '/admin'. ЗАМОРОЗКА ЧИТАЕТ ФАЙЛ КАК
   ТЕКСТ И НЕ РАЗЛИЧАЕТ КОД И КОММЕНТАРИЙ — правило куска 132, и я наступил
   на него третий раз подряд.
   Маска построчная: она не умнее себя и потому СВЕРЯЕТСЯ — если съела всё
   или не съела ничего, правило падает само. СЛЕПОЙ ПРИБОР ДОКЛАДЫВАЕТ НЕ
   ОШИБКУ, А УСПЕХ (кусок 123). */
function безКомментариев(текст) {
    let вБлоке = false;
    return текст.split('\n').map(с => {
        const обрезок = с.trim();
        if (вБлоке) { if (обрезок.indexOf('*/') !== -1) вБлоке = false; return ''; }
        if (обрезок.indexOf('/*') === 0) {
            if (обрезок.indexOf('*/') === -1) вБлоке = true;
            return '';
        }
        if (обрезок.indexOf('//') === 0) return '';
        return с;
    }).join('\n');
}
const кодСлужбы = безКомментариев(СЛУЖБА);
const строкВсего = СЛУЖБА.split('\n').filter(с => с.trim()).length;
const строкКода = кодСлужбы.split('\n').filter(с => с.trim()).length;
правило('маска комментариев не ослепла',
    строкКода > 0 && строкКода < строкВсего,
    'Строк всего ' + строкВсего + ', кода после маски ' + строкКода + '.\n' +
    'Ноль означает, что маска съела файл и правило ниже ничего не проверяет;\n' +
    'равенство — что она не сняла ни одного комментария, и правило упадёт на\n' +
    'тексте вместо кода. СТОРОЖ СТЕРЕЖЁТ СОБСТВЕННУЮ СЛЕПОТУ.');

const абсолютные = [];
const ш = /['"](\/(?!\/)[^'"]*)['"]/g;
let м;
while ((м = ш.exec(кодСлужбы)) !== null) {
    абсолютные.push(м[1] + ' (строка ' + кодСлужбы.slice(0, м.index).split('\n').length + ')');
}
правило('в службе не осталось ни одного пути от корня домена',
    абсолютные.length === 0,
    'Путей от корня домена: ' + абсолютные.length + '\n' +
    абсолютные.slice(0, 6).map(с => '  ' + с).join('\n') + '\n' +
    'Их было ВОСЕМЬ — семь в предзагрузке и проверка админки, — и ни один\n' +
    'не ловился правилами куска 132: в массиве строк рядом нет ни `src=`,\n' +
    'ни `fetch(`.');

/* 10. ОШИБКА РЕГИСТРАЦИИ НЕ ОСТАЁТСЯ НЕМОЙ НАВСЕГДА */
правило('регистрация обёрнута в проверку наличия объявления корня',
    /if \(объявлениеКорня\)/.test(СКРИПТ),
    'Без манифеста на странице корень неизвестен, и служба просто не\n' +
    'регистрируется — это честный отказ, а не падение. Но он ДОЛЖЕН быть\n' +
    'явным условием, а не исключением, проглоченным `catch`: именно\n' +
    'немой `catch` скрывал поломку полтора месяца.');

/* вывод */
console.log('');
if (ошибки.length) {
    console.log('  НЕ ТАК  офлайн-служба — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(([и, п]) => console.log('          x ' + и + '\n            ' + п.replace(/\n/g, '\n            ') + '\n'));
    process.exit(1);
}
console.log('  ок      офлайн-служба: 11 правил');
console.log('          адрес службы — от объявленного корня проекта, не от корня домена');
console.log('          семь путей предзагрузки относительны и все существуют');
console.log('          служба знает свой корень из собственного адреса');
console.log('          админка отсекается относительно корня: те же 28 файлов');
console.log('');
