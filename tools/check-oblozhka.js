const ошибки = [];
const правило = (имя, держится, подсказка) => {
    if (!держится) ошибки.push({ имя, подсказка });
};

/* Тело блока по его открывающей строке. Берём [^}] — внутрь фигурных и не
   дальше: [\s\S]*? перепрыгивает через } в соседний блок. Поймано 04.10. */
const блок = (текст, селектор) => {
    const i = текст.indexOf(селектор);
    if (i < 0) return null;
    const j = текст.indexOf('{', i);
    if (j < 0) return null;
    const k = текст.indexOf('}', j);
    return k < 0 ? null : текст.slice(j + 1, k);
};

/* :root внутри медиазапроса. Ищем по условию, потом первый :root за ним. */
const рутВМедиа = (текст, условие) => {
    const i = текст.indexOf('@media ' + условие);
    if (i < 0) return null;
    const j = текст.indexOf(':root', i);
    if (j < 0 || j - i > 400) return null;
    const o = текст.indexOf('{', j);
    const c = текст.indexOf('}', o);
    return c < 0 ? null : текст.slice(o + 1, c);
};

/* ── 1. ТОКЕН ОБЛОЖКИ ────────────────────────────────────────────────────── */

const корень = ТОК.slice(0, ТОК.indexOf('.section-pad'));
/* Ручки обложки живут в СВОЁМ :root, заведённом после .section-pad. Первый
   замер правил 04.10 искал их в главном :root и не нашёл — прувер поймал бы
   это позже, а поймал сразу прогон самих правил. ПРАВИЛО СМОТРИТ В СВОЙ БЛОК,
   и «свой» надо сперва правильно вырезать. */
const обложкаРут = (() => {
    const i = ТОК.indexOf('.section-pad');
    const j = ТОК.indexOf(':root', i);
    if (j < 0) return '';
    const o = ТОК.indexOf('{', j);
    const c = ТОК.indexOf('}', o);
    return c < 0 ? '' : ТОК.slice(o + 1, c);
})();

