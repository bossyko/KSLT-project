const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');

/* ПОТОЛОК РАВЕН ЗАМЕРЕННОМУ. Снижение опускает его вместе с собой. */
const ПОТОЛОК_МЁРТВЫХ = 0;
const ПОТОЛОК_КЛАССОВ = 366;

function всеФайлы(дир, итог) {
    итог = итог || [];
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        if (['node_modules', '.git', 'build', 'dist', '_sync'].indexOf(э.name) !== -1) continue;
        const п = path.join(дир, э.name);
        if (э.isDirectory()) всеФайлы(п, итог);
        else if (/\.(js|html|json)$/.test(э.name)) итог.push(п);
    }
    return итог;
}

/* ИСТОЧНИКИ — ТОЛЬКО ПРОДУКТ. Сторожа и пробы не разметка: класс, который
   называет лишь правило, в продукте не употребляется. Ровно так `-invite-`
   и выглядели живыми в первом замере. */
const источники = ['js', 'pages', 'partials']
    .map(д => path.join(КОРЕНЬ, д))
    .filter(д => fs.existsSync(д))
    .reduce((в, д) => в.concat(всеФайлы(д)), [])
    .map(п => fs.readFileSync(п, 'utf8'));

const css = чит('css/dashboard.css').replace(/\/\*[\s\S]*?\*\//g, '');
const классы = Array.from(new Set((css.match(/\.db-[a-z0-9-]+/g) || []).map(к => к.slice(1)))).sort();

function живой(к) {
    for (const т of источники) {
        if (т.indexOf(к) !== -1) return true;
        const части = к.split('-');
        for (let n = части.length - 1; n >= 2; n--) {
            const прист = части.slice(0, n).join('-') + '-';
            const щит = прист.replace(/-/g, '\\-');
            if (new RegExp("['\"`]" + щит + "['\"`]?\\s*\\+").test(т)) return true;
            if (new RegExp("['\"`][^'\"`]*\\s" + щит + "['\"]?\\s*\\+").test(т)) return true;
        }
    }
    return false;
}

const мёртвые = классы.filter(к => !живой(к));

const ошибки = [];
let держится = 0;
function правило(имя, годно, подсказка) {
    if (годно) { держится++; console.log('  ✓ ' + имя); }
    else ошибки.push({ имя, подсказка });
}

правило(
    'ни одного мёртвого класса в css кабинета',
    мёртвые.length <= ПОТОЛОК_МЁРТВЫХ,
    'Не употребляются нигде в продукте: ' + мёртвые.join(', ') + '.\n' +
    'МЁРТВЫМ КОД НАЗЫВАЕТСЯ ПОСЛЕ ПРОВЕРКИ: прежде чем снимать, убедись,\n' +
    'что имя не собирается СКЛЕЙКОЙ — так живут `db-invite-*` и `db-tag-*`.');

правило(
    'классов .db- не больше замеренного',
    классы.length <= ПОТОЛОК_КЛАССОВ,
    'Сейчас ' + классы.length + ' при потолке ' + ПОТОЛОК_КЛАССОВ + '.\n' +
    'Рост — новая семья классов; её надо назвать и покрыть, а не копить.');

правило(
    'живые через склейку не считаются мёртвыми',
    ['db-invite-accepted', 'db-invite-declined', 'db-invite-pending',
     'db-tag-rating', 'db-tag-friendly', 'db-inv-contact--tg']
        .every(к => классы.indexOf(к) === -1 || живой(к)),
    'Прибор снова ищет ПОЛНОЕ ИМЯ. Эти шесть собираются склейкой, и если\n' +
    'правило перестало их видеть — следующая уборка снесёт живые стили\n' +
    'трёх статусов приглашения и пяти видов матча.');

console.log('');
if (!ошибки.length) {
    console.log('  ок      мёртвые классы кабинета: ' + держится + ' правил');
    console.log('          классов .db- ' + классы.length + ' (потолок ' + ПОТОЛОК_КЛАССОВ + '), мёртвых ' + мёртвые.length);
    console.log('          признак видит склейку: `db-invite-` + статус, `db-tag-` + вид');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  мёртвые классы кабинета — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
