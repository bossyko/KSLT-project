const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');

/* ПОТОЛОК РАВЕН ЗАМЕРЕННОМУ. Снижение опускает его вместе с собой. */
const ПОТОЛОК_МЁРТВЫХ = 0;
const ПОТОЛОК_КЛАССОВ = 366;   /* только `.db-` кабинета, см. правило 2 */
/* ЧУЖИЕ БИБЛИОТЕКИ ПИШУТ СВОИ КЛАССЫ САМИ, и в нашем коде их нет НИКОГДА.
   Исключения НАЗВАНЫ, а не вычеркнуты молча: Cropper.js — окно обрезки
   фото в кабинете, Leaflet — карта на странице корта. */
const ЧУЖИЕ = /^(cropper|leaflet|lf-)/;

function всеФайлы(дир, итог) {
    итог = итог || [];
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        if (['node_modules', '.git', 'build', 'dist', '_sync'].indexOf(э.name) !== -1) continue;
        const п = path.join(дир, э.name);
        if (э.isDirectory()) всеФайлы(п, итог);
        else if (/\.(js|html|json)$/.test(э.name)) итог.push(п);
    }
    return итог;
}

/* ИСТОЧНИКИ — ТОЛЬКО ПРОДУКТ. Сторожа и пробы не разметка: класс, который
   называет лишь правило, в продукте не употребляется. Ровно так `-invite-`
   и выглядели живыми в первом замере. */
/* ИСТОЧНИКИ — ВСЯ РАЗМЕТКА ПРОДУКТА, И КОРНЕВЫЕ СТРАНИЦЫ ТОЖЕ. Первая
   редакция 22.10 читала только `js`, `pages` и `partials` — и весь лендинг
   выглядел мёртвым целиком: `hero-*`, `section-*`, `sp-*` живут в
   `index.html`, `index-en.html` и `index-kg.html`, то есть В КОРНЕ.
   ПРИБОР, ЧИТАЮЩИЙ ЧАСТЬ РАЗМЕТКИ, ОБЪЯВИТ МЁРТВОЙ ОСТАЛЬНУЮ. */
const источники = ['js', 'pages', 'partials']
    .map(д => path.join(КОРЕНЬ, д))
    .filter(д => fs.existsSync(д))
    .reduce((в, д) => в.concat(всеФайлы(д)), [])
    .concat(fs.readdirSync(КОРЕНЬ)
        .filter(ф => ф.endsWith('.html'))
        .map(ф => path.join(КОРЕНЬ, ф)))
    .map(п => fs.readFileSync(п, 'utf8'));

/* ОДИН ПРОХОД ПО ТЕКСТУ, А НЕ ПО КАЖДОМУ КЛАССУ (22.10).
   Первая редакция гоняла регулярки на КАЖДЫЙ класс по КАЖДОМУ файлу:
   3460 классов × две сотни файлов, и прувер перестал укладываться в срок
   вовсе. Признак от этого не меняется — меняется цена.
   Приставки склейки собираются ОДНИМ проходом в множество, и дальше класс
   проверяется двумя дешёвыми вопросами: встречается ли он целиком, и есть
   ли в множестве хоть одна его приставка.
   ПРОВЕРКА, КОТОРАЯ НЕ УСПЕВАЕТ ПРОЙТИ, НЕ СТОРОЖИТ НИЧЕГО. */
const весьТекст = источники.join('\n');
const приставкиСклеек = (function () {
    const набор = new Set();
    const обр = /['"`]([-\w]*[-\w])-['"`]?\s*\+/g;
    let м;
    while ((м = обр.exec(весьТекст))) набор.add(м[1] + '-');
    const обр2 = /['"`][^'"`\n]*?[\s]([-\w]*[-\w])-['"]?\s*\+/g;
    while ((м = обр2.exec(весьТекст))) набор.add(м[1] + '-');
    return набор;
})();

function живой(к) {
    if (весьТекст.indexOf(к) !== -1) return true;
    const части = к.split('-');
    for (let n = части.length - 1; n >= 2; n--) {
        if (приставкиСклеек.has(части.slice(0, n).join('-') + '-')) return true;
    }
    return false;
}

const css = чит('css/dashboard.css').replace(/\/\*[\s\S]*?\*\//g, '');
const классы = Array.from(new Set((css.match(/\.db-[a-z0-9-]+/g) || []).map(к => к.slice(1)))).sort();

/* ── КЛАССЫ ВСЕХ ФАЙЛОВ CSS ──────────────────────────────────────────────
   КЛАСС БЕРЁТСЯ ИЗ СЕЛЕКТОРА, А НЕ ОТКУДА ПОПАЛО: строки, адреса и
   содержимое `url()` гасятся до поиска, и смотрится ЛЕВАЯ часть правила.
   Иначе `images.unsplash.com` внутри `url(...)` даёт «класс» unsplash. */
function классыФайла(ф) {
    let т = чит('css/' + ф).replace(/\/\*[\s\S]*?\*\//g, '');
    т = т.replace(/url\([^)]*\)/g, 'url()').replace(/"[^"]*"/g, '""').replace(/'[^']*'/g, "''");
    const сел = (т.match(/(^|\})[^{}]*\{/g) || []).join(' ');
    return Array.from(new Set((сел.match(/\.[a-zA-Z][-a-zA-Z0-9_]*/g) || []).map(к => к.slice(1))));
}
const поФайлам = {};
