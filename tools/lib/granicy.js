const fs = require('fs');
const path = require('path');

const корень = path.resolve(__dirname, '..', '..');

function изСправочника() {
    const т = fs.readFileSync(path.join(корень, 'css/tokens.css'), 'utf8');
    const i = т.indexOf('9. БРЕЙКПОИНТЫ');
    if (i < 0) throw new Error('tokens.css: раздела 9 «БРЕЙКПОИНТЫ» нет — границы брать неоткуда');
    const раздел = т.slice(i, i + 1200);
    const макс = [...раздел.matchAll(/@media \(max-width: (\d+)px\)/g)].map(м => +м[1]);
    const мин = [...раздел.matchAll(/@media \(min-width: (\d+)px\)/g)].map(м => +м[1]);
    if (макс.length < 2) throw new Error('tokens.css: в разделе 9 меньше двух границ max-width');
    const узкая = Math.min(...макс);      /* телефон */
    const широкая = Math.max(...макс);    /* телефон и планшет */
    return {
        узкая, широкая,
        парыМин: мин,
        /* Все разрешённые числа — для проверок «мимо шкалы». */
        все: new Set([...макс, ...мин]),
    };
}

module.exports = изСправочника();
