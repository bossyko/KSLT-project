#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ОДИН ВЫБОР СТРАНЫ И ГЛАЗ У КАЖДОГО ПАРОЛЯ» (02.11).
 *
 * ДВА СЛУЧАЯ, ОБА УВИДЕНЫ ГЛАЗАМИ, ОБА — ОДНО ПОНЯТИЕ В НЕСКОЛЬКИХ
 * ОПРЕДЕЛЕНИЯХ.
 *
 * ПЕРВЫЙ — ВЫБОР СТРАНЫ. В приложении их было ДВА: свой `<select>` на
 * восемь стран прямо в разметке входа и `selectHtml` дома в кабинете.
 * Дом `js/phone.js` знает тринадцать стран, их названия, длину номера и
 * разбивку, и только он умеет отличить Казахстан от России — у обоих
 * код `+7`. Свой список этого не умел и слал `+7` как страну; а Android
 * рисовал нативный `<select>` системным окном, в каждой строке которого
 * Костя увидел знак КСЛТ (02.11). Внутрь системного окна css не достаёт,
 * поэтому лечится оно не правкой цвета, а своим органом `pickerHtml`.
 *
 * ВТОРОЙ — ГЛАЗ У ПАРОЛЯ. Полей пароля в приложении шесть, и глаза не
 * было НИ У ОДНОГО, хотя на сайте он есть с сентября. Поле без глаза
 * выглядит ровно как поле с глазом, пока не попробуешь нажать, —
 * поэтому пропажа и жила незамеченной.
 *
 * ЧТО СТЕРЕЖЁТСЯ. Не «красиво», а ВОЗВРАТ к прежнему: второй список
 * стран, нативный селект под страну, экран с паролем без глаза.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ, И ЭТО НАЗВАНО. Прибор читает ФАЙЛ КАК ТЕКСТ. Поле
 * пароля, собранное через `createElement` без слова `password` рядом,
 * он не увидит; выбор страны, написанный третьим способом и без слова
 * `option`, — тоже. Он не заменяет ни тесты, ни глаза.
 *
 *   node tools/check-strana-i-glaz.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ДОМ = 'mobile/www';
const ГЛАЗ_ФАЙЛ = 'js/kslt-glaz-parolya.js';

function файлы(д, вых) {
    вых = вых || [];
    const п = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(п)) return вых;
    for (const э of fs.readdirSync(п, { withFileTypes: true })) {
        const о = д + '/' + э.name;
        if (э.isDirectory()) файлы(о, вых);
        else if (/\.(js|html)$/.test(э.name)) вых.push(о);
    }
    return вых;
}

const все = файлы(ДОМ);
const текст = {};
для_каждого();
function для_каждого() {
    for (const ф of все) текст[ф] = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
}

/**
 * ВТОРОЙ СПИСОК СТРАН — это `<option>` с телефонным кодом в значении.
 * Признак взят по СОДЕРЖИМОМУ (`value="+996"`), а не по имени класса:
 * ПРИБОР, ЗНАЮЩИЙ ИМЯ КЛАССА НАИЗУСТЬ, ОТСТАЁТ ОТ РАЗМЕТКИ.
 */
function своиСтраны(т) {
    const м = т.match(/<option[^>]*value\s*=\s*["']\+\d+["']/g);
    return м ? м.length : 0;
}

const стран = [];
const селектов = [];
for (const ф of все) {
    const н = своиСтраны(текст[ф]);
    if (н) стран.push({ ф, н });
    /* Дом отдаёт ДВА органа. `selectHtml` — нативный, им одевается сайт;
       в приложении он и был вторым определением. Само объявление
       функции в `js/phone.js` не в счёт: файл копируется с сайта целиком
       и правится там. */
    if (/KSLT_PHONE\.selectHtml|P\.selectHtml\s*\(/.test(текст[ф]) &&
        !/^mobile\/www\/js\/phone\.js$/.test(ф)) {
        селектов.push(ф);
    }
}

/* ПОЛЕ ПАРОЛЯ — два написания: в разметке и аргументом типа поля. */
const ПАРОЛЬ = /type\s*=\s*["']password["']|,\s*["']password["']\s*\)/;
const безГлаза = [];
for (const ф of все) {
    if (ф === ДОМ + '/' + ГЛАЗ_ФАЙЛ) continue;
    if (!ПАРОЛЬ.test(текст[ф])) continue;
    const знает = /KSLT_GLAZ/.test(текст[ф]) ||
                  текст[ф].indexOf('kslt-glaz-parolya.js') !== -1;
    if (!знает) безГлаза.push(ф);
}

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('своего списка стран в приложении нет',
    стран.length === 0,
    'Список стран написан заново: ' +
    стран.map(о => '\n  ' + о.ф + ' — ' + о.н + ' строк с телефонным кодом').join('') +
    '\nСтраны живут в `js/phone.js`: тринадцать, с названиями, длиной\n' +
    'номера и разбивкой. Свой список их не знает и Казахстан от России\n' +
    'не отличает — у обоих +7. Зови `KSLT_PHONE.pickerHtml`.');

правило('нативного селекта под страну в приложении нет',
    селектов.length === 0,
    'Нативный `selectHtml` зовут: ' + селектов.map(ф => '\n  ' + ф).join('') +
    '\nВ приложении его рисует Android — системным окном, в которое css\n' +
    'не достаёт, и в закрытом поле он показывает только флаг с кодом.\n' +
    'Для приложения орган один: `KSLT_PHONE.pickerHtml`.');

правило('глаз подключён в доме приложения',
    текст[ДОМ + '/index.html'] &&
    текст[ДОМ + '/index.html'].indexOf('kslt-glaz-parolya.js') !== -1,
    'В `' + ДОМ + '/index.html` нет подключения `' + ГЛАЗ_ФАЙЛ + '`.\n' +
    'Без него поля пароля остаются без глаза все до одного, и узнать об\n' +
    'этом можно только нажав туда, где нажимать нечего.');

правило('каждый экран с паролем знает про глаз',
    безГлаза.length === 0,
    'Поле пароля есть, а про глаз файл не знает: ' +
    безГлаза.map(ф => '\n  ' + ф).join('') +
    '\nПоле, нарисованное скриптом ПОСЛЕ загрузки, глаз сам не получит:\n' +
    'дом одевает то, что было в разметке при старте. Позови\n' +
    '`KSLT_GLAZ.применить(корень)` там же, где рисуешь поле.');

правило('прибор отличает свой список стран от чужого option',
    (function () {
        /* ОБРАЗЕЦ ВНУТРЬ ПРИБОРА: он обязан РАЗЛИЧАТЬ, иначе «ноль мест»
           он скажет и на беде. Три вида: телефонный код в значении,
           обычный option и упоминание кода в тексте. */
        const о = '<option value="+996">KG</option>\n' +
                  '<option value="ru">Русский</option>\n' +
                  "var s = 'код +996 подставится сам';\n";
        return своиСтраны(о) === 1;
    })(),
    'Образец внутри прибора: телефонный код в значении, обычный option\n' +
    'и код в тексте. Прибор обязан насчитать РОВНО одно место. Считает\n' +
    'иначе — значит «своего списка нет» он скажет и тогда, когда он есть.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      страна и глаз: все ' + всего + ' правил держатся');
    console.log('          файлов приложения прочитано ' + все.length);
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  страна и глаз — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
