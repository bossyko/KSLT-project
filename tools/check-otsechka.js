'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ДОМ = 'js/kslt-otsechka.js';
const ПРИЛОЖЕНИЕ = 'mobile/www/js';

function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function безКом(т) {
    return (т || '').replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');
}
function файлы(д, вых) {
    вых = вых || [];
    const п = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(п)) return вых;
    for (const э of fs.readdirSync(п, { withFileTypes: true })) {
        const о = д + '/' + э.name;
        if (э.isDirectory()) файлы(о, вых);
        else if (э.name.endsWith('.js')) вых.push(о);
    }
    return вых;
}

/**
 * СВОЯ ОТСЕЧКА — срез списка по ИМЕНОВАННОМУ пределу (`slice(0, LIMIT)`)
 * или само объявление такого предела.
 *
 * ПОЧЕМУ НЕ ЛЮБОЙ `slice(0, число)`, И ЭТО НАЗВАНО ВСЛУХ. Первая
 * редакция ловила его — и выдала девять мест, из которых настоящих было
 * НОЛЬ: обрезка даты `slice(0, 10)`, инициалы `slice(0, 2)`, первые три
 * тега у тренера, обрезка текста ошибки до 300 знаков. ПРИБОР, КРИЧАЩИЙ
 * ВОЛКАМИ, СНИМАЮТ ЦЕЛИКОМ. Плата названа: отсечку, написанную голым
 * числом без имени, прибор не увидит.
 */
function своя(т) {
    return безКом(т).split('\n').filter(с =>
        /\.slice\(\s*0\s*,\s*(?:LIMIT|ПРЕДЕЛ)\s*\)/.test(с) ||
        /\b(?:LIMIT|ПРЕДЕЛ)\s*=\s*\d+/.test(с)
    ).length;
}

const все = файлы(ПРИЛОЖЕНИЕ);
const свои = [];
for (const ф of все) {
    if (/kslt-otsechka\.js$/.test(ф)) continue;
    const н = своя(чит(ф));
    if (н) свои.push({ ф, н });
}

const дом = безКом(чит(ДОМ));
const игрок = безКом(чит(ПРИЛОЖЕНИЕ + '/screens/player-detail.js'));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('своей отсечки в приложении нет',
    свои.length === 0,
    'Список режут на месте: ' +
    свои.map(о => '\n  ' + о.ф + ' — ' + о.н + ' мест').join('') +
    '\nОтсечку делает дом `' + ДОМ + '`. Написанная заново, она уже\n' +
    'оказалась НЕВЕРНОЙ: кнопка убирала себя и не показывала ничего.');

правило('матчи игрока режет дом',
    !!игрок && /KSLT_OTSECHKA/.test(игрок) &&
    /О\s*\.\s*класс\s*\(/.test(игрок) && /О\s*\.\s*кнопка\s*\(/.test(игрок) &&
    /О\s*\.\s*включить\s*\(/.test(игрок),
    'Матчи игрока перестали звать дом целиком. Нужны все три части:\n' +
    '`класс` на строке, `кнопка` под списком и `включить` на коробке.\n' +
    'Без `включить` кнопка нарисована и мертва.');

правило('дом прячет строку, а не выбрасывает',
    /kslt-skryta/.test(дом) && !/\.slice\(/.test(дом),
    'Дом начал резать список `slice`. Скрытая строка остаётся в\n' +
    'разметке: её находит поиск по странице и читает диктор.\n' +
    'Отрезанная не существует ни для кого.');

правило('одежда отсечки есть в приложении',
    (function () {
        const css = чит('mobile/www/css/app.css') || '';
        return /\.kslt-skryta\s*\{[^}]*display:\s*none/.test(css) &&
               /\.kslt-more\s*\{/.test(css);
    })(),
    'В одежде приложения нет `.kslt-skryta` или `.kslt-more`. Дом ставит\n' +
    'классы, но без правил скрытые строки остаются видимыми, а кнопка —\n' +
    'голой ссылкой посреди списка.');

правило('прибор отличает отсечку от обычного slice',
    (function () {
        /* ОБРАЗЕЦ ВНУТРЬ ПРИБОРА: `slice` с предела — отсечка, `slice`
           с середины или без числа — обычная работа со списком. */
        const о = "var a = list.slice(0, LIMIT);\n" +
                  "var b = list.slice(1);\n" +
                  "var c = list.slice(0, i);\n" +
                  "var d = String(date).slice(0, 10);\n" +
                  "var e = name.slice(0, 2);\n" +
                  "/* list.slice(0, LIMIT) в подписи */\n";
        return своя(о) === 1;
    })(),
    'Образец внутри прибора: отсечка по пределу, срез с единицы, срез по\n' +
    'переменной, обрезка даты, инициалы и срез в подписи. Ждём РОВНО\n' +
    'одно место. Считает иначе — значит падает на обычной работе со\n' +
    'списком или молчит на беде.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      отсечка: все ' + всего + ' правил держатся');
    console.log('          своих отсечек 0, матчи игрока на доме');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  отсечка — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
