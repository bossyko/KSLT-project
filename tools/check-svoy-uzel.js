#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «УЗЕЛ, СОБРАННЫЙ КОДОМ, ИЩЕТ СВОЁ В СЕБЕ» (02.11).
 *
 * ЗАЧЕМ ОН ЕСТЬ — ЗАПЕРТОЕ ПРИЛОЖЕНИЕ, А НЕ ОПАСЕНИЕ. Костя на чистой
 * установке увидел знакомство при первом запуске и не смог из него
 * выйти: кнопки «Далее» и «Пропустить» не отвечали ВОВСЕ, и в кабинет
 * было не попасть.
 *
 * ПРИЧИНА, НАЙДЕННАЯ ЧТЕНИЕМ. `showOnboarding` зовут ДВА места:
 * `checkSession().then` (вошедший открыл приложение) и
 * `APP.onAuthChange` (вход только что произошёл). Защиты от второго
 * окна не было — отметка в `localStorage` ставится лишь при закрытии,
 * а его-то и не происходило. В доме оказывалось ДВА узла с одним `id`,
 * человек видел верхний, а `document.getElementById('onbNext')` отдавал
 * кнопку НИЖНЕГО: обработчики вешались не на то, что нажимают.
 *
 * ПРАВИЛО ШИРЕ СЛУЧАЯ. `getElementById` и `document.querySelector`
 * отвечают на вопрос «есть ли такой узел в ДОКУМЕНТЕ», а спрашивали мы
 * «есть ли он в МОЁМ окне». Пока окно одно, ответы совпадают — и это
 * худший вид беды: она ждёт второго окна. А второе окно появляется само:
 * старое висит в доме ещё 300 мс после закрытия, пока идёт переход.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ. Прибор читает текст и смотрит только на узлы,
 * собранные `createElement` в экранах приложения. Разметка из
 * `index.html` ищется по документу законно: она в единственном числе и
 * существует всегда.
 *
 *   node tools/check-svoy-uzel.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ДОМ = 'mobile/www/js';

function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function безКом(т) {
    return (т || '').replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');
}

function файлы(д, вых) {
    вых = вых || [];
    const п = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(п)) return вых;
    for (const э of fs.readdirSync(п, { withFileTypes: true })) {
        const о = д + '/' + э.name;
        if (э.isDirectory()) файлы(о, вых);
        else if (э.name.endsWith('.js')) вых.push(о);
    }
    return вых;
}

/**
 * Окно, собранное кодом: переменной присвоен `createElement`, ей же
 * поставлен `id`, и она же добавлена в дом. Нас интересуют именно такие:
 * у них `id` живёт столько же, сколько узел, и может задвоиться.
 */
function своиОкна(т) {
    const к = безКом(т);
    const имена = [];
    const re = /(\w+)\.id\s*=\s*['"]([\w-]+)['"]/g;
    let м;
    while ((м = re.exec(к))) {
        const пер = м[1];
        if (new RegExp('(?:var|let|const)\\s+' + пер + '\\s*=\\s*document\\.createElement').test(к)) {
            имена.push({ пер, id: м[2] });
        }
    }
    return имена;
}

/**
 * Зовы по документу за частью СВОЕГО окна.
 *
 * ГРАНИЦА — ВСТАВКА В ДОМ. Обработчики окна вешаются сразу после
 * `appendChild`, и именно там зов по документу подводит. Дальше в файле
 * живут зовы за разметкой ЭКРАНА — она в единственном числе, лежит в
 * `index.html` и существует всегда; искать её по документу законно.
 *
 * ПЕРВАЯ РЕДАКЦИЯ ЭТОГО НЕ РАЗЛИЧАЛА и выдала шестнадцать мест, из
 * которых настоящих было четыре: она считала частью окна всякое имя,
 * встреченное в файле. ПРИБОР, КРИЧАЩИЙ ВОЛКАМИ, СНИМАЮТ ЦЕЛИКОМ —
 * вместе с настоящей проверкой.
 */
/* 1200 ЗНАКОВ — ЭТО ЗАМЕР, А НЕ КРУГЛОЕ ЧИСЛО. От вставки в дом до
   зова за своей кнопкой в живых случаях 60–310 знаков, НО от написания
   разметки до того же зова — до 900: разметка окна длинная, и
   обработчики идут за ней. На 500 правило молчало на знакомстве, ради
   которого и заведено. За соседний код полоса не уезжает: её обрезает
   конец функции. */
const ОКНО_ПОСЛЕ_ВСТАВКИ = 1200;

function чужойПоиск(т, окна) {
    const к = безКом(т);
    const беды = [];
    for (const о of окна) {
        /* ДВЕ ТОЧКИ ОТСЧЁТА, А НЕ ОДНА. Обработчики вешают либо сразу
           после вставки в дом, либо сразу после того, как окну написали
           разметку, — и во втором случае вставка стоит НИЖЕ по файлу.
           Полоса только от `appendChild` не видела беду знакомства: его
           `renderStep` пишет разметку и вешает обработчики задолго до
           вставки. Поймано своим же прувером 02.11 — правило молчало
           ровно на том случае, ради которого заведено. */
        const вставка = new RegExp(
            '(?:appendChild\\(\\s*' + о.пер + '\\s*\\)|' + о.пер + '\\.innerHTML\\s*=)', 'g');
        let в;
        while ((в = вставка.exec(к))) {
            let кусок = к.slice(в.index, в.index + ОКНО_ПОСЛЕ_ВСТАВКИ);
            /* ГРАНИЦА — КОНЕЦ ФУНКЦИИ, А НЕ ЧИСЛО ЗНАКОВ. Закрытие
               блока на отступе в два пробела — её признак в этом коде.
               Без обрезки в полосу попадал СОСЕДНИЙ код: прибор называл
               бедой зовы за разметкой заставки, стоящие ниже по файлу
               и к окну не относящиеся. */
            const конец = кусок.search(/\n {0,2}\}/);
            if (конец > 0) кусок = кусок.slice(0, конец);
            const re = /document\.(?:getElementById\(\s*['"]([\w-]+)['"]|querySelector\(\s*['"]#([\w-]+)['"])/g;
            let м;
            while ((м = re.exec(кусок))) {
                const имя = м[1] || м[2];
                /* Само окно искать по документу можно: так и проверяют,
                   не открыто ли оно уже. Беда — когда ищут ЧАСТЬ. */
                if (имя === о.id) continue;
                /* РОДИТЕЛЬ — НЕ ЧАСТЬ. `document.getElementById('app')
                   .appendChild(окно)` ищет корень приложения, в который
                   окно кладут; он живёт в разметке и всегда один. */
                if (/^\s*\.appendChild\s*\(/.test(кусок.slice(м.index + м[0].length + 1))) continue;
                if (беды.some(б => б.окно === о.id && б.часть === имя)) continue;
                беды.push({ окно: о.id, часть: имя });
            }
        }
    }
    return беды;
}

const все = файлы(ДОМ);
const беды = [];
for (const ф of все) {
    const т = чит(ф);
    if (!т) continue;
    const окна = своиОкна(т);
    if (!окна.length) continue;
    чужойПоиск(т, окна).forEach(б => беды.push({ ф, ...б }));
}

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('окно, собранное кодом, ищет свои части в себе',
    беды.length === 0,
    'Часть своего окна ищется по всему документу: ' +
    беды.map(б => '\n  ' + б.ф + ' — окно `' + б.окно + '`, часть `' + б.часть + '`').join('') +
    '\n`getElementById` отдаёт ПЕРВЫЙ подходящий узел в документе, а не\n' +
    'твой. Пока окно одно, ответы совпадают, и беда ждёт второго —\n' +
    'а второе появляется само: старое висит в доме ещё 300 мс после\n' +
    'закрытия. Зови `окно.querySelector(...)`.');

правило('знакомство не создаётся дважды',
    (function () {
        const т = безКом(чит('mobile/www/js/app.js'));
        if (!т) return false;
        /* Зовов два, и это законно; незаконно — отсутствие защиты. */
        return /getElementById\(\s*['"]onboardingOverlay['"]\s*\)\s*\)\s*return/.test(т);
    })(),
    'В `showOnboarding` нет выхода, когда окно знакомства уже в доме.\n' +
    'Зовут его ДВА места — `checkSession().then` и `APP.onAuthChange`, —\n' +
    'и отметка в `localStorage` от второго зова не спасает: она ставится\n' +
    'только при закрытии. Два окна с одним `id` заперли приложение на\n' +
    'первом экране 02.11.');

правило('прибор отличает зов за частью от зова за самим окном',
    (function () {
        /* ОБРАЗЕЦ ВНУТРЬ ПРИБОРА: искать САМО окно по документу законно
           (так и проверяют, не открыто ли оно), искать его ЧАСТЬ — нет.
           Без этого различения прибор ронял бы и верную защиту. */
        const о = "var ov = document.createElement('div');\n" +
                  "ov.id = 'myOverlay';\n" +
                  "ov.innerHTML = '<button id=\"myBtn\"></button>';\n" +
                  "if (document.getElementById('myOverlay')) return;\n" +
                  "document.body.appendChild(ov);\n" +
                  /* Закрытие функции: без него обрезка полосы ничего не
                     решает, и откат, её ослепляющий, не доказал бы себя. */
                  "document.getElementById('myBtn').onclick = f;\n" +
                  "  }\n" +
                  /* Зов за разметкой ЭКРАНА, далеко от вставки, — законен.
                     Отбивка здесь НАСТОЯЩАЯ, а не `repeat(600)`: прибор
                     читает текст, и строка `'%'.repeat(600)` занимает в
                     нём двадцать восемь знаков, а не шестьсот. На этом
                     образец и попался 02.11. */
                  "var пусто = '" + "x".repeat(600) + "';\n" +
                  "document.getElementById('screenBtn').onclick = g;\n";
        const окна = своиОкна(о);
        if (окна.length !== 1 || окна[0].id !== 'myOverlay') return false;
        const б = чужойПоиск(о, окна);
        return б.length === 1 && б[0].часть === 'myBtn';
    })(),
    'Образец внутри прибора: окно, его защита от второго создания и зов\n' +
    'за кнопкой. Прибор обязан насчитать РОВНО одну беду — кнопку, — и\n' +
    'не считать бедой проверку самого окна. Считает иначе — значит он\n' +
    'либо молчит на беде, либо требует убрать защиту.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      свой узел: все ' + всего + ' правил держатся');
    console.log('          файлов приложения прочитано ' + все.length);
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  свой узел — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
