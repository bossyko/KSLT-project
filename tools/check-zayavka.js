#!/usr/bin/env node
/**
 * ЗАЯВКА НА ТУРНИР — ОДИН ДОМ (шаг A3.7д, 29.10).
 *
 * ЗАЧЕМ. `js/tournament-register.js` (708 строк) и
 * `mobile/www/js/tournament-register.js` (199) носили одно имя
 * `KSLT_REG` и жили двумя телами. Решение о допуске принимает серверная
 * функция — это верно; а вот РАЗБОР её ответа был написан дважды, и на
 * шве уже родились две беды:
 *
 *   1. у приложения НЕ БЫЛО ВЕТКИ `partner_changed` вовсе: ответ не
 *      несёт ни `error`, ни `status`, поэтому успешная замена напарника
 *      доезжала до последней ветки, и человек видел «Заявка не принята»;
 *   2. слов на коды отказа у сайта ДЕВЯТНАДЦАТЬ, у приложения было
 *      ДЕВЯТЬ — остальные десять показывались СЫРЫМ КОДОМ базы.
 *
 * ЧТО ДЕРЖИТ СТОРОЖ: дерево решений живёт в одном доме и отдаёт КЛЮЧИ;
 * слова живут в одном файле на три языка; у КАЖДОГО ключа, который дом
 * умеет отдать, есть слово на всех трёх языках; у продуктов не осталось
 * ни своего зова, ни своего дерева, ни своих слов.
 *
 * Запуск: node tools/check-zayavka.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));
const безКомCss = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

const ДОМ = 'js/kslt-zayavka.js';
const ДОМ_П = 'mobile/www/js/kslt-zayavka.js';
const СЛОВА = 'js/zayavka-texts.js';
const СЛОВА_П = 'mobile/www/js/zayavka-texts.js';
const САЙТ = 'js/tournament-register.js';
const ПРИЛ = 'mobile/www/js/tournament-register.js';

/* Семнадцать разметок, где подключено окно заявки. Список не держится
   руками: он собирается обходом. */
const РАЗМЕТКИ = (function () {
    const найдено = [];
    const обойти = (отн) => {
        const п = path.join(КОРЕНЬ, отн);
        if (!fs.existsSync(п)) return;
        for (const э of fs.readdirSync(п, { withFileTypes: true })) {
            const вложен = отн ? отн + '/' + э.name : э.name;
            if (э.isDirectory()) {
                if (/node_modules|android|ios|\.git|test-results|reports/.test(э.name)) continue;
                if (вложен.indexOf('mobile/android') === 0) continue;
                обойти(вложен);
                continue;
            }
            if (!э.name.endsWith('.html')) continue;
            if (/\/(build|assets)\//.test(вложен)) continue;
            if (/tournament-register\.js/.test(fs.readFileSync(path.join(КОРЕНЬ, вложен), 'utf8'))) {
                найдено.push(вложен);
            }
        }
    };
    обойти('');
    return найдено;
})();

console.log('\n  ЗАЯВКА НА ТУРНИР — ОДИН ДОМ\n');

const дом = безКом(чит(ДОМ));
const слова = чит(СЛОВА);

правило('дом объявлен и отдаёт все четыре действия',
    /KSLT_ZAYAVKA\b/.test(дом) && /API\.зов\s*=/.test(дом) &&
    /API\.разобрать\s*=/.test(дом) && /API\.словами\s*=/.test(дом) &&
    /API\.создана\s*=/.test(дом),
    'Нужны: `зов`, `разобрать`, `словами`, `создана`.\n' +
    'Пропал кто-то один — продукт завёл его себе обратно.');

правило('копии дома побайтово равны',
    чит(ДОМ) === чит(ДОМ_П),
    'Разошлись — значит разбор ответа снова живёт двумя жизнями.');

правило('копии надписей побайтово равны',
    слова === чит(СЛОВА_П),
    'Разошлись — значит слова снова можно поменять в одном месте и\n' +
    'забыть во втором. Ровно так у приложения и осталось девять слов из\n' +
    'девятнадцати.');

правило('адрес серверной функции назван один раз',
    /API\.ФУНКЦИЯ\s*=\s*'tournament-register'/.test(дом) &&
    !/tournament-register/.test(безКом(чит(САЙТ))) &&
    !/tournament-register/.test(безКом(чит(ПРИЛ))),
    'Имя функции допуска — одно определение. Разойдись оно, один продукт\n' +
    'стучался бы не туда и молчал.');

правило('ветка смены напарника стоит ПЕРВОЙ',
    (function () {
        const п = дом.indexOf('partner_changed');
        const у = дом.indexOf("'already_registered'");
        const о = дом.indexOf('if (д.error) {');
        return п !== -1 && у !== -1 && о !== -1 && п < у && у < о;
    })(),
    'ЭТО ТА САМАЯ БЕДА. `partner_changed` не несёт ни `error`, ни\n' +
    '`status`. Поставь его позже — успешная замена напарника доедет до\n' +
    'общего отказа, и человек увидит «Заявка не принята», как это и было\n' +
    'в приложении.');

/* СЛОВО ОТ ИМЕНИ ОТЛИЧАЕТ ПРОБЕЛ, А НЕ АЗБУКА. Первая редакция правила
   искала в доме кириллицу и падала на его же ИМЕНАХ — `ключ`, `коротко`,
   `значок`, `вид: 'отказ'`. Имена ветвей по-русски — это не слова,
   показанные человеку; слово, показанное человеку, — это фраза, и в ней
   есть пробел. Промах поймал прувер. */
/* И ВТОРОЙ ПРОМАХ ТОГО ЖЕ ПРАВИЛА: признак `'[^']*…'` ЛАТАЛСЯ МИМО
   СТРОКИ. Кавычки в файле идут парами, и выражение склеивало закрывающую
   кавычку одной строки с открывающей следующей — между ними оказывался
   КОД с кириллицей и пробелами, и правило падало на пустых строках
   `код: ''`. СТРОКА ЖИВЁТ ВНУТРИ ОДНОЙ СТРОКИ ФАЙЛА: перевод каретки в
   неё не входит. */
правило('дом не знает ни одного слова',
    (дом.match(/'[^'\n]*'/g) || [])
        .every(с => !(/[А-Яа-яЁё]/.test(с) && /\s/.test(с))) && /L\[/.test(дом),
    'Словарь приходит из `zayavka-texts.js`, язык выбирает продукт.\n' +
    'Попади слово в дом — перевод разошёлся бы с продуктом.');

правило('у дома девятнадцать кодов отказа — и у надписей столько же',
    (function () {
        const блоки = слова.split(/T\.(?:ru|en|kg)\s*=/).slice(1);
        if (блоки.length !== 3) return false;
        return блоки.every(б => {
            const м = б.match(/err:\s*\{([\s\S]*?)\n        \}/);
            if (!м) return false;
            return (м[1].match(/^\s{12}[a-z_]+:/gm) || []).length === 19;
        });
    })(),
    'Девятнадцать — это замер сайта 29.10. Меньше в любом языке значит,\n' +
    'что человек на этом языке увидит СЫРОЙ КОД базы вместо объяснения.');

правило('у каждого ключа дома есть слово на всех трёх языках',
    (function () {
        const ключи = new Set();
        const re = /'(ok|stPrefix|inMainDraw|changedKept|refusedGeneric|title[A-Z][A-Za-z]*|short[A-Z][A-Za-z]*|note[A-Z][A-Za-z]*|st[A-Z][A-Za-z]*|review[A-Z][A-Za-z]*)'/g;
        let м;
        while ((м = re.exec(дом)) !== null) ключи.add(м[1]);
        if (ключи.size < 20) return false;
        const блоки = слова.split(/T\.(?:ru|en|kg)\s*=/).slice(1);
        if (блоки.length !== 3) return false;
        for (const б of блоки) {
            for (const к of ключи) {
                const зн = б.match(new RegExp('\\n\\s{8}' + к + ":\\s*'([^']*)'"));
                if (!зн || !зн[1].trim()) return false;
            }
        }
        return true;
    })(),
    'Ключ из дома приходит — слова по нему нет: человек увидит пустоту.\n' +
    'Ключи собираются ИЗ ТЕКСТА ДОМА, а не держатся списком руками.');

[[САЙТ, 'сайта'], [ПРИЛ, 'приложения']].forEach(([ф, имя]) => {
    const т = безКом(чит(ф));

    /* ПРИЗНАК СУЖЕН ДО СВОЕГО АДРЕСА: первая редакция запрещала рядом
       стоящие `getSession()` и `fetch(` — и падала на САЙТЕ, где так
       зовётся ДРУГАЯ функция, `ensure-player-card`. Чужой зов рядом —
       не беда этого куска. */
    правило('у ' + имя + ' нет своего зова функции допуска',
        !/functions\/v1\/tournament-register/.test(т) && /\.зов\(/.test(т),
        'Зов переехал в дом: сессия, токен, отсев пустых полей и\n' +
        'заголовки были написаны знак в знак в двух файлах.');

    правило('у ' + имя + ' нет своего дерева решений',
        !/partner_changed/.test(т) && !/'already_registered'/.test(т) &&
        !/rank_waitlist|draw_full|no_category/.test(т) && !/top_rank/.test(т),
        'Какую ветку показать, решает дом. Осталось дерево на месте —\n' +
        'два дерева, и одно из них однажды потеряет ветку, как уже\n' +
        'потеряло `partner_changed`.');

    правило('у ' + имя + ' нет своих слов на коды отказа',
        !/no_membership|ntrp_combined_exceeded|category_closed|entry_in_draw/.test(т),
        'Слова живут в `zayavka-texts.js`, по словарю на язык.');

    правило('у ' + имя + ' нет своего признака «заявка создана»',
        !/!==\s*'already_registered'/.test(т),
        'Одно выражение, и оно решает, поменяется ли кнопка. Стояло в\n' +
        'двух файлах знак в знак.');

    правило('у ' + имя + ' дом зовётся',
        /KSLT_ZAYAVKA/.test(т) && /\.зов\(/.test(т) &&
        /\.разобрать\(/.test(т) && /\.словами\(/.test(т) && /\.создана\(/.test(т),
        'Без зова работа не сделана.');

    правило('у ' + имя + ' язык выбирается продуктом',
        /KSLT_ZAYAVKA_TEXTS/.test(т) && /\.of\(/.test(т),
        'Дом языка не знает: у сайта он из `KSLT_YAZYK`, у приложения из\n' +
        '`KSLT_I18N`. Словарь берёт продукт и передаёт дому.');
});

правило('вид окна заявки приложения живёт в css, а не в строке js',
    !/injectStyles/.test(безКом(чит(ПРИЛ))) &&
    !/mob-reg-overlay\s*\{/.test(безКом(чит(ПРИЛ))) &&
    /\.mob-reg-overlay\s*\{/.test(безКомCss(чит('mobile/www/css/app.css'))),
    'ПРАВИЛО, ВЫВЕДЕННОЕ НА ОДНОМ КУСКЕ, ПРИМЕНЯЕТСЯ К СЛЕДУЮЩЕМУ БЕЗ\n' +
    'НОВОГО РАЗБОРА: у сайта те же правила строкой снял кусок 174, копия\n' +
    'приложения осталась. Правило в строке js не читает ни один сторож.');

/* МАСКА СТОРОЖИТ СВОЮ СЛЕПОТУ: краска названа в комментарии, который
   объясняет, что её сняли, и правило падало на этой записи. В css нет
   `//`, поэтому маска своя.
   Правило смотрит ТОЛЬКО файлы этого куска: `#ff3b30` живёт ещё в
   `mobile/www/js/screens/tournaments.js:580` инлайном, это чужой экран и
   свой кусок — записано находкой, а не правится здесь. */
правило('четвёртого красного `#ff3b30` в окне заявки больше нет',
    !/#ff3b30/i.test(безКомCss(чит('mobile/www/css/app.css'))) &&
    !/#ff3b30/i.test(безКом(чит(ПРИЛ))),
    'Описание компонента `Input` 25:5 называет его прямо: «the code\n' +
    'currently uses #ff3b30 here, a fourth red that is not in the\n' +
    'palette — it should become status/danger». Теперь `var(--danger)`.');

правило('приложение экранирует то, что пришло от сервера',
    (function () {
        const т = безКом(чит(ПРИЛ));
        return /function esc\s*\(/.test(т) &&
               /esc\(info\.title\)/.test(т) && /esc\(info\.text\)/.test(т) &&
               /esc\(info\.note\)/.test(т);
    })(),
    'В двух ветках текст приходит ОТ СЕРВЕРА: незнакомый код отказа и\n' +
    '`block_reason`, который пишет человек в админке. Сайт экранирует с\n' +
    'куска 157, приложение вставляло как есть.');

правило('дом и надписи подключены во всех разметках, где подключена заявка',
    РАЗМЕТКИ.length >= 17 && РАЗМЕТКИ.every(ф => {
        const т = чит(ф);
        return /kslt-zayavka\.js/.test(т) && /zayavka-texts\.js/.test(т);
    }),
    'Разметок с окном заявки ' + РАЗМЕТКИ.length + ', и каждая обязана\n' +
    'грузить дом и надписи: иначе кнопка «Записаться» упадёт на\n' +
    '`undefined`, и заявка не уйдёт никуда.\n' +
    'Без дома: ' + РАЗМЕТКИ.filter(ф => !/kslt-zayavka\.js/.test(чит(ф))).join(', ') +
    '\nБез надписей: ' + РАЗМЕТКИ.filter(ф => !/zayavka-texts\.js/.test(чит(ф))).join(', '));

правило('дом и надписи грузятся ДО того, кто их зовёт',
    РАЗМЕТКИ.every(ф => {
        const т = чит(ф);
        const д = т.indexOf('kslt-zayavka.js');
        const с = т.indexOf('zayavka-texts.js');
        const з = т.indexOf('tournament-register.js?');
        return д !== -1 && с !== -1 && з !== -1 && д < з && с < з;
    }),
    'Порядок ставится явно, а не на удачу тайминга.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else { console.log('  ок      заявка на турнир: все ' + держится + ' правил держатся · разметок ' + РАЗМЕТКИ.length + '\n'); }
