#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ВЫХОД ИЗ АККАУНТА — ТОЛЬКО ПО ОТВЕТУ СЕРВЕРА» (31.10).
 *
 * ЗАЧЕМ ОН ЕСТЬ — СЛУЧАЙ, А НЕ ОПАСЕНИЕ. Охрана страниц
 * (`js/auth-guard.js`) считала мёртвым входом ЛЮБУЮ ошибку от
 * `auth.getUser()` и выходила из аккаунта: `signOut`, чистка хранилища,
 * увод на форму входа. «Сервер ответил, что входа нет» и «до сервера не
 * дошли» — ДВА РАЗНЫХ СОБЫТИЯ, а ветка была одна. Ночной прогон 30.10
 * показал цену: 118 падений кабинета и админки, и ни одно не от вёрстки —
 * под нагрузкой запрос срывался, и страница выходила из аккаунта сама.
 * В жизни это метро, лифт, слабый вайфай.
 *
 * И БЕДА БЫЛА НЕ ОДНА, А ТРИ, ВСЕ ОДНОГО КОРНЯ — РЕШЕНИЕ ПРИНИМАЛОСЬ ПО
 * ОТСУТСТВИЮ ОТВЕТА:
 *   · `getUser` с ошибкой → выход из аккаунта;
 *   · `maybeSingle()` при сбое сети даёт `{ data: null, error }`, а ветка
 *     смотрела только на `data` — и показывала «Профиль не найден»,
 *     затирая `body.innerHTML` целиком;
 *   · `requireStaff`/`requireAdmin` смотрели на пустой `ksltProfile` и
 *     уводили сотрудника на главную.
 *
 * ПРАВИЛО ОТСЮДА: ОТСУТСТВИЕ ОТВЕТА — НЕ ОТВЕТ. Решение, которое стирает
 * вход или сообщает о беде, принимается ТОЛЬКО по тому, что сервер
 * сказал, а не по тому, что он молчит.
 *
 * ЧТО СТЕРЕЖЁТ. Признаки стоят на СОДЕРЖИМОМ ветвей, а не на их
 * положении: какие коды HTTP дают `true`, что отвечает `catch`, через
 * какую функцию решают роль, отделена ли ошибка запроса от пустого
 * ответа. Якорь не держится ни на номере строки, ни на версии файла.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ, И ЭТО НАЗВАНО. Правила читают файл как текст: что
 * `fetch` действительно отклоняется только без ответа — договор
 * платформы, а не наше утверждение, и проверяется прогоном, а не здесь.
 * Близнец дома в `mobile/www/js/` сторожится `check-mobilnye-kopii.js` —
 * второго правила на одно понятие здесь не заводится.
 *
 *   node tools/check-vyhod-po-otvetu.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');

function читать(о) {
    return fs.readFileSync(path.join(КОРЕНЬ, о), 'utf8');
}

const ДОМ_СЫРОЙ = читать('js/kslt-baza.js');
const ОХРАНА_СЫРАЯ = читать('js/auth-guard.js');
const ДОМ = безКомментариев(ДОМ_СЫРОЙ);
const ОХРАНА = безКомментариев(ОХРАНА_СЫРАЯ);

/** Тело функции по имени — от `имя = function` до парной скобки. */
function тело(текст, имя) {
    const i = текст.indexOf(имя);
    if (i === -1) return '';
    const о = текст.indexOf('{', i);
    if (о === -1) return '';
    let гл = 0;
    for (let j = о; j < текст.length; j++) {
        if (текст[j] === '{') гл++;
        else if (текст[j] === '}') { гл--; if (!гл) return текст.slice(о, j + 1); }
    }
    return текст.slice(о);
}

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

/* ══ ДОМ: ОДНО ОПРЕДЕЛЕНИЕ «ВХОД ОТОЗВАН» ══════════════════════════════ */

правило('дом базы объявляет «вход отозван»',
    /API\.входОтозван\s*=\s*function/.test(ДОМ),
    'Понятие «сервер сказал, что входа больше нет» живёт в\n' +
    '`js/kslt-baza.js` одним определением. Нет его — каждый зовущий\n' +
    'заведёт своё, и беда вернётся на первом же шве.');

const ТЕЛО_ОТОЗВАН = тело(ДОМ, 'API.входОтозван');

правило('«вход отозван» отвечает да только на 401 и 403',
    /status\s*===\s*401/.test(ТЕЛО_ОТОЗВАН) &&
    /status\s*===\s*403/.test(ТЕЛО_ОТОЗВАН) &&
    !/status\s*===\s*(?!401|403)\d+/.test(ТЕЛО_ОТОЗВАН),
    'Только 401 и 403 означают «этот токен больше не ваш». 5xx — это\n' +
    'беда сервера, 200 — живой вход, и ни то ни другое не повод\n' +
    'стирать вход человеку. Появился третий код — значит понятие\n' +
    'поехало, и решать это правкой правила нельзя.');

правило('отсутствие ответа отвечает «не отозван»',
    /\.catch\(function\s*\([^)]*\)\s*\{\s*return false;/.test(ТЕЛО_ОТОЗВАН),
    '`fetch` отклоняется ТОЛЬКО когда ответа не было вовсе: нет сети,\n' +
    'не разрешилось имя, прервали по сроку. Это не ответ сервера, и\n' +
    '`catch` обязан отвечать `false`. Вернёт `true` — вернётся та самая\n' +
    'беда: человек без связи теряет вход.');

правило('у щупа есть свой срок',
    /AbortController/.test(ТЕЛО_ОТОЗВАН) && /abort\(\)/.test(ТЕЛО_ОТОЗВАН),
    'Запрос без срока висит, пока браузер не сдастся, и охрана\n' +
    'держит страницу скрытой всё это время. Срок свой, а не чужой.');

правило('дом не выходит из аккаунта сам',
    !/signOut|removeItem/.test(ТЕЛО_ОТОЗВАН),
    'Дом отвечает да или нет. Решение — у зовущего: тот же ответ\n' +
    'нужен и охране страниц, и приложению, а поступают они иначе.');

/* ══ ОХРАНА: РЕШЕНИЕ ПО ОТВЕТУ, А НЕ ПО МОЛЧАНИЮ ══════════════════════ */

const ТЕЛО_ЖИВ = тело(ОХРАНА, 'async function живЛиВход');

правило('охрана переживает короткий сбой повторами',
    /var ПОВТОРЫ = \[\s*\d+/.test(ОХРАНА) && /ПОВТОРЫ\[i\]/.test(ТЕЛО_ЖИВ),
    'Блип короче полусекунды, и повтор его переживает, не отправляя\n' +
    'лишнего запроса никому. Повторов нет — щуп зовётся на каждую\n' +
    'икоту сети.');

правило('охрана спрашивает вход через повторы, а не напрямую',
    (function () {
        if (!/await живЛиВход\(\)/.test(ОХРАНА)) return false;
        /* СЧИТАЕМ ЗОВЫ ВНЕ `живЛиВход`, А НЕ ВСЕ: внутри их законно два —
           первый и повторный. Первая редакция правила требовала «ровно
           один» и упала на верном коде: ПРИБОР, СЧИТАЮЩИЙ НЕ ТО, ЧТО
           СТЕРЕЖЁТ, НЕ СТОРОЖИТ НИЧЕГО. */
        const снаружи = ОХРАНА.split(ТЕЛО_ЖИВ).join('');
        return (снаружи.match(/client\.auth\.getUser\(\)/g) || []).length === 0;
    })(),
    'Зов `client.auth.getUser()` в охране живёт ТОЛЬКО внутри `живЛиВход`.\n' +
    'Зов мимо повторов снова принесёт решение по первой же ошибке сети.');

правило('перед выходом из аккаунта спрашивают, отозван ли вход',
    /входОтозван\(/.test(ОХРАНА) &&
    /if \(!отозван\)/.test(ОХРАНА),
    'Ветка «мёртвый вход» обязана сперва отличить ответ сервера от его\n' +
    'отсутствия. Без этого `signOut` стирает живую сессию.');

правило('без связи вход не стирается',
    (function () {
        const т = тело(ОХРАНА, 'function безСвязи');
        return т.length > 0 && !/signOut|removeItem|location\.href/.test(т);
    })(),
    '`безСвязи` — это «открыли страницу по локальной сессии». Появился\n' +
    'там `signOut`, чистка хранилища или увод — понятие схлопнулось\n' +
    'обратно в выход, и правка бесполезна.');

правило('без связи страница всё равно показывается',
    /classList\.add\('auth-ready', 'kslt-bez-svyazi'\)/.test(ОХРАНА),
    'Признак `auth-ready` открывает страницу (css/dashboard.css:11,\n' +
    'css/admin.css:11). Не поставить его — человек увидит пустоту\n' +
    'вместо объяснения, то есть беду вместо сообщения о беде.');

правило('ошибка чтения профиля отделена от пустого ответа',
    /if \(profileResult\.error\)/.test(ОХРАНА) &&
    ОХРАНА.indexOf('if (profileResult.error)') <
        ОХРАНА.indexOf('if (!profileResult.data)'),
    '`maybeSingle()` при сбое сети даёт `{ data: null, error }`. Ветка\n' +
    '«профиля нет» затирает `body.innerHTML` целиком — значит на одном\n' +
    'оборванном запросе страница сообщит о беде, которой нет. Проверка\n' +
    'ошибки стоит ПЕРЕД проверкой пустоты.');

правило('роль решается одной функцией',
    /function рольСейчас\(\)/.test(ОХРАНА) &&
    /requireStaff[\s\S]{0,200}рольСейчас\(\)/.test(ОХРАНА) &&
    /requireAdmin[\s\S]{0,200}рольСейчас\(\)/.test(ОХРАНА),
    'Оба сторожа прав решают через `рольСейчас`. Смотреть на\n' +
    '`ksltProfile` напрямую — значит снова решать по отсутствию ответа\n' +
    'и уводить сотрудника на главную при сбое сети.');

правило('роль из хранилища берётся только без связи',
    (function () {
        const т = тело(ОХРАНА, 'function рольСейчас');
        if (!/kslt_role/.test(т)) return false;
        const i = т.indexOf("classList.contains('kslt-bez-svyazi')");
        const j = т.indexOf('kslt_role');
        return i !== -1 && j !== -1 && i < j;
    })(),
    'Запись `kslt_role` — быстрый ответ на время сбоя, и ничего не\n' +
    'разрешает: право на данные решает база. Но брать её при живой\n' +
    'связи значит верить вчерашней роли вместо сегодняшней.');

правило('про отсутствие связи сказано на трёх языках',
    (function () {
        const т = тело(ОХРАНА_СЫРАЯ, 'function безСвязи');
        return /KSLT_YAZYK\.выбрать\(/.test(т) &&
               /[A-Za-z]{4,}/.test(т) && /[а-яё]{4,}/i.test(т) && /[өүңҕ]/i.test(т);
    })(),
    'Сайт ведётся на трёх языках. Надпись на одном — это надпись,\n' +
    'которой два человека из трёх не прочтут.');

/* ══ ВЫВОД ════════════════════════════════════════════════════════════ */

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      выход по ответу сервера: все ' + всего + ' правил держатся');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  выход по ответу сервера — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
