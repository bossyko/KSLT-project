function блокВида(селектор) {
    const re = new RegExp('(^|\\})([^{}]*' + селектор.replace('.', '\\.') +
                          '[^{}]*)\\{([^}]*)\\}', 'm');
    const м = ВИД.match(re);
    return м ? { селекторы: м[2].trim(), тело: м[3] } : null;
}
