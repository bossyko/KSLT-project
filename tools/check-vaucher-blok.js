/* ---- 2. у близнецов своих тел нет. ЧИТАЕТСЯ ДЕРЕВО, а не текст: имена
          классов вроде `co-voucher-title` у них ОСТАЛИСЬ по делу — это
          довод зова, и текстовый поиск принял бы его за своё тело. ---- */
function зовыБазы(т) {
    const найдено = [];
    обойти(дерево(т), у => {
        if (у.type !== 'CallExpression' || !у.callee) return;
        const зов = т.slice(у.callee.start, у.callee.end);
        if (/\.rpc$/.test(зов) && у.arguments[0] && у.arguments[0].value === 'generate_voucher') {
            найдено.push('generate_voucher:' + у.loc.start.line);
        }
        if (/\.from$/.test(зов) && у.arguments[0] && у.arguments[0].value === 'discount_vouchers') {
            найдено.push('discount_vouchers:' + у.loc.start.line);
        }
    });
    обойти(дерево(т), у => {
        if (у.type === 'NewExpression' && у.callee && у.callee.name === 'QRCode') {
            найдено.push('new QRCode:' + у.loc.start.line);
        }
    });
    return найдено;
}
