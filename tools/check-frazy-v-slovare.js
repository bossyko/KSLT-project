if (ошибки.length) {
    console.log('  НЕ ТАК  фразы в словаре — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(([и, п]) => console.log('          x ' + и + '\n            ' + п.replace(/\n/g, '\n            ') + '\n'));
    process.exit(1);
}
console.log('  ок      фразы админки в словаре: 6 правил');
console.log('          зашитых фраз не осталось (было 155), кроме двух селекторов и отладки');
