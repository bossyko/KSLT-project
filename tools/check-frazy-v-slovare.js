/**
 * ЗАМОРОЗКА КУСКА 136 — ФРАЗЫ АДМИНКИ ЖИВУТ В СЛОВАРЕ ЦЕЛИКОМ.
 *
 * Кусок 135 увёл в словарь ПОДПИСИ и оставил 155 фраз: им не находилось
 * читаемого имени. Приём найден здесь: ФРАЗА ЗОВЁТСЯ ПО ВИДУ И ПРЕДМЕТУ,
 * А НЕ ПО ТЕКСТУ. Вид виден из места — Err, Ok, Warn, Msg, Ask, Hint,
 * Tip, — и даёт `brkDrawCancelledV` вместо `brkUEtihMatchey`.
 *
 * ВТОРОЕ, И ОНО ВАЖНЕЕ ИМЕНИ: 109 фраз из 151 собирались СКЛЕЙКОЙ — кусок
 * текста, число, ещё кусок. Такую фразу нельзя ни найти целиком, ни
 * перевести, ни переставить в ней слова: порядок задан расположением
 * плюсов. Теперь фраза лежит в словаре целиком, а места подстановки
 * помечены фигурными скобками и заполняются домом `A.фраза`.
 *
 * РАЗБОР ВЁЛСЯ НАСТОЯЩИМ ПАРСЕРОМ. Три самодельных обхода подряд дали три
 * ложных ответа: один упирался в собственные скобки литерала, второй
 * глядел в окно и принимал `console.error` строкой выше за признак
 * отладки, третий жадно поглощал тернарник целиком. НЕ ПИШИ ПАРСЕР,
 * КОГДА РЯДОМ ЛЕЖИТ НАСТОЯЩИЙ — acorn уже стоит в проекте.
 *
 *   node tools/check-frazy-v-slovare.js
 */
const fs = require('fs');
const path = require('path');
const acorn = require('acorn');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };
const КИР = /[А-Яа-яЁё]/;

const файлы = [];
(function обход(д) {
  fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
    const п = path.join(д, э.name);
    if (э.isDirectory()) обход(п);
    else if (э.name.endsWith('.js') && !э.name.endsWith('constants.js')) файлы.push(п);
  });
})(path.join('js', 'admin'));

function обойти(у, р, дело) {
  if (!у || typeof у.type !== 'string') return;
  дело(у, р);
  for (const к of Object.keys(у)) {
    if (к === 'type' || к === 'start' || к === 'end' || к === 'loc') continue;
    const v = у[к];
    if (Array.isArray(v)) v.forEach(x => x && typeof x.type === 'string' && обойти(x, у, дело));
    else if (v && typeof v.type === 'string') обойти(v, у, дело);
  }
}

/* 1. ДОМ ЕСТЬ И ЗНАЕТ КИРИЛЛИЦУ */
const UT = чит(path.join('js', 'admin', 'core', 'utils.js'));
правило('дом A.фраза заведён',
    /A\.фраза\s*=\s*function\s*\(\s*шаблон\s*,\s*значения\s*\)/.test(UT),
    'Дома подстановки нет. Без него фраза снова соберётся склейкой, и\n' +
    'порядок слов в ней будет задан расположением плюсов.');

правило('дом знает кириллические имена подстановки',
    /\[A-Za-zА-Яа-яЁё0-9_\$\]\+/.test(UT),
    'Имя подстановки здесь бывает кириллическим: `буква`, `двое`, `надо`.\n' +
    '`\\w` в регулярке КИРИЛЛИЦЫ НЕ ЗНАЕТ, и такой шаблон остался бы с\n' +
    'дыркой `{буква}` прямо на экране. Эта же ошибка в тот день дважды\n' +
    'сломала мои приборы: имя переменной обрывалось на первой букве.');

правило('пропущенная подстановка остаётся видимой',
    /return всё;/.test(UT),
    'Неизвестное имя должно остаться в тексте как есть.\n' +
    'НЕЗАПОЛНЕННОЕ МЕСТО ДОЛЖНО БРОСАТЬСЯ В ГЛАЗА — пустая дырка в фразе\n' +
    'не бросается, и ошибку никто не заметит.');

/* 2. ЗАШИТЫХ ФРАЗ НЕ ОСТАЛОСЬ, КРОМЕ ТРЁХ НАЗВАННЫХ */
const остаток = [];
файлы.forEach(ф => {
  const т = чит(ф);
  let д;
  try { д = acorn.parse(т, { ecmaVersion: 2020, locations: true }); }
  catch (e) { остаток.push(ф + ': НЕ РАЗБИРАЕТСЯ — ' + e.message.slice(0, 40)); return; }
  обойти(д, null, (у, р) => {
    if (у.type !== 'Literal' || typeof у.value !== 'string' || !КИР.test(у.value)) return;
    let a = у.start - 1; while (a >= 0 && /\s/.test(т[a])) a--;
    let b = у.end; while (b < т.length && /\s/.test(т[b])) b++;
    if (т[a] !== '(' || т[b] !== ')') return;
    /* селектор и отладка оставлены НАМЕРЕННО: это не текст человеку */
    if (р && р.type === 'CallExpression' && р.callee) {
      const имя = т.slice(р.callee.start, р.callee.end);
      if (/(?:querySelector(All)?|getAttribute|setAttribute|closest|matches)$/.test(имя)) return;
      if (/^console\./.test(имя)) return;
    }
    остаток.push(path.basename(ф) + ':' + у.loc.start.line + ' |' + у.value.slice(0, 40) + '|');
  });
});
правило('зашитых русских фраз в коде админки не осталось',
    остаток.length === 0,
    'Осталось: ' + остаток.length + ' (было 155 до куска)\n' +
    остаток.slice(0, 8).map(с => '  ' + с).join('\n') + '\n' +
    'Намеренно оставлены ТРИ и только три: два селектора `[data-да]` и\n' +
    '`[data-нет]` — это имена атрибутов, не текст; и одна строка\n' +
    '`console.log`, которую человек не видит. Они исключены по РОДИТЕЛЮ в\n' +
    'дереве разбора, а не по соседней строке: ПРИЗНАК, СМОТРЯЩИЙ В ОКНО,\n' +
    'ЛОВИТ СОСЕДА.');

/* 3. ФРАЗЫ ЗОВУТСЯ ЧЕРЕЗ ДОМ, А НЕ СКЛЕИВАЮТСЯ */
let зовов = 0;
файлы.forEach(ф => { зовов += (чит(ф).match(/A\.фраза\(/g) || []).length; });
правило('зовов A.фраза не меньше замеренных 16',
    зовов >= 16,
    'Зовов дома: ' + зовов + ', замерено 16.\n' +
    'Упало — значит фразу снова собрали склейкой. Это ПОЛ: новые фразы\n' +
    'только добавляются.');

/* 4. КАЖДОЕ МЕСТО ПОДСТАНОВКИ ЗАПОЛНЯЕТСЯ */
const СЛ = чит(path.join('js', 'admin', 'core', 'constants.js'));
const н0 = СЛ.indexOf('var L ='), о0 = СЛ.indexOf('{', н0);
let г = 0, з0 = -1;
for (let i = о0; i < СЛ.length; i++) {
  if (СЛ[i] === '{') г++; else if (СЛ[i] === '}') { г--; if (!г) { з0 = i; break; } }
}
const знач = {}; г = 0;
for (let i = о0; i <= з0; i++) {
  const c = СЛ[i];
  if (c === '{' || c === '[') г++; else if (c === '}' || c === ']') г--;
  if (г === 1) {
    const мм = /^[\s,]*([A-Za-z_$][\w$]*)\s*:\s*('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")/.exec(СЛ.slice(i));
    if (мм) { знач[мм[1]] = мм[2].slice(1, -1); i += мм[0].length - 1; }
  }
}
/* ЗОВЫ ИЩУТСЯ ПО ДЕРЕВУ РАЗБОРА, А НЕ РЕГУЛЯРКОЙ ПО ТЕКСТУ.
   Первая попытка этого правила упала на ПРИМЕРЕ В КОММЕНТАРИИ самого
   дома — третий раз за день, и всё та же семья: ЗАМОРОЗКА ЧИТАЕТ ФАЙЛ
   КАК ТЕКСТ И НЕ РАЗЛИЧАЕТ КОД И КОММЕНТАРИЙ. Парсер различает: в
   дереве комментариев нет вовсе, и выдумывать маску не нужно. */
const недозаполнены = [];
файлы.forEach(ф => {
  const т = чит(ф);
  let д;
  try { д = acorn.parse(т, { ecmaVersion: 2020, locations: true }); } catch (e) { return; }
  обойти(д, null, у => {
    if (у.type !== 'CallExpression' || !у.callee) return;
    if (т.slice(у.callee.start, у.callee.end) !== 'A.фраза') return;
    const первый = у.arguments[0];
    if (!первый || первый.type !== 'MemberExpression') return;
    const ключ = т.slice(первый.property.start, первый.property.end);
    const шаблон = знач[ключ];
    if (шаблон === undefined) {
      недозаполнены.push(path.basename(ф) + ':' + у.loc.start.line + ' -> L.' + ключ + ': ключа нет');
      return;
    }
    const места = [...шаблон.matchAll(/\{([A-Za-zА-Яа-яЁё0-9_$]+)\}/g)].map(x => x[1]);
    const второй = у.arguments[1];
    const дано = (второй && второй.type === 'ObjectExpression')
      ? второй.properties.map(p => т.slice(p.key.start, p.key.end).replace(/['"]/g, ''))
      : [];
    const нет = места.filter(и => дано.indexOf(и) === -1);
    if (нет.length) {
      недозаполнены.push(path.basename(ф) + ':' + у.loc.start.line + ' -> L.' + ключ + ': не дано ' + нет.join(', '));
    }
  });
});
правило('каждое место подстановки заполняется в зове',
    недозаполнены.length === 0,
    'Мест без значения: ' + недозаполнены.length + '\n' +
    недозаполнены.slice(0, 6).map(с => '  ' + с).join('\n') + '\n' +
    'Такое место останется на экране фигурными скобками. Оно ВИДНО —\n' +
    'и это лучше пустоты, — но правило ловит его раньше человека.');

/* 5. ИМЯ ФРАЗЫ НЕСЁТ ВИД */
const виды = /(?:Err|Ok|Warn|Msg|Ask|Hint|Tip)/;
const сВидом = Object.keys(знач).filter(к => виды.test(к));
/* ПОРОГ ЗАМЕНЁН ЗАМЕРЕННЫМ ЧИСЛОМ 24.10 (кусок 154), И ПОКАЗАЛ ЭТО ПРУВЕР.
   Стояло «не меньше 96» при 97 живых ключах: откат, снимавший вид у одного
   имени, давал 96 и правило НЕ РОНЯЛ. ПОРОГ С ЗАПАСОМ НЕ СТОРОЖИТ НИЧЕГО —
   то же нашлось у оболочки окна на куске 152 («не меньше восьми» при
   двенадцати). Теперь держится ЗАМЕРЕННОЕ, а рост числа — законное
   событие: он правится здесь с причиной, как и снижение. */
const ВИДОВ = 97;
правило('ключей с видом в имени — замеренные ' + ВИДОВ,
    сВидом.length === ВИДОВ,
    'Ключей с видом: ' + сВидом.length + ', замерено ' + ВИДОВ + '.\n' +
    'ВИД — ЭТО ЧАСТЬ ИМЕНИ, А НЕ УКРАШЕНИЕ: по нему видно, что перед\n' +
    'тобой — ошибка, подтверждение или подсказка, — ещё до чтения текста.\n' +
    'Меньше — у фразы отняли вид. Больше — завели новую, и это хорошо:\n' +
    'число живёт здесь и правится с причиной.');

