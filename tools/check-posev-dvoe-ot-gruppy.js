#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ДВОЕ СЕЯНЫХ ОТ КАЖДОЙ ГРУППЫ» (лиги, 03.11).
 *
 * РЕШЕНИЕ КОСТИ: «согласно от количества групп в каждой группе было 2
 * сеяных — если общее количество групп 4, то будет 8 сеяных, и они будут
 * сеяться 1–4 в разных группах, потом 8 идёт на 1 сеяного, 7 на 2 и так
 * далее».
 *
 * ЧТО ЗДЕСЬ ЗАМОРОЖЕНО — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   · формула позиций ПРОДОЛЖАЕТ продуктовые списки, а не заменяет их;
 *   · сеяных ровно вдвое больше числа групп (пока в лиге есть вторые);
 *   · номера идут эшелонами: сперва все первые, потом все вторые;
 *   · земляки не встречаются в первом круге НИ В ОДНОМ раскладе.
 *
 * ПРИБОР ГОНЯЕТ НАСТОЯЩУЮ ФУНКЦИЮ, А НЕ ЕЁ ОПИСАНИЕ: `позицииПосева`
 * берётся из `js/tournament-generator.js`, посев лиги — из
 * `buildLeagueSEBracket`. Проверка словами о коде доказывает только то,
 * что слова написаны.
 *
 *   node tools/check-posev-dvoe-ot-gruppy.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');

const ГЕН = чит('js/tournament-generator.js');
const СЕТКА = чит('js/admin/sections/bracket.js');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');
const СЕТч = безКом(СЕТКА);

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ─────────── НАСТОЯЩАЯ ФУНКЦИЯ ПОЗИЦИЙ ─────────── */

const мСписки = /var SEED_POSITIONS = \{[\s\S]*?\n\};/.exec(ГЕН);
const мФункция = /function позицииПосева\(размер, сеяных\) \{[\s\S]*?\n\}/.exec(ГЕН);
if (!мСписки || !мФункция) {
    console.log('\n  БЕДА    в tournament-generator.js нет SEED_POSITIONS или позицииПосева\n');
    process.exit(1);
}
const среда = new Function(
    мСписки[0] + '\n' + мФункция[0] +
    '\nreturn { SEED_POSITIONS: SEED_POSITIONS, позицииПосева: позицииПосева };')();
const { SEED_POSITIONS, позицииПосева } = среда;

/* ─────────── 1. ФОРМУЛА ПРОДОЛЖАЕТ, А НЕ ЗАМЕНЯЕТ ─────────── */

const разошлись = Object.keys(SEED_POSITIONS).filter(р => {
    const сп = SEED_POSITIONS[р];
    const ф = позицииПосева(Number(р), сп.length);
    return JSON.stringify(ф) !== JSON.stringify(сп);
});

правило('формула воспроизводит каждый список SEED_POSITIONS до числа',
    разошлись.length === 0,
    'Формула разошлась со списками на размерах: ' + разошлись.join(', ') + '.\n' +
    '      Списки — ЗАМОРОЖЕННОЕ РЕШЕНИЕ: по ним стоят все идущие турниры.\n' +
    '      Формула заведена, чтобы ПРОДОЛЖИТЬ их на большее число сеяных, а\n' +
    '      не чтобы переразложить сетку. Первая попытка формулы (обычная\n' +
    '      рекурсия «x и N+1−x») давала ДРУГОЕ, и видно это только сверкой:\n' +
    '      ОБЕ СХЕМЫ ЗАКОННЫ, НО У НАС СВОЯ.');

/* `.every` ПРОПУСКАЕТ ДЫРЫ РАЗРЕЖЕННОГО МАССИВА, и первое написание этого
   правила МОЛЧАЛО на `new Array(n)` с незаполненными ячейками: прувер
   сломал формулу так, что половина слотов осталась пустой, — а правило
   прошло. Считаем индексным циклом: он видит дыры. */
правило('позиции не повторяются и не выходят за сетку',
    [4, 8, 16, 32, 64, 128].every(р => {
        const п = позицииПосева(р, р);
        if (п.length !== р) return false;
        const видел = {};
        for (let i = 0; i < р; i++) {
            const с = п[i];
            if (!(с >= 1 && с <= р) || видел[с]) return false;
            видел[с] = true;
        }
        return true;
    }),
    'Формула выдала повтор слота или слот вне сетки. Два сеяных в одной\n' +
    '      клетке — это потерянный участник: один перезапишет другого молча.');

/* ─────────── 2. ПОСЕВ ЛИГИ — ПРОГОН, А НЕ ЧТЕНИЕ ─────────── */

/* Тот же расклад, что делает `buildLeagueSEBracket`: эшелоны и разведение
   земляков. Держится в приборе, потому что продукт зовёт его внутри
   async-обработчика, который сюда не поднять. Сверка с кодом — правилами
   ниже: если продукт уедет от этого описания, они упадут. */
function раскладЛиги(групп, вЛигу) {
    const люди = [];
    for (let g = 0; g < групп; g++)
        for (let м = 1; м <= вЛигу; м++)
            /* СИЛА НАРОЧНО ПЕРЕКРЫВАЕТСЯ МЕЖДУ МЕСТАМИ: второе место сильной
               группы бывает сильнее первого места слабой — так в жизни и так
               ломается замысел, если эшелоны пересортировать поверх. Подстава,
               где первые всегда сильнее вторых, этого не поймала бы. */
            люди.push({ id: 'G' + g + 'M' + м, groupIdx: g, place: м,
                        сила: (групп - g) * 10 - м });

    let drawSize = 2;
    while (drawSize < люди.length) drawSize *= 2;

    const поГруппам = {};
    люди.forEach(q => (поГруппам[q.groupIdx] = поГруппам[q.groupIdx] || []).push(q));
    const первые = [], вторые = [];
    Object.keys(поГруппам).forEach(г => {
        const ряд = поГруппам[г].slice().sort((a, b) => a.place - b.place);
        if (ряд[0]) первые.push(ряд[0]);
        if (ряд[1]) вторые.push(ряд[1]);
    });
    const посиле = (a, b) => b.сила - a.сила;
    первые.sort(посиле); вторые.sort(посиле);

    const seeds = первые.concat(вторые);
    const seedCount = Math.min(seeds.length, drawSize);
    const поз = позицииПосева(drawSize, seedCount);

    const половинаСлота = с => (с <= drawSize / 2 ? 0 : 1);
    const первых = первые.length;

    const половинаГруппы = {};
    for (let i = 0; i < первых && i < поз.length; i++) {
        половинаГруппы[seeds[i].groupIdx] = половинаСлота(поз[i]);
    }
    const номераПоПоловинам = [[], []];
    for (let н = первых; н < seedCount; н++) номераПоПоловинам[половинаСлота(поз[н])].push(н);

    const вторыеПоСиле = seeds.slice(первых, seedCount);
    const расставлены = [];
    вторыеПоСиле.forEach(у => {
        const своя = половинаГруппы[у.groupIdx];
        const надо = (своя === undefined) ? -1 : 1 - своя;
        const откуда = (надо !== -1 && номераПоПоловинам[надо].length)
            ? номераПоПоловинам[надо]
            : (номераПоПоловинам[0].length ? номераПоПоловинам[0] : номераПоПоловинам[1]);
        if (!откуда || !откуда.length) return;
        расставлены.push({ номер: откуда.shift(), кто: у });
    });
    расставлены.forEach(р => { seeds[р.номер] = р.кто; });

    /* КРУГ ВСТРЕЧИ, А НЕ ТОЛЬКО ПЕРВЫЙ КРУГ. Прежняя редакция этого правила
       мерила лишь первый круг и показывала ноль столкновений, пока `A1` и
       `A2` спокойно сходились в ПОЛУФИНАЛЕ. Нашёл Костя глазами.
       ПРИБОР, МЕРЯЮЩИЙ ТОЛЬКО ПЕРВЫЙ КРУГ, ПОДТВЕРЖДАЕТ ПЕРВЫЙ КРУГ. */
    const кругВстречи = (i, j) => { let r = 1, a = i, b = j;
        while ((a >> 1) !== (b >> 1)) { a >>= 1; b >>= 1; r++; } return r; };

    /* Слот каждого сеяного → индекс в сетке (0-based), чтобы считать круг. */
    const вСетке = new Array(drawSize).fill(null);
    for (let i = 0; i < seedCount; i++) вСетке[поз[i] - 1] = seeds[i];

    let раньшеВсего = 99;
    for (let i = 0; i < drawSize; i++) for (let j = i + 1; j < drawSize; j++) {
        if (!вСетке[i] || !вСетке[j]) continue;
        if (вСетке[i].groupIdx !== вСетке[j].groupIdx) continue;
        const к = кругВстречи(i, j);
        if (к < раньшеВсего) раньшеВсего = к;
    }
    const кругов = Math.round(Math.log2(drawSize));

    return { drawSize, сеяных: seedCount, первых, кругов,
             раньшеВсего: раньшeВсегоИли(раньшеВсего), seeds, поз };

    function раньшeВсегоИли(з) { return з === 99 ? кругов : з; }
}

const СЛУЧАИ = [[2, 2], [3, 2], [4, 2], [5, 2], [6, 2], [8, 2], [4, 3], [2, 4], [3, 4], [4, 4]];
const сЗемляками = СЛУЧАИ.filter(([г, л]) => {
    const р = раскладЛиги(г, л);
    /* При «выходят двое» планка — финал. Если в лигу уходит больше двух от
       группы, развести всех по двум половинам невозможно в принципе, и
       планка там мягче: не первый круг. Так же рассуждает сторож обычной
       сетки, и это НЕ послабление, а предел расклада. */
    return л >= 3 ? р.раньшеВсего < 2 : р.раньшеВсего < р.кругов;
});

правило('земляки сходятся не раньше финала — та же планка, что в сетке',
    сЗемляками.length === 0,
    'Земляки сходятся раньше финала: ' +
    сЗемляками.map(([г, л]) => г + ' групп по ' + л).join(', ') + '.\n' +
    '      ПЛАНКА ВЗЯТА С ОБЫЧНОЙ СЕТКИ (`раскладСлотов`, 09.10): выходят\n' +
    '      двое — земляки не раньше ФИНАЛА. Половин две, членов группы двое,\n' +
    '      и у каждого второго места есть обязанность уйти в половину, где\n' +
    '      нет его первого. Слово Кости: «А1 вверх идёт, А2 вниз сетки, и\n' +
    '      тогда они точно не встретятся».\n' +
    '      ПЕРВАЯ РЕДАКЦИЯ ЭТОГО ПРАВИЛА МЕРИЛА ТОЛЬКО ПЕРВЫЙ КРУГ и честно\n' +
    '      показывала ноль, пока `A1` и `A2` сходились в ПОЛУФИНАЛЕ.');

правило('сеяных вдвое больше числа групп, пока в лиге есть вторые',
    СЛУЧАИ.every(([г, л]) => {
        const р = раскладЛиги(г, л);
        const ждём = Math.min(л >= 2 ? г * 2 : г, р.drawSize);
        return р.сеяных === ждём;
    }),
    'Число сеяных разошлось с числом групп. Решение Кости: ДВОЕ от каждой\n' +
    '      группы — четыре группы дают восемь сеяных.');

правило('номера идут эшелонами: сперва все первые, потом все вторые',
    СЛУЧАИ.every(([г, л]) => {
        if (л < 2) return true;
        const р = раскладЛиги(г, л);
        /* Первые `первых` номеров — места 1 своих групп, дальше — места 2. */
        return р.seeds.slice(0, р.первых).every(s => s.place === 1) &&
               р.seeds.slice(р.первых, р.сеяных).every(s => s.place === 2);
    }),
    'Эшелоны перемешались: среди первых номеров оказалось второе место или\n' +
    '      наоборот. Общая пересортировка по силе СЛОМАЛА БЫ ЗАМЫСЕЛ — сильный\n' +
    '      второй обошёл бы слабого победителя группы и встал напротив другого\n' +
    '      победителя. Порядок силы живёт ВНУТРИ эшелона, а не поверх него.');

правило('1-й встречает последнего, 2-й предпоследнего — слово Кости',
    (function () {
        const р = раскладЛиги(4, 2);     /* 4 группы → 8 сеяных → сетка 8 */
        if (р.сеяных !== 8 || р.drawSize !== 8) return false;
        const пары = [];
        for (let i = 0; i < 8; i++) {
            const с = р.поз[i];
            const соседний = р.поз.indexOf((с % 2 === 1) ? с + 1 : с - 1);
            if (соседний > i) пары.push((i + 1) + '-' + (соседний + 1));
        }
        return пары.sort().join(' ') === '1-8 2-7 3-6 4-5';
    })(),
    'Пары первого круга при четырёх группах разошлись с «8 идёт на 1,\n' +
    '      7 на 2». Это и есть схема, названная Костей словами; числа её\n' +
    '      подтвердили, и она заморожена именно в таком виде.');

/* ─────────── 3. ПРОДУКТ ДЕЛАЕТ ТО ЖЕ, ЧТО ПРИБОР ─────────── */

правило('лига берёт двоих от группы, а не лучшего',
    /var ряд = поГруппам\[г\]\.slice\(\)\.sort/.test(СЕТч) &&
    /if \(ряд\[1\]\) вторыеВЛиге\.push\(ряд\[1\]\)/.test(СЕТч) &&
    !/var minPlace = qualified\.reduce/.test(СЕТч),
    'Лига снова сеет только лучшего от группы (`place === minPlace`).\n' +
    '      Решение Кости 03.11 — ДВОЕ от каждой группы.');

правило('позиции лиги берутся функцией, а не коротким списком',
    /var seedPositions = позицииПосева\(drawSize, seedCount\)/.test(СЕТч),
    'Посев лиги снова читает `SEED_POSITIONS[drawSize]`. Для сетки 8 там\n' +
    '      ЧЕТЫРЕ позиции, а сеяных до восьми: пятому вставать некуда, и он\n' +
    '      молча уедет в общую кучу несеяных.');

правило('продукт разводит земляков ПО ПОЛОВИНАМ, а не обменом в первом круге',
    /var половинаСлота = function \(слот\) \{ return слот <= drawSize \/ 2/.test(СЕТч) &&
    /var надо = \(своя === undefined\) \? -1 : 1 - своя;/.test(СЕТч) &&
    !/function землякиУ\(номер\)/.test(СЕТч),
    'Лига снова разводит земляков обменом номеров в первом круге. Так беда\n' +
    '      уезжает кругом дальше: первый круг чист, а `A1` и `A2` сходятся в\n' +
    '      ПОЛУФИНАЛЕ. Второму месту нужна ПОЛОВИНА, противоположная своему\n' +
    '      первому, — тогда встреча не раньше финала.');

правило('номера вторых берутся из чужой половины, победители не двигаются',
    /номераПоПоловинам\[половинаСлота\(seedPositions\[н\]\)\]\.push\(н\)/.test(СЕТч) &&
    /var вторыеПоСиле = seeds\.slice\(первых, seedCount\)/.test(СЕТч) &&
    /расставлены\.forEach\(function \(р\) \{ seeds\[р\.номер\] = р\.кто; \}\)/.test(СЕТч),
    'Раздача номеров вторым местам больше не смотрит на половины, или она\n' +
    '      трогает победителей групп. Двигать победителей значит отнимать\n' +
    '      заслуженный номер из-за чужого соседства.');

/* ─────────── СТЕНД ПОВТОРЯЕТ ПРОДУКТ, А НЕ СВОЮ ВЫДУМКУ ─────────── */

const СТЕНД = безКом(чит('maket/stend-setka-dannye.js'));

правило('стенд собирает лиги функцией продукта, а не своей формулой',
    /A\.собратьСеткуЛиги\(Р\.турнир, люди, лига/.test(СТЕНД) &&
    !/Первый круг: сильнейший со слабейшим/.test(чит('maket/stend-setka-dannye.js')) &&
    /A\.собратьСеткуЛиги = buildLeagueSEBracket/.test(СЕТч),
    'Стенд снова раскладывает лиги САМ. Его формула была «сильнейший со\n' +
    '      слабейшим», и она разошлась с продуктом в тот день, когда решено\n' +
    '      сеять двоих от группы: стенд показывал бы расклад, которого в\n' +
    '      админке нет. СТЕНД, НЕ ПОВТОРЯЮЩИЙ ПРОДУКТ, ВРЁТ — и врёт\n' +
    '      убедительно: клетки на месте, имена верные, посев чужой.\n' +
    '      По этому стенду Костя смотрит посев ГЛАЗАМИ, и смотреть он должен\n' +
    '      на продукт, а не на мою выдумку о нём.');

правило('стенд передаёт БРОСОК от зерна, а не само зерно',
    /window\.KSLT_RULES\.бросок\(Р\.турнир\.draw_seed \|\| 1\)/.test(СТЕНД),
    'Стенд передаёт в сборку лиги число вместо броска. `KSLT_RULES.перемешать`\n' +
    '      честно отказывается («нужен бросок от зерна, иначе жеребьёвку не\n' +
    '      повторить»), и стенд навсегда остаётся на «грузится…» — БЕЗ единого\n' +
    '      слова на экране. Моя ошибка 03.11, нашлась только следом из консоли:\n' +
    '      ОТКАЗ, КОТОРЫЙ НЕ ВИДЕН НА ЭКРАНЕ, ВЫГЛЯДИТ КАК ЗАВИСАНИЕ.\n' +
    '      Продукт делает то же через `жребийТурнира`, которая и зовёт `бросок`.');

/* ─────────── ВЫВОД ─────────── */

const всего = 11;
console.log('');
if (!ошибки.length) {
    const р4 = раскладЛиги(4, 2);
    console.log('  ок      посев лиг: все ' + всего + ' правил держатся');
    console.log('          4 группы → ' + р4.сеяных + ' сеяных, сетка ' + р4.drawSize +
                ', земляки сходятся в круге ' + р4.раньшеВсего + ' из ' + р4.кругов + ' (финал)');
    console.log('          формула продолжает все ' + Object.keys(SEED_POSITIONS).length +
                ' списков SEED_POSITIONS до числа');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  посев лиг — ' + ошибки.length + ' из ' + всего + ' правил не держится');
console.log('');
ошибки.forEach(о => {
    console.log('          ✗ ' + о.имя);
    console.log('            ' + о.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
