/**
 * ЗАМОРОЗКА «ДОСТУП СВЕРЯЕТСЯ РАВЕНСТВОМ, А НЕ ВХОЖДЕНИЕМ»
 * (ветка К, кусок 190, 27.10.2026).
 *
 * ЗАМЕР 27.10. В девяти функциях доступ проверялся так:
 *     const serviceKey = Deno.env.get('SUPABASE_SERVICE_ROLE_KEY') || ''
 *     authHeader.includes(serviceKey)
 * У пустой строки `includes('')` ИСТИНЕН ДЛЯ ЛЮБОГО ЗАГОЛОВКА. Пока ключ
 * на месте, всё работает; в день, когда его удалят (а это записано как
 * К1), переменная опустеет — и тридцать две функции начнут пускать кого
 * угодно. Беда ждала ровно того дня, когда мы соберёмся чинить ключ.
 *
 * ЧЕТЫРЕ ИЗ ДЕВЯТИ не имели никакой защиты вовсе, пять прикрывались
 * `!serviceKey ||` — то есть half of the fix уже кто-то писал, но
 * неодинаково. ОДИН ВИД СВЕРКИ НА ВСЕ МЕСТА: иначе разница между ними
 * и есть будущая дыра.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ: не «девять мест», а «во всех местах, где
 * сверяется служебный ключ, сверка одна и та же, строгая, и пустой ключ
 * никого не пускает».
 *
 *   node tools/check-sverka-kluchom.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* КОММЕНТАРИИ ГАСЯТСЯ ПРОБЕЛАМИ. Признак, читающий пояснения, сторожит
   текст, а не продукт: в самих пояснениях прежняя опасная форма названа
   дословно, и без гашения правило падало бы на собственном рассказе. */
const гасить = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/^([ \t]*)\/\/[^\n]*$/gm, (м, о) => о + ' '.repeat(Math.max(0, м.length - о.length)));

const ПАПКА = path.join(КОРЕНЬ, 'supabase', 'functions');
const функции = fs.readdirSync(ПАПКА)
    .filter(д => fs.existsSync(path.join(ПАПКА, д, 'index.ts')))
    .map(д => ({ имя: д, текст: гасить(fs.readFileSync(path.join(ПАПКА, д, 'index.ts'), 'utf8')) }));

/* ── 1. ВХОЖДЕНИЯ БОЛЬШЕ НЕТ ─────────────────────────────────────────── */
const свхождением = функции.filter(ф => /authHeader\s*\.\s*includes\s*\(/.test(ф.текст));
правило('доступ нигде не сверяется вхождением',
    свхождением.length === 0,
    'Сверка через `authHeader.includes(...)` вернулась в: ' +
    свхождением.map(ф => ф.имя).join(', ') + '.\n' +
    'ВХОЖДЕНИЕ — НЕ СВЕРКА. У пустого ключа `includes(\'\')` истинен для\n' +
    'любого заголовка, и функция пустит кого угодно. Нужно равенство.');

/* ── 2. ОДИН ВИД НА ВСЕ МЕСТА ────────────────────────────────────────── */
const ФОРМА = /serviceKey !== ''\s*&&\s*\(authHeader === 'Bearer ' \+ serviceKey \|\| authHeader === serviceKey\)/;
const сверяют = функции.filter(ф => /\bserviceKey\b/.test(ф.текст) && /authHeader/.test(ф.текст)
    && /(isServiceRole|isInternal|if \(!\()/.test(ф.текст));
const сФормой = сверяют.filter(ф => ФОРМА.test(ф.текст));
правило('сверка служебного ключа везде одной формы',
    сверяют.length > 0 && сверяют.length === сФормой.length,
    'Мест, где сверяется служебный ключ: ' + сверяют.length +
    ', из них в общей форме: ' + сФормой.length + '.\n' +
    'Разошлись: ' + сверяют.filter(ф => !ФОРМА.test(ф.текст)).map(ф => ф.имя).join(', ') + '.\n' +
    'ОДИН ВИД СВЕРКИ НА ВСЕ МЕСТА: разница между ними и есть будущая дыра.\n' +
    'Так оно и было — четыре места без защиты, пять с половинчатой.');

/* ── 3. ПУСТОЙ КЛЮЧ НИКОГО НЕ ПУСКАЕТ ────────────────────────────────── */
const безОтказа = сверяют.filter(ф => !/serviceKey !== ''/.test(ф.текст));
правило('пустой ключ никого не пускает',
    безОтказа.length === 0,
    'Нет отказа на пустом ключе в: ' + безОтказа.map(ф => ф.имя).join(', ') + '.\n' +
    'Это ровно тот случай, ради которого правило и заведено: ключ удалят,\n' +
    'переменная опустеет, и проверка станет пропускать всех.');

/* ── 4. ПАРОЛЬ РАСПИСАНИЯ ТОЖЕ СВЕРЯЕТСЯ РАВЕНСТВОМ ──────────────────── */
/* ПРАВИЛО СМОТРИТ НА СМЫСЛ, А НЕ НА НАПИСАНИЕ. Первая редакция требовала
   только утвердительную форму `===` и объявила кривыми четыре места, где
   стоит отрицательная `!==` с отказом на пустом пароле. Код был прав,
   правило — нет. Требуется ровно две вещи: сравнение идёт с ПОЛНОЙ
   строкой `Bearer ${cronSecret}`, и нигде нет вхождения. */
const сCron = функции.filter(ф => /cronSecret/.test(ф.текст));
const кривые = сCron.filter(ф =>
    !/`Bearer \$\{cronSecret\}`/.test(ф.текст) || /includes\s*\(\s*cronSecret/.test(ф.текст));
правило('пароль расписания сверяется полной строкой, а не вхождением',
    сCron.length > 0 && кривые.length === 0,
    'Сверка `cronSecret` не полной строкой или через вхождение в: ' +
    кривые.map(ф => ф.имя).join(', ') + '.\n' +
    'Тот же разбор, что и для служебного ключа: вхождение — не сверка.');

/* ── 5. ХРАПОВИК МЕСТ ────────────────────────────────────────────────── */
const ПОЛ_МЕСТ = 9;
правило('мест сверки не становится меньше замеренного',
    сверяют.length >= ПОЛ_МЕСТ,
    'Мест сверки служебного ключа: ' + сверяют.length + ' при поле ' + ПОЛ_МЕСТ + '.\n' +
    'Стало меньше — значит проверку где-то СНЯЛИ, а не починили.');

const ВСЕГО = 5;
if (ошибки.length) {
    console.log('\n  СВЕРКА КЛЮЧОМ — ПРАВИЛО УПАЛО (' + ошибки.length + ' из ' + ВСЕГО + ')\n');
    ошибки.forEach(о => { console.log('  x ' + о.имя); console.log('    ' + о.подсказка.split('\n').join('\n    ') + '\n'); });
    process.exit(1);
}
console.log('  v сверка ключом: ' + ВСЕГО + ' правил, мест сверки ' + сверяют.length +
            ' (пол ' + ПОЛ_МЕСТ + '), все одной формы');
