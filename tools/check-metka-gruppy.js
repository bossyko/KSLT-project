/**
 * ЗАМОРОЗКА: ОТКУДА ПРИЕХАЛ ЧЕЛОВЕК В КЛЕТКЕ — ОДНА КАРТА НА ПРОДУКТ.
 *
 * Просьба Кости, сказанная трижды: «в админке показывается, кто с какой
 * группы выходит куда, а на публичной нет — может, также отрисовать её с
 * G1 F1». Метку строила только админка, и зритель её не видел.
 *
 * ЧЕГО ЭТИ ПРАВИЛА СТЕРЕГУТ. Соблазн был простой: скопировать цикл из
 * админки на страницу турнира. Тогда одно понятие получило бы два
 * определения, и беда родилась бы ровно на шве — как она уже родилась у
 * МЕСТА В РЕЙТИНГЕ (02.10: 161-е место при 105 строках) и у РУЧНЫХ МЕСТ.
 *
 * РУЧНЫЕ МЕСТА — НАЙДЕНО ПО ДОРОГЕ И ЗАКРЫТО ТУТ ЖЕ. Проверка «набор мест
 * остался тем же» жила ТОЛЬКО в админке (`bracket.js:6278`, девять
 * вызовов), а страница турнира применяла перестановку двумя своими
 * копиями (`tournament-detail.js:1657` и `:1951`) БЕЗ неё. Метка строится
 * из места — значит без этой проверки метки у менеджера и у зрителя
 * разошлись бы молча.
 *
 *   node tools/check-metka-gruppy.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ГРУППЫ  = чит('js/group-standings.js');
const ГРУППЫч = безКом(ГРУППЫ);
const МОБ     = чит('mobile/www/js/group-standings.js');
const СЕТч    = безКом(чит('js/admin/sections/bracket.js'));
const СТРч    = безКом(чит('js/tournament-detail.js'));
const CSSадм  = безКом(чит('css/admin.css'));
const CSSстр  = безКом(чит('css/tournament-detail.css'));

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ── 1. КАРТА СТРОИТСЯ В ОДНОМ МЕСТЕ ────────────────────────────────── */
правило('общий модуль отдаёт карту меток',
    /меткиИгроков:\s*меткиИгроков/.test(ГРУППЫч) &&
    /function\s+меткиИгроков\s*\(/.test(ГРУППЫч),
    'js/group-standings.js больше не отдаёт `меткиИгроков`. Карта ' +
    '«кто из какой группы вышел» снова станет считаться в каждом экране ' +
    'по-своему, и метка у менеджера разойдётся с меткой у зрителя');

/* Якорь держится на СОДЕРЖИМОМ тела, а не на том, что имя где-то
   встретилось: функция обязана звать общий расчёт и общую перестановку,
   иначе она посчитает места своим способом. */
const телоМеток = (ГРУППЫч.match(/function\s+меткиИгроков[\s\S]*?\n    \}/) || [''])[0];
правило('карта считает места общим расчётом и общей перестановкой',
    /ручныеМеста\(\s*расчёт\(/.test(телоМеток),
    '`меткиИгроков` перестала звать `расчёт` вместе с `ручныеМеста`. ' +
    'Метка выводится из МЕСТА: посчитав место иначе, она назовёт другую ' +
    'группу тому же человеку');

/* ── 2. АДМИНКА БЕРЁТ КАРТУ ОТТУДА ЖЕ ───────────────────────────────── */
правило('админка не строит карту своим циклом',
    /playerGroupLabel\s*=\s*KSLT_GROUPS\.меткиИгроков\(/.test(СЕТч) &&
    !/playerGroupLabel\[[^\]]+\]\s*=/.test(СЕТч),
    'в админке снова появилось своё построение `playerGroupLabel`. Было ' +
    'именно так до 02.10, и поэтому метку видел только менеджер');

/* ── 3. СТРАНИЦА ТУРНИРА — ТОЖЕ ─────────────────────────────────────── */
правило('страница турнира берёт карту из общего модуля',
    /tdМеткиГрупп\s*=\s*KSLT_GROUPS\.меткиИгроков\(/.test(СТРч),
    'страница турнира перестала брать метки у `KSLT_GROUPS.меткиИгроков`. ' +
    'Либо метка пропала с публичной сетки, либо её считают здесь заново');

/* ПОРЯДОК: сброс стоит ДО заполнения. `indexOf` отдаёт -1, когда строки
   нет вовсе, и -1 меньше чего угодно — поэтому сперва требуем, чтобы обе
   нашлись, иначе правило замолчит ровно тогда, когда сброс исчезнет. */
/* ЯКОРЬ НЕ ДОЛЖЕН ПОПАСТЬ В ОБЪЯВЛЕНИЕ. `var tdМеткиГрупп = {};` стоит
   в начале файла и содержит ту же подстроку, что и сброс: правило,
   написанное простым `indexOf`, держалось на объявлении и молчало, когда
   сброс убирали. Поймал прувер 02.10. Берём сброс с отступом — то есть
   тот, что стоит ВНУТРИ функции, — и без `var`. */
const мСброс = СТРч.match(/(?:^|\n)[ \t]+tdМеткиГрупп = \{\};/);
const iСброс = мСброс ? мСброс.index : -1;
const iЗаполн = СТРч.indexOf('tdМеткиГрупп = KSLT_GROUPS.меткиИгроков(');
правило('карта сбрасывается перед отрисовкой, а не после',
    iСброс > -1 && iЗаполн > -1 && iСброс < iЗаполн,
    'сброс `tdМеткиГрупп` пропал или уехал ниже заполнения. Турнир ' +
    'меняется без перезагрузки страницы: метка прошлого турнира ' +
    'переживёт смену и встанет рядом с чужим именем');

/* ── 4. МЕТКУ ВИДЯТ ОБА ИГРОКА КЛЕТКИ ───────────────────────────────── */
правило('метка рисуется обоим игрокам клетки',
    /tdМеткиГрупп\[match\.player1Id\]/.test(СТРч) &&
    /tdМеткиГрупп\[match\.player2Id\]/.test(СТРч) &&
    (СТРч.match(/td-grp-label/g) || []).length >= 2,
    'метка в `renderMatch` осталась у одного игрока из двух. В клетке ' +
    'сетки их всегда двое, и показать, откуда приехал только верхний, ' +
    'хуже, чем не показывать вовсе');

/* ── 5. МЕТКА НЕ ВЫДУМЫВАЕТСЯ НОМЕРОМ ───────────────────────────────── */
правило('без списка букв метка не выдумывается номером',
    /if\s*\(!буква\)\s*continue;/.test(телоМеток) &&
    !/букваГруппы\(г\)\s*\|\|/.test(телоМеток),
    'в `меткиИгроков` вернулся запасной вариант `|| String(г)`. Девятая ' +
    'группа тогда назовётся `91` вместо `I1`, а алфавит продукта — один ' +
    'список без `I` и `Q`. Молчание честнее неверной метки');

/* ── 6. РУЧНЫЕ МЕСТА — ОДНО ОПРЕДЕЛЕНИЕ ─────────────────────────────── */
правило('перестановка мест живёт в общем модуле',
    /ручныеМеста:\s*ручныеМеста/.test(ГРУППЫч) &&
    /function\s+ручныеМеста\s*\(/.test(ГРУППЫч),
    'js/group-standings.js больше не отдаёт `ручныеМеста`. Проверка ' +
    '«набор мест тот же» снова станет жить в одной админке');

const телоРучных = (ГРУППЫч.match(/function\s+ручныеМеста[\s\S]*?\n    \}/) || [''])[0];
правило('перестановка проверяется, а не применяется на веру',
    /было\s*!==\s*стало/.test(телоРучных) && /return\s+места;/.test(телоРучных),
    '`ручныеМеста` перестала отбрасывать правку, меняющую НАБОР мест. ' +
    'Тогда менеджер сможет задать «двух вторых», и метки `A2` получат ' +
    'двое, а `A3` — никто');

правило('страница турнира не присваивает места сама',
    !/st\.place\s*=\s*\w*Ov\[/.test(СТРч) &&
    (СТРч.match(/KSLT_GROUPS\.ручныеМеста\(/g) || []).length >= 2,
    'на странице турнира вернулась своя копия ручных мест. Их там было ' +
    'ДВЕ, и обе без проверки — это и есть шов, на котором метка ' +
    'расходится с админской');

правило('админка зовёт общую перестановку, а не держит свою',
    /KSLT_GROUPS\.ручныеМеста\(standings,\s*overrides\)/.test(СЕТч) &&
    !/было\s*!==\s*стало/.test(СЕТч),
    '`применитьРучныеМеста` в админке снова несёт собственное тело. ' +
    'Два тела одного правила разъедутся — вопрос только когда');

/* ── 7. ДВЕ КОПИИ МОДУЛЯ СОВПАДАЮТ ──────────────────────────────────── */
правило('копии модуля не разошлись',
    ГРУППЫ === МОБ,
    'js/group-standings.js и mobile/www/js/group-standings.js разошлись — ' +
    'сайт и приложение посчитают места и метки по-разному');

/* ── 8. ПЛАШКА ОДНОЙ ШИРИНЫ НА ОБОИХ ЭКРАНАХ ────────────────────────
   Замораживается ОТНОШЕНИЕ: не «22», а «одно и то же число у обеих».
   Метки `A1` и `G2` обязаны занимать одно место, иначе имена в соседних
   клетках встают разными левыми краями. */
const ширина = (css, сел) => {
    const тело = (css.match(new RegExp('\\' + сел + '\\s*\\{([^}]*)\\}')) || ['', ''])[1];
    const м = тело.match(/(?:^|[;\s])width:\s*([^;]+)/);
    return м ? м[1].trim() : null;
};
const шАдм = ширина(CSSадм, '.ad-brk-grp-label');
const шСтр = ширина(CSSстр, '.td-grp-label');
правило('плашка метки одной ширины в админке и на сайте',
    !!шАдм && !!шСтр && шАдм === шСтр,
    'ширина метки разошлась: в админке ' + шАдм + ', на сайте ' + шСтр +
    '. Одно понятие рисуется одинаково на обоих экранах, иначе имена в ' +
    'соседних клетках встают разными левыми краями');

правило('метка не отнимает ширину у имени',
    /\.td-grp-label\s*\{[^}]*flex-shrink:\s*0/.test(CSSстр),
    '`.td-grp-label` потеряла `flex-shrink: 0`. Имя в клетке и так режется ' +
    'многоточием: плашка, сжимаясь первой, перестанет читаться сама');

/* ── 8б. ПУСТАЯ КЛЕТКА ГОВОРИТ, КОГО ЖДЁТ ───────────────────────────
   Метка слота живёт в базе (`slot1_label`) и до 02.10 читалась только
   админкой: зритель видел пятнадцать «TBD» подряд. */
правило('метки слотов снимаются одной точкой, а не в семи местах',
    /tdМеткиСлотов\[м\.id\]\s*=/.test(СТРч) &&
    (СТРч.match(/tdМеткиСлотов\[[^\]]+\]\s*=/g) || []).length === 1,
    'карта меток слотов строится больше чем в одном месте. Объект матча ' +
    'для `renderMatch` собирается семью кусками: протащив поля через ' +
    'каждый, их станет негде не забыть');

правило('пустая клетка на сайте показывает метку слота',
    /слоты\.s1 && p1\.name === 'TBD'/.test(СТРч) &&
    /слоты\.s2 && p2\.name === 'TBD'/.test(СТРч),
    'метка слота перестала попадать в клетку хотя бы у одного игрока. ' +
    'Зритель снова увидит «TBD» там, где менеджер видит `A1` и `IG1`');

правило('BYE метка не перебивает',
    СТРч.indexOf("p1 = { name: 'BYE'") > -1 &&
    СТРч.indexOf("p1 = { name: 'BYE'") < СТРч.indexOf('слоты.s1'),
    'подстановка метки слота встала ПЕРЕД разбором BYE. Там соперника не ' +
    'будет вовсе — ждать некого, и писать адрес нельзя');

правило('метка слота взяла померенную краску',
    /\.td-slot-wait\s*\{[^}]*color:\s*var\(--text-secondary\)/.test(CSSстр),
    '`.td-slot-wait` сменила краску мимо замера. `--text-secondary` на ' +
    'фоне клетки даёт 9.98, а `--text-dim` — 3.21 и провал WCAG 1.4.3');

/* ── 9. ВЕРСИЯ ОДНА НА ВСЕ СТРАНИЦЫ ─────────────────────────────────
   Держится ОТНОШЕНИЕ, а не число: «не меньше такого-то» состарится в
   день следующей правки — это уже случалось, и не раз. */
const страницы = [];
(function обойти(дир) {
    fs.readdirSync(path.join(КОРЕНЬ, дир), { withFileTypes: true }).forEach(э => {
        const п = dir => dir + '/' + э.name;
        if (э.isDirectory()) {
            if (['.git', 'node_modules', 'test-results', 'mobile'].includes(э.name)) return;
            обойти(п(дир));
        } else if (э.name.endsWith('.html')) {
            страницы.push(fs.readFileSync(path.join(КОРЕНЬ, п(дир)), 'utf8'));
        }
    });
})('.');

const версии = имя => {
    const найдено = new Set();
    страницы.forEach(s => {
        const re = new RegExp(имя.replace('.', '\\.') + '\\?v=(\\d+)', 'g');
        let m; while ((m = re.exec(s))) найдено.add(m[1]);
    });
    return [...найдено];
};
[['group-standings.js'], ['tournament-detail.js'], ['tournament-detail.css']].forEach(([ф]) => {
    const в = версии(ф);
    правило('версия ' + ф + ' одна на все страницы',
        в.length === 1,
        ф + ' подключён разными версиями: ' + (в.join(', ') || 'нигде') +
        '. У кого страница в кеше, тот увидит старый файл, и метка либо ' +
        'не появится, либо встанет по старому расчёту');
});

/* ── вывод ───────────────────────────────────────────────────────────── */
if (ошибки.length) {
    console.log('✗ Метка группы: ' + ошибки.length + ' правил упало\n');
    ошибки.forEach(о => console.log('  • ' + о.имя + '\n    ' + о.подсказка + '\n'));
    process.exit(1);
}
console.log('✓ Метка группы — одна карта на админку и сайт: все правила держат');
