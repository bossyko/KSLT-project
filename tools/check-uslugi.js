/* 07.10 · ПРАВИЛО БЫЛО СЛАБЫМ, поймал прувер: оно искало `--fs-md` ГДЕ
   УГОДНО в файле и зеленело от объявления в медиа ≤992, даже когда базовое
   откатывали. Теперь смотрит в ПЕРВОЕ объявление — то, что стоит в самом
   компоненте, — и заодно стережёт, что оно одно. */
правило('лестница: заголовок колонки ВЫШЕ имени главной карточки',
    /\.sv-column-title\s*\{[^}]*font-size:\s*var\(--fs-lg\)/.test(CSS) &&
    (CSS.match(/\.sv-featured-content h3\s*\{/g) || []).length === 2 &&
    /\n\.sv-featured-content h3\s*\{[^}]*font-size:\s*var\(--fs-md\)/.test(CSS),
    'Было h2 18 при h3 21 — лестница вверх ногами на самом видном месте.');

правило('подзаголовок обложки переведён на все три языка',
    /heroDesc: 'Корты, тренеры и партнёры по игре'/.test(JS) &&
    /heroDesc: 'Courts, coaches and hitting partners'/.test(JS) &&
    /heroDesc: 'Корттор, машыктыруучулар жана оюн боюнча өнөктөштөр'/.test(JS),
    'Три языка — один макет: если подпись переписана на одном, на двух\n' +
    '          других останется прежняя, и страницы разойдутся.');

правило('страница подключает свои файлы одной версией на три языка',
    (() => {
        const в = т => (т.match(/services\.(?:css|js)\?v=(\d+)/g) || []).sort().join('|');
        return в(RU) !== '' && в(RU) === в(EN) && в(EN) === в(KG);
    })(),
    'Версия файла одна на все страницы: это держит правило заморозки.');

if (ошибки.length === 0) {
    console.log(`\n  ок      обзорная «Услуги»: ${ВСЕГО} правил\n`);
    process.exit(0);
}
console.log(`\n  НЕ ТАК  обзорная «Услуги»: ${ВСЕГО} правил, упало ${ошибки.length}.\n`);
ошибки.forEach(о => {
    console.log(`  ✗ ${о.имя}`);
    if (о.подсказка) console.log(`          ${о.подсказка}`);
    console.log('');
});
process.exit(1);
