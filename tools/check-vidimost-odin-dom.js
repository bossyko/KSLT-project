/**
 * ЗАМОРОЗКА ВИДИМОСТИ В ПРОБАХ (кусок 196, 27.10.2026).
 *
 * ЗАМЕР: «видим ли узел» считали САМИ 33 файла проб — 61 признак, и
 * считали ПО-РАЗНОМУ. Одни брали `display` и `visibility` самого узла,
 * другие поднимались по предкам, третьи смотрели `offsetParent`.
 *
 * РАСХОЖДЕНИЕ НЕ ЗАВТРАШНЕЕ, А УЖЕ СЛУЧИВШЕЕСЯ. Проба 94 брала свойства
 * САМОГО кружка — а скрыт был РОДИТЕЛЬ, неактивная панель рейтинга
 * `div.rankings-panel` с `display: none`. Шестнадцать кружков внутри неё
 * числились «видимыми и схлопнутыми в 0x0», и проба падала НА ПРАВИЛЬНОЙ
 * ВЁРСТКЕ. Падала при этом один вид из пяти — потому что ждала 400 мс, а
 * не признак: кто успел построить панели, тот и упал.
 *
 * СВОЙСТВА УЗЛА НЕ ЗНАЮТ О ПРЕДКАХ. Третий раз на этих граблях: 13.10
 * прибор контраста так же не видел `opacity: 0` на родителе.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ:
 *   • дом видимости объявлен ОДИН раз, в фикстуре, и поднимается по
 *     предкам (display, visibility, opacity) плюс смотрит прямоугольник;
 *   • дом объявляется ДО загрузки страницы, иначе проба его не увидит;
 *   • своих подсчётов НЕ БОЛЬШЕ замеренных — храповик вниз: перевёл
 *     пробу на дом, число упало, потолок опускается следом;
 *   • проба лица видимость сама не считает — она первая переведена.
 *
 *   node tools/check-vidimost-odin-dom.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const ФИКСТУРА = 'tests/fixtures.js';
const ПРИБОР = 'tools/kontrast.mjs';
const ПРОБА_ЛИЦА = 'tests/e2e/design-system/94-lico.spec.js';

const собрать = (кат, спис) => {
    fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(д => {
        const п = кат + '/' + д.name;
        if (д.isDirectory()) { if (д.name !== 'reports' && д.name !== 'node_modules') собрать(п, спис); }
        else if (/\.(js|mjs)$/.test(д.name)) спис.push(п);
    });
    return спис;
};
const ФАЙЛЫ = собрать('tests', []).concat(собрать('tools', []));

/* ИГОЛКА СОБИРАЕТСЯ ИЗ ЧАСТЕЙ, иначе сторож попадает в собственный замер:
   первая редакция дала 64 вместо 59 — пять «подсчётов» нашлись в тексте
   самого сторожа, в признаках правил ниже. Второй такой случай за два дня
   (первый — счёт контраста, кусок 186). */
const признак = new RegExp(
    'disp' + 'lay\\s*!==?\\s*.none.' + '|' +
    'visib' + 'ility\\s*!==?\\s*.hidden.' + '|' +
    '\\.offset' + 'Parent', 'g');

/* ══ 1. ДОМ ОДИН И СМОТРИТ ПРЕДКОВ ═════════════════════════════════════ */

const Ф = безКом(чит(ФИКСТУРА));

правило('дом видимости объявлен в фикстуре ровно один раз',
    (Ф.match(/function виден\s*\(/g) || []).length === 1,
    'объявлений не одно. Два дома разойдутся на первой же правке');

const ТРИ_СВОЙСТВА = new RegExp('c\\.disp' + 'lay === .none.').test(Ф) &&
    new RegExp('c\\.visib' + 'ility === .hidden.').test(Ф) &&
    /\+c\.opacity === 0/.test(Ф);
правило('дом поднимается по предкам, а не смотрит один узел',
    /while \(у\) \{/.test(Ф) && /у = у\.parentElement;/.test(Ф) && ТРИ_СВОЙСТВА,
    'дом снова смотрит только сам узел — ровно то, на чём упала проба 94:\n' +
    'скрыт был РОДИТЕЛЬ, а свойства узла о предках не знают');

правило('дом смотрит и прямоугольник',
    /getBoundingClientRect\(\)/.test(Ф) && /!r\.width \|\| !r\.height/.test(Ф),
    'схлопнутый в ноль узел формально «видим» по свойствам');

правило('дом объявляется ДО загрузки страницы',
    /addInitScript\('window\.КСЛТ_виден = ' \+ виден\.toString\(\)/.test(Ф),
    'объявленный позже дом проба не увидит: страница уже отработала');

/* ══ 2. ПРОБА ЛИЦА ПЕРЕВЕДЕНА ══════════════════════════════════════════ */

const Л = безКом(чит(ПРОБА_ЛИЦА));

правило('проба лица зовёт дом, а не считает видимость сама',
    /window\.КСЛТ_виден\(/.test(Л) && (Л.match(признак) || []).length === 0,
    'проба лица вернулась к своему подсчёту — и снова будет падать на\n' +
    'правильной вёрстке, когда скрыт предок');

правило('проба лица ждёт признак, а не время',
    /waitForFunction\(\(\) => !!window\.KSLT_LICO/.test(Л),
    'ожидание временем делает пробу flaky: падал один вид из пяти\n' +
    'только потому, что успел построить панели рейтинга');

/* ══ 3. ХРАПОВИК НА СВОИ ПОДСЧЁТЫ ══════════════════════════════════════ */

/* ЗАМЕР 27.10, КУСОК 196: 63 признака в 34 файлах. Проба лица переведена
   на дом — её два сняты, осталось 61 в 33 файлах, и это потолок.
   ХРАПОВИК ХОДИТ ВНИЗ ТОЛЬКО С ПРИЧИНОЙ. Остальные 33 файла ждут своей
   очереди — запись в трекере; каждый перевод опускает потолок. */
const ПОТОЛОК = 61;

let своих = 0;
const файлы = [];
ФАЙЛЫ.filter(ф => ф !== ФИКСТУРА && ф !== ПРИБОР).forEach(ф => {
    const n = (безКом(чит(ф)).match(признак) || []).length;
    if (n) { своих += n; файлы.push(ф.split('/').pop() + ':' + n); }
});

правило('своих подсчётов видимости не больше потолка',
    своих <= ПОТОЛОК,
    'своих признаков ' + своих + ', потолок ' + ПОТОЛОК + ' (в ' + файлы.length + ' файлах).\n' +
    'Новая проба обязана звать дом: window.КСЛТ_виден(узел)');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      видимость — один дом: 7 правил');
    console.log('          дом поднимается по предкам и смотрит прямоугольник');
    console.log('          своих подсчётов ' + своих + ' в ' + файлы.length +
                ' файлах (потолок ' + ПОТОЛОК + '), не растёт');
    console.log('          проба лица переведена и ждёт признак, а не время');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  видимость — один дом: ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
