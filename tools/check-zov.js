#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ЗОВ СЕРВЕРНОЙ ФУНКЦИИ — ОДИН ДОМ» (30.10).
 *
 * ЗАМЕР ДО ПРАВКИ, ЧТЕНИЕМ: мест, собирающих адрес `/functions/v1/…`, в
 * продукте было 35 — из них 12 внутри домов (по одному на понятие) и
 * **23 рукописных**, написанных ПЯТЬЮ разными способами. В семи из
 * девяти публичных стоял слепой `r.json()`: функция, упавшая на сервере,
 * отвечает не JSON, разбор бросал `SyntaxError`, и человек видел общее
 * «ошибка» без причины. В двух местах кабинета зов уходил ДАЖЕ БЕЗ
 * СЕССИИ, с пустым `Bearer`, — сервер отвечал 401, и причина терялась
 * там же. И одно место в профиле приложения держало ЗАШИТЫЙ адрес базы
 * со `|| ''` вместо ключа: пустой ключ даёт молчаливый отказ сервера.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ, А НЕ ЧИСЛА САМИ ПО СЕБЕ:
 *   • дом объявлен ОДИН раз, копии побайтово равны;
 *   • адрес и ключ дом берёт у настроек и не подставляет свои;
 *   • разбор идёт ЧЕРЕЗ ТЕКСТ: «не JSON» отличается от отказа;
 *   • без токена сервер не зовут ВОВСЕ;
 *   • в публичной части (всё, кроме `js/admin/`) зова мимо дома НЕТ;
 *   • долг админки назван ЧИСЛОМ и может только убывать.
 *
 * ПОЧЕМУ АДМИНКА ОСТАЛАСЬ ДОЛГОМ, А НЕ СВЕДЕНА ЗАОДНО. Её четырнадцать
 * зовов пишут в базу, экран за входом, и ни проба, ни браузер до них не
 * доходят: доказывать правку было бы нечем, кроме чтения. Это названо
 * числом здесь и строкой в трекере, а не отложено молча.
 *
 *   node tools/check-zov.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = т => безКомментариев(т);

const ДОМ = 'js/kslt-zov.js';
const ДОМ_П = 'mobile/www/js/kslt-zov.js';
const дом = безКом(чит(ДОМ));

const ПРОПУСК = /^(node_modules|\.git|android|ios|build|test-results|playwright-report|slepki|_figma|tools|tests|maket)$/;
function всеJs(д, вых) {
    вых = вых || [];
    fs.readdirSync(path.join(КОРЕНЬ, д || '.'), { withFileTypes: true }).forEach(э => {
        const п = д ? д + '/' + э.name : э.name;
        if (э.isDirectory()) {
            if (!ПРОПУСК.test(э.name) && !э.name.startsWith('.')) всеJs(п, вых);
        } else if (э.name.endsWith('.js')) вых.push(п);
    });
    return вых;
}
const JS = всеJs('');

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

/* ══ 1. ДОМ ОДИН, И КОПИИ РАВНЫ ═════════════════════════════════════════ */

/* ПРИЗНАК СЧИТАЕТ ОБА НАПИСАНИЯ. Первая редакция искала только
   `global.KSLT_ZOV =` — так объявлен сам дом, — и прувер сразу показал
   цену: второй дом, заведённый как `window.KSLT_ZOV = …` (а живой код
   пишут именно так), правило НЕ РОНЯЛ. ОДНО ПОНЯТИЕ — ДВА НАПИСАНИЯ,
   и прибор обязан видеть оба. */
const объявления = JS.filter(ф => /(?:global|window)\.KSLT_ZOV\s*=/.test(безКом(чит(ф))));
правило('дом зова объявлен ровно один раз на продукт',
    объявления.length === 2 &&
    объявления.indexOf(ДОМ) !== -1 && объявления.indexOf(ДОМ_П) !== -1,
    'Объявлений: ' + объявления.length + ' — ' + объявления.join(', ') + '.\n' +
    'Две — это сайт и его побайтовая копия в приложении; третья означает,\n' +
    'что зов снова живёт двумя жизнями.');

правило('копии дома побайтово равны',
    чит(ДОМ) === чит(ДОМ_П),
    'Разошлись — и беда родится ровно на шве: один продукт станет звать\n' +
    'функции по-своему.');

/* ══ 2. АДРЕС И КЛЮЧ — У НАСТРОЕК ════════════════════════════════════════ */

правило('адрес базы и ключ дом берёт у настроек, а не вписывает',
    /global\.SUPABASE_URL/.test(дом) && /global\.SUPABASE_ANON_KEY/.test(дом) &&
    !/[a-z0-9]{15,}\.supabase\.co/.test(дом) &&
    /* ПРИЗНАК СУЖЕН ДО САМИХ НАСТРОЕК: запрет любого `|| ''` падал бы на
       законных `тело || {}` и `значение == null ? '' : …`. */
    !/SUPABASE_(?:URL|ANON_KEY)\s*\|\|/.test(дом),
    'Вписанный адрес — второе место, где живёт адрес базы (шаг A3.4).\n' +
    'Пустой ключ по умолчанию ещё хуже: сервер отказывает МОЛЧА, и это\n' +
    'ровно то, что лежало в профиле приложения до 30.10.');

/* ══ 3. РАЗБОР ОТВЕТА ════════════════════════════════════════════════════ */

правило('ответ разбирается через текст, а не слепым json',
    /resp\.text\(\)/.test(дом) && !/resp\.json\(\)/.test(дом),
    'Слепой `resp.json()` на теле вроде `<html>502` бросает SyntaxError\n' +
    'ВМЕСТО ответа: дальше по функции не идёт ничего — ни показа ошибки,\n' +
    'ни возврата кнопки в рабочее состояние.');

правило('о не-JSON дом говорит вслух и называет функцию',
    /console\.error/.test(дом) &&
    /throw new Error\(\s*имя \+ ': HTTP '/.test(дом),
    'Без имени функции и кода ответа в консоли «что-то не сработало»\n' +
    'неразбираемо — это и была беда в семи местах из девяти.');

правило('отказ сервера возвращается ДАННЫМИ, а не исключением',
    /if \(!resp\.ok \|\| данные\.error\)/.test(дом) &&
    /return данные;/.test(дом),
    'Код отказа нужен продукту: по нему заявка и вызов выбирают СВОЁ\n' +
    'слово. Бросок на отказе лишил бы их этого выбора.');

/* ══ 4. БЕЗ ТОКЕНА СЕРВЕР НЕ ЗОВУТ ═══════════════════════════════════════ */

правило('без токена дом не зовёт сервер вовсе',
    /if \(!токен\)/.test(дом) &&
    /error: 'not_logged_in'/.test(дом),
    'Пустой `Bearer` даёт 401 и потерянную причину — так было в двух\n' +
    'местах кабинета. Ответ «не вошёл» даётся тем же ключом, каким его\n' +
    'вернул бы сервер: продукту не нужно знать два способа про одно.');

правило('зов от имени спрашивает сессию у клиента, а не у зовущего',
    /API\.отИмени = function \(client, имя, тело\)/.test(дом) &&
    /client\.auth\.getSession\(\)/.test(дом),
    'Иначе каждый зовущий снова решал бы сам, где взять токен — именно\n' +
    'это и дало двадцать три рукописных места.');

/* ══ 5. ПУБЛИЧНАЯ ЧАСТЬ — ТОЛЬКО ЧЕРЕЗ ДОМ ═══════════════════════════════ */

/* МЕСТА СЧИТАЮТСЯ ПРИБОРОМ, КОТОРЫЙ ЗНАЕТ СТРОКИ. Прежний замер этого
   куска НЕДОСЧИТАЛ место в профиле приложения: оно стоит после
   `accept="image/*"`, и стриппер комментариев регулярками ослеп до конца
   файла. Теперь снятие комментариев живёт в `tools/bez-kommentariev.js`
   и знает строки — иначе правило ниже говорило бы «ноль» и зеленело. */
const зовы = { дом: 0, админ: 0, публичные: [] };
JS.forEach(ф => {
    const т = безКом(чит(ф));
    const вДоме = ф === ДОМ || ф === ДОМ_П;
    const вАдминке = ф.indexOf('js/admin/') === 0;
    т.split('\n').forEach((с, i) => {
        if (с.indexOf('functions/v1/') === -1) return;
        if (вДоме) zovДом();
        else if (вАдминке) зовы.админ++;
        else зовы.публичные.push(ф + ':' + (i + 1));
    });
    function zovДом() { зовы.дом++; }
});

правило('в публичной части зова мимо дома нет ни одного',
    зовы.публичные.length === 0,
    'Мест: ' + зовы.публичные.length + ' — ' + зовы.публичные.join(', ') + '.\n' +
    'Публичная часть — это всё, кроме `js/admin/`: кабинет, колокольчик,\n' +
    'страница турнира, приглашения приложения, профиль приложения.');

правило('сам дом собирает адрес функции ровно в двух местах на копию',
    зовы.дом === 4,
    'В доме мест: ' + зовы.дом + ', а должно быть четыре — по два на\n' +
    'копию: зов без входа и зов с токеном. Третье в доме означает, что\n' +
    'внутри дома понятие тоже раздвоилось.');

/* ХРАПОВИК АДМИНКИ — ТОЛЬКО ВНИЗ. Её четырнадцать зовов пишут в базу,
   экран за входом, пробой не достаётся — поэтому правка там отдельным
   куском и по слову Кости, а число стоит здесь, чтобы долг не вырос
   молча и не был забыт. */
const ПОТОЛОК_АДМИНКИ = 14;
правило('рукописных зовов в админке не больше замеренных 14',
    зовы.админ <= ПОТОЛОК_АДМИНКИ,
    'В админке мест: ' + зовы.админ + ', потолок ' + ПОТОЛОК_АДМИНКИ + '.\n' +
    'Новый рукописный зов — это новая копия понятия, которое уже сведено.');

правило('потолок админки не завышен',
    зовы.админ >= ПОТОЛОК_АДМИНКИ,
    'В админке мест: ' + зовы.админ + ' при потолке ' + ПОТОЛОК_АДМИНКИ + '.\n' +
    'ХРАПОВИК ОПУСКАЕТСЯ: поправь ПОТОЛОК_АДМИНКИ на ' + зовы.админ + ' —\n' +
    'иначе запас пустит обратно столько же молча.');

/* ══ 6. СЛЕПОЙ РАЗБОР В ПУБЛИЧНОЙ ЧАСТИ ══════════════════════════════════ */

/* ПРИЗНАК БЕРЁТ ОКНО ПОСЛЕ ЗОВА ДОМА, А НЕ ВЕСЬ ФАЙЛ: `.json()` в файле
   может принадлежать совсем другому запросу — к REST, например. И
   спрашивает он именно про ЗОВ ДОМА: дом отдаёт уже разобранные ДАННЫЕ,
   и `.json()` на них — это возврат к прежней беде, только снаружи.
   ПОЧЕМУ НЕ «ЛЮБОЙ json РЯДОМ С functions/v1»: такой признак нельзя
   уронить по отдельности — первым падало бы правило про зов мимо дома,
   и прувер честно говорил бы «упало ДРУГОЕ». */
const слепые = [];
JS.forEach(ф => {
    if (ф === ДОМ || ф === ДОМ_П || ф.indexOf('js/admin/') === 0) return;
    const т = безКом(чит(ф));
    т.split(/KSLT_ZOV\s*\./).slice(1).forEach(часть => {
        if (/\.json\(\)/.test(часть.slice(0, 200))) слепые.push(ф);
    });
});
правило('на ответе дома никто не зовёт json ещё раз',
    слепые.length === 0,
    'Файлы: ' + [...new Set(слепые)].join(', ') + '.\n' +
    'Дом отдаёт разобранные данные. `.json()` поверх них — это `undefined\n' +
    'is not a function` в лучшем случае и прежняя слепота в худшем.');

/* ══ 7. ДОМ ДОЕЗЖАЕТ ДО СТРАНИЦ И СТОИТ РАНЬШЕ ЗОВУЩИХ ═══════════════════ */

/* ЗОВУЩИЕ ЧИТАЮТСЯ ИЗ КОДА, А НЕ ПЕРЕЧИСЛЯЮТСЯ: перечень устарел бы на
   следующем куске, и правило бы молча ослабло. */
const зовущие = JS.filter(ф => ф !== ДОМ && ф !== ДОМ_П &&
    /KSLT_ZOV\./.test(безКом(чит(ф)))).map(ф => ф.split('/').pop());
const имяДома = 'kslt-zov.js';

function всеHtml(д, вых) {
    вых = вых || [];
    fs.readdirSync(path.join(КОРЕНЬ, д || '.'), { withFileTypes: true }).forEach(э => {
        const п = д ? д + '/' + э.name : э.name;
        if (э.isDirectory()) {
            if (!/^(node_modules|\.git|android|ios|build|test-results|playwright-report|slepki|_figma)$/.test(э.name)
                && !э.name.startsWith('.')) всеHtml(п, вых);
        } else if (э.name.endsWith('.html')) вых.push(п);
    });
    return вых;
}
const теги = с => (с.match(/<script[^>]+src="[^"]+"/g) || [])
    .map(т => (т.match(/src="([^"]+)"/) || ['', ''])[1].split('?')[0].split('/').pop());

const безДома = [], позже = [];
всеHtml('').forEach(с => {
    const и = теги(чит(с));
    const свои = и.map((н, i) => ({ н, i })).filter(x => зовущие.indexOf(x.н) !== -1);
    if (!свои.length) return;
    const д = и.indexOf(имяДома);
    if (д === -1) { безДома.push(с); return; }
    if (д > свои[0].i) позже.push(с + ' (дом ' + д + ', зовущий ' + свои[0].i + ')');
});

правило('дом подключён на каждой странице, где его зовут',
    безДома.length === 0,
    'страниц без дома: ' + безДома.length + ' — ' + безДома.slice(0, 5).join(', ') +
    '.\nБез него первый же зов функции упадёт на `KSLT_ZOV is not defined`.');

правило('дом стоит раньше своих зовущих',
    позже.length === 0,
    'позже зовущего: ' + позже.slice(0, 5).join(', ') + '.\n' +
    'Скрипт, стоящий выше, выполняется раньше: зовущий не найдёт дом.\n' +
    'Дом ни от чего не зависит — его место первым безопасно.');

/* ══ 8. ДОМ ВХОДА ЗОВЁТ ДОМ ЗОВА, А НЕ ДЕРЖИТ ВТОРОЙ ════════════════════ */

const вход = безКом(чит('js/kslt-vhod.js'));
правило('дом входа зовёт дом зова и своего разбора не держит',
    /KSLT_ZOV/.test(вход) &&
    !/resp\.text\(\)/.test(вход) && !/'apikey'/.test(вход),
    'Вход был первым, кто завёл у себя заголовки и разбор — и из него\n' +
    'это разошлось. Теперь он зовёт дом; своя копия здесь означала бы\n' +
    'два определения одного понятия.');

/* ───────── вывод ───────── */
console.log('');
if (!ошибки.length) {
    console.log('  ок      зов серверной функции: все ' +
        (fs.readFileSync(__filename, 'utf8').match(/правило\('/g) || []).length +
        ' правил держатся');
    console.log('          зовов в доме 4 (две копии × два зова), в публичной части мимо дома 0');
    console.log('          долг админки: ' + зовы.админ + ' рукописных зовов под храповиком');
    console.log('          слепого разбора в публичной части ноль');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  зов серверной функции — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
