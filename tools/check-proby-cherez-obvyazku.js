'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');

/* ПРИБОР ЧИТАЕТ КОД, А НЕ ПОДПИСИ К НЕМУ. Поймано на себе 01.11: новое
   правило «ожидание не бывает асинхронным» упало на ФАЙЛЕ, который я сам
   же и починил, — в его подписи процитирован образец беды. Признак,
   читающий комментарии, ловит рассказ о беде вместо беды. */
function код(ф) {
    return безКомментариев(fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'), ф);
}

/* ЗАМЕРЕНО 31.10. Опускается КАЖДЫЙ раз, когда пробу переводят на
   обвязку: порог с запасом не сторожит ничего. */
const ПОТОЛОК_МИМО = 0;

function пробы(д, вых) {
    вых = вых || [];
    const полный = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(полный)) return вых;
    fs.readdirSync(полный, { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) пробы(п, вых);
        else if (э.name.endsWith('.spec.js')) вых.push(п);
    });
    return вых;
}

const все = пробы('tests/e2e');
/* МИМО ОБВЯЗКИ — ЭТО ТОТ, КТО БЕРЁТ У ПАКЕТА `test`. Именно `test`
   создаёт страницу и решает, какая база подставлена и грузятся ли
   картинки. Файл, тянущий оттуда только `expect`, условий прогона не
   меняет — и бедой не является. */
const мимо = все.filter(ф =>
    /const \{[^}]*\btest\b[^}]*\} = require\(['"]@playwright\/test['"]\)/
        .test(код(ф)));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('проб мимо обвязки не больше замеренных ' + ПОТОЛОК_МИМО,
    мимо.length <= ПОТОЛОК_МИМО,
    'Стало ' + мимо.length + '. Каждая такая проба гоняет сайт против\n' +
    'БОЕВОЙ базы и тянет из неё все снимки. Новая проба берёт\n' +
    '`require(\'../../fixtures\')`, а не `@playwright/test`.');

/* ВТОРОЕ ПРАВИЛО ХРАПОВИКА — «ПОТОЛОК НЕ ЗАВЫШЕН» — СНЯТО 31.10,
   ПОТОМУ ЧТО ПРИ НУЛЕ ОНО СТАЛО ТОЖДЕСТВОМ. `мимо.length >= 0` верно
   всегда, то есть правило перестало что-либо доказывать, а выглядело
   как два. ПУСТОЕ ПРАВИЛО ХУЖЕ ОТСУТСТВУЮЩЕГО: оно создаёт чувство
   присмотра там, где присмотра нет. Храповик дошёл до дна, и опускать
   больше нечего.
   Вместо него — правило, которое при нуле ЕЩЁ ЗНАЧИТ: обвязку можно
   обойти не только через `require`. */

правило('обвязку не обходят и через import',
    !все.some(ф => /import\s[^;]*from\s*['"]@playwright\/test['"]/
        .test(код(ф))),
    'Признак выше читает только `require`. Запись через `import` даёт\n' +
    'ровно тот же обход — боевая база и все снимки, — и проскочила бы\n' +
    'мимо прибора молча.');

/* ══ ОЖИДАНИЕ НЕ БЫВАЕТ АСИНХРОННЫМ (01.11) ═══════════════════════════
   `page.waitForFunction(async () => …)` НЕ ЖДЁТ НИЧЕГО: внутри бегунка
   стоит `const success = predicate(); if (success) fulfill(success)`, а
   асинхронная проверка возвращает промис, и промис всегда истинен.
   Ожидание заканчивается на первом проходе и отдаёт то, чем промис
   разрешится, — хоть `false`.
   ЗАМЕРЕНО ОПЫТОМ, А НЕ ВЫЧИТАНО: признак, верный через 1200 мс.
   Асинхронный вернул `false` через 57 мс, синхронный дождался за 1221.
   ЦЕНА: две пробы офлайн-службы читали поле у `false` и падали, третья
   ЗЕЛЕНЕЛА ВСЛЕПУЮ. Асинхронное ждёт дом `дождатьсяЗамера`. */

const сАсинхроннымОжиданием = все.filter(ф =>
    /waitForFunction\(\s*async/.test(код(ф)));

правило('ожидание не бывает асинхронным',
    сАсинхроннымОжиданием.length === 0,
    'Так ждут: ' + сАсинхроннымОжиданием.join(', ') + '\n' +
    '`waitForFunction` с async-проверкой кончается на первом проходе\n' +
    'тем, чем разрешится промис, — хоть `false`. Проба либо читает поле\n' +
    'у `false`, либо зеленеет вслепую. Асинхронный замер ждёт дом\n' +
    '`дождатьсяЗамера` из `tests/fixtures.js`.');

правило('дом ожидания на месте и ждёт циклом, а не признаком бегунка',
    (function () {
        const о = код('tests/fixtures.js');
        const i = о.indexOf('async function дождатьсяЗамера');
        if (i === -1) return false;
        const тело = о.slice(i, i + 1200);
        return /page\.evaluate\(замер\)/.test(тело) && /for \(;;\)|while \(/.test(тело);
    })(),
    'Дом обязан ждать САМ — циклом с `page.evaluate`, который промисы\n' +
    'ждать умеет. Переписать его через `waitForFunction` значило бы\n' +
    'вернуть ту же беду в одно место вместо трёх.');

правило('обвязка объявляет то, ради чего в неё ходят',
    (function () {
        const о = код('tests/fixtures.js');
        return /window\.KSLT_DB = cfg/.test(о) &&
               /window\.КСЛТ_виден = /.test(о) &&
               /resourceType\(\)/.test(о);
    })(),
    'Обвязка держит три вещи разом: адрес тестовой базы, общий дом\n' +
    'видимости и отсечку тяжёлых файлов. Пропала любая — переход на\n' +
    'обвязку перестаёт что-либо значить.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      пробы через обвязку: все ' + всего + ' правил держатся');
    console.log('          проб всего ' + все.length + ', мимо обвязки ' + мимо.length +
                ' (потолок ' + ПОТОЛОК_МИМО + ')');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  пробы через обвязку — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
