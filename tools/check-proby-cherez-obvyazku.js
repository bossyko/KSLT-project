#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ПРОБА ИДЁТ ЧЕРЕЗ ОБВЯЗКУ, А НЕ МИМО НЕЁ» (31.10).
 *
 * ЗАЧЕМ ОН ЕСТЬ — СЛУЧАЙ, А НЕ ОПАСЕНИЕ. Проба 33 брала
 * `require('@playwright/test')` напрямую. Поймалось СЛУЧАЙНО: новая
 * проверка позвала дом `КСЛТ_виден`, который объявляет обвязка, и
 * получила `undefined is not a function` на всех пяти видах.
 *
 * ЧЕМ ЭТО ПЛОХО, СЛОВАМИ САМОЙ ОБВЯЗКИ (`tests/fixtures.js`):
 *   · она подставляет адрес ТЕСТОВОЙ базы до загрузки страницы —
 *     «без подстановки страница ушла бы в боевую базу: тысяча шестьсот
 *     прогонов оставили бы там мусор и потратили месячную квоту»;
 *   · она же режет картинки, шрифты и видео — «пятнадцать прогонов в
 *     день съели месячный лимит исходящего трафика и остановили сайт
 *     целиком, до конца платёжного периода».
 * Проба мимо обвязки делает ровно оба этих дела: читает боевую базу и
 * тянет из неё все снимки. И молчит об этом — она же зелёная.
 *
 * ХРАПОВИК ВНИЗ, А НЕ ЗАПРЕТ. На 31.10 таких проб **76**. Перевести их
 * одним движением нельзя: обвязка меняет условия прогона (другая база,
 * пустые картинки), и у части проб от этого поедут числа — это свой
 * кусок с прогоном. Поэтому число заморожено: расти нельзя, падать
 * можно. Каждая переведённая проба опускает порог.
 *
 * ПОЧЕМУ ПОРОГ, А НЕ СПИСОК ИМЁН. Список в семьдесят шесть строк
 * устареет на первой же правке и начнёт врать; число — нет.
 *
 *   node tools/check-proby-cherez-obvyazku.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');

/* ЗАМЕРЕНО 31.10. Опускается КАЖДЫЙ раз, когда пробу переводят на
   обвязку: порог с запасом не сторожит ничего. */
const ПОТОЛОК_МИМО = 76;

function пробы(д, вых) {
    вых = вых || [];
    const полный = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(полный)) return вых;
    fs.readdirSync(полный, { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) пробы(п, вых);
        else if (э.name.endsWith('.spec.js')) вых.push(п);
    });
    return вых;
}

const все = пробы('tests/e2e');
const мимо = все.filter(ф =>
    /require\(['"]@playwright\/test['"]\)/.test(fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8')));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('проб мимо обвязки не больше замеренных ' + ПОТОЛОК_МИМО,
    мимо.length <= ПОТОЛОК_МИМО,
    'Стало ' + мимо.length + '. Каждая такая проба гоняет сайт против\n' +
    'БОЕВОЙ базы и тянет из неё все снимки. Новая проба берёт\n' +
    '`require(\'../../fixtures\')`, а не `@playwright/test`.');

правило('потолок не завышен',
    мимо.length >= ПОТОЛОК_МИМО,
    'Проб мимо обвязки стало ' + мимо.length + ' при потолке ' + ПОТОЛОК_МИМО + '.\n' +
    'ПОТОЛОК ОПУСКАЕТСЯ: поправь ПОТОЛОК_МИМО на ' + мимо.length + '.\n' +
    'Запас пустил бы обратно ровно столько же проб молча.');

правило('обвязка объявляет то, ради чего в неё ходят',
    (function () {
        const о = fs.readFileSync(path.join(КОРЕНЬ, 'tests/fixtures.js'), 'utf8');
        return /window\.KSLT_DB = cfg/.test(о) &&
               /window\.КСЛТ_виден = /.test(о) &&
               /resourceType\(\)/.test(о);
    })(),
    'Обвязка держит три вещи разом: адрес тестовой базы, общий дом\n' +
    'видимости и отсечку тяжёлых файлов. Пропала любая — переход на\n' +
    'обвязку перестаёт что-либо значить.');

console.log('');
if (!ошибки.length) {
    console.log('  ок      пробы через обвязку: все 3 правил держатся');
    console.log('          проб всего ' + все.length + ', мимо обвязки ' + мимо.length +
                ' (потолок ' + ПОТОЛОК_МИМО + ')');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  пробы через обвязку — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
