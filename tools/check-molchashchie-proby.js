#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ПРОБА НЕ ПРОПУСКАЕТ САМУ СЕБЯ МОЛЧА» (06.11).
 *
 * ОТКУДА ПРАВИЛО. 04.11 в `35-ekran-battla.spec.js` нашлось
 * `if (window.KSLT_I18N.set) ... .set(язык)`, а метода `set` у дома слов
 * НЕТ вовсе — он зовётся `setLang`. Условие было ложно всегда, язык не
 * переключался, и три «языка» файла проверяли один и тот же. Проба была
 * зелёной и не проверяла ничего.
 *
 * ПОИСК ПО ТОМУ ЖЕ ПРИЗНАКУ (06.11) нашёл ещё три таких места:
 *   · `55-oblozhka-razdela` — `if (кат.цифра && обз.цифра) expect(...)`:
 *     пропажа цифры с ОДНОЙ страницы и есть то расхождение, ради
 *     которого проба написана, а она его молча пропускала;
 *   · `42-live-stranica` — три проверки счёта под `if (л.очки && л.сет)`:
 *     на стенде без живого счёта проба зелёная и пустая;
 *   · `36-reyting` — проверка кольца под `if (первый && первый.кольцо)`:
 *     при смене разметки не выполнялась ни разу.
 *
 * ЧТО СТЕРЕЖЁТ. `expect`, стоящий под проверкой НАЛИЧИЯ, без одного из
 * трёх честных выходов рядом:
 *   · `test.skip(условие, причина)` — пропуск виден в отчёте;
 *   · `throw new Error('...')` — отказ с именем;
 *   · счётчик срабатываний и `expect(счёт).toBeGreaterThan(0)` — молчание
 *     становится падением.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ. Условия, за которыми нет `expect` вовсе: уборка
 * после пробы (`if (п && п.своя) п.сетка.remove()`) к делу не относится.
 *
 *   node tools/check-molchashchie-proby.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ПАПКА = 'tests/e2e';
const ОКНО = 14;   // строк после `if`, в которых ищется expect

/* Условие спрашивает НАЛИЧИЕ: дом, метод, поле снимка. Именно такое
   молчит при опечатке в имени или при смене разметки. */
const НАЛИЧИЕ = [
    /\bif\s*\(\s*(?:window\.)?[A-ZА-Я_][\w.]*\.[\wА-Яа-я]+\s*\)/,
    /\bif\s*\(\s*typeof\s+[\w.]+\s*===?\s*['"]function['"]\s*\)/,
    /\bif\s*\([^)]*&&\s*[\wА-Яа-я.]+\.[\wА-Яа-я]+\s*\)/
];
const ВЫХОДЫ = [/test\.skip\s*\(/, /throw\s+new\s+Error/, /toBeGreaterThan\s*\(\s*0\s*\)/, /\belse\b/];

/* НАЗВАННЫЕ ИСКЛЮЧЕНИЯ — С ПРИЧИНОЙ, А НЕ СПИСКОМ. Условие законно,
   когда оно спрашивает не РАЗМЕТКУ, а довод самого прогона: язык, вид,
   выбранный стенд. Такое условие не может стать ложным по опечатке. */
const ИСКЛЮЧЕНИЯ = {
    'tests/e2e/design-system/68-novost-statya.spec.js:552':
        '`Я.чужой` — язык прогона, он задан списком языков в самом файле, ' +
        'а не найден в разметке: ложным по опечатке стать не может'
};

/** Тело блока, начинающегося на строке `i`: от неё до закрытия скобок.
 *  Однострочный `if` без тела возвращает саму строку — и если `expect`
 *  стоит в ней же, это проверка, а не уборка. */
function телоБлока(строки, i) {
    let баланс = 0, начали = false;
    const из = [];
    for (let j = i; j < строки.length && j < i + 60; j++) {
        из.push(строки[j]);
        const открыл = (строки[j].match(/\{/g) || []).length;
        const закрыл = (строки[j].match(/\}/g) || []).length;
        if (открыл) начали = true;
        баланс += открыл - закрыл;
        if (начали && баланс <= 0) break;
        if (!начали && j > i) break;       // тело без скобок — одна строка
    }
    return из.join('\n');
}

/** Хвост текущей пробы: от строки `i` до начала следующего `test(`.
 *  Счётчик срабатываний — законный выход, но его итоговый `expect`
 *  стоит ПОСЛЕ цикла, то есть вне блока. Искать его надо в пределах
 *  той же пробы, а не в окне из N строк: окно ловило чужой `test.skip`
 *  из соседнего теста и глушило находку. */
function хвостПробы(строки, i) {
    const из = [];
    for (let j = i; j < строки.length; j++) {
        if (j > i && /^\s*test(\.\w+)?\s*\(/.test(строки[j])) break;
        из.push(строки[j]);
    }
    return из.join('\n');
}

function пробы(д, вых) {
    вых = вых || [];
    const п = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(п)) return вых;
    for (const э of fs.readdirSync(п, { withFileTypes: true })) {
        const о = д + '/' + э.name;
        if (э.isDirectory()) пробы(о, вых);
        else if (э.name.endsWith('.spec.js')) вых.push(о);
    }
    return вых;
}

/* КОММЕНТАРИИ СРЕЗАЮТСЯ ДО ПОИСКА. В самих пробах прежний вид записан
   словами — с цитатой `if (...) expect(...)`, — и правило, ищущее его
   где угодно, падало на собственном пояснении. Строки не выбрасываются,
   а гасятся пробелами: номера строк в находках должны остаться верными.
   ПРАВИЛО, КОТОРОЕ ЛОВИТ СЛОВО ГДЕ УГОДНО, НЕ ЛОВИТ НИЧЕГО. */
function безКом(текст) {
    const вышло = текст
        .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
        .replace(/^([ \t]*)\/\/.*$/gm, (м, отступ) => отступ);
    return вышло;
}

const находки = [];
for (const ф of пробы(ПАПКА)) {
    const строки = безКом(fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8')).split('\n');
    for (let i = 0; i < строки.length; i++) {
        const с = строки[i];
        if (!НАЛИЧИЕ.some(ш => ш.test(с))) continue;
        /* ГРАНИЦЫ БЛОКА СЧИТАЮТСЯ ПО СКОБКАМ, А НЕ ОКНОМ В N СТРОК.
           Окно врало в обе стороны: чужой `test.skip` из соседнего теста
           попадал внутрь и глушил находку, а `expect` ниже по коду
           приписывался однострочной уборке. Выход засчитывается только
           тот, что стоит В ЭТОМ блоке или вплотную перед ним. */
        const блок = телоБлока(строки, i);
        if (блок.indexOf('expect(') === -1) continue;          // уборка, не проверка
        const перед = строки.slice(Math.max(0, i - 2), i).join('\n');
        const хвост = хвостПробы(строки, i);
        if (ВЫХОДЫ.some(ш => ш.test(блок) || ш.test(перед) || ш.test(хвост))) continue;
        const место = ф + ':' + (i + 1);
        if (ИСКЛЮЧЕНИЯ[место]) continue;
        находки.push(место + '\n      ' + с.trim().slice(0, 110));
    }
}

const безПричины = Object.keys(ИСКЛЮЧЕНИЯ).filter(м => (ИСКЛЮЧЕНИЯ[м] || '').trim().length < 30);
if (безПричины.length) {
    console.log('НЕ ТАК  молчащие пробы: у исключения не названа причина\n');
    for (const м of безПричины) console.log('  ✗ ' + м);
    process.exit(1);
}

if (находки.length) {
    console.log('НЕ ТАК  молчащие пробы: ' + находки.length + '\n');
    console.log('  ✗ `expect` под проверкой наличия, без честного выхода:');
    for (const н of находки) console.log('    ' + н);
    console.log('\n    Проба, защищённая `if`, молча пропускает саму себя: условие\n' +
                '    ложно — проверка не выполняется, и прогон зелёный. Нужен один\n' +
                '    из трёх выходов рядом: `test.skip(условие, причина)` — пропуск\n' +
                '    виден в отчёте; `throw new Error(...)` — отказ с именем;\n' +
                '    счётчик срабатываний и `expect(счёт).toBeGreaterThan(0)`.\n');
    process.exit(1);
}
console.log('ок      молчащие пробы: ' + пробы(ПАПКА).length + ' файлов проверено');
