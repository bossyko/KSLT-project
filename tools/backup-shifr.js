#!/usr/bin/env node
/**
 * ШИФРОВАНИЕ РЕЗЕРВНОЙ КОПИИ — ОДНО ОПРЕДЕЛЕНИЕ НА ОБА КОНЦА.
 *
 * Дом зовут двое: `backup.js` (запирает) и `backup-otkryt.js` (отпирает).
 * Держать это в двух местах нельзя: разойдутся — и копия, которую нечем
 * прочитать, ничем не лучше её отсутствия.
 *
 * ЗАЧЕМ ВООБЩЕ. В копии лежат 399 человек: имена, телефоны, почта,
 * фотографии, история матчей и оплат. Папка кладётся «в облако или на
 * внешний диск» — то есть туда, где её может увидеть не только Костя.
 * Политика конфиденциальности КСЛТ обещает шифрование резервных копий
 * (п. 11.1); до этого куска обещание было неправдой.
 *
 * КАК. AES-256-GCM. Ключ выводится из пароля через scrypt с солью —
 * пароль сам по себе ключом не становится, подбор по словарю дорожает.
 * GCM выбран не ради моды: он не только прячет, но и ЛОВИТ ПОДМЕНУ —
 * испорченный или подменённый файл не расшифруется молча, а упадёт.
 *
 * ФОРМАТ ФАЙЛА — ЗАГОЛОВОК ВПЕРЕДИ, ПЕЧАТЬ СЗАДИ:
 *
 *     KSLTBAK1  (8 байт)   чтобы человек и прибор узнали файл
 *     соль      (16 байт)  своя у каждой копии
 *     iv        (12 байт)  своё у каждой копии
 *     ...шифротекст...     tar всей папки
 *     печать    (16 байт)  GCM отдаёт её только в конце, оттого и сзади
 *
 * ПАРОЛЬ НЕ ПЕЧАТАЕТСЯ НИКОГДА — ни в отчёт, ни на экран, ни в имя файла.
 *
 * ПОТЕРЯЛ ПАРОЛЬ — ПОТЕРЯЛ КОПИЮ. Восстановить его нельзя ничем: в этом
 * и смысл. Пароль хранится там же, где пароли от ключа подписи Android,
 * и отдельно от самой копии — иначе шифрование защищает от того, у кого
 * нет папки, и ни от кого больше.
 */
'use strict';

const fs = require('fs');
const path = require('path');
const os = require('os');
const crypto = require('crypto');
const { spawn } = require('child_process');
const { pipeline } = require('stream/promises');

const ЗАГОЛОВОК = Buffer.from('KSLTBAK1', 'utf8');
const СОЛЬ = 16;
const IV = 12;
const ПЕЧАТЬ = 16;
/* 2^15 — выбор между «долго ждать» и «дёшево подобрать». На ноутбуке это
   доли секунды, подбирающему — столько же на КАЖДЫЙ вариант пароля. */
const ЦЕНА = 1 << 15;

function ключ(пароль, соль) {
    return crypto.scryptSync(String(пароль), соль, 32, { N: ЦЕНА, r: 8, p: 1, maxmem: 128 * 1024 * 1024 });
}

/* ПЕЧАТЬ ДОПИСЫВАЕТСЯ ОТДЕЛЬНЫМ ЗАХОДОМ, А НЕ ИЗ СОБЫТИЯ ПОТОКА.
   Первая редакция ждала `end` у шифра и закрывала выход оттуда же — и
   висела: поток ждал сам себя, а работа была давно сделана. Висело так
   тихо, что `process.exit(0)` в конце прибора это пряталo, и беда
   выглядела как «иногда не завершается».
   ПОТОК, КОТОРЫЙ ЗАКРЫВАЮТ ИЗ ЕГО ЖЕ СОБЫТИЯ, ЖДЁТ СЕБЯ.
   `pipeline` закрывает конец сам и возвращает управление, только когда
   всё дописано; печать кладётся следующей строкой, ждать нечего. */

/** tar всей папки → процесс. Системный tar есть и на macOS, и на Linux. */
function потокПапки(папка) {
    return spawn('tar', ['-cf', '-', '-C', path.dirname(папка), path.basename(папка)],
        { stdio: ['ignore', 'pipe', 'inherit'] });
}

/**
 * Запирает папку в один файл.
 * @returns {Promise<{файл: string, байт: number}>}
 */
async function зашифровать(папка, пароль, кудаФайл) {
    if (!пароль) throw new Error('пароль не задан');
    const соль = crypto.randomBytes(СОЛЬ);
    const iv = crypto.randomBytes(IV);
    const шифр = crypto.createCipheriv('aes-256-gcm', ключ(пароль, соль), iv);

    fs.writeFileSync(кудаФайл, Buffer.concat([ЗАГОЛОВОК, соль, iv]));
    const tar = потокПапки(папка);
    try {
        await pipeline(tar.stdout, шифр, fs.createWriteStream(кудаФайл, { flags: 'a' }));
    } catch (e) {
        try { tar.kill(); } catch (_) {}
        throw e;
    }
    fs.appendFileSync(кудаФайл, шифр.getAuthTag());
    return { файл: кудаФайл, байт: fs.statSync(кудаФайл).size };
}

/**
 * Отпирает файл обратно в папку.
 * @returns {Promise<string>} куда положено
 */
async function расшифровать(файл, пароль, кудаПапка) {
    if (!пароль) throw new Error('пароль не задан');
    const всего = fs.statSync(файл).size;
    const шапка = ЗАГОЛОВОК.length + СОЛЬ + IV;
    if (всего <= шапка + ПЕЧАТЬ) throw new Error('файл слишком мал — это не копия КСЛТ');

    const ф = fs.openSync(файл, 'r');
    const голова = Buffer.alloc(шапка);
    fs.readSync(ф, голова, 0, шапка, 0);
    const печать = Buffer.alloc(ПЕЧАТЬ);
    fs.readSync(ф, печать, 0, ПЕЧАТЬ, всего - ПЕЧАТЬ);
    fs.closeSync(ф);

    if (!голова.subarray(0, ЗАГОЛОВОК.length).equals(ЗАГОЛОВОК)) {
        throw new Error('не похоже на копию КСЛТ: нет метки KSLTBAK1');
    }
    const соль = голова.subarray(ЗАГОЛОВОК.length, ЗАГОЛОВОК.length + СОЛЬ);
    const iv = голова.subarray(ЗАГОЛОВОК.length + СОЛЬ);

    const шифр = crypto.createDecipheriv('aes-256-gcm', ключ(пароль, соль), iv);
    шифр.setAuthTag(печать);

    fs.mkdirSync(кудаПапка, { recursive: true });
    /* ЖАЛОБЫ TAR КОПЯТСЯ, А НЕ ЛЬЮТСЯ НА ЭКРАН. На неверном пароле в tar
       летит мусор, и он честно ругается «does not look like a tar archive» —
       но человеку в этот миг нужно одно слово «неверный пароль», а не три
       строки про архив. Настоящие жалобы покажем, если дело не в пароле. */
    const tar = spawn('tar', ['-xf', '-', '-C', кудаПапка], { stdio: ['pipe', 'ignore', 'pipe'] });
    let ворчание = '';
    tar.stderr.on('data', д => { ворчание += д.toString(); });
    try {
        await pipeline(
            fs.createReadStream(файл, { start: шапка, end: всего - ПЕЧАТЬ - 1 }),
            шифр,
            tar.stdin
        );
    } catch (e) {
        /* TAR УБИВАЕТСЯ РУКАМИ, А НЕ ОСТАВЛЯЕТСЯ УМИРАТЬ САМ: иначе на
           неверном пароле он остаётся жив, держит цикл событий и ждёт
           ввода, которого уже не будет. ПРОЦЕСС, ЗАПУЩЕННЫЙ НАМИ, НАМИ ЖЕ
           И ЗАКРЫВАЕТСЯ — на всех путях, включая путь отказа. */
        try { tar.kill(); } catch (_) {}
        throw new Error('не расшифровалось: неверный пароль либо файл испорчен или подменён');
    }
    await new Promise((г, б) => tar.on('close', к =>
        к === 0 ? г() : б(new Error('tar не справился: ' + ворчание.trim()))));
    return кудаПапка;
}

/** Проверка на месте: запер — отпер — сверил. Зовётся прибором. */
async function проверитьСебя() {
    const врем = fs.mkdtempSync(path.join(os.tmpdir(), 'kslt-shifr-'));
    const исход = path.join(врем, 'данные');
    fs.mkdirSync(исход);
    fs.writeFileSync(path.join(исход, 'проба.json'), JSON.stringify({ игрок: 'Иванов', очки: 1234 }));
    const файл = path.join(врем, 'копия.enc');
    await зашифровать(исход, 'пароль-пробы', файл);

    const сырое = fs.readFileSync(файл);
    if (сырое.includes(Buffer.from('Иванов', 'utf8'))) {
        fs.rmSync(врем, { recursive: true, force: true });
        throw new Error('имя игрока читается в зашифрованном файле');
    }

    let упалоНаЧужом = false;
    try { await расшифровать(файл, 'чужой-пароль', path.join(врем, 'чужое')); }
    catch (e) { упалоНаЧужом = true; }
    if (!упалоНаЧужом) {
        fs.rmSync(врем, { recursive: true, force: true });
        throw new Error('чужой пароль открыл копию');
    }

    await расшифровать(файл, 'пароль-пробы', path.join(врем, 'назад'));
    const назад = JSON.parse(fs.readFileSync(path.join(врем, 'назад', 'данные', 'проба.json'), 'utf8'));
    fs.rmSync(врем, { recursive: true, force: true });
    if (назад.игрок !== 'Иванов' || назад.очки !== 1234) throw new Error('данные вернулись не теми');
    return true;
}

module.exports = { зашифровать, расшифровать, проверитьСебя, ЗАГОЛОВОК };

if (require.main === module) {
    /* ВЫХОД НАЗЫВАЕТСЯ ЯВНО. Без него прибор однажды повис на ровном
       месте: где-то остался незакрытый поток, цикл событий не опустел,
       и `node` ждал неизвестно чего, хотя вся работа была сделана.
       ПРИБОР, КОТОРЫЙ НЕ ВЫХОДИТ САМ, НЕОТЛИЧИМ ОТ УПАВШЕГО. */
    проверитьСебя()
        .then(() => {
            console.log('\n  ок  шифрование запирает, чужой пароль не открывает, данные возвращаются целыми\n');
            process.exit(0);
        })
        .catch(e => { console.error('\n  НЕ ТАК  ' + e.message + '\n'); process.exit(1); });
}
