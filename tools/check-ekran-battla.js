#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ЭКРАН БАТТЛА В ПРИЛОЖЕНИИ: КАРТА И ОТМЕНЁННЫЙ БАТТЛ» (30.10).
 *
 * ЗАМЕР ДО ПРАВКИ, ЧТЕНИЕМ — И ЭТО БЫЛА НЕ НЕХВАТКА, А ПОЛОМКА.
 *
 * 1. ОТМЕНЁННЫЙ БАТТЛ РИСОВАЛСЯ КАК ЖИВОЙ. Ни один список баттлов не
 *    фильтрует по статусу: `mobile/www/js/screens/home.js:129`,
 *    `screens/battles.js:29` и на сайте `js/battles-overview.js:253`
 *    берут всё с `battle_published = true`. Значит отменённый баттл
 *    остаётся в ленте. Сайт на этот случай показывает «Баттл отменён»
 *    (`js/challenge-detail.js:296`), а приложение открывало его целиком
 *    — с кнопками голосования.
 *    И СЕРВЕР ТАКОЙ ГОЛОС ПРИНИМАЛ: `cast_battle_vote` смотрит
 *    `battle_published`, `voting_closed` и время матча, а статус не
 *    смотрит вовсе (`sql/функции/battle-vote-rpc.sql:25-41`). Человек
 *    голосовал за игру, которой не будет.
 *    ЗАПРЕТ НА СТОРОНЕ СЕРВЕРА ЗДЕСЬ НЕ СТЕРЕЖЁТСЯ: это правило о
 *    данных, оно ждёт слова Кости и своего куска. Записано в трекер.
 *
 * 2. КАРТЫ НЕ БЫЛО, ХОТЯ ДАННЫЕ БЫЛИ. `get_battle_public` отдаёт
 *    `court_google_maps` и `court_twogis`
 *    (`sql/функции/battle-court-links-migration.sql:19-20`), а
 *    приложение не читало их НИ РАЗУ — посчитано. Место показывалось
 *    одной строкой текста.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ:
 *   • отменённый баттл в приложении НЕ доходит до голосования;
 *   • слова отмены есть на всех трёх языках и совпадают с сайтом;
 *   • адрес карты собирает ДОМ, своей копии в приложении нет;
 *   • дом карты — побайтовая копия сайта и подключён раньше зовущего;
 *   • карта рисуется только когда есть хоть одна ссылка.
 *
 *   node tools/check-ekran-battla.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = т => безКомментариев(т);

const ЭКРАН = 'mobile/www/js/screens/home.js';
const ДОМ = 'js/kslt-karta.js';
const ДОМ_П = 'mobile/www/js/kslt-karta.js';
const СЛОВАРЬ = 'mobile/www/js/i18n.js';
const РАЗМЕТКА = 'mobile/www/index.html';
const CSS = 'mobile/www/css/app.css';

const экран = безКом(чит(ЭКРАН));
const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

/* ══ 1. ОТМЕНЁННЫЙ БАТТЛ НЕ ДОХОДИТ ДО ГОЛОСОВАНИЯ ══════════════════════ */

/* ПРИЗНАК СМОТРИТ ПОРЯДОК, А НЕ НАЛИЧИЕ. Проверка статуса, стоящая
   ПОСЛЕ отрисовки, не спасает ни от кнопок, ни от голоса: важно, что
   она раньше. */
/* ПРИЗНАК ПЕРЕВЕДЁН НА ДОМ 07.11. Искалась строка
   `_battleData.status === 'cancelled'`. Её в файле больше нет: понятие
   «баттл отменён» переехало в дом формата — `KSLT_BATTLE_FORMAT.isCancelled`
   (`mobile/www/js/battle-format.js:179`), и экран зовёт его.
   СТОРОЖ, ДЕРЖАЩИЙ СТРОКУ КОДА, ПАДАЕТ ПРИ ПЕРЕЕЗДЕ ПОНЯТИЯ В ДОМ — и
   выглядит это как возврат беды, которой нет. Признак держит ОТНОШЕНИЕ:
   отмена спрашивается РАНЬШЕ отрисовки и голосования, кем бы ни был
   спрошен. Обе формы приняты: и зов дома, и прежняя строка. */
правило('отменённый баттл отсекается ДО отрисовки и голосования',
    (function () {
        const зовДома = экран.indexOf('isCancelled(_battleData)');
        const прежняя = экран.indexOf("_battleData.status === 'cancelled'");
        const п = зовДома !== -1 ? зовДома : прежняя;
        const р = экран.indexOf('renderBattleOverlay(_battleData');
        const г = экран.indexOf('loadBattleMyVote(bid)');
        return п !== -1 && р !== -1 && г !== -1 && п < р && п < г;
    })(),
    'Проверка статуса стоит после отрисовки (или её нет вовсе) — значит\n' +
    'человек снова увидит кнопки голосования на отменённом баттле, а\n' +
    'сервер такой голос ПРИМЕТ: он статус не смотрит.');

правило('ветка отмены выходит из функции, а не просто рисует',
    /(isCancelled\(_battleData\)|status === 'cancelled')\)\s*\{[\s\S]{0,400}?return;/.test(экран),
    'Без `return` отрисовка пойдёт дальше и положит поверх полный экран\n' +
    'баттла. Ветка обязана заканчивать разбор.');

/* ══ 2. СЛОВА ОТМЕНЫ — НА ТРЁХ ЯЗЫКАХ И ТЕ ЖЕ, ЧТО У САЙТА ══════════════ */

const словарь = чит(СЛОВАРЬ);
['battles.cancelled', 'battles.cancelledDesc', 'battles.place'].forEach(ключ => {
    правило('слово ' + ключ + ' есть на всех трёх языках',
        (function () {
            const i = словарь.indexOf("'" + ключ + "'");
            if (i === -1) return false;
            const строка = словарь.slice(i, словарь.indexOf('\n', i));
            return /ru:/.test(строка) && /en:/.test(строка) && /kg:/.test(строка);
        })(),
        'Ключ без одного языка — это пустое место на экране у человека,\n' +
        'который читает приложение на этом языке.');
});

правило('слова отмены совпадают с сайтом',
    (function () {
        const сайт = чит('js/challenge-detail.js');
        return сайт.indexOf('Баттл отменён') !== -1 &&
               словарь.indexOf('Баттл отменён') !== -1 &&
               сайт.indexOf('Battle cancelled') !== -1 &&
               словарь.indexOf('Battle cancelled') !== -1;
    })(),
    'Одно событие — одно слово в двух продуктах. Разойдутся — человек\n' +
    'решит, что это разные вещи.');

/* ══ 3. АДРЕС КАРТЫ СОБИРАЕТ ДОМ ════════════════════════════════════════ */

правило('экран берёт адрес карты у дома, а не собирает сам',
    /window\.KSLT_KARTA/.test(экран) &&
    !/maps\.google\.com\/maps\?q=/.test(экран) &&
    !/output=embed/.test(экран),
    'Дом знает четыре вида ссылок Google (встроенная, `?q=`, координаты\n' +
    '`@`, `/place/`) и отдельно 2ГИС, где долгота и широта стоят В\n' +
    'ОБРАТНОМ ПОРЯДКЕ. Своя копия разойдётся на первой же короткой\n' +
    'ссылке — именно так и разошлись четыре копии на сайте до 19.10.');

правило('дом карты объявлен ровно один раз на продукт',
    (function () {
        const свои = [ДОМ, ДОМ_П, ЭКРАН, 'js/challenge-detail.js', 'js/courts.js',
                      'js/tournament-detail.js'];
        return свои.filter(ф => /window\.KSLT_KARTA\s*=/.test(безКом(чит(ф)))).length === 2;
    })(),
    'Объявлений должно быть два: сайт и побайтовая копия приложения.');

правило('копии дома карты побайтово равны',
    чит(ДОМ) === чит(ДОМ_П),
    'Разошлись — и один продукт начнёт показывать карту другого места.');

правило('дом карты подключён в приложение раньше экрана',
    (function () {
        const т = чит(РАЗМЕТКА);
        const д = т.indexOf('js/kslt-karta.js');
        const э = т.indexOf('js/screens/home.js');
        return д !== -1 && э !== -1 && д < э;
    })(),
    'Скрипт выше выполняется раньше. Без дома первый же баттл с кортом\n' +
    'упадёт на `KSLT_KARTA is not defined` ещё до отрисовки карты.');

/* ══ 4. КАРТА РИСУЕТСЯ ТОЛЬКО КОГДА ЕСТЬ ССЫЛКА ═════════════════════════ */

правило('без ссылок блок карты не рисуется вовсе',
    /function renderBattleMap\(b\) \{[\s\S]{0,200}?if \(!gm && !tg\) return '';/.test(экран),
    'Пустая рамка с заголовком «Место» хуже отсутствия блока: человек\n' +
    'видит место, где что-то должно быть, и не понимает, что потерялось.');

правило('ссылки экранируются, как и все данные',
    (function () {
        const i = экран.indexOf('function renderBattleMap');
        const тело = экран.slice(i, i + 1400);
        return /esc\(gm\)/.test(тело) && /esc\(tg\)/.test(тело) && /esc\(адрес\)/.test(тело);
    })(),
    'Ссылку на корт вписывает менеджер в админке — это данные, и в\n' +
    'разметку они идут только через экранирование.');

правило('у карты и отмены есть свой вид в css',
    ['.bd-map-box', '.bd-map-links', '.bd-map-link', '.bd-map', '.bd-cancelled']
        .every(с => new RegExp(с.replace('.', '\\.') + '\\s*\\{').test(чит(CSS))),
    'Блок без правил вида встанет голым текстом поверх накладки.');

/* ───────── вывод ───────── */
console.log('');
if (!ошибки.length) {
    console.log('  ок      экран баттла в приложении: все ' +
        (fs.readFileSync(__filename, 'utf8').match(/правило\('/g) || []).length +
        ' правил держатся');
    console.log('          отменённый баттл до голосования не доходит');
    console.log('          адрес карты собирает дом, копии равны');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  экран баттла в приложении — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
