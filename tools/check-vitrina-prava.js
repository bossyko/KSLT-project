#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ВИТРИНА ИГРОКОВ ЧИТАЕТСЯ ГОСТЕМ» (06.11).
 *
 * ЧТО СЛУЧИЛОСЬ. 04.11 витрина `players_public` была пересоздана с
 * признаком `zakryt`, который читает `players.banned_until` и таблицу
 * `profiles`. Витрина стоит на `security_invoker = on` — читает ПРАВАМИ
 * СПРАШИВАЮЩЕГО, — а гостю `banned_until` не выдан намеренно
 * (`sql/доступ/players-public-view.sql`, колоночный GRANT). Гость стал
 * получать `42501 permission denied for table players` на ЛЮБОЙ запрос
 * к витрине, даже на `select id`. Рейтинг, карточки игроков и NTRP у
 * партнёров были пусты две недели — на сайте и в приложении.
 *
 * ПРАВИЛО, КОТОРОЕ ЭТО ПОРОДИЛО:
 *   ВИТРИНА С security_invoker ТРЕБУЕТ ПРАВ НА ВСЁ СВОЁ ОПРЕДЕЛЕНИЕ,
 *   А НЕ НА ЗАПРОШЕННЫЕ СТОЛБЦЫ.
 * Поэтому `select id` падал так же, как `select *`: права проверяются
 * по телу витрины целиком, до того как лишние столбцы отброшены.
 *
 * ЧТО СТЕРЕЖЁТ. Тело ДЕЙСТВУЮЩЕГО определения витрины: в нём не должно
 * быть ни одного имени, закрытого для гостя, и обращения к `profiles`.
 * Признак «закрыт» считается функцией `igrok_zakryt` — она объявлена
 * SECURITY DEFINER и потому не требует от гостя прав на эти столбцы.
 *
 * ПОЧЕМУ ДЕЙСТВУЮЩЕЕ ОДНО. Файлов, создающих витрину, в истории
 * несколько, и это нормально. Но действующее определение обязано быть
 * ОДНО: два живых определения разойдутся, и беда родится ровно на шве.
 * Отработавший файл помечается строкой `ОПРЕДЕЛЕНИЕ УСТАРЕЛО` над своим
 * `CREATE VIEW` — тогда прибор считает его историей, а не правилом.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ. Прибор читает файлы, а не базу: он не знает, что
 * в базе выполнено на самом деле. Проверку правами гостя делает сам
 * SQL-файл блоком `SET LOCAL ROLE anon`.
 *
 *   node tools/check-vitrina-prava.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ПАПКА = 'sql/доступ';
const ФУНКЦИЯ = 'igrok_zakryt';

/* Столбцы `players`, которых гостю не выдают. Список ведётся вместе с
   колоночным GRANT в `players-public-view.sql`: что не выдано там —
   то не имеет права встречаться в теле витрины. */
const ЗАКРЫТЫЕ = ['banned_until', 'ban_reason', 'email', 'phone',
                  'show_phone', 'account_deleted_at'];

/* КОММЕНТАРИИ СРЕЗАЮТСЯ ДО ВСЯКОГО ПОИСКА. В этом самом файле слова
   «SECURITY DEFINER» и имя `banned_until` стоят в пояснениях — правило,
   которое ищет слово ГДЕ УГОДНО, не ловит ничего: оно одинаково
   проходит и на верном коде, и на откате. */
function безКом(т) {
    return (т || '').replace(/--[^\n]*/g, ' ').replace(/\/\*[\s\S]*?\*\//g, ' ');
}
function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function sqlФайлы() {
    const п = path.join(КОРЕНЬ, ПАПКА);
    if (!fs.existsSync(п)) return [];
    return fs.readdirSync(п).filter(и => и.endsWith('.sql')).map(и => ПАПКА + '/' + и);
}

/** Тела всех `CREATE VIEW public.players_public ... ;` в файле, с пометкой
 *  «устарело», взятой из 12 строк НАД самим CREATE VIEW. */
function определения(т) {
    const из = [];
    const ре = /CREATE\s+VIEW\s+public\.players_public\b/gi;
    let м;
    while ((м = ре.exec(т)) !== null) {
        const конец = т.indexOf(';', м.index);
        const тело = конец === -1 ? т.slice(м.index) : т.slice(м.index, конец);
        const шапка = т.slice(0, м.index).split('\n').slice(-12).join('\n');
        из.push({ тело: безКом(тело), устарело: /ОПРЕДЕЛЕНИЕ\s+УСТАРЕЛО/i.test(шапка) });
    }
    return из;
}

const живые = [];
for (const ф of sqlФайлы()) {
    const т = чит(ф);
    if (!т) continue;
    for (const о of определения(т)) if (!о.устарело) живые.push({ файл: ф, тело: о.тело });
}

const тело = живые.length === 1 ? живые[0].тело : '';
const фТекст = живые.length === 1 ? безКом(чит(живые[0].файл) || '') : '';

const нашлись = ЗАКРЫТЫЕ.filter(с => new RegExp('\\b' + с + '\\b').test(тело));
const профили = /\bprofiles\b/i.test(тело);

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя: имя, подсказка: подсказка });
}

правило('действующее определение витрины одно',
    живые.length === 1,
    'Непомеченных `CREATE VIEW public.players_public` найдено ' + живые.length +
    (живые.length ? ':' + живые.map(о => '\n  ' + о.файл).join('') : '') +
    '\nОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. Отработавший файл помечается\n' +
    'строкой `ОПРЕДЕЛЕНИЕ УСТАРЕЛО` над своим `CREATE VIEW` — он остаётся\n' +
    'в истории, но перестаёт быть вторым живым правилом.');

правило('в теле витрины нет столбцов, закрытых для гостя',
    живые.length === 1 && нашлись.length === 0,
    'В теле витрины встречаются закрытые имена: ' + нашлись.join(', ') +
    '\nВитрина стоит на `security_invoker`: права проверяются по ВСЕМУ её\n' +
    'определению, а не по запрошенным столбцам. Любое из этих имён в теле\n' +
    'закрывает гостю витрину целиком — он получит 42501 даже на `select id`.\n' +
    'Нужен признак из закрытого столбца — считай его функцией SECURITY\n' +
    'DEFINER, как `' + ФУНКЦИЯ + '`, и отдавай витриной только результат.');

правило('витрина не ходит в profiles напрямую',
    живые.length === 1 && !профили,
    'В теле витрины есть обращение к `profiles`. Правила строк этой\n' +
    'таблицы прячут от гостя чужие записи, поэтому прямое обращение из\n' +
    'витрины либо упрётся в отказ, либо молча соврёт нулём. Признак\n' +
    'считает функция `' + ФУНКЦИЯ + '` правами владельца.');

правило('признак «закрыт» считает функция',
    живые.length === 1 && new RegExp('public\\.' + ФУНКЦИЯ + '\\s*\\(').test(тело),
    'В теле витрины нет вызова `public.' + ФУНКЦИЯ + '(`. Либо признак\n' +
    '`zakryt` пропал из витрины вовсе — и метка бана перестанет\n' +
    'показываться в списках, — либо его снова считают прямым чтением.');

правило('функция объявлена как SECURITY DEFINER с прибитым search_path',
    /CREATE\s+(OR\s+REPLACE\s+)?FUNCTION\s+public\.igrok_zakryt/i.test(фТекст) &&
    /SECURITY\s+DEFINER/i.test(фТекст) &&
    /SET\s+search_path\s*=/i.test(фТекст),
    'Функция `' + ФУНКЦИЯ + '` должна быть создана в том же файле, что и\n' +
    'витрина, объявлена `SECURITY DEFINER` и с прибитым `SET search_path`.\n' +
    'Без DEFINER она не поможет гостю вовсе. Без прибитого `search_path`\n' +
    'функция, работающая правами владельца, берёт имена таблиц из чужого\n' +
    'пути — это уже не удобство, а дыра.');

правило('право вызова выдано поимённо, а не всем',
    /REVOKE\s+ALL\s+ON\s+FUNCTION\s+public\.igrok_zakryt[^;]*FROM\s+PUBLIC/i.test(фТекст) &&
    /GRANT\s+EXECUTE\s+ON\s+FUNCTION\s+public\.igrok_zakryt[^;]*TO\s+anon/i.test(фТекст) &&
    /GRANT\s+EXECUTE\s+ON\s+FUNCTION\s+public\.igrok_zakryt[^;]*TO\s+authenticated/i.test(фТекст),
    'У функции SECURITY DEFINER право вызова по умолчанию есть у всех.\n' +
    'Нужны три строки: `REVOKE ALL ... FROM PUBLIC`, затем `GRANT EXECUTE`\n' +
    'гостю и вошедшему поимённо.');

правило('проверка файла смотрит глазами гостя',
    /SET\s+LOCAL\s+ROLE\s+anon/i.test(фТекст),
    'В файле нет блока `SET LOCAL ROLE anon`. Ломалось именно у гостя, а\n' +
    'счёт твоими правами проходил и тогда: «у меня зелёное» ничего не\n' +
    'доказывает. Проверка обязана считать строки витрины под ролью гостя.');

if (ошибки.length) {
    console.log('НЕ ТАК  витрина игроков и права гостя: ' + ошибки.length + ' из 7 правил упало\n');
    for (const о of ошибки) console.log('  ✗ ' + о.имя + '\n    ' + о.подсказка.replace(/\n/g, '\n    ') + '\n');
    process.exit(1);
}
console.log('ок      витрина игроков и права гостя: 7 правил');
