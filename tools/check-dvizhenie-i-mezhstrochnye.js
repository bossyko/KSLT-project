/**
 * ЗАМОРОЗКА ДВИЖЕНИЯ И МЕЖСТРОЧНЫХ (заход B4, 15.10.2026).
 *
 * ЗАМЕР 15.10, и обе записи трекера были неверны.
 *
 * ДВИЖЕНИЕ. Записывалось «46 бесконечных анимаций без
 * prefers-reduced-motion». Бесконечных 38, а блок отказа был в 21 файле
 * из 29 — на вид сделано. Проверено не наличие блока, а что он ГАСИТ:
 * 26 анимаций из 38 не гасились вовсе. Причина — 27 копий одного
 * понятия: каждый блок перечислял один-четыре селектора ПОИМЁННО, и
 * список в каждом отстал от своего файла. ПРАВИЛО, ПЕРЕЧИСЛЯЮЩЕЕ ИМЕНА,
 * СТАРЕЕТ ВМЕСТЕ С КОДОМ.
 *
 * МЕЖСТРОЧНЫЕ. Записывалось «три мимо лестницы в courts.css». В
 * courts.css их не было вовсе — свели куском корт. По настоящей лестнице
 * 1 · 1.1 · 1.3 · 1.5 · 1.65 мимо стояло 69 мест в восьми файлах.
 * Лестницу сторожили два правила по своим файлам — потому 69 и жили в
 * остальных двадцати семи.
 *
 * ЗАМОРОЖЕНЫ ОТНОШЕНИЯ:
 *   • движение выключается ОДНИМ местом и через звёздочку, а не списком;
 *   • длительность 0.01ms, а не `none`: `none` оставляет элемент в
 *     начальном кадре, и всё, что появляется через opacity 0 → 1, у
 *     rm-посетителя осталось бы невидимым навсегда;
 *   • копии общего блока не заводятся заново по файлам;
 *   • движение, которое ВЕЗЁТ содержимое, не просто останавливают: две
 *     ленты получают взамен прокрутку пальцем, иначе доступность одного
 *     человека прячет от него же половину спонсоров;
 *   • каждый межстрочный стоит на ступени лестницы.
 *
 * ЗАМЕРЕНО В БРАУЗЕРЕ: с включённой настройкой — 1712 узлов главной,
 * движения ноль; с выключенной — 31 анимация и 342 перехода на месте.
 * Лестница текста снята на пяти видах страницы турнира: 30-32 уровня,
 * мимо лестницы ноль на каждом.
 *
 *   node tools/check-dvizhenie-i-mezhstrochnye.js
 */
const fs = require('fs');
const path = require('path');
const ДВИЖ = require('./dvizhenie.js');

const КОРЕНЬ = path.join(__dirname, '..');
const ПАПКА = path.join(КОРЕНЬ, 'css');
const ФАЙЛЫ = fs.readdirSync(ПАПКА).filter(ф => ф.endsWith('.css'));
const чит = ф => fs.readFileSync(path.join(ПАПКА, ф), 'utf8');
const гасить = s => s.replace(/\/\*[\s\S]*?\*\//g, m => m.replace(/[^\n]/g, ' '));

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ══ 1. ОБЩИЙ БЛОК ЕСТЬ И ОН ПРАВИЛЬНЫЙ ════════════════════════════════ */

правило('движение выключается одним общим местом',
    ДВИЖ.общееГашение(),
    ДВИЖ.ПОДСКАЗКА);

/* ══ 2. КОПИИ НЕ ЗАВОДЯТСЯ ЗАНОВО ══════════════════════════════════════ */

/* Два файла держат СВОИ блоки законно: там лента, которую мало
   остановить — ей отдают прокрутку. Четыре чинят видимость (opacity,
   display, scroll-snap), чего общий сброс не делает. Список закрыт:
   новая копия роняет правило. */
const ЗАКОННЫЕ = {
    'style.css': 'лента логотипов: движение снимается, взамен прокрутка пальцем',
    'services.css': 'лента услуг: то же самое',
    'news.css': 'возвращает видимость: opacity',
    'players.css': 'возвращает видимость: opacity',
    'podium.css': 'возвращает видимость: opacity, display, transition-delay',
    'tournaments-overview.css': 'снимает прилипание прокрутки: scroll-snap-type'
};
const своиБлоки = [];
ФАЙЛЫ.forEach(ф => {
    if (ф === 'tokens.css') return;
    const т = гасить(чит(ф));
    const n = (т.match(/@media[^{]*prefers-reduced-motion/g) || []).length;
    if (n > 0) своиБлоки.push({ файл: ф, n });
});
const лишние = своиБлоки.filter(б => !(б.файл in ЗАКОННЫЕ));

правило('копии общего блока не заводятся по файлам',
    лишние.length === 0,
    'файлов со своим блоком отказа от движения сверх списка: ' + лишние.length + '\n            ' +
    лишние.map(б => б.файл + ' ×' + б.n).join(', ') +
    '\n            До 15.10 таких копий было 27 в 21 файле, и 26 бесконечных анимаций\n' +
    '            из 38 не гасились вовсе. Свой блок заводится только там, где\n' +
    '            общего СБРОСА НЕ ХВАТАЕТ: вернуть видимость или отдать прокрутку.');

/* ══ 3. ЛЕНТА, КОТОРАЯ ВЕЗЁТ, ПОЛУЧАЕТ ПРОКРУТКУ ═══════════════════════ */

function вБлокеОтказа(текст, что) {
    const re = /@media[^{]*prefers-reduced-motion[^{]*\{/g;
    let м;
    while ((м = re.exec(текст)) !== null) {
        let гл = 1, j = м.index + м[0].length;
        const о = j;
        while (j < текст.length && гл) {
            if (текст[j] === '{') гл++;
            else if (текст[j] === '}') гл--;
            j++;
        }
        if (текст.slice(о, j).indexOf(что) !== -1) return true;
    }
    return false;
}
const СТИ = гасить(чит('style.css'));
const СЕРВ = гасить(чит('services.css'));

правило('ленте логотипов отдают прокрутку, а не просто стоп',
    вБлокеОтказа(СТИ, 'overflow-x: auto') && вБлокеОтказа(СТИ, 'mask-image: none'),
    'лента едет 90 с, и родитель держит overflow: hidden. Останови её — и\n' +
    '            логотипы за краем станут недоступны НИКАК. До 15.10 здесь стояло\n' +
    '            `animation: none`, и лента замирала на первом кадре вместе с\n' +
    '            половиной спонсоров. WCAG 2.3.3 и 1.4.2.');

правило('ленте услуг отдают прокрутку, а не просто стоп',
    вБлокеОтказа(СЕРВ, 'overflow-x: auto'),
    'то же, что у ленты логотипов: карточки услуг везёт лента, и родитель\n' +
    '            режет всё за краем');

/* ══ 4. ЛЕСТНИЦА МЕЖСТРОЧНЫХ — НА ВЕСЬ ПРОДУКТ ═════════════════════════ */

/* Лестницу сторожили ДВА правила по своим файлам (кабинет и английские
   корты), и ровно поэтому 69 мест жили в остальных двадцати семи. */
const СТУПЕНИ = [1, 1.1, 1.3, 1.5, 1.65];
const мимо = [];
ФАЙЛЫ.forEach(ф => {
    const т = гасить(чит(ф));
    const re = /line-height\s*:\s*([\d.]+)\s*[;}]/g;
    let м;
    while ((м = re.exec(т)) !== null) {
        const v = parseFloat(м[1]);
        /* Больше трёх — это не отношение, а пиксели без единицы; такие
           ловит другое правило. */
        if (v > 3) continue;
        if (СТУПЕНИ.some(с => Math.abs(с - v) < 1e-9)) continue;
        мимо.push(ф + ':' + т.slice(0, м.index).split('\n').length + '  ' + v);
    }
});

правило('каждый межстрочный стоит на ступени лестницы',
    мимо.length === 0,
    'мимо лестницы 1 · 1.1 · 1.3 · 1.5 · 1.65: ' + мимо.length + '\n            ' +
    мимо.slice(0, 8).join('\n            ') +
    '\n            Ступень выбирается по УРОВНЮ ТЕКСТА, а не подгонкой высоты блока.\n' +
    '            15.10 подтянуто 69 мест в восьми файлах.');

/* ══ ВЫВОД ═════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('\n  ок      движение и межстрочные: 5 правил');
    console.log('          движение гасится одним местом через звёздочку, копий нет');
    console.log('          две ленты получают прокрутку вместо остановки');
    console.log('          межстрочные стоят на пяти ступенях, мимо ноль\n');
} else {
    console.log('\n  НЕ ТАК  движение и межстрочные — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(о => {
        console.log('          x ' + о.имя);
        console.log('            ' + о.подсказка + '\n');
    });
    process.exitCode = 1;
}
