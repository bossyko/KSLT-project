/**
 * КАЖДАЯ ПУБЛИЧНАЯ СТРАНИЦА ОТКРЫВАЕТСЯ ХОТЬ ОДНОЙ ПРОБОЙ (12.11.2026).
 *
 * ОТКУДА. Кусок планшетных ширин держали открытым ради урока: «два
 * дефекта жили ровно там, куда мы не заглядывали». Урок верный, но
 * памятью он не работает — при закрытии куска обход показал ТРИ
 * страницы, которых не открывала ни одна проба: terms,
 * privacy-policy, download, все на трёх языках. Это те самые места,
 * куда приходят из сторов и из подвала: молчаливое падение там
 * заметят снаружи.
 *
 * ПОЧЕМУ ПРАВИЛО, А НЕ ЗАПИСЬ В ТРЕКЕРЕ: запись стареет молча, а это
 * падает в тот день, когда в продукте появится страница, которую
 * никто не открывает. ПАМЯТЬ ЗАМЕНЯЕТСЯ ПРОВЕРКОЙ.
 *
 * ЧТО СТОРОЖИТСЯ: список публичных страниц берётся с диска тем же
 * признаком, что и карта сайта (служебная — та, что носит noindex, и
 * превью), и каждая обязана встречаться в tests/.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');

const ошибки = [];
const правило = (имя, условие, почему) => { if (!условие) ошибки.push(имя + ' — ' + почему); };

/* ОДИН ПРИЗНАК ПУБЛИЧНОСТИ НА ПРОДУКТ: тот же, что у карты сайта. */
const все = fs.readdirSync(КОРЕНЬ).filter(и => и.endsWith('.html'))
    .concat(fs.readdirSync(path.join(КОРЕНЬ, 'pages')).filter(и => и.endsWith('.html')).map(и => 'pages/' + и));
const служебная = п => path.basename(п).startsWith('_preview') || /noindex/.test(чит(п));
const публичные = все.filter(п => !служебная(п)).sort();

/* Пробы читаем все разом: страницу может открывать любая, не только
   01-pages-load — важно, что её открывает хоть кто-то. */
function файлыПроб(д, итог) {
    итог = итог || [];
    for (const э of fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true })) {
        const п = д + '/' + э.name;
        if (э.isDirectory()) { if (э.name !== 'reports' && э.name !== 'node_modules') файлыПроб(п, итог); }
        else if (/\.(js|mjs)$/.test(э.name)) итог.push(п);
    }
    return итог;
}
const текстПроб = файлыПроб('tests').map(чит).join('\n');

const безПробы = публичные.filter(п => текстПроб.indexOf(path.basename(п)) === -1);
правило('каждую публичную страницу открывает хоть одна проба',
    безПробы.length === 0,
    'страниц, которых не открывает ни одна проба: ' + безПробы.length + '\n    ' +
    безПробы.join('\n    ') +
    '\n    Дефект живёт ровно там, куда не заглядывают: так жили h270 и h274.');

if (ошибки.length) {
    console.error('СТРАНИЦЫ ПОД ПРОБОЙ — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
console.log('страницы под пробой: публичных ' + публичные.length + ', без пробы 0');
