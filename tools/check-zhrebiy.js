#!/usr/bin/env node
/**
 * ЗАМОРОЗКА ЖЕРЕБЬЁВКИ — шаг 3 разбора турнира, 29.09.
 *
 * Здесь заморожены ОТНОШЕНИЯ, а не числа: «случайность идёт от зерна»,
 * «формула одна», «умолчание живёт в данных», «сыгранное не сносится».
 *
 *   node tools/check-zhrebiy.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ПРАВИЛА = чит('js/kslt-rules.js');
const ПРАВч   = безКом(ПРАВИЛА);
const СЕТКА   = чит('js/admin/sections/bracket.js');
const СЕТч    = безКом(СЕТКА);
const ФОРМА   = безКом(чит('js/admin/sections/tournaments.js'));
const АДМИНCSS = безКом(чит('css/admin.css'));
const СТРАНИЦА = чит('pages/admin.html');

const ошибки = [];
/* ЧИСЛО ПРАВИЛ СЧИТАЕТСЯ, А НЕ ПИШЕТСЯ РУКАМИ. 09.10 здесь стояло зашитое
   `const всего = 16` при двадцати двух живых правилах: файл отчитывался
   числом, которого не мерил, и шесть новых правил в отчёте не существовали. */
let всегоПравил = 0;
const правило = (имя, условие, подсказка) => {
    всегоПравил++;
    if (!условие) ошибки.push({ имя, подсказка });
};

/* ─────────── ЖРЕБИЙ ─────────── */

/* Math.random в файле сетки допустим РОВНО ОДИН раз — там, где рождается
   само зерно. Всё остальное считается от него, иначе расклад не повторить. */
правило('случайность в сетке берётся только для рождения зерна',
    (СЕТч.match(/Math\.random\(/g) || []).length === 1,
    'в bracket.js снова больше одного Math.random — расклад перестал быть повторяемым');

/* НЕ СЧИТАЕМ ВЫЗОВЫ. Счёт «не меньше семи» говорил о том же, о чём правило
   выше: верни одну тасовку на место — и упали бы оба. Прувер это поймал.
   Здесь стережём ТОЛЬКО то, что общая тасовка существует и ею пользуются. */
правило('тасовка живёт одним определением в общих правилах',
    /R\.перемешать\s*=\s*function/.test(ПРАВч) &&
    /KSLT_RULES\.перемешать\(/.test(СЕТч),
    'тасовка снова написана на месте вместо KSLT_RULES.перемешать');

правило('перемешать не работает без броска',
    /typeof\s+бросок\s*!==\s*'function'[\s\S]{0,120}throw/.test(ПРАВч),
    'молчаливая подстановка случайности вернулась: жеребьёвку снова не повторить');

правило('бросок считается от зерна, а не от времени',
    /R\.бросок\s*=\s*function\s*\(\s*зерно\s*\)/.test(ПРАВч) &&
    !/Date\.now|performance\.now/.test(блок(ПРАВч, 'R.бросок = function')),
    'бросок перестал зависеть только от зерна — повторить его больше нельзя');

правило('жеребьёвка берёт зерно турнира',
    /async function жребийТурнира\(tournament\)/.test(СЕТч) &&
    /KSLT_RULES\.бросок\(tournament\.draw_seed\)/.test(СЕТч),
    'зерно перестало браться из турнира');

/* ─────────── РАСКЛАД СВОБОДНЫХ МЕСТ ─────────── */

правило('формула свободных мест — одно определение',
    /R\.раскладСвободных\s*=\s*function/.test(ПРАВч) &&
    !/свободно\s*\*\s*2/.test(СЕТч) && !/свободно\s*\*\s*2/.test(ФОРМА),
    'формула снова написана на месте — подсказка и сетка разойдутся');
/* Два правила рядом, и они НЕ ПЕРЕСЕКАЮТСЯ: первое стережёт копии формулы,
   второе — что обе стороны зовут общую. Прувер 29.09 поймал, что один откат
   ронял оба: значит правила говорили об одном и том же. */

правило('и сетка, и форма зовут её',
    /KSLT_RULES\.раскладСвободных\(/.test(СЕТч) &&
    /KSLT_RULES\.раскладСвободных\(/.test(ФОРМА),
    'одна из двух сторон считает по-своему');

правило('меток не больше, чем претендентов',
    /проходом:\s*с\s*-\s*матчей\s*-\s*безИгры/.test(ПРАВч),
    'исчез третий исход: клетка снова может ждать несуществующего человека');

/* ─────────── УМОЛЧАНИЯ ─────────── */

правило('групповая жеребьёвка не придумывает число групп',
    !/group_count\s*\|\|/.test(блок(СЕТч, 'async function generateGroupDraw')),
    'умолчание вернулось: пустое поле снова молча станет двойкой');

правило('настройку судит общее правило, а не две разные проверки',
    /KSLT_RULES\.бедаНастройкиГрупп\(/.test(СЕТч) &&
    /KSLT_RULES\.бедаНастройкиГрупп\(/.test(ФОРМА),
    'форма и жеребьёвка снова судят разными мерками');

правило('«группа не отсеивает» — предупреждение, а не отказ',
    /R\.предупреждениеОГруппах\s*=\s*function/.test(ПРАВч) &&
    /предупреждениеОГруппах\(/.test(СЕТч),
    'решение Кости 29.09 отменено: расклад снова запрещён, а не оплачен');

/* ─────────── ПЕРЕЖЕРЕБЬЁВКА ─────────── */

/* Стеречь надо ПРИМЕНЕНИЕ, а не существование: функция может остаться в
   файле, а её ответ перестать смотреть — правило было пустым, прувер поймал. */
правило('сыгранное считается до сноса',
    /await\s+сыгранныхМатчей\(tournamentId\)/.test(СЕТч) &&
    /сыграно\s*>\s*0[\s\S]{0,200}regenerateBlocked/.test(СЕТч),
    'снос снова идёт без счёта сыгранных — результаты уйдут молча');

правило('пережеребьёвка бросает НОВЫЙ жребий',
    /update\(\{\s*draw_seed:\s*null\s*\}\)/.test(СЕТч),
    'зерно не сбрасывается: «Пережеребить» повторит тот же расклад');

правило('кнопка пережеребьёвки — одно определение',
    (СЕТч.match(/id="adBrkRegenerate"/g) || []).length === 1,
    'кнопка снова размножена по панелям — подпись отстанет в трёх из четырёх');

правило('подпись под кнопкой, а не по наведению',
    /\.ad-brk-regen-podpis\s*\{/.test(АДМИНCSS) &&
    !/\.ad-brk-regen-podpis[^{]*:hover/.test(АДМИНCSS),
    'подпись уехала в наведение — на планшете её не будет вовсе');

правило('номер жребия виден в шапке сетки',
    /tournament\.draw_seed[\s\S]{0,200}ad-brk-zerno"/.test(СЕТч) &&
    /\.ad-brk-zerno\s*\{/.test(АДМИНCSS),
    'номер жребия пропал: спор о раскладе снова нечем разрешить');

/* ─────────── ЛЕСТНИЦА КАТЕГОРИЙ В ПОСЕВЕ ─────────── */

/* РЕШЕНИЕ КОСТИ 30.09: «лестница категорий главнее места в ней». Сначала
   ступень категории игрока, сверху вниз; своих не хватило на сеяных — добор
   идёт ниже по той же лестнице, и только внутри ступени решает место в
   рейтинге.

   09.10, БОЕВОЙ `5b5e2260`: сеяные встали 3·4·5·6·8 — пять мест подряд, то
   есть чисто по рейтингу, и Tour-игрок обошёл четверых Masters. Правило
   лежало в коде с 01.10 и молча не работало: `ступень` читает
   `playersMap[...].category_id`, а дверь «Пережеребить» собирала игроков
   выборкой БЕЗ `category_id` — `лестница[undefined] || 0` давало ноль всем,
   первый ключ сортировки становился ничейным. Вторая дверь категорию брала.
   ОДНО ПОНЯТИЕ, ДВА ПОВЕДЕНИЯ — и посев зависел от нажатой кнопки.

   Поэтому сторожим не намерение, а ШОВ: каждая выборка игроков, из которой
   строится `playersMap`, обязана нести категорию. */

const ВЫБОРКИ_ИГРОКОВ = (СЕТч.match(/from\('players'\)\s*\n?\s*\.select\('id, name, name_en, points[^']*'/g) || []);

/* ПРЕДПОСЫЛКА СТОРОЖА: он обязан видеть ВСЕ выборки игроков с очками, а не
   те, что попали под его шаблон. Иначе достаточно переписать одну выборку
   чуть иначе — и она выпадет из-под присмотра, а правило ниже останется
   зелёным, проверяя оставшиеся. Пустой `every` тоже зелен: это и есть
   «правило, которое ничего не держит». */
const ВСЕ_ВЫБОРКИ_С_ОЧКАМИ = (СЕТч.match(/from\('players'\)\s*\n?\s*\.select\('[^']*points[^']*'/g) || []);

правило('ни одна выборка игроков с очками не ускользает от сторожа',
    ВСЕ_ВЫБОРКИ_С_ОЧКАМИ.length >= 3 &&
    ВЫБОРКИ_ИГРОКОВ.length === ВСЕ_ВЫБОРКИ_С_ОЧКАМИ.length,
    'выборка игроков написана иначе и выпала из-под правила о категории');

/* ЧИСЛО ДВЕРЕЙ СТОРОЖИТ ОДНО ПРАВИЛО, ИХ СОДЕРЖИМОЕ — ДРУГОЕ. Иначе откат,
   убирающий дверь, валит оба, и ни один из них ничего не доказывает. */
правило('КАЖДАЯ дверь жеребьёвки берёт категорию игрока',
    ВЫБОРКИ_ИГРОКОВ.every(в => /category_id/.test(в)),
    'выборка игроков снова без category_id: ступень лестницы станет нулём у всех, '
    + 'и посев молча поедет по одному рейтингу — как на 5b5e2260 09.10');

правило('ступень посева берётся из лестницы категорий, а не из своего порядка',
    /function ступень\(r\)[\s\S]{0,260}лестница\[кат\]/.test(СЕТч) &&
    /from\('categories'\)\.select\('id, sort_order'\)/.test(СЕТч),
    'ступень считается не по categories.sort_order — завелась вторая лестница');

/* ОДНО ОПРЕДЕЛЕНИЕ КАТЕГОРИИ НА ЭКРАН И НА ПОСЕВ. 09.10 на боевом 5b5e2260
   колонка «КАТЕГОРИЯ» и посев отвечали на один вопрос по-разному: колонка
   брала категорию, откуда взято место, посев — разряд из карточки. У семерых
   из двадцати это разные категории, и сеялись не те. Источник теперь один —
   карточка места; разряд остаётся запасным, когда места нет нигде. */
правило('ступень читает ту же категорию, что показана в заявках',
    /function ступень\(r\)[\s\S]{0,200}места\[r\.player_id\][\s\S]{0,160}св\.категория/.test(СЕТч),
    'ступень снова считается по разряду из карточки — экран и посев разойдутся, '
    + 'как на 5b5e2260: колонка masters 8, а посев считает игрока Tour');

правило('ступень решает РАНЬШЕ места в рейтинге',
    /var сA = ступень\(a\), сB = ступень\(b\);[\s\S]{0,120}return сB - сA;[\s\S]{0,400}\.место \|\| 0;/.test(СЕТч),
    'порядок ключей сортировки сменился: место в рейтинге снова перебивает категорию');

/* ─────────── ВЕРСИИ ─────────── */

правило('версии подняты — иначе браузер отдаст старое из кеша',
    /kslt-rules\.js\?v=(2[0-9]|[3-9]\d)/.test(СТРАНИЦА) &&
    /sections\/bracket\.js\?v=(19[7-9]|[2-9]\d\d)/.test(СТРАНИЦА),
    'версия kslt-rules.js или bracket.js не поднята после правки');

/* Блок функции или css по имени, со счётом скобок */
function блок(текст, имя) {
    const i = текст.indexOf(имя);
    if (i === -1) return '';
    let гл = 0, j = текст.indexOf('{', i);
    if (j === -1) return '';
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}

const всего = всегоПравил;
if (ошибки.length) {
    console.log('\n  ✗ жеребьёвка — ' + ошибки.length + ' из ' + всего + ':\n');
    ошибки.forEach(о => console.log('    · ' + о.имя + '\n      ' + о.подсказка));
    console.log('');
    process.exit(1);
}
console.log('ок жеребьёвка: ' + всего + ' правил');
