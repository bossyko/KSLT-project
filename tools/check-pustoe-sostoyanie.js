/**
 * ЗАМОРОЗКА КУСКА 129 — ДВА РАЗНЫХ ПУСТЫХ СОСТОЯНИЯ, А НЕ ОДНО.
 *
 * ЗАМЕРЕНО НА БОЕВОЙ 22.10, «Корты»: двенадцать кортов в базе, поиск без
 * совпадений — и экран говорит «🏟️ Кортов пока нет. Нажмите "Добавить
 * корт" для создания». Человеку с двенадцатью кортами предлагают завести
 * первый. То же в «Транзакциях» при шести записях.
 *
 * Причина одна на все места: пустота считалась от УЖЕ отфильтрованного
 * списка. В отрисовку приходит выборка — `renderCrtRows(pageItems)`,
 * `renderVchTable(pageItems)`, `renderNewsRows(filtered.slice(…))`.
 *
 * Способов рисовать пустоту было ДВА: блок `.ad-empty-state` (22 места,
 * правила под него нет НИ В ОДНОМ css — класс стоял, вида не было) и
 * строка таблицы с инлайнами (9 мест).
 *
 * Дом `A.пустоеСостояние` спрашивает, пуста ли БАЗА, и сам выбирает,
 * что сказать. Там, где фильтр уходит в базу (игроки), числа взять
 * неоткуда — дом спрашивает признак «стоит ли фильтр».
 *
 *   node tools/check-pustoe-sostoyanie.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const УТИЛ = чит('js/admin/core/utils.js');
const СЛОВАРЬ = чит('js/admin/core/constants.js');
const AD = чит('css/admin.css');
const РАЗДЕЛЫ = fs.readdirSync(path.join(КОРЕНЬ, 'js/admin/sections'))
    .filter(н => н.endsWith('.js')).sort()
    .map(н => ['js/admin/sections/' + н, чит('js/admin/sections/' + н)]);

/* ── 1. ДОМ РАЗЛИЧАЕТ ДВА СОСТОЯНИЯ ──────────────────────────────────── */
правило('дом пустого состояния есть и различает базу от выборки',
    /function пустоеСостояние\(о\)/.test(УТИЛ) &&
    /var вБазеПусто = о\.фильтры !== undefined \? !о\.фильтры : !о\.всего;/.test(УТИЛ) &&
    /A\.пустоеСостояние = пустоеСостояние;/.test(УТИЛ),
    'Дом пропал или перестал различать «в базе пусто» и «фильтр ничего не нашёл».\n' +
    'Пока он их не различал, экран предлагал завести первый корт человеку с\n' +
    'двенадцатью — ЗАМЕРЕНО на боевой, а не выведено.');

правило('дом знает оба признака — и число, и флаг фильтров',
    /о\.фильтры !== undefined/.test(УТИЛ) && /о\.всего/.test(УТИЛ),
    'Дом перестал принимать один из двух признаков. Там, где фильтр уходит В\n' +
    'БАЗУ, числа «сколько всего» взять неоткуда без второго запроса.\n' +
    'ПРИЗНАК БЕРЁТСЯ ТОТ, КОТОРЫЙ В ЭТОМ МЕСТЕ ЕСТЬ.');

/* ── 2. СЛОВА ЖИВУТ В СЛОВАРЕ ────────────────────────────────────────── */
['pustoNeNaydeno', 'pustoSbrosFiltry'].forEach(к => {
    правило('ключ `' + к + '` заведён в словаре',
        new RegExp('^\\s*' + к + ':', 'm').test(СЛОВАРЬ),
        'Ключа нет, а дом его зовёт — диктор и экран получат «undefined».\n' +
        'Ровно это случилось 22.10 с подписью закрывашки окна.');
});

/* ── 3. ТАБЛИЧНЫЕ МЕСТА ЗОВУТ ДОМ, А НЕ РИСУЮТ САМИ ──────────────────── */
const сами = [];
РАЗДЕЛЫ.forEach(([имя, текст]) => {
    const n = (текст.match(/<td colspan="\d+" style="text-align:center;padding:60px/g) || []).length;
    if (n) сами.push(имя + ' — ' + n);
});
правило('ни одно табличное место не рисует пустоту своими инлайнами',
    сами.length === 0,
    'Рисуют сами: ' + сами.join(', ') + '.\n' +
    'ОДНО ПОНЯТИЕ — ОДИН СПОСОБ: иначе часть мест различает два состояния, а\n' +
    'часть по-прежнему говорит «пока нет» на непустой базе.');

const зовов = РАЗДЕЛЫ.reduce((с, [, т]) => с + (т.match(/A\.пустоеСостояние\(\{/g) || []).length, 0);
правило('дом зовут все 27 мест, где рисуется пустота',
    зовов === 27,
    'Зовов `A.пустоеСостояние`: ' + зовов + ', а переведено 27: восемь\n' +
    'табличных (кусок 129) и девятнадцать блочных (кусок 130). Меньше — место\n' +
    'вернулось к своей разметке; больше — завелось новое, и его не мерили.');

/* ОТКАЗ — НЕ ПУСТОТА (кусок 130). Под именем `.ad-empty-state` жили ТРИ
   понятия: список пуст, база отказала, доступ запрещён. Выглядели
   одинаково, и «игроков нет» читалось там, где база ответила 403. */
правило('дом отказа есть и отделён от пустоты',
    /function отказСостояние\(о\)/.test(УТИЛ) &&
    /A\.отказСостояние = отказСостояние;/.test(УТИЛ),
    'Дом отказа пропал. Тогда отказ базы снова станет неотличим от пустого\n' +
    'списка — беду эту уже чинили точечно в куске 121, и она вернётся.');

const отказов = РАЗДЕЛЫ.reduce((с, [, т]) => с + (т.match(/A\.отказСостояние\(\{/g) || []).length, 0);
правило('три места отказа зовут свой дом',
    отказов === 3,
    'Зовов `A.отказСостояние`: ' + отказов + ', а замерено три: отказ базы в\n' +
    'рейтинге игроков, запрет доступа и недоступная таблица цен в настройках.');

правило('имени `.ad-empty-state` в разметке больше нет',
    РАЗДЕЛЫ.every(([, т]) => т.indexOf('ad-empty-state') === -1),
    'Имя вернулось в разметку. Правила под него нет ни в одном css, и оно\n' +
    'несло три разных понятия разом.');

/* ── 4. У ПУСТОГО СОСТОЯНИЯ ЕСТЬ ВИД ─────────────────────────────────── */
['ad-pusto', 'ad-pusto-znak', 'ad-pusto-zagolovok', 'ad-pusto-podskazka'].forEach(к => {
    const блок = (AD.match(new RegExp('\\.' + к + '\\s*\\{[^}]*\\}')) || [''])[0];
    правило('`.' + к + '` не просто есть, а что-то задаёт',
        блок.length > 0 && /[a-z-]+:\s*[^;]+;/.test(блок),
        'Правило `.' + к + '` пропало или опустело. Прежнее имя `.ad-empty-state`\n' +
        'звали 22 места, и правила под него не было ни в одном css — блок\n' +
        'рисовался голым текстом в потоке. ИМЯ БЕЗ ПРАВИЛА ВЫГЛЯДИТ КАК РЕШЕНИЕ.');
});

/* ── вывод ───────────────────────────────────────────────────────────── */
console.log('');
if (ошибки.length) {
    console.log('  НЕ ТАК  пустое состояние — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(([и, п]) => console.log('          ✗ ' + и + '\n            ' + п.replace(/\n/g, '\n            ') + '\n'));
    process.exit(1);
}
console.log('  ок      пустое состояние: 14 правил');
console.log('          дом различает базу и выборку, восемь мест зовут его');
console.log('          слова в словаре, у пустоты есть вид');
console.log('          отказ отделён от пустоты: 27 зовов пустоты, 3 отказа');
console.log('');
