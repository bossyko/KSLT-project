/**
 * ЗАМОРОЗКА СЕКЦИИ ЗНАЧКОВ `.section-badges-cta`.
 *
 * Решения Кости 24.09, доска 358:9:
 *   подписи значков нейтральные — лайм принадлежит одной кнопке;
 *   плитка — компонент Card 29:65, Padding=Dense 12;
 *   перебивка говорит ТИШЕ раздела: 21/Bold широкий, 16/Bold с 768;
 *   кнопка — высота свойством, ступень md 44; радиус 12 остаётся;
 *   два ряда, туман и наезд коробки — форма секции, не трогаются;
 *   коробка становится эталонной: поля на шкале.
 *
 * ГЛАВНОЕ ЗДЕСЬ — ПРАВИЛО ОБ ОТНОШЕНИИ, А НЕ О ЧИСЛЕ. Перебивка обязана быть
 * мельче заголовка раздела на каждом виде. Когда заголовок раздела переедет с
 * 768 на 640, перебивка либо поедет за ним, либо это правило упадёт и скажет.
 *
 *   node tools/check-znachki.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');
const СТИ = безКом(чит('css/style.css'));

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* Блок по селектору с якорем на начало строки: '.badge-cta-card {' встречается
   и как '.badges-cta-cards.badges-all .badge-cta-card {'. За три дня на этих
   граблях наступали семь раз. */
function блок(сел) {
    const м = СТИ.match(new RegExp('(?:^|\\n)' + сел.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{[^}]*\\}'));
    return м ? м[0] : null;
}
/* Слой ищется по условию И по содержимому: одно условие встречается в файле
   несколько раз. */
function слой(условие, маркер) {
    let i = -1;
    while ((i = СТИ.indexOf('@media ' + условие, i + 1)) !== -1) {
        const j = СТИ.indexOf('@media ', i + 7);
        const кусок = СТИ.slice(i, j === -1 ? СТИ.length : j);
        if (!маркер || кусок.indexOf(маркер) !== -1) return кусок;
    }
    return null;
}
const свойство = (т, имя) => {
    if (!т) return null;
    const м = т.match(new RegExp('(?:^|\\n)\\s*' + имя + ':\\s*([^;]+);'));
    return м ? м[1].trim() : null;
};
const ЛЕНТА = '(max-width: 992px) and (orientation: landscape) and (max-height: 500px)';

/* ── лайм принадлежит действию ───────────────────────────────────────────── */
const подпись = блок('.badge-cta-name');
правило('подпись значка нейтральная, а не лаймовая',
    свойство(подпись, 'color') === 'var(--text-primary)',
    'Сейчас: ' + свойство(подпись, 'color') + '\n' +
    '          Лайм висел на двенадцати плитках — шести открытых и шести под\n' +
    '          туманом — прямо над лаймовой кнопкой, единственным действием\n' +
    '          секции. Правило 109:370: лайм принадлежит одному главному\n' +
    '          действию в поле зрения.');
правило('кнопка осталась единственным лаймовым пятном секции',
    (СТИ.match(/\.badge-cta-[\w-]+\s*\{[^}]*var\(--accent\)/g) || []).length === 0,
    'Ни одна часть плитки не берёт --accent. Иначе счёт снова станет «двенадцать\n' +
    '          против одного».');

/* ── плитка = Card 29:65, Padding=Dense 12 ───────────────────────────────── */
const плитка = блок('.badge-cta-card');
правило('плитка — Padding=Dense 12, одна плотность на все виды',
    свойство(плитка, 'padding') === 'var(--space-3)',
    'Сейчас: ' + свойство(плитка, 'padding') + '\n' +
    '          Было 12/10 на широком и 9/5 на узком — ни то, ни другое не\n' +
    '          значение компонента. Dense заведён В КОМПОНЕНТЕ Card 29:65:\n' +
    '          поле 12 встречается в продукте 64 раза, чаще шестнадцати, и\n' +
    '          стоит на шкале, тогда как 10 — нет.');
правило('плитка держит остальное от компонента Card',
    свойство(плитка, 'border-radius') === 'var(--radius-lg)'
        && свойство(плитка, 'background') === 'var(--bg-card)'
        && /border:\s*1px solid var\(--border-subtle\)/.test(плитка || ''),
    'Радиус 16, фон bg/card, край border/subtle — это и есть Card 29:65.');
правило('поля плитки больше нигде не переопределяются',
    !/(?:^|\n)\s*\.badge-cta-card\s*\{[^}]*padding:/.test(СТИ.replace(плитка || '', '')),
    'Одна плотность — значит ровно одно правило с полями. Иначе вернётся\n' +
    '          тот же дубль, из-за которого три слоя css были мёртвыми.');

/* ── перебивка говорит тише раздела: ОТНОШЕНИЕ, а не число ───────────────── */
const перебивка = блок('.badges-cta-text h2');
правило('перебивка набрана ступенью h3, а не голосом раздела',
    свойство(перебивка, 'font-size') === 'var(--fs-lg)'
        && свойство(перебивка, 'font-weight') === 'var(--fw-bold)',
    'Сейчас: ' + свойство(перебивка, 'font-size') + ' / ' + свойство(перебивка, 'font-weight') + '\n' +
    '          Было clamp(1.05rem, 1.8vw, 1.25rem) при весе 800: четыре кегля,\n' +
    '          из них на шкале один, и вес раздела на всех видах.');
правило('перебивка НЕ входит в правило заголовков разделов',
    !/\.section-header h2,\s*\n\s*section > h2,\s*\n\s*\.badges-cta-text h2/.test(СТИ),
    'Попав в это правило, перебивка получала ровно голос раздела — 21 / Extra\n' +
    '          Bold, — и на 768 и на 390 была от него НЕОТЛИЧИМА. Замерено 24.09.');

const ш768 = слой('(max-width: 768px)', '.badges-cta-text h2');
правило('перебивка падает на ступень ниже там же, где заголовок раздела (768)',
    ш768 && /\.badges-cta-text h2\s*\{\s*font-size: var\(--fs-base\)/.test(ш768),
    'Заголовки разделов падают на мобильную ступень с 768. Если перебивка\n' +
    '          переключится позже, в полосе 641–768 они станут одинаковыми.\n' +
    '          Это осознанное 768 в секции, которая в остальном живёт на 640/992.');
/* ОТНОШЕНИЕ, ради которого всё затевалось */
const разделШирокий = свойство(блок('.section-header h2'), 'font-size');
правило('перебивка мельче раздела НА ШИРОКОМ: fs-lg против fs-xl',
    свойство(перебивка, 'font-size') === 'var(--fs-lg)' && разделШирокий === 'var(--fs-xl)',
    'Раздел сейчас: ' + разделШирокий + ' · перебивка: ' + свойство(перебивка, 'font-size') + '\n' +
    '          Ступень раздела на широком — --fs-xl (26), перебивки — --fs-lg (21).\n' +
    '          Если раздел уедет на другую ступень, это правило упадёт, и его\n' +
    '          надо будет пересмотреть вместе с перебивкой, а не молча.');
const ш768раздел = слой('(max-width: 768px)', '.section-header h2');
правило('перебивка мельче раздела НА УЗКОМ: fs-base против fs-lg',
    ш768раздел && /font-size: var\(--fs-lg\)/.test(ш768раздел)
        && ш768 && /\.badges-cta-text h2\s*\{\s*font-size: var\(--fs-base\)/.test(ш768),
    'На 768 раздел становится 21, перебивка — 16. Проверяем обе стороны\n' +
    '          отношения, а не только свою: правило должно падать и тогда, когда\n' +
    '          поехал РАЗДЕЛ.');

const слойПары = слой('(max-width: 768px)', '.badges-cta-text h2');

/* ── подзаголовок ────────────────────────────────────────────────────────── */
/* ЯКОРЬ ПЕРЕПИСАН 24.09. Было: слой 640 искался по маркеру '.badges-cta-text p'.
   Я перенёс подзаголовок на границу 768 — и оба правила ниже умерли разом,
   включая то, которое к подзаголовку отношения не имеет. Якорь держится на
   том, что живёт в слое ПОСТОЯННО, а не на соседе, который может уехать. */
const ш640 = слой('(max-width: 640px)', '.badge-cta-name');
правило('подпись значка на телефоне — телефонная ступень card title',
    ш640 && /\.badge-cta-name\s*\{[^}]*font-size: var\(--fs-sm\)/.test(ш640),
    'Было 11 — мимо ступени 14 и мельче порога читаемости.');

/* ОТНОШЕНИЕ, А НЕ ЧИСЛО: подзаголовок стоит строго ниже заголовка на лестнице
   кеглей. Поменяем сами токены — правило переживёт; схлопнем пару — упадёт. */
const ЛЕСТНИЦА = ['--fs-2xs','--fs-xs','--fs-sm','--fs-base','--fs-md','--fs-lg','--fs-xl','--fs-2xl','--fs-3xl'];
const ступень = т => ЛЕСТНИЦА.indexOf(т);
const кегльВ = (кусок, сел) => {
    if (!кусок) return null;
    const м = кусок.match(new RegExp(сел.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{[^}]*font-size:\\s*var\\((--fs-[a-z0-9]+)\\)'));
    return м ? м[1] : null;
};
const зГ = кегльВ(слойПары, '.badges-cta-text h2');
const зП = кегльВ(слойПары, '.badges-cta-text p');
правило('подзаголовок на ступень НИЖЕ заголовка перебивки',
    зГ && зП && ступень(зП) > -1 && ступень(зГ) > -1 && ступень(зП) < ступень(зГ),
    'Сейчас заголовок ' + зГ + ', подзаголовок ' + зП + '.\n' +
    '          При равных кеглях пара отличается только жирностью и читается\n' +
    '          как одна мысль в два приёма. Лестница: ' + ЛЕСТНИЦА.join(' < '));

/* ── кнопка ──────────────────────────────────────────────────────────────── */
const кнопка = блок('.badges-cta-btn');
правило('высота кнопки задаётся свойством, а не полями',
    свойство(кнопка, 'height') === 'var(--btn-h-md)' && /display: inline-flex/.test(кнопка || ''),
    'Сейчас: height ' + свойство(кнопка, 'height') + '\n' +
    '          Было padding 13/36, из чего выходило 47 на широком и 43 на узком.\n' +
    '          43 ниже порога цели нажатия 44 — на единственной кнопке секции.\n' +
    '          Правило компонента Button 17:82: высота задаётся height.');
правило('горизонтальное поле кнопки — ступень шкалы',
    свойство(кнопка, 'padding') === '0 var(--space-8)',
    'Сейчас: ' + свойство(кнопка, 'padding') + ' · было 36, не ступень.');
правило('кнопка вынута из ступени «обычная 40»',
    !/\.badges-cta-btn\.badges-cta-btn,/.test(СТИ),
    'В блоке телефонных кнопок она стояла второй ступенью с min-height 40 —\n' +
    '          при том что это главный призыв своего экрана. Оттуда и 43.');
правило('радиус кнопки не тронут — он решается вместе с коробкой',
    свойство(кнопка, 'border-radius') === '12px',
    'Решение Кости 24.09, вариант A: двенадцать носят все восемь кнопок внутри\n' +
    '          коробок-гейтов, и радиус для всех восьми решается на шаге\n' +
    '          компонентов. Одна круглая кнопка среди восьми — новое расхождение.');

/* ── раскладка и лестница границ ─────────────────────────────────────────── */
/* ЯКОРЬ НА БАЗОВЫЙ БЛОК, А НЕ НА ФАЙЛ. Первая редакция искала «repeat(6, 1fr)»
   где угодно и находила его в блоке ленты: откат ломал базу, а правило
   оставалось зелёным. Девятый случай за три дня, и снова тот же — якорь
   держался на подстроке, а не на блоке. */
const сетка = блок('.badges-cta-cards');
правило('база — шесть колонок',
    свойство(сетка, 'grid-template-columns') === 'repeat(6, 1fr)',
    'Сейчас: ' + свойство(сетка, 'grid-template-columns') + '\n' +
    '          Шесть открытых значков заполняют ряд целиком — правило витрины.');
const с992 = слой('(max-width: 992px)', '.badges-cta-cards');
правило('от 992 и уже — три колонки',
    с992 && /grid-template-columns: repeat\(3, 1fr\)/.test(с992),
    'Новая лестница границ: по ширине только 640 и 992. На 768 секция\n' +
    '          перестаёт быть телефоном.');
const лента = слой(ЛЕНТА, '.badges-cta-cards');
правило('в тесной по высоте ленте колонки ВОЗВРАЩАЮТСЯ на шесть',
    лента && /\.badges-cta-cards\s*\{ grid-template-columns: repeat\(6, 1fr\); \}/.test(лента),
    'Без этой строки 844 попадает в max-width: 992 и получает три колонки —\n' +
    '          замерено 559 при экране 390, хуже исходных 469. Блок, который не\n' +
    '          перебить снизу, обязан ограничить сам себя.');
правило('пояснение скрыто ОДНИМ правилом, от 992 и уже',
    с992 && /\.badge-cta-desc \{ display: none; \}/.test(с992),
    'Перебивка-баннер не разрастается ради второй строки: с пояснениями на\n' +
    '          768 секция выходила 518 против 444.');
правило('мёртвых слоёв 540 и 480 больше нет',
    !/@media \(max-width: 540px\)[\s\S]{0,200}badges-cta-cards/.test(СТИ)
        && !/@media \(max-width: 480px\)[\s\S]{0,200}badges-cta-cards/.test(СТИ),
    'Они просили по две колонки, а намерено было три: их перекрывал блок 768\n' +
    '          ниже по файлу. Правило может быть зелёным, читаемым и мёртвым.');
/* ЯКОРЬ ВНУТРИ СЛОЯ, А НЕ ЧЕРЕЗ ВЕСЬ ФАЙЛ. Первая редакция этого правила
   искала '.badges-cta-cards {' где угодно после любого '@media (max-width:
   768px)' и падала на исправном коде — мой же якорь на положение, восьмой
   случай за три дня. Теперь спрашиваем слой. */
правило('слоя 768 с колонками больше нет',
    слой('(max-width: 768px)', '.badges-cta-cards') === null,
    'Два блока max-width: 768 на один селектор — та самая мина, из-за которой\n' +
    '          три слоя css не работали.');

/* ── форма секции: два ряда, туман, наезд ────────────────────────────────── */
const туман = блок('.badges-cta-locked');
правило('туман не тронут: размытие и маска на месте',
    /filter:\s*blur\(2\.5px\)/.test(туман || '') && /mask-image:\s*linear-gradient\(to bottom, rgba\(0,0,0,0\.55\) 0%, transparent 62%\)/.test(туман || ''),
    'Два ряда, туман и наезд — форма секции, решение Кости 24.09. Они не\n' +
    '          меняются ни на одном виде.');
правило('закрытый ряд не ловит мышь',
    свойство(туман, 'pointer-events') === 'none', 'Под туманом нажимать нечего.');
const коробка = блок('.badges-cta-box');
правило('коробка наезжает на закрытый ряд',
    свойство(коробка, 'margin-top') === '-46px', 'Наезд −46 — часть формы секции.');
правило('поля коробки встали на шкалу',
    свойство(коробка, 'padding') === 'var(--space-6) var(--space-8)',
    'Сейчас: ' + свойство(коробка, 'padding') + ' · было 22/34, ни одно не ступень.\n' +
    '          Эта коробка назначена ЭТАЛОННОЙ: три её копии подключаются к ней\n' +
    '          на шаге компонентов.');

/* ── пара «заголовок + подзаголовок» едет ОДНОЙ границей ─────────────────── */
/* ПОЙМАЛ НАСТОЯЩИЙ PLAYWRIGHT 24.09, а не эта проверка: 3 падения из 150, все
   на планшете 768, на трёх языках. Заголовок перебивки падал на 768,
   подзаголовок — на 640, и в полосе 641-768 оба сидели на 16.
   Почему старые правила молчали: они проверяли, что ОБА правила в файле есть.
   Оба и были — в разных медиаслоях. Файл как текст этого не видит, видит
   только браузер. Теперь сторожим ОТНОШЕНИЕ: обе строки обязаны лежать в
   ОДНОМ слое. Переедет заголовок на 640 — подзаголовок поедет с ним, или это
   правило упадёт и скажет, какой именно из двух остался. */
правило('заголовок и подзаголовок перебивки падают на ОДНОЙ границе',
    !!слойПары && /\.badges-cta-text h2\s*\{[^}]*font-size/.test(слойПары)
              && /\.badges-cta-text p\s*\{[^}]*font-size/.test(слойПары),
    'Заголовок и подзаголовок перебивки обязаны менять кегль в одном\n' +
    '          медиаслое. Разъехались — в полосе между границами пара\n' +
    '          схлопывается в один кегль и отличается только жирностью.');

правило('кегль подзаголовка перебивки задан ровно дважды: база и одна граница',
    (СТИ.match(/\.badges-cta-text p\s*\{[^}]*font-size/g) || []).length === 2,
    'Третье объявление означает третью границу — а их у нас две, 640 и 992.\n' +
    '          Если нужен новый размер, он заводится в компоненте, а не здесь.');

/* ── движение и доступность ──────────────────────────────────────────────── */
правило('движение выключается тем, кто попросил его выключить',
    /@media \(prefers-reduced-motion: reduce\)[\s\S]{0,200}\.badges-cta-box::before/.test(СТИ),
    'Обводка коробки крутится бесконечно. WCAG 2.3.3. В проекте 46 бесконечных\n' +
    '          анимаций и до 24.09 не было ни одного такого блока.');
const js = безКом(чит('js/home-badges.js'));
