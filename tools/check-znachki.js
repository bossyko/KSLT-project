#!/usr/bin/env node
/**
 * ЗНАЧКИ У ИМЕНИ В СПИСКЕ — ОДИН ДОМ (29.10).
 *
 * ЗАМЕР: на сайте значки у имени в рейтинге живут с давних пор
 * (`js/players.js`, 29 упоминаний), а на экране рейтинга приложения их
 * НЕ БЫЛО ВОВСЕ — ноль упоминаний на 444 строки. Человек видел свои
 * достижения на сайте и не видел в приложении.
 *
 * У значка ТРИ ПРАВИЛА, и каждое легко разъехать: сколько показывать,
 * в каком порядке и как он зовётся на языке страницы. Все три в доме.
 *
 * ЧЕГО В ДОМЕ НЕТ: разметки и экранирования — у сайта `KSLT_экранировать`,
 * у приложения своя `esc`. Дом отдаёт ДАННЫЕ.
 *
 * Запуск: node tools/check-znachki.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));
const безКомCss = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

const ДОМ = 'js/kslt-znachki.js';
const ДОМ_П = 'mobile/www/js/kslt-znachki.js';
const САЙТ = 'js/players.js';
const ПРИЛ = 'mobile/www/js/screens/rating.js';
const дом = безКом(чит(ДОМ));

console.log('\n  ЗНАЧКИ У ИМЕНИ — ОДИН ДОМ\n');

правило('дом объявлен и отдаёт все четыре понятия',
    /KSLT_ZNACHKI/.test(дом) && /API\.СКОЛЬКО/.test(дом) &&
    /API\.загрузить\s*=/.test(дом) && /API\.первые\s*=/.test(дом) &&
    /API\.название\s*=/.test(дом),
    'Нужны: сколько, загрузить, первые, название.');

правило('копии дома побайтово равны',
    чит(ДОМ) === чит(ДОМ_П),
    'Разошлись — значит число значков в строке снова живёт двумя жизнями.');

правило('сколько значков в строке — одно число',
    /API\.СКОЛЬКО = 5;/.test(дом),
    'Пять — замер строки рейтинга: шестой выдавливает столбец очков.\n' +
    'Разойдись число — на телефоне строка поедет, а на сайте нет.');

правило('порядок задаёт БАЗА, а не продукт',
    /order\('earned_at', \{ ascending: true \}\)/.test(дом),
    'От раннего — это путь человека, а не случайный набор. Сортируй\n' +
    'каждый продукт сам — получишь два разных порядка.');

правило('грузится двумя запросами, а не по запросу на игрока',
    (дом.match(/client\.from\(/g) || []).length === 2,
    'В Futures под две сотни человек. По запросу на строку список не\n' +
    'нарисуется никогда.');

правило('дом не бросает ни при отказе, ни при броске на месте',
    /\.catch\(function \(\) \{/.test(дом) && /try \{/.test(дом) &&
    /catch \(e\) \{\s*return Promise\.resolve/.test(дом),
    'Значки — украшение списка: список без них лучше списка, который не\n' +
    'нарисовался. И `client.from(...)` может бросить СРАЗУ — `.catch`\n' +
    'такого не видит, он ловит только отказ уже созданного обещания.\n' +
    'Нашёл это свой же тест.');

правило('дом не знает ни разметки, ни экранирования',
    !/<span/.test(дом) && !/экранировать|\besc\(/.test(дом),
    'У сайта экранирует `KSLT_экранировать`, у приложения своя `esc`.\n' +
    'Дом отдаёт данные, вставляет продукт.');

[[САЙТ, 'сайта'], [ПРИЛ, 'приложения']].forEach(function (пара) {
    const ф = пара[0], имя = пара[1];
    const т = безКом(чит(ф));

    правило('у ' + имя + ' дом зовётся',
        /KSLT_ZNACHKI/.test(т) && /\.первые\(/.test(т) && /\.название\(/.test(т),
        'Без зова работа не сделана.');

    правило('у ' + имя + ' нет своей загрузки значков',
        !/from\('player_badges'\)/.test(т) && !/from\('badge_definitions'\)/.test(т),
        'Два запроса и две карты жили на сайте, а в приложении не жило\n' +
        'ничего. Теперь запрос один на оба.');

    правило('у ' + имя + ' нет своего числа значков в строке',
        !/slice\(0,\s*(?:maxCount \|\| )?5\)/.test(т),
        'Число живёт в доме. Своя пятёрка здесь — второе определение.');

    правило('у ' + имя + ' значок И подсказка экранируются',
        /* ПРИБОР БЕЗ ФЛАГА `g` СЧИТАЕТ ОДИН РАЗ, А НЕ ВСЕ: `match` с
           обычным выражением отдаёт первое совпадение, и правило видело
           одно экранирование из двух — падало на верном коде. */
        (function () {
            const куски = т.match(/(?:pl-badge|rr-badge)[\s\S]{0,220}/g) || [];
            return куски.length > 0 && куски.every(function (к) {
                return (к.match(/KSLT_экранировать|esc\(/g) || []).length >= 2;
            });
        })(),
        '`badge_definitions.icon` и `name` — текстовые столбцы, которые\n' +
        'пишет человек. Куском A3.7б уже закрывалась дыра, где значок\n' +
        'вставлялся сырым.');
});

правило('у значка в строке есть вид в обоих продуктах',
    /\.pl-badge/.test(безКомCss(чит('css/players.css'))) &&
    /\.rr-badge/.test(безКомCss(чит('mobile/www/css/app.css'))),
    'Без вида значки слипнутся с именем.');

правило('дом подключён и грузится ДО того, кто его зовёт',
    ['pages/players.html', 'pages/players-en.html', 'pages/players-kg.html',
     'mobile/www/index.html'].every(ф => {
        const t = чит(ф);
        const д = t.indexOf('kslt-znachki.js');
        const з = Math.min.apply(null,
            ['js/players.js?', 'js/screens/rating.js?'].map(с => t.indexOf(с))
                .filter(и => и !== -1).concat([Infinity]));
        return д !== -1 && з !== Infinity && д < з;
    }),
    'Без дома строка рейтинга упадёт на `undefined` при первом показе.');

правило('список рисуется НЕ ДОЖИДАЯСЬ значков',
    (function () {
        const т = безКом(чит(ПРИЛ));
        return /загрузить\(supabaseClient\)\.then/.test(т) && /loadCategories\(\);/.test(т) &&
               т.indexOf('загрузить(supabaseClient)') < т.lastIndexOf('loadCategories();');
    })(),
    'Значки — украшение. Таблица, которая ждёт их, хуже таблицы без них:\n' +
    'пришли — перерисуем.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else { console.log('  ок      значки: все ' + держится + ' правил держатся\n'); }
