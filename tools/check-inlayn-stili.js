/* ХРАПОВИК ПО РОЛЯМ, А НЕ ПО СПИСКУ. Список ловит НОВОЕ написание; это
   правило ловит РОСТ числа написаний внутри роли — шестой красный не
   пройдёт, даже если его впишут в список выше. Роль берётся по ТОНУ
   краски, а не по имени: имя можно назвать как угодно. */
function рольКраски(hex) {
    var h = hex.replace('#', '');
    if (h.length === 3) h = h.split('').map(function (c) { return c + c; }).join('');
    var r = parseInt(h.slice(0, 2), 16) / 255,
        g = parseInt(h.slice(2, 4), 16) / 255,
        b = parseInt(h.slice(4, 6), 16) / 255;
    var мх = Math.max(r, g, b), мн = Math.min(r, g, b);
    if (мх === мн) return 'серый';
    var д = мх - мн, т;
    if (мх === r) т = ((g - b) / д) % 6;
    else if (мх === g) т = (b - r) / д + 2;
    else т = (r - g) / д + 4;
    т *= 60; if (т < 0) т += 360;
    if (т >= 345 || т < 15) return 'красный';
    if (т < 45) return 'оранжевый';
    if (т < 70) return 'жёлтый';
    if (т < 165) return 'зелёный';
    if (т < 290) return 'голубой';
    return 'розовый';
}
