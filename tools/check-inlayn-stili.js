function инлайны(т) {
    const из = [];
    let м;
    const дв = /style="([^"]*)"/gs;
    while ((м = дв.exec(т))) из.push(м[1]);
    const од = /style='([^']*)'/gs;
    while ((м = од.exec(т))) из.push(м[1]);
    const ct = /style\.cssText\s*=\s*'([^']*)'/gs;
    while ((м = ct.exec(т))) из.push(м[1]);
    return из;
}

function разбор(тело) {
    const из = [];
    тело.split(';').forEach(об => {
        const и = об.indexOf(':');
        if (и === -1) return;
        из.push([об.slice(0, и).trim(), об.slice(и + 1).trim()]);
    });
    return из;
}

