/**
 * ПОКАЗ ДАТЫ — СТОРОЖ (11.11.2026).
 *
 * ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ: день, который видит человек, задаёт клуб в
 * Бишкеке, а не часы смотрящего. Способов ровно два, и оба допустимы:
 *
 *   1. МОМЕНТ СО ВРЕМЕНЕМ (created_at, played_at, banned_until) —
 *      показывается с timeZone из дома времени KSLT_VREMYA.зона;
 *   2. ЧИСТАЯ ДАТА ('2026-11-08') — разбирается как ЛОКАЛЬНАЯ полночь
 *      через + 'T00:00:00', и тогда день одинаков в любом поясе.
 *
 * ЧЕМ ЭТО ДОКАЗАНО, А НЕ ПРИДУМАНО. Замер 11.11 из браузера в Чикаго:
 * `new Date('2026-11-08')` — это UTC-полночь, и getDate() отдаёт СЕДЬМОЕ.
 * Турнир, который в базе стоит восьмым ноября, человек западнее Гринвича
 * видел бы седьмым. На публичных страницах этого уже не происходит —
 * замер показал ноль таких мест, там всё разобрано правильно. А вот
 * моменты со временем показывались по часам смотрящего в СЕМНАДЦАТИ
 * местах, почти все — в админке. Для Бишкека это незаметно, и потому
 * прожило долго: клуб смотрит из Бишкека. Костя смотрел из Чикаго и
 * видел вчерашний день.
 *
 * ПОЯС ОБЯЗАН СТОЯТЬ ВТОРЫМ АРГУМЕНТОМ (найдено 11.11, в тот же день,
 * в МОЕЙ ЖЕ правке). Два места из семнадцати вышли такими:
 *
 *     new Date(x).toLocaleDateString({ timeZone: ... })
 *
 * У toLocaleDateString(locales, options) первый аргумент — ЯЗЫК. Объект
 * на его месте не бросает и не ругается: он просто отбрасывается вместе
 * с поясом. Замер в живом браузере из Чикаго: с поясом вторым выходит
 * 12 ноября, с поясом первым — 11 ноября. Разница ровно в сутки, и
 * ничто на неё не указывает.
 *
 * Прежнее правило брало ВСЁ, что в скобках, и искало там слово timeZone
 * — то есть засчитывало обе записи. ПРАВИЛО, КОТОРОЕ СМОТРИТ НА СЛОВО, А
 * НЕ НА МЕСТО, ПРОПУСКАЕТ ПОДМЕНУ. Теперь проверяется место аргумента.
 *
 * ПОЧЕМУ ПРАВИЛО НЕ ТРЕБУЕТ ПОЯС ВЕЗДЕ. Вызов с 'T00:00:00' пояса не
 * хочет и не должен: там уже нет момента, там день как он есть.
 * ПРАВИЛО, ЦЕЛЯЩЕЕ ШИРЕ СВОЕГО ПРЕДМЕТА, ЛОВИТ НЕВИНОВНЫХ — сегодня я
 * трижды на этом попался, здесь предмет назван точно.
 */
const fs = require('fs');
const path = require('path');

const корень = path.resolve(__dirname, '..');
const без = т => т.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/.*$/gm, '$1');
const ошибки = [];

function файлы(дир, акк = []) {
    for (const и of fs.readdirSync(дир, { withFileTypes: true })) {
        if (и.name === 'node_modules') continue;
        const п = path.join(дир, и.name);
        if (и.isDirectory()) файлы(п, акк);
        else if (и.name.endsWith('.js')) акк.push(п);
    }
    return акк;
}

const дом = path.join(корень, 'js/kslt-vremya.js');
if (!fs.existsSync(дом)) {
    ошибки.push('js/kslt-vremya.js не найден — дома времени нет');
} else if (!/В\.зона\s*=/.test(fs.readFileSync(дом, 'utf8'))) {
    ошибки.push('дом времени больше не отдаёт зону — показывать дату не от чего');
}

let всего = 0, сПоясом = 0, локальных = 0;
for (const ф of файлы(path.join(корень, 'js'))) {
    const имя = path.relative(корень, ф);
    const т = без(fs.readFileSync(ф, 'utf8'));
    for (const м of т.matchAll(/new Date\(([^)]*)\)\.toLocale(?:Date|Time)?String\(((?:[^()]|\([^()]*\))*)\)/g)) {
        всего++;
        const арг = м[1], опции = м[2];
        if (арг.includes('T00:00:00')) { локальных++; continue; }
        const строка = т.slice(0, м.index).split('\n').length;
        /* ПОЯС СЧИТАЕТСЯ ТОЛЬКО ВТОРЫМ АРГУМЕНТОМ: перед `{` обязана
           стоять запятая, то есть язык (пусть и `undefined`). */
        if (/^\s*\{/.test(опции) && опции.includes('timeZone')) {
            ошибки.push(`${имя}:${строка} — пояс стоит ПЕРВЫМ аргументом, на месте языка, и молча отбрасывается: ${м[0].replace(/\s+/g, ' ').slice(0, 70)}`);
            continue;
        }
        if (/,\s*\{[\s\S]*timeZone/.test(опции)) { сПоясом++; continue; }
        ошибки.push(`${имя}:${строка} — момент показывается без пояса: ${м[0].replace(/\s+/g, ' ').slice(0, 60)}`);
    }
}
if (!всего) ошибки.push('показов даты не найдено вовсе — правило стало мёртвым');

/* ЗОНА НАЗЫВАЕТСЯ В ОДНОМ МЕСТЕ. Если 'Asia/Bishkek' начнёт появляться
   россыпью по файлам, дом времени перестанет быть домом. */
const россыпь = [];
for (const ф of файлы(path.join(корень, 'js'))) {
    const имя = path.relative(корень, ф);
    if (имя === 'js/kslt-vremya.js') continue;
    const т = без(fs.readFileSync(ф, 'utf8'));
    const n = (т.match(/'Asia\/Bishkek'/g) || []).length;
    /* Запасное значение рядом с KSLT_VREMYA.зона — это не россыпь, а
       страховка на случай, если дом не успел загрузиться. */
    const страховок = (т.match(/KSLT_VREMYA\.зона\)\s*\|\|\s*'Asia\/Bishkek'/g) || []).length;
    if (n > страховок) россыпь.push(`${имя} (${n - страховок})`);
}
/* ПОРОГ, ЗАДАННЫЙ ЧИСЛОМ ФАЙЛОВ, ПРОПУСКАЕТ ПЕРВЫЕ ТРИ. Первая редакция
   падала только при четырёх файлах — прувер показал, что откат в одном
   файле проходит мимо. Зона вне дома допустима РОВНО как страховка
   рядом с KSLT_VREMYA.зона, и ни в каком другом виде. */
if (россыпь.length) {
    ошибки.push(`'Asia/Bishkek' написан руками вне дома времени: ${россыпь.join(', ')}. Зона живёт в js/kslt-vremya.js, здесь допустима только страховка вида (KSLT_VREMYA.зона) || 'Asia/Bishkek'`);
}

/* ПОКАЗ ПЕРЕЕХАЛ В ДОМ, И ТЕПЕРЬ ДЫРА В ДОМЕ СТОИТ СЕМНАДЦАТИ ДЫР (12.11).
   До 11.11 каждый зовущий писал пояс сам, и сторож ловил его на месте
   зова: `new Date(...).toLocaleDateString(язык, { timeZone })`. Починка
   увела семнадцать мест в `KSLT_VREMYA.показДня` / `показМомента` — и
   признак выше их БОЛЬШЕ НЕ ВИДИТ: в доме зов написан не от `new Date`, а
   от переменной. То есть переставь доводы в доме — и пояс молча пропадёт
   сразу у всех семнадцати, а сторож останется зелёным.
   ПРИБОР ОБЯЗАН ИДТИ ЗА КОДОМ, КОГДА КОД ПЕРЕЕХАЛ. Здесь морозится
   устройство самого дома: показов ровно два, у каждого пояс ВТОРЫМ
   доводом через `сПоясом`, и `сПоясом` ставит зону ПОСЛЕ вида — иначе
   зовущий, передавший свой `timeZone`, перебил бы дом. */
if (fs.existsSync(дом)) {
    const тд = без(fs.readFileSync(дом, 'utf8'));
    const показы = [...тд.matchAll(/d\.toLocale(?:Date|Time)?String\(([^;]*?)\);/g)].map(м => м[1]);
    /* Их три, и это законно: два показа человеку (`показДня`,
       `показМомента`) плюс `деньПоБишкеку`, который собирает ISO-вид через
       'sv-SE'. ЧИСЛО НЕ МОРОЗИМ — морозим то, что у КАЖДОГО пояс стоит
       вторым доводом: либо через `сПоясом(вид)`, либо объектом с `ЗОНА`. */
    if (показы.length < 2) {
        ошибки.push(`в доме времени показов ${показы.length} — показывать дату стало нечем`);
    }
    for (const довод of показы) {
        const т = довод.trim();
        const черезДом = /,\s*сПоясом\(вид\)\s*$/.test(т);
        const поясомПрямо = /,\s*\{[^}]*timeZone:\s*ЗОНА[^}]*\}\s*$/.test(т);
        if (!черезДом && !поясомПрямо) {
            ошибки.push(`показ в доме времени идёт без пояса вторым доводом: ${т.replace(/\s+/g, ' ').slice(0, 70)}`);
        }
    }
    const тело = (тд.match(/function сПоясом\(вид\)\s*\{([\s\S]*?)\n    \}/) || [, ''])[1];
    const местоКопии = тело.indexOf('о[к] = вид[к]');
    const местоЗоны = тело.indexOf('о.timeZone = ЗОНА');
    if (местоКопии === -1 || местоЗоны === -1 || местоЗоны < местоКопии) {
        ошибки.push('сПоясом ставит зону НЕ ПОСЛЕ вида: вид, пришедший от зовущего, перебьёт пояс дома');
    }
}

if (ошибки.length) {
    console.error('ПОКАЗ ДАТЫ — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
console.log(`показ даты: ${всего} мест — ${сПоясом} с поясом из дома, ${локальных} локальной полночью, без пояса 0`);
