const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
const { безКомментариев } = require('./bez-kommentariev.js');
/* СНЯТИЕ КОММЕНТАРИЕВ — ОБЩИЙ ДОМ (30.10). Своё `безКом` здесь было
   слепым: строка с `accept="image` и открывашкой блочного комментария
   внутри открывала для регулярки «комментарий» до следующей настоящей
   закрывашки, и прибор не видел кода до конца файла. Имя `безКом`
   оставлено — его зовут правила ниже. */
const безКом = безКомментариев;

const ДОМ_САЙТ = 'js/kslt-kategorii.js';
const ДОМ_ПРИЛ = 'mobile/www/js/kslt-kategorii.js';

console.log('\n  РАЗБИВКА ПО КАТЕГОРИЯМ — ОДИН ДОМ\n');

правило('дом объявлен',
    /KSLT_KATEGORII/.test(чит(ДОМ_САЙТ)) &&
    /API\.строки\s*=/.test(чит(ДОМ_САЙТ)) &&
    /API\.блок\s*=/.test(чит(ДОМ_САЙТ)) &&
    /API\.все\s*=/.test(чит(ДОМ_САЙТ)),
    'Нужны три зова: `строки` (данные с местом), `блок`, `все`.');

правило('копии дома побайтово равны',
    чит(ДОМ_САЙТ) === чит(ДОМ_ПРИЛ),
    'Дом лежит копией в приложении. Разошлись — значит МЕСТО снова\n' +
    'считается двумя способами, и числа у сайта и приложения разойдутся.');

/* ---- ЧТО ОБЯЗАН ДЕРЖАТЬ ДОМ ---- */
[['friendly выброшен', /!==\s*'friendly'/],
 ['домашняя категория видна без очков', /points:\s*0,\s*wins:\s*0/],
 ['место считается по своему полу', /\.eq\('gender'/],
 ['чужая категория без очков в счёт места не идёт', /!\(очкиВ\[o\.id\]\s*>\s*0\)/],
 ['полоса побед', /kst-cat-bar-w/],
 ['метка закрытой категории с причиной', /closed_reason/]
].forEach(([имя, пр]) => {
    правило('в доме есть: ' + имя, пр.test(безКом(чит(ДОМ_САЙТ))),
        'Это и есть то, что нельзя считать дважды. Признак: ' + пр);
});

правило('число к склонению добавляет ДОМ',
    /н \+ ' ' \+ форма\(/.test(чит(ДОМ_САЙТ)),
    '`опции.счёт` — правило выбора формы, оно отдаёт только слово (так\n' +
    'устроен `KSLT_YAZYK.счёт`). Если число припишет зовущий, сайт и\n' +
    'приложение разойдутся на пробеле.');

правило('дом экранирует данные',
    /KSLT_экранировать/.test(чит(ДОМ_САЙТ)),
    'Причина закрытия категории — текст, который пишет администратор.\n' +
    'Без экранирования кавычка в нём даёт обработчик.');

/* ---- ОБА ПРОДУКТА ЗОВУТ ДОМ ---- */
правило('кабинет сайта зовёт дом',
    /KSLT_KATEGORII\.строки/.test(безКом(чит('js/dashboard.js'))) &&
    /KSLT_KATEGORII\.все/.test(безКом(чит('js/dashboard.js'))),
    'Разбивку обязан собирать дом, а не склейка на месте.');

/* ПРИЗНАК НЕ ТРЕБУЕТ ОДНОЙ ФОРМЫ ЗАПИСИ. Первая редакция искала
   `KSLT_KATEGORII.строки` — а профиль берёт дом в переменную
   (`var K = window.KSLT_KATEGORII`) и зовёт `K.строки`. Правило
   упало на верном коде: БЕДА ОДНА, ФОРМ У НЕЁ МНОГО. */
правило('профиль приложения зовёт дом',
    (function () {
        const т = безКом(чит('mobile/www/js/screens/profile.js'));
        return /KSLT_KATEGORII/.test(т) && /\.строки\(/.test(т) && /\.все\(/.test(т);
    })(),
    'Шаг A3.6 и есть «блока в приложении не было вовсе». Если зова нет,\n' +
    'работа не сделана.');

/* ---- СВОИХ КОПИЙ ЛОГИКИ НЕ ОСТАЛОСЬ ---- */
/* ПРИЗНАК ЛОВИТ ЧТЕНИЕ РАЗБИВКИ, А НЕ ЛЮБОЕ ЧТЕНИЕ ТАБЛИЦЫ. Первая
   редакция искала `from('player_categories')` и упала на двух верных
   чтениях: карточка профиля берёт из той же таблицы `category_id,
   points, closed_at` — это СПИСОК категорий в шапке, другое понятие.
   Разбивку выдаёт запрос с `wins` и `losses`. */
[['js/dashboard.js', /from\('player_categories'\)[\s\S]{0,120}wins/, 'своё чтение разбивки'],
 ['js/dashboard.js', /function catBarHtml/, 'своя полоса побед'],
 ['js/dashboard.js', /function catRateHtml/, 'свой процент категории'],
 ['js/dashboard.js', /function plural\(/, 'своё склонение']
].forEach(([ф, пр, имя]) => {
    правило('в кабинете нет своего: ' + имя,
        !пр.test(безКом(чит(ф))),
        'Переехало в дом. Осталось на месте — значит два определения\n' +
        'одного понятия. Признак: ' + пр);
});

/* ---- КРАСКА ЕСТЬ У ОБОИХ ---- */
/* ИМЯ ПРАВИЛА — ТОЖЕ ЯКОРЬ (см. `check-plitki.js`). */
[['css/dashboard.css', 'сайта'], ['mobile/www/css/app.css', 'приложения']].forEach(([ф, имя]) => {
    const css = чит(ф);
    правило('краска блока есть у ' + имя,
        ['\\.kst-cat-block', '\\.kst-cat-name', '\\.kst-cat-dot', '\\.kst-cat-bar',
         '\\.kst-cat-legend', '\\.kst-cat-rate']
            .every(п => new RegExp(п + '\\s*\\{').test(css)),
        'Одно имя на одно понятие не значит один вид — значит одно место,\n' +
        'где вид задаётся. У приложения этих правил не было вовсе.');
});

/* ---- ТОЧКА И ПОЛОСА РАВНЫ В ДВУХ ПРОДУКТАХ (30.10) ---- */
/* ЗАМОРОЖЕНО ОТНОШЕНИЕ, А НЕ ЧИСЛО: «точка квадратная и одинаковая в
   обоих продуктах», «высота полосы одна на оба». Разметку рисует ОБЩИЙ
   дом, а вид расходился: точка была 10×10 на сайте при 8×8 в
   приложении, полоса 6 против 8, отступ `8px 0 5px` (5 мимо ступеней) и
   радиус 3 числом против скругления таблеткой.
   СТОРОЖ «ОДНИ КЛАССЫ В ДВУХ ПРОДУКТАХ» ЭТОГО НЕ ВИДЕЛ И БЫЛ ЗЕЛЁНЫМ:
   он сверяет ИМЕНА классов, а не числа внутри них. Прибор, смотрящий
   имена, про числа не знает — и наоборот. */
function числоВПравиле(css, селектор, свойство) {
    const i = css.indexOf(селектор);
    if (i === -1) return null;
    const блок = css.slice(i, css.indexOf('}', i));
    const m = блок.match(new RegExp(свойство + ':\\s*([^;]+);'));
    return m ? m[1].trim() : null;
}
const цСайт = чит('css/dashboard.css');
const цПрил = чит('mobile/www/css/app.css');

правило('точка категории одинакова в двух продуктах и квадратна',
    (function () {
        const ш = числоВПравиле(цСайт, '.kst-cat-dot', 'width');
        const в = числоВПравиле(цСайт, '.kst-cat-dot', 'height');
        const шП = числоВПравиле(цПрил, '.kst-cat-dot', 'width');
        const вП = числоВПравиле(цПрил, '.kst-cat-dot', 'height');
        return !!ш && ш === в && ш === шП && шП === вП;
    })(),
    'Сайт: ' + числоВПравиле(цСайт, '.kst-cat-dot', 'width') + '×' +
        числоВПравиле(цСайт, '.kst-cat-dot', 'height') +
    ', приложение: ' + числоВПравиле(цПрил, '.kst-cat-dot', 'width') + '×' +
        числоВПравиле(цПрил, '.kst-cat-dot', 'height') + '.\n' +
    'Одна разметка, один дом — и две разные точки: человек видит на сайте\n' +
    'одно, в приложении другое, и ни одно число не названо намеренным.');

правило('высота полосы категорий одна на оба продукта',
    (function () {
        const в = числоВПравиле(цСайт, '.kst-cat-bar', 'height');
        return !!в && в === числоВПравиле(цПрил, '.kst-cat-bar', 'height');
    })(),
    'Сайт: ' + числоВПравиле(цСайт, '.kst-cat-bar', 'height') +
    ', приложение: ' + числоВПравиле(цПрил, '.kst-cat-bar', 'height') + '.\n' +
    'НАМЕРЕНО 8 — это графика, и помечено так в обоих файлах.');

правило('полоса категорий скругляется таблеткой, а не половиной высоты',
    (function () {
        const р = числоВПравиле(цСайт, '.kst-cat-bar', 'border-radius');
        const рП = числоВПравиле(цПрил, '.kst-cat-bar', 'border-radius');
        const полное = з => з === '999px' || /radius-full/.test(з || '');
        return полное(р) && полное(рП);
    })(),
    'Сайт: ' + числоВПравиле(цСайт, '.kst-cat-bar', 'border-radius') +
    ', приложение: ' + числоВПравиле(цПрил, '.kst-cat-bar', 'border-radius') + '.\n' +
    'Радиус в половину высоты — это полное скругление, записанное числом:\n' +
    'поменяется высота, и половина уедет, а число нет.');

правило('у приложения есть мини-сетка',
    /\.kst-grid-mini\s*\{/.test(чит('mobile/www/css/app.css')) &&
    /\.kst-cat-top \.kst-grid\s*\{/.test(чит('mobile/www/css/app.css')),
    'Без неё плитки внутри блока встают СТОЛБИКОМ: `auto-fit,\n' +
    'minmax(70px, 1fr)` в flex-ребёнке берёт минимальную ширину, сетка\n' +
    'сжимается до 113 px, и блок вырастает с 155 до 448. Замер на 390.');

правило('дом языка подключён в приложение',
    /kslt-yazyk\.js/.test(чит('mobile/www/index.html')),
    'Склонение берётся из дома языка. Он и раньше ЗВАЛСЯ двумя файлами\n' +
    'приложения (`kslt-sponsory.js`, `tournament-slots.js`), но не был\n' +
    'подключён — там было `undefined` (долг G3, закрыт 29.10).');

правило('дом подключён во всех разметках',
    ['pages/dashboard.html', 'pages/dashboard-en.html', 'pages/dashboard-kg.html',
     'mobile/www/index.html'].every(ф => /kslt-kategorii\.js/.test(чит(ф))),
    'Страница зовёт дом, но не грузит его — блок просто не появится.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      разбивка по категориям: все ' + держится + ' правил держатся\n');
}
