/**
 * ЗАМОРОЗКА: ПОЛ ТУРНИРА — ОТКАЗ, А НЕ ПОМЕТКА.
 *
 * Слово Кости 01.10: «Рейтинговые турниры — жёсткие правила: не проходит
 * она туда и не принимается заявка». До этого женщина ПРОХОДИЛА в мужской
 * одиночный турнир — вставала в основу с пометкой `review_reasons:
 * ['gender']` и ждала решения менеджера. Замер 01.10 на турнире d8b39287:
 * Эркайым Исматова (`gender: women`) оказалась в сетке мужского
 * одиночного турнира со статусом `approved`.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ: «у турнира с полом состав не предмет решения».
 * Делим по полю `gender` турнира, а не по словам «рейтинговый/дружеский»:
 * рейтинговый (`isUnrankedTournament` — одиночный и не `friendly`) всегда
 * имеет пол `men` или `women`, и то же правило накрывает мужские и
 * женские парные. Микст (`gender: mixed`) НЕ трогаем: там требование
 * разнополой пары остаётся пометкой.
 *
 * ДВЕРЕЙ ЧЕТЫРЕ, И КАЖДАЯ ОБЯЗАНА СПРОСИТЬ. Пропущенная дверь — это та,
 * через которую беда и вернётся.
 *
 *   node tools/check-pol-turnira.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СЕТКА = чит('js/admin/sections/bracket.js');
const СЕТч = безКом(СЕТКА);
const ПОДПИСИ = чит('js/admin/core/constants.js');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

function тело(текст, имя) {
    const i = текст.indexOf('function ' + имя + '(');
    if (i === -1) return '';
    let гл = 0, j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}

const БЕДА = тело(СЕТч, 'бедаПоПолу');

/* ── 1. Судья по полу есть ───────────────────────────────────────────── */
правило('бедаПоПолу на месте',
    БЕДА.length > 0,
    'функция `бедаПоПолу` не найдена в js/admin/sections/bracket.js. ' +
    'Она — единственное место, где пол турнира превращается в отказ');

/* ── 2. Отказ только у турниров с полом ──────────────────────────────── */
правило('микст судья не трогает',
    /турнир\s*!==\s*'men'\s*&&\s*турнир\s*!==\s*'women'[\s\S]{0,40}return\s+''/.test(БЕДА),
    'в `бедаПоПолу` пропал ранний выход для турниров без пола. Микст ' +
    '(`gender: mixed`) обязан остаться с ПОМЕТКОЙ: там состав решает клуб, ' +
    'а очков микст не даёт вовсе');

/* ── 3. Судья опирается на общий предикат, а не на свою копию ────────── */
правило('бедаПоПолу спрашивает составСошёлся',
    /составСошёлся\s*\(/.test(БЕДА),
    '`бедаПоПолу` перестала звать `составСошёлся` и считает совпадение ' +
    'пола сама. Одно понятие — два определения, они разойдутся');

/* ── 4. ЧЕТЫРЕ ДВЕРИ. Каждая зовёт судью ─────────────────────────────── */
const ДВЕРИ = [
    ['замена игрока или напарника', 'openReplaceModal'],
    ['замена пары целиком',          'openReplacePairModal']
];
ДВЕРИ.forEach(([имя, функция]) => {
    const т = тело(СЕТч, функция);
    правило('дверь «' + имя + '» спрашивает про пол',
        т.length > 0 && /бедаПоПолу\s*\(/.test(т),
        'в `' + функция + '` пропал вызов `бедаПоПолу`. Через эту дверь ' +
        'состав не того пола снова попадёт в турнир');
});

/* Двери добавления заявки лежат в обработчиках, а не в именованных
   функциях: считаем вызовы по всему файлу. Их должно быть не меньше
   четырёх — замена, замена пары, добавление одиночной стороны,
   добавление пары. */
const вызовов = (СЕТч.match(/бедаПоПолу\s*\(/g) || []).length - 1; // минус объявление
правило('все четыре двери спрашивают',
    вызовов >= 4,
    'вызовов `бедаПоПолу` осталось ' + вызовов + ', а дверей четыре: ' +
    'замена игрока, замена пары, добавление одиночной стороны, добавление ' +
    'пары. Пропущенная дверь — та, через которую беда вернётся');

/* ── 5. Отказ останавливает запись ───────────────────────────────────── */
/* Пометка без `return` — это не отказ, а надпись: заявка всё равно ляжет
   в базу. Каждый вызов обязан завершаться выходом. */
/* ОБЪЯВЛЕНИЕ ОПОЗНАЁМ ПО СЛОВУ `function`, А НЕ ПО ПОРЯДКУ.
   Первая редакция правила пропускала два первых вхождения, считая, что
   объявление идёт раньше вызовов. В файле оно НИЖЕ первого вызова
   (`:1298` против `:1946`), и правило мерило тело самой функции вместо
   двери. Поймано своим же прувером 01.10. */
const кусочки = [];
СЕТч.replace(/(function\s+)?бедаПоПолу\s*\(/g, (м, объявление, и) => {
    if (!объявление) кусочки.push(СЕТч.slice(и, и + 400));
    return м;
});
const безВыхода = кусочки.filter(к => !/return;/.test(к));
правило('отказ по полу останавливает запись',
    кусочки.length > 0 && безВыхода.length === 0,
    'у ' + безВыхода.length + ' вызовов `бедаПоПолу` рядом нет `return;`. ' +
    'Без выхода отказ превращается в надпись, и заявка всё равно ' +
    'записывается — ровно то поведение, которое чинили');

/* ── 6. Подписи отказа есть на обоих языках ──────────────────────────── */
['regGenderMenOnly', 'regGenderWomenOnly'].forEach(ключ => {
    const сколько = (ПОДПИСИ.match(new RegExp(ключ + '\\s*:', 'g')) || []).length;
    правило('подпись ' + ключ + ' на двух языках',
        сколько === 2,
        'ключ `' + ключ + '` встречается в constants.js ' + сколько +
        ' раз, а должен дважды — русский и английский. Админка живёт на ' +
        'русском, но подписи заведены парами');
});

/* ── вывод ───────────────────────────────────────────────────────────── */
if (ошибки.length) {
    console.log('✗ Пол турнира: ' + ошибки.length + ' правил упало\n');
    ошибки.forEach(о => console.log('  • ' + о.имя + '\n    ' + о.подсказка + '\n'));
    process.exit(1);
}
console.log('✓ Пол турнира — отказ, а не пометка: все правила держат');
