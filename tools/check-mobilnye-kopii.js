const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => {
    ВСЕГО++;
    if (!условие) ошибки.push({ имя, подсказка });
};

/** Все файлы приложения, у которых на сайте есть файл с тем же путём. */
function копии() {
    const итог = [];
    const обойти = папка => {
        if (!fs.existsSync(папка)) return;
        fs.readdirSync(папка, { withFileTypes: true }).forEach(э => {
            const полный = path.join(папка, э.name);
            if (э.isDirectory()) return обойти(полный);
            const отн = path.relative(ПРИЛОЖЕНИЕ, полный).split(path.sep).join('/');
            if (fs.existsSync(path.join(КОРЕНЬ, отн))) итог.push(отн);
        });
    };
    обойти(ПРИЛОЖЕНИЕ);
    return итог.sort();
}

const ВСЕ = копии();

/**
 * Сверка одной копии: `true` — совпадают, `false` — разошлись, строка — почему
 * сверить нельзя.
 *
 * Молчать про пропавший файл нельзя: копия, у которой на сайте не осталось
 * оригинала, — это и есть расхождение, только наоборот. И прувер гоняет
 * сторожа на УРЕЗАННОМ дереве, где часть файлов не копируется вовсе, —
 * падение по `ENOENT` там означало бы, что ни одно правило не отработало.
 */
const одинаков = отн => {
    const наСайте = path.join(КОРЕНЬ, отн);
    const вПриложении = path.join(ПРИЛОЖЕНИЕ, отн);
    if (!fs.existsSync(наСайте)) return 'на сайте файла нет';
    if (!fs.existsSync(вПриложении)) return 'в приложении файла нет';
    return fs.readFileSync(наСайте).equals(fs.readFileSync(вПриложении));
};

