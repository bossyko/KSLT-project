/**
 * СТАТУС «ИДЁТ» — ОДНА РОЛЬ НА ВЕСЬ ПРОДУКТ. Круг 16 ветки D, 18.10.
 * Находка 96г.
 *
 * ДВА ПОНЯТИЯ, КОТОРЫЕ НЕЛЬЗЯ ПУТАТЬ:
 *   «турнир идёт»  — состояние турнира между регистрацией и завершением.
 *                    Роль `--role-manager`, объявленная в `tokens.css`
 *                    как «менеджер / идёт сейчас» ещё 17.10.
 *   «матч идёт»    — эфир. Роль `--danger`, сведённая кругом 2б ветки B.
 * Их сторожат РАЗНЫЕ правила: эфир — `check-efir-odnoy-kraskoy.js`,
 * статус турнира — это.
 *
 * ЧТО БЫЛО. Запись трекера говорила «два определения». Прибор нашёл ТРИ
 * краски на статус турнира: фиолетовая в списке админки (верная),
 * ЛАЙМОВАЯ в её же форме (ΔE 164 от верной) и голубой `#00A3FF` ЧИСЛОМ на
 * сайте — в трёх файлах сразу. Человек видел один турнир лаймовым в форме
 * админки и голубым на странице.
 *
 * ПРИНЯТОЕ НЕ ПЕРЕОТКРЫВАЕТСЯ: роль была решена 17.10, круг 16 лишь
 * донёс её до отставших мест.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ: все места статуса «идёт» берут ОДНУ роль,
 * ни одно не красится числом, и роль эта — не та, которой говорит эфир.
 * Последнее важно: спутать «турнир идёт» с «матч в эфире» — значит
 * вернуть ту же беду с другой стороны.
 *
 *   node tools/check-status-idet.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чисто = п => fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

/* Все места, где рисуется статус «турнир идёт». Якорь — имя селектора:
   переименовали — поправь здесь, иначе правило перестанет сторожить МОЛЧА. */
const МЕСТА = [
    ['css/admin.css',                 '.ad-status-ongoing'],
    ['css/admin.css',                 '.ad-trn-status-field.ad-status-ongoing'],
    ['css/tournament-detail.css',     '.td-status-badge.ongoing'],
    ['css/tournaments-overview.css',  '.to-featured-status.ongoing'],
    ['css/tournaments-overview.css',  '.to-compact-status.ongoing'],
    ['css/tournaments.css',           '.tournament-status.ongoing']
];

/* Краска эфира и прочие роли: статус турнира ими говорить не должен. */
const ЧУЖИЕ_РОЛИ = ['--danger', '--success', '--warning', '--info', '--accent'];

const файлы = {};
МЕСТА.forEach(([ф]) => { if (!файлы[ф]) файлы[ф] = чисто(ф); });

function тело(текст, селектор) {
    const р = /([^{}\n][^{}]*?)\{([^{}]*)\}/g;
    let м, найдено = null;
    while ((м = р.exec(текст))) {
        if (м[1].split(',').some(ч => ч.trim() === селектор)) найдено = м[2];
    }
    return найдено;
}

/* ПРАВИЛО 1. Все места на месте: исчезнувший селектор — молчащий сторож. */
const пропали = МЕСТА.filter(([ф, с]) => тело(файлы[ф], с) === null)
                     .map(([ф, с]) => ф + ' ' + с);
правило('все места статуса «идёт» на месте',
    пропали.length === 0,
    'Селекторы исчезли: ' + пропали.join(', ') + '.\n' +
    'Якорь держится на имени. Переименовал — поправь список в правиле,\n' +
    'иначе оно перестанет сторожить блок МОЛЧА.');

/* ПРАВИЛО 2. Ни одно место не красится ЧИСЛОМ.
   Голубой `#00A3FF` стоял числом в трёх файлах. */
const числом = МЕСТА.filter(([ф, с]) => {
    const т = тело(файлы[ф], с);
    return т && /#[0-9a-fA-F]{3,8}\b|rgba?\(\s*\d/.test(т);
}).map(([ф, с]) => ф + ' ' + с);
правило('статус «идёт» нигде не красится числом',
    числом.length === 0,
    'Краска числом: ' + числом.join(', ') + '.\n' +
    'Было `#00A3FF` в трёх файлах сразу — и ни один сторож красок его не\n' +
    'видел, потому что каждый смотрел свой файл.');

/* ПРАВИЛО 3. Все места берут ОДНУ роль — ту, что решена 17.10. */
const РОЛЬ = '--role-manager';
const мимоРоли = МЕСТА.filter(([ф, с]) => {
    const т = тело(файлы[ф], с);
    return т && !new RegExp('var\\(' + РОЛЬ).test(т);
}).map(([ф, с]) => ф + ' ' + с);
правило('статус «идёт» говорит одной ролью',
    мимоРоли.length === 0,
    'Мимо роли ' + РОЛЬ + ': ' + мимоРоли.join(', ') + '.\n' +
    'Роль объявлена в `tokens.css` как «менеджер / идёт сейчас» 17.10.\n' +
    'ПРИНЯТОЕ НЕ ПЕРЕОТКРЫВАЕТСЯ: краску можно сменить в ОДНОМ месте —\n' +
    'в токенах, — а не по разделам.');

/* ПРАВИЛО 4. Статус турнира НЕ говорит краской эфира и других ролей.
   Спутать «турнир идёт» с «матч в эфире» — та же беда с другой стороны. */
const чужое = [];
МЕСТА.forEach(([ф, с]) => {
    const т = тело(файлы[ф], с);
    if (!т) return;
    ЧУЖИЕ_РОЛИ.forEach(р => {
        if (new RegExp('var\\(' + р + '[-)]').test(т)) чужое.push(ф + ' ' + с + ' ← ' + р);
    });
});
правило('статус турнира не говорит краской эфира и чужих ролей',
    чужое.length === 0,
    'Чужая роль в статусе «идёт»:\n  ' + чужое.join('\n  ') + '\n' +
    '`--danger` — это ЭФИР (матч идёт прямо сейчас), и путать его со\n' +
    'статусом турнира нельзя: это разные состояния на одном экране.\n' +
    'Лайм `--accent` здесь уже стоял — в форме админки.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      статус «идёт»: 4 правила');
    console.log('          ' + МЕСТА.length + ' мест в ' + Object.keys(файлы).length +
                ' файлах — все на роли ' + РОЛЬ);
    console.log('          числом не красится нигде; эфир сторожится отдельно');
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  статус «идёт» — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
