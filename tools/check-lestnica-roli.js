/**
 * ЛЕСТНИЦА РОЛИ — СТОРОЖ (ветка D, круг 5, 17.10).
 *
 * ЧТО СЛУЧИЛОСЬ. Пять состояний админки красились числом: успех пятью
 * написаниями, внимание семью (оранжевый пополам с жёлтым), сведения
 * пятью, «менеджер / идёт сейчас» двумя, «завершён» двумя. Подложка у
 * роли была одна — 15 %, — а код звал одиннадцать прозрачностей:
 * 0.04 · 0.05 · 0.06 · 0.08 · 0.1 · 0.12 · 0.16 · 0.2 · 0.3 · 0.35 · 0.4.
 * Замер 17.10 на стенде `maket/kraski-admin-zamer.html`: разброс
 * контраста ВНУТРИ одной роли доходил до 4.0 единиц — одно и то же
 * состояние светилось по-разному в разных таблицах.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ, А НЕ ЧИСЛО. Ступени три, и важно не то,
 * что подложка равна 0.15, а что ГРАНИЦА СТРОГО ЯРЧЕ ПОДЛОЖКИ, а
 * подложка строго ярче тусклой: иначе рамка сливается с заливкой, и
 * бейдж теряет край. Числа проверяются отдельно и только как «ступень
 * есть и она одна».
 *
 * ПОЧЕМУ ЭТОГО НЕ ЛОВИТ ХРАПОВИК `check-admin-sloy.js`. Тот считает
 * ЧИСЛО голых красок и роняет правило при росте. Он не знает, что
 * `--success-border` обязан быть ярче `--success-subtle`, и не заметит,
 * если роль заведут мимо лестницы ИМЕНЕМ: `--success-border: 0.1` —
 * краска названа, храповик молчит, а рамка пропала.
 *
 *   node tools/check-lestnica-roli.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}
const ТОКЕНЫ = fs.readFileSync(path.join(КОРЕНЬ, 'css/tokens.css'), 'utf8');

/* ---- разбор объявлений: имя -> значение, с разворачиванием var(--…) ---- */
const карта = {};
(ТОКЕНЫ.replace(/\/\*[\s\S]*?\*\//g, ' ').match(/--[\w-]+\s*:\s*[^;]+/g) || [])
    .forEach(об => {
        const и = об.indexOf(':');
        карта[об.slice(0, и).trim()] = об.slice(и + 1).trim();
    });
function развернуть(имя, глубина) {
    if ((глубина || 0) > 8) return null;
    const зн = карта[имя];
    if (!зн) return null;
    const ссылка = зн.match(/^var\(\s*(--[\w-]+)\s*\)$/);
    if (ссылка) return развернуть(ссылка[1], (глубина || 0) + 1);
    return зн;
}
function разобрать(зн) {
    if (!зн) return null;
    let м = зн.match(/^#([0-9a-fA-F]{6})$/);
    if (м) return { r: parseInt(м[1].slice(0,2),16), g: parseInt(м[1].slice(2,4),16),
                    b: parseInt(м[1].slice(4,6),16), a: 1 };
    м = зн.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)$/);
    if (м) return { r: +м[1], g: +м[2], b: +м[3], a: м[4] === undefined ? 1 : +м[4] };
    return null;
}
function поверх(п, з) {
    return { r: п.r*п.a + з.r*(1-п.a), g: п.g*п.a + з.g*(1-п.a), b: п.b*п.a + з.b*(1-п.a), a: 1 };
}
function Я(ц) {
    const f = v => { v /= 255; return v <= 0.03928 ? v/12.92 : Math.pow((v+0.055)/1.055, 2.4); };
    return 0.2126*f(ц.r) + 0.7152*f(ц.g) + 0.0722*f(ц.b);
}
function контраст(а, б) {
    const x = Я(а), y = Я(б), hi = Math.max(x,y), lo = Math.min(x,y);
    return Math.round((hi + 0.05) / (lo + 0.05) * 100) / 100;
}

/* Основа, на которой живут бейджи админки: карточка поверх страницы. */
const ОСНОВА = поверх(разобрать(развернуть('--bg-card')) || {r:20,g:20,b:20,a:1},
                      разобрать(развернуть('--bg-base')) || {r:10,g:10,b:10,a:1});

const РОЛИ = ['success', 'warning', 'info', 'danger', 'role-manager'];
const СТУПЕНИ = ['faint', 'subtle', 'border'];

/* 1. У КАЖДОЙ РОЛИ ЕСТЬ ВСЕ ТРИ СТУПЕНИ. Пропущенная ступень — это место,
      где следующий раз напишут число. */
const нет = [];
РОЛИ.forEach(р => {
    if (!развернуть('--' + р)) нет.push('--' + р);
    СТУПЕНИ.forEach(с => { if (!развернуть('--' + р + '-' + с)) нет.push('--' + р + '-' + с); });
});
правило('у каждой роли объявлены все три ступени',
    нет.length === 0,
    'Не объявлены: ' + нет.join(', ') + '.\n' +
    'Роль без ступени — приглашение написать прозрачность числом.');

/* 2. ОТНОШЕНИЕ: граница ярче подложки, подложка ярче тусклой.
      Замораживается именно оно: числа 0.06 · 0.15 · 0.30 могут поехать,
      порядок — нет. */
const сломано = [];
РОЛИ.forEach(р => {
    const т = разобрать(развернуть('--' + р + '-faint'));
    const п = разобрать(развернуть('--' + р + '-subtle'));
    const г = разобрать(развернуть('--' + р + '-border'));
    if (!т || !п || !г) return;
    if (!(г.a > п.a)) сломано.push(р + ': граница ' + г.a + ' не ярче подложки ' + п.a);
    if (!(п.a > т.a)) сломано.push(р + ': подложка ' + п.a + ' не ярче тусклой ' + т.a);
});
правило('граница строго ярче подложки, подложка строго ярче тусклой',
    сломано.length === 0,
    сломано.join('\n') + '\n' +
    'Рамка одной ступени с заливкой не видна: бейдж теряет край.');

/* 3. ОДИН ТОН НА РОЛЬ. Ступень, намешанная из другого тона, — это вторая
      краска под именем роли. */
const чужие = [];
РОЛИ.forEach(р => {
    const осн = разобрать(развернуть('--' + р));
    if (!осн) return;
    СТУПЕНИ.forEach(с => {
        const ст = разобрать(развернуть('--' + р + '-' + с));
        if (!ст) return;
        if (ст.r !== осн.r || ст.g !== осн.g || ст.b !== осн.b) {
            чужие.push('--' + р + '-' + с + ' намешана не из --' + р);
        }
    });
});
правило('ступени роли намешаны из её же тона',
    чужие.length === 0,
    чужие.join('\n') + '\n' +
    'Ступень из чужого тона — вторая краска, спрятанная под именем роли.');

/* 4. ТЕКСТ РОЛИ НА СВОЕЙ ПОДЛОЖКЕ ЧИТАЕТСЯ. WCAG 1.4.3: подпись бейджа
      мелкая, норма 4.5. Считается на карточке, как в админке. */
const слабые = [];
РОЛИ.forEach(р => {
    const цв = разобрать(развернуть('--' + р));
    const п = разобрать(развернуть('--' + р + '-subtle'));
    if (!цв || !п) return;
    const фон = поверх(п, ОСНОВА);
    const к = контраст(поверх(цв, фон), фон);
    if (к < 4.5) слабые.push('--' + р + ' на своей подложке: ' + к);
});
правило('текст роли на своей подложке не ниже 4.5',
    слабые.length === 0,
    слабые.join('\n') + '\nWCAG 1.4.3 для мелкого текста — 4.5.');

/* 5. ТЕКСТ ПОВЕРХ СПЛОШНОЙ ЗАЛИВКИ. Белый на светлой заливке — провал,
      который держался в коде незамеченным: на клетке «выиграл» белый по
      #4CAF50 давал 2.78 ЕЩЁ ДО сведения. */
const заливки = [['--success', '--success-on'], ['--danger', '--danger-on']];
const провал = [];
заливки.forEach(([з, т]) => {
    const фон = разобрать(развернуть(з)), текст = разобрать(развернуть(т));
    if (!фон || !текст) { провал.push(з + ' или ' + т + ' не объявлены'); return; }
    const к = контраст(текст, фон);
    if (к < 4.5) провал.push(т + ' на ' + з + ': ' + к);
});
правило('текст поверх сплошной заливки роли не ниже 4.5',
    провал.length === 0,
    провал.join('\n') + '\nЗаливка яркая — текст на ней берётся почти-чёрный.');

/* 6. РОЛИ РАЗЛИЧИМЫ МЕЖДУ СОБОЙ. «Менеджер» заводился как отдельная роль
      именно потому, что ни одна занятая ей не подходила; если его тон
      съедет к синему, смысл роли исчезнет, а код будет выглядеть чистым. */
function тон(ц) {
    const r = ц.r/255, g = ц.g/255, b = ц.b/255;
    const макс = Math.max(r,g,b), мин = Math.min(r,g,b), д = макс - мин;
    if (!д) return 0;
    let h;
    if (макс === r) h = ((g - b) / д) % 6;
    else if (макс === g) h = (b - r) / д + 2;
    else h = (r - g) / д + 4;
    h *= 60;
    return h < 0 ? h + 360 : h;
}
const близкие = [];
for (let i = 0; i < РОЛИ.length; i++) {
    for (let j = i + 1; j < РОЛИ.length; j++) {
        const а = разобрать(развернуть('--' + РОЛИ[i]));
        const б = разобрать(развернуть('--' + РОЛИ[j]));
        if (!а || !б) continue;
        let д = Math.abs(тон(а) - тон(б));
        if (д > 180) д = 360 - д;
        if (д < 25) близкие.push(РОЛИ[i] + ' и ' + РОЛИ[j] + ': ' + Math.round(д) + '°');
    }
}
правило('роли различимы по тону не меньше чем на 25°',
    близкие.length === 0,
    близкие.join('\n') + '\n' +
    'Две роли одного тона — это одна роль, названная дважды.');

/* 7. ТОН РОЛИ НЕ ПИШЕТСЯ ЧИСЛОМ В СЛОЕ АДМИНКИ. Храповик считает краски
      вообще; это правило ловит именно возврат роли числом — ту самую
      копию, ради снятия которой затевался круг. */
const файлы = [path.join(КОРЕНЬ, 'css/admin.css')];
(function обойти(д) {
    fs.readdirSync(д, { withFileTypes: true }).forEach(э => {
        const п = path.join(д, э.name);
        if (э.isDirectory()) обойти(п);
        else if (э.name.endsWith('.js')) файлы.push(п);
    });
})(path.join(КОРЕНЬ, 'js/admin'));

const тона = {};
РОЛИ.forEach(р => {
    const ц = разобрать(развернуть('--' + р));
    if (ц) тона[р] = ц;
});
const возвраты = [];
файлы.forEach(ф => {
    const текст = fs.readFileSync(ф, 'utf8').replace(/\/\*[\s\S]*?\*\//g, ' ');
    текст.split('\n').forEach((стр, н) => {
        /* ПЕЧАТЬ И ГРАФИКИ НЕ СЧИТАЮТСЯ, И ЭТО НАЙДЕНО ЗАМЕРОМ, А НЕ
           ПРИДУМАНО: окно печати грузится без `tokens.css`, а canvas у
           Chart.js не понимает `var(--…)` вовсе. */
        if (/\.report-|\.stat-box|@media print|@page/.test(стр)) return;
        if (/borderColor|backgroundColor|pointBackgroundColor|pointBorderColor/.test(стр)) return;
        Object.keys(тона).forEach(р => {
            const ц = тона[р];
            const hex = '#' + [ц.r, ц.g, ц.b].map(в => в.toString(16).padStart(2, '0')).join('');
            const re = new RegExp(hex + '\\b|rgba?\\(\\s*' + ц.r + '\\s*,\\s*' + ц.g + '\\s*,\\s*' + ц.b, 'i');
            if (re.test(стр)) {
                возвраты.push(path.relative(КОРЕНЬ, ф) + ':' + (н + 1) + ' — тон роли ' + р + ' числом');
            }
        });
    });
});
правило('тон роли не написан числом в слое админки',
    возвраты.length === 0,
    возвраты.slice(0, 12).join('\n') + '\n' +
    'Роль зовётся именем: var(--success), var(--warning), var(--info),\n' +
    'var(--danger), var(--role-manager). Число — это копия понятия.');

if (!ошибки.length) {
    console.log('\n  ок      лестница роли: 7 правил');
    console.log('          пять ролей, по три ступени: тускло · подложка · граница');
    РОЛИ.forEach(р => {
        const цв = разобрать(развернуть('--' + р));
        const п = разобрать(развернуть('--' + р + '-subtle'));
        const фон = поверх(п, ОСНОВА);
        console.log('          --' + (р + '            ').slice(0, 13) +
            ' текст на своей подложке ' + контраст(поверх(цв, фон), фон));
    });
    console.log('');
    process.exit(0);
}
console.log('\n  УПАЛО: ' + ошибки.length + '\n');
ошибки.forEach(о => console.log('  x  ' + о.имя + '\n     ' + о.подсказка.replace(/\n/g, '\n     ') + '\n'));
process.exit(1);
