#!/usr/bin/env node
/**
 * ПЕРЕСТАНОВКА МЕСТА: ПРИЗНАК РАБОТЫ И СЛЕД (кусок 04.11).
 *
 * ДВА СЛОВА КОСТИ В ОДИН ДЕНЬ, И ОБА ПРО ОДНО МЕСТО.
 *
 * ПЕРВОЕ: «а то, что меняется в сетке с задержкой, это нормально?».
 * Задержка настоящая: правка места снимает имена со ВСЕХ клеток с метками,
 * расставляет их заново и перерисовывает сетку целиком — три захода в базу.
 * Всё это время на экране не менялось ничего, а выпадашки оставались
 * живыми. РАБОТА, КОТОРАЯ НЕ ВИДНА, НЕОТЛИЧИМА ОТ БЕЗДЕЙСТВИЯ — близнец
 * правила про невидимый отказ, выведенного на этом же проекте.
 *
 * ВТОРОЕ: «нет у нас журнала, и никто не будет писать причину». Спрос
 * причины введён 03.11 и отменён 04.11 — не потому что довод был плох, а
 * потому что причина уходила в JSON поля турнира, и прочитать её нельзя
 * было ничем, кроме запроса к базе. ЗАЩИТА, КОТОРУЮ НИКТО НЕ МОЖЕТ
 * ПРОЧИТАТЬ, НЕ ЗАЩИЩАЕТ.
 *
 * ЗАМОРОЖЕНЫ ОТНОШЕНИЯ:
 *   · пока идёт пересборка — выпадашки заперты, и это видно;
 *   · запертое отпускается на ВСЕХ путях, включая отказ;
 *   · причина не спрашивается, но след перестановки пишется ВСЕГДА.
 *
 * ПОЧЕМУ СЛЕД ОТДЕЛЬНЫМ ПРАВИЛОМ: убрать спрос причины легко заодно с
 * записью — и тогда от перестановки не останется ничего. Экран журнала
 * когда-нибудь напишут, и данные для него должны копиться с этого дня.
 *
 *   node tools/check-perestanovka-mesta.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');

const код = безКомментариев(чит('js/admin/sections/bracket.js'));
const слова = чит('js/admin/core/constants.js');
const одежда = чит('css/admin.css');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const тело = (код.match(/sel\.addEventListener\('change', async function\(\)[\s\S]*?\n            \}\);/) || [''])[0];

/* ── 1. признак работы ───────────────────────────────────────────────── */
правило('выпадашки запираются на время пересборки',
    /выпадашкиГруппы\.forEach\(function\(в\) \{ в\.disabled = true; \}\)/.test(тело),
    'выпадашки остаются живыми, пока идёт пересборка — второе нажатие ляжет поверх');

/* МЕРЯЕТСЯ ИМЕННО ТОТ НАБОР, КОТОРЫЙ ЗАПИРАЮТ. Прувер показал дыру:
   правило искало селектор группы по всему обработчику и находило его у
   СОСЕДНЕГО набора (`groupSelects`, он собирает раскладку мест). Откат,
   подменивший запираемый набор на одну выпадашку, проходил молча.
   ОДИН И ТОТ ЖЕ ТЕКСТ В ДВУХ МЕСТАХ — ЭТО ДВА РАЗНЫХ ПОНЯТИЯ, и мерить
   надо то, которое правило называет. */
правило('запирается вся группа, а не одна выпадашка',
    /выпадашкиГруппы = container\.querySelectorAll\(\s*\n?\s*'\.ad-grp-place-select\[data-group="' \+ window\.KSLT_селектор\(groupNum\)/.test(тело),
    'запирается только та выпадашка, которую тронули — сосед запишет поверх');

правило('работа видна глазами',
    /classList\.add\('ad-grp-busy'\)/.test(тело) &&
    /\.ad-grp-busy\s*\{[^}]*opacity\s*:/.test(одежда),
    'нет видимого признака работы или в css нет приглушения. ПРОВЕРЯЕТСЯ ИМЕННО ' +
    'ПРИГЛУШЕНИЕ: класс объявлен в файле дважды, и второе объявление живёт в ' +
    'медиазапросе про укрощённое движение. Прувер показал, что правило, ищущее ' +
    'просто имя класса, успокаивается этим вторым — а оно без первого не делает ' +
    'ничего. ОДНО ИМЯ В ДВУХ ОБЪЯВЛЕНИЯХ — ЭТО ДВА РАЗНЫХ ПРАВИЛА.');

правило('работа видна диктору',
    /setAttribute\('aria-busy', 'true'\)/.test(тело),
    'нет aria-busy — для диктора ничего не происходит');

правило('запертое отпускается на удачном пути',
    (тело.match(/отпустить\(\)/g) || []).length >= 2,
    'отпускание зовётся меньше двух раз — один из путей оставит группу запертой');

правило('отпускание снимает всё, что надело',
    /отпустить = function\(\)[\s\S]{0,400}disabled = false[\s\S]{0,300}removeAttribute\('aria-busy'\)[\s\S]{0,200}classList\.remove\('ad-grp-busy'\)/.test(тело),
    'отпускание снимает не всё — часть признака останется навсегда');

/* ── 2. причина не спрашивается ──────────────────────────────────────── */
правило('причина больше не спрашивается',
    !/window\.prompt\s*\(\s*L\.groupPlaceWhy/.test(код),
    'спрос причины вернулся — помеха без пользы, журнала для неё нет');

правило('мёртвой подписи не осталось',
    !/groupPlaceWhy/.test(слова),
    'в словаре осталась подпись groupPlaceWhy, которую никто не зовёт');

/* ── 3. след остаётся ────────────────────────────────────────────────── */
/* УСЛОВИЕ ЛОВИТСЯ ЛЮБОЕ, А НЕ ТОЛЬКО ПРЕЖНЕЕ. Первая редакция искала
   ровно `if (причина)` — то самое условие, которое мы и снимали. Прувер
   подставил `if (false)`, и правило смолчало. ПРАВИЛО, ИЩУЩЕЕ ОДНО
   КОНКРЕТНОЕ УСЛОВИЕ, СТОРОЖИТ ЕГО ИМЯ, А НЕ ЕГО ОТСУТСТВИЕ. */
правило('след перестановки пишется всегда',
    /mgp\.__журнал\.push\(/.test(тело) &&
    !/\bif\s*\([^)]*\)\s*mgp\.__журнал\.push\(/.test(тело) &&
    !/\bif\s*\([^)]*\)\s*\{[^{}]{0,80}__журнал\s*=/.test(тело),
    'запись в журнал идёт под условием или пропала вовсе');

правило('в следе названы обе стороны перестановки',
    /было:\s*прежнее/.test(тело) && /стало:\s*newPlace/.test(тело) &&
    /напарник:/.test(тело),
    'след не называет, кто с кем поменялся местами — по нему ничего не восстановить');

const ВСЕГО = 10;
console.log('\n  ПЕРЕСТАНОВКА МЕСТА\n');
if (ошибки.length === 0) {
    console.log('  ок      все ' + ВСЕГО + ' правил держат\n');
    process.exit(0);
}
ошибки.forEach(о => {
    console.log('  НЕ ТАК  ' + о.имя);
    console.log('          ' + о.подсказка);
});
console.log('\n  НЕ ТАК  ' + ошибки.length + ' из ' + ВСЕГО + '\n');
process.exit(1);
