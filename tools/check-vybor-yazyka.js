/**
 * ЗАМОРОЗКА КУСКА 137 — ВЫБОР ЯЗЫКА ДЕЛАЕТСЯ ОДНИМ ЗОВОМ.
 *
 * ЧТО БЫЛО: 1151 тернарник по языку, из них 513 — полные тройки вида
 * `isEn ? A : isKg ? B : C`. Каждая тройка считается дважды и читается
 * тяжело; забыть в ней ветвь ничего не стоит, и именно так на сайте
 * появились 87 пар БЕЗ кыргызского (находка этого куска, см. трекер).
 *
 * 512 троек сведены к `KSLT_YAZYK.выбрать(en, kg, ru)` — дом заведён
 * куском 133. Осталось 127 тернарников: пары и редкие формы.
 *
 * СУФФИКС СТРАНИЦЫ УШЁЛ В ДОМ. Тринадцать зовов `выбрать('-en','-kg','')`
 * и своё чтение суффикса из пути в `session-monitor.js` — четырнадцать
 * определений одного понятия. Теперь `KSLT_YAZYK.суффикс`, одна строка.
 * ЗАОДНО ЭТО СНЯЛО ЕДИНСТВЕННОЕ ЗАКОННОЕ ПУСТОЕ ЗНАЧЕНИЕ: у русского
 * имени суффикса нет, и правило «ни одна ветвь не пуста» стало строгим
 * без исключений. Пустые ветви были не бедой, а подсказкой, где дом.
 *
 * ЕЩЁ СЕМЬ ФАЙЛОВ ПРИВЕДЕНЫ К ДОМУ: они читали язык из адреса в два
 * шага (`var p = pathname` … `p.indexOf('-en')`), и текстовое правило
 * куска 133 этой формы не видело — 18 мест в 9 файлах. Два из девяти
 * оставлены: `site-content.js` и `tournament-slots.js` побайтово делятся
 * с приложением, где дома нет; их держит правило в сторожe 133.
 *
 * ОДНА ТРОЙКА НЕ ТРОНУТА НАМЕРЕННО: в её ветвях есть вызов `.trim()`.
 * ТЕРНАРНИК ЛЕНИВ, А ВЫЗОВ ФУНКЦИИ — НЕТ: доводы зова вычисляются все
 * три, и перенос изменил бы поведение. Это проверено ПО ДЕРЕВУ — первая
 * проверка регуляркой приняла скобку ВНУТРИ СТРОКИ («Башталгыч (1.0–2.5)»)
 * за вызов и насчитала четырнадцать ложных.
 *
 *   node tools/check-vybor-yazyka.js
 */
const fs = require('fs');
const path = require('path');
const acorn = require('acorn');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const файлы = [];
(function обход(д) {
  fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
    const п = path.join(д, э.name);
    if (э.isDirectory()) { if (!/^(admin|node_modules)$/.test(э.name)) обход(п); }
    else if (э.name.endsWith('.js')) файлы.push(п);
  });
})('js');

function обойти(у, р, дело) {
  if (!у || typeof у.type !== 'string') return;
  дело(у, р);
  for (const к of Object.keys(у)) {
    if (к === 'type' || к === 'start' || к === 'end' || к === 'loc') continue;
    const v = у[к];
    if (Array.isArray(v)) v.forEach(x => x && typeof x.type === 'string' && обойти(x, у, дело));
    else if (v && typeof v.type === 'string') обойти(v, у, дело);
  }
}
function содержит(у, типы) {
  let да = false;
  обойти(у, null, x => { if (типы.indexOf(x.type) !== -1) да = true; });
  return да;
}

let тернарников = 0, зовов = 0, неразобран = 0, читателейСуффикса = 0;
const тройки = [], неТриДовода = [], сВызовом = [], пустыеВетви = [], суффиксМимоДома = [];
файлы.forEach(ф => {
  const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
  let д;
  try { д = acorn.parse(т, { ecmaVersion: 2020, locations: true }); }
  catch (e) { неразобран++; return; }
  обойти(д, null, (у, р) => {
    if (у.type === 'ConditionalExpression') {
      const усл = т.slice(у.test.start, у.test.end);
      if (!/\bis(?:En|Kg)\b/.test(усл)) return;
      тернарников++;
      /* полная тройка: isEn ? … : isKg ? … : … */
      if (усл.trim() === 'isEn' && у.alternate &&
          у.alternate.type === 'ConditionalExpression' &&
          т.slice(у.alternate.test.start, у.alternate.test.end).trim() === 'isKg') {
        /* ЛЕНЬ — ЕДИНСТВЕННАЯ ЗАКОННАЯ ПРИЧИНА ОСТАТЬСЯ ТЕРНАРНИКОМ:
           в ветви есть вызов, и перенос в зов вычислил бы ВСЕ ТРИ. */
        const ветви = [у.consequent, у.alternate.consequent, у.alternate.alternate];
        const лень = ветви.some(в => содержит(в, ['CallExpression', 'NewExpression',
                                                  'AwaitExpression', 'AssignmentExpression',
                                                  'UpdateExpression']));
        тройки.push({ где: path.basename(ф) + ':' + у.loc.start.line, лень: лень });
      }
      /* выбор суффикса страницы тернарником — мимо дома */
      const ветвиТ = [у.consequent, у.alternate];
      if (ветвиТ.some(в => в && в.type === 'Literal' && (в.value === '-en' || в.value === '-kg'))) {
        суффиксМимоДома.push(path.basename(ф) + ':' + у.loc.start.line + ' тернарник');
      }
      return;
    }
    if (у.type === 'MemberExpression' && т.slice(у.start, у.end) === 'KSLT_YAZYK.суффикс') {
      читателейСуффикса++;
      return;
    }
    if (у.type !== 'CallExpression' || !у.callee) return;
    if (т.slice(у.callee.start, у.callee.end) !== 'KSLT_YAZYK.выбрать') return;
    зовов++;
    const зн = у.arguments.map(a => a.type === 'Literal' ? a.value : undefined);
    if (зн[0] === '-en' || зн[1] === '-kg') {
      суффиксМимоДома.push(path.basename(ф) + ':' + у.loc.start.line + ' зов `выбрать`');
    }
    if (у.arguments.length !== 3) {
      неТриДовода.push(path.basename(ф) + ':' + у.loc.start.line + ' доводов ' + у.arguments.length);
      return;
    }
    у.arguments.forEach((д_, i) => {
      if (содержит(д_, ['CallExpression', 'NewExpression', 'AssignmentExpression',
                         'UpdateExpression', 'AwaitExpression'])) {
        сВызовом.push(path.basename(ф) + ':' + у.loc.start.line + ' довод ' + (i + 1));
      }
      if (д_.type === 'Literal' && д_.value === '') {
        пустыеВетви.push(path.basename(ф) + ':' + у.loc.start.line + ' довод ' + (i + 1));
      }
    });
  });
});

