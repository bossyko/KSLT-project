#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ПРЕДЕЛ ТЕСТА БОЛЬШЕ СУММЫ ЕГО ИМЕНОВАННЫХ ОЖИДАНИЙ» (01.11).
 *
 * ЗАЧЕМ ОН ЕСТЬ — СЛУЧАЙ, А НЕ ОПАСЕНИЕ. Проба «полоса Новостей листает»
 * падала пятнадцать раз подряд словами
 *
 *     Test timeout of 30000ms exceeded.
 *
 * и БОЛЬШЕ НИЧЕМ. Какое из четырёх ожиданий не дождалось — не сказано, и
 * разбирать нечего: внутри пробы стоят 15000 + 20000 + 15000 + 15000, то
 * есть 65000 при пределе 30000. Тест умирает раньше, чем успевает
 * провалиться первое же ожидание с ИМЕНЕМ.
 *
 * ОТКАЗ БЕЗ ИМЕНИ — ЭТО ПОТЕРЯННЫЙ ЧАС, А НЕ НЕУДОБСТВО. Именованное
 * ожидание говорит, ЧЕГО не дождались («#newsPagination .pl-page-btn»);
 * общий срок говорит только, что время вышло. Поэтому предел пробы обязан
 * быть БОЛЬШЕ суммы её собственных ожиданий — тогда первым падает то, что
 * умеет себя назвать.
 *
 * ПОЧЕМУ СУММА, А НЕ МАКСИМУМ. Ожидания в пробе идут ПОДРЯД, одно за
 * другим: открыть, дождаться дома, дождаться полосы, нажать, дождаться
 * второй страницы. В худшем случае каждое съедает свой срок целиком, и
 * верхняя граница — именно сумма.
 *
 * ПРЕДЕЛ ЧИТАЕТСЯ ИЗ ТОГО ЖЕ БЛОКА. `test.setTimeout(N)` стоит внутри
 * пробы, рядом с ожиданиями, которые он покрывает: ПРИЗНАК СТАВИТСЯ В ТОМ
 * БЛОКЕ, КОТОРЫЙ МЕРИМ. Общий `configure` на файл принимается как
 * запасной, а если нет и его — берётся предел из `playwright.config.js`.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ, И ЭТО НАЗВАНО. Прибор читает ЧИСЛА, написанные в
 * файле. Ожидание без своего срока (`waitForSelector` без `timeout`)
 * берёт срок из конфига, и в сумму здесь не попадает — такое место прибор
 * не видит. Не видит он и `expect(...).toPass()`, и сроки, собранные из
 * переменных.
 *
 *   node tools/check-predely-prob.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');

/* Предел по умолчанию читается из конфига, а не зашивается вторым
   числом: ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. */
function пределКонфига() {
    const п = path.join(КОРЕНЬ, 'playwright.config.js');
    if (!fs.existsSync(п)) return 30000;
    /* ВЕРХНИЙ УРОВЕНЬ, А НЕ ЛЮБОЙ `timeout:`. В конфиге их два: предел
       теста на верхнем уровне и предел `expect` внутри своего блока.
       Признак `^\s*timeout:` брал второй — 10000, — и прибор объявлял
       тесными десятки свободных проб. Поймано прувером. */
    const м = fs.readFileSync(п, 'utf8').match(/^ {4}timeout:\s*(\d+)/m);
    return м ? Number(м[1]) : 30000;
}

function файлы(д, вых) {
    вых = вых || [];
    const п = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(п)) return вых;
    for (const э of fs.readdirSync(п, { withFileTypes: true })) {
        const о = д + '/' + э.name;
        if (э.isDirectory()) файлы(о, вых);
        else if (э.name.endsWith('.spec.js')) вых.push(о);
    }
    return вых;
}

/**
 * Тело одной пробы — ПО СКОБКАМ, а не окном в N знаков.
 *
 * ДВЕ ЛОВУШКИ, ОБЕ ПОЙМАНЫ НА СЕБЕ 01.11:
 *   · ТЕЛО НАЧИНАЕТСЯ ПОСЛЕ СТРЕЛКИ. Первая `{` после `test(` — это
 *     разбор довода `async ({ page }) =>`, и счёт глубины от неё
 *     закрывает «блок» через четыре знака. Первая редакция дала РОВНО
 *     НОЛЬ мест на файле, где беда лежала открыто.
 *   · НИ ХВОСТА СЛЕВА, НИ ТОЧКИ. `\btest\(` мало: граница слова стоит и
 *     после точки, поэтому `/re/.test(т)` принималось за объявление
 *     пробы — два ложных места из семи.
 */
function пробы(т) {
    const вых = [];
    const re = /(?<![.\w$])test\(/g;
    let м;
    while ((м = re.exec(т))) {
        const стрелка = т.indexOf('=>', м.index);
        if (стрелка === -1) continue;
        const i = т.indexOf('{', стрелка);
        if (i === -1) continue;
        let гл = 0;
        for (let j = i; j < т.length; j++) {
            if (т[j] === '{') гл++;
            else if (т[j] === '}') {
                гл--;
                if (!гл) { вых.push({ начало: м.index, текст: т.slice(i, j + 1) }); break; }
            }
        }
    }
    return вых;
}

const ПО_УМОЛЧАНИЮ = пределКонфига();
const тесные = [];

for (const ф of файлы('tests/e2e')) {
    const т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
    const наФайл = т.match(/configure\(\s*\{[^}]*timeout:\s*(\d+)/);
    for (const б of пробы(т)) {
        const числа = [...б.текст.matchAll(/timeout:\s*(\d+)/g)].map(x => Number(x[1]));
        if (!числа.length) continue;
        const сумма = числа.reduce((a, b) => a + b, 0);
        const свой = б.текст.match(/test\.setTimeout\(\s*(\d+)/);
        const предел = свой ? Number(свой[1])
            : (наФайл ? Number(наФайл[1]) : ПО_УМОЛЧАНИЮ);
        /* РОВНО РАВНО — ЭТО ТОЖЕ ТЕСНО. Предел, совпавший с суммой,
           кончается в тот же миг, что и последнее ожидание, и кто
           сработает первым, решает случай. Правило говорит «больше». */
        if (сумма >= предел) {
            тесные.push({
                ф, строка: т.slice(0, б.начало).split('\n').length,
                предел, сумма, числа
            });
        }
    }
}

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('предел пробы больше суммы её именованных ожиданий',
    тесные.length === 0,
    'Так тесно: ' +
    тесные.sort((a, b) => (b.сумма - b.предел) - (a.сумма - a.предел))
        .map(о => '\n  ' + о.ф + ':' + о.строка + ' — предел ' + о.предел +
                  ', ожиданий ' + о.сумма + ' (' + о.числа.join(' + ') + ')').join('') +
    '\nТакая проба умирает по общему сроку РАНЬШЕ, чем падает первое\n' +
    'ожидание с именем, — и отчёт говорит «Test timeout», а чего не\n' +
    'дождались, не говорит. Поставь в самой пробе\n' +
    '`test.setTimeout(сумма + запас)`.');

правило('прибор читает пробы, а не всё подряд со словом test',
    (function () {
        /* ОБРАЗЕЦ ВНУТРЬ ПРИБОРА: он обязан РАЗЛИЧАТЬ, иначе «ноль мест»
           ничего не значит. Два ложных вида и один настоящий. */
        const о = "test('A', async ({ page }) => {\n" +
                  "  if (/x/.test(а)) return;\n" +
                  "  await page.waitForSelector('a', { timeout: 20000 });\n" +
                  "});\n" +
                  "test('B', async ({ page }) => {\n" +
                  "  await page.waitForSelector('b', { timeout: 10000 });\n" +
                  "});\n" +
                  "const latest = (x) => x;\n";
        const н = пробы(о);
        /* ДВЕ ПРОБЫ, НЕ ТРИ И НЕ ОДНА. Ложное совпадение на `.test(а)`
           берёт стрелку СЛЕДУЮЩЕЙ пробы и приписывает себе ЕЁ тело —
           так образец и различает: при слабом признаке блоков станет три.
           Первая редакция образца этого не ловила: `.test(а)` стоял
           последним, и за ним не было стрелки с телом вовсе. */
        if (н.length !== 2) return false;
        if (о.slice(н[0].начало, н[0].начало + 9) !== "test('A',") return false;
        if (о.slice(н[1].начало, н[1].начало + 9) !== "test('B',") return false;
        const первой = [...н[0].текст.matchAll(/timeout:\s*(\d+)/g)].map(x => Number(x[1]));
        const второй = [...н[1].текст.matchAll(/timeout:\s*(\d+)/g)].map(x => Number(x[1]));
        return первой.length === 1 && первой[0] === 20000 &&
               второй.length === 1 && второй[0] === 10000;
    })(),
    'Образец внутри прибора: одна проба с двумя ожиданиями, рядом `.test(`\n' +
    'и `latest`. Прибор обязан найти РОВНО одну пробу и оба её срока.\n' +
    'Не находит — значит «ноль тесных мест» он скажет и на беде.');

правило('предел по умолчанию взят из конфига, а не зашит',
    /^ {4}timeout:\s*\d+/m.test(fs.readFileSync(
        path.join(КОРЕНЬ, 'playwright.config.js'), 'utf8')),
    'Число 30000 живёт в `playwright.config.js`. Зашить его вторым\n' +
    'числом сюда — значит развести два определения одного понятия: на\n' +
    'первой правке конфига прибор начнёт мерить по старому.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      пределы проб: все ' + всего + ' правил держатся');
    console.log('          предел по умолчанию ' + ПО_УМОЛЧАНИЮ + ', тесных проб 0');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  пределы проб — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
