/**
 * ЗАГОЛОВОК ОКНА — ОДНО ОПРЕДЕЛЕНИЕ, ПАРА НА СТУПЕНЬ. Круг 13 ветки D, 18.10.
 *
 * ЧТО БЫЛО. «Заголовок окна» — одно понятие, а определений два, и между
 * ними ТРИ расхождения: окно подтверждения 18 / вес 600, обычное окно
 * 16 / вес 700 (вес браузерный, у `h3`, его никто не задавал). Пара
 * «заголовок + тело» стояла у подтверждения на ДВЕ ступени (18 -> 14), у
 * обычного на одну. Запись трекера знала про две ступени, но не знала ни
 * про второе определение, ни про разные веса.
 *
 * А ПО ВСЕМУ ПРОДУКТУ ЗАГОЛОВОК ОКНА НАПИСАН ЧЕТЫРЬМЯ СПОСОБАМИ:
 * админка (сведена кругом 13), `.pt-modal-title` в `style.css`
 * (`clamp(1.05rem, 4.6vw, 1.2rem)` — плавный кегль мимо всякой шкалы, вес
 * 800, межстрочный 1.3 числом) и `.auth-modal-title` (21 / вес 700).
 * Публичная часть — ВНЕ блока этого куска, поэтому она под ХРАПОВИКОМ:
 * вычистить нельзя, но пятое написание не заведётся молча.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ, А НЕ ЧИСЛО. Не «заголовок 18», а: заголовок
 * окна объявлен ОДИН раз на все окна админки; пара «заголовок + тело»
 * отстоит РОВНО на одну ступень шкалы кеглей; вес берётся у системы;
 * межстрочный — ступенью. Какие именно кегли — решает замер.
 *
 *   node tools/check-lestnica-okna.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чисто = п => fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));
const admin = чисто('css/admin.css');
const style = чисто('css/style.css');
const tokens = чисто('css/tokens.css');

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}
const строка = (т, поз) => т.slice(0, поз).split('\n').length;

/* ---- ШКАЛА КЕГЛЕЙ ИЗ ТОКЕНОВ, а не из моей памяти ---- */
const ШКАЛА = [];
{
    const р = /(--fs-(?:2xs|xs|sm|base|md|lg|xl|2xl|3xl|4xl))\s*:\s*([\d.]+)rem/g;
    let м;
    while ((м = р.exec(tokens))) {
        if (!ШКАЛА.some(с => с.имя === м[1])) ШКАЛА.push({ имя: м[1], px: +м[2] * 16 });
    }
    ШКАЛА.sort((а, б) => а.px - б.px);
}
const ступень = имя => ШКАЛА.findIndex(с => с.имя === имя);

/* ---- блоки и их свойства ---- */
function свойство(текст, селектор, св) {
    const р = /([^{}\n][^{}]*?)\{([^{}]*)\}/g;
    let м, найдено = null;
    while ((м = р.exec(текст))) {
        const сел = м[1].trim();
        const есть = сел.split(',').some(ч => ч.trim() === селектор);
        if (!есть) continue;
        const з = м[2].match(new RegExp(св + '\\s*:\\s*([^;]+)'));
        if (з) найдено = { знач: з[1].trim(), стр: строка(текст, м.index), сел };
    }
    return найдено;
}

/* ПРАВИЛО 1. Заголовок окна объявлен ОДНИМ правилом на оба окна. */
const общий = /\.ad-confirm-title\s*,\s*\n?\s*\.ad-modal-header h3\s*\{/.test(admin) ||
              /\.ad-modal-header h3\s*,\s*\n?\s*\.ad-confirm-title\s*\{/.test(admin);
правило('заголовок окна объявлен одним правилом на все окна',
    общий,
    'Заголовок окна снова определён порознь: `.ad-confirm-title` и\n' +
    '`.ad-modal-header h3` должны стоять в ОДНОМ правиле. Пока их два,\n' +
    'они разойдутся — так и вышло: 18 против 16, вес 600 против 700.');

/* ПРАВИЛО 2. Пара «заголовок + тело» — РОВНО одна ступень шкалы.
   Это и есть замороженное отношение: не числа, а расстояние между ними. */
const зТ = свойство(admin, '.ad-confirm-title', 'font-size');
const тТ = свойство(admin, '.ad-confirm-text', 'font-size');
const тН = свойство(admin, '.ad-modal-note', 'font-size');
const токен = з => (з && з.знач.match(/var\((--fs-[a-z0-9-]+)\)/) || [])[1];
const пары = [
    ['окно подтверждения', токен(зТ), токен(тТ)],
    ['обычное окно', токен(зТ), токен(тН)]
];
const кривые = пары.filter(([, з, т]) => {
    if (!з || !т) return true;
    const д = ступень(з) - ступень(т);
    return д !== 1;
});
правило('пара «заголовок окна + тело» отстоит ровно на ступень',
    кривые.length === 0,
    'Пара разъехалась: ' + кривые.map(([имя, з, т]) =>
        имя + ' (' + (з || '?') + ' против ' + (т || '?') + ', ступеней ' +
        (з && т ? Math.abs(ступень(з) - ступень(т)) : '?') + ')').join('; ') + '.\n' +
    'Шкала кеглей: ' + ШКАЛА.map(с => Math.round(с.px)).join(' · ') + '.\n' +
    'ЗАМОРОЖЕНО ОТНОШЕНИЕ, А НЕ ЧИСЛО: кегли можно менять, расстояние\n' +
    'между заголовком и телом — ровно одна ступень.');

/* ПРАВИЛО 3. Вес заголовка окна — из системы, а не числом и не от браузера. */
const вес = свойство(admin, '.ad-confirm-title', 'font-weight');
правило('вес заголовка окна берётся у системы',
    !!(вес && /var\(--fw-/.test(вес.знач)),
    'Вес заголовка окна: ' + (вес ? вес.знач + ' (строка ' + вес.стр + ')' : 'не задан') + '.\n' +
    'Ступени веса объявлены в `tokens.css` (--fw-medium, --fw-semibold,\n' +
    '--fw-bold). Не задать вес вовсе — тоже беда: у `h3` он браузерный 700,\n' +
    'и обычное окно оказалось ЖИРНЕЕ окна подтверждения.');

/* ПРАВИЛО 4. Межстрочный тела окна — ступенью лестницы, не числом. */
const мж = свойство(admin, '.ad-modal-note', 'line-height');
правило('межстрочный тела окна стоит ступенью лестницы',
    !!(мж && /var\(--lh-/.test(мж.знач)),
    'Межстрочный тела окна: ' + (мж ? мж.знач + ' (строка ' + мж.стр + ')' : 'не задан') + '.\n' +
    'Лестница межстрочных: --lh-none · --lh-tight · --lh-snug · --lh-normal\n' +
    '· --lh-relaxed. Было `1.5` числом — это ровно --lh-normal.');

/* ПРАВИЛО 5. ХРАПОВИК НА ВЕСЬ ПРОДУКТ. Написаний заголовка окна не
   больше замеренного: админка свела своё, публичная часть ждёт очереди.
   ЗАМЕРЕНО 18.10: три — одно в админке, `.pt-modal-title` и
   `.auth-modal-title` в `style.css`. */
const ПОТОЛОК_НАПИСАНИЙ = 3;
const написания = [];
[['css/admin.css', admin], ['css/style.css', style]].forEach(([имя, текст]) => {
    const р = /([^{}\n][^{}]*?)\{([^{}]*)\}/g;
    let м;
    while ((м = р.exec(текст))) {
        const сел = м[1].trim();
        if (!/(modal|okno)[^{,]*(title|header\s+h[1-6])/i.test(сел)) continue;
        if (!/font-size\s*:/.test(м[2])) continue;
        /* СЧИТАЕМ СЕЛЕКТОРЫ, А НЕ ОБЪЯВЛЕНИЯ: `.pt-modal-title` объявлен
           дважды — база и медиа, — но это ОДНО написание понятия, а не
           два. Первая редакция считала объявления и дала 4 там, где
           написаний 3: число берётся у прибора, а прибор должен мерить
           то, что названо. */
        const ключ = сел.split(',')[0].trim().slice(0, 40);
        if (!написания.some(н => н.сел === ключ)) {
            написания.push({ сел: ключ, где: имя + ':' + строка(текст, м.index) });
        }
    }
});
правило('написаний заголовка окна не больше потолка',
    написания.length <= ПОТОЛОК_НАПИСАНИЙ,
    'Заголовок окна написан ' + написания.length + ' раз, потолок ' +
    ПОТОЛОК_НАПИСАНИЙ + ':\n  ' + написания.map(н => н.где + ' ' + н.сел).join('\n  ') + '\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. Админка сведена кругом 13;\n' +
    'публичная часть под храповиком — вычистить нельзя, но новое\n' +
    'написание не заведётся молча.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      лестница окна: 5 правил');
    console.log('          заголовок окна объявлен один раз на все окна админки');
    console.log('          пара «заголовок + тело»: ' + (токен(зТ) || '?') + ' / ' +
                (токен(тТ) || '?') + ' — ровно ступень');
    console.log('          вес из системы, межстрочный ступенью');
    console.log('          написаний по продукту ' + написания.length +
                ' (потолок ' + ПОТОЛОК_НАПИСАНИЙ + ')');
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  лестница окна — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
