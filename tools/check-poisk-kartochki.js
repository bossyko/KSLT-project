#!/usr/bin/env node
/**
 * ПОИСК КАРТОЧКИ ИГРОКА — ОДИН ДОМ, И ОН ЗОВЁТСЯ ОТОВСЮДУ.
 *
 * ЗАЧЕМ. Искать карточку по имени нужно в двух местах: кабинет («кажется,
 * это ваша карточка») и админка (перед тем как заводить новую). До 13.11
 * первый умел это по-своему, а второй не умел вовсе — форма только
 * СОЗДАВАЛА, уникализируя id суффиксом «-2». Так рождались дубли, и за
 * одни сутки их пришлось разбирать в базе дважды (Атаханов, Джумабаев).
 *
 * Правило держит ОТНОШЕНИЕ, а не строку: приём один, живёт в доме, и оба
 * зовущих берут его оттуда. Второе написание — это будущее расхождение.
 *
 * Запуск: node tools/check-poisk-kartochki.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_ROOT || path.join(__dirname, '..');
const ДОМ = 'js/kslt-poisk-kartochki.js';
const КАБИНЕТ = 'js/dashboard.js';
const АДМИНКА = 'js/admin/sections/users.js';

const ошибки = [];
const ок = [];
function правило(имя, держится, почему) {
    if (держится) ок.push(имя); else ошибки.push({ имя, почему });
}

const читать = (ф) => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = (т) => т.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/[^\n]*$/gm, '');

const дом = безКом(читать(ДОМ));
const кабинет = безКом(читать(КАБИНЕТ));
const админка = безКом(читать(АДМИНКА));

правило('дом поиска отдаёт обратную раскладку и сам поиск',
    /К\.обратно\s*=\s*function/.test(дом) && /К\.искать\s*=\s*async function/.test(дом) &&
    /window\.KSLT_KARTOCHKA\s*=\s*К/.test(дом),
    'Дом перестал отдавать одно из двух. Зовущие держатся за имена\n' +
    '`KSLT_KARTOCHKA.обратно` и `KSLT_KARTOCHKA.искать`.');

правило('занятые карточки не показываются вовсе',
    /\.eq\('has_account',\s*false\)/.test(дом) && /\.eq\('is_guest',\s*false\)/.test(дом),
    'Из поиска убран отбор по has_account или is_guest. Предложить\n' +
    'занятую карточку — значит предложить чужую: за ней уже стоит\n' +
    'учётная запись с её рейтингом и историей.');

/* ВТОРОЕ НАПИСАНИЕ — ЭТО БУДУЩЕЕ РАСХОЖДЕНИЕ. Таблица обратной раскладки
   жила в кабинете; если она вернётся туда или заведётся в админке, два
   поиска начнут отвечать по-разному на одно имя. */
const своиТаблицы = [[КАБИНЕТ, кабинет], [АДМИНКА, админка]]
    /* БЕЗ \b ПЕРЕД КИРИЛЛИЦЕЙ. `\b` в JS считает границу слова по ASCII:
       перед «Л» её нет вовсе, и признак с `\bЛАТ` не находит ничего —
       поймано своим же откатом, который не уронил правило. */
    .filter(([, т]) => /(?:^|[^\wА-Яа-яЁё])ЛАТ\s*=\s*\{|(?:^|[^\wА-Яа-яЁё])ПАРЫ\s*=\s*\[\[/.test(т))
    .map(([ф]) => ф);
правило('таблицы раскладки нет нигде, кроме дома',
    своиТаблицы.length === 0,
    'Своя таблица раскладки завелась в: ' + своиТаблицы.join(', ') + '\n' +
    'Два поиска по одному имени ответят по-разному в тот день, когда\n' +
    'правят одну из таблиц.');

правило('кабинет ищет через дом',
    /window\.KSLT_KARTOCHKA\.искать\(client,/.test(кабинет),
    'Кабинет снова ищет карточки сам. Приём обязан приходить из дома.');

/* ГЛАВНОЕ ПРАВИЛО КУСКА: создание — не единственный путь. */
правило('админка ищет двойников ПЕРЕД тем, как заводить новую',
    /window\.KSLT_KARTOCHKA\.искать\(A\.client,/.test(админка) &&
    админка.indexOf('KSLT_KARTOCHKA.искать') < админка.indexOf("from('players').insert("),
    'Форма пользователя снова заводит карточку, не посмотрев, нет ли\n' +
    'такой же. Именно так родилась вторая карточка Атаханова: имя в\n' +
    'профиле латиницей дало другой slug, и проверка уникальности\n' +
    'промолчала.');

правило('у админа есть путь привязать, а не только создать',
    /update\(\{ player_id: выбор \}\)/.test(админка) &&
    /L\.usrPrivyazat/.test(админка) && /L\.usrVsyoRavnoNovuyu/.test(админка),
    'Пропал путь «привязать к существующей». Тогда у админа снова один\n' +
    'выход — завести новую, и дубль рождается молча.');

правило('молчаливого пути из окна нет',
    /закрыть\('cancel'\)/.test(админка) && /закрыть\('new'\)/.test(админка) &&
    /выбор === 'cancel'/.test(админка),
    'У окна выбора появился путь, который ничего не говорит вызвавшему.\n' +
    'Ошибка здесь стоит чужого рейтинга — ответ обязан быть явным.');

const страницы = ['pages/dashboard.html', 'pages/dashboard-en.html',
                  'pages/dashboard-kg.html', 'pages/admin.html'];
const безДома = страницы.filter(ф => !/kslt-poisk-kartochki\.js/.test(читать(ф)));
правило('дом подключён на всех страницах, где его зовут',
    безДома.length === 0,
    'Нет дома на: ' + безДома.join(', ') + '\n' +
    'Страница позовёт KSLT_KARTOCHKA и получит «не определено» — поиск\n' +
    'молча перестанет работать.');

console.log('');
ок.forEach(и => console.log('  ок      ' + и));
ошибки.forEach(о => console.log('\n  НЕ ТАК  ' + о.имя + '\n          ' + о.почему.split('\n').join('\n          ')));
console.log('');
if (ошибки.length) { console.log('  Поиск карточки: не сошлось ' + ошибки.length + '\n'); process.exit(1); }
console.log('  ок      поиск карточки: ' + ок.length + ' правил, зовущих дом мест 2\n');
