/**
 * ЗАМОРОЗКА: МЕСТО В РЕЙТИНГЕ — ОДИН СПИСОК НА ПРОДУКТ.
 *
 * Беда 02.10, боевой CHALLENGERS. В листе ожидания гостю Баитикову Аделу
 * выписано «место 161», а публичный рейтинг категории показывает 105
 * человек. Числа 161 не существует нигде, кроме этой колонки.
 *
 * ПРАВИЛО МЕСТА БЫЛО ОДНО — `KSLT_RULES.рейтингКатегории`. Разошёлся ВХОД:
 * публичная таблица отбрасывала гостей своей строкой
 * (`rankings-data.js:53`), а `местаВКатегории` в админке поле `is_guest`
 * даже не запрашивала. Замер: 162 строки против 105, разница — 57 гостей,
 * из них с очками один.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ: «кого нет в рейтинге, у того нет и места». Признак
 * один — `KSLT_RULES.вРейтинге`, спрашивают его обе стороны, и сам отбор
 * живёт внутри `рейтингКатегории`: мимо него список не собрать.
 *
 * Гость — карточка без человека: публичной страницы, кабинета и места в
 * рейтинге у неё нет (решение Кости 30.09).
 *
 *   node tools/check-mesto-v-reytinge.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ПРАВИЛА = чит('js/kslt-rules.js');
const ПРч = безКом(ПРАВИЛА);
const РЕЙТИНГ = безКом(чит('js/rankings-data.js'));
const СЕТч = безКом(чит('js/admin/sections/bracket.js'));

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

function тело(текст, имя) {
    const i = текст.indexOf(имя);
    if (i === -1) return '';
    let гл = 0, j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}

/* ── 1. ПРИЗНАК ОДИН ─────────────────────────────────────────────────── */
правило('вРейтинге объявлена ровно один раз',
    (ПРч.match(/R\.вРейтинге\s*=\s*function/g) || []).length === 1,
    'признак «стоит ли карточка в рейтинге» снова определён дважды. ' +
    'Именно на этом шве и родилась беда: админка считала по одному списку, ' +
    'публичная страница — по другому');

правило('вРейтинге отбивает гостя',
    /!!\s*карточка\s*&&\s*!карточка\.is_guest/.test(тело(ПРч, 'R.вРейтинге')),
    '`вРейтинге` перестала смотреть на `is_guest`. Гость — карточка без ' +
    'человека: места в рейтинге у неё нет (решение Кости 30.09)');

/* ── 2. ОТБОР ВНУТРИ РАСЧЁТА, А НЕ СНАРУЖИ ───────────────────────────
   Если отсев оставить вызывающим, кто-нибудь однажды забудет — ровно так
   и было. Внутри `рейтингКатегории` мимо него список не собрать. */
const РАСЧЁТ = тело(ПРч, 'R.рейтингКатегории');
правило('рейтингКатегории сама спрашивает вРейтинге',
    /if\s*\(\s*!R\.вРейтинге\(и\)\s*\)\s*return false/.test(РАСЧЁТ),
    'отсев тех, кого нет в рейтинге, ушёл из `рейтингКатегории` наружу. ' +
    'Снаружи его забудут: так админка и выписала гостю место 161');

правило('в таблицу входит домашний или набравший очки',
    /и\.category_id === катId \|\| \(в\[и\.id\] \|\| 0\) > 0/.test(РАСЧЁТ),
    'правило состава таблицы категории изменилось. В неё входит тот, у ' +
    'кого она домашняя, и тот, кто пришёл со стороны и набрал в ней очки');

/* ── 3. ОБЕ СТОРОНЫ ЗОВУТ ОБЩЕЕ ──────────────────────────────────────── */
правило('публичный рейтинг зовёт общий признак',
    /KSLT_RULES\.вРейтинге\(p\)/.test(РЕЙТИНГ),
    'в `rankings-data.js` вернулась своя строка отсева гостей. Копия ' +
    'разойдётся с админкой так же, как разошлась 02.10');

правило('админка спрашивает is_guest у карточек',
    (СЕТч.match(/select\('id, gender, category_id, ntrp_singles, is_guest'\)/g) || []).length === 2,
    '`местаВКатегории` перестала запрашивать `is_guest` хотя бы в одном ' +
    'из двух чтений `players`. Без поля `вРейтинге` не отличит гостя, и ' +
    'место снова посчитается по списку, которого нет нигде');

/* ── 4. МЕСТО СЧИТАЕТ ОДНА ФУНКЦИЯ ───────────────────────────────────── */
правило('место в категории считают только через общее правило',
    (СЕТч.match(/KSLT_RULES\.рейтингКатегории\(/g) || []).length >= 1 &&
    !/sort\([^)]*\)\s*\.map\([^)]*\)\s*;\s*\/\/\s*своё место/.test(СЕТч),
    'в админке завёлся свой счёт места мимо `KSLT_RULES.рейтингКатегории`');

/* ── вывод ───────────────────────────────────────────────────────────── */
if (ошибки.length) {
    console.log('✗ Место в рейтинге: ' + ошибки.length + ' правил упало\n');
    ошибки.forEach(о => console.log('  • ' + о.имя + '\n    ' + о.подсказка + '\n'));
    process.exit(1);
}
console.log('✓ Место в рейтинге — один список на продукт: все правила держат');
