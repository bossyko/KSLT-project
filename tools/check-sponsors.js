/* ЯКОРЬ, ДЕРЖАЩИЙСЯ НА ПОРЯДКЕ СВОЙСТВ, СЛЕПНЕТ ОТ ЛЮБОЙ ВСТАВКИ (11.11).
   Правило требовало `height` ПЕРВОЙ строкой блока. Переделка окна 11.11
   дописала выше `flex-shrink: 0` — высота осталась той же, ступень та же,
   а правило упало и назвало беду, которой нет. Теперь признак читает ТЕЛО
   блока и ищет свойство где угодно внутри него. Имя блока берётся с
   границей, иначе `.spon-modal-close` поймала бы соседа
   `.spon-modal-close-btn`. */
const тело = сел => {
    const м = СТИ.match(new RegExp('(?:^|[\\s,}])' +
        сел.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{([^}]*)\\}'));
    return м ? м[1] : '';
};
правило('крестик и «Закрыть» — высотой-свойством и не ниже порога',
    /width: var\(--btn-h-md\)/.test(тело('.spon-modal-close')) &&
    /height: var\(--btn-h-md\)/.test(тело('.spon-modal-close')) &&
    /height: var\(--btn-h-md\)/.test(тело('.spon-modal-close-btn')),
    'Было 22 × 32 и 99 × 36: крестик уже даже минимума 24 из WCAG 2.5.8,\n' +
    '          а кнопка ниже порога 44 — на кнопке, которой закрывают окно.');

правило('у окна есть кольцо фокуса на всех трёх видах управления',
    /\.spon-modal-close:focus-visible,\s*\.spon-modal-close-btn:focus-visible,\s*\.spon-modal-action:focus-visible \{[^}]*outline: (?:3px|var\(--bw-heavy\))/.test(СТИ),
    'Крестик, кнопка и строки действий.');

