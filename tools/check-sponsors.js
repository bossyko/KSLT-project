/**
 * ЗАМОРОЗКА СЕКЦИИ СПОНСОРОВ `#sponsors` НА ГЛАВНОЙ И ОКНА СПОНСОРА.
 *
 * Доски 73:9 (три концепта) и 285:9 (цели нажатия, фокус, окно).
 * Решения Кости 24.09: вариант C — равные плитки; генеральный той же плитки,
 * просто выше, без лайма; порядок среди равных случайный.
 *
 * ЗАМОРАЖИВАЮТСЯ ОТНОШЕНИЯ:
 *   • все плитки одного размера на каждом виде — равенство спонсоров
 *     держит коробка, а не логотип;
 *   • цель нажатия — вся плитка, и она выше порога на каждом слое;
 *   • перемешивание одно на весь список, а не своё в каждом блоке;
 *   • окно объявляет себя окном и запирает страницу под собой.
 *
 *   node tools/check-sponsors.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СТИ = безКом(чит('css/style.css'));
const ЗАГ = чит('js/sponsors-loader.js');
const ЗАГчист = безКом(ЗАГ);
const СТР = { ru: чит('index.html'), en: чит('index-en.html'), kg: чит('index-kg.html') };

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };
const сколько = (т, р) => (т.match(р) || []).length;

/* ══ ГДЕ ЖИВЁТ СЕКЦИЯ ═════════════════════════════════════════════════════ */

const нач = СТИ.indexOf('.sponsor-hero {');
const кон = СТИ.indexOf('.spon-modal-overlay {');
правило('секция лежит одним куском',
    нач > 0 && кон > нач,
    'Не нашёл границы: от .sponsor-hero до .spon-modal-overlay.');
const БЛОК = нач > 0 && кон > нач ? СТИ.slice(нач, кон) : '';

/* ══ РАВЕНСТВО ПЛИТОК ═════════════════════════════════════════════════════ */

правило('плитка одна на всех троих: генеральный, ссылка и статичный логотип',
    /\.sponsor-hero-logo,\s*\.sponsors-cloud \.sponsor-logo-link,\s*\.sponsors-cloud \.spon-static \{/.test(БЛОК),
    'Генеральный отличается подписью и своей строкой, а не размером —\n' +
    '          решение Кости 24.09. Логотип без ссылок тоже стоит в такой же\n' +
    '          коробке, иначе ряд идёт рваный.');

правило('у плитки есть своя поверхность: заливка, контур и радиус',
    /flex: 0 0 calc\(/.test(БЛОК) && /background: var\(--bg-card\)/.test(БЛОК) &&
    /border: 1px solid var\(--border-subtle\)/.test(БЛОК) && /border-radius: var\(--radius-lg\)/.test(БЛОК),
    'До 24.09 плиток не было вовсе: в ряд стояли сами логотипы. Замерено на\n' +
    '          1280 — ширина от 39 до 140 при одной высоте 44, то есть вес на\n' +
    '          экране втрое разный. Не потому, что кто-то больше заплатил, а\n' +
    '          потому, что логотип вытянутый.');

правило('потолок логотипа внутри плитки один на всех',
    /\.sponsor-hero-logo img,\s*\.sponsors-cloud \.sponsor-logo-link img,\s*\.sponsors-cloud \.spon-static img \{[\s\S]{0,200}max-width: 70%[\s\S]{0,60}max-height: 58%/.test(БЛОК),
    'Иначе равные коробки снова дадут неравный вес.');

правило('ряд заполняется целиком, последний неполный встаёт по центру',
    /\.sponsors-cloud \{[\s\S]{0,200}flex-wrap: wrap[\s\S]{0,120}justify-content: center/.test(БЛОК),
    'Кирпичная кладка — вариант C — получается из ЧИСЛА карточек: когда их\n' +
    '          не делится на число колонок, нижний ряд сам оказывается со\n' +
    '          смещением. Рисовать её отдельно не нужно.');

/* ══ ЦЕЛЬ НАЖАТИЯ И ФОКУС ═════════════════════════════════════════════════ */

const высоты = (БЛОК.match(/height: (\d+)px/g) || []).map(s => Number(s.match(/\d+/)[0]));
правило('высота плитки выше порога нажатия на каждом слое',
    высоты.length >= 3 && высоты.every(в => в >= 44),
    'Найдено: ' + высоты.join(' · ') + '\n' +
    '          До 24.09 целью был сам логотип: «STRETCH» давал 39 в ширину.');

правило('у плитки есть кольцо фокуса',
    /\.sponsors-cloud \.sponsor-logo-link:focus-visible,\s*\.sponsor-hero-logo:focus-visible \{[^}]*outline: 3px/.test(БЛОК),
    'Десять целей были недостижимы глазом с клавиатуры. WCAG 2.4.7.');

правило('движение гасится по просьбе системы',
    /@media \(prefers-reduced-motion: reduce\) \{[\s\S]{0,300}\.sponsors-cloud \.sponsor-logo-link:hover \{ transform: none/.test(БЛОК),
    'Плитка поднимается при наведении — гасим и переход, и сдвиг.');

/* ══ ЛАЙМ ═════════════════════════════════════════════════════════════════ */

правило('лайма в секции нет нигде, кроме кольца фокуса',
    !/color: var\(--accent\)/.test(БЛОК),
    'Подпись «Генеральный спонсор» была лаймовой. Правило 109:370: лайм\n' +
    '          принадлежит одному действию в поле зрения, и это кнопка\n' +
    '          «Подробнее о спонсорстве» прямо над секцией.');

/* ══ ГРАНИЦЫ ══════════════════════════════════════════════════════════════ */

const ширины = [...new Set((БЛОК.match(/max-width:\s*(\d+)px/g) || []).map(s => s.match(/\d+/)[0]))];
правило('в секции нет ни одной ширины, кроме 640 и 992',
    ширины.every(ш => ш === '640' || ш === '992'),
    'Найдено: ' + ширины.join(' · ') + '\n' +
    '          Было 768 — граница не из лестницы.');

/* ══ МЁРТВОЕ ══════════════════════════════════════════════════════════════ */

правило('мёртвого семейства .main-sponsor больше нет',
    !/\.main-sponsor/.test(СТИ),
    'Шесть правил на 46 строк: ни в одном html, ни в одном js класса не было.\n' +
    '          Проверено поиском по всем файлам, а не по виду.');

/* ══ ПОРЯДОК ══════════════════════════════════════════════════════════════ */

правило('перемешивание одно, и стоит там, где список приходит из базы',
    /_cache = главные\.concat\(прочие\)/.test(ЗАГчист) && сколько(ЗАГчист, /Math\.random\(\)/g) === 1,
    'Логотипы выводятся дважды — карусель в шапке и секция внизу. Если\n' +
    '          каждый перетасует сам, на одном экране будут два разных порядка,\n' +
    '          и это читается не как случайность, а как поломка.');

правило('генеральный в перемешивание не попадает',
    /список\.forEach\(function\(s\) \{ \(s\.is_hero \? главные : прочие\)\.push\(s\); \}\)/.test(ЗАГчист),
    'Он платит за первое место, а не за случайное.');

правило('у карусели больше нет своей сортировки',
    !/sort\(function\(a, b\)/.test(ЗАГчист),
    'Секция брала sort_order по возрастанию, карусель тем же полем по\n' +
    '          убыванию: один список выстроен наоборот в двух местах.');

/* ══ ОКНО СПОНСОРА ════════════════════════════════════════════════════════ */

правило('окно объявляет себя окном и называет себя',
    /role="dialog" aria-modal="true" aria-label=/.test(ЗАГчист),
    'Не было ни role, ни aria-modal, ни метки: окно открывалось, а для\n' +
    '          чтения с экрана ничего не происходило.');

правило('страница под окном заперта',
    /document\.body\.style\.overflow = 'hidden'/.test(ЗАГчист) &&
    /document\.body\.style\.overflow = overlay\._былОтступ/.test(ЗАГчист),
    'Было overflow: visible — фон листался под модалкой.');

правило('фокус уходит внутрь окна и возвращается тому, кто открыл',
    /первый\.focus\(\)/.test(ЗАГчист) && /overlay\._вернутьФокус\.focus\(\)/.test(ЗАГчист),
    'activeElement оставался BODY: с клавиатуры человек продолжал табать\n' +
    '          страницу ПОД окном, а после закрытия оказывался в начале.');

правило('Escape закрывает окно, и слушатель снимается при закрытии',
    /if \(e\.key === 'Escape'\) \{ closeSponsorModal\(overlay\); \}/.test(ЗАГчист) &&
    /overlay\._снятьEscape\(\)/.test(ЗАГчист),
    'Обработчика не было вовсе. На доске 285:9 записано, что Escape\n' +
    '          закрывает и это проверено настоящим нажатием — проверен был\n' +
    '          боковой лист, а не это окно. Нашёл Playwright 24.09.\n' +
    '          Слушатель обязан сниматься: иначе каждое открытие вешает новый.');

правило('табуляция не выходит за пределы открытого окна',
    /e\.key !== 'Tab'/.test(ЗАГчист) && /shiftKey/.test(ЗАГчист),
    'Ловушка фокуса — вторая половина того же требования.');

правило('крестик и «Закрыть» — высотой-свойством и не ниже порога',
    /\.spon-modal-close \{[\s\S]{0,400}width: var\(--btn-h-md\);\s*height: var\(--btn-h-md\)/.test(СТИ) &&
    /\.spon-modal-close-btn \{\s*height: var\(--btn-h-md\)/.test(СТИ),
    'Было 22 × 32 и 99 × 36: крестик уже даже минимума 24 из WCAG 2.5.8,\n' +
    '          а кнопка ниже порога 44 — на кнопке, которой закрывают окно.');

правило('у окна есть кольцо фокуса на всех трёх видах управления',
    /\.spon-modal-close:focus-visible,\s*\.spon-modal-close-btn:focus-visible,\s*\.spon-modal-action:focus-visible \{[^}]*outline: 3px/.test(СТИ),
    'Крестик, кнопка и строки действий.');

/* ══ РАЗМЕТКА, ТРИ ЯЗЫКА ══════════════════════════════════════════════════ */

for (const [яз, html] of Object.entries(СТР)) {
    правило('секция спонсоров на месте · ' + яз,
        /<section id="sponsors" class="section-sponsors-compact"><\/section>/.test(html),
        'Секция наполняется из базы, в разметке остаётся пустой.');
}

правило('версии подняты',
    Number((СТР.ru.match(/style\.css\?v=(\d+)/) || [0, 0])[1]) >= 370 &&
    Number((СТР.ru.match(/sponsors-loader\.js\?v=(\d+)/) || [0, 0])[1]) >= 6,
    'Не поднял версию — смотришь старый сайт.');

/* ══ ВЫВОД ════════════════════════════════════════════════════════════════ */

console.log('');
if (ошибки.length === 0) {
    console.log('  ок      секция спонсоров: ' + ВСЕГО + ' правил');
    console.log('          плитки равны   ·   цель нажатия вся плитка   ·   лайма нет');
    console.log('          порядок один на оба блока   ·   окно заперто и объявлено');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  спонсоры — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s+/g, '\n            '));
    console.log('');
});
process.exit(1);
