/**
 * ЗАМОРОЗКА ПОРЯДКА БЛОКОВ СЕТКИ И СТУПЕНЕЙ ПОДЗАГОЛОВКА
 * (кусок 71, часть «порядок блоков», 14.10.2026).
 *
 * ЗАМЕР. Плей-офф клеился после групп БЕЗУСЛОВНО (`tournament-detail.js`),
 * а комментарий рядом обещал условие «пока плей-офф пуст», которого в коде
 * не было. На идущем турнире 153bc688 группы были доиграны 12 из 12, а
 * плей-офф играл 3 из 9 — и зритель листал 771 пиксель законченных таблиц,
 * прежде чем увидеть то, что играется сейчас. В ветке двух лиг перекос был
 * ЗЕРКАЛЬНЫЙ: пустые сетки лиг висели над играющимися группами.
 *
 * И три ступени лестницы, которых замер 06.10 не видел вовсе: подзаголовок
 * блока сетки шёл 17.6/700 инлайном, название группы 15.2/700 инлайном,
 * подзаголовок участников 18/600 из своего класса. Прибор лестницы ходил
 * по списку css-селекторов, а эти рисуются строкой из js и класса не имеют.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • порядок блоков решается СОСТОЯНИЕМ, и состояние читается по матчам,
 *     а не по статусу турнира;
 *   • признак «групповой этап закрыт» объявлен по одному разу на ветку;
 *   • группы и плей-офф копятся в РАЗНЫЕ строки — иначе порядок не задать;
 *   • кегль подзаголовка раздела объявлен ОДИН раз на страницу;
 *   • подзаголовок строго мельче заголовка раздела на каждом виде;
 *   • кеглей, записанных числом мимо шкалы, в файле не остаётся.
 *
 *   node tools/check-poryadok-blokov.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const JS  = безКом(чит('js/tournament-detail.js'));
const CSS = чит('css/tournament-detail.css');
const CSSб = безКом(CSS);

/* ---- 1. Порядок блоков решает состояние ---- */

правило('круговая: порядок блоков решает состояние',
    /bHtml\s*\+=\s*allGroupDone\s*\?/.test(JS),
    'Склейка круговой ветки перестала смотреть на `allGroupDone`. Порядок\n' +
    'блоков — функция состояния: группы выше плей-оффа ровно пока в\n' +
    'групповом этапе есть несыгранный матч.');

правило('круговая: живое выше законченного, а не наоборот',
    /bHtml\s*\+=\s*allGroupDone\s*\?\s*\(\s*плейоффHtml\s*\+\s*группы\s*\)\s*:\s*\(\s*группы\s*\+\s*плейоффHtml\s*\)/.test(JS),
    'Ветки склейки переставлены местами. Групповой этап ЗАКРЫТ — наверх\n' +
    'идёт плей-офф; этап ИДЁТ — наверх идут группы.');

правило('две лиги: порядок блоков решает состояние',
    /glHtml\s*\+=\s*glAllGroupDone\s*\?\s*\(\s*лиги\s*\+\s*группыЛиг\s*\)\s*:\s*\(\s*группыЛиг\s*\+\s*лиги\s*\)/.test(JS),
    'Ветка двух лиг снова клеит безусловно. Беда там зеркальная: пустые\n' +
    'сетки лиг над играющимися группами.');

/* ---- 2. Состояние читается по матчам ---- */

правило('признак закрытого этапа считается по матчам',
    /var\s+allGroupDone\s*=\s*grpMatches\.length\s*>\s*0\s*&&\s*grpMatches\.every/.test(JS) &&
    /var\s+glAllGroupDone\s*=\s*glGrpMatches\.length\s*>\s*0\s*&&\s*glGrpMatches\.every/.test(JS),
    'Признак «групповой этап закрыт» перестал считаться по матчам.\n' +
    'СОСТОЯНИЕ ЧИТАЕТСЯ ПО МАТЧАМ, А НЕ ПО СТАТУСУ ТУРНИРА:\n' +
    '`registration_closed` встречается с доигранными группами,\n' +
    '`completed` — с недоигранным плей-оффом.');

правило('порядок блоков не смотрит на статус турнира',
    !/(?:bHtml|glHtml)\s*\+=\s*[^;]*\b(?:t|tournament)\.status\b/.test(JS),
    'В склейку порядка блоков пролез `tournament.status`. Статус турнира\n' +
    'НЕ отвечает на вопрос «доигран ли групповой этап».');

правило('признак закрытого этапа объявлен по одному разу на ветку',
    (JS.match(/var\s+allGroupDone\s*=/g) || []).length === 1 &&
    (JS.match(/var\s+glAllGroupDone\s*=/g) || []).length === 1,
    'Появилось второе объявление признака. ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО\n' +
    'ПОНЯТИЕ — беда родится ровно на шве.');

/* ---- 3. Блоки копятся в разные строки ---- */

правило('круговая: группы копятся отдельно от плей-оффа',
    /var\s+группы\s*=\s*''/.test(JS) && (JS.match(/группы\s*\+=/g) || []).length >= 20,
    'Накопитель групп исчез или в него перестали писать. Пока группы и\n' +
    'плей-офф пишутся в одну строку, порядок задать нечем.');

правило('две лиги: сетки и группы копятся отдельно',
    /var\s+лиги\s*=\s*''/.test(JS) && /var\s+группыЛиг\s*=\s*''/.test(JS) &&
    (JS.match(/лиги\s*\+=/g) || []).length >= 8 && (JS.match(/группыЛиг\s*\+=/g) || []).length >= 20,
    'Накопители ветки двух лиг исчезли или опустели.');

/* ---- 4. Ступени лестницы ---- */

правило('кегль подзаголовка раздела объявлен один раз на широких видах',
    /\.td-section-header h3,[\s\S]{0,120}?\{[^}]*font-size:\s*var\(--fs-lg\)/.test(CSSб) &&
    (CSSб.match(/font-size:\s*var\(--fs-lg\)/g) || []).length >= 1,
    'Общее правило подзаголовка раздела (21, ступень --fs-lg) исчезло.\n' +
    'До 14.10 его на широких видах не было вовсе, и кегль брался инлайном\n' +
    'из js — 17.6, которого на шкале нет.');

правило('подзаголовок блока сетки не задаёт кегль сам',
    /\.td-bracket-subtitle\s*\{[^}]*\}/.test(CSSб) &&
    !/\.td-bracket-subtitle\s*\{[^}]*font-size/.test(CSSб),
    'Класс `.td-bracket-subtitle` снова задаёт кегль. Он несёт ТОЛЬКО\n' +
    'краску и отступ: кегль приходит от правила подзаголовка раздела,\n' +
    'одним определением на страницу.');

правило('подзаголовок участников не задаёт кегль сам',
    !/\.td-participants-subtitle\s*\{[^}]*font-size/.test(CSSб),
    'У `.td-participants-subtitle` снова свой кегль. Он шёл 18/600 против\n' +
    '17.6/700 у соседнего подзаголовка — одно понятие, две ступени, и ни\n' +
    'одна не на шкале.');

правило('название группы стоит на ступени card title',
    /\.td-group-name\s*\{[^}]*font-size:\s*var\(--fs-base\)/.test(CSSб),
    'Название группы съехало со ступени: лестница 86:10 назначила ему\n' +
    'card title — 16 на широких. Было 15.2 инлайном, такой ступени нет.');

правило('название группы на узких — ступень ниже',
    /@media \(max-width: 640px\)[\s\S]{0,600}?\.td-group-name\s*\{[^}]*font-size:\s*var\(--fs-sm\)/.test(CSSб),
    'Шаг на 640 исчез: на узких видах название группы должно падать на\n' +
    'ступень ниже — 14, как велит card title.');

правило('инлайновых кеглей блока сетки в js не осталось',
    !/font-size:1\.1rem/.test(JS) && !/font-size:0\.95rem/.test(JS),
    'В js вернулся инлайновый кегль подзаголовка (1.1rem = 17.6) или\n' +
    'названия группы (0.95rem = 15.2). Оба мимо шкалы, и оба были\n' +
    'НЕВИДИМЫ для прибора лестницы: у элемента нет класса.');

правило('кеглей числом мимо токенов в js не осталось',
    !/font-size:\s*[0-9][0-9.]*rem/.test(JS),
    'В `tournament-detail.js` снова появился кегль, записанный числом.\n' +
    'Замер 14.10 нашёл четыре таких уровня — 12.8, 11.2, 13.6 и 14.4, —\n' +
    'и ни один не стоял на шкале 11 · 12 · 14 · 16 · 18 · 21 · 26.');

правило('ширины шапки таблицы стоят на шкале',
    !/min-width:46px/.test(JS) && !/width:30px/.test(JS),
    'Вернулись ширины 46 и 30 — таких ступеней нет. Шкала: 48 и 32.');

/* ---- 5. Сторож на приём гашения ---- */

правило('короткая подпись расписания живёт псевдоэлементом',
    /\.td-sched-round,\s*\n\s*\.td-sched-court-cell\s*\{\s*font-size:\s*0/.test(CSSб) &&
    /\.td-sched-round::after,\s*\n\s*\.td-sched-court-cell::after\s*\{[^}]*content:\s*attr\(data-short\)/.test(CSSб),
    'Пара «гашение нулём + короткая подпись через ::after» распалась.\n' +
    'Либо подпись станет полной и переносится по слогам, либо исчезнет\n' +
    'вовсе: кегль 0 без псевдоэлемента — пустая клетка.');

/* ---- 6. Счётчик «в рейтинге»: два определения не расходятся ---- */

const СТАТЫ = (() => {
    const из = [];
    const обойти = кат => {
        fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(д => {
            const п = кат + '/' + д.name;
            if (д.isDirectory()) обойти(п);
            else if (д.name.endsWith('.sql')) {
                const т = чит(п);
                /* Считаем только ЖИВЫЕ определения: строка, начинающаяся с
                   CREATE, а не слово CREATE внутри комментария. */
                if (/^\s*CREATE (?:OR REPLACE )?FUNCTION\s+public\.get_club_stats/m.test(т)) из.push({ п, т });
            }
        });
    };
    обойти('sql');
    return из;
})();

правило('счётчик клубных цифр жив хотя бы в одном файле',
    СТАТЫ.length > 0,
    'Ни один файл больше не создаёт `get_club_stats`. Пять счётчиков на\n' +
    'главной идут из неё одной — без неё там прочерки.');

правило('все определения счётчика начинаются колонкой ranked',
    СТАТЫ.every(ф => /RETURNS TABLE\s*\(\s*\n?\s*ranked\b/.test(ф.т)),
    'Определение `get_club_stats` снова начинается не с `ranked`.\n' +
    'ЭТО УЖЕ СЛУЧАЛОСЬ: оба файла — `CREATE OR REPLACE`, и запуск\n' +
    'отставшего МОЛЧА возвращал счётчик к числу членств. На главной\n' +
    'тогда встала единица вместо четырёхсот.\n' +
    'Файлы, создающие счётчик: ' + СТАТЫ.map(ф => ф.п).join(', '));

правило('боевая и тестовая считают «в рейтинге» одинаково',
    СТАТЫ.every(ф => /is_guest IS NOT TRUE AND category_id IS NOT NULL/.test(ф.т)),
    'Условие «в рейтинге» разошлось между определениями. Базы должны\n' +
    'считать это одинаково, иначе прогон меряет не то, что боевая.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      порядок блоков и ступени подзаголовка: 19 правил');
    console.log('          живое выше законченного   ·   состояние по матчам');
    console.log('          кегль подзаголовка — одно определение на страницу');
    console.log('          счётчик «в рейтинге» не расходится между базами');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  порядок блоков — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
