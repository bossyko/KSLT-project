/**
 * ЗАМОРОЗКА ШЕСТИ РАЗДЕЛОВ КАБИНЕТА — статистика, скидки, уведомления,
 * профиль, настройки и списки «Игр».
 *
 * Слово Кости 12.10: «это все сразу сделай». Общий слой кабинета (кусок 58)
 * лестницу уже выправил, поэтому здесь чинился ШОВ: высоты, которых нет,
 * цели нажатия без слоя, краска мимо шкалы и график, который ничего о себе
 * не сообщает.
 *
 * ЧТО ЗАМОРАЖИВАЕТСЯ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • высота элемента управления держится СТУПЕНЬЮ, а не суммой полей —
 *     это говорит сам Button 17:82, и до 12.10 код этого не выполнял;
 *   • кнопка кабинета не стоит в ЧУЖОЙ шкале кнопок сайта: там ступени
 *     48/40/32, а у компонента 28/36/44/52, и удвоенный класс бил своё
 *     правило по весу;
 *   • у всего, что ниже 44, есть прозрачный слой цели — включая общую
 *     полосу страниц, где слой был только по высоте;
 *   • крупная цифра объявлена ОДИН раз и одной ступенью на весь кабинет;
 *   • один уровень — один межстрочный, и ни одного «normal»: это ссылка
 *     на шрифт, а не значение;
 *   • график НАЗЫВАЕТ СЕБЯ, и имя собирается из данных, а не общей фразой;
 *   • четвёртое окно кабинета носит ту же оболочку, что три первых;
 *   • краска подписей из шкалы: 3.21 и 4.16 были ниже нормы AA.
 *
 *   node tools/check-kabinet-razdely.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const CSS = безКом(чит('css/dashboard.css'));
const ОБЩИЙ = безКом(чит('css/style.css'));
const JS = безКом(чит('js/dashboard.js'));
const ГРАФ = безКом(чит('js/rating-chart.js'));
const СТРАНИЦЫ = ['pages/dashboard.html', 'pages/dashboard-en.html', 'pages/dashboard-kg.html'].map(чит);

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };
const тело = сел => {
    const i = CSS.indexOf(сел + ' {');
    if (i === -1) return '';
    const j = CSS.indexOf('}', i);
    return j === -1 ? '' : CSS.slice(i, j + 1);
};

/* ══ 1. ВЫСОТА — СТУПЕНЬЮ, А НЕ ПОЛЯМИ ═════════════════════════════════ */

правило('кнопка кабинета держит высоту ступенью компонента',
    /\.db-btn \{[^}]*min-height:\s*var\(--btn-h-md/.test(тело('.db-btn')),
    'высота снова складывается из полей: было padding 12/32 и ни одной высоты');

правило('поле ввода держит высоту явно — Input 25:5 велит это прямо',
    /\.db-field-input \{[^}]*min-height:\s*44px/.test(тело('.db-field-input')),
    '«Height 44px… set explicitly — a select computes its height from the\n' +
    '          option font otherwise and drifts 2-4px». Наши поля были 43');

правило('чип фильтра стоит на ступени своего компонента',
    /\.db-chip \{[^}]*min-height:\s*36px/.test(тело('.db-chip')),
    'Filter chip 49:77 — 36 высотой; было 32 из полей 5/14');

правило('кнопка значков стоит на ступени Utility, а не Button',
    /\.db-badges-expand-btn \{[^}]*min-height:\s*36px/.test(тело('.db-badges-expand-btn')),
    'она ничего не отправляет, только разворачивает список — Utility button\n' +
    '          56:101, размеры xs 28 и sm 36. Было 39 из полей 10/16');

правило('кнопка Телеграма стоит на ступени',
    /\.db-tg-btn \{[^}]*min-height:\s*36px/.test(тело('.db-tg-btn')),
    'высота 36 складывалась из полей 9/18 — число то же, но не названное');

/* ══ 2. КНОПКА КАБИНЕТА НЕ В ЧУЖОЙ ШКАЛЕ ═══════════════════════════════ */

правило('чип фильтра вынут из чужой шкалы «мелкая ступень»',
    !/\.db-chip\.db-chip/.test(ОБЩИЙ),
    'в css/style.css снова есть .db-chip.db-chip — ступень «мелкая» даёт 32,\n' +
    '          а чип это переключатель фильтра: 32 ниже цели 44 по WCAG 2.5.5.\n' +
    '          Там же записаны два таких же случая — .trn-chip и .pl-category-pill');

правило('таблица матчей называет себя своим классом',
    /db-matches-table db-games-table/.test(JS) &&
    /\.db-games-table tbody tr \{[^}]*display: grid/.test(CSS),
    'класс .db-matches-table носят пятеро — матчи, баттлы, приглашения,\n' +
    '          платежи и баллы. Без своего имени раскладка списком достаётся всем');

правило('кнопка кабинета вынута из чужой шкалы кнопок сайта',
    !/\.db-btn\.db-btn/.test(ОБЩИЙ),
    'в css/style.css снова есть .db-btn.db-btn — это блок со ступенями\n' +
    '          48/40/32, которых нет у компонента Button 17:82. Удвоенный класс\n' +
    '          бьёт правило кабинета по весу, и min-height 44 молча проигрывает');

/* ══ 3. СЛОЙ ЦЕЛИ 44 ═══════════════════════════════════════════════════ */

правило('слой цели 44 объявлен одним списком на все ступени ниже 44',
    /\.db-chip::after,[\s\S]{0,200}?\.db-btn-sm::after,[\s\S]{0,200}?min-width:\s*44px/.test(CSS),
    'список слоёв разошёлся: ступень ниже 44 законна только со слоем');

правило('у общей полосы страниц слой 44 по ОБЕИМ сторонам',
    /\.pl-page-btn::after \{[^}]*min-width:\s*var\(--btn-h-md\)[\s\S]*?height:\s*var\(--btn-h-md\)/.test(ОБЩИЙ),
    'слой был только по высоте: 36 в ширину, и палец мимо попадал по\n' +
    '          горизонтали. Зазор 8 плюс коробка 36 дают ровно 44 — впритык');

/* ══ 4. КРУПНАЯ ЦИФРА — ОДНА СТУПЕНЬ НА КАБИНЕТ ════════════════════════ */

/* СЧИТАЕМ ОБЪЯВЛЕНИЯ СО СВОИМ ЧИСЛОМ, а не всякое упоминание кегля:
   три места зовут одну переменную — это и есть одно понятие в трёх
   контекстах. Своим кеглем остаются только вторичные числа категории,
   16 при главном 26: разница между ними и есть смысл того блока */
const своиКегли = (CSS.match(/\.db-stat-value[^{]*\{[^}]*font-size:\s*var\(--fs-[^)]+\)/g) || []);
правило('крупная цифра не заводит своих ступеней помимо вторичных чисел',
    своиКегли.length === 1,
    'объявлений СВОЕГО кегля у .db-stat-value стало ' + своиКегли.length +
    ' вместо одного:\n          было шесть штук пятью ступенями (3xl, 2xl, xl, lg, md, base)');

правило('все три места крупной цифры зовут одну переменную',
    (CSS.match(/font-size:\s*var\(--db-fs-cifra\)/g) || []).length === 5,
    'мест, зовущих --db-fs-cifra, не пять (баланс, окно обмена, плитки\n' +
    '          платежей, плитки статистики, главное число категории): ' +
    (CSS.match(/font-size:\s*var\(--db-fs-cifra\)/g) || []).length);

/* ══ 5. ОДИН УРОВЕНЬ — ОДИН МЕЖСТРОЧНЫЙ, И НИ ОДНОГО «NORMAL» ══════════ */

const межстрочные = {};
(CSS.match(/[^{}]+\{[^}]*\}/g) || []).forEach(бл => {
    const сел = бл.slice(0, бл.indexOf('{')).trim();
    const m = бл.match(/line-height:\s*([^;]+);/);
    if (!m || !сел.startsWith('.db-')) return;
    const ключ = сел.split(/\s+/).pop().split(':')[0];
    (межстрочные[ключ] = межстрочные[ключ] || new Set()).add(m[1].trim());
});
const двойные = Object.keys(межстрочные).filter(k => межстрочные[k].size > 1);
правило('ни один уровень кабинета не несёт два межстрочных',
    двойные.length === 0,
    'уровней с двумя значениями: ' + двойные.join(', ') + '\n' +
    '          — выигрывает то, что ниже по файлу, и правка верхнего молча ничего не даёт');

правило('у управляющих элементов межстрочный назван значением',
    /\.db-chip \{[^}]*line-height:\s*var\(--lh-none\)/.test(тело('.db-chip')) &&
    /\.db-choice \{[^}]*line-height:\s*var\(--lh-none\)/.test(тело('.db-choice')),
    '«normal» — это ссылка на шрифт, а не значение (правило 29.09)');

/* ══ 6. КРАСКА ПОДПИСЕЙ ════════════════════════════════════════════════ */

правило('срок действия ваучера красится токеном',
    /\.db-voucher-dates \{[^}]*color:\s*var\(--text-muted\)/.test(тело('.db-voucher-dates')),
    'контраст был 3.21 при норме AA 4.5: по этой строке человек решает,\n' +
    '          успеет он воспользоваться скидкой или нет');

правило('кнопка Телеграма читается на своём фоне',
    /\.db-tg-btn \{[^}]*background:\s*rgba\(0, 136, 204, 0\.28\)/.test(тело('.db-tg-btn')),
    'контраст был 4.16. Краска синяя фирменная — её не осветляют, растят фон');

/* ══ 7. ГРАФИК НАЗЫВАЕТ СЕБЯ ═══════════════════════════════════════════ */

правило('у графиков есть общая назвалка',
    /function назватьГрафик\(canvas, подпись\)/.test(ГРАФ),
    'холст сам по себе не говорит ничего: ни role, ни имени, ни запасного текста');

правило('назвалка ставит роль, имя и запасной текст разом',
    /setAttribute\('role', 'img'\)/.test(ГРАФ) &&
    /setAttribute\('aria-label', подпись\)/.test(ГРАФ) &&
    /canvas\.textContent = подпись/.test(ГРАФ),
    'одного role мало: запасной текст читают и те, у кого canvas не нарисовался');

правило('назвалку зовут ОБА графика — рейтинговый и NTRP',
    (ГРАФ.match(/назватьГрафик\(/g) || []).length === 3,
    'вызовов назватьГрафик не три (объявление плюс два графика): ' +
    (ГРАФ.match(/назватьГрафик\(/g) || []).length);

правило('имя графика собирается ИЗ ДАННЫХ, а не общей фразой',
    /v\[0\]/.test(ГРАФ) && /v\[v\.length - 1\]/.test(ГРАФ) &&
    /ntrpText\(values\[0\]\)/.test(ГРАФ),
    'в имени нет первого и последнего значения — диктор получит «график»\n' +
    '          вместо того, что видит глазами зрячий');

/* ══ 8. ЧЕТВЁРТОЕ ОКНО КАБИНЕТА ════════════════════════════════════════ */

const QR = (() => {
    const i = JS.indexOf('dbQrModal');
    if (i === -1) return '';
    const j = JS.indexOf('\n    function ', i);
    return JS.slice(Math.max(0, i - 600), j === -1 ? JS.length : j);
})();

правило('тело окна QR нашлось — иначе правила ниже проверяют пустоту',
    QR.length > 500, 'окно QR не найдено в js/dashboard.js');

правило('накладка окна QR — общий класс, а не семь свойств инлайном',
    /overlay\.className = 'db-modal-back'/.test(QR) && !/overlay\.style\.cssText/.test(QR),
    'накладка снова собрана инлайном');

правило('окно QR называет себя окном и несёт имя',
    /db-qr-modal" role="dialog" aria-modal="true"/.test(QR) &&
    /aria-labelledby="' \+ идЗаголовкаQR/.test(QR),
    'ни role, ни aria-modal, ни имени');

правило('окно QR выходит по Escape и возвращает фокус',
    /function поКлавишеQR\(e\) \{ if \(e\.key === 'Escape'\) закрытьQR\(\); \}/.test(QR) &&
    /var фокусДоQR = document\.activeElement/.test(QR),
    'Escape и возврат фокуса у четвёртого окна');

/* ПРАВИЛО СМОТРИТ НА ОТНОШЕНИЕ, А НЕ НА НАПИСАНИЕ ТЕЛА (21.10).
   Ловушка сведена в дом `js/kslt-fokus.js`: шесть копий жили в четырёх
   местах `dashboard.js`, в `player.js` и в оболочке окна админки, и УЖЕ
   РАЗОШЛИСЬ — две не перечисляли поля, пять не возвращали фокус из-под
   окна. Отношение, которое морозится: у окна есть ловушка, она взята
   домом и навешана на его корень. */
правило('окно QR держит Tab внутри себя',
    /var ловушкаQR = window\.KSLT_FOKUS\.ловушка\(overlay\)/.test(QR) &&
    /overlay\.addEventListener\('keydown', ловушкаQR\)/.test(QR),
    'ловушки Tab нет');

правило('размеры окна QR живут в классах, а не в ветке по ширине окна',
    /\.db-qr-modal \{[^}]*max-width:\s*340px/.test(CSS) && !/телефон \? '1\.15rem'/.test(JS),
    'кегли в rem и поля снова считаются в js веткой if по innerWidth, причём\n' +
    '          по границе 560 — её нет среди разрешённых 640 и 992');

/* ══ 9. СТОРОЖ НА ОТСТУПЫ ══════════════════════════════════════════════ */

const ШКАЛА = new Set([0, 4, 8, 12, 16, 20, 24, 32, 40, 48, 64, 80, 128]);
const свои = /\.db-(stat|badge|chart|ntrp|vouch|notif|notify|profile|contacts|avatar|photo|settings|pw|chip|choice|tg-|field|btn|qr-)/;
let мимоШкалы = 0;
(CSS.match(/[^{}]+\{[^}]*\}/g) || []).forEach(бл => {
    const сел = бл.slice(0, бл.indexOf('{'));
    if (!свои.test(сел)) return;
    (бл.match(/(padding|margin|gap|row-gap|column-gap)(-\w+)?\s*:\s*[^;]+;/g) || []).forEach(об => {
        if (об.indexOf('var(') !== -1) return;
        (об.match(/(\d+(?:\.\d+)?)px/g) || []).forEach(ч => {
            const n = parseFloat(ч);
            if (n && !ШКАЛА.has(n)) мимоШкалы++;
        });
    });
});
/* В СВОИХ РАЗДЕЛАХ ИХ НОЛЬ — порог точный, а не «не больше». 74 значения
   переведены 12.10; остальные 99 живут в общем слое кабинета и идут со
   своим куском, под этот сторож они не попадают */
правило('отступы своих разделов не уходят со шкалы',
    мимоШкалы === 0,
    'отступов мимо шкалы стало ' + мимоШкалы + ' вместо нуля — новое число\n' +
    '          заведено мимо шкалы 4 · 8 · 12 · 16 · 20 · 24 · 32 · 40');

/* ══ 10. ВЕРСИИ ════════════════════════════════════════════════════════ */

const версии = имя => {
    const найдено = new Set();
    СТРАНИЦЫ.forEach(s => {
        const re = new RegExp('/' + имя.replace('.', '\\.') + '\\?v=(\\d+)', 'g');
        let m; while ((m = re.exec(s))) найдено.add(m[1]);
    });
    return [...найдено];
};
[['dashboard.css'], ['dashboard.js'], ['rating-chart.js'], ['style.css']].forEach(([ф]) => {
    const в = версии(ф);
    правило('версия ' + ф + ' одна на все три языка',
        в.length === 1,
        ф + ' подключён разными версиями: ' + в.join(', '));
});

if (ошибки.length === 0) {
    console.log(`\n  ок      разделы кабинета: ${ВСЕГО} правил\n`);
    process.exit(0);
}
console.log(`\n  НЕ ТАК  разделы кабинета: ${ВСЕГО} правил, упало ${ошибки.length}.\n`);
ошибки.forEach(о => {
    console.log(`  ✗ ${о.имя}`);
    if (о.подсказка) console.log(`          ${о.подсказка}`);
    console.log('');
});
process.exit(1);
