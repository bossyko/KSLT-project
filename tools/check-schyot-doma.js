const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = о => fs.readFileSync(path.join(КОРЕНЬ, о), 'utf8');
const чисто = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '));

const ПРОПУСК = ['node_modules', 'test-results', 'mobile', 'lib', 'playwright-report',
                 'tests', 'tools', '_sync'];

function всеJS(дир, итог) {
    итог = итог || [];
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        const п = path.join(дир, э.name);
        if (э.isDirectory()) всеJS(п, итог);
        else if (э.name.endsWith('.js')) итог.push(п);
    }
    return итог;
}

function всеHTML() {
    const итог = [];
    (function обойти(дир) {
        for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
            if (э.name.startsWith('.')) continue;
            const п = path.join(дир, э.name);
            if (э.isDirectory()) { if (ПРОПУСК.indexOf(э.name) === -1) обойти(п); }
            else if (э.name.endsWith('.html')) итог.push(п);
        }
    })(КОРЕНЬ);
    return итог;
}

const подключённые = т => {
    const обр = /<script[^>]*\ssrc="([^"]+)"/g;
    const итог = [];
    let м;
    while ((м = обр.exec(т))) итог.push(м[1].split('?')[0].replace(/^(\.\.\/)+/, ''));
    return итог;
};

const файлыJS = всеJS(path.join(КОРЕНЬ, 'js'));
const дом = чисто(чит('js/kslt-rules.js'));
const ошибки = [];
let держится = 0;
function правило(имя, годно, подсказка) {
    if (годно) { держится++; console.log('  ✓ ' + имя); }
    else ошибки.push({ имя, подсказка });
}

/* ── 1. своих определений нет НИ ПОД ОДНИМ из имён ── */
const ИМЕНА = ['formatScore', 'flipScore', 'parseScoreStats',
               'dbFormatScore', 'dbFlipScore', 'dbParseScoreStats', 'isValidSet'];
const свои = [];
for (const п of файлыJS) {
    const т = чисто(fs.readFileSync(п, 'utf8'));
    for (const и of ИМЕНА) {
        if (new RegExp('function\\s+' + и + '\\s*\\(').test(т)) {
            свои.push(path.relative(КОРЕНЬ, п) + ':' + и);
        }
    }
}
правило(
    'своих определений счёта нет ни под одним именем',
    свои.length === 0,
    'Остались: ' + свои.join(', ') + '.\n' +
    'Имён СЕМЬ на четыре понятия: половина копий носила префикс `db`, и\n' +
    'по имени родство не видно вовсе. Правило перечисляет все семь именно\n' +
    'потому, что переименованная копия — самая опасная.');

/* ── 2. дом объявляет все четыре ── */
const МЕТОДЫ = ['показатьСчёт', 'перевернутьСчёт', 'разборСчёта', 'сетГоден'];
const нет = МЕТОДЫ.filter(м => !new RegExp('R\\.' + м + '\\s*=\\s*function').test(дом));
правило(
    'дом правил объявляет все четыре понятия счёта',
    нет.length === 0,
    'Не объявлены: ' + нет.join(', ') + '.\n' +
    'Признак — ОБЪЯВЛЕНИЕ, а не упоминание имени: имя встречается в доме\n' +
    'и в описании, и правило на имени осталось бы зелёным после\n' +
    'переименования объявления (урок куска 110).');

/* ── 3. BYE не становится нулевой победой ── */
правило(
    'BYE не считается матчем: разбор счёта возвращает ничего',
    /разборСчёта[\s\S]{0,400}?===\s*'BYE'[\s\S]{0,80}?return null/.test(дом),
    'BYE — пропуск круга, а не игра. Без этой проверки он дал бы 0:0 по\n' +
    'геймам и 0:0 по сетам, то есть ВОШЁЛ БЫ В СТАТИСТИКУ как сыгранный\n' +
    'матч с нулевым результатом, и средние по игроку поехали бы.');

/* ── 4. короткий формат не принимает 7:5 и 7:6 ── */
const тело = (дом.match(/R\.сетГоден\s*=\s*function[\s\S]*?\n    \};/) || [''])[0];
правило(
    'короткий формат ограничен шестью, а не семью',
    /формат === 'short'/.test(тело) && /> 6 \|\| b > 6/.test(тело) && /> 7 \|\| b > 7/.test(тело),
    'В коротком формате сет идёт до 6, при 6:5 играется тай-брейк, и ни\n' +
    '7:5, ни 7:6 в нём не бывает. Это ОТДЕЛЬНАЯ ветка, а не общий порог:\n' +
    'замерено на стенде — 7:5 в коротком не годен, 6:5 годен.');

/* ── 5. дом подключён там, где зовут счёт ── */
const зовут = файлыJS
    .filter(п => /KSLT_RULES\.(показатьСчёт|перевернутьСчёт|разборСчёта|сетГоден)/.test(чисто(fs.readFileSync(п, 'utf8'))))
    .map(п => path.relative(КОРЕНЬ, п).split(path.sep).join('/'));
const безДома = всеHTML().filter(п => {
    const свои2 = подключённые(fs.readFileSync(п, 'utf8'));
    return зовут.some(путь => свои2.indexOf(путь) !== -1)
        && свои2.indexOf('js/kslt-rules.js') === -1;
}).map(п => path.relative(КОРЕНЬ, п));
правило(
    'дом подключён на каждой странице, где зовут счёт',
    безДома.length === 0,
    'Страницы без дома: ' + безДома.join(', ') + '.\n' +
    'Зовущих файлов: ' + зовут.length + '. Дом без тега — это тихая\n' +
    'поломка, и она СПИТ до первого зова, как было со статусом турнира.');

/* ── 6. стенд мерит дом, а не свою копию ── */
const стенд = чит('maket/schyot-zamer.html');
правило(
    'стенд счёта подключает дом и своей копии не держит',
    стенд.indexOf('js/kslt-rules.js') !== -1
    && !/function\s+(показатьСчёт|перевернутьСчёт|разборСчёта|сетГоден)\s*\(/.test(чисто(стенд)),
    'Стенд обязан мерить ПРОДУКТ. Своя копия на стенде означала бы, что\n' +
    'замер говорит о стенде, а не о доме — за эту сессию такое ловилось\n' +
    'четыре раза.');

console.log('');
if (!ошибки.length) {
    console.log('  ок      счёт: ' + держится + ' правил');
    console.log('          восемь копий четырёх понятий сведены в дом правил');
    console.log('          замерено стендом: BYE → ничего, супер-ТБ → сет, 7:5 коротким не годен');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  счёт — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
