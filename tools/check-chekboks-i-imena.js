/**
 * ЗАМОРОЗКА КУСКА 119 — ЗАМКНУТЫЙ КРУГ РАЗОРВАН, ИМЕНА РАЗВЕДЕНЫ.
 *
 * Чекбокс массового выбора нёс инлайн `width:18px;height:18px;
 * accent-color:…;cursor:pointer`, а css перебивал его ДВУМЯ важностями.
 * Инлайн держался тем, что его перебивают, важность — тем, что есть
 * инлайн. Все три свойства инлайна замерены мёртвыми 22.10.
 *
 * И два ключа словаря служили каждый ДВУМ понятиям: `crtServiceName` —
 * заголовку колонки и подсказке поля, `chalCancelBattle` — кнопке строки
 * и заголовку окна. ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ.
 *
 *   node tools/check-chekboks-i-imena.js
 */
const fs = require('fs');
const path = require('path');
const { маска } = require('./razovye/maska.js');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const UT = чит('js/admin/core/utils.js');
const AD = чит('css/admin.css');
const CN = чит('js/admin/core/constants.js');
const CR = чит('js/admin/sections/courts.js');
const CH = чит('js/admin/sections/challenges.js');

/* ── 1. ЧЕКБОКС БЕЗ ИНЛАЙНА ───────────────────────────────────────────── */
const тегиЧекбокса = (UT.match(/<input type="checkbox" class="ad-bulk-[a-z]+"[^>]*>/g) || []);
правило('оба чекбокса массового выбора рисуются, и их ровно два',
    тегиЧекбокса.length === 2,
    'Тегов `.ad-bulk-*` в utils.js: ' + тегиЧекбокса.length + ', а замерено два.\n' +
    'ПРОВЕРКА, КОТОРАЯ ИЩЕТ В ПУСТОМ СПИСКЕ, ЗЕЛЕНЕЕТ ВСЕГДА.');
правило('ни у одного чекбокса массового выбора нет инлайна',
    тегиЧекбокса.every(т => !/style\s*=/.test(т)),
    'Инлайн вернулся: ' + тегиЧекбокса.filter(т => /style=/.test(т)).join(' | ') + '.\n' +
    'Все три прежних свойства были мертвы, и это ЗАМЕРЕНО, а не выведено:\n' +
    'размер перебивался важностью (при инлайне 40px браузер давал 18),\n' +
    '`cursor` css объявляет тем же значением, а `accent-color` красит\n' +
    'НАТИВНЫЙ чекбокс — его нет, `appearance: none`, и галочку рисует\n' +
    'свой `::after` с `color: var(--neutral-black)`.');

/* ── 2. ВАЖНОСТИ НЕ ВЕРНУЛИСЬ ─────────────────────────────────────────── */
const блокЧек = (function () {
    const i = AD.indexOf('.ad-bulk-item,\n.ad-bulk-all {');
    return i === -1 ? '' : AD.slice(i, AD.indexOf('}', i) + 1);
})();
правило('блок чекбокса массового выбора на месте',
    блокЧек.length > 0,
    'Не нашёл `.ad-bulk-item, .ad-bulk-all { … }` в admin.css — правила ниже\n' +
    'искали бы в пустоте.');
правило('у чекбокса нет важностей — перебивать больше нечего',
    блокЧек.indexOf('!important') === -1,
    'Важность вернулась в блок чекбокса. Она стояла против ИНЛАЙНА, и\n' +
    'инлайна больше нет. ВАЖНОСТЬ БЕЗ КОНКУРЕНТА — ЭТО НЕ ВАЖНОСТЬ,\n' +
    'А МУСОР, и правило о конкуренте её не поймает: конкурента у неё\n' +
    'и правда нет, но беда не в этом.');
правило('размер чекбокса остался замеренным — 18 и рамка 2',
    /width:\s*18px/.test(блокЧек) && /height:\s*18px/.test(блокЧек) &&
    /border:\s*var\(--bw-thick\)/.test(блокЧек) && /appearance:\s*none/.test(блокЧек),
    'Замер 22.10 в браузере: 18×18, рамка 2px лайм, радиус 4, цель нажатия\n' +
    '44×44, отмеченный — лаймовый фон и чёрная «✓». Снятие инлайна и\n' +
    'важностей не изменило НИЧЕГО, и это заморожено.');

/* ── 3. ДВА ПОНЯТИЯ — ДВА ИМЕНИ ───────────────────────────────────────── */
/* СКОЛЬКО МЕСТ — СТОЛЬКО И ПРОВЕРЯЕМ. Подсказок услуги ДВЕ, и правило,
   которому хватает одной, сторожит половину: прувер это и показал,
   сломав одну из двух и не уронив правило. */
const пары = [
    ['crtServiceName', 'crtServiceNameHint', CR, 2, 'подсказка поля ввода услуги'],
    ['chalCancelBattle', 'chalCancelBattleTitle', CH, 1, 'заголовок окна отмены баттла'],
];
пары.forEach(([общее, своё, файл, сколько, что]) => {
    правило('ключ `' + своё + '` заведён в словаре',
        new RegExp('^\\s{8}' + своё + ':', 'm').test(CN),
        что + ' снова делит имя с `' + общее + '`. ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО\n' +
        'ПОНЯТИЕ: пока имя общее, правка одного места молча меняет другое.');
    const найдено = (файл.match(new RegExp('L\\.' + своё + '(?![\\w])', 'g')) || []).length;
    правило('`' + что + '` зовёт своё имя во всех ' + сколько + ' местах',
        найдено === сколько,
        что + ': зовов `L.' + своё + '` ' + найдено + ', а замерено ' + сколько +
        '.\nМеньше — часть вернулась к общему ключу `' + общее + '`; больше —\n' +
        'своё имя расползлось туда, где его не мерили.');
});
/* ПРОВЕРКА, КОТОРАЯ НЕ МОЖЕТ УПАСТЬ, НИЧЕГО НЕ ДОКАЗЫВАЕТ: общий ключ
   обязан остаться живым у СВОЕГО понятия, иначе разведение выродилось бы
   в переименование. */
правило('общие имена остались у своих понятий',
    /<span>' \+ L\.crtServiceName \+ '<\/span>/.test(CR) &&
    /data-cancel="' \+ c\.id \+ '">' \+ L\.chalCancelBattle/.test(CH),
    'Заголовок колонки услуги или кнопка отмены в строке потеряли свой ключ —\n' +
    'значит имена не развели, а переименовали.');

/* ── вывод ───────────────────────────────────────────────────────────── */
console.log('');
if (ошибки.length) {
    console.log('  НЕ ТАК  чекбокс и имена — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(([и, п]) => console.log('          ✗ ' + и + '\n            ' + п.replace(/\n/g, '\n            ') + '\n'));
    process.exit(1);
}
console.log('  ок      чекбокс и имена: 9 правил');
console.log('          инлайна нет, важностей в блоке нет, размер 18 замерен');
console.log('          два имени разведены на четыре, слова не тронуты');
console.log('');
