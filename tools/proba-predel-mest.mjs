/**
 * ПРОБА ПРЕДЕЛА МЕСТ: доходит ли предел до денег.
 *
 * Утверждение, которое надо доказать, а не объявить: когда места за
 * пределом уровня НЕ ПОПАДАЮТ в разбор `{место: очки}`, участник за ними
 * получает ноль — и отдельного условия на предел в `rating-points.js`
 * заводить не нужно.
 *
 * Берётся НАСТОЯЩИЙ `заМесто`/`поТурниру` и НАСТОЯЩИЕ числа итогового
 * уровня из `sql/схема/kategorii-i-ochki.sql` (колонка «Четвёртая»).
 * ПРОВЕРКА, КОТОРАЯ НЕ МОЖЕТ УПАСТЬ, НИЧЕГО НЕ ДОКАЗЫВАЕТ: поэтому рядом
 * с урезанной таблицей тот же участник считается по ПОЛНОЙ, и там он
 * обязан получить ненулевое — иначе проба зелёная по другой причине.
 */
import { readFileSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const P = require('../js/rating-points.js');

// Колонка «Четвёртая» = нынешний Итоговый турнир, места 1…34 (35…64 нули)
const ИТОГОВЫЙ = {
    1: 130, 2: 80, 3: 55, 4: 48, 5: 33, 6: 28, 7: 23, 8: 23,
    9: 18, 10: 16, 11: 13, 12: 13, 13: 11, 14: 11, 15: 11, 16: 11,
    17: 10, 18: 8, 19: 6, 20: 6, 21: 4, 22: 4, 23: 4, 24: 4,
    25: 3, 26: 3, 27: 3, 28: 3, 29: 3, 30: 3, 31: 3, 32: 3, 33: 3, 34: 2
};
const ПРЕДЕЛ = 8;

const урезанная = {};
for (const м of Object.keys(ИТОГОВЫЙ)) {
    if (Number(м) <= ПРЕДЕЛ) урезанная[м] = ИТОГОВЫЙ[м];
}

let ок = 0, плохо = 0;
const проба = (имя, ждём, получили) => {
    if (JSON.stringify(ждём) === JSON.stringify(получили)) {
        console.log(`  [+] ${имя} = ${JSON.stringify(получили)}`);
        ок++;
    } else {
        console.log(`  [-] ${имя}: ждали ${JSON.stringify(ждём)}, получили ${JSON.stringify(получили)}`);
        плохо++;
    }
};

console.log('ОСНОВАНИЕ: предел не выдуман, а взят из таблицы');
проба('мест в полной таблице итогового', 34, Object.keys(ИТОГОВЫЙ).length);
проба('мест в урезанной пределом', 8, Object.keys(урезанная).length);
проба('место 8 платится и там и там', [23, 23],
      [P.заМесто(8, ИТОГОВЫЙ), P.заМесто(8, урезанная)]);

console.log('\nПРЕДЕЛ ДОХОДИТ ДО ДЕНЕГ — И ПРОБА МОЖЕТ УПАСТЬ');
// Если бы предел не работал, слева стояло бы 18 — поэтому проба не пустая
проба('место 9: полная платит, урезанная нет', [18, 0],
      [P.заМесто(9, ИТОГОВЫЙ), P.заМесто(9, урезанная)]);
проба('место 34: полная платит, урезанная нет', [2, 0],
      [P.заМесто(34, ИТОГОВЫЙ), P.заМесто(34, урезанная)]);
проба('место 64: ноль у обеих — за таблицей ничего и не было', [0, 0],
      [P.заМесто(64, ИТОГОВЫЙ), P.заМесто(64, урезанная)]);

console.log('\nВЕСЬ ТУРНИР РАЗОМ: восьмёрка платится, девятый нет');
const участники = [];
for (let м = 1; м <= 12; м++) участники.push({ place: м, разыграно: true, побед: 0 });

const полный = P.поТурниру(JSON.parse(JSON.stringify(участники)), ИТОГОВЫЙ, {});
const предельный = P.поТурниру(JSON.parse(JSON.stringify(участники)), урезанная, {});

// Поле зовётся `points_earned`, а не `очки` (`rating-points.js:119`).
// Первая редакция пробы читала `.очки`, получала восемь `null` слева и
// восемь справа — и первая проверка прошла ВХОЛОСТУЮ: сравнивала пустоту
// с пустотой. Уронили её соседние строки, у которых стояли настоящие числа.
проба('первые восемь — настоящие числа, а не пустота',
      [130, 80, 55, 48, 33, 28, 23, 23],
      предельный.slice(0, 8).map(у => у.points_earned));
проба('первые восемь в полной те же',
      [130, 80, 55, 48, 33, 28, 23, 23],
      полный.slice(0, 8).map(у => у.points_earned));
проба('места 9–12 в полной платятся', [18, 16, 13, 13],
      полный.slice(8).map(у => у.points_earned));
проба('места 9–12 за пределом — ноль', [0, 0, 0, 0],
      предельный.slice(8).map(у => у.points_earned));
проба('сумма турнира: 480 против 480 − 60', [480, 420],
      [полный.reduce((с, у) => с + у.points_earned, 0),
       предельный.reduce((с, у) => с + у.points_earned, 0)]);

console.log('\nИСТОЧНИК ЧИСЕЛ НЕ ИЗ ПАМЯТИ');
const файл = readFileSync(new URL('../sql/схема/kategorii-i-ochki.sql', import.meta.url), 'utf8');
проба('строка места 9 стоит в файле наполнения', true,
      файл.includes('(9, 145, 90, 50, 30, 18)'));
проба('строка места 34 стоит в файле наполнения', true,
      файл.includes('(34, 20, 12, 6, 4, 2)'));

console.log(`\nИТОГ: прошло ${ок}, не прошло ${плохо}`);
process.exit(плохо ? 1 : 0);
