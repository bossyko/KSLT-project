const безСлов157 = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '));
const телоПереходника = (function () {
    const чистый = безСлов157(рег);
    const н = чистый.indexOf('function noticeModal');
    if (н === -1) return '';
    let гл = 0;
    const о = чистый.indexOf('{', н);
    for (let i = о; i < чистый.length; i++) {
        if (чистый[i] === '{') гл++;
        else if (чистый[i] === '}') { гл--; if (гл === 0) return чистый.slice(н, i + 1); }
    }
    return '';
})();
