#!/usr/bin/env node
/**
 * ОДНО ПОНЯТИЕ — ОДНИ КЛАССЫ В ОБОИХ ПРОДУКТАХ (кусок 231, 28.10).
 *
 * ВОПРОС КОСТИ 28.10: «кегли и классы чтобы все были одни». Число,
 * которое я тогда назвал, — 954 класса в приложении, из них 143 общих с
 * сайтом, 811 своих — ОКАЗАЛОСЬ НЕ ПРО ТО. Большая часть «своих» законна:
 * это экраны, которых на сайте нет вовсе.
 *
 * ДВА ПРИБОРА НЕ СРАБОТАЛИ, И ЭТО ТОЖЕ ЗАМЕР:
 *   · «одинаковое оформление — одно понятие» дал 64 пары, и почти все
 *     ложные: `.pd-matches-list` и `.card-info` совпали телом случайно
 *     (flex, колонка, зазор 2). СОВПАДЕНИЕ ПРАВИЛ — НЕ ОДНО ПОНЯТИЕ.
 *   · «частые приставки у файлов, читающих одну таблицу» утонул в шуме:
 *     файлы приложения большие и мешают по десятку приставок сразу.
 * Автоматически «одно понятие, два имени» по этим двум продуктам НЕ
 * НАХОДИТСЯ. Поэтому список прочитан ГЛАЗАМИ, назван поимённо, и сторож
 * держит ровно его — плюс храповик, чтобы третьего долга не завелось.
 *
 * Запуск: node tools/check-odni-klassy.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;
function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const сайтCSS = чит('css/tournament-detail.css') + чит('css/style.css') +
                чит('css/news.css') + чит('css/services.css');
const прилCSS = чит('mobile/www/css/app.css');

/* ПОНЯТИЯ, ЖИВУЩИЕ В ОБОИХ ПРОДУКТАХ. Каждое прочитано по месту.
   `сведено: true` — имена уже одни; `false` — названный ДОЛГ. */
const ПОНЯТИЯ = [
    { имя: 'круговая таблица группы', приставка: 'td-gt-', сведено: true,
      как: 'разметку рисует общий дом js/kslt-setka.js (кусок 216)' },
    { имя: 'клетка матча', приставка: 'td-match', сведено: true,
      как: 'общий дом js/kslt-setka.js (кусок 217)' },
    { имя: 'сетка плей-офф', приставка: 'td-bracket', сведено: true,
      как: 'общий дом js/kslt-setka.js (кусок 217)' },
    { имя: 'матч за третье место', приставка: 'td-third-place', сведено: true,
      как: 'хвост последнего круга в доме (кусок 221)' },
    { имя: 'расписание запусков', приставка: 'td-sched-', сведено: true,
      как: 'имена совпали сразу: строение взято у сайта (кусок 216)' },
    { имя: 'лента кадров новости', приставка: 'news-carousel', сведено: true,
      как: 'общий дом js/kslt-lenta.js (кусок 220)' },

    { имя: 'список участников турнира', приставка: null, сведено: false,
      сайт: 'td-reg-', приложение: 'td-part-',
      как: 'ДОЛГ: одно понятие, две семьи имён. Строение приложения взято ' +
           'у сайта (кусок 216), а имена я завёл свои. Чинится переездом ' +
           'в общий дом, а не переименованием: переименование оставит две ' +
           'разметки с одинаковыми именами, и это хуже.' },
    { имя: 'плашка состояния турнира', приставка: null, сведено: false,
      сайт: 'td-status-badge', приложение: 'td-badge',
      как: 'ДОЛГ: сайт пишет `.td-status-badge.completed`, приложение — ' +
           '`.td-badge.status-completed`. Имя приложения ЛУЧШЕ (у сайта ' +
           '`.completed` — слишком общее и может столкнуться), поэтому ' +
           'сводить надо сайт к приложению, а не наоборот. Это правка в ' +
           'большом продукте и идёт отдельным куском.' }
];

ПОНЯТИЯ.filter(п => п.сведено).forEach(п => {
    правило(
        'понятие «' + п.имя + '» зовётся одинаково в обоих продуктах',
        сайтCSS.indexOf(п.приставка) >= 0 && прилCSS.indexOf(п.приставка) >= 0,
        'Приставка `' + п.приставка + '` пропала у одного из продуктов.\n' +
        п.как + '.\n' +
        'Разойдутся имена — и общий дом перестанет быть общим: разметка\n' +
        'одна, а краска у неё в каждом продукте своя.');
});

/* ХРАПОВИК: названных долгов не больше, чем прочитано. Новый долг — это
   новое понятие, нарисованное в приложении своими именами, и он обязан
   быть НАЗВАН здесь, а не появиться молча. */
const ПОТОЛОК_ДОЛГОВ = 2;
const долги = ПОНЯТИЯ.filter(п => !п.сведено);
правило(
    'названных долгов не больше прочитанного',
    долги.length <= ПОТОЛОК_ДОЛГОВ,
    'Долгов в списке ' + долги.length + ', потолок ' + ПОТОЛОК_ДОЛГОВ + '.\n' +
    'Храповик только опускается: свели понятие — опусти число здесь же.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      одни классы: все ' + держится + ' правил держатся');
    console.log('          сведено понятий: ' + ПОНЯТИЯ.filter(п => п.сведено).length +
                ', названных долгов: ' + долги.length);
    долги.forEach(д => console.log('          ДОЛГ · ' + д.имя +
        ': сайт `' + д.сайт + '`, приложение `' + д.приложение + '`'));
    console.log('');
}
