#!/usr/bin/env node
/**
 * ДАТА РОЖДЕНИЯ — НЕОБЯЗАТЕЛЬНА, И ЭТО СКАЗАНО ЧЕСТНО (шаг A5, 29.10).
 *
 * ЗАМЕР 29.10. `birth_day/_month/_year` встречаются в 42 местах, и НИ В
 * ОДНОМ из них нет проверки возраста: ни 18+, ни возрастных категорий. В
 * админке поле только показывается (`users.js:693`, `readonly`), у
 * карточки игрока `players` столбца возраста нет вовсе, сервер принимает
 * пусто (`verify-otp/index.ts:271` — `number | null`), а при обычной
 * регистрации дату не спрашивают совсем. Слово Кости 29.10: возрастных
 * категорий не будет.
 *
 * А ОБЕЩАНИЙ ОБЯЗАТЕЛЬНОСТИ БЫЛО ТРИ: звёздочка в кабинете, звёздочка на
 * трёх страницах входа и атрибут `required` у двух полей там же —
 * единственный из трёх, который браузер ДЕЙСТВИТЕЛЬНО требовал.
 * НАДПИСЬ, КОТОРУЮ НИКТО НЕ ПРОВЕРЯЕТ, — ТАКОЙ ЖЕ ВРУЩИЙ ОРГАН, КАК
 * ПОЛЗУНОК БЕЗ ЧИТАТЕЛЯ.
 *
 * И ТУТ ЖЕ НАШЛАСЬ ЖИВАЯ БЕДА: `tg-birth-year` читался БЕЗ ЗАЩИТЫ в
 * `js/auth.js`, а элемента с таким id НЕТ НИ В ОДНОЙ РАЗМЕТКЕ — значит
 * регистрация через Telegram ПАДАЛА при отправке формы. Строкой выше тот
 * же элемент читается защищённо: автор знал, что его может не быть, и
 * забыл про второе место.
 *
 * Запуск: node tools/check-data-rozhdeniya.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));

const ВХОД = ['pages/auth.html', 'pages/auth-en.html', 'pages/auth-kg.html'];

console.log('\n  ДАТА РОЖДЕНИЯ — НЕОБЯЗАТЕЛЬНА\n');

правило('у полей даты рождения нет атрибута required',
    ВХОД.every(ф => !/id="tg-birth-(?:day|month|year)"[^>]*\brequired\b/.test(чит(ф))),
    'Это был ЕДИНСТВЕННЫЙ из трёх обещаний, который браузер\n' +
    'действительно требовал: форма не отправлялась без дня и месяца.\n' +
    'Проверки возраста при этом нет ни в одном из 42 мест.');

правило('у даты рождения на страницах входа нет звёздочки',
    ВХОД.every(ф => {
        const т = чит(ф);
        const м = т.match(/<label class="auth-label">[^<]*(?:Дата рождения|Date of Birth|Туулган күнү)[^<]*(<span class="auth-required">\*<\/span>)?\s*<\/label>/);
        return м && !м[1];
    }),
    'Звёздочка обещает обязательность, которой нет ни у кого.');

правило('у даты рождения в кабинете нет звёздочки',
    (function () {
        const т = безКом(чит('js/dashboard.js'));
        return /L\.birthday \+ '<\/label>'/.test(т) &&
               !/L\.birthday \+ ' <span class="db-required">/.test(т);
    })(),
    'Ни `isProfileComplete`, ни `профильНеполон` дату не спрашивают, и\n' +
    'сервер принимает пусто. Звёздочка врала.');

правило('обязательность не вернулась в проверку полноты профиля',
    (function () {
        const т = безКом(чит('js/dashboard.js'));
        const м = т.match(/window\.isProfileComplete = function\(\) \{[\s\S]*?\n    \};/);
        return м && !/birth_/.test(м[0]);
    })(),
    'Полнота профиля — ФИО, пол, телефон. Дата туда не входит, и пока\n' +
    'возрастных категорий нет, входить не должна: иначе баннер\n' +
    '«заполните профиль» вернётся ко всем, у кого её нет.');

правило('подача заявки не спрашивает дату рождения',
    !/birth_/.test(безКом(чит('js/tournament-register.js'))),
    'Проверка перед подачей смотрит ФИО, пол и телефон\n' +
    '(`tournament-register.js:253`). Добавь сюда дату — и человек без\n' +
    'неё не сможет записаться на турнир, хотя клуб её не использует.');

правило('приложение дату рождения не спрашивает',
    !/birth_day|birth_month|birth_year/.test(безКом(чит('mobile/www/js/auth.js'))) &&
    !/birth_day|birth_month|birth_year/.test(безКом(чит('mobile/www/js/screens/profile.js'))),
    'Собирать данные, которыми не пользуешься, — лишняя строка в анкете\n' +
    'Data safety и лишний вопрос от Apple. В приложении их не\n' +
    'спрашивали и раньше; правило держит, чтобы не завели.');

правило('`tg-birth-year` читается только защищённо',
    (function () {
        const т = безКом(чит('js/auth.js'));
        return !/getElementById\('tg-birth-year'\)\s*\.\s*value/.test(т);
    })(),
    'ЭТО БЫЛА ЖИВАЯ БЕДА: элемента с таким id нет ни в одной разметке, и\n' +
    '`.value` у `null` бросал TypeError — РЕГИСТРАЦИЯ ЧЕРЕЗ TELEGRAM\n' +
    'ПАДАЛА при отправке формы, без всякого сообщения человеку.');

правило('элемента `tg-birth-year` действительно нет ни в одной разметке',
    (function () {
        const пропуск = /^(node_modules|\.git|android|ios|build|assets|test-results|reports)$/;
        let нашлось = false;
        const обойти = (отн) => {
            const п = path.join(КОРЕНЬ, отн || '.');
            if (!fs.existsSync(п)) return;
            for (const э of fs.readdirSync(п, { withFileTypes: true })) {
                const в = отн ? отн + '/' + э.name : э.name;
                if (э.isDirectory()) { if (!пропуск.test(э.name)) обойти(в); continue; }
                if (!э.name.endsWith('.html')) continue;
                if (/\/(build|assets)\//.test(в)) continue;
                if (/id="tg-birth-year"/.test(fs.readFileSync(path.join(КОРЕНЬ, в), 'utf8'))) нашлось = true;
            }
        };
        обойти('');
        return !нашлось;
    })(),
    'ПРАВИЛО ПАРНОЕ К ПРЕДЫДУЩЕМУ: если год однажды добавят в разметку,\n' +
    'оно упадёт — и тогда защищённое чтение можно будет снять осознанно,\n' +
    'а не наткнуться на него через полгода.');

правило('чтение полей входа идёт через одно место',
    (function () {
        const т = безКом(чит('js/auth.js'));
        return /function поле\(id\) \{[\s\S]{0,120}return э \? э\.value : '';/.test(т);
    })(),
    'Защищённое чтение — одно определение на файл. Иначе следующий\n' +
    '`getElementById(...).value` снова уронит экран.');

правило('дата рождения по-прежнему СОБИРАЕТСЯ, а не выброшена',
    /birth_day/.test(безКом(чит('js/dashboard.js'))) &&
    /birth_day/.test(безКом(чит('supabase/functions/verify-otp/index.ts'))),
    'Поле осталось — просто необязательное. У десяти профилей значения\n' +
    'уже есть, и прятать от человека его же данные хуже, чем показать\n' +
    'необязательное поле. Выбросить столбцы — отдельный разговор и\n' +
    'пишущий SQL: это данные.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else { console.log('  ок      дата рождения: все ' + держится + ' правил держатся\n'); }
