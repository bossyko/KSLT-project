#!/usr/bin/env node
/**
 * ЗАМОРОЗКА СТРАНИЦЫ «ЦЕНЫ» — кусок 55-й, 09.10.
 *
 * Страница своя, не из общего файла раздела: у неё css/pricing.css и свой
 * инлайн-скрипт. С языками это ТРИ html, и до 09.10 они были двумя разными
 * продуктами: на русской прайс из трёх строк и окно с периодами, на en и
 * kg — одиночная карточка с ценой 1 000 KGS, ВПИСАННОЙ В РАЗМЕТКУ.
 *
 * ЧТО БЫЛО ДО ПРАВКИ (замер пяти видов, трёх языков):
 * заголовок 22.62 · 42.2 · 27.2 · 51.2 · 51.2 — ни одного на ступени, все
 * шесть плавающих кеглей из четырёх clamp; обложка лёжа 77% экрана;
 * межстрочных восемь, шесть мимо лестницы; 72 отступа мимо шкалы; границ
 * четыре при двух разрешённых; :focus-visible один на 157 блоков;
 * prefers-reduced-motion ноль при 24 движущихся правилах; 27 классов жили
 * только на чужих языках, ещё 4 мертвы вовсе; таблицы pricing_plans не
 * было в базе; у кнопки оплаты не было ни одного обработчика.
 *
 * ЧЕГО ЭТА ЗАМОРОЗКА НЕ ДЕРЖИТ, И ЭТО НАЗВАНО ВСЛУХ: суммы и текст плашки
 * приходят ИЗ БАЗЫ (pricing_plans, site_content) — заморозка читает файлы
 * и о данных не знает. Что страница показывает «уточняется» при пустой
 * сумме, проверяет проба.
 *
 *   node tools/check-ceny.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '');

const CSS = чит('css/pricing.css');
const CSSч = безКом(CSS);
const ЯЗЫКИ = ['', '-en', '-kg'];
const HTML = {};
ЯЗЫКИ.forEach(я => { HTML['pricing' + я] = чит('pages/pricing' + я + '.html'); });
const RU = HTML['pricing'];
const MEMB = чит('js/membership.js');
const VREM = чит('js/kslt-vremya.js');
const TOAST = чит('js/kslt-toast.js');
const SETT = чит('js/admin/sections/settings.js');

const ошибки = [];
let всегоПравил = 0;
function правило(имя, условие, подсказка) {
    всегоПравил++;
    if (!условие) ошибки.push({ имя, подсказка });
}
function блок(текст, якорь) {
    const i = текст.indexOf(якорь);
    if (i === -1) return '';
    const j = текст.indexOf('}', i);
    return текст.slice(i, j === -1 ? текст.length : j);
}

/* ─────────── ОБЛОЖКА ─────────── */

правило('высота обложки — общая крутилка раздела',
    /min-height:\s*var\(--oblozhka-pol\)/.test(блок(CSSч, '.pr-hero {')),
    'обложка «Цен» вернулась к своему числу: стояло min-height 300, и раздел разъезжался с восемью соседними');

правило('воздух обложки — общие крутилки',
    /padding:\s*var\(--oblozhka-vozduh\) var\(--pad-x\) var\(--oblozhka-vozduh-niz\)/.test(блок(CSSч, '.pr-hero {')),
    'воздух обложки задан своими числами: стояло 120/24/60');

правило('заголовок обложки — крутилка --fs-hero',
    /font-size:\s*var\(--fs-hero\)/.test(блок(CSSч, '.pr-hero-title {')),
    'заголовок ушёл с общей крутилки: стоял clamp(2rem, 5vw, 3.2rem) — 22.62 · 42.2 · 27.2 · 51.2 · 51.2, ни одного числа на ступени');

правило('перебивка обложки — крутилка --fs-hero-sub',
    /font-size:\s*var\(--fs-hero-sub\)/.test(блок(CSSч, '.pr-hero-subtitle {')),
    'перебивка ушла с крутилки — пара «заголовок + перебивка» перестанет ехать одной связкой на три ступени');

/* Считаем ОБЪЯВЛЕНИЯ, а не блоки: прувер уронил первую редакцию, где
   регексп ловил блок целиком — два font-size внутри одного блока он
   видел как одно совпадение. ПРАВИЛО СМОТРИТ НА ТО, ЧТО СТЕРЕЖЁТ. */
const кеглиПеребивки = (CSSч.match(/\.pr-hero-subtitle\s*\{[^}]*\}/g) || [])
    .reduce((н, б) => н + (б.match(/font-size/g) || []).length, 0);
правило('кегль перебивки объявлен в файле РОВНО ОДИН раз',
    кеглиПеребивки === 1,
    'кегль перебивки объявлен второй раз — ровно тот шов, что нашёлся 09.10 на шести страницах раздела');

правило('у обложки есть правило низкого горизонтального',
    /@media \(max-height: 500px\) and \(orientation: landscape\)/.test(CSSч) &&
    /min-height:\s*0/.test(CSS.slice(CSS.indexOf('(max-height: 500px)'))),
    'снято правило телефона лёжа: обложка снова заберёт 77% экрана, замер 300 при окне 390');

/* ─────────── ШКАЛЫ ─────────── */

/* Прувер уронил первую редакцию: она ловила clamp ТОЛЬКО у кегля, и
   откат валил заодно правило «все кегли крутилкой» — два правила на одно
   отношение. Здесь стережём сам приём: плавающих чисел в файле нет вовсе,
   ни в кегле, ни в отступе. ОДНО ПРАВИЛО — ОДНО ОТНОШЕНИЕ. */
правило('плавающих чисел clamp в файле нет вовсе',
    !/clamp\(/.test(CSSч),
    'вернулся clamp: четыре таких давали шесть кеглей мимо шкалы, и столько же непредсказуемых отступов');

const кеглиНеКрутилкой = (CSSч.match(/font-size\s*:\s*([^;}]+)/g) || [])
    .filter(с => !/var\(--fs-/.test(с));
правило('все кегли берутся крутилкой --fs-*',
    кеглиНеКрутилкой.length === 0,
    'кегль задан мимо шкалы: ' + кеглиНеКрутилкой.slice(0, 3).join(' · '));

const ЛЕСТНИЦА = new Set(['1', '1.1', '1.3', '1.5', '1.65']);
const межстрочные = [...new Set((CSSч.match(/line-height\s*:\s*([\d.]+)/g) || [])
    .map(с => с.split(':')[1].trim()))];
правило('межстрочные — только ступени лестницы',
    межстрочные.every(м => ЛЕСТНИЦА.has(м)),
    'межстрочный мимо лестницы: ' + межстрочные.filter(м => !ЛЕСТНИЦА.has(м)).join(' · ') +
    ' — было восемь значений, шесть из них свои');

const ШАГИ = new Set(['2', '3', '4', '6', '8', '10']);
const ступени = [...new Set((CSSч.match(/--space-(\d+)/g) || []).map(с => с.slice(8)))];
правило('отступы — только ступени шкалы 8 · 12 · 16 · 24 · 32 · 40',
    ступени.every(с => ШАГИ.has(с)),
    'отступ взят мимо шкалы: --space-' + ступени.filter(с => !ШАГИ.has(с)).join(', --space-'));

const голыеПиксели = (безКом(CSS).match(/(?:padding|margin|gap)[^:]*:\s*[^;}]*?(\d+)px/g) || [])
    .map(с => с.match(/(\d+)px/)[1])
    .filter(ч => !['8', '12', '16', '24', '32', '40', '0'].includes(ч));
правило('голых пикселей в отступах нет, кроме цели нажатия 44',
    голыеПиксели.every(ч => ч === '44'),
    'в отступы вернулось число мимо шкалы: ' + голыеПиксели.join(' · ') + ' (было 72 таких)');

const границы = [...new Set((CSSч.match(/@media \(max-width: (\d+)px\)/g) || [])
    .map(с => с.match(/(\d+)/)[1]))];
правило('границ по ширине ровно две — 640 и 992',
    границы.length === 2 && границы.includes('640') && границы.includes('992'),
    'вернулась своя точка останова: ' + границы.join(' · ') + ' — было 768 трижды, самодельная 780, плюс 480 и 375');

/* ─────────── ЦЕЛИ, ФОКУС, ДВИЖЕНИЕ ─────────── */

правило('высота кнопки карточки держится свойством, а не полями',
    /min-height:\s*44px/.test(блок(CSSч, '.pm-btn {')),
    'высоту кнопки снова дают поля — замер давал 41 на двух видах из пяти, мимо цели нажатия 44');

правило('закрытие окна — цель 44 × 44',
    /width:\s*44px/.test(блок(CSSч, '.pmm-close {')) && /height:\s*44px/.test(блок(CSSч, '.pmm-close {')),
    'крестик окна снова меньше пальца: замер давал 15 × 26');

правило('у способа оплаты есть своя высота цели',
    /min-height:\s*44px/.test(блок(CSSч, '.pmm-way {')),
    'способ оплаты потерял высоту цели нажатия');

const фокусные = ['.pm-btn:focus-visible', '.pmm-close:focus-visible', '.pmm-opt:focus-visible',
                  '.pmm-way:focus-visible', '.pmm-go:focus-visible'];
правило('фокус с клавиатуры виден у всех пяти нажимаемых',
    фокусные.every(с => CSSч.includes(с)),
    'пропал :focus-visible у ' + фокусные.filter(с => !CSSч.includes(с)).join(', ') +
    ' — до правки правило было ОДНО на 157 блоков');

правило('движение спрашивает системную настройку',
    /@media \(prefers-reduced-motion: reduce\)/.test(CSSч),
    'снято уважение к «меньше движения» при 24 движущихся правилах');

правило('transition: all не вернулся',
    !/transition:\s*all/.test(CSSч),
    'вернулся transition: all — он анимирует и то, что анимировать нельзя');

правило('тихий цвет --text-dim в тексте не вернулся',
    !/--text-dim/.test(CSSч),
    'вернулся --text-dim: контраст 3.14 на фоне, мимо AA, и решение Кости 06.10 убирает его из текста');

/* ─────────── ВЫБОР МЕНЯЕТ ТОЛЬКО ГРАНИЦУ ─────────── */

правило('выбранный период меняет ТОЛЬКО границу',
    /border-color:\s*var\(--accent\)/.test(блок(CSSч, '.pmm-opt.on {')) &&
    !/background/.test(блок(CSSч, '.pmm-opt.on {')),
    'выбранному варианту вернули заливку — описание Card 29:65 запрещает прямо: «do not also change the fill, or selection and hover become indistinguishable»');

правило('окно шириной md 520 по Modal 26:143',
    /max-width:\s*520px/.test(блок(CSSч, '.pmm {')),
    'ширина окна ушла от ступени компонента: стояло 460, а число полей даёт md 520');

/* ─────────── СТАРЫЙ МЕХАНИЗМ НЕ ВОЗВРАЩАЕТСЯ ─────────── */

const СТАРЫЕ = ['.pr-card', '.pr-badge', '.pr-plan-name', '.pr-price', '.pr-features',
                '.pr-cta-btn', '.pr-modal', '.pr-pay-', '.pr-faq-item', '.pr-faq-question'];
правило('классы старого механизма не вернулись в css',
    СТАРЫЕ.every(к => !CSSч.includes(к)),
    'вернулся класс одиночной карточки или своей раскрывашки: ' +
    СТАРЫЕ.filter(к => CSSч.includes(к)).join(' · ') + ' — их было 27 плюс 4 мёртвых');

правило('раскрывашка берётся из общего файла раздела',
    Object.values(HTML).every(h => h.includes('ip-faq-question') && !h.includes('pr-faq-question')) &&
    Object.values(HTML).every(h => /info-pages\.css\?v=/.test(h)),
    'страница снова рисует свою раскрывашку вместо общей ip-faq-* — это второе определение одного понятия');

правило('цена не вписана в разметку ни на одном языке',
    Object.values(HTML).every(h => !/>\s*1[,.\s]?000\s*</.test(h) && !/KGS/.test(h)),
    'в разметку вернулась сумма: на en и kg стояло «1,000 KGS» прямо в html, и менять её приходилось выкладкой');

правило('третья копия цены в коде не вернулась',
    !/window\.KSLT_MEMBERSHIP_PLAN\s*=/.test(MEMB),
    'вернулся KSLT_MEMBERSHIP_PLAN с price: 1000 — объект, которого не читал никто');

/* ─────────── ДАННЫЕ И ВРЕМЯ ─────────── */

правило('суммы читаются из таблицы pricing_plans',
    /from\('pricing_plans'\)/.test(RU),
    'страница перестала спрашивать суммы у базы');

правило('блок бесплатного периода есть и по умолчанию скрыт',
    Object.values(HTML).every(h => /id="prFree"[^>]*hidden/.test(h)),
    'блок бесплатного периода пропал или показывается до ответа базы — он СВОЙСТВО ДАННЫХ: нет даты, нет блока');

правило('текст блока берётся из site_content, а не из разметки',
    Object.values(HTML).every(h => h.includes("KSLT_CONTENT.get('pricing_free_title'")),
    'текст плашки снова держится разметкой — его правка пойдёт через выкладку');

правило('дата блока разбирается по частям, а не через Date',
    Object.values(HTML).every(h => !/new Date\(до\)/.test(h)),
    'дата снова читается как момент: new Date(\'2026-12-31\') — это UTC-полночь, и замер давал «30 декабря» там, где в базе 31-е');

правило('день считается по Бишкеку, а не по Гринвичу',
    /KSLT_VREMYA\s*&&\s*window\.KSLT_VREMYA\.сегодня\(\)/.test(MEMB) &&
    /СМЕЩЕНИЕ_МИНУТ\s*=\s*6\s*\*\s*60/.test(VREM),
    'членство и бесплатный период снова считают день по Гринвичу — слово Кости 09.10: основное время клуба Бишкек');

правило('ключ сессии спрашивается у клиента, а не вписан строкой',
    Object.values(HTML).every(h => !/sb-[a-z]{20}-auth-token/.test(h)),
    'в страницу вернулся id боевого проекта строкой — на тестовой базе вход не определится никогда');

/* ─────────── ОКНО И КНОПКИ ─────────── */

/* Стережём ОБЪЯВЛЕНИЕ, а не упоминание: прувер уронил первую редакцию —
   переименованная функция оставляла свои вызовы, и правило зеленело от
   них. ЧИТАТЕЛЬ — НЕ ОБЪЯВЛЕНИЕ, и правило обязано различать. */
правило('у окна есть ловушка Tab и возврат фокуса',
    /function фокусируемые\(\)/.test(RU) && /var фокусДоОкна/.test(RU),
    'из окна снова уходит Tab, и фокус не возвращается на кнопку, с которой его открыли');

правило('у кнопки оплаты есть обработчик',
    /go\.addEventListener\('click', скоро\)/.test(RU),
    'кнопка «Перейти к оплате» снова ничего не делает: до 09.10 у #payGo не было ни одного обработчика');

правило('способы оплаты — кнопки, а не div',
    Object.values(HTML).every(h => (h.match(/<button type="button" class="pmm-way">/g) || []).length === 4),
    'способы оплаты снова стали div — с клавиатуры в них не попасть');

правило('уведомление берётся из общего, а не заводится седьмым',
    /KSLT_TOAST\.показать/.test(RU) && /window\.KSLT_TOAST\s*=/.test(TOAST),
    'уведомление снова своё: в проекте уже ШЕСТЬ разных showToast, седьмого не заводим');

/* ─────────── АДМИНКА ─────────── */

правило('карточка цен в админке есть и зовётся только администратору',
    /renderSetPrices/.test(SETT) &&
    /key: 'prices'/.test(SETT) &&
    SETT.indexOf('renderSetPrices();') > SETT.indexOf("if (A.currentRole === 'admin')"),
    'карточка «Цены» пропала из настроек или стала видна менеджеру — слово Кости 09.10: менять цены может только администратор');

правило('админка правит суммы в pricing_plans и текст в site_content',
    /from\('pricing_plans'\)\s*\n?\s*\.update/.test(SETT) && /from\('site_content'\)\.upsert/.test(SETT),
    'экран настроек перестал писать туда, откуда страница читает — ровно тот шов, что был у таблицы очков 02.10');

/* ─────────── ВЕРСИИ ─────────── */

const версии = Object.values(HTML).map(h => (h.match(/pricing\.css\?v=(\d+)/) || [])[1]);
правило('версия стиля поднята и одинакова на всех трёх страницах',
    версии.length === 3 && версии.every(в => в && Number(в) >= 25) && new Set(версии).size === 1,
    'версия pricing.css не поднята или разошлась между языками — часть людей получит старое из кеша');

const всего = всегоПравил;
if (ошибки.length) {
    console.log('\n  ✗ «Цены» — ' + ошибки.length + ' из ' + всего + ':\n');
    ошибки.forEach(о => console.log('    · ' + о.имя + '\n      ' + о.подсказка));
    console.log('');
    process.exit(1);
}
console.log('ок «Цены»: ' + всего + ' правил');
