/**
 * ЗАМОРОЗКА ВЕРСИЙ ФАЙЛОВ (заход B5, 15.10.2026).
 *
 * ЗАМЕР 15.10: три файла расходились версиями в продукте — `coaches.js`
 * 21 против 22 и `courts.js` 32 против 33 (обоих не догнала `admin.html`),
 * `kslt-rules.js` 27 против 29 (не догнали три главные). Ещё четыре СВОИХ
 * файла подключались БЕЗ версии вовсе: `countries.js`, `membership.js`,
 * `players-data.js`, `scroll-spy.js`. `membership.js` при этом правился
 * 09.10 — у всех, кто был на сайте раньше, в кеше лежал старый.
 *
 * ПРИЧИНА — НЕ ЗАБЫВЧИВОСТЬ, А ОБЛАСТЬ ВЗГЛЯДА СТОРОЖА. Сторожа версий
 * уже были, но каждый привязан к своему куску и смотрит ДВЕ-ТРИ страницы.
 * `check-alfavit-grupp.js` прямо сторожит `kslt-rules.js` — и честно
 * проходил, потому что видел три файла из двадцати одного. ПРАВИЛО,
 * СМОТРЯЩЕЕ ЧАСТЬ ПРОДУКТА, НЕ СТОРОЖИТ НИЧЕГО: расхождение живёт ровно
 * там, куда сторож не смотрит.
 *
 * ЗАМОРОЖЕНЫ ОТНОШЕНИЯ, А НЕ НОМЕРА:
 *   • у СВОЕГО файла версия ЕСТЬ в каждом подключении;
 *   • версия ОДНА на весь продукт — страницы, партиалы и стенды вместе;
 *   • чужая библиотека (внешний адрес) версией не сторожится: её номер
 *     живёт в адресе CDN и нам не принадлежит;
 *   • один файл не подключается на странице дважды.
 *
 * ПОЧЕМУ СТЕНДЫ СЧИТАЮТСЯ НАРАВНЕ СО СТРАНИЦАМИ: стенд читает те же css,
 * и отставший номер там показывает НЕ ТО, по чему принимается решение
 * глазами. Этот заход и начался с того, что стенд круга B3 подключал
 * восемь css без версии вовсе.
 *
 *   node tools/check-versii-fajlov.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const П = (...ч) => path.join(КОРЕНЬ, ...ч);

/* ── свои файлы: всё, что лежит у нас, а не на чужом адресе ──────────── */
const СВОИ = new Map();
['js', 'css', 'data', path.join('js', 'sections')].forEach(д => {
    const полный = П(д);
    if (!fs.existsSync(полный)) return;
    fs.readdirSync(полный).forEach(ф => {
        if (/\.(js|css)$/.test(ф) && !СВОИ.has(ф)) СВОИ.set(ф, path.join(д, ф));
    });
});

/* ── все html продукта ───────────────────────────────────────────────── */
const СТРАНИЦЫ = [];
['index.html', 'index-en.html', 'index-kg.html'].forEach(ф => {
    if (fs.existsSync(П(ф))) СТРАНИЦЫ.push(ф);
});
['pages', 'partials', 'maket'].forEach(д => {
    const полный = П(д);
    if (!fs.existsSync(полный)) return;
    fs.readdirSync(полный).filter(ф => ф.endsWith('.html')).forEach(ф => СТРАНИЦЫ.push(path.join(д, ф)));
});

const ПОДКЛ = /(?:src|href)\s*=\s*"([^"]*?\/?([\w.-]+\.(?:js|css)))(\?v=(\d+))?"/g;

const версии = new Map();      // имя -> Map(версия -> [страницы])
const безВерсии = new Map();   // имя -> [страницы]
const дубли = [];

СТРАНИЦЫ.forEach(стр => {
    const т = fs.readFileSync(П(стр), 'utf8');
    const насчитано = new Map();
    let м;
    ПОДКЛ.lastIndex = 0;
    while ((м = ПОДКЛ.exec(т)) !== null) {
        const путь = м[1], имя = м[2], вер = м[4];
        /* Чужая библиотека: внешний адрес. Её номер живёт в адресе CDN. */
        if (/^https?:/.test(путь) || /^\/\//.test(путь)) continue;
        if (!СВОИ.has(имя)) continue;
        насчитано.set(имя, (насчитано.get(имя) || 0) + 1);
        if (вер) {
            if (!версии.has(имя)) версии.set(имя, new Map());
            const м2 = версии.get(имя);
            if (!м2.has(вер)) м2.set(вер, []);
            м2.get(вер).push(стр);
        } else {
            if (!безВерсии.has(имя)) безВерсии.set(имя, []);
            безВерсии.get(имя).push(стр);
        }
    }
    насчитано.forEach((n, имя) => { if (n > 1) дубли.push(стр + ': ' + имя + ' ×' + n); });
});

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ══ 1. ВЕРСИЯ ЕСТЬ ════════════════════════════════════════════════════ */

const перечень = м => [...м.entries()].slice(0, 6)
    .map(([имя, где]) => имя + ' → ' + где.slice(0, 3).join(', ') + (где.length > 3 ? ' и ещё ' + (где.length - 3) : ''))
    .join('\n            ');

правило('у своего файла версия есть в каждом подключении',
    безВерсии.size === 0,
    'файлов без версии: ' + безВерсии.size + '\n            ' + перечень(безВерсии) +
    '\n            Без версии правка не доезжает до того, у кого файл в кеше,\n' +
    '            и поломка выглядит как «у меня работает».');

/* ══ 2. ВЕРСИЯ ОДНА НА ВЕСЬ ПРОДУКТ ════════════════════════════════════ */

const разъехались = [...версии.entries()].filter(([, м]) => м.size > 1);

правило('версия файла одна на весь продукт',
    разъехались.length === 0,
    'разошлись: ' + разъехались.length + '\n            ' +
    разъехались.slice(0, 6).map(([имя, м]) =>
        имя + ' → ' + [...м.entries()].sort((a, b) => b[1].length - a[1].length)
            .map(([в, где]) => 'v=' + в + ' ×' + где.length + (где.length <= 2 ? ' (' + где.join(', ') + ')' : ''))
            .join('  ')).join('\n            ') +
    '\n            СТОРОЖ, СМОТРЯЩИЙ ЧАСТЬ ПРОДУКТА, НЕ СТОРОЖИТ НИЧЕГО: до 15.10\n' +
    '            `kslt-rules.js` сторожили по трём файлам из двадцати одного.');

/* ══ 3. ОДИН ФАЙЛ — ОДНО ПОДКЛЮЧЕНИЕ НА СТРАНИЦЕ ═══════════════════════ */

правило('один файл подключён на странице один раз',
    дубли.length === 0,
    'двойных подключений: ' + дубли.length + '\n            ' + дубли.slice(0, 6).join('\n            ') +
    '\n            Второе подключение — это второе исполнение: обработчики\n' +
    '            вешаются дважды, и беда родится ровно на шве.');

/* ══ 4. ОБЛАСТЬ ВЗГЛЯДА САМОГО СТОРОЖА ═════════════════════════════════ */

/* Сторож, который перестал видеть продукт целиком, — это беда, ради
   которой заход и заводился. Поэтому он сам себя и меряет. */
правило('сторож видит весь продукт, а не горстку страниц',
    СТРАНИЦЫ.length >= 100 && СВОИ.size >= 80,
    'страниц в поле зрения: ' + СТРАНИЦЫ.length + ', своих файлов: ' + СВОИ.size + '.\n' +
    '            Было 15.10: страниц 135, своих файлов 112. Падение числа значит,\n' +
    '            что сторож ослеп — папку переименовали или перенесли.');

/* ══ ВЫВОД ═════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('\n  ок      версии файлов: 4 правила');
    console.log('          ' + СТРАНИЦЫ.length + ' страниц, ' + версии.size + ' своих файлов — у каждого версия и ровно одна');
    console.log('          чужие библиотеки не сторожатся: их номер живёт в адресе CDN');
    console.log('          двойных подключений нет\n');
} else {
    console.log('\n  НЕ ТАК  версии файлов — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(о => {
        console.log('          x ' + о.имя);
        console.log('            ' + о.подсказка + '\n');
    });
    process.exitCode = 1;
}
