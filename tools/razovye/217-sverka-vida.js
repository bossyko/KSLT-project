#!/usr/bin/env node
/**
 * ДОКАЗАТЕЛЬСТВО, ЧТО ВИД НЕ ИЗМЕНИЛСЯ (08.11).
 *
 * Разворачивает каждую `var(--роль)` в новом `app.css` обратно в краску
 * по словарю токенов и сличает с файлом ДО правки — посимвольно.
 * Совпало — значит браузер отрисует то же самое, и смотреть глазами
 * нужно не «не сломалось ли», а только новую тему.
 *
 * ВИД РАБОТЫ НЕ МЕНЯЕТСЯ, ЧИНИТСЯ ВНУТРЕННОСТЬ — и это проверяется
 * замером ДО и ПОСЛЕ, а не на глаз.
 *
 * Запуск: node sverka-vida.js <корень> <файл-до>
 */
const fs = require('fs');
const path = require('path');
const корень = process.argv[2];
const пДо = process.argv[3];
if (!корень || !пДо) { console.log('нужен корень и файл-до'); process.exit(1); }

const токены = fs.readFileSync(path.join(корень, 'mobile/www/css/tokens.css'), 'utf8');
const знач = {};
токены.replace(/\/\*[\s\S]*?\*\//g, '').split('\n').forEach(с => {
    const м = с.match(/^\s*(--[\w-]+)\s*:\s*([^;]+);/);
    if (м) знач[м[1]] = м[2].trim();
});
function развернуть(в, г) {
    if (г > 6) return в;
    const м = в.match(/^var\(\s*(--[\w-]+)\s*\)$/);
    return (м && знач[м[1]]) ? развернуть(знач[м[1]], г + 1) : в;
}

/* Сравниваем ПО ЧИСЛАМ: `rgba(255,255,255,.08)` и
   `rgba(255, 255, 255, 0.08)` — один цвет. Прибор, который этого не
   видит, нашёл бы расхождение там, где его нет.
   ПОЧТИ ТОЧНЫЙ ПРИБОР — НЕТОЧНЫЙ ПРИБОР. */
function ключ(ц) {
    const м = ц.match(/rgba?\(([^)]+)\)/i);
    if (м) {
        const ч = м[1].split(',').map(x => x.trim());
        const a = ч.length > 3 ? String(parseFloat(ч[3])) : '1';
        return 'rgba:' + ч.slice(0, 3).map(x => String(parseInt(x, 10))).join(',') + ',' + a;
    }
    const h = ц.match(/^#([0-9a-fA-F]{3,8})$/);
    if (h) {
        let s = h[1].toLowerCase();
        if (s.length === 3) s = s.split('').map(x => x + x).join('');
        if (s.length === 8 && s.slice(6) === 'ff') s = s.slice(0, 6);
        return 'hex:' + s;
    }
    return ц;
}

const до = fs.readFileSync(пДо, 'utf8').split('\n');
const после = fs.readFileSync(path.join(корень, 'mobile/www/css/app.css'), 'utf8').split('\n');

if (до.length !== после.length) {
    console.log('✗ разное число строк: ' + до.length + ' и ' + после.length);
    process.exit(1);
}

const ЦВЕТ = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)/g;
const ВАР = /var\(\s*(--[\w-]+)\s*\)/g;

let сверено = 0, расхождений = 0;
for (let i = 0; i < до.length; i++) {
    if (до[i] === после[i]) continue;
    /* Строка изменилась — значит в ней подставляли роль. Разворачиваем
       обратно и сличаем краски в том же порядке. */
    /* РАЗВОРАЧИВАЕМ ОБЕ СТОРОНЫ, А НЕ ОДНУ (08.11). Первая редакция
       разворачивала роли только в новом файле, а в старом считала
       краской лишь то, что написано краской. Выходило, что строка
       `background: rgba(...); color: var(--green)` до правки даёт одну
       краску, а после — две, и прибор кричал о расхождении там, где
       его нет. ПОЧТИ ТОЧНЫЙ ПРИБОР — НЕТОЧНЫЙ ПРИБОР. */
    const краски = строка => {
        const из = [];
        строка.replace(ВАР, (_, имя) => { из.push(ключ(развернуть('var(' + имя + ')', 0))); return ''; });
        (строка.replace(ВАР, '').match(ЦВЕТ) || []).forEach(ц => из.push(ключ(ц)));
        return из;
    };
    const краскиДо = краски(до[i]);
    const краскиПосле = краски(после[i]);

    /* Порядок красок в строке мог перемешаться (часть осталась сырой) —
       сравниваем как мешки, а не как списки. */
    const мешок = а => а.slice().sort().join('|');
    if (мешок(краскиДо) !== мешок(краскиПосле)) {
        расхождений++;
        if (расхождений <= 8) {
            console.log('✗ строка ' + (i + 1));
            console.log('   до:    ' + до[i].trim().slice(0, 90));
            console.log('   после: ' + после[i].trim().slice(0, 90));
        }
    }
    сверено++;
}

console.log('\nСВЕРКА ВИДА: изменённых строк ' + сверено + ', расхождений по краске ' + расхождений);
process.exit(расхождений ? 1 : 0);
