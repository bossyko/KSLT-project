const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..', '..');
const чит = п => { try { return fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8'); } catch (e) { return null; } };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

function собрать(расш, кроме) {
    const итог = [];
    (function идти(д) {
        let сп = [];
        try { сп = fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }); } catch (e) { return; }
        сп.forEach(э => {
            const п = д ? д + '/' + э.name : э.name;
            if (кроме.some(к => п === к || п.indexOf(к + '/') === 0)) return;
            if (э.isDirectory()) идти(п);
            else if (расш.some(р => э.name.endsWith(р))) итог.push(п);
        });
    })('');
    return итог;
}
const КРОМЕ = ['node_modules', '.git', 'mobile', 'tests', 'tools', 'maket', 'test-results', 'supabase'];
const JS = собрать(['.js'], КРОМЕ);
const CSS = собрать(['.css'], КРОМЕ);
const HTML = собрать(['.html'], КРОМЕ);

function счёт(набор, признак, безК) {
    let н = 0;
    набор.forEach(ф => { let т = чит(ф); if (т === null) return; if (безК) т = безКом(т); н += (т.match(признак) || []).length; });
    return н;
}
function файлов(набор, признак, безК) {
    return набор.filter(ф => { let т = чит(ф); if (т === null) return false; if (безК) т = безКом(т); return признак.test(т); }).length;
}

