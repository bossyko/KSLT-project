/**
 * ЗАМЕР 26.10: МЁРТВЫЕ КЛЮЧИ СЛОВАРЯ АДМИНКИ. Кусок 183.
 *
 * Запись 22.10: «признак из куска 117 НЕ ПЕРЕНОСИТСЯ: одиннадцать мест берут
 * ключ, собранный на ходу — `L['role' + …]`, `L['vchStatus' + …]`,
 * `L['usrMonths' + m]` и `L[key]`, где ключ — имя вкладки. Доказать ключ
 * мёртвым поиском имени нельзя».
 *
 * ПРИЗНАК ЗДЕСЬ ДВОЙНОЙ, И ВТОРАЯ ПОЛОВИНА — ЩЕДРАЯ:
 *   1. прямой зов — `L.ключ` или `L['ключ']`;
 *   2. СБОРКА НА ХОДУ — `L['приставка' + …]`: тогда ЖИВЫМИ считаются ВСЕ
 *      ключи с этой приставкой. Доказать поимённо нельзя, а цена ошибки —
 *      «undefined» на экране менеджера. ЩЕДРОСТЬ ВЫБИРАЕТСЯ ПО ЦЕНЕ ОШИБКИ.
 *   3. `L[переменная]` без приставки — признак бессилен ВООБЩЕ: такие места
 *      называются поимённо и гасят проверку целиком, если их больше нуля
 *      там, где приставку вывести не удалось.
 *
 *   node tools/razovye/183-mertvye-klyuchi.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..', '..');
const чит = п => fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8');
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

/* ── 1. ВСЕ КЛЮЧИ СЛОВАРЯ ────────────────────────────────────────────── */
const СЛОВАРЬ = безКом(чит('js/admin/core/constants.js'));
const ключи = [];
const признакКлюча = /^[ \t]{8}([A-Za-zА-Яа-я_$][\w$]*)\s*:/gm;
let м;
while ((м = признакКлюча.exec(СЛОВАРЬ)) !== null) ключи.push(м[1]);

/* ── 2. ВСЕ ФАЙЛЫ АДМИНКИ ────────────────────────────────────────────── */
function собрать(д) {
    const итог = [];
    (function идти(п) {
        fs.readdirSync(path.join(КОРЕНЬ, п), { withFileTypes: true }).forEach(э => {
            const ф = п + '/' + э.name;
            if (э.isDirectory()) идти(ф);
            else if (э.name.endsWith('.js')) итог.push(ф);
        });
    })(д);
    return итог;
}
const ФАЙЛЫ = собрать('js/admin');
const ВЕСЬ = ФАЙЛЫ.map(ф => безКом(чит(ф))).join('\n');

/* ── 3. ПРЯМЫЕ ЗОВЫ ──────────────────────────────────────────────────── */
const прямые = new Set();
[...ВЕСЬ.matchAll(/\bL\.([A-Za-zА-Яа-я_$][\w$]*)/g)].forEach(м => прямые.add(м[1]));
[...ВЕСЬ.matchAll(/\bL\[\s*'([^']+)'\s*\]/g)].forEach(м => прямые.add(м[1]));
[...ВЕСЬ.matchAll(/\bL\[\s*"([^"]+)"\s*\]/g)].forEach(м => прямые.add(м[1]));

/* ── 4. СБОРКА НА ХОДУ: ПРИСТАВКИ ────────────────────────────────────── */
const приставки = [];
[...ВЕСЬ.matchAll(/\bL\[\s*'([^']*)'\s*\+/g)].forEach(м => { if (м[1]) приставки.push(м[1]); });
[...ВЕСЬ.matchAll(/\bL\[\s*"([^"]*)"\s*\+/g)].forEach(м => { if (м[1]) приставки.push(м[1]); });
/* `L[переменная]` — приставку вывести нельзя */
const безПриставки = (ВЕСЬ.match(/\bL\[\s*[A-Za-zА-Яа-я_$][\w$.]*\s*\]/g) || []);

const живые = new Set(прямые);
ключи.forEach(к => { if (приставки.some(п => к.indexOf(п) === 0)) живые.add(к); });

/* ── 4б. ПРИЗНАК НАУЧЕН ЧИТАТЬ ДВА ОСТАВШИХСЯ `L[переменная]` ─────────
   Запись 22.10 говорила «доказать ключ мёртвым поиском имени нельзя»,
   потому что ключ приходит переменной. Но обе переменные приходят из
   ЗАКРЫТЫХ списков, и списки лежат в этом же коде:
     `L[key]` (`layout.js:85`) — key идёт из `ROLE_SECTIONS`, шестнадцать
       имён разделов;
     `L[tabTarget]` (`:331`) — tabTarget это последний довод
       `buildActivityTableHtml`, и все его зовы видны в том же файле.
   ЗАКРЫТЫЙ СПИСОК ЧИТАЕТСЯ, А НЕ УГАДЫВАЕТСЯ. */
const разделы = [];
const мРазделы = СЛОВАРЬ.match(/ROLE_SECTIONS\s*=\s*\{[\s\S]*?\n {4}\};/);
if (мРазделы) {
    [...мРазделы[0].matchAll(/'([a-z][a-z0-9_]*)'/g)].forEach(м => разделы.push(м[1]));
}
const целиВкладок = [];
[...ВЕСЬ.matchAll(/buildActivityTableHtml\([\s\S]*?,\s*'([a-z][a-z0-9_]*)'\s*\)/g)]
    .forEach(м => целиВкладок.push(м[1]));
разделы.concat(целиВкладок).forEach(к => живые.add(к));

const мёртвые = ключи.filter(к => !живые.has(к));

/* ── вывод ───────────────────────────────────────────────────────────── */
console.log('');
console.log('  КЛЮЧЕЙ В СЛОВАРЕ АДМИНКИ: ' + ключи.length);
console.log('    зовут прямо: ' + [...прямые].filter(к => ключи.indexOf(к) !== -1).length);
console.log('    живы через приставку: ' + (живые.size - [...прямые].filter(к => ключи.indexOf(к) !== -1).length));
console.log('    НИ ОДНОГО ЗОВА: ' + мёртвые.length);
console.log('');
console.log('  ПРИСТАВКИ СБОРКИ НА ХОДУ (' + new Set(приставки).size + '): ' +
            [...new Set(приставки)].join(', '));
console.log('  ЗОВОВ `L[переменная]`: ' + безПриставки.length +
            (безПриставки.length ? '  — ' + [...new Set(безПриставки)].join(' ') : ''));
console.log('    ОБА ЧИТАЮТСЯ ИЗ ЗАКРЫТЫХ СПИСКОВ: разделов ' + new Set(разделы).size +
            ' (ROLE_SECTIONS), целей вкладок ' + new Set(целиВкладок).size +
            ' (зовы buildActivityTableHtml).');
console.log('');
console.log('  КЛЮЧИ БЕЗ ЕДИНОГО ЗОВА — ' + мёртвые.length + ':');
мёртвые.forEach(к => console.log('    ' + к));
console.log('');
