#!/usr/bin/env node
/**
 * БУКВЫ ПОВЕРХ АКЦЕНТА — НА ГОТОВУЮ РОЛЬ (08.11). Одноразовый.
 *
 * ЗАЧЕМ. Десять мест пишут `color: #0A0A0A` рядом с
 * `background: var(--accent)`. Понятие у них одно — «буквы поверх
 * лаймовой заливки», — и роль под него В СИСТЕМЕ УЖЕ ЕСТЬ:
 * `--accent-on: var(--neutral-950)` (`tokens.css:230`). Я чуть не завёл
 * вторую под именем `--on-accent`: ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ, и
 * сверка готового (шаг 6) на то и нужна.
 *
 * ПОЧЕМУ ЭТО БЕЗОПАСНО ДЛЯ ВИДА. `--accent-on` = `--neutral-950` =
 * `#0A0A0A` — знак в знак то, что стоит сейчас.
 *
 * ПОЧЕМУ НЕ `--bg-base`. Он тоже равен `--neutral-950`, и прежний
 * прибор свёл бы на него по совпадению значения. Но в светлой теме
 * `--bg-base` станет БЕЛЫМ, и надпись на лаймовой кнопке исчезнет.
 * ЗНАЧЕНИЕ СОВПАЛО, А СМЫСЛ РАЗНЫЙ.
 *
 * ЯКОРЬ НА ОКРУЖЕНИИ: правится только то `color`, у которого в ТОМ ЖЕ
 * блоке стоит акцентная заливка. Остальные `#0A0A0A` этот прибор не
 * трогает — у них своё понятие.
 *
 * Запуск: node tools/razovye/217-svesti-bukvy-na-akcente.js <корень> [--пиши]
 */
const fs = require('fs');
const path = require('path');
const корень = process.argv[2] || path.join(__dirname, '..', '..');
const пиши = process.argv.indexOf('--пиши') !== -1;
const пCss = path.join(корень, 'mobile/www/css/app.css');
let css = fs.readFileSync(пCss, 'utf8');

/* Примечания не трогаем: цвет в пояснении — не цвет на экране. */
const куски = css.split(/(\/\*[\s\S]*?\*\/)/);
let правок = 0;
const где = [];

for (let i = 0; i < куски.length; i += 2) {
    /* Блоки правил, каждый целиком: понятие видно по окружению. */
    куски[i] = куски[i].replace(/\{[^{}]*\}/g, блок => {
        if (!/background(-color)?:\s*var\(--accent\)/.test(блок)) return блок;
        return блок.replace(/(color:\s*)#0[aA]0[aA]0[aA]\b/g, (_, п) => {
            правок++; return п + 'var(--accent-on)';
        });
    });
}
css = куски.join('');

/* Места перечисляем по номерам строк — для отчёта и для глаз. */
css.split('\n').forEach((с, и) => { if (/color:\s*var\(--accent-on\)/.test(с)) где.push(и + 1); });

console.log('\nБУКВЫ ПОВЕРХ АКЦЕНТА -> --accent-on\n');
console.log('  подставлено: ' + правок);
console.log('  строк с ролью после правки: ' + где.length);
console.log('  ' + где.join(', '));

/* Что осталось сырым — для следующего понятия. */
const остаток = [];
css.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
   .split('\n').forEach((с, и) => {
    if (/color:\s*#0[aA]0[aA]0[aA]\b/.test(с)) остаток.push(и + 1);
});
console.log('\n  осталось сырых `color: #0A0A0A` вне акцентных блоков: ' +
            остаток.length + (остаток.length ? ' (' + остаток.join(', ') + ')' : ''));

if (пиши) { fs.writeFileSync(пCss, css, 'utf8'); console.log('\n  ЗАПИСАНО'); }
else console.log('\n  (ничего не записано — запусти с --пиши)');
