#!/usr/bin/env node
/**
 * ВУАЛИ И ПОДЛОЖКИ — НА РОЛИ (08.11). Одноразовый.
 *
 * ЗАЧЕМ. Светлая тема переопределяет РОЛИ. Белая вуаль, написанная
 * краской, в светлой теме останется белой — на белом фоне её не станет
 * вовсе (контраст 1.00, посчитано `217-chto-slomaetsya.js`).
 *
 * ГЛАВНОЕ РАЗЛИЧЕНИЕ КУСКА: ВУАЛЬ И ПОДЛОЖКА ВЫГЛЯДЯТ ОДИНАКОВО, А
 * ВЕДУТ СЕБЯ ПРОТИВОПОЛОЖНО. Вуаль лежит на фоне темы и обязана
 * перевернуться вместе с ним; подложка окна затемняет экран и обязана
 * остаться тёмной, иначе в светлой теме модалка перестанет отделяться.
 * Прибор, сводящий их на одну роль, уронил бы все модалки сразу.
 *
 * СТУПЕНЬ ВЫБИРАЕТСЯ ПО РОЛИ В ЭЛЕМЕНТЕ, А НЕ ПО БЛИЗОСТИ ЧИСЛА — так
 * же, как лестница ролей в `tokens.css`: тускло / подложка / граница.
 * Поэтому таблица ниже называет КАЖДОЕ место: прибор не угадывает.
 *
 * ЦЕНА НАЗВАНА: наибольший сдвиг прозрачности 0.10 (кнопка увеличения
 * поверх кадра: 0.55 к 0.45 — она уезжает на готовую роль слоя поверх
 * фотографии, где ступень уже выбрана и посчитана). У остальных
 * восемнадцати мест сдвиг 0.03 и меньше.
 *
 * Запуск: node tools/razovye/217-svesti-vuali-i-podlozhki.js <корень> [--пиши]
 */
const fs = require('fs');
const path = require('path');
const корень = process.argv[2] || path.join(__dirname, '..', '..');
const пиши = process.argv.indexOf('--пиши') !== -1;
const пCss = path.join(корень, 'mobile/www/css/app.css');

/* [что ищем, на что меняем, почему именно эта роль] — по одному месту. */
const ЗАМЕНЫ = [
  /* ── ПОВЕРХ ФОТОГРАФИИ: роли уже есть, темы не знают нарочно ──── */
  ['background: rgba(10,10,10,0.55);', 'background: var(--on-image-fill);',
   'кнопка увеличения лежит на кадре новости — слой поверх фото'],
  ['border: 1px solid rgba(255,255,255,0.22);', 'border: 1px solid var(--on-image-border);',
   'её же обводка — там же, поверх кадра'],
  ['background: rgba(0,0,0,0.45);\n  border: none;', 'background: var(--on-image-fill);\n  border: none;',
   'стрелка карусели новостей — орган поверх кадра'],

  /* ── ПОДЛОЖКА ДИАЛОГА: тёмная в ОБЕИХ темах ─────────────────────── */
  ['background: rgba(0, 0, 0, 0.7);', 'background: var(--scrim-dialog);', 'подложка окна'],
  ['background: rgba(0, 0, 0, 0.75);', 'background: var(--scrim-dialog);', 'подложка окна'],
  ['background: rgba(0,0,0,0.72);', 'background: var(--scrim-dialog);', 'подложка окна'],
  ['background: rgba(0,0,0,0.94);', 'background: var(--overlay-bg);',
   'просмотрщик фото на весь экран — ступень 0.95 уже есть и уже зовётся'],

  /* ── ВУАЛЬ НА ФОНЕ ТЕМЫ: переворачивается вместе с темой ─────────── */
  ['background: rgba(255,255,255,0.03);', 'background: var(--surface-glass);', 'стекло, самая тусклая ступень'],
  ['background: rgba(255,255,255,0.05);', 'background: var(--surface-glass);', 'стекло'],
  ['background: rgba(255,255,255,0.06);', 'background: var(--surface-glass-hover);', 'стекло, ступень выше'],
  ['background: rgba(255, 255, 255, 0.06);', 'background: var(--surface-glass-hover);', 'стекло, ступень выше'],
  ['background: rgba(255,255,255,.08);', 'background: var(--border-subtle);', 'полоса и заливка закрытого'],
  ['background: rgba(255,255,255,0.1);', 'background: var(--border-light);', 'подложка бейджа'],
  ['background: rgba(255,255,255,0.10);', 'background: var(--border-light);', 'подложка бейджа'],
  ['background: rgba(255,255,255,0.14);', 'background: var(--border-light);', 'бегунок переключателя'],
  ['stroke: rgba(255, 255, 255, 0.06);', 'stroke: var(--surface-glass-hover);', 'сетка корта'],
  ['color: rgba(255,255,255,0.75);', 'color: var(--text-secondary);', 'подпись просмотрщика — вторичный текст'],
  ['color: rgba(255,255,255,0.38);', 'color: var(--text-dim);', 'имя напарника — приглушённый текст'],
];

let css = fs.readFileSync(пCss, 'utf8');
/* Примечания не трогаем. */
const куски = css.split(/(\/\*[\s\S]*?\*\/)/);

let всего = 0;
const отчёт = [];
ЗАМЕНЫ.forEach(([было, стало, почему]) => {
    let n = 0;
    for (let i = 0; i < куски.length; i += 2) {
        const части = куски[i].split(было);
        n += части.length - 1;
        куски[i] = части.join(стало);
    }
    всего += n;
    отчёт.push({ было, n, почему });
});
css = куски.join('');

console.log('\nВУАЛИ И ПОДЛОЖКИ -> РОЛИ\n');
отчёт.forEach(о => console.log('  ' + String(о.n).padStart(2) + '×  ' +
    о.было.replace(/\n.*/, ' …').padEnd(46) + '  ' + о.почему));
console.log('\n  подставлено всего: ' + всего);

const нетронутые = [];
css.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
   .split('\n').forEach((с, и) => {
    if (/rgba\(\s*(255,\s*255,\s*255|0,\s*0,\s*0|10,\s*10,\s*10)\s*,/.test(с)) нетронутые.push((и + 1) + ': ' + с.trim().slice(0, 56));
});
console.log('\n  осталось сырых вуалей и подложек: ' + нетронутые.length);
нетронутые.forEach(с => console.log('     ' + с));

if (пиши) { fs.writeFileSync(пCss, css, 'utf8'); console.log('\n  ЗАПИСАНО'); }
else console.log('\n  (ничего не записано — запусти с --пиши)');
