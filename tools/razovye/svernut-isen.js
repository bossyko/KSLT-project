const fs = require('fs'), path = require('path');
const ПИСАТЬ = process.argv.includes('--писать');

function файлы(д) { let r = []; for (const и of fs.readdirSync(д)) { const п = path.join(д, и);
  const s = fs.statSync(п); if (s.isDirectory()) r = r.concat(файлы(п)); else if (и.endsWith('.js')) r.push(п); } return r; }

const { маска } = require('./maska.js');

const ОТКР = '([{', ЗАКР = ')]}';

/* ПРЕДШЕСТВЕННИК РЕШАЕТ, ГДЕ НАЧИНАЕТСЯ УСЛОВИЕ.
   `'' + isEn ? a : b` — условие это `'' + isEn`, и свернуть его как `isEn`
   значит ПОМЕНЯТЬ СМЫСЛ. Поэтому разрешены только те предшественники,
   после которых условие заведомо начинается с самого `isEn`. */
const РАЗРЕШЁННЫЕ = new Set(['(', ',', '=', '[', '{', ';', '?', ':', '&', '|', '']);
function предшественник(m, от) {
  let i = от - 1;
  while (i >= 0 && /\s/.test(m[i])) i--;
  if (i < 0) return { знак: '', слово: '' };
  /* слово перед: return, var, && , || */
  const хвост = m.slice(Math.max(0, i - 7), i + 1);
  const сл = /([A-Za-z_$][\w$]*)$/.exec(хвост);
  return { знак: m[i], слово: сл ? сл[1] : '', двойной: m.slice(i - 1, i + 1) };
}

/* от `?` ищем СВОЙ `:`, считая вложенные тернарники и скобки */
function свойДвоеточие(m, отВопроса) {
  let гл = 0, терн = 0;
  for (let i = отВопроса + 1; i < m.length; i++) {
    const c = m[i];
    if (ОТКР.includes(c)) gl: { гл++; continue; }
    if (ЗАКР.includes(c)) { if (гл === 0) return -1; гл--; continue; }
    if (гл) continue;
    if (c === '?') { терн++; continue; }
    if (c === ':') { if (терн) { терн--; continue; } return i; }
  }
  return -1;
}

const план = [], отказы = [];
for (const ф of файлы('js/admin')) {
  const t = fs.readFileSync(ф, 'utf8'), m = маска(t);
  const обр = /\bisEn\s*\?/g; let мм;
  while ((мм = обр.exec(m))) {
    const началоУсловия = мм.index;
    const вопрос = мм.index + мм[0].length - 1;
    /* `A.isEn ?` — условие начинается у `A` */
    const точка = m.slice(0, началоУсловия).match(/([A-Za-z_$][\w$]*)\.\s*$/);
    const старт = точка ? началоУсловия - точка[0].length : началоУсловия;
    const п = предшественник(m, старт);
    const строка = t.slice(0, старт).split('\n').length;
    if (п.двойной === '&&' || п.двойной === '||' || (п.знак && !РАЗРЕШЁННЫЕ.has(п.знак) && п.слово !== 'return' && п.слово !== 'var')) {
      отказы.push({ ф, строка, причина: 'предшественник `' + (п.двойной === '&&' || п.двойной === '||' ? п.двойной : (п.слово || п.знак)) + '` — условие шире, чем `isEn`',
                    текст: t.split('\n')[строка - 1].trim().slice(0, 90) });
      continue;
    }
    const двоеточие = свойДвоеточие(m, вопрос);
    if (двоеточие === -1) { отказы.push({ ф, строка, причина: 'не нашёл своё двоеточие', текст: t.split('\n')[строка - 1].trim().slice(0, 90) }); continue; }
    план.push({ ф, старт, конец: двоеточие + 1, строка, снято: t.slice(старт, двоеточие + 1) });
  }
}

const поФайлам = {};
план.forEach(п => (поФайлам[п.ф] = поФайлам[п.ф] || []).push(п));

console.log('\n  ПЛАН СВЁРТКИ `isEn ? A : B`  →  `B`');
console.log('  свернуть: ' + план.length + '   отказано: ' + отказы.length + '\n');
Object.entries(поФайлам).sort((a, b) => b[1].length - a[1].length)
  .forEach(([ф, сп]) => console.log('  ' + String(сп.length).padStart(4) + '  ' + ф));
if (отказы.length) {
  console.log('\n  ОТКАЗЫ — разбираются ЧТЕНИЕМ, а не прибором:');
  отказы.forEach(о => console.log('    ' + о.ф + ':' + о.строка + '\n        ' + о.причина + '\n        ' + о.текст));
}
/* длиннейшие снимаемые куски — глазами, прежде чем резать */
const длинные = план.slice().sort((a, b) => b.снято.length - a.снято.length).slice(0, 5);
console.log('\n  ПЯТЬ САМЫХ ДЛИННЫХ СНИМАЕМЫХ КУСКОВ (строк):');
длинные.forEach(п => console.log('    ' + String(п.снято.split('\n').length).padStart(5) + '  ' + п.ф + ':' + п.строка + '   ' + п.снято.slice(0, 60).replace(/\n/g, '⏎')));

if (!ПИСАТЬ) { console.log('\n  сухой прогон — ничего не записано\n'); process.exit(0); }

/* ── ЗАПИСЬ ── */
let всегоСнято = 0, файловТронуто = 0;
for (const [ф, сп] of Object.entries(поФайлам)) {
  const t = fs.readFileSync(ф, 'utf8');
  const былоЧисло = (маска(t).match(/\bisEn\s*\?/g) || []).length;
  let out = t;
  /* режем С КОНЦА, чтобы смещения не поехали */
  сп.slice().sort((a, b) => b.старт - a.старт).forEach(п => {
    out = out.slice(0, п.старт) + out.slice(п.конец).replace(/^[ \t]+/, '');
  });
  const сталоЧисло = (маска(out).match(/\bisEn\s*\?/g) || []).length;
  const ожидалось = былоЧисло - сп.length;
  if (сталоЧисло !== ожидалось) {
    console.log('  ОТКАЗ ПИСАТЬ ' + ф + ': ожидалось ' + ожидалось + ' тернарников, стало ' + сталоЧисло);
    continue;
  }
  const снятоСтрок = t.split('\n').length - out.split('\n').length;
  fs.writeFileSync(ф, out);
  всегоСнято += снятоСтрок; файловТронуто++;
  console.log('  ' + String(сп.length).padStart(4) + ' свёрнуто, ' + String(снятоСтрок).padStart(5) + ' строк снято   ' + ф);
}
console.log('\n  файлов тронуто ' + файловТронуто + ', строк снято ' + всегоСнято + '\n');
