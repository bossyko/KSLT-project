#!/usr/bin/env node
/**
 * СВЕРКА СДВИГОВ: ЧТО ИЗМЕНИЛОСЬ И НА СКОЛЬКО (08.11).
 *
 * ЗАЧЕМ. `217-sverka-vida.js` доказывает, что вид НЕ менялся вовсе, —
 * и это верный прибор для сведения знак в знак. Но приведение к шкале
 * вид МЕНЯЕТ намеренно: вуаль 0.06 становится ступенью 0.08. Прибор
 * «совпало или нет» на такой правке даёт 25 расхождений и выключается
 * целиком: ПРИБОР, КОТОРЫЙ КРИЧИТ ВОЛКАМИ, НЕ ЧИТАЮТ.
 *
 * ЧТО СЧИТАЕТ ЭТОТ. Для каждой изменённой строки разворачивает роль
 * обратно в краску и сравнивает с прежней ПО ВЕЛИЧИНЕ: отдельно тон
 * (rgb) и отдельно прозрачность. Тон обязан совпасть знак в знак;
 * прозрачность вправе сдвинуться на НАЗВАННУЮ величину — и прибор
 * показывает фактическую, чтобы цену называли числом, а не словом
 * «немного».
 *
 * ПОРОГ ВЗЯТ ИЗ ПРЕЖНИХ СВЕДЕНИЙ ЭТОГО ПРОДУКТА: шкала прозрачности
 * сводилась 13.10 со сдвигом до 0.10, лестница роли 17.10 — тоже до
 * 0.10. Здесь порог 0.03, и каждое место сверх него называется.
 *
 * Запуск: node tools/razovye/217-sverka-sdvigov.js <корень> <файл-до> [порог]
 */
const fs = require('fs');
const path = require('path');
const корень = process.argv[2];
const пДо = process.argv[3];
const ПОРОГ = parseFloat(process.argv[4] || '0.03');
/* Чистый чёрный к чернилам продукта (10,10,10) — ровно 30 по сумме. */
const ПОРОГ_ТОНА = 30;
if (!корень || !пДо) { console.log('нужен корень и файл-до'); process.exit(1); }

const токены = fs.readFileSync(path.join(корень, 'mobile/www/css/tokens.css'), 'utf8');
const знач = {};
/* ЧИТАЕМ ТОЛЬКО ТЁМНУЮ ТЕМУ. Прибор брал ПОСЛЕДНЕЕ объявление каждой
   роли, а с появлением блока `[data-theme="light"]` последним стало
   светлое: `--accent-text` разворачивался в #446000, и сверка объявила
   «тон поехал» на 57 правках, где он не двигался вовсе.
   ПРИБОР, ЧИТАЮЩИЙ ПОСЛЕДНЕЕ ОБЪЯВЛЕНИЕ, ВИДИТ НЕ ТУ ТЕМУ. */
{
    let вТеме = 0;
    токены.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
          .split('\n').forEach(с => {
        if (/\[data-theme=/.test(с)) вТеме = 1;
        if (вТеме) {
            вТеме += (с.match(/\{/g) || []).length - (с.match(/\}/g) || []).length;
            if (вТеме <= 1 && /\}/.test(с)) вТеме = 0;
            return;
        }
        const м = с.match(/^\s*(--[\w-]+)\s*:\s*([^;]+);/);
        if (м) знач[м[1]] = м[2].trim();
    });
}
function развернуть(в, г) {
    if (г > 6) return в;
    /* `var(--роль, запас)` — берём роль, запас мёртв, пока роль жива. */
    const м = в.match(/^var\(\s*(--[\w-]+)\s*(?:,[^)]*)?\)$/);
    return (м && знач[м[1]]) ? развернуть(знач[м[1]], г + 1) : в;
}

function разобрать(ц) {
    let м = ц.match(/^#([0-9a-fA-F]{3,8})$/);
    if (м) {
        let s = м[1];
        if (s.length === 3) s = s.split('').map(x => x + x).join('');
        return { r: parseInt(s.slice(0, 2), 16), g: parseInt(s.slice(2, 4), 16),
                 b: parseInt(s.slice(4, 6), 16),
                 a: s.length === 8 ? parseInt(s.slice(6, 8), 16) / 255 : 1 };
    }
    м = ц.match(/rgba?\(([^)]+)\)/i);
    if (м) {
        const ч = м[1].split(',').map(x => parseFloat(x.trim()));
        if (ч.slice(0, 3).some(isNaN)) return null;
        return { r: ч[0], g: ч[1], b: ч[2], a: ч.length > 3 ? ч[3] : 1 };
    }
    return null;
}

const ЦВЕТ = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)/g;
const ВАР = /var\(\s*(--[\w-]+)\s*(?:,[^)]*)?\)/g;

const до = fs.readFileSync(пДо, 'utf8').split('\n');
const после = fs.readFileSync(path.join(корень, 'mobile/www/css/app.css'), 'utf8').split('\n');
if (до.length !== после.length) {
    console.log('✗ разное число строк: ' + до.length + ' и ' + после.length);
    process.exit(1);
}

let строк = 0, тонПоехал = 0, вПороге = 0;
const сверхПорога = [], безТона = [];

for (let i = 0; i < до.length; i++) {
    if (до[i] === после[i]) continue;
    строк++;
    /* ПОРЯДОК ЦВЕТОВ БЕРЁТСЯ ПО МЕСТУ В СТРОКЕ, А НЕ ДВУМЯ ПРОХОДАМИ.
       Прежняя редакция собирала сначала все роли, потом все краски — и в
       строке `color: #0A0A0A; background: var(--accent)` ставила лайм
       первым. Пары смещались, и прибор давал Δтон=449 там, где тон не
       двигался вовсе. Тот же урок, что в `217-chto-slomaetsya.js`:
       СВОЙСТВО И ПОРЯДОК ЧИТАЮТСЯ ПО МЕСТУ, А НЕ ПО ДВУМ ПРОХОДАМ. */
    const краски = (строка) => {
        const найдено = [];
        ВАР.lastIndex = 0;
        let м;
        while ((м = ВАР.exec(строка)) !== null) {
            найдено.push({ место: м.index,
                           ц: разобрать(развернуть('var(' + м[1] + ')', 0)) });
        }
        /* Краски ищем в строке БЕЗ ролей — чтобы не поймать число внутри
           запаса роли, — но место запоминаем настоящее. */
        const безРолей = строка.replace(ВАР, с => ' '.repeat(с.length));
        ЦВЕТ.lastIndex = 0;
        while ((м = ЦВЕТ.exec(безРолей)) !== null) {
            найдено.push({ место: м.index, ц: разобрать(м[0]) });
        }
        return найдено.sort((a, b) => a.место - b.место)
                      .map(н => н.ц).filter(Boolean);
    };
    const старые = краски(до[i]);
    const новые = краски(после[i]);

    /* Сравниваем по порядку столько пар, сколько есть с обеих сторон. */
    const н = Math.min(старые.length, новые.length);
    for (let k = 0; k < н; k++) {
        const с = старые[k], п = новые[k];
        const dтон = Math.abs(с.r - п.r) + Math.abs(с.g - п.g) + Math.abs(с.b - п.b);
        const dа = Math.abs(с.a - п.a);
        if (dтон > ПОРОГ_ТОНА) {
            тонПоехал++;
            безТона.push({ строка: i + 1, до: до[i].trim().slice(0, 62),
                           после: после[i].trim().slice(0, 62), dтон: dтон });
        } else if (dа > ПОРОГ + 1e-9) {
            сверхПорога.push({ строка: i + 1, dа: dа.toFixed(2),
                               до: до[i].trim().slice(0, 56) });
        } else вПороге++;
    }
}

console.log('\nСВЕРКА СДВИГОВ (порог прозрачности ' + ПОРОГ + ')\n');
console.log('  изменённых строк: ' + строк);
console.log('  тон совпал, прозрачность в пороге: ' + вПороге);
console.log('  тон совпал, прозрачность СВЕРХ порога: ' + сверхПорога.length);
console.log('  ТОН ПОЕХАЛ (это беда, если не названо): ' + тонПоехал + '\n');

if (сверхПорога.length) {
    console.log('── СДВИГИ СВЕРХ ПОРОГА — КАЖДЫЙ ОБЯЗАН БЫТЬ НАЗВАН');
    сверхПорога.forEach(с => console.log('   ' + String(с.строка).padStart(5) +
        '  Δa=' + с.dа + '  ' + с.до));
    console.log('');
}
if (тонПоехал) {
    console.log('── ТОН ПОЕХАЛ');
    безТона.forEach(с => {
        console.log('   ' + String(с.строка).padStart(5) + '  Δтон=' + с.dтон);
        console.log('      до:    ' + с.до);
        console.log('      после: ' + с.после);
    });
}
process.exit(тонПоехал ? 1 : 0);
