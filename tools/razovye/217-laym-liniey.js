#!/usr/bin/env node
/**
 * ЛАЙМ КАК ЛИНИЯ И БУКВЫ -> --accent-text (08.11). Одноразовый.
 *
 * ЗАЧЕМ. `--accent` (#CCFF00) на белом даёт 1.18 — ниже любой планки.
 * Различение заведено давно и записано в токенах: `--accent` это
 * ЗАЛИВКА, `--accent-text` это БУКВЫ И ТОНКИЕ ЛИНИИ, и в светлой теме
 * второй уходит на #446000 (7.19 на белом). Но применено оно было не
 * везде: замер 08.11 нашёл 65 мест, где лаймом написаны обводка,
 * штрих, заливка значка или цвет букв.
 *
 * СРЕДИ НИХ ДВАДЦАТЬ ПЯТЬ ОБВОДОК ФОКУСА. Невидимая обводка фокуса —
 * это не «бледно», это человек с клавиатурой, который не знает, где
 * стоит. Планка доступности, а не вкус.
 *
 * ЧТО НЕ ТРОГАЕМ: блоки, где в том же правиле стоит
 * `background: var(--accent)`. Там линия идёт ПО лаймовой заливке и
 * обязана остаться лаймовой, иначе чип обведётся тёмным по светлому.
 * ОКРУЖЕНИЕ РЕШАЕТ, А НЕ СВОЙСТВО.
 *
 * ПОЧЕМУ ПЕРВАЯ РЕДАКЦИЯ ПРОПУСТИЛА ДЕСЯТЬ МЕСТ. Она резала файл по
 * примечаниям и искала блоки в кусках между ними — а примечание ВНУТРИ
 * блока разрезает сам блок, и `{...}` в куске уже не находится.
 * ПРИБОР, РЕЖУЩИЙ ФАЙЛ ПО ПРИМЕЧАНИЯМ, ТЕРЯЕТ БЛОКИ С ПРИМЕЧАНИЕМ
 * ВНУТРИ. Теперь примечания ГАСЯТСЯ пробелами той же длины: блоки
 * находятся целиком, места в оригинале совпадают знак в знак, а текст
 * примечаний остаётся нетронутым.
 *
 * ВИД ТЁМНОЙ ТЕМЫ НЕ МЕНЯЕТСЯ: `--accent-text` в ней равен
 * `var(--accent)` знак в знак. Это проверяется сверкой.
 *
 * Запуск: node tools/razovye/217-laym-liniey.js <корень> [--пиши]
 */
const fs = require('fs');
const path = require('path');
const корень = process.argv[2] || path.join(__dirname, '..', '..');
const пиши = process.argv.indexOf('--пиши') !== -1;
const пCss = path.join(корень, 'mobile/www/css/app.css');

const оригинал = fs.readFileSync(пCss, 'utf8');
/* ДЛИНА СОХРАНЯЕТСЯ — значит места в погашенном тексте и в оригинале
   совпадают, и правку можно класть по позиции. */
const погашен = оригинал.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

const ЛИНИЯ = /\b(color|border|border-color|border-top-color|border-bottom-color|border-left-color|border-right-color|outline|outline-color|fill|stroke|text-decoration-color|caret-color)(\s*:\s*[^;{}]*?)var\(--accent\)/g;
const БЛОК = /\{[^{}]*\}/g;

const правки = [];      // {от, до, на}
let пропущено = 0, б;
БЛОК.lastIndex = 0;
while ((б = БЛОК.exec(погашен)) !== null) {
    const тело = б[0], начало = б.index;
    const заливка = /background(-color)?:\s*[^;]*var\(--accent\)/.test(тело);
    ЛИНИЯ.lastIndex = 0;
    let м;
    while ((м = ЛИНИЯ.exec(тело)) !== null) {
        const местоVar = начало + м.index + м[1].length + м[2].length;
        if (заливка) { пропущено++; continue; }
        правки.push({ от: местоVar, до: местоVar + 'var(--accent)'.length,
                      на: 'var(--accent-text)' });
    }
}

/* Кладём с конца, чтобы места не поехали. */
let css = оригинал;
правки.sort((a, b) => b.от - a.от).forEach(п => {
    const было = css.slice(п.от, п.до);
    if (было !== 'var(--accent)') {
        throw new Error('место ' + п.от + ': ожидали var(--accent), нашли «' + было + '»');
    }
    css = css.slice(0, п.от) + п.на + css.slice(п.до);
});

console.log('\nЛАЙМ КАК ЛИНИЯ И БУКВЫ -> --accent-text\n');
console.log('  переведено: ' + правки.length);
console.log('  оставлено лаймом (линия по лаймовой заливке): ' + пропущено);

const осталось = [];
css.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
   .split('\n').forEach((с, и) => {
    ЛИНИЯ.lastIndex = 0;
    if (ЛИНИЯ.test(с)) осталось.push((и + 1) + ': ' + с.trim().slice(0, 62));
});
console.log('  осталось лаймовых линий: ' + осталось.length);
осталось.forEach(с => console.log('     ' + с));

if (пиши) { fs.writeFileSync(пCss, css, 'utf8'); console.log('\n  ЗАПИСАНО'); }
else console.log('\n  (ничего не записано — запусти с --пиши)');
