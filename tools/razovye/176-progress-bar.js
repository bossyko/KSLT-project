const КОРЕНЬ = path.join(__dirname, '..', '..');
const чит = п => { try { return fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8'); } catch (e) { return null; } };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

/* Все файлы продукта, без мобильного, проб и приборов. */
function собрать(корень, расш, кроме) {
    const итог = [];
    (function идти(д) {
        let сп = [];
        try { сп = fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }); } catch (e) { return; }
        сп.forEach(э => {
            const п = д ? д + '/' + э.name : э.name;
            if (кроме.some(к => п.indexOf(к) === 0 || п.indexOf('/' + к) !== -1)) return;
            if (э.isDirectory()) идти(п);
            else if (расш.some(р => э.name.endsWith(р))) итог.push(п);
        });
    })(корень);
    return итог;
}
