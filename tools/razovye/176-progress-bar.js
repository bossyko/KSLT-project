/* Сколько раз признак встречается во всех файлах набора. */
function счёт(набор, признак, безКомментариев) {
    let н = 0;
    набор.forEach(ф => {
        let т = чит(ф); if (т === null) return;
        if (безКомментариев) т = безКом(т);
        н += (т.match(признак) || []).length;
    });
    return н;
}
function файловС(набор, признак, безКомментариев) {
    return набор.filter(ф => {
        let т = чит(ф); if (т === null) return false;
        if (безКомментариев) т = безКом(т);
        return признак.test(т);
    });
}

