/* РАЗОВЫЙ ПРИБОР: СКОЛЬКО КУСКОВ ДО ЗАПИРАНИЯ ВСЕХ ФАЙЛОВ СО СКЛЕЙКАМИ.
   Слово Кости 25.10: «до конца». Решение зависит от количества мест в коде,
   значит СНАЧАЛА ПОСЧИТАТЬ, потом решать. Прибор ничего не правит.
   ВТОРОГО ПРИЗНАКА ЗДЕСЬ НЕТ: счёт по файлам берётся из того же
   `tools/priznak-dannye-v-razmetke.js` (`поФайлам`), а список запертых и
   названные места — ЧТЕНИЕМ сторожа, а не перенабором. */
const path = require('path');
const fs = require('fs');
const КОРЕНЬ = path.join(__dirname, '..', '..');
const признак = require(path.join(КОРЕНЬ, 'tools', 'priznak-dannye-v-razmetke.js'));

const поФайлам = признак.поФайлам();

const сторож = fs.readFileSync(path.join(КОРЕНЬ, 'tools', 'check-dannye-v-razmetku.js'), 'utf8');
function блок(имя) {
    const м = сторож.match(new RegExp('const ' + имя + ' = \\[([\\s\\S]*?)\\n\\];'));
    return м ? м[1] : '';
}
const ЗАПЕРТЫЕ = new Set([...блок('ЗАПЕРТЫЕ').matchAll(/'([^']+\.js)'/g)].map(x => x[1]));
/* НАЗВАННЫЕ_МЕСТА — тройки ['файл', 'выражение', 'почему']: берём ПЕРВЫЙ
   элемент каждой тройки, а не все строки подряд. */
const МЕСТА = [...блок('НАЗВАННЫЕ_МЕСТА').matchAll(/\[\s*'([^']+)'/g)].map(x => x[1]);
/* СПИСКА НАЗВАННЫХ ФАЙЛОВ БОЛЬШЕ НЕТ: снят куском 165 вместе со старым
   прибором правила 1. */
const НАЗВАННЫЕ_ФАЙЛЫ = [];

const именВФайле = {};
for (const ф of МЕСТА) именВФайле[ф] = (именВФайле[ф] || 0) + 1;
for (const ф of НАЗВАННЫЕ_ФАЙЛЫ) именВФайле[ф] = (именВФайле[ф] || 0) + 1;

const участвуют = Object.keys(поФайлам).filter(ф => поФайлам[ф].склеек > 0).sort();
const незаперто = участвуют.filter(ф => !ЗАПЕРТЫЕ.has(ф));

const строки = незаперто.map(ф => ({
    файл: ф,
    дыр: поФайлам[ф].дыр,
    вАтрибуте: поФайлам[ф].вАтрибуте,
    имён: именВФайле[ф] || 0,
    склеек: поФайлам[ф].склеек
})).sort((a, b) => (b.дыр - a.дыр) || (b.имён - a.имён) || a.файл.localeCompare(b.файл));

const чистые = строки.filter(с => с.дыр === 0 && с.имён === 0);
const толькоИмена = строки.filter(с => с.дыр === 0 && с.имён > 0);
const сДырами = строки.filter(с => с.дыр > 0);

function печать(имя, набор, подробно) {
    console.log('');
    console.log('  ' + имя + ': ' + набор.length + ' файлов, склеек ' +
                набор.reduce((s, с) => s + с.склеек, 0) +
                ', дыр ' + набор.reduce((s, с) => s + с.дыр, 0) +
                ', имён ' + набор.reduce((s, с) => s + с.имён, 0));
    if (подробно) for (const с of набор) {
        console.log('    · ' + с.файл.replace(/^js\//, '') +
                    '  склеек ' + с.склеек +
                    (с.дыр ? ', ДЫР ' + с.дыр + (с.вАтрибуте ? ' (в атрибутах ' + с.вАтрибуте + ')' : '') : '') +
                    (с.имён ? ', имён ' + с.имён : ''));
    }
}

console.log('');
console.log('  ФАЙЛОВ СО СКЛЕЙКАМИ: ' + участвуют.length +
            ', заперто ' + участвуют.filter(ф => ЗАПЕРТЫЕ.has(ф)).length +
            ', незаперто ' + незаперто.length);
console.log('  ЗАПЕРТЫХ В СПИСКЕ СТОРОЖА: ' + ЗАПЕРТЫЕ.size);
console.log('  НАЗВАННЫХ МЕСТ: ' + МЕСТА.length + ', названных файлов: ' + НАЗВАННЫЕ_ФАЙЛЫ.length);

печать('А · ЗАПИРАЮТСЯ ХОТЬ СЕЙЧАС, ЦЕНА НОЛЬ', чистые, true);
печать('Б · ДЕРЖАТСЯ ТОЛЬКО ИМЕНАМИ — ПРАВОК НЕТ, НУЖЕН РАЗБОР ИМЕНИ', толькоИмена, true);
печать('В · ТРЕБУЮТ ПРАВОК', сДырами, true);

console.log('');
console.log('  ЦЕНА ДОВЕДЕНИЯ ДО КОНЦА, ПОСЧИТАННАЯ, А НЕ НАЗВАННАЯ НА ГЛАЗ:');
console.log('    правок (дыр): ' + сДырами.reduce((s, с) => s + с.дыр, 0) +
            ' в ' + сДырами.length + ' файлах');
console.log('    имён на разбор: ' + толькоИмена.reduce((s, с) => s + с.имён, 0) +
            ' в ' + толькоИмена.length + ' файлах');
console.log('    файлов без работы вовсе: ' + чистые.length);
console.log('');
