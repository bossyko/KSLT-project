#!/usr/bin/env node
/**
 * РАЗБОР СЫРЫХ ЦВЕТОВ ПО НАЗНАЧЕНИЮ (08.11). Одноразовый, замерочный.
 *
 * ЗАЧЕМ. Светлая тема переопределяет РОЛИ, а не краски. Цвет, написанный
 * краской, о теме не знает. Прежний прибор (`217-svesti-cveta.js`)
 * подставил роли там, где значение совпало ЗНАК В ЗНАК — безопасно и
 * молча. Остаток совпадений не имеет, и его нельзя свести скопом:
 * `#0A0A0A` стоит и фоном страницы, и цветом букв на лаймовой кнопке.
 * ЗНАЧЕНИЕ СОВПАЛО, А СМЫСЛ РАЗНЫЙ.
 *
 * ЧТО ДЕЛАЕТ. Берёт каждый сырой цвет и называет его НАЗНАЧЕНИЕ по тому
 * свойству, в котором он стоит, и по селектору блока. Отдаёт таблицу:
 * строка, селектор, свойство, цвет, назначение. Ничего не меняет.
 *
 * Запуск: node tools/razovye/217-razbor-po-smyslu.js <корень>
 */
const fs = require('fs');
const path = require('path');
const корень = process.argv[2] || path.join(__dirname, '..', '..');
const файл = path.join(корень, 'mobile/www/css/app.css');
const текст = fs.readFileSync(файл, 'utf8');

/* Примечания выбрасываем, но ДЛИНУ СОХРАНЯЕМ — иначе номера строк
   уедут, и таблица будет указывать не туда.
   ПРИБОР, КОТОРЫЙ ВРЁТ НОМЕРОМ СТРОКИ, ХУЖЕ ОТСУТСТВУЮЩЕГО. */
const код = текст.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

const ЦВЕТ = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)/g;
const строки = код.split('\n');

/* СЕЛЕКТОР БЕРЁТСЯ ПОИСКОМ ВВЕРХ до ближайшей открывающей скобки: это
   то, чему цвет принадлежит, а не то, что стоит рядом. */
function селектор(и) {
    let глубина = 0;
    for (let j = и; j >= 0; j--) {
        const с = строки[j];
        for (let k = с.length - 1; k >= 0; k--) {
            if (с[k] === '}') глубина++;
            else if (с[k] === '{') {
                if (глубина === 0) {
                    const до = (j === и ? с.slice(0, k) : с.slice(0, k));
                    const вс = (до.trim() || (строки[j - 1] || '').trim());
                    if (/^@/.test(вс)) { глубина = 0; break; }   /* медиа — идём выше */
                    return вс.replace(/\s+/g, ' ').slice(0, 54);
                }
                глубина--;
            }
        }
    }
    return '(верхний уровень)';
}

/* НАЗНАЧЕНИЕ — ЭТО СВОЙСТВО ПЛЮС МЕСТО, а не сам цвет. */
function назначение(свойство, сел, цвет, строка) {
    if (/--on-image|\.hh[\s.{,-]|\.splash/.test(сел + строка)) return 'поверх фото и сплэш — темы не знает';
    if (/telegram|apple|google|\.auth-social/.test(сел)) return 'бренд чужой — темы не знает';
    if (/shadow/.test(свойство)) return 'тень — своя в каждой теме';
    if (/gradient/.test(строка)) return 'градиент фона';
    if (/^color$/.test(свойство)) return 'цвет букв';
    if (/border|outline/.test(свойство)) return 'обводка';
    if (/background/.test(свойство)) {
        if (/rgba\(\s*(255,\s*255,\s*255|0,\s*0,\s*0|10,\s*10,\s*10)/.test(цвет)) return 'вуаль фона';
        return 'фон блока';
    }
    if (/fill|stroke/.test(свойство)) return 'рисунок';
    return 'прочее: ' + свойство;
}

const находки = [];
строки.forEach((с, и) => {
    const м = с.match(ЦВЕТ);
    if (!м) return;
    const св = (с.match(/^\s*([-a-z]+)\s*:/) || [])[1] ||
               (с.match(/[{;]\s*([-a-z]+)\s*:/) || [])[1] || '?';
    м.forEach(ц => находки.push({
        строка: и + 1, цвет: ц, свойство: св,
        селектор: селектор(и), назначение: назначение(св, селектор(и), ц, с),
        текст: с.trim().slice(0, 62),
    }));
});

const кучи = {};
находки.forEach(н => (кучи[н.назначение] = кучи[н.назначение] || []).push(н));

console.log('\nРАЗБОР СЫРЫХ ЦВЕТОВ ПО НАЗНАЧЕНИЮ — ' + находки.length + ' мест\n');
Object.keys(кучи).sort((a, b) => кучи[b].length - кучи[a].length).forEach(к => {
    console.log('── ' + к.toUpperCase() + ' (' + кучи[к].length + ')');
    кучи[к].forEach(н => {
        console.log('   ' + String(н.строка).padStart(5) + '  ' + н.цвет.padEnd(24) +
                    '  ' + н.селектор);
    });
    console.log('');
});
