#!/usr/bin/env node
/**
 * СЫРОЙ ЦВЕТ → ГОТОВАЯ РОЛЬ (08.11). Одноразовый, но проверяемый.
 *
 * ЗАЧЕМ. Светлая тема переопределяет РОЛИ. Цвет, написанный мимо роли,
 * о теме не знает и остаётся тёмным — ровно поэтому вчерашняя светлая
 * тема вышла дырявой: шесть правил спорили со 138 зашитыми цветами.
 *
 * ЧТО ДЕЛАЕТ. Читает токены приложения, строит обратный словарь
 * «значение → имя роли» и заменяет в `app.css` только ТОЧНЫЕ совпадения
 * значений. Ничего не переименовывает и не придумывает: если роли с
 * таким значением нет — строка остаётся как была и попадает в отчёт.
 *
 * ПОЧЕМУ ЭТО БЕЗОПАСНО ДЛЯ ВИДА. Подстановка значение-в-значение: в
 * тёмной теме `var(--alpha-white-08)` разворачивается ровно в
 * `rgba(255, 255, 255, 0.08)`. ВИД РАБОТЫ НЕ МЕНЯЕТСЯ, ЧИНИТСЯ
 * ВНУТРЕННОСТЬ — и это проверяется замером до и после, а не на глаз.
 *
 * Запуск:  node svesti-cveta.js <корень> [--пиши]
 * Без `--пиши` только считает и показывает, что сделал бы.
 */
const fs = require('fs');
const path = require('path');

const корень = process.argv[2];
const пиши = process.argv.indexOf('--пиши') !== -1;
if (!корень) { console.log('нужен путь к корню'); process.exit(1); }

const пТокены = path.join(корень, 'mobile/www/css/tokens.css');
const пCss = path.join(корень, 'mobile/www/css/app.css');

/* ── 1. СЛОВАРЬ РОЛЕЙ ────────────────────────────────────────────── */
const токены = fs.readFileSync(пТокены, 'utf8');
const прямой = {};                       // имя → значение (как написано)
токены.replace(/\/\*[\s\S]*?\*\//g, '')
      .split('\n').forEach(с => {
    const м = с.match(/^\s*(--[\w-]+)\s*:\s*([^;]+);/);
    if (м) прямой[м[1]] = м[2].trim();
});

/* Разворачиваем ссылки `var(--x)` до настоящего значения: роль может
   указывать на роль, а сравнивать надо с краской. */
function развернуть(знач, глубина) {
    if (глубина > 6) return знач;
    const м = знач.match(/^var\(\s*(--[\w-]+)\s*\)$/);
    if (м && прямой[м[1]]) return развернуть(прямой[м[1]], глубина + 1);
    return знач;
}

/* ЦВЕТ СРАВНИВАЕТСЯ ПО ЧИСЛАМ, А НЕ ПО НАПИСАНИЮ. `rgba(255,255,255,.08)`
   и `rgba(255, 255, 255, 0.08)` — один цвет, и прибор обязан это видеть,
   иначе половина мест останется ненайденной. */
function ключ(ц) {
    const м = ц.match(/rgba?\(([^)]+)\)/i);
    if (м) {
        const ч = м[1].split(',').map(x => x.trim());
        const a = ч.length > 3 ? String(parseFloat(ч[3])) : '1';
        return 'rgba:' + ч.slice(0, 3).map(x => String(parseInt(x, 10))).join(',') + ',' + a;
    }
    const h = ц.match(/^#([0-9a-fA-F]{3,8})$/);
    if (h) {
        let s = h[1].toLowerCase();
        if (s.length === 3) s = s.split('').map(x => x + x).join('');
        if (s.length === 8 && s.slice(6) === 'ff') s = s.slice(0, 6);
        return 'hex:' + s;
    }
    return null;
}

const обратный = {};                     // ключ → имя роли
Object.keys(прямой).forEach(имя => {
    /* ПОДСТАВЛЯЕМ ТОЛЬКО РОЛИ НАЗНАЧЕНИЯ (08.11, после первой пробы).
       ЗНАЧЕНИЕ СОВПАЛО, А СМЫСЛ РАЗНЫЙ — вот чем опасна подстановка по
       краске. Прибор заменил `color: #0A0A0A` на `var(--bg-base)`: в
       тёмной теме цвет тот же, а в светлой `--bg-base` станет БЕЛЫМ, и
       чёрная надпись на лаймовой кнопке исчезнет. То же вышло с `#fff`
       → `--text-primary` на чёрной кнопке Apple. Сверка вида это и
       поймала: 21 строка из 66.
       Поэтому берём только вуали и подложки (`--alpha-*`, `-subtle`,
       `-faint`): у них назначение написано в имени, и в светлой теме они
       меняются ПРАВИЛЬНО — вуаль остаётся вуалью. Поверхности, текст и
       краски палитры разбираются по одной, руками и по смыслу. */
    if (!/^--(alpha-|.*-subtle$|.*-faint$)/.test(имя)) return;
    const знач = развернуть(прямой[имя], 0);
    const к = ключ(знач);
    if (!к) return;
    /* ПЕРВОЕ ИМЯ ПОБЕЖДАЕТ — но осмысленное важнее сырого: роль со
       словом alpha/subtle/faint описывает НАЗНАЧЕНИЕ, краска — нет. */
    const осмысленная = /alpha|subtle|faint|bg|text|border|surface|overlay/.test(имя);
    if (!обратный[к] || (осмысленная && !/alpha|subtle|faint|bg|text|border|surface|overlay/.test(обратный[к]))) {
        обратный[к] = имя;
    }
});

/* ── 2. ЗАМЕНА В app.css ─────────────────────────────────────────── */
let css = fs.readFileSync(пCss, 'utf8');
const ЦВЕТ = /#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)/g;

let заменено = 0;
const нетРоли = {};
const пропущено = [];

/* Примечания не трогаем: цвет в пояснении — не цвет на экране. */
const куски = css.split(/(\/\*[\s\S]*?\*\/)/);
for (let i = 0; i < куски.length; i++) {
    if (i % 2 === 1) continue;                 // это примечание
    куски[i] = куски[i].split('\n').map(строка => {
        /* СТРОКУ, ГДЕ ЦВЕТ ЛЕЖИТ НА ФОТОГРАФИИ, НЕ ТРОГАЕМ: у неё своя
           поверхность, и тема ей не указ. */
        if (/--on-image|\.hh[\s.{,-]/.test(строка)) { return строка; }
        /* Объявления самих ролей тоже мимо: роль не ссылается на себя. */
        if (/^\s*--[\w-]+\s*:/.test(строка)) { return строка; }
        /* ЗАПАСНОЕ ЗНАЧЕНИЕ ВНУТРИ `var(...)` — НЕ ТРОГАЕМ. Оно для
           случая, когда роль не объявлена вовсе; заменив его на ту же
           роль, мы оставили бы `var(--x, var(--x))` — запас, который
           ничего не запасает. */
        if (/var\(\s*--[\w-]+\s*,/.test(строка)) { return строка; }
        return строка.replace(ЦВЕТ, ц => {
            const к = ключ(ц);
            if (!к) return ц;
            const роль = обратный[к];
            if (!роль) { нетРоли[ц] = (нетРоли[ц] || 0) + 1; return ц; }
            заменено++;
            return 'var(' + роль + ')';
        });
    }).join('\n');
}
css = куски.join('');

console.log('\nСЫРОЙ ЦВЕТ → ГОТОВАЯ РОЛЬ\n');
console.log('  ролей в словаре: ' + Object.keys(обратный).length);
console.log('  подставлено: ' + заменено);
const без = Object.keys(нетРоли);
console.log('  осталось без роли: ' + без.reduce((с, к) => с + нетРоли[к], 0) +
            ' (разных: ' + без.length + ')\n');
без.sort((a, b) => нетРоли[b] - нетРоли[a]).slice(0, 25).forEach(ц => {
    console.log('   ' + String(нетРоли[ц]).padStart(3) + '×  ' + ц);
});

if (пиши) {
    fs.writeFileSync(пCss, css, 'utf8');
    console.log('\n  ЗАПИСАНО в mobile/www/css/app.css');
} else {
    console.log('\n  (ничего не записано — запусти с --пиши)');
}
