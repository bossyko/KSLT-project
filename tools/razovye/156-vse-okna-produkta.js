const fs = require('fs');
const path = require('path');
const acorn = require(path.join(__dirname, '..', '..', 'node_modules', 'acorn'));

const КОРЕНЬ = path.join(__dirname, '..', '..');
const чит = о => fs.readFileSync(path.join(КОРЕНЬ, о), 'utf8');

function всеJS(дир, итог) {
    итог = итог || [];
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        const п = path.join(дир, э.name);
        if (э.isDirectory()) всеJS(п, итог);
        else if (э.name.endsWith('.js')) итог.push(path.relative(КОРЕНЬ, п).split(path.sep).join('/'));
    }
    return итог;
}
const файлы = всеJS(path.join(КОРЕНЬ, 'js'));

/* Страницы считаются ОДИН раз на файл: обход всех html на каждое окно
   занимал минуты. */
const страницПоФайлу = {};
(function собрать() {
    const все = [];
    (function обойти(дир) {
        for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
            if (э.name.startsWith('.')) continue;
            const п = path.join(дир, э.name);
            if (э.isDirectory()) {
                if (['node_modules','test-results','mobile','lib','playwright-report','tests','tools'].indexOf(э.name) !== -1) continue;
                обойти(п);
            } else if (э.name.endsWith('.html')) все.push(п);
        }
    })(КОРЕНЬ);
    все.forEach(п => {
        const т = fs.readFileSync(п, 'utf8');
        const обр = /<script[^>]*\ssrc="([^"]+)"/g;
        let м;
        while ((м = обр.exec(т))) {
            const ф = м[1].split('?')[0].replace(/^(\.\.\/)+/, '');
            (страницПоФайлу[ф] = страницПоФайлу[ф] || new Set()).add(path.relative(КОРЕНЬ, п));
        }
    });
})();

/* МЕСТО СОЗДАНИЯ ПОДЛОЖКИ. Два написания: присваивание className и
   classList.add. Классы продукта: *-overlay, *-modal-overlay, ad-modal-… */
const ПОДЛОЖКА = /(?:className\s*=\s*|classList\.add\(\s*)['"]([a-zA-Zа-яА-Я0-9_-]*(?:overlay|modal|подложк)[a-zA-Zа-яА-Я0-9_ -]*)['"]/g;

const окна = [];
файлы.forEach(ф => {
    const т = чит(ф);
    let д;
    try { д = acorn.parse(т, { ecmaVersion: 2020, locations: true }); } catch (e) { return; }

    /* Все функции файла со своими границами — чтобы найти объемлющую. */
    const функции = [];
    (function поДереву(у) {
        if (!у || typeof у !== 'object') return;
        if (Array.isArray(у)) { у.forEach(поДереву); return; }
        if (у.type === 'FunctionDeclaration' || у.type === 'FunctionExpression' ||
            у.type === 'ArrowFunctionExpression') {
            функции.push({ начало: у.start, конец: у.end, строка: у.loc.start.line,
                           имя: (у.id && у.id.name) || null });
        }
        for (const к in у) if (к !== 'loc' && к !== 'start' && к !== 'end') поДереву(у[к]);
    })(д);

    let м;
    ПОДЛОЖКА.lastIndex = 0;
    const занятые = new Set();
    while ((м = ПОДЛОЖКА.exec(т))) {
        /* Ближайшая объемлющая — самая КОРОТКАЯ из тех, что накрывают место. */
        const накрывают = функции.filter(ф2 => ф2.начало <= м.index && м.index < ф2.конец);
        if (!накрывают.length) continue;
        const своя = накрывают.sort((a, b) => (a.конец - a.начало) - (b.конец - b.начало))[0];
        /* Подложка могла получить класс и вторым зовом (`classList.add('active')`
           рядом) — одно окно на одну объемлющую функцию. */
        const ключ = своя.начало + ':' + своя.конец;
        if (занятые.has(ключ)) continue;
        занятые.add(ключ);

        const тело = т.slice(своя.начало, своя.конец);
        окна.push({
            файл: ф,
            строка: т.slice(0, м.index).split('\n').length,
            имя: своя.имя || 'без имени, строка функции ' + своя.строка,
            класс: м[1],
            /* ДВЕ ЗАКОННЫЕ ФОРМЫ: `запереть` (дом с куска 152) и `оснастить`
               (кусок 156, даёт четвёрку одним зовом). Признак, знавший одну,
               соврал в ту же минуту, когда появилась вторая: я оснастил 16
               окон, а прибор сказал «без запирания 32», как и до правки. */
            запирание: /KSLT_FOKUS\s*\.\s*(запереть|оснастить)/.test(тело),
            домВФайле: /KSLT_FOKUS\s*\.\s*(запереть|оснастить)/.test(т),
            escape: /['"]Escape['"]/.test(тело),
            role: /role\s*=\s*\\?["']dialog|setAttribute\(\s*['"]role['"]/.test(тело),
            ariaModal: /aria-modal/.test(тело),
            фокусВнутрь: /\.focus\(\)/.test(тело),
            строкТела: тело.split('\n').length
        });
    }
});

const поФайлам = {};
окна.forEach(о => { (поФайлам[о.файл] = поФайлам[о.файл] || []).push(о); });

let безЗапирания = 0, подозрительных = 0;
const страницПодУдаром = new Set();
console.log('ОКОН НАЙДЕНО ПРИЗНАКОМ: ' + окна.length + ' в ' + Object.keys(поФайлам).length + ' файлах');
console.log('');
Object.keys(поФайлам).sort((a, b) => {
    const са = (страницПоФайлу[b] ? страницПоФайлу[b].size : 0);
    const сб = (страницПоФайлу[a] ? страницПоФайлу[a].size : 0);
    return са - сб;
}).forEach(ф => {
    const стр = страницПоФайлу[ф] ? страницПоФайлу[ф].size : 0;
    const плохие = поФайлам[ф].filter(о => !о.запирание);
    безЗапирания += плохие.length;
    подозрительных += плохие.filter(о => о.домВФайле).length;
    if (плохие.length && страницПоФайлу[ф]) страницПоФайлу[ф].forEach(с => страницПодУдаром.add(с));
    console.log(ф + '  · окон ' + поФайлам[ф].length + ' · страниц ' + стр +
                (плохие.length ? '  <-- БЕЗ ЗАПИРАНИЯ: ' + плохие.length : '  (все заперты)'));
    поФайлам[ф].forEach(о => {
        console.log('        :' + о.строка + '  ' + о.имя + '  .' + о.класс + '  — ' + [
            о.запирание ? 'ЗАПЕРТО' : 'НЕ ЗАПЕРТО',
            о.escape ? 'Escape' : 'нет Escape',
            о.role ? 'role' : 'нет role',
            о.ariaModal ? 'aria-modal' : 'нет aria-modal',
            о.фокусВнутрь ? 'фокус внутрь' : 'нет фокуса'
        ].join(' · ') + (!о.запирание && о.домВФайле ? '   [запирание есть в файле — ПРОВЕРИТЬ ЗОВОМ]' : ''));
    });
});
console.log('');
console.log('ИТОГ: окон ' + окна.length + ', без запирания ' + безЗапирания +
            ', из них под вопросом ' + подозрительных + ' (запирание есть в файле)');
console.log('      страниц, где живёт хоть одно незапертое окно: ' + страницПодУдаром.size);
