/** Сколько файлов набора содержат признак, и какие (до трёх имён). */
function где(набор, признак, безКомментариев) {
    const нашлось = [];
    набор.forEach(ф => {
        let т = чит(ф); if (т === null) return;
        if (безКомментариев) т = безКом(т);
        const м = т.match(признак);
        if (м) нашлось.push(ф + ':' + (т.slice(0, т.search(признак)).split('\n').length));
    });
    return нашлось;
}

