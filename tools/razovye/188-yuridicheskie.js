const КОРЕНЬ = path.join(__dirname, '..', '..');
const чит = п => { try { return fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8'); } catch (e) { return null; } };
/* КОММЕНТАРИИ ГАСЯТСЯ ПРОБЕЛАМИ, А НЕ ВЫРЕЗАЮТСЯ: вырезанный комментарий
   сдвигает все строки ниже, и номер в отчёте начинает показывать чужую
   строку. Первый заход этого прибора так и показал `js/auth.js:833` —
   закрывающую скобку вместо находки. НОМЕР СТРОКИ, КОТОРЫЙ ВРЁТ, ХУЖЕ
   ОТСУТСТВУЮЩЕГО. */
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/^([ \t]*)\/\/[^\n]*$/gm, (м, о) => о + ' '.repeat(Math.max(0, м.length - о.length)));

function собрать(корень, расш, кроме) {
    const из = [];
    (function идти(д) {
        let сп = [];
        try { сп = fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }); } catch (e) { return; }
        сп.forEach(э => {
            const п = д ? д + '/' + э.name : э.name;
            if (кроме.some(к => п === к || п.indexOf(к + '/') === 0)) return;
            if (э.isDirectory()) идти(п);
            else if (расш.some(р => э.name.endsWith(р))) из.push(п);
        });
    })(корень);
    return из;
}
