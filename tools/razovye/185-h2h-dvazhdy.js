const раз = s => {
    let м = s.match(/^#([0-9a-f]{6})$/i);
    if (м) return [parseInt(м[1].slice(0,2),16), parseInt(м[1].slice(2,4),16), parseInt(м[1].slice(4,6),16), 1];
    м = s.match(/rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)\s*(?:[,/]\s*([\d.]+))?\s*\)/i);
    if (м) return [+м[1], +м[2], +м[3], м[4] === undefined ? 1 : +м[4]];
    throw new Error('не разобрал краску: ' + s);
};
/** слои снизу вверх: нижний непрозрачен */
function плоско(слои) {
    let низ = раз(слои[0]).slice(0,3);
    for (let i = 1; i < слои.length; i++) {
        const с = раз(слои[i]);
        низ = [0,1,2].map(k => с[k] * с[3] + низ[k] * (1 - с[3]));
    }
    return низ;
}
const свет = rgb => {
    const [r,g,b] = rgb.map(v => { const s = v/255; return s <= 0.03928 ? s/12.92 : Math.pow((s+0.055)/1.055, 2.4); });
    return 0.2126*r + 0.7152*g + 0.0722*b;
};
const контраст = (текст, слои) => {
    const ф = плоско(слои);
    const т = плоско(слои.concat([текст]));
    const a = свет(т), b = свет(ф);
    return ((Math.max(a,b)+0.05)/(Math.min(a,b)+0.05));
};

