/** ТОЛЬКО БЛОКИ ВЕРХНЕГО УРОВНЯ: блок внутри @media стоит с отступом, и
    если смешать его с базовым, замер соврёт — базовое значение затрётся
    поправкой для узкого вида. Поправки считаются отдельно. */
function блоки(текст) {
    const карта = {};
    const т = безКом(текст);
    const при = /^([ \t]*)([^\n{}]*?)\{([^}]*)\}/gm;
    let м;
    карта.__медиа = 0;
    while ((м = при.exec(т)) !== null) {
        const отступ = м[1], сел = м[2].trim().replace(/\s+/g, ' ');
        if (сел.indexOf('.h2h-') === -1) continue;
        if (отступ.length) { карта.__медиа++; continue; }
        const свойства = {};
        м[3].split(';').forEach(с => {
            const i = с.indexOf(':');
            if (i === -1) return;
            свойства[с.slice(0, i).trim()] = с.slice(i + 1).trim().replace(/\s+/g, ' ');
        });
        if (Object.keys(свойства).length) карта[сел] = свойства;
    }
    return карта;
}
