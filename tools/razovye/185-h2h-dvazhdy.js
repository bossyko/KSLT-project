/* ── 5. ΔE ТРЁХ ЧУЖИХ КРАСОК ДО СИСТЕМНЫХ ────────────────────────────── */
/* CIE76 по Lab — тот же счёт, каким мерены краски 19.10. */
function лаб(hex) {
    let [r, g, b] = раз(hex).slice(0, 3).map(v => v / 255);
    [r, g, b] = [r, g, b].map(v => v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4));
    const X = (r * 0.4124 + g * 0.3576 + b * 0.1805) / 0.95047;
    const Y = (r * 0.2126 + g * 0.7152 + b * 0.0722);
    const Z = (r * 0.0193 + g * 0.1192 + b * 0.9505) / 1.08883;
    const ф = v => v > 0.008856 ? Math.cbrt(v) : (7.787 * v + 16 / 116);
    const [fx, fy, fz] = [ф(X), ф(Y), ф(Z)];
    return [116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)];
}
const дЕ = (a, b) => { const A = лаб(a), B = лаб(b);
    return Math.sqrt(Math.pow(A[0]-B[0],2) + Math.pow(A[1]-B[1],2) + Math.pow(A[2]-B[2],2)); };

