#!/usr/bin/env node
/**
 * РОЛИ-ПРИЗРАКИ: ЗОВУТ ТО, ЧЕГО НЕТ (08.11).
 *
 * ЗАЧЕМ. `var(--роль)` у необъявленной роли молча даёт ПУСТО, а
 * `var(--роль, запас)` молча даёт ЗАПАС — и то и другое светлая тема не
 * перекроет никогда, потому что перекрывать нечего. Нашлось случайно:
 * поле ввода звало `var(--input-bg, rgba(255,255,255,0.06))`, а
 * `--input-bg` в системе НЕ ОБЪЯВЛЕН ВОВСЕ.
 *
 * ПРАВИЛО: РОЛЬ, КОТОРОЙ НЕТ, ДЕЛАЕТ ЗАПАС ПОСТОЯННЫМ ЗНАЧЕНИЕМ.
 *
 * ЧТО ДЕЛАЕТ. Собирает все зовы `var(--...)` в одежде приложения и
 * сличает с объявлениями в токенах и в самой одежде. Отдельно считает
 * зовы С запасом при ЖИВОЙ роли — запас там мёртвый и врёт про цвет.
 *
 * Запуск: node tools/razovye/217-roli-prizraki.js <корень>
 */
const fs = require('fs');
const path = require('path');
const корень = process.argv[2] || path.join(__dirname, '..', '..');

const файлы = ['mobile/www/css/tokens.css', 'mobile/www/css/app.css'];
const объявлено = new Set();
файлы.forEach(ф => {
    fs.readFileSync(path.join(корень, ф), 'utf8')
      .replace(/\/\*[\s\S]*?\*\//g, '')
      .split('\n').forEach(с => {
        const м = с.match(/^\s*(--[\w-]+)\s*:/);
        if (м) объявлено.add(м[1]);
    });
});

const одежда = fs.readFileSync(path.join(корень, 'mobile/www/css/app.css'), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

const призраки = {}, мёртвыйЗапас = {};
одежда.split('\n').forEach((с, и) => {
    for (const м of с.matchAll(/var\(\s*(--[\w-]+)\s*(,\s*[^)]*)?\)/g)) {
        const имя = м[1], запас = м[2];
        if (!объявлено.has(имя)) {
            (призраки[имя] = призраки[имя] || []).push(и + 1);
        } else if (запас) {
            (мёртвыйЗапас[имя] = мёртвыйЗапас[имя] || []).push(и + 1);
        }
    }
});

console.log('\nРОЛИ-ПРИЗРАКИ В ОДЕЖДЕ ПРИЛОЖЕНИЯ\n');
console.log('  объявлено ролей: ' + объявлено.size);
const п = Object.keys(призраки);
console.log('  ЗОВУТ НЕОБЪЯВЛЕННОЕ: ' + п.length + ' имён, ' +
            п.reduce((с, и) => с + призраки[и].length, 0) + ' мест\n');
п.sort((a, b) => призраки[b].length - призраки[a].length).forEach(и => {
    console.log('   ' + String(призраки[и].length).padStart(3) + '×  ' + и.padEnd(24) +
                '  строки: ' + призраки[и].slice(0, 8).join(', ') +
                (призраки[и].length > 8 ? ' …' : ''));
});

const з = Object.keys(мёртвыйЗапас);
console.log('\n  ЗАПАС ПРИ ЖИВОЙ РОЛИ (мёртвый код, врёт про цвет): ' +
            з.reduce((с, и) => с + мёртвыйЗапас[и].length, 0) + ' мест');
з.forEach(и => console.log('   ' + и.padEnd(24) + '  строки: ' + мёртвыйЗапас[и].join(', ')));
