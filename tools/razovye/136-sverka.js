/* ДОКАЗАТЕЛЬСТВО: текстовые части фразы не изменились.
   Для куска — значение ключа равно прежнему тексту.
   Для фразы — шаблон, из которого убраны места подстановки, равен
   склейке прежних литералов. Подстановки сверить статически нельзя:
   их значения известны только на ходу. */
const fs = require('fs');
const св = JSON.parse(fs.readFileSync('/tmp/сверка136.json', 'utf8'));

const m = fs.readFileSync('js/admin/core/constants.js', 'utf8');
const н = m.indexOf('var L ='), о = m.indexOf('{', н);
let г = 0, з = -1;
for (let i = о; i < m.length; i++) { if (m[i] === '{') г++; else if (m[i] === '}') { г--; if (!г) { з = i; break; } } }
const знач = {}; г = 0;
for (let i = о; i <= з; i++) {
  const c = m[i];
  if (c === '{' || c === '[') г++; else if (c === '}' || c === ']') г--;
  if (г === 1) {
    const мм = /^[\s,]*([A-Za-z_$][\w$]*)\s*:\s*('(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*")/.exec(m.slice(i));
    if (мм) {
      знач[мм[1]] = мм[2].slice(1, -1).replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\\\/g, '\\');
      i += мм[0].length - 1;
    }
  }
}
let ок = 0; const беды = [];
св.куски.forEach(к => {
  if (знач[к.ключ] === к.текст) ок++;
  else беды.push('кусок ' + к.ключ + ': |' + к.текст + '| -> |' + знач[к.ключ] + '|');
});
св.фразы.forEach(ф => {
  const вСловаре = знач[ф.ключ];
  if (вСловаре === undefined) { беды.push('фраза ' + ф.ключ + ': ключа нет'); return; }
  /* убираем места подстановки и сравниваем с прежней склейкой текстов */
  /* ТОТ ЖЕ КЛАСС, ЧТО В ДОМЕ: иначе сверялка «не видит» кириллическое
     имя подстановки и объявляет расхождение там, где его нет. */
  const безМест = вСловаре.replace(/\{[A-Za-zА-Яа-яЁё0-9_$]+\}/g, '\u0000');
  const прежде = ф.текстовыеЧасти.join('\u0000');
  const чисто = s => s.split('\u0000').join('');
  if (чисто(безМест) === чисто(прежде)) ок++;
  else беды.push('фраза ' + ф.ключ + ':\n      было  |' + чисто(прежде).slice(0, 90) +
                 '|\n      стало |' + чисто(безМест).slice(0, 90) + '|');
});
console.log(JSON.stringify({ 'проверено': св.куски.length + св.фразы.length,
  'совпало ЗНАК В ЗНАК': ок, 'расходятся': беды.length }, null, 1));
беды.slice(0, 8).forEach(б => console.log('  x ' + б));
if (беды.length) process.exit(1);
