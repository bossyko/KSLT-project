const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..', '..');
const ЗАПИСИ = JSON.parse(fs.readFileSync(path.join(__dirname, '176c-priznaki.json'), 'utf8'));

function собрать(расш, кроме) {
    const итог = [];
    (function идти(д) {
        let сп = [];
        try { сп = fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }); } catch (e) { return; }
        сп.forEach(э => {
            const п = д ? д + '/' + э.name : э.name;
            if (кроме.some(к => п === к || п.indexOf(к + '/') === 0)) return;
            if (э.isDirectory()) идти(п);
            else if (расш.some(р => э.name.endsWith(р))) итог.push(п);
        });
    })('');
    return итог;
}
const ФАЙЛЫ = собрать(['.js', '.css', '.html', '.ts', '.sql'],
    ['node_modules', '.git', 'test-results', 'tools']);
const ТЕКСТ = {};
ФАЙЛЫ.forEach(ф => { try { ТЕКСТ[ф] = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'); } catch (e) {} });

/** Сколько файлов содержат признак и сколько всего вхождений. */
function искать(признак) {
    let файлов = 0, всего = 0;
    const где = [];
    const чистый = признак.replace(/\*$/, '');   // `.hero-stat-*` -> `.hero-stat-`
    Object.keys(ТЕКСТ).forEach(ф => {
        const части = ТЕКСТ[ф].split(чистый).length - 1;
        if (части > 0) { файлов++; всего += части; if (где.length < 3) где.push(ф); }
    });
    return { файлов, всего, где };
}

const итог = [];
ЗАПИСИ.forEach(з => {
    const найдено = з.признаки.map(([род, п]) => {
        const р = искать(п);
        return { род, признак: п, файлов: р.файлов, всего: р.всего, где: р.где };
    });
    const живых = найдено.filter(н => н.всего > 0).length;
    итог.push({ стр: з.стр, первая: з.первая, раздел: з.раздел, найдено, живых });
});

console.log('');
console.log('  ДВОЙНАЯ ПРОВЕРКА ОТКРЫТЫХ ЗАПИСЕЙ ПО КОДУ — ' + итог.length + ' записей');
console.log('');
const мёртвые = итог.filter(и => и.живых === 0);
console.log('  ПРЕДМЕТА ЗАПИСИ В КОДЕ НЕТ ВОВСЕ — ' + мёртвые.length +
            ' записей. ЧИТАТЬ И, СКОРЕЕ ВСЕГО, ЗАКРЫВАТЬ:');
мёртвые.forEach(и => {
    console.log('    трекер:' + и.стр + '  ' + и.первая);
    console.log('        не найдено: ' + и.найдено.map(н => '`' + н.признак + '`').join(', '));
});
console.log('');
const частично = итог.filter(и => и.живых > 0 && и.живых < и.найдено.length);
console.log('  ЧАСТЬ ПРИЗНАКОВ ПРОПАЛА — ' + частично.length + ' записей (запись устарела наполовину):');
частично.forEach(и => {
    console.log('    трекер:' + и.стр + '  ' + и.первая);
    и.найдено.forEach(н => console.log('        ' + (н.всего ? 'жив  ' : 'НЕТ  ') +
        '`' + н.признак + '`' + (н.всего ? ' — ' + н.всего + ' вхождений в ' + н.файлов + ' файлах' : '')));
});
console.log('');
console.log('  ВСЕ ПРИЗНАКИ ЖИВЫ — ' + итог.filter(и => и.живых === и.найдено.length).length +
            ' записей: предмет на месте, запись честно открыта.');
console.log('');
