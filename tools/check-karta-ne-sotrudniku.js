/**
 * ЗАМОРОЗКА КУСКА 143 — КАРТОЧКА ИГРОКА НЕ ЗАВОДИТСЯ СОТРУДНИКУ.
 *
 * Кусок 142 снял обход: роль больше не даёт членства. Этот кусок закрывает
 * вторую половину того же решения — «под рабочей почтой они не играют», —
 * со стороны, где карточку заводят РУКАМИ: админка.
 *
 * ЧТО БЫЛО ПОМЕРЕНО 23.10:
 *   · `autoCreatePlayer` в `js/admin/sections/users.js` создавал карточку и
 *     привязывал её к профилю, НЕ СПРАШИВАЯ РОЛЬ вовсе. Админ мог завести
 *     карточку сотруднику, пока кабинет и членство уже считали, что тот не
 *     играет;
 *   · заявку на привязку от профиля сотрудника одобрить было нечем
 *     остановить (подать её из кабинета нельзя с куска 142, но прежние
 *     заявки могли остаться);
 *   · решение было записано СЛОВАМИ в трёх местах админки («членства у
 *     сотрудников нет и быть не может») — и ни одного правила рядом.
 *
 * ОДНО СЛОВО — ТРИ ПОНЯТИЯ, и это главное, из-за чего правило здесь
 * устроено связкой, а не запретом сравнения:
 *   · `A.currentRole === 'admin'` — ЧТО ПОЗВОЛЕНО МНЕ (25 мест);
 *   · `usrFilterRole === 'admin'` — ВЫБРАННЫЙ ФИЛЬТР списка;
 *   · `u.role === 'manager'` поодиночке — ИМЕННО МЕНЕДЖЕР, не «сотрудник».
 * Сводится только четвёртое: связка `роль === 'admin' || роль === 'manager'`
 * об одном и том же человеке — она и есть предикат «сотрудник клуба».
 *
 *   node tools/check-karta-ne-sotrudniku.js
 */
const fs = require('fs');
const path = require('path');
const acorn = require('acorn');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const ПОТОЛОК_СРАВНЕНИЙ = 5;   /* фильтр ×2, «именно менеджер», счёт ролей ×2 */

function обойти(у, дело, род) {
    if (!у || typeof у.type !== 'string') return;
    дело(у, род);
    for (const к of Object.keys(у)) {
        if (к === 'type' || к === 'start' || к === 'end' || к === 'loc') continue;
        const v = у[к];
        if (Array.isArray(v)) v.forEach(x => x && typeof x.type === 'string' && обойти(x, дело, у));
        else if (v && typeof v.type === 'string') обойти(v, дело, у);
    }
}
const дерево = т => acorn.parse(т, { ecmaVersion: 2020, locations: true });

function файлыАдминки() {
    const out = [];
    (function о(д) {
        fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
            const п = path.join(д, э.name);
            if (э.isDirectory()) { о(п); return; }
            if (э.name.endsWith('.js')) out.push(п);
        });
    })('js/admin');
    return out;
}

/* ---- 1. предикат живёт в доме админки ---- */
const УТИЛ = чит('js/admin/core/utils.js');
let предикатВДоме = false;
обойти(дерево(УТИЛ), (у, род) => {
    if (у.type === 'FunctionExpression' && род && род.type === 'AssignmentExpression' &&
        УТИЛ.slice(род.left.start, род.left.end) === 'A.сотрудник') предикатВДоме = true;
});
правило('предикат сотрудника объявлен в доме админки',
    предикатВДоме,
    'В `js/admin/core/utils.js` нет `A.сотрудник`. Понятие «этот человек —\n' +
    'сотрудник клуба» должно быть объявлено один раз: оно уже стоило\n' +
    'противоречия между кабинетом и членством.');

/* ---- 2. связка двух ролей вне дома не пишется ---- */
const связки = [];
файлыАдминки().forEach(ф => {
    if (/core[\/\\]utils\.js$/.test(ф)) return;
    let дер;
    try { дер = дерево(чит(ф)); } catch (e) { return; }
    const т = чит(ф);
    обойти(дер, у => {
        if (у.type !== 'LogicalExpression' || у.operator !== '||') return;
        const части = [у.left, у.right].map(ч => ч && ч.type === 'BinaryExpression' &&
            ч.operator === '===' && ч.right && ч.right.type === 'Literal' ? ч : null);
        if (!части[0] || !части[1]) return;
        const роли = части.map(ч => ч.right.value).sort().join(',');
        const кто = части.map(ч => т.slice(ч.left.start, ч.left.end));
        /* `A.currentRole === 'admin' || A.currentRole === 'manager'` — ЭТО
           НЕ ПРЕДИКАТ СОТРУДНИКА, а «мне позволено вести членство»: речь о
           смотрящем, а не о том, на кого смотрят. Первая запись правила их
           не различала и назвала бедой два законных места. */
        if (кто[0] === 'A.currentRole') return;
        if (роли === 'admin,manager' && кто[0] === кто[1]) связки.push(ф + ':' + у.loc.start.line);
    });
});
правило('связка двух ролей вне дома не пишется',
    связки.length === 0,
    'Предикат «сотрудник» снова написан на месте:\n' + связки.map(с => '  ' + с).join('\n') + '\n' +
    'Это понятие живёт в `A.сотрудник`. Своя копия — вторая правда о том,\n' +
    'кто играет, а кто ведёт клуб.');

/* ---- 3. храповик на одиночные сравнения ролей ---- */
const одиночные = [];
файлыАдминки().forEach(ф => {
    if (/core[\/\\]utils\.js$/.test(ф)) return;
    let дер;
    try { дер = дерево(чит(ф)); } catch (e) { return; }
    const т = чит(ф);
    обойти(дер, у => {
        if (у.type === 'BinaryExpression' && у.operator === '===' &&
            у.right && у.right.type === 'Literal' &&
            (у.right.value === 'admin' || у.right.value === 'manager')) {
            if (т.slice(у.left.start, у.left.end) === 'A.currentRole') return;  /* мои права */
            одиночные.push(ф + ':' + у.loc.start.line);
        }
    });
});
правило('одиночных сравнений с ролью не прибавилось',
    одиночные.length <= ПОТОЛОК_СРАВНЕНИЙ,
    'Сравнений с ролью вне дома: ' + одиночные.length + ', потолок ' + ПОТОЛОК_СРАВНЕНИЙ + '\n' +
    одиночные.map(с => '  ' + с).join('\n') + '\n' +
    'Законные пять: выбранный ФИЛЬТР списка (две), «ИМЕННО менеджер» в\n' +
    'правах на модерацию и СЧЁТ админов и менеджеров по отдельности (две).\n' +
    'Шестое — повод спросить, не предикат ли это снова.');
правило('потолок сравнений не завышен',
    одиночные.length >= ПОТОЛОК_СРАВНЕНИЙ,
    'Сравнений ' + одиночные.length + ' при потолке ' + ПОТОЛОК_СРАВНЕНИЙ +
    ' — ХРАПОВИК ОПУСКАЕТСЯ: поправь ПОТОЛОК_СРАВНЕНИЙ на ' + одиночные.length + '.');

/* ---- 4. карточка не заводится сотруднику, и отказ ГОВОРИТСЯ ---- */
const ЛЮДИ = чит('js/admin/sections/users.js');
let стражКарточки = false, отказГоворится = false, заявкаПодУсловием = false;
{
    const дер = дерево(ЛЮДИ);
    обойти(дер, у => {
        if (у.type !== 'FunctionDeclaration' || !у.id || у.id.name !== 'autoCreatePlayer') return;
        обойти(у.body, в => {
            if (в.type !== 'IfStatement' || !в.test) return;
            const тест = ЛЮДИ.slice(в.test.start, в.test.end);
            if (тест.indexOf('A.сотрудник') === -1) return;
            стражКарточки = true;
            const тело = ЛЮДИ.slice(в.consequent.start, в.consequent.end);
            if (тело.indexOf('showToast') !== -1 && тело.indexOf('usrStaffNoCardErr') !== -1) отказГоворится = true;
        });
    });
    /* заявка на привязку: кнопка одобрения под условием о роли */
    обойти(дер, у => {
        if (у.type !== 'ConditionalExpression' || !у.test) return;
        const тест = ЛЮДИ.slice(у.test.start, у.test.end);
        const ветви = ЛЮДИ.slice(у.start, у.end);
        if (тест.indexOf('A.сотрудник') !== -1 && ветви.indexOf('ad-link-yes') !== -1) заявкаПодУсловием = true;
    });
}
правило('карточка игрока не заводится сотруднику',
    стражКарточки,
    'В `autoCreatePlayer` нет условия о роли. Сюда приходят из сохранения\n' +
    'пользователя: выбрана категория, карточки нет — значит её создают, и\n' +
    'до куска 143 роль здесь не спрашивалась вовсе.');
правило('отказ говорится, а не молчит',
    отказГоворится,
    'Отказ завести карточку стал тихим возвратом. Молчаливый отказ\n' +
    'читается как «кнопка не работает»: НЕЗАПОЛНЕННОЕ МЕСТО ДОЛЖНО\n' +
    'БРОСАТЬСЯ В ГЛАЗА (правило куска 136).');
правило('заявку на привязку от сотрудника не одобряют',
    заявкаПодУсловием,
    'Кнопка одобрения заявки снова рисуется всем. Подать заявку сотрудник\n' +
    'из кабинета больше не может, но прежние заявки могли остаться —\n' +
    'и одобрить их было нечем остановить.');

/* ---- 5. фразы отказа лежат в словаре, а не в коде ---- */
const СЛОВАРЬ = чит('js/admin/core/constants.js');
const ключи = new Set();
обойти(дерево(СЛОВАРЬ), у => {
    if (у.type === 'Property' && у.key && (у.key.name || у.key.value)) ключи.add(у.key.name || у.key.value);
});
['usrStaffNoCardErr', 'linkStaffNo'].forEach(к => {
    правило('фраза `' + к + '` лежит в словаре',
        ключи.has(к),
        'Ключа `' + к + '` в словаре админки нет. Фраза, собранная в коде,\n' +
        'не ищется и не переводится (правила кусков 135 и 136).');
});

/* ---- 6. роль читается там, где решают о заявке ---- */
let рольВЗапросе = false;
обойти(дерево(ЛЮДИ), у => {
    /* ИЩЕТСЯ ИМЕННО ТОТ ЗАПРОС, А НЕ ЛЮБОЙ ПОХОЖИЙ. Первая запись правила
       искала литерал с `full_name` и `role` по всему файлу — и находила
       запрос СПИСКА пользователей, который берёт роль по своим делам.
       Откат, снявший роль у заявок, правило не уронил. Теперь поиск идёт
       внутри тела `нарисоватьЗаявкиНаКарточку`. */
    if (у.type !== 'FunctionDeclaration' || !у.id ||
        у.id.name !== 'нарисоватьЗаявкиНаКарточку') return;
    обойти(у.body, в => {
        if (в.type === 'Literal' && typeof в.value === 'string' &&
            в.value.indexOf('full_name') !== -1 && в.value.indexOf('role') !== -1) рольВЗапросе = true;
    });
});
правило('роль читается в запросе заявок на карточку',
    рольВЗапросе,
    'Запрос профилей для заявок перестал брать `role` — значит условие о\n' +
    'сотруднике получит `undefined` и ПРОПУСТИТ его. Правило, которому\n' +
    'нечего читать, молча разрешает.');

/* ---- 7. кабинет не предлагает сотруднику привязку ---- */
const КАБИНЕТ = чит('js/dashboard.js');
let подсказокПодУсловием = 0;
обойти(дерево(КАБИНЕТ), у => {
    if (у.type !== 'IfStatement' || !у.test) return;
    const тест = КАБИНЕТ.slice(у.test.start, у.test.end);
    if (тест.indexOf('player_id') !== -1 && тест.indexOf('сотрудник') !== -1) подсказокПодУсловием++;
});
правило('кабинет не предлагает сотруднику привязать карточку',
    подсказокПодУсловием === 2,
    'Мест, где подсказка о карточке укрыта условием о сотруднике: ' +
    подсказокПодУсловием + ', замерено 2 (разметка и отрисовка).\n' +
    'Одно без другого даёт пустую коробку или подсказку сотруднику.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      карточка не заводится сотруднику: ' +
        (fs.readFileSync(__filename, 'utf8').match(/правило\('/g) || []).length + ' правил');
    console.log('          предикат один: A.сотрудник; связок двух ролей вне дома ноль');
    console.log('          одиночных сравнений с ролью: ' + одиночные.length + ' из ' + ПОТОЛОК_СРАВНЕНИЙ +
                ' — фильтр, «именно менеджер», счёт');
    console.log('');
} else {
    console.log('');
    console.log('  НЕ ТАК  карточка не заводится сотруднику — ' + ошибки.length + ' правил не держится');
    console.log('');
    ошибки.forEach(([и, п]) => {
        console.log('          x ' + и);
        п.split('\n').forEach(л => console.log('            ' + л));
        console.log('');
    });
    process.exit(1);
}
