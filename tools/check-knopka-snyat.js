/**
 * ЗАМОРОЗКА: «СНЯТЬ» — ТИШЕ «ИЗМ.», И ГРОМЧЕ ТАМ, ГДЕ ОНА ЛЕЧЕНИЕ.
 *
 * Слово Кости 01.10: «кнопку снять можно будет делать только активной у
 * кого было изменения… а то админ будет путаться нажимать изменять».
 * Решение из трёх вариантов — первый: кнопка остаётся везде, но по виду
 * тише, а на клетке с дублем или расхождением встаёт в краску пометки.
 *
 * ЧТО ЗАМЕРЕНО 01.10 (браузер, фон клетки `#111`):
 *   «Изм.»  — `rgb(204,255,0)`, лайм
 *   «Снять» — `rgb(204,255,0)`, ТОТ ЖЕ ЛАЙМ
 * Правило `.ad-brk-clear { color: var(--text-dim) }` стояло в файле ВЫШЕ
 * `.ad-brk-edit`. У кнопки оба класса, вес одинаковый — побеждал тот, что
 * ниже. Комментарий над правилом обещал «не должно спорить по яркости», а
 * правило не работало НИ ОДНОГО ДНЯ. Это и есть путаница, на которую
 * Костя показал: две одинаковые кнопки рядом.
 *
 * ПРАВИЛО ДЕРЖИТСЯ НА ДОСТИЖИМОСТИ, А НЕ НА ПРИСУТСТВИИ ТЕКСТА: мало,
 * чтобы краска была написана — она должна побеждать.
 *
 * КОНТРАСТ ПОМЕРЕН, А НЕ ВЫБРАН НА ГЛАЗ: `--text-secondary` на `#111`
 * даёт 9.98, `--warning` — 9.25, оба проходят WCAG 1.4.3 при кегле 11.
 * `--text-dim` дал бы 3.21 и провалил.
 *
 *   node tools/check-knopka-snyat.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const CSS  = чит('css/admin.css');
const CSSч = безКом(CSS);
const СЕТч = безКом(чит('js/admin/sections/bracket.js'));

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ── 1. КРАСКА «СНЯТЬ» ПОБЕЖДАЕТ, А НЕ ПРОСТО НАПИСАНА ──────────────── */
const поз = сел => {
    const i = CSSч.search(new RegExp('^' + сел.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{', 'm'));
    return i;
};
const пЧист = поз('.ad-brk-clear');
const пПрав = поз('.ad-brk-edit');

правило('краска «Снять» объявлена ниже краски «Изм.»',
    пЧист > -1 && пПрав > -1 && пЧист > пПрав,
    'в css/admin.css `.ad-brk-clear` снова стоит ВЫШЕ `.ad-brk-edit`. У ' +
    'кнопки оба класса и одинаковый вес — побеждает тот, что ниже, и ' +
    '«Снять» выходит тем же лаймом, что «Изм.». Замер 01.10: ровно это и ' +
    'было, а комментарий над правилом обещал обратное');

/* ── 2. ТИХАЯ КРАСКА — ПОМЕРЕННАЯ, А НЕ ЛЮБАЯ ───────────────────────── */
const телоЧист = (CSSч.slice(пЧист).match(/\{([^}]*)\}/) || ['', ''])[1];

правило('«Снять» не лаймовая',
    !/--accent|204\s*,\s*255\s*,\s*0|#CCFF00/i.test(телоЧист),
    '`.ad-brk-clear` взяла акцентную краску. Снятие — действие редкое и ' +
    'необратимое: спорить по яркости с «Изм.» ему незачем');

правило('«Снять» взяла померенную краску',
    /color:\s*var\(--text-secondary\)/.test(телоЧист),
    '`.ad-brk-clear` сменила краску мимо замера. На фоне клетки `#111` ' +
    '`--text-secondary` даёт 9.98, а `--text-dim` — 3.21 и провал WCAG ' +
    '1.4.3 при кегле 11. Новая краска меряется в браузере ДО того, как ' +
    'станет решением');

/* ── 3. АКЦЕНТ ТОЛЬКО ТАМ, ГДЕ СНЯТИЕ — ЛЕЧЕНИЕ ─────────────────────── */
правило('у горячей «Снять» краска пометки, а не своя',
    /\.ad-brk-clear\.ad-brk-clear-hot\s*\{[^}]*--warning[^}]*\}/.test(CSSч),
    '`.ad-brk-clear-hot` перестала брать `--warning`. Кнопка обязана ' +
    'читаться заодно с пометкой, которая её и позвала: инструкция ' +
    '«снимите счёт» и кнопка — одно действие, а не два разных');

правило('горячей кнопка становится по ДВУМ тонам, а не по одному',
    /лечитПометку\s*=\s*!!пометка\s*&&\s*\(\s*пометка\.тон === 'dup' \|\| пометка\.тон === 'mismatch'\s*\)/.test(СЕТч),
    'акцент у «Снять» держится не на обоих тонах. Дубль тяжелее ' +
    'расхождения: если оставить акцент только у оранжевого расхождения, ' +
    'самая опасная беда останется без видимого лечения. `same` — земляки ' +
    '— снятием не лечится и акцента не получает');

/* `indexOf` отдаёт -1, когда строки НЕТ, и -1 меньше чего угодно:
   правило, написанное одним сравнением, молчало бы и при пропавшем
   чтении пометки. Поэтому сперва требуем, чтобы обе строки нашлись. */
const iПометка = СЕТч.indexOf('var пометка = пометки[match.id];');
const iГорячая = СЕТч.indexOf('ad-brk-clear-hot');
правило('пометка читается ДО кнопок',
    iПометка > -1 && iГорячая > -1 && iПометка < iГорячая,
    'пометку снова читают ПОСЛЕ кнопок — тогда к моменту отрисовки ' +
    '«Снять» неизвестно, лечит она что-нибудь или нет, и акцент не ' +
    'поставить');

/* ── 4. ВЫСОТА КНОПОК ОДНА ───────────────────────────────────────────
   Полоса из двух кнопок не должна делать клетку выше соседних:
   соединительные линии считаются от середины блока. */
правило('обе кнопки живут в одной полосе',
    /\.ad-brk-actions\s*\{[^}]*display:\s*flex/.test(CSSч) &&
    /ad-brk-actions.*?>.*?<button class="ad-brk-edit"/s.test(СЕТч.replace(/\n/g, ' ')),
    '«Снять» выехала из полосы `.ad-brk-actions`. Второй строкой клетка ' +
    'становится выше соседних, и позиция матчей в следующем круге ' +
    'накапливает расхождение от круга к кругу');

/* ── вывод ───────────────────────────────────────────────────────────── */
if (ошибки.length) {
    console.log('✗ Кнопка «Снять»: ' + ошибки.length + ' правил упало\n');
    ошибки.forEach(о => console.log('  • ' + о.имя + '\n    ' + о.подсказка + '\n'));
    process.exit(1);
}
console.log('✓ Кнопка «Снять» — тише «Изм.», громче при пометке: все правила держат');
