function всеФайлы(каталог, окончание, собрано) {
    собрано = собрано || [];
    let список;
    try { список = fs.readdirSync(каталог, { withFileTypes: true }); }
    catch (e) { return собрано; }
    список.forEach(з => {
        const п = path.join(каталог, з.name);
        if (з.isDirectory()) всеФайлы(п, окончание, собрано);
        else if (з.name.endsWith(окончание)) собрано.push(п);
    });
    return собрано;
}

const задания = new Map();   // имя функции -> где её зовут
всеФайлы(path.join(КОРЕНЬ, 'sql'), '.sql').forEach(ф => {
    const т = fs.readFileSync(ф, 'utf8');
    const при = /позвать_функцию\(\s*'([a-z0-9-]+)'/g;
    let м;
    while ((м = при.exec(т)) !== null) {
        const строка = т.slice(0, м.index).split('\n').length;
        if (!задания.has(м[1])) задания.set(м[1], []);
        задания.get(м[1]).push(path.relative(КОРЕНЬ, ф) + ':' + строка);
    }
});

