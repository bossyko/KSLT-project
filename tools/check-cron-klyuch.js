/* ПРАВИЛО ЧИТАЕТ КОД, А НЕ ПРИМЕЧАНИЯ. Первый прогон упал на шести
   функциях — и правильно падать ему было не на чем: `.includes(` стоял
   в примечании, где процитирован прежний, плохой код. Сторож, который
   ловит разговор о беде вместо беды, врёт в обе стороны.
   Двойные косые внутри адресов (`https://`) прикрываются, чтобы
   съёмщик примечаний не отрезал конец строки с настоящим кодом. */
function безПримечаний(т) {
    return т.replace(/:\/\//g, ':\u0000\u0000')
            .replace(/\/\*[\s\S]*?\*\//g, ' ')
            .replace(/\/\/[^\n]*/g, ' ')
            .replace(/:\u0000\u0000/g, '://');
}

