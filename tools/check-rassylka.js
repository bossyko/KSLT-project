#!/usr/bin/env node
/**
 * РАССЫЛКА — НЕОБРАТИМОЕ ДЕЙСТВИЕ НАЗЫВАЕТ ЧИСЛО (h222, 12.11.2026).
 *
 * Рассылку нельзя отозвать: письмо и телеграм уходят сразу. Окно
 * спрашивало «отправить выбранной аудитории?» и НЕ говорило, скольким —
 * то есть просило согласия на действие, размер которого человек не видел.
 *
 * ЧТО СТОРОЖИТСЯ:
 *   1. подтверждение перед отправкой есть и стоит ДО зова сервера;
 *   2. в теле подтверждения называется число людей в выборке;
 *   3. отбор для счёта повторяет серверный: all — профили, members —
 *      активные нeистёкшие членства (supabase/functions/broadcast);
 *   4. счёт — ЧТЕНИЕ: head/count, без изменения данных;
 *   5. названа разница между «в выборке» и «получат»: согласие и канал
 *      отсеивают часть уже на сервере.
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, ' ');

const ошибки = [];
const правило = (имя, условие, почему) => { if (!условие) ошибки.push(имя + ' — ' + почему); };

const б = безКом(чит('js/admin/sections/broadcast.js'));
const словарь = чит('js/admin/core/constants.js');

правило('подтверждение перед отправкой есть',
    /showConfirmAsync\(/.test(б),
    'рассылка уходит без вопроса — отозвать её нельзя');

const iПодтв = б.indexOf('showConfirmAsync');
const iЗов = б.indexOf("'broadcast'");
правило('подтверждение стоит ДО зова сервера',
    iПодтв !== -1 && iЗов !== -1 && iПодтв < iЗов,
    'вопрос задаётся после отправки — это не вопрос, а уведомление');

/* ПРИЗНАК, НАХОДЯЩИЙ СЕБЯ В ОБЪЯВЛЕНИИ, НИЧЕГО НЕ СТОРОЖИТ — третий раз
   за сутки. Первая редакция искала «посчитатьПолучателей(audience)», а
   ровно это написано в САМОЙ сигнатуре функции: выброси зов — правило
   осталось бы зелёным. Спрашивается ЗОВ С ОЖИДАНИЕМ. */
правило('число людей в выборке считается',
    /await\s+посчитатьПолучателей\s*\(/.test(б) && /async function посчитатьПолучателей/.test(б),
    'счёт получателей пропал — окно снова просит согласия, не называя размера');

правило('число попадает в тело подтверждения',
    /showConfirmAsync\(\s*L\.broadcastConfirm\s*,\s*тело/.test(б) &&
    /broadcastVVyborke/.test(б),
    'число посчитано, но в окно не передано');

правило('отбор повторяет серверный: all — профили, members — активные членства',
    /audience === 'all'[\s\S]{0,200}from\('profiles'\)/.test(б) &&
    /audience === 'members'[\s\S]{0,300}from\('memberships'\)[\s\S]{0,200}eq\('status', 'active'\)[\s\S]{0,200}gte\('expires_at'/.test(б),
    'клиент считает не тех, кому уйдёт: отбор разошёлся с supabase/functions/broadcast');

правило('счёт — чтение, а не правка',
    /count: 'exact', head: true/.test(б) && !/\.(insert|update|delete)\(/.test(б),
    'в счёт получателей попала запись в базу — считать можно только чтением');

правило('разница «в выборке» и «получат» названа',
    /broadcastSkolkoDoydyot/.test(б) &&
    /broadcastSkolkoDoydyot:/.test(словарь),
    'без этой строки число читается как «столько получат», а сервер отсеет часть по согласию и каналу');

правило('не посчитали — окно всё равно открывается',
    /=== null/.test(б),
    'при сбое счёта окно должно открыться без числа, а не молча показать ноль');

if (ошибки.length) {
    console.error('РАССЫЛКА — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
console.log('рассылка: 8 правил держатся');
