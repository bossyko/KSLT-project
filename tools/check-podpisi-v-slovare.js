/* ЛЕКСЕР: идём по файлу и знаем, где литерал, где код, где комментарий.
   Регулярка этого не умеет — в строке с текстом ` (` она видит скобку,
   литерал и скобку и принимает КУСОК ЧУЖОГО ТЕКСТА за группировку.
   На замере это дало 3 ложных из 329. */
function литералы(т) {
  const из = [];
  let i = 0, строка = 1;
  while (i < т.length) {
    const c = т[i];
    if (c === '\n') { строка++; i++; continue; }
    if (c === '/' && т[i + 1] === '/') { while (i < т.length && т[i] !== '\n') i++; continue; }
    if (c === '/' && т[i + 1] === '*') {
      i += 2;
      while (i < т.length && !(т[i] === '*' && т[i + 1] === '/')) { if (т[i] === '\n') строка++; i++; }
      i += 2; continue;
    }
    if (c === "'" || c === '"' || c === '`') {
      const кав = c, начало = i, нс = строка;
      i++;
      while (i < т.length) {
        if (т[i] === '\\') { i += 2; continue; }
        if (т[i] === кав) break;
        if (т[i] === '\n') { строка++; if (кав !== '`') break; }
        i++;
      }
      из.push({ начало, конец: i, строка: нс, знач: т.slice(начало + 1, i) });
      i++; continue;
    }
    i++;
  }
  return из;
}

