/**
 * ЗАМОРОЗКА РАЗДЕЛА «О ПРОЕКТЕ КСЛТ» `#about` НА ГЛАВНОЙ.
 *
 * Доска 427:9, компонент Feature icon 429:191, решения Кости 24.09:
 * плитки становятся ссылками, иконки — объёмная плашка, «Всё о КСЛТ» ведёт
 * на info.html, «Сообщество» — на partners.html.
 *
 * ГЛАВНОЕ ЗДЕСЬ — ОТНОШЕНИЯ И ЕДИНСТВЕННОСТЬ:
 *   • сетка возможностей идёт во всю ширину, а не в колонке рядом с фото;
 *   • у каждого понятия ОДНО определение — мёртвого правила в том же
 *     условии больше нет;
 *   • порядок на узком: смысл → навигация → снимок;
 *   • имя строго крупнее строки под ним на каждом виде;
 *   • внутри секции нет --text-dim и нет эмодзи;
 *   • отношение сторон фотографии — свойство файла, а не высота числом.
 *
 *   node tools/check-about.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СТИ = безКом(чит('css/style.css'));
const СТР = { ru: чит('index.html'), en: чит('index-en.html'), kg: чит('index-kg.html') };

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };
const сколько = (т, р) => (т.match(р) || []).length;

function слои(текст) {
    const вых = [];
    const рег = /@media[^{]*\{/g;
    let м;
    while ((м = рег.exec(текст)) !== null) {
        let i = рег.lastIndex, d = 1;
        while (d && i < текст.length) { if (текст[i] === '{') d++; else if (текст[i] === '}') d--; i++; }
        вых.push({ текст: текст.slice(м.index, i), начало: м.index });
    }
    return вых;
}
const ВСЕ = слои(СТИ);
const ЦЕЛЬ = /\.about-|\.feature/;
const свои = ВСЕ.filter(с => ЦЕЛЬ.test(с.текст));
/* Базовый слой — файл БЕЗ медиазапросов. Без этого правило про базу ловит
   одноимённое объявление из узкого слоя: подстрока нашлась, правило зелёное,
   а держит оно чужой блок. */
const БАЗА = ВСЕ.reduce((т, с) => т.replace(с.текст, ''), СТИ);
const слой = усл => свои.find(с => new RegExp(усл).test(с.текст.slice(0, с.текст.indexOf('{')))) || null;

const секция = (() => {
    const i = СТИ.indexOf('.section-about {');
    const j = СТИ.indexOf('.about-image img {');
    return i >= 0 && j > i ? СТИ.slice(i, СТИ.indexOf('}', j) + 1) : '';
})();

/* ══ СЛОИ И ГРАНИЦЫ ══════════════════════════════════════════════════════ */

const границы = [...new Set(свои.map(с => с.текст.slice(0, с.текст.indexOf('{')).trim()))];

правило('у раздела нет ни одной границы мимо лестницы 640 · 992',
    границы.every(у => !/(1024|1100|768|600|560|480|375)px/.test(у)),
    'Найдено: ' + границы.join('  |  ') + '\n' +
    '          До 24.09 раздел стоял на 992 и 768, и 768 не из лестницы.');

правило('слоёв ровно три: ≤992, ≤640 и поворот',
    границы.length === 4,
    'Сейчас: ' + границы.length + ' — ' + границы.join(' | ') + '\n' +
    '          Четвёртый — prefers-reduced-motion, он не про ширину.');

правило('у сетки плиток ОДНО определение колонок на вид',
    сколько(СТИ, /\.about-features[^{]*\{[^}]*grid-template-columns/g) === 2,
    'Сейчас объявлений: ' + сколько(СТИ, /\.about-features[^{]*\{[^}]*grid-template-columns/g) + '\n' +
    '          Было ТРИ, и одно из них мёртвое: строка 7734 ставила одну колонку\n' +
    '          и не работала никогда — ниже, в ТОМ ЖЕ условии @media 768, стояли\n' +
    '          две. Одно понятие, определённое дважды внутри одного условия.');

/* ══ РАСКЛАДКА ═══════════════════════════════════════════════════════════ */

const узкий = слой('max-width: 992px');

/* ПОПРАВКА 24.09, вечер. Здесь стояло правило «сетка идёт во всю ширину».
   Решение Кости его отменило: плитки остаются в левой колонке под текстом,
   а снимок встаёт справа ростом с эту колонку. Моё возражение снято числами —
   сжималась плитка не от колонки, а от ТРЁХ колонок внутри неё. */
правило('на широком снимок ростом с левую часть, а не по своему отношению',
    /\.about-image \{\s*grid-column: 2;\s*grid-row: 1 \/ span 2;/.test(СТИ) &&
    /\.about-image img \{[\s\S]{0,120}height: 100%/.test(СТИ),
    'Снимок тянется на обе строки левой части — вступление и плитки. Замер:\n' +
    '          левая часть 592, снимок 593.');

правило('плиток в ряд две, а не три',
    /\.about-features \{[\s\S]{0,260}grid-template-columns: repeat\(2, 1fr\)/.test(БАЗА),
    'Три колонки внутри левой части давали плитку 177 на 1280 и 133 на 1024\n' +
    '          при кегле имени 16. Две дают 307.');

правило('на узком порядок по смыслу: вступление → плитки → снимок',
    !!узкий && /\.about-lead\s+\{[^}]*order: 1/.test(узкий.текст) &&
    /\.about-features \{[^}]*order: 2/.test(узкий.текст) &&
    /\.about-image\s+\{[^}]*order: 3/.test(узкий.текст) &&
    !/order: -1/.test(СТИ.slice(СТИ.indexOf('.section-about'), СТИ.indexOf('.section-about') + 6000)),
    'Было order: -1 у картинки — снимок стоял ПЕРВЫМ, выше и вступления, и\n' +
    '          плиток. Плитки это навигация, они важнее снимка.');

правило('на узком фотография возвращается к отношению своего файла',
    !!узкий && /aspect-ratio: 1400 \/ 691/.test(узкий.текст) &&
    !/\.about-image img \{[^}]*(?<!max-)height:\s*\d+px/.test(СТИ),
    'Файл 1400 × 691. Когда колонка одна, снимок не режется вовсе, а место\n' +
    '          под него резервируется до загрузки. Высота числом не возвращается\n' +
    '          ни на одном виде.');

правило('потолок высоты фотографии падает по видам',
    !!узкий && /max-height: 240px/.test(узкий.текст) &&
    !!слой('orientation: landscape') && /max-height: 160px/.test(слой('orientation: landscape').текст),
    'Телефон боком: секция была 998 при экране 390, и 340 из них занимала одна\n' +
    '          фотография. Вид делится поворотом и высотой, а не шириной.');

/* ══ ПЛИТКА — ССЫЛКА ═════════════════════════════════════════════════════ */

for (const [яз, html] of Object.entries(СТР)) {
    const i = html.indexOf('<section id="about"');
    const кусок = html.slice(i, html.indexOf('</section>', i));
    const суф = яз === 'ru' ? '' : '-' + (яз === 'kg' ? 'kg' : 'en');

    правило('плитки — ссылки, все шесть · ' + яз,
        сколько(кусок, /class="feature" href=/g) === 6 && !/<div class="feature">/.test(кусок),
        'Шесть плиток называли шесть разделов сайта и никуда не вели. Человек\n' +
        '          читал «полный список кортов Кыргызстана», нажимал и не получал ничего.');

    правило('шесть плиток — список, а не шесть див · ' + яз,
        /<ul class="about-features">/.test(кусок) && сколько(кусок, /<li>/g) === 6,
        'Диктор должен сказать «список из шести».');

    правило('имя плитки — h3, уровень не пропущен · ' + яз,
        сколько(кусок, /<h3>/g) === 6 && !/<h4>/.test(кусок),
        'Было h2 → h4: диктор объявляет второй уровень, следом четвёртый, и\n' +
        '          человек слышит, что между ними что-то потерялось.');

    правило('эмодзи в разделе нет, есть шесть иконок · ' + яз,
        !/[\u{1F000}-\u{1FAFF}]/u.test(кусок) && сколько(кусок, /<svg /g) === 6 &&
        сколько(кусок, /aria-hidden="true"/g) >= 6,
        'Эмодзи игнорируют объявленный цвет, рисуются шрифтом системы и читаются\n' +
        '          диктором вслух: «теннисный мяч Турниры регулярные соревнования».');

    правило('адреса плиток совпадают с языком страницы · ' + яз,
        ['tournaments-overview', 'partners', 'players', 'courts', 'coaches', 'pricing']
            .every(а => кусок.indexOf('pages/' + а + суф + '.html') !== -1),
        'Русская плитка не должна вести на английскую страницу и наоборот.');

    правило('у фотографии объявлены ширина и высота · ' + яз,
        /<img [^>]*width="1400"[^>]*height="691"/.test(кусок),
        'Без них браузер не знает пропорций до загрузки и дёргает раскладку.\n' +
        '          Это тот же механизм, который ломает «назад».');
}

/* ══ ЛЕСТНИЦА И ЦВЕТ ═════════════════════════════════════════════════════ */

правило('имя плитки стоит на ступени card title, а не вровень со строкой',
    /\.feature h3 \{[\s\S]{0,140}var\(--fs-base\)/.test(СТИ) &&
    !!слой('max-width: 640px') && /\.feature h3 \{ font-size: var\(--fs-sm\)/.test(слой('max-width: 640px').текст),
    'Было: имя 16 и строка под ним 16 — разница только в весе. Ступень\n' +
    '          card title по лестнице 86:10: 16 на широком, 14 на телефоне.');

правило('строка плитки мельче имени на каждом виде',
    /\.feature p \{[\s\S]{0,160}var\(--fs-sm\)/.test(СТИ) &&
    !!слой('max-width: 640px') && /\.feature p \{[\s\S]{0,120}var\(--fs-xs\)/.test(слой('max-width: 640px').текст),
    'ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ: 16 > 14 на широком, 14 > 12 на телефоне.');

правило('на телефоне строка плитки — caption, то есть Medium',
    !!слой('max-width: 640px') && /\.feature p \{[\s\S]{0,140}font-weight: 500/.test(слой('max-width: 640px').текст),
    'Ступень caption в лестнице 86:10 — 12 / Medium, а не Regular.');

правило('вступление стоит на ступени lead 21 · 16',
    /\.about-lead \{[\s\S]{0,200}var\(--fs-lg\)/.test(СТИ) &&
    !!узкий && /\.about-lead \{[\s\S]{0,140}var\(--fs-base\)/.test(узкий.текст),
    'Было 21 / 14 — на узком мельче, чем строка плитки на широком.\n' +
    '          Ступень lead 24.09 дорисована в лестницу 86:10: её там не было.');

правило('внутри раздела нет --text-dim',
    !/\.feature p \{[^}]*--text-dim/.test(СТИ) && !/\.about-lead \{[^}]*--text-dim/.test(СТИ),
    'Строка плитки давала 3.14 : 1 при пороге WCAG 1.4.3 = 4.5 — СЕДЬМОЕ место\n' +
    '          с этим дефектом по сайту, и текст здесь не мелкий: 16.');

/* ══ ИКОНКА И СОСТОЯНИЯ ══════════════════════════════════════════════════ */

правило('плашка иконки — 44 и радиус со шкалы',
    /\.feature-icon \{[\s\S]{0,200}width: 44px;[\s\S]{0,60}height: 44px;[\s\S]{0,80}border-radius: var\(--radius-lg\)/.test(СТИ),
    'Компонент Feature icon 429:191. Это НЕ Icon button 40:93: у той радиус\n' +
    '          full, потому что на неё нажимают пальцем. Здесь нажимается вся\n' +
    '          плитка. Ступень 44 взята у её lg, форма — нет. Радиус 14 из моих\n' +
    '          набросков был произволом: шкала 8 · 12 · 16 · 24.');

правило('иконка внутри плашки — 24',
    /\.feature-icon svg \{[\s\S]{0,120}width: 24px;[\s\S]{0,40}height: 24px/.test(СТИ),
    'Шкалы иконок в проекте нет — её задаёт этот компонент.');

правило('кольцо фокуса есть у плитки',
    /\.feature:focus-visible \{[\s\S]{0,140}outline: 3px solid var\(--accent\)/.test(СТИ),
    'До 24.09 во всём разделе не было ни одного :focus-visible. WCAG 2.4.7.');

правило('движение спрашивает разрешения',
    /@media \(prefers-reduced-motion: reduce\) \{[\s\S]{0,300}\.feature:hover \.feature-icon,[\s\S]{0,120}transform: none/.test(СТИ),
    'Плашка поднимается и поворачивается при наведении. Гасить надо и переход,\n' +
    '          и сам сдвиг.');

правило('пункт списка тянет ссылку на всю высоту',
    /\.about-features > li \{\s*display: flex;\s*\}/.test(СТИ) && /\.feature \{[\s\S]{0,200}flex: 1/.test(СТИ),
    'Иначе плитки в ряду разной высоты, а нажимается только текст.');

правило('версии подняты',
    /style\.css\?v=(\d+)/.test(СТР.ru) && Number(СТР.ru.match(/style\.css\?v=(\d+)/)[1]) >= 363,
    'Не поднял версию — смотришь старый сайт и думаешь, что правка не сработала.');

/* ══ ВЫВОД ═══════════════════════════════════════════════════════════════ */

console.log('');
if (ошибки.length === 0) {
    console.log('  ок      раздел «О проекте»: ' + (24 + 18) + ' правил');
    console.log('          снимок ростом с левой частью   ·   плитки ведут   ·   список из шести');
    console.log('          имя крупнее строки   ·   эмодзи нет   ·   фото держит файл');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  «О проекте» — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s+/g, '\n            '));
    console.log('');
});
process.exit(1);
