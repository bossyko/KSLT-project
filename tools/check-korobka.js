/**
 * СТОРОЖ КОРОБКИ-ГЕЙТА с бегущей обводкой.
 *
 * Эта коробка существует в проекте В ЧЕТЫРЁХ КОПИЯХ. 24.09 Костя решил не
 * сводить их сейчас — две живут на экранах, куда маршрут ещё не дошёл, — а
 * сделать ОДНУ эталонной и подключить к ней остальные на шаге компонентов.
 *
 * Пока этого не случилось, забыть про три другие копии нельзя. Помнить должен
 * не человек, а проверка: она падает, если появилась ПЯТАЯ копия или если одна
 * из четырёх разъехалась с общей формой.
 *
 *   node tools/check-korobka.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ЭТАЛОН — та самая, что сделана 24.09 в секции значков. */
const ЭТАЛОН = { файл: 'css/style.css', сел: '.badges-cta-box' };
/* ПОДКЛЮЧЕНЫ 24.09 — все три. Их числа больше не свои: поля обязаны
   совпадать с полями эталона на обеих ступенях, а кнопка — с его кнопкой.
   Это и сторожат правила ниже. Своими у копии остаются только ширина и
   собственные уровни внутри (значок, заголовок, текст). */
const КОПИИ = [
    { файл: 'css/style.css',    сел: '.guest-cta-card', кн: '.guest-cta-btn',
      экран: 'плашка-гейт на лендинге' },
    { файл: 'css/players.css',  сел: '.pl-guest-cta',   кн: '.pl-guest-btn',
      экран: 'рейтинг — «Весь рейтинг виден после входа»' },
    { файл: 'css/partners.css', сел: '.pt-guest-cta',   кн: '.pt-guest-btn',
      экран: 'партнёры' }
];
const КНОПКА_ЭТАЛОНА = { файл: 'css/style.css', сел: '.badges-cta-btn' };

const ФАЙЛЫ = ['css/style.css', 'css/players.css', 'css/partners.css', 'css/tokens.css'];
const текст = {};
ФАЙЛЫ.forEach(ф => { текст[ф] = безКом(чит(ф)); });

function блок(ф, сел) {
    const м = текст[ф].match(new RegExp('(?:^|\\n)' + сел.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{[^}]*\\}'));
    return м ? м[0] : null;
}
/* ВСЕ объявления селектора, а не первое: телефонная ступень лежит внутри
   @media и приходит с отступом, поэтому якорь на начало строки её теряет. */
function всеБлоки(ф, сел) {
    const re = new RegExp('(?:^|\\n)[ \\t]*' + сел.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{[^}]*\\}', 'g');
    return текст[ф].match(re) || [];
}
const свойство = (т, имя) => {
    if (!т) return null;
    /* «{» в якоре: однострочное правило вида `.x { padding: 8px; }` не имеет
       перевода строки перед свойством, и без этого правило читало null. */
    const м = т.match(new RegExp('(?:^|\\n|\\{)\\s*' + имя + ':\\s*([^;]+);'));
    return м ? м[1].trim() : null;
};

/* ── пятой копии нет ─────────────────────────────────────────────────────── */
const всеФайлы = fs.readdirSync(path.join(КОРЕНЬ, 'css'))
    .filter(ф => ф.endsWith('.css') && ф.indexOf('backup') === -1);
const носители = [];
всеФайлы.forEach(ф => {
    const s = безКом(чит('css/' + ф));
    const re = /(?:^|\n)([.#][\w.-]+)::before\s*\{[^}]*conic-gradient[^}]*\}/g;
    let m;
    while ((m = re.exec(s)) !== null) носители.push('css/' + ф + ' ' + m[1]);
});
const ожидаем = [ЭТАЛОН, ...КОПИИ].map(к => к.файл + ' ' + к.сел).sort();
правило('копий коробки ровно четыре, и это те самые четыре',
    носители.sort().join(' | ') === ожидаем.join(' | '),
    'Ожидали:\n            ' + ожидаем.join('\n            ') + '\n' +
    '          Нашли:\n            ' + (носители.length ? носители.join('\n            ') : '— ничего —') + '\n' +
    '          Появилась пятая копия — значит кто-то снова скопировал коробку\n' +
    '          вместо того, чтобы взять эталон. Либо одну подключили, и тогда\n' +
    '          список выше надо обновить вместе с этой проверкой.');

/* ── эталон ──────────────────────────────────────────────────────────────── */
const эт = блок(ЭТАЛОН.файл, ЭТАЛОН.сел);
правило('эталон на месте',
    эт !== null, 'Блок ' + ЭТАЛОН.сел + ' пропал из ' + ЭТАЛОН.файл + '.');
правило('поля эталона стоят на шкале',
    свойство(эт, 'padding') === 'var(--space-6) var(--space-8)',
    'Сейчас: ' + свойство(эт, 'padding') + '\n' +
    '          Было 22/34 — ни одно не ступень шкалы 8 · 12 · 16 · 24 · 32 · 40.\n' +
    '          Остальные три подключаются К ЭТАЛОНУ, поэтому его числа должны\n' +
    '          быть правильными ДО того, как их начнут копировать.');

/* ── все три копии берут числа эталона, а не свои ────────────────────────── */
/* ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ, А НЕ ЧИСЛО: правила сравнивают копии С ЭТАЛОНОМ.
   Переедет эталон на другую ступень — копии обязаны переехать следом, иначе
   упадут вот эти правила и назовут, какая из четырёх осталась. */
const этБлоки = всеБлоки(ЭТАЛОН.файл, ЭТАЛОН.сел);
правило('у эталона ровно две ступени полей — широкая и телефонная',
    этБлоки.length === 2,
    'Нашли объявлений .badges-cta-box: ' + этБлоки.length + '\n' +
    '          Две ступени — это и есть лестница 640 / 992. Третья означает,\n' +
    '          что появилась граница мимо лестницы.');
правило('телефонная ступень эталона стоит на шкале',
    свойство(этБлоки[1], 'padding') === 'var(--space-4) var(--space-6)',
    'Сейчас: ' + свойство(этБлоки[1], 'padding') + '\n' +
    '          Было 16 / 20, и 20 не ступень шкалы 8 · 12 · 16 · 24 · 32 · 40.\n' +
    '          Широкую ступень эталона поставили на шкалу 24.09, телефонную\n' +
    '          забыли — и неверным числом эталон делился бы дальше.');

const этКн = блок(КНОПКА_ЭТАЛОНА.файл, КНОПКА_ЭТАЛОНА.сел);
КОПИИ.forEach(к => {
    const копБлоки = всеБлоки(к.файл, к.сел);
    правило('у копии ' + к.сел + ' ровно две ступени полей',
        копБлоки.length === 2,
        'Нашли объявлений ' + к.сел + ': ' + копБлоки.length + '\n' +
        '          ' + к.экран + '\n' +
        '          До 24.09 у .guest-cta-card их было четыре, а у .pt-guest-cta\n' +
        '          одна — телефонной ступени не было вовсе. Две — это лестница\n' +
        '          640 / 992 и ничего сверх неё.');
    [0, 1].forEach(i => {
        правило(к.сел + ' берёт поля эталона, ступень ' + (i === 0 ? 'широкая' : 'телефонная'),
            !!копБлоки[i] && свойство(копБлоки[i], 'padding') === свойство(этБлоки[i], 'padding'),
            'Эталон: ' + свойство(этБлоки[i], 'padding') + '\n' +
            '          Копия:  ' + (копБлоки[i] ? свойство(копБлоки[i], 'padding') : '— ступени нет —') + '\n' +
            '          ' + к.экран + '\n' +
            '          Подключена к .badges-cta-box 24.09. Свои числа у неё\n' +
            '          кончились: расходиться им больше нельзя. Своими остаются\n' +
            '          только ширина и собственные уровни внутри.');
    });
    const копКн = блок(к.файл, к.кн);
    [['height', 'высоту'], ['padding', 'поля']].forEach(([имя, словом]) => {
        правило('кнопка ' + к.кн + ' берёт ' + словом + ' у кнопки эталона',
            свойство(копКн, имя) === свойство(этКн, имя) && свойство(этКн, имя) !== null,
            'Эталон .badges-cta-btn: ' + свойство(этКн, имя) + '\n' +
            '          Копия  ' + к.кн + ': ' + свойство(копКн, имя) + '\n' +
            '          ' + к.экран + '\n' +
            '          Замер 24.09 дал у копий высоты 43, 48 и 43 — ни одна не\n' +
            '          ступень Button 17:82 (28 · 36 · 44 · 52), и все три были\n' +
            '          заданы полями, а не свойством. Кнопки одной роли в\n' +
            '          одинаковой коробке стоят на одной ступени или нигде.');
    });
});

/* ── общая форма всех четырёх ────────────────────────────────────────────── */
const ОБЩЕЕ = [
    ['background',      'rgba(18, 18, 18, 0.85)'],
    ['border-radius',   '24px'],
    ['backdrop-filter', 'blur(20px)'],
    ['isolation',       'isolate'],
    ['overflow',        'hidden']
];
[ЭТАЛОН, ...КОПИИ].forEach(к => {
    const б = блок(к.файл, к.сел);
    ОБЩЕЕ.forEach(([имя, знач]) => {
        правило(к.сел + ' держит общую форму: ' + имя,
            свойство(б, имя) === знач,
            'Сейчас: ' + свойство(б, имя) + ' · ожидали ' + знач + '\n' +
            '          ' + (к.экран || 'эталон') + '\n' +
            '          Четыре копии обязаны расходиться ТОЛЬКО полями и шириной.\n' +
            '          Если разъехалось что-то ещё — сведение станет дороже.');
    });
});

/* ── угол вращения ───────────────────────────────────────────────────────── */
/* ГРАНИЦА ПОСЛЕ ИМЕНИ ОБЯЗАТЕЛЬНА: без неё «--guest-angle» совпадает и с
   «--guest-angle-unused», и откат, переименовавший переменную, правило не
   ронял. Десятый случай за три дня, когда якорь оказался подстрокой. */
правило('@property для угла объявлен — без него обводка не крутится вовсе',
    /@property --guest-angle\s*\{/.test(текст['css/style.css']),
    'Угол в conic-gradient анимируется только у зарегистрированной переменной.\n' +
    '          Без @property обводка стоит на месте, и этого никто не замечает.');
const углы = new Set();
всеФайлы.forEach(ф => {
    const s = чит('css/' + ф);
    (s.match(/from var\((--[\w-]+)/g) || []).forEach(m => углы.add(m.replace('from var(', '')));
});
правило('имён у переменной угла не больше двух — и оба известны',
    [...углы].sort().join(' ') === '--guest-angle --pt-angle',
    'Сейчас: ' + [...углы].sort().join(' ') + '\n' +
    '          Партнёры завели свою копию переменной под другим именем. Это\n' +
    '          известный долг: при сведении остаётся одно имя. Если имён стало\n' +
    '          БОЛЬШЕ — кто-то копирует дальше.');

/* ── движение ────────────────────────────────────────────────────────────── */
правило('у эталона есть защита prefers-reduced-motion',
    /@media \(prefers-reduced-motion: reduce\)[\s\S]{0,200}\.badges-cta-box::before/.test(текст['css/style.css']),
    'Обводка крутится бесконечно. WCAG 2.3.3. В проекте 46 бесконечных анимаций\n' +
    '          и до 24.09 не было ни одной такой защиты — остальные в долг.');

console.log('');
if (ошибки.length === 0) {
    console.log('  ок      коробка-гейт: ' + (2 + 2 + 5 * 3 + 5 * 4 + 3) + ' правил');
    console.log('          эталон .badges-cta-box   ·   все три копии подключены   ·   пятой нет');
    console.log('          поля и кнопка сверяются С ЭТАЛОНОМ, а не с числом');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  коробка-гейт — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s+/g, '\n            '));
    console.log('');
});
process.exit(1);
