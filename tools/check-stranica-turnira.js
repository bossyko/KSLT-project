/* Окно правила — СВОЙ блок со счётом скобок: голое число ловится и у
   соседа, а `[\s\S]*?` перепрыгивает через `}` в следующий блок. */
function блок(текст, селектор) {
    const i = текст.indexOf(селектор + ' {');
    if (i === -1) return '';
    let гл = 0;
    const j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}

