/* Окно между двумя вехами — чтобы правило не считало по всему файлу */
function кусок(текст, от, до) {
    const i = текст.indexOf(от);
    if (i === -1) return '';
    const j = текст.indexOf(до, i);
    return j === -1 ? текст.slice(i) : текст.slice(i, j);
}

/* Тела ВСЕХ блоков отказа от движения — со счётом скобок */
function блокиОтказаОтДвижения(текст) {
    const куски = [];
    let поз = 0;
    for (;;) {
        const i = текст.indexOf('@media (prefers-reduced-motion', поз);
        if (i === -1) break;
        const j = текст.indexOf('{', i);
        let гл = 0;
        for (let k = j; k < текст.length; k++) {
            if (текст[k] === '{') гл++;
            else if (текст[k] === '}') {
                гл--;
                if (!гл) { куски.push(текст.slice(j + 1, k)); поз = k + 1; break; }
            }
        }
        if (гл) break;
    }
    return куски;
}

/* Тело функции по имени — со счётом скобок, как и блок css */
function блокФункции(текст, имя) {
    const i = текст.indexOf('function ' + имя);
    if (i === -1) return '';
    let гл = 0;
    const j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}

