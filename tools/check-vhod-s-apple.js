#!/usr/bin/env node
/**
 * ГДЕ СТОРОННИЙ ВХОД — ТАМ И ВХОД С APPLE (кусок 04.11, шаг E3).
 *
 * ПРАВИЛО APPLE 4.8 ДОСЛОВНО: приложение, которое заводит основную учётную
 * запись через сторонний вход (Facebook Login, **Google Sign-In**, …),
 * «must also offer as an equivalent option another login service», который
 * среди прочего «allows users to keep their email address private».
 *
 * ЗАМЕР 29.10 и 04.11: на сайте вход с Apple написан (`js/auth.js:1705`),
 * в приложении был только Google. Без Apple — ПРЯМОЙ ОТКАЗ в App Store.
 *
 * СВОЙ ВХОД ПО ПИСЬМУ ЭТОГО НЕ ЗАКРЫВАЕТ, и это стоит записать, потому
 * что звучит убедительно и неверно: из трёх условий правила он выполняет
 * два, но не даёт СКРЫТЬ АДРЕС. Ради этого условия правило и написано.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ, А НЕ НАЛИЧИЕ: «сколько сторонних входов, столько
 * и мест, где рядом стоит Apple». Появится завтра вход через Facebook —
 * правило упадёт, пока рядом не встанет Apple. Правило, проверяющее
 * только «есть ли Apple», пропустило бы новый вход молча.
 *
 * ФЛАГ — ЧАСТЬ ПРАВИЛА. Кнопка, показанная до настройки провайдера, даёт
 * человеку ошибку, которую нечем объяснить: МЁРТВАЯ КНОПКА ХУЖЕ
 * ОТСУТСТВУЮЩЕЙ. Поэтому разметка держит кнопки спрятанными, а снимает
 * прятки только флаг — и прибор следит за обоими концами.
 *
 *   node tools/check-vhod-s-apple.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const П = (...ч) => path.join(КОРЕНЬ, ...ч);
const чит = ф => fs.readFileSync(П(ф), 'utf8');
const есть = ф => fs.existsSync(П(ф));

const ВХОД = 'mobile/www/js/auth.js';
const КОНФИГ = 'mobile/www/js/supabase-config.js';
const СТРАНИЦА = 'mobile/www/index.html';
const СЛОВАРЬ = 'mobile/www/js/i18n.js';

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const вход = есть(ВХОД) ? безКомментариев(чит(ВХОД)) : '';
const конфиг = есть(КОНФИГ) ? безКомментариев(чит(КОНФИГ)) : '';
const стр = есть(СТРАНИЦА) ? чит(СТРАНИЦА) : '';
const словарь = есть(СЛОВАРЬ) ? чит(СЛОВАРЬ) : '';

/* ── 1. СУТЬ ПРАВИЛА: сторонних входов не больше, чем мест с Apple ───── */
const ЧУЖИЕ = ['google', 'facebook', 'twitter', 'linkedin', 'amazon', 'wechat', 'github', 'azure'];
const найденыЧужие = ЧУЖИЕ.filter(п =>
    new RegExp("provider:\\s*'" + п + "'").test(вход));
const естьApple = /provider:\s*'apple'/.test(вход);

правило('при стороннем входе предложен и вход с Apple',
    найденыЧужие.length === 0 || естьApple,
    'в приложении есть сторонний вход (' + найденыЧужие.join(', ') +
    '), а входа с Apple нет — правило 4.8 даёт прямой отказ');

правило('вход с Apple зовёт провайдера apple',
    естьApple && /AUTH\.loginApple\s*=/.test(вход),
    'нет AUTH.loginApple или в нём не apple');

/* ── 2. кнопки есть на обоих экранах, где есть чужие ─────────────────── */
правило('кнопка Apple стоит рядом с кнопкой входа Google',
    !/id="authGoogle"/.test(стр) || /id="authApple"/.test(стр),
    'на экране входа есть Google, а Apple нет');

правило('кнопка Apple стоит рядом с кнопкой регистрации Google',
    !/id="regGoogle"/.test(стр) || /id="regApple"/.test(стр),
    'на экране регистрации есть Google, а Apple нет');

/* ── 3. кнопки спрятаны в разметке ───────────────────────────────────── */
['authApple', 'regApple'].forEach(ид => {
    const кусок = (стр.match(new RegExp('<button[^>]*id="' + ид + '"[^>]*>')) || [''])[0];
    правило('кнопка ' + ид + ' спрятана в разметке',
        /\bhidden\b/.test(кусок),
        'кнопка ' + ид + ' показана до настройки провайдера — человек получит ошибку');
});

/* ── 4. прятки снимает только флаг ───────────────────────────────────── */
правило('флаг входа с Apple объявлен и по умолчанию выключен',
    /window\.KSLT_APPLE\s*=\s*window\.KSLT_APPLE\s*\|\|\s*false/.test(конфиг),
    'в ' + КОНФИГ + ' нет window.KSLT_APPLE или он включён по умолчанию');

const показ = (вход.match(/if\s*\(window\.KSLT_APPLE\)[\s\S]{0,700}/) || [''])[0];
правило('кнопки показываются только под флагом',
    /hidden\s*=\s*false/.test(показ) && /authApple/.test(показ) && /regApple/.test(показ),
    'прятки с кнопок снимаются не под флагом KSLT_APPLE');

правило('обе кнопки ведут в один вход',
    (показ.match(/loginApple\s*\(/g) || []).length >= 2,
    'кнопки Apple не зовут AUTH.loginApple');

/* ── 5. подпись переведена ───────────────────────────────────────────── */
правило('подпись кнопки переведена на три языка',
    /'auth\.regApple':\s*\{[^}]*ru:[^}]*en:[^}]*kg:/.test(словарь),
    'в словаре нет auth.regApple на трёх языках');

/* ── 6. значок не выдуман ────────────────────────────────────────────── */
правило('значок Apple не нарисован по памяти',
    !/<svg[^>]*>(?:(?!<\/svg>)[\s\S])*<\/svg>/.test(
        (стр.match(/<button[^>]*id="authApple"[\s\S]*?<\/button>/) || [''])[0]),
    'в кнопке Apple нарисован свой значок — Apple задаёт его своим руководством ' +
    'и отдаёт готовым; приблизительный значок это повод для отказа');

/* ── вывод ───────────────────────────────────────────────────────────── */
const ВСЕГО = 11;
console.log('\n  ВХОД С APPLE\n');
if (ошибки.length === 0) {
    console.log('  ок      все ' + ВСЕГО + ' правил держат\n');
    process.exit(0);
}
ошибки.forEach(о => {
    console.log('  НЕ ТАК  ' + о.имя);
    console.log('          ' + о.подсказка);
});
console.log('\n  НЕ ТАК  ' + ошибки.length + ' из ' + ВСЕГО + '\n');
process.exit(1);
