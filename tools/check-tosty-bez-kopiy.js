/**
 * ЗАМОРОЗКА ТОСТОВ АДМИНКИ ОТ КОПИЙ (кусок 203, 27.10.2026).
 *
 * ЗАМЕР: зашитых русских тостов в `js/admin` — 86 в шестнадцати файлах,
 * 77 различных текстов. ПОВТОРЯЛИСЬ ПЯТЬ: «Удалено» пять раз,
 * «Сохранено» три, «Имя обязательно», «Название обязательно» и «Поля
 * разблокированы» по два — ЧЕТЫРНАДЦАТЬ мест в семи файлах.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Остальные 72 текста НЕ переносились в
 * словарь, и это решение, а не недоделка. Я записал их как беду
 * перевода — «на английской админке будет русский», — и ПРОВЕРИЛ ПЕРЕД
 * ТЕМ, КАК ДЕЛАТЬ: АДМИНКА ОДНОЯЗЫЧНА. Словарь `L` в
 * `admin/core/constants.js` без языков вовсе, `pages/admin-en.html` —
 * перенаправление на `admin.html`, и правило «ни одна страница с `-en`
 * в пути не грузит админских скриптов» это держит. Английской и
 * кыргызской админки НЕ СУЩЕСТВУЕТ, то есть 77 ключей с переводами
 * были бы работой в пустоту. ЗАПИСЬ В ТРЕКЕРЕ ВРАЛА, и исправлена.
 *
 * Осталась настоящая польза: ОДИН ТЕКСТ — ОДНО МЕСТО ПРАВКИ. Пять
 * общих ключей, и ни одного повтора.
 *
 *   node tools/check-tosty-bez-kopiy.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const собрать = (кат, спис) => {
    fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(д => {
        const п = кат + '/' + д.name;
        if (д.isDirectory()) собрать(п, спис);
        else if (д.name.endsWith('.js')) спис.push(п);
    });
    return спис;
};
const АДМИН = собрать('js/admin', []);
const СЛОВАРЬ = безКом(чит('js/admin/core/constants.js'));

/* ══ 1. НИ ОДНОГО ПОВТОРЯЮЩЕГОСЯ ТОСТА ════════════════════════════════ */

/* ИГОЛКА СОБИРАЕТСЯ ИЗ ЧАСТЕЙ: иначе сторож и его прувер попадают в
   собственный замер — на этих граблях кусок 196 стоял дважды. */
const пТост = new RegExp('show' + 'Toast\\(\\s*\'([^\']*[А-Яа-яЁё][^\']*)\'', 'g');
const счёт = new Map();
АДМИН.forEach(ф => {
    const т = безКом(чит(ф));
    let м;
    const р = new RegExp(пТост.source, 'g');
    while ((м = р.exec(т)) !== null) счёт.set(м[1], (счёт.get(м[1]) || 0) + 1);
});
const повторы = [...счёт.entries()].filter(([, n]) => n > 1);

правило('ни один текст тоста не стоит в админке дважды',
    повторы.length === 0,
    'повторяющихся текстов: ' + повторы.length + ' — ' +
    повторы.slice(0, 3).map(([т, n]) => '«' + т.slice(0, 30) + '» ×' + n).join(', ') + '.\n' +
    'Один текст — одно место правки. Их было ПЯТЬ на четырнадцать мест');

/* ══ 2. ОБЩИЕ КЛЮЧИ ЕСТЬ И ИХ ЗОВУТ ═══════════════════════════════════ */

const КЛЮЧИ = ['toastDeleted', 'toastSaved', 'toastNameRequired',
                'toastTitleRequired', 'toastFieldsUnlocked'];
const безКлюча = КЛЮЧИ.filter(к => !new RegExp('\\b' + к + ':').test(СЛОВАРЬ));

правило('общие ключи тостов заведены в словаре',
    безКлюча.length === 0,
    'нет в словаре: ' + безКлюча.join(', ') + '.\n' +
    'Зовущие получат undefined, и человек увидит пустой тост');

let зовов = 0;
АДМИН.forEach(ф => {
    const т = безКом(чит(ф));
    КЛЮЧИ.forEach(к => { зовов += (т.match(new RegExp('L\\.' + к + '\\b', 'g')) || []).length; });
});

правило('общие ключи зовут из всех четырнадцати мест',
    зовов >= 14,
    'зовов общих ключей ' + зовов + ', замерено 14. Стало меньше — значит\n' +
    'место вернулось к зашитому тексту, а признак выше это пропустил');

/* ══ 3. АДМИНКА ОСТАЁТСЯ ОДНОЯЗЫЧНОЙ ══════════════════════════════════ */

/* ЕСЛИ ЭТО ПЕРЕСТАНЕТ БЫТЬ ВЕРНЫМ, остальные 72 текста превратятся из
   решения в долг — и правило скажет об этом сразу, а не через полгода. */
правило('админка одноязычна, и перевод тостов не нужен',
    !/KSLT_YAZYK/.test(СЛОВАРЬ) &&
    /window\.location\.replace\('admin\.html'\)/.test(чит('pages/admin-en.html')),
    'у админки появился второй язык — значит 72 зашитых тоста стали долгом,\n' +
    'и их надо переносить в словарь. До этого они были решением');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      тосты админки без копий: 4 правила');
    console.log('          зашитых текстов ' + счёт.size + ', повторов ноль');
    console.log('          пять общих ключей, зовов ' + зовов);
    console.log('          админка одноязычна — перевод не нужен, и это сторожится');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  тосты админки — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
