#!/usr/bin/env node
/**
 * «ОНЛАЙН» — ОДНО ПРАВИЛО, И НА РЕЙТИНГЕ ЕГО НЕТ ПО РЕШЕНИЮ (29.10).
 *
 * ЗАЧЕМ. Костя велел взять раздел «Игроки». Замер показал, что добавлять
 * там нечего: подиум, категории со страницами и поиск есть, значки
 * сведены домом `kslt-znachki.js`, а «онлайн» СНЯТ С РЕЙТИНГА ЕГО ЖЕ
 * СЛОВОМ 06.10 — «смысла нет там это отображать».
 *
 * НО ПОНЯТИЕ ЖИВО: «в сети» считается из `last_seen` одним правилом
 * `KSLT_LICO.вСети` с порогом `ПОРОГ_В_СЕТИ`, и его зовут услуги,
 * партнёры и главная. Второго правила нет — проверено чтением.
 *
 * ЧТО БЫЛО МЁРТВЫМ И СНЯТО: на рейтинге поле `online` всегда стояло
 * `false` (`js/rankings-data.js:141`), в `true` его не ставил никто — а
 * на нём висели точка `.pl-online-dot` с пульсацией, кнопка письма
 * `.pl-btn-message`, счётчик `countOnline()` (всегда ноль) и подписи
 * «онлайн» в трёх словарях. Ничего из этого не могло появиться на
 * экране.
 *
 * ЭТОТ СТОРОЖ ДЕРЖИТ ДВА ОТНОШЕНИЯ: правило «в сети» остаётся ОДНО, и
 * мёртвое украшение не возвращается само.
 *
 * Запуск: node tools/check-onlayn.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));
const безКомCss = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

const ДОМ = 'js/kslt-lico.js';
/* Кто спрашивает «в сети». Список собирается обходом, а не держится
   руками: появится четвёртый — он попадёт под правило сам. */
const СПРАШИВАЮТ = (function () {
    const найдено = [];
    const пропуск = /^(node_modules|\.git|build|assets|vendor|admin)$/;
    const обойти = (отн) => {
        const п = path.join(КОРЕНЬ, отн);
        if (!fs.existsSync(п)) return;
        for (const э of fs.readdirSync(п, { withFileTypes: true })) {
            const в = отн + '/' + э.name;
            if (э.isDirectory()) { if (!пропуск.test(э.name)) обойти(в); continue; }
            if (!э.name.endsWith('.js') || в.indexOf('kslt-lico') !== -1) continue;
            if (/вСети\(/.test(безКом(чит(в)))) найдено.push(в);
        }
    };
    обойти('js');
    обойти('mobile/www/js');
    return найдено;
})();

console.log('\n  «ОНЛАЙН» — ОДНО ПРАВИЛО\n');

правило('правило «в сети» объявлено в доме и ровно одно',
    /function вСети\(/.test(безКом(чит(ДОМ))) &&
    /ПОРОГ_В_СЕТИ/.test(безКом(чит(ДОМ))),
    'Порог жил числом внутри экрана главной, пока его не свели сюда.\n' +
    'Два порога — это «он онлайн» на одном экране и «нет» на другом.');

правило('спрашивающих нашлось, и все зовут дом',
    СПРАШИВАЮТ.length >= 3,
    'Найдено: ' + (СПРАШИВАЮТ.join(', ') || 'НИЧЕГО') + '.\n' +
    'Если ноль — сломался ПРИБОР, и правила ниже пусты. Оно стоит ПЕРЕД\n' +
    'ними нарочно.');

правило('ни у кого нет своего порога «в сети»',
    СПРАШИВАЮТ.every(ф => {
        const т = безКом(чит(ф));
        return !/Date\.now\(\)\s*-\s*new Date\([^)]*last_seen/.test(т) &&
               !/5\s*\*\s*60\s*\*\s*1000/.test(т);
    }),
    'Свой подсчёт у спрашивающего — второе определение порога. Вот у кого:\n' +
    СПРАШИВАЮТ.filter(ф => /Date\.now\(\)\s*-\s*new Date\([^)]*last_seen/
        .test(безКом(чит(ф)))).map(ф => '  · ' + ф).join('\n'));

правило('на рейтинге поля `online` больше нет',
    !/online:/.test(безКом(чит('js/rankings-data.js'))) &&
    !/\bonline\b/.test(безКом(чит('js/players.js'))),
    'Оно всегда было `false`, и в `true` его не ставил никто: онлайн с\n' +
    'рейтинга убран словом Кости 06.10. Поле, которое никто не наполняет,\n' +
    'держит на себе украшение, которое не может появиться.');

правило('мёртвое украшение онлайна снято',
    (function () {
        const js = безКом(чит('js/players.js'));
        const css = безКомCss(чит('css/players.css'));
        return !/countOnline|pl-online-dot|pl-online-pulse|pl-btn-message/.test(js) &&
               !/\.pl-online-dot\s*\{|\.pl-online-pulse\s*\{|\.pl-btn-message/.test(css) &&
               !/@keyframes pl-pulse/.test(css);
    })(),
    'Точка с пульсацией, кнопка письма, счётчик `countOnline()` (всегда\n' +
    'ноль) и подписи «онлайн» в трёх словарях висели на поле, которое\n' +
    'всегда `false`. МЁРТВЫМ КОД НАЗЫВАЕТСЯ ПОСЛЕ ПРОВЕРКИ — проверено:\n' +
    'в `true` поле не ставил никто.');

правило('вернуть онлайн на рейтинг сказано ГДЕ, а не забыто',
    /KSLT_LICO\.вСети/.test(чит('js/rankings-data.js')) &&
    /last_seen/.test(чит('js/rankings-data.js')),
    'Снятое решение не стирается, а помечается с причиной: решишь вернуть\n' +
    '— передай в загрузчик `last_seen`, правило уже есть, второе писать\n' +
    'не надо. Без этой записи через полгода напишут второе.');

/* ПРАВИЛО БЫЛО ПУСТЫМ: в приложении копии дома `kslt-lico.js` нет
   вовсе, спрашивающих там ноль, и «каждый из нуля» верно всегда — такое
   правило не держит ничего, и прувер это показал.
   Переписано на то, что действительно есть чему держать: приложение
   last_seen ПИШЕТ (`auth.js:70`, `kslt-vhod.js:148`), а не читает. Если
   однажды начнёт читать — обязано прийти с копией дома, а не со своим
   порогом. */
правило('приложение last_seen пишет, а «в сети» не считает само',
    (function () {
        const пишет = /last_seen: new Date\(\)\.toISOString\(\)/
            .test(безКом(чит('mobile/www/js/kslt-vhod.js')));
        const свои = СПРАШИВАЮТ.filter(ф => ф.indexOf('mobile/www') === 0);
        if (!пишет) return false;
        /* Начал читать — обязан прийти с копией дома. */
        return свои.length === 0
            ? !fs.existsSync(path.join(КОРЕНЬ, 'mobile/www/js/kslt-lico.js'))
            : свои.every(ф => /KSLT_LICO/.test(чит(ф)));
    })(),
    'Приложение отмечает время последнего входа — это и даёт «в сети» на\n' +
    'сайте. Считать «в сети» оно пока не считает, и копии дома у него нет.\n' +
    'Появится спрашивающий — обязан звать дом, а не свой порог: порог один\n' +
    'на продукт.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else { console.log('  ок      онлайн: все ' + держится + ' правил держатся · спрашивают ' + СПРАШИВАЮТ.length + '\n'); }
