/**
 * ПРУВЕР ЗАМОРОЗКИ «ПОЛ ТУРНИРА — ОТКАЗ, А НЕ ПОМЕТКА».
 *
 * Берёт КОПИЮ файлов, возвращает по одному прежнему значению и требует,
 * чтобы упало ИМЕННО то правило, которое за это отвечает.
 *
 * Откаты — то, что жило в коде до 01.10, и те способы, какими отказ может
 * тихо превратиться обратно в надпись.
 *
 *   node tools/check-pol-turnira-otkat.js
 */
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');
const os = require('os');

const КОРЕНЬ = path.join(__dirname, '..');
const ВРЕМ = fs.mkdtempSync(path.join(os.tmpdir(), 'kslt-pol-'));

['js', 'tools'].forEach(д =>
    fs.cpSync(path.join(КОРЕНЬ, д), path.join(ВРЕМ, д), { recursive: true }));

const СЕТКА = 'js/admin/sections/bracket.js';
const ПОДП  = 'js/admin/core/constants.js';

const ОТКАТЫ = [
    /* 1. Дверь замены перестала спрашивать — прежнее поведение: женщина
       вставала в основу с пометкой и ждала решения. */
    [СЕТКА,
     "            var бедаПол = бедаПоПолу(tournament, полПервого, полВторого);\n            if (бедаПол) { A.showToast(бедаПол, 'error'); return; }\n\n",
     '',
     'дверь «замена игрока или напарника» спрашивает про пол'],

    /* 2. Дверь замены пары перестала спрашивать. */
    [СЕТКА,
     "            var бедаПолПары = бедаПоПолу(tournament,\n                await полИгрока(первый, playersMap),\n                await полИгрока(второй, playersMap));\n            if (бедаПолПары) { A.showToast(бедаПолПары, 'error'); return; }\n\n",
     '',
     'дверь «замена пары целиком» спрашивает про пол'],

    /* 3. Вызов на месте, но без выхода: отказ показан и тут же забыт,
       заявка всё равно записывается. Самый тихий способ вернуть беду —
       строка в файле есть, глазами всё хорошо. */
    [СЕТКА,
     "                    var бедаПолОдин = бедаПоПолу(tournament, extGender, null);\n                    if (бедаПолОдин) { A.showToast(бедаПолОдин, 'error'); return; }",
     "                    var бедаПолОдин = бедаПоПолу(tournament, extGender, null);\n                    if (бедаПолОдин) { A.showToast(бедаПолОдин, 'error'); }",
     'отказ по полу останавливает запись'],

    /* 4. Судья завёл свою проверку совпадения пола вместо общей. */
    [СЕТКА,
     '        if (составСошёлся(tournament, полПервого, полВторого)) return \'\';',
     "        if (полПервого === турнир && (!полВторого || полВторого === турнир)) return '';",
     'бедаПоПолу спрашивает составСошёлся'],

    /* 5. Ранний выход для микста убран — пара в миксте стала получать
       отказ вместо пометки, хотя состав там решает клуб. */
    [СЕТКА,
     "        if (турнир !== 'men' && турнир !== 'women') return '';",
     '',
     'микст судья не трогает'],

    /* 6. Подпись осталась на одном языке. */
    [ПОДП,
     "        regGenderMenOnly: 'Турнир мужской — женщину в него заявить нельзя',\n",
     '',
     'подпись regGenderMenOnly на двух языках']
];

let провалов = 0;

ОТКАТЫ.forEach(([файл, было, стало, ждём], и) => {
    const путь = path.join(ВРЕМ, файл);
    const исходный = fs.readFileSync(путь, 'utf8');

    const встреч = исходный.split(было).length - 1;
    if (встреч !== 1) {
        console.log('✗ откат ' + (и + 1) + ': якорь встречается ' + встреч +
            ' раз — нужен ровно один\n    ' + было.slice(0, 70).replace(/\n/g, ' ⏎ '));
        провалов++;
        return;
    }

    fs.writeFileSync(путь, исходный.replace(было, стало));

    let вывод = '', упало = false;
    try {
        execFileSync(process.execPath, [path.join(ВРЕМ, 'tools/check-pol-turnira.js')],
            { cwd: ВРЕМ, encoding: 'utf8' });
    } catch (e) {
        упало = true;
        вывод = (e.stdout || '') + (e.stderr || '');
    }

    fs.writeFileSync(путь, исходный);

    if (!упало) {
        console.log('✗ откат ' + (и + 1) + ' («' + ждём + '»): правило НЕ упало — оно ничего не держит');
        провалов++;
    } else if (вывод.indexOf(ждём) === -1) {
        console.log('✗ откат ' + (и + 1) + ': упало не то правило. Ждали «' + ждём + '», а в выводе:\n' +
            вывод.split('\n').filter(с => с.indexOf('•') !== -1).join('\n'));
        провалов++;
    } else {
        console.log('✓ откат ' + (и + 1) + ' уронил «' + ждём + '»');
    }
});

fs.rmSync(ВРЕМ, { recursive: true, force: true });

if (провалов) {
    console.log('\n✗ Прувер: ' + провалов + ' из ' + ОТКАТЫ.length + ' откатов не доказали правило');
    process.exit(1);
}
console.log('\n✓ Прувер: все ' + ОТКАТЫ.length + ' откатов уронили свои правила');
