#!/usr/bin/env node
/**
 * Чтение снимков целей нажатия — с отказом читать смешанный прогон.
 *
 * ЗАЧЕМ ОТКАЗ. 20.09 в папке лежали пять файлов: три из свежего прогона и
 * два из прогона получасовой давности, потому что в интерфейсе Playwright
 * были отмечены не все проекты. Разницы на глаз никакой — те же имена, тот
 * же вид. Я чуть не доложил «на 844 и 1024 всё в порядке», глядя на замеры,
 * сделанные ДО правки. Поэтому здесь: разные метки прогона — не сравниваем,
 * а называем, какие файлы устарели.
 *
 * Запуск:  node tools/read-taps.js
 */
const fs = require('fs');
const path = require('path');

const ПАПКА = path.join(__dirname, '..', 'tests', 'reports', 'header-taps');
const НОРМА = 44;

if (!fs.existsSync(ПАПКА)) {
    console.log('Снимков нет. Прогнать tests/e2e/design-system/21-header-tap-targets.spec.js');
    process.exit(1);
}

const файлы = fs.readdirSync(ПАПКА).filter(f => f.endsWith('.json')).sort();
const снимки = файлы.map(f => JSON.parse(fs.readFileSync(path.join(ПАПКА, f), 'utf8')));

const метки = [...new Set(снимки.map(с => с.прогон || 'без метки'))];
if (метки.length > 1) {
    const свежая = метки.slice().sort().pop();
    console.log('');
    console.log('СМЕШАННЫЙ ПРОГОН — НЕ ЧИТАЮ.');
    console.log('В папке снимки из ' + метки.length + ' разных прогонов.');
    console.log('Свежий: ' + свежая);
    console.log('');
    for (const с of снимки) {
        const свой = (с.прогон || 'без метки') === свежая;
        console.log('  ' + (свой ? 'свежий ' : 'СТАРЫЙ ') + (с.проект + '          ').slice(0, 18) + (с.прогон || 'без метки'));
    }
    console.log('');
    console.log('Старые файлы — с прошлого прогона. Сравнивать с ними нельзя:');
    console.log('они сняты до правки и выглядят точно так же, как свежие.');
    console.log('Отметить в Playwright ВСЕ нужные проекты и прогнать заново.');
    console.log('');
    process.exit(1);
}

console.log('');
console.log('Прогон ' + метки[0]);
console.log('');
for (const с of снимки) {
    const все = [...с.шапка.map(э => ({ ...э, где: 'шапка' })),
                 ...с.бургер.map(э => ({ ...э, где: 'бургер' }))];
    const мелкие = все.filter(э => э.в < НОРМА);
    console.log('### ' + с.проект + '  ' + с.окно.width + 'x' + с.окно.height +
                (с.бургерПоказан ? '  бургер показан' : '  бургера нет'));
    if (с.ушлиСоСтраницы && с.ушлиСоСтраницы.length)
        console.log('    УШЛИ СО СТРАНИЦЫ на шагах: ' +
            с.ушлиСоСтраницы.map(у => у.шаг).join(', ') + ' — замер шатается');
    if (с.отсевБургера)
        console.log('    бургер: нашли ' + с.отсевБургера.всего +
            ', выброшено за нулевой размер ' + с.отсевБургера.нулевойРазмер +
            ', за скрытость стилем ' + с.отсевБургера.скрытСтилем +
            ', измерено ' + с.бургер.length);
    if (с.состояние && с.состояние.разделы)
        console.log('    разделы: ' + с.состояние.разделы
            .map(р => р.имя + (р.раскрыт ? ' раскрыт' : ' ЗАКРЫТ') + '(' + р.ссылок + ')')
            .join(', '));
    console.log('    измерено ' + все.length + ', ниже ' + НОРМА + ': ' + мелкие.length);
    for (const м of мелкие)
        console.log('        ' + м.в + '  ' + м.где + '  ' + м.ключ + '  ' + (м.текст || ''));
    console.log('');
}
