/**
 * ЯЗЫК ОТКРЫТОЙ ВКЛАДКИ — ОДНО ОПРЕДЕЛЕНИЕ НА ВЕСЬ ЭКРАН.
 * Круг 14 ветки D, 18.10. Пункт 81 трекера.
 *
 * ЧТО БЫЛО. Три редактора (RU/EN/KG) живут в DOM одновременно, и «текст,
 * который автор сейчас пишет» — это поле ОТКРЫТОЙ вкладки. Понятие было
 * определено трижды: перевод (`translateToEmpty`) читал активную вкладку
 * ВЕРНО, а предпросмотр, время чтения и слушатель правок брали жёстко
 * русское поле `adNewsContent`. Автор писал английскую новость и видел в
 * предпросмотре русскую — экран показывал первый из трёх.
 *
 * ДАННЫЕ БЫЛИ ЦЕЛЫ, И ЭТО ПРОВЕРЕНО ЧТЕНИЕМ КОДА: сохранение читает все
 * три поля (`sections/news.js`, строки с `content_en` и `content_kg`).
 * Врал только экран.
 *
 * ЭТАЛОН УЖЕ БЫЛ В КОДЕ — третий раз за ветку D: правильный разбор
 * активной вкладки лежал в `translateToEmpty`, и его просто никто не звал.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ. Не «читать adNewsContentEn», а: язык
 * вкладки определён ОДИН раз, все три экранных места берут поле у этого
 * определения, слушатели навешены на ВСЕ языковые поля, а перерисовка
 * висит на коробе текста.
 *
 *   node tools/check-yazyk-vkladki.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const читать = п => fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8');
/* КОММЕНТАРИИ СНИМАЮТСЯ, И ЭТО НЕ МЕЛОЧЬ: прувер поймал правило, которое
   видело `A.полеВкладки` в ПОЯСНЕНИИ к коду и оставалось зелёным, когда
   сам вызов откатили. СТОРОЖ ЧИТАЕТ КОД, А НЕ СЛОВА О КОДЕ. Переводы
   строк сохраняются, иначе врут номера строк. */
const безСлов = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:'"\\])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));
const utils = безСлов(читать('js/admin/core/utils.js'));
const news = безСлов(читать('js/admin/sections/news.js'));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

/* ---- тело функции по имени: ищем от объявления до её закрывающей скобки ---- */
function тело(текст, объявление) {
    const н = текст.indexOf(объявление);
    if (н === -1) return '';
    const о = текст.indexOf('{', н);
    let глуб = 1, j = о + 1;
    while (j < текст.length && глуб > 0) {
        if (текст[j] === '{') глуб++;
        else if (текст[j] === '}') глуб--;
        j++;
    }
    return текст.slice(о, j);
}

/* ПРАВИЛО 1. Язык вкладки определён ОДИН раз и выведен наружу. */
правило('язык открытой вкладки определён один раз',
    /function\s+языкВкладки\s*\(/.test(utils) &&
    /function\s+полеВкладки\s*\(/.test(utils) &&
    /A\.полеВкладки\s*=/.test(utils),
    'Общее определение языка вкладки пропало из `js/admin/core/utils.js`.\n' +
    'Пока его нет, каждое место считает активную вкладку само — так и было:\n' +
    'перевод считал верно, предпросмотр и время чтения брали русское поле.');

/* ПРАВИЛО 2. Перевод НЕ считает активную вкладку заново — зовёт общее.
   Это и было сведение: его код был эталоном. */
const тПеревод = тело(utils, 'async function translateToEmpty');
правило('перевод берёт язык у общего определения',
    /языкВкладки\s*\(/.test(тПеревод) &&
    !/querySelector\(['"]\.ad-lang-tab\.active/.test(тПеревод),
    'Перевод снова разбирает активную вкладку сам:\n' +
    '`querySelector(\'.ad-lang-tab.active\')` внутри translateToEmpty.\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ — зовётся `языкВкладки(card)`.');

/* ПРАВИЛО 3. Предпросмотр читает поле ОТКРЫТОЙ вкладки. */
const тПредпросмотр = тело(news, 'function renderNewsPreview');
правило('предпросмотр читает поле открытой вкладки',
    /A\.полеВкладки/.test(тПредпросмотр),
    'Предпросмотр снова берёт текст жёстким id, а не у открытой вкладки.\n' +
    'Три редактора лежат в DOM разом: жёсткий `adNewsContent` всегда\n' +
    'показывает ПЕРВЫЙ, и автор английской новости видит русскую.');

/* ПРАВИЛО 4. Время чтения считается по открытой вкладке. */
const тМета = тело(news, 'function updateMetaPreview');
правило('время чтения считается по открытой вкладке',
    /A\.полеВкладки/.test(тМета),
    'Время чтения снова считается по русскому полю: английская новость\n' +
    'показывала время русской.');

/* ПРАВИЛО 5. Слушатели правок — на ВСЕХ трёх полях.
   Иначе правка в английской вкладке предпросмотр не трогает вовсе. */
/* ЯКОРЬ СУЖЕН: массив трёх полей встречается в файле ДВАЖДЫ — у
   `attachEditor` и у слушателя предпросмотра, — и правило держалось на
   первом, оставаясь зелёным при откате второго. Поймал прувер. Держимся
   за `previewTimer`: он живёт только в слушателе предпросмотра. */
const всеТри = /\[\s*'adNewsContent'\s*,\s*'adNewsContentEn'\s*,\s*'adNewsContentKg'\s*\][\s\S]{0,400}?previewTimer/;
правило('правки слушаются во всех трёх языковых полях',
    всеТри.test(news),
    'Слушатель правок навешен не на все три поля. Пока он на одном,\n' +
    'предпросмотр не шевелится, когда печатают в английской вкладке.');

/* ПРАВИЛО 6. Перерисовка при смене вкладки висит на коробе текста,
   а НЕ на `.ad-section`: его вокруг предпросмотра нет, и первая редакция
   правки молча не делала ничего — поймано прибором на стенде. */
правило('перерисовка при смене вкладки висит на коробе текста',
    /coробТекста|коробТекста/.test(news) &&
    /closest\('\.ad-form-card'\)[\s\S]{0,300}?addEventListener\('click'/.test(news) &&
    !/getElementById\('adNewsPreview'\)[\s\S]{0,80}?closest\('\.ad-section'\)/.test(news),
    'Перерисовка при смене языковой вкладки потеряла свой якорь.\n' +
    'Предпросмотр лежит в своём `.ad-form-card`, и `.ad-section` вокруг\n' +
    'него НЕТ: слушатель, прибитый к разделу, выходит молча и не делает\n' +
    'ничего. Якорь — короб русского поля (`adNewsContent.closest`).');

/* ПРАВИЛО 7. ДАННЫЕ ЦЕЛЫ: сохранение по-прежнему пишет все три языка.
   Сторож на то, чего чинить не надо, — чтобы круг не сломал базу. */
правило('сохранение пишет все три языка',
    /content_en\s*:/.test(news) && /content_kg\s*:/.test(news) &&
    /title_en\s*:/.test(news) && /excerpt_en\s*:/.test(news),
    'Из сохранения новости пропали языковые поля. Экран может показывать\n' +
    'один язык, но в базу идут ВСЕ: это свойство данных, а не вида.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      язык вкладки: 7 правил');
    console.log('          определение одно, перевод его зовёт');
    console.log('          предпросмотр и время чтения — по открытой вкладке');
    console.log('          слушатели на всех трёх полях, перерисовка на коробе текста');
    console.log('          сохранение пишет все три языка');
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  язык вкладки — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
