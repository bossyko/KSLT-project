#!/usr/bin/env node
/**
 * ЗАЯВКИ НА ПРИВЯЗКУ — ДВА ВИДА СПИСКА, А НЕ ВЫГРУЗКА (12.11.2026).
 *
 * ОТКУДА. Кнопка «История заявок» стояла третьей подряд с «Печать» и
 * «CSV» в ряду периода и тем же видом ad-btn-sm ad-btn-outline. Соседи
 * отдают файл, а она раскрывала ВТОРУЮ таблицу над основной и сдвигала
 * весь раздел вниз: вид обещал одно, делал другое. При этом в админке
 * два списка одних и тех же заявок — ожидающие (status pending) и
 * решённые, — и это именно два ВИДА одного, а не разные сущности.
 *
 * ЧТО СТОРОЖИТСЯ:
 *   1. кнопки истории в ряду выгрузки больше нет;
 *   2. есть вкладки с обоими видами и обе панели;
 *   3. вкладки взяты ГОТОВЫМ компонентом .ad-rat-tab, а не нарисованы
 *      заново — его уже носят Игроки, Вызовы, Live, Лояльность,
 *      Настройки;
 *   4. счётчик ожидающих берётся из того же запроса, что и список, —
 *      второго источника одного числа не заводим;
 *   5. история читается один раз за отрисовку, а не на каждое нажатие.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, ' ');

const ошибки = [];
const правило = (имя, условие, почему) => { if (!условие) ошибки.push(имя + ' — ' + почему); };

const усы = безКом(чит('js/admin/sections/users.js'));
const сло = чит('js/admin/core/constants.js');
const сти = чит('css/admin.css');

правило('кнопки истории в ряду выгрузки нет',
    !/adLinkHistoryBtn/.test(усы),
    'кнопка «История заявок» снова стоит кнопкой рядом с «Печать» и «CSV»:\n' +
    'соседи отдают файл, а она открывает другой вид списка');

правило('оба вида списка стоят вкладками',
    /data-usrlink="pending"/.test(усы) && /data-usrlink="history"/.test(усы) &&
    /id="adUsrLinkPanelPending"/.test(усы) && /id="adUsrLinkPanelHistory"/.test(усы),
    'пропала вкладка или панель одного из видов — до решённых заявок\n' +
    'станет не добраться, либо ожидающие потеряют своё место');

правило('вкладки взяты готовым компонентом, а не нарисованы заново',
    /class="ad-rat-tabs"/.test(усы) && /class="ad-rat-tab active"/.test(усы) &&
    /\.ad-rat-tabs\s*\{/.test(сти) && /\.ad-rat-panel\.active\s*\{/.test(сти),
    'вкладки раздела нарисованы своим классом: компонент .ad-rat-tab уже есть\n' +
    'и живёт в пяти разделах — второй такой разойдётся с ним на первой правке');

/* Признак смотрит в ТЕЛО функции, которая читает заявки: счёт, взятый
   где-то ещё, — это второй запрос за тем же числом. */
const телоСписка = (усы.match(/async function нарисоватьЗаявкиНаКарточку\(\)[\s\S]*?\n    \}/) || [''])[0];
правило('счётчик ожидающих берётся из того же запроса',
    /adUsrLinkCount/.test(телоСписка) && /заявки\.length/.test(телоСписка),
    'счётчик на вкладке считается отдельно от списка: одно число — один источник,\n' +
    'иначе вкладка и таблица разойдутся ровно на шве');

const телоВкладок = (усы.match(/function подключитьИсторию\([\s\S]*?\n    \}/) || [''])[0];
/* ПРИЗНАК, НАХОДЯЩИЙ СЕБЯ В ОБЪЯВЛЕНИИ, НИЧЕГО НЕ СТОРОЖИТ: первая
   редакция искала слово «загружена» и проходила, когда откат снёс саму
   проверку, оставив `var загружена = false`. Спрашивается ВЫХОД по
   признаку, а не наличие имени. */
правило('история читается один раз за отрисовку',
    /if\s*\(загружена\)\s*return;/.test(телоВкладок) && /загружена\s*=\s*true/.test(телоВкладок),
    'ленивая загрузка снята: каждое нажатие вкладки снова бьёт в базу за\n' +
    'решёнными заявками, которые не меняются');

правило('подписи вкладок живут в словаре',
    /linkPending:/.test(сло) && /linkHistory:/.test(сло) && /linkPendingEmpty:/.test(сло),
    'подпись вкладки или пустого списка зашита на месте вместо словаря админки');

if (ошибки.length) {
    console.error('ЗАЯВКИ ВКЛАДКАМИ — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
console.log('заявки вкладками: 6 правил держатся');
