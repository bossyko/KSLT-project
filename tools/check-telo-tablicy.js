/**
 * ЗАМОРОЗКА КУСКА 127 — СЛУШАТЕЛЬ НА ТЕЛЕ ТАБЛИЦЫ РОВНО ОДИН.
 *
 * Кнопки в строках таблиц админки вешаются делегированием, и слушатель
 * ставился ВНУТРИ функции отрисовки: `tbody.addEventListener('click')`.
 * Узел `tbody` при перерисовке не пересоздаётся — меняется только
 * `innerHTML`, — значит каждый фильтр, каждая страница и каждый ввод в
 * поиск добавляли ЕЩЁ ОДИН слушатель.
 *
 * ЗАМЕРЕНО НА БОЕВОЙ 22.10, раздел «Корты»: после четырёх перерисовок
 * ОДНО нажатие строки дало ПЯТЬ запросов к базе вместо одного. Это не
 * выведено из кода — подменён `fetch` и посчитаны обращения.
 *
 * `onclick` ЗАМЕНЯЕТ слушателя, а не добавляет. Так уже было сделано в
 * разделе турниров — единственном из семи; теперь это общий дом
 * `A.наТелоТаблицы`, и способ ОДИН на все семь.
 *
 *   node tools/check-telo-tablicy.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const УТИЛ = чит('js/admin/core/utils.js');
const РАЗДЕЛЫ = fs.readdirSync(path.join(КОРЕНЬ, 'js/admin/sections'))
    .filter(н => н.endsWith('.js')).sort()
    .map(н => ['js/admin/sections/' + н, чит('js/admin/sections/' + н)]);

/* ── 1. ДОМ ЕСТЬ И ЗАМЕНЯЕТ, А НЕ ДОБАВЛЯЕТ ──────────────────────────── */
правило('дом слушателя на теле таблицы есть и ставит его заменой',
    /function наТелоТаблицы\(тело, обработчик\) \{[\s\S]{0,160}тело\.onclick = обработчик;/.test(УТИЛ) &&
    /A\.наТелоТаблицы = наТелоТаблицы;/.test(УТИЛ),
    'Дом `наТелоТаблицы` пропал или перестал ставить слушатель ЗАМЕНОЙ.\n' +
    '`addEventListener` ДОБАВЛЯЕТ: при перерисовке в том же узле слушателей\n' +
    'становится двое, трое, пятеро — замерено на боевой, пять запросов к базе\n' +
    'на одно нажатие строки.');

/* ── 2. НИ ОДИН РАЗДЕЛ НЕ ВЕШАЕТ СЛУШАТЕЛЬ САМ ───────────────────────── */
const сами = [];
РАЗДЕЛЫ.forEach(([имя, текст]) => {
    const n = (текст.match(/tbody\.(addEventListener\('click'|onclick\s*=)/g) || []).length;
    if (n) сами.push(имя + ' — ' + n);
});
правило('ни один раздел не вешает слушатель на тело таблицы сам',
    сами.length === 0,
    'Вешают сами: ' + сами.join(', ') + '.\n' +
    'ОДНО ПОНЯТИЕ — ОДИН СПОСОБ. Пока способов было два, шесть разделов\n' +
    'копили слушателей, а седьмой нет, и отличить одно от другого можно было\n' +
    'только замером.');

/* ── 3. ВСЕ СЕМЬ МЕСТ ЗОВУТ ДОМ ──────────────────────────────────────── */
const зовов = РАЗДЕЛЫ.reduce((с, [, т]) => с + (т.match(/A\.наТелоТаблицы\(tbody,/g) || []).length, 0);
правило('дом зовут все семь мест',
    зовов === 7,
    'Зовов `A.наТелоТаблицы(tbody, …)`: ' + зовов + ', а замерено семь — тренеры,\n' +
    'корты, финансы, новости, игроки, турниры, скидки. Меньше — место\n' +
    'вернулось к своему способу; больше — появилось новое, и его не мерили.');

/* ── вывод ───────────────────────────────────────────────────────────── */
console.log('');
if (ошибки.length) {
    console.log('  НЕ ТАК  тело таблицы — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(([и, п]) => console.log('          ✗ ' + и + '\n            ' + п.replace(/\n/g, '\n            ') + '\n'));
    process.exit(1);
}
console.log('  ок      тело таблицы: 3 правила');
console.log('          слушатель ставится заменой, семь мест зовут один дом');
console.log('');
