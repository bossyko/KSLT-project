/* тело правила по селектору: от «селектор {» до ближайшей «}», по тексту
   без комментариев. */
function тело(селектор) {
    const i = тЧ.indexOf(селектор + ' {');
    if (i === -1) return null;
    const j = тЧ.indexOf('}', i);
    return j === -1 ? null : тЧ.slice(i, j);
}

