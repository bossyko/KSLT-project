const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ── 1. Какие таблицы ссылаются на одну и ту же больше раза ───────── */

const снимок = (() => {
    try { return fs.readFileSync(path.join(КОРЕНЬ, 'sql/схема/schema-snapshot.sql'), 'utf8'); }
    catch (e) { return null; }
})();

правило('снимок схемы на месте',
    снимок !== null,
    'Нет sql/схема/schema-snapshot.sql — связи взять неоткуда.\n' +
    'Без него правило молчало бы, а молчание сторожа выглядит как\n' +
    'зелёный прогон. Лучше упасть.');

const парные = new Map();   // 'memberships' -> Map('profiles' -> [имена ключей])
if (снимок) {
    const при = /^-- (\w+) : (\w+) : FOREIGN KEY \(([^)]+)\) REFERENCES (\w+)\(/gm;
    let м;
    while ((м = при.exec(снимок)) !== null) {
        const [, откуда, имяКлюча, , куда] = м;
        if (!парные.has(откуда)) парные.set(откуда, new Map());
        const к = парные.get(откуда);
        if (!к.has(куда)) к.set(куда, []);
        к.get(куда).push(имяКлюча);
    }
}

const двойные = [];
parneAll: for (const [откуда, цели] of парные) {
    for (const [куда, ключи] of цели) {
        if (ключи.length > 1) двойные.push({ откуда, куда, ключи });
    }
}

/* ── 2. Где в коде просят вложенную таблицу без имени связи ───────── */

const ФАЙЛЫ = [];
(function идти(д) {
    let сп = [];
    try { сп = fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }); } catch (e) { return; }
    сп.forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) { if (э.name !== 'node_modules') идти(п); }
        else if (/\.(ts|js)$/.test(э.name)) ФАЙЛЫ.push(п);
    });
})('supabase/functions');
(function идти(д) {
    let сп = [];
    try { сп = fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }); } catch (e) { return; }
    сп.forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) { if (э.name !== 'node_modules') идти(п); }
        else if (/\.js$/.test(э.name)) ФАЙЛЫ.push(п);
    });
})('js');

const найдено = [];
ФАЙЛЫ.forEach(ф => {
    let т;
    try { т = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'); } catch (e) { return; }

    двойные.forEach(({ откуда, куда, ключи }) => {
        /* ГРАНИЦА ЗАПРОСА — ПО СКОБКАМ, А НЕ ПО ОКНУ В N СТРОК.
           Окно врёт в обе стороны: короткий запрос захватит соседний,
           длинный — обрежется. Ищем `.from('A')` и затем ближайший
           `.select(` до следующего `.from(`. */
        const приFrom = new RegExp("\\.from\\(\\s*['\"]" + откуда + "['\"]\\s*\\)", 'g');
        let м;
        while ((м = приFrom.exec(т)) !== null) {
            const от = м.index;
            const следующий = т.indexOf('.from(', от + 6);
            const кусок = т.slice(от, следующий === -1 ? т.length : следующий);

            const приSelect = /\.select\(\s*(['"`])([\s\S]*?)\1/;
            const с = кусок.match(приSelect);
            if (!с) continue;
            const поля = с[2];

            /* `куда(` без восклицательного знака перед скобкой — просьба
               без имени связи. `куда!имя(` — названная связь, это и
               нужно. */
            const безИмени = new RegExp("(^|[^!\\w])" + куда + "\\s*\\(");
            if (безИмени.test(поля)) {
                const строка = т.slice(0, от).split('\n').length;
                найдено.push(ф + ':' + строка + '  ' + откуда + ' → ' + куда +
                             '  (ключей ' + ключи.length + ': ' + ключи.join(', ') + ')');
            }
        }
    });
});

правило('вложенная таблица с двумя связями названа по имени ключа',
    найдено.length === 0,
    'Запрос просит вложенную таблицу, у которой НЕ ОДНА связь:\n  ' +
    найдено.join('\n  ') + '\n\n' +
    'PostgREST отвечает «more than one relationship was found» и 500.\n' +
    'Писать надо `' + (двойные[0] ? двойные[0].куда + '!' + двойные[0].ключи[0] : 'таблица!имя_ключа') + '(...)`.\n' +
    'Беда не видна в журнале заданий: там стоит «успешно», потому что\n' +
    'запрос лишь ставится в очередь. Видно только в net._http_response.');

