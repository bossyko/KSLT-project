/**
 * МОЙ МАТЧ — ТОЛЬКО МОЙ, И ТОЛЬКО ПОКА ТУРНИР ОТКРЫТ. 14.11.
 *
 * ЧТО БЫЛО. Кнопка «Вписать счёт» показывалась по плоскому списку
 * карточек: своя плюс капитаны ВСЕХ пар, где человек когда-либо был
 * напарником. Список не знал турнира, и человек, бывший напарником
 * один раз, видел матчи того капитана ВЕЗДЕ — чужие пары, чужие
 * одиночки, чужие турниры. Находка Кости 14.11: «они могут не свои
 * игры счёт вписывать», снимок окна «Кошойбеков — Каракетов».
 *
 * База такой счёт отбивала: `match_side_of` сверяет напарничество с
 * турниром МАТЧА. То есть беда была не в записи, а в обещании:
 * КНОПКА ОБЕЩАЕТ РОВНО ТО, ЧТО СДЕЛАЕТ.
 *
 * ВТОРАЯ БЕДА, ТОГО ЖЕ ДНЯ: закрытый турнир ничем не был закрыт. Ни
 * экран, ни база не смотрели на статус турнира. ЗАМЕР 14.11: матчей
 * без победителя или в ожидании — 207 в `completed` и 33 в
 * `registration_closed`. Первые висели и каждый день просили счёт.
 * `registration_closed` — идущий турнир с закрытой записью, его
 * матчи счёт ждут по делу, и закрывать его нельзя.
 *
 * ТРЕТЬЕ, что здесь заперто: счёт, вписанный менеджером, окончателен.
 * Админка ставит `score_status: 'confirmed'`, правило отдаёт на него
 * `done` — у игроков ни кнопки, ни подтверждения. Держим обе стороны
 * вместе: порознь каждая выглядит согласной сама с собой.
 *
 *   node tools/check-svoy-match.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = о => fs.readFileSync(path.join(КОРЕНЬ, о), 'utf8');
/* КОММЕНТАРИЙ — НЕ КОД. Пример в примечании ловился уже дважды. */
const чисто = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '))
    .replace(/^\s*--[^\n]*/gm, '');

const ошибки = [];
let держится = 0;
function правило(имя, годно, подсказка) {
    if (годно) { держится++; return; }
    ошибки.push({ имя, подсказка });
}

const САЙТ = чисто(чит('js/match-score.js'));
const КАБ  = чисто(чит('js/my-match-actions.js'));
const СЕТ  = чисто(чит('js/my-match-buttons.js'));
const ПРИЛ = чисто(чит('mobile/www/js/match-score.js'));
const СВОД = чисто(чит('js/kslt-rules.js'));
const АДМ  = чисто(чит('js/admin/sections/bracket.js'));
const SQL  = чисто(чит('sql/функции/zakrytyy-turnir-ne-prinimaet-schyot-14noy.sql'));

/* ЯКОРЬ ДЕРЖИТСЯ НА ТЕЛЕ, А НЕ НА ФАЙЛЕ. Первая редакция прувера это и
   поймала: `[\s\S]*?` от имени функции перескакивал через её конец в
   следующую и зеленел на чужом замке. Режем файл по телам. */
function тело(имя) {
    const н = SQL.indexOf('FUNCTION public.' + имя + '(');
    if (н === -1) return '';
    const к = SQL.indexOf('$$;', н);
    return к === -1 ? SQL.slice(н) : SQL.slice(н, к);
}
const ВПИСАТЬ = тело('submit_match_score');
const ПОДТВЕРДИТЬ = тело('confirm_match_score');

/* ── 1. напарничество считается вместе с турниром ── */

правило(
    'сайт складывает капитанов по турнирам, а не в один список',
    /поТурниру/.test(САЙТ) && /tournament_registrations[\s\S]{0,400}?select\('player_id, tournament_id'\)/.test(САЙТ),
    'В `js/match-score.js` заявки напарника обязаны читаться вместе с\n' +
    '`tournament_id` и складываться в карту «турнир → капитаны». Плоский\n' +
    'список не знает, где человек пара, и показывает чужие матчи.');

правило(
    'сайт отдаёт карточки ПОД ТУРНИР',
    /MS\.myPlayerIdsIn\s*=\s*(async\s*)?function\s*\(\s*tournamentId\s*\)/.test(САЙТ),
    'Нужен `MS.myPlayerIdsIn(tournamentId)`: своя карточка плюс капитаны\n' +
    'ИМЕННО этого турнира. Без него решать «мой ли матч» нечем.');

правило(
    'окно счёта решает под турнир открытого матча',
    /myPlayerIdsIn\(m\.tournament_id\)/.test(САЙТ),
    'В `MS.open` карточки обязаны считаться от `m.tournament_id`, то есть\n' +
    'ПОСЛЕ чтения матча. Список, собранный до матча, турнира не знает.');

правило(
    'кабинет решает под турнир каждого матча',
    /поТурниру\[m\.tournament_id\]/.test(КАБ) && /tournament_id/.test(КАБ),
    'В `js/my-match-actions.js` матч признаётся своим по карточкам ТОГО\n' +
    'турнира, где он сыгран. Базе список отдаётся пошире — иначе пришлось\n' +
    'бы спрашивать по турниру, — но решение принимается поуже.');

правило(
    'сетка берёт карточки под свой турнир',
    /myPlayerIdsIn\(\s*id\s*\)/.test(СЕТ),
    'В `js/my-match-buttons.js` список обязан считаться от номера турнира\n' +
    'со страницы. Плоский список показывал кнопку там, где человек не играет.');

правило(
    'приложение складывает капитанов по турнирам',
    /_поТурниру/.test(ПРИЛ) && /select\('player_id, tournament_id'\)/.test(ПРИЛ),
    'У приложения своё окно счёта и была та же дыра. `mobile/www/js/\n' +
    'match-score.js` обязан читать `tournament_id` вместе с заявкой.');

правило(
    'приложение решает под турнир матча',
    /MS\.myIdsIn\s*=\s*function/.test(ПРИЛ) &&
    /matchScoreState\(match,\s*MS\.myIdsIn\(match\.tournament_id\)/.test(ПРИЛ),
    'В приложении `stateOf` обязан звать `myIdsIn(match.tournament_id)`.\n' +
    'Широкий список `myIds()` годится только чтобы спросить базу.');

/* ── 2. закрытый турнир ── */

правило(
    'признак закрытости у сайта один и назван',
    /MS\.турнирЗакрыт\s*=\s*function/.test(САЙТ) &&
    /'completed'/.test(САЙТ) && /'cancelled'/.test(САЙТ),
    'Нужен один признак `MS.турнирЗакрыт(t)` на окно, список и сетку.\n' +
    'Три раза написанное «status === completed» разойдётся на первой правке.');

правило(
    'признак закрытости есть и у приложения',
    /MS\.турнирЗакрыт\s*=\s*function/.test(ПРИЛ),
    'У приложения своё окно — и свой такой же признак. Без него закрытый\n' +
    'турнир примет счёт с телефона.');

правило(
    'идущий турнир с закрытой записью счёт принимает',
    !/registration_closed/.test(САЙТ) && !/registration_closed/.test(ПРИЛ) &&
    !/registration_closed/.test(КАБ),
    'ЗАКРЫТА ЗАПИСЬ — НЕ ЗАКРЫТ ТУРНИР. `registration_closed` это идущий\n' +
    'турнир (замер 14.11: 33 матча ждут счёта). Попадёт в признак\n' +
    'закрытости — игроки лишатся кнопки на живых матчах.');

правило(
    'окно закрытого турнира не открывается',
    /турнирЗакрыт\(m\.tournament\)/.test(САЙТ) && /турнирЗакрыт\(m\.tournament\)/.test(ПРИЛ),
    'Окно обязано отказывать до показа полей: иначе человек впишет счёт,\n' +
    'нажмёт отправку и получит отказ базы на готовом счёте.');

правило(
    'статус турнира вообще читается запросом',
    /set_format, status/.test(САЙТ) && /set_format, status/.test(ПРИЛ) &&
    /title_kg, status/.test(КАБ),
    'СТОРОЖ, ПОТЕРЯВШИЙ ПРЕДМЕТ, ЗЕЛЕНЕЕТ НА ПУСТОТЕ: без `status` в\n' +
    'выборке `турнирЗакрыт` всегда вернёт «открыт», и правила выше\n' +
    'перестанут что-либо значить.');

правило(
    'сетка закрытого турнира кнопок не даёт',
    /турнирЗакрыт\([\s\S]{0,40}?\)/.test(СЕТ) && /from\('tournaments'\)/.test(СЕТ),
    'В `js/my-match-buttons.js` статус турнира обязан читаться и\n' +
    'проверяться до разметки: иначе в сетке закрытого турнира клетки\n' +
    'останутся нажимаемыми.');

/* ── 3. замок в базе: экран не замок ── */

правило(
    'в базе есть один признак закрытости для счёта',
    /CREATE OR REPLACE FUNCTION public\.turnir_zakryt_dlya_schyota/.test(SQL) &&
    /'completed', 'cancelled'/.test(SQL),
    'ЭКРАН — НЕ ЗАМОК: запрос уходит в базу напрямую. Нужна функция\n' +
    '`turnir_zakryt_dlya_schyota(match_id)` и проверка в зовах.');

правило(
    'вписать в закрытый турнир база не даёт',
    /turnir_zakryt_dlya_schyota\(p_match_id\)[\s\S]{0,160}?'tournament_closed'/.test(ВПИСАТЬ),
    '`submit_match_score` обязан отказывать на закрытом турнире кодом\n' +
    '`tournament_closed` — и ДО разбора счёта, чтобы не считать зря.');

правило(
    'подтвердить в закрытом турнире база не даёт',
    /turnir_zakryt_dlya_schyota\(p_match_id\)[\s\S]{0,160}?'tournament_closed'/.test(ПОДТВЕРДИТЬ),
    '`confirm_match_score` обязан отказывать так же: иначе счёт, вписанный\n' +
    'до закрытия, можно подтвердить после.');

/* ── 4. счёт менеджера окончателен ── */

правило(
    'админка пишет счёт сразу подтверждённым',
    /score_status:\s*'confirmed'/.test(АДМ),
    'Счёт от менеджера подтверждать некому. Поставь админка `pending` —\n' +
    'игроки получат окно «подтвердите счёт» на уже решённом матче.');

/* ── 5. в паре счёт закрывается у обоих ── */

правило(
    'подтверждает ДРУГАЯ СТОРОНА, а не другой человек',
    /мояСторона/.test(СВОД) && /ихСторона/.test(СВОД) &&
    /score_submitted_player/.test(СВОД),
    'В паре напарник вписавшего видел «Подтвердить» на своём же счёте\n' +
    '(слово Кости 14.11). Сторона вписавшего обязана выводиться из\n' +
    '`score_submitted_player` и сравниваться со своей стороной.');

правило(
    'карточка вписавшего приезжает в выборках',
    /score_submitted_player/.test(КАБ) && /score_submitted_player/.test(СЕТ),
    'СТОРОЖ, ПОТЕРЯВШИЙ ПРЕДМЕТ, ЗЕЛЕНЕЕТ НА ПУСТОТЕ: без поля в выборке\n' +
    'сторона вписавшего неизвестна, и правило тихо откатится на сравнение\n' +
    'по человеку — ровно то, что чинили.');

правило(
    'карточку вписавшего кладёт база',
    /score_submitted_player\s*=\s*v_karta/.test(чисто(чит('sql/схема/storona-vpisavshego-14noy.sql'))),
    '`submit_match_score` обязан записывать карточку вписавшего. Иначе\n' +
    'поле всегда пусто, и сторону вывести не из чего.');

правило(
    'старым записям сторона досчитана',
    /UPDATE public\.matches m SET score_submitted_player/.test(чит('sql/схема/storona-vpisavshego-14noy.sql')),
    'Без заполнения прежних записей все висящие сейчас счета остались бы\n' +
    'на старом сравнении по человеку.');

правило(
    'без карточки вписавшего правило не падает, а считает по-старому',
    /return match\.score_submitted_by === myUserId \? 'wait' : 'confirm';/.test(СВОД),
    'УМОЛЧАНИЕ — СВОЙСТВО ДАННЫХ. Поля может не быть (запись из админки,\n' +
    'старый матч): тогда сравниваем по человеку, как раньше, а не\n' +
    'показываем пустоту.');

правило(
    'подтверждённый счёт игроку делать нечего',
    /score_status === 'confirmed'[\s\S]{0,80}?return 'done'/.test(СВОД),
    'В `js/kslt-rules.js` на `confirmed` правило обязано отдавать `done`:\n' +
    'это и есть то, из-за чего счёт менеджера не спрашивают у игроков.');

console.log('');
if (!ошибки.length) {
    console.log('  ок      свой матч: ' + держится + ' правил');
    console.log('          напарничество считается вместе с турниром — и на сайте, и в приложении');
    console.log('          закрытый турнир заперт дважды: экраном и базой');
    console.log('          замер 14.11: 207 матчей в completed, 33 в registration_closed');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  свой матч — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
