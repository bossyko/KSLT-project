#!/usr/bin/env node
/**
 * ОПИСАНИЕ СХЕМЫ — ОДНО, И ЭТО СНИМОК.
 *
 * ЗАЧЕМ. В репозитории лежат ДВА описания устройства базы:
 *   • `supabase/migrations/…_baseline.sql` — слепок от 10.08.2026, снятый
 *     один раз и с тех пор не обновлявшийся;
 *   • `sql/схема/schema-snapshot.sql` — снимок, который пересобирается
 *     прибором из чтения каталога постгреса.
 * Схему после августа правили 187 скриптами, и слепок отстал на три
 * месяца.
 *
 * ЧЕМ ЭТО КОНЧИЛОСЬ 13.11. Три запроса подряд упали на колонках, которых
 * в боевой нет; хуже — в слепке НЕТ таблиц `player_link_requests` и
 * `registration_changes`, а у первой внешний ключ с ON DELETE CASCADE.
 * Недостающая колонка даёт ошибку сразу, неизвестная связь с каскадом
 * уносит данные молча: так чуть не пропала заявка игрока на турнир.
 * И прибор вызова три месяца читал статусы ИЗ СЛЕПКА — совпали они
 * случайно, то есть это было везение, а не проверка.
 *
 * ПРАВИЛО ДЕРЖИТ ОТНОШЕНИЕ: правду о схеме знает снимок, слепок помечен
 * и никем не читается.
 *
 * Запуск: node tools/check-opisanie-shemy.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_ROOT || path.join(__dirname, '..');
/* СЛЕПКА БОЛЬШЕ НЕТ — он удалён 13.11 по слову Кости. Имя оставлено,
   чтобы правило могло проверить, что он не вернулся: пока оно здесь,
   возвращение файла поймается сразу, а не через три месяца молчания. */
const СЛЕПОК = 'supabase/migrations/20260210000000_baseline.sql';
const СНИМОК = 'sql/схема/schema-snapshot.sql';

const ошибки = [];
const ок = [];
function правило(имя, держится, почему) {
    if (держится) ок.push(имя); else ошибки.push({ имя, почему });
}
const читать = (ф) => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');

const снимок = читать(СНИМОК);

правило('описание схемы ровно одно — слепок удалён и не вернулся',
    !fs.existsSync(path.join(КОРЕНЬ, СЛЕПОК)),
    'Слепок `' + СЛЕПОК + '` снова лежит в дереве.\n' +
    'Он был снят один раз 10.08 и отстал на три месяца: три запроса 13.11\n' +
    'упали на колонках, которых в боевой нет, а двух таблиц с каскадным\n' +
    'удалением он не знал вовсе. Пока описаний два, беда рождается не в\n' +
    'коде, а в том, кто какой файл открыл. Правда — в `' + СНИМОК + '`.');

/* СНИМОК ЗНАЕТ ТО, ЧЕГО НЕ ЗНАЕТ СЛЕПОК. Это не украшение, а
   доказательство, что снимок новее: обе таблицы появились после августа,
   и у первой каскадное удаление. */
const ПОЗЖЕ_АВГУСТА = ['player_link_requests', 'registration_changes'];
const нетВСнимке = ПОЗЖЕ_АВГУСТА.filter(т => snimokНеЗнает(т));
function snimokНеЗнает(имя) { return snimokСчёт(имя) === 0; }
function snimokСчёт(имя) { return (снимок.match(new RegExp(имя, 'g')) || []).length; }
правило('снимок знает таблицы, заведённые после слепка',
    нетВСнимке.length === 0,
    'Снимок не знает: ' + нетВСнимке.join(', ') + '\n' +
    'Значит он сам отстал — пересобрать: прогнать sql/схема/snyat-shemu.sql\n' +
    'и `node tools/sobrat-snimok-shemy.js <выгрузка>`.');

/* НИ ОДИН ПРИБОР НЕ ЧИТАЕТ СЛЕПОК. Прибор, читающий устаревшее описание,
   даёт ложную уверенность — и даёт её молча. */
const приборы = fs.readdirSync(path.join(КОРЕНЬ, 'tools'))
    .filter(ф => ф.endsWith('.js'))
    .filter(ф => ф !== 'check-opisanie-shemy.js' && ф !== 'check-opisanie-shemy-otkat.js');
const читающие = приборы.filter(ф =>
    /20260210000000_baseline/.test(fs.readFileSync(path.join(КОРЕНЬ, 'tools', ф), 'utf8')));
правило('ни один прибор не читает слепок как описание схемы',
    читающие.length === 0,
    'Читают слепок: ' + читающие.join(', ') + '\n' +
    'Прибор, сверяющийся с описанием трёхмесячной давности, зеленеет не\n' +
    'потому, что код верен, а потому, что описание устарело вместе с ним.\n' +
    'Читать `' + СНИМОК + '`.');

правило('снимок остался чтением, а не скриптом',
    !/^\s*(CREATE|ALTER|DROP|INSERT|UPDATE|DELETE)\b/mi.test(снимок),
    'В снимке появились исполняемые запросы. Он нарочно сделан целиком\n' +
    'комментарием: прежний снимок был выгрузкой pg_dump, его прогнали в\n' +
    'живой базе 09.10, и он успел объявить десять функций прежде чем\n' +
    'свалиться. ФАЙЛ, КОТОРЫЙ НЕЛЬЗЯ ЗАПУСТИТЬ, НЕ НАДО ПОМНИТЬ НЕ\n' +
    'ЗАПУСКАТЬ.');

console.log('');
ок.forEach(и => console.log('  ок      ' + и));
ошибки.forEach(о => console.log('\n  НЕ ТАК  ' + о.имя + '\n          ' + о.почему.split('\n').join('\n          ')));
console.log('');
if (ошибки.length) { console.log('  Описание схемы: не сошлось ' + ошибки.length + '\n'); process.exit(1); }
console.log('  ок      описание схемы: ' + ок.length + ' правила, приборов проверено ' + приборы.length + '\n');
