#!/usr/bin/env node
/**
 * ТАБЛО ТУРНИРА В ПРИЛОЖЕНИИ — ЗАМОРОЗКА КУСКОВ 221-225 (28.10).
 *
 * Пять кусков одного дня, и все они — про одно табло: таблицу группы,
 * сетку плей-офф, расписание, очки и нижнюю навигацию. Правила собраны
 * в один сторож, потому что беда у них общая: одно понятие,
 * нарисованное в двух местах, и число, посчитанное на глаз.
 *
 * ЗАМОРОЖЕНЫ ОТНОШЕНИЯ, А НЕ ЧИСЛА — кроме тех, что названы ЗАМЕРОМ:
 * колонка имени 152 взята не из головы, а как единственная ширина, при
 * которой пара укладывается в ДВЕ строки, а не в четыре.
 *
 * Запуск: node tools/check-tablo-turnira-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
function безСлов(отн) {
    return чит(отн).replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const css = безСлов('mobile/www/css/app.css');
const главная = безСлов('mobile/www/js/screens/home.js');
const оболочка = безСлов('mobile/www/js/app.js');
const домСетки = безСлов('js/kslt-setka.js');
const домПравил = безСлов('js/kslt-rules.js');

/* ── ПАРА ИГРОКОВ ── */
правило(
    'пара разделена косой, а не просто двумя строками',
    /\.tm-p:not\(:last-child\)::after\s*\{[^}]*content:\s*' \/'/.test(css),
    'На сайте пара пишется через косую (js/tournament-detail.js:160).\n' +
    'В приложении разделитель был потерян: два имени шли двумя блоками,\n' +
    'и на узком виде каждое ещё переносилось — пара читалась четырьмя\n' +
    'строками без признака пары. «vs» тут не годится: им разделяют\n' +
    'СОПЕРНИКОВ, а не партнёров.');

правило(
    'имя — один блок, иначе посев уезжает над ним',
    /\.tm-pair\s*\{[^}]*display:\s*block[^}]*overflow:\s*hidden/.test(css) &&
    (главная.match(/<span class="tm-pair">/g) || []).length >= 3,
    'Пока имя было двумя блоками подряд, номер посева начинал строку\n' +
    'сам по себе и вставал НАД именем.');

правило(
    'посев плавает слева, а имя обтекает его справа',
    /\.td-gt-name \.td-gt-seed\s*\{[^}]*float:\s*left/.test(css),
    'Замер на настоящей разметке: flex ставил номер на первую строку, но\n' +
    'отнимал у имени ширину, и пара разъезжалась на ЧЕТЫРЕ строки.\n' +
    'Обтекание даёт и номер слева, и полную ширину имени.');

правило(
    'колонка имени 152 — ЗАМЕРЕННАЯ, а не задуманная',
    /\.td-gt-name\s*\{[^}]*min-width:\s*152px/.test(css),
    'Семь вариантов мерены одним прогоном на 411. При 120 пара занимала\n' +
    'ЧЕТЫРЕ строки и 79.4 px на ряд при любой правке; при 152 — ДВЕ\n' +
    'строки и 50 px. Это единственное число, при котором пара\n' +
    'укладывается, поэтому оно и заморожено.');

правило(
    'пара в таблице группы пишется сокращённо, одиночник — целиком',
    /function коротко\s*\(/.test(главная) &&
    (главная.match(/коротко\(/g) || []).length >= 3,
    'Прежняя запись в этом файле говорила «в таблице места больше, и\n' +
    'обрезать нечего». Замер её отменил: один человек в клетку\n' +
    'помещается, двое — нет.');

/* ── СЕТКА ── */
правило(
    'матч за третье место отдаётся ХВОСТОМ последнего круга',
    /опции\.хвост = хвост/.test(главная) &&
    !/h \+= '<div class="td-third-place">'/.test(главная),
    'Дописанный ПОСЛЕ сетки блок уезжал под первый столбец: полоса\n' +
    'сетки прокручивается вбок, а он стоял за её пределами. На сайте\n' +
    'записано прямо: «в колонке финала, но ниже»\n' +
    '(js/tournament-detail.js:1715).');

правило(
    'дом вставляет хвост ВНУТРЬ последнего столбца',
    /if \(i === круги\.length - 1 && опции\.хвост\) h \+= опции\.хвост;/.test(домСетки),
    'Хвост обязан лежать в том же столбце, что и финал, иначе он снова\n' +
    'окажется вне прокручиваемой полосы.');

правило(
    'при проходе BYE пишется ОДИН раз',
    /if \(этоПроход\) \{ сырые = \[\]; исход = ''; \}/.test(домСетки),
    'BYE приходил дважды: именем соперника и ещё раз из поля счёта,\n' +
    'рядом с именем победителя, отжимая его на две строки.\n' +
    'ОДНО ПОНЯТИЕ — ОДНО МЕСТО.');

/* ── РЯД КРУГОВ НАД СЕТКОЙ (кусок 232) ── */
правило(
    'дом рисует ряд кругов, когда его просят',
    /опции\.круги && круги\.length > 1/.test(домСетки) &&
    /class="td-round-chip"/.test(домСетки) &&
    /экр\(круг\.name\)/.test(домСетки),
    'Замер на 375: при 4 кругах сетка 776 при видимых 343 (2.26 экрана),\n' +
    'при 6 кругах — 1176 (3.43 экрана). Без ряда человек листает вслепую\n' +
    'и не знает, сколько ещё. Подпись круга ЭКРАНИРУЕТСЯ: она приходит\n' +
    'доводом от зовущего, и дом не может проверить, что это словарь.');

правило(
    'нажатие на круг подводит и ПО ВЫСОТЕ, а не только вбок',
    /клетка\.scrollIntoView\(\{ block: 'center'/.test(домСетки),
    'При 64 участниках столбец первого раунда высотой 3406 px, а клетки\n' +
    'стоят по центру своего столбца. Перепрыгнув вбок на финал, человек\n' +
    'упёрся бы в ПУСТОТУ: единственная клетка висит посреди трёх с\n' +
    'половиной тысяч пикселей. Боковой подводки тут мало.');

правило(
    'боковой ход у сетки НЕ отнят — ряд это второй путь',
    /\.td-bracket-scroll\s*\{[^}]*overflow-x:\s*auto/.test(css) &&
    /\.td-rounds\s*\{[^}]*overflow-x:\s*auto/.test(css),
    'ЕДИНСТВЕННЫЙ ПУТЬ ДЕЙСТВИЯ — ЭТО ОТСУТСТВИЕ ПУТИ ДЛЯ ПОЛОВИНЫ ЛЮДЕЙ.\n' +
    'Ряд добавлен К прокрутке, а не вместо неё. Сам ряд тоже листается:\n' +
    'при шести кругах подписи занимают 633 px при видимых 343.');

правило(
    'приложение просит ряд и заводит его ПРИ ПОКАЗЕ вкладки',
    /опции\.круги = true/.test(главная) &&
    /KSLT_SETKA\.завестиКруги\(узел\)/.test(главная),
    'Заводить надо при показе: у скрытого элемента ширина ноль, и\n' +
    'считать смещения столбцов не от чего — правило уже в указателе.');

/* ── ОТСЕЧКА ── */
правило(
    'отсечка стоит и на Очках',
    /data-cut-block="results"/.test(главная) &&
    /\.td-points-list\.is-cut > \.pd-match:nth-child\(n \+ 11\)/.test(css),
    'Механизм заведён куском 216 и стоял на участниках и расписании.\n' +
    'Очки — список из div, а не таблица, поэтому у них своё правило.');

правило(
    'число строк в кнопке отсечки кладётся ПРИ СБОРКЕ, а не считается по DOM',
    /data-total="' \+ всего \+ '"/.test(главная) &&
    !/setAttribute\('data-total', блок\.querySelectorAll/.test(главная),
    'Одно и то же число жило в двух местах. Для списка из div второй\n' +
    'счёт (по `tbody tr`) давал НОЛЬ.');

/* ── НИЖНЯЯ НАВИГАЦИЯ ── */
правило(
    'накладка-подробность не закрывает нижнюю панель',
    /\.td-overlay\s*\{[^}]*bottom:\s*calc\(var\(--tab-height\) \+ var\(--safe-bottom\)\)/.test(css),
    'Навигация верхнего уровня остаётся на экранах-подробностях — так у\n' +
    'Material и у Apple HIG. Прячется она только на настоящих модалках.');

правило(
    'полноэкранный Live тоже оставляет панель',
    /\.live-full\s*\{[^}]*bottom:\s*calc\(var\(--tab-height\) \+ var\(--safe-bottom\)\)/.test(css),
    'Слово Кости: «сделай так, чтобы на всех страницах нижняя навигация\n' +
    'отображалась». Без панели остаётся только просмотр снимка\n' +
    '(.nm-viewer): там она закрывает само фото.');

правило(
    'нижняя кнопка закрывает и накладки, и Live',
    /querySelectorAll\('\.td-overlay\.open, \.live-full\.open'\)/.test(оболочка),
    'ОТКРЫТЫЙ ДОСТУП К УПРАВЛЕНИЮ РОЖДАЕТ ПУТЬ, КОТОРОГО НЕ БЫЛО: пока\n' +
    'накладка перекрывала панель, нажать было нечего. Открыли — и\n' +
    'нажатие переключало экран ПОД накладкой, а она оставалась поверх.');

правило(
    'подпись в боковом меню по левому краю',
    /\.menu-item span\s*\{[^}]*text-align:\s*left/.test(css),
    'Длинная подпись переносилась на две строки и вставала по центру —\n' +
    'одна строка списка выбивалась из колонки.');

/* ── ТАЙ-БРЕЙК ── */
правило(
    'мировая запись тай-брейка живёт в доме правил',
    /R\.сетПоМировому = function/.test(домПравил) &&
    /R\.счётПоМировому = function/.test(домПравил),
    'В скобке очки ПРОИГРАВШЕГО, одним числом, и скобка на стороне\n' +
    'проигравшего сет — слово Кости 28.10. Дом один на оба продукта,\n' +
    'значит и запись одна.');

правило(
    'в базу кладётся ПОЛНЫЙ счёт, а не урезанный до мировой записи',
    /сеты\.push\(a \+ '\/' \+ b\);/.test(домПравил) &&
    !/var п = R\.сетПоМировому\(a, b\);/.test(домПравил),
    'ЗАМЕР БАЗЫ 28.10: 105 строк со скобкой, странных ноль, и все одной\n' +
    'формы `(p1-p2)` — хранятся ОБА счёта тай-брейка. Мировая запись\n' +
    'оставляет только очки проигравшего, то есть канонизация при\n' +
    'сохранении ТЕРЯЛА БЫ ДАННЫЕ и завела бы в одном столбце две формы.\n' +
    'ХРАНИМ ПОЛНОЕ, ПОКАЗЫВАЕМ ПРИНЯТОЕ.');

правило(
    'клетка сетки показывает счёт по мировой записи',
    /KSLT_RULES\.счётПоМировому\(м\.score\)/.test(домСетки),
    'Старые строки в базе не тронуты — они приводятся к виду при показе.');

правило(
    'переворот счёта переставляет СТОРОНЫ, а не пары цифр',
    !/replace\(\/\(\\d\+\)\\\/\(\\d\+\)\/g, '\$2\/\$1'\)/.test(домПравил) &&
    /R\.перевернутьСчёт[\s\S]{0,400}?с\.slice\(i \+ 1\) \+ '\/' \+ с\.slice\(0, i\)/.test(домПравил),
    'Прежнее выражение на «6/5(7-5)» давало «5/6(7-5)» — скобка\n' +
    'оставалась у того, кто сет ВЫИГРАЛ. Этим счётом страница игрока\n' +
    'показывает матч глазами соперника.');

/* ── КОПИИ ── */
правило(
    'копии домов в приложении совпадают с сайтом до байта',
    чит('js/kslt-setka.js') === чит('mobile/www/js/kslt-setka.js') &&
    чит('js/kslt-rules.js') === чит('mobile/www/js/kslt-rules.js'),
    'Разойдутся — и беда родится ровно на шве.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      табло турнира приложения: все ' + держится + ' правил держатся');
    console.log('          пара, посев, сетка, отсечка, навигация, тай-брейк\n');
}
