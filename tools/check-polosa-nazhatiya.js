/**
 * ЗАМОРОЗКА КУСКА 149 — НАЖАТИЯ ПОЛОСЫ СТРАНИЦ ЖИВУТ ТАМ, ГДЕ ПОЛОСА
 * РИСУЕТСЯ.
 *
 * ЧТО БЫЛО. Полосу рисовал ОДИН дом `js/polosa-stranic.js`, а решение
 * «что делает нажатие» было определено СЕМЬ раз: кабинет трижды
 * (`dashboard.js`), «Новости» один раз, «Игроки» дважды и седьмой — в доме
 * витрины, куда за ним приходили корты, тренеры и партнёры. Имя класса
 * `pl-page-btn` жило в рисовании, а судьба этого класса решалась в шести
 * других файлах: ровно тот шов, на котором беда и родится.
 *
 * ТРИ КОПИИ КАБИНЕТА ВЕШАЛИ СЛУШАТЕЛЯ НА КАЖДУЮ КНОПКУ ПРИ КАЖДОЙ
 * ОТРИСОВКЕ — по слушателю на кнопку вместо одного на полосу.
 *
 * Правила ниже держат не форму записи, а ОТНОШЕНИЕ: тело одно, зовут его
 * все, у каждого зова свой ключ, повторный зов второго слушателя не вешает,
 * а доводы берутся из хранилки, а не из замыкания.
 */
const fs = require('fs');
const path = require('path');
const acorn = require(path.join(__dirname, '..', 'node_modules', 'acorn'));

const КОРЕНЬ = path.join(__dirname, '..');
const чит = (ф) => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const есть = (ф) => fs.existsSync(path.join(КОРЕНЬ, ф));

let плохо = 0, правил = 0;
function правило(имя, ок, беда) {
    правил++;
    if (ок) return;
    плохо++;
    console.log('\n  НЕ ТАК  ' + имя + '\n          ' + String(беда).split('\n').join('\n          '));
}
const дерево = (т) => acorn.parse(т, { ecmaVersion: 2022, locations: true });
function обойти(узел, дело, род) {
    if (!узел || typeof узел !== 'object') return;
    if (узел.type) дело(узел, род);
    for (const к in узел) {
        if (к === 'loc') continue;
        const з = узел[к];
        if (Array.isArray(з)) з.forEach(д => обойти(д, дело, узел));
        else if (з && typeof з === 'object' && з.type) обойти(з, дело, узел);
    }
}

const ДОМ = 'js/polosa-stranic.js';
const ВИТРИНА = 'js/kslt-vitrina.js';
const ПОТРЕБИТЕЛИ = ['js/dashboard.js', 'js/news.js', 'js/players.js'];

/* ---- 1. тело решения одно на продукт ---- */
const СВОИ = [];
fs.readdirSync(path.join(КОРЕНЬ, 'js')).forEach(ф => {
    if (!/\.js$/.test(ф)) return;
    const пт = 'js/' + ф;
    if (пт === ДОМ) return;
    const т = чит(пт);
    if (/pl-page-prev/.test(т) && /pl-page-next/.test(т)) СВОИ.push(пт);
});
правило('решение о нажатии полосы определено только в доме',
    СВОИ.length === 0,
    'Своё тело вернулось в: ' + СВОИ.join(', ') + '.\n' +
    'Имя класса `pl-page-prev` живёт там, где полоса рисуется, и решение\n' +
    'о нём — там же. Семь определений на одно рисование уже было.');

/* ---- 2. у дома есть понятие и оно одно ---- */
const домТекст = чит(ДОМ);
правило('дом полосы отдаёт понятие `нажатия`',
    /полосаСтраниц\.нажатия\s*=\s*function/.test(домТекст),
    'В `' + ДОМ + '` нет `полосаСтраниц.нажатия`. Потребители зовут его\n' +
    'по имени, и без него полоса перестанет нажиматься МОЛЧА.');

/* ---- 3. повторный зов не вешает второго слушателя ---- */
let дедуп = false;
обойти(дерево(домТекст), (у, род) => {
    if (!(у.type === 'FunctionExpression' && род && род.type === 'AssignmentExpression' &&
          домТекст.slice(род.left.start, род.left.end) === 'полосаСтраниц.нажатия')) return;
    const тело = домТекст.slice(у.start, у.end);
    дедуп = /__ksltПолосаКлючи/.test(тело) && /return;/.test(тело) &&
            /addEventListener/.test(тело);
});
правило('повторный зов не вешает второго слушателя',
    дедуп,
    'Понятие `нажатия` обязано помнить пару «область + ключ» и выходить\n' +
    'при повторном зове. Иначе каждая отрисовка добавляет слушателя, и\n' +
    'одно нажатие даст столько переходов, сколько было отрисовок.');

/* ---- 3а. дом берёт СВОЮ кнопку, а не любую ----
   НАЙДЕНО СТЕНДОМ, А НЕ РАЗБОРОМ КОДА. Слушатель на `document` слышит
   нажатия ВСЕХ полос страницы. Замер 23.10 на стенде с двумя полосами:
   одно нажатие в первой уводило на вторую страницу ОБЕ, а нажатие в
   третьей полосе уводило первые две на пятую. На живых экранах полоса
   сегодня одна, поэтому беда не выстреливала — и именно поэтому её надо
   держать правилом, а не памятью. */
let своя = false;
обойти(дерево(домТекст), (у, род) => {
    if (!(у.type === 'FunctionExpression' && род && род.type === 'AssignmentExpression' &&
          домТекст.slice(род.left.start, род.left.end) === 'полосаСтраниц.нажатия')) return;
    const тело = домТекст.slice(у.start, у.end);
    своя = /о\.полоса/.test(тело) && /contains\(кнопка\)/.test(тело);
});
правило('дом берёт свою кнопку, а не любую на странице',
    своя,
    'Понятие `нажатия` обязано принимать довод `полоса` и выходить, если\n' +
    'нажатая кнопка лежит ВНЕ его полосы. Без этого две полосы на одной\n' +
    'области ходят вместе: замерено на стенде `maket/stend-polosa-nazhatiya.html`.');

/* ---- 3б. стенд держит именно этот случай ---- */
const СТЕНД = 'maket/stend-polosa-nazhatiya.html';
правило('стенд полосы на месте и показывает крайний случай',
    есть(СТЕНД) && (() => {
        const с = чит(СТЕНД);
        return /полоса: имя === 'C' \? null : полоса/.test(с) &&
               /область: имя === 'C' \? полоса : document/.test(с) &&
               /сНуля/.test(с) && /stZanovo/.test(с);
    })(),
    'Стенд обязан держать три полосы: две на одной области с разными\n' +
    'ключами (так ходят «Игроки»), одна со счётом С НУЛЯ (так ходят «Мои\n' +
    'игры» в кабинете) и кнопка повторной регистрации. Удобный стенд\n' +
    'доказывает только себя.');

/* ---- 4. витрина делегирует, а не держит своё ---- */
const витТекст = чит(ВИТРИНА);
let витДелегирует = false;
обойти(дерево(витТекст), (у, род) => {
    if (!(у.type === 'FunctionExpression' && род && род.type === 'AssignmentExpression' &&
          витТекст.slice(род.left.start, род.left.end) === 'В.нажатияПолосы')) return;
    const тело = витТекст.slice(у.start, у.end);
    витДелегирует = /KSLT_полосаСтраниц\.нажатия/.test(тело) &&
                    !/pl-page-prev/.test(тело);
});
правило('витрина зовёт дом полосы, а не держит своё тело',
    витДелегирует,
    'Дом витрины снова разбирает нажатие сам. Он переходник: три витрины\n' +
    'зовут его прежним доводом, а тело живёт в доме полосы.');

/* ---- 5. все зовы на месте и у каждого свой ключ ---- */
const зовы = [];
[ДОМ, ВИТРИНА].concat(ПОТРЕБИТЕЛИ).forEach(ф => {
    const т = чит(ф);
    обойти(дерево(т), (у) => {
        if (у.type !== 'CallExpression') return;
        const имя = т.slice(у.callee.start, у.callee.end);
        if (!/нажатия$/.test(имя)) return;
        const довод = у.arguments[0];
        const ключи = (довод && довод.type === 'ObjectExpression')
            ? довод.properties.map(п => п.key && (п.key.name || п.key.value)) : [];
        зовы.push({ файл: ф, строка: у.loc.start.line, поля: ключи });
    });
});
const ЖДЁМ_ЗОВОВ = 7;
правило('зовут дом все семь мест',
    зовы.length === ЖДЁМ_ЗОВОВ,
    'Зовов `нажатия`: ' + зовы.length + ', ждём ' + ЖДЁМ_ЗОВОВ + ' — три в\n' +
    'кабинете, один в «Новостях», два у «Игроков» и один переходник\n' +
    'витрины. Найдено:\n' +
    зовы.map(з => '  ' + з.файл + ':' + з.строка).join('\n'));
const безКлюча = зовы.filter(з => з.поля.indexOf('ключ') === -1);
правило('у каждого зова есть ключ',
    безКлюча.length === 0,
    'Без ключа: ' + безКлюча.map(з => з.файл + ':' + з.строка).join(', ') + '.\n' +
    'Ключ отличает полосы на одной области: у «Игроков» их две на\n' +
    '`document`, и без ключа вторая потерялась бы МОЛЧА.');
const ключи = зовы.map(з => з.поля.indexOf('ключ') !== -1);
правило('обязательные доводы на месте у каждого зова',
    зовы.every(з => ['взять', 'поставить', 'перерисовать'].every(п => з.поля.indexOf(п) !== -1)),
    'У зова не хватает `взять`, `поставить` или `перерисовать`:\n' +
    зовы.filter(з => !['взять','поставить','перерисовать'].every(п => з.поля.indexOf(п) !== -1))
        .map(з => '  ' + з.файл + ':' + з.строка + ' — ' + з.поля.join(', ')).join('\n'));

/* ---- 6. счёт с нуля назван доводом, и только там, где он такой ---- */
const сНуля = зовы.filter(з => з.поля.indexOf('сНуля') !== -1);
правило('счёт с нуля назван доводом ровно в одном месте',
    сНуля.length === 1 && /dashboard\.js$/.test(сНуля[0].файл),
    'Довод `сНуля` стоит у ' + сНуля.length + ' зовов: ' +
    сНуля.map(з => з.файл + ':' + з.строка).join(', ') + '.\n' +
    'Страницы «Моих игр» в кабинете считаются С НУЛЯ, все остальные с\n' +
    'единицы. Это свойство ЗОВУЩЕГО и говорится вслух, а не подгоняется\n' +
    'внутри дома.');

/* ---- 7. доводы берутся из хранилки, а не из замыкания ---- */
const кабТекст = чит('js/dashboard.js');
let хранилка = false;
обойти(дерево(кабТекст), (у) => {
    if (!(у.type === 'FunctionDeclaration' && у.id && у.id.name === 'renderPaged')) return;
    const тело = кабТекст.slice(у.start, у.end);
    хранилка = /__ksltСтраницы/.test(тело) &&
               /состояние\.items\s*=/.test(тело) &&
               /renderPaged\(container,\s*состояние\.items/.test(тело);
});
правило('кабинет берёт доводы из хранилки, а не из замыкания',
    хранилка,
    '`renderPaged` зовут ПЯТЬ разных списков кабинета, и у каждого данные\n' +
    'перезагружаются. Слушатель ставится один раз: замкни на нём `items`\n' +
    'первой отрисовки — и после обновления данных полоса перерисует\n' +
    'СТАРЫЙ список молча. Хранилка живёт на коробке и обновляется каждой\n' +
    'отрисовкой.');

/* ---- 8. дом подключён там, где его зовут ---- */
const posix = (s) => s.split(path.sep).join('/');
function страницы() {
    const из = [];
    const обход = (д) => fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(e => {
        const п = д + '/' + e.name;
        if (e.isDirectory()) {
            if (/node_modules|archive|backups|builds|mobile/.test(e.name)) return;
            обход(п);
        } else if (/\.html$/.test(e.name)) из.push(п.replace(/^\.\//, ''));
    });
    обход('.');
    return из;
}
const зовущиеФайлы = ['js/kslt-vitrina.js', 'js/dashboard.js', 'js/news.js', 'js/players.js',
                      'js/coaches.js', 'js/courts.js', 'js/partners.js'];
const безДома = [];
страницы().forEach(с => {
    const т = чит(с);
    const ссылки = [];
    const re = /(?:src|href)="([^"]+\.js)(?:\?v=\d+)?"/g;
    let м;
    while ((м = re.exec(т)) !== null) {
        ссылки.push(posix(path.posix.normalize(path.posix.join(path.posix.dirname(posix(с)), м[1]))));
    }
    const зовёт = ссылки.some(п => зовущиеФайлы.indexOf(п) !== -1);
    if (зовёт && ссылки.indexOf('js/polosa-stranic.js') === -1) безДома.push(с);
});
правило('дом полосы стоит на каждой странице, где его зовут',
    безДома.length === 0,
    'Страницы зовут полосу, но дома на них нет:\n' + безДома.map(с => '  ' + с).join('\n') +
    '\nБез дома нажатие полосы не делает НИЧЕГО и не говорит об этом.');

/* ---- вывод ---- */
console.log('');
if (плохо === 0) {
    console.log('  ок      нажатия полосы страниц: ' + правил + ' правил');
    console.log('          тело одно, зовов ' + зовы.length + ', у каждого свой ключ');
    console.log('          счёт с нуля назван доводом, доводы — из хранилки');
} else {
    console.log('  НЕ ТАК  ' + плохо + ' из ' + правил + ' правил');
    process.exitCode = 1;
}
