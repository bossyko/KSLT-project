#!/usr/bin/env node
/**
 * НЕРЕЙТИНГОВАЯ КАТЕГОРИЯ — СВОЙСТВО ДАННЫХ, А НЕ СЛОВО В КОДЕ
 * (кусок «Open Friendly», 07.11).
 *
 * ЗАЧЕМ. Признак «дружеский турнир: без очков, без проверок пола и
 * разряда» держался на ЗАШИТОМ СЛОВЕ `'friendly'`: замер 07.11 по коду
 * без примечаний дал 33 живых места в `js/`, `mobile/www/js/` и серверной
 * функции заявок, плюс СЕМЬ мест внутри `recalc_player_categories`. Пока
 * такая категория одна, это работало. Вторая — а её завели по слову Кости
 * — стала бы для всего продукта РЕЙТИНГОВОЙ: отказ по полу, проверка
 * разряда и NTRP, очки в таблицы. То есть ровно обратное замыслу.
 *
 * ЧТО ДЕРЖИТ СТОРОЖ:
 *   • признак спрашивается у дома, а дом читает `categories.is_rating`;
 *   • ПАМЯТЬ КАТЕГОРИЙ ОДНА. Я завёл было вторую и поймал себя на шве:
 *     две памяти разошлись бы на первом же экране, наполнившем одну;
 *   • `NON_RATING` остаётся ЗАПАСОМ на первый кадр и ничем больше;
 *   • сервер решает допуск по `is_rating` из базы — он источник истины,
 *     клиент только показывает;
 *   • в базе признак тоже ОДИН — `нерейтинговая_категория()`, и
 *     `recalc_player_categories` зовёт её вместо семи литералов;
 *   • у нерейтинговой категории пол не спрашивается, а ставится `mixed`:
 *     столбец `tournaments.gender` обязателен, и спрятанное пустое поле
 *     не дало бы сохранить турнир вовсе.
 *
 * Запуск: node tools/check-bez-reytinga.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const { безКомментариев } = require('./bez-kommentariev.js');
const безКом = безКомментариев;

const ДОМ    = 'js/kslt-rules.js';
const ДОМ_П  = 'mobile/www/js/kslt-rules.js';
const АДМИНКА = 'js/admin/sections/tournaments.js';
const СЕРВЕР = 'supabase/functions/tournament-register/index.ts';

/* ВСЕ ФАЙЛЫ КУСКА, А НЕ ПОСЛЕДНИЙ ПО ИМЕНИ (починка 07.11). Первая
   редакция брала `.sort().pop()` — то есть ОДИН файл. В тот же день у
   куска появился второй, `open-friendly-stupen-07nov.sql`, и по алфавиту
   он встал последним: прибор начал читать ступень вместо признака и
   уронил три правила на коде, который не менялся.
   КУСОК МОЖЕТ ЛЕЖАТЬ В НЕСКОЛЬКИХ ФАЙЛАХ, И ПРИБОР ОБЯЗАН ЧИТАТЬ ВСЕ:
   иначе сторож стережёт то, что назвали последним. */
function файлБазы(вид) {
    const д = path.join(КОРЕНЬ, 'sql', 'схема');
    if (!fs.existsSync(д)) return '';
    return fs.readdirSync(д).filter(и => вид.test(и)).sort()
        .map(и => fs.readFileSync(path.join(д, и), 'utf8')).join('\n');
}
/* SQL ЧИТАЕТСЯ БЕЗ ПРИМЕЧАНИЙ. Поймано на себе сразу: правило «слова не
   осталось» упало на ЦИТАТЕ в шапке файла, где объясняется, что именно
   заменили. ЦИТАТА — НЕ ВТОРОЕ ОПРЕДЕЛЕНИЕ, третий раз за двое суток. */
function безКомSql(т) {
    return String(т || '').split('\n')
        .map(с => с.replace(/--.*$/, ''))
        .join('\n');
}
const SQL_ТЕКСТ = файлБазы(/^open-friendly-.*\.sql$/);
const SQL = безКомSql(SQL_ТЕКСТ);

const дом = безКом(чит(ДОМ), ДОМ);

console.log('\n  БЕЗ РЕЙТИНГА — ПРИЗНАК ИЗ ДАННЫХ, А НЕ ИЗ СЛОВА\n');

/* ── 1. ПРИБОР ВИДИТ ДОМ ───────────────────────────────────────────── */
правило('дом правил найден и отдаёт признак',
    /R\.нерейтинговая\s*=\s*function/.test(дом) && /R\.рейтинговая\s*=\s*function/.test(дом),
    'Ослепни читалка дома — все сверки ниже бессмысленны. Признак живёт в\n' +
    '`js/kslt-rules.js`: `нерейтинговая` и обратное ей `рейтинговая`.');

/* ── 2. ПРИЗНАК ЧИТАЕТ ДАННЫЕ ──────────────────────────────────────── */
правило('признак читает `is_rating`, а не список имён',
    /is_rating === false/.test(дом) && /knownCategories\(\)/.test(дом),
    'Правило обязано спрашивать строку категории из базы. Спроси оно\n' +
    'список в коде — вторая дружеская категория стала бы рейтинговой, и\n' +
    'человек получил бы отказ по полу на турнире, где пола нет.');

/* ── 3. ПАМЯТЬ КАТЕГОРИЙ ОДНА ──────────────────────────────────────── */
правило('память категорий в доме одна',
    (дом.match(/R\.rememberCategories\s*=/g) || []).length === 1 &&
    !/R\.запомнитьКатегории\s*=/.test(дом) &&
    !/R\._категории/.test(дом),
    'В доме уже была память — `rememberCategories`/`knownCategories`. Я\n' +
    'завёл было вторую, свою: ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ — две\n' +
    'памяти разошлись бы на первом же экране, который наполнил одну.');

/* ── 4. ЗАПАС ОСТАЛСЯ ЗАПАСОМ ──────────────────────────────────────── */
правило('`NON_RATING` читается только внутри дома',
    /R\.NON_RATING\s*=\s*\['friendly'\]/.test(дом) &&
    (function () {
        const чужие = [];
        for (const ф of ['js/admin/sections/bracket.js', 'js/rankings-data.js',
                         'js/tournaments-overview.js', 'js/dashboard.js']) {
            if (/NON_RATING/.test(безКом(чит(ф), ф))) чужие.push(ф);
        }
        return чужие.length === 0;
    })(),
    'Запас нужен на первый кадр: страница рисуется раньше ответа базы.\n' +
    'Но читать его продукт не должен — иначе список снова станет вторым\n' +
    'определением признака. Спрашивать надо `нерейтинговая`.');

/* ── 5. В ПРОДУКТЕ НЕТ ЗАШИТОГО ПРИЗНАКА ───────────────────────────── */
const ЛИТЕРАЛ = /category_id\s*(===|!==|==|!=)\s*'friendly'|'friendly'\s*(===|!==)\s*category/;
const зашитые = [];
(function обойти(д) {
    for (const э of fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true })) {
        const п = д + '/' + э.name;
        if (э.isDirectory()) {
            if (/node_modules|vendor|\.git/.test(э.name)) continue;
            обойти(п); continue;
        }
        if (!/\.(js|ts)$/.test(э.name)) continue;
        /* Дом — единственное место, где слово стоит законно: там запас. */
        if (п === ДОМ || п === ДОМ_П) continue;
        const т = безКом(чит(п), п);
        т.split('\n').forEach((с, i) => {
            if (!ЛИТЕРАЛ.test(с)) return;
            /* Запасная ветка рядом с зовом дома — законна: она работает,
               пока дома нет на странице. Признак такой ветки — зов дома
               в той же или соседней строке. */
            const окно = т.split('\n').slice(Math.max(0, i - 3), i + 1).join(' ');
            if (/KSLT_RULES/.test(окно)) return;
            зашитые.push(п + ':' + (i + 1));
        });
    }
})('js');
['mobile/www/js', 'supabase/functions'].forEach(к => (function обойти(д) {
    for (const э of fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true })) {
        const п = д + '/' + э.name;
        if (э.isDirectory()) {
            if (/node_modules|vendor|\.git/.test(э.name)) continue;
            обойти(п); continue;
        }
        if (!/\.(js|ts)$/.test(э.name)) continue;
        if (п === ДОМ || п === ДОМ_П) continue;
        const т = безКом(чит(п), п);
        т.split('\n').forEach((с, i) => {
            if (!ЛИТЕРАЛ.test(с)) return;
            const окно = т.split('\n').slice(Math.max(0, i - 3), i + 1).join(' ');
            if (/KSLT_RULES|безРейтинга|categories/.test(окно)) return;
            зашитые.push(п + ':' + (i + 1));
        });
    }
})(к));
правило('признак нигде не зашит словом',
    зашитые.length === 0,
    'Зашито: ' + (зашитые.join(', ') || '—') + '.\n' +
    'Сравнение `category_id === \'friendly\'` — это второе определение\n' +
    'признака. Их было 33; каждое новое вернёт беду, ради которой кусок и\n' +
    'делался.');

/* ── 6. СЕРВЕР РЕШАЕТ ПО ДАННЫМ ────────────────────────────────────── */
const сервер = безКом(чит(СЕРВЕР), СЕРВЕР);
правило('сервер читает `is_rating` и решает допуск по нему',
    /categories\(is_rating\)/.test(сервер) &&
    /безРейтинга/.test(сервер) &&
    !/tournament\.category_id !== 'friendly'/.test(сервер),
    'Клиент показывает, а допускает СЕРВЕР: он обязан спрашивать базу.\n' +
    'Оставь здесь слово — и дружеский турнир отказал бы человеку по полу,\n' +
    'хотя пола у него нет.');

/* ── 7. В БАЗЕ ПРИЗНАК ТОЖЕ ОДИН ───────────────────────────────────── */
правило('в базе объявлено одно определение признака',
    /CREATE OR REPLACE FUNCTION public\."нерейтинговая_категория"/.test(SQL) &&
    (SQL.match(/нерейтинговая_категория"\(/g) || []).length >= 8,
    'Файл куска обязан завести `нерейтинговая_категория(text)` и позвать\n' +
    'её во всех семи местах `recalc_player_categories` — там литералы и\n' +
    'жили. Меньше зовов значит, что часть мест осталась со словом.');

/* ── 8. ПЕРЕСЧЁТ БЕЗ ЛИТЕРАЛА ──────────────────────────────────────── */
правило('в новой редакции пересчёта слова `friendly` не осталось',
    /CREATE OR REPLACE FUNCTION public\.recalc_player_categories/.test(SQL) &&
    !/<>\s*'friendly'/.test(SQL),
    'Пересчёт очков, побед, поражений и формы — то место, где слово\n' +
    'решало, начислять ли. Останься оно — новая категория начисляла бы\n' +
    'очки, и узнали бы мы об этом из рейтинга.');

/* ── 9. СТОЛБЕЦ И КАТЕГОРИЯ ЗАВОДЯТСЯ ──────────────────────────────── */
правило('файл заводит столбец признака и саму категорию',
    /ADD COLUMN IF NOT EXISTS is_rating/.test(SQL) &&
    /* СКОБКА В ПРИЗНАКЕ НЕ УКРАШЕНИЕ: без неё `public.categories_чужая`
       проходит как `public.categories`, и откат прувера правило не уронил.
       ПОЧТИ ТОЧНЫЙ ПРИБОР — ЭТО НЕТОЧНЫЙ ПРИБОР. */
    /INSERT INTO public\.categories\s*\(/.test(SQL) &&
    /'open-friendly'/.test(SQL) &&
    /UPDATE public\.categories SET is_rating = false WHERE id = 'friendly'/.test(SQL),
    'Столбца `is_rating` в базе не было вовсе — код читал его и всегда\n' +
    'получал пустоту (замер 07.11 по снимку схемы). Файл обязан завести\n' +
    'столбец, пометить действующую дружескую категорию и добавить новую.');

/* ── 10. ПОЛ У НЕРЕЙТИНГОВОЙ КАТЕГОРИИ ─────────────────────────────── */
const админка = безКом(чит(АДМИНКА), АДМИНКА);
правило('у нерейтинговой категории пол не спрашивается, а ставится',
    /* ДЕРЖИТСЯ СМЫСЛ, А НЕ НАПИСАНИЕ ЗОВА. За один день правило
       переписывалось дважды: сперва требовало `дружескийТурнир()` в обоих
       местах, потом `A.безОчковЗаКатегорию` — и оба раза падало на
       починенном коде, потому что держало БУКВУ. Теперь держится то, что
       не меняется от правки: определение одно, зовут его и видимость
       поля, и сборка данных, и пол при этом становится `mixed`. */
    (админка.match(/function дружескийТурнир/g) || []).length === 1 &&
    (админка.match(/дружескийТурнир\(\)/g) || []).length >= 3 &&
    /fmt === 'mixed_doubles' \|\| дружескийТурнир\(\)/.test(админка) &&
    /\? 'mixed'/.test(админка),
    'Слово Кости: «ПОЛ убрать, там все играют». Но `tournaments.gender`\n' +
    'обязателен (NOT NULL, CHECK men/women/mixed): спрячь поле пустым — и\n' +
    'турнир не сохранится вовсе, а причина будет не видна. Поэтому поле\n' +
    'прячется И получает `mixed`, и решает это ОДНО место на экран и на\n' +
    'сохранение.');

/* ── 11. КАТЕГОРИИ ОТДАЮТСЯ ДОМУ ───────────────────────────────────── */
const отдают = ['js/tournaments-overview.js', 'js/rankings-data.js',
                'js/admin/core/constants.js', 'js/dashboard.js']
    .filter(ф => /rememberCategories\(/.test(безКом(чит(ф), ф)));
правило('загрузчики категорий отдают список дому',
    отдают.length === 4,
    'Отдают: ' + отдают.length + ' из 4. Дом своего запроса не делает — он\n' +
    'знает правила, а ходить в базу работа продукта. Не отдаст страница\n' +
    'список — признак свалится на запас, и новая категория будет выглядеть\n' +
    'рейтинговой.');

/* ── 12. ПОБАЙТОВЫЕ КОПИИ ──────────────────────────────────────────── */
const копии = [[ДОМ, ДОМ_П],
               ['js/kslt-kategorii.js', 'mobile/www/js/kslt-kategorii.js'],
               ['js/kslt-grafik-dannye.js', 'mobile/www/js/kslt-grafik-dannye.js']]
    .filter(([а, б]) => чит(а) !== чит(б));
правило('дома лежат побайтовыми копиями в приложении',
    копии.length === 0,
    'Разошлись: ' + (копии.map(([а]) => а).join(', ') || '—') + '.\n' +
    'Приложение грузит свою копию файлом: правка в одном месте — это\n' +
    'правка, которая дойдёт до половины людей.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else {
    console.log('  ок      без рейтинга: все ' + держится + ' правил держатся');
    console.log('          признак — `categories.is_rating`, один на продукт и базу\n');
}
