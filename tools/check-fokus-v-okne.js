'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ДОМ = 'mobile/www/js/kslt-okno.js';
const РАЗМЕТКА = 'mobile/www/index.html';

function читать(о) {
    const п = path.join(КОРЕНЬ, о);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}

function безКомментариев(т) {
    return т.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/(^|[^:])\/\/[^\n]*/g, '$1 ');
}

const дом = читать(ДОМ);
const код = безКомментариев(дом || '');

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('дом спрашивает видимость, а не верит классу',
    /visibility[\s\S]{0,40}hidden/.test(код),
    'В ' + ДОМ + ' нигде не спрашивается `visibility`. Класс `open`\n' +
    'появляется сразу, а окно остаётся скрытым ещё 0.25 с — и `focus()`\n' +
    'в этот миг не делает НИЧЕГО. Замер 06.11: шесть окон из одиннадцати\n' +
    'оставались без фокуса навсегда.');

правило('у увода фокуса есть вторая попытка',
    /addEventListener\(\s*'transitionend'/.test(код) || /setInterval\(/.test(код),
    'Фокус уводится ОДИН раз, в момент появления класса. Если окно в\n' +
    'этот миг скрыто, второй попытки не будет ни у кого, и фокус\n' +
    'останется снаружи навсегда. Нужен слушатель конца перехода или\n' +
    'повтор по часам.');

правило('у ожидания есть потолок',
    /setTimeout\([\s\S]{0,200}?\d{3,}\s*\)/.test(код),
    'У ожидания видимости нет потолка. Свёрнутое приложение кадров не\n' +
    'рисует, `transitionend` может не прийти вовсе — и тогда фокус не\n' +
    'уведётся никогда. Потолок — это страховка, а не замена вопросу о\n' +
    'видимости.');

/* ПРОВЕРЯЕТСЯ ПАРА В ОДНОМ УСЛОВИИ, А НЕ СЛОВО ГДЕ-НИБУДЬ В ФАЙЛЕ.
   Первая попытка искала `classList.contains('open')` по всему дому и
   проходила на откате: это слово есть и в разборе класса, который к
   уводу фокуса отношения не имеет. ПРАВИЛО, КОТОРОЕ ЛОВИТ СЛОВО ГДЕ
   УГОДНО, НЕ ЛОВИТ НИЧЕГО. */
правило('перед уводом проверяется, что окно ещё открыто',
    /вСтопке\([^)]*\)[^;]{0,80}classList\.contains\(\s*'open'\s*\)/.test(код),
    'Окно могли закрыть, пока дом ждал его видимости. Фокус в закрытое\n' +
    'окно — это фокус в никуда: следующий Tab уходит читать страницу под\n' +
    'ним, то есть ровно та беда, от которой дом и поставлен.');

правило('стопка ищется по окну, а не по записи о нём',
    !/стопка\.indexOf\(/.test(код),
    'В доме стоит `стопка.indexOf(узел)`, а стопка хранит записи вида\n' +
    '`{окно, открывший}`. Такой поиск НЕ НАХОДИТ НИЧЕГО НИКОГДА, и одно\n' +
    'окно ложится в стопку дважды — замер 06.11 показал два окна в\n' +
    'стопке при одном видимом. ЗАЩИТА, КОТОРАЯ НЕ СРАБАТЫВАЕТ НИ РАЗУ,\n' +
    'выглядит в коде точно так же, как рабочая.');

правило('дом подключён в разметке',
    (читать(РАЗМЕТКА) || '').indexOf('js/kslt-okno.js') > -1,
    'В ' + РАЗМЕТКА + ' нет подключения дома окон — тогда ни одно окно\n' +
    'не получит ни роли, ни подписи, ни фокуса, и все сторожа вокруг\n' +
    'будут зелёными.');

правило('прибор не принимает комментарий за код',
    (function () {
        /* ОБРАЗЕЦ ВНУТРЬ ПРИБОРА: в этом самом файле слова `visibility`,
           `transitionend` и `стопка.indexOf` стоят в объяснениях. Прибор,
           читающий собственное объяснение как улику, зелёный на пустом
           файле и красный на верном коде. */
        const о = '/* тут про visibility: hidden и про стопка.indexOf(узел) */\n' +
                  '// и про transitionend\n' +
                  'var a = 1;\n';
        const б = безКомментариев(о);
        return !/visibility/.test(б) && !/стопка\.indexOf\(/.test(б) &&
               !/transitionend/.test(б);
    })(),
    'Образец внутри прибора: все сторожимые слова, но в комментариях.\n' +
    'После снятия комментариев от них не должно остаться ничего.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      фокус в окне: все ' + всего + ' правил держатся');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  фокус в окне — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
