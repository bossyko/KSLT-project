const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const LAYOUT = чит('js/admin/core/layout.js');
const CONST = чит('js/admin/core/constants.js');
const CSS = чит('css/admin.css');
const СТЕНД = чит('maket/polosa-filtrov-zamer.html');

/* ── 1. ССЫЛКА НАЗЫВАЕТ СВОЮ ТАБЛИЦУ ───────────────────────────────── */

правило('ссылка «Все →» собирает имя из своего заголовка',
    /aria-labelledby="' \+ id \+ 'Link ' \+ id \+ 'Title"/.test(LAYOUT),
    'У ссылки нет `aria-labelledby`, собранного из её id и id заголовка.\n' +
    'Три ссылки из шести ведут в один раздел и звучат одинаково: диктор,\n' +
    'читающий список ссылок, не знает, какая из трёх таблиц перед ним.');

правило('заголовок таблицы несёт имя, на которое ссылается ссылка',
    /<span id="' \+ id \+ 'Title">' \+ title \+ '<\/span>/.test(LAYOUT),
    'Заголовок таблицы потерял свой `id`. `aria-labelledby` сошлётся в\n' +
    'пустоту, и имя ссылки молча станет прежним — СЛЕПОЙ ПРИБОР\n' +
    'ДОКЛАДЫВАЕТ УСПЕХ, а диктор читает три одинаковых ссылки.');

правило('счётчик не попадает в имя ссылки',
    LAYOUT.indexOf("'Title\">' + title + '</span>' +") !== -1 &&
    LAYOUT.indexOf("ad-dash-count-badge") > LAYOUT.indexOf("'Title\">"),
    'Счётчик строк должен стоять ВНЕ `<span id="…Title">`: число в имени\n' +
    'ссылки — шум, и оно меняется при каждом обновлении данных.');

const таблиц = (LAYOUT.match(/buildActivityTableHtml\(/g) || []).length - 1; /* минус объявление */
правило('таблиц активности на дашборде шесть — замерено',
    таблиц === 6,
    'Таблиц активности: ' + таблиц + ', замерено 6.\n' +
    'Число вверх — появилась новая таблица, и её ссылке тоже нужно имя;\n' +
    'ПРОВЕРКА, КОТОРАЯ ИЩЕТ В ПУСТОМ, ЗЕЛЕНЕЕТ ВСЕГДА.');

/* ── 2. ОДИН СМЫСЛ — ОДИН КЛЮЧ ─────────────────────────────────────── */

/* КЛЮЧ ИЩЕТСЯ В ДЕРЕВЕ, А НЕ В ТЕКСТЕ. Первая запись этого правила
   искала имя подстрокой — и упала на СВОЁМ ЖЕ комментарии, где это имя
   названо. Шестой раз за ветку одна и та же ловушка: ЗАМОРОЗКА ЧИТАЕТ
   ФАЙЛ КАК ТЕКСТ И НЕ РАЗЛИЧАЕТ КОД И КОММЕНТАРИЙ. Дерево различает. */
const acorn = require('acorn');
function ключиСловаря(текст) {
    const из = new Set();
    let д;
    try { д = acorn.parse(текст, { ecmaVersion: 2020 }); } catch (e) { return null; }
    (function обойти(у) {
        if (!у || typeof у.type !== 'string') return;
        if (у.type === 'Property' && у.key) из.add(у.key.name || у.key.value);
        for (const к of Object.keys(у)) {
            if (к === 'type' || к === 'start' || к === 'end' || к === 'loc') continue;
            const v = у[к];
            if (Array.isArray(v)) v.forEach(x => x && typeof x.type === 'string' && обойти(x));
            else if (v && typeof v.type === 'string') обойти(v);
        }
    })(д);
    return из;
}
const КЛЮЧИ = ключиСловаря(CONST);
правило('словарь админки разбирается парсером',
    КЛЮЧИ !== null,
    'Словарь админки не разобрался. Правило ниже читает ДЕРЕВО, и без\n' +
    'разбора оно слепо: СЛЕПОЙ ПРИБОР ДОКЛАДЫВАЕТ УСПЕХ.');

правило('ключ «игроки не найдены» в админке один',
    КЛЮЧИ !== null && !КЛЮЧИ.has('brkPlayersNeNotFound' + '2'),
    'Вернулся второй ключ `brkPlayersNeNotFound2` на тот же случай.\n' +
    'Два ключа — это два текста, которые завтра разойдутся, и человек\n' +
    'увидит разные слова на одном и том же пустом поиске.');

const зовов = (чит('js/admin/sections/bracket.js').match(/L\.brkPlayersNeNotFound\b/g) || []).length +
              (чит('js/admin/sections/players.js').match(/L\.brkPlayersNeNotFound\b/g) || []).length;
правило('все три места зовут этот ключ, а не свой текст',
    зовов === 3,
    'Зовов `L.brkPlayersNeNotFound`: ' + зовов + ', замерено 3 (две сетки и\n' +
    'уведомление в списке игроков). Меньше — кто-то снова зашил текст\n' +
    'строкой: третья копия и жила зашитой.');

правило('зашитого «Игроки не найдены» в админке не осталось',
    !/showToast\('Игроки не найдены'/.test(чит('js/admin/sections/players.js')),
    'Текст снова зашит в вызов. Зашитая строка не переводится, не ищется\n' +
    'и расходится с ключом молча.');

/* ── 3. ЛИПКОСТЬ ДОКАЗАНА, А НЕ ОБЪЯВЛЕНА ──────────────────────────── */

const полос = (fs.readdirSync(path.join(КОРЕНЬ, 'js/admin/sections'))
  .filter(и => и.endsWith('.js'))
  .reduce((н, и) => н + (чит('js/admin/sections/' + и).match(/ad-filter-row[^"']*ad-filter-sticky/g) || []).length, 0));
const безЛипкости = (fs.readdirSync(path.join(КОРЕНЬ, 'js/admin/sections'))
  .filter(и => и.endsWith('.js'))
  .reduce((н, и) => {
    const т = чит('js/admin/sections/' + и);
    return н + (т.match(/class="ad-filter-row(?![^"]*ad-filter-sticky)[^"]*"/g) || []).length;
  }, 0));

правило('все полосы фильтров админки липкие — 12, и ни одной без',
    полос >= 12 && безЛипкости === 0,
    'Липких полос: ' + полос + ' (пол 12); полос без липкости: ' + безЛипкости + '\n' +
    'Понятие одно — полоса фильтров раздела. Полоса без общего имени\n' +
    'раньше молча стояла статичной: у «Финансов» и «Скидок» имя было\n' +
    'мёртвое (`sticky`, правила под него нет).');

правило('полоса липнет к высоте шапки, а не к своему числу',
    /\.ad-filter-sticky \{[\s\S]{0,200}top: var\(--header-h\)/.test(CSS),
    'У `.ad-filter-sticky` пропал `top: var(--header-h)` — полоса уедет\n' +
    'под шапку сайта или встанет не там. Высота шапки живёт ОДНИМ\n' +
    'определением, и полоса обязана брать его, а не своё число.');

правило('секция не делается прокручиваемым предком',
    /\.ad-section\.active \{[\s\S]{0,160}overflow: visible/.test(CSS),
    'У `.ad-section.active` пропал `overflow: visible`.\n' +
    'ЛИПКОЕ ЛИПНЕТ К ПРОКРУЧИВАЕМОМУ ПРЕДКУ, А НЕ К ОКНУ: стоит предку\n' +
    'получить `overflow` (даже `-x: hidden` — вторую ось браузер делает\n' +
    '`auto`), и полоса перестанет липнуть МОЛЧА. Тот же капкан уже ловили\n' +
    'на липкой шапке турнира: при прокрутке на 800 она уезжала на -423.');

правило('стенд доказывает липкость продуктовой цепочкой, а не удобной',
    /ad-section active/.test(СТЕНД) && /ad-filter-row ad-filter-sticky" id="липкая"/.test(СТЕНД) &&
    /i <= 60/.test(СТЕНД),
    'На стенде нет продуктовой цепочки предков или длинного списка.\n' +
    'СТЕНД, КОТОРОМУ УДОБНЕЕ, ЧЕМ ПРОДУКТУ, МЕРИТ СТЕНД: без\n' +
    '`.ad-section.active` вокруг и без списка длиннее окна замер липкости\n' +
    'ничего не доказывает — а именно этого и не хватало «Транзакциям».');

