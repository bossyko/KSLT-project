/**
 * ЗАМОРОЗКА «ТЕЛЕФОН ВЕРТИКАЛЬНО: КАРТОЧКА ТУРНИРА И СЕТКА» (10.11.2026).
 *
 * Костя увидел глазами две беды на 390, и обе родились НА ШВЕ — там, где
 * одно понятие определено в коде дважды.
 *
 * 1. НАЗВАНИЕ ПОВЕРХ АФИШИ. Место под афишу держал `padding-left` у
 *    .to-compact-thumb, а ниже по файлу, в медиа 640, стояло
 *    `.to-compact { padding: ... }` — та же специфичность, но позже.
 *    СОКРАЩЁННАЯ ЗАПИСЬ ЗАТИРАЕТ ОТДЕЛЬНОЕ СВОЙСТВО, ДАЖЕ ЕСЛИ ТО НАПИСАНО
 *    ТОЧНЕЕ. Замер: афиша занимала слева 120, текст начинался с 41-го —
 *    наезд 95. После правки текст с 161-го, зазор 25.
 *
 * 2. ФАМИЛИИ В СЕТКЕ ОБРЕЗАНЫ. Ширина колонки объявлена в одном файле ПЯТЬ
 *    раз: 210, clamp(160..180), 1 1 0, 0 0 200 и 0 0 150. Побеждало
 *    последнее: колонка 150, имени 62 пикселя, из 160 фамилий обрезано 28.
 *    Замер всех вариантов одним прогоном: 176 -> 6, 192 -> 0, 200 -> 0.
 *    192 — первая ступень без обрезки.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ, А НЕ ЧИСЛО: отступ карточки живёт в переменной, и
 * точки останова меняют переменную, а не свойство; колонка сетки на
 * телефоне не уже той ступени, на которой фамилии перестали обрезаться.
 *
 *   node tools/check-telefon-karta-i-setka.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const ОБЗОР = 'css/tournaments-overview.css';
const ТУРНИР = 'css/tournament-detail.css';
const обзор = чит(ОБЗОР);
const турнир = чит(ТУРНИР);

/* ── КАРТОЧКА ТУРНИРА ───────────────────────────────────────────────── */

правило('отступ карточки объявлен через переменные',
    /padding:\s*var\(--to-pad-y\)\s+var\(--to-pad-x\)\s+var\(--to-pad-y\)\s+var\(--to-pad-left\)/.test(обзор),
    ОБЗОР + ': у .to-compact пропало объявление отступов через переменные.\n' +
    'Без него любое правило с сокращённым `padding` ниже по файлу снова\n' +
    'затрёт место под афишу, и название ляжет поверх картинки.');

правило('место под афишу задаётся переменной, а не padding-left',
    obзорБезPaddingLeft(),
    ОБЗОР + ': место под афишу снова держится `padding-left`.\n' +
    'Сокращённый `padding` ниже по файлу затирает его молча.\n' +
    'Нужно: --to-pad-left: calc(var(--to-thumb) + зазор).');
function obзорБезPaddingLeft() {
    return !/padding-left:\s*calc\(var\(--to-thumb/.test(обзор);
}

правило('точки останова меняют переменные, а не свойство',
    !/\.to-compact\s*\{\s*(\/\*[^]*?\*\/\s*)?padding:\s*var\(--space-sm\)/.test(обзор),
    ОБЗОР + ': в медиа снова стоит сокращённый `padding` у .to-compact.\n' +
    'Это второе определение одного понятия — беда родится ровно на нём.\n' +
    'Нужно менять --to-pad-y и --to-pad-x.');

/* ── СЕТКА НА ТЕЛЕФОНЕ ──────────────────────────────────────────────── */

const СТУПЕНЬ = 192;
const колонка = турнир.match(/\.td-bracket-round\s*\{[^}]*flex:\s*0 0 (\d+)px/);
правило('колонка сетки на телефоне не уже замеренной ступени',
    !!колонка && +колонка[1] >= СТУПЕНЬ,
    ТУРНИР + ': колонка сетки на телефоне ' +
    (колонка ? колонка[1] : 'не найдена') + ' при ступени ' + СТУПЕНЬ + '.\n' +
    'Замер 10.11 на 390: 150 -> обрезано 28 фамилий, 176 -> 6, 192 -> 0.\n' +
    'Ужимать ради лишней половины круга значит вернуть «Толгонай…».');

/* ЛЕСТНИЦА, А НЕ ОДНО ЧИСЛО. Колонка честно сужается с шириной экрана:
   210 на широком, 200 на планшете, 192 на телефоне. Это не копии одного
   понятия, а ступени одного — и мерить надо САМУЮ УЗКУЮ. Пятикратное
   определение 10.11 было бедой не числом, а тем, что ступени спорили:
   среди них стояли clamp(160..180) и flex: 1 1 0, не связанные ни с чем. */
const ступени = (турнир.match(/\.td-bracket-round\s*\{[^}]*?(?:flex:\s*0 0 (\d+)px|min-width:\s*(\d+)px)/g) || [])
    .map(к => { const м = к.match(/(\d+)px/); return м ? +м[1] : null; })
    .filter(ч => ч !== null && ч > 0);
правило('ни одна ступень колонки сетки не уже замеренной',
    ступени.length > 0 && Math.min(...ступени) >= СТУПЕНЬ,
    ТУРНИР + ': самая узкая ступень колонки сетки ' +
    (ступени.length ? Math.min(...ступени) : 'не найдена') +
    ' при замеренной ' + СТУПЕНЬ + '.\n' +
    'Ступени найдены: ' + ступени.join(', ') + '.\n' +
    'ОДНО ПОНЯТИЕ — ОДНА ЛЕСТНИЦА: 10.11 ширина была объявлена пять раз,\n' +
    'и среди ступеней стояли clamp(160..180) и flex: 1 1 0, не связанные\n' +
    'ни с чем. Побеждало последнее — 150, и фамилии резались.');

правило('в лестнице нет ступеней мимо шкалы',
    !/\.td-bracket-round\s*\{[^}]*min-width:\s*clamp/.test(турнир),
    ТУРНИР + ': колонка сетки снова задана через clamp.\n' +
    'Ступень берётся из шкалы и мерится, а clamp прячет число.');

const клетка = турнир.match(/\.td-match\s*\{\s*box-sizing: border-box;\s*width:\s*(\d+)px/);
правило('клетка сетки не уже колонки минус зазор',
    !!клетка && +клетка[1] >= СТУПЕНЬ - 8,
    ТУРНИР + ': клетка сетки ' + (клетка ? клетка[1] : 'не найдена') +
    ' при колонке ' + СТУПЕНЬ + '.\n' +
    'Клетка уже колонки на один зазор — иначе имени опять не хватит места.');

правило('имя в сетке не обрезается многоточием',
    !/-webkit-line-clamp:\s*2;[^}]*text-overflow:\s*ellipsis/.test(турнир),
    ТУРНИР + ': имя в сетке снова обрезается многоточием.\n' +
    'Правило куска 216 (mobile/www/css/app.css): «обрезать фамилию\n' +
    'многоточием нельзя» — на телефоне пара это два человека.');

/* ── ВЫВОД ──────────────────────────────────────────────────────────── */
const ВСЕГО = 8;
if (ошибки.length) {
    console.log('\n  x ТЕЛЕФОН: КАРТОЧКА И СЕТКА — ' + ошибки.length + ' из ' + ВСЕГО + '\n');
    ошибки.forEach(о => { console.log('  x ' + о.имя); console.log('    ' + о.подсказка.split('\n').join('\n    ') + '\n'); });
    process.exit(1);
}
console.log('  v телефон: карточка и сетка — ' + ВСЕГО + ' правил');
