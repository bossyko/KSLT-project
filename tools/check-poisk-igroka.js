/**
 * ЗАМОРОЗКА СТРАНИЦЫ «ПОИСК ИГРОКА» — `pages/partners.html`.
 *
 * ЧТО ЗАМОРАЖИВАЕТСЯ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • обложка стоит на ОБЩИХ крутилках раздела, своих чисел у неё нет;
 *   • полоса «назад · поиск · фильтры» — общие классы, а не своя копия;
 *   • тип корта — такая же выпадашка, как город и покрытие;
 *   • число колонок — следствие ширины карточки, а не границы экрана;
 *   • шаг страницы — колонок × рядов, а не число;
 *   • полоса страниц — общий компонент и ширина своей витрины;
 *   • карточка берёт размеры и лестницу у витрины лендинга;
 *   • внутри карточки одно действие, и оно не повторяет саму карточку.
 *
 *   node tools/check-poisk-igroka.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const CSS = безКом(чит('css/partners.css'));
const СТИ = безКом(чит('css/style.css'));
const JS  = безКом(чит('js/partners.js'));
const ПОЛОСА = безКом(чит('js/polosa-stranic.js'));
const RU = чит('pages/partners.html');
