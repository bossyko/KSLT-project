#!/usr/bin/env node
/**
 * РЕЗЕРВНАЯ КОПИЯ ЛОЖИТСЯ ЗАПЕРТОЙ (кусок 04.11).
 *
 * ЗАМЕР 04.11: `backup.js` складывал рядом с проектом открытую папку —
 * 65 таблиц, 12034 строки, 227 файлов: имена, телефоны, почта, фотографии
 * и оплаты 399 человек. Сам же скрипт советовал «скопировать в облако или
 * на внешний диск», то есть ровно туда, где её увидит не только владелец.
 * Политика конфиденциальности КСЛТ (п. 11.1) при этом ОБЕЩАЛА шифрование
 * резервных копий — обещание было неправдой.
 *
 * ЗАМОРОЖЕНО ОТНОШЕНИЕ: «копия ложится запертой, и её есть чем открыть» —
 * а не «в строке такой-то стоит AES».
 *
 * ПОЧЕМУ ОТКРЫВАЛКА СТОРОЖИТСЯ НАРАВНЕ С ЗАМКОМ: запертая копия, которую
 * нечем открыть, — это не копия, а её отсутствие с лишними хлопотами.
 * Беда вскроется в худший день, когда открывать будут не от любопытства.
 *
 * ПРИБОР НЕ ТОЛЬКО ЧИТАЕТ ТЕКСТ, НО И МЕРЯЕТ ПОВЕДЕНИЕ: он гоняет
 * самопроверку дома шифрования — запер, не открыл чужим паролем, вернул
 * данные целыми. Правило, читающее только слова, подтвердило бы и
 * «шифрование», которое ничего не шифрует.
 *
 *   node tools/check-bekap-zaperto.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const П = (...ч) => path.join(КОРЕНЬ, ...ч);
const чит = ф => fs.readFileSync(П(ф), 'utf8');
const есть = ф => fs.existsSync(П(ф));

const ВЫГРУЗКА = 'tools/backup.js';
const ДОМ = 'tools/backup-shifr.js';
const ОТКРЫВАЛКА = 'tools/backup-otkryt.js';

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

правило('дом шифрования на месте', есть(ДОМ), ДОМ + ' не найден');
правило('открывалка на месте', есть(ОТКРЫВАЛКА), ОТКРЫВАЛКА + ' не найден');

const дом = есть(ДОМ) ? безКомментариев(чит(ДОМ)) : '';
const выг = есть(ВЫГРУЗКА) ? безКомментариев(чит(ВЫГРУЗКА)) : '';
const откр = есть(ОТКРЫВАЛКА) ? безКомментариев(чит(ОТКРЫВАЛКА)) : '';

/* ── 1. выгрузка запирает ────────────────────────────────────────────── */
правило('выгрузка зовёт шифрование',
    /require\(['"]\.\/backup-shifr\.js['"]\)/.test(выг) && /зашифровать\s*\(/.test(выг),
    'backup.js не зовёт дом шифрования');

правило('открывалка зовёт тот же дом',
    /require\(['"]\.\/backup-shifr\.js['"]\)/.test(откр) && /расшифровать\s*\(/.test(откр),
    'backup-otkryt.js не зовёт backup-shifr.js — значит дом не один');

/* ── 2. без пароля выгрузка не идёт, и спрашивает ДО работы ─────────── */
/* МЕРЯЕТСЯ СВЯЗКА, А НЕ УПОМИНАНИЕ. Прувер показал дыру: откат подменил
   источник пароля на свой, а слова `BACKUP_PASSWORD` остались в тексте
   сообщения — и правило смолчало. ПРАВИЛО, ИЩУЩЕЕ СЛОВО, ПОДТВЕРЖДАЕТ
   НАЛИЧИЕ СЛОВА, А НЕ ПОВЕДЕНИЯ: смотреть надо, откуда берётся значение. */
правило('без пароля выгрузка останавливается',
    /const\s+пароль\s*=\s*process\.env\.BACKUP_PASSWORD\s*;/.test(выг) &&
    /if\s*\(!пароль\)[\s\S]{0,1200}process\.exit\(1\)/.test(выг),
    'backup.js не берёт пароль из BACKUP_PASSWORD или не выходит без него');

/* СРАВНИВАЕТСЯ С ЗОВОМ, А НЕ С ОБЪЯВЛЕНИЕМ. Первая редакция правила
   искала просто `listTables` — и находила объявление функции в начале
   файла, задолго до `main`. Правило падало на верном коде.
   МЕСТО ОБЪЯВЛЕНИЯ НИЧЕГО НЕ ГОВОРИТ О ПОРЯДКЕ РАБОТЫ: порядок задаёт
   зов, и мерить надо его. */
const гдеПароль = выг.indexOf('BACKUP_PASSWORD');
const гдеЗовТаблиц = выг.indexOf('await listTables(');
правило('пароль спрашивается до выгрузки, а не после',
    гдеПароль !== -1 && гдеЗовТаблиц !== -1 && гдеПароль < гдеЗовТаблиц,
    'проверка пароля стоит после запроса таблиц — полчаса работы уйдут впустую');

/* ── 3. открытая папка не остаётся рядом с запертой ──────────────────── */
правило('открытая папка убирается после запирания',
    /rmSync\(dir,\s*\{\s*recursive:\s*true/.test(выг),
    'backup.js не удаляет открытую папку — шифрование тогда ни от чего не защищает');

правило('удаление идёт ПОСЛЕ проверки запертого файла',
    выг.indexOf('зашифровать(') !== -1 &&
    выг.indexOf('зашифровать(') < выг.indexOf('rmSync(dir'),
    'папка удаляется раньше, чем запертый файл проверен');

/* ── 4. замок настоящий ──────────────────────────────────────────────── */
/* ТРЕБУЕТСЯ НА ОБОИХ КОНЦАХ. Прувер показал: откат менял шифр только в
   запирании, а правило находило `aes-256-gcm` в отпирании и молчало.
   ОДНОГО УПОМИНАНИЯ ДОСТАТОЧНО ДЛЯ СЛОВА, НО НЕ ДЛЯ ЗАМКА: мерить надо
   каждый конец отдельно. */
правило('шифр — AES-256-GCM',
    /createCipheriv\(\s*'aes-256-gcm'/.test(дом) &&
    /createDecipheriv\(\s*'aes-256-gcm'/.test(дом),
    'aes-256-gcm стоит не на обоих концах — запирание и отпирание разошлись');

правило('ключ выводится из пароля, а не берётся им',
    /scrypt(Sync)?\s*\(/.test(дом),
    'пароль идёт в ключ напрямую — подбор по словарю ничего не стоит');

правило('соль и iv берутся случайными',
    (дом.match(/randomBytes\s*\(/g) || []).length >= 2,
    'соль или iv зашиты в коде — одинаковые у всех копий');

правило('подмена ловится печатью',
    /getAuthTag\s*\(/.test(дом) && /setAuthTag\s*\(/.test(дом),
    'печать GCM не ставится или не проверяется — испорченный файл откроется молча');

/* ── 5. пароль не печатается ─────────────────────────────────────────── */
const печатаетПароль = [дом, выг, откр].some(т =>
    /console\.(log|error|warn)\([^)]*\bпароль\b[^)]*\)/.test(т) ||
    /console\.(log|error|warn)\([^)]*BACKUP_PASSWORD\s*\)/.test(т));
правило('пароль нигде не печатается',
    !печатаетПароль,
    'пароль попадает на экран или в отчёт');

/* ── 6. ПОВЕДЕНИЕ, А НЕ СЛОВА ────────────────────────────────────────── */
let поведение = null;
try {
    const { проверитьСебя } = require(П(ДОМ));
    поведение = проверитьСебя();
} catch (e) {
    поведение = Promise.reject(e);
}

поведение.then(() => {
    правило('замок держит на самом деле', true, '');
    вывод();
}).catch(e => {
    правило('замок держит на самом деле', false,
        'самопроверка дома не прошла: ' + e.message);
    вывод();
});

function вывод() {
    const ВСЕГО = 13;
    console.log('\n  БЭКАП ЛОЖИТСЯ ЗАПЕРТЫМ\n');
    if (ошибки.length === 0) {
        console.log('  ок      все ' + ВСЕГО + ' правил держат\n');
        process.exit(0);
    }
    ошибки.forEach(о => {
        console.log('  НЕ ТАК  ' + о.имя);
        console.log('          ' + о.подсказка);
    });
    console.log('\n  НЕ ТАК  ' + ошибки.length + ' из ' + ВСЕГО + '\n');
    process.exit(1);
}
