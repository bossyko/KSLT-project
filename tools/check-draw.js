#!/usr/bin/env node
/**
 * Проверка жеребьёвки и сеток за места.
 *
 * Три набора, как договаривались: 32 участника без проходов, 22 участника
 * в сетке на 32, и 64 участника. Проверяется счётом, а не глазами — сетку
 * на 64 глазами и не пересчитать.
 *
 * Запуск: node tools/check-draw.js
 */

const path = require('path');
const ROOT = path.join(__dirname, '..');

global.window = {};
require(path.join(ROOT, 'js', 'bracket-draw.js'));
require(path.join(ROOT, 'js', 'kslt-rules.js'));
const D = global.window.KSLT_DRAW;
const R = global.window.KSLT_RULES;

let провалов = 0;
function проверь(условие, что) {
    if (условие) {
        console.log('  ✓ ' + что);
    } else {
        console.error('  ✗ ' + что);
        провалов++;
    }
}

function людей(сколько) {
    const л = [];
    for (let i = 1; i <= сколько; i++) л.push('p' + i);
    return л;
}

/** В какой части сетки лежит линия: половина, четверть, восьмая. */
function часть(линия, размер, начастей) {
    return Math.ceil(линия / (размер / начастей));
}

function проверитьРаскладку(размер, участников) {
    console.log(`\n— сетка ${размер}, участников ${участников} —`);
    const люди = людей(участников);
    const зерно = 12345;
    const линии = D.разложить(размер, люди, зерно);

    const где = {};
    линии.forEach((у, i) => { if (у) где[у] = i + 1; });

    проверь(где['p1'] === 1, 'сеяный 1 на первой линии');
    проверь(где['p2'] === размер, 'сеяный 2 на последней линии');

    if (участников >= 4) {
        проверь(часть(где['p3'], размер, 2) !== часть(где['p4'], размер, 2),
                'сеяные 3 и 4 в разных половинах');
    }
    if (участников >= 8) {
        const чет = [5, 6, 7, 8].map(н => часть(где['p' + н], размер, 4));
        проверь(new Set(чет).size === 4, 'сеяные 5-8 по одному в каждой четверти');
    }
    if (участников >= 16 && размер >= 32) {
        const вос = [];
        for (let н = 9; н <= 16; н++) вос.push(часть(где['p' + н], размер, 8));
        проверь(new Set(вос).size === 8, 'сеяные 9-16 по одному в каждой восьмой части');
    }

    // Все участники расставлены, и никто дважды
    const расставлено = линии.filter(Boolean);
    проверь(расставлено.length === участников, 'все участники на сетке');
    проверь(new Set(расставлено).size === участников, 'никто не стоит дважды');

    // Проходы без игры — верхним сеяным подряд
    const проходов = размер - участников;
    if (проходов > 0) {
        const безСоперника = [];
        for (let м = 0; м < размер; м += 2) {
            const a = линии[м], b = линии[м + 1];
            if (a && !b) безСоперника.push(a);
            if (!a && b) безСоперника.push(b);
        }
        const ожидаем = [];
        for (let н = 1; н <= проходов; н++) ожидаем.push('p' + н);
        проверь(безСоперника.length === проходов,
                `проходов ${проходов}, столько и есть`);
        проверь(ожидаем.every(у => безСоперника.includes(у)),
                `проходы у сеяных с 1 по ${проходов} и ни у кого больше`);
    }

    // Повторная жеребьёвка тем же зерном даёт ту же сетку
    const снова = D.разложить(размер, люди, зерно);
    проверь(JSON.stringify(снова) === JSON.stringify(линии),
            'та же сетка при повторной раскладке');
    const другое = D.разложить(размер, люди, зерно + 1);
    проверь(JSON.stringify(другое) !== JSON.stringify(линии),
            'другое зерно даёт другую сетку');
}

function проверитьМеста(размер) {
    console.log(`\n— сетка «все места» на ${размер} —`);
    const кругов = Math.round(Math.log2(размер));
    const матчей = кругов * (размер / 2);
    проверь(матчей === (размер === 32 ? 80 : размер === 64 ? 192 : матчей),
            `матчей в турнире: ${матчей}`);

    const ветки = R.ficSections(размер, 'ru');

    // Каждая клетка размечена ровно раз
    const занято = {};
    let дважды = 0;
    ветки.forEach(в => {
        в.rounds.forEach(r => {
            for (let m = r.matchStart; m <= r.matchEnd; m++) {
                const k = r.roundNum + ':' + m;
                if (занято[k]) дважды++;
                занято[k] = в.label;
            }
        });
        if (в.placeMatch) {
            const k = в.placeMatch.roundNum + ':' + в.placeMatch.matchOrder;
            if (занято[k]) дважды++;
            занято[k] = в.label;
        }
    });
    проверь(Object.keys(занято).length === матчей,
            `размечены все ${матчей} клеток`);
    проверь(дважды === 0, 'ни одна клетка не размечена дважды');

    // Победитель остаётся в своей ветке — считаем тем же правилом, что и база
    let вЧужую = 0;
    for (let r = 1; r < кругов; r++) {
        for (let m = 1; m <= размер / 2; m++) {
            const тут = занято[r + ':' + m];
            const пв = занято[(r + 1) + ':' + D.адрес(размер, r, m, true)];
            if (тут && пв && тут !== пв) вЧужую++;
        }
    }
    проверь(вЧужую === 0, 'победитель никогда не уходит из своей ветки');

    // Места идут подряд, без пропусков и повторов
    const места = [];
    ветки.forEach(в => {
        места.push(в.первоеМесто, в.первоеМесто + 1, в.первоеМесто + 2, в.первоеМесто + 3);
    });
    места.sort((a, b) => a - b);
    let подряд = true;
    for (let i = 0; i < места.length; i++) if (места[i] !== i + 1) подряд = false;
    проверь(подряд && места.length === размер,
            `места с 1 по ${размер} идут подряд, без пропусков и повторов`);
}

console.log('Жеребьёвка');
проверитьРаскладку(32, 32);
проверитьРаскладку(32, 22);
проверитьРаскладку(64, 64);

console.log('\nСетки за места');
проверитьМеста(32);
проверитьМеста(64);

// ---- Маршрут: куда попадает проигравший ----
console.log('\nКуда идёт проигравший');
[8, 16, 32, 64].forEach(размер => {
    const ветки = R.ficSections(размер, 'ru');
    const чей = {};
    ветки.forEach(в => {
        в.rounds.forEach(r => {
            for (let m = r.matchStart; m <= r.matchEnd; m++) чей[r.roundNum + ':' + m] = в.label;
        });
        if (в.placeMatch) чей[в.placeMatch.roundNum + ':' + в.placeMatch.matchOrder] = 'место:' + в.label;
    });
    const кругов = Math.round(Math.log2(размер));
    console.log(`\n— сетка ${размер} —`);

    // Проигравший каждого круга — в свой блок, по номеру круга
    for (let r = 1; r < кругов; r++) {
        const куда = чей[(r + 1) + ':' + D.адрес(размер, r, 1, false)] || '—';
        const ожидаем = r === кругов - 1
            ? 'место:'
            : String(размер / Math.pow(2, r) + 1);
        const верно = r === кругов - 1
            ? куда.indexOf('место:') === 0
            : куда.indexOf(ожидаем + '-') === 0;
        проверь(верно, `проигравший круга ${r} → ${куда}`);
    }

    // Победитель не покидает свою ветку
    let вЧужую = 0;
    for (let r = 1; r < кругов; r++) {
        for (let m = 1; m <= размер / 2; m++) {
            const тут = чей[r + ':' + m];
            const пв = чей[(r + 1) + ':' + D.адрес(размер, r, m, true)];
            if (тут && пв && тут !== пв) вЧужую++;
        }
    }
    проверь(вЧужую === 0, 'победитель никогда не уходит из своей ветки');

    // Каждая клетка следующего круга принимает ровно двоих
    const занято = {};
    for (let r = 1; r < кругов; r++) {
        for (let m = 1; m <= размер / 2; m++) {
            [true, false].forEach(поб => {
                const k = (r + 1) + ':' + D.адрес(размер, r, m, поб);
                занято[k] = (занято[k] || 0) + 1;
            });
        }
    }
    проверь(Object.keys(занято).every(k => занято[k] === 2),
            'каждая клетка следующего круга принимает ровно двоих');
});
