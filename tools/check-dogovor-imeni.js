/**
 * ОДИН ДОГОВОР НА ИМЯ УЧАСТНИКА. Кусок 176, 26.10.
 *
 * ЧТО БЫЛО. Кусок 158 (25.10) поставил `KSLT_экранировать` на МЕСТО
 * ВСТАВКИ имени в клетку сетки — `js/tournament-detail.js`. Это верно
 * ровно для тех путей, которые кладут в `p.name` СЫРОЕ имя: одиночный
 * плей-офф и `fic`. Но в то же поле кладут ещё двое:
 *   лиговый путь — имя, уже прошедшее через `pName`, а в парном турнире
 *   ещё и обёрнутое в `<span class="td-team-name">`;
 *   метка слота — готовую разметку `<span class="td-slot-wait">A1</span>`.
 * Один и тот же зов одним путям помогал, другим ломал вид. Замер 26.10 на
 * боевом `66f22aa4` (парный круговой): **14 клеток из 14** показывали
 * людям тег текстом вместо имён. Таких турниров в базе восемь. Нашла это
 * чужая проба 48 — по следу, а не глазами.
 *
 * ЧЕГО ЭТИ ПРАВИЛА СТЕРЕГУТ. Соблазн был починить строку: снять зов
 * экранирования там, где он мешает. Тогда в сетку снова приезжала бы
 * разметка из трёх мест, и следующая правка выбрала бы любой из трёх
 * договоров наугад. Заморожен ДОГОВОР, а не строка:
 *   в `p.name` лежат ДАННЫЕ — всегда, на всех путях;
 *   чем их оформить, говорит отдельное поле `оформление` с закрытым
 *   списком из двух слов;
 *   экранирует и оформляет КЛЕТКА, одним местом — `имяВКлетку`;
 *   дом имени участника один — `имяУчастникаТекстом`, и оформленная
 *   отдача `getPublicTeamName` построена НА НЁМ, а не рядом с ним.
 *
 * ЭТО ТРЕТИЙ ВИД ОДНОЙ И ТОЙ ЖЕ БЕДЫ, И ДВА ПРЕДЫДУЩИХ УЖЕ ЗАПИСАНЫ:
 * кусок 174 — вид уехал в строку js; кусок 175 — состояние уехало в
 * разметку. Здесь — договор поля разъехался по зовущим.
 *
 *   node tools/check-dogovor-imeni.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const читать = п => fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8');
/* КОД БЕЗ ПОЯСНЕНИЙ: иначе правило падает на собственном комментарии —
   на этом я попадался трижды за октябрь. */
const безПояснений = т => т
    .replace(/\/\*[\s\S]*?\*\//g, '')
    .replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const СТРАНИЦА = читать('js/tournament-detail.js');
const СТРч = безПояснений(СТРАНИЦА);
const CSSч = безПояснений(читать('css/tournament-detail.css'));

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ── 1. КЛЕТКА ОФОРМЛЯЕТ ОДНИМ МЕСТОМ ───────────────────────────────── */
правило('имя в клетку сетки кладёт один оформитель',
    /function\s+имяВКлетку\s*\(участник\)/.test(СТРч) &&
    (СТРч.match(/имяВКлетку\(/g) || []).length === 3,
    'Оформителя `имяВКлетку` в файле нет, либо его зовут не два раза.\n' +
    'Он должен быть ОДИН и зваться РОВНО из двух мест — строка игрока 1 и\n' +
    'строка игрока 2 (плюс само объявление). Третий зов значит, что\n' +
    'появился путь, который оформляет имя по-своему.');

/* ── 2. ОФОРМИТЕЛЬ ЭКРАНИРУЕТ ВСЕГДА, А НЕ В ОДНОЙ ИЗ ВЕТОК ─────────── */
const тело = (СТРч.match(/function\s+имяВКлетку[\s\S]*?\n}/) || [''])[0];
/* ЭКРАНИРУЕТ КАЖДАЯ ВЕТКА, И ЗОВ СТОИТ НА ВИДУ. Первая редакция
   экранировала один раз в переменную над ветками — красивее, но чужой
   сторож «данные в разметке» на этом вырос в слепоте: переменная в
   склейке для его признака невидима. ВЕТОК ТРИ, ЗОВОВ ТРИ, И НИ ОДНА НЕ
   ОТДАЁТ СЫРОЕ ИМЯ. */
const веток = (тело.match(/return /g) || []).length;
const зововВОформителе = (тело.match(/KSLT_экранировать\(участник\.name\)/g) || []).length;
правило('каждая ветка оформителя экранирует данные',
    веток === 3 && зововВОформителе === 3 &&
    !/return\s+участник\.name/.test(тело) &&
    !/return\s+'<span[^']*'\s*\+\s*участник\.name/.test(тело),
    'Ветвей у `имяВКлетку` ' + веток + ', зовов экранирования ' + зововВОформителе + '.\n' +
    'Их должно быть по три: метка, пара и простое имя — и КАЖДАЯ ветка\n' +
    'экранирует сама. Ветка без зова отдаёт сырое имя в разметку, и\n' +
    'договор держится только на той ветке, которую помнили.');

/* ── 3. РАЗМЕТКЕ НЕ МЕСТО В ПОЛЕ ИМЕНИ ──────────────────────────────── */
правило('в поле имени не кладут разметку',
    !/name:\s*'<|name:\s*"</.test(СТРч),
    'Снова появилось `name: \'<...\'` — поле имени несёт разметку.\n' +
    'Именно так жила метка слота до куска 176, и клетка экранировала её\n' +
    'второй раз: зритель видел `<span class="td-slot-wait">A1</span>`\n' +
    'текстом. Разметку накручивает оформитель клетки, а не кормилец.');

/* ── 4. В СЕТКУ НЕ ПРИЕЗЖАЕТ УЖЕ ЭКРАНИРОВАННОЕ ─────────────────────── */
правило('кормильцы сетки не экранируют имя за клетку',
    !/name:\s*KSLT_экранировать\(/.test(СТРч) &&
    !/name:\s*pName\(/.test(СТРч) &&
    !/name:\s*getPublicTeamName\(/.test(СТРч),
    'Кормилец сетки снова кладёт в `name` готовую к вставке строку —\n' +
    '`KSLT_экранировать(...)`, `pName(...)` или `getPublicTeamName(...)`.\n' +
    'Клетка экранирует сама, и второй заход по той же строке показывает\n' +
    'либо тег текстом, либо `&amp;` вместо `&`. Кормилец отдаёт ТЕКСТ.');

/* ── 5. ОБА КОРМИЛЬЦА ЛИГОВОЙ СЕТКИ БЕРУТ ТЕКСТ ─────────────────────── */
правило('лиговая сетка получает имя текстом, оба раза',
    (СТРч.match(/renderLeagueBracketPublic\([^)]*pNameТекстом\)/g) || []).length === 2 &&
    !/renderLeagueBracketPublic\([^)]*,\s*pName\)/.test(СТРч),
    'Премьер-лига и утешительная лига — ДВА зова одной сетки, и оба\n' +
    'обязаны получать `pNameТекстом`. Если один из них снова получит\n' +
    '`pName`, сломается ровно одна из двух лиг, и это заметят не сразу.');

/* ── 6. ОФОРМЛЕНИЕ — ЗАКРЫТЫЙ СПИСОК ИЗ ДВУХ СЛОВ ───────────────────── */
const слова = new Set((СТРч.match(/оформление(?:\s*[:=]+\s*|\s*===\s*)'([^']+)'/g) || [])
    .map(с => с.replace(/[\s\S]*'([^']+)'/, '$1'))
    .filter(с => с !== ''));
правило('у оформления два написания, и третьего нет',
    слова.size === 2 && слова.has('метка') && слова.has('пара'),
    'Написаний оформления стало ' + слова.size + ' (' + [...слова].join(', ') + ').\n' +
    'Их ровно два: `метка` и `пара`. Третье слово — это новое понятие,\n' +
    'которое оформитель клетки молча не узнает и нарисует как простое имя.');

/* ── 7. ДОМ ИМЕНИ ОДИН, И ОФОРМЛЕННАЯ ОТДАЧА СТОИТ НА НЁМ ───────────── */
правило('дом имени участника один, оформленная отдача построена на нём',
    (СТРч.match(/function\s+имяУчастникаТекстом\s*\(/g) || []).length === 1 &&
    /function\s+getPublicTeamName[\s\S]{0,400}имяУчастникаТекстом\(/.test(СТРч),
    'Либо `имяУчастникаТекстом` объявлен не один раз, либо\n' +
    '`getPublicTeamName` перестал звать его и снова выбирает язык и\n' +
    'партнёра сам. Тогда у одного понятия два определения, и беда родится\n' +
    'на шве: имя пары в сетке и в расписании разойдутся.');

/* ── 8. ДОМ ОТДАЁТ ДАННЫЕ, А НЕ РАЗМЕТКУ ────────────────────────────── */
const домТело = (СТРч.match(/function\s+имяУчастникаТекстом[\s\S]*?\n}/) || [''])[0];
правило('дом имени не экранирует и не оформляет',
    домТело.indexOf('KSLT_экранировать') === -1 &&
    домТело.indexOf('<span') === -1 &&
    /пара:\s*(?:true|false)/.test(домТело),
    'В `имяУчастникаТекстом` появилось экранирование или разметка. Он\n' +
    'отдаёт ДАННЫЕ и признак `пара` — кто двое, решает зовущий. Стоит ему\n' +
    'начать оформлять, и оба его выхода опять станут одним.');

/* ── 9. ОДНО ОПРЕДЕЛЕНИЕ НА ОФОРМЛЕНИЕ ──────────────────────────────── */
['.td-team-name', '.td-slot-wait'].forEach(кл => {
    const сколько = (CSSч.match(new RegExp('^\\' + кл + '\\s*\\{', 'gm')) || []).length;
    правило('«' + кл + '» объявлен в css один раз',
        сколько === 1,
        'Правил `' + кл + '` в `css/tournament-detail.css` ' + сколько + '.\n' +
        'Оформитель клетки навешивает это имя, и второе определение решало\n' +
        'бы порядком в файле — ровно та беда, которую я чуть не завёл на\n' +
        'куске 175 с `.ad-tb-wrap`.');
});

/* ── 10. ХРАПОВИК: ЭКРАНИРОВАНИЕ НЕ РАСТЕРЯЛОСЬ ─────────────────────── */
/* Замер 26.10 после куска: 34 зова. Кусок 158 принёс их на эту страницу,
   и починка договора не должна их СНИМАТЬ — только переставить. Потолок
   снизу: меньше — значит чьё-то поле осталось без экранирования. */
/* ЗАМЕРЕНО ПОСЛЕ КУСКА 176: 36. Было 34 до правки — оформитель клетки
   экранирует в каждой из трёх ветвей, и два зова на месте вставки стали
   тремя внутри него. ХРАПОВИК СНИЗУ ПОДНИМАЕТСЯ ДО ЗАМЕРЕННОГО: меньше
   значит, что чьё-то поле снова осталось без защиты. */
const ПОЛ_ЭКРАНИРОВАНИЙ = 36;
const зовов = (СТРч.match(/KSLT_экранировать\(/g) || []).length;
правило('зовов экранирования не меньше замеренного',
    зовов >= ПОЛ_ЭКРАНИРОВАНИЙ,
    'Зовов `KSLT_экранировать` на странице турнира ' + зовов +
    ', замерено 26.10 — ' + ПОЛ_ЭКРАНИРОВАНИЙ + '.\n' +
    'Снятый зов — это поле, которое снова уехало в разметку без защиты.\n' +
    'Если зов снят ОСОЗНАННО, число меняется здесь, вместе с причиной.');

/* ── 11. ВЕРСИЯ ОДНА НА ВСЕ ПОДКЛЮЧЕНИЯ ─────────────────────────────── */
const страницы = ['pages/tournament.html', 'pages/tournament-en.html', 'pages/tournament-kg.html'];
const версии = new Set();
страницы.forEach(с => {
    const м = читать(с).match(/tournament-detail\.js\?v=(\d+)/);
    версии.add(м ? м[1] : 'нет');
});
правило('страница турнира подключена одной версией на трёх языках',
    версии.size === 1 && !версии.has('нет'),
    'Версии `tournament-detail.js` на трёх языках: ' + [...версии].join(', ') + '.\n' +
    'У кого страница в кеше, тот увидит старый файл — и парные имена в\n' +
    'сетке снова станут тегом. Беда куска 158 жила три дня именно потому,\n' +
    'что её никто не видел.');

/* ── вывод ───────────────────────────────────────────────────────────── */
console.log('');
if (!ошибки.length) {
    console.log('  ок      один договор на имя участника: 12 правил держатся');
    console.log('          зовов экранирования ' + зовов + ' (потолок снизу ' + ПОЛ_ЭКРАНИРОВАНИЙ +
                '), оформлений ' + слова.size + ', версия одна на три языка');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  договор имени — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          x ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
