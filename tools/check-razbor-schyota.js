/**
 * РАЗБОР СЧЁТА — ОДНО ОПРЕДЕЛЕНИЕ НА ПОНЯТИЕ. Круг 20 ветки D, 19.10.
 *
 * ЭТО ТРОГАЕТ ОЧКИ, а не вид: из разобранного счёта считаются геймы,
 * сеты и места в группе.
 *
 * ЧТО БЫЛО. Прибор искал по ОБРАЗЦУ, а не по имени функции, и нашёл
 * разбор счёта в 9 файлах, 27 мест, пятью разными образцами. `parseSets`
 * лежала ЧЕТЫРЬМЯ копиями внутри одного `bracket.js` — побайтово
 * одинаковыми, то есть разойтись ещё не успели.
 *
 * НАСТОЯЩИЙ ШОВ БЫЛ В ТИРЕ. Длинное и среднее тире в тай-брейке понимал
 * ТОЛЬКО `js/group-standings.js`. Счёт `7/6(5–7)` — из экселя или
 * напечатанный вручную — таблица группы разбирала с тай-брейком, а сетка
 * без него: одно и то же выглядело по-разному на двух экранах.
 *
 * ВТОРОЙ ШОВ: ПРИЗНАК СУПЕР-ТАЙ-БРЕЙКА БЫЛ ПОСЧИТАН ДВАЖДЫ — в окне
 * ввода счёта и в групповой таблице. Второй нёс комментарий «одно
 * понятие — одно определение» и ссылку на СТРОКИ первого; к 19.10 ссылка
 * устарела на полторы тысячи строк. ССЫЛКА НА НОМЕР СТРОКИ СТАРЕЕТ.
 *
 * ДВЕ ПОПРАВКИ К ЗАМЕРУ, И ОБЕ — ПРО НАМЕРЕННОЕ. Образец
 * `^(\d+)/(\d+)$` в групповой таблице — не разбор счёта, а признак
 * супер-ТБ, и строгость там нужна. Образец с тай-брейком ОДНИМ числом в
 * `bracket.js` — запасной путь для старого формата, он стоит в `else`
 * после основного. ПРИБОР, СРАВНИВАЮЩИЙ ФОРМУ ОБРАЗЦА, А НЕ ЕГО
 * НАЗНАЧЕНИЕ, ВРЁТ — и оба раза он был готов объявить бедой решение.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ:
 *   1. `parseSets` объявлена в `bracket.js` ОДИН раз;
 *   2. разбор тай-брейка с двумя числами принимает ЛЮБОЕ тире — дефис,
 *      длинное, среднее — везде, где он вообще разбирается;
 *   3. признак супер-ТБ объявлен один раз, и это дом правил;
 *   4. оба прежних места зовут дом, а не считают сами;
 *   5. страница, зовущая дом правил, его подключает.
 *
 *   node tools/check-razbor-schyota.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const СЕТКА = 'js/admin/sections/bracket.js';
const ГРУППЫ = 'js/group-standings.js';
const ДОМ = 'js/kslt-rules.js';

const чисто = п => fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

const сетка = чисто(СЕТКА);
const группы = чисто(ГРУППЫ);
const дом = чисто(ДОМ);
const строка = (т, поз) => т.slice(0, поз).split('\n').length;

/* ---- 1. parseSets объявлена один раз ---- */
const объявлений = (сетка.match(/function\s+parseSets\s*\(/g) || []).length;
правило('parseSets объявлена в сетке один раз',
    объявлений === 1,
    'Объявлений: ' + объявлений + '.\n' +
    'До 19.10 их было ЧЕТЫРЕ — внутри renderPlayoffBracketHtml,\n' +
    'renderBracketPanel, renderFicBracketPanel и renderLeagueBracketHtml.\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: они были одинаковы лишь пока\n' +
    'никто не правил одну из четырёх.');

/* ---- 2. тай-брейк с двумя числами принимает любое тире ---- */
/* Образец, разбирающий тай-брейк ДВУМЯ числами: в скобках два числа через
   разделитель. Если разделитель — только дефис, место отстало. */
const ДВА_ЧИСЛА = /\\\(\(\\d\+\)([^)]{0,24}?)\(\\d\+\)\\\)/g;
const отставшие = [];
[['сетка', СЕТКА, сетка], ['группы', ГРУППЫ, группы]].forEach(([имя, ф, т]) => {
    const р = new RegExp(ДВА_ЧИСЛА.source, 'g');
    let м;
    while ((м = р.exec(т))) {
        const разделитель = м[1];
        /* Любое тире — это класс знаков, перечисляющий дефис и тире. */
        const любое = /\[[^\]]*[-–—][^\]]*\]/.test(разделитель);
        if (!любое) отставшие.push(ф + ':' + строка(т, м.index) + ' ← ' + м[0]);
    }
});
правило('тай-брейк с двумя числами принимает любое тире',
    отставшие.length === 0,
    'Разбирают только дефис:\n  ' + отставшие.join('\n  ') + '\n' +
    'Счёт `7/6(5–7)` с длинным тире приходит из экселя и от ручного\n' +
    'ввода. Пока его понимала лишь групповая таблица, один и тот же счёт\n' +
    'выглядел в ней с тай-брейком, а в сетке — без.\n' +
    'Замер 19.10: расширение не меняет НИ ОДНОГО счёта, который\n' +
    'разбирался прежде (0 расхождений на 14 видах).');

/* ---- 3. признак супер-ТБ живёт в доме и только там ---- */
правило('признак супер-тай-брейка объявлен в доме правил',
    /R\.этоСуперТБ\s*=\s*function/.test(дом),
    'В ' + ДОМ + ' нет `R.этоСуперТБ`. Признак нужен и окну ввода счёта,\n' +
    'и групповой таблице: без общего дома он снова разойдётся.');

/* ПРИЗНАК, А НЕ ЗАПИСЬ ОБРАЗЦА: ищем сам расчёт — разбор счёта, а рядом
   порог десяти. Кто считает это своими руками, тот и есть второе
   определение. Первая редакция правила держалась за ТОЧНУЮ запись
   образца `^(\d+)/(\d+)$` и переэкранировала её — правило молчало, а
   падало соседнее. ПРАВИЛО, ДЕРЖАЩЕЕСЯ ЗА ЗАПИСЬ, НЕ ДЕРЖИТ НИЧЕГО. */
const СВОИМИ_РУКАМИ = /\.match\([^)]{0,80}\)[\s\S]{0,160}?>=\s*10/;
const свои = [];
[[СЕТКА, сетка], [ГРУППЫ, группы]].forEach(([ф, т]) => {
    if (СВОИМИ_РУКАМИ.test(т)) свои.push(ф);
});
правило('признак супер-ТБ больше нигде не считается своими руками',
    свои.length === 0,
    'Считают сами: ' + свои.join(', ') + '\n' +
    'Это ВТОРОЕ определение одного понятия. Прежний комментарий обещал\n' +
    '«одно понятие — одно определение» и ссылался на СТРОКИ другого\n' +
    'места — ссылка устарела на полторы тысячи строк, а беда осталась.');

правило('оба прежних места зовут дом правил',
    /KSLT_RULES\.этоСуперТБ/.test(сетка) && /KSLT_RULES\.этоСуперТБ/.test(группы),
    'Окно ввода счёта или групповая таблица перестали звать дом.\n' +
    'Тогда признак снова считается в двух местах, и беда родится ровно\n' +
    'на шве между ними.');

/* ---- 4. страницы: зовёшь дом правил — подключи его ---- */
function всеJs(д, вых) {
    вых = вых || [];
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) { if (э.name !== 'node_modules') всеJs(п, вых); }
        else if (э.name.endsWith('.js')) вых.push(п);
    });
    return вых;
}
function страницы() {
    const вых = [];
    (function обойти(д) {
        fs.readdirSync(path.join(КОРЕНЬ, д || '.'), { withFileTypes: true }).forEach(э => {
            const п = д ? д + '/' + э.name : э.name;
            if (э.isDirectory()) {
                if (/^(node_modules|\.git|mobile|test-results|playwright-report|build)$/.test(э.name)) return;
                обойти(п);
            } else if (э.name.endsWith('.html')) вых.push(п);
        });
    })('');
    return вых;
}
/* НЕЗАЩИЩЁННЫЙ зов дома: без проверки `window.KSLT_RULES &&` в той же
   строке. Такой упадёт с TypeError, а не промолчит. */
const зовущие = всеJs('js').filter(п => {
    if (п === ДОМ) return false;
    const т = чисто(п);
    const стр = т.split('\n');
    return стр.some(s => /KSLT_RULES\s*\./.test(s) && !/KSLT_RULES\s*&&|typeof\s+window\.KSLT_RULES|!window\.KSLT_RULES|KSLT_RULES\s*\?/.test(s));
});
const безДома = [];
страницы().forEach(стр => {
    const т = fs.readFileSync(path.join(КОРЕНЬ, стр), 'utf8');
    const база = path.dirname(стр);
    const пути = [];
    const р = /<script[^>]*src="([^"]+)"/g;
    let м;
    while ((м = р.exec(т))) {
        const ч = м[1].split('?')[0];
        if (/^(https?:)?\/\//.test(ч)) continue;
        пути.push(path.posix.normalize(path.posix.join(база === '.' ? '' : база, ч)).replace(/^\.\//, ''));
    }
    const нужны = пути.filter(п => зовущие.indexOf(п) !== -1);
    if (нужны.length && пути.indexOf(ДОМ) === -1) {
        безДома.push(стр + ' ← ' + нужны.map(п => path.basename(п)).join(', '));
    }
});
правило('страница, зовущая дом правил без проверки, его подключает',
    безДома.length === 0,
    'Дом не подключён, а зовут его НЕЗАЩИЩЁННО:\n  ' + безДома.join('\n  ') + '\n' +
    '`window.KSLT_RULES` будет undefined, и окно упадёт с TypeError в тот\n' +
    'миг, когда человек его откроет.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      разбор счёта: 6 правил');
    console.log('          parseSets одна вместо четырёх; тире любое');
    console.log('          признак супер-ТБ один, и это дом правил');
    console.log('          ' + зовущие.length + ' файлов зовут дом незащищённо — он подключён везде');
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  разбор счёта — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
