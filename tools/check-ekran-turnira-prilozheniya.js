/**
 * ЭКРАН ТУРНИРА В ПРИЛОЖЕНИИ — ЗАМОРОЗКА КУСКА 216 (28.10).
 *
 * ЗАМЕР ДО. Вкладок было три против шести на сайте: ни участников, ни
 * расписания запусков, а группы и плей-офф лежали одной лентой в 4.68
 * экрана прокрутки. «Информация» — 1350 пикселей, 1.66 экрана. Описание
 * шло голым `t.description` в `esc()`: абзацы схлопывались в сплошное
 * полотно, а переводы из базы не брались вовсе. Участники были пусты
 * ВСЕГДА — запрос сортировался по `created_at`, которого у
 * `tournament_registrations` НЕТ (есть `registered_at`), Postgres отвечал
 * 400. Тот же несуществующий столбец убивал «Турниры игрока» на странице
 * каждого игрока. Окно-экран имело безусловный `max-width: 440px` мимо
 * шкалы: на телефоне лёжа 844 оно вставало полосой по центру, и по краям
 * была видна главная.
 *
 * ГЛАВНОЕ. Группа в приложении рисовалась СВОЯ: таблица итогов плюс
 * отдельная карточка на каждый матч. Те же данные ложились дважды, а
 * главного — кто кого обыграл — видно не было. На сайте группа это
 * КРУГОВАЯ ТАБЛИЦА, где на пересечении стоит счёт встречи. Костя сказал
 * прямо: «не понятно, а не получится поместить группу как на сайте».
 * Рисунок переехал в общий дом `js/kslt-setka.js` — скопировать его в
 * приложение значило бы завести второе определение одного понятия.
 *
 * ЗАМЕР ПОСЛЕ, в браузере на 375×812 загрузкой на нужной ширине:
 *   информация   1350 → 835 пикселей (1.66 → 1.03 экрана)
 *   группы       5.24 → 1.95 экрана, шесть круговых таблиц
 *   участники    пусто всегда → 18 + лист ожидания, 1.10 экрана
 *   расписание   не было → 18 строк, 1.54 экрана
 *   плей-офф     0.35 экрана отдельной вкладкой
 *   обрезок на всех вкладках 0, боковой прокрутки у вкладок нет
 * Сайт после переезда перемерен: таблица 150, ширина 595, обёртка
 * 343/595, вкладка 2431 — ВСЕ ЧИСЛА СОВПАЛИ С ЗАМЕРОМ ДО.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Настоящей SE-сетки в приложении: её рисовальщик на
 * сайте — связка больше четырёхсот строк с кругами, матчами за места,
 * предсказаниями и проходом, который после отрисовки меряет столбцы.
 * Переносить его в дом надо тем же порядком, что круговую таблицу, и это
 * отдельный кусок — записан в трекер.
 *
 * Запуск: node tools/check-ekran-turnira-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
function безСлов(отн) {
    return чит(отн).replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const РАЗМЕТКА = 'mobile/www/index.html';
const ДОМ = 'js/kslt-setka.js';
const ГЛАВНАЯ = 'mobile/www/js/screens/home.js';

const разметка = безСлов(РАЗМЕТКА);
const главная = безСлов(ГЛАВНАЯ);
const дом = безСлов(ДОМ);

/* ── 1. ШЕСТЬ ВКЛАДОК, КАК НА САЙТЕ ── */
(function () {
    const вкладки = разметка.match(/<button class="td-tab[^>]*data-tab="(\w+)"/g) || [];
    const поля = разметка.match(/<div class="td-tab-content[^>]*id="(\w+)"/g) || [];
    правило(
        'вкладок шесть и у каждой своё поле',
        вкладки.length === 6 && поля.length === 6,
        'Было три против шести на сайте: ни участников, ни расписания,\n' +
        'а группы и плей-офф одной лентой.\n' +
        'Вкладок: ' + вкладки.length + ', полей: ' + поля.length);

    ['tdInfo', 'tdPart', 'tdGroups', 'tdPlayoff', 'tdSched', 'tdResults'].forEach(function (id) {
        правило(
            'вкладка на месте: ' + id,
            разметка.indexOf('data-tab="' + id + '"') >= 0 &&
            разметка.indexOf('id="' + id + '"') >= 0,
            'Участники, расписание, группы и плей-офф — каждый своей\n' +
            'вкладкой: порядок задан сайтом, а не выдуман.');
    });

    правило(
        'вкладки размечены для диктора',
        /role="tablist"/.test(разметка) &&
        (разметка.match(/role="tab"/g) || []).length === 6 &&
        (разметка.match(/role="tabpanel"/g) || []).length === 6,
        'Правило куска 215 применяется к следующему без нового разбора.');

    const рядом = /tab\.classList\.add\('active'\);\s*\n\s*tab\.setAttribute\('aria-selected', 'true'\)/.test(главная);
    правило(
        'признак выбранной вкладки переставляется там же, где класс',
        рядом,
        'Разъедутся — диктор назовёт открытой прежнюю вкладку,\n' +
        'и глазами это не видно вовсе.');
})();

/* ── 2. ОЧКИ — ОДНО ПРАВИЛО НА САЙТ И ПРИЛОЖЕНИЕ ── */
(function () {
    const правила = безСлов('js/kslt-rules.js');
    правило(
        'правило «идут ли очки» живёт в общем доме',
        /* ПЕРЕПИСАНО 07.11: правило держало ФОРМУ — литерал
           `category_id === 'friendly'` внутри `идутОчки`. Признак стал
           свойством данных, и правило упало на починенном коде. Теперь
           держится смысл: очки не идут у нерейтинговой категории и у
           парных. */
        /R\.идутОчки = function/.test(правила) &&
        /R\.нерейтинговая\(турнир\.category_id\)/.test(правила) &&
        /'doubles'|mixed_doubles/.test(правила),
        'Правило жило ТОЛЬКО на сайте, в приложении его не было вовсе:\n' +
        'вкладка вела в пустой раздел, и человек ждал, что там что-то\n' +
        'появится, а появиться было нечему.');

    правило(
        'сайт зовёт общий дом, а не считает сам',
        /идутОчки\(t\)/.test(безСлов('js/tournament-detail.js')) &&
        !/category_id === 'friendly'/.test(безСлов('js/tournament-detail.js')),
        'Второе определение одного понятия расходится на первой правке.');

    правило(
        'приложение прячет вкладку очков тем же правилом',
        /KSLT_RULES\.идутОчки\(t\)/.test(главная) &&
        /вкладкаОчков\.hidden/.test(главная),
        'На дружеских и парных очков нет — значит нет и вкладки.');
})();

/* ── 3. ОБЩИЕ ФАЙЛЫ СВЕРЯЮТСЯ ДО БАЙТА ── */
[['js/kslt-rules.js', 'mobile/www/js/kslt-rules.js', 'правила клуба'],
 ['js/kslt-setka.js', 'mobile/www/js/kslt-setka.js', 'рисунок группы и сетки']
].forEach(function (п) {
    правило(
        'копия общего файла совпадает: ' + п[2],
        чит(п[0]) !== '' && чит(п[0]) === чит(п[1]),
        'Приложение держит свою копию папкой. Разойдутся — беда родится\n' +
        'ровно на шве, и увидит её не тот, кто правил.');
});

/* ── 4. ГРУППУ РИСУЕТ ДОМ, А НЕ КАЖДЫЙ СВОИМИ РУКАМИ ── */
(function () {
    правило(
        'дом круговой таблицы объявлен',
        /S\.круговаяГруппа = function/.test(дом) && /KSLT_SETKA/.test(дом),
        'Рисунок группы — одно понятие на сайт и приложение.');

    правило(
        'дом не знает ни про язык сайта, ни про словарь приложения',
        !/KSLT_YAZYK/.test(дом) && !/I18N\./.test(дом),
        'Слова и имена дому даёт зовущий — иначе он потянет за собой\n' +
        'половину того продукта, из которого переехал.');

    [[ГЛАВНАЯ, 'приложение'], ['js/tournament-detail.js', 'сайт']].forEach(function (п) {
        const т = безСлов(п[0]);
        правило(
            'круговую таблицу не рисует сам: ' + п[1],
            т.indexOf('круговаяГруппа({') >= 0 &&
            т.indexOf('<table class="td-group-table"') < 0,
            'Разметка таблицы обязана идти из дома целиком.');
    });

    правило(
        'своя таблица итогов в приложении снесена',
        главная.indexOf('mob-standings') < 0,
        'Таблица итогов и карточки матчей показывали те же данные\n' +
        'дважды: 5.24 экрана против 2.99 на сайте.');
})();

/* ── 5. СТОЛБЕЦ ВРЕМЕНИ ЗАПИСИ СУЩЕСТВУЕТ ── */
(function () {
    [[ГЛАВНАЯ, 'участники турнира'],
     ['mobile/www/js/screens/player-detail.js', 'турниры игрока']
    ].forEach(function (п) {
        const т = безСлов(п[0]);
        const куски = т.split('tournament_registrations');
        const плохо = куски.slice(1).some(function (к) {
            return /^[\s\S]{0,400}?\.order\('created_at'/.test(к);
        });
        правило(
            'заявки сортируются по существующему столбцу: ' + п[1],
            !плохо && /\.order\('registered_at'/.test(т),
            '`created_at` у `tournament_registrations` НЕТ. Postgres\n' +
            'отвечал 400, список был пуст ВСЕГДА — и это выглядело как\n' +
            '«заявок нет», а не как беда.');
    });
})();

/* ── 6. ОПИСАНИЕ: ПЕРЕНОСЫ И ПЕРЕВОД ── */
правило(
    'описание турнира сохраняет абзацы и берёт перевод',
    /I18N\.поле\(t, 'description'\)/.test(главная) &&
    /replace\(\/\\n\/g, '<br>'\)/.test(главная),
    'Шло голым `t.description` в `esc()`: 1113 знаков схлопывались в\n' +
    'сплошное полотно, а переводы из базы не брались никогда.\n' +
    'На сайте перенос есть (`js/tournament-detail.js`).');

/* ── 7. ОКНО-ЭКРАН ЕДЕТ ГРАНИЦЕЙ ТЕЛА ── */
(function () {
    const css = чит('mobile/www/css/app.css');
    const блок = css.match(/\.td-overlay \{[^}]*\}/);
    правило(
        'у окна-экрана нет безусловной границы ширины',
        !!блок && !/max-width/.test(блок[0]),
        'Стоял `max-width: 440px` мимо шкалы: на телефоне лёжа 844 окно\n' +
        'вставало полосой по центру, и по краям была видна главная.');
    правило(
        'граница окна живёт в медиа вместе с телом',
        /@media \(min-width: 640px\) and \(min-height: 640px\) \{[\s\S]{0,600}?\.td-overlay[^{]*\{[^}]*max-width/.test(css),
        'ЗАМОРОЖЕНО ОТНОШЕНИЕ: окно шириной с тело, а не число 440.');
})();

/* ── 8. ПАРА — ДВЕ СТРОКИ, А НЕ СКЛЕЕННАЯ ── */
правило(
    'имя пары рисуется блоками по игроку',
    /class="tm-p"/.test(главная) && /function имяПарыТекстом\(/.test(главная),
    'Пара шла строкой «А / Б» и ломалась посреди фамилии.\n' +
    'Там, где нужен чистый текст, зовётся `имяПарыТекстом`: разметка\n' +
    'в атрибуте была бы прочитана диктором вслух.');

/* ── 9. ОТСЕЧКА ДЛИННЫХ СПИСКОВ — ОДИН ПОРОГ ── */
(function () {
    правило(
        'порог отсечки один на все списки',
        (главная.match(/ПОРОГ_ОТСЕЧКИ/g) || []).length >= 3 &&
        /var ПОРОГ_ОТСЕЧКИ = 10/.test(главная),
        'Двадцать участников и восемнадцать строк расписания шли\n' +
        'сплошняком. Порог 10 взят у сайта, чтобы одно понятие вело\n' +
        'себя одинаково в обоих продуктах.');
    правило(
        'раскрывашка говорит диктору, раскрыта ли она',
        /aria-expanded/.test(главная) && /связатьОтсечки/.test(главная),
        'Кнопка меняет содержимое списка — значит обязана называть\n' +
        'своё состояние.');
})();

/* ── 10. ФОКУС: СВОЯ ОБВОДКА, НЕ БРАУЗЕРНАЯ ── */
правило(
    'у вкладок и таблеток кругов своя обводка фокуса',
    /\.td-tab:focus \{ outline: none; \}/.test(чит('mobile/www/css/app.css')) &&
    /* ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ, А НЕ ИМЯ КРАСКИ: 08.11 обводки фокуса
       переведены на `--accent-text`, потому что лайм на белом даёт 1.18.
       Держим «обводка СВОЯ, краской семейства акцента», а не точное имя. */
    /\.td-tab:focus-visible \{[\s\S]{0,120}?outline: 2px solid var\(--(?:accent|accent-text|accent-dim|on-image-accent)\)/.test(чит('mobile/www/css/app.css')),
    'Браузер рисовал свою синюю — она не из нашей палитры и оставалась\n' +
    'даже после нажатия мышью. Костя увидел это глазами.');

/* ── 11. ВЕРСИИ ПОДНЯТЫ ── */
(function () {
    const ВЕРСИИ = [
        ['css/app.css', 22], ['js/screens/home.js', 8], ['js/i18n.js', 9],
        ['js/screens/player-detail.js', 3], ['js/kslt-rules.js', 2], ['js/kslt-setka.js', 1]
    ];
    const отстали = [];
    ВЕРСИИ.forEach(function (в) {
        const м = разметка.match(new RegExp(в[0].replace(/[./]/g, '\\$&') + '\\?v=(\\d+)'));
        if (!м || Number(м[1]) < в[1]) отстали.push(в[0] + ' = ' + (м ? м[1] : 'нет'));
    });
    правило(
        'версии правленых файлов подняты',
        отстали.length === 0,
        'Правка без поднятия версии невидима: браузер отдаёт прежний\n' +
        'файл из кэша.\nОтстали: ' + отстали.join(', '));

    правило(
        'общий дом подключён в приложении',
        /js\/kslt-setka\.js\?v=/.test(разметка),
        'Без подключения группа не нарисуется вовсе.');
})();

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      экран турнира приложения: все ' + держится + ' правил держатся');
    console.log('          шесть вкладок, группа из общего дома, отсечка одна\n');
}
