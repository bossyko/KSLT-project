'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ДОМ = 'mobile/www';
const РЕЖИМЫ = ['light', 'dark', 'system'];

function файлы(д, вых) {
    вых = вых || [];
    const п = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(п)) return вых;
    for (const э of fs.readdirSync(п, { withFileTypes: true })) {
        const о = д + '/' + э.name;
        if (э.isDirectory()) файлы(о, вых);
        else if (/\.(js|html)$/.test(э.name)) вых.push(о);
    }
    return вых;
}

/**
 * КНОПКИ ТЕМЫ в тексте файла.
 *
 * ЛОВУШКА, РАДИ КОТОРОЙ ЭТО ОТДЕЛЬНАЯ ФУНКЦИЯ: `data-theme` стоит и на
 * корне документа — `<html lang="ru" data-theme="dark">`. Это НЕ орган
 * переключения, это место, куда орган пишет. Считать их вместе — значит
 * назвать бедой разметку, которая ни при чём.
 *
 * Отличие берётся по тексту СЛЕВА до ближайшей закрывающей скобки тега:
 * у кнопки там найдётся `<button`. Склейка строк в JS этому не мешает —
 * `'<button class="seg-btn' + (…) + '" data-theme="light">'` не содержит
 * между ними ни одного `>`.
 */
function кнопкиТемы(т) {
    const вых = [];
    const re = /data-theme\s*=\s*["']([a-z]+)["']/g;
    let м;
    while ((м = re.exec(т))) {
        const доЭтого = т.slice(0, м.index);
        const скобка = доЭтого.lastIndexOf('>');
        const кусок = доЭтого.slice(скобка + 1);
        if (кусок.indexOf('<button') === -1) continue;
        вых.push({ режим: м[1], строка: доЭтого.split('\n').length });
    }
    return вых;
}

const места = [];
for (const ф of файлы(ДОМ)) {
    const к = кнопкиТемы(fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'));
    if (к.length) места.push({ ф, кнопки: к });
}

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('переключатель темы в приложении один',
    места.length === 1,
    места.length === 0
        ? 'Кнопок темы не нашлось ВОВСЕ. Либо переключатель убрали целиком —\n' +
          'тогда снимай и это правило, — либо его собрали без слова `<button`,\n' +
          'и прибор ослеп.'
        : 'Кнопки темы лежат в ' + места.length + ' файлах:' +
          места.map(м => '\n  ' + м.ф + ' — строки ' +
              м.кнопки.map(к => к.строка).join(', ')).join('') +
          '\nДва переключателя одного понятия расходятся на шве: подсветка\n' +
          'каждого снимается один раз и своим же нажатием, поэтому второй\n' +
          'показывает прежнее. Оставь один — тот, что в боковом меню.');

правило('кнопок темы ровно три — свет, тьма, система',
    места.length === 1 &&
    места[0].кнопки.length === 3 &&
    РЕЖИМЫ.every(р => места[0].кнопки.some(к => к.режим === р)),
    места.length !== 1 ? 'Сначала сведи переключатель к одному месту.'
        : 'В ' + места[0].ф + ' кнопок ' + места[0].кнопки.length + ': ' +
          места[0].кнопки.map(к => к.режим).join(', ') +
          '\nЖдём ровно три и именно эти: ' + РЕЖИМЫ.join(', ') + '. Четвёртый\n' +
          'режим — это новое понятие, и заводится он в компоненте, а не\n' +
          'дописывается кнопкой в разметку.');

правило('прибор отличает кнопку от корневого data-theme',
    (function () {
        /* ОБРАЗЕЦ ВНУТРЬ ПРИБОРА: он обязан РАЗЛИЧАТЬ, иначе «одно место»
           он скажет и тогда, когда считает корень документа. Три вида:
           корень, прямая кнопка, кнопка из склейки строк. */
        const о = '<html lang="ru" data-theme="dark">\n' +
                  '<button class="seg-btn" data-theme="light">a</button>\n' +
                  'html += \'<button class="seg-btn\' + x + \'" data-theme="system">b</button>\';\n';
        const н = кнопкиТемы(о);
        return н.length === 2 &&
               н[0].режим === 'light' && н[1].режим === 'system';
    })(),
    'Образец внутри прибора: корень документа, прямая кнопка и кнопка,\n' +
    'склеенная из строк. Прибор обязан увидеть РОВНО две кнопки и не\n' +
    'принять за кнопку `<html data-theme>`. Не видит — значит «один\n' +
    'переключатель» он скажет и на двух.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      переключатель темы: все ' + всего + ' правил держатся');
    console.log('          один переключатель, ' + места[0].кнопки.length +
                ' кнопки, ' + места[0].ф);
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  переключатель темы — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
