#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ПРАВИЛА ЛИГИ — ОДИН ДОКУМЕНТ НА ТРЁХ ЯЗЫКАХ» (06.11).
 *
 * ЧТО БЫЛО ПОМЕРЕНО. Русская страница правил несла 7 разделов и 55
 * пунктов, английская и кыргызская — 6 разделов и меньше пунктов,
 * причём разделы были сгруппированы ИНАЧЕ: три русских («Категории и
 * уровни», «Заявка и сетка», «Формат матчей») слиты в один «Tournaments
 * & Matches», зато стоял раздел «Sanctions & Disqualification», которого
 * в русской редакции нет вовсе. Это были не сокращённые переводы, а
 * ДВА РАЗНЫХ СВОДА ПРАВИЛ: англоязычный игрок читал не то, по чему его
 * снимают с турнира.
 *
 * РЕШЕНИЕ КОСТИ 06.11: выравнивать по русской редакции.
 *
 * ЧТО СТЕРЕЖЁТ. Три страницы держат ОДНУ структуру: те же разделы, в том
 * же порядке, с тем же числом пунктов, и оглавление каждой отвечает её
 * разделам. Прибор НЕ проверяет смысл перевода — это глаза человека;
 * он ловит расхождение СТРУКТУРЫ, с которого и началась беда: правку
 * внесли в один язык и забыли про два других.
 *
 * ПОЧЕМУ СЧИТАЮТСЯ ПУНКТЫ, А НЕ ЗНАКИ. Длина перевода законно отличается
 * от оригинала, а вот пропавший пункт — это пропавшее правило.
 *
 *   node tools/check-pravila-tri-redakcii.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const СТРАНИЦЫ = [
    { язык: 'русская',     файл: 'pages/rules.html' },
    { язык: 'английская',  файл: 'pages/rules-en.html' },
    { язык: 'кыргызская',  файл: 'pages/rules-kg.html' }
];

function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function разбор(т) {
    const разделы = [];
    const ре = /<div class="ip-rules-section[^"]*" id="([^"]+)">([\s\S]*?)<\/ol>/g;
    let м;
    while ((м = ре.exec(т)) !== null) {
        const пункты = (м[2].match(/<li>/g) || []).length;
        const пустые = (м[2].match(/<li>\s*<\/li>/g) || []).length;
        разделы.push({ id: м[1], пунктов: пункты, пустых: пустые });
    }
    const оглавление = (т.match(/<ol class="ip-toc-list">([\s\S]*?)<\/ol>/) || [, ''])[1];
    const якоря = (оглавление.match(/href="#([^"]+)"/g) || []).map(с => с.slice(7, -1));
    return { разделы: разделы, якоря: якоря };
}

const чтение = СТРАНИЦЫ.map(с => {
    const т = чит(с.файл);
    return Object.assign({}, с, { есть: т !== null }, т ? разбор(т) : { разделы: [], якоря: [] });
});
const нет = чтение.filter(с => !с.есть).map(с => с.файл);
const основа = чтение[0];

function подпись(с) {
    return с.разделы.map(р => р.id + ':' + р.пунктов).join(' ');
}
const расходятся = чтение.slice(1).filter(с => подпись(с) !== подпись(основа));
const оглавлениеВрёт = чтение.filter(с =>
    с.якоря.join(' ') !== с.разделы.map(р => р.id).join(' '));
const пустые = chtoPusto();
function chtoPusto() {
    const из = [];
    for (const с of чтение) for (const р of с.разделы) if (р.пустых) из.push(с.файл + ' / ' + р.id);
    return из;
}

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя: имя, подсказка: подсказка });
}

правило('все три страницы правил на месте',
    нет.length === 0,
    'Нет файлов: ' + нет.join(', '));

правило('три редакции держат одну структуру',
    нет.length === 0 && расходятся.length === 0,
    'Структура разошлась с русской редакцией:\n' +
    ['  русская:     ' + подпись(основа)]
        .concat(расходятся.map(с => '  ' + (с.язык + ':').padEnd(13) + подпись(с)))
        .join('\n') +
    '\nЗапись `id:пунктов`. Правила — один документ на трёх языках:\n' +
    'раздел или пункт, которого нет в переводе, — это правило, по\n' +
    'которому игрока снимут с турнира, а он его не читал.');

правило('оглавление отвечает разделам страницы',
    оглавлениеВрёт.length === 0,
    'Оглавление не совпадает с разделами: ' +
    оглавлениеВрёт.map(с => '\n  ' + с.файл +
        '\n     в оглавлении: ' + с.якоря.join(' ') +
        '\n     на странице:  ' + с.разделы.map(р => р.id).join(' ')).join('') +
    '\nОглавление — второй список тех же разделов, и он обязан совпадать\n' +
    'с первым: иначе ссылка ведёт в пустоту, а раздел остаётся ненайденным.');

правило('ни один пункт не пуст',
    пустые.length === 0,
    'Пустые пункты: ' + пустые.map(с => '\n  ' + с).join('') +
    '\nПустой `<li>` — это след правки, которую бросили на полпути.');

if (ошибки.length) {
    console.log('НЕ ТАК  правила лиги: ' + ошибки.length + ' из 4 правил упало\n');
    for (const о of ошибки) console.log('  ✗ ' + о.имя + '\n    ' + о.подсказка.replace(/\n/g, '\n    ') + '\n');
    process.exit(1);
}
console.log('ок      правила лиги: 4 правила, ' + основа.разделы.length + ' разделов, ' +
    основа.разделы.reduce((с, р) => с + р.пунктов, 0) + ' пунктов на каждом языке');
