/**
 * ЗАМОРОЗКА ДЕЙСТВИЙ НАД ПОЛЬЗОВАТЕЛЕМ (кусок 201, 27.10.2026).
 *
 * ЗАМЕР ФАКТОМ, А НЕ ЛИНТЕРОМ. Линтер ловит необъявленные ИМЕНА, но зов
 * `A.чегоНет()` он пропускает: `A` объявлен, и этого ему довольно.
 * Сверил все зовы `A.x(` в `js/admin` с тем, что реально выдано в
 * `KSLT_ADMIN` (через `A.x =`, `window.KSLT_ADMIN.x =` и литерал
 * объявления): выдано 154, различных зовов 87, МЁРТВЫЙ — РОВНО ОДИН.
 *
 * `A.adminAction` ЕЁ НЕ ЗАБЫЛИ — ЕЁ ПОДРАЗУМЕВАЛИ. Кнопка
 * «Разблокировать» в карточке пользователя звала её у
 * `sections/users.js:730`, а такой функции не было НИКОГДА: зов падал в
 * `catch`, человек получал красный тост «Ошибка», блокировка входа не
 * снималась. Остальные четыре места в том же файле писали тот же
 * `fetch` руками — пятая копия одного понятия.
 *
 * СЕРВЕР ВСЁ УМЕЛ: `supabase/functions/admin-manage-user` знает
 * `unblock_otp` (строка 415) наравне с остальными действиями.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ. Два зова в `sections/players.js` на дом НЕ
 * переведены, и это решение, а не недосмотр: они намеренно
 * «выстрелил и забыл» (`fetch(...).catch(function(){})` без `await`), а
 * дом ждёт ответа и бросает. Но там беда крупнее копии: бан игрока
 * пишется ДВАЖДЫ — сперва клиентом напрямую в `players`, потом
 * функцией `ban_player`, которая пишет то же самое и шлёт Telegram.
 * ДВЕ ПРАВДЫ О ТОМ, КТО БАНИТ. Ошибка функции при этом проглочена
 * пустым `.catch()`. Это про данные, и решение за Костей.
 *
 *   node tools/check-deystvie-nad-polzovatelem.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const собрать = (кат, спис) => {
    fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(д => {
        const п = кат + '/' + д.name;
        if (д.isDirectory()) собрать(п, спис);
        else if (д.name.endsWith('.js')) спис.push(п);
    });
    return спис;
};
const JS = собрать('js', []);
const АДМИН = JS.filter(ф => ф.indexOf('js/admin') === 0);
const УТИЛ = безКом(чит('js/admin/core/utils.js'));
const ПОЛЬЗ = безКом(чит('js/admin/sections/users.js'));

/* ══ 1. ДОМ ЕСТЬ И ОДИН ════════════════════════════════════════════════ */

правило('дом действия над пользователем объявлен ровно один раз',
    JS.reduce((с, ф) => с + (безКом(чит(ф)).match(/A\.adminAction\s*=/g) || []).length, 0) === 1,
    'объявлений не одно. Два дома разойдутся на первой же правке');

/* БРОСАЕТ, А НЕ ГЛОТАЕТ. Зовущий у кнопки разблокировки обёрнут в
   `try/catch` и ждёт именно исключения: дом, вернувший ошибку молча,
   превратит её в успех, и человек увидит зелёный тост на несделанном. */
правило('дом доносит ошибку исключением, а не молча',
    /if \(отв && отв\.error\) throw new Error\(отв\.error\);/.test(УТИЛ) &&
    /if \(!ответ\.ok\) throw new Error\('HTTP ' \+ ответ\.status\);/.test(УТИЛ),
    'ошибка сервера станет молчаливым успехом, и кнопка соврёт человеку');

/* ══ 2. НИ ОДНОГО МЁРТВОГО ЗОВА ════════════════════════════════════════ */

/* ПРИЗНАК СЧИТАЕТ ВЫДАЧУ ТРЕМЯ СПОСОБАМИ. Первая редакция знала только
   `A.x =` и обвинила ЧЕТЫРЕ живых зова: выдача идёт ещё и через
   `window.KSLT_ADMIN.x =`, и внутри литерала объявления. ПРИЗНАК,
   ЗНАЮЩИЙ ОДИН СПОСОБ ИЗ ТРЁХ, НАХОДИТ БЕДУ ТАМ, ГДЕ ЕЁ НЕТ. */
const выдано = new Set();
JS.forEach(ф => {
    const т = безКом(чит(ф));
    let м;
    const пр = /(?:(?<![\w.])A|window\.KSLT_ADMIN)\.([A-Za-zА-Яа-я_][\w]*)\s*=(?!=)/g;
    while ((м = пр.exec(т)) !== null) выдано.add(м[1]);
    const пл = /window\.KSLT_ADMIN\s*=\s*\{/g;
    while ((м = пл.exec(т)) !== null) {
        let гл = 0, j = т.indexOf('{', м.index), тело = '';
        for (let k = j; k < т.length; k++) {
            if (т[k] === '{') гл++;
            else if (т[k] === '}') { гл--; if (!гл) { тело = т.slice(j, k); break; } }
        }
        let мм;
        const пк = /[\n{]\s*([A-Za-zА-Яа-я_][\w]*)\s*:/g;
        while ((мм = пк.exec(тело)) !== null) выдано.add(мм[1]);
    }
});
const мёртвые = [];
АДМИН.forEach(ф => {
    const т = безКом(чит(ф));
    let м;
    const пз = /(?<![\w.])A\.([A-Za-zА-Яа-я_][\w]*)\s*\(/g;
    while ((м = пз.exec(т)) !== null) {
        if (!выдано.has(м[1])) мёртвые.push(ф.split('/').pop() + ':' + (т.slice(0, м.index).split('\n').length) + ' → A.' + м[1]);
    }
});

правило('мёртвых зовов через дом админки нет',
    мёртвые.length === 0,
    'зовов в пустоту: ' + мёртвые.length + ' — ' + мёртвые.slice(0, 4).join(', ') + '.\n' +
    'Линтер их НЕ ловит: `A` объявлен, и этого ему довольно. Кнопка\n' +
    'падает в catch, человек получает «Ошибка», а дело не делается');

/* ══ 3. СВОЕГО fetch В РАЗДЕЛЕ ПОЛЬЗОВАТЕЛЕЙ НЕТ ═══════════════════════ */

правило('раздел пользователей зовёт действия только домом',
    !/functions\/v1\/admin-manage-user/.test(ПОЛЬЗ) &&
    (ПОЛЬЗ.match(/A\.adminAction\(/g) || []).length >= 4,
    'в разделе снова свой `fetch` на admin-manage-user. Их было ПЯТЬ копий\n' +
    'одного понятия, и пятая — та самая кнопка, которая не работала');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      действие над пользователем: 4 правила');
    console.log('          выдано в KSLT_ADMIN ' + выдано.size + ' имён, мёртвых зовов ноль');
    console.log('          дом доносит ошибку исключением, а не молча');
    console.log('          раздел пользователей зовёт только домом');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  действие над пользователем — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
