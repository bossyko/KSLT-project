/**
 * ПАЛИТРА РАЗЛИЧИТЕЛЕЙ — «ТАКОЙ ТИП» НЕ ПУТАЕТСЯ С «ТАКИМ СОСТОЯНИЕМ».
 * Круг 15 ветки D, 18.10. Находка 96а.
 *
 * ЧТО БЫЛО. Роли состояния есть (успех, опасность, внимание, сведения,
 * акцент, менеджер), а РАЗЛИЧИТЕЛЯ не было: тип корта, тип платежа и
 * назначение красились числами, и каждый раздел изобретал своё. Запись
 * говорила «шесть красок числом» — прибор нашёл СЕМЬ, и ПЯТЬ из них
 * можно было спутать с ролью при пороге заметности 2.3:
 *
 *   закрытый корт  #64B4FF  против «сведений»  ΔE  8.8
 *   платёж «корт»  #2196f3  против «сведений»  ΔE  9.0  + контраст 4.34 (НИЖЕ AA)
 *   открытый корт  #64DC64  против «успеха»    ΔE 13.1
 *   платёж «игрок» #ff9800  против «внимания»  ΔE 16.7
 *   платёж «тренер»#ce93d8  против «менеджера» ΔE 25.7
 *
 * То есть открытый корт красился как успех, а игрок — как внимание. Та же
 * беда, что круг 4 чинил с красным: одна краска значила и отказ, и эфир.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ, И ПРАВИЛО СЧИТАЕТ ЕГО САМО, а не ищет
 * строки: каждая краска палитры проходит AA на своей подложке и отстоит
 * не меньше чем на ΔE 30 от КАЖДОЙ роли состояния и от других
 * различителей. Краску в палитре можно сменить — правило пересчитает и
 * скажет, годится ли она.
 *
 * ПОЧЕМУ ТРИ, А НЕ ЧЕТЫРЕ: шесть ролей заняли основные тона, а бейдж
 * 12px/600 — мелкий текст (порог 4.5, не 3.0). Четвёртой далёкой краски
 * в системе нет. Поэтому краской помечается то, что ВЫДЕЛЯЕТ, а обычное
 * назначение («аренда», «прочее») остаётся нейтральным.
 *
 *   node tools/check-palitra-kategoriy.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чисто = п => fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));
const tokens = чисто('css/tokens.css');
const admin = чисто('css/admin.css');

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

/* ---- ЧИСЛА БЕРУТСЯ У ТОКЕНОВ, А НЕ ИЗ ПАМЯТИ ---- */
function значение(имя, глубина) {
    глубина = глубина || 0;
    if (глубина > 8) return null;
    const м = tokens.match(new RegExp('(?:^|[;{\\s])' + имя + '\\s*:\\s*([^;]+);'));
    if (!м) return null;
    const зн = м[1].trim();
    const ссылка = зн.match(/^var\((--[a-z0-9-]+)\)$/);
    if (ссылка) return значение(ссылка[1], глубина + 1);
    return зн;
}
function разбор(зн) {
    if (!зн) return null;
    let м = зн.match(/^#([0-9a-fA-F]{3,8})$/);
    if (м) {
        let c = м[1];
        if (c.length === 3) c = c.split('').map(x => x + x).join('');
        return { r: parseInt(c.slice(0, 2), 16), g: parseInt(c.slice(2, 4), 16),
                 b: parseInt(c.slice(4, 6), 16), a: 1 };
    }
    м = зн.match(/rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*(?:,\s*([\d.]+)\s*)?\)/);
    if (м) return { r: +м[1], g: +м[2], b: +м[3], a: м[4] === undefined ? 1 : +м[4] };
    return null;
}
const слой = (в, н) => ({
    r: Math.round(в.r * в.a + н.r * (1 - в.a)),
    g: Math.round(в.g * в.a + н.g * (1 - в.a)),
    b: Math.round(в.b * в.a + н.b * (1 - в.a)), a: 1
});
function L(c) {
    const f = v => { v /= 255; return v <= 0.03928 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); };
    return 0.2126 * f(c.r) + 0.7152 * f(c.g) + 0.0722 * f(c.b);
}
const контраст = (a, b) => {
    const la = L(a), lb = L(b), hi = Math.max(la, lb), lo = Math.min(la, lb);
    return Math.round(((hi + 0.05) / (lo + 0.05)) * 100) / 100;
};
function lab(c) {
    const f = v => { v /= 255; return v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); };
    const r = f(c.r), g = f(c.g), b = f(c.b);
    const X = (r * 0.4124 + g * 0.3576 + b * 0.1805) / 0.95047;
    const Y = r * 0.2126 + g * 0.7152 + b * 0.0722;
    const Z = (r * 0.0193 + g * 0.1192 + b * 0.9505) / 1.08883;
    const g2 = t => t > 0.008856 ? Math.pow(t, 1 / 3) : 7.787 * t + 16 / 116;
    const fx = g2(X), fy = g2(Y), fz = g2(Z);
    return [116 * fy - 16, 500 * (fx - fy), 200 * (fy - fz)];
}
const dE = (a, b) => {
    const la = lab(a), lb = lab(b);
    return Math.round(Math.sqrt(la.reduce((s, v, i) => s + (v - lb[i]) * (v - lb[i]), 0)) * 10) / 10;
};

/* ---- палитра и роли ---- */
const РАЗЛИЧИТЕЛИ = ['--cat-1', '--cat-2', '--cat-3'];
const РОЛИ = ['--success', '--danger', '--warning', '--info', '--accent', '--role-manager'];
const КОРОБ = разбор(значение('--bg-elevated')) || { r: 30, g: 30, b: 30, a: 1 };

/* ПРАВИЛО 1. Палитра объявлена. */
const цвета = {};
РАЗЛИЧИТЕЛИ.forEach(и => { цвета[и] = разбор(значение(и)); });
const нет = РАЗЛИЧИТЕЛИ.filter(и => !цвета[и]);
правило('палитра различителей объявлена в токенах',
    нет.length === 0,
    'Нет красок палитры: ' + нет.join(', ') + '.\n' +
    'Различитель — не роль состояния. Пока палитры нет, каждый раздел\n' +
    'изобретает свою краску числом, и типы путаются с состояниями.');

/* ПРАВИЛО 2. Каждая краска палитры ПРОХОДИТ AA на своей подложке.
   Считается, а не берётся на веру: бейдж 12px/600 — мелкий текст, 4.5. */
const ПОРОГ_AA = 4.5;
const слабые = [];
РАЗЛИЧИТЕЛИ.forEach(и => {
    const текст = цвета[и];
    const подл = разбор(значение(и + '-subtle'));
    if (!текст || !подл) { слабые.push(и + ' (нет подложки)'); return; }
    const к = контраст(текст, слой(подл, КОРОБ));
    if (к < ПОРОГ_AA) слабые.push(и + ' даёт ' + к);
});
правило('каждый различитель проходит AA на своей подложке',
    слабые.length === 0,
    'Ниже порога ' + ПОРОГ_AA + ': ' + слабые.join(', ') + '.\n' +
    'Бейдж — 12px вес 600, то есть МЕЛКИЙ текст по WCAG: порог 4.5, а не\n' +
    '3.0. Прежний синий #2196f3 давал ровно 4.34 и не проходил.');

/* ПРАВИЛО 3. Каждый различитель ДАЛЕКО от КАЖДОЙ роли состояния.
   Это и есть замороженное отношение — «тип не выглядит как состояние». */
const ПОРОГ_DE = 30;
const близкие = [];
РАЗЛИЧИТЕЛИ.forEach(и => {
    const ц = цвета[и];
    if (!ц) return;
    РОЛИ.forEach(р => {
        const цр = разбор(значение(р));
        if (!цр) return;
        const d = dE(ц, цр);
        if (d < ПОРОГ_DE) близкие.push(и + ' против ' + р + ': ΔE ' + d);
    });
});
правило('различители не похожи ни на одну роль состояния',
    близкие.length === 0,
    'Слишком близко (порог ΔE ' + ПОРОГ_DE + ', заметность начинается с 2.3):\n  ' +
    близкие.join('\n  ') + '\n' +
    'ТИП НЕ ДОЛЖЕН ВЫГЛЯДЕТЬ КАК СОСТОЯНИЕ. Так открытый корт красился\n' +
    'как «успех» (ΔE 13.1), а игрок как «внимание» (16.7).');

/* ПРАВИЛО 4. Различители отличимы ДРУГ ОТ ДРУГА. */
const слиплись = [];
for (let i = 0; i < РАЗЛИЧИТЕЛИ.length; i++) {
    for (let j = i + 1; j < РАЗЛИЧИТЕЛИ.length; j++) {
        const a = цвета[РАЗЛИЧИТЕЛИ[i]], b = цвета[РАЗЛИЧИТЕЛИ[j]];
        if (!a || !b) continue;
        const d = dE(a, b);
        if (d < ПОРОГ_DE) слиплись.push(РАЗЛИЧИТЕЛИ[i] + ' / ' + РАЗЛИЧИТЕЛИ[j] + ': ΔE ' + d);
    }
}
правило('различители отличимы друг от друга',
    слиплись.length === 0,
    'Две краски палитры слиплись: ' + слиплись.join(', ') + '.\n' +
    'В одном списке стоят рядом до трёх различителей — они обязаны\n' +
    'читаться как разные.');

/* ПРАВИЛО 5. Сами различители в админке берут краску У ПАЛИТРЫ, а не числом. */
const КЛАССЫ = ['ad-type-indoor', 'ad-type-outdoor', 'ad-pay-type-court',
                'ad-pay-type-coach', 'ad-pay-type-player',
                'ad-pay-purpose-sponsorship', 'ad-pay-purpose-rental'];
const числом = [];
КЛАССЫ.forEach(кл => {
    const м = admin.match(new RegExp('\\.' + кл + '\\s*\\{([^}]*)\\}'));
    if (!м) { числом.push(кл + ' (правила нет)'); return; }
    const тело = м[1];
    if (/#[0-9a-fA-F]{3,8}\b|rgba?\(/.test(тело)) числом.push(кл + ' красится числом');
    /* Роль состояния у различителя — та же беда с другой стороны. */
    if (/var\(--(?:success|danger|warning|info|accent|role-manager)/.test(тело)) {
        числом.push(кл + ' взял краску РОЛИ');
    }
});
правило('различители берут краску у палитры, а не числом и не у роли',
    числом.length === 0,
    'Мимо палитры: ' + числом.join('; ') + '.\n' +
    'Краска различителя — `var(--cat-N)` и `var(--cat-N-subtle)`. Число\n' +
    'здесь не просто мимо системы: оно врёт о роли.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      палитра различителей: 5 правил');
    РАЗЛИЧИТЕЛИ.forEach(и => {
        const ц = цвета[и], подл = разбор(значение(и + '-subtle'));
        const к = контраст(ц, слой(подл, КОРОБ));
        const бл = РОЛИ.map(р => ({ р, d: dE(ц, разбор(значение(р))) }))
                       .sort((a, b) => a.d - b.d)[0];
        console.log('          ' + и + ' контраст ' + к +
                    ', ближайшая роль ' + бл.р + ' ΔE ' + бл.d);
    });
    console.log('          семь различителей админки — все на палитре');
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  палитра различителей — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
