#!/usr/bin/env node
/**
 * ГЛАВНАЯ ПРИЛОЖЕНИЯ — ЗАМОРОЗКА КУСКА 211 (27.10).
 *
 * ЧТО БЫЛО. Девяносто один блок в `app.css`, двадцать три текстовых
 * уровня на экране — вдвое больше, чем на рейтинге. Из них:
 *   23 кегля мимо шкалы, СЕМЬ ИЗ НИХ ДРОБНЫЕ (11.5 · 12.5 · 12.5 · 13.5 ·
 *   10.5 · 14.5 · 11.5); 20 отступов мимо сетки (3 · 4 · 5 · 6 · 7 · 10 ·
 *   13 · 14 · 18 · 20); 7 размеров мимо сетки; ТРИ границы ширины
 *   (340 · 414 · 500), задевавшие главную одиннадцатью правилами.
 * Хуже всего `.hh-stat-cap` — подписи под числами клуба («В рейтинге»,
 * «Аккаунтов») стояли **8px**: на три ступени ниже низа шкалы.
 *
 * ИЕРАРХИЯ — УРОК ПЕРЕКЛЮЧАТЕЛЯ ПОЛА (кусок 210). Замер площади акцента:
 * «Начать путь к победе» весило 17665px² сплошного лайма, а ГЛАВНОЕ
 * действие экрана «Найти игрока» — 7092px², вдвое меньше. Самое крупное
 * акцентное пятно стояло не на главном действии. Второй призыв стал
 * контуром: 30538 → 12862px², крупнейшее пятно теперь `.hh-btn`.
 *
 * Две цели нажатия не дотягивали: `.hh-btn` 43 — НА ОДИН ПИКСЕЛЬ, глазами
 * такое не ловится; ссылка «Все» 21.
 *
 * ПОСЛЕ: одна лестница на всех видах (11 · 12 · 14 · 16 · 18 · 26 · 40),
 * мимо шкалы ни одного, целей ниже 44 ни одной, перелива нет.
 *
 * Запуск: node tools/check-glavnaya-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

const КЕГЕЛЬ = [11, 12, 14, 16, 18, 21, 26, 32, 40];
const КНОПКА = [28, 36, 44, 52];
const РАЗДЕЛ = /\.(hh-|hb-|tcv-|news-|section-title|see-all|home-)/;

let упало = 0, держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const стили = чит('mobile/www/css/app.css');

/* Блоки главной — без комментариев: признак берёт объявление, а не слова */
const блоки = [];
(function собрать() {
    const рег = /(^|\n)([^\n{}]*)\{([^}]*)\}/g;
    let м;
    while ((м = рег.exec(стили)) !== null) {
        const сел = м[2].trim();
        if (!РАЗДЕЛ.test(сел) || /@/.test(сел)) continue;
        блоки.push({ сел, тело: м[3].replace(/\/\*[\s\S]*?\*\//g, '') });
    }
})();

правило(
    'блоки главной найдены',
    блоки.length > 50,
    'Признак перестал находить раздел — проверьте список селекторов.\n' +
    'Найдено блоков: ' + блоки.length);

/* ── 1. КЕГЛИ ── */
(function кегли() {
    const мимо = [], дроби = [];
    блоки.forEach(б => {
        (б.тело.match(/font-size:\s*([^;]+);/g) || []).forEach(з => {
            if (/var\(--fs-/.test(з)) return;
            (з.match(/(\d+(?:\.\d+)?)px/g) || []).map(parseFloat).forEach(v => {
                if (v % 1 !== 0) дроби.push(б.сел + ' → ' + v);
                if (!КЕГЕЛЬ.includes(v)) мимо.push(б.сел + ' → ' + v);
            });
        });
    });
    правило(
        'ни одного дробного кегля',
        дроби.length === 0,
        'ДРОБНЫЙ КЕГЕЛЬ — ЭТО КЕГЕЛЬ, КОТОРЫЙ НИКТО НЕ ВЫБИРАЛ: он остаётся\n' +
        'от подгонки на глаз. Было семь: 11.5 · 12.5 · 12.5 · 13.5 · 10.5 ·\n' +
        '14.5 · 11.5.\nНайдено: ' + дроби.slice(0, 8).join('; '));
    правило(
        'каждый кегель главной — ступень шкалы',
        мимо.length === 0,
        'Шкала: ' + КЕГЕЛЬ.join(' · ') + '.\nМимо неё: ' + мимо.slice(0, 10).join('; '));
})();

/* ── 2. ПОДПИСЬ ПОД ЧИСЛОМ НЕ НИЖЕ НИЗА ШКАЛЫ ── */
правило(
    'подпись под числом клуба не ниже низа шкалы',
    (function () {
        const б = блоки.find(x => /\.hh-stat-cap/.test(x.сел));
        if (!б) return false;
        const м = б.тело.match(/font-size:\s*([^;]+);/);
        if (!м) return false;
        if (/--fs-2xs/.test(м[1])) return true;
        const п = м[1].match(/(\d+(?:\.\d+)?)px/);
        return !!п && parseFloat(п[1]) >= 11;
    })(),
    'Подписи «В рейтинге», «Аккаунтов», «Турниров» стояли 8px — на три\n' +
    'ступени ниже низа шкалы. На телефоне их просто не прочесть.');

/* ── 3. ОТСТУПЫ И РАЗМЕРЫ НА СЕТКЕ ── */
(function setka() {
    const мимоО = [], мимоР = [];
    блоки.forEach(б => {
        (б.тело.match(/(?:^|\n)\s*(?:margin|padding|gap|row-gap|column-gap)(?:-(?:top|right|bottom|left))?:\s*([^;]+);/g) || [])
            .forEach(з => {
                if (/var\(--space-/.test(з) || /calc\(/.test(з)) return;
                (з.match(/(\d+(?:\.\d+)?)px/g) || []).map(parseFloat).forEach(v => {
                    if (v !== 0 && v !== 2 && v % 8 !== 0 && ![12, 24, 40].includes(v)) {
                        мимоО.push(б.сел + ' → ' + v);
                    }
                });
            });
        (б.тело.match(/(?:^|\n)\s*(?:width|height|min-height|min-width|max-width):\s*([^;]+);/g) || [])
            .forEach(з => {
                if (/var\(--|%|calc\(|auto|none|100|vw/.test(з)) return;
                (з.match(/(\d+(?:\.\d+)?)px/g) || []).map(parseFloat).forEach(v => {
                    if (v % 8 !== 0 && !КНОПКА.includes(v) && !КЕГЕЛЬ.includes(v)) {
                        мимоР.push(б.сел + ' → ' + v);
                    }
                });
            });
    });
    правило(
        'каждый отступ главной на сетке восьмёрки',
        мимоО.length === 0,
        'Отступ стоит на шкале (8 · 12 · 16 · 24 · 32 · 40) или кратен\n' +
        'восьми; 2 — оптическая правка. Было двадцать мимо.\n' +
        'Найдено: ' + мимоО.slice(0, 10).join('; '));
    правило(
        'каждый размер главной на сетке',
        мимоР.length === 0,
        'Размер кратен восьми либо стоит на ступени кнопок или кеглей.\n' +
        'Найдено: ' + мимоР.slice(0, 10).join('; '));
})();

/* ── 4. НИ ОДНОЙ ГРАНИЦЫ ШИРИНЫ НА ГЛАВНОЙ ── */
(function границы() {
    const строки = стили.split('\n');
    let гл = 0, вМедиа = false, граница = '';
    const найдено = [];
    строки.forEach(function (с, i) {
        const м = с.match(/@media \((?:min|max)-width:\s*(\d+)px\)/);
        if (м) { вМедиа = true; граница = м[1]; гл = 0; }
        if (вМедиа) {
            for (const ч of с) { if (ч === '{') гл++; if (ч === '}') гл--; }
            if (РАЗДЕЛ.test(с) && граница !== '640' && граница !== '992') {
                найдено.push((i + 1) + ' (' + граница + 'px): ' + с.trim());
            }
            if (гл === 0) вМедиа = false;
        }
    });
    правило(
        'главная не стоит ни на одной границе ширины',
        найдено.length === 0,
        'Главная держалась на трёх границах — 340 · 414 · 500, одиннадцать\n' +
        'правил. На шкале проекта границ две: 640 и 992.\n' +
        'Найдено: ' + найдено.slice(0, 6).join('\n'));
})();

/* ── 5. ТО, ЧТО РАНЬШЕ ДЕЛАЛИ ГРАНИЦЫ, ДЕЛАЕТ САМА РАСКЛАДКА ── */
правило(
    'сетка «о клубе» сама кладёт столько колонок, сколько влезает',
    /\.hb-about-grid\s*\{[\s\S]{0,400}?grid-template-columns:\s*repeat\(auto-fit/.test(стили),
    'Три колонки включались границей 500. `repeat(auto-fit, minmax(...))`\n' +
    'делает то же без границы.');

правило(
    'ряд чисел клуба тянется, а не переключается границей',
    /\.hh-stat\s*\{[\s\S]{0,600}?flex:\s*1 1\s/.test(стили),
    'На 500 включалось «пять в ряд» и особый случай на четыре карточки.\n' +
    'Ряд обязан класть столько, сколько влезает по нижнему пределу.');

правило(
    'карточка новости тянется между своими пределами',
    /\.news-card\s*\{[\s\S]{0,400}?width:\s*\d+vw/.test(стили),
    'Было три набора ширин по трём границам — 220/240, 256/280, 280/310.\n' +
    'Карточка тянется от нижнего предела к верхнему и больше нигде не\n' +
    'переопределяется.');

/* ── 6. ЦЕЛИ НАЖАТИЯ ── */
[['.hh-btn', 'главное действие «Найти игрока»'],
 ['.hb-cta', 'второй призыв'],
 ['.section-title .see-all', 'ссылка «Все»']].forEach(function (п) {
    const б = блоки.find(x => x.сел === п[0]);
    правило(
        'цель нажатия: ' + п[1],
        !!б && /min-height:\s*44px/.test(б.тело),
        'У `' + п[0] + '` обязан стоять `min-height: 44px`.\n' +
        'У главной кнопки было 43 — НА ОДИН ПИКСЕЛЬ, глазами такое не\n' +
        'поймать; у ссылки «Все» — 21.');
});

/* ── 7. ОДНО ГЛАВНОЕ ДЕЙСТВИЕ — ОДНА ЗАЛИВКА ── */
(function ierarhiya() {
    const глав = блоки.find(x => x.сел === '.hh-btn');
    const второй = блоки.find(x => x.сел === '.hb-cta');
    правило(
        'главное действие экрана залито акцентом',
        !!глав && /background:\s*var\(--accent\)/.test(глав.тело),
        'Заливка акцентом — признак ГЛАВНОГО действия экрана.');
    правило(
        'второй призыв не залит акцентом',
        !!второй && !/background:\s*var\(--accent\)/.test(второй.тело) &&
        /border:\s*2px solid var\(--accent\)/.test(второй.тело),
        'ОДНО ГЛАВНОЕ ДЕЙСТВИЕ НА ЭКРАН — ОДНА ЗАЛИВКА. «Начать путь к\n' +
        'победе» весило 17665px² сплошного лайма против 7092px² у главного\n' +
        'действия: самое крупное акцентное пятно стояло не на главном.\n' +
        'Второй призыв остаётся призывом, но контуром.');
})();

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      главная приложения: все ' + держится + ' правил держатся');
    console.log('          одна лестница на всех видах, ни одной границы ширины\n');
}
