/**
 * ЗАМОРОЗКА «СЧЁТ КОНТРАСТА ОДИН, И ГРАДИЕНТ ОН СКЛАДЫВАЕТ»
 * (ветка B, кусок 186, 26.10.2026).
 *
 * ЗАМЕР. Запись 72г говорила: «48 текстовых узлов на градиенте не мерены
 * из 1478; проходят они или нет — НЕ ЗНАЮ (13.10)». Причина нашлась не в
 * продукте, а в ПРИБОРЕ: проба `92-tihiy-tekst.spec.js` держала свою
 * копию формулы WCAG, и копия выходила из счёта на первой же картинке —
 * «картинка или градиент на пути — узел не мерится».
 *
 * КАРТИНКА И ГРАДИЕНТ — РАЗНЫЕ ВЕЩИ, И В ЭТОМ БЫЛА ОШИБКА. Градиент задан
 * красками: его можно сложить, взяв ВСЕ остановки и ХУДШУЮ из них — узел
 * проходит, только если проходит на самом светлом месте. Фотография
 * числом не описывается вовсе, и такой узел честно называется НЕ МЕРЕНЫМ.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ, А НЕ ЧИСЛО: счёт контраста в продукте ОДИН,
 * проба зовёт его, а не свою копию, и градиент в нём складывается
 * списком остановок, а не одним числом.
 *
 * ПОЧЕМУ ХРАПОВИК НА 43. Формула WCAG скопирована ещё в 43 файлах — это
 * долг, замеренный 26.10, а не решение: 28 проб, 7 стендов в maket и
 * 8 приборов, включая мой же разовый 185-h2h-dvazhdy.js от 25.10.
 * ПО ДОРОГЕ ЭТОТ ЖЕ СТОРОЖ ПОЙМАЛ САМ СЕБЯ: пока иголка была написана
 * числом, он и его прувер считались сорок четвёртой и сорок пятой
 * копиями. Отсюда правило: ПРИБОР НЕ ДОЛЖЕН ПОПАДАТЬ В СОБСТВЕННЫЙ ЗАМЕР.
 * Храповик идёт только вниз: новая копия роняет правило, сведённая —
 * опускает число. Храповик идёт только вниз: новая копия роняет правило,
 * сведённая — опускает число.
 *
 *   node tools/check-odin-schyot-kontrasta.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ИГОЛКА СОБИРАЕТСЯ ИЗ ЧАСТЕЙ НАМЕРЕННО. Напиши её здесь целиком — и
   сторож вместе со своим прувером станут сорок пятой и сорок шестой
   копиями формулы, уронив правило, которое сами и сторожат. ПРИБОР НЕ
   ДОЛЖЕН ПОПАДАТЬ В СОБСТВЕННЫЙ ЗАМЕР. */
const ИГОЛКА = '0.' + '2126';
const ИГОЛКА2 = '0.' + '03928';

const МОДУЛЬ = 'tools/kontrast.mjs';
const ПРОБА = 'tests/e2e/design-system/92-tihiy-tekst.spec.js';
const есть = ф => fs.existsSync(path.join(КОРЕНЬ, ф));

правило('счёт контраста лежит в одном модуле',
    есть(МОДУЛЬ) && есть(ПРОБА),
    'Нет файла: ' + [МОДУЛЬ, ПРОБА].filter(ф => !есть(ф)).join(', ') + '.\n' +
    'Якорь держится на ИМЕНИ ФАЙЛА: модуль переехал — правило перестало бы\n' +
    'сторожить его молча, и копия формулы вернулась бы незамеченной.');

const М = есть(МОДУЛЬ) ? чит(МОДУЛЬ) : '';
const П = есть(ПРОБА) ? чит(ПРОБА) : '';
/* ПРАВИЛО СМОТРИТ НА КОД, А НЕ НА ПОЯСНЕНИЕ. Проверка «afterAll больше нет»
   упала на моём же комментарии, в котором слово afterAll названо как
   рассказ о прежней ошибке. Признак, читающий комментарии, сторожит текст,
   а не продукт. */
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');
const Пк = безКом(П);

правило('модуль отдаёт наружу и замер, и саму формулу',
    /export function замер/.test(М) && /export const контраст/.test(М) &&
    /export const раз/.test(М) && /export const поверх/.test(М),
    'Модуль должен отдавать `замер`, `контраст`, `раз` и `поверх`.\n' +
    'Отдаёт только замер — и соседняя проверка, которой нужна одна\n' +
    'формула, заведёт себе вторую копию. Так эта беда и родилась.');

правило('фотография и градиент различаются',
    /const фотография = s =>[\s\S]{0,120}\(\?!data:\)/.test(М) && /const изГрадиента/.test(М),
    'В модуле нет различения фотографии и градиента.\n' +
    'Градиент задан красками и складывается. Фотография числом не\n' +
    'описывается. Значок `data:` подложкой текста не является — он лежит\n' +
    'поверх краски фона у края поля, и краска под текстом не меняется.');

правило('фотография не записывается в прошедшие',
    /if \(!фоны\) \{ неМерено\.push/.test(М),
    'Узел, под которым фотография, должен попасть в `неМерено`, а не\n' +
    'пройти молча. ЧИСЛО, КОТОРОГО НЕ ПОМЕРИТЬ, НЕ ВЫДУМЫВАЕТСЯ.');

правило('градиент складывается ВСЕМИ остановками, а не одной',
    /варианты\.forEach\(в => гр\.forEach\(г => нов\.push/.test(М) &&
    /if \(v < худший\)/.test(М),
    'Градиент должен размножать варианты подложки по всем остановкам, а\n' +
    'узел — считаться по ХУДШЕЙ. Одна остановка — это снова «одним числом\n' +
    'градиент не описать», с которого всё и началось.');

правило('у пробы нет своей копии формулы',
    П.indexOf(ИГОЛКА) === -1 && П.indexOf(ИГОЛКА2) === -1,
    'В `' + ПРОБА + '` снова появилась формула WCAG.\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: беда родится ровно на шве, когда\n' +
    'копия и модуль разойдутся — как они и разошлись на градиенте.');

/* ТРИ МЕСТА, А НЕ «НЕ МЕНЬШЕ ДВУХ». Прувер показал, почему: при пороге
   «>= 2» откат снимал один зов из трёх, и правило оставалось зелёным. */
правило('проба зовёт модуль во всех трёх местах',
    /const ЗАМЕР = async page => page\.evaluate\(\s*async \(\) => \(await import\('\/tools\/kontrast\.mjs'\)\)\.замер/.test(П) &&
    /const САМОПРОВЕРКА = async page => page\.evaluate\(\s*async \(\) => \(await import\('\/tools\/kontrast\.mjs'\)\)\.самопроверка/.test(П) &&
    /const м = await import\('\/tools\/kontrast\.mjs'\);/.test(П),
    'Проба должна звать `/tools/kontrast.mjs` в ТРЁХ местах: замер узлов,\n' +
    'самопроверка складывания и проверка лестницы тихого текста. Зовов\n' +
    'найдено: ' + (П.match(/import\('\/tools\/kontrast\.mjs'\)/g) || []).length +
    '. Порог «не меньше двух» негоден: при нём снятие одного зова из трёх\n' +
    'правило не роняло — это показал прувер.');

правило('проба требует нуля не мереных и нуля ниже нормы',
    /expect\(р\.неМерено,[\s\S]{0,220}\)\.toBe\(0\)/.test(П) &&
    /expect\(р\.нижеНормы,[\s\S]{0,120}\)\.toBe\(0\)/.test(П),
    'Проба должна падать и на узле ниже AA, и на узле, который не\n' +
    'померить. Второе важнее: молчаливое «не мерено» и было бедой.');

/* ПОРОГ НЕ ДЕРЖИТСЯ НИ НА СЧЁТЧИКЕ, НИ НА ДАННЫХ. Обе прежние попытки
   были неверны: счётчик через afterAll не переживал границу рабочего, а
   числа «на главной 16, на рейтинге 18» были сняты с БОЕВОЙ базы, тогда
   как проба ходит в ТЕСТОВУЮ, где подиума нет вовсе — ВСЕ градиентные
   узлы продукта приходят из данных.
   ПОРОГ, КОТОРЫЙ ЗАВИСИТ ОТ ДАННЫХ, НЕ ПОРОГ. */
правило('порог складывания не зависит ни от данных, ни от рабочего',
    /export function самопроверка/.test(М) &&
    /const САМОПРОВЕРКА = async page/.test(П) &&
    /expect\(с\.сложилось,[\s\S]{0,400}toBe\(true\)/.test(П) &&
    !/ГРАДИЕНТНЫЕ/.test(Пк) && !/afterAll/.test(Пк),
    'Складывание градиента должен доказывать САМ МОДУЛЬ на своём узле с\n' +
    'заранее известным переходом, а проба — звать `самопроверка()` на\n' +
    'каждой странице. Якорь на числе градиентных узлов страницы негоден:\n' +
    'он зависит от того, что лежит в базе, и падает при смене базы.');

правило('самопроверка доказывает ОБА конца градиента',
    /виденСветлыйКонец/.test(М) && /виденТёмныйКонец/.test(М) &&
    /фоны\.length > 1/.test(М),
    'Самопроверке мало «фонов больше одного»: нужно, чтобы белый текст\n' +
    'на переходе от чёрного к белому дал и тёмный конец (контраст выше\n' +
    '15), и светлый (ниже 1.2). Иначе складывание можно подменить одним\n' +
    'фоном, повторённым дважды, и порог этого не заметит.');

правило('сравнение языков идёт по статической оболочке',
    /waitForSelector\('footer, \.site-footer'/.test(П) &&
    /querySelectorAll\('header \*, nav \*, footer \*'\)/.test(П),
    'Сравнение языков должно смотреть ТОЛЬКО шапку, навигацию и подвал:\n' +
    'они лежат в разметке (partials/) и приходят со страницей. Сравнение\n' +
    'страницы целиком ловило не язык, а ВРЕМЯ — список рейтинга приходит\n' +
    'из сети, и на узком виде одна страница успевала отрисоваться, а\n' +
    'вторая нет. Проба падала на двух видах из пяти и называла это\n' +
    '«краска зависит от языка».');

правило('проба сторожит независимость краски от языка',
    /краска текста не зависит от языка/.test(П) && /players-en\.html/.test(П),
    'Контраст меряется на ОДНОМ языке — и это законно ровно до тех пор,\n' +
    'пока краска от языка не зависит. Проверка должна сравнивать набор\n' +
    '«краска + кегль + вес» на русской и английской странице.');

/* css не завязан на язык — основание мерить один язык. */
const цсс = fs.readdirSync(path.join(КОРЕНЬ, 'css')).filter(ф => ф.endsWith('.css'));
const поЯзыку = [];
цсс.forEach(ф => {
    const т = чит('css/' + ф).replace(/\/\*[\s\S]*?\*\//g, '');
    if (/:lang\(|\[lang[\s~^|$*]?=/.test(т)) поЯзыку.push('css/' + ф);
});
правило('css не завязан на язык',
    поЯзыку.length === 0,
    'Правила, завязанные на язык, нашлись в: ' + поЯзыку.join(', ') + '.\n' +
    'Тогда контраст надо мерить на ВСЕХ трёх языках, а не на одном, и\n' +
    'список страниц пробы вырастает втрое. Это решение, а не мелочь.');

/* ── ХРАПОВИК КОПИЙ ФОРМУЛЫ ──────────────────────────────────────────── */
const ПОТОЛОК_КОПИЙ = 43;
function всеФайлы(д, итог) {
    итог = итог || [];
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д ? д + '/' + э.name : э.name;
        if (/^(node_modules|\.git|test-results|builds)$/.test(э.name)) return;
        if (п.indexOf('mobile/android') === 0) return;
        if (э.isDirectory()) всеФайлы(п, итог);
        else if (/\.(js|mjs|html)$/.test(э.name)) итог.push(п);
    });
    return итог;
}
const копии = всеФайлы('').filter(ф => ф !== МОДУЛЬ && чит(ф).indexOf(ИГОЛКА) !== -1);
правило('копий формулы контраста не прибавляется',
    копии.length <= ПОТОЛОК_КОПИЙ,
    'Файлов со своей копией формулы WCAG: ' + копии.length + ' при потолке ' +
    ПОТОЛОК_КОПИЙ + '.\n' + копии.slice(0, 6).join('\n') + '\n\n' +
    'Храповик идёт ТОЛЬКО ВНИЗ. Перевёл пробу на модуль — опусти число\n' +
    'здесь же. Это долг, замеренный 26.10, а не разрешение копировать.');

