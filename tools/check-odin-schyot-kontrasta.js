function всеФайлы(д, итог) {
    итог = итог || [];
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д ? д + '/' + э.name : э.name;
        if (/^(node_modules|\.git|test-results|builds)$/.test(э.name)) return;
        if (п.indexOf('mobile/android') === 0) return;
        if (э.isDirectory()) всеФайлы(п, итог);
        else if (/\.(js|mjs|html)$/.test(э.name)) итог.push(п);
    });
    return итог;
}
