const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = о => fs.readFileSync(path.join(КОРЕНЬ, о), 'utf8');

/* Гасим комментарии, СОХРАНЯЯ переводы строк: прибор, склеивающий строки,
   врёт местом, а неверное место заметить труднее, чем неверный счёт. */
const чисто = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '));

/* Блок селектора вырезается по балансу скобок, считая С ОТКРЫВАЮЩЕЙ.
   Начни с нуля — и блок захватит полфайла: ровно это дало 33 ложных места
   19.10 утром. */
function блок(текст, селектор) {
    const обр = new RegExp('(^|[\\s}])' + селектор.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{', 'm');
    const м = обр.exec(текст);
    if (!м) return null;
    const о = текст.indexOf('{', м.index);
    let гл = 0;
    for (let i = о; i < текст.length; i++) {
        if (текст[i] === '{') гл++;
        else if (текст[i] === '}') { гл--; if (гл === 0) return текст.slice(о + 1, i); }
    }
    return текст.slice(о + 1);
}

const style = чисто(чит('css/style.css'));
const admin = чисто(чит('css/admin.css'));
const dash = чисто(чит('css/dashboard.css'));
const layout = чисто(чит('js/admin/core/layout.js'));
const users = чисто(чит('js/admin/sections/users.js'));
const dashJs = чисто(чит('js/dashboard.js'));
/* ЯКОРЬ ПЕРЕЕХАЛ ВМЕСТЕ С СОДЕРЖИМЫМ (кусок 167): значок роли собирали ЧЕТЫРЕ
   места в этих трёх файлах, теперь его отдаёт ДОМ РОЛИ. Правила ниже стали
   СТРОЖЕ: вместо «каждое место зовёт класс» теперь «своего значка нет ни у
   кого, и класс пишет дом». */
const домРоли = чисто(чит('js/kslt-dostup.js'));
const зовущиеРоли = [layout, users, dashJs];

const РОЛИ = ['admin', 'manager', 'player', 'user'];
const ошибки = [];
let держится = 0;
function правило(имя, годно, подсказка) {
    if (годно) { держится++; console.log('  ✓ ' + имя); }
    else ошибки.push({ имя, подсказка });
}

/* ---- 1. определение ровно одно, и оно в общем файле ---- */
const вStyle = (style.match(/(^|[\s}])\.kslt-role\s*\{/gm) || []).length;
правило(
    'определение бейджа роли стоит в style.css, и ровно одно',
    вStyle === 1,
    'Найдено ' + вStyle + ' объявлений `.kslt-role {` в css/style.css.\n' +
    'Роль рисуется и в админке, и в кабинете; общий у них только style.css.\n' +
    'Два объявления — это два понятия, и беда родится ровно на шве.');

правило(
    'своих копий бейджа роли в admin.css и dashboard.css нет',
    !/\.ad-role-badge/.test(admin) && !block_imeet_krasku(dash, '.db-sidebar-role') && !block_imeet_krasku(admin, '.ad-sidebar-role'),
    'admin.css держал `.ad-role-badge-*` высотой 19, dashboard.css —\n' +
    '`.db-sidebar-role` высотой 21 с отступами 3·10. Боковым панелям\n' +
    'оставлено ТОЛЬКО положение: ни краски, ни кегля, ни радиуса.');

function block_imeet_krasku(текст, сел) {
    const б = блок(текст, сел);
    if (б === null) return false;
    return /background|color|font-size|border-radius|letter-spacing|text-transform/.test(б);
}

/* ---- 2. числа взяты именами ---- */
const тело = блок(style, '.kslt-role') || '';
правило(
    'высота, кегль и вес бейджа роли названы именами, а не числами',
    /min-height:\s*var\(--chip-h\)/.test(тело)
    && /font-size:\s*var\(--fs-2xs\)/.test(тело)
    && /font-weight:\s*var\(--fw-medium\)/.test(тело)
    && /padding:\s*0\s+var\(--space-2\)/.test(тело)
    && /border-radius:\s*var\(--radius-full\)/.test(тело),
    'Эталон — компонент Badge 27:53: высота 24, отступ 8, радиус full,\n' +
    '11px Medium. Для всех четырёх в системе есть имена: --chip-h,\n' +
    '--space-2, --radius-full, --fs-2xs, --fw-medium. Число вместо имени\n' +
    'разъедется с эталоном при первой же правке шкалы.');

/* ---- 3. обводка внутренней тенью: border ломает высоту ---- */
