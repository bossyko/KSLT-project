function тело(текст, имя) {
    const i = текст.indexOf('function ' + имя + '(');
    if (i === -1) return '';
    let гл = 0, j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}
function блокCSS(текст, селектор) {
    const i = текст.indexOf(селектор + ' {');
    if (i === -1) return '';
    const j = текст.indexOf('}', i);
    return j === -1 ? '' : текст.slice(i, j);
}

