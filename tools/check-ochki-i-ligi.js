/**
 * ЗАМОРОЗКА: ОЧКИ ЗА ТУРНИР И ДВЕ ЛИГИ.
 *
 * Решения Кости 30.09 по Положению КСЛТ:
 *   · места 1–4 платятся ТОЛЬКО таблицей, без 25 за победу;
 *   · всем остальным — 25 за каждую победу, включая доп. матчи, а кто не
 *     выиграл ни одной — 10; таблица им не платится вовсе;
 *   · в олимпийке таблица платит за каждое место, победы не прибавляются;
 *   · верхняя лига платится таблицей своего уровня, нижняя — уровнем ниже.
 *
 * Здесь заморожены ОТНОШЕНИЯ, а не числа.
 *
 *   node tools/check-ochki-i-ligi.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ОЧКИ   = чит('js/rating-points.js');
const ОЧч    = безКом(ОЧКИ);
const СЕТКА  = чит('js/admin/sections/bracket.js');
const СЕТч   = безКом(СЕТКА);
const CSS    = чит('css/admin.css');
const СТРАНИЦА = чит('pages/admin.html');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

function тело(текст, имя) {
    const i = текст.indexOf('function ' + имя + '(');
    if (i === -1) return '';
    let гл = 0, j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}
function блокCSS(текст, селектор) {
    const i = текст.indexOf(селектор + ' {');
    if (i === -1) return '';
    const j = текст.indexOf('}', i);
    return j === -1 ? '' : текст.slice(i, j);
}

/* ─────────── ОДНО ИЛИ ДРУГОЕ, А НЕ ОБА РАЗОМ ─────────── */

const ТЕЛО_ОЧКИ = тело(ОЧч, 'очки');

правило('первые места платятся только таблицей и выходят сразу',
    /место <= МЕСТ_ПО_ТАБЛИЦЕ\) return заМесто\(место, таблица\);/.test(ТЕЛО_ОЧКИ),
    'ранний возврат по таблице пропал — победы снова начнут прибавляться поверх места');

правило('остальным платятся ТОЛЬКО победы, без таблицы',
    /return побед > 0 \? побед \* ЗА_ПОБЕДУ : ЗА_УЧАСТИЕ;/.test(ТЕЛО_ОЧКИ) &&
    !/сумма \+=/.test(ТЕЛО_ОЧКИ),
    'вернулось сложение таблицы с победами — победитель получит 360 плюс победы');

правило('граница названа отношением, а не числом в теле',
    /var МЕСТ_ПО_ТАБЛИЦЕ = \d+;/.test(ОЧч) &&
    !/<= 4\b/.test(ТЕЛО_ОЧКИ),
    'в теле расчёта появилось голое число вместо названной границы');

правило('олимпийка платит только таблицей',
    (СЕТч.match(/поТурниру\([^,]+, таблицаМест, \{\}\)/g) || []).length >= 2 &&
    /return заМесто\(место, таблица\);\s*$/.test(ТЕЛО_ОЧКИ.trim()),
    'в олимпийку пришли правила с победами, либо расчёт без правил перестал платить таблицей');

/* ─────────── ДВЕ ЛИГИ — ДВЕ ТАБЛИЦЫ ─────────── */

правило('таблица уровнем ниже объявлена ровно один раз',
    (СЕТч.match(/async function таблицаУровнемНиже\(/g) || []).length === 1,
    'второе определение нижней таблицы — беда родится ровно на шве');

правило('нижняя лига платится своей таблицей, верхняя своей',
    /processLeague\(matches\.filter\(isPLMatch\), tournament\.category_id, 'PL', таблицаМест\)/.test(СЕТч) &&
    /processLeague\(matches\.filter\(isCLMatch\), нижняяКатегория, 'CL', таблицаНижней\)/.test(СЕТч) &&
    /таблицаЛиги \|\| таблицаМест/.test(СЕТч),
    'лиги снова платятся одной таблицей — Положение требует второй и третьей категории');

правило('нижняя таблица берётся соседом снизу по порядку уровней',
    /у\.sort_order < свой\.sort_order/.test(тело(СЕТч, 'таблицаУровнемНиже')),
    'нижняя таблица берётся не соседом снизу — уровень и очки разойдутся');

/* ─────────── КТО В КАКУЮ ЛИГУ — ОДНО ОПРЕДЕЛЕНИЕ ─────────── */

правило('деление по лигам объявлено один раз',
    (СЕТч.match(/function лигаМеста\(/g) || []).length === 1,
    'второе определение того, кто уходит наверх — таблица и генератор снова разойдутся');

правило('генератор лиг и групповая таблица делят одинаково',
    (СЕТч.match(/лигаМеста\(tournament, st\.place\)/g) || []).length >= 2,
    'одно из двух мест снова делит своей формулой: при «выходят 2» второе место ' +
    'показывалось уходящим в Утешительную, хотя уходило в Высшую');

правило('деление считает от «выходят из группы», а не от половины',
    /place <= выходит/.test(тело(СЕТч, 'лигаМеста')) &&
    !/\/ 2/.test(тело(СЕТч, 'лигаМеста')),
    'вернулось деление пополам — оно расходится с генератором лиг');

/* ─────────── КУДА ИДЁТ ИГРОК — СЛОВОМ, А НЕ ЦВЕТОМ ─────────── */

правило('в строке стоит название лиги, а не значок',
    /ad-league-pl">' \+ L\.premierLeague/.test(СЕТч) &&
    /ad-league-cl">' \+ L\.consolationLeague/.test(СЕТч) &&
    !/&#9654;/.test(СЕТч),
    'вернулся цветной треугольник: один знак на оба исхода, различимый только краской');

правило('пометка появляется, когда доиграна СВОЯ группа',
    /вЛигу === 'PL' && группаДоиграна/.test(СЕТч) &&
    /вЛигу === 'CL' && группаДоиграна/.test(СЕТч),
    'пометка снова ждёт, пока доиграют ВСЕ группы, — своя группа уже всё решила');

правило('бейдж лиги стоит на шкале и не раздвигает строку',
    /font-size: var\(--fs-2xs\)/.test(блокCSS(CSS, '.ad-league-go')) &&
    /white-space: nowrap/.test(блокCSS(CSS, '.ad-league-go')),
    'кегль бейджа ушёл со шкалы или он начал переносить строку имени');

правило('высшая лига красится акцентом с почти-чёрным текстом',
    /background: var\(--accent\)/.test(блокCSS(CSS, '.ad-league-pl')) &&
    /color: #0A0A0A/.test(блокCSS(CSS, '.ad-league-pl')),
    'текст на лайме перестал быть почти-чёрным — контраст провалится');

/* ─────────── ВЕРСИИ ─────────── */

правило('версии подняты — иначе правка не доедет до того, у кого файл в кеше',
    /rating-points\.js\?v=([2-9]|\d\d)/.test(СТРАНИЦА) &&
    /sections\/bracket\.js\?v=(21[4-9]|2[2-9]\d|[3-9]\d\d)/.test(СТРАНИЦА) &&
    /admin\.css\?v=(17[4-9]|1[89]\d|[2-9]\d\d)/.test(СТРАНИЦА),
    'версия rating-points.js, bracket.js или admin.css не поднята после правки');

/* ─────────── ВЫВОД ─────────── */

const всего = 15;
if (ошибки.length) {
    console.log('\n  ✗ очки за турнир и две лиги — ' + ошибки.length + ' из ' + всего + ':\n');
    ошибки.forEach(о => console.log('    · ' + о.имя + '\n      ' + о.подсказка));
    console.log('');
    process.exit(1);
}
console.log('ок очки за турнир и две лиги — ' + всего + ' правил');
