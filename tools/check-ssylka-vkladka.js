#!/usr/bin/env node
/**
 * ССЫЛКА СНАРУЖИ И ВКЛАДКА ВНУТРИ ЗОВУТ ОДНО И ТО ЖЕ (12.11.2026).
 *
 * ОТКУДА. `auth.html?tab=register` открывал ВХОД. Две беды разом:
 * js/auth.js читал из адреса только `return` — обработчика `tab` не
 * было вовсе; и имена не совпадали — ссылка зовёт `register`, вкладка
 * внутри `signup`, так что даже с обработчиком по имени не сошлось бы.
 * Ссылку раздают шесть мест продукта: главная на трёх языках, кнопка
 * на закрытом турнире, карточка игрока для гостя, приглашение игрока.
 *
 * ЧТО СТОРОЖИТСЯ:
 *   1. адрес читается и по нему открывается вкладка;
 *   2. КАЖДОЕ имя, которым зовут ссылки продукта, словарь понимает —
 *      это и есть шов, на котором беда родилась;
 *   3. словарь ведёт только к вкладкам, которые есть в разметке;
 *   4. открываем нажатием самой вкладки, а не копией её работы.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, ' ');

const ошибки = [];
const правило = (имя, условие, почему) => { if (!условие) ошибки.push(имя + ' — ' + почему); };

const авт = безКом(чит('js/auth.js'));

/* Все места продукта, где дают ссылку с ?tab= — ищем, а не перечисляем:
   ПРАВИЛО СО СПИСКОМ СТОРОЖИТ СПИСОК, А НЕ ПРОДУКТ. */
function файлыПродукта(д, итог) {
    итог = итог || [];
    for (const э of fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true })) {
        const п = д ? д + '/' + э.name : э.name;
        if (/^(node_modules|\.git|test-results|builds|tests|tools|maket|mobile)$/.test(э.name)) continue;
        if (э.isDirectory()) файлыПродукта(п, итог);
        else if (/\.(js|html)$/.test(э.name)) итог.push(п);
    }
    return итог;
}
/* ТОЛЬКО ССЫЛКИ НА СТРАНИЦУ ВХОДА. Первая редакция ловила любое
   `?tab=` и упала на `?tab=men` в index-en.html — это вкладка рейтинга,
   чужое понятие с тем же именем параметра. Признак смотрит, что слева
   от вопроса стоит адрес входа: сам файл или переменная с ним. */
const зовут = new Map();
for (const ф of файлыПродукта('')) {
    for (const м of чит(ф).matchAll(/(.{0,60})\?tab=([a-zA-Z]+)/g)) {
        if (!/auth/i.test(м[1])) continue;
        if (!зовут.has(м[2])) зовут.set(м[2], ф);
    }
}

правило('страница входа читает имя вкладки из адреса',
    /params\.get\('tab'\)/.test(авт),
    'js/auth.js снова читает из адреса только `return`: ссылка на регистрацию\n' +
    'откроет вход, и так во всех шести местах, где её дают');

const словарь = (авт.match(/ИМЕНА_ВКЛАДОК\s*=\s*\{([\s\S]*?)\}/) || [, ''])[1];
const понимает = new Set([...словарь.matchAll(/(\w+)\s*:\s*'(\w+)'/g)].map(м => м[1]));
const кудаВедёт = [...словарь.matchAll(/(\w+)\s*:\s*'(\w+)'/g)].map(м => м[2]);

правило('словарь имён вкладок объявлен',
    понимает.size > 0,
    'в js/auth.js пропал словарь ИМЕНА_ВКЛАДОК — соответствие «слово в ссылке»\n' +
    '→ «вкладка внутри» снова будет разбросано по коду или исчезнет');

const непонятые = [...зовут.keys()].filter(и => !понимает.has(и.toLowerCase()));
правило('каждое имя из ссылок продукта понимается словарём',
    непонятые.length === 0,
    'ссылки зовут имена, которых словарь не знает: ' +
    непонятые.map(и => и + ' (' + зовут.get(и) + ')').join(', ') +
    '\n    именно на этом шве беда и родилась: ссылка звала register, вкладка — signup');

/* Куда словарь ведёт — должно существовать в разметке страницы входа. */
const размётка = чит('pages/auth.html');
const естьВкладки = [...размётка.matchAll(/data-tab="(\w+)"/g)].map(м => м[1]);
const вНикуда = [...new Set(кудаВедёт)].filter(в => естьВкладки.indexOf(в) === -1);
правило('словарь ведёт к вкладкам, которые есть в разметке',
    естьВкладки.length > 0 && вНикуда.length === 0,
    'словарь ведёт к вкладкам, которых на странице нет: ' + вНикуда.join(', ') +
    '\n    (в разметке есть: ' + естьВкладки.join(', ') + ')');

правило('вкладка открывается её же нажатием, а не копией её работы',
    /вкладкаИзАдреса[\s\S]{0,400}\.click\(\)/.test(авт),
    'открытие вкладки из адреса переписано своей копией: обработчик вкладок\n' +
    'умеет снять активность с прежней, показать форму и свернуть поля\n' +
    'регистрации — вторая копия разойдётся с ним на первой же правке');

if (ошибки.length) {
    console.error('ССЫЛКА НА ВКЛАДКУ — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
console.log('ссылка на вкладку: 5 правил держатся, имён в ссылках ' + зовут.size);
