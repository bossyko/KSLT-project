#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «СКЛАДКА — ЭТО `<details>`, И У НЕЁ ЕСТЬ СЧЁТ» (02.11).
 *
 * ЗАЧЕМ. Слово Кости о странице игрока: «достижения — надо раскрывашку
 * сделать, матчи тоже и в турнирах тоже». Три раздела подряд в десятки
 * строк каждый.
 *
 * ЧТО СТЕРЕЖЁТСЯ, И ЭТО НЕ «КРАСИВО»:
 *   · СВОРАЧИВАНИЕ ОСТАЁТСЯ НА `<details>`. Переписать его классом и
 *     слушателем легко и заманчиво — и тогда уходит всё, что даёт
 *     платформа: клавиатура, голос диктора «свёрнуто/развёрнуто» и
 *     работа без скрипта. Третье определение понятия, которое браузер
 *     уже знает.
 *   · У КАЖДОГО РАЗДЕЛА СТАВИТСЯ СЧЁТ. Свёрнутый раздел молчит о том,
 *     что внутри: пусто там или двадцать матчей, не видно, пока не
 *     нажмёшь. Складка без счёта хуже развёрнутого списка — она прячет
 *     и содержимое, и сам факт его наличия.
 *   · ШАПКА — ЦЕЛЬ НАЖАТИЯ 44.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ. Прибор читает код. Он не знает, свернётся ли
 * раздел на живом экране, и не заменяет ни тесты, ни глаза.
 *
 *   node tools/check-skladka.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ДОМ = 'mobile/www/js/kslt-skladka.js';
const ИГРОК = 'mobile/www/js/screens/player-detail.js';
const ОДЕЖДА = 'mobile/www/css/app.css';
/* Разделы, которые Костя назвал поимённо 02.11. */
const РАЗДЕЛЫ = ['pdMatches', 'pdTournaments', 'pdAchievements'];

function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function безКом(т) {
    return (т || '').replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');
}

const дом = безКом(чит(ДОМ));
const игрок = безКом(чит(ИГРОК));
const одежда = чит(ОДЕЖДА) || '';

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('сворачивание осталось на `<details>`',
    !!дом && /<details class="kslt-skladka/.test(дом) && /<summary class="kslt-skladka-shapka/.test(дом),
    'Дом `' + ДОМ + '` перестал строить `<details>/<summary>`.\n' +
    'Своё сворачивание классом и слушателем выглядит так же, но теряет\n' +
    'клавиатуру и голос диктора «свёрнуто/развёрнуто»: `aria-expanded`\n' +
    'руками ставят не везде, и первым это замечает тот, кто не видит\n' +
    'экрана. НЕ ИЗОБРЕТАТЬ ТО, ЧТО ЕСТЬ В ПЛАТФОРМЕ.');

правило('все три раздела игрока — складки',
    !!игрок && РАЗДЕЛЫ.every(id =>
        new RegExp("id:\\s*'" + id + "'").test(игрок)),
    'Раздел страницы игрока перестал быть складкой. Костя назвал три\n' +
    'поимённо: матчи, турниры, достижения (' + РАЗДЕЛЫ.join(', ') + ').\n' +
    'Каждый из них в десятки строк, и на телефоне человек прокручивает\n' +
    'мимо того, что ему сейчас не нужно.');

правило('у каждой складки ставится счёт',
    (function () {
        if (!игрок) return false;
        /* Четыре зова: матчи (пусто и полно), турниры (пусто и полно),
           достижения (пусто и дробь) — считаем, что их не меньше пяти. */
        const н = (игрок.match(/KSLT_SKLADKA\s*\.\s*счёт/g) || []).length;
        return н >= 5;
    })(),
    'Счёт ставится реже, чем есть веток с содержимым. Свёрнутый раздел\n' +
    'молчит о том, что внутри: ноль — такой же ответ, как двадцать, и\n' +
    'ради него не надо открывать. ПУСТАЯ ВЕТКА ТОЖЕ СТАВИТ СЧЁТ.');

правило('шапка складки — цель нажатия 44',
    /\.kslt-skladka-shapka\s*\{[^}]*min-height:\s*44px/.test(одежда),
    'У `.kslt-skladka-shapka` нет `min-height: 44px`. Шапка и есть то,\n' +
    'по чему нажимают, а 44 — нижняя граница цели нажатия и ступень\n' +
    'шкалы кнопок.');

правило('складка не путается с отсечкой',
    (function () {
        /* ДВА РАЗНЫХ ПОНЯТИЯ, И ОНИ НЕ ОДНО. Отсечка показывает первые
           десять строк («10 везде», слово Кости 06.10), складка прячет
           РАЗДЕЛ за заголовком. Дом складки не должен знать про
           `kslt-skryta` — иначе понятия начнут сливаться. */
        return !!дом && !/kslt-skryta|СТРОК_СРАЗУ/.test(дом);
    })(),
    'В доме складки появились признаки отсечки (`kslt-skryta`,\n' +
    '`СТРОК_СРАЗУ`). Это разные понятия: отсечка режет СПИСОК, складка\n' +
    'прячет РАЗДЕЛ. Складка может держать внутри отсечённый список — но\n' +
    'знать о нём ей незачем.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      складка: все ' + всего + ' правил держатся');
    console.log('          разделов на складке ' + РАЗДЕЛЫ.length + ', сворачивание на `<details>`');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  складка — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
