/** префиксы, стоящие в js перед склейкой: `class="ad-status-" + статус` */
function префиксыСклейки(к) {
    const из = [];
    for (let i = 0; i < к.length; i++) {
        if (к[i] !== '-') continue;
        const п = к.slice(0, i + 1);
        /* минимум два сегмента: 'ad-' ловит пол-админки и склеивает ID */
        if ((п.match(/-/g) || []).length >= 2) из.push(п);
    }
    return из.sort((a, b) => b.length - a.length);
}
function живётСклейкой(к) {
    return префиксыСклейки(к).some(п => {
        const э = п.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        return new RegExp("['\"`][^'\"`\\n]*" + э + "(?:\\$\\{|['\"`]\\s*\\+)").test(КОД);
    });
}
