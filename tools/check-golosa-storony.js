/**
 * ЗАМОРОЗКА ГОЛОСОВ ВЫЗОВА: ГОЛОС ПРИНАДЛЕЖИТ СТОРОНЕ, А НЕ ИГРОКУ.
 *
 * ЗАЧЕМ ЭТОТ КУСОК ВООБЩЕ ПОЯВИЛСЯ. `get_battle_votes` объявлена в проекте
 * ЧЕТЫРЬМЯ разными формами (battle-migration.sql:64 и schema-snapshot.sql:870
 * — `(player_id, votes)`; battle-external-players.sql:160 —
 * `(side, player_id, votes)`, она и живая; battle-vote-cleanup.sql:34 —
 * `(side, votes)`). Пять мест в коде читают эту функцию, и 09.10 ДВА из них
 * читали по игроку, а три — по стороне. ОДНО ПОНЯТИЕ, ДВА ПОВЕДЕНИЯ.
 *
 * Чем это стоило: «точность прогноза» на странице вызова показывала НОЛЬ при
 * любых голосах — ключа `player_id` в объекте, набранном по стороне, нет
 * вовсе. Беда родилась ровно на шве и жила молча: ошибки нет, просто ноль.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ, А НЕ ЧИСЛО: голос читается ТОЛЬКО по стороне,
 * и читается так во ВСЕХ пяти местах, а старой колонки в коде нет вовсе.
 * Пока это держится, sql/схема/battle-vote-cleanup.sql можно гонять: он
 * убирает `player_id` из формы, и код этого не заметит.
 *
 *   node tools/check-golosa-storony.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
/* КОММЕНТАРИИ СРЕЗАЕМ: в них самих названы и `player_id`, и
   `predicted_winner_id` — объяснение не должно ронять правило. */
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ЧИТАТЕЛИ = [
    ['js/admin/sections/challenges.js', 'админка «Вызовы»'],
    ['js/challenge-detail.js',          'страница вызова'],
    ['js/battles-overview.js',          'обзор вызовов'],
    ['js/battle-cards.js',              'плитки вызова'],
    ['mobile/www/js/screens/home.js',   'приложение, главная'],
];
const ТЕКСТЫ = ЧИТАТЕЛИ.map(([ф, имя]) => ({ имя, ф, т: безКом(чит(ф)) }));

let ВСЕГО = 0;
const ошибки = [];
function правило(имя, держит, подсказка) {
    ВСЕГО++;
    if (!держит) ошибки.push({ имя, подсказка });
}

правило('голос читается по стороне, а не по игроку',
    ТЕКСТЫ.every(({ т }) =>
        !/\[\s*v\.player_id\s*\]/.test(т) &&
        !/_votes\[\s*b\.(challenger|opponent)_player_id\s*\]/.test(т) &&
        !/vm\[\s*c\.(challenger|opponent)_player_id\s*\]/.test(т)),
    'До 09.10 так читали два места из пяти: js/admin/sections/challenges.js\n' +
    '          (голоса во «Вызовах») и js/challenge-detail.js (точность\n' +
    '          прогноза, показывала ноль всегда).');

правило('все пять мест наполняют голоса по стороне',
    ТЕКСТЫ.every(({ т }) => /\[\s*v\.side\s*\]\s*=\s*parseInt\(\s*v\.votes/.test(т)),
    'Наполнение и чтение обязаны ходить одним ключом. Если наполнять по\n' +
    '          стороне, а читать по чему-то ещё, объект молча отдаёт нули.');

правило('сторона — это 1 и 2, и ключ один на весь проект',
    /vm\[1\]/.test(ТЕКСТЫ[0].т) && /vm\[2\]/.test(ТЕКСТЫ[0].т) &&
    /_votes\[1\]/.test(ТЕКСТЫ[1].т) && /votes\[1\]/.test(ТЕКСТЫ[1].т) &&
    /votes\[1\]/.test(ТЕКСТЫ[4].т),
    '1 — вызвавший, 2 — соперник: так пишет cast_battle_vote и так считает\n' +
    '          get_battle_votes. Третьего значения у стороны не бывает.');

правило('старой колонки predicted_winner_id в коде нет вовсе',
    ТЕКСТЫ.every(({ т }) => !/predicted_winner_id/.test(т)),
    'Пока она встречается в коде, sql/схема/battle-vote-cleanup.sql гонять\n' +
    '          нельзя: он её удаляет из таблицы, и место чтения умрёт молча.');

if (ошибки.length === 0) {
    console.log(`\n  ок      голоса вызова: ${ВСЕГО} правил\n`);
    process.exit(0);
}
console.log(`\n  НЕ ТАК  голоса вызова: ${ВСЕГО} правил, упало ${ошибки.length}.\n`);
ошибки.forEach(о => {
    console.log(`  ✗ ${о.имя}`);
    if (о.подсказка) console.log(`          ${о.подсказка}`);
});
console.log('');
process.exit(1);
