#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «НАСТРОЙКИ БАЗЫ — ОДИН ДОМ» (30.10).
 *
 * ЗАМЕР ДО ПРАВКИ, ЧТЕНИЕМ. Адрес базы и публикуемый ключ стояли
 * литералами в ТРЁХ местах (`js/supabase-config.js`,
 * `mobile/www/js/supabase-config.js`, `js/auth-nav.js`), и у третьего
 * причина была подписана: шапка подключена ВЫШЕ конфига на 25 страницах
 * из 80 — посчитано, не на вид.
 *
 * А БЕДА ЖИЛА РЯДОМ. Из адреса выводится имя записи, в которой браузер
 * держит сессию (`sb-<проект>-auth-token`). Это имя было определено в
 * ПЯТИ местах, и только ОДНО считало его из адреса. Четыре зашиты
 * буквами на боевой проект:
 *   · `js/coaches.js:233`        — вошёл ли человек;
 *   · `js/players.js:69`         — вошёл ли человек;
 *   · `js/home-rankings.js:264`  — гость ли;
 *   · `js/session-monitor.js:23` — сторож простоя сессии.
 * Проверки подставляют ДРУГУЮ базу (`tests/fixtures.js`), значит эти
 * четыре читали запись боевого проекта, которой в прогоне нет, и
 * отвечали «гость» ВСЕГДА. Проверка смотрела гостевой вид, считая его
 * видом вошедшего, и молчала. В жизни то же случилось бы при переезде
 * на другой проект.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • дом объявлен ОДИН раз на копию, копии побайтово равны;
 *   • адрес, ключ и имя записи собираются ТОЛЬКО в доме;
 *   • подставленное `window.KSLT_DB` сильнее зашитого, и читает его
 *     один дом;
 *   • имя записи СЧИТАЕТСЯ из адреса, а не вписывается;
 *   • просроченный токен — это выход, а не вход;
 *   • закрытое хранилище даёт «не вошёл», а не падение;
 *   • дом подключён на каждой странице, где его зовут, и стоит раньше
 *     зовущих.
 *
 *   node tools/check-baza.js
 */
'use strict';
const fs = require('fs');
const path = require('path');
const { безКомментариев } = require('./bez-kommentariev.js');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = т => безКомментариев(т);

const ДОМ = 'js/kslt-baza.js';
const ДОМ_П = 'mobile/www/js/kslt-baza.js';
const дом = безКом(чит(ДОМ));

const ПРОПУСК = /^(node_modules|\.git|android|ios|build|test-results|playwright-report|slepki|_figma|tools|tests|maket)$/;
function всеJs(д, вых) {
    вых = вых || [];
    fs.readdirSync(path.join(КОРЕНЬ, д || '.'), { withFileTypes: true }).forEach(э => {
        const п = д ? д + '/' + э.name : э.name;
        if (э.isDirectory()) {
            if (!ПРОПУСК.test(э.name) && !э.name.startsWith('.')) всеJs(п, вых);
        } else if (э.name.endsWith('.js')) вых.push(п);
    });
    return вых;
}
const JS = всеJs('');

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

/* ══ 1. ДОМ ОДИН, И КОПИИ РАВНЫ ═════════════════════════════════════════ */

/* ПРИЗНАК СЧИТАЕТ ОБА НАПИСАНИЯ. Дом объявлен как `global.KSLT_BAZA`, а
   живой код пишут `window.KSLT_BAZA` — прибор обязан видеть и то и
   другое, иначе второй дом, заведённый вторым написанием, правило не
   уронит. Это уже стоило одной правки прувера на доме зова. */
const объявления = JS.filter(ф => /(?:global|window)\.KSLT_BAZA\s*=/.test(безКом(чит(ф))));
правило('дом настроек базы объявлен ровно один раз на продукт',
    объявления.length === 2 &&
    объявления.indexOf(ДОМ) !== -1 && объявления.indexOf(ДОМ_П) !== -1,
    'Объявлений: ' + объявления.length + ' — ' + объявления.join(', ') + '.\n' +
    'Две — это сайт и побайтовая копия приложения; третья означает, что\n' +
    'настройки базы снова живут двумя жизнями.');

правило('копии дома побайтово равны',
    чит(ДОМ) === чит(ДОМ_П),
    'Разошлись — и беда родится ровно на шве: один продукт пойдёт в\n' +
    'другую базу, а второй останется там, где был.');

/* ══ 2. АДРЕС, КЛЮЧ И ИМЯ ЗАПИСИ — ТОЛЬКО В ДОМЕ ════════════════════════ */

const вЖивом = (признак) => {
    const найдено = [];
    JS.forEach(ф => {
        const т = безКом(чит(ф));
        т.split('\n').forEach((с, i) => {
            if (признак.test(с)) найдено.push(ф + ':' + (i + 1));
        });
    });
    return найдено;
};

const адреса = вЖивом(/[a-z0-9]{15,}\.supabase\.co/);
правило('адрес базы написан буквами только в доме',
    адреса.length === 2 &&
    адреса.every(м => м.indexOf(ДОМ + ':') === 0 || м.indexOf(ДОМ_П + ':') === 0),
    'Мест: ' + адреса.length + ' — ' + адреса.join(', ') + '.\n' +
    'Два — по одному на копию дома. Третье означает, что адрес снова\n' +
    'вписан мимо настроек: подставят другую базу — это место останется\n' +
    'в боевой.\n' +
    'ПРИЗНАК СНИМАЕТ КОММЕНТАРИИ: адрес, названный в подписи (возвратный\n' +
    'адрес Apple в `js/supabase-config.js`), — это объяснение, а не код.');

const ключи = вЖивом(/sb_publishable_/);
правило('публикуемый ключ написан буквами только в доме',
    ключи.length === 2 &&
    ключи.every(м => м.indexOf(ДОМ + ':') === 0 || м.indexOf(ДОМ_П + ':') === 0),
    'Мест: ' + ключи.length + ' — ' + ключи.join(', ') + '.\n' +
    'Ключ публикуемый, тайны в нём нет — беда в том, что КОПИЯ ключа и\n' +
    'копия адреса разъезжаются по отдельности.');

const записи = вЖивом(/-auth-token/);
/* ДВА, А НЕ ОДНО — И ЭТО ПОПРАВКА К СЕБЕ, СДЕЛАННАЯ ПРУВЕРОМ СРАЗУ.
   Я написал правилу «ровно одно место» и подписал причину: мол, из
   приложения записи сессии никто не читает. Причина верная, а число
   неверное: копии дома ПОБАЙТОВО РАВНЫ, значит строка есть в обеих, и
   иначе было бы нельзя. ЧИСЛО БЕРЁТСЯ ИЗ ЗАМЕРА, А НЕ ИЗ РАССУЖДЕНИЯ. */
правило('имя записи с сессией собирается только в доме',
    записи.length === 2 &&
    записи.every(м => м.indexOf(ДОМ + ':') === 0 || м.indexOf(ДОМ_П + ':') === 0),
    'Мест: ' + записи.length + ' — ' + записи.join(', ') + '.\n' +
    'Два — по одному на копию дома, где имя СЧИТАЕТСЯ из адреса.\n' +
    'Третье место — это ровно та беда, что дала четыре точки,\n' +
    'отвечавших «гость» в каждом прогоне.');

правило('имя записи считается из адреса, а не вписывается',
    /API\.проект = function/.test(дом) &&
    /API\.адрес/.test(дом.slice(дом.indexOf('API.проект'))) &&
    /'sb-' \+ API\.проект\(\) \+ '-auth-token'/.test(дом),
    'Если имя записи перестанет выводиться из адреса, подстановка базы\n' +
    'снова разъедется с чтением сессии — и молча.');

const читаютПодстановку = JS.filter(ф => /KSLT_DB/.test(безКом(чит(ф))));
правило('подставленную базу читает один дом',
    читаютПодстановку.length === 2 &&
    читаютПодстановку.indexOf(ДОМ) !== -1 && читаютПодстановку.indexOf(ДОМ_П) !== -1,
    'Читают: ' + читаютПодстановку.join(', ') + '.\n' +
    'Каждое второе место, заглядывающее в `window.KSLT_DB`, решает\n' +
    'САМО, что делать, если подстановки нет, — и решает по-своему.');

/* ══ 3. ЧТО ДОМ ОБЕЩАЕТ ПРО СЕССИЮ ══════════════════════════════════════ */

правило('просроченный токен дом считает выходом',
    /expires_at > Math\.floor\(Date\.now\(\) \/ 1000\)/.test(дом),
    'Без сравнения со временем вчерашняя запись считалась бы входом:\n' +
    'человек видел бы своё меню, а любой запрос получал 401.');

правило('закрытое хранилище даёт «не вошёл», а не падение',
    /try \{[\s\S]*?localStorage[\s\S]*?catch/.test(дом),
    'Хранилище бывает закрыто настройками браузера, а запись —\n' +
    'испорченной. Бросок отсюда уронил бы шапку целиком: человек\n' +
    'остался бы без меню и без кнопки «Войти».');

правило('дом не знает ни одного слова для человека',
    !/[А-Яа-я]{3,}['"]/.test(дом.replace(/API\.\w+/g, '')) ||
    !/(Войти|Вход|Гость|ошибка)/.test(дом),
    'Дом отдаёт ДАННЫЕ. Надпись здесь означала бы, что он начал решать\n' +
    'за экран, — и перевод на три языка пришлось бы искать в доме.');

/* ══ 4. ЗОВУЩИЕ НЕ ДЕРЖАТ СВОЕЙ КОПИИ ═══════════════════════════════════ */

const конфиг = безКом(чит('js/supabase-config.js'));
const конфигП = безКом(чит('mobile/www/js/supabase-config.js'));
правило('оба конфига берут адрес и ключ у дома',
    /SUPABASE_URL = window\.KSLT_BAZA\.адрес/.test(конфиг) &&
    /SUPABASE_ANON_KEY = window\.KSLT_BAZA\.ключ/.test(конфиг) &&
    /SUPABASE_URL = window\.KSLT_BAZA\.адрес/.test(конфигП) &&
    /SUPABASE_ANON_KEY = window\.KSLT_BAZA\.ключ/.test(конфигП),
    'Имена `SUPABASE_URL` и `SUPABASE_ANON_KEY` оставлены для SDK и\n' +
    'десятков файлов, но ЗНАЧЕНИЕ приходит из дома. Своё `||` здесь —\n' +
    'это второе правило о том, что делать без подстановки.');

const шапка = безКом(чит('js/auth-nav.js'));
правило('шапка берёт настройки у дома и своего имени записи не считает',
    /DB_URL = window\.KSLT_BAZA\.адрес/.test(шапка) &&
    /DB_KEY = window\.KSLT_BAZA\.ключ/.test(шапка) &&
    /KSLT_BAZA\.запись\(\)/.test(шапка) &&
    !/DB_REF/.test(шапка),
    'Шапка — единственная, кому дом НУЖЕН раньше конфига: она читает\n' +
    'сессию на загрузке, а конфиг на 25 страницах из 80 идёт позже неё.\n' +
    'Именно поэтому дом отдельным файлом и первым тегом.');

const ЧИТАТЕЛИ = [
    ['js/coaches.js', /KSLT_BAZA\.вошёл\(\)/],
    ['js/players.js', /KSLT_BAZA\.вошёл\(\)/],
    ['js/home-rankings.js', /KSLT_BAZA\.гость\(\)/],
    ['js/session-monitor.js', /KSLT_BAZA\.имяЗаписи\(\)/]
];
const своиРазборы = ЧИТАТЕЛИ.filter(([ф, п]) => {
    const т = безКом(чит(ф));
    return !п.test(т) || /localStorage\.getItem\(\s*['"]sb-/.test(т);
}).map(([ф]) => ф);
правило('четыре места про вход спрашивают дом, а не разбирают запись сами',
    своиРазборы.length === 0,
    'Со своим разбором: ' + своиРазборы.join(', ') + '.\n' +
    'Это те самые четыре места, что отвечали «гость» в каждом прогоне.\n' +
    'Своя копия здесь не «некрасиво», а неверный ответ.');

правило('сторож простоя спрашивает имя записи функцией, а не на загрузке',
    /function записьСессии\(\) \{ return window\.KSLT_BAZA\.имяЗаписи\(\); \}/
        .test(безКом(чит('js/session-monitor.js'))),
    'Этот файл на 24 страницах из 59 подключён выше дома зова: порядок\n' +
    'тегов здесь не ровен. Значение, посчитанное на загрузке, рискует\n' +
    'спросить дом раньше, чем тот появится; функция спросит вовремя.');

/* ══ 5. ДОМ ДОЕЗЖАЕТ ДО СТРАНИЦ И СТОИТ РАНЬШЕ ЗОВУЩИХ ══════════════════ */

/* ЗОВУЩИЕ ЧИТАЮТСЯ ИЗ КОДА, А НЕ ПЕРЕЧИСЛЯЮТСЯ: перечень устарел бы на
   следующем куске, и правило молча ослабло бы. */
const зовущие = JS.filter(ф => ф !== ДОМ && ф !== ДОМ_П &&
    /KSLT_BAZA\./.test(безКом(чит(ф)))).map(ф => ф.split('/').pop());
const имяДома = 'kslt-baza.js';

function всеHtml(д, вых) {
    вых = вых || [];
    fs.readdirSync(path.join(КОРЕНЬ, д || '.'), { withFileTypes: true }).forEach(э => {
        const п = д ? д + '/' + э.name : э.name;
        if (э.isDirectory()) {
            if (!/^(node_modules|\.git|android|ios|build|test-results|playwright-report|slepki|_figma)$/.test(э.name)
                && !э.name.startsWith('.')) всеHtml(п, вых);
        } else if (э.name.endsWith('.html')) вых.push(п);
    });
    return вых;
}
const теги = с => (с.match(/<script[^>]+src="[^"]+"/g) || [])
    .map(т => (т.match(/src="([^"]+)"/) || ['', ''])[1].split('?')[0].split('/').pop());

const безДома = [], позже = [], дважды = [];
всеHtml('').forEach(с => {
    const и = теги(чит(с));
    const свои = и.map((н, i) => ({ н, i })).filter(x => зовущие.indexOf(x.н) !== -1);
    if (!свои.length) return;
    const д = и.indexOf(имяДома);
    if (д === -1) { безДома.push(с); return; }
    if (и.filter(н => н === имяДома).length > 1) дважды.push(с);
    if (д > свои[0].i) позже.push(с + ' (дом ' + д + ', зовущий ' + свои[0].i + ')');
});

правило('дом подключён на каждой странице, где его зовут',
    безДома.length === 0,
    'страниц без дома: ' + безДома.length + ' — ' + безДома.slice(0, 5).join(', ') +
    '.\nБез него первая же страница упадёт на `KSLT_BAZA is not defined`\n' +
    'ещё в конфиге — то есть не загрузится вовсе.');

правило('дом стоит раньше своих зовущих',
    позже.length === 0,
    'позже зовущего: ' + позже.slice(0, 5).join(', ') + '.\n' +
    'Скрипт выше выполняется раньше. Дом ни от чего не зависит — его\n' +
    'место первым безопасно, и только там он успевает.');

правило('дом подключён ровно одним тегом на страницу',
    дважды.length === 0,
    'дважды: ' + дважды.slice(0, 5).join(', ') + '.\n' +
    'Второе выполнение перезаписало бы `KSLT_BAZA` новым объектом уже\n' +
    'после того, как конфиг взял из него значения.');

/* ───────── вывод ───────── */
console.log('');
if (!ошибки.length) {
    console.log('  ок      настройки базы: все ' +
        (fs.readFileSync(__filename, 'utf8').match(/правило\('/g) || []).length +
        ' правил держатся');
    console.log('          адрес и ключ буквами: 2 места (по одному на копию дома)');
    console.log('          имя записи с сессией: 2 места (по копии дома), считается из адреса');
    console.log('          страниц с домом: ' + всеHtml('').filter(с => теги(чит(с)).indexOf(имяДома) !== -1).length);
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  настройки базы — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
