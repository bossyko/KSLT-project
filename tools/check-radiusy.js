/**
 * РАДИУСЫ — СТОРОЖ НА ВЕСЬ ПРОДУКТ (ветка D, круг 6, 17.10).
 *
 * ПОЧЕМУ ОТДЕЛЬНО ОТ ОТСТУПОВ. Храповик админки считал `border-radius`
 * вместе с `padding` и `margin` — и 38 из «261 отступа мимо шкалы»
 * оказались радиусами. У радиуса СВОЯ шкала (2 · 4 · 8 · 12 · 16 · 24 ·
 * 32 и полное скругление), и мерить его шкалой отступов — всё равно что
 * мерить кегль отступом: число совпадёт, смысл нет.
 *
 * ЧТО НАШЁЛ ЗАМЕР 17.10. Восемь мест из 38 были НЕ числом, а КАПСУЛОЙ,
 * записанной числом: полоса высотой 4 с радиусом 2, высотой 6 с радиусом
 * 3, счётчик высотой 20 с радиусом 10, высотой 18 с радиусом 9 — доля
 * радиуса от высоты ровно 0.5 во всех случаях (замер в браузере). Плюс
 * три бейджа, у которых высота не объявлена: замер дал 20.5 и 22 при
 * радиусе 10, то есть на экране это тоже капсула.
 * ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ: капсула зовётся `--radius-full`, а не
 * половиной высоты. Поменяется кегль — половина уедет, имя нет.
 *
 * ХРАПОВИК ДЛЯ ТОГО, ЧТО ЕЩЁ НЕ ЧИЩЕНО. Админка держит НОЛЬ жёстко;
 * публичная часть — 62 места, и это потолок, который только падает.
 * Правило, смотрящее часть продукта, не сторожит ничего: поставь я его
 * на один `admin.css`, беда осталась бы в `dashboard.css` и в js.
 *
 *   node tools/check-radiusy.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}
/* МАСКА ОБЯЗАНА СОХРАНЯТЬ ПЕРЕВОДЫ СТРОК. Замена комментария на строку
   пробелов той же ДЛИНЫ схлопывает многострочный комментарий в одну
   строку, и вся нумерация едет — на этом прибор соврал номерами 17.10. */
function безКом(т) {
    return т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));
}

const ШКАЛА = new Set(['0', '0px', '2px', '4px', '8px', '12px', '16px', '24px', '32px', '100px']);
/* ПЕЧАТЬ НЕ СЧИТАЕТСЯ, И ЭТО НАЙДЕНО ЗАМЕРОМ: окно отчёта открывается
   без `tokens.css`, у листа бумаги своя мера. Три `.stat-box` в
   finances, users и vouchers. */
const ПЕЧАТЬ = /\.stat-box|@media print|\.report-|@page/;

function файлы(каталог, расш, собранное) {
    собранное = собранное || [];
    fs.readdirSync(path.join(КОРЕНЬ, каталог), { withFileTypes: true }).forEach(э => {
        const п = каталог + '/' + э.name;
        if (э.isDirectory()) файлы(п, расш, собранное);
        else if (расш.some(р => э.name.endsWith(р))) собранное.push(п);
    });
    return собранное;
}

function считать(списокФайлов) {
    let всего = 0;
    const места = [];
    списокФайлов.forEach(ф => {
        const текст = безКом(fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'));
        текст.split('\n').forEach((с, i) => {
            if (ПЕЧАТЬ.test(с)) return;
            let m;
            const re = /border-radius\s*:\s*([^;}"']+)/g;
            while ((m = re.exec(с))) {
                m[1].split(/\s+/).forEach(ч => {
                    if (/^\d+(\.\d+)?px$/.test(ч) && !ШКАЛА.has(ч)) {
                        всего++; места.push(ф + ':' + (i + 1) + '  ' + ч);
                    }
                });
            }
        });
    });
    return { всего, места };
}

/* ---- 1. ШКАЛА ОБЪЯВЛЕНА ЦЕЛИКОМ ---- */
const ТОКЕНЫ = fs.readFileSync(path.join(КОРЕНЬ, 'css/tokens.css'), 'utf8');
const ступени = { '2xs': 2, 'xs': 4, 'sm': 8, 'md': 12, 'lg': 16, 'xl': 24, '2xl': 32 };
const нет = [];
Object.keys(ступени).forEach(имя => {
    const m = ТОКЕНЫ.match(new RegExp('--radius-' + имя + '\\s*:\\s*(\\d+)px'));
    if (!m) nетДобавить(имя);
    else if (Number(m[1]) !== ступени[имя]) нет.push('--radius-' + имя + ' = ' + m[1] + ', ждали ' + ступени[имя]);
    function nетДобавить(и) { нет.push('--radius-' + и + ' не объявлен'); }
});
if (!/--radius-full\s*:/.test(ТОКЕНЫ)) нет.push('--radius-full не объявлен');
правило('шкала радиусов объявлена целиком: 2 · 4 · 8 · 12 · 16 · 24 · 32 и полное',
    нет.length === 0,
    нет.join('\n') + '\n' +
    'Пропущенная ступень — это место, где следующий раз напишут число:\n' +
    'ступени 2 не было, и микро-элементы держали радиус числом.');

/* ---- 2. АДМИНКА — НОЛЬ, ЖЁСТКО ---- */
const адм = считать(['css/admin.css'].concat(файлы('js/admin', ['.js'])));
правило('в слое админки нет радиуса мимо шкалы',
    адм.всего === 0,
    'Радиусов мимо шкалы: ' + адм.всего + ', держим ноль.\n' +
    адм.места.slice(0, 8).join('\n') + '\n' +
    'Радиус зовётся ступенью: var(--radius-2xs | xs | sm | md | lg | xl | 2xl | full).');

/* ---- 3. ОСТАЛЬНОЙ ПРОДУКТ — ХРАПОВИК ---- */
const остальные = файлы('css', ['.css']).filter(ф => ф !== 'css/admin.css')
    .concat(файлы('js', ['.js']).filter(ф => !ф.startsWith('js/admin/')));
const пуб = считать(остальные);
const ПОТОЛОК = 62;   /* ЗАМЕРЕНО 17.10 ЭТИМ ЖЕ ПРИБОРОМ. Только вниз. */
правило('радиусов мимо шкалы в остальном продукте не больше потолка',
    пуб.всего <= ПОТОЛОК,
    'Радиусов мимо шкалы: ' + пуб.всего + ', потолок ' + ПОТОЛОК + '.\n' +
    пуб.места.slice(0, 8).join('\n') + '\n' +
    'Публичная часть ждёт своего круга; число только убывает.');

/* ---- 4. КАПСУЛА ЗОВЁТСЯ ИМЕНЕМ, А НЕ ПОЛОВИНОЙ ВЫСОТЫ ---- */
const капсулы = [];
['css/admin.css'].concat(остальные.filter(ф => ф.endsWith('.css'))).forEach(ф => {
    const текст = безКом(fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'));
    /* блок целиком: от селектора до закрывающей скобки */
    const re = /([^{}]+)\{([^{}]*)\}/g;
    let m;
    while ((m = re.exec(текст))) {
        const тело = m[2];
        const в = тело.match(/(?<![-\w])height\s*:\s*(\d+(?:\.\d+)?)px/);
        const р = тело.match(/border-radius\s*:\s*(\d+(?:\.\d+)?)px/);
        if (в && р) {
            const высота = Number(в[1]), радиус = Number(р[1]);
            if (Math.abs(радиус - высота / 2) < 0.51 && высота > 0) {
                капсулы.push(ф + ': ' + m[1].trim().split('\n').pop().trim().slice(0, 40) +
                    ' — высота ' + высота + ', радиус ' + радиус);
            }
        }
    }
});
const капсулыАдм = капсулы.filter(с => с.indexOf('css/admin.css') === 0);
правило('в админке капсула зовётся --radius-full, а не половиной высоты',
    капсулыАдм.length === 0,
    капсулыАдм.join('\n') + '\n' +
    'Радиус в половину высоты — это полное скругление, записанное числом.\n' +
    'Поменяется высота или кегль — половина уедет, а имя нет.');

/* ХРАПОВИК ПО КАПСУЛАМ В ПУБЛИЧНОЙ ЧАСТИ. Их девять, и все — полосы
   голосования и прогресса (высота 6 и 7 при радиусе 3 и 4), точка
   уведомления 16 с радиусом 8 и полоса предсказания 18 с радиусом 9.
   Вид при переводе на имя НЕ меняется — это проверено замером доли
   радиуса от высоты (ровно 0.5), — но чинить их значит трогать ветку C
   и гонять её пробы. Находка записана в трекер, число заморожено. */
const ПОТОЛОК_КАПСУЛ = 9;
правило('капсул, записанных числом, в остальном продукте не больше потолка',
    капсулы.length - капсулыАдм.length <= ПОТОЛОК_КАПСУЛ,
    (капсулы.length - капсулыАдм.length) + ' при потолке ' + ПОТОЛОК_КАПСУЛ + ':\n' +
    капсулы.filter(с => с.indexOf('css/admin.css') !== 0).slice(0, 10).join('\n'));

if (!ошибки.length) {
    console.log('\n  ок      радиусы: 5 правил');
    console.log('          шкала 2 · 4 · 8 · 12 · 16 · 24 · 32 и полное');
    console.log('          админка ' + адм.всего + ' мимо шкалы, остальной продукт ' +
        пуб.всего + '/' + ПОТОЛОК);
    console.log('          капсул числом: админка ' + капсулыАдм.length + ', остальное ' +
        (капсулы.length - капсулыАдм.length) + '/' + ПОТОЛОК_КАПСУЛ + '\n');
    process.exit(0);
}
console.log('\n  УПАЛО: ' + ошибки.length + '\n');
ошибки.forEach(о => console.log('  x  ' + о.имя + '\n     ' + о.подсказка.replace(/\n/g, '\n     ') + '\n'));
process.exit(1);
