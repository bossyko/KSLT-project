const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const читать = п => fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8');
/* css без пояснений: иначе правило падает на собственном комментарии —
   на этом я попадался 16.10 и 17.10. */
const безПояснений = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

const admin = безПояснений(читать('css/admin.css'));
const style = безПояснений(читать('css/style.css'));
const bracket = читать('js/admin/sections/bracket.js');
const doubles = читать('js/doubles-entry.js');
const reg = читать('js/tournament-register.js');

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

/* ── все js продукта: ищем вписывание css строкой ───────────────────── */
const ФАЙЛЫ = [];
(function обойти(д) {
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) {
            if (/node_modules|\.git|tests|mobile|_sync|dist|build|razovye/.test(э.name)) return;
            обойти(п);
        } else if (э.name.endsWith('.js')) ФАЙЛЫ.push(п);
    });
})('js');

const вписывают = [];
ФАЙЛЫ.forEach(ф => {
    const т = читать(ф);
    if (/createElement\(\s*['"]style['"]\s*\)/.test(т)) вписывают.push(ф);
    /* второй путь к тому же: вставка тега <style> разметкой */
    if (/innerHTML\s*[+]?=\s*['"`]\s*<style/.test(т)) вписывают.push(ф + ' (через innerHTML)');
});

правило('ни один js не вписывает css строкой',
    вписывают.length === 0,
    'Вписывают css из js: ' + вписывают.join(', ') + '\n' +
    'ПРАВИЛО В СТРОКЕ JS НЕ ЧИТАЕТ НИ ОДИН СТОРОЖ. Сторож инлайнов смотрит\n' +
    'style="…" и cssText; сторожа красок, прозрачностей, межстрочных и шкал\n' +
    'читают css. Вид, уехавший в строку js, выпадает из всех проверок — и\n' +
    'приезжает он лишь тогда, когда js до этой строки доберётся.');

/* ── окно ввода счёта: правила в css, ни одного !important ──────────── */
const чипВCss = /\.ad-outcome-chip\s*\{/.test(admin);
const чипВкл = /\.ad-outcome-chip\.active\s*\{/.test(admin);
const чипФокус = /\.ad-outcome-chip:focus-visible\s*\{/.test(admin);
правило('правила чипов исхода живут в css',
    чипВCss && чипВкл && чипФокус,
    'В `css/admin.css` нет полного набора: сам чип ' + чипВCss +
    ', включённый ' + чипВкл + ', видимый фокус ' + чипФокус + '.\n' +
    'До куска 174 все три приезжали строкой из `bracket.js`, и фокуса\n' +
    'с клавиатуры у чипа не было вовсе.');

const блокЧипов = (admin.match(/\.ad-outcome-chip[\s\S]*?\.ad-btn\.ad-retired-btn\.active[\s\S]*?\}/) || [''])[0];
правило('вид чипов и кнопки выбывшего обходится без !important',
    !/!important/.test(блокЧипов),
    '`!important` вернулся в правила окна счёта. Их было три — все на\n' +
    '`.ad-retired-btn.active`, и были они подпоркой под слабый селектор.\n' +
    'ТОЧНОСТЬ ВМЕСТО СИЛЫ: три класса (.ad-btn.ad-retired-btn.active)\n' +
    'перевешивают два (.ad-btn-secondary) без восклицательного знака.');

правило('переход чипа перечисляет свойства, а не `all`',
    !/\.ad-outcome-chip\s*\{[^}]*transition:\s*all/.test(admin),
    '`transition: all` в чипе исхода. `all` гоняет и те свойства, что\n' +
    'меняются при пересчёте вида, а замер внутри перехода возвращает\n' +
    'старое значение — на этом врёт замер «сжатым окном».');

/* ── пометка исхода: ОДНО определение, и вид не зависит от окна ─────── */
const пометкаВCss = (admin.match(/\.ad-brk-outcome\s*\{[^}]*\}/g) || []);
правило('пометка исхода определена один раз',
    пометкаВCss.length === 1,
    'Правил `.ad-brk-outcome` в css: ' + пометкаВCss.length + ', нужно одно.\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ — беда родится ровно на шве.');

правило('пометка исхода не описана в js',
    !/ad-brk-outcome\s*\{/.test(bracket),
    'В `bracket.js` снова есть правило `.ad-brk-outcome{…}`. Это второе\n' +
    'определение, и приезжает оно только после первого открытия окна\n' +
    'счёта: до него пометка в сетке — обычный белый текст без подложки.');

правило('пометка исхода несёт и положение, и вид',
    /\.ad-brk-outcome\s*\{[^}]*position:\s*absolute[^}]*\}/.test(admin) &&
    /\.ad-brk-outcome\s*\{[^}]*background:\s*var\(--accent-subtle\)[^}]*\}/.test(admin) &&
    /\.ad-brk-outcome\s*\{[^}]*color:\s*var\(--accent\)[^}]*\}/.test(admin),
    'Единственное правило пометки потеряло часть: в нём должны быть и\n' +
    'намеренное положение (absolute — «пишем поверх строки счёта, иначе\n' +
    'блок с W/O выше остальных»), и вид, который до 26.10 приезжал из js.');

/* ── чипы говорят состояние диктору ────────────────────────────────── */
const чиповВРазметке = (bracket.match(/class="ad-outcome-chip/g) || []).length;
const арийВРазметке = (bracket.match(/aria-pressed=/g) || []).length;
правило('каждый чип исхода говорит состояние диктору',
    чиповВРазметке > 0 && арийВРазметке >= чиповВРазметке,
    'Чипов в разметке ' + чиповВРазметке + ', aria-pressed ' + арийВРазметке + '.\n' +
    'КЛАСС КРАСИТ, aria-pressed ПРОИЗНОСИТ. Без него диктор читает пять\n' +
    'обычных кнопок, а не переключатель с выбранным значением.');

правило('состояние для диктора меняется вместе с классом',
    /classList\.add\('active'\);\s*\n\s*chip\.setAttribute\('aria-pressed', 'true'\)/.test(bracket),
    'Класс `active` навешивается без `aria-pressed`. Два написания одного\n' +
    'состояния разъедутся на первой же правке.');

/* ── цель нажатия чипа — ступень шкалы, и 44 на узком виде ─────────── */
правило('высота чипа — ступень шкалы кнопок',
    /\.ad-outcome-chip\s*\{[^}]*min-height:\s*var\(--btn-h-xs\)/.test(admin),
    'Высота чипа задана не ступенью шкалы кнопок (28 · 36 · 44 · 52).\n' +
    'До куска 174 чип был 27 — не ступень вовсе, и цель нажатия, МЕРЕНАЯ\n' +
    'ПОПАДАНИЕМ, давала 2 точки из 6.');

правило('на узком виде чип дорастает до цели 44',
    /@media \(max-width: 640px\)\s*\{\s*\.ad-outcome-chip\s*\{\s*min-height:\s*var\(--btn-h-md\)/.test(admin),
    'Нет медиа ≤640, поднимающего чип до --btn-h-md (44). На телефоне\n' +
    '28 мало: планка цели нажатия 44, и мерится она попаданием.');

/* ── два публичных окна: правила в css, функция вида пуста ─────────── */
правило('правила окна парной заявки живут в css',
    /^\.de-overlay\s*\{/m.test(style) && /^\.de-modal\s*\{/m.test(style) &&
    /^\.de-switch button\s*\{/m.test(style) && /^\.de-input\s*\{/m.test(style),
    'В `css/style.css` нет правил окна парной заявки. Они жили строкой в\n' +
    '`doubles-entry.js` — 33 правила, которых не читал ни один сторож.');

/* СЕЛЕКТОР ИЩЕТСЯ С НАЧАЛА СТРОКИ: `.trn-register-modal {` встречается и
   внутри составного `.trn-register-modal-overlay.active .trn-register-modal {`,
   и первая редакция правила принимала составной за своё. Поймал прувер. */
правило('правила окна записи живут в css',
    /^\.trn-register-modal\s*\{/m.test(style) &&
    /^\.trn-register-modal-overlay\s*\{/m.test(style) &&
    /^\.trn-register-modal-btn\s*\{/m.test(style),
    'В `css/style.css` нет правил окна «войдите, чтобы записаться».\n' +
    'Они жили строкой в `tournament-register.js` — 17 правил.');

правило('функции вида в обоих окнах пусты',
    /function стили\(\)\s*\{\}/.test(doubles) && /function injectStyles\(\)\s*\{\}/.test(reg),
    'Функция, вписывающая стили, снова что-то делает. Зов оставлен пустым\n' +
    'телом НАМЕРЕННО: он стоит в четырёх местах двух файлов, и пустое тело —\n' +
    'ОДИН шов вместо четырёх правок.');

/* ── в переехавших блоках: ни чисел мимо шкалы, ни запасных значений ── */
function блок(css, от, до) {
    const н = css.indexOf(от);
    const к = css.indexOf(до, н);
    return (н === -1 || к === -1) ? '' : css.slice(н, к);
}
/* ГРАНИЦЫ БЛОКА БЕРУТСЯ ПО КОДУ, А НЕ ПО ПОЯСНЕНИЮ: css читается с
   вымаранными комментариями, и маркер-комментарий тут не найдётся —
   на этом прибор соврал с первого прогона. */
const переехало = (function () {
    const н = style.indexOf('.trn-register-modal-overlay {');
    const х = style.indexOf('.de-bad-note {');
    if (н === -1 || х === -1) return '';
    const к = style.indexOf('}', х);
    return style.slice(н, к + 1);
})();

const запасные = (переехало.match(/var\(--[a-z0-9-]+\s*,\s*(#[0-9a-fA-F]{3,8}|rgba?\()/g) || []);
правило('в переехавших окнах нет запасных значений у токенов',
    запасные.length === 0,
    'Запасных значений: ' + запасные.length + ' — ' + запасные.slice(0, 4).join(', ') + '\n' +
    'ЗАПАСНОЕ ЧИСЛО ЖИВЁТ СВОЕЙ ЖИЗНЬЮ: `var(--text-dim,#888)` красит #888\n' +
    'там, где токен не доехал, и ни один сторож красок про это не знает.\n' +
    'Токен или есть, или беда видна сразу.');

const ШКАЛА_ОТСТУПОВ = new Set(['0', '0px', '4px', '8px', '12px', '16px', '24px', '32px', '40px']);
const отступыЧислом = [];
переехало.replace(/(padding|margin|gap|row-gap|column-gap)(-top|-bottom|-left|-right)?:\s*([^;]+);/g,
    (м, _1, _2, знач) => {
        знач.split(/\s+/).forEach(ч => {
            if (/^\d+(\.\d+)?px$/.test(ч) && !ШКАЛА_ОТСТУПОВ.has(ч)) отступыЧислом.push(м.trim());
        });
        return м;
    });
правило('отступы переехавших окон — ступени шкалы',
    отступыЧислом.length === 0,
    'Отступов мимо шкалы 8 · 12 · 16 · 24 · 32 · 40: ' + отступыЧислом.length + '\n  ' +
    отступыЧислом.slice(0, 5).join('\n  ') + '\n' +
    'В строках js их было 19, считая 10px девять раз.');

const кеглиЧислом = (переехало.match(/font-size:\s*(\d|\.)/g) || []);
правило('кегли переехавших окон — токены шкалы, а не числа',
    кеглиЧислом.length === 0,
    'Кеглей числом: ' + кеглиЧислом.length + '. В строках js их было 16, и\n' +
    'почти все в rem: .72rem, .82rem, .9rem, 1.15rem, 2.4rem — шкала\n' +
    'кеглей 11 · 12 · 14 · 16 · 18 · 21 · 26 · 32 · 40 этих значений не знает.');

правило('поле ввода не мельче 16',
    /\.de-input\s*\{[^}]*font-size:\s*var\(--input-fs\)/.test(style),
    'Кегль поля задан не `--input-fs` (16). НИЖЕ 16 SAFARI НА iOS ЗУМИТ\n' +
    'СТРАНИЦУ ПРИ ФОКУСЕ — в строке js кегль не задавался вовсе, и поле\n' +
    'рисовалось браузерным 13.33.');

правило('поле ввода и кнопки окон — ступень 44',
    /\.de-input\s*\{[^}]*min-height:\s*var\(--input-h\)/.test(style) &&
    /\.de-btn\s*\{[^}]*min-height:\s*var\(--btn-h-md\)/.test(style) &&
    /\.trn-register-modal-btn\s*\{[^}]*min-height:\s*var\(--btn-h-md\)/.test(style),
    'Высоты полей и кнопок переехавших окон не на ступени 44. Было: поле\n' +
    '38, кнопки 40 — и цель, МЕРЕНАЯ ПОПАДАНИЕМ, давала 4 и 5 точек из 6.');

