/* СЛОЙ ИЩЕТСЯ ПО УСЛОВИЮ И ПО СОДЕРЖИМОМУ. Одно условие встречается в файле
   несколько раз: @media (max-width: 900px) есть и у блока спонсорского
   предложения, а условие ленты — и у турниров, и у новостей. indexOf брал
   первое попавшееся, и семь правил падали на исправном коде.
   Пятый случай за два дня, когда якорь держался на положении, а не на
   содержании. Поэтому берём тот блок, внутри которого есть нужный селектор. */
function слой(условие, маркер) {
    let i = -1;
    while ((i = СТИ.indexOf('@media ' + условие, i + 1)) !== -1) {
        const j = СТИ.indexOf('@media ', i + 7);
        const кусок = СТИ.slice(i, j === -1 ? СТИ.length : j);
        if (!маркер || кусок.indexOf(маркер) !== -1) return кусок;
    }
    return null;
}
/* блок по селектору, С ЯКОРЕМ НА НАЧАЛО СТРОКИ: '.hn-card {' встречается и
   как '.hn-grid .hn-card {'. На этих граблях за два дня наступали четырежды. */
function блок(сел) {
    const м = СТИ.match(new RegExp('(?:^|\\n)' + сел.replace(/\./g, '\\.') + '\\s*\\{[^}]*\\}'));
    return м ? м[0] : null;
}
const свойство = (т, имя) => {
    if (!т) return null;
    const м = т.match(new RegExp('(?:^|\\n)\\s*' + имя + ':\\s*([^;]+);'));
    return м ? м[1].trim() : null;
};

