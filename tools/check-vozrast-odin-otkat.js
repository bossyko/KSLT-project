/**
 * ДОКАЗАТЕЛЬСТВО СТОРОЖА ВОЗРАСТА (кусок 189). На КОПИИ.
 *   node tools/check-vozrast-odin-otkat.js
 *
 * «У МЕНЯ ЗЕЛЁНОЕ» НИЧЕГО НЕ ДОКАЗЫВАЕТ. Каждый откат возвращает ОДНО
 * прежнее значение и обязан уронить ИМЕННО то правило, которое за него
 * отвечает. Три из пяти откатов возвращают ровно те числа, что стояли в
 * документах до 27.10: 14 в русских Условиях, 13 в английских, 13 в
 * кыргызских.
 */
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');

const КОРЕНЬ = path.join(__dirname, '..');
const песок = fs.mkdtempSync(path.join(os.tmpdir(), 'kslt-vozrast-'));
['pages', 'tools', 'mobile'].forEach(д =>
    fs.cpSync(path.join(КОРЕНЬ, д), path.join(песок, д), { recursive: true }));

const RU = 'pages/terms.html', EN = 'pages/terms-en.html', KG = 'pages/terms-kg.html',
      OFF = 'pages/offer.html', МОБ = 'mobile/www/index.html';
const ФАЙЛЫ = [RU, EN, KG, OFF, МОБ];
const исходник = {};
ФАЙЛЫ.forEach(ф => { исходник[ф] = fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8'); });

/* ОТКАТ МОЖЕТ ТРОГАТЬ НЕСКОЛЬКО ФАЙЛОВ (07.11). Правило «возраст
   совпадает с решением» падает только тогда, когда число уехало ВЕЗДЕ:
   поменяй один документ — упадёт соседнее правило, про одинаковость.
   Прежний откат на это и наткнулся: ему передавали `null`, то есть он
   не менял ничего и уронить ничего не мог. ОТКАТ, КОТОРЫЙ НЕ ПРИМЕНИЛСЯ,
   НИЧЕГО НЕ ДОКАЗАЛ. Теперь правка — это список троек. */
function прогон(правка) {
    const список = !правка ? [] : (Array.isArray(правка[0]) ? правка : [правка]);
    ФАЙЛЫ.forEach(ф => {
        let т = исходник[ф];
        список.forEach(п => { if (п[0] === ф) т = т.replace(п[1], п[2]); });
        fs.writeFileSync(path.join(песок, ф), т);
    });
    try {
        execFileSync(process.execPath,
            [path.join(песок, 'tools', 'check-vozrast-odin.js')], { encoding: 'utf8' });
        return { упало: false, вывод: '' };
    } catch (e) { return { упало: true, вывод: (e.stdout || '') + (e.stderr || '') }; }
}

const ОТКАТЫ = [
    /* ЯКОРЯ ПЕРЕПИСАНЫ 07.11: Условия пересобраны из редакции,
       утверждённой приказом № 1, и прежних фраз в них нет — откаты
       молча перестали применяться. Взяты нынешние формулировки,
       снятые чтением страниц. */
    ['увести русские Условия на чужой возраст',
     [RU, 'Сервис доступен лицам от 14 лет', 'Сервис доступен лицам от 16 лет'],
     'возраст «пользование» одинаков во всех документах и на всех языках'],

    ['увести английские Условия на чужой возраст',
     [EN, 'persons aged 14 and over', 'persons aged 13 and over'],
     'возраст «пользование» одинаков во всех документах и на всех языках'],

    ['увести кыргызские Условия на чужой возраст',
     [KG, 'Кызмат 14 жаштан', 'Кызмат 13 жаштан'],
     'возраст «пользование» одинаков во всех документах и на всех языках'],

    /* Все пять разом на одно и то же чужое число: правило равенства
       молчит — падает ровно правило «совпадает с решением». */
    /* ИМЯ ПРАВИЛА ПЕРЕПИСАНО 07.11 вслед за самим правилом: оно
       проверяет возраст ПО НАЗНАЧЕНИЮ (пользование 14, участие 18), и
       прежнее имя «возраст совпадает с решением» в выводе не
       встречалось — откат молча «проходил». */
    ['увести ВСЕ документы на одно чужое число',
     [[RU, 'Сервис доступен лицам от 14 лет', 'Сервис доступен лицам от 16 лет'],
      [EN, 'persons aged 14 and over', 'persons aged 16 and over'],
      [KG, 'Кызмат 14 жаштан', 'Кызмат 16 жаштан']],
     'возраст совпадает с решением по своему назначению'],

    ['переписать фразу о возрасте в английских Условиях',
     [EN, 'the Service is available to persons aged', 'this service may be used by people aged'],
     'фраза о возрасте на месте во всех названных документах'],

    ['заставить приложение называть возраст само',
     [МОБ, '</body>', '<p>16 лет</p>\n</body>'],
     'приложение не называет возраст само']
];

const база = прогон(null);
if (база.упало) {
    console.log('\n  x база: правила падают на ЧИСТОЙ копии — чинить сторож, а не код\n');
    console.log(база.вывод);
    fs.rmSync(песок, { recursive: true, force: true });
    process.exit(1);
}
console.log('  база    исходный код правила проходит\n');

let плохих = 0;
ОТКАТЫ.forEach(([имя, правка, ждём]) => {
    /* ЯКОРЬ ПРОВЕРЯЕТСЯ У КАЖДОЙ ТРОЙКИ, а не только у первой:
       откат на несколько файлов молча пропустил бы мёртвый якорь во
       второй и третьей. */
    if (правка) {
        const тройки = Array.isArray(правка[0]) ? правка : [правка];
        let мёртвый = null;
        тройки.forEach(п => {
            if (мёртвый) return;
            const n = исходник[п[0]].split(п[1]).length - 1;
            if (n !== 1) мёртвый = { ф: п[0], n: n };
        });
        if (мёртвый) {
            console.log('  ? ' + имя + '  ->  якорь встречается ' + мёртвый.n +
                        ' раз в ' + мёртвый.ф);
            плохих++; return;
        }
    }
    let р;
    if (правка) { р = прогон(правка); }
    else {
        /* пятый откат: меняем решение в самом стороже на копии */
        const сп = path.join(песок, 'tools', 'check-vozrast-odin.js');
        const было = fs.readFileSync(sp_путь(), 'utf8');
        fs.writeFileSync(сп, было.replace("const РЕШЕНО = '18';", "const РЕШЕНО = '16';"));
        ФАЙЛЫ.forEach(ф => fs.writeFileSync(path.join(песок, ф), исходник[ф]));
        try { execFileSync(process.execPath, [сп], { encoding: 'utf8' }); р = { упало: false, вывод: '' }; }
        catch (e) { р = { упало: true, вывод: (e.stdout || '') + (e.stderr || '') }; }
        fs.writeFileSync(сп, было);
    }
    прогон(null);
    if (!р.упало) { console.log('  x ' + имя + '  ->  правило НЕ упало'); плохих++; }
    else if (р.вывод.indexOf(ждём) === -1) {
        console.log('  ~ ' + имя + '  ->  упало ДРУГОЕ. Ждали: ' + ждём); плохих++;
    } else console.log('  v ' + имя + '  ->  «' + ждём + '»');
});
function sp_путь() { return path.join(песок, 'tools', 'check-vozrast-odin.js'); }
fs.rmSync(песок, { recursive: true, force: true });
console.log('');
if (плохих === 0) {
    console.log('  ок      все ' + ОТКАТЫ.length + ' откатов доказали свои правила');
    console.log('          оригиналы не трогались — работа шла на копии\n');
} else {
    console.log('  НЕ ТАК  ' + плохих + ' из ' + ОТКАТЫ.length + ' откатов не доказали правило\n');
    process.exitCode = 1;
}
