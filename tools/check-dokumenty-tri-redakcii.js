'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');

const ДОКУМЕНТЫ = [
    {
        имя: 'правила лиги', единица: 'пунктов',
        файлы: { русская: 'pages/rules.html', английская: 'pages/rules-en.html', кыргызская: 'pages/rules-kg.html' },
        раздел: () => /<div class="ip-rules-section[^"]*" id="([^"]+)">([\s\S]*?)<\/ol>/g,
        кусок: () => /<li>/g,
        пустой: () => /<li>\s*<\/li>/g,
        оглавление: /<ol class="ip-toc-list">([\s\S]*?)<\/ol>/,
        пометка: null
    },
    {
        имя: 'публичная оферта', единица: 'пунктов',
        файлы: { русская: 'pages/offer.html', английская: 'pages/offer-en.html', кыргызская: 'pages/offer-kg.html' },
        раздел: () => /<div class="ip-rules-section[^"]*" id="([^"]+)">([\s\S]*?)(?=<div class="ip-rules-section|<section|<\/main)/g,
        кусок: () => /<p[^>]*><strong>\d+(?:\.\d+)*\.<\/strong>/g,
        пустой: () => /<p[^>]*><strong>\d+(?:\.\d+)*\.<\/strong>\s*<\/p>/g,
        оглавление: null, пометка: null
    },
    {
        имя: 'политика конфиденциальности', единица: 'пунктов',
        файлы: { русская: 'pages/privacy-policy.html', английская: 'pages/privacy-policy-en.html', кыргызская: 'pages/privacy-policy-kg.html' },
        раздел: () => /<div class="ip-rules-section[^"]*" id="([^"]+)">([\s\S]*?)(?=<div class="ip-rules-section|<section|<\/main)/g,
        кусок: () => /<p[^>]*><strong>\d+(?:\.\d+)*\.<\/strong>/g,
        пустой: () => /<p[^>]*><strong>\d+(?:\.\d+)*\.<\/strong>\s*<\/p>/g,
        оглавление: null, пометка: null
    },
    {
        имя: 'условия использования', единица: 'абзацев',
        файлы: { русская: 'pages/terms.html', английская: 'pages/terms-en.html', кыргызская: 'pages/terms-kg.html' },
        раздел: () => /<div class="ip-about-section[^"]*">\s*<h2[^>]*>([\s\S]*?)<\/h2>([\s\S]*?)(?=<div class="ip-about-section|<section|<\/main)/g,
        кусок: () => /<p class="ip-about-text"/g,
        пустой: () => /<p class="ip-about-text">\s*<\/p>/g,
        оглавление: null,
        пометка: 'ip-draft-note'
    }
];

function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}

/** Разбор одной страницы: список разделов (сколько кусков в каждом). */
function разбор(док, т) {
    const разделы = [];
    const ре = док.раздел();
    let м;
    let н = 0;
    while ((м = ре.exec(т)) !== null) {
        н++;
        const тело = м[2] !== undefined ? м[2] : м[1];
        /* У правил раздел назван своим id — он и держит ссылку из
           оглавления. У условий id нет, и порядковый номер здесь не
           выдумка, а единственное, чем раздел отличим: названия на трёх
           языках заведомо разные. */
        const имя = (м[2] !== undefined && /^[a-z0-9-]+$/i.test(м[1])) ? м[1] : ('№' + н);
        разделы.push({
            имя: имя,
            кусков: (тело.match(док.кусок()) || []).length,
            пустых: (тело.match(док.пустой()) || []).length
        });
    }
    const якоря = док.оглавление
        ? ((т.match(док.оглавление) || [, ''])[1].match(/href="#([^"]+)"/g) || []).map(с => с.slice(7, -1))
        : null;
    /* ПОДСТРОКА — НЕ ПРИЗНАК. Проверка `indexOf('ip-draft-note')`
       проходила и на откате, где класс переименован в
       `ip-draft-note-ubrana`: искомое имя целиком лежит внутри нового.
       Поэтому имя класса ищется с границей. */
    const естьПометка = док.пометка
        ? new RegExp('class="[^"]*\\b' + док.пометка + '(?:\\s|")').test(т)
        : null;
    return { разделы: разделы, якоря: якоря, пометка: естьПометка };
}

function подпись(стр) {
    return стр.разделы.map(р => р.имя + ':' + р.кусков).join(' ');
}

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя: имя, подсказка: подсказка });
}

let всегоРазделов = 0, всегоКусков = 0;

for (const док of ДОКУМЕНТЫ) {
    const языки = Object.keys(док.файлы);
    const нет = языки.filter(я => чит(док.файлы[я]) === null);
    правило(док.имя + ': все три страницы на месте', нет.length === 0,
        'Нет файлов: ' + нет.map(я => док.файлы[я]).join(', '));
    if (нет.length) continue;

    const стр = {};
    for (const я of языки) стр[я] = разбор(док, чит(док.файлы[я]));
    const основа = стр['русская'];
    всегоРазделов += основа.разделы.length;
    всегоКусков += основа.разделы.reduce((с, р) => с + р.кусков, 0);

    const расходятся = языки.slice(1).filter(я => подпись(стр[я]) !== подпись(основа));
    правило(док.имя + ': три редакции держат одну структуру',
        расходятся.length === 0,
        'Структура разошлась с русской редакцией:\n' +
        ['  русская:     ' + подпись(основа)]
            .concat(расходятся.map(я => '  ' + (я + ':').padEnd(13) + подпись(стр[я]))).join('\n') +
        '\nЗапись «раздел:' + док.единица.slice(0, -2) + 'ов». Это один документ на трёх\n' +
        'языках: раздел или кусок, которого нет в переводе, — это условие,\n' +
        'которое читатель на своём языке не прочитал, а оно на него действует.');

    if (док.оглавление) {
        const врут = языки.filter(я =>
            (стр[я].якоря || []).join(' ') !== стр[я].разделы.map(р => р.имя).join(' '));
        правило(док.имя + ': оглавление отвечает разделам',
            врут.length === 0,
            'Оглавление не совпадает с разделами: ' + врут.map(я => '\n  ' + док.файлы[я] +
                '\n     в оглавлении: ' + (стр[я].якоря || []).join(' ') +
                '\n     на странице:  ' + стр[я].разделы.map(р => р.имя).join(' ')).join('') +
            '\nОглавление — второй список тех же разделов, и он обязан совпадать\n' +
            'с первым: иначе ссылка ведёт в пустоту.');
    }

    if (док.пометка) {
        const без = языки.filter(я => основа.пометка && !стр[я].пометка);
        правило(док.имя + ': пометка о черновике есть на всех языках',
            без.length === 0,
            'Пометка «' + док.пометка + '» стоит по-русски, но её нет: ' +
            без.map(я => '\n  ' + док.файлы[я]).join('') +
            '\nЧитатель на своём языке должен видеть то же предупреждение, что и\n' +
            'русский: иначе он принимает проект документа за утверждённый.');
    }

    const пустые = [];
    for (const я of языки) for (const р of стр[я].разделы) if (р.пустых) пустые.push(док.файлы[я] + ' / ' + р.имя);
    правило(док.имя + ': ни один кусок не пуст', пустые.length === 0,
        'Пустые куски: ' + пустые.map(с => '\n  ' + с).join('') +
        '\nПустой кусок — это след правки, которую бросили на полпути.');
}

if (ошибки.length) {
    console.log('НЕ ТАК  документы лиги: ' + ошибки.length + ' правил упало\n');
    for (const о of ошибки) console.log('  ✗ ' + о.имя + '\n    ' + о.подсказка.replace(/\n/g, '\n    ') + '\n');
    process.exit(1);
}
console.log('ок      документы лиги: ' + ДОКУМЕНТЫ.length + ' документа × 3 языка, ' +
    всегоРазделов + ' разделов, ' + всегоКусков + ' кусков');
