#!/usr/bin/env node
/**
 * СТАТУС И ИМЕНА В ПРИЛОЖЕНИИ — ЗАМОРОЗКА КУСКА 218 (28.10).
 *
 * ТРИ НАХОДКИ КОСТИ ГЛАЗАМИ, И ПЕРВАЯ ОКАЗАЛАСЬ КРУПНЕЕ ВИДА.
 *
 * 1. НА ЭКРАНЕ СТОЯЛО «registration_closed». Приложение держало СВОЮ
 *    карту подписей — и не одну, а ДВЕ одинаковые (`home.js` и
 *    `tournaments.js`), и обе знали состояния `upcoming`, `live`,
 *    `completed`. В базе состояния другие: `completed` — 47 турниров,
 *    `registration_closed` — 4, `registration_open` — 1 (посчитано
 *    чтением базы). То есть ДВА ИЗ ТРЁХ реальных состояний не
 *    переводились НИКОГДА и показывались сырым именем столбца, а два
 *    ключа карты (`upcoming`, `live`) не встречаются в базе вовсе.
 *    КАРТА ПИСАЛАСЬ НЕ ПО БАЗЕ.
 *    На сайте для этого давно есть общий дом `js/tournament-status.js`
 *    («одно определение на одно понятие», шесть состояний на трёх
 *    языках) — в приложении его просто не было. Теперь есть, копия
 *    сверяется до байта.
 *
 * 2. ИМЯ СОКРАЩАЛОСЬ ТАМ, ГДЕ МЕСТА ХВАТАЕТ. В таблице группы и в
 *    списке участников стояло «А. Канаев»: сокращение нужно в клетке
 *    сетки, где ширина 168, а в таблице колонка переносится в две
 *    строки. Слово Кости: «можно отображать полностью имя и фамилия».
 *
 * 3. ПОСЕВ УЕЗЖАЛ ТРЕТЬЕЙ СТРОКОЙ под фамилией, и ТАБЛИЦА ГРУППЫ ЛЁЖА
 *    НЕ ЗАНИМАЛА ЭКРАН: 844 в ширину, таблица 530, справа пустота.
 *    `min-width: 100%` закрывает оба случая одним правилом — и когда
 *    таблица уже экрана, и когда шире и её двигают вбок.
 *
 * ЗАМЕР ПОСЛЕ: бейдж «Рег. закрыта»; имена полные («Амир Канаев [1]»),
 * посев в одной строке с именем; лёжа таблица 780 при обёртке 780,
 * боковой прокрутки нет, обрезок 0.
 *
 * Запуск: node tools/check-status-i-imena-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
function безСлов(отн) {
    return чит(отн).replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const главная = безСлов('mobile/www/js/screens/home.js');
const турниры = безСлов('mobile/www/js/screens/tournaments.js');
const разметка = безСлов('mobile/www/index.html');
const css = безСлов('mobile/www/css/app.css');

/* ── 1. СТАТУС — ИЗ ОБЩЕГО ДОМА ── */
правило(
    'дом статуса лежит в приложении и подключён',
    чит('mobile/www/js/tournament-status.js') !== '' &&
    /js\/tournament-status\.js\?v=/.test(разметка),
    'На сайте он есть давно, в приложении его не было вовсе.');

правило(
    'копия дома статуса совпадает до байта',
    чит('js/tournament-status.js') !== '' &&
    чит('js/tournament-status.js') === чит('mobile/www/js/tournament-status.js'),
    'Разойдутся — одно состояние будет называться по-разному на сайте\n' +
    'и в приложении, и беда родится ровно на шве.');

[['mobile/www/js/screens/home.js', главная, 'окно турнира'],
 ['mobile/www/js/screens/tournaments.js', турниры, 'список турниров']
].forEach(function (п) {
    правило(
        'подпись статуса берётся из дома: ' + п[2],
        /KSLT_STATUS\.подпись\(/.test(п[1]),
        'Своя карта знала `upcoming`, `live`, `completed`, а в базе\n' +
        '`completed`, `registration_closed`, `registration_open`.');
    правило(
        'своя карта статусов снесена: ' + п[2],
        п[1].indexOf('var statusMap') < 0,
        'Их было ДВЕ одинаковых — второе определение одного понятия.');
});

/* ── 2. ИМЯ ПОЛНОЕ ТАМ, ГДЕ МЕСТА ХВАТАЕТ ── */
правило(
    'имя без сокращения заведено отдельным домом',
    /function полноеИмя\(/.test(главная),
    'Сокращение «А. Канаев» нужно в клетке сетки (ширина 168), а в\n' +
    'таблице колонка переносится в две строки.');

правило(
    'таблица группы берёт полное имя',
    /имя: function \(id\) \{ return полноеИмя\(/.test(главная),
    'Слово Кости: «можно отображать полностью имя и фамилия».');

правило(
    'список участников берёт полное имя',
    /\? полноеИмя\(reg\.player_id, regsMap, playersMap, isDbl\)/.test(главная),
    'Правило, выведенное на одном куске, применяется к следующему\n' +
    'без нового разбора.');

правило(
    'в клетке сетки имя остаётся сокращённым',
    /имя: getMobileTeamName\(id, regsMap, playersMap, isDbl\)/.test(главная),
    'Там ширина 168, и полное имя пары ломало бы клетку.');

/* ── 3. ШИРИНА ТАБЛИЦЫ И ПОСЕВ ── */
правило(
    'таблица группы тянется на всю ширину, когда влезает',
    /\.td-group-table \{[^}]*min-width: 100%/.test(css),
    'Костя увидел лёжа: экран 844, таблица 530, справа пустота.\n' +
    '`min-width` закрывает оба случая — и когда уже экрана, и когда\n' +
    'шире и её двигают вбок. ЗАМОРОЖЕНО ОТНОШЕНИЕ, а не число.');

правило(
    'посев не уезжает отдельной строкой',
    /\.td-gt-seed \{[^}]*white-space: nowrap/.test(css),
    'Костя увидел «[1]» третьей строкой под фамилией.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      статус и имена: все ' + держится + ' правил держатся');
    console.log('          статус из дома, имя полное там, где влезает\n');
}
