/**
 * ПЕЧАТНАЯ КАРТОЧКА — ОДНО ОПРЕДЕЛЕНИЕ. Круг 18 ветки D, 19.10.
 * Находка 96е.
 *
 * ЧТО БЫЛО. Картинку, которую человек скачивает и показывает в клубе,
 * рисовали ЧЕТЫРЕ раза: ваучер на странице кортов, на странице тренеров
 * и в кабинете, плюс QR профиля игрока. Замер: рисование у кортов и
 * тренеров совпадало СЛОВО В СЛОВО — 60 строк, сходство 1.00; у кабинета
 * 0.95. `roundRect` лежал тремя побайтово одинаковыми копиями.
 *
 * БЕДА РОДИЛАСЬ РОВНО НА ШВЕ. Кабинет научился проверять пустые значения,
 * корты и тренеры — нет: ваучер без скидки рисовал «-undefined%». Третья
 * копия знала, две не знали, и узнать об этом было негде.
 *
 * `var(--alpha-lime-20)` СТОЯЛ В ЧЕТЫРЁХ КОПИЯХ: холст var() не понимает,
 * и разделительная линия под логотипом не рисовалась НИ НА ОДНОЙ из
 * четырёх карточек. Прибор, читающий исходник, видел «краска задана».
 *
 * ПОРОГ ЗДЕСЬ СТРОЖЕ ЭКРАННОГО: это картинка, которую показывают с
 * телефона, случается — на солнце. Три текста стояли ниже AA 4.5 —
 * подзаголовок 3.81, подпись под QR 3.20, адрес сайта 2.26. Поднято до
 * ступени 0.50 — наименьшей на лестнице прозрачности, дающей 4.5 на ОБОИХ
 * концах градиента (5.34 сверху, 5.12 снизу).
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ, А НЕ ЧИСЛО:
 *   1. рисование карточки живёт ТОЛЬКО в доме: ни один зовущий файл не
 *      рисует её сам;
 *   2. `roundRect` объявлен один раз — в доме;
 *   3. краска в доме берётся домом красок; числом остаются лишь чёрное и
 *      белое QR-кода и белая подложка под ним — это требование
 *      считывания, а не роль;
 *   4. пустые скидка и срок проверяются В ДОМЕ, то есть во всех местах
 *      сразу;
 *   5. тихий текст карточки стоит на ступени не ниже 0.50 — ниже неё
 *      контраст к градиенту падает под порог;
 *   6. кегли карточки — со шкалы продукта;
 *   7. страница, зовущая дом карточки, подключает и его, и дом красок.
 *
 *   node tools/check-kartochka-holsta.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const ДОМ = 'js/kslt-vaucher-kartochka.js';
const КРАСКИ = 'js/kslt-kraska.js';
const ЗОВУЩИЕ = ['js/courts.js', 'js/coaches.js', 'js/dashboard.js'];
const ШКАЛА = [11, 12, 14, 16, 18, 21, 26, 32, 40];
const СТУПЕНЬ_ТИХОГО = 0.50;

/* СТОРОЖ ЧИТАЕТ КОД, А НЕ СЛОВА О КОДЕ. Комментарии гасятся пробелами с
   сохранением переводов строк: иначе номера строк в подсказке врут. */
const чисто = п => fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}
const строка = (т, поз) => т.slice(0, поз).split('\n').length;

const дом = чисто(ДОМ);
const зов = {};
ЗОВУЩИЕ.forEach(ф => { зов[ф] = чисто(ф); });

/* ---- 1. карточку рисует только дом ---- */
/* ПРАВИЛО НЕ ДЕРЖИТСЯ ЗА ИМЯ ПЕРЕМЕННОЙ. Первая редакция искала
   `ctx.fillText(` и промолчала на `qrCanvas.getContext('2d').fillText(` —
   откат доказал это сразу. Признак рисования — ВЫЗОВ, кто бы ни держал
   холст. */
const РИСОВАНИЕ = /createLinearGradient\s*\(|\.\s*fillText\s*\(|\.\s*(?:fillStyle|strokeStyle)\s*=/;
const сами = [];
ЗОВУЩИЕ.forEach(ф => {
    const р = new RegExp(РИСОВАНИЕ.source, 'g');
    let м;
    while ((м = р.exec(зов[ф]))) сами.push(ф + ':' + строка(зов[ф], м.index) + ' ← ' + м[0].trim());
});
правило('карточку рисует только дом, зовущие её не рисуют',
    сами.length === 0,
    'Рисование на холсте вне дома:\n  ' + сами.join('\n  ') + '\n' +
    'До 19.10 эти 60 строк жили в трёх файлах, у кортов и тренеров СЛОВО\n' +
    'В СЛОВО. Беда родилась на шве: проверку пустой скидки знала только\n' +
    'копия кабинета, и ваучер без скидки рисовал «-undefined%».\n' +
    'Рисуй через window.KSLT_VAUCHER.нарисовать / .профиль.');

/* ---- 2. roundRect объявлен один раз, и это дом ---- */
function всеJs(д, вых) {
    вых = вых || [];
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) { if (э.name !== 'node_modules') всеJs(п, вых); }
        else if (э.name.endsWith('.js')) вых.push(п);
    });
    return вых;
}
const скруглённые = всеJs('js').filter(п => /function\s+(?:roundRect|скруглённый)\s*\(/.test(чисто(п)));
правило('скругление объявлено один раз, и это дом',
    скруглённые.length === 1 && скруглённые[0] === ДОМ,
    'Объявлено в: ' + (скруглённые.join(', ') || 'нигде') + '\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. До 19.10 `roundRect` лежал тремя\n' +
    'ПОБАЙТОВО одинаковыми копиями — в кортах, тренерах и кабинете.');

/* ---- 3. краска в доме — домом красок ---- */
const КРАСКА = /#[0-9a-fA-F]{3,8}\b|rgba?\(\s*[\d.]+[^)]*\)|var\(--/;
const мимо = [];
дом.split('\n').forEach((s, i) => {
    const м = s.match(new RegExp(КРАСКА.source, 'g'));
    if (!м) return;
    /* Чёрное и белое QR-кода — требование считывания, а не роль:
       считыватель ждёт максимального контраста модулей. */
    const qr = /colorDark|colorLight|#ffffff/.test(s) && /#(?:000000|ffffff)/i.test(s);
    if (qr) return;
    м.forEach(c => мимо.push((i + 1) + ' ← ' + c + ' | ' + s.trim().slice(0, 50)));
});
правило('краска в доме берётся домом красок',
    мимо.length === 0,
    'Краска мимо дома красок:\n  ' + мимо.join('\n  ') + '\n' +
    '`var(--…)` в холсте ХУЖЕ числа: холст его не понимает и рисует\n' +
    'НИЧЕМ. Именно так разделитель не рисовался ни на одной из четырёх\n' +
    'прежних карточек.');

/* ---- 4. пустые значения проверяются в доме ---- */
правило('пустая скидка и пустой срок проверяются в доме',
    /if\s*\(\s*o\.скидка/.test(дом) && /if\s*\(\s*o\.срок\s*\)/.test(дом),
    'В доме нет проверки `o.скидка` или `o.срок`.\n' +
    'УМОЛЧАНИЕ — СВОЙСТВО ДАННЫХ: нет скидки — нет блока, а не\n' +
    '«-undefined%» на картинке, которую человек показывает в клубе.');

/* ---- 5. тихий текст не ниже ступени 0.50 ---- */
/* Ступени объявлены ИМЕНАМИ — число стоит один раз. Правило читает
   объявления, а не места рисования: иначе оно требовало бы числа там,
   где его как раз быть не должно. */
const ступени = [];
{
    const р = /var\s+(?:ТИХО|СРЕДНЕ)\s*=\s*([\d.]+)\s*;/g;
    let м;
    while ((м = р.exec(дом))) ступени.push(parseFloat(м[1]));
}
/* И ни одной прозрачности числом мимо этих имён. */
const числом = [];
{
    const р = /краска\(\s*'[^']+'\s*,\s*([\d.]+)\s*\)/g;
    let м;
    while ((м = р.exec(дом))) {
        const a = parseFloat(м[1]);
        /* 0.20 — обводка разделителя, не текст: своё имя ей не нужно. */
        if (м[0].indexOf('--neutral-white') !== -1) числом.push(a);
    }
}
const низкие = ступени.filter(a => a < СТУПЕНЬ_ТИХОГО).concat(числом.filter(a => a < СТУПЕНЬ_ТИХОГО));
правило('тихий текст карточки не ниже ступени 0.50',
    ступени.length >= 2 && низкие.length === 0,
    'Ступени ниже 0.50: ' + (низкие.join(', ') || 'их нет, но и объявленных ступеней меньше двух') + '\n' +
    'Карточку показывают с телефона, случается — на солнце. Ниже 0.50\n' +
    'контраст к градиенту падает под AA 4.5: при 0.40 он 3.81, при 0.35\n' +
    '— 3.20, при 0.25 — 2.26. Все три числа стояли в продукте.');

/* ---- 6. кегли со шкалы ---- */
const кегли = [];
{
    const р = /шрифт\(\s*(\d+)/g;
    let м;
    while ((м = р.exec(дом))) кегли.push(parseInt(м[1], 10));
}
const мимоШкалы = [...new Set(кегли.filter(k => ШКАЛА.indexOf(k) === -1))];
правило('кегли карточки стоят на шкале продукта',
    кегли.length > 0 && мимоШкалы.length === 0,
    'Мимо шкалы: ' + мимоШкалы.join(', ') + '\n' +
    'Шкала: ' + ШКАЛА.join(' · ') + '. В прежних копиях стояли 10, 13 и 15 —\n' +
    'причём 10 ниже самой мелкой ступени продукта.');

/* ---- 8. знак и расшифровка — те же, что во всём продукте ---- */
const ОБЛОЖКА = 'js/kslt-oblozhka.js';
const ГЕРОЙ = 'index.html';
const ВЫГРУЗКА = 'js/admin/core/export.js';

/* Расшифровка взята дословно из продукта. Якорь — САМ ТЕКСТ: если он
   разойдётся хоть в одном месте, родится второе имя клуба. */
const РАСШИФРОВКА_RU = 'Кыргызстанское Сообщество Любителей Тенниса';
правило('расшифровка на карточке — та же, что в титуле, герое и печати',
    дом.indexOf(РАСШИФРОВКА_RU) !== -1 &&
    fs.readFileSync(path.join(КОРЕНЬ, ГЕРОЙ), 'utf8').indexOf(РАСШИФРОВКА_RU) !== -1 &&
    fs.readFileSync(path.join(КОРЕНЬ, ВЫГРУЗКА), 'utf8').indexOf(РАСШИФРОВКА_RU) !== -1,
    'Расшифровка имени клуба на карточке разошлась с продуктом.\n' +
    'Она стоит в титуле, в герое главной, в подвале и в печати выгрузки —\n' +
    'дословно «' + РАСШИФРОВКА_RU + '».\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: два написания имени клуба — это\n' +
    'два клуба для того, кто читает картинку.');

/* Знак кириллицей на русском, латиницей на прочих — правило обложки,
   решённое 04.10. Карточка его донесла, а не переоткрыла. */
правило('знак на карточке кириллицей на русском и латиницей на прочих',
    /ЗНАК\s*=\s*\{\s*ru:\s*'КСЛТ'/.test(дом) &&
    /en:\s*'KSLT'/.test(дом) && /kg:\s*'KSLT'/.test(дом),
    'Знак на карточке перестал следовать правилу обложки:\n' +
    'на русском «КСЛТ», на английском и кыргызском «KSLT».\n' +
    'Решено 04.10 и не переоткрывается.');

/* Аббревиатура в строку расшифровки не входит — замер, а не вкус. */
правило('аббревиатура не повторяется в строке расшифровки',
    dom_без_знака(),
    'В строке расшифровки снова стоит аббревиатура. Замер 19.10:\n' +
    '«КСЛТ — » плюс расшифровка даёт 320.2 при полосе 300 между концами\n' +
    'разделителя — строка вылезет на линию. И повторять незачем: знак\n' +
    'стоит строкой выше.');
function dom_без_знака() {
    const м = dom_расшифровки();
    return м.every(с => с.indexOf('КСЛТ') === -1 && с.indexOf('KSLT') === -1);
}
function dom_расшифровки() {
    const н = дом.indexOf('РАСШИФРОВКА = {');
    if (н === -1) return [];
    const к = дом.indexOf('};', н);
    return (дом.slice(н, к).match(/'([^']+)'/g) || []).map(s => s.slice(1, -1));
}

/* ---- 7. страницы: зовёшь дом — подключи дом и краски ---- */
function страницы() {
    const вых = [];
    (function обойти(д) {
        fs.readdirSync(path.join(КОРЕНЬ, д || '.'), { withFileTypes: true }).forEach(э => {
            const п = д ? д + '/' + э.name : э.name;
            if (э.isDirectory()) {
                if (/^(node_modules|\.git|mobile|test-results|playwright-report|build)$/.test(э.name)) return;
                обойти(п);
            } else if (э.name.endsWith('.html')) вых.push(п);
        });
    })('');
    return вых;
}
const зовутДом = всеJs('js').filter(п => п !== ДОМ && /\bKSLT_VAUCHER\s*\./.test(чисто(п)));
const безДома = [];
страницы().forEach(стр => {
    const т = fs.readFileSync(path.join(КОРЕНЬ, стр), 'utf8');
    const база = path.dirname(стр);
    const пути = [];
    const р = /<script[^>]*src="([^"]+)"/g;
    let м;
    while ((м = р.exec(т))) {
        const ч = м[1].split('?')[0];
        if (/^(https?:)?\/\//.test(ч)) continue;
        пути.push(path.posix.normalize(path.posix.join(база === '.' ? '' : база, ч)).replace(/^\.\//, ''));
    }
    const нужны = пути.filter(п => зовутДом.indexOf(п) !== -1);
    if (!нужны.length) return;
    const нет = [];
    if (пути.indexOf(ДОМ) === -1) нет.push('дом карточки');
    if (пути.indexOf(КРАСКИ) === -1) нет.push('дом красок');
    if (нет.length) безДома.push(стр + ' ← ' + нужны.map(п => path.basename(п)).join(', ') + ' | нет: ' + нет.join(' и '));
});
правило('страница, зовущая дом карточки, подключает его и дом красок',
    безДома.length === 0,
    'Не подключено:\n  ' + безДома.join('\n  ') + '\n' +
    'Без дома карточки кнопка «скачать» упадёт с TypeError, без дома\n' +
    'красок карточка нарисуется прозрачной.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      печатная карточка: 10 правил');
    console.log('          ' + ЗОВУЩИЕ.length + ' зовущих файла, ни один не рисует сам');
    console.log('          скругление одно, краски домом, пустые значения в доме');
    console.log('          знак и расшифровка — те же, что в продукте, по языку');
    console.log('          ступени тихого текста: ' + ступени.join(' · ') + ', все ≥ 0.50');
    console.log('          кегли со шкалы: ' + [...new Set(кегли)].sort((a, b) => a - b).join(' · '));
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  печатная карточка — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
