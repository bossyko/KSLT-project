#!/usr/bin/env node
/**
 * КНОПКА НАВЕРХ НЕ ПЕРЕХВАТЫВАЕТ ЧУЖИЕ НАЖАТИЯ (12.11.2026).
 *
 * ОТКУДА. Замер живьём в админке: раздел «Уведомления», иконка
 * «Удалить рассылку» занимает 1412-1448 по горизонтали, кнопка наверх
 * 1436-1480 — пересечение 12 точек, и кнопка сверху (z-index 100,
 * position fixed). Человек, целившийся в удаление строки, улетал
 * наверх списка. В шести других разделах чисто: там у правого края
 * целей нет.
 * Это уже вторая такая беда у одной кнопки: в сентябре она так же
 * ложилась на заголовки гармошки в подвале — там её увёл признак
 * «подвал в кадре». Админку тот признак не закрывает: подвала в ней
 * нет вовсе, и признак честно отвечает «подвала не видно».
 *
 * ЧТО СТОРОЖИТСЯ:
 *   1. в админке кнопка не заводится вовсе;
 *   2. уход от подвала на сайте остался;
 *   3. подпись для диктора берётся у дома языка, а не зашита по-английски;
 *   4. под пальцем цель не мельче ступени касания.
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, ' ');

const ошибки = [];
const правило = (имя, условие, почему) => { if (!условие) ошибки.push(имя + ' — ' + почему); };

const скр = безКом(чит('js/script.js'));
const сти = чит('css/style.css');

/* Тело того самого самозапуска, а не весь файл: признак, нашедший себя
   в соседнем куске, ничего не сторожит. */
const тело = (скр.match(/var btn = document\.createElement\('button'\);[\s\S]{0,2000}?scroll-to-top[\s\S]{0,2000}?\}\)\(\);/) || [''])[0];
const кусок = (скр.match(/\(function\s*\(\)\s*\{[^]{0,600}?scroll-to-top[^]*?\}\)\(\);/) || [''])[0];

правило('в админке кнопка наверх не заводится',
    /\.ad-layout'\)\)\s*return;/.test(кусок) &&
    кусок.indexOf(".ad-layout') return") < кусок.indexOf("createElement('button')") + 400,
    'выход по признаку админки пропал: кнопка снова встанет поверх колонки\n' +
    'действий и перехватит «Удалить рассылку» (замер 12.11: пересечение 12 точек)');

правило('уход от подвала остался',
    /подвалВКадре\(\)/.test(кусок) && /scrollY > 400/.test(кусок),
    'кнопка больше не уходит от подвала — вернётся сентябрьская беда:\n' +
    'правые 44 точки заголовков гармошки принимали нажатие на себя');

правило('подпись для диктора берётся у дома языка',
    /aria-label'\s*,\s*KSLT_YAZYK\.выбрать\(/.test(кусок) &&
    !/aria-label'\s*,\s*'Scroll to top'/.test(кусок),
    'подпись снова зашита строкой: диктор читает английскую фразу русскому\n' +
    'и кыргызскому человеку');

/* ЦЕЛЬ ПОД ПАЛЬЦЕМ МЕРЯЕТСЯ СТУПЕНЬЮ, А НЕ ЧИСЛОМ: правило, написанное
   через 44, устареет вместе с числом. Спрашивается имя ступени. */
/* ЦЕЛЬ ПОД ПАЛЬЦЕМ НЕ МЕРЯЕТСЯ ШИРИНОЙ ЭКРАНА. Первая редакция
   поднимала размер в медиа по ширине 640 — и чужой сторож «цель по
   указателю» справедливо упал: планшет боком шире 640, а палец тот
   же. Уменьшения теперь нет вовсе, и правило сторожит именно это. */
/* БАЗОВЫЙ БЛОК — ТОТ, ЧТО С position, а не первый попавшийся: копий
   селектора в файле несколько, и первая из них лежит внутри медиа. */
const все = сти.match(/\.scroll-to-top\s*\{[^}]*\}/g) || [];
const баз = все.filter(б => /position:\s*fixed/.test(б))[0] || '';
const вМедиа = все.filter(б => б !== баз).join('\n');
правило('кнопка нигде не мельче ступени касания',
    /width:\s*44px/.test(баз) && /height:\s*44px/.test(баз) &&
    !/width:\s*\d+px/.test(вМедиа) && !/height:\s*\d+px/.test(вМедиа),
    'размер кнопки снова перебит в медиа по ширине: было 40x40 — ниже порога 44\n' +
    'ровно там, где жмут пальцем, а планшет боком такое медиа и не поймает');

if (ошибки.length) {
    console.error('КНОПКА НАВЕРХ — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
console.log('кнопка наверх: 4 правила держатся');
