/**
 * ЗАМОРОЗКА «ЦВЕТ, У КОТОРОГО ЕСТЬ ИМЯ, ЗАПИСАН ИМЕНЕМ» (ветка B, заход B3,
 * круг 1, 15.10.2026).
 *
 * ЗАМЕР. В публичном css (29 файлов минус админка, кабинет и сам tokens.css)
 * 795 цветовых значений вне комментариев. У 242 из них значение УЖЕ названо
 * в токенах — записано числом при живом имени. Все 242 заменены один в один:
 * вид не изменился ни на одном узле, померено загрузкой «до против после».
 *
 * ПРЕЖНЯЯ ЦИФРА 553 — ОШИБКА ПРИБОРА, А НЕ ЗАМЕР. Прибор перевернул группы:
 * 552 — это места, где имени НЕТ, а не есть. Цифру, которую нельзя
 * воспроизвести, нельзя и записывать: ни одна граница корпуса (публичный
 * css, все css, css с html и js) не даёт 553.
 *
 * ПОЧЕМУ ЗАМЕНА ЭКВИВАЛЕНТНА — проверено, а не предположено:
 *   • каждый целевой токен объявлен РОВНО ОДИН РАЗ (иначе var() взял бы
 *     другое значение в медиа-запросе или теме);
 *   • tokens.css подключён на всех страницах, где лежит заменённый css —
 *     иначе var() отдал бы пусто и цвет уехал бы в наследуемый;
 *   • сверка загрузкой «до против после»: ни одного расхождения в color,
 *     фоне, рамках, тени, обводке, fill и stroke, включая ::before и ::after.
 *
 * КАК ПРИБОР СВЕРКИ ВРАЛ ТРИ РАЗА — каждый раз поймано калибровкой «до
 * против до» на ОДИНАКОВОМ коде, и это главный приём, а не формальность:
 *   1. сопоставлял узлы по номеру — блок из базы сдвигал нумерацию, 166
 *      ложных расхождений на одинаковом коде;
 *   2. снимал цвет ПОСРЕДИ ПЕРЕХОДА: на `.nav-dropdown-item` стоит
 *      `transition: all`, а класс `.active` навешивает js — 10 ложных
 *      расхождений, и они пропадали при повторе;
 *   3. ждал признак БЕЗ ВЕРХНЕГО ПРЕДЕЛА — на странице кортов карта
 *      докручивает тайлы, число узлов не стабилизируется никогда.
 *
 * ЧТО ЭТО ПРАВИЛО ДЕРЖИТ:
 *   • число с живым именем не возвращается — ПЕРЕСЧЁТОМ, а не списком;
 *   • цветовой токен не объявляется дважды: на шве родится беда, и замена
 *     перестанет быть эквивалентной молча;
 *   • css не живёт внутри html — сторож на НОВЫЙ блок <style>.
 *
 *   node tools/check-cvet-imenem.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/** Комментарии гасим ПРОБЕЛАМИ ТОЙ ЖЕ ДЛИНЫ, а не вырезаем: иначе
    объявление, начавшееся внутри комментария, жадно съедает текст после
    `*\/` — на этом первый прибор потерял живое место в coaches.css. */
function гасить(s) {
    const из = s.split('');
    s.replace(/\/\*[\s\S]*?\*\//g, (м, i) => {
        for (let k = i; k < i + м.length; k++) if (из[k] !== '\n') из[k] = ' ';
        return м;
    });
    return из.join('');
}

const ВСЕ_CSS = fs.readdirSync(path.join(КОРЕНЬ, 'css')).filter(ф => ф.endsWith('.css')).sort();
/* админка и кабинет не входят в круг 1 — их 103 мёртвых класса и свои
   цвета ждут своей ветки; tokens.css — место объявлений, а не применений */
const ПУБЛ = ВСЕ_CSS.filter(ф => ф !== 'admin.css' && ф !== 'dashboard.css' && ф !== 'tokens.css');

/* ───────── объявления токенов ───────── */

const объявлен = new Map();              // имя -> [{значение, файл}]
ВСЕ_CSS.forEach(ф => {
    const т = гасить(чит('css/' + ф));
    let м;
    const Р = /(--[\w-]+)\s*:\s*([^;}]+)/g;
    while ((м = Р.exec(т))) {
        if (!объявлен.has(м[1])) объявлен.set(м[1], []);
        объявлен.get(м[1]).push({ значение: м[2].trim(), файл: ф });
    }
});

/** Одно значение — одна запись. `#FFF` и `#ffffff` — одно и то же число,
    и прибор, который этого не знает, пропускает половину мест. */
function норма(v) {
    const s = String(v).trim().toLowerCase();
    let м = /^#([0-9a-f]{3})$/.exec(s);
    if (м) return '#' + м[1].split('').map(c => c + c).join('');
    if (/^#[0-9a-f]{6}$/.test(s)) return s;
    м = /^rgba?\(([^)]+)\)$/.exec(s);
    if (м) {
        /* ЧИСЛА ПРИВОДЯТСЯ К ЧИСЛАМ, А НЕ К СТРОКАМ. Первая редакция
           склеивала части как есть, и `0.60` из tokens.css не совпадало с
           `0.6` из кода: одно и то же число считалось двумя разными.
           Круг 1 из-за этого пропустил 42 места с ТОЧНЫМ совпадением —
           `--alpha-black-60`, `--alpha-white-50`, `--alpha-black-30`,
           `--alpha-black-20`. Нашлось только в круге 3, когда прозрачные
           слои считал другой прибор и цифры разошлись. */
        const ч = м[1].split(/[,\s/]+/).filter(Boolean).map(x => {
            const n = parseFloat(x);
            return Number.isFinite(n) ? String(n) : x;
        });
        return 'rgba(' + ч.join(',') + ')';
    }
    return null;
}
const цветной = v => норма(v) !== null;

/* ───────── правило: цветовой токен объявлен один раз ───────── */

const двойные = [...объявлен.entries()]
    .filter(([, зз]) => зз.length > 1 && зз.some(з => цветной(з.значение)))
    .map(([и, зз]) => и + ' (' + зз.map(з => з.файл + ' = ' + з.значение).join(' · ') + ')');

правило('цветовой токен объявлен один раз',
    двойные.length === 0,
    'Цветовых токенов с несколькими объявлениями: ' + двойные.length + '.\n' +
    двойные.join('\n') + '\n\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. Пока токен объявлен один раз,\n' +
    '`var(--x)` и число означают одно и то же, и замена числа именем\n' +
    'ничего не меняет. Со вторым объявлением это перестаёт быть верным\n' +
    'МОЛЧА: в одном медиа-запросе var() отдаст одно, в другом другое.\n' +
    'Проверка размеров сюда не считается — у --fs-hero и --to-slot\n' +
    'переопределения НАМЕРЕННЫЕ, они не цветовые.');

/* ИМЯ ЦВЕТА — НЕ ТО ЖЕ, ЧТО ИМЯ МЕСТА. Это главный урок круга 1, и он
   стоил семи упавших сторожей. `--tab-bg` и `rgba(10,10,10,0.92)` — одно
   и то же ЧИСЛО, но разные ПОНЯТИЯ: первое означает «фон вкладки». Когда
   я подставил его в левый стоп затемнения на карточке live, вид не
   изменился ни на пиксель, а смысл сломался — и правило check-live.js
   упало правильно, потому что держало не число, а смысл.
   Поэтому имена мест в замену НЕ идут. Отличить их от имён цветов нельзя
   счётом — только чтением, поэтому здесь список, и он единственный. */
const ИМЕНА_МЕСТ = new Set([
    '--tab-bg',            // фон вкладки
    '--guest-gradient-mid',// середина гостевого градиента
    '--guest-gradient-end',// его конец
    '--guest-cta-bg',      // фон гостевой коробки-гейта
    '--onb-bg',            // фон онбординга
    '--overlay-bg',        // фон модального слоя
    '--sb-podlozhka',      // подложка табло поверх видео
    '--img-overlay-top'    // затемнение снимка сверху
]);

/* имя для значения — только от токенов, объявленных ровно один раз */
const имя = new Map();
for (const [и, зз] of объявлен) {
    if (зз.length !== 1) continue;
    if (ИМЕНА_МЕСТ.has(и)) continue;
    const н = норма(зз[0].значение);
    if (н && !имя.has(н)) имя.set(н, и);
}

/* ───────── правило: число с живым именем не вернулось ───────── */

const ЦВЕТ = /#[0-9a-fA-F]{3,8}\b|rgba?\(\s*[\d.%]+\s*[,\s][^)]*\)/g;
const ОБЪЯВЛЕНИЕ = /(?<![-\w])([-a-zA-Z][\w-]*)\s*:\s*([^;{}]+)/g;

const безымени = [];
ПУБЛ.forEach(ф => {
    const сырое = чит('css/' + ф);
    const т = гасить(сырое);
    /* роль каждого байта: что это за место в файле */
    const роль = new Array(т.length).fill('?');
    for (let i = 0; i < т.length; i++) if (т[i] === ' ' && сырое[i] !== ' ') роль[i] = 'ком';
    /* глубина блока: в селекторной позиции `#fff` — это ID, а не цвет */
    let у = 0;
    const глуб = new Array(т.length).fill(0);
    for (let i = 0; i < т.length; i++) {
        if (т[i] === '{') у++;
        глуб[i] = у;
        if (т[i] === '}') у = Math.max(0, у - 1);
    }
    for (let i = 0; i < т.length; i++) if (роль[i] === '?' && глуб[i] === 0) роль[i] = 'сел';
    let м;
    ОБЪЯВЛЕНИЕ.lastIndex = 0;
    while ((м = ОБЪЯВЛЕНИЕ.exec(т))) {
        if (роль[м.index] !== '?') continue;
        const р = м[1].startsWith('--') ? 'токен' : (м[2].includes('url(') ? 'url' : 'знач');
        const с = м.index + м[0].length - м[2].length;
        for (let i = с; i < с + м[2].length; i++) роль[i] = р;
    }
    ЦВЕТ.lastIndex = 0;
    while ((м = ЦВЕТ.exec(т))) {
        if (роль[м.index] !== 'знач') continue;
        const н = норма(м[0]);
        if (н && имя.has(н)) {
            const строка = т.slice(0, м.index).split('\n').length;
            безымени.push('css/' + ф + ':' + строка + '  ' + м[0] + '  ->  var(' + имя.get(н) + ')');
        }
    }
});

правило('цвет, у которого есть имя, записан именем',
    безымени.length === 0,
    'Мест, где цвет записан числом при живом имени: ' + безымени.length + '.\n' +
    безымени.slice(0, 12).join('\n') + (безымени.length > 12 ? '\n…' : '') + '\n\n' +
    'ПРАВИЛО ПЕРЕСЧИТЫВАЕТ, А НЕ ПОМНИТ: список из 242 мест устарел бы к\n' +
    'следующему куску. Число с живым именем — это ВТОРОЕ ОПРЕДЕЛЕНИЕ того\n' +
    'же цвета: поменяешь токен, а эти места останутся прежними, и беда\n' +
    'родится ровно на шве.\n' +
    'ИМЯ МЕСТА В ЗАМЕНУ НЕ ИДЁТ: `--tab-bg` равен этому числу, но значит\n' +
    '«фон вкладки». Список имён мест — в ИМЕНА_МЕСТ выше.\n' +
    'Прибор смотрит только СПРАВА от `prop:` внутри блока: `#fff` в\n' +
    'селекторной позиции — это ID, а `.db-inv-contact--tg:hover` не\n' +
    'объявление токена, хотя и выглядит похоже (на этом первый прибор\n' +
    'потерял два живых места).');

/* ───────── правило: css не живёт внутри html ───────── */

function обойти(д, из) {
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д === '.' ? э.name : д + '/' + э.name;
        if (э.isDirectory()) {
            /* `test-results` — ВЫХОД ПРОГОНА, а не продукт: Playwright
               кладёт туда следы со страницами, которые сам же и снял, и
               правило ловило чужие блоки `<style>` внутри них. Прибор,
               читающий выход прогона, говорит о прогоне, а не о коде —
               и падает ровно тогда, когда идут тесты (17.10). */
            if (/^(node_modules|\.git|tests|test-results|tools|dist|build|_sync|mobile|backups|archive|slepki|exports|import|builds|maket)$/.test(э.name)) return;
            if (э.name.startsWith('_do-')) return;        // копии «до» для сверки
            обойти(п, из);
        } else if (э.name.endsWith('.html')) из.push(п);
    });
    return из;
}

/* ИЗВЕСТНЫЙ ДОЛГ, А НЕ РАЗРЕШЕНИЕ. Три страницы скачивания держат ОДИН И
   ТОТ ЖЕ блок в 21 правило, скопированный трижды: правка одной копии
   оставит две прежними. Их вынос в css/download.css — отдельный кусок,
   и пункт маршрута заводит Костя, а не находка. До тех пор сторож держит
   числа: если копий станет больше или блок разрастётся — правило упадёт.
   _preview-mobile.html — служебный стенд, не страница продукта. */
const ДОЛГ = {
    'pages/download.html': 21,
    'pages/download-en.html': 21,
    'pages/download-kg.html': 21,
    'pages/_preview-mobile.html': 16
};

const лишние = [];
обойти('.', []).forEach(ф => {
    const т = чит(ф);
    const блоки = т.match(/<style[\s>][\s\S]*?<\/style>/gi) || [];
    if (!блоки.length) return;
    const правил = блоки.reduce((с, б) => с + (б.match(/\{/g) || []).length, 0);
    const было = ДОЛГ[ф];
    if (было === undefined) лишние.push(ф + ': новый блок <style>, правил ' + правил);
    else if (правил > было) лишние.push(ф + ': блок разросся — было ' + было + ' правил, стало ' + правил);
});

правило('css не живёт внутри html',
    лишние.length === 0,
    'Блоков <style> в разметке прибавилось: ' + лишние.length + '.\n' +
    лишние.join('\n') + '\n\n' +
    'Заходом B3 из index.html, index-en.html и index-kg.html снесены блоки\n' +
    'на 16, 28 и 12 правил — они переопределяли то, что и так есть в css,\n' +
    'и переопределяли ПО-РАЗНОМУ на трёх языках. Стиль внутри html не\n' +
    'виден ни одному прибору, который читает css, не кешируется и живёт\n' +
    'ровно до того дня, когда его копию на другом языке забудут поправить.\n' +
    'Долг трёх страниц скачивания назван в ДОЛГ выше — он ждёт своей\n' +
    'очереди, но РАСТИ ему это правило не даёт.');

/* ───────── вывод ───────── */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      цвет с именем: 3 правила');
    console.log('          242 места ПЕРЕСЧИТАНЫ, а не вспомнены');
    console.log('          цветовые токены объявлены по одному разу');
    console.log('          css в html не прибавилось');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  цвет с именем — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          x ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
