#!/usr/bin/env node
/**
 * СТОЛБЦОВ В colgroup СТОЛЬКО ЖЕ, СКОЛЬКО В ШАПКЕ (h158, 12.11.2026).
 *
 * ОТКУДА. Жалоба Кости по Тренерам: «всё в ряд идёт». Замер показал
 * ДЕВЯТЬ <col> против ВОСЬМИ <th>: лишний первый сдвигал раздачу на
 * колонку, ФИО получали 36 точек от колонки-значка, а теги — ширину
 * цены. Шесть чипов (539 суммарной ширины) не влезали и вставали
 * столбиком, ряд рос до 169 вместо обычных ~70.
 *
 * ПОЧЕМУ ПРАВИЛО ОБЩЕЕ, А НЕ ПРО ТРЕНЕРОВ: такой перекос не виден
 * глазами — таблица просто «некрасивая». Прибор считает пары colgroup/
 * thead во ВСЕХ разделах админки и падает на любом расхождении.
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const дир = path.join(КОРЕНЬ, 'js/admin/sections');
const беды = [];
let пар = 0;

for (const ф of fs.readdirSync(дир)) {
    if (!ф.endsWith('.js')) continue;
    const т = fs.readFileSync(path.join(дир, ф), 'utf8');
    /* Берём каждый colgroup и ближайший за ним thead — они всегда идут
       подряд в одной сборке разметки. */
    const рег = /<colgroup>([\s\S]*?)<\/colgroup>([\s\S]{0,2000}?)<\/tr><\/thead>/g;
    let м;
    while ((м = рег.exec(т))) {
        пар++;
        const колонок = (м[1].match(/<col\b/g) || []).length;
        /* ПРИБОР СЧИТАЕТ РАЗМЕТКУ, А НЕ БУКВЫ «<th». Половина разделов
           собирает заголовки функцией (crtColHeader и такие же): первая
           редакция этого правила увидела у Кортов два <th> вместо десяти
           и показала беду там, где её нет. Зовы генераторов считаются
           наравне с буквальными ячейками. */
        const шапок = (м[2].match(/<th\b/g) || []).length +
            (м[2].match(/\b\w*ColHeader\s*\(/g) || []).length;
        if (колонок !== шапок) {
            const строка = т.slice(0, м.index).split('\n').length;
            беды.push(ф + ':' + строка + ' — <col> ' + колонок + ', <th> ' + шапок);
        }
    }
}

/* ХРАПОВИК: в админке ровно два colgroup — Тренеры и Корты. Станет
   меньше — либо раздел снесли, либо прибор ослеп; и то и другое нельзя
   пропускать молча. */
if (пар < 2) {
    console.error('СТОЛБЦЫ ТАБЛИЦ — НАРУШЕНО:');
    console.error('  · пар colgroup/thead найдено ' + пар + ', замерено 2 — прибор ослеп либо раздел снесли');
    process.exit(1);
}
if (беды.length) {
    console.error('СТОЛБЦЫ ТАБЛИЦ — НАРУШЕНО:');
    for (const б of беды) console.error('  · ' + б);
    console.error('    Лишний или недостающий <col> сдвигает ВСЕ ширины на одну колонку.');
    process.exit(1);
}
console.log('столбцы таблиц: ' + пар + ' пар colgroup/thead, ширины розданы по своим колонкам');
