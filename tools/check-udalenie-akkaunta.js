/**
 * ЗАМОРОЗКА СТРАНИЦЫ УДАЛЕНИЯ АККАУНТА (кусок 204, 27.10.2026).
 *
 * ЗАЧЕМ. Google Play требует в `Data safety → Data deletion` ПУБЛИЧНЫЙ
 * URL, по которому человек читает, как удалить учётную запись и что при
 * этом происходит. Кнопка внутри кабинета этому требованию не отвечает:
 * до неё надо войти. Без URL приложение не проходит проверку — это и
 * был блокер Ю5 к выпуску Android.
 *
 * ТЕКСТ СВЕРЕН С КОДОМ, А НЕ НАПИСАН ПО ПАМЯТИ:
 *   • `functions/delete-account` помечает профиль и даёт 30 дней на
 *     возврат (`GRACE_DAYS = 30`), действие `restore` возвращает;
 *   • `functions/purge-deleted-accounts` через срок удаляет учётную
 *     запись входа, баллы лояльности и настройки уведомлений;
 *   • КАРТОЧКА ИГРОКА ОСТАЁТСЯ — ей ставится `account_deleted_at`, и
 *     `js/player.js:682` рисует на ней метку «Аккаунт удалён».
 *
 * ПОПУТНО ИСПРАВЛЕНА НЕПРАВДА В КАБИНЕТЕ. Окно удаления обещало потерю
 * места в рейтинге и истории матчей — ни то, ни другое не пропадает:
 * результаты принадлежат турнирам, в которых человек играл, и стереть
 * их значило бы изменить итоги чужих соревнований. Окно пугало тем,
 * чего не происходит, и молчало о том, что остаётся.
 *
 *   node tools/check-udalenie-akkaunta.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const есть = ф => fs.existsSync(path.join(КОРЕНЬ, ф));

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const СТРАНИЦЫ = ['pages/delete-account.html', 'pages/delete-account-en.html',
                   'pages/delete-account-kg.html'];
const КАБИНЕТ = чит('js/dashboard.js');
const ФУНКЦИЯ = чит('supabase/functions/delete-account/index.ts');
const УБОРЩИК = чит('supabase/functions/purge-deleted-accounts/index.ts');

/* ══ 1. СТРАНИЦА ЕСТЬ НА ТРЁХ ЯЗЫКАХ ═══════════════════════════════════ */

const нет = СТРАНИЦЫ.filter(ф => !есть(ф));
правило('страница удаления есть на всех трёх языках',
    нет.length === 0,
    'нет страниц: ' + нет.join(', ') + '.\n' +
    'Google Play требует публичный URL, и он должен открываться на языке\n' +
    'человека так же, как остальные правовые страницы');

/* ДОСТУПНА БЕЗ ВХОДА. Страница, которая сама требует входа, этому
   требованию не отвечает — ровно поэтому кнопки в кабинете было мало. */
const сВходом = СТРАНИЦЫ.filter(ф => есть(ф) &&
    /auth-guard\.js|KSLT_AUTH\.требоватьВход|location\.replace\('auth/.test(чит(ф)));
правило('страница открывается без входа',
    сВходом.length === 0,
    'страниц за входом: ' + сВходом.join(', ') + '.\n' +
    'Проверяющий Google не входит в аккаунт — он открывает URL');

/* ══ 2. СТРАНИЦА ГОВОРИТ ТО, ЧТО ДЕЛАЕТ КОД ════════════════════════════ */

/* СРОК БЕРЁТСЯ ИЗ ФУНКЦИИ, А НЕ ИЗ ПАМЯТИ: поменяют `GRACE_DAYS` — и
   правило упадёт, а не оставит на странице прежнее число. */
const мСрок = /GRACE_DAYS\s*=\s*(\d+)/.exec(ФУНКЦИЯ);
const срок = мСрок ? мСрок[1] : null;
/* СРОК ИЩЕТСЯ РЯДОМ СО СЛОВОМ, А НЕ ПРОСТО ЧИСЛОМ: голое «14» нашлось бы
   в версии файла (`?v=14`) и в политике, и правило зеленело бы на любом
   сроке. Поймал прувер. */
const рядом = new RegExp(срок + '\\s*(?:дн|күн|day)', 'i');
const словом = { '30': /тридцат|отуз|thirty/i };
const безСрока = СТРАНИЦЫ.filter(ф => есть(ф) &&
    !рядом.test(чит(ф)) && !(словом[срок] && словом[срок].test(чит(ф))));

правило('срок возврата на странице совпадает с кодом',
    !!срок && безСрока.length === 0,
    'срок в коде: ' + срок + ', страниц без него: ' + безСрока.join(', ') + '.\n' +
    'Человек прочитает одно, а функция сделает другое');

/* КАРТОЧКА ОСТАЁТСЯ — И СТРАНИЦА ОБ ЭТОМ ГОВОРИТ. Это главное, в чём
   легко соврать: уборщик помечает карточку, а не удаляет её. */
правило('уборщик помечает карточку игрока, а не удаляет её',
    /\.from\('players'\)[\s\S]{0,120}account_deleted_at/.test(УБОРЩИК) &&
    !/\.from\('players'\)[\s\S]{0,60}\.delete\(\)/.test(УБОРЩИК),
    'уборщик стал удалять карточку игрока — тогда текст страницы и\n' +
    'метка «Аккаунт удалён» на карточке говорят неправду');

/* ПРИЗНАК ТРЕБУЕТ ОБЪЯСНЕНИЯ, А НЕ ОДНОГО СЛОВА. Первая редакция искала
   метку «Аккаунт удалён» — и откат, убравший объяснение, её не ронял:
   сама метка в тексте осталась. Нужны ОБА куска: что карточка остаётся и
   что на ней появляется метка. */
правило('страница называет, что карточка игрока остаётся',
    СТРАНИЦЫ.filter(ф => есть(ф) && (т =>
        /Аккаунт удалён|Account deleted|Аккаунт өчүрүлгөн/.test(т) &&
        /карточка игрока[^.]{0,80}остаётся|player card[^.]{0,80}stays|картасы калат/i.test(т)
    )(чит(ф))).length === 3,
    'хотя бы одна страница молчит о том, что карточка остаётся. Это\n' +
    'главное, в чём легко соврать: уборщик её ПОМЕЧАЕТ, а не удаляет');

/* ══ 3. КАБИНЕТ НЕ ОБЕЩАЕТ ЛИШНЕГО ════════════════════════════════════ */

правило('окно удаления не обещает потерю рейтинга и истории матчей',
    !/Место в рейтинге и набранные очки/.test(КАБИНЕТ) &&
    !/История турниров и матчей/.test(КАБИНЕТ) &&
    !/Tournament and match history/.test(КАБИНЕТ),
    'окно снова пугает тем, чего не происходит: результаты принадлежат\n' +
    'турнирам, карточка остаётся с меткой «Аккаунт удалён»');

/* КЛЮЧ НУЖЕН НА ВСЕХ ТРЁХ ЯЗЫКАХ: один снятый не ронял правило, потому
   что `deleteMore:` оставался у двух других. Поймал прувер. */
правило('из окна удаления ведёт ссылка на публичную страницу',
    (КАБИНЕТ.match(/deleteMore:/g) || []).length === 3 &&
    /href="delete-account' \+\s*KSLT_YAZYK\.суффикс/.test(КАБИНЕТ),
    'человеку некуда прочитать подробности до нажатия, а тот же адрес\n' +
    'стоит в Play Console');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      удаление аккаунта: 7 правил');
    console.log('          страница на трёх языках, открывается без входа');
    console.log('          срок возврата взят из кода: ' + срок + ' дней');
    console.log('          карточка игрока остаётся, и страница это говорит');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  удаление аккаунта — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
