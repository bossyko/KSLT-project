'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ДОМ = 'mobile/www/js';
const SQL = 'sql/доступ/players-public-view.sql';

/* НАЗВАННЫЕ ИСКЛЮЧЕНИЯ — С ПРИЧИНОЙ, А НЕ СПИСКОМ. Прямое чтение
   таблицы законно там, где нужны столбцы, которых в витрине нет
   нарочно. */
const ИСКЛЮЧЕНИЯ = {
    'mobile/www/js/screens/tournaments.js':
        'нужны `banned_until` и `ban_reason` — ими объясняют отказ в записи',
    'mobile/www/js/kslt-kategorii.js':
        'дом, копия с сайта; сводится вместе с сайтом, а не в одиночку'
};

function чит(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}
function безКом(т) {
    return (т || '').replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');
}
function файлы(д, вых) {
    вых = вых || [];
    const п = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(п)) return вых;
    for (const э of fs.readdirSync(п, { withFileTypes: true })) {
        const о = д + '/' + э.name;
        if (э.isDirectory()) файлы(о, вых);
        else if (э.name.endsWith('.js')) вых.push(о);
    }
    return вых;
}

/** Прямое чтение таблицы: `from('players')` без `_public`. */
function прямые(т) {
    return (безКом(т).match(/from\(\s*['"]players['"]\s*\)/g) || []).length;
}
/** Звёздочка у players или у витрины — у таблицы она и упирается в отказ. */
function звёздочки(т) {
    const к = безКом(т);
    const м = к.match(/from\(\s*['"]players['"]\s*\)[\s\S]{0,80}?\.select\(\s*['"]\*['"]/g);
    return м ? м.length : 0;
}

const все = файлы(ДОМ);
const нарушители = [];
const звёзды = [];
for (const ф of все) {
    const т = чит(ф);
    if (!т) continue;
    if (звёздочки(т)) звёзды.push(ф);
    if (прямые(т) && !ИСКЛЮЧЕНИЯ[ф]) нарушители.push(ф);
}

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('звёздочки у таблицы игроков нет',
    звёзды.length === 0,
    '`select(\'*\')` у `players`: ' + звёзды.map(ф => '\n  ' + ф).join('') +
    '\nПрава выданы ПО СТОЛБЦАМ, и звёздочка упирается в отказ — это\n' +
    'записано в `' + SQL + '` словами «`select=*` от анонима упирается\n' +
    'в отказ». Человек при этом видит не ошибку, а «не найдено».\n' +
    'Звёздочка законна у витрины `players_public`: она и есть список\n' +
    'разрешённых столбцов.');

правило('карточки игроков читаются из витрины',
    нарушители.length === 0,
    'Прямое чтение `players` вне названных исключений: ' +
    нарушители.map(ф => '\n  ' + ф).join('') +
    '\nПубличные карточки читает витрина `players_public`. Перечислять\n' +
    'столбцы руками в каждом экране значит завести второй список, и\n' +
    'разойдётся он молча — до первого отказа у человека на экране.\n' +
    'Нужен закрытый столбец (бан) — добавь файл в исключения С ПРИЧИНОЙ.');

правило('у каждого исключения названа причина',
    Object.keys(ИСКЛЮЧЕНИЯ).every(ф => {
        const п = ИСКЛЮЧЕНИЯ[ф];
        return typeof п === 'string' && п.trim().length > 20 && чит(ф) !== null;
    }),
    'Исключение без причины — это просто дыра в правиле. У каждого файла\n' +
    'в списке обязана стоять строка, объясняющая, какой закрытый столбец\n' +
    'ему нужен, и сам файл обязан существовать.');

правило('витрина заведена и описана в sql',
    (function () {
        const т = чит(SQL);
        return !!т && /CREATE VIEW public\.players_public/.test(т) &&
               /GRANT SELECT ON public\.players_public TO anon, authenticated/.test(т);
    })(),
    'В `' + SQL + '` нет витрины или права на неё не выданы. Без витрины\n' +
    'правило выше требует невозможного.');

правило('прибор отличает таблицу от витрины',
    (function () {
        /* ОБРАЗЕЦ ВНУТРЬ ПРИБОРА: имена различаются одним хвостом, и
           прибор, считающий `players_public` за `players`, назвал бы
           бедой ровно верный код. */
        const о = "a = from('players').select('*');\n" +
                  "b = from('players_public').select('*');\n" +
                  "c = from('players').select('id, name');\n" +
                  "/* from('players').select('*') в подписи */\n";
        return прямые(о) === 2 && звёздочки(о) === 1;
    })(),
    'Образец внутри прибора: таблица со звёздочкой, витрина со\n' +
    'звёздочкой, таблица со списком столбцов и упоминание в подписи.\n' +
    'Ждём два прямых чтения и ровно одну звёздочку у таблицы.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      витрина игроков: все ' + всего + ' правил держатся');
    console.log('          прямых чтений вне исключений 0, звёздочек у таблицы 0');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  витрина игроков — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
