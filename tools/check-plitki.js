#!/usr/bin/env node
/**
 * ПЛИТКА ЧИСЛА С ПОДПИСЬЮ — ОДИН ДОМ РАЗМЕТКИ (шаг A3.5, 29.10).
 *
 * ЗАМЕР 29.10: одно понятие жило под ВОСЬМЬЮ семьями имён, строителей
 * было ЧЕТЫРЕ плюс склейки руками:
 *   `db-stat-*` кабинет сайта · `stat-*` витрина главной · `stat-*`
 *   профиль приложения · `pd-stat-*` карточки игрока и тренера ·
 *   `ad-stat-*` админка · `pp-stat-*` страница игрока сайта.
 *
 * ПЕРЕЕХАЛО В ДОМ: кабинет сайта и приложение (профиль, парный блок,
 * карточка игрока). Имя дома — `kst-*`, третье: `stat-*` на сайте УЖЕ
 * ЗАНЯТО витриной главной (`css/style.css:1933`, `clamp` по ширине
 * окна), а `db-` в приложении соврало бы.
 *
 * НЕ ПЕРЕЕХАЛО, И ЭТО РЕШЕНИЕ, А НЕ ЗАБЫВЧИВОСТЬ:
 *   · страница игрока сайта — кегль цифры 21 стоит ПО СЛОВУ КОСТИ
 *     («сказал мельче», доска 722:12). Свести под одним именем значит
 *     потерять это решение; нужен модификатор вида — долг A3.5б;
 *   · витрина главной — другие данные (число игроков и турниров);
 *   · админка — плитка несёт иконку;
 *   · карточки тренера — цена и опыт, не статистика игрока.
 *
 * Запуск: node tools/check-plitki.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
function безКомJS(т) {
    return т
        .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
        .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));
}

const ДОМ_САЙТ = 'js/kslt-plitki.js';
const ДОМ_ПРИЛ = 'mobile/www/js/kslt-plitki.js';

console.log('\n  ПЛИТКА ЧИСЛА С ПОДПИСЬЮ — ОДИН ДОМ\n');

правило('дом объявлен',
    /KSLT_PLITKI/.test(чит(ДОМ_САЙТ)) &&
    /API\.плитка\s*=/.test(чит(ДОМ_САЙТ)) &&
    /API\.сетка\s*=/.test(чит(ДОМ_САЙТ)) &&
    /API\.подпись\s*=/.test(чит(ДОМ_САЙТ)),
    'Нужны три зова: `плитка`, `сетка`, `подпись`.');

правило('копии дома побайтово равны',
    чит(ДОМ_САЙТ) === чит(ДОМ_ПРИЛ),
    'Дом лежит копией в приложении. Разошлись — значит разметка плитки\n' +
    'снова строится двумя способами.');

правило('дом экранирует значение',
    /KSLT_экранировать/.test(чит(ДОМ_САЙТ)) &&
    /\[&<>"'\]/.test(чит(ДОМ_САЙТ)),
    'Плитка печатает значение из базы — человек вписывает его сам.\n' +
    'Без экранирования кавычка в нём даёт обработчик. Дом берёт общее\n' +
    'экранирование, если оно есть, иначе своё.');

правило('ноль в сдвиге не рисуется',
    /сдвиг !== 0/.test(чит(ДОМ_САЙТ)),
    '«+0» ничего не сообщает, поэтому нулевой сдвиг не рисуется вовсе.');

/* ---- СТАРЫХ СЕМЕЙ НЕ ОСТАЛОСЬ ТАМ, ОТКУДА ПЕРЕЕХАЛИ ---- */
const ПЕРЕЕХАЛИ = [
    ['js/dashboard.js',                      /db-stat-card|db-stats-grid|db-stats-note/],
    ['css/dashboard.css',                    /db-stat-card|db-stats-grid|db-stats-note/],
    ['mobile/www/js/screens/profile.js',     /class="stat-card"|class="stats-grid"/],
    ['mobile/www/js/app.js',                 /class="stat-card"|class="stats-grid/],
    ['mobile/www/css/app.css',               /\.stat-card|\.stats-grid/]
];
ПЕРЕЕХАЛИ.forEach(([ф, пр]) => {
    правило('старых имён нет в `' + ф.split('/').pop() + '`',
        !пр.test(безКомJS(чит(ф))),
        'Экран переехал в дом — старая семья имён там жить не должна.\n' +
        'Признак: ' + пр);
});

правило('`db-status-*` не пострадал при переименовании',
    (чит('css/dashboard.css').match(/db-status/g) || []).length >= 3,
    '`db-status-badge` содержит подстроку `db-stat` — замена подстрокой\n' +
    'сломала бы его. Переименование шло ПОИМЁННО, и это правило\n' +
    'сторожит, что состояния целы.');

/* ---- ПЕРЕЕХАВШИЕ ЗОВУТ ДОМ ---- */
[['js/dashboard.js', 'кабинет сайта'],
 ['mobile/www/js/screens/profile.js', 'профиль приложения'],
 ['mobile/www/js/app.js', 'парный блок приложения'],
 ['mobile/www/js/screens/player-detail.js', 'карточка игрока']].forEach(([ф, имя]) => {
    правило(имя + ' зовёт дом',
        /KSLT_PLITKI/.test(безКомJS(чит(ф))),
        'Разметку плитки обязан давать дом, а не склейка на месте.');
});

/* ---- ДОМ ПОДКЛЮЧЁН ВЕЗДЕ, ГДЕ ЕГО ЗОВУТ ---- */
const безДома = [];
['pages/dashboard.html', 'pages/dashboard-en.html', 'pages/dashboard-kg.html',
 'mobile/www/index.html'].forEach(ф => {
    if (!/kslt-plitki\.js/.test(чит(ф))) безДома.push(ф);
});
правило('дом подключён во всех разметках',
    безДома.length === 0,
    'Страницы зовут дом, но не грузят его — ' + безДома.length + ':\n' +
    безДома.map(с => '  · ' + с).join('\n') +
    '\nПропущенная страница МОЛЧИТ: плитки просто не нарисуются.');

/* ---- КРАСКА ЕСТЬ В ОБОИХ ПРОДУКТАХ ---- */
/* ИМЯ ПРАВИЛА — ТОЖЕ ЯКОРЬ: прувер ищет его строкой, поэтому
   склейка обязана давать «у приложения», а не «у приложение». */
[['css/dashboard.css', 'сайта'], ['mobile/www/css/app.css', 'приложения']].forEach(([ф, имя]) => {
    const css = чит(ф);
    правило('краска плитки есть у ' + имя,
        /\.kst-card\s*\{/.test(css) && /\.kst-value\s*\{/.test(css) &&
        /* ПРИЗНАК ЛОВИТ БАЗОВОЕ ПРАВИЛО, А НЕ ПРИСТАВКУ. Первая редакция
           искала `.kst-change` — и не упала, когда снесли само правило:
           остались `.kst-change.up` и `.kst-change.down`. Третий раз за
           день: ПРАВИЛО, СЧИТАЮЩЕЕ ТЕКСТ, ЛОВИТ СЛОВА, А НЕ БЕДУ. */
        /\.kst-label\s*\{/.test(css) && /\.kst-grid\s*\{/.test(css) &&
        /\.kst-change\s*\{/.test(css),
        'Одно имя на одно понятие не значит один вид — значит ОДНО\n' +
        'МЕСТО, где вид задаётся. Правила `kst-*` обязаны быть у каждого\n' +
        'продукта, включая `kst-change`: иначе первый зов сдвига\n' +
        'нарисует неокрашенный текст.');
});

/* ---- СТРАНИЦА ИГРОКА ОСТАЛАСЬ СВОЕЙ, И ПРИЧИНА НАПИСАНА ---- */
правило('долг страницы игрока назван в коде, а не замолчан',
    /ПО СЛОВУ КОСТИ/.test(чит('js/player.js')) &&
    /pp-stat-num/.test(чит('js/player.js')),
    'Страница игрока не переехала нарочно: кегль 21 стоит по слову\n' +
    'Кости (доска 722:12). Причина обязана быть написана рядом с\n' +
    'кодом — иначе следующий читающий сведёт и потеряет решение.');

правило('в разметке кабинета нет размеров строкой',
    !/db-stats-grid" style="margin-bottom/.test(чит('js/dashboard.js')) &&
    /kst-grid-pay/.test(чит('css/dashboard.css')),
    'У сетки платежей отступ стоял прямо в разметке. Такие размеры\n' +
    '«жили отдельной жизнью и на телефоне выходили вдвое крупнее» —\n' +
    'вынесены в класс `kst-grid-pay`.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      плитки: все ' + держится + ' правил держатся\n');
}
