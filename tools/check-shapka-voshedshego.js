const fs = require('fs');
const path = require('path');

const корень = path.resolve(__dirname, '..');
const безКомм = т => т.replace(/\/\*[\s\S]*?\*\//g, '');
const стиль = безКомм(fs.readFileSync(path.join(корень, 'css/style.css'), 'utf8'));

const ошибки = [];
const проверить = (имя, условие, почему) => { if (!условие) ошибки.push(имя + ' — ' + почему); };

/* ТЕЛО ПРАВИЛА БЕРЁТСЯ ПО ТОЧНОМУ СЕЛЕКТОРУ, А НЕ ПО ПОДСТРОКЕ: иначе
   `.logo` читает `.logo-text`, а `.user-dropdown-item` — свой же
   `:hover`. ЯКОРЬ, ЧИТАЮЩИЙ СОСЕДА, СТОРОЖИТ ЧУЖОЕ. */
function тело(селектор, текст) {
    const рег = new RegExp('(?:^|[},])\\s*' + селектор.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '\\s*\\{([^}]*)\\}', 'm');
    const м = текст.match(рег);
    return м ? м[1] : null;
}

/* Медиа-блоки с указателем — те же, что у check-cel-po-ukazatelyu. */
function блоки(текст) {
    const итог = [];
    for (const м of текст.matchAll(/@media([^{]*)\{/g)) {
        let гл = 1, j = м.index + м[0].length;
        while (j < текст.length && гл) {
            if (текст[j] === '{') гл++;
            else if (текст[j] === '}') гл--;
            j++;
        }
        итог.push({ условие: м[1].trim(), тело: текст.slice(м.index + м[0].length, j) });
    }
    return итог;
}
const подУказателем = блоки(стиль).filter(б => /pointer/.test(б.условие)).map(б => б.тело).join('\n');

/* 1 и 2. ПУНКТ ПАНЕЛИ — ОДНА СТУПЕНЬ ДЛЯ ССЫЛКИ И ДЛЯ КНОПКИ. */
const пункт = тело('.user-dropdown-item', стиль);
проверить('пункт панели объявлен', пункт !== null,
    'правило .user-dropdown-item пропало из css/style.css');
проверить('высота пункта — ступень кнопок, а не сумма отступов',
    пункт && /min-height:\s*var\(--btn-h-/.test(пункт),
    'без min-height со ступени высота считается из padding и кегля: замер 12.11 дал 37 у ссылки и 33 у кнопки, оба мимо шкалы 28 · 36 · 44 · 52');
проверить('высота строки пункта задана',
    пункт && /line-height:/.test(пункт),
    'ссылка и кнопка нормализуют line-height по-разному — ровно отсюда взялась разница 37 против 33');

/* 3. ПАНЕЛЬ НЕ ВЫЛЕЗАЕТ ЗА НИЖНИЙ КРАЙ. */
const панель = тело('.user-dropdown-menu', стиль);
проверить('панель объявлена', панель !== null, 'правило .user-dropdown-menu пропало');
проверить('предел высоты панели считается от ступени шапки',
    панель && /max-height:\s*calc\([^)]*var\(--header-h\)/.test(панель),
    'без предела панель уезжает ниже окна: на телефоне боком (390 высотой) шапка 64 плюс панель 334 не помещаются, и нижние пункты недостижимы');
проверить('панель прокручивается сама',
    панель && /overflow-y:\s*auto/.test(панель),
    'предел без прокрутки просто обрезает пункты');

/* 4. ЦЕЛЬ АВАТАРА ПОД ПАЛЬЦЕМ — ОБЕ СТОРОНЫ. */
const кнопка = тело('.user-dropdown-toggle', подУказателем);
проверить('кнопка аватара переведена под указатель', кнопка !== null,
    'нет правила .user-dropdown-toggle в медиа с указателем — на телефоне цель останется 38');
проверить('у кнопки аватара заданы ОБЕ стороны',
    кнопка && /min-height:\s*var\(--btn-h-/.test(кнопка) && /min-width:\s*var\(--btn-h-/.test(кнопка),
    'на телефоне имя скрыто и ширину держит кружок аватара 28 — одной высоты мало, замер дал 38x44');

/* 5. ЛОГОТИП ПОД ПАЛЬЦЕМ НЕ УЖЕ СТУПЕНИ. */
const лого = тело('.logo', подУказателем);
проверить('логотип имеет нижний предел ширины под указателем',
    лого && /min-width:\s*var\(--btn-h-/.test(лого),
    'на кыргызском при 1180 ряд длиннее и логотип сжимался до 31 при высоте 44 — ниже минимума касания');

if (ошибки.length) {
    console.error('ШАПКА ВОШЕДШЕГО — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
