#!/usr/bin/env node
/**
 * ДОСТУПНОСТЬ ПРИЛОЖЕНИЯ — ЗАМОРОЗКА КУСКА 215 (28.10).
 *
 * ЗАМЕР ДО. Из одиннадцати экранов разметку для диктора имел ОДИН —
 * рейтинг. У остальных десяти: ни одного `role`, ни одного `aria`.
 * Списков не было вовсе: диктор читал карточки турниров, новостей,
 * кортов, тренеров и игроков подряд, не говоря ни «список», ни «пункт
 * такой-то из такого-то». Ряды фильтров стояли без имени: «Все,
 * Предстоящие, Текущие» — без того, ЧТО этим выбирают. Выбранная кнопка
 * отличалась только классом `active`, то есть только цветом: диктору она
 * ничем не отличалась от остальных.
 *
 * ЗАМЕР ПОСЛЕ, в браузере на 375×812, загрузкой на нужной ширине:
 * восемь экранов с данными — у каждого ровно один именованный список,
 * каждая карточка пункт, чужих детей в списках ноль.
 *   турниры 10/10 «Турниры»       новости 34/34 «Новости»
 *   рейтинг 3 «Первая тройка» + таблица    игроки 5+окно «Поиск игрока»
 *   тренеры 1/1 «Тренеры»         корты 5+окно «Корты»
 *   Live 1/1 «Матчи в прямом эфире»        спонсоры 10/10 «Спонсоры»
 *
 * ПОПУТНО НАЙДЕНО ЖИВОЕ, вторая такая беда за приложение: экран Live
 * сортировал запрос по `updated_at`, которого у `live_matches` НЕТ.
 * Postgres отвечал 400, `r.data` приходил пустым, и экран был пуст
 * ВСЕГДА — даже когда матч идёт. Проверено чтением базы: столбцов у
 * таблицы 32, `updated_at` среди них нет; с сортировкой по `created_at`
 * тот же запрос вернул идущий матч. Ошибку запроса теперь видно в
 * консоли, а не проглатывается молча.
 *
 * ОКНО ГОСТЯ — ПУНКТ СПИСКА, А НЕ ЧУЖОЙ. Оно лежит в потоке внутри
 * контейнера (`position: relative; margin-top: -120px`), поэтому у
 * `role="list"` оказывалось дитя не-`listitem` — структура, на которой
 * Safari теряет список целиком. Так же поступает и FAANG: «войдите,
 * чтобы увидеть остальное» идёт последним пунктом списка, а не поверх.
 *
 * ЧЕГО ЗДЕСЬ НЕТ. Диалоги: четырнадцать окон (`td-overlay`, `otp`,
 * `tg-reg`, меню, уведомления) без `role="dialog"`, без возврата
 * фокуса и без его удержания. Это поведение, а не разметка, и идёт
 * отдельным куском — записано в трекер.
 *
 * Запуск: node tools/check-dostupnost-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
function безСлов(отн) {
    return чит(отн).replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const РАЗМЕТКА = 'mobile/www/index.html';
const ОБОЛОЧКА = 'mobile/www/js/app.js';
const СЛОВАРЬ = 'mobile/www/js/i18n.js';

const разметка = безСлов(РАЗМЕТКА);
const оболочка = безСлов(ОБОЛОЧКА);
const словарь = чит(СЛОВАРЬ);

/* ── 1. ОБОЛОЧКА: ТРИ ОБЛАСТИ ЭКРАНА НАЗВАНЫ ── */
правило(
    'шапка — область `banner`',
    /<header class="header"[^>]*role="banner"/.test(разметка),
    'Диктор обходит страницу областями. Без `banner` шапка —\n' +
    'безымянный набор кнопок посреди ничего.');

правило(
    'экраны лежат в `main`',
    /<main class="screens"/.test(разметка) && /<\/main>/.test(разметка),
    'Главная область страницы одна, и это экраны, а не шапка\n' +
    'и не полоса вкладок. Был `div`.');

правило(
    'полоса вкладок — область `navigation` с переводимым именем',
    /<nav class="tab-bar"[^>]*role="navigation"[^>]*data-i18n-aria="menu\.sections"/.test(разметка),
    'Имя области обязано переводиться: единственное зашитое —\n' +
    '«Разделы» — оставалось русским на английском и киргизском.');

/* ── 2. ТЕКУЩАЯ ВКЛАДКА НАЗВАНА, И ПРИЗНАК ЕДЕТ С КЛАССОМ ── */
правило(
    'активная вкладка помечена `aria-current` в разметке',
    /class="tab-item active"[^>]*aria-current="page"/.test(разметка),
    'До первого нажатия активная вкладка отличалась только цветом.');

(function () {
    const снятие = /removeAttribute\('aria-current'\)/.test(оболочка);
    const постановка = /setAttribute\('aria-current', 'page'\)/.test(оболочка);
    /* Признак и класс обязаны стоять в одном месте: разъедутся — диктор
       будет называть открытым прежний экран. */
    const рядомСнятие = /classList\.remove\('active'\);[\s\S]{0,120}?removeAttribute\('aria-current'\)/.test(оболочка);
    const рядомПостановка = /classList\.add\('active'\);[\s\S]{0,120}?setAttribute\('aria-current', 'page'\)/.test(оболочка);
    правило(
        '`aria-current` ставится и снимается там же, где класс вкладки',
        снятие && постановка && рядомСнятие && рядомПостановка,
        'Снятие: ' + снятие + ', постановка: ' + постановка + ',\n' +
        'рядом с классом: снятие ' + рядомСнятие + ', постановка ' + рядомПостановка);
})();

/* ── 3. РЯДЫ ФИЛЬТРОВ: У КАЖДОГО ИМЯ, И ОНО ПЕРЕВОДИТСЯ ── */
(function () {
    /* КЛАСС У РЯДА МОЖЕТ БЫТЬ НЕ ОДИН: полоса кортов носит ещё и
       `kslt-dd-row`, и точное написание `class="filters-row"` её не
       видело — поймано 02.11, прибор насчитал пять рядов из шести.
       ПРИБОР, ЗНАЮЩИЙ ТОЧНОЕ НАПИСАНИЕ, ОТСТАЁТ ОТ РАЗМЕТКИ. */
    const ряды = разметка.match(/<div class="[^"]*\bfilters-row\b[^"]*"[^>]*>/g) || [];
    /* ПЯТЬ, А НЕ ВОСЕМЬ — С 02.11. Три ряда кортов (тип, город,
       покрытие) стали тремя выпадашками в одной полосе: слово Кости
       «фильтры наверно надо будет сделать выпадающем меню». Полоса
       кортов осталась рядом фильтров и считается здесь, а доступность
       её выпадашек — `role="listbox"`, `aria-haspopup`, `aria-expanded`,
       `aria-selected` — стережёт `check-vypadashka.js`, потому что
       живёт она в доме, а не в разметке. */
    правило(
        'все ряды фильтров найдены',
        ряды.length === 6,
        'Ждали шесть рядов (турниры, новости, баттлы, пол и уровень\n' +
        'игрока, полоса фильтров кортов), нашли ' + ряды.length + '.\n' +
        'Появился новый ряд — он тоже обязан быть названной группой.');

    const безГруппы = ряды.filter(р => !/role="group"/.test(р));
    правило(
        'каждый ряд фильтров — группа',
        безГруппы.length === 0,
        'Без `role="group"` имя ряду приписать некуда: диктор читает\n' +
        'кнопки подряд, не сказав, что ими выбирают.\n' +
        'Без группы: ' + безГруппы.join(' '));

    const безИмени = ряды.filter(р => !/data-i18n-aria="a11y\./.test(р));
    правило(
        'имя каждого ряда берётся из словаря',
        безИмени.length === 0,
        'Зашитое имя останется русским на двух других языках.\n' +
        'Без ключа словаря: ' + безИмени.join(' '));
})();

/* ── 4. НАЖАТОСТЬ ЕДЕТ ВМЕСТЕ С КЛАССОМ ── */
(function () {
    const кнопки = разметка.match(/<button class="filter-chip[^>]*>/g) || [];
    const безНажатости = кнопки.filter(к => !/aria-pressed="(true|false)"/.test(к));
    правило(
        'каждая кнопка фильтра в разметке говорит, нажата ли она',
        кнопки.length >= 17 && безНажатости.length === 0,
        'Кнопок: ' + кнопки.length + ', без признака нажатости: ' +
        безНажатости.length + '.\n' +
        'Выбранный фильтр отличался только цветом.');

    const снятие = /classList\.remove\('active'\);\s*\n\s*c\.setAttribute\('aria-pressed', 'false'\)/.test(оболочка);
    const постановка = /chip\.classList\.add\('active'\);\s*\n\s*chip\.setAttribute\('aria-pressed', 'true'\)/.test(оболочка);
    правило(
        'нажатость переставляется там же, где класс кнопки',
        снятие && постановка,
        'Разъедутся — диктор назовёт выбранным прежний фильтр.\n' +
        'Снятие рядом: ' + снятие + ', постановка рядом: ' + постановка);

    /* ПРАВИЛО ПЕРЕЕХАЛО, А НЕ ИСЧЕЗЛО. До 02.11 город и покрытие кортов
       рисовались кнопками-чипами, и признак нажатости обязан был
       рисоваться вместе с ними. Теперь их рисует дом выпадашки, и
       говорит он не `aria-pressed`, а `aria-selected` на пункте списка:
       у пункта `role="option"`, нажатости у него не бывает. Сторожит
       это `check-vypadashka.js` правилом «дом не растерял доступность»
       — здесь остаётся только ПРОВЕРКА, ЧТО КОРТЫ ДЕЙСТВИТЕЛЬНО УШЛИ НА
       ДОМ, иначе правило тихо исчезло бы вместе с чипами. */
    const корты = безСлов('mobile/www/js/screens/courts.js');
    правило(
        'фильтры кортов рисует дом выпадашки, а не свои чипы',
        /KSLT_VYPADASHKA\s*\./.test(корты) && !/filter-chip/.test(корты),
        'Корты либо перестали звать `KSLT_VYPADASHKA`, либо снова рисуют\n' +
        '`filter-chip` руками. Доступность выпадашки живёт в доме и\n' +
        'стережётся `check-vypadashka.js`; вернувшиеся чипы останутся без\n' +
        'признака нажатости, как это и было до 28.10.');
})();

/* ── 5. СПИСКИ: КОНТЕЙНЕР НАЗВАН, КАРТОЧКА — ПУНКТ ── */
(function () {
    const СПИСКИ = [
        ['mobile/www/js/screens/tournaments.js', 'tournaments.title', '.tc-card', 'турниры'],
        ['mobile/www/js/screens/news.js', 'news.title', '.news-list-item', 'новости'],
        ['mobile/www/js/screens/battles.js', 'battles.title', '.battle-card', 'баттлы'],
        ['mobile/www/js/screens/courts.js', 'courts.title', '.court-card', 'корты'],
        ['mobile/www/js/screens/coaches.js', 'coaches.title', '.coach-card', 'тренеры'],
        ['mobile/www/js/screens/partners.js', 'partners.title', '.partner-card', 'поиск игрока'],
        ['mobile/www/js/screens/live.js', 'a11y.liveList', '.live-list-card', 'Live']
    ];
    СПИСКИ.forEach(function (с) {
        const т = безСлов(с[0]);
        правило(
            'контейнер списка назван: ' + с[3],
            /setAttribute\('role', 'list'\)/.test(т) &&
            т.indexOf("setAttribute('aria-label'") >= 0 &&
            т.indexOf(с[1]) >= 0,
            'Контейнер обязан объявить себя списком и назвать себя\n' +
            'ключом словаря `' + с[1] + '`: безымянный список диктор\n' +
            'читает как «список», не сказав чего.');
        правило(
            'карточка — пункт списка: ' + с[3],
            /role="listitem"/.test(т),
            'Без пункта диктор не скажет «такой-то из такого-то»,\n' +
            'и список окажется пустым при полном экране карточек.');
    });

    правило(
        'сетка спонсоров — тоже названный список',
        /class="sponsors-grid" role="list"/.test(безСлов('mobile/www/js/screens/partners.js')),
        'Десять карточек спонсоров читались подряд без списка.');
})();

/* ── 6. ОКНО ГОСТЯ — ПУНКТ, А НЕ ЧУЖОЙ В СПИСКЕ ── */
(function () {
    ['courts', 'coaches', 'partners'].forEach(function (имя) {
        const т = безСлов('mobile/www/js/screens/' + имя + '.js');
        if (т.indexOf('rr-guest-overlay') < 0) return;
        правило(
            'окно гостя — пункт списка: ' + имя,
            /class="rr-guest-overlay" role="listitem"/.test(т),
            'Окно лежит в потоке ВНУТРИ контейнера, а не поверх него.\n' +
            'Дитя не-`listitem` ломает список целиком.');
    });
    правило(
        'окно гостя рейтинга лежит ВНЕ таблицы',
        /html \+= '<\/div>';\s*\n\s*\n\s*if \(!isGuest/.test(безСлов('mobile/www/js/screens/rating.js')),
        'В рейтинге таблица закрывается до окна гостя — и это верно.\n' +
        'Уедет окно внутрь — у `role="table"` появится чужая строка.');
})();

/* ── 7. LIVE СОРТИРУЕТСЯ ПО СУЩЕСТВУЮЩЕМУ СТОЛБЦУ ── */
(function () {
    const т = безСлов('mobile/www/js/screens/live.js');
    правило(
        'Live не сортируется по `updated_at`',
        т.indexOf('updated_at') < 0,
        'Этого столбца у `live_matches` НЕТ. Postgres отвечал 400,\n' +
        'и экран был пуст всегда — даже когда матч идёт.');
    правило(
        'Live сортируется по `created_at`',
        /order\('created_at'/.test(т),
        '`created_at` есть у каждой строки, в отличие от `started_at`,\n' +
        'пустого у разминки.');
    правило(
        'ошибка запроса Live не проглатывается',
        /if \(r\.error\)/.test(т) && /console\.error\('\[KSLT live\]/.test(т),
        'Молчаливый `r.data || []` и прятал эту беду полгода:\n' +
        'пустой экран выглядел как «матчей нет».');
})();

/* ── 8. СЛОВАРЬ: ИМЕНА ДЛЯ ДИКТОРА НА ТРЁХ ЯЗЫКАХ ── */
(function () {
    const КЛЮЧИ = ['a11y.fStatus', 'a11y.fSection', 'a11y.fBattle', 'a11y.fGender',
                   'a11y.fLevel', 'a11y.fCourtType', 'a11y.fCity', 'a11y.fSurface',
                   'a11y.liveList'];
    КЛЮЧИ.forEach(function (к) {
        const стр = new RegExp("'" + к.replace('.', '\\.') + "':\\s*\\{([^}]*)\\}");
        const м = словарь.match(стр);
        правило(
            'ключ заведён на трёх языках: ' + к,
            !!м && /ru:/.test(м[1]) && /en:/.test(м[1]) && /kg:/.test(м[1]),
            'Имя для диктора — такая же подпись, как любая другая,\n' +
            'и обязана быть на всех трёх языках.');
    });

    правило(
        'подпись для диктора переводится вместе с текстом',
        /data-i18n-aria/.test(безСлов(СЛОВАРЬ)) &&
        /setAttribute\('aria-label', I18N\.t\(/.test(безСлов(СЛОВАРЬ)),
        '`updateDOM` переводил только текст. Без этого ряда ни одно\n' +
        'имя группы не сменится при смене языка.');
})();

/* ── 9. ВЕРСИИ ПОДНЯТЫ: ИНАЧЕ БРАУЗЕР ОТДАСТ ПРЕЖНИЙ ФАЙЛ ── */
(function () {
    const ВЕРСИИ = [
        ['js/i18n.js', 6], ['js/app.js', 3], ['js/screens/news.js', 2],
        ['js/screens/battles.js', 3], ['js/screens/live.js', 3],
        ['js/screens/tournaments.js', 3], ['js/screens/courts.js', 4],
        ['js/screens/coaches.js', 2], ['js/screens/partners.js', 4]
    ];
    const отставшие = [];
    ВЕРСИИ.forEach(function (в) {
        const м = разметка.match(new RegExp(в[0].replace(/[./]/g, '\\$&') + '\\?v=(\\d+)'));
        if (!м || Number(м[1]) < в[1]) отставшие.push(в[0] + ' = ' + (м ? м[1] : 'нет'));
    });
    правило(
        'версии правленых файлов подняты',
        отставшие.length === 0,
        'Правка без поднятия версии невидима: браузер отдаёт прежний\n' +
        'файл из кэша. Так новости и остались без списка в первом\n' +
        'замере — код был правлен, а версия нет.\n' +
        'Отстали: ' + отставшие.join(', '));
})();

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      доступность приложения: все ' + держится + ' правил держатся');
    console.log('          три области, восемь названных групп, семь списков\n');
}
