/**
 * ЗАМОРОЗКА ПОЛИТИКИ БЕЗОПАСНОСТИ (кусок 70, 13.10.2026).
 *
 * Померено 13.10: политика была написана руками в каждой странице, и это
 * дало ВОСЕМЬ разных вариантов плюс ВОСЕМЬ страниц без политики вовсе —
 * девять состояний одного понятия. Без политики стояли ТРИ СТРАНИЦЫ ВХОДА
 * и английская админка.
 *
 * ПРИЧИНА НЕ В ДИРЕКТИВАХ, А В СПОСОБЕ. Текст, скопированный в 92 файла,
 * расходится сам — ровно это уже было с шапкой и подвалом, пока их не
 * начал разносить tools/build-partials.js. Политику разносит он же.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ:
 *   • политика объявлена ОДИН раз, страницы её не пишут, а называют
 *     надобности: карты, ролики, живой счёт, вход, таблицы;
 *   • каждая страница продукта несёт политику;
 *   • три языка одной страницы несут ОДНУ политику;
 *   • разрешение стоит там, где оно нужно, и не стоит, где не нужно.
 *
 *   node tools/check-csp.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

/* ЧИТАЕМ СБОРКУ СЫРОЙ, И ЭТО НЕ ЛЕНЬ. Грубая чистка комментариев
   (`/*` … `*​/`) съедает объявление `CSP_НАДОБНОСТИ` целиком: в списке
   адресов стоит `wss://*.supabase.co`, а в нём есть `//*` — и чистка
   принимает это за начало комментария. 24-й случай подстроки, и первый,
   где подстрока пришла из ЧУЖОГО синтаксиса, а не из нашего. */
const СБОРКА = чит('tools/build-partials.js');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* Своя страница: инструмент просмотра, на него не ссылается ни один файл
   продукта. download оставлен вне маршрута словом Кости 12.10, но политику
   получает вместе со всеми — отдельного случая у него нет. */
const СВОИ = new Set(['_preview-mobile.html']);

const страницы = [
    ...fs.readdirSync(КОРЕНЬ).filter(ф => /^index.*\.html$/.test(ф)).map(ф => ф),
    ...fs.readdirSync(path.join(КОРЕНЬ, 'pages')).filter(ф => ф.endsWith('.html'))
        .map(ф => 'pages/' + ф)
].filter(ф => !СВОИ.has(path.basename(ф)));

const политика = {};
страницы.forEach(ф => {
    const м = чит(ф).match(/Content-Security-Policy"\s+content="([^"]*)"/);
    политика[ф] = м ? м[1] : null;
});

const директива = (п, имя) => {
    if (!п) return null;
    const д = п.split(';').map(s => s.trim()).find(s => s === имя || s.indexOf(имя + ' ') === 0);
    return д ? д.slice(имя.length).trim() : '';
};

/* ══ ОДНО ОБЪЯВЛЕНИЕ ════════════════════════════════════════════════════ */

правило('политика объявляется один раз и разносится сборкой',
    /CSP_БАЗА\s*=/.test(СБОРКА) && /CSP_НАДОБНОСТИ\s*=/.test(СБОРКА) &&
    /CSP_СТРАНИЦЫ\s*=/.test(СБОРКА) && /function cspДляСтраницы/.test(СБОРКА),
    'до 13.10 политика была написана руками в каждой из 92 страниц:\n' +
    'восемь вариантов и восемь пропусков');

правило('у сборки есть маркеры политики и вставка туда, где её не было',
    /<!-- CSP:START -->/.test(СБОРКА) && /<!-- CSP:END -->/.test(СБОРКА) &&
    /after:\s*\/\[ \\t\]\*<meta name="viewport"/.test(СБОРКА),
    'восемь страниц политики не имели вовсе: без вставки сборка прошла бы\n' +
    'мимо них молча');

правило('политика собирается из частей, а не лежит готовой строкой',
    /Object\.keys\(политика\)/.test(СБОРКА) && /д \+ ' ' \+ политика\[д\]\.join\(' '\)/.test(СБОРКА),
    'если в сборке появится готовая строка политики — значит завелось\n' +
    'второе определение понятия');

/* ══ КАЖДАЯ СТРАНИЦА НЕСЁТ ПОЛИТИКУ ════════════════════════════════════ */

const безПолитики = страницы.filter(ф => !политика[ф]);
правило('каждая страница продукта несёт политику безопасности',
    безПолитики.length === 0,
    'без политики: ' + (безПолитики.join(', ') || '—') + '\n' +
    'до 13.10 без неё стояли ТРИ страницы входа и английская админка');

const безМаркеров = страницы.filter(ф => чит(ф).indexOf('<!-- CSP:START -->') === -1);
правило('политика на каждой странице стоит между маркерами сборки',
    безМаркеров.length === 0,
    'без маркеров: ' + (безМаркеров.join(', ') || '—') + '\n' +
    'политика вне маркеров переживёт пересборку и разойдётся снова');

/* ══ ТРИ ЯЗЫКА — ОДНА ПОЛИТИКА ═════════════════════════════════════════ */

const семьи = {};
страницы.forEach(ф => {
    const б = path.basename(ф, '.html');
    const корень = path.join(path.dirname(ф), б.replace(/-(en|kg)$/, '') + '.html');
    (семьи[корень] = семьи[корень] || []).push(ф);
});
/* ОДНО ИСКЛЮЧЕНИЕ, И ОНО НАЗВАНО. `pages/admin-en.html` — это 25 строк
   ПЕРЕНАПРАВЛЕНИЯ на русскую админку (решение Кости написано прямо в том
   файле), скриптов там нет вовсе. Давать заглушке таблицы, переводчик и
   шесть источников кадров — ослабление ни за чем. Поэтому у неё база, а не
   политика админки. Правило это знает ПОИМЁННО: если исключений станет
   больше, они должны быть названы так же. */
const ИСКЛЮЧЕНИЯ = new Set(['pages/admin.html']);
const разошлись = Object.keys(семьи).filter(к => семьи[к].length > 1 &&
    !ИСКЛЮЧЕНИЯ.has(к) &&
    new Set(семьи[к].map(ф => политика[ф])).size > 1);

правило('у перенаправления английской админки своя, УЗКАЯ политика',
    политика['pages/admin-en.html'] === политика['index.html'] &&
    политика['pages/admin.html'] !== политика['pages/admin-en.html'],
    'это страница-перенаправление: ей нужна база и ничего сверх неё');

правило('три языка одной страницы несут одну политику',
    разошлись.length === 0,
    'разошлись: ' + (разошлись.join(', ') || '—') + '\n' +
    'до 13.10 расходились лендинг (у ru не было frame-src и wss, у en и kg\n' +
    'были — при том что кадра на лендинге нет вовсе) и админка');

/* ══ РАЗРЕШЕНИЕ СТОИТ ТАМ, ГДЕ НУЖНО ═══════════════════════════════════ */

const ждём = [
    ['pages/news.html',       'frame-src', /youtube\.com/,              'ролики новостей'],
    ['pages/news.html',       'frame-src', /instagram\.com/,            'ролики новостей'],
    ['pages/live-match.html', 'connect-src', /wss:\/\/\*\.supabase\.co/, 'счёт идёт по вебсокету'],
    ['pages/scoreboard.html', 'connect-src', /wss:\/\/\*\.supabase\.co/, 'табло слушает тот же сокет'],
    ['pages/auth.html',       'script-src', /challenges\.cloudflare\.com/, 'Turnstile на входе'],
    ['pages/auth.html',       'frame-src',  /challenges\.cloudflare\.com/, 'Turnstile рисует кадр'],
    ['pages/court.html',      'frame-src',  /maps\.google\.com/,         'карта корта'],
    ['pages/admin.html',      'script-src', /cdn\.sheetjs\.com/,         'выгрузка в Excel']
];
ждём.forEach(([ф, д, ре, зачем]) => {
    правило('есть разрешение там, где нужно: ' + path.basename(ф) + ' · ' + зачем,
        ре.test(директива(политика[ф], д) || ''),
        'страница этим пользуется, и без разрешения браузер её закроет');
});

const неЖдём = [
    ['index.html',           'frame-src',   /youtube/,  'кадра на лендинге нет ни на одном языке'],
    ['index-en.html',        'frame-src',   /youtube/,  'то же самое'],
    ['index.html',           'connect-src', /wss:/,     'лендинг вебсокета не открывает'],
    ['index-en.html',        'connect-src', /wss:/,     'то же самое'],
    ['pages/admin-en.html',  'script-src',  /sheetjs/,  'это 25 строк перенаправления, скриптов нет'],
    ['pages/auth.html',      'frame-src',   /accounts\.google\.com/,
        'signInWithOAuth уводит на страницу Google целиком, кадра нет'],
    ['pages/players.html',   'frame-src',   /./,        'кадров на рейтинге нет']
];
неЖдём.forEach(([ф, д, ре, зачем]) => {
    правило('нет лишнего разрешения: ' + path.basename(ф) + ' · ' + д,
        !ре.test(директива(политика[ф], д) || ''),
        зачем + '. Лишнее разрешение — это ослабление ни за что');
});

/* ══ БАЗА ═══════════════════════════════════════════════════════════════ */

правило('у всех страниц один и тот же default-src',
    new Set(страницы.map(ф => директива(политика[ф], 'default-src'))).size === 1,
    'основание политики не может быть разным у разных страниц');

правило('своего кадра продукт не делает, и `self` в кадрах не нужен',
    страницы.every(ф => !/'self'/.test(директива(политика[ф], 'frame-src') || '')) &&
    !/<iframe[^>]*src="(?:\.\.?\/|\/)/.test(чит('js/kslt-video.js') + чит('js/kslt-lenta.js')),
    'все кадры собираются из закрытого списка трёх хостов\n' +
    '(js/kslt-video.js:29-47) плюс карты Google: своего кадра не бывает');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

const вариантов = new Set(страницы.map(ф => политика[ф])).size;

if (ошибки.length === 0) {
    console.log('  ок      политика безопасности: 25 правил');
    console.log('          одно объявление   ·   страниц ' + страницы.length +
                '   ·   вариантов ' + вариантов);
    console.log('          три языка — одна политика   ·   лишних разрешений нет');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  политика безопасности — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
