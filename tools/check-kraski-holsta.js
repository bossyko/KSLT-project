/**
 * КРАСКИ ХОЛСТА — ТОЛЬКО ЧЕРЕЗ ДОМ. Круг 17 ветки D, 19.10. Находка 96б.
 *
 * ЧТО БЫЛО. Холст (`<canvas>`, настройки Chart.js) css-переменных НЕ
 * понимает: ему нужна готовая строка. Поэтому графики говорили числами —
 * замер нашёл 71 краску мимо системы против 19 совпавших, причём роли
 * были записаны ЧУЖОЙ палитрой: `rgba(76,175,80,1)` Material вместо
 * `--success` `#2ED573`. Фон подсказки был записан ТРЕМЯ разными числами
 * в трёх файлах — одно понятие в трёх видах.
 *
 * ХУЖЕ ЧИСЛА — `var(--accent)` В ХОЛСТЕ. Такую запись холст не понимает
 * и рисует НИЧЕМ: ряд графика исчезает молча, и причину искать негде.
 * Прибор нашёл четыре таких места, из них одно — заливка под линией
 * графика пользователей, которой пользователь просто никогда не видел.
 *
 * ЕЩЁ ХУЖЕ — СКЛЕЙКА HEX-ХВОСТА. `c.color + '38'` даёт прозрачность,
 * пока краска записана шестнадцатеричным. Стоило цвету прийти в виде
 * `rgba(...)` — холст отвечает «не разобрать цвет» и НЕ РИСУЕТ ГРАФИК
 * ЦЕЛИКОМ. Поймано прогоном, а не чтением: по исходнику склейка
 * выглядит безобидно.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЕ, А НЕ ЧИСЛО:
 *   1. внутри `new Chart(…)` и у рисовалки холста нет ни краски числом,
 *      ни `var(--…)`: всё берётся домом `KSLT_KRASKA`;
 *   2. прозрачность краске даёт `сАльфой`, а не склейка hex-хвоста;
 *   3. подсказка графика названа ОДНИМ именем — `--chart-tip-*`, и эти
 *      имена в `tokens.css` есть;
 *   4. страница, подключившая файл, который зовёт дом, подключает и дом.
 *
 * Правило 4 — про НАЛИЧИЕ, не про порядок: все зовы дома лежат внутри
 * функций рисования, а они исполняются после загрузки страницы. Мерить
 * порядок значило бы сторожить то, от чего ничего не зависит.
 *
 *   node tools/check-kraski-holsta.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');

/* Файлы графиков: те, что рисуют на холсте через Chart.js. */
const ФАЙЛЫ_ГРАФИКОВ = [
    'js/rating-chart.js',
    'js/admin/sections/analytics.js',
    'js/admin/sections/users.js',
    'js/admin/sections/finances.js'
];
const ДОМ_ФАЙЛ = 'js/kslt-kraska.js';
const ТОКЕНЫ = 'css/tokens.css';

/* СТОРОЖ ЧИТАЕТ КОД, А НЕ СЛОВА О КОДЕ: комментарии гасятся, иначе
   правило остаётся зелёным от строки в пояснении. */
const чисто = п => fs.readFileSync(path.join(КОРЕНЬ, п), 'utf8')
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

const ПУСТО = ' ';
const КРАСКА = /#[0-9a-fA-F]{3,8}\b|rgba?\(\s*[\d.]+[^)]*\)|var\(--/;

/** Куски исходника ВНУТРИ `new Chart( … )` — по балансу скобок. */
function блокиChart(т) {
    const вых = [];
    const р = /new\s+Chart\s*\(/g;
    let м;
    while ((м = р.exec(т))) {
        /* Открывающая скобка `new Chart(` — последний знак совпадения.
           Считать баланс надо С НЕЁ: начни с нуля — и блок захватит
           полфайла, а правило станет врать на сотню мест. */
        let i = м.index + м[0].length - 1;
        let гл = 0;
        while (i < т.length) {
            if (т[i] === '(') гл++;
            else if (т[i] === ')') { гл--; if (гл === 0) break; }
            i++;
        }
        вых.push({ от: м.index, текст: т.slice(м.index + м[0].length, i) });
    }
    return вых;
}

const исх = {};
ФАЙЛЫ_ГРАФИКОВ.forEach(ф => { исх[ф] = чисто(ф); });
const строка = (т, поз) => т.slice(0, поз).split('\n').length;

/* ---- 1. внутри new Chart() краски нет ---- */
const вЧарте = [];
ФАЙЛЫ_ГРАФИКОВ.forEach(ф => {
    блокиChart(исх[ф]).forEach(б => {
        const р = new RegExp(КРАСКА.source, 'g');
        let м;
        while ((м = р.exec(б.текст))) {
            вЧарте.push(ф + ':' + строка(исх[ф], б.от + м.index) + ' ← ' + м[0]);
        }
    });
});
правило('внутри new Chart() краска не пишется ни числом, ни var()',
    вЧарте.length === 0,
    'Краска мимо дома в настройках графика:\n  ' + вЧарte(вЧарте) + '\n' +
    'Число — рассинхрон с системой. `var(--…)` ХУЖЕ числа: холст его не\n' +
    'понимает и рисует НИЧЕМ — ряд исчезает молча.\n' +
    'Бери краску домом: window.KSLT_KRASKA.цвет(\'--роль\', альфа).');
function вЧарte(с) { return с.join('\n  '); }

/* ---- 2. у рисовалки холста краски нет ---- */
const РИСОВАЛКА = /\.(?:fillStyle|strokeStyle|shadowColor)\s*=\s*([^;]+);|addColorStop\s*\(\s*[\d.]+\s*,\s*([^)]+)\)/g;
const вРисовалке = [];
ФАЙЛЫ_ГРАФИКОВ.forEach(ф => {
    let м;
    const р = new RegExp(РИСОВАЛКА.source, 'g');
    while ((м = р.exec(исх[ф]))) {
        const знач = (м[1] || м[2] || '').trim();
        if (КРАСКА.test(знач)) вРисовалке.push(ф + ':' + строка(исх[ф], м.index) + ' ← ' + знач.slice(0, 40));
    }
});
правило('рисовалка холста красится домом, а не числом',
    вРисовалке.length === 0,
    'Краска мимо дома у fillStyle / strokeStyle / addColorStop:\n  ' +
    вРисовалке.join('\n  ') + '\n' +
    'Это прямое рисование на холсте — var() там тоже не работает.');

/* ---- 3. прозрачность — сАльфой, а не склейка hex-хвоста ---- */
const склейки = [];
ФАЙЛЫ_ГРАФИКОВ.forEach(ф => {
    const р = /(?:color|цвет|цв)\s*\+\s*['"][0-9a-fA-F]{2}['"]/gi;
    let м;
    while ((м = р.exec(исх[ф]))) склейки.push(ф + ':' + строка(исх[ф], м.index) + ' ← ' + м[0]);
});
правило('прозрачность даётся сАльфой, а не склейкой hex-хвоста',
    склейки.length === 0,
    'Склейка hex-хвоста:\n  ' + склейки.join('\n  ') + '\n' +
    'Пока краска записана шестнадцатеричным — работает. Приди она в виде\n' +
    '`rgba(...)` — холст ответит «не разобрать цвет» и НЕ НАРИСУЕТ ГРАФИК\n' +
    'ЦЕЛИКОМ. Одна дорога на оба случая: KSLT_KRASKA.сАльфой(цвет, альфа).');

/* ---- 4. дом умеет сАльфой ---- */
const домТекст = чисто(ДОМ_ФАЙЛ);
правило('дом красок умеет сАльфой',
    /сАльфой\s*:\s*function/.test(домТекст),
    'В ' + ДОМ_ФАЙЛ + ' нет метода `сАльфой`. Без него прозрачность\n' +
    'краске из базы дать нечем, и склейка hex-хвоста вернётся.');
правило('цвет() с альфой идёт через сАльфой — одно определение',
    /this\.сАльфой\(/.test(домТекст),
    '`цвет(имя, альфа)` считает прозрачность сам, не через `сАльфой`.\n' +
    'Два определения одного понятия — беда родится ровно на шве.');

/* ---- 5. подсказка графика названа одним именем ---- */
const токены = чисто(ТОКЕНЫ);
const ИМЕНА_ПОДСКАЗКИ = ['--chart-tip-bg', '--chart-tip-border',
                         '--chart-tip-title', '--chart-tip-body'];
const нетИмени = ИМЕНА_ПОДСКАЗКИ.filter(и =>
    !new RegExp('^\\s*' + и + '\\s*:', 'm').test(токены));
правило('имена подсказки графика объявлены в tokens.css',
    нетИмени.length === 0,
    'Нет в ' + ТОКЕНЫ + ': ' + нетИмени.join(', ') + '\n' +
    'Дом вернёт пустую строку, и подсказка нарисуется ПРОЗРАЧНОЙ.');

const двойные = ИМЕНА_ПОДСКАЗКИ.filter(и =>
    (токены.match(new RegExp('^\\s*' + и + '\\s*:', 'gm')) || []).length > 1);
правило('подсказка графика определена один раз',
    двойные.length === 0,
    'Определено дважды: ' + двойные.join(', ') + '\n' +
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ — беда родится на шве.');

/* ---- 6. страницы: подключил звонящего — подключи дом ---- */
function страницы() {
    const вых = [];
    (function обойти(д) {
        fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
            const п = д ? д + '/' + э.name : э.name;
            if (э.isDirectory()) {
                if (/^(node_modules|\.git|mobile|test-results|playwright-report|build)$/.test(э.name)) return;
                обойти(п);
            } else if (э.name.endsWith('.html')) вых.push(п);
        });
    })('');
    return вых;
}
/* Кто зовёт дом: ищем по всем js, а не по списку — новый звонящий
   попадает под правило сам, без правки сторожа. */
function всеJs(д, вых) {
    вых = вых || [];
    fs.readdirSync(path.join(КОРЕНЬ, д), { withFileTypes: true }).forEach(э => {
        const п = д + '/' + э.name;
        if (э.isDirectory()) { if (э.name !== 'node_modules') всеJs(п, вых); }
        else if (э.name.endsWith('.js')) вых.push(п);
    });
    return вых;
}
const звонящие = всеJs('js').filter(п =>
    п !== ДОМ_ФАЙЛ && /\bKSLT_KRASKA\s*\./.test(чисто(п)));

const безДома = [];
страницы().forEach(стр => {
    const т = fs.readFileSync(path.join(КОРЕНЬ, стр), 'utf8');
    const база = path.dirname(стр);
    const пути = [];
    const р = /<script[^>]*src="([^"]+)"/g;
    let м;
    while ((м = р.exec(т))) {
        const ч = м[1].split('?')[0];
        if (/^(https?:)?\/\//.test(ч)) continue;
        пути.push(path.posix.normalize(path.posix.join(база === '.' ? '' : база, ч)).replace(/^\.\//, ''));
    }
    const нужны = пути.filter(п => звонящие.indexOf(п) !== -1);
    if (нужны.length && пути.indexOf(ДОМ_ФАЙЛ) === -1) {
        безДома.push(стр + ' ← ' + нужны.map(п => path.basename(п)).join(', '));
    }
});
правило('страница, зовущая дом красок, его подключает',
    безДома.length === 0,
    'Дом не подключён, а звонящие есть:\n  ' + безДома.join('\n  ') + '\n' +
    '`window.KSLT_KRASKA` будет undefined, и рисование упадёт с\n' +
    'TypeError в тот миг, когда график понадобится. Добавь\n' +
    '<script src="…/js/kslt-kraska.js"> рядом с домом времени.');

/* ---- 7. дом не молчит о ненайденном токене ---- */
правило('дом жалуется на ненайденный токен, а не молчит',
    /console\.warn\(/.test(домТекст) && /жалобы/.test(домТекст),
    'Дом отдаёт пустую строку молча. Холст нарисует ПРОЗРАЧНЫМ, ряд\n' +
    'графика исчезнет, и причину искать будет негде.\n' +
    'ПРОВЕРКА, КОТОРАЯ ВЫХОДИТ МОЛЧА, ХУЖЕ ПАДЕНИЯ.');

/* ---- вывод ---- */
if (!ошибки.length) {
    console.log('');
    console.log('  ок      краски холста: 8 правил');
    console.log('          ' + ФАЙЛЫ_ГРАФИКОВ.length + ' файлов графиков — ни числа, ни var() в холсте');
    console.log('          прозрачность через сАльфой; подсказка — одно имя');
    console.log('          ' + звонящие.length + ' звонящих, дом подключён на всех их страницах');
    console.log('');
    process.exit(0);
}
console.log('');
console.log('  НЕ ТАК  краски холста — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
