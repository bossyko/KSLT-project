const ЗАПИСЬ = ['update', 'insert', 'upsert', 'delete'];
const СПРОС = ['showConfirm', 'showConfirmAsync'];
function обработчикиНажатий(д) {
    const найдены = [];
    обойти(д, у => {
        if (у.type === 'CallExpression' && у.callee) {
            const имя = у.callee.property && у.callee.property.name;
            if (имя === 'addEventListener' && у.arguments[0] &&
                ['click', 'change', 'submit'].indexOf(у.arguments[0].value) !== -1 &&
                у.arguments[1] && /Function/.test(у.arguments[1].type)) найдены.push(у.arguments[1]);
            if (имя === 'наТелоТаблицы' && у.arguments[1] &&
                /Function/.test(у.arguments[1].type)) найдены.push(у.arguments[1]);
        }
        if (у.type === 'AssignmentExpression' && у.left.type === 'MemberExpression' &&
            у.left.property && /^on(click|change|submit)$/.test(у.left.property.name) &&
            /Function/.test(у.right.type)) найдены.push(у.right);
    });
    return найдены;
}
/* ПРИЗНАК ВЫПРАВЛЯЛСЯ ТРИЖДЫ, И КАЖДЫЙ РАЗ ПОПРАВЛЯЛ ПРИБОР, А НЕ Я.
   · Первая мерка: «спрос в той же функции, что запись» — 210 голых из 214.
     Ерунда: `showConfirm(…, function () { update })` держит спрос в
     РОДИТЕЛЬСКОЙ функции, и запись в колбэке считалась голой.
   · Вторая: обход выходил из ветки, встретив спрос, — но спрос стоит
     ОТДЕЛЬНЫМ выражением перед записью, и обход читал дальше. Наша же
     публикация оказалась «голой».
   · Третья: «запись после первого спроса в обработчике — спрошена». Это
     уронил ПРУВЕР: в обработчике таблицы один спрос стоит для ОДНОЙ
     кнопки, и запись для ДРУГОЙ кнопки ниже считалась накрытой.
   ПРИЗНАК СЕЙЧАС: спрос накрывает запись, если стоит ПЕРЕД ней И в том же
   блоке или в блоке, объемлющем запись. Ветка соседней кнопки — другой
   блок, и её запись остаётся голой. */
function записиБезСпроса(тело) {
    const блокиЗаписи = new Map();   /* запись -> набор блоков-предков */
    const спросы = [];               /* {место, блок} */
    (function ход(у, предкиБлоки) {
        if (!у || typeof у !== 'object') return;
        if (у.type === 'CallExpression' && у.callee) {
            const имя = у.callee.property ? у.callee.property.name : у.callee.name;
            if (СПРОС.indexOf(имя) !== -1) спросы.push({ место: у.start, предки: предкиБлоки });
            else if (у.callee.property && ЗАПИСЬ.indexOf(у.callee.property.name) !== -1) {
                блокиЗаписи.set(у, предкиБлоки);
            }
        }
        const свои = (у.type === 'BlockStatement' || у.type === 'Program')
            ? предкиБлоки.concat([у]) : предкиБлоки;
        for (const к in у) {
            if (к === 'loc') continue;
            const з = у[к];
            if (Array.isArray(з)) з.forEach(д => ход(д, свои));
            else if (з && typeof з === 'object' && з.type) ход(з, свои);
        }
    })(тело, []);
    const голые = [];
    блокиЗаписи.forEach((предки, запись) => {
        /* НАКРЫВАЕТ ТОТ СПРОС, ЧЕЙ СОБСТВЕННЫЙ БЛОК ОБЪЕМЛЕТ ЗАПИСЬ.
           Сравнивать НАБОРЫ предков нельзя: у спроса внутри `if (pubBtn)`
           в предках лежит и тело обработчика, и тогда «накрытой»
           оказывается запись из ветки соседней кнопки — ровно это и уронил
           прувер. Берём ближайший блок спроса и спрашиваем, стоит ли
           запись внутри него. */
        const накрыт = спросы.some(с => {
            if (с.место >= запись.start) return false;
            const свой = с.предки[с.предки.length - 1];
            return !!свой && предки.indexOf(свой) !== -1;
        });
        if (!накрыт) голые.push(запись.loc.start.line);
    });
    return голые;
}
