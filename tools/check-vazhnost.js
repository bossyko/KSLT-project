const чисто = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

/* РАЗРЯД ОПРЕДЕЛЯЕТСЯ МЕСТОМ, А НЕ ИМЕНЕМ СВОЙСТВА. «animation: none» в
   обычном блоке и в блоке отказа от движения — разные вещи, и спрашивать
   надо, ВНУТРИ КАКОГО медиа стоит строка. Первый прибор спрашивал имя
   свойства и дал 4 вместо 8. */
function разобрать(текст) {
    const стрки = чисто(текст).split('\n');
    const места = [];
    let сел = '', стек = [], гл = 0;
    for (let i = 0; i < стрки.length; i++) {
        const с = стрки[i];
        const мМедиа = с.match(/\s*(@media[^{]*)\{/);
        if (мМедиа) стек.push([гл, мМедиа[1]]);
        const м = с.match(/\s*([.#\[&:a-zA-Z*][^{};]*?)\s*\{/);
        if (м && м[1].indexOf('@') === -1) сел = м[1].trim();
        гл += (с.split('{').length - 1) - (с.split('}').length - 1);
        while (стек.length && гл <= стек[стек.length - 1][0]) стек.pop();
        if (с.indexOf('!important') === -1) continue;
        const медиа = стек.map(x => x[1]).join(' ');
        const св = (с.match(/\s*([-a-zA-Z]+)\s*:/) || [, '?'])[1];
        let р;
        if (медиа.indexOf('prefers-reduced-motion') !== -1) р = 'отказ от движения';
        else if (медиа.indexOf('print') !== -1 || сел.indexOf('print') !== -1) р = 'печать';
        else if (/-webkit-autofill|-internal-autofill|::-webkit-|::-moz-|:-moz-/.test(сел)) р = 'браузер';
        else if (св === 'display' && /hidden|skryta/.test(сел)) р = 'утилита видимости';
        else р = 'свой css';
        места.push({ строка: i + 1, сел, св, разряд: р });
    }
    return места;
}

