/* ИНЛАЙН ИЩЕТСЯ В ОДНОМ ТЕГЕ, А НЕ В ОКНЕ ИЗ ТРЁХ СТРОК. Первый прибор
   21.10 смотрел окно и держал важность `font-weight` у `.ad-score-input` на
   ЛОЖНОМ конкуренте: `font-weight:600` стоял на соседнем `<span>`, а не на
   поле. ОКНО ИЗ СТРОК — НЕ ЭЛЕМЕНТ: класс и стиль должны стоять в ОДНОМ
   теге, иначе инлайн чужой.
   Присвоение через `.style.prop` и `setProperty` остаётся по окну: там
   элемент приходит переменной, и тег прочитать нечем — это названная
   щедрость, и ошибка в эту сторону оставляет лишнюю важность, а не ломает
   экран. */
function инлайнЕсть(классы, св) {
    if (!классы.length) return false;
    const камень = св.replace(/-([a-z])/g, (_, б) => б.toUpperCase());
    const черезСвойство = new RegExp('\\.style\\.' + камень + '\\s*=');
    const черезSet = new RegExp('setProperty\\(\\s*[\'"]' + св + '[\'"]');
    for (const и of источники) {
        const весь = и.стрки.join('\n');
        /* один тег: от `<` до `>`, внутри и класс, и стиль с этим свойством */
        const теги = весь.match(/<[a-zA-Z][^>]*>/g) || [];
        for (const тег of теги) {
            if (!классы.some(к => new RegExp('[\\s"\'`]' + к + '[\\s"\'`]').test(тег))) continue;
            if (new RegExp('style\\s*=\\s*["\'][^"\']*' + св + '\\s*:').test(тег)) return true;
        }
        for (let i = 0; i < и.стрки.length; i++) {
            const окно = (и.стрки[i - 1] || '') + '\n' + и.стрки[i] + '\n' + (и.стрки[i + 1] || '');
            if (!классы.some(к => new RegExp('[\\s"\'`]' + к + '[\\s"\'`]').test(окно))) continue;
            if (черезСвойство.test(окно) || черезSet.test(окно)) return true;
        }
    }
    return false;
}

/* НАБОРЫ КЛАССОВ БЕРУТСЯ ИЗ РАЗМЕТКИ, А НЕ ИЗ СЕЛЕКТОРА. И это третий
   раз, когда прибор спрашивал ИМЯ вместо признака: он искал конкурента по
   ОБЩЕМУ ИМЕНИ КЛАССА и не видел, что у `.ad-score-input` конкурент —
   `.ad-field-input` НА ТОМ ЖЕ ЭЛЕМЕНТЕ. Ровно та дыра, что поймалась на
   `.ad-crt-page-active` в куске 112: КОНКУРЕНТОМ БЫВАЕТ ДРУГОЙ КЛАСС ТОГО
   ЖЕ ЭЛЕМЕНТА, и какие классы стоят рядом — знает только разметка. */
const наборыКлассов = (function () {
    const итог = [];
    const обр = /class=(?:\\?["']([^"'\\]*)\\?["'])/g;
    for (const и of источники) {
        const т = и.стрки.join('\n');
        let м;
        while ((м = обр.exec(т))) {
            const классы = (м[1] || '').split(/\s+/).filter(к => /^[-\w]+$/.test(к));
            if (классы.length) итог.push(классы);
        }
    }
    return итог;
})();

/* попадает ли правило на элемент с таким набором классов */
function ветьПопадает(ветка, набор, мойТег) {
    const к = кусокСелектора(ветка), кКл = классыКуска(к), кТег = тегКуска(к);
    if (кКл.length) return кКл.every(x => набор.indexOf(x) !== -1);
    return к === '*' || (кТег && кТег === мойТег);
}

function конкурентЕсть(ф, м, мояВетка) {
    const конец = кусокСелектора(мояВетка);
    const моиКл = классыКуска(конец), мойТег = тегКуска(конец);
    /* наборы разметки, на которые попадает САМА эта важность */
    const мои = наборыКлассов.filter(н => моиКл.length && моиКл.every(x => н.indexOf(x) !== -1));
    for (const о of всеОбъявления) {
        if (о.св !== м.св) continue;
        if (о.ф === ф && о.строка === м.строка) continue;
        for (const в of веткиСелектора(о.сел)) {
            /* ЕСТЬ РАЗМЕТКА — СПРАШИВАЕМ ЕЁ. Конкурент тот, кто попадает на
               тот же набор классов, что и важность. */
            if (мои.length) {
                if (мои.some(н => ветьПопадает(в, н, мойТег))) return true;
                continue;
            }
            /* НЕТ РАЗМЕТКИ — и это не значит «мёртвое»: класс мог
               навешиваться `classList` или склейкой. Тогда запасной,
               нарочно ЩЕДРЫЙ признак: общий класс, голый тег, предок.
               Щедрый — потому что ошибка в эту сторону оставляет лишнюю
               важность, а в другую СЛОМАЛА БЫ ЭКРАН. */
            const к = кусокСелектора(в), кКл = классыКуска(к), кТег = тегКуска(к);
            const общий = кКл.some(x => моиКл.indexOf(x) !== -1);
            const поТегу = кКл.length === 0 && (к === '*' || (кТег && кТег === мойТег));
            const предок = моиКл.some(x => new RegExp('\\.' + x + '(?![-\\w])').test(в)) && !общий;
            if (общий || поТегу || предок) return true;
        }
    }
    return инлайнЕсть(моиКл, м.св);
}

