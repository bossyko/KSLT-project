/* инлайны из js и разметки: окно в три строки, потому что разметка рвётся
   склейкой, и класс с `style=` часто стоят на разных строках */
function всеФайлы(дир, итог) {
    итог = итог || [];
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        if (['node_modules', '.git', 'build'].indexOf(э.name) !== -1) continue;
        const п = path.join(дир, э.name);
        if (э.isDirectory()) всеФайлы(п, итог);
        else if (/\.(js|html)$/.test(э.name)) итог.push(п);
    }
    return итог;
}
const источники = ['js', 'pages', 'partials']
