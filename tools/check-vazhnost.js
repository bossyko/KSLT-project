/**
 * `!important` — ХРАПОВИК ПО РАЗРЯДАМ. Пункт 80а, 19.10.
 *
 * ПОЧЕМУ ХРАПОВИК, А НЕ ЧИСТКА. Замер 19.10 развёл 115 мест по РАЗРЯДУ —
 * по признаку «что именно этот `!important` перебивает», а не по написанию:
 *   печать 30 — `@media print` и `body.ad-printing`: лист бумаги обязан
 *     перебить экранные стили, иначе печать унаследует тёмный фон;
 *   браузер 8 — `-webkit-autofill`, `-internal-autofill`: стили подстановки
 *     браузера из файла иначе не перебить вовсе;
 *   отказ от движения 8 — внутри `@media (prefers-reduced-motion)`: без
 *     важности ЛЮБОЕ правило с анимацией победит отказ, и это доступность;
 *   утилита видимости 2 — `[hidden]`, `.kslt-skryta`: весь смысл класса в
 *     его весе, решение от 11.10, принятое и не переоткрываемое;
 *   свой css 66 — те, где важность перебивает НАШЕ ЖЕ правило.
 *
 * ПЕРВЫЕ ЧЕТЫРЕ РАЗРЯДА (49 мест) ЗАКОННЫ С НАЗВАННОЙ ПРИЧИНОЙ. Пятый —
 * долг, и он заморожен потолком, а не вычищен. Причина честная: чтобы
 * снять важность, нужно доказать, что правило и без неё выигрывает, а это
 * МЕРИТСЯ, а не читается. Прибор для этого замера соврал за один кусок
 * ПЯТЬ раз, и последний раз его поймал контрольный проход: двойник файла
 * БЕЗ ЕДИНОЙ ПРАВКИ дал 9 расхождений вместо нуля — на странице шли
 * анимации, и значения менялись сами между двумя снятиями.
 * А 38 из 66 живут в админке и на странице турнира, где элементов по этим
 * селекторам на пустых данных нет вовсе: «изменилось 0» там значит
 * «мерить было нечем», а не «важность лишняя».
 *
 * ЧТО ДЕРЖИТ ЭТОТ СТОРОЖ: ни одна новая важность не проскочит молча, и ни
 * одна НУЖНАЯ не исчезнет. Снижение потолка опускает потолок вместе с
 * собой — так ветка D чистит его кругами.
 *
 * ПОТОЛКИ РАВНЫ ЗАМЕРЕННОМУ (прибор 19.10), а не задуманному.
 *
 *   node tools/check-vazhnost.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');

/* ЗАМЕРЕНО 19.10 */
const ПОТОЛОК_ВСЕГО   = 115;
const ПОТОЛОК_СВОИХ   = 66;
const ПОТОЛОК_JS      = 3;
const НУЖНЫХ_ДВИЖЕНИЕ = 8;   /* не потолок, а МИНИМУМ: доступность */
const НУЖНЫХ_ВИДИМОСТЬ = 3;  /* не потолок, а МИНИМУМ: смысл в весе */

/* Комментарии гасим, СОХРАНЯЯ переводы строк. Прибор, склеивающий строки,
   врёт местом, а неверное место заметить труднее, чем неверный счёт. */
const чисто = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '));

/* РАЗРЯД ОПРЕДЕЛЯЕТСЯ МЕСТОМ, А НЕ ИМЕНЕМ СВОЙСТВА. «animation: none» в
   обычном блоке и в блоке отказа от движения — разные вещи, и спрашивать
   надо, ВНУТРИ КАКОГО медиа стоит строка. Первый прибор спрашивал имя
   свойства и дал 4 вместо 8. */
function разобрать(текст) {
    const стрки = чисто(текст).split('\n');
    const места = [];
    let сел = '', стек = [], гл = 0;
    for (let i = 0; i < стрки.length; i++) {
        const с = стрки[i];
        const мМедиа = с.match(/\s*(@media[^{]*)\{/);
        if (мМедиа) стек.push([гл, мМедиа[1]]);
        const м = с.match(/\s*([.#\[&:a-zA-Z*][^{};]*?)\s*\{/);
        if (м && м[1].indexOf('@') === -1) сел = м[1].trim();
        гл += (с.split('{').length - 1) - (с.split('}').length - 1);
        while (стек.length && гл <= стек[стек.length - 1][0]) стек.pop();
        if (с.indexOf('!important') === -1) continue;
        const медиа = стек.map(x => x[1]).join(' ');
        const св = (с.match(/\s*([-a-zA-Z]+)\s*:/) || [, '?'])[1];
        let р;
        if (медиа.indexOf('prefers-reduced-motion') !== -1) р = 'отказ от движения';
        else if (медиа.indexOf('print') !== -1 || сел.indexOf('print') !== -1) р = 'печать';
        else if (/-webkit-autofill|-internal-autofill|::-webkit-|::-moz-|:-moz-/.test(сел)) р = 'браузер';
        else if (св === 'display' && /hidden|skryta/.test(сел)) р = 'утилита видимости';
        else р = 'свой css';
        места.push({ строка: i + 1, сел, св, разряд: р });
    }
    return места;
}

const разряды = {};
let всего = 0;
const поФайлам = {};
for (const ф of fs.readdirSync(path.join(КОРЕНЬ, 'css')).sort()) {
    if (!ф.endsWith('.css')) continue;
    const места = разобрать(fs.readFileSync(path.join(КОРЕНЬ, 'css', ф), 'utf8'));
    поФайлам[ф] = места.length;
    всего += места.length;
    места.forEach(м => { разряды[м.разряд] = (разряды[м.разряд] || 0) + 1; });
}

let вJS = 0;
(function обойти(дир) {
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        const п = path.join(дир, э.name);
        if (э.isDirectory()) обойти(п);
        else if (э.name.endsWith('.js')) {
            const т = fs.readFileSync(п, 'utf8');
            вJS += (т.match(/!important/g) || []).length;
        }
    }
})(path.join(КОРЕНЬ, 'js'));

const свои = разряды['свой css'] || 0;
const ошибки = [];
let держится = 0;
function правило(имя, годно, подсказка) {
    if (годно) { держится++; console.log('  ✓ ' + имя); }
    else ошибки.push({ имя, подсказка });
}

правило(
    'важностей в css не больше замеренного',
    всего <= ПОТОЛОК_ВСЕГО,
    'Сейчас ' + всего + ' при потолке ' + ПОТОЛОК_ВСЕГО + '.\n' +
    'Потолок равен ЗАМЕРЕННОМУ 19.10, а не задуманному. Снижение опускает\n' +
    'потолок вместе с собой — так ветка D чистит его кругами.\n' +
    'По файлам сейчас: ' + JSON.stringify(поФайлам));

правило(
    'важностей «свой css» не больше замеренного',
    свои <= ПОТОЛОК_СВОИХ,
    'Сейчас ' + свои + ' при потолке ' + ПОТОЛОК_СВОИХ + '.\n' +
    'Это единственный разряд, который должен ТАЯТЬ. Рост здесь — новая\n' +
    'важность, перебивающая НАШЕ ЖЕ правило: значит в каскаде спор, и\n' +
    'решать его надо порядком или весом селектора, а не важностью.');

правило(
    'отказ от движения держится важностью, и её не убавилось',
    (разряды['отказ от движения'] || 0) >= НУЖНЫХ_ДВИЖЕНИЕ,
    'Сейчас ' + (разряды['отказ от движения'] || 0) + ', нужно не меньше ' + НУЖНЫХ_ДВИЖЕНИЕ + '.\n' +
    'Это НЕ потолок, а минимум: внутри @media (prefers-reduced-motion) без\n' +
    'важности любое правило с анимацией победит отказ. Доступность, WCAG\n' +
    '2.3.3 — и единственный разряд, где важность обязательна.');

правило(
    'утилита видимости держится важностью',
    (разряды['утилита видимости'] || 0) >= НУЖНЫХ_ВИДИМОСТЬ,
    'Сейчас ' + (разряды['утилита видимости'] || 0) + ', нужно не меньше ' + НУЖНЫХ_ВИДИМОСТЬ + '.\n' +
    'Решение 11.10: весь смысл класса-переключателя видимости в его весе.\n' +
    'Принятое не переоткрывается.');

правило(
    'важностей в js не больше замеренного',
    вJS <= ПОТОЛОК_JS,
    'Сейчас ' + вJS + ' при потолке ' + ПОТОЛОК_JS + '.\n' +
    'Важность в строке js — это стиль, собранный в коде и перебивающий\n' +
    'файл стилей: починить его из css нельзя вовсе.');

правило(
    'каждая важность попадает в названный разряд',
    Object.keys(разряды).every(р => ['печать','браузер','отказ от движения','утилита видимости','свой css'].indexOf(р) !== -1),
    'Разряды сейчас: ' + JSON.stringify(разряды) + '.\n' +
    'Разряд определяется МЕСТОМ (внутри какого медиа стоит строка), а не\n' +
    'именем свойства: первый прибор спрашивал имя и дал 4 вместо 8.');

console.log('');
if (!ошибки.length) {
    console.log('  ок      важность: ' + держится + ' правил');
    console.log('          всего ' + всего + ' (потолок ' + ПОТОЛОК_ВСЕГО + '), свой css ' + свои + ' (потолок ' + ПОТОЛОК_СВОИХ + '), js ' + вJS);
    console.log('          законных с названной причиной: печать ' + (разряды['печать']||0) +
                ', браузер ' + (разряды['браузер']||0) +
                ', отказ от движения ' + (разряды['отказ от движения']||0) +
                ', видимость ' + (разряды['утилита видимости']||0));
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  важность — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
