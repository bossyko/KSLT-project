const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const CSS   = безКом(чит('css/live-match.css'));
const JS    = чит('js/live-match.js');
const JSч   = безКом(JS);
const СТИ   = безКом(чит('css/style.css'));
const СУД   = безКом(чит('js/umpire.js'));
const АДМ   = безКом(чит('js/admin/sections/live.js'));
const SQL   = чит('sql/схема/live-match-point-log.sql');
const СТР   = {
    ru: чит('pages/live-match.html'),
    en: чит('pages/live-match-en.html'),
    kg: чит('pages/live-match-kg.html')
};

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };
const сколько = (т, р) => (т.match(р) || []).length;

/** Ступень шкалы по имени переменной. Сравниваем СТУПЕНИ, а не пиксели. */
const СТУПЕНИ = ['--fs-2xs', '--fs-xs', '--fs-sm', '--fs-base', '--fs-md',
                 '--fs-lg', '--fs-xl', '--fs-2xl', '--fs-3xl'];
const ступень = имя => СТУПЕНИ.indexOf(имя);
/** Кегль правила по селектору: ищем в заданном куске css. */
const кегльВ = (кусок, селектор) => {
    const м = кусок.match(new RegExp('\\' + selEsc(селектор) + '\\s*\\{[^}]*font-size:\\s*var\\((--fs-[a-z0-9]+)\\)'));
    return м ? м[1] : null;
};
function selEsc(s) { return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&').slice(1); }

const БАЗА = CSS.split('@media')[0];
const ТЕЛЕФОН = (CSS.match(/@media \(max-width: 640px\) \{([\s\S]*?)\n\}/) || [])[1] || '';

/* ══ РАМКА СТРАНИЦЫ ═══════════════════════════════════════════════════════ */

правило('поле от края экрана берётся у страницы, а не задаётся своим числом',
    /\.lm-container \{[^}]*var\(--pad-x\)/.test(БАЗА) &&
    !/\.lm-container \{[^}]*padding:[^;]*\d+px/.test(БАЗА),
    'Было padding: 80px 20px 40px, и левый край страницы уходил на 110 при\n' +
    '          28 у шапки. Это дефект h243 из описания Header 168:147: содержимое\n' +
    '          на контейнере 1100 против шапки на 1400.');

/* ПЕРЕПИСАНО 25.09. Было: «страница считает отбивку от --header-h». Оказалось,
   что при этом высота шапки считалась ДВАЖДЫ — main { padding-top: var(--header-h) }
   даёт её первый раз, и ссылка «На главную» стояла на 168 вместо 104.
   Замораживается новое отношение: ОТБИВКУ ОТ ШАПКИ ЗАДАЁТ ОДИН, И ЭТО main. */
правило('страница НЕ отбивает шапку второй раз',
    !/\.lm-container \{[^}]*calc\(var\(--header-h\)/.test(БАЗА) &&
    !/\.lm-container \{[^}]*padding-top:\s*calc\(var\(--header-h\)/.test(CSS) &&
    /^main \{[^}]*padding-top: var\(--header-h\)/m.test(СТИ),
    'Высота шапки считалась дважды: main 64 плюс своя рамка 64 + 40 — под\n' +
    '          шапкой выходило 104 пустоты вместо сорока, и вся страница была на\n' +
    '          64 ниже. Та же поломка описана в style.css у main:has(.hero).');

правило('своей ширины у страницы нет — ширину держит та же формула, что у лендинга',
    !/--container-narrow/.test(CSS) && !/max-width:\s*\d+px/.test(БАЗА),
    'Контейнер 1100 отвергнут Костей 19.09: всё на 1400. --pad-x сам\n' +
    '          центрует содержимое и сам ставит потолок.');

/* ══ ГРАНИЦЫ ══════════════════════════════════════════════════════════════ */

const ширины = [...CSS.matchAll(/max-width:\s*(\d+)px/g)].map(м => Number(м[1]));
правило('по ширине ровно две границы, и это 992 и 640',
    ширины.length === 2 && ширины.includes(992) && ширины.includes(640),
    'Было 991 · 480 · 375. Решение Кости 23.09: две ширины на весь продукт.\n' +
    '          Нашёл: ' + (ширины.join(', ') || 'ни одной'));

правило('тесная высота делится поворотом и высотой, а не ещё одной шириной',
    /@media \(orientation: landscape\) and \(max-height: 500px\)/.test(CSS),
    'Телефон боком — 844 по ширине, то есть «широкий» вид. Лестница там\n' +
    '          обязана опускаться, и опускает её высота, а не новая граница.');

/* ══ ЛЕСТНИЦА — ОТНОШЕНИЯ ═════════════════════════════════════════════════ */

const очкиШир = кегльВ(БАЗА, '.lm-points-score');
const сетШир  = кегльВ(БАЗА, '.lm-set-score');
const имяШир  = кегльВ(БАЗА, '.lm-player-name');
const h1Шир   = кегльВ(БАЗА, '.lm-title');

/* ПЕРЕОТКРЫТО КОСТЕЙ 25.09: «лаймовые цифры надо будет сделать такого же
   размера, что и геймы». Моё прежнее решение «очки 40 · сеты 26» отменено и
   помечено на доске 447:9, не стёрто. Довод Кости тот же, которым он снял
   лишнюю ширину у ячейки «ГЕЙМ»: лайм ЕСТЬ признак, размером его дублировать
   не надо. Замораживается новое отношение — одна ступень, разный цвет. */
правило('очки и счёт сета стоят на ОДНОЙ ступени и различаются цветом',
    ступень(очкиШир) === ступень(сетШир) && ступень(сетШир) >= 0 &&
    /\.lm-points-score \{[\s\S]{0,240}color: var\(--accent\)/.test(БАЗА) &&
    /\.lm-set-score \{[\s\S]{0,200}color: var\(--text-muted\)/.test(БАЗА),
    'Если размер сравнялся, всю работу делает краска: очки лаймом, сеты\n' +
    '          приглушённым. Уберёшь цвет — два числа станут неразличимы.\n' +
    '          Нашёл: очки ' + очкиШир + ', сет ' + сетШир);

правило('счёт сета строго крупнее имени игрока',
    ступень(сетШир) > ступень(имяШир) && ступень(имяШир) >= 0,
    'Нашёл: сет ' + сетШир + ', имя ' + имяШир);

правило('заголовок матча стоит на ступени H1',
    h1Шир === '--fs-2xl',
    'Заголовка у страницы не было вовсе: первым заголовком документа был h4\n' +
    '          подвала. Нашёл: ' + h1Шир);

const очкиТел = кегльВ(ТЕЛЕФОН, '.lm-points-score');
const сетТел  = кегльВ(ТЕЛЕФОН, '.lm-set-score');
const имяТел  = кегльВ(ТЕЛЕФОН, '.lm-player-name');
const h1Тел   = кегльВ(ТЕЛЕФОН, '.lm-title');

/* ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ, А НЕ ЧИСЛО ШАГОВ. Первой версией я требовал
   «ровно на одну ступень» — и правило упало на честном коде: имя идёт
   21 → 16, минуя 18, потому что ступень `card title` в лестнице 86:10 так
   и задана: 21 · 16 · 14. Важно, что каждый уровень на телефоне НИЖЕ
   своего широкого и что лестница остаётся лестницей, а не сколько именно
   ступеней он перешагнул. */
[['очки', очкиТел, очкиШир], ['счёт сета', сетТел, сетШир],
 ['имя игрока', имяТел, имяШир], ['заголовок', h1Тел, h1Шир]].forEach(function(пара) {
    правило('на телефоне ' + пара[0] + ' опускается по шкале',
        ступень(пара[1]) >= 0 && ступень(пара[1]) < ступень(пара[2]),
        'Нашёл: ' + пара[2] + ' → ' + пара[1]);
});

правило('на телефоне отношение то же, что на широком: очки = сет > имя',
    ступень(очкиТел) === ступень(сетТел) && ступень(сетТел) > ступень(имяТел),
    'Замораживается ОТНОШЕНИЕ, а не числа: на телефоне ступени ниже, но\n' +
    '          раскладываются так же. Нашли: очки ' + очкиТел + ', сет ' + сетТел +
    ', имя ' + имяТел);

/* ПУСТОЕ ПРАВИЛО, поймано прувером: я считал вхождения по всему файлу, а
   их три — сет, очки и очко в ленте. Убери одно из двух нужных, и счётчик
   всё равно показывал два. Правилу, которому хватает одного совпадения
   там, где элементов несколько, верить нельзя. */
[['.lm-set-score', 'счёта сета'], ['.lm-points-score', 'очков']].forEach(function(п) {
    правило('цифры ' + п[1] + ' моноширинные',
        new RegExp('\\' + п[0].slice(1) + ' \\{[^}]*font-variant-numeric:\\s*tabular-nums').test(БАЗА),
        'Счёт скачет при смене 1 на 4, если цифры разной ширины.');
});

/* ══ БЕЙДЖ СТАТУСА — ОДНО ОПРЕДЕЛЕНИЕ НА ВЕСЬ ПРОДУКТ ═════════════════════ */

правило('у страницы НЕТ своего бейджа статуса',
    !/\.lm-live-badge\s*\{/.test(CSS) && !/lm-badge-warmup|lm-badge-paused|lm-badge-completed/.test(CSS),
    'До 24.09 определений было два, и они разошлись: разминка была янтарной\n' +
    '          на главной и серой здесь, пауза наоборот. Бейдж один — .live-badge.');

правило('страница выдаёт общие классы бейджа',
    /is-warmup/.test(JSч) && /is-paused/.test(JSч) && /is-completed/.test(JSч) && /class="live-badge /.test(JSч),
    'Классы тонов те же, что у лендинга.');

правило('тон ЗАВЕРШЁН заведён у общего бейджа',
    /\.live-badge\.is-completed \{/.test(СТИ),
    'На лендинге было три тона, странице нужен четвёртый.');

const тонПауза = (СТИ.match(/\.live-badge\.is-paused \{([^}]*)\}/) || [])[1] || 'нет';
const тонЗавершён = (СТИ.match(/\.live-badge\.is-completed \{([^}]*)\}/) || [])[1] || 'нет2';
