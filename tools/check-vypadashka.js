#!/usr/bin/env node
/**
 * ЗАМОРОЗКА «ВЫПАДАЮЩИЙ ФИЛЬТР СТРОИТ ДОМ, А НЕ КАЖДЫЙ САМ» (02.11).
 *
 * ЗАЧЕМ ОН ЕСТЬ — ЗАМЕР, А НЕ ОПАСЕНИЕ. Слово Кости было про приложение:
 * «фильтры наверно надо будет сделать выпадающем меню, а не так как
 * сейчас». Померено: на сайте этот фильтр уже написан ЧЕТЫРЕЖДЫ —
 * `js/courts.js`, `js/coaches.js`, `js/partners.js`, `js/news.js`, — а
 * ряд чипов в приложении был бы пятым способом.
 *
 * И РАЗНИЦА НЕ В БУКВАХ. `aria-haspopup`, `aria-expanded`,
 * `role="listbox"` и галочка у выбранного пункта были РОВНО В ОДНОЙ
 * копии из четырёх. Трём остальным диктор читает просто кнопку с
 * непонятным словом, а человек, не различающий два серых, не видит
 * своего выбора вовсе — `Menu item 32:44` требует галочки прямо.
 *
 * ЧТО СТЕРЕЖЁТСЯ:
 *   · мёртвое имя `.ct-dd` не возвращается;
 *   · корты обоих продуктов зовут дом, а не строят разметку руками;
 *   · число СВОИХ выпадашек не растёт — долг назван и заморожен;
 *   · дом не теряет доступность, ради которой затевался.
 *
 * ЧЕГО НЕ СТЕРЕЖЁТ. Прибор читает файл как текст: пятый способ,
 * написанный без слова `dd`, он не увидит. Он не заменяет ни тесты, ни
 * глаза.
 *
 *   node tools/check-vypadashka.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN || path.join(__dirname, '..');
const ДОМ = 'js/kslt-vypadashka.js';

/* ДОЛГ, НАЗВАННЫЙ ПОИМЁННО, А НЕ «ГДЕ-ТО ЕЩЁ ЕСТЬ». */
/* ДОЛГ ЗАКРЫТ 02.11: тренеры, партнёры и новости переведены на дом.
   Список пуст НАРОЧНО и не снят — он и есть то место, где долг виден.
   Появится новый — впишется сюда с причиной, а не растворится. */
const ДОЛГ = [];

function читать(ф) {
    const п = path.join(КОРЕНЬ, ф);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : null;
}

function файлы(д, вых) {
    вых = вых || [];
    const п = path.join(КОРЕНЬ, д);
    if (!fs.existsSync(п)) return вых;
    for (const э of fs.readdirSync(п, { withFileTypes: true })) {
        const о = д + '/' + э.name;
        if (э.isDirectory()) файлы(о, вых);
        else if (/\.(js|css|html)$/.test(э.name)) вых.push(о);
    }
    return вых;
}

/** СВОЯ выпадашка — это `f-dd` или `ct-dd` в коде, а не в рассказе о нём. */
function безКомментариев(т) {
    return т.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^\s*\/\/.*$/gm, ' ');
}
function свои(т) {
    const м = безКомментариев(т).match(/["'.][cf]t?-?dd[-\w]*/g) || [];
    return м.filter(s => /f-dd|ct-dd/.test(s)).length;
}

const всеФайлы = []
    .concat(файлы('js'), файлы('css'), файлы('pages'), файлы('mobile/www'));

const сCtDd = [];
const своиМеста = {};
for (const ф of всеФайлы) {
    const т = читать(ф);
    if (т === null) continue;
    const чистый = безКомментариев(т);
    if (/ct-dd/.test(чистый)) сCtDd.push(ф);
    const н = свои(т);
    if (н) своиМеста[ф] = н;
}

const лишние = Object.keys(своиМеста).filter(ф => ДОЛГ.indexOf(ф) === -1
    && !/^css\/style\.css$/.test(ф));

const ошибки = [];
function правило(имя, держится, подсказка) {
    if (!держится) ошибки.push({ имя, подсказка });
}

правило('мёртвое имя ct-dd не вернулось',
    сCtDd.length === 0,
    'Имя `.ct-dd` снова в коде: ' + сCtDd.map(ф => '\n  ' + ф).join('') +
    '\nОно снято 02.11 вместе с переездом кортов на общий `.kslt-dd`.\n' +
    'Вернуть его — значит завести шестое определение одного понятия.');

правило('корты обоих продуктов зовут дом',
    ['js/courts.js', 'mobile/www/js/screens/courts.js'].every(ф => {
        const т = читать(ф);
        /* ЗОВ, А НЕ УПОМИНАНИЕ: имя дома стоит и в подписях к коду.
           Признак — точка после имени, и читается он в тексте БЕЗ
           комментариев. */
        return т !== null && /KSLT_VYPADASHKA\s*\./.test(безКомментариев(т));
    }),
    'Корты перестали звать `KSLT_VYPADASHKA`. Разметку выпадашки строит\n' +
    'дом `' + ДОМ + '`; написанная руками, она потеряет либо\n' +
    'доступность, либо галочку выбранного — как это и случилось у трёх\n' +
    'из четырёх сайтовых копий.');

правило('своих выпадашек не прибавилось',
    лишние.length === 0,
    'Своя выпадашка в файле, которого нет в названном долге: ' +
    лишние.map(ф => '\n  ' + ф + ' — ' + своиМеста[ф] + ' мест').join('') +
    '\nДолг заморожен поимённо: ' + ДОЛГ.join(', ') + '.\n' +
    'Новый экран с фильтром берёт дом, а не пишет шестую копию.');

правило('дом не растерял доступность',
    (function () {
        const т = читать(ДОМ);
        if (т === null) return false;
        /* ПОЙМАНО НА СЕБЕ 02.11: `aria-haspopup` стоит в доме ТРИЖДЫ, и
           дважды — в подписях к коду. Прибор, читавший файл целиком,
           оставался зелёным, когда признак сняли с самой кнопки. Третий
           раз одна и та же ловушка: ПРИБОР ЧИТАЕТ КОД, А НЕ РАССКАЗ. */
        const код = безКомментариев(т);
        return ['aria-haspopup', 'aria-expanded', 'role="listbox"',
                'aria-selected', 'kslt-dd-tick'].every(с => код.indexOf(с) !== -1);
    })(),
    'В доме `' + ДОМ + '` пропало что-то из того, ради чего он заводился:\n' +
    '`aria-haspopup`, `aria-expanded`, `role="listbox"`, `aria-selected`,\n' +
    'галочка выбранного. Без них это снова кнопка с непонятным словом.');

правило('прибор отличает код от рассказа о коде',
    (function () {
        /* ОБРАЗЕЦ ВНУТРЬ ПРИБОРА. На этом он уже попадался дважды: имя
           класса, упомянутое в КОММЕНТАРИИ, ловилось как живой код. */
        const о = "/* прежде здесь был .ct-dd */\n" +
                  "var a = '.f-dd-item';\n" +
                  "// и ещё .ct-dd в заметке\n";
        return свои(о) === 1 && !/ct-dd/.test(безКомментариев(о));
    })(),
    'Образец внутри прибора: имя в блочном комментарии, имя в строке кода\n' +
    'и имя в строчном комментарии. Прибор обязан насчитать РОВНО одно\n' +
    'живое место. Считает иначе — значит он падает на подписях и зеленеет\n' +
    'на беде.');

console.log('');
if (!ошибки.length) {
    const всего = (fs.readFileSync(__filename, 'utf8').match(/^правило\('/gm) || []).length;
    console.log('  ок      выпадающий фильтр: все ' + всего + ' правил держатся');
    console.log('          на доме корты обоих продуктов; в долге ' + ДОЛГ.length + ' файла');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  выпадающий фильтр — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
