#!/usr/bin/env node
/**
 * ОБЛОЖКА НОВОСТИ ЗАВОДИТСЯ ТОЛЬКО КАДРИРОВАНИЕМ (12.11.2026).
 *
 * ОТКУДА. В базе 30 обложек ШЕСТИ пропорций: 1280x720, 1024x1280,
 * 2560x1707, 940x788, 960x1280, 1080x1350 — три вертикальные. В шапке
 * новости 1512x460 вертикальная 1024x1280 показывала 24% своей высоты.
 * Причина не в возрасте картинок: cover-crop.js добавлен 09.08
 * (8d25339), и статей с обложкой СТАРШЕ этой даты ноль. Картинки
 * приходили ВТОРЫМ ПУТЁМ — полем «или вставьте ссылку» рядом с формой:
 * файл шёл через A.cropCover и приходил одной пропорцией, а ссылка
 * ложилась в базу как есть.
 *
 * РЕШЕНИЕ КОСТИ 12.11: поле ссылки убрать совсем; старые обложки
 * оставить как архив — кадрируются только новые. Чужую картинку
 * кадрировать и нельзя: холст портится (tainted canvas), так что
 * проверкой пропорции путь не закрыть.
 *
 * ЧТО СТОРОЖИТСЯ: обратно поле не вернётся, а кадрирование из формы
 * не исчезнет. ДВА ПРАВИЛА, А НЕ ОДНО: убрать поле и забыть позвать
 * cropCover — это та же дыра с другой стороны.
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.resolve(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, ' ');

const ошибки = [];
const правило = (имя, условие, почему) => { if (!условие) ошибки.push(имя + ' — ' + почему); };

const нов = безКом(чит('js/admin/sections/news.js'));
const дом = безКом(чит('js/admin/core/cover-crop.js'));
const стр = чит('pages/admin.html');

правило('у обложки новости нет второго пути — поля ссылки',
    !/adNewsImgUrl/.test(нов) && !/ad-image-url-row/.test(нов),
    'в форме новости снова поле «или вставьте ссылку»: картинка по ссылке\n' +
    'ляжет в базу как есть, мимо кадрирования — так и родились шесть пропорций');

правило('обложка новости проходит через кадрирование',
    /A\.cropCover\s*\(/.test(нов),
    'форма новости больше не зовёт A.cropCover: обложка пойдёт в базу\n' +
    'в той пропорции, в какой её выбрали');

правило('кадрирование живёт в доме, а не в разделе',
    /A\.cropCover\s*=|KSLT_ADMIN[\s\S]{0,200}cropCover/.test(дом) &&
    !/function\s+cropCover/.test(нов),
    'cropCover завели второй раз внутри раздела — одно определение на одно понятие');

const iДом = стр.indexOf('core/cover-crop.js');
const iНов = стр.indexOf('sections/news.js');
правило('дом кадрирования подключён ДО новостей',
    iДом !== -1 && iНов !== -1 && iДом < iНов,
    'cover-crop.js грузится позже news.js — A.cropCover будет пустым, и\n' +
    'обложка молча пройдёт некадрированной (admin.html)');

/* ПУТЬ ФАЙЛА ОСТАЁТСЯ ЕДИНСТВЕННЫМ: поле выбора файла не должно исчезнуть
   заодно с полем ссылки — иначе обложку не завести вовсе. */
правило('поле выбора файла у обложки на месте',
    /* ПРИЗНАК ЛОВИТ ЦЕЛОЕ ИМЯ, А НЕ ПОДСТРОКУ: первая редакция искала
       adNewsImgInput и проходила на adNewsImgInputUbran — откат её не
       уронил. Кавычка после имени и делает признак точным. */
    /id="adNewsImgInput"/.test(нов) && /accept="image\/jpeg,image\/png"/.test(нов),
    'из формы пропал выбор файла — обложку новости стало нечем заводить');

if (ошибки.length) {
    console.error('ОБЛОЖКА НОВОСТИ — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
console.log('обложка новости: 5 правил держатся');
