/**
 * ЗАМОРОЗКА СУДЕЙСКОГО ОКНА `pages/umpire.html`.
 *
 * Решения Кости 24.09: берём ЭЙС и ДВОЙНУЮ, БЕЗ деления на первую и вторую
 * подачу, плюс отмена очка. «Виннер» и «невынужденную» не спрашиваем: у
 * больших их считает отдельный логгер у корта, а у нас один человек с
 * телефоном.
 *
 * ЗАМОРАЖИВАЮТСЯ ОТНОШЕНИЯ:
 *   • имя игрока НИКОГДА не обрезается — перепутать игроков дороже строки;
 *   • на телефоне кегли НЕ мельчают: судья читает экран на солнце;
 *   • метка ставится ПО НОМЕРУ розыгрыша, а не на «последний»;
 *   • своих красок ровно две, и обе названы по имени с причиной.
 *
 *   node tools/check-sudya.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const CSS  = чит('css/umpire.css');
const CSSч = безКом(CSS);
const JS   = чит('js/umpire.js');
const JSч  = безКом(JS);
const HTML = чит('pages/umpire.html');
const SQL  = чит('sql/схема/live-match-point-mark.sql');
const СТР  = безКом(чит('js/live-match.js'));

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };
const сколько = (т, р) => (т.match(р) || []).length;

const БАЗА = CSSч.split('@media')[0];
const ТЕЛЕФОН = (CSSч.match(/@media \(max-width: 640px\) \{([\s\S]*?)\n\}/) || [])[1] || '';

/* ══ ПАЛИТРА ══════════════════════════════════════════════════════════════ */

правило('свои имена красок ведут к токенам, а не к своим числам',
    /--um-bg:\s*var\(--bg-base\)/.test(БАЗА) &&
    /--um-red:\s*var\(--danger\)/.test(БАЗА) &&
    /--um-green:\s*var\(--success\)/.test(БАЗА),
    'Было #EF5350 против --danger #FF4757, #66BB6A против --success #2ED573,\n' +
    '          #0a0a0a против --bg-base. В продукте выходило два красных и два\n' +
    '          зелёных, и разошлись бы они незаметно.');

const краски = (CSSч.match(/#[0-9a-fA-F]{3,8}\b/g) || []);
правило('своих красок числом не осталось вовсе',
    краски.length === 0,
    'С 24.09 даже две краски игроков — общие токены --player-1 и\n' +
    '          --player-2: до этого судейское окно красило игроков синим и\n' +
    '          оранжевым, а лента на странице матча — зелёным и янтарным, то\n' +
    '          есть красками статусов. Одно понятие — одно определение.\n' +
    '          Нашёл: ' + (краски.join(' ') || 'ни одной'));

правило('краски игроков берутся из общих токенов',
    /--um-p1:\s*var\(--player-1\)/.test(БАЗА) && /--um-p2:\s*var\(--player-2\)/.test(БАЗА),
    'Судья должен различать две кнопки боковым зрением, не читая, — но\n' +
    '          сама пара живёт в токенах, а не тут.');

правило('в файле не осталось ни одной rgba',
    !/rgba?\(/.test(CSSч),
    'Прозрачные слои есть в токенах: --surface-glass, --accent-subtle,\n' +
    '          --warning-subtle, --danger-subtle, --border-subtle.');

правило('градиентов у кнопок очка нет',
    !/linear-gradient/.test(CSSч),
    'Были два градиента — ещё две пары синих и оранжевых сверх краски\n' +
    '          игрока. Заливка одна, и она же краска игрока.');

правило('текст на кнопке очка почти-чёрный, а не белый',
    /\.um-btn-p1, \.um-btn-p2 \{[\s\S]{0,200}color: var\(--accent-on\)/.test(БАЗА),
    'Белый на светлой заливке порог контраста не проходит. То же правило,\n' +
    '          что у Badge 27:53 в стиле Solid.');

/* ══ ИМЯ ИГРОКА ═══════════════════════════════════════════════════════════ */

правило('имя игрока НИКОГДА не обрезается',
    !/\.um-player-name \{[^}]*text-overflow/.test(CSSч) &&
    !/\.um-player-name \{[^}]*white-space:\s*nowrap/.test(CSSч),
    'Было nowrap + ellipsis: на 390 «Иван Корабельников» показывался как\n' +
    '          «Иван Корабельн…» — 203 пикселя текста в коробке 178. Судья обязан\n' +
    '          видеть, кто есть кто: перепутать игроков дороже второй строки.');

/* ══ КЕГЛИ НА ТЕЛЕФОНЕ ════════════════════════════════════════════════════ */

правило('СТОРОЖ: на телефоне кегли счёта и имени НЕ уменьшаются',
    !/\.um-player-name \{[^}]*font-size/.test(ТЕЛЕФОН) &&
    !/\.um-games[^{]*\{[^}]*font-size/.test(ТЕЛЕФОН),
    'Поправка к себе от 24.09: прежний блок стоял на 375 и мельчил имя до\n' +
    '          16, счёт до 21. Я расширил границу до 640 — и уменьшение поехало\n' +
    '          на ВСЕ телефоны, померено на 390. Судья читает этот экран на\n' +
    '          улице; ему нужно крупнее. Повод мельчить исчез вместе с обрезкой\n' +
    '          имени: оно теперь переносится.');

правило('по ширине одна граница, и это 640',
    (CSSч.match(/max-width:\s*(\d+)px/g) || []).filter(x => !/500px/.test(x)).join() === 'max-width: 640px',
    'Было 375 — граница, которой нет в лестнице: отдельный мир для iPhone SE\n' +
    '          рядом с iPhone 14.');

правило('тесная высота делится поворотом, а не ещё одной шириной',
    /@media \(orientation: landscape\) and \(max-height: 500px\)/.test(CSSч),
    'Телефон боком — это высота, а не ширина.');

/* ══ ЭМОДЗИ И ЗНАЧОК ПОДАЧИ ═══════════════════════════════════════════════ */

правило('в судейском модуле не осталось ни одного эмодзи',
    !/[\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}]/u.test(JS),
    'Было три мяча и кубок. Эмодзи рисует операционная система: на одном\n' +
    '          телефоне он жёлтый, на другом зелёный, и размер нам не подчиняется.');

правило('значок подачи рисуется стилем, а не буквой',
    /\.um-serve-dot::before \{[\s\S]{0,200}border-radius: var\(--radius-full\)/.test(БАЗА),
    'Свой кружок вместо 🎾.');

/* ══ ЗАГОЛОВОК МАТЧА ══════════════════════════════════════════════════════ */

правило('судья видит, какой матч ведёт',
    /um-match-players/.test(JSч) && /um-match-head/.test(CSSч),
    'До 24.09 на экране были только счёт и кнопки. При двух матчах подряд\n' +
    '          перепутать было легко.');

/* ══ МЕТКА РОЗЫГРЫША ══════════════════════════════════════════════════════ */

правило('метка ставится ПО НОМЕРУ розыгрыша, а не на «последний»',
    /p_seq integer/.test(SQL) && /AND seq = p_seq/.test(SQL) &&
    !/seq = \(SELECT MAX\(seq\)[^)]*\)\s*\n\s*RETURNING/.test(SQL),
    'Первым заходом я написал «последний» — и это была дыра: вставка\n' +
    '          розыгрыша уходит асинхронно, а судья жмёт метку сразу. Задержись\n' +
    '          сеть — и эйс достался бы ПРЕДЫДУЩЕМУ очку.');

правило('судейский модуль передаёт номер розыгрыша',
    /p_seq: markSeq/.test(JSч) && /markSeq = res\.data\.seq/.test(JSч),
    'Номер приходит из umpire_log_point и хранится до метки.');

правило('новое очко обнуляет прежний номер',
    /markSeq = null;\s*\/\/ новый розыгрыш|markSeq = null;[\s\S]{0,80}openMarkWindow\(\)/.test(JS),
    'Иначе метка легла бы на предыдущий розыгрыш, пока новый ещё в пути.');

правило('отмена очка уносит и метку',
    /undoPoint\(\);[\s\S]{0,220}markSeq = null; markSet = null; markUntil = 0;/.test(JS),
    'Строки больше нет — помечать нечего.');

правило('метка необязательна: кнопки «обычный розыгрыш» нет',
    /um-btn-mark/.test(JSч) && !/обычн/i.test(JSч),
    'Пусто значит «судья не отметил», а НЕ «эйса не было». Кнопка «обычный»\n' +
    '          превратила бы пропуск в утверждение.');

правило('окно метки закрывается само',
    /markUntil = Date\.now\(\) \+ 3000/.test(JSч) && /markWindowOpen/.test(JSч),
    'Три секунды и уходит: поток судьи не меняется, одно касание на\n' +
    '          розыгрыш остаётся одним.');

правило('спрашиваем только то, что судья объявляет вслух',
    !/невынужден|unforced|winner_shot|виннер/i.test(JSч),
    'У больших «виннер» и «невынужденную» считает ОТДЕЛЬНЫЙ логгер у корта.\n' +
    '          У нас один человек: попросив его судить качество удара, получим\n' +
    '          медленного судью и данные, которым нельзя верить.');

/* ══ СТРАНИЦА МАТЧА ЧИТАЕТ МЕТКУ ══════════════════════════════════════════ */

правило('лента зрителя показывает метку и молчит, когда её нет',
    /,mark'/.test(СТР) && /pt\.mark === 'ace'/.test(СТР),
    'Метка необязательна, поэтому её отсутствие ничего не утверждает —\n' +
    '          надписи просто нет.');

/* ══ ДОСТУПНОСТЬ ══════════════════════════════════════════════════════════ */

правило('у кнопок есть кольцо фокуса',
    /\.um-btn:focus-visible \{[\s\S]{0,120}outline: 3px solid/.test(CSSч),
    'Не было ни у одной. WCAG 2.4.7.');

правило('движение выключается по просьбе системы',
    /@media \(prefers-reduced-motion: reduce\) \{[\s\S]{0,320}\.um-status-live \{ animation: none/.test(CSSч),
    'Полоса LIVE пульсирует бесконечно и висит перед судьёй весь матч.');

/* ══ ЭКРАН НЕ ГАСНЕТ ══════════════════════════════════════════════════════ */

правило('экран держится незаснувшим, пока идёт матч',
    /navigator\.wakeLock/.test(JSч) && /keepAwake\(\)/.test(JSч),
    'Судья держит телефон весь матч, и система усыпляет его между\n' +
    '          розыгрышами.');

правило('блокировка возвращается, когда судья вернулся во вкладку',
    /visibilitychange/.test(JSч),
    'Браузер снимает её при уходе в фон и сам не возвращает.');

/* ══ ВЕРСИИ ═══════════════════════════════════════════════════════════════ */

правило('у стиля и скрипта судьи есть версия',
    /umpire\.css\?v=\d+/.test(HTML) && /umpire\.js\?v=\d+/.test(HTML),
    'Версии не было вовсе, и это поймано вживую 24.09: браузер крутил\n' +
    '          СТАРЫЙ umpire.css из кеша, где кегли стояли числом, пока в файле\n' +
    '          давно были токены. Судья открывает ссылку перед самым матчем.');

/* ══ ВЫВОД ════════════════════════════════════════════════════════════════ */

console.log('');
if (ошибки.length === 0) {
    console.log('  ок      судейское окно: ' + ВСЕГО + ' правил');
    console.log('          имя не обрезается   ·   кегли не мельчают   ·   метка по номеру');
    console.log('          спрашиваем только то, что судья объявляет вслух');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  судейское окно — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s+/g, '\n            '));
    console.log('');
});
process.exit(1);
