#!/usr/bin/env node
/**
 * ЛЕНТА КАДРОВ И ГРУППА ВПЕРЁД — ЗАМОРОЗКА КУСКА 220 (28.10).
 *
 * 1. ФОТО И ВИДЕО В ОДНОЙ ЛЕНТЕ. В приложении была СВОЯ сборка, и она
 *    брала ТОЛЬКО фотографии: видео шло отдельными кадрами друг за
 *    другом. Костя сказал про это то же, что говорил про сайт 08.10:
 *    «инста наверно тоже карусель сделать, или поместить вместе с фото
 *    в одну». Для сайта тогда же завели общий дом `js/kslt-lenta.js` —
 *    он собирает фото и видео в одну ленту и снимает отношение коробки
 *    с ПЕРВОГО кадра, чтобы она не прыгала при листании. В приложении
 *    его не было. Своя сборка снесена.
 *    Замер после: новость с двумя врезками — ОДНА лента на два кадра,
 *    отдельных `iframe` вне ленты ноль, листается 1/2 → 2/2; новость с
 *    фотографиями — 1/5 → кнопка → 2/5 → миниатюра → 3/5.
 *
 * 2. СНИМОК ЦЕЛИКОМ, А НЕ ОБРЕЗКОМ. Стояло `object-fit: cover`, и
 *    вертикальные кадры резались сверху и снизу. Правило было выведено
 *    раньше на афише новости («афиша показывается целиком, пустоту по
 *    краям закрывает подложка») — применено к ленте и к миниатюрам, без
 *    нового разбора.
 *
 * 3. ИТОГ ГРУППЫ ВПЕРЁД. Замер на 375 при четырёх игроках: таблица 477
 *    при видимых 311, и колонки «В · Геймы · М» оставались за краем —
 *    то есть МЕСТО, за которым таблицу и открывают, не было видно без
 *    прокрутки. Порядок зависит от ШИРИНЫ, а не от продукта, поэтому он
 *    стал настройкой дома: приложение ставит итог вперёд, сайт — нет,
 *    там места хватает. Номер и имя закреплены при боковом ходе.
 *
 * 4. СЕТКА ОТКРЫВАЕТСЯ НА ПОСЛЕДНЕМ СЫГРАННОМ КРУГЕ. Она шире экрана
 *    (776 при видимых 311) и открывалась слева, на «Раунде 1» месячной
 *    давности. Прокрутка применяется ПРИ ПОКАЗЕ вкладки: до него у
 *    элемента ширина ноль — правило в указателе, и я на него наступил.
 *
 * Запуск: node tools/check-lenta-prilozheniya.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;

function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
function безСлов(отн) {
    return чит(отн).replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');
}
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}

const медиа = безСлов('mobile/www/js/news-media.js');
const главная = безСлов('mobile/www/js/screens/home.js');
const дом = безСлов('js/kslt-setka.js');
const css = безСлов('mobile/www/css/app.css');
const разметка = безСлов('mobile/www/index.html');

/* ── 1. ЛЕНТА — ИЗ ОБЩЕГО ДОМА ── */
правило(
    'дом ленты лежит в приложении и подключён',
    чит('mobile/www/js/kslt-lenta.js') !== '' &&
    /js\/kslt-lenta\.js\?v=/.test(разметка),
    'На сайте он есть с 08.10 — его зовёт и предпросмотр админки.');

[['js/kslt-lenta.js', 'лента кадров'],
 ['js/kslt-ekranirovanie.js', 'экранирование']
].forEach(function (п) {
    правило(
        'копия общего файла совпадает: ' + п[1],
        чит(п[0]) !== '' && чит(п[0]) === чит('mobile/www/' + п[0]),
        'Разойдутся — беда родится ровно на шве.');
});

правило(
    'ленту собирает дом, а не приложение',
    /KSLT_LENTA\.собрать\(/.test(медиа) &&
    медиа.indexOf('function собратьСнимкиВТексте') < 0,
    'Своя сборка брала ТОЛЬКО фотографии, и видео шло отдельными\n' +
    'кадрами друг за другом.');

правило(
    'каждая лента заводится, а не только рисуется',
    /KSLT_LENTA\.завести\(wrap, кадры, подпись\)/.test(медиа),
    'Сборка только рисует разметку. Без `завести` кнопки стоят, но не\n' +
    'работают — это поймал замер, а не глаз.');

правило(
    'просмотр открывается с кадра ленты',
    /news-carousel-kadr, \.news-carousel-main/.test(медиа),
    'Иначе крупный кадр новой ленты не открывался бы на весь экран.');

/* ── 2. СНИМОК ЦЕЛИКОМ ── */
правило(
    'крупный кадр ленты показывается целиком',
    /\.news-carousel-main \{[^}]*object-fit: contain/.test(css),
    'Стояло `cover`: вертикальные кадры резались сверху и снизу —\n' +
    'у человека пропадали голова и диплом в руках.');

правило(
    'миниатюра показывает тот же кадр целиком',
    /\.news-carousel-thumb img \{[^}]*object-fit: contain/.test(css),
    'Иначе в полосе и в крупном кадре человек видит РАЗНЫЕ куски\n' +
    'одного снимка.');

/* ── 3. ИТОГ ГРУППЫ ВПЕРЁД ── */
правило(
    'порядок колонок — настройка дома, а не его жёсткий вид',
    /итогВперёд/.test(дом) &&
    /h \+= итогВперёд \? \(шапкаИтога \+ шапкаВстреч\) : \(шапкаВстреч \+ шапкаИтога\)/.test(дом),
    'Порядок зависит от ШИРИНЫ, а не от продукта: на сайте места\n' +
    'хватает, и там он прежний.');

правило(
    'приложение ставит итог вперёд',
    /итогВперёд: true/.test(главная),
    'Место, за которым таблицу и открывают, оставалось за краем.');

правило(
    'номер и имя не уезжают при боковом ходе',
    /\.td-group-table \.td-gt-name,[\s\S]{0,200}?position: sticky/.test(css),
    'Листая встречи, человек должен видеть, ЧЬЯ это строка — иначе\n' +
    'счёт в клетке не к кому отнести.');

/* ── 4. СЕТКА НА ПОСЛЕДНЕМ СЫГРАННОМ КРУГЕ ── */
правило(
    'сетка подводится к последнему сыгранному кругу',
    /function кПоследнемуКругу/.test(главная) &&
    /поКругам\[rn\]\.some\(function \(m\) \{ return m\.status === 'completed'; \}\)/.test(главная),
    'Она шире экрана и открывалась слева, на «Раунде 1» месячной\n' +
    'давности.');

правило(
    'прокрутка применяется при ПОКАЗЕ вкладки',
    /function применитьПрокрутку/.test(главная) &&
    /if \(!полоса \|\| !полоса\.clientWidth\) return;/.test(главная),
    'До показа у элемента ширина ноль — правило «элемент со скрытым\n' +
    'родителем отдаёт нули» уже в указателе, и я на него наступил:\n' +
    'сдвиг считался нулевым.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      лента и группа: все ' + держится + ' правил держатся');
    console.log('          фото и видео вместе, итог впереди встреч\n');
}
