const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const ошибки = [];
const правило = (имя, держится, почему) => { if (!держится) ошибки.push([имя, почему]); };

const ПРОПУСК = /^(node_modules|\.git|test-results|playwright-report|_figma|mobile|import|_sync|tools|tests|slepki)$/;

function обход(дир, сп, расш) {
    fs.readdirSync(path.join(КОРЕНЬ, дир), { withFileTypes: true }).forEach(э => {
        if (э.isDirectory()) {
            if (ПРОПУСК.test(э.name) || э.name.startsWith('.')) return;
            обход(path.join(дир, э.name), сп, расш);
        } else if (расш.test(э.name)) {
            сп.push(path.join(дир, э.name).replace(/^\.\//, ''));
        }
    });
    return сп;
}
const HTML = обход('.', [], /\.html$/);
const ВСЕ = обход('.', [], /\.(html|css|js|json|webmanifest)$/);

/* 1-3. МАНИФЕСТ: ССЫЛКИ ВНУТРИ ФАЙЛА */
const манифест = JSON.parse(чит('manifest.json'));

