/**
 * ЗАМОРОЗКА СТРАНИЦЫ «НОВОСТИ» — список `pages/news.html`.
 *
 * Не путать с `check-novosti.js`: та замораживает СЕКЦИЮ новостей на
 * лендинге (доска 347:9, 23.09). Здесь — отдельная страница списка.
 *
 * ЧТО ЗАМОРАЖИВАЕТСЯ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • обложка списка стоит на ОБЩИХ крутилках раздела, своих чисел нет;
 *   • воздух обложки объявлен ОДИН раз — у самой обложки;
 *   • доля высоты окна принадлежит обложке ОТДЕЛЬНОЙ новости, не списку;
 *   • карточку рисует общий компонент `.tc`, своей вёрстки у новостей нет;
 *   • раскладка: крупная на два ряда, боковые 2 × 2, ряд из четырёх;
 *   • на телефоне новости идут ПО ОДНОЙ — товар новости это заголовок;
 *   • шаг страницы — колонок × рядов, число читается из живой сетки;
 *   • полоса страниц — общий компонент, своих кнопок у страницы нет;
 *   • статья без перевода не уходит на чужой язык;
 *   • пустые состояния говорят РАЗНОЕ про поиск и про категорию.
 *
 *   node tools/check-novosti-stranica.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const CSS = безКом(чит('css/news.css'));
const СТИ = безКом(чит('css/style.css'));
const JS  = безКом(чит('js/news.js'));
const RU = чит('pages/news.html');
const EN = чит('pages/news-en.html');
const KG = чит('pages/news-kg.html');

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };

const блок = (текст, якорь) => {
    const i = текст.indexOf(якорь);
    if (i === -1) return '';
    let j = текст.indexOf('{', i), г = 0, с = j;
    for (; j < текст.length; j++) {
        if (текст[j] === '{') г++;
        else if (текст[j] === '}') { г--; if (г === 0) return текст.slice(с + 1, j); }
    }
    return '';
};

/* ══ 1. ОБЛОЖКА СПИСКА — НА ОБЩИХ КРУТИЛКАХ ════════════════════════════ */

const ОБЛ = блок(CSS, '.news-hero-list {');

правило('пол обложки списка берётся из общей крутилки раздела',
    /min-height:\s*var\(--oblozhka-pol\)/.test(ОБЛ),
    'Замер 08.10: 360 · 360 · 275 · 67 · 275 — ровно как у шести\n' +
    '          приведённых разделов. Своё число вернёт разнобой.');

правило('воздух обложки — тоже крутилки, а не --section-y',
    /padding:\s*var\(--oblozhka-vozduh\) var\(--pad-x\) var\(--oblozhka-vozduh-niz\)/.test(ОБЛ),
    'Эталон — css/partners.css:20.');

правило('у содержимого обложки своего вертикального воздуха нет',
    /padding:\s*0;/.test(блок(CSS, '.news-hero-content-list {')),
    'ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: пока отступ стоял и у обложки,\n' +
    '          и у содержимого, замер давал 32 + 24 сверху на десктопе.');

правило('заголовок обложки — ступень шкалы, а не доля ширины',
    /font-size:\s*var\(--fs-hero\)/.test(блок(CSS, '.news-list-header h1 {')) &&
    /font-weight:\s*var\(--fw-extrabold\)/.test(блок(CSS, '.news-list-header h1 {')),
    'Замер 07.10 давал 21 при ступени 26 на телефоне.');

правило('обложка списка входит в общий список обложек разделов',
    /\.news-hero-list\.news-hero-list,/.test(СТИ),
    'Высоту на телефоне всем разделам задаёт один список в style.css.');

правило('доля высоты окна принадлежит обложке ОТДЕЛЬНОЙ новости',
    /\.news-hero:not\(:has\(\.news-hero-content-list\)\)\s*\{\s*height:\s*50vh/.test(
        CSS.replace(/\s+/g, ' ').replace(/\.news-hero:not\(:has\(\.news-hero-content-list\)\) \{ height: 50vh/g,
            '.news-hero:not(:has(.news-hero-content-list)) { height: 50vh')) ||
    /\.news-hero:not\(:has\(\.news-hero-content-list\)\)\s*\{[^}]*50vh/.test(CSS),
    'Без оговорки правило доставало и обложку СПИСКА: замер на 390×844\n' +
    '          дал 422 вместо 275, и пол раздела переставал значить что-либо.');

/* ══ 2. КАРТОЧКА — ОБЩИЙ КОМПОНЕНТ ═════════════════════════════════════ */

правило('карточку новости рисует общий компонент .tc',
    /class="tc' \+ \(isLarge \? ' tc-featured' : ''\)/.test(JS) &&
    /'<div class="tc-image"'/.test(JS) && /class="tc-body"/.test(JS),
    'Слово Кости: своей карточки у новостей нет.');

правило('своей вёрстки карточки (бенто) в коде не осталось',
    !/news-bento/.test(JS) && !/news-bento/.test(CSS),
    'Пятая копия карточки снесена 08.10 — 59 блоков css.');

правило('витрина несёт ОБА класса: правила карточки и свою раскладку',
    /class="tournaments-grid news-grid"/.test(JS),
    'Без tournaments-grid заголовок на телефоне шёл в восемь строк.');

правило('название карточки не берёт капс у заголовка секции',
    /text-transform:\s*none/.test(блок(CSS, '.news-grid .tc-title {')),
    'Крупная карточка несёт h2, а глобальный h2 в style.css — uppercase.');

правило('крупная — h2, боковая — h3: уровень не пропускается',
    /isLarge \? '<h2 class="tc-title">' : '<h3 class="tc-title">'/.test(JS),
    'Иерархия h1 → h2 → h3 без пропуска уровня.');

правило('внешняя новость уходит в новую вкладку и помечена стрелкой',
    /target="_blank" rel="noopener"/.test(JS) && /news-outside/.test(JS) &&
    /\.news-outside \.tc-title::after/.test(CSS),
    'Статью с чужого сайта мы не перепечатываем — переход наружу\n' +
    '          обязан быть виден до нажатия.');

/* ══ 3. РАСКЛАДКА ══════════════════════════════════════════════════════ */

правило('раскладка списка записана УДВОЕННЫМ классом',
    /\.news-grid\.news-grid > \.tc \{ grid-column: span 3; \}/.test(CSS),
    'Правила витрины лендинга записаны через :nth-child и весят больше\n' +
    '          простого `.news-grid > .tc`: замер 08.10 дал span 4 вместо 3.');

правило('крупная занимает половину ширины и ОБА ряда боковых',
    (() => {
        const б = блок(CSS, '.news-grid.news-grid > .tc:nth-child(1) {');
        return /grid-column:\s*span 6/.test(б) && /grid-row:\s*span 2/.test(б);
    })(),
    'Высота «крупная = две боковые» держится ОТНОШЕНИЕМ, а не числом.');

правило('на телефоне новости идут ПО ОДНОЙ',
    /\.news-grid\.news-grid > \.tc \{ grid-column: span 12; \}/.test(CSS),
    'Замер 08.10 на 390: колонка названия 137, срезано 4 заголовка из 7.\n' +
    '          У новости товар — заголовок, и он обязан читаться целиком.');

правило('на телефоне у заголовка списка три строки, а не две',
    /-webkit-line-clamp:\s*3/.test(CSS),
    'Две строки — правило витрины лендинга: там название турнира короткое.');

правило('витрина идёт по ширине общего ящика',
    /max-width:\s*var\(--container-max\)/.test(блок(CSS, '.news-list-page {')),
    'Узкий ящик страницы давал крупную 506 вместо посчитанных 676.');

правило('правила СПИСКА живут только на границах 640 и 992',
    (() => {
        const узкие = CSS.split(/@media \(max-width: (?:768|480|375)px\)/).slice(1)
            .map(ч => ч.slice(0, ч.indexOf('\n}\n') + 1))
            /* Оговорка «кроме списка» — это и есть граница между кусками,
               её наличие в узком блоке правилу не противоречит */
            .map(ч => ч.replace(/:not\(:has\(\.news-hero-content-list\)\)/g, ''));
        return !узкие.some(ч => /news-grid|news-list-page|news-list-header|news-hero-list|news-pagination|news-hero-content-list/.test(ч));
    })(),
    'Границы 768, 480 и 375 в файле остались, но только у СТРАНИЦЫ НОВОСТИ —\n' +
    '          это отдельный кусок, он не мерен и трогать его вслепую нельзя.');

/* ══ 4. ШАГ СТРАНИЦЫ И ПОЛОСА ══════════════════════════════════════════ */

правило('шаг страницы читается из живой сетки крутилкой',
    /getPropertyValue\('--novostey'\)/.test(JS) && /--novostey:\s*9/.test(CSS),
    'Число новостей на странице — колонок × рядов, а не зашитое число.');

правило('полосу страниц рисует общий компонент',
    /window\.KSLT_полосаСтраниц\(/.test(JS) && /polosa-stranic\.js/.test(RU) &&
    !/news-page-btn\s*\{/.test(CSS),
    'Пятая копия кнопок страниц снесена 07.10.');

/* ══ 5. ТРИ ЯЗЫКА ══════════════════════════════════════════════════════ */

правило('статья без перевода не уходит на чужой язык',
    /переведена:\s*isEn \? !!row\.title_en : \(isKg \? !!row\.title_kg : true\)/.test(JS) &&
    /a\.переведена !== false/.test(JS),
    'Решение Кости 08.10: новость из бота живёт только на русской версии —\n' +
    '          её текст по внешней ссылке всё равно русский.');

правило('подписи страницы есть на всех трёх языках',
    (() => {
        const п = JS.indexOf('var ПОДПИСИ = {');
        return п !== -1 && /ru:\s*\{/.test(JS.slice(п, п + 400)) &&
               /\n\s{4}en:\s*\{/.test(JS) && /\n\s{4}kg:\s*\{/.test(JS);
    })(),
    'До 08.10 window.newsLabels не объявляли нигде, и en/kg страницы\n' +
    '          стояли целиком по-русски.');

правило('пустые состояния говорят РАЗНОЕ про поиск и про категорию',
    /labels\.emptySearch \|\|/.test(JS) && /labels\.emptyCategory \|\|/.test(JS) &&
    /labels\.emptySearchHint \|\|/.test(JS) && /labels\.emptyCategoryHint \|\|/.test(JS),
    '«Ничего не нашлось» и «в категории пусто» — разные тупики,\n' +
    '          и выход из них разный.');

/* ══ 6. ДВИЖЕНИЕ И ВЕРСИИ ══════════════════════════════════════════════ */

правило('движение выключается по просьбе системы',
    /@media \(prefers-reduced-motion: reduce\)/.test(CSS) &&
    /\.news-grid > \.tc,/.test(блок(CSS, '@media (prefers-reduced-motion: reduce) {')),
    'Правило перенесено с «Игроков» и «Услуг» без нового разбора.');

правило('страница подключает свои файлы одной версией на три языка',
    (() => {
        const в = т => (т.match(/(?:news\.(?:css|js)|polosa-stranic\.js)\?v=(\d+)/g) || []).sort().join('|');
        return в(RU) !== '' && в(RU) === в(EN) && в(EN) === в(KG);
    })(),
    'Версия файла одна на все страницы: это держит правило заморозки.');

if (ошибки.length === 0) {
    console.log(`\n  ок      страница «Новости»: ${ВСЕГО} правил\n`);
    process.exit(0);
}
console.log(`\n  НЕ ТАК  страница «Новости»: ${ВСЕГО} правил, упало ${ошибки.length}.\n`);
ошибки.forEach(о => {
    console.log(`  ✗ ${о.имя}`);
    if (о.подсказка) console.log(`          ${о.подсказка}`);
});
console.log('');
process.exit(1);
