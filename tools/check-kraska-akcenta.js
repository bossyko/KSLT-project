/**
 * ЗАМОРОЗКА КРАСКИ АКЦЕНТА (кусок 74, 13.10.2026).
 *
 * ЗАМЕР: цвет акцента объявлен в `css/tokens.css` один раз, а записан в коде
 * числом — `#CCFF00` в 73 местах двадцати файлов и `rgba(204, 255, 0, …)`
 * ещё в 378. Прозрачностей оказалось ТРИДЦАТЬ ТРИ при двух заведённых
 * токенах (`--accent-subtle` 0.15 и `--accent-glow` 0.30).
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ:
 *   • числа акцента в продукте нет: цвет берётся токеном, а на холсте —
 *     читалкой токена;
 *   • читалка ОДНА: вторая копия разойдётся с первой;
 *   • запасного значения `var(--accent, #CCFF00)` нет нигде — оно и есть
 *     второе определение цвета, и оно врёт молча, если токен переименуют;
 *   • страница, зовущая холст, подключает читалку — иначе цвет не придёт
 *     вовсе (та же беда, что с правилом шрифта: правило стоит столько,
 *     сколько страниц его видят);
 *   • точные совпадения с токенами прозрачности записаны токеном.
 *
 *   node tools/check-kraska-akcenta.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const собрать = (кат, рас, спис) => {
    fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(д => {
        const п = кат + '/' + д.name;
        if (д.isDirectory()) собрать(п, рас, спис);
        else if (рас.test(д.name)) спис.push(п);
    });
    return спис;
};
const ФАЙЛЫ = собрать('css', /\.css$/, []).concat(собрать('js', /\.js$/, []));

/* ══ 1. ЧИСЛА АКЦЕНТА В ПРОДУКТЕ НЕТ ═══════════════════════════════════ */

/* ДОМ ОПРЕДЕЛЕНИЯ — `css/tokens.css`, и читалка, которая объясняет, зачем
   она есть. Выгрузка — единственное законное число: это ОТДЕЛЬНЫЙ html-файл
   без наших таблиц стилей, var(--accent) там не из чего разрешить. */
const ДОМ = ['css/tokens.css', 'js/kslt-kraska.js'];
const ВЫГРУЗКА = 'js/admin/core/export.js';

const слитералом = ФАЙЛЫ.filter(ф => ДОМ.indexOf(ф) === -1)
    .map(ф => ({ ф, n: (безКом(чит(ф)).match(/#ccff00/gi) || []).length }))
    .filter(x => x.n > 0);
const лишние = слитералом.filter(x => x.ф !== ВЫГРУЗКА);

правило('числа акцента в коде нет',
    лишние.length === 0,
    'файлов с #CCFF00: ' + лишние.length + ' — ' +
    лишние.slice(0, 4).map(x => x.ф + ' (' + x.n + ')').join(', ') + '.\n' +
    'Цвет объявлен один раз в css/tokens.css; на холсте его отдаёт\n' +
    'js/kslt-kraska.js. Число в коде — второе определение того же понятия');

const вВыгрузке = (слитералом.filter(x => x.ф === ВЫГРУЗКА)[0] || { n: 0 }).n;
правило('у выгрузки число одно и названо',
    вВыгрузке === 1,
    'в ' + ВЫГРУЗКА + ' чисел акцента: ' + вВыгрузке + ' при одном разрешённом');

/* ══ 2. ЗАПАСНОЕ ЗНАЧЕНИЕ — ЭТО ВТОРОЕ ОПРЕДЕЛЕНИЕ ═════════════════════ */

/* `var(--accent, #CCFF00)` выглядит заботой, а на деле прячет поломку:
   если токен переименуют, страница останется лаймовой и никто не заметит,
   пока не поменяют сам цвет. Токен живёт в `tokens.css`, который грузят
   все 90 страниц продукта — доказано куском 72. */
const запасные = ФАЙЛЫ.filter(ф => ДОМ.indexOf(ф) === -1)
    .map(ф => ({ ф, n: (безКом(чит(ф)).match(/var\(\s*--[\w-]*accent[\w-]*\s*,[^)]*\)/gi) || []).length }))
    .filter(x => x.n > 0);

правило('запасного значения у токена акцента нет',
    запасные.length === 0,
    'файлов с var(--accent, …): ' + запасные.length + ' — ' +
    запасные.slice(0, 4).map(x => x.ф + ' (' + x.n + ')').join(', '));

/* ══ 3. ЧИТАЛКА ОДНА И ЕЁ ПОДКЛЮЧАЮТ ТЕ, КОМУ ОНА НУЖНА ════════════════ */

/* СЧИТАЕМ ОБЪЯВЛЕНИЯ, А НЕ ФАЙЛЫ: две читалки в ОДНОМ файле — это тоже
   две читалки, и счёт по файлам их не увидит. Поймал прувер. */
const объявлений = ФАЙЛЫ.reduce((с, ф) => {
    const n = (безКом(чит(ф)).match(/window\.KSLT_KRASKA\s*=/g) || []).length;
    return с.concat(n ? [{ ф, n }] : []);
}, []);
const всегоЧиталок = объявлений.reduce((с, x) => с + x.n, 0);
правило('читалка токена одна на продукт',
    всегоЧиталок === 1 && объявлений.length === 1 && объявлений[0].ф === 'js/kslt-kraska.js',
    'объявлений window.KSLT_KRASKA: ' + всегоЧиталок + ' в ' + объявлений.length +
    ' файлах — ' + объявлений.map(x => x.ф + ' (' + x.n + ')').join(', ') +
    '.\nДве читалки разойдутся на первой же правке');

const ЗОВУТ = ФАЙЛЫ.filter(ф => /KSLT_KRASKA\.цвет/.test(безКом(чит(ф))));
const СТРАНИЦЫ = fs.readdirSync(path.join(КОРЕНЬ, 'pages'))
    .filter(ф => ф.endsWith('.html')).map(ф => 'pages/' + ф);
const безЧиталки = [];
СТРАНИЦЫ.forEach(с => {
    const т = чит(с);
    const зовёт = ЗОВУТ.some(ф => т.indexOf('/' + ф.split('/').pop() + '?v=') !== -1);
    if (зовёт && т.indexOf('kslt-kraska.js') === -1) безЧиталки.push(с);
});

правило('читалку подключают все страницы, которым она нужна',
    безЧиталки.length === 0,
    'страниц, зовущих холст без читалки: ' + безЧиталки.length + ' — ' +
    безЧиталки.slice(0, 4).join(', ') + '.\n' +
    'Правило стоит столько, сколько страниц его видят — то же, на чём\n' +
    'подвёл шрифт управлений в тот же день');

/* ══ 4. ТОЧНЫЕ СОВПАДЕНИЯ ЗАПИСАНЫ ТОКЕНОМ ═════════════════════════════ */

/* 0.15 и 0.30 заведены токенами. Число, равное токену, — копия. */
const копииТокенов = ФАЙЛЫ.filter(ф => ДОМ.indexOf(ф) === -1)
    .map(ф => ({ ф, n: (безКом(чит(ф))
        .match(/rgba\(\s*204\s*,\s*255\s*,\s*0\s*,\s*0?\.(?:15|150|3|30|300)\s*\)/g) || []).length }))
    .filter(x => x.n > 0);

правило('прозрачности, у которых есть токен, записаны токеном',
    копииТокенов.length === 0,
    'мест: ' + копииТокенов.reduce((с, x) => с + x.n, 0) + ' в ' +
    копииТокенов.length + ' файлах — ' +
    копииТокенов.slice(0, 3).map(x => x.ф).join(', ') + '.\n' +
    '0.15 — это --accent-subtle, 0.30 — --accent-glow');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      краска акцента: 6 правил');
    console.log('          числа в коде нет   ·   читалка одна и подключена');
    console.log('          запасных значений нет   ·   токены прозрачности не дублируются');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  краска акцента — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
