/**
 * ЗАМОРОЗКА СПИСКОВ КАБИНЕТА НА ТЕЛЕФОНЕ — баттлы и приглашения.
 *
 * Шесть колонок на 375 не помещаются ни при каких ширинах. Слово Кости
 * 12.10: прокрутка вбок не годится. На видах ≤640 строка перестаёт быть
 * строкой таблицы и становится строкой списка; на широких видах таблица
 * остаётся ровно такой, какой была.
 *
 * ЧТО ЗАМОРАЖИВАЕТСЯ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   • прячется ПАРА «заголовок + ячейка», а не номер колонки: номер
 *     принадлежит таблице матчей, а класс .db-matches-table носят пятеро;
 *   • на узком виде строка — грид с НАЗВАННЫМИ областями, а не дорожками
 *     по номеру;
 *   • клетка списка берёт ширину своей области, а не прежней колонки —
 *     и вес правила это обеспечивает, а не надежда на порядок;
 *   • имя стоит в одну строку и обрезается, а значок не сжимается;
 *   • клетка называет, что в ней лежит: значок или кнопки ответа;
 *   • кружок в списке — своя ступень, не ступень строки таблицы;
 *   • значок статуса собран по компоненту, и фон у него НЕПРОЗРАЧНЫЙ;
 *   • у каждой кнопки строки есть прозрачный слой цели 44;
 *   • высота кнопки держится свойством, а не суммой полей;
 *   • одно объявление на один класс.
 *
 *   node tools/check-kabinet-spiski.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const CSS = безКом(чит('css/dashboard.css'));
const JS  = безКом(чит('js/dashboard.js'));
const ТОК = чит('css/tokens.css');
const СТРАНИЦЫ = ['pages/dashboard.html', 'pages/dashboard-en.html', 'pages/dashboard-kg.html'].map(чит);

const ошибки = [];
let ВСЕГО = 0;
const правило = (имя, условие, подсказка) => { ВСЕГО++; if (!условие) ошибки.push({ имя, подсказка }); };

/** Тело блока @media ≤640, в котором живёт раскладка списком. */
const СПИСОК = (() => {
    const i = CSS.indexOf('@media (max-width: 640px)', CSS.indexOf('.db-battles-table,\n    .db-battles-table tbody') - 400);
    if (i === -1) return '';
    let j = CSS.indexOf('{', i), г = 0;
    for (; j < CSS.length; j++) {
        if (CSS[j] === '{') г++;
        else if (CSS[j] === '}') { г--; if (г === 0) return CSS.slice(i, j + 1); }
    }
    return '';
})();

/* ══ 1. ПРЯЧЕТСЯ ПАРА, А НЕ НОМЕР ═══════════════════════════════════════
   Правило писалось для таблицы матчей — там пятая колонка турнир. Класс
   .db-matches-table носят ещё баттлы, приглашения, платежи и баллы, и у
   баттлов пятая колонка — статус: заголовок исчезал, ячейка оставалась. */

правило('прячется пара «заголовок + ячейка», а не номер колонки',
    /\.db-matches-table th\.db-th-tournament,\s*\n\s*\.db-matches-table td\.db-match-tournament \{\s*\n\s*display: none/.test(CSS) &&
    !/\.db-matches-table th:nth-child\(5\)/.test(CSS),
    'колонка снова прячется по НОМЕРУ: номер принадлежит таблице матчей, а\n' +
    '          класс .db-matches-table носят пятеро. У баттлов пятая колонка —\n' +
    '          статус, и заголовок исчезал, а ячейка оставалась: в шапке пять\n' +
    '          клеток, в теле шесть, и table-layout: fixed раздавал ширины со сдвигом');

правило('заголовок колонки турнира назван во всех трёх таблицах матчей',
    (JS.match(/<th class="db-th-tournament">/g) || []).length === 3,
    'один из заголовков турнира снова безымянный — значит прячется он\n' +
    '          номером, и пара разъедется опять');

/* ══ 2. СПИСОК НА УЗКОМ ВИДЕ ════════════════════════════════════════════ */

правило('на узком виде строка — список, а не строка таблицы',
    /\.db-battles-table tbody tr,\s*\n\s*\.db-invites-table tbody tr \{[^}]*display: grid/.test(СПИСОК),
    'строка снова рисуется таблицей на телефоне: шесть колонок на 375 не\n' +
    '          помещаются ни при каких ширинах, и остаётся прокрутка вбок');

правило('области грида названы именами, а не номерами дорожек',
    /grid-template-areas:\s*\n\s*"who\s+who\s+who\s+who status"\s*\n\s*"date score res\s+act\s+h2h"/.test(СПИСОК) &&
    /grid-template-areas:\s*\n\s*"who\s+who\s+status"\s*\n\s*"date \.\s+act"/.test(СПИСОК),
    'раскладка перешла на номера дорожек: номер молчит о смысле, и клетка,\n' +
    '          переехавшая в разметке, встанет не туда без единой ошибки');

правило('клетка списка снимает ширину прежней колонки',
    /\.db-battles-table\.db-battles-table tbody td:nth-child\(1\)/.test(СПИСОК) &&
    /\.db-invites-table\.db-invites-table tbody td:nth-child\(4\)[\s\S]{0,80}width: auto/.test(СПИСОК),
    'клетка снова держит ширину колонки таблицы. Ширины записаны через\n' +
    '          td:nth-child(N) и весят (0,3,1); простое правило списка весит\n' +
    '          (0,1,2) и проигрывает — замер 12.10 дал клетку имени 44 вместо 222');

правило('имя стоит в одну строку и обрезается, а не переносится',
    /\.db-battles-table \.db-opp-link,[\s\S]{0,120}text-overflow: ellipsis;[\s\S]{0,40}white-space: nowrap/.test(СПИСОК),
    'имя снова переносится: при самом длинном значке под него остаётся 133,\n' +
    '          а самое длинное имя в базе просит 142 — строка вырастет на этаж');

правило('кружок в списке стоит на своей ступени',
    /\.db-battles-table \.db-match-avatar,[\s\S]{0,220}width: 32px/.test(СПИСОК),
    'кружок вернулся к 24 — это ступень строки ТАБЛИЦЫ (Avatar 29:82:\n' +
    '          «xs 24 for table rows, sm 32 for lists»), а строка теперь список');

/* ══ 3. КЛЕТКА НАЗЫВАЕТ, ЧТО В НЕЙ ЛЕЖИТ ════════════════════════════════ */

правило('клетка статуса и клетка кнопок различаются по имени',
    /db-cell-actions' : 'db-cell-status/.test(JS) &&
    /td\.db-cell-status\s*\{ grid-area: status/.test(СПИСОК) &&
    /td\.db-cell-actions \{ grid-area: act/.test(СПИСОК),
    'клетки снова различаются только номером. Значок встаёт в первую линию\n' +
    '          рядом с именем, кнопки — во вторую: вместе они не помещаются\n' +
    '          (посчитано: имя 133 минимум плюс кнопки 147 при ширине 324)');

/* ══ 4. ЗНАЧОК ПО КОМПОНЕНТУ, И ФОН НЕПРОЗРАЧНЫЙ ════════════════════════
   Badge 27:53: «Height 24px, horizontal padding 8px, radius/full, 11px
   Medium uppercase with 0.5px letter spacing». */

правило('значок статуса собран по компоненту Badge',
    /\.db-status-badge \{[^}]*min-height: 24px[^}]*border-radius: 999px[^}]*font-weight: 500/.test(CSS),
    'значок разошёлся с компонентом: высота 24, поля 8, радиус full и\n' +
    '          11 Medium — это его описание, а не вкус');

правило('фон значка — непрозрачная ступень, а не прозрачный тинт',
    /\.db-invite-declined \{[^}]*background: var\(--danger-surface\)/.test(CSS) &&
    /\.db-invite-accepted \{[^}]*background: var\(--success-surface\)/.test(CSS) &&
    /--danger-surface/.test(ТОК),
    'фон значка снова прозрачный. ПРОЗРАЧНАЯ КРАСКА СМЕШИВАЕТСЯ С ФОНОМ, а\n' +
    '          подложек у значка в кабинете три — #0A0A0A, #111111 и #1E1E1E:\n' +
    '          контраст одного и того же значка получается разный. На тинте\n' +
    '          красный давал 4.10 при норме AA 4.5, на ступени шкалы — 5.16');

/* МЕРИМ СВОЙ КУСОК, А НЕ ВЕСЬ ФАЙЛ. Material-цвета остались ещё в четырёх
   местах кабинета — .db-modal-done, две строки статистики и рамка поля
   (css/dashboard.css 2589, 2605, 2757, 5017). Это находка, записанная в
   трекер, и чинится она своими кусками; правило сторожит ТОЛЬКО значок. */
правило('тона значка берутся из шкалы, а не свои',
    /\.db-invite-declined \{[^}]*color: var\(--red-500\)/.test(CSS) &&
    /\.db-invite-accepted \{[^}]*color: var\(--green-500\)/.test(CSS) &&
    !/\.db-invite-(declined|accepted) \{[^}]*#[0-9a-f]{6}/i.test(CSS),
    'в значок вернулись цвета Material (#4caf50, #f44336), которых в палитре\n' +
    '          КСЛТ нет вовсе');

/* ══ 5. ЦЕЛИ НАЖАТИЯ И ВЫСОТА КНОПОК ════════════════════════════════════ */

правило('у H2H и кнопки ответа есть прозрачный слой цели 44',
    /\.db-match-h2h::after,\s*\n\.db-chal-btn::after \{[\s\S]{0,260}min-height: 44px/.test(CSS),
    'слой цели пропал: H2H красится 40x21, кнопка ответа 28 — пальцем в них\n' +
    '          не попасть, а красить их крупнее значило бы развести со строкой');

правило('высота кнопки ответа держится свойством, а не суммой полей',
    /\.db-chal-btn \{[^}]*min-height: 28px[^}]*line-height: 1/.test(CSS),
    'высота кнопки снова складывается из полей: замер 12.10 дал 25 — ни одной\n' +
    '          ступени шкалы 28 · 36 · 44 · 52');

правило('закрытие окна H2H на узких видах — ступень под палец',
    /\.h2h-close \{[^}]*min-height: 44px/.test(CSS),
    'закрытие окна вернулось к 36: Icon button 40:93 — «Only lg (44) meets\n' +
    '          the 44pt minimum touch target», а 36 это размер для мыши');

правило('межстрочный H2H стоит на ступени лестницы',
    /\.db-match-h2h \{[^}]*line-height: 1;/.test(CSS),
    'у H2H снова браузерный normal — единственный уровень строки мимо\n' +
    '          лестницы 1 · 1.1 · 1.3 · 1.5 · 1.65');

/* ══ 6. ОДНО ОБЪЯВЛЕНИЕ НА ОДИН КЛАСС ═══════════════════════════════════ */

правило('.db-chal-actions объявлен один раз',
    (CSS.match(/\.db-chal-actions \{/g) || []).length === 1,
    'класс снова объявлен дважды — выигрывает последнее, и правка первого\n' +
    '          блока молча ни на что не влияет');

/* СЧИТАЕМ ТОЛЬКО НАЗНАЧЕННЫЕ ШИРИНЫ, а не всякое упоминание width: сброс
   `width: auto` в списке — это снятие ширины, а не новый набор. */
const назначенныхШирин = (CSS.match(
    /\.db-(matches|battles|invites)-table[^{]*td:nth-child\(\d\)[^{]*\{[^}]*width:\s*\d/g) || []).length;
правило('ширины колонок не разрослись сверх трёх известных наборов',
    назначенныхШирин === 7,
    'наборов ширин стало ' + назначенныхШирин + ' вместо семи объявлений в трёх\n' +
    '          наборах: 110 и 34 % у матчей, 150 и 70 у баттлов, 76 · 104 · 210 у\n' +
    '          приглашений. Четвёртый набор — ещё один источник одного правила');

/* ══ 7. ВЕРСИИ ══════════════════════════════════════════════════════════ */

const версии = имя => {
    const найдено = new Set();
    СТРАНИЦЫ.forEach(s => {
        const re = new RegExp('/' + имя.replace('.', '\\.') + '\\?v=(\\d+)', 'g');
        let m; while ((m = re.exec(s))) найдено.add(m[1]);
    });
    return [...найдено];
};
[['dashboard.css'], ['dashboard.js']].forEach(([ф]) => {
    const в = версии(ф);
    правило('версия ' + ф + ' одна на все три языка',
        в.length === 1,
        ф + ' подключён разными версиями: ' + в.join(', '));
});

if (ошибки.length === 0) {
    console.log(`\n  ок      списки кабинета: ${ВСЕГО} правил\n`);
    process.exit(0);
}
console.log(`\n  НЕ ТАК  списки кабинета: ${ВСЕГО} правил, упало ${ошибки.length}.\n`);
ошибки.forEach(о => {
    console.log(`  ✗ ${о.имя}`);
    if (о.подсказка) console.log(`          ${о.подсказка}`);
    console.log('');
});
process.exit(1);
