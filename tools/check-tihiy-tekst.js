/**
 * ЗАМОРОЗКА ТИХОГО ТЕКСТА (кусок 73, 13.10.2026).
 *
 * РЕШЕНИЕ КОСТИ 06.10: «тихих уровней текста ТРИ: --text-dim уходит из
 * текста». Исполнено оно не было. Замер 13.10 нашёл `--text-dim` в 220
 * местах, из них 206 — цвет текста.
 *
 * ПОСЧИТАНО И ПРОВЕРЕНО В БРАУЗЕРЕ (WCAG 2.1, формула относительной
 * яркости), белый с альфой на трёх фонах продукта:
 *
 *            --bg-base #0A0A0A   --bg-card #111111   --bg-elevated #1E1E1E
 *   dim 0.35        3.14 МИМО          3.21 МИМО            3.21 МИМО
 *   muted 0.50      5.33 AA            5.33 AA              5.12 AA
 *   secondary 0.72 10.25 AA            9.98 AA              9.16 AA
 *
 * Норма AA — 4.5 для обычного текста и 3.0 для крупного (>= 24px, или
 * >= 18.66px полужирного). КРУПНОГО СРЕДИ НИХ НЕ БЫЛО НИ ОДНОГО: все 83
 * объявления в css стояли на кеглях 11-18.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ:
 *   • `--text-dim` не красит текст нигде, кроме НЕАКТИВНОГО — WCAG 1.4.3
 *     делает исключение только для него;
 *   • список неактивных ПОИМЁННЫЙ, а не по виду имени;
 *   • тихий уровень темнее своего соседа, но не ниже порога: альфа
 *     muted строго между dim и secondary;
 *   • в js цвета текста токеном `--text-dim` нет вовсе.
 *
 *   node tools/check-tihiy-tekst.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ══ 1. ПОИМЁННЫЙ СПИСОК НЕАКТИВНОГО ═══════════════════════════════════ */

/* WCAG 1.4.3 освобождает от порога контраста ТОЛЬКО неактивные элементы.
   Всё прочее — читаемый текст, и он обязан проходить AA. Список закрыт и
   назван поимённо: «по виду имени» тут не годится — `.ad-chal-none` звучит
   как пустое состояние, но это читаемая подпись, и она переведена. */
const НЕАКТИВНЫЕ = [
    '.ad-pts-in.ad-pts-zero',      // поле ввода очков, выключено
    '.ad-pts-off',                 // разряд выключен
    '.pl-row-guest .pl-col-rank',  // гостевая карточка — приглушение, решение продукта
    '.pl-guest-mark'               // метка гостя на той же карточке
];

const ФАЙЛЫ = fs.readdirSync(path.join(КОРЕНЬ, 'css')).filter(ф => ф.endsWith('.css'));
const найдено = [];
ФАЙЛЫ.forEach(ф => {
    const т = безКом(чит('css/' + ф));
    const бл = /([^{}]+)\{([^{}]*)\}/g;
    let м;
    while ((м = бл.exec(т)) !== null) {
        /* ЗАПИСЬ С ФОЛБЭКОМ — ТА ЖЕ КРАСКА. Первая редакция искала
           `color: var(--text-dim)` ТОЧНЫМ совпадением, и три места,
           записанные как `var(--text-dim, #666)`, правило не видело
           вовсе: решение 06.10 там не было исполнено, а сторож молчал.
           Фолбэк на вид не влияет, пока токен жив, — красит именно dim.
           ПРАВИЛО-СТОРОЖ, КОТОРОЕ ВРЁТ, ХУЖЕ ОТСУТСТВУЮЩЕГО. */
        if (!/color\s*:\s*var\(\s*--text-dim\s*[,)]/.test(м[2])) continue;
        найдено.push({ файл: ф, сел: м[1].split(/\s+/).filter(Boolean).join(' ') });
    }
});
const лишние = найдено.filter(н => НЕАКТИВНЫЕ.indexOf(н.сел) === -1);

правило('тихий текст не красится --text-dim',
    лишние.length === 0,
    'мест вне списка неактивных: ' + лишние.length + ' — ' +
    лишние.slice(0, 4).map(н => н.файл + ' ' + н.сел).join(', ') + '.\n' +
    'Посчитано: --text-dim даёт 3.14 на фоне страницы при норме AA 4.5.\n' +
    'Решение Кости 06.10: тихих уровней ТРИ, --text-dim уходит из текста');

правило('список неактивного не растёт молча',
    найдено.length <= НЕАКТИВНЫЕ.length,
    'объявлений color с --text-dim стало ' + найдено.length + ' при ' +
    НЕАКТИВНЫЕ.length + '.\nНовое неактивное заводится СПИСКОМ в этом файле, а не само собой');

/* ══ 2. В JS ЕГО НЕТ ВОВСЕ ═════════════════════════════════════════════ */

/* 136 инлайнов в двадцати файлах — «Загрузка…», подписи полей, счётчики,
   прочерки. Ничего выключенного среди них не было: проверено поиском
   disabled/readonly рядом — ноль совпадений. */
const пройтиJs = (кат, спис) => {
    fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(д => {
        const п = кат + '/' + д.name;
        if (д.isDirectory()) пройтиJs(п, спис);
        else if (д.name.endsWith('.js')) спис.push(п);
    });
    return спис;
};
const вJs = пройтиJs('js', []).reduce((с, ф) => {
    const n = (безКом(чит(ф)).match(/var\(--text-dim\)/g) || []).length;
    return n ? с.concat([{ ф, n }]) : с;
}, []);

правило('в js токена тихого текста нет',
    вJs.length === 0,
    'файлов с var(--text-dim): ' + вJs.length + ' — ' +
    вJs.slice(0, 3).map(x => x.ф + ' (' + x.n + ')').join(', ') + '.\n' +
    'Инлайн в js не виден ни заморозке лестницы, ни правке токена');

/* ══ 3. ЛЕСТНИЦА ТИХИХ УРОВНЕЙ — ОТНОШЕНИЕ, А НЕ ЧИСЛО ═════════════════ */

const ТОК = безКом(чит('css/tokens.css'));
const альфа = имя => {
    const м = ТОК.match(new RegExp('--' + имя + ':\\s*var\\(--alpha-white-(\\d+)\\)'));
    return м ? Number(м[1]) / 100 : null;
};
const a = { dim: альфа('text-dim'), muted: альфа('text-muted'), secondary: альфа('text-secondary') };

правило('тихие уровни стоят лестницей',
    a.dim !== null && a.muted !== null && a.secondary !== null &&
    a.dim < a.muted && a.muted < a.secondary,
    'альфы: dim ' + a.dim + ', muted ' + a.muted + ', secondary ' + a.secondary + '.\n' +
    'Три уровня обязаны идти по возрастанию — иначе «тише» перестаёт значить тише');

/* ПОРОГ КОНТРАСТА СЧИТАЕТСЯ, А НЕ ПОМНИТСЯ. Белый с альфой на самом
   тёмном фоне продукта: если альфа muted упадёт, текст уедет мимо AA, и
   правило упадёт раньше, чем это увидит человек. */
const лин = c => { c /= 255; return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4); };
const ярк = (r, g, b) => 0.2126 * лин(r) + 0.7152 * лин(g) + 0.0722 * лин(b);
const наФоне = (альфа, фон) => фон.map(c => 255 * альфа + c * (1 - альфа));
const контраст = (c1, c2) => {
    const l1 = ярк.apply(null, c1), l2 = ярк.apply(null, c2);
    return (Math.max(l1, l2) + 0.05) / (Math.min(l1, l2) + 0.05);
};
const ФОН = [10, 10, 10];
const кMuted = a.muted ? контраст(наФоне(a.muted, ФОН), ФОН) : 0;

правило('тихий уровень проходит AA на фоне страницы',
    кMuted >= 4.5,
    'посчитано: --text-muted даёт ' + кMuted.toFixed(2) + ' на #0A0A0A при норме 4.5');

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      тихий текст: 5 правил');
    console.log('          --text-dim только на неактивном (' + НЕАКТИВНЫЕ.length + ' мест, поимённо)');
    console.log('          в js его нет   ·   лестница альф   ·   muted ' + кMuted.toFixed(2) + ' на фоне страницы');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  тихий текст — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
