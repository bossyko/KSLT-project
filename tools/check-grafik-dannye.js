#!/usr/bin/env node
/**
 * ДАННЫЕ ГРАФИКА РЕЙТИНГА — ОДИН ДОМ НА ДВА ПРОДУКТА (шаг A3.3, 29.10).
 *
 * ЧТО БЫЛО. `js/rating-chart.js` и `mobile/www/js/rating-chart.js` — не
 * копия и отставшая копия, а ДВЕ РЕАЛИЗАЦИИ: сайт рисует через Chart.js,
 * приложение — свой SVG. Рисование законно разное, а логика данных была
 * продублирована и разошлась на пяти местах: `friendly` не выбрасывался
 * в приложении, порядок категорий считался своей арифметикой вместо
 * правила, второго ключа сортировки `created_at` не было (линия шла
 * зигзагом), `ntrp_after` не запрашивался, цвет-заглушка был зашит.
 *
 * ГРАНИЦА. Дом держит ДАННЫЕ. Язык и цвет-заглушка остаются продукту:
 * у приложения язык через `KSLT_I18N`, у сайта через `KSLT_YAZYK`, и
 * `KSLT_KRASKA` в приложении нет вовсе. Поэтому сторож НЕ требует, чтобы
 * язык и цвет жили в доме, — он требует, чтобы ДАННЫЕ не жили вне дома.
 *
 * Якоря держатся на содержимом, не на номерах строк.
 *
 * Запуск: node tools/check-grafik-dannye.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}
/* ЧИТАЕМ КОД, А НЕ ПОЯСНЕНИЯ: в шапках файлов перечислено, что здесь
   КОГДА-ТО стояло, и правило, считающее комментарий кодом, ловит слова,
   а не беду. Строки сохраняем на месте, чтобы номера не уехали. */
function безКом(т) {
    return т
        .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
        .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));
}

const ДОМ_САЙТ = 'js/kslt-grafik-dannye.js';
const ДОМ_ПРИЛ = 'mobile/www/js/kslt-grafik-dannye.js';
const ГРАФ_САЙТ = 'js/rating-chart.js';
const ГРАФ_ПРИЛ = 'mobile/www/js/rating-chart.js';

const домСайт = чит(ДОМ_САЙТ);
const домПрил = чит(ДОМ_ПРИЛ);

console.log('\n  ДАННЫЕ ГРАФИКА РЕЙТИНГА — ОДИН ДОМ\n');

правило('дом существует в обоих продуктах',
    domЕсть(),
    'Нужны оба файла: `' + ДОМ_САЙТ + '` и `' + ДОМ_ПРИЛ + '`.');
function domЕсть() { return domНеПуст(домСайт) && domНеПуст(домПрил); }
function domНеПуст(т) { return !!т && /KSLT_GRAFIK_DANNYE/.test(т); }

правило('копии дома побайтово равны',
    домСайт === домПрил,
    'Дом лежит копией в приложении. Копии разошлись — значит одно\n' +
    'понятие снова считается двумя разными способами, и беда родится\n' +
    'ровно на шве. Сверять память нельзя, сверяет проверка.');

/* ЧТО ОБЯЗАН ДЕРЖАТЬ ДОМ. Каждое — то, что разошлось 29.10. */
const ДОЛЖНО_БЫТЬ_В_ДОМЕ = [
    ['начало сезона 1 сентября', /-09-01/],
    ['отбор точек оценки', /API\.ntrpPoints\s*=/],
    ['печать оценки 4.0, а не 4', /API\.ntrp[А-Яа-я]+\s*=/],
    ['второй ключ сортировки created_at', /order\(\s*'created_at'/],
    /* ПРАВИЛО ЛОВИТ ЗАПРОС, А НЕ СЛОВО. Первая редакция искала просто
       `ntrp_after` — и перестала падать, когда в доме появился
       `API.ntrpPoints` с тем же словом внутри. Прувер это и показал:
       ПРАВИЛО, СЧИТАЮЩЕЕ ТЕКСТ, ЛОВИТ СЛОВА, А НЕ БЕДУ. */
    ['оценка ntrp_after читается из базы', /select\([^)]*ntrp_after/],
    ['friendly выброшен из зачёта', /!==\s*'friendly'/],
    ['парные не идут в очки', /is_doubles\s*!==\s*true/],
    ['порядок берётся у правила', /поСилеКатегорий/]
];
ДОЛЖНО_БЫТЬ_В_ДОМЕ.forEach(([имя, пр]) => {
    правило('в доме есть: ' + имя, пр.test(безКом(домСайт)),
        'Это разошлось между сайтом и приложением 29.10 и потому живёт\n' +
        'в доме. Признак: ' + пр);
});

правило('дом ПАДАЕТ без правила порядка',
    /throw new Error\(\s*'KSLT_GRAFIK_DANNYE/.test(домСайт),
    'Первая редакция дома имела мягкий откат на свою арифметику по\n' +
    '`sort_order`. Это ровно та беда, от которой дом заводился: без\n' +
    'правила порядок линий молча становился другим. ТИХОЕ РАСХОЖДЕНИЕ\n' +
    'ХУЖЕ ПАДЕНИЯ — дом обязан падать, а не подменять.');

/* ЧЕГО НЕ ДОЛЖНО БЫТЬ В РИСОВАЛЬЩИКАХ. Рисование остаётся своё,
   данные — нет. */
const НЕ_ДОЛЖНО_В_ГРАФИКЕ = [
    ['своё начало сезона', /-09-01/],
    ['свой отбор точек оценки', /ntrp_after\s*==\s*null/],
    ['своя печать оценки', /Math\.round\(\s*n\s*\*\s*100\s*\)/],
    ['свой выброс friendly', /'friendly'/],
    ['свой отбор парных', /is_doubles\s*!==\s*true/],
    ['своё чтение rating_history', /from\(\s*'rating_history'\s*\)/],
    ['своя сортировка категорий по sort', /\.sort\s*\)\s*\|\|\s*0/]
];
[ГРАФ_САЙТ, ГРАФ_ПРИЛ].forEach(ф => {
    const т = безКом(чит(ф));
    НЕ_ДОЛЖНО_В_ГРАФИКЕ.forEach(([имя, пр]) => {
        правило('в `' + ф.split('/').pop() + '` (' + (ф === ГРАФ_САЙТ ? 'сайт' : 'прил') +
                ') нет своего: ' + имя,
            !пр.test(т),
            'Данные обязаны идти из дома. Найдено в `' + ф + '`.\n' +
            'Признак: ' + пр);
    });
    правило('`' + ф.split('/').pop() + '` (' + (ф === ГРАФ_САЙТ ? 'сайт' : 'прил') +
            ') зовёт дом',
        /KSLT_GRAFIK_DANNYE/.test(т),
        'Рисовальщик обязан брать данные у дома по имени.');
});

/* ДОМ ПОДКЛЮЧЁН ВЕЗДЕ, ГДЕ ПОДКЛЮЧЁН ГРАФИК. Пропущенная страница
   молчит: график просто не нарисуется, а в консоли будет undefined. */
const РАЗМЕТКА = [
    'pages/admin.html', 'pages/dashboard.html', 'pages/dashboard-en.html',
    'pages/dashboard-kg.html', 'pages/player.html', 'pages/player-en.html',
    'pages/player-kg.html', 'mobile/www/index.html'
];
const безДома = [];
РАЗМЕТКА.forEach(ф => {
    const т = чит(ф);
    if (!/rating-chart\.js/.test(т)) return;
    if (!/kslt-grafik-dannye\.js/.test(т)) безДома.push(ф);
});
правило('в приложении есть график оценки',
    /API\.ntrpSvg\s*=/.test(безКом(чит(ГРАФ_ПРИЛ))),
    'Шаг A3.3б, слово Кости 29.10: «если на сайте есть, значит и в\n' +
    'приложении надо». На сайте график оценки рисует `renderNtrp`,\n' +
    'в приложении — `API.ntrpSvg`.');

/* Проверяем ТРИ имени, а не приставку: прувер переименовал только
   `.rc-single`, а `.rc-single-value` и `.rc-single-note` остались — и
   правило по приставке промолчало. Блок без своей краски разъедется. */
правило('одно измерение показано числом, а не графиком',
    /rc-single\b/.test(чит(ГРАФ_ПРИЛ)) &&
    ['\\.rc-single\\s*\\{', '\\.rc-single-value', '\\.rc-single-note']
        .every(п => new RegExp(п).test(чит('mobile/www/css/app.css'))),
    'График из единственной точки в углу пустого поля не сообщает\n' +
    'ничего. Решение взято у сайта — значит и разметка, и её краска\n' +
    'обязаны быть на месте в обоих продуктах.');

правило('подписи графика оценки есть в словаре',
    (function () {
        const d = чит('mobile/www/js/i18n.js');
        return /'pd\.ntrpHistory'/.test(d) && /'pd\.ntrpOnce'/.test(d) &&
               /'pd\.ntrpPoints'/.test(d);
    })(),
    'Новый блок обязан говорить словами из словаря, а не зашитым\n' +
    'текстом: словарь сохранён и вернётся вместе с языками (этап G).');

правило('дом подключён везде, где подключён график',
    безДома.length === 0,
    'Страницы грузят график без дома — ' + безДома.length + ':\n' +
    безДома.map(с => '  · ' + с).join('\n') +
    '\nПропущенная страница МОЛЧИТ: график не нарисуется, и всё.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      данные графика: все ' + держится + ' правил держатся\n');
}
