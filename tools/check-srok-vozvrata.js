#!/usr/bin/env node
/**
 * СРОК ВОЗВРАТА УДАЛЁННОГО АККАУНТА — ОДНО ЧИСЛО ВЕЗДЕ (шаг A3.7, 29.10).
 *
 * ЗАМЕР 29.10: срок жил в ТРИНАДЦАТИ местах — четыре объявления кода
 * (`js/account-restore.js`, `mobile/www/js/account-restore.js`,
 * `supabase/functions/delete-account`, `.../purge-deleted-accounts`) и
 * девять упоминаний словами на трёх языковых страницах удаления.
 *
 * ЭТО СРОК, ПОСЛЕ КОТОРОГО ДАННЫЕ УХОДЯТ НАВСЕГДА. Разойдись он —
 * человеку скажут «у вас ещё 30 дней», а `purge` удалит через
 * четырнадцать, и возвращать будет нечего. Поэтому правило держит не
 * «тридцать», а РАВЕНСТВО ВСЕХ МЕСТ: ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ, А НЕ
 * ЧИСЛО. Поменяли срок — поменяли в доме, и сторож потребует того же от
 * серверных функций и от текстов.
 *
 * Браузерные два свёл дом `js/kslt-rules.js` (`R.ДНЕЙ_НА_ВОЗВРАТ`).
 * Серверные функции живут отдельно и этот файл прочитать не могут —
 * поэтому их число сверяется, а не переносится.
 *
 * Запуск: node tools/check-srok-vozvrata.js
 */

const fs = require('fs');
const path = require('path');

const КОРЕНЬ = process.env.KSLT_KOREN
    ? path.resolve(process.env.KSLT_KOREN)
    : path.join(__dirname, '..');

let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
function чит(отн) {
    const п = path.join(КОРЕНЬ, отн);
    return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : '';
}

/* ---- ДОМ ---- */
const домТекст = чит('js/kslt-rules.js');
const мДом = домТекст.match(/R\.ДНЕЙ_НА_ВОЗВРАТ\s*=\s*(\d+)/);
const вДоме = мДом ? Number(мДом[1]) : null;

console.log('\n  СРОК ВОЗВРАТА — ОДНО ЧИСЛО ВЕЗДЕ\n');

правило('срок объявлен в доме правил',
    вДоме !== null,
    'В `js/kslt-rules.js` должен стоять `R.ДНЕЙ_НА_ВОЗВРАТ = <дней>`.');

правило('дом умеет считать дату удаления',
    /R\.датаУдаления\s*=/.test(домТекст),
    'Дату считали оба продукта своими руками, одинаковым кодом.\n' +
    'Считает дом — тогда и округление, и мусор на входе одни.');

правило('копии дома правил побайтово равны',
    чит('js/kslt-rules.js') === чит('mobile/www/js/kslt-rules.js'),
    'Разошлись — значит срок снова живёт двумя числами.');

/* ---- БРАУЗЕРНЫЕ НЕ ОБЪЯВЛЯЮТ СВОЁ ---- */
/* ИМЯ ПРАВИЛА СКЛЕИВАЕТСЯ ПРАВИЛЬНО, А НЕ «У САЙТ». Прувер ищет имя
   правила СТРОКОЙ, и склейка «у ' + имя + '» давала «у сайт нет…» —
   прувер не находил и молчал. Та же беда была в `check-plitki.js`
   («есть у приложение»): ИМЯ ПРАВИЛА — ТОЖЕ ЯКОРЬ. */
[['js/account-restore.js', 'сайта'],
 ['mobile/www/js/account-restore.js', 'приложения']].forEach(([ф, имя]) => {
    правило('у ' + имя + ' нет своего объявления срока',
        !/GRACE_DAYS\s*=\s*\d+/.test(чит(ф)),
        'Срок берётся из дома. Своё число здесь — второе определение.');
});

правило('сайт читает срок ЛЕНИВО, а не при загрузке',
    /get graceDays\(\)/.test(чит('js/account-restore.js')),
    'На `pages/dashboard.html` этот файл стоит в разметке РАНЬШЕ\n' +
    '`kslt-rules.js` (327 против 328). Жадное чтение дало бы ошибку на\n' +
    'загрузке. Зов во время работы не зависит от порядка тегов вовсе.');

/* ---- СЕРВЕРНЫЕ РАВНЫ ДОМУ ---- */
const СЕРВЕРНЫЕ = [
    'supabase/functions/delete-account/index.ts',
    'supabase/functions/purge-deleted-accounts/index.ts'
];
const расх = [];
СЕРВЕРНЫЕ.forEach(ф => {
    const м = чит(ф).match(/GRACE_DAYS\s*=\s*(\d+)/);
    if (!м) { расх.push(ф + ': объявления нет'); return; }
    if (Number(м[1]) !== вДоме) расх.push(ф + ': ' + м[1] + ' против ' + вДоме);
});
правило('серверные функции держат тот же срок',
    расх.length === 0,
    'Расходятся с домом — ' + расх.length + ':\n' +
    расх.map(с => '  · ' + с).join('\n') +
    '\nИменно здесь беда и случилась бы молча: страница обещает один\n' +
    'срок, а удаляет функция по своему.');

/* ---- ТЕКСТЫ СТРАНИЦ РАВНЫ ДОМУ ---- */
const СТРАНИЦЫ = [
    ['pages/delete-account.html', /(\d+)\s*дн/g],
    ['pages/delete-account-en.html', /(\d+)\s*days?/g],
    ['pages/delete-account-kg.html', /(\d+)\s*к[үу]н/g]
];
const вТекстах = [];
СТРАНИЦЫ.forEach(([ф, пр]) => {
    const т = чит(ф);
    if (!т) { вТекстах.push(ф + ': страницы нет'); return; }
    let м, нашлось = 0;
    пр.lastIndex = 0;
    while ((м = пр.exec(т)) !== null) {
        нашлось++;
        if (Number(м[1]) !== вДоме) вТекстах.push(ф + ': «' + м[0].trim() + '»');
    }
    if (!нашлось) вТекстах.push(ф + ': срок словами не найден вовсе');
});
правило('тексты страниц удаления называют тот же срок',
    вТекстах.length === 0,
    'Расходятся с домом — ' + вТекстах.length + ':\n' +
    вТекстах.map(с => '  · ' + с).join('\n') +
    '\nЧеловек читает ЧИСЛО НА СТРАНИЦЕ, а не константу в коде.\n' +
    'Поменяли срок в доме — обязаны поменять и здесь, во всех трёх\n' +
    'языках. Это ровно то место, где Play ловит на расхождении.');

console.log('');
if (упало) {
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n');
    process.exitCode = 1;
} else {
    console.log('  ок      срок возврата: все ' + держится + ' правил держатся');
    console.log('          срок в доме: ' + вДоме + ' дней, и столько же в двух');
    console.log('          серверных функциях и на трёх языковых страницах\n');
}
