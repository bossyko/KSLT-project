#!/usr/bin/env node
/**
 * ЗАМОРОЗКА СТРАНИЦ РАЗДЕЛА «ИНФО» — кусок 54-й, 09.10.
 *
 * ОДИН ФАЙЛ — ШЕСТЬ СТРАНИЦ. `css/info-pages.css` обслуживает «О проекте»,
 * «Правила», FAQ, «Условия», «Политику» и «Оферту», а с языками это
 * ВОСЕМНАДЦАТЬ html. Поэтому правила здесь стерегут общий слой: одна
 * поломка в нём — это шесть сломанных страниц.
 *
 * ЧТО БЫЛО ДО ПРАВКИ (замер 09.10, пять видов, три языка): обложка
 * занимала 33% · 87% · 27% · 44% · 38% экрана и объявляла свои 340 и поля
 * 120/60; заголовок шёл 22.62 · 42.2 · 27.2 · 51.2 · 51.2; межстрочных
 * девять разных; точек останова ПЯТЬ (375 · 480 · 720 · 768 · 992) при двух
 * разрешённых; 74 отступа мимо шкалы; `:focus-visible` ноль при 140
 * правилах; `prefers-reduced-motion` ноль при двадцати движущихся; два
 * мёртвых правила.
 *
 * ЧЕГО ЭТА ЗАМОРОЗКА НЕ ДЕРЖИТ, И ЭТО НАЗВАНО ВСЛУХ: текст «Оферты» и
 * «Политики» приходит ИЗ БАЗЫ (`site_documents`, js/site-content.js:173).
 * 09.10 оттуда сняты восемь инлайновых кеглей, но вернуться они могут
 * только через базу, а заморозка читает ФАЙЛЫ. Сторожить данные нечем —
 * нужен замер в браузере, он в пробе.
 *
 *   node tools/check-info-stranicy.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '');

const CSS  = чит('css/info-pages.css');
const CSSч = безКом(CSS);
const СТРАНИЦЫ = ['about', 'rules', 'faq', 'terms', 'privacy-policy', 'offer'];
const ЯЗЫКИ = ['', '-en', '-kg'];
const HTML = {};
СТРАНИЦЫ.forEach(с => ЯЗЫКИ.forEach(я => { HTML[с + я] = чит('pages/' + с + я + '.html'); }));

const ошибки = [];
let всегоПравил = 0;
const правило = (имя, условие, подсказка) => {
    всегоПравил++;
    if (!условие) ошибки.push({ имя, подсказка });
};

function блок(текст, селектор) {
    const i = текст.indexOf(селектор);
    if (i === -1) return '';
    const о = текст.indexOf('{', i);
    if (о === -1) return '';
    let гл = 0;
    for (let j = о; j < текст.length; j++) {
        if (текст[j] === '{') гл++;
        else if (текст[j] === '}') { гл--; if (!гл) return текст.slice(о, j + 1); }
    }
    return '';
}

/* ─────────── ОБЛОЖКА, ОДНА НА ШЕСТЬ СТРАНИЦ ─────────── */

правило('высота обложки — общая крутилка раздела',
    /min-height:\s*var\(--oblozhka-pol\)/.test(блок(CSSч, '.ip-hero {')),
    'в обложку вернулось своё число высоты — шесть страниц разойдутся с остальным сайтом');

правило('воздух обложки — общие крутилки',
    /padding:\s*var\(--oblozhka-vozduh\)\s+var\(--pad-x\)\s+var\(--oblozhka-vozduh-niz\)/
        .test(блок(CSSч, '.ip-hero {')),
    'воздух обложки снова задан своими числами: было 120 сверху и 60 снизу, оба мимо шкалы');

/* ─────────── ЛЕСТНИЦА ─────────── */

правило('заголовок обложки — крутилка --fs-hero',
    /font-size:\s*var\(--fs-hero\)/.test(блок(CSSч, '.ip-hero-title {')),
    'заголовок снова считается своим clamp — он давал пять чисел мимо шкалы');

правило('подзаголовок обложки — крутилка --fs-hero-sub',
    /font-size:\s*var\(--fs-hero-sub\)/.test(блок(CSSч, '.ip-hero-subtitle {')),
    'подзаголовок ушёл со ступени обложки раздела');

правило('ни одного clamp для кегля во всём файле',
    !/font-size:\s*clamp\(/.test(CSSч),
    'вернулся clamp: кегль перестал быть ступенью и поплывёт между видами на шести страницах');

правило('межстрочные — только ступени лестницы',
    (CSSч.match(/line-height:\s*([0-9.]+)/g) || [])
        .map(с => parseFloat(с.split(':')[1]))
        .every(з => [1, 1.1, 1.3, 1.5, 1.65].includes(з)),
    'в файле снова межстрочный мимо лестницы 1 · 1.1 · 1.3 · 1.5 · 1.65');

правило('у кнопки вопроса межстрочный задан, а не оставлен шрифту',
    /line-height:\s*1\.3/.test(блок(CSSч, '.ip-faq-question {')),
    '`normal` — это не значение, а ссылка на метрику гарнитуры: кнопка снова вне лестницы');

/* ─────────── ГРАНИЦЫ ─────────── */

правило('границ ровно две — 640 и 992',
    (CSSч.match(/@media \(max-width: (\d+)px\)/g) || [])
        .map(с => с.match(/(\d+)px/)[1])
        .every(ш => ш === '640' || ш === '992'),
    'в файл вернулась третья точка останова: было пять — 375 · 480 · 720 · 768 · 992');

/* ─────────── ШКАЛА ОТСТУПОВ ─────────── */

правило('ни одного отступа мимо шкалы',
    !(CSSч.match(/(?:padding|margin|gap)[a-z-]*:\s*[^;]+;/g) || [])
        .some(с => /\b(?:1|2|3|5|6|7|9|10|11|13|14|15|17|18|19|20|21|22|23|25|26|27|28|29|30|31|33|34|35|36|37|38|39|41|42|44|45|46|48|50|52|54|56|60|64|72|80|100|120)px/.test(с)),
    'вернулся отступ мимо шкалы 8 · 12 · 16 · 24 · 32 · 40 — их было 74');

/* ─────────── ДОСТУПНОСТЬ ─────────── */

/* ПОИМЁННО, А НЕ СЧЁТОМ. Первая редакция требовала «пять и больше»
   вхождений :focus-visible, и когда 09.10 к ним добавилась кнопка призыва,
   откат одного перестал ронять правило: счёт оставался выше порога.
   ПРАВИЛО, КОТОРОЕ СЧИТАЕТ ШТУКИ, СЛАБЕЕТ ОТ КАЖДОЙ НОВОЙ ШТУКИ. */
const ФОКУСНЫЕ = ['.ip-faq-question:focus-visible', '.ip-cta-btn:focus-visible'];
правило('фокус с клавиатуры виден у вопроса и у кнопки призыва',
    ФОКУСНЫЕ.every(с => CSSч.includes(с)) &&
    (CSSч.match(/:focus-visible/g) || []).length >= 5,
    'пропал :focus-visible у ' + ФОКУСНЫЕ.filter(с => !CSSч.includes(с)).join(', ') +
    ' — было ноль при 140 правилах, и это шесть страниц сразу');

правило('движение спрашивает системную настройку',
    /@media \(prefers-reduced-motion: reduce\)/.test(CSSч),
    'снято уважение к «меньше движения» при двадцати движущихся правилах');

/* ─────────── МЁРТВОЕ ─────────── */

правило('мёртвые правила не вернулись',
    !/\.ip-team-photo\b/.test(CSSч) && !/\.ip-rules-nav\b/.test(CSSч),
    'вернулся класс, которого нет ни в одной разметке и ни в одном js — проверено поиском по проекту');

/* ─────────── ОФОРМЛЕНИЕ ДОКУМЕНТОВ ЖИВЁТ В КЛАССАХ ─────────── */

/* Текст «Оферты» и «Политики» приходит из базы. 09.10 из тел документов
   сняты инлайновые кегли — значит кегль обязан быть в классе, иначе
   абзацы останутся без размера вовсе. */
правило('кегль вводного абзаца и строки о редакции задан классами',
    /font-size:\s*var\(--fs-/.test(блок(CSSч, '.ip-doc-lead {')) &&
    /font-size:\s*var\(--fs-/.test(блок(CSSч, '.ip-doc-revision {')),
    'класс документа перестал задавать кегль — а в данных его больше нет, снят 09.10');

/* ─────────── ОБЛОЖКА: ОДНА ЛЕСТНИЦА НА ДЕВЯТЬ РАЗДЕЛОВ ─────────── */

/* 09.10, ПОСЛЕ КОДА. Кегль перебивки был объявлен ДВАЖДЫ: крутилкой в
   основном блоке и своим --fs-sm в блоке ≤992. Выигрывало второе, и замер
   дал 21 · 14 · 14 · 14 · 21 вместо эталонных 21 · 18 · 16 — у «Инфо»
   завелась третья лестница обложки. Проба этого не поймала: 14 — законная
   ступень шкалы, а она проверяет «со шкалы», а не «равен крутилке».
   ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ: кегль перебивки — ТОЛЬКО крутилка. */
/* ПРУВЕР УРОНИЛ ПЕРВУЮ РЕДАКЦИЮ: я проверял здесь ЗАОДНО и саму крутилку,
   а это отношение соседнего правила — откат к --fs-md валил оба.
   ОДНО ПРАВИЛО — ОДНО ОТНОШЕНИЕ. Здесь стережём только ЧИСЛО объявлений. */
правило('кегль перебивки обложки объявлен в файле РОВНО ОДИН раз',
    (CSSч.match(/\.ip-hero-subtitle\s*\{[^}]*font-size/g) || []).length === 1,
    'кегль перебивки объявлен второй раз — обложка «Инфо» разойдётся с восемью соседними разделами, и замер покажет 14 там, где эталон 18 и 16');

/* ─────────── ВЕРСИИ ─────────── */

const версии = Object.keys(HTML).map(к => (HTML[к].match(/info-pages\.css\?v=(\d+)/) || [])[1]);
правило('версия стиля поднята и одинакова на всех восемнадцати страницах',
    версии.length === 18 && версии.every(в => в && Number(в) >= 43) &&
    new Set(версии).size === 1,
    'версия info-pages.css не поднята или разошлась между страницами — часть получит старое из кеша');

const всего = всегоПравил;
if (ошибки.length) {
    console.log('\n  ✗ страницы «Инфо» — ' + ошибки.length + ' из ' + всего + ':\n');
    ошибки.forEach(о => console.log('    · ' + о.имя + '\n      ' + о.подсказка));
    console.log('');
    process.exit(1);
}
console.log('ок страницы «Инфо»: ' + всего + ' правил');
