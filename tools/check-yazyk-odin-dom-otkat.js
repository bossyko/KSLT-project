/* ЯКОРЬ НА ТЕГ СКРИПТА БЕРЁТСЯ ИЗ ФАЙЛА, А НЕ ПИШЕТСЯ ПО ПАМЯТИ. Внутри
   тега стоит номер версии, а его поднимает КАЖДЫЙ кусок, трогающий файл:
   записанный в прувер литерал `?v=1` переставал встречаться, и прувер
   говорил «якорь встречается 0 раз» — честно, но без доказательства.
   Якорь держится на СОДЕРЖИМОМ: имя файла в теге живёт там постоянно. */
function тег(файл, имяСкрипта) {
    const т = fs.readFileSync(path.join(ВРЕМ, файл), 'utf8');
    const ш = new RegExp('[ \\t]*<script src="[^"]*' + имяСкрипта.replace('.', '\\.') + '[^"]*"></script>\\n');
    const м = т.match(ш);
    if (!м) { console.log('\n  x нет тега ' + имяСкрипта + ' в ' + файл); process.exit(1); }
    return м[0];
}

