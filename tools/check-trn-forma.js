/**
 * ЗАМОРОЗКА ВКЛАДКИ «РЕДАКТИРОВАНИЕ» ФОРМЫ ТУРНИРА.
 *
 * Замер 28.09 и решения Кости того же дня. Здесь заморожены ОТНОШЕНИЯ, а
 * не числа: «ширина поля берётся ступенью компонента, а не пишется в
 * секции», «цель нажатия определена один раз», «сетка формы одна».
 *
 *   node tools/check-trn-forma.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ТУРНИРЫ  = чит('js/admin/sections/tournaments.js');
const ТУРч     = безКом(ТУРНИРЫ);
const АДМИН    = чит('css/admin.css');
const АДч      = безКом(АДМИН);
const СТРАНИЦА = чит('pages/admin.html');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* Блок css по имени селектора, со счётом скобок: вложенное регуляркой
   не огораживается, и «блок» без счёта утекает до конца файла */
function блок(текст, селектор) {
    const i = текст.indexOf(селектор + ' {');
    if (i === -1) return '';
    let гл = 0, j = текст.indexOf('{', i);
    for (let k = j; k < текст.length; k++) {
        if (текст[k] === '{') гл++;
        else if (текст[k] === '}') { гл--; if (!гл) return текст.slice(j + 1, k); }
    }
    return '';
}

/* ─────────── СЕТКА ФОРМЫ ─────────── */

правило('сетка формы одна: инлайн-гридов в секции нет',
    !/display:\s*grid;\s*grid-template-columns:\s*repeat/.test(ТУРч),
    'вернулась инлайн-сетка в разметке — медиа-правило знает только классы, ' +
    'и на узком виде такой ряд не схлопнется');

правило('готовые ряды взяты из компонента, а не написаны заново',
    /ad-field-row-4/.test(ТУРч) && /ad-field-row \{/.test(АДч),
    '.ad-field-row-4 больше не используется или пропал из admin.css');

правило('ряд полей сетки идёт потоком, а не колонками',
    (ТУРч.match(/ad-field-row ad-field-flow/g) || []).length === 3 &&
    блок(АДч, '.ad-field-flow').includes('flex-wrap'),
    'рядов-потоков в карточке «Тип сетки» должно быть ровно три: настройки ' +
    'сетки, расписание матча, подписи протокола');

/* ─────────── ШИРИНА ПОЛЯ ─────────── */

правило('ступени ширины поля заведены в компоненте',
    /--pole-shirina/.test(АДч) &&
    ['.ad-pole-uzkoe', '.ad-pole-srednee', '.ad-pole-shirokoe']
        .every(к => блок(АДч, к).includes('--pole-shirina')),
    'ступени ширины поля пропали из admin.css — секция начнёт писать числа сама');

правило('ширина поля не пишется числом в секции',
    !/class="ad-field[^"]*"[^>]*style="[^"]*width:/.test(ТУРч),
    'в разметке появилась ширина поля числом: новый размер заводится в компоненте');

правило('ступени ширины стоят на шкале восьмёрки',
    (блок(АДч, '.ad-pole-uzkoe') + блок(АДч, '.ad-pole-srednee') + блок(АДч, '.ad-pole-shirokoe'))
        .match(/(\d+)px/g).every(п => parseInt(п, 10) % 8 === 0),
    'ступень ширины поля перестала делиться на 8');

/* ─────────── КНОПКИ ─────────── */

правило('высота кнопки — свойством, а не полями',
    /height:\s*var\(--ad-btn-h/.test(блок(АДч, '.ad-btn')) &&
    !/padding:\s*\d+px\s+\d+px/.test(блок(АДч, '.ad-btn')),
    'у .ad-btn вернулся вертикальный padding вместо height — высота поедет мимо шкалы');

правило('ступени кнопки берут переменные, а не числа',
    ['.ad-btn-xs', '.ad-btn-sm', '.ad-btn-lg'].every(к => /var\(--btn-h-/.test(блок(АДч, к))),
    'ступень кнопки записана числом вместо --btn-h-*');

правило('цель нажатия 44 определена ОДИН раз',
    (АДч.match(/--ad-cel-h,\s*var\(--btn-h-sm\)\)\)\s*\/\s*-2\)/g) || []).length === 2,
    'слой цели нажатия снова написан копией — он должен быть в одном блоке');

правило('цель нажатия считается из ступени, а не зашита числом',
    /calc\(\(var\(--btn-h-md\)\s*-\s*var\(--ad-cel-h/.test(АДч),
    'слой цели вернулся к зашитым -4px: при другой ступени он соврёт');

правило('крестик удаления афиши знает свою ступень xs',
    /\.ad-image-upload-remove\s*\{\s*--ad-cel-h:\s*var\(--btn-h-xs\)/.test(АДч),
    'крестику 28×28 вернули слой на 4 вместо 8 — цель нажатия снова меньше 44');

правило('кольцо фокуса стоит на базовом классе кнопки',
    блок(АДч, '.ad-btn:focus-visible').includes('outline'),
    ':focus-visible снова у избранных классов — клавиатурой по админке не пройти');

/* ─────────── УРОВЕНЬ И ОЧКИ ─────────── */

правило('уровень турнира скрыт там, где очков не дают',
    /безОчков\s*=\s*isDbl\s*\|\|\s*дружескийТурнир\(\)/.test(ТУРч),
    'условие показа уровня сузилось: дружеский турнир снова сможет начислить очки');

правило('скрытый уровень обнуляется, а не уезжает в базу',
    /if\s*\(безОчков\s*&&\s*lvlField\)\s*lvlField\.value\s*=\s*''/.test(ТУРч),
    'спрятанный уровень перестал сбрасываться — значение уедет в базу');

правило('«дружеский» определён в одном месте',
    (ТУРч.match(/===\s*'friendly'/g) || []).length === 1,
    'проверка friendly появилась второй копией — беда родится на шве');

правило('смена категории перерисовывает форму',
    /getElementById\('adTrnCat'\)\.addEventListener\('change',\s*toggleFormatDependentFields\)/.test(ТУРч),
    'категория перестала перерисовывать форму: уровень останется от прежнего выбора');

правило('взаимоисключающие поля стоят соседями и делят ячейку',
    ТУРч.indexOf('adTrnLevelWrap') < ТУРч.indexOf('adTrnNtrpCombinedWrap') &&
    ТУРч.indexOf('adTrnNtrpCombinedWrap') - ТУРч.indexOf('adTrnLevelWrap') < 700,
    'уровень и общий NTRP разъехались по разметке — между ними встанет дыра');

/* ─────────── УМОЛЧАНИЕ — СВОЙСТВО ДАННЫХ ─────────── */

правило('скрытие полей сетки не зашито в разметку',
    !/id="adTrn(GroupCount|PerGroup|Qualifiers|Playoff)Wrap"\s+style="display:none/.test(ТУРч),
    'начальное состояние поля вернулось в разметку: умолчание — свойство данных');

правило('подсказка расчёта без инлайн-стиля',
    !/id="adTrnDrawHint"[^>]*style=/.test(ТУРч),
    'подсказке вернули инлайн-стиль с отрицательным отступом');

правило('отступы подсказки расчёта со шкалы',
    /padding:\s*12px\s+16px/.test(блок(АДч, '.ad-sched-note')),
    'отступы подсказки снова мимо шкалы 8·12·16·24·32·40');

/* ─────────── ВЕРСИИ ─────────── */

правило('версии подняты — иначе браузер отдаст старое из кеша',
    /sections\/tournaments\.js\?v=(4[9-9]|[5-9]\d)/.test(СТРАНИЦА) &&
    /admin\.css\?v=1(6[7-9]|[7-9]\d)/.test(СТРАНИЦА),
    'версия tournaments.js или admin.css не поднята после правки');

/* ─────────── ВЫВОД ─────────── */

const всего = 21;
if (ошибки.length) {
    console.log('\n  ✗ форма турнира, вкладка «Редактирование» — ' + ошибки.length + ' из ' + всего + ':\n');
    ошибки.forEach(о => console.log('    · ' + о.имя + '\n      ' + о.подсказка));
    console.log('');
    process.exit(1);
}
console.log('ок форма турнира, вкладка «Редактирование»: ' + всего + ' правил');
