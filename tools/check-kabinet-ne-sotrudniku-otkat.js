function копия() {
    const к = fs.mkdtempSync(path.join(os.tmpdir(), 'kslt-kabinet-'));
    /* КОПИЯ, НЕПОЛНАЯ ОТНОСИТЕЛЬНО ПРОВЕРЯЕМОГО, НИЧЕГО НЕ ДОКАЗЫВАЕТ.
       С 09.11 сторож читает и кабинет ПРИЛОЖЕНИЯ — правило про обработчик
       без кнопки. Третий раз за сутки одна и та же беда у разных пруверов. */
    for (const о of ['js', 'tools', 'pages', 'mobile']) {
        const и = path.join(КОРЕНЬ, о);
        if (fs.existsSync(и)) fs.cpSync(и, path.join(к, о), { recursive: true });
    }
    /* КОРНЕВЫЕ СТРАНИЦЫ ТОЖЕ: правила про версии и порядок подключения
       обходят ВСЕ страницы сайта, и без корневых прибор мерил бы половину. */
    for (const и of fs.readdirSync(КОРЕНЬ)) {
        if (и.endsWith('.html')) fs.cpSync(path.join(КОРЕНЬ, и), path.join(к, и));
    }
    return к;
}
function прогон(к) {
    try {
        return execFileSync('node', [path.join(к, 'tools/check-kabinet-ne-sotrudniku.js')],
            { env: { ...process.env, KSLT_KOREN: к }, encoding: 'utf8' });
    } catch (e) { return (e.stdout || '') + (e.stderr || ''); }
}

