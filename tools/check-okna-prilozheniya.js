#!/usr/bin/env node
/**
 * ОКНА ПРИЛОЖЕНИЯ — НИ ОДНО НЕ ОСТАЛОСЬ БЕЗ ОСНАСТКИ (29.10).
 *
 * ЗАЧЕМ. Кусок 230 (28.10) завёл дом `mobile/www/js/kslt-okno.js`: он
 * СЛУШАЕТ появление класса `open` и сам ставит окну `role="dialog"`,
 * `aria-modal`, подпись для диктора, уводит фокус внутрь, держит Tab,
 * слушает Esc и возвращает фокус тому, кто окно открыл. Ни один из 76
 * зовов для этого не правится — и это верно.
 *
 * НО ДОМ УЗНАЁТ ОКНО ПО СПИСКУ КЛАССОВ, А СПИСОК ДЕРЖАЛСЯ РУКАМИ — И
 * ОТСТАЛ. Замер 29.10: класс `open` ставят в **26 местах**, а в списке
 * было ВОСЕМЬ классов, и СЕМЬ окон в него не попали: возврат учётной
 * записи, онбординг, смена пароля, вход через Telegram, приглашения на
 * игру и личные встречи (из двух мест). Для диктора этих семи окон не
 * существовало, Tab уходил читать страницу под окном, Esc не работал.
 *
 * ЧТО ДЕРЖИТ СТОРОЖ: он обходит ВСЕ места, где ставится класс `open`,
 * разбирает, какой узел открывается и какой у него класс, и требует,
 * чтобы каждое окно было либо накрыто списком дома, либо НАЗВАНО
 * ИСКЛЮЧЕНИЕМ С ПРИЧИНОЙ. Список он читает ИЗ ДОМА, а не держит свой:
 * иначе отстал бы и он.
 *
 * ПОЧЕМУ НЕ «ЛЮБОЙ УЗЕЛ С КЛАССОМ open»: класс `open` носит и НЕ-ОКНО —
 * `.tc-status.open` (корт «открыт», `app.css:911`). Дом, объявивший
 * такую плашку окном, увёл бы в неё фокус.
 *
 * Запуск: node tools/check-okna-prilozheniya.js
 */
const fs = require('fs');
const path = require('path');
const КОРЕНЬ = process.env.KSLT_KOREN ? path.resolve(process.env.KSLT_KOREN)
                                      : path.join(__dirname, '..');
let упало = 0, держится = 0;
function правило(имя, условие, объяснение) {
    if (условие) { держится++; return; }
    упало++;
    console.log('  ✗ ' + имя);
    console.log('    ' + объяснение.split('\n').join('\n    '));
}
const чит = о => { const п = path.join(КОРЕНЬ, о); return fs.existsSync(п) ? fs.readFileSync(п, 'utf8') : ''; };
const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
                     .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + ' '.repeat(м.length - п.length));

function главное() {
const ДОМ = 'mobile/www/js/kslt-okno.js';
const РАЗМЕТКА = 'mobile/www/index.html';

/**
 * ОКНА, КОТОРЫЕ НАМЕРЕННО НЕ ОКНА. Безымянных исключений не бывает.
 */
const ИСКЛЮЧЕНИЯ = {
    'auth-screen': 'ЭТО НЕ ОКНО ПОВЕРХ СТРАНИЦЫ, А САМ ЭКРАН ВХОДА. Под ним ' +
        'нет страницы, к которой можно вернуться, и возвращать фокус ' +
        'некому: вошёл — экран уходит, не вошёл — он единственное, что ' +
        'есть. `role="dialog"` здесь сказал бы диктору неправду.'
};

/* СПИСОК КЛАССОВ ЧИТАЕТСЯ ИЗ ДОМА. */
const СПИСОК = (function () {
    const м = безКом(чит(ДОМ)).match(/var ОКНА = ([\s\S]*?);/);
    if (!м) return null;
    return (м[1].match(/\.([A-Za-z0-9_-]+)/g) || []).map(с => с.slice(1));
})();

/* ВСЕ МЕСТА, ГДЕ СТАВИТСЯ КЛАСС `open`, И КАКОЙ УЗЕЛ ОТКРЫВАЕТСЯ. */
const МЕСТА = (function () {
    const разметка = чит(РАЗМЕТКА);
    const классыПоId = (id) => {
        const м = разметка.match(new RegExp('<[^>]*id="' + id + '"[^>]*>'));
        if (!м) return null;
        const к = м[0].match(/class="([^"]*)"/);
        return к ? к[1] : '';
    };
    const файлы = [];
    const пропуск = /^(node_modules|\.git|build|assets|vendor)$/;
    const обойти = (отн) => {
        const п = path.join(КОРЕНЬ, отн);
        if (!fs.existsSync(п)) return;
        for (const э of fs.readdirSync(п, { withFileTypes: true })) {
            const в = отн + '/' + э.name;
            if (э.isDirectory()) { if (!пропуск.test(э.name)) обойти(в); continue; }
            if (э.name.endsWith('.js') && !/\/(build|assets)\//.test(в)) файлы.push(в);
        }
    };
    обойти('mobile/www/js');

    const найдено = [];
    for (const ф of файлы) {
        if (ф.indexOf('kslt-okno.js') !== -1) continue;
        const т = чит(ф);
        const стр = т.split('\n');
        стр.forEach((с, i) => {
            /* СПЕРВА НАХОДИМ МЕСТО, ПОТОМ РАЗБИРАЕМ УЗЕЛ. Первая редакция
               искала сразу `<переменная>.classList.add('open')` — и место
               `document.getElementById('authScreen').classList.add('open')`
               не попадало в список ВОВСЕ: перед `.classList` стоит `)`, а
               не слово. Прибор показывал 25 мест из 26, и двадцать шестое
               проходило мимо проверки МОЛЧА. ПРИБОР, КОТОРЫЙ НЕ ВИДИТ
               МЕСТА, ХУЖЕ ОТСУТСТВУЮЩЕГО: он даёт зелёный свет тому, чего
               не посмотрел. Ниже стоит правило, сверяющее число найденных
               мест с сырым счётом. */
            if (с.indexOf("classList.add('open')") === -1) return;
            const м = с.match(/([A-Za-zА-Яа-я_$][\w$А-Яа-я]*)\s*\.classList\.add\(\s*'open'\s*\)/);
            const узел = м ? м[1] : null;
            let классы = null, откуда = '';
            const назад = (строка) => {
                let мм;
                if ((мм = строка.match(new RegExp(узел + "\\.className\\s*=\\s*'([^']*)'")))) { классы = мм[1]; откуда = 'создан в js'; return true; }
                if ((мм = строка.match(new RegExp(узел + "\\.classList\\.add\\('((?!open)[^']*)'\\)")))) { классы = мм[1]; откуда = 'класс добавлен'; return true; }
                if ((мм = строка.match(new RegExp("(?:var|let|const)\\s+" + узел + "\\s*=\\s*document\\.getElementById\\('([^']+)'\\)")))) {
                    классы = классыПоId(мм[1]); откуда = 'разметка, id=' + мм[1]; return true;
                }
                if ((мм = строка.match(new RegExp("(?:var|let|const)\\s+" + узел + "\\s*=\\s*document\\.querySelector\\('\\.([A-Za-z0-9_-]+)")))) { классы = мм[1]; откуда = 'querySelector'; return true; }
                return false;
            };
            if (узел) { for (let j = i; j >= Math.max(0, i - 80) && классы === null; j--) назад(стр[j]); }
            if (классы === null) {
                /* Зов без переменной: `document.getElementById('x').classList.add('open')` */
                const прямо = с.match(/document\.getElementById\('([^']+)'\)\.classList\.add\(\s*'open'\s*\)/);
                if (прямо) { классы = классыПоId(прямо[1]); откуда = 'разметка напрямую, id=' + прямо[1]; }
            }
            if (классы === null && узел) {
                for (let j = 0; j < стр.length && классы === null; j++) назад(стр[j]);
            }
            найдено.push({ место: ф + ':' + (i + 1), классы, откуда });
        });
    }
    return найдено;
})();

function накрыто(м) {
    if (м.классы === null) return false;
    const части = String(м.классы).split(/\s+/).filter(Boolean);
    if (части.some(к => СПИСОК.indexOf(к) !== -1)) return true;
    return части.some(к => Object.prototype.hasOwnProperty.call(ИСКЛЮЧЕНИЯ, к));
}

console.log('\n  ОКНА ПРИЛОЖЕНИЯ — НИ ОДНО БЕЗ ОСНАСТКИ\n');

правило('дом окон объявлен и слушает смену класса',
    /KSLT_OKNO/.test(чит(ДОМ)) && /MutationObserver/.test(безКом(чит(ДОМ))) &&
    /role'?,?\s*'dialog'|'role', 'dialog'/.test(безКом(чит(ДОМ))),
    'Дом обязан СЛУШАТЬ класс, а не зваться руками: класс ставится в 26\n' +
    'местах и снимается в 50 — это 76 определений одного понятия.');

правило('дом подключён в разметке',
    /kslt-okno\.js/.test(чит(РАЗМЕТКА)),
    'Без него ни одно окно приложения не получит ни роли, ни фокуса.');

правило('прибор нашёл места, где открываются окна',
    МЕСТА.length >= 20 && СПИСОК && СПИСОК.length >= 8,
    'Найдено мест: ' + МЕСТА.length + ', классов в списке дома: ' +
    (СПИСОК ? СПИСОК.length : 'СПИСОК НЕ ПРОЧИТАН') + '.\n' +
    'Если мест ноль или список не прочитан — сломался ПРИБОР, а не\n' +
    'продукт, и все сверки ниже стали бы пустыми. Правило стоит ПЕРЕД\n' +
    'ними нарочно.');

правило('прибор видит ВСЕ места, а не часть',
    (function () {
        const пропуск = /^(node_modules|\.git|build|assets|vendor)$/;
        let сырых = 0;
        const обойти = (отн) => {
            const п = path.join(КОРЕНЬ, отн);
            if (!fs.existsSync(п)) return;
            for (const э of fs.readdirSync(п, { withFileTypes: true })) {
                const в = отн + '/' + э.name;
                if (э.isDirectory()) { if (!пропуск.test(э.name)) обойти(в); continue; }
                if (!э.name.endsWith('.js') || /\/(build|assets)\//.test(в)) continue;
                if (в.indexOf('kslt-okno.js') !== -1) continue;
                сырых += (чит(в).match(/classList\.add\('open'\)/g) || []).length;
            }
        };
        обойти('mobile/www/js');
        return сырых === МЕСТА.length;
    })(),
    'Сырой счёт `classList.add(\'open\')` и число разобранных мест должны\n' +
    'совпадать. Разошлись — значит прибор НЕ ВИДИТ часть мест и даёт\n' +
    'зелёный свет тому, чего не посмотрел. Так и было: 25 из 26, и\n' +
    'двадцать шестое (`authScreen`) проходило мимо молча, потому что перед\n' +
    '`.classList` там стоит `)`, а не имя переменной.');

/* БЕЗ СПИСКА ДАЛЬШЕ СЧИТАТЬ НЕЧЕГО — выходим с диагнозом, а не падаем
   на `СПИСОК.length`: упавший сторож скрывает, какие правила не
   прогонялись вовсе. */
if (!СПИСОК) {
    console.log('');
    console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится);
    console.log('          список окон из дома не прочитан — остальные правила не прогонялись\n');
    process.exitCode = 1;
    return;
}

правило('у каждого места определён открываемый узел',
    МЕСТА.every(м => м.классы !== null),
    'Прибор не смог понять, что открывается:\n' +
    МЕСТА.filter(м => м.классы === null).map(м => '  · ' + м.место).join('\n') +
    '\nЭто беда ПРИБОРА, и её нельзя прятать: неопознанное место могло бы\n' +
    'оказаться окном без оснастки и пройти мимо проверки.');

правило('ни одно окно не осталось без оснастки',
    МЕСТА.every(накрыто),
    'Окна, которых дом не узнаёт:\n' +
    МЕСТА.filter(м => !накрыто(м))
         .map(м => '  · ' + м.место + '  класс=' + JSON.stringify(м.классы) +
                   ' [' + м.откуда + ']').join('\n') +
    '\nДля диктора такого окна НЕ СУЩЕСТВУЕТ: он продолжает читать\n' +
    'страницу ПОД ним. С клавиатуры из него не выйти — Esc не работает,\n' +
    'Tab уходит на то, что окно закрыло.\n' +
    'Либо добавь класс в список `ОКНА` дома, либо назови исключением с\n' +
    'причиной в `ИСКЛЮЧЕНИЯХ` этого сторожа.');

правило('у каждого исключения названа причина',
    Object.keys(ИСКЛЮЧЕНИЯ).every(к => String(ИСКЛЮЧЕНИЯ[к]).length > 60),
    'БЕЗЫМЯННЫХ ИСКЛЮЧЕНИЙ НЕ БЫВАЕТ: либо сказано, почему это не окно,\n' +
    'либо это окно.');

правило('исключение не объявлено окном в доме',
    Object.keys(ИСКЛЮЧЕНИЯ).every(к => СПИСОК.indexOf(к) === -1),
    'Класс не может быть одновременно окном и исключением — это два\n' +
    'определения одного понятия, и они разойдутся.');

/* ПРАВИЛО СДЕЛАНО ПРОВЕРЯЕМЫМ: первая редакция смотрела, что список
   НЕПУСТ и содержит `td-overlay`, — а это верно и для списка, зашитого
   в сам сторож. Прувер это показал: откат «сторож держит список руками»
   правило НЕ УРОНИЛ. Теперь правило смотрит на ТЕКСТ САМОГО СТОРОЖА:
   имени окна в нём быть не должно, оно читается из дома. */
правило('список окон дома читается, а не держится в сторожe руками',
    /match\(\/var ОКНА = /.test(чит('tools/check-okna-prilozheniya.js')) &&
    !/'(?:td|otp|notif|menu|msa|ar|gi|pd)-[a-z0-9-]*(?:overlay|modal)'/
        .test(безКом(чит('tools/check-okna-prilozheniya.js'))) &&
    СПИСОК.length >= 14 &&
    СПИСОК.every(к => чит(ДОМ).indexOf('.' + к) !== -1),
    'Первая редакция ПРИБОРА держала те же восемь классов своим списком —\n' +
    'и после расширения дома показывала семь «не накрытых» окон, которых\n' +
    'уже не было. СПИСОК, КОТОРЫЙ ДЕРЖИТСЯ РУКАМИ, ОТСТАЁТ — в приборе\n' +
    'тоже.');

правило('класс `open` у не-окна не объявлен окном',
    СПИСОК.indexOf('tc-status') === -1,
    '`.tc-status.open` — это корт «открыт» (`app.css:911`), плашка, а не\n' +
    'окно. Объяви её окном — дом уведёт в неё фокус.');

console.log('');
if (упало) { console.log('  БЕДА    правил упало: ' + упало + ', держится: ' + держится + '\n'); process.exitCode = 1; }
else {
    console.log('  ок      окна приложения: все ' + держится + ' правил держатся');
    console.log('          мест, где открывается окно: ' + МЕСТА.length +
                ' · классов в доме: ' + СПИСОК.length +
                ' · названных исключений: ' + Object.keys(ИСКЛЮЧЕНИЯ).length + '\n');
}
}
главное();
