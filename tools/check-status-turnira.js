const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = о => fs.readFileSync(path.join(КОРЕНЬ, о), 'utf8');
const чисто = т => т
    .replace(/\/\*[\s\S]*?\*\//g, м => м.replace(/[^\n]/g, ' '))
    .replace(/(^|[^:])\/\/[^\n]*/g, (м, п) => п + м.slice(п.length).replace(/[^\n]/g, ' '));

/* `_sync` исключён: он в .gitignore, это архив синхронизации, а не продукт.
   Прибор принял его за разметку и дал ложную дыру. */
const ПРОПУСК = ['node_modules', 'test-results', 'mobile', 'lib', 'playwright-report',
                 'tests', 'tools', '_sync'];

function всеHTML() {
    const итог = [];
    (function обойти(дир) {
        for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
            if (э.name.startsWith('.')) continue;
            const п = path.join(дир, э.name);
            if (э.isDirectory()) { if (ПРОПУСК.indexOf(э.name) === -1) обойти(п); }
            else if (э.name.endsWith('.html')) итог.push(п);
        }
    })(КОРЕНЬ);
    return итог;
}

function всеJS(дир, итог) {
    итог = итог || [];
    for (const э of fs.readdirSync(дир, { withFileTypes: true })) {
        const п = path.join(дир, э.name);
        if (э.isDirectory()) всеJS(п, итог);
        else if (э.name.endsWith('.js')) итог.push(п);
    }
    return итог;
}

/* ПОДКЛЮЧЕНИЕ — ЭТО ТЕГ, А НЕ УПОМИНАНИЕ, и сравнивается ПУТЬ, А НЕ ИМЯ.
   Оба урока стоили по ложной дыре каждый. */
const подключённые = т => {
    const обр = /<script[^>]*\ssrc="([^"]+)"/g;
    const итог = [];
    let м;
    while ((м = обр.exec(т))) итог.push(м[1].split('?')[0].replace(/^(\.\.\/)+/, ''));
    return итог;
};
const версии = т => {
    const обр = /tournament-status\.js\?v=(\d+)/g;
    const итог = [];
    let м;
    while ((м = обр.exec(т))) итог.push(м[1]);
    return итог;
};

const файлыJS = всеJS(path.join(КОРЕНЬ, 'js'));
const ошибки = [];
let держится = 0;
function правило(имя, годно, подсказка) {
    if (годно) { держится++; console.log('  ✓ ' + имя); }
    else ошибки.push({ имя, подсказка });
}

/* ── 1. своих определений нет ── */
const свои = файлыJS.filter(п =>
    /function\s+(computeStatus|computeTournamentStatus)\s*\(/.test(чисто(fs.readFileSync(п, 'utf8'))))
    .map(п => path.relative(КОРЕНЬ, п));
правило(
    'статус турнира определён только в доме',
    /* ПРИЗНАК — ОБЪЯВЛЕНИЕ, А НЕ СЛОВО. Слово `вычислить` встречается в
       доме трижды: объявление, запись в API и упоминание в описании. Пока
       правило искало слово, прувер подменял объявление на `вычислитьNETU`,
       и правило оставалось зелёным — слово-то на месте. */
    свои.length === 0 && /function\s+вычислить\s*\(/.test(чисто(чит('js/tournament-status.js'))),
    'Свои определения остались в: ' + свои.join(', ') + '.\n' +
    'Их было ЧЕТЫРЕ, все побайтово одинаковые, под двумя именами — и по\n' +
    'имени их не видно: нашёл только хеш тела. Посредник, который ничего\n' +
    'не добавляет, это то же понятие под новым именем.');

/* ── 2. дом подключён там, где его зовут ── */
const зовут = файлыJS
    .filter(п => /KSLT_STATUS\.(вычислить|подписи)/.test(чисто(fs.readFileSync(п, 'utf8'))))
    .map(п => path.relative(КОРЕНЬ, п).split(path.sep).join('/'));
const безДома = всеHTML().filter(п => {
    const свои2 = подключённые(fs.readFileSync(п, 'utf8'));
    return зовут.some(путь => свои2.indexOf(путь) !== -1)
        && свои2.indexOf('js/tournament-status.js') === -1;
}).map(п => path.relative(КОРЕНЬ, п));
правило(
    'дом статуса подключён на каждой странице, где его зовут',
    безДома.length === 0,
    'Страницы без дома: ' + безДома.join(', ') + '.\n' +
    'Беда СПИТ до первой правки: сегодня статус там просто не доходит до\n' +
    'зова, а завтра дойдёт — и страница сломается целиком. Так было со\n' +
    'стендом proba-itogi-lig.html до 19.10.');

/* ── 3. версия дома одна на всю разметку ── */
const всеВерсии = {};
всеHTML().forEach(п => {
    версии(fs.readFileSync(п, 'utf8')).forEach(в => {
        (всеВерсии[в] = всеВерсии[в] || []).push(path.relative(КОРЕНЬ, п));
    });
});
правило(
    'дом статуса подключён ОДНОЙ версией на всю разметку',
    Object.keys(всеВерсии).length <= 1,
    'Версий в разметке: ' + JSON.stringify(Object.keys(всеВерсии).map(в =>
        в + ' (' + всеВерсии[в].length + ' стр.)')) + '.\n' +
    'Один файл двумя версиями значит, что у половины продукта он из кэша, а\n' +
    'у половины свежий. До 19.10 так и было: ?v=1 на главной и ?v=12 на\n' +
    'остальных двадцати девяти страницах.');

/* ── 4. админский посредник — ссылка на дом, а не копия ── */
const constants = чисто(чит('js/admin/core/constants.js'));
правило(
    'посредник админки зовёт дом, а своего тела не держит',
    /computeTournamentStatus:\s*function[^}]*KSLT_STATUS\.вычислить/.test(constants.replace(/\s+/g, ' ')),
    'Имя в API модуля остаётся — его зовут шесть мест в sections/tournaments.js,\n' +
    'и переименование было бы правкой ради правки. Но тела у него быть не\n' +
    'должно: только зов дома, иначе расходиться снова будет чему.');

console.log('');
if (!ошибки.length) {
    console.log('  ок      статус турнира: ' + держится + ' правил');
    console.log('          четыре обёртки под двумя именами сведены на дом');
    console.log('          дом подключён всюду, где зовут, и одной версией');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  статус турнира — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
