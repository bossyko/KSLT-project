/**
 * ЗАМОРОЗКА «СВЕДЕНИЯ О ПОСТАВЩИКЕ В ПОДВАЛЕ» (Ю7, 11.11.2026).
 *
 * Статья 33 требует, чтобы покупатель видел наименование, регистрационный
 * номер, юридический адрес и применимое право. Замер 11.11 по боевым
 * страницам: в подвале не было НИ ОДНОГО из этих полей — ни на русском, ни
 * на английском, ни на кыргызском.
 *
 * ДАННЫЕ НЕ ПРИДУМАНЫ: они уже жили в опубликованной оферте (пункт 1.3) на
 * всех трёх языках. ДАННЫЕ БЫЛИ В ПРОДУКТЕ, НО НЕ ТАМ, ГДЕ ТРЕБУЕТ ЗАКОН.
 *
 * И ОТСЮДА ГЛАВНЫЙ РИСК КУСКА: теперь реквизиты лежат В ДВУХ МЕСТАХ —
 * в оферте и в подвале. ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: беда родится
 * ровно на шве, когда фонд сменит адрес и поправят только оферту. Поэтому
 * сторож не просто проверяет наличие — он СВЕРЯЕТ подвал с офертой.
 *
 *   node tools/check-svedeniya-o-postavshchike.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const есть = ф => fs.existsSync(path.join(КОРЕНЬ, ф));
const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

/* ПОЛЯ, КОТОРЫХ ТРЕБУЕТ ЗАКОН, А НЕ ВСЕ, ЧТО ЕСТЬ В ОФЕРТЕ. */
const ИНН = '01905202110030';
const РЕГ = '197575-3301';

const ЯЗЫКИ = [
    { к: 'ru', подвал: 'partials/footer-ru.html', оферта: 'pages/offer.html',
      имя: 'Кыргызстанское сообщество любителей тенниса', право: /законодательств/i },
    { к: 'en', подвал: 'partials/footer-en.html', оферта: 'pages/offer-en.html',
      имя: 'Kyrgyzstan Social Lawn Tennis Community', право: /laws of the Kyrgyz Republic/i },
    { к: 'kg', подвал: 'partials/footer-kg.html', оферта: 'pages/offer-kg.html',
      имя: 'коомдук фонду', право: /мыйзамдар/i },
];

ЯЗЫКИ.forEach(я => {
    const п = чит(я.подвал);

    правило('подвал ' + я.к + ': блок сведений на месте',
        /class="footer-entity"/.test(п),
        я.подвал + ': пропал блок `.footer-entity`.\n' +
        'Статья 33 требует наименование, рег. номер, адрес и применимое право.');

    правило('подвал ' + я.к + ': наименование на своём языке',
        п.indexOf(я.имя) !== -1,
        я.подвал + ': нет наименования «' + я.имя + '».\n' +
        'ЮРИДИЧЕСКОЕ НАИМЕНОВАНИЕ НЕ ПЕРЕВОДИТСЯ ВОЛЬНО — у него есть\n' +
        'официальная форма на каждом языке, и она взята из оферты.');

    правило('подвал ' + я.к + ': ИНН и регистрационный номер',
        п.indexOf(ИНН) !== -1 && п.indexOf(РЕГ) !== -1,
        я.подвал + ': нет ИНН или регистрационного номера.');

    правило('подвал ' + я.к + ': применимое право названо',
        я.право.test(п),
        я.подвал + ': не сказано, право какой страны применяется.');

    /* ШОВ: ПОДВАЛ И ОФЕРТА ГОВОРЯТ ОДНО. */
    if (есть(я.оферта)) {
        const о = чит(я.оферта);
        правило('подвал ' + я.к + ' не разошёлся с офертой по ИНН',
            о.indexOf(ИНН) === -1 || п.indexOf(ИНН) !== -1,
            'ИНН в оферте есть, а в подвале нет: ' + я.подвал + '.');
        правило('подвал ' + я.к + ' не разошёлся с офертой по рег. номеру',
            о.indexOf(РЕГ) === -1 || п.indexOf(РЕГ) !== -1,
            'Регистрационный номер в оферте есть, а в подвале нет.');
    }

    /* ПЕРСОНАЛЬНЫЕ ДАННЫЕ ЖИВОГО ЧЕЛОВЕКА В ПОДВАЛ НЕ ВЫНОСЯТСЯ. */
    правило('подвал ' + я.к + ': без ФИО директора',
        !/Чокоев|Chokoeva/i.test(п),
        я.подвал + ': в подвал вынесено ФИО директора.\n' +
        'Статья 33 его НЕ требует, а это персональные данные живого\n' +
        'человека на 79 страницах. В оферте оно есть — этого довольно.');
});

/* ── РАЗНЕСЕНО ПО СТРАНИЦАМ, А НЕ ТОЛЬКО В ОБРАЗЦЕ ───────────────────── */

const страницы = fs.readdirSync(path.join(КОРЕНЬ, 'pages'))
    .filter(ф => /\.html$/.test(ф) && !/^_/.test(ф))
    .map(ф => 'pages/' + ф)
    .concat(['index.html']);
const сПодвалом = страницы.filter(ф => /class="footer-bottom"/.test(чит(ф)));
const безСведений = сПодвалом.filter(ф => !/class="footer-entity"/.test(чит(ф)));

правило('сведения разнесены по всем страницам с подвалом',
    сПодвалом.length > 50 && безСведений.length === 0,
    'Страниц с подвалом: ' + сПодвалом.length + ', из них без сведений: ' +
    безСведений.length + '.\n' + безСведений.slice(0, 6).join(', ') + '\n' +
    'ОБРАЗЕЦ, НЕ РАЗНЕСЁННЫЙ ПО СТРАНИЦАМ, НИКОМУ НЕ ВИДЕН.\n' +
    'Запусти: node tools/build-partials.js');

/* ── КРАСКА И КЕГЛЬ — РОЛЬЮ, А НЕ ЧИСЛОМ ─────────────────────────────── */

const стиль = чит('css/style.css');
const блок = стиль.match(/\.footer-entity\s*\{[^}]*\}/);
правило('сведения стоят на роли и ступени, а не на своих числах',
    !!блок && /var\(--text-muted\)/.test(блок[0]) && /var\(--fs-xs\)/.test(блок[0]),
    'css/style.css, `.footer-entity`: краска или кегль заданы числом.\n' +
    'СТУПЕНЬ БЕРЁТСЯ У СОСЕДА: те же роль и кегль, что у `.footer-made` —\n' +
    'замерено 11.11 на 390: контраст 10.25 при планке 4.5, кегль 12.');

правило('строка сведений занимает всю ширину полосы',
    !!блок && /flex:\s*0 0 100%/.test(блок[0]),
    'css/style.css, `.footer-entity`: строка больше не занимает всю ширину.\n' +
    'В полосе подвала стоит `space-between`: короткий блок встанет рядом с\n' +
    'копирайтом и сломает раскладку на узком виде.');

/* ── вывод ───────────────────────────────────────────────────────────── */
const ВСЕГО = 20;
if (ошибки.length) {
    console.log('\n  x СВЕДЕНИЯ О ПОСТАВЩИКЕ — ' + ошибки.length + ' из ' + ВСЕГО + '\n');
    ошибки.forEach(о => { console.log('  x ' + о.имя); console.log('    ' + о.подсказка.split('\n').join('\n    ') + '\n'); });
    process.exit(1);
}
console.log('  v сведения о поставщике: ' + ВСЕГО + ' правил · страниц с подвалом ' +
            сПодвалом.length + ', без сведений 0');
