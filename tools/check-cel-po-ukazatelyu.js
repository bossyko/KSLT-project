/**
 * ЦЕЛЬ НАЖАТИЯ — ПО УКАЗАТЕЛЮ, А НЕ ПО ШИРИНЕ (правило h270, 11.11.2026).
 *
 * ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ: РАЗМЕР ЦЕЛИ — ВОПРОС УКАЗАТЕЛЯ. Раскладка по
 * месту и длина подписи — вопрос ширины.
 *
 * ОТКУДА ПРАВИЛО. Ширина окна ничего не говорит о том, чем тыкают в
 * экран: iPad Mini боком — 1024, iPhone боком — 844, оба шире любой нашей
 * границы и оба сенсорные. Браузер отвечает `(any-pointer: coarse)`, мы
 * просто не спрашивали: на 20.09 во всём css было 65 медиазапросов с
 * условиями и НИ ОДНОГО про указатель.
 *
 * ЗАМЕР 11.11 на 1024: из 132 целей главной мельче 44 остаются две семьи
 * без единого правила под указателем — вкладки разряда (118x36, восемь
 * штук) и кнопки соцсетей (32x32, три). Остальное либо уже 44, либо
 * получает 44 под указателем (шапка, боковой лист, подвал — 21.09).
 *
 * ЧТО СТОРОЖИТСЯ:
 *   1. блоки с указателем не исчезают и не редеют;
 *   2. названные семьи получают цель под указателем, а не по ширине;
 *   3. размер цели берётся со ступени кнопок, а не числом;
 *   4. если цель поднимают до 44 ТОЛЬКО внутри медиа по ширине — это
 *      ошибка рассуждения: на планшете боком правило не сработает.
 */
const fs = require('fs');
const path = require('path');

const корень = path.resolve(__dirname, '..');
const безКомм = т => т.replace(/\/\*[\s\S]*?\*\//g, '');
const ошибки = [];

/* Разбор медиа-блоков файла: условие и тело. */
function блоки(текст) {
    const итог = [];
    for (const м of текст.matchAll(/@media([^{]*)\{/g)) {
        let гл = 1, j = м.index + м[0].length;
        while (j < текст.length && гл) {
            if (текст[j] === '{') гл++;
            else if (текст[j] === '}') гл--;
            j++;
        }
        итог.push({ условие: м[1].trim(), тело: текст.slice(м.index + м[0].length, j) });
    }
    return итог;
}

const стиль = безКомм(fs.readFileSync(path.join(корень, 'css/style.css'), 'utf8'));
const все = блоки(стиль);
const указатель = все.filter(б => /pointer/.test(б.условие));

/* 1. БЛОКИ С УКАЗАТЕЛЕМ ЖИВЫ. */
if (указатель.length < 7) {
    ошибки.push(`блоков с указателем ${указатель.length} — было семь и больше; правило h270 откатывают назад к ширине`);
}

/* 2 и 3. НАЗВАННЫЕ СЕМЬИ ПОЛУЧАЮТ ЦЕЛЬ ПО УКАЗАТЕЛЮ, СО СТУПЕНИ. */
/* 12.11: к семьям добавлена шапка ВОШЕДШЕГО. Её никто не мерил —
   в наборе Figma на её месте стоял админ. Замер под живым игроком
   дал колокольчик 36x36 и кнопку с аватаром 38x38 на всех сенсорных
   видах, и шесть пунктов панели 37/39. */
const СЕМЬИ = ['.rankings-tab', '.social-link',
    '.site-notif-btn', '.user-dropdown-toggle', '.user-dropdown-item'];
for (const сел of СЕМЬИ) {
    const где = указатель.filter(б => б.тело.indexOf(сел) !== -1);
    if (!где.length) {
        ошибки.push(`${сел}: нет правила под указателем — на планшете боком цель останется десктопной`);
        continue;
    }
    const тела = где.map(б => {
        const i = б.тело.indexOf(сел);
        const н = б.тело.indexOf('{', i), к = б.тело.indexOf('}', н);
        return б.тело.slice(н, к);
    }).join(' ');
    if (!/var\(--btn-h-/.test(тела))
        ошибки.push(`${сел}: размер цели задан мимо ступени кнопок`);
}

/* 4. ЦЕЛЬ НЕ ПОДНИМАЮТ ТОЛЬКО ПО ШИРИНЕ.
   Берём правила, которые ставят высоту цели ступенью md или больше
   внутри медиа ПО ШИРИНЕ, и требуем, чтобы у того же селектора был
   блок с указателем. Иначе на 1024 с пальцем правило не сработает. */
const поШирине = все.filter(б => /max-width/.test(б.условие) && !/pointer/.test(б.условие));
let проверено = 0;
for (const б of поШирине) {
    /* СЕЛЕКТОР — ВСЁ ДО СКОБКИ, А НЕ ОДНО ИМЯ КЛАССА. Первая редакция
       искала `[.#][\w-]+` и пропускала составные вроде
       `.de-switch button` — а именно такой и нашёлся единственным
       нарушителем. ПРАВИЛО, ЧИТАЮЩЕЕ ОДНО СЛОВО ИЗ ДВУХ, СТОРОЖИТ
       ПОЛОВИНУ. */
    for (const м of б.тело.matchAll(/(?:^|\n)\s*([^{}\n]+?)\s*\{([^}]*)\}/g)) {
        const сел = м[1], тело = м[2];
        if (!/(?:min-)?height:\s*var\(--btn-h-(?:md|lg)\)/.test(тело)) continue;
        проверено++;
        const подУказателем = указатель.some(у => у.тело.indexOf(сел) !== -1);
        if (!подУказателем) {
            ошибки.push(`${сел}: цель поднята до ступени только в медиа по ширине (${б.условие.slice(0, 40)}) — на планшете боком с пальцем это не сработает`);
        }
    }
}

if (ошибки.length) {
    console.error('ЦЕЛЬ ПО УКАЗАТЕЛЮ — НАРУШЕНО:');
    for (const о of ошибки) console.error('  · ' + о);
    process.exit(1);
}
console.log(`цель по указателю: ${указатель.length} блоков с указателем, ${СЕМЬИ.length} семьи переведены, ${проверено} правил по ширине проверены на пару`);
