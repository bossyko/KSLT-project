/**
 * ЗАМОРОЗКА КУСКА 118 — АДМИНКА ГОВОРИТ ОДНИМ ЯЗЫКОМ.
 *
 * Слово Кости 22.10: «у нас нет английской версии, только на русском же».
 * До этого куска админка несла второй язык, которого никто не видел:
 * `isEn` вычислялся из `-en` в адресе, а `pages/admin-en.html` — 25 строк
 * перенаправления, админских скриптов не грузит вовсе.
 *
 * ВЕТКА, КОТОРУЮ НЕ ВИДЯТ, ОТСТАЁТ МОЛЧА — и это не догадка: у 1582
 * английских ключей русский близнец был у ВСЕХ, а по-русски нашлось ТРИ,
 * которых по-английски не было (`finalizeMismatchTitle/Text/Go`). На
 * английской админке человек прочитал бы «undefined».
 *
 *   node tools/check-admin-odin-yazyk.js
 */
const fs = require('fs');
const path = require('path');
const { маска } = require('./razovye/maska.js');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
function файлы(д) { let r = []; for (const и of fs.readdirSync(path.join(КОРЕНЬ, д))) {
    const п = path.join(д, и);
    if (fs.statSync(path.join(КОРЕНЬ, п)).isDirectory()) r = r.concat(файлы(п));
    else if (и.endsWith('.js')) r.push(п); } return r; }

const ошибки = [];
function правило(имя, держится, почему) { if (!держится) ошибки.push([имя, почему]); }

const АДМИН = файлы('js/admin');

/* ── 1. НИ ОДНОГО ТЕРНАРНИКА `isEn ?` ─────────────────────────────────── */
/* МАСКА ЗНАЕТ РЕГУЛЯРНЫЕ ЛИТЕРАЛЫ. Первая версия прибора куска 118 их не
   знала: `.replace(/"/g, …)` открывал мнимую строку, и 376 тернарников из
   шести файлов были НЕВИДИМЫ — прибор докладывал «ноль». Здесь поэтому
   сверяются ДВА счёта: сырой и масочный. СЛЕПОЙ ПРИБОР ДОКЛАДЫВАЕТ НЕ
   ОШИБКУ, А УСПЕХ. */
let сыроеВсего = 0, масочноеВсего = 0;
const сТернарником = [];
АДМИН.forEach(ф => {
    const t = чит(ф);
    const с = (t.match(/\bisEn\s*\?/g) || []).length;
    const м = (маска(t).match(/\bisEn\s*\?/g) || []).length;
    сыроеВсего += с; масочноеВсего += м;
    if (с) сТернарником.push(ф + ' (' + с + ')');
});
правило('в админке нет ни одного тернарника `isEn ?`',
    сыроеВсего === 0,
    'Нашлись: ' + сТернарником.join(', ') + '.\n' +
    'Админка живёт на русском (слово Кости 22.10). Второй язык, которого\n' +
    'никто не видит, расходится молча — у словаря это уже случилось трижды.');

правило('маска прибора видит столько же, сколько сырой поиск',
    сыроеВсего === масочноеВсего,
    'сырых ' + сыроеВсего + ', масочных ' + масочноеВсего + '. Маска ослепла —\n' +
    'скорее всего на регулярном литерале с кавычкой внутри. Прибор, который\n' +
    'не видит кода, докладывает НЕ ОШИБКУ, А УСПЕХ.');

/* ── 2. ФЛАГ НЕ ОБЪЯВЛЯЕТСЯ И НЕ ВЫВОДИТСЯ ───────────────────────────── */
const сОбъявлением = АДМИН.filter(ф => /\bvar\s+isEn\s*=/.test(маска(чит(ф))));
правило('флаг `isEn` в админке не объявляется нигде',
    сОбъявлением.length === 0,
    'Объявлен в: ' + сОбъявлением.join(', ') + '.\n' +
    'Живое объявление зовёт к себе ветки: уберёшь ветки, оставишь флаг — и\n' +
    'ветки вернутся по одной.');

правило('флаг не выводится наружу через window.KSLT_ADMIN',
    !/window\.KSLT_ADMIN\s*=\s*\{[\s\S]{0,300}?\bisEn\s*:/.test(маска(чит('js/admin/core/constants.js'))),
    'Флаг снова выведен в пространство админки. Читателей у него не было\n' +
    'ни одного вне самой админки — проверено поиском по стендам, пробам и\n' +
    'сторожам.');

/* ── 3. ЯЗЫК ОБЩЕМУ С САЙТОМ ГРАФИКУ НАЗВАН ЯВНО ─────────────────────── */
/* УМОЛЧАНИЕ — СВОЙСТВО ДАННЫХ, А НЕ РАЗМЕТКИ. `js/rating-chart.js` общий
   с публичной частью, где язык ПРАВДА переключается; молчание там читалось
   бы как «язык не важен». */
правило('общему с сайтом графику язык назван словом',
    /KSLT_RATING_CHART\.render\(\{[\s\S]{0,400}?isEn:\s*false/.test(маска(чит('js/admin/sections/players.js'))),
    'Админка перестала называть язык графику рейтинга. График общий с\n' +
    'сайтом (`js/rating-chart.js`), и там язык переключается по-настоящему.');

/* ── 4. АНГЛИЙСКАЯ СТРАНИЦА ОСТАЁТСЯ ПЕРЕНАПРАВЛЕНИЕМ ────────────────── */
const АНГЛ = чит('pages/admin-en.html');
правило('admin-en.html остаётся перенаправлением и не грузит админских скриптов',
    /location\.replace\('admin\.html'\)/.test(АНГЛ) && АНГЛ.indexOf('js/admin/') === -1,
    'Английская страница админки снова грузит скрипты. Она жива только\n' +
    'ради старых ссылок и закладок: причина записана в ней самой.');

/* ── 5. НИ ОДНА СТРАНИЦА С `-en` В ПУТИ НЕ ГРУЗИТ АДМИНКУ ────────────── */
/* ИМЕННО ЭТО ДЕЛАЛО ФЛАГ КОНСТАНТНО ЛОЖНЫМ. Правило сторожит ПРИЧИНУ, а
   не следствие: появится английская страница с админскими скриптами —
   и весь кусок 118 разом станет неверным. */
function страницы(д) { let r = []; for (const и of fs.readdirSync(path.join(КОРЕНЬ, д))) {
    const п = path.join(д, и);
    const s = fs.statSync(path.join(КОРЕНЬ, п));
    if (s.isDirectory()) { if (!/node_modules|\.git|test-results|reports|^mobile\/android/.test(п)) r = r.concat(страницы(п)); }
    else if (и.endsWith('.html')) r.push(п); } return r; }
/* ПРИЗНАК — ТЕГ `<script src=…>`, А НЕ УПОМИНАНИЕ ИМЕНИ. Первый замер дал
   девять страниц, но две из них лишь СОССЫЛАЮТСЯ на админку в комментарии
   (`maket/lestnica-formy-turnira.html`, `maket/zayavki-stroka.html`), а
   скриптов не грузят. Комментарий ничего не выполняет: грузят СЕМЬ. */
const грузит = /<script[^>]+src=["'][^"']*js\/admin\//;
const сАдминкой = страницы('pages').concat(страницы('maket'))
    .filter(ф => грузит.test(чит(ф)));
const сEn = сАдминкой.filter(ф => ('/' + ф).indexOf('-en') !== -1);
правило('ни одна страница с `-en` в пути не грузит админских скриптов',
    сEn.length === 0,
    'Грузят: ' + сEn.join(', ') + '.\n' +
    'Флаг вычислялся как `pathname.indexOf(\'-en\') !== -1`. Пока таких\n' +
    'страниц нет, русский язык админки — следствие, а не совпадение.');
правило('страниц, грузящих админку, не меньше замеренных семи',
    сАдминкой.length >= 7,
    'Нашлось ' + сАдминкой.length + ' при замере 7. Правило, которое ищет\n' +
    'в пустом списке, зеленеет всегда: ПРОВЕРКА, КОТОРАЯ НЕ МОЖЕТ УПАСТЬ,\n' +
    'НИЧЕГО НЕ ДОКАЗЫВАЕТ.');

/* ── 6. В СЛОВАРЕ НЕТ ПОВТОРЁННЫХ КЛЮЧЕЙ ─────────────────────────────── */
/* ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. Пока словарь был двуязычным, повтор
   прятался: семь имён стояли дважды В КАЖДОЙ ветке, и у четырёх пар тексты
   РАЗНЫЕ — молча побеждала поздняя. `chalCancelled` был объявлен и как
   «Баттл отменён, уведомлено:», и как «Баттл отменён», а зовущий сам
   дописывает число. */
(function () {
    const t = чит('js/admin/core/constants.js'), m = маска(t);
    const н = m.indexOf('var L =');
    const о = m.indexOf('{', н);
    let г = 0, з = -1;
    for (let i = о; i < m.length; i++) { if (m[i] === '{') г++; else if (m[i] === '}') { г--; if (!г) { з = i; break; } } }
    if (з === -1) { правило('словарь L читается целиком', false, 'не нашёл границ словаря `var L = {`'); return; }
    const счёт = {}; г = 0;
    for (let i = о; i <= з; i++) {
        const c = m[i];
        if (c === '{' || c === '[') г++; else if (c === '}' || c === ']') г--;
        if (г === 1) { const мм = /^[\s,]*([A-Za-z_$][\w$]*)\s*:/.exec(m.slice(i));
            if (мм) { счёт[мм[1]] = (счёт[мм[1]] || 0) + 1; i += мм[0].length - 1; } }
    }
    const имён = Object.keys(счёт).length;
    const дубли = Object.entries(счёт).filter(([, n]) => n > 1).map(([к]) => к);
    правило('в словаре админки нет повторённых ключей',
        дубли.length === 0,
        'Повторены: ' + дубли.join(', ') + '.\n' +
        'В литерале объекта побеждает ПОЗДНЯЯ запись, ранняя недостижима\n' +
        'никаким путём — ни именем, ни склейкой `L[\'x\' + y]`. Глазами это\n' +
        'не видно: словарь идёт полторы тысячи строк подряд.');
    правило('имён в словаре не меньше замеренных 1578',
        имён >= 1578,
        'Имён ' + имён + ' при замере 1578. Если словарь похудел — значит\n' +
        'подписи снимали, а это свой кусок: `L[\'role\' + …]`, `L[key]` и ещё\n' +
        'девять мест берут ключ, СОБРАННЫЙ НА ХОДУ, и мёртвым ключ по\n' +
        'поиску имени не доказывается.');
    if (!ошибки.length) console.log('          словарь: ' + имён + ' имён, повторов 0');
})();

/* ── вывод ───────────────────────────────────────────────────────────── */
console.log('');
if (ошибки.length) {
    console.log('  НЕ ТАК  админка одним языком — ' + ошибки.length + ' правил не держится\n');
    ошибки.forEach(([и, п]) => console.log('          ✗ ' + и + '\n            ' + п.replace(/\n/g, '\n            ') + '\n'));
    process.exit(1);
}
console.log('  ок      админка одним языком: 9 правил');
console.log('          тернарников `isEn ?` 0, сырой и масочный счёт сошлись');
console.log('          страниц с админкой ' + сАдминкой.length + ', с `-en` в пути 0');
console.log('');
