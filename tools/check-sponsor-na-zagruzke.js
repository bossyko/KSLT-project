/* ══ 3в. ПОЯВЛЕНИЕ: ИЗ РАЗМЫТИЯ, ПОТОМ БЛИК (08.11) ══════════════════
   Слово Кости: «смешай» — третий вариант с пятым из шести показанных.
   ДВА ОТСКОКА НА ОДНОМ ЭКРАНЕ ОТМЕНЯЮТ ДРУГ ДРУГА: знак КСЛТ прыгает с
   перелётом прямо над спонсором, и вторая пружина в 300 мс от первой
   читается дёрганьем. Размытие работает в другой плоскости — наводит
   резкость, не двигая, — и потому уживается с прыжком. */
правило('спонсор проявляется из размытия, а не всплывает',
    /animation: splashSponsorIn /.test(CSS) &&
    /@keyframes splashSponsorIn \{[\s\S]{0,220}?filter: blur\(/.test(CSSК) &&
    !/\.splash-sponsor \{[\s\S]{0,320}?animation: splashFadeUp/.test(CSSК),
    'Блок спонсора обязан появляться своим `splashSponsorIn` — проявление\n' +
    'с наводкой резкости. Возврат к общему `splashFadeUp` отменяет выбор\n' +
    'Кости и возвращает третье движение на экран, где их уже два.');

правило('блик — слой на коробке, один проход',
    /\.splash-sponsor-box::after/.test(CSS) &&
    /animation: splashSheen /.test(CSS) &&
    /@keyframes splashSheen/.test(CSS) &&
    !/splashSheen[^;]*infinite/.test(CSS) &&
    /\.splash-sponsor-box \{[\s\S]{0,200}?overflow: hidden/.test(CSSК),
    'Блик обязан быть ОТДЕЛЬНЫМ слоем (`::after` на коробке), а не\n' +
    'правкой самого знака: чужой фирменный цвет не наш, чтобы его мять.\n' +
    'Коробка обязана резать по своим границам (`overflow: hidden`) —\n' +
    'иначе светлая полоса проедет по всему тёмному экрану.\n' +
    'И проход ОДИН: экран живёт две секунды, повторяться нечему.');

/* ЭТО ПРАВИЛО СВЯЗЫВАЕТ ДВА ФАЙЛА, И В ЭТОМ ЕГО СМЫСЛ. Срок экрана
   живёт в `app.js`, раскладка движения — в `app.css`, и разойтись они
   могут молча: подняли одно, забыли другое, и блик обрывается на
   середине у всех и навсегда. ЧИСЛО, ЖИВУЩЕЕ В ДВУХ ФАЙЛАХ, СТЕРЕЖЁТСЯ
   ОДНИМ ПРАВИЛОМ. */
правило('движение успевает закончиться до ухода экрана',
    (() => {
        const срок = Number((ПРИЛ.match(/SPLASH_SO_SPONSOROM_MS = (\d+)/) || [])[1]);
        const бл = CSSК.match(/animation: splashSheen ([\d.]+)s[^;]*?([\d.]+)s both/);
        if (!срок || !бл) return false;
        const конецБлика = (Number(бл[2]) + Number(бл[1])) * 1000;
        return конецБлика <= срок;
    })(),
    (() => {
        const срок = (ПРИЛ.match(/SPLASH_SO_SPONSOROM_MS = (\d+)/) || [])[1] || '—';
        const бл = CSSК.match(/animation: splashSheen ([\d.]+)s[^;]*?([\d.]+)s both/);
        const конец = бл ? (Number(бл[2]) + Number(бл[1])) * 1000 : '—';
        return 'Блик заканчивается на ' + конец + ' мс, экран уходит на ' + срок + '.\n' +
               'Движение, оборванное на середине, читается как подвисание —\n' +
               'и читается так у КАЖДОГО, на каждом запуске.';
    })());

/* ══ 3г. МЕНЬШЕ ДВИЖЕНИЯ — ЗНАЧИТ И ЗДЕСЬ ═══════════════════════════
   ЗАМЕР 08.11: во всей одежде приложения `prefers-reduced-motion` стоял
   ОДИН раз — на ленте спонсоров главной. Экран загрузки не был прикрыт
   вовсе, а на нём живёт самое заметное движение продукта: прыжок знака
   с перелётом и БЕСКОНЕЧНЫЙ пульс свечения. Для человека, который эту
   настройку включил, бесконечный пульс — ровно то, от чего он
   отписывался. */
правило('экран загрузки уважает «меньше движения»',
    (() => {
        const и = CSSК.indexOf('@media (prefers-reduced-motion: reduce)');
        if (и === -1) return false;
        /* Ищем ИМЕННО тот блок, что прикрывает экран загрузки. */
        const блоки = CSSК.split('@media (prefers-reduced-motion: reduce)').slice(1);
        return блоки.some(б => {
            const тело = б.slice(0, б.indexOf('\n}') + 2);
            return /\.splash-logo/.test(тело) && /\.splash-sponsor/.test(тело) &&
                   /\.splash-glow/.test(тело) && /animation: none/.test(тело);
        });
    })(),
    'Экран загрузки обязан быть прикрыт `prefers-reduced-motion`, и\n' +
    'прикрыт целиком: знак, подписи, спонсор, блик и свечение.\n' +
    'ПУЛЬС ГАСИТСЯ ОТДЕЛЬНО (`animation: none`) — у него бесконечный\n' +
    'повтор, и одной короткой длительности мало.');

правило('«меньше движения» снимает движение, а не показ',
    (() => {
        const блоки = CSSК.split('@media (prefers-reduced-motion: reduce)').slice(1);
        return блоки.some(б => {
            const тело = б.slice(0, б.indexOf('\n}') + 2);
            if (!/\.splash-sponsor/.test(тело)) return false;
            /* У блока спонсора стоит `both`: `animation: none` оставил бы
               его в НАЧАЛЬНОМ кадре, то есть невидимым. Поэтому
               мгновенная длительность, а не отмена. */
            return /animation-duration:\s*1ms/.test(тело) &&
                   !/\.splash-sponsor[^{]*\{[^}]*animation:\s*none/.test(тело);
        });
    })(),
    'У блока спонсора стоит `both`, и `animation: none` оставил бы его в\n' +
    'НАЧАЛЬНОМ кадре — прозрачным. Человек с настройкой «меньше\n' +
    'движения» не увидел бы спонсора ВООБЩЕ, а спонсор платит за показ.\n' +
    'Снимаем движение мгновенной длительностью, а не отменой.');

/* ══ 4. ЧИСЛА БЛОКА — СТУПЕНИ ПРОЕКТА ════════════════════════════════ */

