/**
 * ЗАМОРОЗКА ДОМА СПОНСОРОВ И ЭКРАНА ЗАГРУЗКИ (кусок 205, 27.10.2026).
 *
 * ЗАЧЕМ. Костя попросил показывать генерального спонсора на экране
 * загрузки приложения несколько секунд. Чтение таблицы `sponsors` жило
 * внутри `js/sponsors-loader.js`, в его собственной области, наружу
 * ничего не отдавая: приложению пришлось бы написать СВОЙ запрос — и
 * получить второе определение одного понятия.
 *
 * ЧТО СДЕЛАНО. Чтение вынесено в дом `js/kslt-sponsory.js`, один на сайт
 * и приложение (копия сверяется до байта сторожем копий). Загрузчик
 * целиком в приложение НЕ взят: он правит шапку САЙТА и считает визит на
 * сайт — в приложении первое ничего не найдёт, второе припишет сайту
 * чужие заходы.
 *
 * ЧТО ЗАМОРОЖЕНО — ОТНОШЕНИЯ:
 *   • чтение таблицы объявлено ОДИН раз, и это дом;
 *   • загрузчик сайта берёт список у дома, а не у базы напрямую;
 *   • перемешивание равных осталось в загрузчике: это про ПОКАЗ;
 *   • экран загрузки показывает спонсора из памяти СРАЗУ, а свежего
 *     догоняет — ждать базу значит держать человека перед пустым экраном;
 *   • срока два: без спонсора прежние 1500 мс, со спонсором 3000;
 *   • числа блока спонсора — ступени проекта, а не подогнанные.
 *
 *   node tools/check-sponsor-na-zagruzke.js
 */
const fs = require('fs');
const path = require('path');

const КОРЕНЬ = path.join(__dirname, '..');
const чит = ф => fs.readFileSync(path.join(КОРЕНЬ, ф), 'utf8');
const безКом = s => s.replace(/\/\*[\s\S]*?\*\//g, ' ').replace(/^[ \t]*\/\/[^\n]*$/gm, '');

const ошибки = [];
const правило = (имя, условие, подсказка) => { if (!условие) ошибки.push({ имя, подсказка }); };

const ДОМ = безКом(чит('js/kslt-sponsory.js'));
const ЗАГ = безКом(чит('js/sponsors-loader.js'));
const ПРИЛ = безКом(чит('mobile/www/js/app.js'));
const РАЗМЕТКА = чит('mobile/www/index.html');
const CSS = чит('mobile/www/css/app.css');

/* ══ 1. ЧТЕНИЕ — ОДНО ═════════════════════════════════════════════════ */

const собрать = (кат, спис) => {
    fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(д => {
        const п = кат + '/' + д.name;
        if (д.isDirectory()) собрать(п, спис);
        else if (д.name.endsWith('.js')) спис.push(п);
    });
    return спис;
};
const ВСЕ = собрать('js', []).concat(собрать('mobile/www/js', []));
const читают = ВСЕ.filter(ф => /from\('sponsors'\)/.test(безКом(чит(ф))))
    .map(ф => ф.split('/').pop());

/* АДМИНКА ЧИТАЕТ ДЛЯ УПРАВЛЕНИЯ, А НЕ ДЛЯ ПОКАЗА, и это другое понятие:
   она правит и удаляет записи, ей нужен один спонсор по номеру и счёт
   показов. Дом отдаёт список для ПОКАЗА. Поэтому `admin/sections/*`
   названы здесь с причиной, а не просто исключены.

   ЗАМЕР 27.10 НАЙДЕН ПРАВИЛОМ, А НЕ МНОЙ: я считал, что чтение живёт в
   одном загрузчике, а оно было размазано по ПЯТИ местам показа. И хуже:
   `js/sponsors-page.js` сортировал `sort_order` ПО УБЫВАНИЮ, тогда как
   загрузчик — по возрастанию. Один список был выстроен наоборот в двух
   местах — ровно то, от чего сторож охраняет карусель с 24.09, но
   признак смотрел только в загрузчик. */
const УПРАВЛЕНИЕ = ['sponsors.js', 'analytics.js'];
const показ = читают.filter(н => УПРАВЛЕНИЕ.indexOf(н) === -1);

правило('таблицу спонсоров для показа читает только дом',
    показ.length === 2 && показ.every(н => н === 'kslt-sponsory.js'),
    'читающих для показа: ' + показ.length + ' — ' + показ.join(', ') + '.\n' +
    'Их должно быть два и оба `kslt-sponsory.js`: сайтовый и его копия в\n' +
    'приложении, побайтово равная (это держит сторож копий)');

правило('загрузчик сайта берёт список у дома',
    /window\.KSLT_SPONSORY;/.test(ЗАГ) && /Д\.все\(\)/.test(ЗАГ),
    'загрузчик снова ходит в базу сам — и дом перестаёт быть источником');

/* ПЕРЕМЕШИВАНИЕ ОСТАЛОСЬ В ЗАГРУЗЧИКЕ, И ЭТО РЕШЕНИЕ: оно про показ.
   Утащить его в дом значило бы тасовать список и там, где показа нет —
   на экране загрузки, где спонсор ровно один. */
правило('перемешивание равных живёт в показе, а не в чтении',
    /Math\.random\(\)/.test(ЗАГ) && !/Math\.random\(\)/.test(ДОМ),
    'тасовка переехала в дом: экран загрузки берёт одного спонсора, и\n' +
    'тасовать там нечего');

/* ══ 2. ПАМЯТЬ, А НЕ ОЖИДАНИЕ ═════════════════════════════════════════ */

правило('дом помнит последнего генерального и отдаёт его без сети',
    /localStorage\.setItem/.test(ДОМ) && /localStorage\.getItem/.test(ДОМ) &&
    /функция изПамяти|изПамяти: изПамяти/.test(ДОМ),
    'без памяти экран загрузки либо ждёт базу неизвестное время, либо\n' +
    'показывает спонсора только со второго запуска');

/* В ПАМЯТЬ КЛАДЁТСЯ ТОЛЬКО ИМЯ И ЗНАК. Адреса, телефоны и ссылки
   спонсора экрану загрузки не нужны, а в чужой памяти им делать нечего. */
правило('в памяти лежат только имя и логотип',
    /JSON\.stringify\(\{\s*name: с\.name \|\| '', logo: с\.logo \|\| ''\s*\}\)/.test(ДОМ),
    'в память уехали лишние поля спонсора');

правило('экран загрузки берёт спонсора из памяти и догоняет свежего',
    /Д\.изПамяти\(\)/.test(ПРИЛ) && /Д\.генеральный\(\)\.then/.test(ПРИЛ),
    'либо спонсор появится только со второго запуска, либо экран будет\n' +
    'ждать ответа базы неизвестное время');

/* ══ 3. ДВА СРОКА ═════════════════════════════════════════════════════ */

правило('срока два: без спонсора 1500, со спонсором 3000',
    /SPLASH_MIN_MS = 1500/.test(ПРИЛ) && /SPLASH_SO_SPONSOROM_MS = 3000/.test(ПРИЛ) &&
    /спонсорПоказан \? SPLASH_SO_SPONSOROM_MS : SPLASH_MIN_MS/.test(ПРИЛ),
    'один срок на оба случая: либо спонсора не успеют прочитать, либо\n' +
    'человека держат перед пустым местом');

/* ══ 4. ЧИСЛА БЛОКА — СТУПЕНИ ПРОЕКТА ════════════════════════════════ */

const блок = (() => {
    const и = CSS.indexOf('.splash-sponsor {');
    return и === -1 ? '' : CSS.slice(и, CSS.indexOf('@keyframes splashBounceIn'));
})();

правило('блок спонсора объявлен и стоит на токенах',
    /gap: var\(--space-3\)/.test(блок) && /margin-top: var\(--space-6\)/.test(блок) &&
    /font-size: var\(--fs-2xs\)/.test(блок) && /color: var\(--text-muted\)/.test(блок),
    'числа блока ушли с токенов — а это первый блок приложения,\n' +
    'написанный по системе сайта, и эталон для остальных');

/* КОРОБКА ЛОГОТИПА ПОСТОЯННОЙ ВЫСОТЫ. Логотипы приходят из базы разных
   пропорций, и без коробки экран дёргался бы на каждом новом спонсоре. */
правило('логотип встаёт в коробку постоянной высоты',
    /height: 52px/.test(блок) && /object-fit: contain/.test(блок),
    'логотип будет тянуть экран загрузки по своей высоте, и у разных\n' +
    'спонсоров он окажется разного размера');

правило('разметка экрана загрузки держит блок спонсора скрытым',
    /id="splashSponsor" hidden/.test(РАЗМЕТКА) &&
    /id="splashSponsorLogo"/.test(РАЗМЕТКА) && /id="splashSponsorLabel"/.test(РАЗМЕТКА),
    'блок виден до того, как логотип поставлен: на первом запуске\n' +
    'человек увидит пустое место с подписью');

/* ══ 5. ДОМ СТОИТ РАНЬШЕ СВОИХ ЗОВУЩИХ ════════════════════════════════ */

/* ТА ЖЕ БЕДА, ЧТО У ДОМА ЛИЦА И ДОМА ЭКРАНИРОВАНИЯ В ТОТ ЖЕ ДЕНЬ: дом
   подключён, но ПОЗЖЕ тех, кто его зовёт. Держится это только тем, что
   зов идёт из функции, а не при разборе файла. Порядок, который работает
   случайно, однажды перестанет. */
const стр = ф => (чит(ф).match(/<script src="[^"]+"/g) || [])
    .map(т => т.slice(13, -1).split('?')[0].split('/').pop());

const вПрил = стр('mobile/www/index.html');
const зовущиеПрил = ['home-blocks.js', 'partners.js', 'app.js']
    .map(н => вПрил.indexOf(н)).filter(и => и !== -1);

правило('в приложении дом спонсоров стоит раньше своих зовущих',
    вПрил.indexOf('kslt-sponsory.js') !== -1 &&
    вПрил.indexOf('kslt-sponsory.js') < Math.min.apply(null, зовущиеПрил),
    'дом подключён позже зовущих. Сейчас держится только тем, что зов\n' +
    'идёт из функции, а не при разборе файла');

const собратьHTML = (кат, спис) => {
    fs.readdirSync(path.join(КОРЕНЬ, кат), { withFileTypes: true }).forEach(д => {
        const п = кат + '/' + д.name;
        if (д.isDirectory()) { if (!/node_modules|test-results|playwright/.test(д.name)) собратьHTML(п, спис); }
        else if (д.name.endsWith('.html')) спис.push(п);
    });
    return спис;
};
const позже = собратьHTML('pages', []).concat(собратьHTML('maket', []))
    .concat(fs.readdirSync(КОРЕНЬ).filter(ф => /^index.*\.html$/.test(ф)))
    .filter(с => {
        const и = стр(с);
        const д = и.indexOf('kslt-sponsory.js');
        const з = ['sponsors-loader.js', 'sponsors-page.js'].map(н => и.indexOf(н)).filter(x => x !== -1);
        if (!з.length) return false;
        return д === -1 || д > Math.min.apply(null, з);
    });

правило('на сайте дом спонсоров стоит раньше своих зовущих',
    позже.length === 0,
    'страниц с порядком наоборот: ' + позже.length + ' — ' + позже.slice(0, 4).join(', '));

/* ══ ИТОГ ═══════════════════════════════════════════════════════════════ */

if (ошибки.length === 0) {
    console.log('  ок      спонсор на экране загрузки: 11 правил');
    console.log('          таблицу читает только дом, один на сайт и приложение');
    console.log('          память вместо ожидания   ·   два срока: 1500 и 3000');
    console.log('          числа блока — ступени проекта');
    console.log('');
    process.exit(0);
}
console.log('  НЕ ТАК  спонсор на экране загрузки — ' + ошибки.length + ' правил не держится');
console.log('');
ошибки.forEach(е => {
    console.log('          ✗ ' + е.имя);
    console.log('            ' + е.подсказка.replace(/\n\s*/g, '\n            '));
    console.log('');
});
process.exit(1);
