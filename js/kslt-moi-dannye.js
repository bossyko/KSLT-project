/**
 * МОИ ДАННЫЕ — ОДИН ДОМ НА САЙТ И ПРИЛОЖЕНИЕ (Ю4, 07.11).
 *
 * Политика, п. 9.2, и Соглашение, п. 11.2, обещают человеку две вещи:
 * ПОКАЗАТЬ, какие данные о нём есть, и ОТДАТЬ их копию в машиночитаемом
 * виде (ст. 73 и 76 Цифрового кодекса). Обещаны они в обоих продуктах,
 * значит и устройство у них одно.
 *
 * СОБИРАЕТ НЕ КЛИЕНТ, А БАЗА: `public.мои_данные()`. Запрос из клиента
 * к полутора десяткам таблиц вернул бы ПУСТО там, где правило доступа
 * не дало строк, — без ошибки. Выгрузка вышла бы неполной молча, а
 * документ обещает ВСЕ данные.
 *
 * ИМЕНА РАЗДЕЛОВ ПРИХОДЯТ ДОВОДОМ: словари у сайта и приложения свои.
 */
(function (global) {
    'use strict';

    var API = global.KSLT_MOI_DANNYE = {};

    /** Разделы в порядке показа. Имя раздела — ключ словаря. */
    API.РАЗДЕЛЫ = [
        'учётная_запись', 'карточка_игрока', 'согласия', 'заявки_на_турниры',
        'результаты', 'история_рейтинга', 'членство', 'платежи',
        'баллы', 'ваучеры', 'устройства', 'уведомления'
    ];

    /**
     * СКОЛЬКО ЗАПИСЕЙ В РАЗДЕЛЕ.
     * Объект — одна запись, список — его длина, пусто — ноль.
     * Человеку важно видеть «0», а не отсутствие строки: ноль это
     * ответ, а пропуск выглядит как недоработка.
     */
    API.сколько = function (значение) {
        if (значение === null || значение === undefined) return 0;
        if (Array.isArray(значение)) return значение.length;
        return 1;
    };

    /** Запрос к базе. Возвращает обещание с готовой выгрузкой. */
    API.запросить = function (клиент) {
        return клиент.rpc('мои_данные').then(function (ответ) {
            if (ответ.error) throw new Error(ответ.error.message);
            return ответ.data;
        });
    };

    /**
     * ОТДАТЬ ФАЙЛОМ. Имя с датой: человек скачает выгрузку дважды с
     * разницей в месяц, и два файла с одним именем он не различит.
     */
    API.имяФайла = function (дата) {
        var д = дата || new Date();
        var дв = function (ч) { return (ч < 10 ? '0' : '') + ч; };
        return 'kslt-moi-dannye-' + д.getFullYear() + '-' +
               дв(д.getMonth() + 1) + '-' + дв(д.getDate()) + '.json';
    };

    API.скачать = function (данные, имя) {
        var текст = JSON.stringify(данные, null, 2);
        var ссылка = document.createElement('a');
        var адрес = URL.createObjectURL(new Blob([текст], { type: 'application/json' }));
        ссылка.href = адрес;
        ссылка.download = имя || API.имяФайла();
        document.body.appendChild(ссылка);
        ссылка.click();
        document.body.removeChild(ссылка);
        /* Адрес живёт, пока его не отпустят: браузер держит на него
           копию выгрузки в памяти. */
        setTimeout(function () { URL.revokeObjectURL(адрес); }, 1000);
    };

    /**
     * СВОДКА — ЧТО ИМЕННО О ЧЕЛОВЕКЕ ХРАНИТСЯ.
     * Это и есть «показать», обещанное п. 9.2: не сам файл, а список
     * разделов с числом записей. Сами значения человек видит в файле —
     * вываливать полтора десятка таблиц на экран значит не показать
     * ничего.
     */
    API.разметка = function (Т, данные) {
        var экр = global.KSLT_экранировать || function (з) { return з == null ? '' : String(з); };
        var строки = API.РАЗДЕЛЫ.map(function (р) {
            var n = API.сколько(данные ? данные[р] : null);
            return '<li class="db-mydata-row">' +
                '<span class="db-mydata-name">' + экр(Т['dat_' + р] || р) + '</span>' +
                '<span class="db-mydata-count">' + n + '</span>' +
            '</li>';
        }).join('');

        return '<div class="db-card db-settings-section db-mydata-card">' +
            '<div class="db-card-title">' + экр(Т.datTitle) + '</div>' +
            '<p class="db-mydata-intro">' + экр(Т.datIntro) + '</p>' +
            '<ul class="db-mydata-list">' + строки + '</ul>' +
            '<button class="db-btn db-btn-primary db-mydata-save">' + экр(Т.datDownload) + '</button>' +
        '</div>';
    };

})(typeof window !== 'undefined' ? window : this);
