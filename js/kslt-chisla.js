/* ============================================================
   ДОМ ЧИСЕЛ — РАЗДЕЛИТЕЛЬ ТЫСЯЧ ОДИН НА ПРОДУКТ
   ============================================================

   ЧТО БЫЛО. Одно и то же правило — «ставить разделитель каждые три
   цифры» — жило в ШЕСТИ местах, и в двух видах:

     js/tournaments-overview.js:746  function money(n)   неразрывный пробел
     js/tournament-detail.js:1295    function money(n)   неразрывный пробел
     js/tournament-blocks.js:66      function money(n)   неразрывный пробел
     js/tournaments-overlay.js:32    прямо в строке      ОБЫЧНЫЙ пробел
     js/admin/sections/bracket.js:2784    прямо в строке ОБЫЧНЫЙ пробел
     js/admin/sections/tournaments.js:836 своя функция   ОБЫЧНЫЙ пробел

   Разница не бумажная: обычный пробел переносится на новую строку, и
   «1 200» разрывается пополам в узкой колонке, а неразрывный — нет.
   Один и тот же приз в афише и в таблице выглядел по-разному.

   ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ. Здесь — одно.

     KSLT_CHISLA.тысячи(1200)    -> '1 200'  (неразрывный пробел)
     KSLT_CHISLA.деньги(1200.4)  -> '1 200'  (округляет и ставит разделитель)

   Дом ни от чего не зависит и может стоять первым среди скриптов.
   ============================================================ */
(function () {
    'use strict';

    var Ч = {};

    /* Неразрывный пробел, а не обычный: число не должно рваться на
       переносе строки. Выбран как общий вид — он уже стоял в трёх местах
       из шести, и он же верен типографически.
       ЗАПИСАН КОДОМ, А НЕ САМИМ ЗНАКОМ: в файле неразрывный пробел
       глазами неотличим от обычного, и правка «поправил пробел» прошла бы
       незамеченной в любом разборе. ЗНАК, КОТОРОГО НЕ ВИДНО, НЕ ДОЛЖЕН
       РЕШАТЬ. */
    var РАЗДЕЛИТЕЛЬ = String.fromCharCode(0xA0);

    /** Разделитель каждые три цифры. Дробная часть, если есть, остаётся. */
    Ч.тысячи = function (n) {
        if (n === null || n === undefined || n === '') return '';
        var с = String(n);
        var части = с.split('.');
        части[0] = части[0].replace(/\B(?=(\d{3})+(?!\d))/g, РАЗДЕЛИТЕЛЬ);
        return части.join('.');
    };

    /** Деньги: округляем до целого и ставим разделитель.
        ПУСТОТА ОСТАЁТСЯ ПУСТОТОЙ, А НЕ СТАНОВИТСЯ НУЛЁМ: `Number('')`
        даёт 0, и без этой проверки пустое поле цены показало бы «0».
        Поймано на первом же прогоне дома. */
    Ч.деньги = function (n) {
        if (n === null || n === undefined || n === '') return '';
        var ч = Number(n);
        if (!isFinite(ч)) return '';
        return Ч.тысячи(Math.round(ч));
    };

    window.KSLT_CHISLA = Ч;
})();
