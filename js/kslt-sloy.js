/**
 * КСЛТ — СЛОЙ-ССЫЛКА НА КАРТОЧКУ. ОДНО ОПРЕДЕЛЕНИЕ НА ВЕСЬ САЙТ.
 *
 * ЗАЧЕМ. Карточка, которая ведёт на страницу, обязана БЫТЬ ссылкой: иначе её
 * нельзя открыть в новой вкладке, до неё нельзя дойти с клавиатуры, диктор не
 * назовёт её ссылкой и поисковик по ней не пройдёт. Померено 13.10: на поиске
 * игрока девять карточек — `div` с обработчиком, фокусируемых внутри ОДИН
 * (кнопка «Пригласить»), ссылок ноль.
 *
 * ПОЧЕМУ СЛОЙ, А НЕ ОБЁРТКА — решение 04.10, здесь не переоткрывается.
 * Внутри карточки живут свои кнопки, а кнопка внутри ссылки — недопустимая
 * разметка. Обернуть одно название тоже нельзя: у заголовков стоит
 * `overflow: hidden` ради обрезки в две строки, и слой изнутри был бы ею
 * обрезан. Поэтому ссылка — ПРЯМОЙ ребёнок карточки, растянутая на неё
 * целиком.
 *
 * ПОРЯДОК СЛОЁВ, И ЭТО ГЛАВНОЕ. Слой идёт ВЫШЕ неинтерактивного содержимого,
 * а то, у чего своё действие, поднимается НАД слоем:
 *
 *     .карточка            position: relative
 *     .карточка > *        z-index: 1   — содержимое
 *     .карточка > .слой    z-index: 2   — ссылка поверх содержимого
 *     .карточка > .кнопка  z-index: 3   — своё действие поверх ссылки
 *
 * СОДЕРЖИМОЕ СЪЕДАЕТ СЛОЙ, ЕСЛИ СЛОЙ ПОД НИМ. Правило выведено 04.10 на
 * полосе турнира и ПОДТВЕРЖДЕНО ЗАМЕРОМ 13.10 на «Услугах», где слой стоял
 * `z-index: 0`: нажатие на фотографию попадало в `IMG`, нажатие на имя — в
 * `DIV`, и ссылка срабатывала только на пустых полях карточки.
 *
 * ИМЯ УХОДИТ В `aria-label`: пустая ссылка диктору не говорит ничего, а
 * видимый заголовок остаётся заголовком, а не ссылкой.
 */
(function () {
    'use strict';

    function экр(т) {
        return String(т == null ? '' : т)
            .replace(/&/g, '&amp;').replace(/"/g, '&quot;')
            .replace(/</g, '&lt;').replace(/>/g, '&gt;');
    }

    /**
     * @param {string} класс — своё имя слоя у семьи карточек
     * @param {string} href  — куда ведёт карточка
     * @param {string} имя   — что прочитает диктор
     */
    function слой(класс, href, имя) {
        return '<a class="' + экр(класс) + '" href="' + экр(href) + '"' +
               ' aria-label="' + экр(имя) + '"></a>';
    }

    window.KSLT_SLOY = { слой: слой, экр: экр };
})();
