/**
 * ОТСЕЧКА ДЛИННОГО СПИСКА — ОДНА НА ВЕСЬ САЙТ.
 *
 * Слово Кости 06.10: «10 везде» — видны первые десять строк, остальное под
 * кнопкой. 09.10 то же понадобилось публичной странице игрока: матчей 13,
 * турниров 17, и список уходил вниз без конца.
 *
 * ПОЧЕМУ ОБЩИЙ ФАЙЛ, А НЕ ВТОРАЯ КОПИЯ. Механизм был написан для страницы
 * турнира (js/tournament-detail.js) и знал только таблицы: скрытую строку он
 * возвращал через display: table-row. У игрока строка матча — не строка
 * таблицы, а карточка на гриде, и та же правка вернула бы ей display: block,
 * то есть сломала бы раскладку. Второе определение разошлось бы с первым на
 * первой же правке — поэтому механизм вынесен сюда и переписан так, чтобы не
 * знать, как устроена строка.
 *
 * РАСКРЫТИЕ СНИМАЕТ КЛАСС, А НЕ НАЗНАЧАЕТ display. Строка возвращается к
 * своему собственному правилу сама, какое бы оно ни было — tr, карточка или
 * элемент грида.
 *
 * СТРОКА СКРЫТА, А НЕ ВЫБРОШЕНА: она есть в разметке, её находит поиск по
 * странице и читает диктор.
 *
 *   KSLT_OTSECHKA.СТРОК_СРАЗУ        → 10
 *   KSLT_OTSECHKA.класс(номер, всего) → ' kslt-skryta' либо ''
 *   KSLT_OTSECHKA.кнопка(всего, язык) → разметка кнопки либо ''
 *   KSLT_OTSECHKA.включить(контейнер) → навесить обработчики
 */
(function () {
    'use strict';

    var O = {};
    O.СТРОК_СРАЗУ = 10;

    /** Класс для строки по её номеру: скрываем всё, что ниже десятой. */
    O.класс = function (номер, всего) {
        return (всего > O.СТРОК_СРАЗУ && номер >= O.СТРОК_СРАЗУ) ? ' kslt-skryta' : '';
    };

    /**
     * Кнопка под списком. Её нет вовсе, когда прятать нечего: кнопка,
     * которая ничего не раскрывает, — обещание без содержания.
     * @param {number} всего строк в списке
     * @param {string} [язык] 'ru' | 'en' | 'kg'
     */
    O.кнопка = function (всего, язык) {
        if (!всего || всего <= O.СТРОК_СРАЗУ) return '';
        var л = язык || 'ru';
        var слово = л === 'en' ? 'Show all' : (л === 'kg' ? 'Баарын көрсөтүү' : 'Показать все');
        return '<button type="button" class="kslt-more" aria-expanded="false">' +
               слово + ' (' + всего + ')</button>';
    };

    /**
     * КНОПКА РАСКРЫВАЕТ СВОЮ КОРОБКУ, А НЕ ВСЕ: списков на экране бывает
     * несколько — две лиги, заявки и лист ожидания, матчи и турниры, — и
     * раскрытая соседка это чужое решение.
     */
    O.включить = function (контейнер) {
        if (!контейнер) return;
        контейнер.querySelectorAll('.kslt-more').forEach(function (кнопка) {
            кнопка.addEventListener('click', function () {
                var коробка = кнопка.parentElement;
                if (коробка) {
                    коробка.querySelectorAll('.kslt-skryta').forEach(function (строка) {
                        строка.classList.remove('kslt-skryta');
                    });
                }
                кнопка.setAttribute('aria-expanded', 'true');
                кнопка.remove();
            });
        });
    };

    window.KSLT_OTSECHKA = O;
})();
