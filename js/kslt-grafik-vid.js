/**
 * ВИД ГРАФИКА — ОДИН ДОМ НА ВСЕ ГРАФИКИ (12.11.2026).
 *
 * ОТКУДА. Костя про аналитику: «не понятно и не читабельно, всё
 * сливается». Замер по коду: графики рисуются в ЧЕТЫРЁХ местах
 * (analytics, users, finances, rating-chart), и каждое задаёт свои
 * краски, свою сетку и свою толщину полос. На экране это даёт разное
 * прочтение одного и того же.
 *
 * ЧТО ИМЕННО СЛИВАЛОСЬ, числами из кода до правки:
 *   · barThickness 40 при шести строках — полосы стоят вплотную, между
 *     ними нет воздуха, и шесть полос читаются как одна масса;
 *   · stacked: две краски в одной полосе без границы между ними;
 *   · сетка 6% белого — её почти нет, глазу не на что опереться;
 *   · ЧИСЕЛ НЕТ ВОВСЕ: значение читается только наведением мыши, а на
 *     снимке и на планшете мыши нет.
 *
 * РЕШЕНИЕ, ПО ШКАЛЕ И БЕЗ ВЫДУМАННЫХ ЧИСЕЛ:
 *   · полоса 24 (ступень кнопок xs 28 минус рамки — берём 24 как
 *     ступень отступов), зазор между полосами даёт categoryPercentage;
 *   · число пишется В КОНЦЕ полосы — плагином, одинаково для всех;
 *   · сетка 10% вместо 6%, подписи осей 60% и 72%;
 *   · краски: Site — акцент клуба, App — --cat-1; у обеих рамка той же
 *     краски в полную силу, чтобы соседние сегменты не слипались.
 */
(function (global) {
    'use strict';

    var API = global.KSLT_GRAFIK_VID = {};

    /** Краска из токена: дом красок уже есть, свой разбор не заводим. */
    function краска(имя, альфа) {
        return global.KSLT_KRASKA.цвет(имя, альфа);
    }

    /** ТОЛЩИНА ПОЛОСЫ — СТУПЕНЬ, А НЕ ВКУС. */
    API.ПОЛОСА = 24;
    /* 16 — ступень шкалы отступов. Две полосы по 16 с зазором читаются
       как пара и занимают ту же высоту строки, что одна в 40 до правки. */
    API.ПОЛОСА_МАЛАЯ = 16;

    /**
     * ЧИСЛО В КОНЦЕ ПОЛОСЫ. Chart.js сам подписей не рисует, а без них
     * сводка читается только мышью. Плагин один на все графики: иначе
     * шесть мест нарисуют шесть разных подписей.
     */
    API.подписиЗначений = {
        id: 'kslt-podpisi',
        afterDatasetsDraw: function (chart) {
            var ctx = chart.ctx;
            ctx.save();
            ctx.font = '600 12px Inter, system-ui, sans-serif';
            ctx.textBaseline = 'middle';
            chart.data.datasets.forEach(function (набор, i) {
                var мета = chart.getDatasetMeta(i);
                if (мета.hidden) return;
                мета.data.forEach(function (точка, j) {
                    var значение = набор.data[j];
                    /* НОЛЬ НЕ ПОДПИСЫВАЕТСЯ: подпись у нулевой полосы
                       висит в пустоте и читается как чужая. */
                    if (!значение) return;
                    var гор = chart.options.indexAxis === 'y';
                    ctx.fillStyle = краска('--neutral-white', 0.72);
                    ctx.textAlign = гор ? 'left' : 'center';
                    var x = гор ? точка.x + 6 : точка.x;
                    var y = гор ? точка.y : точка.y - 8;
                    ctx.fillText(String(значение), x, y);
                });
            });
            ctx.restore();
        }
    };

    /** ОСИ И СЕТКА — одинаковые во всех графиках. */
    API.ось = function (о) {
        о = о || {};
        return {
            stacked: !!о.стопкой,
            grid: о.безСетки
                ? { display: false }
                : { color: краска('--neutral-white', 0.10), drawTicks: false },
            border: { display: false },
            ticks: {
                color: краска('--neutral-white', о.крупные ? 0.72 : 0.6),
                font: { size: о.крупные ? 13 : 12 },
                padding: 8
            }
        };
    };

    /** ЛЕГЕНДА — точками, а не квадратами: квадрат спорит с полосой. */
    API.легенда = function () {
        return {
            display: true,
            labels: {
                color: краска('--neutral-white', 0.72),
                usePointStyle: true,
                pointStyle: 'circle',
                boxWidth: 8,
                padding: 16,
                font: { size: 12 }
            }
        };
    };

    API.подсказка = function () {
        return {
            backgroundColor: краска('--chart-tip-bg'),
            titleColor: краска('--accent'),
            bodyColor: краска('--chart-tip-body'),
            borderColor: краска('--chart-tip-border'),
            borderWidth: 1,
            padding: 10
        };
    };

    /**
     * НАБОР ДАННЫХ. Краска одна на понятие: сайт — акцент клуба,
     * приложение — --cat-1. Рамка в полную силу держит границу между
     * соседними сегментами в стопке.
     */
    API.набор = function (имя, данные, вид, о) {
        о = о || {};
        /* КРАСКА РЯДА — ИЗ ИМЕНИ РЯДА, А НЕ ИЗ АКЦЕНТА КЛУБА. Акцент
           выделяет ОДНО, а в графике он красил половину площади: при
           контрасте 14.19 к подложке против 7.48 у песка полоса била в
           глаза. Имена --chart-ryad-* живут в tokens.css. */
        var токен = вид === 'app' ? '--chart-ryad-2' : '--chart-ryad-1';
        return {
            label: имя,
            data: данные,
            backgroundColor: краска(токен, о.заливка || 0.85),
            borderColor: краска(токен),
            borderWidth: 1,
            borderRadius: 4,
            borderSkipped: false,
            barThickness: о.тонкая ? API.ПОЛОСА_МАЛАЯ : API.ПОЛОСА,
            maxBarThickness: о.тонкая ? API.ПОЛОСА_МАЛАЯ : API.ПОЛОСА
        };
    };

})(typeof window !== 'undefined' ? window : this);
