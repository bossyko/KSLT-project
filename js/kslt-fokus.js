/**
 * КСЛТ — ЛОВУШКА ФОКУСА. ОДНО ОПРЕДЕЛЕНИЕ НА ВЕСЬ ПРОДУКТ.
 *
 * ЗАЧЕМ. Под открытым окном лежит вся страница с кнопками, которые меняют
 * данные. Обход по ней из открытого окна — это нажатие вслепую, и человек с
 * клавиатуры не видит, куда ушёл фокус. Поэтому Tab внутри окна ходит по
 * кругу, а не уезжает под него.
 *
 * ПОЧЕМУ ДОМ, А НЕ ШЕСТЬ КОПИЙ. Замер 21.10: ловушка жила в ШЕСТИ местах —
 * четыре в `dashboard.js` (1601, 3704, 4486, 6120), одна в `player.js` (1624)
 * и одна внутри оболочки окна админки (`admin/core/utils.js`). И КОПИИ УЖЕ
 * РАЗОШЛИСЬ, причём разошлись ТРИЖДЫ:
 *
 *   1. СПИСОК ФОКУСИРУЕМОГО. Четыре копии перечисляют поля (`input`,
 *      `select`, `textarea`), а две — окна «игрок против игрока» в кабинете
 *      и на странице игрока — только `button`, `a[href]` и `tabindex`.
 *      Сегодня в том окне полей нет, проверено чтением разметки, и бедой это
 *      НЕ БЫЛО. Но безопасность держалась на СОДЕРЖИМОМ окна, а не на
 *      правиле: первое же поле в нём — и Tab уходит под окно молча.
 *      ОДИНАКОВЫЕ КОПИИ — ЭТО ВЕЗЕНИЕ, А НЕ БЕЗОПАСНОСТЬ.
 *   2. ФОКУС СНАРУЖИ. Только копия админки возвращает фокус в окно, если он
 *      оказался под ним. Пять остальных в этом случае не делают НИЧЕГО: Tab
 *      продолжает обход страницы под окном — ровно то, что ловушка и должна
 *      запрещать.
 *   3. ПУСТОЕ ОКНО. Пять копий при отсутствии фокусируемого выходят молча и
 *      отпускают Tab наружу; копия админки гасит нажатие и ставит фокус на
 *      само окно.
 *
 * СВЕДЕНО НА ЛУЧШУЮ КОПИЮ, А НЕ НА ПЕРВУЮ ПОПАВШУЮСЯ: дом повторяет поведение
 * админской — полный список, возврат фокуса снаружи, пустое окно.
 *
 * ЧТО ДОМ НЕ ДЕЛАЕТ. Esc и возврат фокуса ПОСЛЕ закрытия — другое понятие и
 * живут у зовущего: у окна админки они завязаны на `закрыть()`, у окон сайта
 * на своё событие. ОДНО ПОНЯТИЕ — ОДИН ДОМ, а не «всё про окно в одном месте».
 */
(function () {
    'use strict';

    /* ПОЛНЫЙ СПИСОК — ТОТ, ЧТО БЫЛ У ЛУЧШЕЙ КОПИИ. `[href]` без `a`
       намеренно: ссылкой бывает и `area`, и `link` внутри окна не живёт. */
    var ФОКУСИРУЕМОЕ =
        'button:not([disabled]), [href], input:not([disabled]), ' +
        'select:not([disabled]), textarea:not([disabled]), ' +
        '[tabindex]:not([tabindex="-1"])';

    /**
     * Обработчик `keydown` для окна.
     *
     * @param {Element} корень — окно или подложка, внутри которой ходит Tab
     * @returns {function(KeyboardEvent): void}
     */
    function ловушка(корень) {
        return function (e) {
            if (e.key !== 'Tab') return;
            if (!корень) return;
            var сп = корень.querySelectorAll(ФОКУСИРУЕМОЕ);
            /* ПУСТОЕ ОКНО НЕ ОТПУСКАЕТ TAB НАРУЖУ. */
            if (!сп.length) {
                e.preventDefault();
                if (корень.focus) {
                    if (!корень.hasAttribute('tabindex')) корень.setAttribute('tabindex', '-1');
                    корень.focus();
                }
                return;
            }
            var пер = сп[0], посл = сп[сп.length - 1];
            /* ФОКУС МОГ ОКАЗАТЬСЯ ПОД ОКНОМ — возвращаем его внутрь. */
            if (!корень.contains(document.activeElement)) {
                e.preventDefault(); пер.focus(); return;
            }
            if (e.shiftKey && document.activeElement === пер) { e.preventDefault(); посл.focus(); }
            else if (!e.shiftKey && document.activeElement === посл) { e.preventDefault(); пер.focus(); }
        };
    }

    window.KSLT_FOKUS = { ловушка: ловушка, ФОКУСИРУЕМОЕ: ФОКУСИРУЕМОЕ };
})();
