/**
 * КСЛТ — ЛОВУШКА ФОКУСА. ОДНО ОПРЕДЕЛЕНИЕ НА ВЕСЬ ПРОДУКТ.
 *
 * ЗАЧЕМ. Под открытым окном лежит вся страница с кнопками, которые меняют
 * данные. Обход по ней из открытого окна — это нажатие вслепую, и человек с
 * клавиатуры не видит, куда ушёл фокус. Поэтому Tab внутри окна ходит по
 * кругу, а не уезжает под него.
 *
 * ПОЧЕМУ ДОМ, А НЕ ШЕСТЬ КОПИЙ. Замер 21.10: ловушка жила в ШЕСТИ местах —
 * четыре в `dashboard.js` (1601, 3704, 4486, 6120), одна в `player.js` (1624)
 * и одна внутри оболочки окна админки (`admin/core/utils.js`). И КОПИИ УЖЕ
 * РАЗОШЛИСЬ, причём разошлись ТРИЖДЫ:
 *
 *   1. СПИСОК ФОКУСИРУЕМОГО. Четыре копии перечисляют поля (`input`,
 *      `select`, `textarea`), а две — окна «игрок против игрока» в кабинете
 *      и на странице игрока — только `button`, `a[href]` и `tabindex`.
 *      Сегодня в том окне полей нет, проверено чтением разметки, и бедой это
 *      НЕ БЫЛО. Но безопасность держалась на СОДЕРЖИМОМ окна, а не на
 *      правиле: первое же поле в нём — и Tab уходит под окно молча.
 *      ОДИНАКОВЫЕ КОПИИ — ЭТО ВЕЗЕНИЕ, А НЕ БЕЗОПАСНОСТЬ.
 *   2. ФОКУС СНАРУЖИ. Только копия админки возвращает фокус в окно, если он
 *      оказался под ним. Пять остальных в этом случае не делают НИЧЕГО: Tab
 *      продолжает обход страницы под окном — ровно то, что ловушка и должна
 *      запрещать.
 *   3. ПУСТОЕ ОКНО. Пять копий при отсутствии фокусируемого выходят молча и
 *      отпускают Tab наружу; копия админки гасит нажатие и ставит фокус на
 *      само окно.
 *
 * СВЕДЕНО НА ЛУЧШУЮ КОПИЮ, А НЕ НА ПЕРВУЮ ПОПАВШУЮСЯ: дом повторяет поведение
 * админской — полный список, возврат фокуса снаружи, пустое окно.
 *
 * ЧТО ДОМ НЕ ДЕЛАЕТ. Возврат фокуса ПОСЛЕ закрытия — другое понятие и живёт у
 * зовущего: у окна админки он завязан на `закрыть()`, у окон сайта на своё
 * событие. ОДНО ПОНЯТИЕ — ОДИН ДОМ, а не «всё про окно в одном месте».
 *
 * ──────────────────────────────────────────────────────────────────────────
 * КУСОК 152, 23.10: УМЕНИЕ БЫЛО, А ДОСТАТЬ ЕГО МОГЛО ОДНО ОКНО ИЗ ШЕСТИ.
 *
 * ЗАМЕР НАЖАТИЕМ, ПЯТЬ ВИДОВ, стенд `maket/fokus-zamer.html`. Фокус ставился
 * ПОД окно, потом Tab:
 *   · слушатель на ПОДЛОЖКЕ (так были навешаны пять окон сайта) — фокус
 *     уходил в `BODY`, в окно НЕ возвращался. На всех пяти видах;
 *   · слушатель на `document` (так была навешана оболочка окна админки) —
 *     фокус возвращался на первый элемент окна. На всех пяти видах.
 * Ветвь «фокус оказался под окном» у пяти окон была МЁРТВОЙ не потому, что
 * дом её не умеет, а потому, что нажатие под окном до подложки не всплывает.
 * СПОСОБ НАВЕСИТЬ — ЧАСТЬ ПОВЕДЕНИЯ, А НЕ ОФОРМЛЕНИЕ.
 *
 * ПОЭТОМУ НАВЕШИВАНИЕ ПЕРЕЕХАЛО В ДОМ — `запереть`. Один слушатель на
 * `document` на все окна, работает ВЕРХНЕЕ окно стека. Стек, а не один
 * слушатель на окно, — потому что два открытых окна с ловушками на
 * `document` слышат друг друга: стенд 21.10 так и соврал, обе ловушки
 * сработали на один Tab, победила последняя, и фокус уехал в чужое окно.
 * ВЕЗЕНИЕ ЗАМЕНЕНО ПОРЯДКОМ: верхнее окно знает, что оно верхнее.
 *
 * И ЦЕНА ПЕРЕНОСА НАЗВАНА ЗАРАНЕЕ: слушатель на `document` обязан сниматься
 * при закрытии, иначе Tab останется в ловушке на всей странице. Снятие
 * возвращает `запереть`, а окно, закрытое мимо дома (своим `overlay.remove()`
 * — так делают девять рукодельных окон), снимается САМО: признак — узел ушёл
 * из документа. Два окна из шести — оба «игрок против игрока» — именно так и
 * ТЕКЛИ: их слушатель Esc снимался только на пути Esc, а при закрытии
 * кнопкой или фоном оставался на `document` навсегда.
 *
 * ВИДИМОСТЬ СТАЛА ЧАСТЬЮ СПИСКА, И ПРИЗНАК ВЫБРАН ЗАМЕРОМ. Скрытая кнопка
 * последней в окне ломала заворот: дом считал последним ЕЁ, `activeElement`
 * с ней не совпадал, гашения не было, и Tab уходил на страницу под окном —
 * замерено 23.10. Четыре рукодельные копии вне дома это умели, но спрашивали
 * `offsetParent`, а он null И у скрытой кнопки, И у видимой `position:
 * fixed` (замер: высота 0 против 21). Берём ВЫСОТУ — тот же признак, которым
 * оболочка окна админки выбирает, куда вернуть фокус. ОДНО ОПРЕДЕЛЕНИЕ
 * ВИДИМОСТИ НА ПРОДУКТ.
 */
(function () {
    'use strict';

    /* ПОЛНЫЙ СПИСОК — ТОТ, ЧТО БЫЛ У ЛУЧШЕЙ КОПИИ. `[href]` без `a`
       намеренно: ссылкой бывает и `area`, и `link` внутри окна не живёт. */
    var ФОКУСИРУЕМОЕ =
        'button:not([disabled]), [href], input:not([disabled]), ' +
        'select:not([disabled]), textarea:not([disabled]), ' +
        '[tabindex]:not([tabindex="-1"])';

    /* ВИДИМОЕ — ТО, У ЧЕГО ЕСТЬ ВЫСОТА. `offsetParent` врёт на `position:
       fixed`: он null и у скрытой кнопки, и у видимой фиксированной (замер
       23.10 — высота 0 против 21). Высота — тот же признак, которым
       оболочка окна админки выбирает, куда вернуть фокус. */
    function видим(э) {
        return э.getBoundingClientRect().height > 0;
    }

    /**
     * Фокусируемое внутри окна, в порядке обхода, без скрытого.
     *
     * @param {Element} корень
     * @returns {Element[]}
     */
    function фокусируемые(корень) {
        if (!корень) return [];
        return Array.prototype.filter.call(корень.querySelectorAll(ФОКУСИРУЕМОЕ), видим);
    }

    /**
     * Обработчик `keydown` для окна.
     *
     * @param {Element} корень — окно или подложка, внутри которой ходит Tab
     * @returns {function(KeyboardEvent): void}
     */
    function ловушка(корень) {
        return function (e) {
            if (e.key !== 'Tab') return;
            if (!корень) return;
            var сп = фокусируемые(корень);
            /* ПУСТОЕ ОКНО НЕ ОТПУСКАЕТ TAB НАРУЖУ. */
            if (!сп.length) {
                e.preventDefault();
                if (корень.focus) {
                    if (!корень.hasAttribute('tabindex')) корень.setAttribute('tabindex', '-1');
                    корень.focus();
                }
                return;
            }
            var пер = сп[0], посл = сп[сп.length - 1];
            /* ФОКУС МОГ ОКАЗАТЬСЯ ПОД ОКНОМ — возвращаем его внутрь. */
            if (!корень.contains(document.activeElement)) {
                e.preventDefault(); пер.focus(); return;
            }
            if (e.shiftKey && document.activeElement === пер) { e.preventDefault(); посл.focus(); }
            else if (!e.shiftKey && document.activeElement === посл) { e.preventDefault(); пер.focus(); }
        };
    }

    /* ═══ ЛЕСТНИЦА ОКОН: ОДИН СЛУШАТЕЛЬ, ВЕРХНЕЕ ОКНО РАБОТАЕТ ═══ */

    var стек = [];
    var слушает = false;

    /* ОКНО МОГЛИ ЗАКРЫТЬ МИМО ДОМА, И ДВУМЯ РАЗНЫМИ СПОСОБАМИ.
       Девять рукодельных окон закрывают себя своим же `overlay.remove()` —
       узел уходит из документа. А окно спонсоров и окно «обсудим
       сотрудничество» ПРЯЧУТСЯ АТРИБУТОМ `hidden`: узел остаётся на месте,
       и признак «ушёл из документа» их не ловит.

       ЗАМЕР 24.10 СКАЗАЛ, ЧЕМ ЭТО КОНЧАЕТСЯ, И ЭТО ХУЖЕ, ЧЕМ Я ДУМАЛ. У
       спрятанного окна фокусируемого НОЛЬ, то есть дом принимал его за
       ПУСТОЕ окно: гасил нажатие, заводил спрятанному узлу `tabindex="-1"`
       и звал `focus()`. Фокус на спрятанном не ставится — и Tab переставал
       работать НА ВСЕЙ СТРАНИЦЕ: фокус не двигался вовсе. Запертым
       оказывался не человек в окне, а сама клавиша.

       Поэтому запись живёт, пока её окно В ДОКУМЕНТЕ И ВИДИМО — тем же
       признаком высоты, которым дом выбирает фокусируемое. ОДНО
       ОПРЕДЕЛЕНИЕ ВИДИМОСТИ НА ДОМ. Проверяется НА КАЖДОМ нажатии, а не на
       закрытии: закрытия дом не видит. */
    function верхнее() {
        while (стек.length &&
               (!стек[стек.length - 1].корень.isConnected ||
                !видим(стек[стек.length - 1].корень))) стек.pop();
        if (!стек.length) { убратьСлушателя(); return null; }
        return стек[стек.length - 1];
    }

    function поКлавише(e) {
        var в = верхнее();
        if (!в) return;
        /* Esc НЕ ГАСИТСЯ: пять окон сайта и оболочка админки его не гасили,
           и кусок 152 переносит навешивание, а не меняет поведение. */
        if (e.key === 'Escape') { if (в.поEsc) в.поEsc(); return; }
        в.ловушка(e);
    }

    function убратьСлушателя() {
        if (!слушает) return;
        document.removeEventListener('keydown', поКлавише);
        слушает = false;
    }

    /**
     * Запереть фокус в окне: ловушка Tab плюс, если дан, выход по Escape.
     *
     * @param {Element} корень — окно или подложка, внутри которой ходит Tab
     * @param {{поEsc?: function}} [о]
     * @returns {function(): void} снятие — зовётся на КАЖДОМ пути закрытия
     */
    function запереть(корень, о) {
        о = о || {};
        /* ОКНА МОГЛО НЕ НАЙТИСЬ. Оболочка админки берёт его селектором по
           трём именам, и если разметка новая — вернётся `null`. Тогда
           запирать нечего, а снятие обязано быть зовомым: иначе падёт
           закрытие, а не ловушка. */
        if (!корень) return function () {};
        /* ЗАПИРАНИЕ ИДЕМПОТЕНТНО ПО КОРНЮ, И ЭТО НАШЛОСЬ ЗАМЕРОМ 24.10.
           Окно, спрятанное атрибутом, дом снимает со стека САМ — а его
           `снять` у зовущего после этого не снимает ничего. Открыли окно
           снова, зовущий снова позвал `запереть` — и в стеке оказались ДВЕ
           записи одного окна, причём нижняя уже не снимется ничем: её
           корень в документе и виден. Стек тёк бы ровно по одной записи на
           каждое открытие. Поэтому прежние записи этого же корня снимаются
           здесь, а не надеждой на зовущего. */
        for (var i = стек.length - 1; i >= 0; i--) {
            if (стек[i].корень === корень) стек.splice(i, 1);
        }
        var запись = { корень: корень, поEsc: о.поEsc || null, ловушка: ловушка(корень) };
        стек.push(запись);
        if (!слушает) {
            document.addEventListener('keydown', поКлавише);
            слушает = true;
        }
        return function снять() {
            var i = стек.indexOf(запись);
            if (i !== -1) стек.splice(i, 1);
            if (!стек.length) убратьСлушателя();
        };
    }

    window.KSLT_FOKUS = {
        ловушка: ловушка,
        запереть: запереть,
        фокусируемые: фокусируемые,
        ФОКУСИРУЕМОЕ: ФОКУСИРУЕМОЕ,
        /* ЧИСЛО ДЛЯ ЗАМЕРА: стек обязан пустеть. Проба спрашивает его, а не
           верит на слово, что слушатель снялся. */
        открытых: function () { return стек.length; }
    };
})();
