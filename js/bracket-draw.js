/**
 * KSLT — жеребьёвка турнирной сетки.
 *
 * Здесь только счёт: кто на какой линии сетки стоит, кому достаётся проход
 * без игры и куда идут победитель с проигравшим. Ни разметки, ни обращений
 * к базе — чтобы всё это можно было проверить тестами, а не глазами.
 *
 * Файл общий для сайта и приложения, совпадение сверяет tools/check-rules.js.
 */
(function() {
    'use strict';

    var D = window.KSLT_DRAW = {};

    // ---- Линии сеяных ----
    //
    // Сеяные ставятся не по порядку списка, а на постоянные линии, как в ATP,
    // WTA и ITF. Смысл в том, чтобы сильные не встретились раньше срока:
    // первый и второй сходятся только в финале, третий с четвёртым не раньше
    // полуфинала, и так далее.
    //
    // Линии считаются сверху вниз, от единицы до размера сетки.

    var ЛИНИИ = {
        8:  { 1: [1], 2: [8], 3: [3, 6] },
        16: { 1: [1], 2: [16], 3: [5, 12], 5: [4, 8, 9, 13] },
        32: { 1: [1], 2: [32], 3: [9, 24], 5: [8, 16, 17, 25],
              9: [4, 5, 12, 13, 20, 21, 28, 29] },
        64: { 1: [1], 2: [64], 3: [17, 48], 5: [16, 32, 33, 49],
              9: [8, 9, 24, 25, 40, 41, 56, 57],
              17: [4, 5, 12, 13, 20, 21, 28, 29, 36, 37, 44, 45, 52, 53, 60, 61] }
    };

    /** Группы сеяных для этого размера: {первый номер группы: [линии]}. */
    D.линииСеяных = function(размер) {
        return ЛИНИИ[размер] || null;
    };

    /** Сколько сеяных бывает в сетке такого размера. */
    D.сколькоСеяных = function(размер) {
        var г = ЛИНИИ[размер];
        if (!г) return 0;
        var всего = 0;
        Object.keys(г).forEach(function(н) { всего += г[н].length; });
        return всего;
    };

    // ---- Зерно жеребьёвки ----
    //
    // Внутри группы (скажем, кто из 5-8 встанет на линию 16, а кто на 17)
    // решает жребий. Но жребий должен быть один раз: если тянуть заново при
    // каждой отрисовке, сетка будет меняться на глазах у людей. Поэтому
    // зерно хранится вместе с турниром, а розыгрыш от него повторяем.

    D.новоеЗерно = function() {
        return Math.floor(Math.random() * 2147483647) + 1;
    };

    /** Простой воспроизводимый жребий: одно зерно — одна и та же сетка. */
    D.жребий = function(зерно) {
        var s = (зерно || 1) % 2147483647;
        if (s <= 0) s += 2147483646;
        return function() {
            s = (s * 16807) % 2147483647;
            return (s - 1) / 2147483646;
        };
    };

    /** Перемешать список этим жребием. */
    D.перемешать = function(список, бросок) {
        var к = список.slice();
        for (var i = к.length - 1; i > 0; i--) {
            var j = Math.floor(бросок() * (i + 1));
            var t = к[i]; к[i] = к[j]; к[j] = t;
        }
        return к;
    };

    // ---- Размер сетки ----

    /** Ближайшая степень двойки, не меньше числа участников. */
    D.размерСетки = function(участников) {
        var n = 2;
        while (n < участников) n *= 2;
        return Math.max(n, 4);
    };

    // ---- Проходы без игры ----
    //
    // Свободных линий столько, сколько мест в сетке сверх числа участников.
    // Отдаются они верхним сеяным подряд, без пропусков: если проходов
    // десять, их получают ровно сеяные с первого по десятого.

    D.комуПроход = function(размер, участников) {
        var сколько = размер - участников;
        var кому = [];
        for (var i = 1; i <= сколько; i++) кому.push(i);
        return кому;
    };

    // ---- Раскладка сетки ----
    //
    // Возвращает массив длиной в размер сетки: на каждой линии либо
    // участник, либо null — свободная линия.

    D.разложить = function(размер, участники, зерно) {
        var линии = new Array(размер);
        for (var i = 0; i < размер; i++) линии[i] = null;

        var группы = ЛИНИИ[размер];
        if (!группы) return линии;

        var бросок = D.жребий(зерно);
        var сеяных = Math.min(D.сколькоСеяных(размер), участники.length);
        var занято = {};

        // Сеяные — по своим линиям. Внутри группы порядок решает жребий.
        Object.keys(группы).map(Number).sort(function(a, b) { return a - b; })
            .forEach(function(первый) {
                var места = группы[первый];
                var номера = [];
                for (var н = первый; н < первый + места.length; н++) {
                    if (н <= сеяных) номера.push(н);
                }
                if (!номера.length) return;
                var кудаКого = места.length > 1 ? D.перемешать(места, бросок) : места;
                номера.forEach(function(н, i) {
                    var линия = кудаКого[i];
                    линии[линия - 1] = участники[н - 1];
                    занято[линия] = 1;
                });
            });

        // Проходы без игры — верхним сеяным. Занимаем линию соперника, чтобы
        // на неё уже никто не встал.
        var проходы = D.комуПроход(размер, участники.length);
        проходы.forEach(function(н) {
            if (н > сеяных) return;
            var линия = null;
            for (var л = 1; л <= размер; л++) {
                if (линии[л - 1] === участники[н - 1]) { линия = л; break; }
            }
            if (!линия) return;
            var сосед = (линия % 2 === 1) ? линия + 1 : линия - 1;
            занято[сосед] = 'проход';
        });

        // Остальные — по свободным линиям, тем же жребием
        var свободные = [];
        for (var л = 1; л <= размер; л++) if (!занято[л] && !линии[л - 1]) свободные.push(л);
        var прочие = участники.slice(сеяных);
        var порядок = D.перемешать(свободные, бросок);
        прочие.forEach(function(у, i) {
            if (i < порядок.length) линии[порядок[i] - 1] = у;
        });

        return линии;
    };

    // ---- Куда идут игроки после матча ----
    //
    // Маршрут выводится из самой таблицы блоков (R.ficSections), а не из
    // отдельной формулы. Так генератор и отрисовка не могут разойтись: если
    // считать двумя разными способами, рано или поздно они разъедутся, и
    // человек окажется в чужом блоке — именно это и случилось.
    //
    // Устройство простое. У каждой клетки есть отрезок мест, за которые в
    // ней борются: у первого круга это все места, дальше отрезок делится
    // пополам. Победитель уходит в верхнюю половину, проигравший в нижнюю.
    // Блок, разыгрывающий места с a, в круге r занимает отрезок
    // [a, a + 2^(кругов-r+1) - 1] — это видно прямо по таблице.

    /**
     * Куда идёт игрок после матча.
     *
     * Одно правило для всех размеров, то же самое, что в базе
     * (sql/fic-advance-by-round.sql): в круге r сетка поделена на 2^(r-1)
     * блоков по N/2^r матчей, победитель идёт в верхнюю половину своего
     * блока, проигравший — в нижнюю.
     *
     * Отсюда и выходит нужное: проигравший первого круга уходит в нижнюю
     * половину всех мест, второго — в нижнюю половину верхней, и так далее.
     */
    D.адрес = function(размер, круг, номер, победил) {
        var S = размер / Math.pow(2, круг);
        if (S < 1) return null;
        var b = Math.ceil(номер / S);
        var p = номер - (b - 1) * S;
        return (победил ? (2 * b - 2) : (2 * b - 1)) * (S / 2) + Math.ceil(p / 2);
    };
})();
