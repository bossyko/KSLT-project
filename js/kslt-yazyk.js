/**
 * ЯЗЫК СТРАНИЦЫ — ОДИН НА ВЕСЬ САЙТ.
 *
 * ЧТО БЫЛО: язык вычислялся ИЗ ПУТИ, и делали это 37 файлов — 90 мест,
 * из них 82 объявления флага и 8 условий, встроенных прямо в выражение.
 * Одно понятие с 37 определениями: смена способа адресации (скажем,
 * `/en/` вместо `-en`) правилась бы по сорока одному месту, и беда
 * родилась бы ровно на том, которое забыли.
 *
 * ПУТЬ — СПОСОБ АДРЕСАЦИИ, А НЕ СВОЙСТВО ДОКУМЕНТА. Язык страницы уже
 * объявлен в разметке — `<html lang>`: его читает браузер при переносах
 * и кавычках, диктор при выборе голоса, поисковик при выдаче. Вычислять
 * его заново из адреса — второе определение того же понятия, и худшее
 * из двух.
 *
 * ЗАМЕР 22.10: `<html lang>` стоит на 167 страницах (ru 109, en 29,
 * ky 29) и СОВПАДАЕТ с путём на всех 164 настоящих страницах сайта.
 * Три расхождения были у двух стендов-ваучеров и у `pages/admin-en.html`
 * (25 строк перенаправления, скриптов не грузит) — починены тем же
 * куском, иначе новый источник правды врал бы именно на них.
 *
 * ДВА НАПИСАНИЯ ОДНОГО ЯЗЫКА ПРИМИРЯЮТСЯ ЗДЕСЬ. В разметке стоит `ky` —
 * это верный код кыргызского по ISO 639-1; в путях и в коде исторически
 * `kg` (это код СТРАНЫ, а не языка). Дом понимает оба и наружу отдаёт
 * привычное коду `kg`, чтобы 1194 тернарника `isEn ? … : …` остались
 * работать как есть: этот кусок меняет ИСТОЧНИК, а не потребителей.
 *
 *   KSLT_YAZYK.en   → true на английской странице
 *   KSLT_YAZYK.kg   → true на кыргызской
 *   KSLT_YAZYK.ru   → true на русской
 *   KSLT_YAZYK.код  → 'ru' | 'en' | 'kg'
 *
 * ПОДКЛЮЧАЕТСЯ ПЕРВЫМ среди своих скриптов — раньше любого файла,
 * который спрашивает язык. Все скрипты продукта обычные и стоят в
 * `<body>` (замерено: 1155 тегов, ни одного defer или async), поэтому
 * порядок строгий и предсказуемый. Сторож `check-yazyk-odin-dom.js`
 * проверяет и наличие дома на странице, и то, что он стоит РАНЬШЕ.
 */
(function () {
    'use strict';

    /* НОРМАЛИЗАЦИЯ ПО ПРИСТАВКЕ, А НЕ ПО ТОЧНОМУ РАВЕНСТВУ: `lang` может
       прийти как 'en-US' или 'ky-KG' — это законные значения, и страница
       от них не перестаёт быть английской. */
    var объявлен = (document.documentElement.getAttribute('lang') || '').toLowerCase();
    var код;
    if (объявлен.indexOf('en') === 0) код = 'en';
    else if (объявлен.indexOf('ky') === 0 || объявлен.indexOf('kg') === 0) код = 'kg';
    else код = 'ru';

    var Я = {
        код: код,
        ru: код === 'ru',
        en: код === 'en',
        kg: код === 'kg'
    };

    /* ВЫБОР ПО ЯЗЫКУ ОДНИМ ЗОВОМ — для тех мест, где иначе пишется
       тернарник в тернарнике. Порядок доводов тот же, что у них:
       английский, кыргызский, русский. */
    Я.выбрать = function (en, kg, ru) {
        return код === 'en' ? en : (код === 'kg' ? kg : ru);
    };

    /* СУФФИКС СТРАНИЦЫ — одно понятие, одно определение. Русские файлы
       лежат без суффикса (`player.html`), английские и кыргызские — с
       ним (`player-en.html`, `player-kg.html`). Считалось это в 14
       местах: тринадцать звали `выбрать('-en', '-kg', '')`, а
       `session-monitor.js` читал суффикс ИЗ ПУТИ — второй способ того
       же понятия. Смена схемы адресации (скажем, `/en/player.html`)
       правилась бы по четырнадцати местам.
       ПУСТАЯ СТРОКА ЗДЕСЬ ЗАКОННА: у русского имени суффикса нет. Это
       единственное законное пустое значение выбора по языку, и потому
       оно живёт ЗДЕСЬ, а не тринадцатью пустыми ветвями в коде —
       сторож требует, чтобы ни одна ветвь зова не была пуста. */
    Я.суффикс = код === 'en' ? '-en' : (код === 'kg' ? '-kg' : '');

    /* ЛОКАЛЬ СТРАНИЦЫ — ОДНО ПОНЯТИЕ, ОДНО ОПРЕДЕЛЕНИЕ. Её спрашивают у
       браузера для дат, времени и чисел.
       КЫРГЫЗСКОМУ ОТДАЁТСЯ РУССКАЯ ЛОКАЛЬ, И ЭТО ЗАМЕР, А НЕ ЛЕНЬ.
       Замерено в браузере 23.10 (кусок 146):
         Intl.DateTimeFormat.supportedLocalesOf(['ky-KG','ky'])  →  []
         new Intl.DateTimeFormat('ky-KG').resolvedOptions().locale → 'en-US'
         (new Date(2026,9,15)).toLocaleDateString('ky-KG', …)    →  'Oct 15'
       То есть `ky-KG` молча становится АНГЛИЙСКОЙ: кыргызская страница
       печатала английские месяцы, английский порядок даты и английский
       разделитель в числах. А кусок 138 замерил и записал решением:
       сокращения месяцев и порядок даты в кыргызском ТЕ ЖЕ, ЧТО В
       РУССКОМ. Русская локаль даёт кыргызу «15 окт.» и «1 234,5» —
       то, что он и должен видеть.
       ЛОКАЛЬ, КОТОРОЙ НЕТ В БРАУЗЕРЕ, МОЛЧА СТАНОВИТСЯ АНГЛИЙСКОЙ.
       Понятие считалось в ОДИННАДЦАТИ местах (замер 23.10, кусок 147), и
       все одиннадцать отдавали кыргызу английскую раскладку. */
    Я.локаль = код === 'en' ? 'en-US' : 'ru-RU';

    window.KSLT_YAZYK = Я;
})();
