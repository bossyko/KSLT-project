/**
 * ПЛИТКА ЧИСЛА С ПОДПИСЬЮ — ОДИН ДОМ РАЗМЕТКИ (шаг A3.5, 29.10).
 *
 * ЗАМЕР 29.10. Одно понятие — «крупное число и подпись под ним» — жило в
 * продукте под СЕМЬЮ семьями имён:
 *
 *   1. `db-stat-*`  — кабинет сайта (`css/dashboard.css`, 19 правил)
 *   2. `stat-*`     — витринные цифры главной (`css/style.css:1933`)
 *   3. `stat-*`     — профиль приложения (`mobile/www/css/app.css`)
 *   4. `pd-stat-*`  — карточки игрока и тренера в приложении
 *   5. `ad-stat-*`  — админка (`js/admin/sections/loyalty.js:427`)
 *   6. `statCard()` — страница игрока сайта (`js/player.js:500`)
 *   7. склейки руками — в `dashboard.js`, `profile.js`, `app.js`
 *
 * Строителей было ЧЕТЫРЕ разных функции плюс склейки.
 *
 * ГРАНИЦУ ВЫБРАЛ Я, И ПЕРВЫЙ РАЗ ВЫБРАЛ НЕВЕРНО. Сначала я взял две
 * семьи — `db-stat-*` и `stat-*` — и, хуже того, приписал этот выбор
 * Косте. Выбор был мой, и он был мелок.
 *
 * ПРАВИЛЬНАЯ ГРАНИЦА — ПО ДАННЫМ, А НЕ ПО ВИДУ: сводится то, что
 * показывает ОДНУ И ТУ ЖЕ статистику игрока — очки, победы, поражения,
 * процент. Таких мест ЧЕТЫРЕ:
 *
 *   · кабинет сайта            `db-stat-*`   (`js/dashboard.js`)
 *   · страница игрока сайта    `statCard()`  (`js/player.js:500`)
 *   · профиль приложения       `stat-*`      (`screens/profile.js`, `app.js`)
 *   · карточка игрока прил.    `pd-stat-*`   (`screens/player-detail.js`)
 *
 * ВНЕ ГРАНИЦЫ, и это названо числом, а не «похоже-непохоже»:
 *   · витрина главной (`style.css:1933`) — другие цифры: число игроков и
 *     турниров, кегль `clamp` по ширине окна, анимация набега;
 *   · админка (`js/admin/sections/loyalty.js:427`) — плитка несёт ИКОНКУ,
 *     строение другое;
 *   · карточки тренера (`screens/coaches.js:177`) — цена и опыт, не
 *     статистика игрока, хотя носят те же `pd-stat-*`.
 * Третье соседствует с четвёртым по именам, поэтому `pd-stat-*` у
 * тренера после переезда остаётся своим понятием — это записано в трекер
 * как оставшийся долг, а не замолчано.
 *
 * ПОЧЕМУ ТРЕТЬЕ ИМЯ, А НЕ ОДНО ИЗ ДВУХ. Переименовать `db-stat-value` в
 * `stat-value` нельзя: на сайте это имя УЖЕ ЗАНЯТО витринными цифрами
 * главной (`style.css:1933` — `clamp(1.5rem, 4vw, 2.25rem)`, свой цвет,
 * анимация набега). В кабинет прилетели бы чужие правила. Обратное
 * переименование тоже ложь: приставка `db-` значит «кабинет», а в
 * приложении это профиль и карточка игрока.
 * Поэтому приставка дома своя — `kst-`, свободная в обоих продуктах
 * (проверено). Тот же приём, что у общего дома сетки с `td-`.
 *
 * ЧТО В ДОМЕ, А ЧЕГО НЕТ. В доме РАЗМЕТКА и ИМЕНА. Краска остаётся
 * каждому продукту: у кабинета свои токены и свой кегль цифры, у
 * приложения свои. Одно имя на одно понятие не значит один вид — значит
 * одно место, где вид задаётся.
 *
 * Правка этого файла правится В ДВУХ МЕСТАХ: он лежит побайтовой копией
 * в `mobile/www/js/`. Расхождение ловит сторож `check-plitki.js`.
 */
(function (global) {
    'use strict';

    var API = global.KSLT_PLITKI = {};

    /* Экранирование: дом берёт общее, если оно есть, иначе своё. Плитка
       печатает ПОДПИСЬ из словаря и ЗНАЧЕНИЕ из базы — второе человек
       вписывает сам (имя напарника, название турнира), и без
       экранирования кавычка в нём даёт обработчик. */
    function экр(s) {
        if (global.KSLT_экранировать) return global.KSLT_экранировать(s);
        return String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
            return { '&': '&amp;', '<': '&lt;', '>': '&gt;',
                     '"': '&quot;', "'": '&#39;' }[c];
        });
    }

    /**
     * Одна плитка.
     *
     * @param {string|number} значение — крупное число
     * @param {string} подпись — слово под ним
     * @param {object} [опции]
     *        опции.сдвиг — число со знаком под подписью («+3», «−1»);
     *                      ноль и пусто не рисуются вовсе, потому что
     *                      «+0» ничего не сообщает
     *        опции.сдвигКласс — класс сдвига от зовущего («up»/«down»),
     *                      когда направление решает экран, а не знак
     *                      числа: так на странице игрока сайта
     *        опции.готовоеЗначение — true, если значение УЖЕ разметка
     *                      (например, с собственным `<span>`): тогда дом
     *                      его не экранирует, и за это отвечает зовущий
     */
    API.плитка = function (значение, подпись, опции) {
        var о = опции || {};
        var h = '<div class="kst-card">' +
                '<div class="kst-value">' +
                    (о.готовоеЗначение ? значение : экр(значение)) +
                '</div>' +
                '<div class="kst-label">' + экр(подпись) + '</div>';

        var сдвиг = о.сдвиг;
        if (сдвиг !== null && сдвиг !== undefined && сдвиг !== 0 && сдвиг !== '') {
            /* Направление дом считает сам по знаку числа. Но страница
               игрока сайта приносит сдвиг УЖЕ со знаком и со своим
               классом — там направление решает зовущий, и дом за него
               не решает: `опции.сдвигКласс`. */
            var класс = о.сдвигКласс ||
                (Number(сдвиг) > 0 ? 'up' : 'down');
            var текст = о.сдвигКласс
                ? String(сдвиг)
                : (Number(сдвиг) > 0 ? '+' + сдвиг : String(сдвиг));
            h += '<div class="kst-change ' + экр(класс) + '">' +
                 экр(текст) + '</div>';
        }
        return h + '</div>';
    };

    /**
     * Сетка плиток.
     *
     * @param {string[]} плитки — готовые плитки
     * @param {object} [опции]
     *        опции.мини — вариант для сравнения по вертикали: колонки
     *                     постоянной ширины, прижаты влево
     *        опции.свой — дополнительный класс продукта
     */
    API.сетка = function (плитки, опции) {
        var о = опции || {};
        var классы = 'kst-grid' +
            (о.мини ? ' kst-grid-mini' : '') +
            (о.свой ? ' ' + о.свой : '');
        return '<div class="' + классы + '">' + (плитки || []).join('') + '</div>';
    };

    /**
     * Подпись под сеткой — та, что объясняет, что именно посчитано.
     * Живёт в доме, потому что без неё цифры выглядят враньём: в истории
     * матчей одиннадцать игр, а побед и поражений четыре.
     */
    API.подпись = function (текст) {
        return '<div class="kst-note">' + экр(текст) + '</div>';
    };

})(typeof window !== 'undefined' ? window : this);
