/**
 * ПРОСМОТРЫ — ОДИН ДОМ НА ВЕСЬ САЙТ.
 *
 * ЧТО БЫЛО, ИЗМЕРЕНО 11.11. Шесть счётчиков просмотров на сайте НЕ
 * РАБОТАЛИ ВООБЩЕ — ни один просмотр не записывался с 19 сентября.
 * Проверено живьём на несуществующих идентификаторах, чтобы ничего не
 * испортить: падали news, coach, court, player, tournament, sponsor —
 * шесть из семи.
 *
 * ПРИЧИНА. У каждой функции increment_*_view в базе ДВЕ перегрузки:
 * (p_id) и (p_id, p_source DEFAULT 'site'). Когда клиент зовёт её с одним
 * именованным аргументом, PostgREST не может выбрать, какую из двух
 * вызывать, и отвечает PGRST203 — ещё до всякой записи. Приложение звало
 * с двумя (p_source = 'app') и считалось исправно; сайт звал с одним и не
 * считался никогда. Отсюда и загадка аналитики: серия App с числами, а
 * серия Site — нули по всем шести разделам.
 *
 * То есть нули были НЕ оттого, что сайт не выложен.
 *
 * ПОЧЕМУ ДОМ, А НЕ ШЕСТЬ ПРАВОК. Шесть голых вызовов, рассыпанных по
 * шести файлам, — это шесть мест, где завтра снова забудут про источник.
 * В приложении такой дом уже есть (APP.incrementView в mobile/www/js/app.js,
 * он же гасит повторы через localStorage), а у сайта его не было.
 * ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: источник и защита от повторов живут
 * здесь, а страницы только называют, что смотрят.
 *
 *   KSLT_PROSMOTRY.считать(клиент, 'increment_court_view', { p_id: id })
 *   KSLT_PROSMOTRY.заход(клиент)
 *
 * ИСТОЧНИК НАЗЫВАЕТСЯ ЧЕСТНО. Этот файл живёт на сайте, поэтому здесь
 * всегда 'site'. Приложение грузит свою сборку и свой дом — подменять
 * источник по виду адреса или по строке браузера не нужно и нельзя:
 * ИМЯ ПРОВЕРЯЕТСЯ У ДОМА, А НЕ У ПАМЯТИ.
 */
(function (global) {
    'use strict';

    var П = {};
    var ИСТОЧНИК = 'site';

    /** Один просмотр на объект в этом браузере — как в приложении. */
    function ключ(имяRPC, параметры) {
        var хвост = [];
        for (var к in параметры) {
            if (Object.prototype.hasOwnProperty.call(параметры, к)) хвост.push(параметры[к]);
        }
        return 'kslt_view_' + имяRPC + '_' + хвост.join('_');
    }

    /* ХРАНИЛИЩЕ БРАУЗЕРА БРОСАЕТ В ЧАСТНОМ ОКНЕ, и страница обязана это
       пережить: не посчитать просмотр — не беда, уронить страницу — беда. */
    function помнит(к) {
        try { return !!localStorage.getItem(к); } catch (e) { return false; }
    }
    function запомнить(к) {
        try { localStorage.setItem(к, '1'); } catch (e) { /* живём без памяти */ }
    }

    /**
     * Засчитать просмотр объекта.
     * @param {object} клиент   — клиент supabase со страницы
     * @param {string} имяRPC   — increment_court_view и прочие
     * @param {object} параметры — { p_id: ... } или { p_news_id: ... }
     */
    П.считать = function (клиент, имяRPC, параметры) {
        if (!клиент || !имяRPC || !параметры) return;
        var к = ключ(имяRPC, параметры);
        if (помнит(к)) return;

        var полные = {};
        for (var п in параметры) {
            if (Object.prototype.hasOwnProperty.call(параметры, п)) полные[п] = параметры[п];
        }
        /* ВТОРОЙ АРГУМЕНТ — НЕ УКРАШЕНИЕ, А ЕДИНСТВЕННЫЙ СПОСОБ ПОПАСТЬ В
           ФУНКЦИЮ: без него PostgREST не выбирает между перегрузками. */
        полные.p_source = ИСТОЧНИК;

        клиент.rpc(имяRPC, полные).then(function (ответ) {
            /* ОТВЕТ БАЗЫ ПРОВЕРЯЕТСЯ, А НЕ ПРЕДПОЛАГАЕТСЯ. Прежние шесть
               вызовов молчали об ошибке, и поломка прожила два месяца. */
            if (ответ && ответ.error) {
                console.error('[просмотры] ' + имяRPC + ': ' + ответ.error.message);
                return;
            }
            запомнить(к);
        }).catch(function (e) {
            console.error('[просмотры] ' + имяRPC + ': ' + (e && e.message ? e.message : e));
        });
    };

    /**
     * Засчитать заход на сайт — один раз за сеанс.
     *
     * ЗАХОД СЧИТАЕТСЯ НА ЗАГРУЗКЕ СТРАНИЦЫ, А НЕ В ЗАГРУЗЧИКЕ СПОНСОРОВ.
     * До 11.11 единственный вызов site_visit жил в js/sponsors-loader.js —
     * то есть заход на сайт считался там, где рисуются логотипы. Карточки
     * «Заходы на сайт» и «Заходы в приложение» в аналитике показывали ноль
     * и ноль при 4866 просмотрах страниц.
     */
    П.заход = function (клиент) {
        if (!клиент) return;
        try {
            if (sessionStorage.getItem('kslt_sv')) return;
        } catch (e) { /* частное окно: посчитаем ещё раз, это не беда */ }
        клиент.rpc('increment_page_view', { p_page_name: 'site_visit' }).then(function (ответ) {
            if (ответ && ответ.error) {
                console.error('[просмотры] заход: ' + ответ.error.message);
                return;
            }
            try { sessionStorage.setItem('kslt_sv', '1'); } catch (e) {}
        }).catch(function () {});
    };

    global.KSLT_PROSMOTRY = П;
})(typeof window !== 'undefined' ? window : this);
