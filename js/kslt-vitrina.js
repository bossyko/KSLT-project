/**
 * ВИТРИНА РАЗДЕЛА — ОДНО ПОВЕДЕНИЕ НА ТРИ СТРАНИЦЫ.
 *
 * «Корты», «Тренеры» и «Партнёры» — близнецы: один список карточек, одна
 * полоса страниц, один шаг. Замер 23.10: 22 пары функций похожи, и ТРИ
 * понятия совпадали ЗНАК В ЗНАК, различаясь только именами классов:
 *
 *   · ШАГ СЕТКИ — колонок × рядов, числа читаются из живого css
 *     (`--co-ryadov` / `--ct-ryadov` / `--pt-ryadov`);
 *   · СЛЕЖЕНИЕ ЗА ШИРИНОЙ — ResizeObserver, пересчитать и перерисовать;
 *   · НАЖАТИЯ ПОЛОСЫ СТРАНИЦ — «назад», «вперёд», номер.
 *
 * ОТРИСОВКА полосы уже жила домом с 07.10 (`KSLT_полосаСтраниц`), а
 * ПОВЕДЕНИЕ осталось копиями: в дом ушла картинка, а не понятие.
 *
 * «НОВОСТИ» СЮДА НЕ ВХОДЯТ, И ЭТО ЗАМЕРЕНО, А НЕ ЗАБЫТО: у них шаг задан
 * ОДНИМ числом (`--novostey`), а не произведением колонок на ряды. Одно
 * слово «шаг» — два разных понятия; сводить их значило бы прятать
 * разницу.
 *
 * ЗАЩИТА ОТ ПОВТОРНОГО ВХОДА взята у «Новостей»: наблюдатель следит за
 * той самой коробкой, которую перерисовывает, и без сторожа перерисовка
 * вызывает наблюдателя снова. У трёх близнецов сторожа не было —
 * ПРАВИЛО, ВЫВЕДЕННОЕ НА ОДНОМ КУСКЕ, ПРИМЕНЯЕТСЯ К СЛЕДУЮЩЕМУ.
 *
 *   KSLT_VITRINA.шаг('.co-grid', '--co-ryadov')      → число или 0
 *   KSLT_VITRINA.следитьЗаШириной(коробка, приИзменении)
 *   KSLT_VITRINA.нажатияПолосы(коробка, взять, поставить, перерисовать)
 *   KSLT_VITRINA.продвинутыеПервыми(список)
 */
(function () {
    'use strict';

    var В = {};

    /**
     * Шаг страницы: сколько карточек помещается. Колонки берутся из живой
     * сетки, ряды — из своей переменной css. ЧИСЛО ЧИТАЕТСЯ ИЗ ЖИВОЙ
     * СЕТКИ, А НЕ ВЫЧИСЛЯЕТСЯ ПО ШИРИНЕ ОКНА: раскладку решает css.
     * Ноль означает «сетки нет или она ещё не разложена» — зовущий
     * оставляет прежний шаг.
     */
    В.шаг = function (селекторСетки, имяРядов) {
        var сетка = document.querySelector(селекторСетки);
        if (!сетка) return 0;
        var стиль = window.getComputedStyle(сетка);
        var колонок = стиль.gridTemplateColumns.split(' ').filter(Boolean).length;
        var рядов = parseInt(стиль.getPropertyValue(имяРядов), 10);
        if (!колонок || !рядов) return 0;
        return колонок * рядов;
    };

    /** Ширина коробки изменилась — пересчитать и перерисовать. */
    В.следитьЗаШириной = function (коробка, приИзменении) {
        if (!коробка || !window.ResizeObserver) return;
        var идёт = false;
        new ResizeObserver(function () {
            if (идёт) return;          /* перерисовка сама дёргает наблюдателя */
            идёт = true;
            try { приИзменении(); } finally { идёт = false; }
        }).observe(коробка);
    };

    /**
     * Нажатия полосы страниц. Номер страницы живёт У ЗОВУЩЕГО: дом не
     * заводит своей копии состояния, иначе у двух списков на одной
     * странице он был бы общим.
     */
    /* СВЕДЕНО КУСКОМ 149: тело переехало в дом полосы страниц —
       `js/polosa-stranic.js`, туда же, где полоса рисуется. Здесь остался
       переходник: три витрины зовут его прежним доводом, и менять их не
       пришлось. КЛЮЧ ОТЛИЧАЕТ ПОЛОСЫ НА ОДНОЙ ОБЛАСТИ: у витрин слушатель
       стоит на `document`, и на странице со двумя витринами вторая иначе
       потерялась бы молча. */
    В.нажатияПолосы = function (коробка, взять, поставить, перерисовать) {
        if (!window.KSLT_полосаСтраниц || !window.KSLT_полосаСтраниц.нажатия) return;
        window.KSLT_полосаСтраниц.нажатия({
            ключ: 'витрина:' + ((коробка && коробка.id) || 'без-имени'),
            область: document,
            взять: взять,
            поставить: поставить,
            перерисовать: перерисовать,
            кСписку: function () { return коробка; }
        });
    };

    /**
     * Продвинутые первыми, остальные вперемешку. Перемешивание —
     * Фишер — Йетс: при равных условиях никто не стоит первым всегда.
     */
    В.продвинутыеПервыми = function (список) {
        var вперёд = [], остальные = [];
        for (var i = 0; i < список.length; i++) {
            if (список[i]._promoted) вперёд.push(список[i]);
            else остальные.push(список[i]);
        }
        for (var j = остальные.length - 1; j > 0; j--) {
            var k = Math.floor(Math.random() * (j + 1));
            var врем = остальные[j];
            остальные[j] = остальные[k];
            остальные[k] = врем;
        }
        return вперёд.concat(остальные);
    };

    window.KSLT_VITRINA = В;
    /* ======================================================================
       ДОБАВЛЕНО КУСКОМ 144 — ОСТАТОК БЛИЗНЕЦОВ.
       Замер: у `coaches.js` и `courts.js` 21 пара с общим именем плюс ТРИ,
       которых прибор не видел из-за имён (`coCtaLoadServices` против
       `ctaLoadServices`): ИМЯ У КОПИИ МОЖЕТ БЫТЬ ЛЮБЫМ, сравнивать надо
       тела. У перечисленного ниже расхождение было ТОЛЬКО в приставке
       класса (`co-` против `ct-`), в имени словаря (`L` против
       `L_labels`) и в текстах.
       ПРИСТАВКА ОСТАЁТСЯ ДОВОДОМ, А НЕ СВОДИТСЯ: css у разделов свой, и
       сведение имён классов — правка вёрстки с видимым риском, а не
       сведение поведения. Решается отдельно и глазами.
       ====================================================================== */

    /**
     * ПОЯВЛЕНИЕ ПРИ ПРОКРУТКЕ. Наблюдатель один на раздел; элементы ищутся
     * по приставке раздела.
     * ЗАМЕРЕНО ПРИБОРОМ, А НЕ ПО ПАМЯТИ: наблюдателей ИМЕННО ЭТОГО вида
     * (`-fade-in:not(.visible)`) было ТРИ — близнецы и `player.js`.
     * Сведены два; `player.js` остался один и держится храповиком. Слово
     * `visible` трогают девять файлов, но по другим поводам — и это
     * разные понятия, а не копии.
     */
    В.появление = function (приставка) {
        var н = new IntersectionObserver(function (записи) {
            записи.forEach(function (з) {
                if (з.isIntersecting) з.target.classList.add('visible');
            });
        }, { threshold: 0.1 });
        document.querySelectorAll('.' + приставка + '-fade-in:not(.visible)')
            .forEach(function (эл) { н.observe(эл); });
        return н;
    };

    /**
     * ПЕРЕСЧЁТ ШАГА СТРАНИЦЫ. Колонки известны только ПОСЛЕ раскладки,
     * поэтому шаг считается из живой сетки, а не из ширины окна.
     * Число живёт у зовущего: дом его СПРАШИВАЕТ и ОТДАЁТ, а не хранит.
     *
     * ОТДАЁТСЯ ФУНКЦИЯ, А НЕ СТАВИТСЯ НАБЛЮДАТЕЛЬ, и это не красивость:
     * первая запись куска 144 заводила пересчёт ВНУТРИ слежения, а
     * `renderGrid` зовёт его РАНЬШЕ — на первой же отрисовке вышло бы
     * «пересчитатьШаг не функция». Поймано сторожем мёртвого кода и
     * чтением порядка зовов, а не браузером.
     */
    В.пересчётШага = function (о) {
        return function () {
            var шаг = В.шаг(о.селектор, о.ряды);
            if (!шаг || шаг === о.взять()) return false;
            о.поставить(шаг);
            return true;
        };
    };

    /**
     * ПОЛЕ ПОИСКА. Отличие близнецов было ровно в одном зове после
     * перерисовки (у кортов обновляются выпадашки) — он стал крючком.
     */
    В.поиск = function (полеId, поставить, перерисовать, после) {
        var поле = document.getElementById(полеId);
        if (!поле) return;
        поле.addEventListener('input', function () {
            поставить(поле.value.trim());
            перерисовать();
            if (после) после();
        });
    };

    /**
     * ОБЛОЖКА РАЗДЕЛА. Разметка одна, разное — приставка, картинка и два
     * текста. Название без лаймовой подсветки: заголовки разделов белые.
     * ЗАМЕРЕНО: мест, рисующих обложку, девятнадцать в двенадцати файлах;
     * у них разный СОСТАВ (фото, адрес, счётчики), поэтому сведены только
     * два списочных у близнецов, а остальные семнадцать под храповиком.
     */
    В.обложка = function (коробка, о) {
        if (!коробка) return;
        коробка.innerHTML =
            '<div class="' + о.приставка + '-hero-bg" style="background-image: url(\'' +
                о.картинка + '\')"></div>' +
            '<div class="' + о.приставка + '-hero-content">' +
                '<h1 class="' + о.приставка + '-hero-title">' + о.заголовок + '</h1>' +
                '<p class="' + о.приставка + '-hero-subtitle">' + о.подзаголовок + '</p>' +
            '</div>';
    };

    /* ОТСТУП ЛИПКОСТИ. 65 — это высота шапки (64) плюс один: наблюдатель
       должен сработать, когда полоса ПОДОШЛА под шапку, а не когда
       коснулась её. Число взято ЗАМЕРЕННОЕ, из кода всех восьми копий;
       перевод его на `--header-h` меняет порог на пиксель и потому решается
       отдельно, а не заодно. */
    var ОТСТУП_ЛИПКОСТИ = '-65px 0px 0px 0px';

    /**
     * ЛИПКОСТЬ ПОЛОСЫ ФИЛЬТРОВ: метка `stuck`, когда полоса подошла под
     * шапку. Сторож ставится ПЕРЕД полосой, а не внутри.
     * ЗАМЕРЕНО: мест с этой меткой было ВОСЕМЬ. Сведены два, шесть
     * остались и держатся храповиком: обзор баттлов, партнёры, игроки,
     * услуги, наложение турниров и обзор турниров.
     */
    В.липнетПолоса = function (полоса) {
        if (!полоса || !полоса.parentNode) return;
        var сторож = document.createElement('div');
        сторож.style.height = '1px';
        полоса.parentNode.insertBefore(сторож, полоса);
        var н = new IntersectionObserver(function (записи) {
            полоса.classList.toggle('stuck', !записи[0].isIntersecting);
        }, { threshold: [1], rootMargin: ОТСТУП_ЛИПКОСТИ });
        н.observe(сторож);
        return н;
    };

    /**
     * ЧЛЕНСКОЕ ОКНО. Гостю — регистрация, вошедшему без членства — тарифы.
     * Разное у близнецов было только в приставке и в двух текстах.
     */
    В.членскоеОкно = function (класс, уровень, текст) {
        var гость = уровень === 'guest';
        var ссылка = гость
            ? KSLT_YAZYK.выбрать('auth-en.html', 'auth-kg.html', 'auth.html')
            : KSLT_YAZYK.выбрать('pricing-en.html', 'pricing-kg.html', 'pricing.html');
        var заголовок = гость
            ? KSLT_YAZYK.выбрать('Become a KSLT Member', 'KSLT мүчөсү болуңуз', 'Станьте членом KSLT')
            : KSLT_YAZYK.выбрать('Membership Required', 'Мүчөлүк керек', 'Нужно членство');
        var кнопка = гость
            ? KSLT_YAZYK.выбрать('Sign Up', 'Каттоо', 'Регистрация')
            : KSLT_YAZYK.выбрать('View Plans', 'Тарифтар', 'Тарифы');
        var значок = гость
            ? '<svg width="48" height="48" viewBox="0 0 24 24" fill="none" stroke="var(--accent)" stroke-width="1.5"><path d="M20 21v-2a4 4 0 0 0-4-4H8a4 4 0 0 0-4 4v2"/><circle cx="12" cy="7" r="4"/></svg>'
            : '<svg width="48" height="48" viewBox="0 0 24 24" fill="none" stroke="var(--accent)" stroke-width="1.5"><path d="M12 2l3.09 6.26L22 9.27l-5 4.87 1.18 6.88L12 17.77l-6.18 3.25L7 14.14 2 9.27l6.91-1.01L12 2z"/></svg>';

        /* ИМЕНА КЛАССОВ ПРИХОДЯТ ЦЕЛИКОМ, И НЕ СКЛЕИВАЮТСЯ ВОВСЕ. Первая
           запись куска склеивала их из приставки `'co'` — и десять живых
           классов разом стали «мёртвыми» для сторожа: он признаёт
           склеенный класс живым только по префиксу из ДВУХ сегментов,
           стоящему в js. Это не придирка прибора, а то же правило, что и
           у людей: КЛАСС, КОТОРОГО НЕТ В КОДЕ ЦЕЛИКОМ, НЕ НАХОДИТСЯ
           ПОИСКОМ. Поэтому зовущий передаёт пять имён как есть. */
        var подложка = document.createElement('div');
        подложка.className = класс.подложка;
        подложка.innerHTML =
            '<div class="' + класс.окно + '">' +
                '<button class="' + класс.закрыть + '">&times;</button>' +
                '<div class="' + класс.значок + '">' + значок + '</div>' +
                '<h3>' + заголовок + '</h3>' +
                '<p>' + (гость ? текст.гостю : текст.безЧленства) + '</p>' +
                '<a href="' + ссылка + '" class="' + класс.кнопка + '">' + кнопка + '</a>' +
            '</div>';

        document.body.appendChild(подложка);
        requestAnimationFrame(function () { подложка.classList.add('visible'); });

        function закрыть() {
            подложка.classList.remove('visible');
            setTimeout(function () { подложка.remove(); }, 300);
        }
        подложка.querySelector('.' + класс.закрыть).onclick = закрыть;
        подложка.addEventListener('click', function (e) { if (e.target === подложка) закрыть(); });
        return подложка;
    };

    /**
     * НАЖАТИЕ КНОПКИ НА КАРТОЧКЕ. Гостю и вошедшему без членства —
     * членское окно; члену — то, что решит зовущий (ваучер).
     * У близнецов отличие было в написании: один `if` со связкой против
     * двух подряд. ПОВЕДЕНИЕ БЫЛО ОДНО И ТО ЖЕ — проверено по дереву.
     */
    В.нажатияКарточки = function (сеткаId, селекторКнопки, уровень, члену, окно) {
        var сетка = document.getElementById(сеткаId);
        if (!сетка) return;
        сетка.addEventListener('click', function (e) {
            var кнопка = e.target.closest(селекторКнопки);
            if (!кнопка) return;
            e.preventDefault();
            e.stopPropagation();
            var где = уровень();
            if (где === 'guest' || где === 'registered') { окно(где); return; }
            члену(кнопка, кнопка.getAttribute('data-id'));
        });
    };

})();
