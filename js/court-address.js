/**
 * КСЛТ — адрес корта: одно определение на одно понятие.
 *
 * До этого файла адрес собирался в коде ТРИЖДЫ, и все три состава были
 * разные — замерено 28.09:
 *   js/courts.js:435          улица · дом · город
 *   js/services.js:272        улица · дом · район          (без города)
 *   js/tournament-detail.js   улица · дом · город          (без района)
 * Один и тот же корт показывался тремя разными строками на трёх страницах
 * сайта. Беда родится ровно на таком шве.
 *
 * СОСТАВ ОДИН: улица · дом · город · страна.
 * Район выброшен намеренно: он был только в витрине услуг, длинный
 * («Иссык-Кульский район») и повторяет город. Город важнее и теперь есть
 * везде.
 *
 * СТРАНА — ТОЛЬКО ЧУЖАЯ. Клуб играет в Кыргызстане, и «…, Бишкек,
 * Кыргызстан» на каждом из тридцати одного корта — шум. Страна отличает
 * ровно тогда, когда турнир в Алматы.
 */
(function() {
    'use strict';

    var СВОЯ_СТРАНА = 'Кыргызстан';

    /**
     * Кириллица → латиница. Живёт здесь, а не в админке, потому что нужен
     * публичной странице: номер дома пишется «97Б», и без транслита в
     * английском адресе стоит кириллическая Б. Админка берёт эту же
     * функцию через A.transliterate — второго определения нет.
     */
    var БУКВЫ = {'а':'a','б':'b','в':'v','г':'g','д':'d','е':'e','ё':'yo','ж':'zh',
        'з':'z','и':'i','й':'y','к':'k','л':'l','м':'m','н':'n','о':'o','п':'p',
        'р':'r','с':'s','т':'t','у':'u','ф':'f','х':'kh','ц':'ts','ч':'ch','ш':'sh',
        'щ':'shch','ъ':'','ы':'y','ь':'','э':'e','ю':'yu','я':'ya',
        /* кыргызские: без них «Ысык-Көл» выходил «Ysyk-Kөl» */
        'ө':'o','ү':'u','ң':'ng'};

    function транслит(текст) {
        return (текст || '').split('').map(function(ч) {
            var мал = ч.toLowerCase();
            var зам = БУКВЫ[мал];
            if (зам === undefined) return ч;
            if (зам === '') return '';
            return ч !== мал ? зам.charAt(0).toUpperCase() + зам.slice(1) : зам;
        }).join('');
    }

    /** Значение поля на нужном языке с откатом на русское */
    function наЯзыке(корт, поле, язык) {
        if (!корт) return '';
        var свой = язык === 'ru' ? null : корт[поле + '_' + (язык === 'kg' ? 'kg' : 'en')];
        return ((свой || корт[поле] || '') + '').trim();
    }

    /**
     * @param {Object} корт — строка таблицы courts
     * @param {string} [язык] — 'ru' | 'en' | 'kg'; без него берётся русский
     * @returns {string} адрес одной строкой
     */
    function адрес(корт, язык) {
        var я = язык || 'ru';
        var части = [];
        var улица = наЯзыке(корт, 'street', я);
        var дом = (корт && корт.building || '').toString().trim();
        /* Дом — отдельный столбец, языка не имеет: «97Б», «4а», «1г».
           Кириллическая буква в номере на английской версии — ровно то,
           что человек не сможет ни прочитать, ни набрать */
        if (я === 'en') дом = транслит(дом);
        /* В английском адресе номер дома стоит ПЕРЕД улицей и без запятой:
           «2/4 Isy Akhunbaeva St». Русский и кыргызский пишут наоборот —
           оба кириллицей, порядок у них один */
        if (я === 'en' && улица && дом) {
            части.push(дом + ' ' + улица);
        } else {
            if (улица) части.push(улица);
            if (дом) части.push(дом);
        }
        var город = наЯзыке(корт, 'city', я);
        if (город) части.push(город);
        var страна = (корт && корт.country || '').trim();
        if (страна && страна !== СВОЯ_СТРАНА) {
            части.push(я === 'ru' ? страна : ((корт.country_en || страна) + ''));
        }
        return части.join(', ');
    }

    window.KSLT_ADDRESS = { адрес: адрес, транслит: транслит, СВОЯ_СТРАНА: СВОЯ_СТРАНА };
})();
