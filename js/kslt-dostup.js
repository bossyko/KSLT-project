/**
 * УРОВЕНЬ ДОСТУПА — ОДИН НА ВЕСЬ САЙТ.
 *
 * ЧТО БЫЛО: один вопрос — «гость, зарегистрированный или член клуба?» —
 * и ПЯТЬ ответов на него. `coaches.js` и `courts.js` держали копию знак
 * в знак; `players.js` — свою, покороче; `player.js` — свою, с запросом
 * своей карточки; `partners.js` звал готовый дом в `invite-player.js`.
 *
 * ПЯТЬ КОПИЙ ОДНОГО ПОНЯТИЯ РАЗОШЛИСЬ, И ВОТ ЧЕМ (замер 23.10):
 *   · дом в `invite-player.js` считает АДМИНА И МЕНЕДЖЕРА членом клуба —
 *     остальные четыре не считали, и админ видел на «Кортах» ограничения
 *     гостя;
 *   · дом помнит ответ на всю жизнь страницы — остальные спрашивали базу
 *     заново при каждом зове;
 *   · дом заодно достаёт СВОЮ карточку игрока (чтобы не приглашать самого
 *     себя) — это делал ещё `player.js`, двое других нет.
 *
 * ЗДЕСЬ ЖИВЁТ ПОВЕДЕНИЕ ДОМА — самое полное из пяти. Разница названа
 * вслух, а не растворена: переход на него ДАЁТ админу и менеджеру
 * членский доступ на страницах кортов, тренеров, игроков и игрока.
 *
 * `window.ksltUser` дом НЕ ставит, и это замерено, а не забыто:
 * `membership.js:74` заполняет его сам, если его нет.
 *
 *   KSLT_DOSTUP.уровень()    → 'guest' | 'registered' | 'member'
 *   KSLT_DOSTUP.мойИгрок()   → id своей карточки игрока или null
 *
 * ПОДКЛЮЧАЕТСЯ РАНЬШЕ своих потребителей — как и дом языка.
 */
(function () {
    'use strict';

    var _уровень = null;   // 'guest' | 'registered' | 'member'
    var _мойИгрок = null;

    var Д = {};

    /**
     * Уровень доступа. СЧИТАЕТСЯ ОДИН РАЗ ЗА ЖИЗНЬ СТРАНИЦЫ: запрос к базе
     * на каждое нажатие ни к чему, а ответ за время просмотра не меняется.
     */
    Д.уровень = async function () {
        if (_уровень) return _уровень;
        var client = window.supabaseClient;
        var вошёл = false;
        if (client) {
            try {
                var сессия = await client.auth.getSession();
                if (сессия.data && сессия.data.session) вошёл = true;
            } catch (e) {}
        }
        if (!вошёл) { _уровень = 'guest'; return _уровень; }

        _уровень = 'registered';
        try {
            var uid = (await client.auth.getUser()).data.user.id;
            var профиль = await client.from('profiles').select('role, player_id').eq('id', uid).single();
            if (профиль.data) _мойИгрок = профиль.data.player_id || null;
            /* АДМИН И МЕНЕДЖЕР — ЧЛЕНЫ КЛУБА ПО ДОЛЖНОСТИ: им нечего
               показывать в урезанном виде, они и так видят всё в админке. */
            if (профиль.data && (профиль.data.role === 'admin' || профиль.data.role === 'manager')) {
                _уровень = 'member';
                return _уровень;
            }
        } catch (e) {}

        if (typeof window.checkMembership === 'function') {
            try {
                var членство = await window.checkMembership();
                if (членство && членство.active) _уровень = 'member';
            } catch (e) {}
        }
        return _уровень;
    };

    /** Своя карточка игрока — чтобы не приглашать и не вызывать самого себя. */
    Д.мойИгрок = function () { return _мойИгрок; };

    window.KSLT_DOSTUP = Д;
})();
