/**
 * ПОИСК КАРТОЧКИ ИГРОКА — ОДИН ДОМ НА ПРОДУКТ.
 *
 * ЗАЧЕМ ОН ЗАВЕДЁН (13.11). Искать карточку по имени умели в двух местах
 * и по-разному: кабинет — своей обратной раскладкой («Dolgushin» →
 * «Долгушин»), а админка не умела вовсе: форма пользователя могла только
 * СОЗДАТЬ новую карточку, уникализируя имя суффиксом «-2». Так и рождались
 * дубли: у Атаханова старая карточка звалась `daniyar-atahanov`, новая
 * пришла как `daniyar-atakhanov` — совпадения нет, вторая завелась молча.
 *
 * Корень (ключ имени в `ensure-player-card`) починен в тот же день, но
 * второй заслон нужен: чужая транскрипция, смена фамилии, опечатка в базе.
 * Чтобы заслон был ОДИН, а не третьим написанием, поиск живёт здесь.
 *
 *   KSLT_KARTOCHKA.обратно('Dolgushin')  → 'долгушин'
 *   await KSLT_KARTOCHKA.искать(client, { строка, пол, предел })
 *
 * ЗАНЯТЫЕ КАРТОЧКИ НЕ ПОКАЗЫВАЮТСЯ ВОВСЕ: `has_account` стоит у тех, за
 * кем уже есть учётная запись. Предложить занятую — значит предложить
 * чужую.
 */
(function () {
    'use strict';

    var К = {};

    /* ОБРАТНАЯ РАСКЛАДКА. Через Google имя приходит латиницей, а карточки
       в базе кириллицей. Пары разбираются ДО одиночных букв: иначе «sh»
       распалось бы на «с» и «h». */
    var ЛАТ = { a: 'а', b: 'б', v: 'в', g: 'г', d: 'д', e: 'е', z: 'з', i: 'и', y: 'й',
                k: 'к', l: 'л', m: 'м', n: 'н', o: 'о', p: 'п', r: 'р', s: 'с', t: 'т',
                u: 'у', f: 'ф', h: 'х', c: 'ц' };
    var ПАРЫ = [['shch', 'щ'], ['sch', 'щ'], ['dzh', 'дж'], ['sh', 'ш'], ['ch', 'ч'],
                ['zh', 'ж'], ['ts', 'ц'], ['yu', 'ю'], ['ya', 'я'], ['yo', 'ё'],
                ['kh', 'х'], ['ee', 'и']];

    /**
     * Латиница → кириллица. Не перевод, а догадка о написании: ею ищут,
     * а не подменяют данные.
     * @param {string} строка
     * @returns {string|null} null, если латиницы нет вовсе
     */
    К.обратно = function (строка) {
        var т = String(строка || '').toLowerCase();
        if (!/[a-z]/.test(т)) return null;
        ПАРЫ.forEach(function (п) { т = т.split(п[0]).join(п[1]); });
        return т.replace(/[a-z]/g, function (ч) { return ЛАТ[ч] || ч; });
    };

    /**
     * Найти свободные карточки по куску имени.
     *
     * @param {Object} client — клиент Supabase зовущего
     * @param {Object} опции
     *   строка  — что набрали
     *   пол     — 'men' | 'women' | пусто; пустой НЕ сужает
     *   предел  — сколько вернуть, по умолчанию 8
     * @returns {Promise<Array>} карточки, пустой массив при отказе базы
     */
    К.искать = async function (client, опции) {
        опции = опции || {};
        var строка = String(опции.строка || '').trim();
        if (!client || строка.length < 2) return [];

        var запрос = client.from('players')
            .select('id, name, category_id, points, ntrp_singles, ntrp_doubles, photo, gender')
            .eq('is_guest', false)
            .eq('has_account', false)
            .limit(опции.предел || 8);

        /* ПОЛ СУЖАЕТ ПОИСК ТОЛЬКО КОГДА ОН ИЗВЕСТЕН. В кабинете человек
           ищет СЕБЯ, и имена в Кыргызстане часто звучат одинаково у мужчин
           и женщин — без отбора в списке «кажется, это вы» оказывались
           чужие. В админке пол карточки может быть неизвестен, и тогда
           сужать нечем. */
        if (опции.пол === 'men' || опции.пол === 'women') запрос = запрос.eq('gender', опции.пол);

        var кириллица = К.обратно(строка);
        var рез = await (кириллица
            ? запрос.or('name.ilike.%' + строка + '%,name.ilike.%' + кириллица + '%')
            : запрос.ilike('name', '%' + строка + '%'));

        return рез.data || [];
    };

    window.KSLT_KARTOCHKA = К;
})();
