/**
 * Места в группе — один расчёт на всю платформу
 * ==============================================
 *
 * Таблицу группы показывают в трёх местах: админка, страница турнира и
 * приложение. Считали её везде по-своему: в админке по правилам ITF, а на
 * странице и в приложении просто по числу побед. Из-за этого при равенстве
 * менеджер видел один порядок, а игрок — другой.
 *
 * Здесь один расчёт для всех: победы, сеты, геймы и место. Кто как встал,
 * решается в таком порядке:
 *
 *   1. Победы.
 *   2. Равны двое — личная встреча. Кто выиграл очно, тот и выше.
 *   3. Равны трое и больше — мини-турнир между ними: победы внутри круга,
 *      доля сетов, доля геймов.
 *   4. Двое, чью очную встречу счёт не решает (снятие, неявка) — доля сетов,
 *      затем доля геймов.
 *
 * Когда всё сошлось до последней цифры, место помечается признаком `жребий`:
 * система не рассудила, порядок определяется жеребьёвкой.
 *
 * Файл ни от чего не зависит и подключается до тех, кто им пользуется.
 */
(function(global) {
    'use strict';

    var ИСХОДЫ = ['RET', 'W/O', 'DEF', 'NA'];

    // Отделяем сеты от пометки об исходе: «6/3 4/6 RET» → сеты и RET
    function разобратьСчёт(score) {
        if (!score || score === 'BYE') return { сеты: score || '', исход: '' };
        var части = String(score).split(' ');
        var исход = '';
        if (части.length > 0 && ИСХОДЫ.indexOf(части[части.length - 1]) !== -1) {
            исход = части.pop();
        }
        return { сеты: части.join(' '), исход: исход };
    }

    // Сеты и геймы одной стороны матча
    function сетыИГеймы(score, playerId, match) {
        var итог = { setsWon: 0, setsLost: 0, gamesWon: 0, gamesLost: 0 };
        if (!score || score === 'BYE') return итог;

        var первый = match.player1_id === playerId;
        var разбор = разобратьСчёт(score);
        (разбор.сеты ? разбор.сеты.split(' ') : []).forEach(function(сет) {
            var ч = сет.match(/^(\d+)\/(\d+)/);
            if (!ч) return;
            var свои = первый ? +ч[1] : +ч[2];
            var чужие = первый ? +ч[2] : +ч[1];
            итог.gamesWon += свои;
            итог.gamesLost += чужие;
            if (свои > чужие) итог.setsWon++;
            else итог.setsLost++;
        });
        return итог;
    }

    function найтиМатч(matches, p1Id, p2Id) {
        for (var i = 0; i < matches.length; i++) {
            var m = matches[i];
            if ((m.player1_id === p1Id && m.player2_id === p2Id) ||
                (m.player1_id === p2Id && m.player2_id === p1Id)) {
                return m;
            }
        }
        return null;
    }

    /**
     * Кто выиграл матч: сперва по счёту, и только потом по отметке.
     *
     * В таблице показаны цифры, и человек считает победы по ним. Если
     * отметка победителя разошлась со счётом — а такое случалось, пока окно
     * ввода переворачивало цифры не в ту сторону, — в колонке «П» появлялась
     * победа у того, у кого 3:6, и места вставали неверно.
     *
     * Отметка решает там, где счёт не решает: снятие, неявка, отказ — или
     * когда сеты поровну.
     */
    function ктоВыиграл(m) {
        if (!m) return null;
        if (/[A-Za-zА-Яа-я]/.test(String(m.score || ''))) return m.winner_id;

        var сетовП1 = 0, сетовП2 = 0;
        String(m.score || '').split(' ').forEach(function(сет) {
            var ч = сет.match(/^(\d+)\/(\d+)/);
            if (!ч) return;
            if (+ч[1] > +ч[2]) сетовП1++;
            else if (+ч[2] > +ч[1]) сетовП2++;
        });
        if (сетовП1 > сетовП2) return m.player1_id;
        if (сетовП2 > сетовП1) return m.player2_id;
        return m.winner_id;
    }

    function доляСетов(с) { var всего = с.setsWon + с.setsLost; return всего ? с.setsWon / всего : 0; }
    function доляГеймов(с) { var всего = с.gamesWon + с.gamesLost; return всего ? с.gamesWon / всего : 0; }

    /**
     * Чем развели равных — по этому же порядку и объясняем в таблице.
     *
     * Смотрим на соседа по кругу равенства: первое, чем строки отличаются,
     * и есть причина их порядка. У последней строки сосед сверху.
     */
    function отметитьПричину(круг, признаки) {
        for (var i = 0; i < круг.length; i++) {
            var сосед = круг[i + 1] || круг[i - 1];
            if (!сосед) continue;

            for (var п = 0; п < признаки.length; п++) {
                if (признаки[п].значение(круг[i]) !== признаки[п].значение(сосед)) {
                    круг[i].причина = признаки[п].имя;
                    break;
                }
            }
        }
    }

    /**
     * Полное равенство — места разыграны жребием.
     *
     * Когда победы, сеты и геймы сошлись до последней цифры, порядок строк
     * ничем не обоснован: он просто повторяет порядок в массиве. Так бывает
     * в круге из трёх при формате в один сет — каждый обыграл одного и
     * проиграл одному с одинаковым счётом. По правилам ITF в этой точке
     * бросают жребий, поэтому помечаем такие места: менеджер видит, что
     * система их не рассудила, и ставит по итогу жеребьёвки.
     */
    function пометитьЖребий(круг, ключ) {
        for (var i = 0; i < круг.length; i++) {
            var свой = ключ(круг[i]);
            var совпалСоседний =
                (i > 0 && ключ(круг[i - 1]) === свой) ||
                (i < круг.length - 1 && ключ(круг[i + 1]) === свой);
            if (совпалСоседний) круг[i].жребий = true;
        }
    }

    // Двое, чью очную встречу счёт не решил: доля сетов, затем доля геймов
    function поДолям(круг, первоеМесто) {
        круг.sort(function(a, b) {
            if (доляСетов(b) !== доляСетов(a)) return доляСетов(b) - доляСетов(a);
            return доляГеймов(b) - доляГеймов(a);
        });

        отметитьПричину(круг, [
            { имя: 'сеты', значение: доляСетов },
            { имя: 'геймы', значение: доляГеймов }
        ]);
        пометитьЖребий(круг, function(с) {
            return доляСетов(с) + '|' + доляГеймов(с);
        });

        for (var k = 0; k < круг.length; k++) круг[k].place = первоеМесто + k;
    }

    // Трое и больше: считаем заново только их встречи между собой
    function поМиниТурниру(круг, сыгранные, первоеМесто) {
        var свои = круг.map(function(с) { return с.playerId; });
        var междуСвоими = сыгранные.filter(function(m) {
            return свои.indexOf(m.player1_id) !== -1 && свои.indexOf(m.player2_id) !== -1;
        });

        var показатели = {};
        свои.forEach(function(pid) {
            показатели[pid] = { wins: 0, setsWon: 0, setsLost: 0, gamesWon: 0, gamesLost: 0 };
        });

        междуСвоими.forEach(function(m) {
            var победитель = ктоВыиграл(m);
            if (показатели[победитель]) показатели[победитель].wins++;

            [m.player1_id, m.player2_id].forEach(function(pid) {
                if (!показатели[pid]) return;
                var сг = сетыИГеймы(m.score, pid, m);
                показатели[pid].setsWon += сг.setsWon;
                показатели[pid].setsLost += сг.setsLost;
                показатели[pid].gamesWon += сг.gamesWon;
                показатели[pid].gamesLost += сг.gamesLost;
            });
        });

        круг.sort(function(a, b) {
            var са = показатели[a.playerId], сб = показатели[b.playerId];
            if (сб.wins !== са.wins) return сб.wins - са.wins;
            if (доляСетов(сб) !== доляСетов(са)) return доляСетов(сб) - доляСетов(са);
            return доляГеймов(сб) - доляГеймов(са);
        });

        отметитьПричину(круг, [
            { имя: 'между собой', значение: function(с) { return показатели[с.playerId].wins; } },
            { имя: 'сеты', значение: function(с) { return доляСетов(показатели[с.playerId]); } },
            { имя: 'геймы', значение: function(с) { return доляГеймов(показатели[с.playerId]); } }
        ]);
        пометитьЖребий(круг, function(с) {
            var п = показатели[с.playerId];
            return п.wins + '|' + доляСетов(п) + '|' + доляГеймов(п);
        });

        for (var k = 0; k < круг.length; k++) круг[k].place = первоеМесто + k;
    }

    /**
     * Показатели и места всех участников группы.
     *
     * playerIds — кто в группе, groupMatches — её матчи. Возвращает массив
     * в порядке мест: playerId, wins, losses, setsWon/Lost, gamesWon/Lost,
     * place, seed и признак жребий.
     */
    function расчёт(playerIds, groupMatches) {
        var показатели = {};
        playerIds.forEach(function(pid) {
            показатели[pid] = {
                playerId: pid,
                wins: 0,
                losses: 0,
                setsWon: 0,
                setsLost: 0,
                gamesWon: 0,
                gamesLost: 0,
                place: 0,
                жребий: false,
                причина: '',
                seed: null
            };
        });

        groupMatches.forEach(function(m) {
            if (m.seed1 && показатели[m.player1_id]) показатели[m.player1_id].seed = m.seed1;
            if (m.seed2 && показатели[m.player2_id]) показатели[m.player2_id].seed = m.seed2;
        });

        var сыгранные = groupMatches.filter(function(m) {
            return m.status === 'completed' && m.winner_id && m.score && m.score !== 'BYE';
        });

        сыгранные.forEach(function(m) {
            var победитель = ктоВыиграл(m);
            if (показатели[победитель]) показатели[победитель].wins++;
            var проигравший = победитель === m.player1_id ? m.player2_id : m.player1_id;
            if (показатели[проигравший]) показатели[проигравший].losses++;

            [m.player1_id, m.player2_id].forEach(function(pid) {
                if (!показатели[pid]) return;
                var сг = сетыИГеймы(m.score, pid, m);
                показатели[pid].setsWon += сг.setsWon;
                показатели[pid].setsLost += сг.setsLost;
                показатели[pid].gamesWon += сг.gamesWon;
                показатели[pid].gamesLost += сг.gamesLost;
            });
        });

        var строки = playerIds.map(function(pid) { return показатели[pid]; });
        строки.sort(function(a, b) { return b.wins - a.wins; });

        var место = 1;
        var i = 0;
        while (i < строки.length) {
            var j = i;
            while (j < строки.length && строки[j].wins === строки[i].wins) j++;
            var круг = строки.slice(i, j);

            if (круг.length === 1) {
                круг[0].place = место;
            } else if (круг.length === 2) {
                var очная = найтиМатч(сыгранные, круг[0].playerId, круг[1].playerId);
                var кто = ктоВыиграл(очная);
                if (очная && кто) {
                    var первый = кто === круг[0].playerId ? 0 : 1;
                    круг[первый].place = место;
                    круг[1 - первый].place = место + 1;
                    круг[0].причина = 'встреча';
                    круг[1].причина = 'встреча';
                } else {
                    поДолям(круг, место);
                }
            } else {
                поМиниТурниру(круг, сыгранные, место);
            }

            место += круг.length;
            i = j;
        }

        строки.sort(function(a, b) { return a.place - b.place; });
        return строки;
    }

    global.KSLT_GROUPS = {
        расчёт: расчёт,
        ктоВыиграл: ктоВыиграл,
        найтиМатч: найтиМатч,
        сетыИГеймы: сетыИГеймы,
        разобратьСчёт: разобратьСчёт
    };
})(typeof window !== 'undefined' ? window : this);
