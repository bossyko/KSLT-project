/**
 * Очки рейтинга: одно правило на все турниры.
 *
 * Раньше очки считались по стадии — выиграл турнир столько, дошёл до
 * полуфинала столько. В Положении клуба иначе: платит занятое место, и
 * мест больше, чем стадий. Третье и четвёртое различаются, пятое и
 * шестое тоже, а по стадиям оба полуфиналиста одинаковы.
 *
 * Считается в трёх местах — олимпийка, группы, сетка всех мест, — и
 * правило должно быть одно. Поэтому оно здесь, а не в каждой из них.
 *
 * Источник цифр: Приложение 2 к Положению КСЛТ 2021, таблица лежит в
 * базе (`points_by_place`) и в docs/.
 */
(function(global) {
    'use strict';

    var ЗА_ПОБЕДУ = 25;      // за каждую выигранную встречу в группе
    var ЗА_УЧАСТИЕ = 10;     // тому, кто не выиграл ни одной

    /**
     * Сноска Положения (стр. 11): если места внутри двойки, четвёрки,
     * восьмёрки не разыгрывались, всем игрокам этой группы начисляется
     * одинаково — на уровне очков за последнее место группы.
     *
     * Так выходит, что без матча за третье место оба полуфиналиста
     * получают как за четвёртое, а проигравшие четвертьфиналы — все как
     * за восьмое.
     *
     * Принимает список участников с полями:
     *   place    — занятое место
     *   разыграно — было ли место разыграно отдельным матчем
     *
     * Возвращает тот же список, где у каждого проставлено `местоОплаты` —
     * место, по которому считать очки.
     */
    function поСноске(участники) {
        // Собираем по месту: кто на каком стоит
        var неразыгранные = {};
        участники.forEach(function(у) {
            if (у.разыграно) return;
            var к = String(у.place);
            if (!неразыгранные[к]) неразыгранные[к] = 0;
            неразыгранные[к]++;
        });

        // Место, делённое между несколькими, оплачивается по последнему:
        // трое на пятом месте занимают 5, 6 и 7 — платим за 7
        var хвост = {};
        Object.keys(неразыгранные).forEach(function(к) {
            хвост[к] = parseInt(к, 10) + неразыгранные[к] - 1;
        });

        участники.forEach(function(у) {
            у.местоОплаты = у.разыграно ? у.place : (хвост[String(у.place)] || у.place);
        });

        return участники;
    }

    /**
     * Очки за место по таблице категории.
     *
     * Таблица — простой разбор `{место: очки}`. Мест в ней 64; кто занял
     * дальше, не получает ничего.
     */
    function заМесто(место, таблица) {
        if (!таблица || !место) return 0;
        var о = таблица[место] !== undefined ? таблица[место] : таблица[String(место)];
        return о || 0;
    }

    /**
     * Сколько получит участник.
     *
     * @param {Object} у — участник: place, разыграно, побед
     * @param {Object} таблица — {место: очки} своей категории
     * @param {Object} правила — {заПобеды: boolean}
     *
     * В олимпийке победы отдельно не платятся: место уже говорит, сколько
     * человек выиграл. В турнире с группами платятся — там за выход из
     * группы места не дают, а встречи сыграны.
     */
    function очки(у, таблица, правила) {
        var сумма = заМесто(у.местоОплаты || у.place, таблица);

        if (правила && правила.заПобеды) {
            var побед = у.побед || 0;
            сумма += побед > 0 ? побед * ЗА_ПОБЕДУ : ЗА_УЧАСТИЕ;
        }

        return сумма;
    }

    /**
     * Весь турнир разом: проставляет каждому местоОплаты и очки.
     *
     * Участник приходит с полями place, разыграно, побед — и уходит с
     * добавленным points_earned.
     */
    function поТурниру(участники, таблица, правила) {
        поСноске(участники);
        участники.forEach(function(у) {
            у.points_earned = очки(у, таблица, правила);
        });
        return участники;
    }

    /**
     * Сколько встреч выиграл человек. Проходы без игры не считаем:
     * соперника не было, играть не пришлось.
     */
    function победы(playerId, матчи) {
        if (!playerId) return 0;
        var n = 0;
        (матчи || []).forEach(function(m) {
            if (m.status !== 'completed' || m.score === 'BYE') return;
            if (m.winner_id === playerId) n++;
        });
        return n;
    }

    global.KSLT_POINTS = {
        ЗА_ПОБЕДУ: ЗА_ПОБЕДУ,
        ЗА_УЧАСТИЕ: ЗА_УЧАСТИЕ,
        поСноске: поСноске,
        заМесто: заМесто,
        очки: очки,
        поТурниру: поТурниру,
        победы: победы
    };

    if (typeof module !== 'undefined' && module.exports) {
        module.exports = global.KSLT_POINTS;
    }
})(typeof window !== 'undefined' ? window : globalThis);
