/**
 * Очки рейтинга: одно правило на все турниры.
 *
 * Раньше очки считались по стадии — выиграл турнир столько, дошёл до
 * полуфинала столько. В Положении клуба иначе: платит занятое место, и
 * мест больше, чем стадий. Третье и четвёртое различаются, пятое и
 * шестое тоже, а по стадиям оба полуфиналиста одинаковы.
 *
 * Считается в трёх местах — олимпийка, группы, сетка всех мест, — и
 * правило должно быть одно. Поэтому оно здесь, а не в каждой из них.
 *
 * Источник цифр: Приложение 2 к Положению КСЛТ 2021, таблица лежит в
 * базе (`points_by_place`) и в docs/.
 */
(function(global) {
    'use strict';

    /* 25 И 10 — ЭТО УМОЛЧАНИЕ, А НЕ ИСТИНА.
       Истина живёт в версии таблицы очков: `points_versions.per_win` и
       `per_entry`. Эти константы остаются ровно на то время, пока версий в
       базе нет, — тот же порядок выката, что у предела мест с `|| 64`.
       Кто знает версию, передаёт её числа в `правила`; кто не знает —
       получает прежнее поведение.
       ДО 03.10 ВЕРСИЯ ЭТИ ЧИСЛА НЕСЛА, А НАЧИСЛЕНИЕ ИХ НЕ ЧИТАЛО: правка на
       экране не меняла ничего. Ровно та же беда, из-за которой переписывался
       экран раундов. Нашлась на вопросе Кости «и за победу и за участие
       тоже можно будет менять?». */
    var ЗА_ПОБЕДУ = 25;      // за каждую выигранную встречу в группе
    var ЗА_УЧАСТИЕ = 10;     // тому, кто не выиграл ни одной

    /* СКОЛЬКО МЕСТ ПЛАТИТ ТАБЛИЦА В ТУРНИРЕ С ГРУППАМИ.
       Положение называет таблицу только для первых четырёх мест: они
       разыграны в плей-офф. Остальные её не получают вовсе — им платят
       победы. В олимпийке иначе: там таблица платит за каждое место, и
       победы не прибавляются (правило `заПобеды` туда не приходит). */
    var МЕСТ_ПО_ТАБЛИЦЕ = 4;

    /**
     * Сноска Положения (стр. 11): если места внутри двойки, четвёрки,
     * восьмёрки не разыгрывались, всем игрокам этой группы начисляется
     * одинаково — на уровне очков за последнее место группы.
     *
     * Так выходит, что без матча за третье место оба полуфиналиста
     * получают как за четвёртое, а проигравшие четвертьфиналы — все как
     * за восьмое.
     *
     * Принимает список участников с полями:
     *   place    — занятое место
     *   разыграно — было ли место разыграно отдельным матчем
     *
     * Возвращает тот же список, где у каждого проставлено `местоОплаты` —
     * место, по которому считать очки.
     */
    function поСноске(участники) {
        // Собираем по месту: кто на каком стоит
        var неразыгранные = {};
        участники.forEach(function(у) {
            if (у.разыграно) return;
            var к = String(у.place);
            if (!неразыгранные[к]) неразыгранные[к] = 0;
            неразыгранные[к]++;
        });

        // Место, делённое между несколькими, оплачивается по последнему:
        // трое на пятом месте занимают 5, 6 и 7 — платим за 7
        var хвост = {};
        Object.keys(неразыгранные).forEach(function(к) {
            хвост[к] = parseInt(к, 10) + неразыгранные[к] - 1;
        });

        участники.forEach(function(у) {
            у.местоОплаты = у.разыграно ? у.place : (хвост[String(у.place)] || у.place);
        });

        return участники;
    }

    /**
     * Очки за место по таблице категории.
     *
     * Таблица — простой разбор `{место: очки}`. Мест в ней СТОЛЬКО, СКОЛЬКО
     * ПЛАТИТ УРОВЕНЬ: четырём категориям 64, итоговому турниру 8
     * (`tournament_levels.max_place`, читается в `bracket.js`, `местаУровня`).
     * Кто занял дальше предела, в разборе отсутствует и получает ноль здесь
     * же — отдельного условия на предел в этом файле нет и быть не должно.
     */
    function заМесто(место, таблица) {
        if (!таблица || !место) return 0;
        var о = таблица[место] !== undefined ? таблица[место] : таблица[String(место)];
        return о || 0;
    }

    /**
     * Сколько получит участник.
     *
     * @param {Object} у — участник: place, разыграно, побед
     * @param {Object} таблица — {место: очки} своей категории
     * @param {Object} правила — {заПобеды: boolean, заПобеду?: number, заУчастие?: number}
     *
     * В олимпийке победы отдельно не платятся: место уже говорит, сколько
     * человек выиграл. В турнире с группами платятся — там за выход из
     * группы места не дают, а встречи сыграны.
     */
    function очки(у, таблица, правила) {
        var место = у.местоОплаты || у.place;

        /* ОДНО ИЛИ ДРУГОЕ, А НЕ ОБА РАЗОМ — решение Кости 30.09.
           Раньше 25 за победу прибавлялись поверх таблицы всем подряд, и
           победитель второй категории получал 360 плюс победы. По Положению
           первые четыре места платятся ТОЛЬКО таблицей: место уже говорит,
           сколько человек выиграл. Остальным — только победы. */
        if (правила && правила.заПобеды) {
            if (место && место <= МЕСТ_ПО_ТАБЛИЦЕ) return заМесто(место, таблица);
            var побед = у.побед || 0;
            /* Числа версии, если их передали, иначе умолчание. Ноль —
               ЗАКОННОЕ значение версии («за участие не начисляем»), поэтому
               проверка на `число`, а не на `||`: при `|| ` ноль молча стал
               бы десяткой. */
            var заПобеду  = typeof правила.заПобеду  === 'number' ? правила.заПобеду  : ЗА_ПОБЕДУ;
            var заУчастие = typeof правила.заУчастие === 'number' ? правила.заУчастие : ЗА_УЧАСТИЕ;
            return побед > 0 ? побед * заПобеду : заУчастие;
        }

        return заМесто(место, таблица);
    }

    /**
     * Весь турнир разом: проставляет каждому местоОплаты и очки.
     *
     * Участник приходит с полями place, разыграно, побед — и уходит с
     * добавленным points_earned.
     */
    function поТурниру(участники, таблица, правила) {
        поСноске(участники);
        участники.forEach(function(у) {
            у.points_earned = очки(у, таблица, правила);
        });
        return участники;
    }

    /**
     * Сколько встреч выиграл человек. Проходы без игры не считаем:
     * соперника не было, играть не пришлось.
     */
    function победы(playerId, матчи) {
        if (!playerId) return 0;
        var n = 0;
        (матчи || []).forEach(function(m) {
            if (m.status !== 'completed' || m.score === 'BYE') return;
            if (m.winner_id === playerId) n++;
        });
        return n;
    }

    /* ───────── ЭТАП, ДО КОТОРОГО ДОШЁЛ УЧАСТНИК ─────────
     *
     * `round_reached` в `tournament_results` — буквенный код: `W`, `F`,
     * `SF`, `QF`, `R16`, `G1`…`G6`. Переводов этого кода в слова по
     * продукту было ТРИ: админская таблица результатов
     * (`bracket.js:6792`), кабинет (`dashboard.js:4854`) и страница игрока
     * (`player.js:1254`). Четвёртый завели бы на публичной странице
     * турнира — и это ровно тот шов, на котором рождается беда.
     *
     * МЕСТО ПО ЭТАПУ ЗНАЕТ НЕ ВСЁ. У сеточных этапов оно выводится
     * однозначно: финалист — второй, проигравшие полуфинал делят
     * четвёртое. У места в ГРУППЕ такого ответа нет: третье место группы
     * A и третье место группы B — разные строки турнирной таблицы, и
     * какое из них выше, решает сила, а не буква. Поэтому `местоПоРаунду`
     * для `G*` возвращает null, а не догадку: ГДЕ ЧИСЛА НЕТ — ТАМ ЕГО И
     * НЕ ПИШЕМ.
     */
    var ПОДПИСИ_РАУНДА = {
        ru: { W: 'Победитель', F: 'Финалист', '3RD': '3-е место', '4TH': '4-е место',
              SF: 'Полуфинал', QF: 'Четвертьфинал', R16: '1/8 финала', R32: '1/16 финала',
              R64: '1/32 финала', G1: '1-е в группе', G2: '2-е в группе', G3: '3-е в группе',
              G4: '4-е в группе', G5: '5-е в группе', G6: '6-е в группе' },
        en: { W: 'Winner', F: 'Finalist', '3RD': '3rd Place', '4TH': '4th Place',
              SF: 'Semifinal', QF: 'Quarterfinal', R16: 'Round of 16', R32: 'Round of 32',
              R64: 'Round of 64', G1: '1st in Group', G2: '2nd in Group', G3: '3rd in Group',
              G4: '4th in Group', G5: '5th in Group', G6: '6th in Group' },
        kg: { W: 'Жеңүүчү', F: 'Финалист', '3RD': '3-орун', '4TH': '4-орун',
              SF: 'Жарым финал', QF: 'Чейрек финал', R16: '1/8 финал', R32: '1/16 финал',
              R64: '1/32 финал', G1: 'Топто 1-орун', G2: 'Топто 2-орун', G3: 'Топто 3-орун',
              G4: 'Топто 4-орун', G5: 'Топто 5-орун', G6: 'Топто 6-орун' }
    };

    var ПОРЯДОК_РАУНДОВ = { W: 1, F: 2, '3RD': 3, '4TH': 4, SF: 5, QF: 6, R16: 7, R32: 8,
        R64: 9, G3: 10, G4: 11, G5: 12, G6: 13 };

    var МЕСТО_ПО_РАУНДУ = { W: 1, F: 2, '3RD': 3, '4TH': 4, SF: 4, QF: 5, R16: 9, R32: 17, R64: 33 };

    /** Подпись этапа на нужном языке. Неизвестный код возвращаем как есть. */
    function подписьРаунда(код, язык) {
        var т = ПОДПИСИ_РАУНДА[язык] || ПОДПИСИ_РАУНДА.ru;
        return т[код] || код || '';
    }

    /** Место по этапу, или null — если этап места не определяет. */
    function местоПоРаунду(код) {
        var м = МЕСТО_ПО_РАУНДУ[код];
        return м === undefined ? null : м;
    }

    /* ЭТАП ДАЁТ НЕ ОДНО МЕСТО, А ПОЛОСУ.
       Проигравшие четвертьфинал между собой не играли — все четверо стоят
       на местах с пятого по восьмое, и какое из них чьё, не решено ничем.
       Одно число «5» у всех четверых утверждает то, чего не было: будто
       они разделили пятое, а шестое, седьмое и восьмое пусты. Решение
       Кости 01.10 — показывать полосу: 5-8, 9-16 и так далее.

       Границы выводятся из размера круга, а не перечислены руками:
       четвертьфинал — четверо, восьмая финала — восемь. Полоса кончается
       там, где начинается следующая.

       ОПЛАТА ЭТОГО НЕ КАСАЕТСЯ. Очки считает `поСноске` по месту, которое
       назначила админка при завершении; здесь — только подпись. */
    var РАЗМЕР_КРУГА = { SF: 2, QF: 4, R16: 8, R32: 16, R64: 32 };

    function подписьМеста(код) {
        var начало = местоПоРаунду(код);
        if (начало === null) return null;
        var сколько = РАЗМЕР_КРУГА[код];
        if (!сколько || сколько < 2) return String(начало);
        /* `SF` после сыгранного матча за третье не встречается вовсе: там
           стоят `3RD` и `4TH`. А когда его не играли — двое делят 3-4, и
           начало полосы на единицу раньше записанного места оплаты. */
        if (код === 'SF') return (начало - 1) + '-' + начало;
        return начало + '-' + (начало + сколько - 1);
    }

    /* ───────── МАТЧ ЗА МЕСТА — ЭТО И ЕСТЬ ЭТАП ТАМ, ГДЕ РАЗЫГРАНЫ ВСЕ ─────────
     *
     * Решение Кости 02.10: «давай Б, так будет понятнее».
     *
     * В сетке «все места» (`fic`) человек, взявший пятое, играл МАТЧ ЗА 5-6
     * МЕСТО, а не полуфинал. Буквенный код у него при этом `SF`: админка
     * переводит место в код (`bracket.js:12166`) ради ОЧКОВ — по нему
     * считается сноска и таблица, — а не ради подписи. Напиши страница
     * «Полуфинал», она утверждала бы то, чего не было.
     *
     * Прочерк вместо подписи тоже не ответ: он читается как «данных нет»,
     * хотя данные есть и называются иначе.
     *
     * Полоса выводится из места парами, а не перечислена: 5 и 6 играли
     * один матч, 7 и 8 — другой. Первая пара — финал, она так и зовётся.
     *
     * КЫРГЫЗСКАЯ ПОДПИСЬ НОСИТЕЛЕМ НЕ ПРОВЕРЕНА — как и прочие 31 строка,
     * долг записан в трекере.
     */
    var ПОДПИСИ_МАТЧА = {
        ru: { финал: 'Финал', за: 'Матч за % место' },
        en: { финал: 'Final', за: 'Match for places %' },
        kg: { финал: 'Финал', за: '% орун үчүн оюн' }
    };

    /**
     * Как назвать этап там, где разыграны все места.
     * @param {number} место — место, занятое участником
     * @param {string} язык — ru | en | kg
     */
    function подписьМатчаЗаМеста(место, язык) {
        var м = Number(место);
        if (!м || м < 1) return '';
        var т = ПОДПИСИ_МАТЧА[язык] || ПОДПИСИ_МАТЧА.ru;
        if (м <= 2) return т.финал;
        var начало = (м % 2) ? м : м - 1;
        return т.за.replace('%', начало + '-' + (начало + 1));
    }

    /** Насколько далеко прошёл: меньше — дальше. Для сортировки. */
    function порядокРаунда(код) {
        return ПОРЯДОК_РАУНДОВ[код] || 99;
    }

    global.KSLT_POINTS = {
        ПОДПИСИ_РАУНДА: ПОДПИСИ_РАУНДА,
        подписьРаунда: подписьРаунда,
        местоПоРаунду: местоПоРаунду,
        подписьМеста: подписьМеста,
        подписьМатчаЗаМеста: подписьМатчаЗаМеста,
        порядокРаунда: порядокРаунда,
        ЗА_ПОБЕДУ: ЗА_ПОБЕДУ,
        ЗА_УЧАСТИЕ: ЗА_УЧАСТИЕ,
        МЕСТ_ПО_ТАБЛИЦЕ: МЕСТ_ПО_ТАБЛИЦЕ,
        поСноске: поСноске,
        заМесто: заМесто,
        очки: очки,
        поТурниру: поТурниру,
        победы: победы
    };

    if (typeof module !== 'undefined' && module.exports) {
        module.exports = global.KSLT_POINTS;
    }
})(typeof window !== 'undefined' ? window : globalThis);
