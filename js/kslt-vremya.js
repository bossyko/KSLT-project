/**
 * ВРЕМЯ КЛУБА — ОДНО НА ВЕСЬ ПРОДУКТ.
 *
 * Слово Кости 09.10: основное время — Бишкек. Клуб играет в Кыргызстане,
 * турниры, сроки заявок и членство считаются по его дню, а не по дню того,
 * кто смотрит страницу.
 *
 * ЧТО БЫЛО: «сегодня» считалось как new Date().toISOString().split('T')[0] —
 * это день по ГРИНВИЧУ. Пересчитано 09.10: восемь таких мест в пяти файлах.
 * Бишкек идёт на шесть часов впереди, поэтому с полуночи до 6 утра по
 * Бишкеку код считал ещё вчерашний день: заявка, закрытая «сегодня»,
 * оставалась открытой, а членство, истекающее сегодня, — ещё живым.
 * В обратную сторону, западнее Гринвича, ошибка та же, но на день вперёд.
 *
 * Здесь одно определение, и дальше его зовут все.
 *
 *   KSLT_VREMYA.сегодня()        → '2026-10-09'  (день в Бишкеке)
 *   KSLT_VREMYA.сейчас()         → Date
 *   KSLT_VREMYA.деньПоБишкеку(d) → '2026-10-09' для любого Date или строки
 *
 * ПОЯС НЕ ПЕРЕВОДИТСЯ НА ЛЕТНЕЕ ВРЕМЯ: Кыргызстан держит UTC+6 круглый год
 * с 2005-го, поэтому смещение постоянное. Если это когда-нибудь изменится,
 * менять придётся ровно одно число — здесь.
 */
(function () {
    'use strict';

    var В = {};
    var СМЕЩЕНИЕ_МИНУТ = 6 * 60;   // Asia/Bishkek, UTC+6 круглый год

    /** @returns {Date} момент «сейчас», как его видит браузер */
    В.сейчас = function () { return new Date(); };

    /**
     * День в Бишкеке для любого момента.
     * @param {Date|string|number} [когда] — по умолчанию сейчас
     * @returns {string} 'ГГГГ-ММ-ДД'
     */
    В.деньПоБишкеку = function (когда) {
        var d = (когда === undefined || когда === null) ? new Date() : new Date(когда);
        if (isNaN(d.getTime())) return '';
        var сдвинут = new Date(d.getTime() + СМЕЩЕНИЕ_МИНУТ * 60000);
        return сдвинут.toISOString().slice(0, 10);
    };

    /** @returns {string} сегодняшний день в Бишкеке, 'ГГГГ-ММ-ДД' */
    В.сегодня = function () { return В.деньПоБишкеку(); };

    window.KSLT_VREMYA = В;
})();
