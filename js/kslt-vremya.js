/**
 * ВРЕМЯ КЛУБА — ОДНО НА ВЕСЬ ПРОДУКТ.
 *
 * Слово Кости 09.10: основное время — Бишкек. Клуб играет в Кыргызстане,
 * турниры, сроки заявок и членство считаются по его дню, а не по дню того,
 * кто смотрит страницу.
 *
 * ЧТО БЫЛО: «сегодня» считалось как new Date().toISOString().split('T')[0] —
 * это день по ГРИНВИЧУ. Пересчитано 09.10: восемь таких мест в пяти файлах.
 * Бишкек идёт на шесть часов впереди, поэтому с полуночи до 6 утра по
 * Бишкеку код считал ещё вчерашний день: заявка, закрытая «сегодня»,
 * оставалась открытой, а членство, истекающее сегодня, — ещё живым.
 * В обратную сторону, западнее Гринвича, ошибка та же, но на день вперёд.
 *
 * Здесь одно определение, и дальше его зовут все.
 *
 *   KSLT_VREMYA.сегодня()        → '2026-10-09'  (день в Бишкеке)
 *   KSLT_VREMYA.сейчас()         → Date
 *   KSLT_VREMYA.деньПоБишкеку(d) → '2026-10-09' для любого Date или строки
 *
 * ПОЯС БЕРЁТСЯ ПО ИМЕНИ, А НЕ ЧИСЛОМ. Кыргызстан держит UTC+6 круглый год
 * с 2005-го, но зашитое смещение верно ровно до того дня, когда часы
 * тронут, — а база считает `AT TIME ZONE 'Asia/Bishkek'`, то есть по
 * имени зоны. Два определения одного понятия разошлись бы ровно на шве.
 *
 * 17.10 · ЭТОТ ДОМ — ЕДИНСТВЕННЫЙ. До него «сегодня по Бишкеку» жило в
 * коде ДВАЖДЫ: здесь со смещением числом и в `js/admin/core/utils.js`
 * (`A.сегодняБишкек`) через имя зоны. Теперь приём один — по имени, —
 * а `A.сегодняБишкек` оставлен обёрткой: его зовут из разделов админки,
 * и ломать их вызовы ради переименования незачем.
 */
(function () {
    'use strict';

    var В = {};
    var ЗОНА = 'Asia/Bishkek';

    /** @returns {Date} момент «сейчас», как его видит браузер */
    В.сейчас = function () { return new Date(); };

    /**
     * День в Бишкеке для любого момента.
     * @param {Date|string|number} [когда] — по умолчанию сейчас
     * @returns {string} 'ГГГГ-ММ-ДД'
     */
    В.деньПоБишкеку = function (когда) {
        var d = (когда === undefined || когда === null) ? new Date() : new Date(когда);
        if (isNaN(d.getTime())) return '';
        /* ЗОНА, А НЕ ЗАШИТОЕ СМЕЩЕНИЕ. Было `+ 6 * 60` минут вручную: это
           верно ровно до того дня, когда Кыргызстан тронет часы, и
           расходится с базой, где сторож считает `AT TIME ZONE
           'Asia/Bishkek'`. Приём взят у второго дома времени, который
           жил в админке (`A.сегодняБишкек`, utils.js): `sv-SE` даёт
           ISO-вид «2026-10-17» без ручной сборки из частей. */
        return d.toLocaleDateString('sv-SE', { timeZone: ЗОНА });
    };

    /* ПОКАЗ ДНЯ И МОМЕНТА — ИМЯ ЗОНЫ НЕ УХОДИТ ИЗ ДОМА (11.11).
       Починка пояса 11.11 дописывала пояс прямо в зовущем:
       `toLocaleDateString('ru-RU', { timeZone: ... })` — то есть заводила
       ВТОРОЙ ДОМ ВРЕМЕНИ в каждом файле, где так написано, и сторож
       `check-vremya-kluba` это назвал. Хуже другое: в трёх местах пояс
       оказался ТРЕТЬИМ доводом (`toLocale…(речь, вид, { timeZone })`) —
       язык третьего довода не читает, и пояс не делал НИЧЕГО.
       Поэтому зовущий просит ПОКАЗ, а зону подставляет дом — и подставляет
       её ПОСЛЕ вида, чтобы вид её не перебил. */
    function сПоясом(вид) {
        var о = {};
        if (вид) for (var к in вид) {
            if (Object.prototype.hasOwnProperty.call(вид, к)) о[к] = вид[к];
        }
        о.timeZone = ЗОНА;
        return о;
    }

    /**
     * День для показа человеку.
     * @param {Date|string|number} когда
     * @param {string} [речь] — локаль показа; без неё берётся язык браузера
     * @param {Object} [вид] — остальные доводы Intl, кроме пояса
     * @returns {string} пустая строка, если даты нет
     */
    В.показДня = function (когда, речь, вид) {
        var d = new Date(когда);
        if (isNaN(d.getTime())) return '';
        return d.toLocaleDateString(речь || undefined, сПоясом(вид));
    };

    /** Момент (день и время) для показа человеку — доводы как у показДня. */
    В.показМомента = function (когда, речь, вид) {
        var d = new Date(когда);
        if (isNaN(d.getTime())) return '';
        return d.toLocaleString(речь || undefined, сПоясом(вид));
    };

    /** @returns {string} сегодняшний день в Бишкеке, 'ГГГГ-ММ-ДД' */
    В.сегодня = function () { return В.деньПоБишкеку(); };

    /**
     * МОМЕНТ ПО ЧАСАМ БИШКЕКА.
     *
     * ЧТО БЫЛО (найдено Костей 08.11 на боевой). Обратный отсчёт строил
     * цель как `new Date('2026-11-08T09:00:00')` — без пояса, то есть по
     * часам ТОГО, КТО СМОТРИТ. Костя смотрел из Чикаго: турнир в Бишкеке
     * шёл полным ходом, а карточка писала «старт через 07ч 41м». Разница
     * ровно в двенадцать часов — столько между поясами.
     *
     * ВРЕМЯ СТАРТА — СВОЙСТВО ТУРНИРА, А НЕ ЗРИТЕЛЯ. В базе лежит «9:00»
     * без пояса, и эти девять утра — бишкекские: клуб играет там. Значит
     * и собирать момент надо по часам Бишкека, а разницу со своими часами
     * считает уже браузер.
     *
     * ПОЯС БЕРЁТСЯ ПО ИМЕНИ, А НЕ ЧИСЛОМ — как и везде в этом доме:
     * смещение вычисляется для КОНКРЕТНОГО дня, и в день, когда часы
     * тронут, ничего переписывать не придётся.
     *
     * @param {string} день — 'ГГГГ-ММ-ДД'
     * @param {string} [время] — 'ЧЧ:ММ', по умолчанию полночь
     * @returns {Date|null} момент, когда в Бишкеке будет это время
     */
    В.моментПоБишкеку = function (день, время) {
        if (!день) return null;
        /* ВРЕМЯ ПРИНИМАЕТСЯ И С СЕКУНДАМИ. Конец дня в коде пишут как
           '23:59:59', старт турнира — как '09:00'; дом берёт оба вида,
           чтобы зовущему не приходилось дописывать секунды самому. */
        var t = время || '00:00';
        if (t.split(':').length === 2) t += ':00';
        var пробный = new Date(день + 'T' + t + 'Z');
        if (isNaN(пробный.getTime())) return null;
        var вЗоне = new Date(пробный.toLocaleString('en-US', { timeZone: ЗОНА }));
        var вUTC  = new Date(пробный.toLocaleString('en-US', { timeZone: 'UTC' }));
        return new Date(пробный.getTime() - (вЗоне.getTime() - вUTC.getTime()));
    };

    /* ИМЯ ЗОНЫ ОТДАЁТСЯ НАРУЖУ. Оно нужно не только для «сегодня»: кабинет
       показывает дату матча в зоне клуба через Intl, и до 17.10 строка
       'Asia/Bishkek' жила там ВТОРЫМ местом. Одно понятие — одно имя. */
    В.зона = ЗОНА;

    window.KSLT_VREMYA = В;
})();
