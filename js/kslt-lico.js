/**
 * ЛИЦО БЕЗ ФОТОГРАФИИ — ОДНО ОПРЕДЕЛЕНИЕ НА ПРОДУКТ.
 *
 * Замер 13.10: инициалы считались ВОСЕМЬЮ разными функциями, и вели они
 * себя ПЯТЬЮ разными способами:
 *
 *   services.js, partners.js   первое + второе слово, ВЕРХНИЙ, пусто → «?»
 *   home-partners.js           первое + второе слово, ВЕРХНИЙ, пусто → «?»
 *   players.js, home-rankings.js, battle-cards.js
 *                              первое + второе, БЕЗ верхнего, пусто → «»
 *   match-score.js             ОДНА буква, ВЕРХНИЙ, пусто → «?»
 *   player.js                  первое + ПОСЛЕДНЕЕ слово, ВЕРХНИЙ, «?»
 *
 * Одно и то же имя давало разные кружки на разных экранах, а у трёх
 * реализаций пустое имя давало ПУСТОЙ кружок вместо знака вопроса.
 *
 * ПРИНЯТО ПОВЕДЕНИЕ `player.js`: первая буква первого слова плюс первая
 * буква ПОСЛЕДНЕГО, верхним регистром. Так делают Apple в Контактах и
 * Linear: человека узнают по имени и фамилии, а не по первым двум словам.
 * На нынешних данных разницы нет — имён длиннее двух слов в рейтинге нет
 * ни одного (померено 13.10), — но правило держится на смысле, а не на
 * том, что сегодня в базе.
 *
 * ЗАГЛУШКА — ТОЖЕ ЗДЕСЬ. Нет фотографии — рисуем инициалы, а не просим
 * картинку у чужого сайта: `placehold.co` стоял ещё в двух местах и давал
 * серый «?» плюс запрос наружу на каждую карточку.
 *
 *     KSLT_LICO.инициалы('Константин Лазаренко')   → 'КЛ'
 *     KSLT_LICO.кружок(игрок.name, 'pl-photo')     → <div class=…>КЛ</div>
 *     KSLT_LICO.лицо(фото, имя, 'pl-photo')        → <img> или кружок
 *     KSLT_LICO.имяНаЯзыке(игрок)                → 'Константин Хан' или '?'
 *     KSLT_LICO.вСети(игрок.last_seen)           → true / false
 *     KSLT_LICO.ПОРОГ_В_СЕТИ                       → 300000
 *
 * ИМЯ НА ЯЗЫКЕ СТРАНИЦЫ И «В СЕТИ» ПРИШЛИ СЮДА КУСКОМ 155. Оба про
 * одного человека, оба стояли копиями, и «в сети» было ЧЕТЫРЬМЯ
 * копиями, а не двумя: прибор видит копию только целой функцией с тем
 * же телом, а здесь расходились и подпись, и запись.
 *   services.js      isOnline(last_seen) + свой порог
 *   partners.js      isOnline(last_seen) + свой порог
 *   home-partners.js online(ИГРОКА), порог числом внутри выражения
 *   admin/users.js   вписано в строку отрисовки, порог числом
 * ПОРОГ ОБЪЯВЛЯЛСЯ ЧЕТЫРЕЖДЫ ОДНИМ ЧИСЛОМ — сходился случайно, и
 * разошёлся бы молча: «в сети» на одной странице и «был сегодня» на
 * другой про одного человека в одну минуту.
 */
(function () {
    'use strict';

    /* ЭКРАНИРОВАНИЕ — ДОМ (кусок 146). */
    function экр(s) {
        return window.KSLT_экранировать(s);
    }

    function инициалы(имя) {
        var слова = String(имя == null ? '' : имя).trim().split(/\s+/).filter(Boolean);
        if (слова.length === 0) return '?';
        if (слова.length === 1) return слова[0].charAt(0).toUpperCase();
        return (слова[0].charAt(0) + слова[слова.length - 1].charAt(0)).toUpperCase();
    }

    /**
     * Кружок с инициалами. Класс заглушки — ТОТ ЖЕ, что у фотографии,
     * поэтому размер и скругление у них общие и второго объявления не
     * появляется. Avatar 29:82.
     */
    function кружок(имя, класс) {
        return '<div class="' + экр(класс || '') + ' avatar-initials" aria-hidden="true">' +
               экр(инициалы(имя)) + '</div>';
    }

    /**
     * Фотография или кружок. Подпись отдаётся картинке; кружок скрыт от
     * диктора, потому что имя и так стоит рядом текстом.
     */
    function лицо(фото, имя, класс) {
        if (!фото) return кружок(имя, класс);
        return '<img src="' + экр(фото) + '" alt="' + экр(имя || '') +
               '" class="' + экр(класс || '') + '">';
    }

    /**
     * Имя человека на языке страницы. Запасной ход — русское имя, а не
     * пустота: в базе `name_en` и `name_kg` заполнены не у всех, и пустое
     * имя на карточке читается как потеря данных.
     */
    function имяНаЯзыке(игрок) {
        if (!игрок) return '?';
        var Я = window.KSLT_YAZYK;
        if (Я && Я.en) return игрок.name_en || игрок.name || '?';
        if (Я && Я.kg) return игрок.name_kg || игрок.name || '?';
        return игрок.name || '?';
    }

    /* Пять минут тишины — человек больше не «в сети». Слово Кости 06.10. */
    var ПОРОГ_В_СЕТИ = 5 * 60 * 1000;

    /**
     * «В сети» — ПО ВРЕМЕНИ, А НЕ ПО ИГРОКУ: одна копия принимала игрока,
     * три — дату, и зовущему приходилось знать, какая у него под рукой.
     * Дом принимает время; у кого на руках игрок, передаёт его поле.
     */
    function вСети(когдаБылВидно) {
        if (!когдаБылВидно) return false;
        return Date.now() - new Date(когдаБылВидно).getTime() < ПОРОГ_В_СЕТИ;
    }

    window.KSLT_LICO = { инициалы: инициалы, кружок: кружок, лицо: лицо,
                         имяНаЯзыке: имяНаЯзыке, вСети: вСети,
                         ПОРОГ_В_СЕТИ: ПОРОГ_В_СЕТИ };
})();
