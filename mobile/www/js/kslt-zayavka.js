/**
 * ЗАЯВКА НА ТУРНИР: ЗОВ И РАЗБОР ОТВЕТА — ОДИН ДОМ (шаг A3.7д, 29.10).
 *
 * ЧТО БЫЛО. `js/tournament-register.js` (708 строк) и
 * `mobile/www/js/tournament-register.js` (199) носили одно имя
 * `KSLT_REG` и жили двумя телами. Решение о допуске принимает серверная
 * функция `tournament-register` — и это правильно. А ВОТ РАЗБОР ЕЁ
 * ОТВЕТА был написан дважды:
 *
 *   · зов функции: сессия → токен → отсев пустых полей → `fetch`;
 *   · дерево решений по ответу: смена напарника → уже подана → отказ →
 *     принята → лист ожидания → общий отказ;
 *   · тон, значок и короткая подпись для каждой ветки;
 *   · признак «заявка создана», по которому кнопка меняет вид.
 *
 * И ДВЕ БЕДЫ УЖЕ РОДИЛИСЬ НА ШВЕ:
 *
 *   1. У ПРИЛОЖЕНИЯ НЕТ ВЕТКИ СМЕНЫ НАПАРНИКА ВОВСЕ. Ответ
 *      `partner_changed` не несёт ни `error`, ни `status`, поэтому в
 *      приложении он доезжал до последней ветки — и человек после
 *      УСПЕШНОЙ замены напарника видел «⛔ Заявка не принята».
 *   2. СЛОВ НА КОДЫ ОТКАЗА У САЙТА ДЕВЯТНАДЦАТЬ, У ПРИЛОЖЕНИЯ БЫЛО
 *      ДЕВЯТЬ. Остальные десять приложение показывало человеку СЫРЫМ
 *      КОДОМ: `category_closed`, `entry_in_draw`, `partner_taken`.
 *
 * ЧЕГО В ДОМЕ НЕТ: ни одного слова. Дом отдаёт КЛЮЧ, слово по ключу
 * берётся из общих надписей `js/zayavka-texts.js`. Разметка окна,
 * оснастка фокуса, экранирование и тост — забота продукта: у сайта окно
 * посередине с запиранием Tab, у приложения своя накладка.
 *
 * Правка правится В ДВУХ МЕСТАХ: побайтовая копия в `mobile/www/js/`.
 */
(function (global) {
    'use strict';

    var API = global.KSLT_ZAYAVKA = {};

    /** Адрес серверной функции. Один на оба продукта. */
    API.ФУНКЦИЯ = 'tournament-register';

    /**
     * ЗОВ ФУНКЦИИ ДОПУСКА.
     *
     * Пустые поля отсеиваются ЗДЕСЬ, а не у зовущего: `partner_id`
     * пустой строкой сервер понял бы как «напарник есть, имя пустое».
     *
     * @param {Object} client — клиент базы (нужен только для сессии)
     * @param {string} турнирId
     * @param {Object} [extra] — `partner_id` или `partner_external_*`
     * @returns {Promise<{ok: boolean, data: Object}>}
     */
    API.зов = function (client, турнирId, extra) {
        return client.auth.getSession().then(function (сессия) {
            var токен = (сессия.data && сессия.data.session)
                ? сессия.data.session.access_token : '';
            var посылка = { tournament_id: турнирId };
            if (extra) {
                for (var к in extra) {
                    if (extra[к] !== undefined && extra[к] !== null && extra[к] !== '') {
                        посылка[к] = extra[к];
                    }
                }
            }
            /* ЗОВ ЧЕРЕЗ ДОМ ЗОВА (30.10): заголовки, адрес, ключ и
               разбор ответа — одно место на продукт. Здесь остаётся
               своё: имя функции и отсев пустых полей.
               `ok` ПРЕЖНЕЙ ФОРМЫ СОХРАНЁН: его читают зовущие — у
               заявки «не ок» и «ок с отказом» это разные ветки. Дом
               отдаёт сами данные, а `ok` выводится из них: нет кода
               отказа — значит сервер согласился. */
            return global.KSLT_ZOV.сТокеном(токен, API.ФУНКЦИЯ, посылка)
                .then(function (data) {
                    return { ok: !(data && data.error), data: data || {} };
                });
        }).catch(function (e) {
            return { ok: false, data: { error: e.message } };
        });
    };

    /* Какое слово на какой статус уже поданной заявки и какая подпись. */
    var ПО_СТАТУСУ = {
        approved:  { ключ: 'inMainDraw', коротко: 'shortInDraw' },
        draw:      { ключ: 'stDraw',     коротко: 'shortInDraw' },
        pending:   { ключ: 'stPending',  коротко: 'shortReview' },
        waitlist:  { ключ: 'stWaitlist', коротко: 'shortWaitlist' },
        rejected:  { ключ: 'stRejected', коротко: 'shortRejected' },
        withdrawn: { ключ: 'stWithdrawn', коротко: 'shortWithdrawn' },
        blocked:   { ключ: 'stBlocked',  коротко: 'shortNotAccepted' }
    };

    /* Почему заявка ушла в лист ожидания. */
    var ПО_ПРИЧИНЕ = {
        no_category:   'reviewNoCategory',
        rank_waitlist: 'reviewRank',
        draw_full:     'reviewFull'
    };

    /**
     * РАЗБОР ОТВЕТА — ОДНО ДЕРЕВО РЕШЕНИЙ НА ОБА ПРОДУКТА.
     *
     * Отдаёт КЛЮЧИ, а не слова: словарь приходит из общих надписей, и
     * язык выбирает продукт.
     *
     * Порядок ветвей важен и повторяет серверный договор:
     *   `partner_changed` не несёт ни `error`, ни `status` — он ПЕРВЫЙ,
     *   иначе успешная замена напарника доезжает до общего отказа, как
     *   это и было в приложении.
     *
     * @returns {{вид, тон, значок, титулКлюч, ключ, короткоКлюч,
     *            заметкаКлюч, код, статус, гость}}
     */
    API.разобрать = function (data) {
        var д = data || {};

        if (д.partner_changed) {
            var гость = !!д.guest;
            return {
                вид: 'сменаНапарника',
                тон: 'success',
                значок: гость ? '⏳' : '✅',
                титулКлюч: 'titleChanged',
                ключ: гость ? 'noteGuest' : 'changedKept',
                короткоКлюч: гость ? 'shortReview' : 'shortChanged',
                заметкаКлюч: '',
                код: '',
                статус: '',
                гость: гость
            };
        }

        if (д.error === 'already_registered') {
            var по = ПО_СТАТУСУ[д.status] || null;
            var плохо = (д.status === 'rejected' || д.status === 'blocked');
            return {
                вид: 'уже',
                тон: плохо ? 'error' : 'success',
                значок: плохо ? '⛔' : '📋',
                титулКлюч: 'titleAlready',
                ключ: по ? по.ключ : '',
                короткоКлюч: по ? по.коротко : 'shortApplied',
                заметкаКлюч: '',
                код: '',
                статус: д.status || '',
                гость: false
            };
        }

        if (д.error) {
            return {
                вид: 'отказ',
                тон: 'error',
                значок: '⛔',
                титулКлюч: 'titleRefused',
                ключ: '',
                короткоКлюч: 'shortNotAccepted',
                заметкаКлюч: '',
                код: д.error,
                статус: '',
                гость: false
            };
        }

        if (д.status === 'approved') {
            return {
                вид: 'принята',
                тон: 'success',
                значок: '✅',
                титулКлюч: 'titleAccepted',
                ключ: 'inMainDraw',
                короткоКлюч: 'shortInDraw',
                заметкаКлюч: (д.reason === 'top_rank') ? 'noteTopRank' : '',
                код: '',
                статус: 'approved',
                гость: false
            };
        }

        if (д.status === 'waitlist') {
            return {
                вид: 'ожидание',
                тон: 'success',
                значок: '⏳',
                титулКлюч: 'titleReview',
                ключ: ПО_ПРИЧИНЕ[д.reason] || 'reviewAdmin',
                короткоКлюч: 'shortReview',
                заметкаКлюч: '',
                код: '',
                статус: 'waitlist',
                гость: false
            };
        }

        return {
            вид: 'неПринята',
            тон: 'error',
            значок: '⛔',
            титулКлюч: 'titleRefused',
            ключ: 'refusedGeneric',
            короткоКлюч: 'shortNotAccepted',
            заметкаКлюч: '',
            код: '',
            статус: '',
            гость: false
        };
    };

    /**
     * СЛОВАМИ: разбор плюс словарь → то, что показывают человеку.
     *
     * Склейка тоже была написана дважды, и у неё есть свои углы: у
     * «уже подана» с незнакомым статусом текста нет, и вместо пустоты
     * показывается «Статус: <как есть>»; у общего отказа сервер может
     * прислать свою причину словами (`block_reason`), и она важнее
     * нашего общего слова.
     *
     * Возвращает ТЕКСТ, а не разметку: экранирует тот, кто вставляет.
     */
    API.словами = function (разбор, L, data) {
        var д = data || {};
        var текст;

        if (разбор.вид === 'отказ') {
            текст = (L.err && L.err[разбор.код]) || разбор.код;
        } else if (разбор.вид === 'уже' && !разбор.ключ) {
            текст = L.stPrefix + разбор.статус;
        } else if (разбор.вид === 'неПринята' && д.block_reason) {
            текст = д.block_reason;
        } else {
            текст = L[разбор.ключ] || '';
        }

        return {
            тон: разбор.тон,
            значок: разбор.значок,
            титул: L[разбор.титулКлюч] || '',
            текст: текст,
            заметка: разбор.заметкаКлюч ? (L[разбор.заметкаКлюч] || '') : '',
            коротко: L[разбор.короткоКлюч] || ''
        };
    };

    /**
     * СОЗДАНА ЛИ ЗАЯВКА — признак, по которому кнопка меняет вид.
     *
     * Одно выражение, и оно стояло в двух файлах знак в знак. Тонкость в
     * том, что `already_registered` — это ОТКАЗ по коду, но кнопку
     * менять надо: заявка в турнире есть, просто она была раньше.
     */
    API.создана = function (data) {
        var д = data || {};
        return !(д.error && д.error !== 'already_registered');
    };

})(typeof window !== 'undefined' ? window : this);
