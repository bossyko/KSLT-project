/**
 * KSLT — ЖУРНАЛ ХОДА МАТЧА. ОДИН НА ДВА ПРОДУКТА.
 *
 * ЧТО ЭТО. Лента геймов с розыгрышами внутри: верхняя строка — очки
 * первого игрока, нижняя — второго, выигравший очко виден по тому, ЧЬЁ
 * ЧИСЛО СДВИНУЛОСЬ. Занимает место видео, когда трансляции нет
 * (решение Кости по макету Б2 от 25.09).
 *
 * ЗАЧЕМ ВЫНЕСЕН. На сайте журнал был, в приложении — нет: там на месте
 * видео стояла надпись «Нет трансляции», и счёт человек видел только в
 * табло. Написать журнал в приложении заново значило бы завести второе
 * определение на пятьсот строк — а продукты показывают ОДИН И ТОТ ЖЕ
 * матч, и разойтись им нельзя.
 *
 * ЧТО ДОМ ЗНАЕТ И ЧЕГО НЕ ЗНАЕТ. Он знает, как выглядит гейм и как
 * читается розыгрыш. Он НЕ ходит в базу, не знает языка и не хранит,
 * какой сет выбран: подписи и выбранный сет приходят доводом, данные —
 * тоже. Поэтому один и тот же дом работает и на странице сайта, и в
 * накладке приложения.
 *
 * РЕШЕНИЯ, ПЕРЕНЕСЁННЫЕ ВМЕСТЕ С КОДОМ — их не переоткрывать:
 *   · ГЕЙМЫ ИДУТ НОВЫМ СВЕРХУ, очки внутри гейма слева направо, у
 *     каждого гейма написан номер: направление времени нигде не
 *     гадается;
 *   · ЗАКРЫТЫЙ ГЕЙМ УНОСИТ СВОИ РОЗЫГРЫШИ С СОБОЙ. До 25.09 он
 *     схлопывался в строку и терял их все — Костя открыл матч после
 *     гейма и увидел пустую панель;
 *   · КРАСКА НЕ КОДИРУЕТ ПОБЕДИТЕЛЯ ГЕЙМА. Синий и оранжевый уже
 *     значат «кто взял ОЧКО»; та же пара за «кто взял ГЕЙМ» — одно
 *     определение на два понятия, и оба перестают читаться;
 *   · ПОСЛЕДНЕЕ ОЧКО ГЕЙМА ПРИХОДИТ ИЗ БАЗЫ УЖЕ СО СБРОШЕННЫМ СЧЁТОМ
 *     (0 : 0). Настоящий счёт розыгрыша потерян судейским модулем; там
 *     и чинить. Здесь у победителя стоит слово, у второго — ничего:
 *     нули, которые ничего не значат, не показываются;
 *   · ТОЧКА ПОДАЧИ — ТОЛЬКО НА ИДУЩЕМ ГЕЙМЕ. Подающего на прошлых
 *     геймах база не хранит, а выводить чередованием нельзя: на
 *     тай-брейке подача меняется каждые два очка. ЧИСЛО, КОТОРОГО НЕ
 *     МОГУ ПОМЕРИТЬ, НЕ ВЫДУМЫВАЮ.
 */
(function () {
    'use strict';

    var Ж = window.KSLT_ZHURNAL = {};

    function экр(s) {
        return window.KSLT_экранировать
            ? window.KSLT_экранировать(s)
            : String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
                return { '&': '&amp;', '<': '&lt;', '>': '&gt;',
                         '"': '&quot;', "'": '&#39;' }[c];
            });
    }

    /**
     * «Иван Корабельников» → «Иван К.» — по просьбе Кости 24.09.
     * В ленте имя стоит в строке гейма рядом со счётом, и полное имя её
     * разрывает. Одно слово остаётся как есть: сокращать нечего.
     */
    Ж.короткоеИмя = function (полное) {
        var части = String(полное || '').trim().split(/\s+/);
        if (части.length < 2) return части[0] || '—';
        return части[0] + ' ' + части[1].charAt(0).toUpperCase() + '.';
    };

    /** Розыгрыши в геймы: база отдаёт их одной лентой, по возрастанию. */
    Ж.геймы = function (список) {
        var игры = [];
        var тек = null;
        (список || []).forEach(function (pt) {
            if (!тек || тек.set_no !== pt.set_no || тек.game_no !== pt.game_no) {
                тек = { set_no: pt.set_no, game_no: pt.game_no, points: [], won: null, is_break: false };
                игры.push(тек);
            }
            тек.points.push(pt);
            if (pt.game_won) {
                тек.won = pt.game_won;
                тек.is_break = !!pt.is_break;
                тек.g1 = pt.g1;
                тек.g2 = pt.g2;
            }
        });
        return игры;
    };

    function ячейка(текст, взял, гейм, метка) {
        return '<span class="lm-cell' + (взял ? ' is-won' : '') +
            (гейм ? ' is-game' : '') + '">' + экр(String(текст)) +
            (метка ? '<i class="lm-cell-mark">' + метка + '</i>' : '') +
        '</span>';
    }

    function строкаИгрока(имя, n, подаёт, ячейки) {
        return '<div class="lm-game-row lm-row-' + n + '">' +
            '<span class="lm-row-name">' +
                (подаёт ? '<i class="lm-row-serve" aria-hidden="true"></i>' : '') +
                экр(Ж.короткоеИмя(имя)) +
            '</span>' +
            '<span class="lm-row-cells">' + ячейки + '</span>' +
        '</div>';
    }

    function чип(значение, подпись, выбран) {
        return '<button type="button" class="lm-chip' + (выбран ? ' is-active' : '') +
            '" data-set="' + (значение === null ? '' : значение) + '"' +
            (выбран ? ' aria-pressed="true"' : ' aria-pressed="false"') + '>' +
            экр(подпись) + '</button>';
    }

    function гейм(о, г) {
        var очки = г.points;
        var ячеек1 = '', ячеек2 = '';

        for (var i = 0; i < очки.length; i++) {
            var pt = очки[i];
            var последнее = (i === очки.length - 1) && г.won;

            if (последнее) {
                ячеек1 += ячейка(г.won === 1 ? о.подписи.gameCell : '·', г.won === 1, true);
                ячеек2 += ячейка(г.won === 2 ? о.подписи.gameCell : '·', г.won === 2, true);
            } else {
                var метка = pt.mark === 'ace' ? о.подписи.ace
                    : pt.mark === 'double' ? о.подписи.doubleF : '';
                ячеек1 += ячейка(pt.p1, pt.winner === 1, false, pt.winner === 1 ? метка : '');
                ячеек2 += ячейка(pt.p2, pt.winner === 2, false, pt.winner === 2 ? метка : '');
            }
        }

        var идёт = !г.won;
        var подаёт1 = идёт && о.подающий === 1;
        var подаёт2 = идёт && о.подающий === 2;

        var итог;
        if (!г.won) {
            итог = '<span class="lm-game-res is-now">' + экр(о.подписи.gameLive) + '</span>';
        } else if (г.is_break) {
            итог = '<span class="lm-break">' + экр(о.подписи.breakLabel) + '</span>';
        } else {
            итог = '<span class="lm-game-res">' +
                экр(Ж.короткоеИмя(о.имя(г.won)) + ' — ' + (г.g1 + ' : ' + г.g2)) +
                '</span>';
        }

        return '<div class="lm-game' + (идёт ? ' is-now' : '') + '"' +
                (идёт ? ' aria-live="polite"' : '') + '>' +
            '<div class="lm-game-head">' +
                '<span class="lm-game-no">' + экр(о.подписи.game + ' ' + г.game_no) + '</span>' +
                итог +
            '</div>' +
            строкаИгрока(о.имя(1), 1, подаёт1, ячеек1) +
            строкаИгрока(о.имя(2), 2, подаёт2, ячеек2) +
        '</div>';
    }

    /**
     * ЛЕНТА ИЗ ТОГО, ЧТО БАЗА ПИШЕТ ВСЕГДА — сеты и текущий гейм.
     * Запасной путь, когда журнала розыгрышей нет. Не притворяется
     * подробной: показывает ровно столько, сколько знает.
     */
    function грубая(о) {
        var п = о.подписи;
        var строки = (о.сеты || []).map(function (s, i) {
            return { lead: (i + 1) + '-й ' + п.setN + ' — ' + s.g1 + ' : ' + s.g2, now: false };
        });
        if (!о.завершён) {
            /* Счёт очков стоит СРАЗУ за геймом, а не улетает к дальнему
               краю: в одной строке разрыв на три четверти ширины
               читается так же плохо, как растянутое табло. */
            var очки = о.тайбрейк
                ? (о.тб1 || 0) + ' : ' + (о.тб2 || 0)
                : (о.очки1 || '0') + ' : ' + (о.очки2 || '0');
            строки.push({
                lead: п.gameNow + ' — ' + (о.гейм1 || 0) + ' : ' + (о.гейм2 || 0) +
                      '   ·   ' + очки,
                now: true
            });
        }
        if (!строки.length) return '';
        return '<div class="lm-feed">' +
            '<p class="lm-feed-title">' + экр(п.feedTitle) + '</p>' +
            '<ul class="lm-feed-list">' +
            строки.map(function (it) {
                return '<li class="lm-feed-item' + (it.now ? ' is-now' : '') + '">' +
                    '<span>' + экр(it.lead) + '</span></li>';
            }).join('') +
            '</ul></div>';
    }

    /**
     * Разметка журнала.
     *
     * о.очки      — лента розыгрышей из базы (по возрастанию)
     * о.сеты      — `sets_data` матча, для запасной ленты
     * о.имя(n)    — полное имя игрока 1 или 2
     * о.подающий  — 1, 2 или ничего
     * о.выбранСет — номер сета или `null` (все)
     * о.разминка  — матч ещё не начался
     * о.завершён  — матч окончен
     * о.подписи   — слова на языке зовущего (см. список ниже)
     *
     * ЖУРНАЛА НЕТ — ЭТО ТРИ РАЗНЫХ СЛУЧАЯ, И ОНИ НЕ ОДИН. Первым заходом
     * на все три показывалось «Матч ещё не начался», и Костя поймал это
     * на живом матче: справа шёл счёт 1 : 0 и статус LIVE, а слева
     * стояло, что матч не начался. ПОДПИСЬ ВРАЛА.
     */
    Ж.разметка = function (о) {
        о = о || {};
        var п = о.подписи || {};
        var игры = Ж.геймы(о.очки);

        if (!игры.length) {
            if (о.разминка) {
                return '<div class="lm-empty">' +
                    '<p class="lm-empty-title">' + экр(п.emptyTitle) + '</p>' +
                    '<p class="lm-empty-text">' + экр(п.emptyText) + '</p>' +
                '</div>';
            }
            return грубая(о);
        }

        var наборы = [];
        игры.forEach(function (г) {
            if (наборы.indexOf(г.set_no) === -1) наборы.push(г.set_no);
        });

        var чипы = '';
        if (наборы.length > 1) {
            чипы += чип(null, п.allSets, о.выбранСет == null);
            наборы.forEach(function (n) {
                чипы += чип(n, n + '-й ' + п.setN, о.выбранСет === n);
            });
            чипы = '<div class="lm-feed-chips">' + чипы + '</div>';
        }

        var видимые = игры.filter(function (г) {
            return о.выбранСет == null || г.set_no === о.выбранСет;
        });

        /* Заголовок и чипы сетов стоят НЕПОДВИЖНО, прокручивается только
           список геймов. Иначе, уехав к первому сету, человек теряет и
           подпись панели, и переключатель, которым он туда шёл. */
        return '<div class="lm-feed">' +
            '<p class="lm-feed-title">' + экр(п.feedTitle) + '</p>' + чипы +
            '<div class="lm-feed-games">' +
                видимые.slice().reverse().map(function (г) { return гейм(о, г); }).join('') +
            '</div>' +
        '</div>';
    };

    /**
     * Нажатия на чипы сетов. Зовущий решает, что делать с выбором:
     * у него состояние и у него перерисовка.
     */
    Ж.включить = function (корень, приВыборе) {
        if (!корень || typeof приВыборе !== 'function') return;
        корень.addEventListener('click', function (e) {
            var чип = e.target.closest ? e.target.closest('.lm-chip') : null;
            if (!чип || !корень.contains(чип)) return;
            var знач = чип.getAttribute('data-set');
            приВыборе(знач === '' ? null : Number(знач));
        });
    };
})();
