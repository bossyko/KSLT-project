(function (global) {
    'use strict';

    var API = global.KSLT_DOKUMENTY = {};

    /**
     * СПИСОК ДОКУМЕНТОВ. Порядок — от того, что спрашивают площадки, к
     * тому, что читает человек: политика первой.
     */
    API.СПИСОК = [
        { имя: 'privacy', страница: 'privacy-policy' },
        { имя: 'offer',   страница: 'offer' },
        { имя: 'rules',   страница: 'rules' },
        { имя: 'terms',   страница: 'terms' }
    ];

    /**
     * Адрес документа на нужном языке.
     *
     * @param {string} страница — имя файла без расширения
     * @param {string} язык — 'ru' | 'en' | 'kg'
     */
    API.адрес = function (страница, язык) {
        var сайт = global.KSLT_SAYT;
        if (!сайт || !сайт.адрес) {
            /* БЕЗ ДОМА АДРЕСА НЕ УГАДЫВАЕМ: вписанный здесь адрес стал бы
               вторым определением одного понятия — ровно тем, что снял
               шаг A3.4. Пусто значит «ссылку не рисуем». */
            if (global.console && console.error) {
                console.error('KSLT_DOKUMENTY: нет KSLT_SAYT.адрес — ' +
                    'ссылки на документы не построены');
            }
            return '';
        }
        var файл = страница;
        if (язык === 'en' || язык === 'kg') файл = страница + '-' + язык;
        return сайт.адрес + '/pages/' + файл + '.html';
    };

    /** Все документы с готовыми адресами. Пустой адрес — документ пропущен. */
    API.все = function (язык) {
        var готово = [];
        API.СПИСОК.forEach(function (д) {
            var а = API.адрес(д.страница, язык);
            if (а) готово.push({ имя: д.имя, страница: д.страница, адрес: а });
        });
        return готово;
    };

})(typeof window !== 'undefined' ? window : this);
