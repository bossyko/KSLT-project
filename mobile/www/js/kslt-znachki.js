/**
 * ЗНАЧКИ ИГРОКА В СПИСКЕ — ОДИН ДОМ (29.10).
 *
 * ЧТО БЫЛО, ИЗМЕРЕНО ЧТЕНИЕМ. На сайте значки у имени в рейтинге живут
 * с давних пор: `js/players.js` грузит определения и значки игроков,
 * держит их в двух картах и рисует до пяти штук с подсказкой. В
 * приложении, на экране рейтинга, значков **НЕТ ВОВСЕ** — ноль
 * упоминаний на 444 строки.
 *
 * ПОЧЕМУ ДОМ, А НЕ ВТОРАЯ КОПИЯ: у значка три правила, и каждое легко
 * разъехать —
 *   · СКОЛЬКО показывать (пять: шестой не влезает в строку таблицы и
 *     выдавливает очки);
 *   · В КАКОМ ПОРЯДКЕ (по времени получения, от раннего — так человек
 *     видит свой путь, а не случайный набор);
 *   · КАК ЗОВЁТСЯ значок на языке страницы (`name`, `name_en`,
 *     `name_kg`).
 *
 * ЧЕГО В ДОМЕ НЕТ: разметки и экранирования. У сайта экранирует
 * `KSLT_экранировать`, у приложения своя `esc` — дом отдаёт ДАННЫЕ, а
 * вставляет их продукт. Это не придирка: `badge_definitions.icon` и
 * `name` — текстовые столбцы, которые пишет человек, и кусок 29.10
 * (A3.7б) уже закрывал дыру, где значок вставлялся сырым.
 *
 * Правка правится В ДВУХ МЕСТАХ: побайтовая копия в `mobile/www/js/`.
 */
(function (global) {
    'use strict';

    var API = global.KSLT_ZNACHKI = {};

    /**
     * СКОЛЬКО ЗНАЧКОВ ПОКАЗЫВАТЬ В СТРОКЕ СПИСКА.
     *
     * Пять — замер строки рейтинга: шестой выдавливает столбец очков.
     * Число одно на оба продукта, иначе на телефоне строка поедет, а на
     * сайте нет, и никто не поймёт почему.
     */
    API.СКОЛЬКО = 5;

    /**
     * ЗАГРУЗИТЬ ЗНАЧКИ ИГРОКОВ.
     *
     * Два запроса, а не один на каждого игрока: в Futures под две сотни
     * человек, и по запросу на строку список не нарисуется никогда.
     *
     * Порядок — по времени получения, от раннего: это путь человека, а
     * не случайный набор. Порядок задаёт БАЗА, а не мы, иначе два
     * продукта отсортируют по-разному.
     *
     * Никогда не бросает: значки — украшение списка, и список без них
     * лучше, чем список, который не нарисовался.
     *
     * @returns {Promise<{поИгрокам: Object, определения: Object}>}
     */
    API.загрузить = function (client) {
        if (!client) return Promise.resolve({ поИгрокам: {}, определения: {} });
        var определения = {};
        /* БРОСОК НА МЕСТЕ ЛОВИТСЯ ТОЖЕ, А НЕ ТОЛЬКО ОТКАЗ ОБЕЩАНИЯ:
           `client.from(...)` может бросить СРАЗУ (нет клиента, нет связи),
           и `.catch` ниже такого не видит — он ловит только отказ уже
           созданного обещания. Нашёл это свой же тест. Та же форма, что
           закрыта в доме входа у `запомнитьУстройство`. */
        try {
        return client.from('badge_definitions').select('*')
            .then(function (r) {
                (r.data || []).forEach(function (д) { определения[д.id] = д; });
                return client.from('player_badges')
                    .select('player_id, badge_id, badge:badge_definitions(icon)')
                    .order('earned_at', { ascending: true });
            })
            .then(function (r) {
                var поИгрокам = {};
                (r.data || []).forEach(function (пб) {
                    if (!поИгрокам[пб.player_id]) поИгрокам[пб.player_id] = [];
                    поИгрокам[пб.player_id].push({
                        badge_id: пб.badge_id,
                        icon: пб.badge ? (пб.badge.icon || '') : ''
                    });
                });
                return { поИгрокам: поИгрокам, определения: определения };
            })
            .catch(function () {
                return { поИгрокам: {}, определения: определения };
            });
        } catch (e) {
            return Promise.resolve({ поИгрокам: {}, определения: определения });
        }
    };

    /**
     * ЗНАЧКИ ОДНОГО ИГРОКА — не больше, чем влезает в строку.
     *
     * Отдаёт МАССИВ ДАННЫХ, а не разметку: вставляет и экранирует
     * продукт.
     */
    API.первые = function (слепок, игрокId, сколько) {
        var все = (слепок && слепок.поИгрокам && слепок.поИгрокам[игрокId]) || [];
        var n = сколько || API.СКОЛЬКО;
        return все.slice(0, n);
    };

    /**
     * НАЗВАНИЕ ЗНАЧКА НА ЯЗЫКЕ СТРАНИЦЫ.
     *
     * Язык передаёт продукт: у сайта он из адреса страницы, у приложения
     * из `KSLT_I18N`. Нет определения — отдаём сам номер: пустая
     * подсказка хуже непонятной.
     */
    API.название = function (слепок, значокId, язык) {
        var о = слепок && слепок.определения && слепок.определения[значокId];
        if (!о) return значокId;
        if (язык === 'en') return о.name_en || о.name || значокId;
        if (язык === 'kg') return о.name_kg || о.name || значокId;
        return о.name || значокId;
    };

})(typeof window !== 'undefined' ? window : this);
