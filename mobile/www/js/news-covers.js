/**
 * KSLT — обложка новости, когда своей картинки нет.
 *
 * Мировые новости приходят из лент источников без картинки: чужие снимки мы
 * не берём принципиально, за них платят по счетам. Раньше пустое место
 * закрывала заглушка с чужого сайта placehold.co — серый прямоугольник,
 * да ещё и запросом наружу при каждой загрузке ленты.
 *
 * Вместо неё ставим свои снимки из images/news-covers: десять кадров,
 * купленных под свободной лицензией и обрезанных под карточку.
 *
 * Обложку выбираем не случайно, а по номеру новости. Это важно: при случайном
 * выборе одна и та же новость меняла бы вид при каждом заходе, а на странице
 * и в карточке была бы разной.
 *
 * Файл общий для сайта и приложения — копия лежит в mobile/www/js/,
 * совпадение сверяет tools/check-rules.js.
 */
(function() {
    'use strict';

    var NC = window.KSLT_NEWS_COVERS = {};

    NC.ВСЕГО = 10;

    /**
     * Номер обложки по любому опознавателю новости: uuid, slug — что есть.
     * Простая сумма кодов букв. Криптографии тут не надо, нужна только
     * устойчивость: один и тот же ключ всегда даёт одно и то же число.
     */
    NC.номер = function(ключ) {
        var s = String(ключ || '');
        if (!s) return 1;
        var сумма = 0;
        for (var i = 0; i < s.length; i++) {
            сумма = (сумма * 31 + s.charCodeAt(i)) % 100000;
        }
        return (сумма % NC.ВСЕГО) + 1;
    };

    /**
     * Путь к обложке. Приставку задаёт вызывающий: страницы новостей лежат
     * в pages/, приложение — в корне своей папки.
     */
    NC.путь = function(ключ, приставка) {
        return (приставка || '') + 'images/news-covers/' + NC.номер(ключ) + '.jpg';
    };
})();
