/**
 * РИСУНОК ГРУППЫ И СЕТКИ — ОДИН ДОМ НА САЙТ И ПРИЛОЖЕНИЕ (кусок 216, 28.10).
 *
 * ЗАЧЕМ. Круговая таблица группы жила только в `js/tournament-detail.js`.
 * Приложение рисовало СВОЁ: таблицу итогов плюс отдельные карточки каждого
 * матча. Те же данные были разложены дважды и занимали 5.24 экрана против
 * 2.99 на сайте, а главного — кто кого обыграл — в приложении видно не
 * было. Костя сказал про это прямо: «не понятно, а не получится поместить
 * группу как на сайте».
 *
 * Скопировать рисовальщик в приложение значило бы завести второе
 * определение одного понятия — и они разошлись бы на первой же правке.
 * Поэтому он здесь: файл общий, копия в `mobile/www/js/` сверяется до
 * байта сторожем.
 *
 * ЧТО ЗДЕСЬ НЕТ. Расчёта мест: он давно в общем доме `KSLT_GROUPS`
 * (`js/group-standings.js`). Здесь только разметка.
 *
 * ЧЕМ КОРМИТЬ. Зовущий даёт данные и две подстановки, своя у каждого
 * продукта:
 *   имя(playerId)   → РАЗМЕТКА имени участника (у пары — два блока);
 *   слово(ключ)     → перевод подписи, ключи ниже в `СЛОВА`.
 * Так дом не знает ни про язык сайта, ни про словарь приложения.
 */
(function (global) {
    'use strict';

    var S = {};

    /* Исходы, которые стоят в счёте последним словом: снятие, неявка. */
    var ИСХОДЫ = ['RET', 'W/O', 'DEF', 'NA'];

    /* Ключи подписей, которые обязан знать зовущий. */
    S.СЛОВА = ['num', 'player', 'wins', 'games', 'place', 'group',
               'lot', 'lotHint', 'whyHead', 'whyMini', 'whySets', 'whyGames'];

    /**
     * Почему место такое: жребий либо то, чем развели равных.
     * Разметка одна, слова — от зовущего.
     */
    function почемуМесто(st, слово) {
        if (st.жребий) {
            return '<span class="td-grp-lot" title="' + слово('lotHint') + '">' +
                   слово('lot') + '</span>';
        }
        var ключ = {
            'встреча': 'whyHead',
            'между собой': 'whyMini',
            'сеты': 'whySets',
            'геймы': 'whyGames'
        }[st.причина];
        return ключ ? '<span class="td-grp-lot">' + слово(ключ) + '</span>' : '';
    }

    /**
     * Счёт в клетке «кто кого». Разворачивается, если игрок стоит вторым:
     * в своей строке человек обязан видеть СВОЙ счёт первым.
     */
    function счётВКлетке(match, playerId) {
        var части = match.score.split(' ');
        var исход = '';
        if (части.length > 0 && ИСХОДЫ.indexOf(части[части.length - 1]) !== -1) {
            исход = части.pop();
        }
        var счёт;
        if (match.player2_id === playerId) {
            счёт = части.map(function (s) {
                var p = s.split('/');
                return p.length === 2 ? p[1] + ':' + p[0] : s;
            }).join(' ');
        } else {
            счёт = части.join(' ').replace(/\//g, ':');
        }
        return исход ? счёт + ' ' + исход : счёт;
    }

    /**
     * КРУГОВАЯ ТАБЛИЦА ОДНОЙ ГРУППЫ.
     *
     * опции:
     *   буква        — «A», «B»: как группа называется
     *   места        — расчёт KSLT_GROUPS.расчёт, уже с ручными местами
     *   матчи        — матчи ЭТОЙ группы
     *   имя          — имя(playerId) → разметка
     *   слово        — слово(ключ) → перевод
     *   проходят     — сколько мест выводит из группы
     *   прошёл       — прошёл(st) → выделять ли строку. По умолчанию
     *                  «место не ниже `проходят`, и этап закрыт».
     *                  У лиг своё: верх идёт в высшую, низ в утешительную,
     *                  выделяются обе — поэтому решение отдано зовущему
     *   классПрошедшего — имя класса такой строки (по умолчанию
     *                  `td-gt-qualified`)
     *   итогВперёд   — поставить «В · Геймы · М» СРАЗУ ПОСЛЕ ИМЕНИ, а
     *                  встречи увести вправо. Нужно на узком экране:
     *                  замер на 375 при четырёх игроках — таблица 477
     *                  при видимых 311, и место, ЗА КОТОРЫМ таблицу и
     *                  открывают, оставалось за краем. Порядок зависит
     *                  от ШИРИНЫ, а не от продукта: на сайте места
     *                  хватает, и там он прежний
     *   фамилия      — фамилия(playerId) → фамилия текстом, для клетки
     *                  незаполненного матча (необязательно)
     *   группаЗакрыта — все матчи сыграны (от этого знак жеребьёвки)
     *   этапЗакрыт   — закрыт весь групповой этап (от этого подсветка прошедших)
     */
    S.круговаяГруппа = function (опции) {
        var места = опции.места || [];
        var матчи = опции.матчи || [];
        var имя = опции.имя;
        var слово = опции.слово;
        var естьРезультаты = матчи.some(function (m) { return m.status === 'completed'; });

        var итогВперёд = !!опции.итогВперёд;
        var шапкаИтога = '<th class="td-gt-wins">' + слово('wins') + '</th>' +
                         '<th class="td-gt-games">' + слово('games') + '</th>' +
                         '<th class="td-gt-place">' + слово('place') + '</th>';
        var шапкаВстреч = '';
        for (var c = 0; c < места.length; c++) шапкаВстреч += '<th class="td-gt-opp">' + (c + 1) + '</th>';

        var h = '<div class="td-gt-block">';
        h += '<div class="td-group-name">' + слово('group') + ' ' + опции.буква + '</div>';
        h += '<div class="td-gt-scroll"><table class="td-group-table' +
             (итогВперёд ? ' itog-vperyod' : '') + '">';
        h += '<thead><tr><th>' + слово('num') + '</th><th>' + слово('player') + '</th>';
        h += итогВперёд ? (шапкаИтога + шапкаВстреч) : (шапкаВстреч + шапкаИтога);
        h += '</tr></thead><tbody>';

        var классПрошедшего = опции.классПрошедшего || 'td-gt-qualified';
        var прошёлЛи = опции.прошёл || function (st) {
            return st.place <= (опции.проходят || 2) && опции.этапЗакрыт;
        };

        for (var row = 0; row < места.length; row++) {
            var st = места[row];
            var прошёл = прошёлЛи(st);

            h += '<tr data-player-id="' + st.playerId + '"' +
                 (прошёл ? ' class="' + классПрошедшего + '"' : '') + '>';
            h += '<td class="td-gt-num">' + (row + 1) + '</td>';
            /* 28.10, КУСОК 219: посев ПЕРЕД именем. Слово Кости: «номер
               сеяного наверно лучше поставить перед ФИО, а не после».
               Так же стоит и в клетке сетки — посев там всегда был
               первым, и теперь оба места читаются одинаково. */
            h += '<td class="td-gt-name">' +
                 (st.seed ? '<span class="td-gt-seed">[' + st.seed + ']</span> ' : '') +
                 имя(st.playerId) + '</td>';

            var встречи = '';
            for (var col = 0; col < места.length; col++) {
                if (row === col) { встречи += '<td class="td-gt-self">&times;</td>'; continue; }
                var oppId = места[col].playerId;
                var match = матчи.find(function (m) {
                    return (m.player1_id === st.playerId && m.player2_id === oppId) ||
                           (m.player1_id === oppId && m.player2_id === st.playerId);
                });
                if (match && match.status === 'completed' && match.score) {
                    var выиграл = match.winner_id === st.playerId;
                    встречи += '<td class="td-gt-score' + (выиграл ? ' td-gt-win' : '') + '">' +
                         счётВКлетке(match, st.playerId) + '</td>';
                } else if (match) {
                    /* Матч есть, счёта ещё нет: клетка несёт номер матча —
                       по нему свой счёт заполняется прямо отсюда. Фамилия
                       соперника кладётся рядом: `js/my-match-buttons.js`
                       подставляет её подложкой, иначе две соседние клетки
                       сливаются в полосу и непонятно, с кем какой матч. */
                    var фам = опции.фамилия ? опции.фамилия(oppId) : '';
                    встречи += '<td class="td-grp-cell td-gt-empty" data-match-id="' + match.id +
                         '" data-opp="' + фам + '">—</td>';
                } else {
                    встречи += '<td class="td-gt-empty">—</td>';
                }
            }

            var доли = global.KSLT_GROUPS.долиГеймов(st.разбор);
            var итог = '<td class="td-gt-total">' + st.wins + '</td>';
            /* Процент геймов — только у спорных: `разбор` заполняется лишь
               у тех, кого разводил расчёт при равных победах. У кого спора
               не было — прочерк, число там только мешает (слово Кости 01.10). */
            итог += '<td class="td-gt-ratio">' +
                 (естьРезультаты && доли
                    ? st.разбор.gamesWon + '-' + st.разбор.gamesLost +
                      '<br><span class="td-gt-ratio-pct">' + доли.процент + '</span>'
                    : '—') + '</td>';
            итог += '<td class="td-gt-pos' + (прошёл ? ' td-gt-win' : '') + '">' +
                 (естьРезультаты ? st.place : '—') +
                 (опции.группаЗакрыта ? почемуМесто(st, слово) : '') + '</td>';

            h += итогВперёд ? (итог + встречи) : (встречи + итог);
            h += '</tr>';
        }

        h += '</tbody></table></div></div>';
        return h;
    };

    /**
     * КЛЕТКА МАТЧА В СЕТКЕ.
     *
     * Разметка одна на сайт и приложение; всё, что зависит от продукта,
     * приходит подстановками:
     *   игрок(id)        → { имя: РАЗМЕТКА, посев, оформление }
     *   меткаГруппы(id)  → «A1», «G2» или пусто
     *   слот(matchId)    → { s1, s2 } — кого ждёт пустая клетка
     *   проход(матч)     → в клетке окажется ровно один человек
     *   подвал(матч)     → свой довесок под клеткой (у сайта — полоса
     *                      предсказания; у приложения её нет)
     *
     * ПУСТАЯ КЛЕТКА БЫВАЕТ ДВУХ РОДОВ: BYE — соперника не будет вовсе,
     * TBD — он ещё приедет из прошлого круга. Решает `проход`, а где
     * метки слотов проставлены — отсутствие метки и есть BYE (слово
     * Кости 02.10: «поставим BYE, а не TBD, где понятно, что нет игр»).
     */
    /* Метка пустого слота: «A1» — победитель группы A, «Q1» — первый из
       отбора. Понятнее безликого «TBD» и видно сразу после жеребьёвки. */
    function метка(текст) {
        return '<span class="td-slot-wait">' + текст + '</span>';
    }

    S.матч = function (м, опции) {
        var игрок = опции.игрок;
        var p1 = игрок(м.player1Id);
        var p2 = игрок(м.player2Id);

        var этоПроход = !!опции.проход && опции.проход(м) &&
                        !!(м.player1Id || м.player2Id);
        if (!м.player1Id && м.player2Id && этоПроход) p1 = { имя: 'BYE' };
        if (!м.player2Id && м.player1Id && этоПроход) p2 = { имя: 'BYE' };

        var слоты = опции.слот ? опции.слот(м.matchId) : null;
        if (слоты) {
            if (!м.player1Id && p1.имя === 'TBD') {
                p1 = слоты.s1 ? { имя: метка(слоты.s1) } : { имя: 'BYE' };
            }
            if (!м.player2Id && p2.имя === 'TBD') {
                p2 = слоты.s2 ? { имя: метка(слоты.s2) } : { имя: 'BYE' };
            }
        }

        /* Счёт приводится к мировой записи ПЕРЕД разбором: в скобке
           очки проигравшего одним числом, и скобка у проигравшего сет
           (слово Кости 28.10). Дом общий, значит и сайт, и приложение
           показывают одинаково. Нет дома правил — показываем как есть,
           а не падаем. */
        var строкаСчёта = (global.KSLT_RULES && global.KSLT_RULES.счётПоМировому)
            ? global.KSLT_RULES.счётПоМировому(м.score) : м.score;
        var сырые = строкаСчёта ? String(строкаСчёта).split(' ') : [];
        var исход = '';
        if (сырые.length > 0 && ИСХОДЫ.indexOf(сырые[сырые.length - 1]) !== -1) {
            исход = сырые.pop();
        }
        /* ПРОХОД: BYE уже написан ИМЕНЕМ СОПЕРНИКА. Вторым разом он
           приходил из поля счёта и вставал рядом с именем победителя,
           отжимая его на две строки. Одно понятие — одно место. */
        if (этоПроход) { сырые = []; исход = ''; }

        var p1Класс = м.winnerId === м.player1Id ? 'winner' : (м.winnerId ? 'loser' : '');
        var p2Класс = м.winnerId === м.player2Id ? 'winner' : (м.winnerId ? 'loser' : '');

        function сторона(p, класс, метка, номер) {
            var h = '<div class="td-match-player ' + класс + '">' +
                (p.посев ? '<span class="td-seed">[' + p.посев + ']</span>'
                         : '<span class="td-seed"></span>') +
                (метка ? '<span class="td-grp-label">' + метка + '</span>' : '') +
                '<span class="td-player-name">' + p.имя + '</span>';
            if (м.status === 'live' && сырые.length > 0 && номер === 1) {
                h += '<span class="td-match-score live-score">' + сырые.join(' ') + '</span>';
            } else if (м.status !== 'live') {
                сырые.forEach(function (s) {
                    var ч = s.split('/');
                    h += '<span class="td-match-score">' + (ч[номер - 1] || '') + '</span>';
                });
            }
            if (номер === 1 && исход) h += '<span class="td-match-outcome">' + исход + '</span>';
            return h + '</div>';
        }

        /* Состояние идёт в ИМЯ КЛАССА, поэтому сюда пускаются только
           буквы и подчёркивание: столбец `matches.status` текстовый и
           без CHECK со списком значений, то есть по схеме его может
           написать человек. Экранирование тут не спасло бы — в значении
           атрибута нужен не обход кавычек, а белый список. Поймал
           сторож «данные в разметке» куском 227. */
        var состояние = String(м.status || '').replace(/[^a-zA-Z_]/g, '');
        var h = '<div class="td-match ' + состояние + '"' +
                ' data-p1="' + (м.player1Id || '') + '" data-p2="' + (м.player2Id || '') + '"' +
                (м.matchId ? ' data-match-id="' + м.matchId + '"' : '') + '>';
        h += сторона(p1, p1Класс, опции.меткаГруппы ? опции.меткаГруппы(м.player1Id) : '', 1);
        h += сторона(p2, p2Класс, опции.меткаГруппы ? опции.меткаГруппы(м.player2Id) : '', 2);
        if (опции.подвал) h += опции.подвал(м) || '';
        return h + '</div>';
    };

    /**
     * СЕТКА СТОЛБЦАМИ: круг, столбец соединительных линий, следующий круг.
     *
     * Та же разметка стояла в коде сайта ЧЕТЫРЕЖДЫ — у одиночной сетки, у
     * лиги, у кругового плей-офф и у сетки «все места». Одно понятие,
     * четыре копии: беда родилась бы ровно на шве.
     *
     * круги: [{ name, matches: [матч] }]
     */
    /* Экранирование — из общего дома, когда он есть; иначе свои пять
       знаков. Второго определения не заводим: это ТОТ ЖЕ набор знаков,
       что в `js/kslt-ekranirovanie.js`, и он сверяется правилом ниже. */
    function экр(значение) {
        if (global.KSLT_экранировать) return global.KSLT_экранировать(значение);
        if (значение === null || значение === undefined) return '';
        return String(значение).replace(/&/g, '&amp;').replace(/</g, '&lt;')
            .replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
    }

    S.сетка = function (круги, опции) {
        var h = '<div class="td-bracket-scroll"><div class="td-bracket">';
        круги.forEach(function (круг, i) {
            h += '<div class="td-bracket-round">';
            /* Подпись круга приходит доводом от зовущего. Сегодня её
               отдаёт словарь (`playoffRoundName`), но дом не может это
               ПРОВЕРИТЬ — он видит только строку. Экранируем: назвать
               место исключением значило бы решить за Костю, что дыру мы
               чиним словами, а не кодом (кусок 227). */
            h += '<div class="td-round-title">' + экр(круг.name) + '</div>';
            h += '<div class="td-bracket-matches">';
            круг.matches.forEach(function (м) { h += S.матч(м, опции); });
            h += '</div>';
            /* Хвост последнего круга — матч за третье место. Он стоит В
               КОЛОНКЕ ФИНАЛА, но ниже: так на сайте
               (js/tournament-detail.js:1715). Отдельным блоком ПОСЛЕ всей
               сетки он уезжал под первый столбец, потому что полоса
               прокручивается вбок, а блок за её пределами — нет. */
            if (i === круги.length - 1 && опции.хвост) h += опции.хвост;
            h += '</div>';
            if (i < круги.length - 1) {
                /* Столбец линий между кругами. Пар ровно вдвое меньше,
                   чем матчей в текущем круге: каждая пара сводится в один
                   матч следующего. */
                var пар = Math.floor(круг.matches.length / 2);
                h += '<div class="td-connector-column">';
                h += '<div class="td-round-title td-round-title-spacer">&nbsp;</div>';
                h += '<div class="td-connector-inner">';
                for (var c = 0; c < пар; c++) {
                    h += '<div class="td-connector-pair"><div class="td-conn-top"></div>' +
                         '<div class="td-conn-mid"></div><div class="td-conn-bottom"></div></div>';
                }
                h += '</div></div>';
            }
        });
        return h + '</div></div>';
    };

    global.KSLT_SETKA = S;
})(typeof window !== 'undefined' ? window : this);
