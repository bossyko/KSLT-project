/**
 * ВХОД: ОБЩИЕ ПРАВИЛА И ЗОВЫ — ОДИН ДОМ (шаг A3.7е, 29.10).
 *
 * ЧТО БЫЛО. `js/auth.js` (2162 строки) и `mobile/www/js/auth.js` (1089)
 * — самое крупное расхождение продукта и последний ДОЛГ переписи копий.
 * Экраны входа у сайта и приложения законно разные: у сайта страница с
 * вкладками, у приложения накладка. А вот ОДИННАДЦАТЬ ПОНЯТИЙ были
 * написаны дважды и трижды — 34 места в четырёх файлах, — и на каждом
 * шве уже что-то разошлось:
 *
 *   1. ПОХОЖЕ ЛИ НА ПОЧТУ — два объявления, сегодня знак в знак;
 *   2. ПРОСТОЙ ХЕШ — два объявления, знак в знак;
 *   3. ОТПЕЧАТОК УСТРОЙСТВА и письмо о новом входе — два места, и у
 *      приложения АДРЕС БАЗЫ ЗАШИТ строкой, а ключ пуст по умолчанию:
 *      то же, что снял шаг A3.4 в другом файле;
 *   4. ЗАДЕРЖКА ПОВТОРНОЙ ОТПРАВКИ КОДА — у сайта ЛЕСТНИЦА
 *      30 · 60 · 120 · 300, выведенная из серверного предела «пять
 *      запросов в час», у приложения ПЛОСКИЕ 60 в двух местах. Человек в
 *      приложении, не получивший письма, жмёт повтор каждую минуту,
 *      упирается в предел на пятом разе и получает блокировку на
 *      четверть часа — наказание за медленное письмо. И первое ожидание
 *      у него 60 вместо 30: ждёт вдвое дольше, чем нужно;
 *   5. ЗОВ `send-otp` — два места. У сайта уходит ЯЗЫК СТРАНИЦЫ (сервер
 *      иначе не знает, на каком языке писать: при регистрации профиля
 *      ещё нет), у приложения НЕ УХОДИТ. И у сайта есть разбор ответа,
 *      который пришёл не в JSON, а у приложения слепой `r.json()`:
 *      упади функция — человек получает SyntaxError вместо объяснения;
 *   6. ЗОВ `verify-otp` — ШЕСТЬ МЕСТ: пять на сайте, одно в приложении.
 *      Каждое собирает свои заголовки;
 *   7. ЗОВ `ensure-player-card` — ПЯТЬ МЕСТ: `auth.js`,
 *      `tournament-register.js`, `dashboard.js` дважды и приложение;
 *   8. ЗОВЫ `telegram-auth` (2) и `rate-limit` (3) — своего правила не
 *      несут, им нужен один способ позвать; в трёх местах приложения
 *      рядом стоял ЗАШИТЫЙ АДРЕС БАЗЫ;
 *   9. ПИСЬМО О СОБЫТИИ БЕЗОПАСНОСТИ — ЧЕТЫРЕ МЕСТА: новое устройство у
 *      сайта и у приложения, смена телефона и смена пароля в кабинете;
 *  10. ТРЕТЬЯ КОПИЯ ХЕША нашлась в `js/dashboard.js` (список устройств),
 *      и в её подписи стояло «считаем в точности как при входе
 *      (js/auth.js, simpleHash)» — автор ЗНАЛ, что это копия, и попросил
 *      будущего себя не разойтись. ПОЧИНИЛ ОДИН — ПРОВЕРЬ БЛИЗНЕЦА.
 *
 * ЧЕГО В ДОМЕ НЕТ: ни одного экрана, ни одной надписи, ни одного
 * обработчика нажатия. Дом отдаёт ДАННЫЕ и ЧИСЛА; что показать человеку,
 * решает продукт.
 *
 * ЧЕГО ОН НЕ ТРОГАЕТ НАМЕРЕННО: вход через Apple. У сайта он есть
 * (`js/auth.js`), у приложения нет, и без него правило 4.8 даёт прямой
 * отказ в App Store. Это шаг E3, отдельный кусок.
 *
 * Правка правится В ДВУХ МЕСТАХ: побайтовая копия в `mobile/www/js/`.
 */
(function (global) {
    'use strict';

    var API = global.KSLT_VHOD = {};

    /* ОДИН АДРЕС БАЗЫ НА ПРОДУКТ. Приложение держало здесь строку
       `https://…supabase.co` и пустой ключ по умолчанию: пустой ключ даёт
       молчаливый отказ сервера, а зашитый адрес — второе место, где
       живёт адрес базы. Шаг A3.4 назвал это бедой в другом файле. */
    function настройки() {
        return {
            адрес: global.SUPABASE_URL,
            ключ: global.SUPABASE_ANON_KEY
        };
    }

    /**
     * ПОХОЖЕ ЛИ НА ПОЧТУ.
     *
     * Правило нарочно мягкое: решает сервер, а здесь — чтобы не гонять
     * человека за кодом на заведомо не-адрес.
     */
    API.почтой = function (адрес) {
        return /^[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+(\.[A-Za-z0-9-]+)*\.[A-Za-z]{2,}$/
            .test(адрес || '');
    };

    /** ПРОСТОЙ ХЕШ строки. Не для тайны — только чтобы узнать устройство. */
    API.хеш = function (строка) {
        var h = 0;
        var с = String(строка == null ? '' : строка);
        for (var i = 0; i < с.length; i++) {
            h = ((h << 5) - h) + с.charCodeAt(i);
            h |= 0;
        }
        return h.toString(36);
    };

    /** ОТПЕЧАТОК УСТРОЙСТВА: обозреватель плюс размер экрана. */
    API.отпечаток = function () {
        var ua = (global.navigator && global.navigator.userAgent) || '';
        var э = global.screen || {};
        return API.хеш(ua + '|' + (э.width || 0) + 'x' + (э.height || 0));
    };

    /**
     * ПИСЬМО О СОБЫТИИ БЕЗОПАСНОСТИ — почтой и в телеграм.
     *
     * Зов стоял в ЧЕТЫРЁХ местах: новое устройство у сайта и у
     * приложения, смена телефона и смена пароля в кабинете. Каждое место
     * само добывало токен и само собирало заголовки.
     *
     * Ничего не держит и никогда не бросает: событие уже случилось, и
     * неудачное письмо о нём не должно ломать то, что человек делал.
     */
    API.письмоБезопасности = function (client, событие, подробности) {
        return client.auth.getSession().then(function (s) {
            var токен = s.data && s.data.session && s.data.session.access_token;
            if (!токен) return false;
            var н = настройки();
            return fetch(н.адрес + '/functions/v1/security-notify', {
                method: 'POST',
                headers: {
                    'Authorization': 'Bearer ' + токен,
                    'Content-Type': 'application/json',
                    'apikey': н.ключ
                },
                body: JSON.stringify({
                    event_type: событие,
                    metadata: подробности || {}
                })
            }).then(function () { return true; }).catch(function () { return false; });
        }).catch(function () { return false; });
    };

    /**
     * ЗАПОМНИТЬ УСТРОЙСТВО, А О НОВОМ — НАПИСАТЬ ЧЕЛОВЕКУ.
     *
     * Ничего не держит и никогда не бросает: вход не должен падать из-за
     * того, что не записалось устройство.
     */
    API.запомнитьУстройство = function (client, профильId) {
        try {
            var отпечаток = API.отпечаток();
            var ua = ((global.navigator && global.navigator.userAgent) || '').substring(0, 500);
            return client.from('user_devices')
                .select('id')
                .eq('profile_id', профильId)
                .eq('device_hash', отпечаток)
                .maybeSingle()
                .then(function (res) {
                    var новое = !res.data;
                    client.from('user_devices').upsert({
                        profile_id: профильId,
                        device_hash: отпечаток,
                        user_agent: ua,
                        last_seen: new Date().toISOString()
                    }, { onConflict: 'profile_id,device_hash' }).then(function () {});
                    if (!новое) return false;
                    return API.письмоБезопасности(client, 'new_device_login', { user_agent: ua });
                }).catch(function () { return false; });
        } catch (e) {
            return Promise.resolve(false);
        }
    };

    /* ЛЕСТНИЦА ПОВТОРНОЙ ОТПРАВКИ КОДА.
       ПОЧЕМУ ЛЕСТНИЦА, А НЕ ОДНО ЧИСЛО: первое ожидание в отрасли
       30 секунд — за это время письмо либо дошло, либо не дойдёт, и 60
       заставляло человека ждать зря. Дальше растёт, чтобы повтор не
       дёргали без конца. Верхняя ступень 300 держится и дальше — это
       укладывается в серверный предел пяти запросов в час (`send-otp`,
       RATE_LIMIT_MAX).
       СЛОМАЕТСЯ, ЕСЛИ не сбросить шаг при входе на экран кода: человек,
       вернувшийся к форме заново, получит ожидание с прошлого раза. */
    API.ЛЕСТНИЦА_ПОВТОРА = [30, 60, 120, 300];
    var _шаг = 0;

    API.задержкаПовтора = function () {
        var с = API.ЛЕСТНИЦА_ПОВТОРА[Math.min(_шаг, API.ЛЕСТНИЦА_ПОВТОРА.length - 1)];
        _шаг++;
        return с;
    };

    API.сбросПовтора = function () { _шаг = 0; };

    /**
     * РАЗБОР ОТВЕТА СЕРВЕРНОЙ ФУНКЦИИ.
     *
     * Ответ разбирался вслепую. Если функция не развёрнута или упала,
     * тело приходит не в JSON, разбор падает — и человек видел «произошла
     * ошибка» без единого намёка на причину, а в консоли не оставалось и
     * того. У сайта это починено, у приложения стоял слепой `r.json()`.
     */
    function разобрать(resp, имя) {
        return resp.text().then(function (текст) {
            var данные;
            try {
                данные = JSON.parse(текст);
            } catch (e) {
                if (global.console && console.error) {
                    console.error('[KSLT] ' + имя + ' ответил не JSON:',
                        resp.status, String(текст).slice(0, 300));
                }
                throw new Error(имя + ': HTTP ' + resp.status);
            }
            if (!resp.ok || данные.error) {
                if (global.console && console.error) {
                    console.error('[KSLT] ' + имя + ':', resp.status, данные);
                }
            }
            return данные;
        });
    }
    API.разобрать = разобрать;

    /**
     * ОДИН ЗОВ ФУНКЦИИ БЕЗ ВХОДА. Заголовки собирались в ДЕВЯТИ местах:
     * `send-otp` 2, `verify-otp` 6, `telegram-auth` 2, `rate-limit` 3 —
     * и в трёх местах приложения рядом стоял ЗАШИТЫЙ АДРЕС БАЗЫ со
     * ПУСТЫМ ключом по умолчанию, то есть молчаливый отказ сервера.
     *
     * Отдан наружу как `зовФункции`: `telegram-auth` и `rate-limit`
     * своего правила не несут — им нужен только один способ позвать.
     */
    function позвать(имя, тело) {
        var н = настройки();
        return fetch(н.адрес + '/functions/v1/' + имя, {
            method: 'POST',
            headers: { 'Content-Type': 'application/json', 'apikey': н.ключ },
            body: JSON.stringify(тело)
        }).then(function (resp) { return разобрать(resp, имя); });
    }

    API.зовФункции = позвать;

    /**
     * ОТПРАВИТЬ КОД.
     *
     * ЯЗЫК ОБЯЗАТЕЛЕН И ПЕРЕДАЁТСЯ ПРОДУКТОМ: при регистрации профиля
     * ещё нет, и сервер не знает, на каком языке писать. У приложения
     * язык не уходил вовсе.
     *
     * @param {Object} о — { поток, адресат, видАдресата, язык,
     *                       телеграм, turnstile }
     */
    API.отправитьКод = function (о) {
        о = о || {};
        var тело = {
            flow: о.поток,
            identifier: о.адресат,
            identifier_type: о.видАдресата,
            lang: о.язык || 'ru'
        };
        if (о.телеграм) тело.telegram_chat_id = о.телеграм;
        if (о.turnstile) тело.turnstile_token = о.turnstile;
        return позвать('send-otp', тело);
    };

    /**
     * ПРОВЕРИТЬ КОД.
     *
     * Зов стоял в ШЕСТИ местах: пять на сайте (регистрация, забытый
     * пароль, смена пароля, вход по коду, регистрация через телеграм) и
     * одно в приложении. Поток и всё, что к нему приложено, передаёт
     * зовущий — дом собирает посылку и разбирает ответ.
     */
    API.проверитьКод = function (поток, адресат, код, ещё) {
        var тело = { flow: поток, identifier: адресат, code: код };
        if (ещё) {
            Object.keys(ещё).forEach(function (к) {
                if (ещё[к] !== undefined) тело[к] = ещё[к];
            });
        }
        return позвать('verify-otp', тело);
    };

    /**
     * ЗАВЕСТИ КАРТОЧКУ ИГРОКА.
     *
     * Зов стоял в ПЯТИ местах. Отдаёт `'created'`, `'candidate'` или
     * пусто: нашлась похожая карточка с чужим рейтингом и историей —
     * сервер её не присваивает, человек подтверждает сам.
     *
     * Этот зов идёт ОТ ИМЕНИ ЧЕЛОВЕКА, поэтому ему нужен токен, а не
     * только ключ.
     */
    API.карточкаИгрока = function (client, тело) {
        return client.auth.getSession().then(function (сессия) {
            if (!(сессия.data && сессия.data.session)) return null;
            var н = настройки();
            return fetch(н.адрес + '/functions/v1/ensure-player-card', {
                method: 'POST',
                headers: {
                    'Content-Type': 'application/json',
                    'apikey': н.ключ,
                    'Authorization': 'Bearer ' + сессия.data.session.access_token
                },
                body: JSON.stringify(тело || {})
            }).then(function (resp) {
                return разобрать(resp, 'ensure-player-card');
            });
        }).catch(function () { return null; });
    };

    /**
     * ТОЛЬКО СТАТУС — для тех трёх мест, которым больше ничего не нужно.
     * Кабинету нужен весь ответ: там ещё `candidate` и `player_id`,
     * поэтому он зовёт `карточкаИгрока` напрямую.
     */
    API.завестиКарточку = function (client) {
        return API.карточкаИгрока(client).then(function (д) {
            return (д && д.status) || '';
        });
    };

})(typeof window !== 'undefined' ? window : this);
