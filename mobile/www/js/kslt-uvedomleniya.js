/**
 * НАСТРОЙКИ УВЕДОМЛЕНИЙ — ОДИН ДОМ (шаг A2.3, 29.10).
 *
 * ЧТО БЫЛО, ИЗМЕРЕНО ЧТЕНИЕМ.
 *
 * Настройки живут в `profiles.notify_preferences` (jsonb) в виде
 * `{ канал: { раздел: true|false } }`, и читают их ШЕСТНАДЦАТЬ серверных
 * функций одним и тем же правилом `shouldNotify(prefs, channel, cat)`:
 * нет настроек — отправляем, нет канала — отправляем, иначе смотрим
 * `!== false`. То есть УМОЛЧАНИЕ — «включено», и это свойство данных, а
 * не разметки.
 *
 * А экраны расходились с этим договором по трём местам:
 *
 *   1. САЙТ рисовал ТРИ канала — `site`, `tg`, `email`
 *      (`js/dashboard.js:5711`), а канал `site` НЕ СПРАШИВАЕТ НИ ОДНА из
 *      шестнадцати функций. Человек выключал ползунок, и ничего не
 *      менялось. ОРГАН УПРАВЛЕНИЯ, КОТОРЫЙ ДЕЛАЕТ НЕ ТО, ЧТО ОБЕЩАЕТ,
 *      ХУЖЕ ОТСУТСТВУЮЩЕГО — столбец снят. Научить сервер его
 *      спрашивать значило бы тронуть ТРИНАДЦАТЬ мест записи в
 *      колокольчик (7 edge-функций и 6 функций в базе) и сперва
 *      починить словарь `notification_log.type`, где уже живут два
 *      написания одного понятия (`challenge`/`challenges`,
 *      `match`/`matches`). Это свой кусок.
 *
 *   2. РАЗДЕЛОВ НА ЭКРАНЕ БЫЛО ЧЕТЫРЕ, а сервер спрашивает ШЕСТЬ:
 *      кроме `membership`, `tournaments`, `matches`, `challenges` ещё
 *      `security` (письма о входе с нового устройства) и `general`.
 *      Их нельзя было выключить вовсе — а мы в анкетах магазинов
 *      заявляем, что человек управляет рассылками.
 *
 *   3. ПРИЛОЖЕНИЕ НЕ СОВПАДАЛО НИ В ЧЁМ: писало в таблицу
 *      `notification_preferences`, КОТОРОЙ В БАЗЕ НЕТ ВОВСЕ (проверено
 *      запросом 29.10: «relation does not exist», ни в одной схеме);
 *      каналы звались `telegram`/`email` вместо `tg`/`email`; разделы —
 *      `tournament`/`payment`/`system`/`marketing` вместо шести
 *      настоящих. Восемь ползунков показывались ВКЛЮЧЁННЫМИ
 *      (`profile.js:1546`, `// default on`) и падали при касании, а
 *      перед падением приложение успевало спросить у человека системное
 *      разрешение на пуши.
 *
 * ЧЕГО В ДОМЕ НЕТ: ни одной надписи и ни одной строки разметки. Дом
 * знает ИМЕНА каналов и разделов — те самые, что спрашивает сервер, — и
 * правило «включено ли». Слова и вид берёт продукт.
 *
 * Правка правится В ДВУХ МЕСТАХ: побайтовая копия в `mobile/www/js/`.
 */
(function (global) {
    'use strict';

    var API = global.KSLT_UVEDOMLENIYA = {};

    /**
     * КАНАЛЫ — РОВНО ТЕ, ЧТО СПРАШИВАЕТ СЕРВЕР.
     *
     * Замер 29.10 по `supabase/functions/`: `shouldNotify` зовут с
     * `'tg'` 26 раз и с `'email'` 13 раз. С `'site'` — НИ РАЗУ.
     */
    API.КАНАЛЫ = ['tg', 'email'];

    /**
     * РАЗДЕЛЫ — РОВНО ТЕ, ЧТО СПРАШИВАЕТ СЕРВЕР.
     *
     * Замер 29.10: `tournaments` 9 зовов · `challenges` 11 ·
     * `membership` 8 · `matches` 7 · `security` 2 · `general` 2.
     * Порядок — от частого к редкому, чтобы человек видел главное сверху.
     */
    API.РАЗДЕЛЫ = ['tournaments', 'challenges', 'membership', 'matches',
                   'security', 'general'];

    /** Настройки из профиля. Нет профиля или нет столбца — пусто. */
    API.прочитать = function (профиль) {
        return (профиль && профиль.notify_preferences) ? профиль.notify_preferences : {};
    };

    /**
     * ВКЛЮЧЕНО ЛИ — ТО ЖЕ ПРАВИЛО, ЧТО У СЕРВЕРА.
     *
     * Повторяет `shouldNotify` знак в знак: нет настроек — отправляем,
     * нет канала — отправляем, иначе `!== false`. Разойдись оно —
     * экран показывал бы одно, а сервер делал другое, и спорить было бы
     * не о чем: прав всегда сервер.
     *
     * УМОЛЧАНИЕ — СВОЙСТВО ДАННЫХ, А НЕ РАЗМЕТКИ: пусто значит
     * «включено», и это решает ОДНО место.
     */
    API.включено = function (настройки, канал, раздел) {
        if (!настройки) return true;
        var ч = настройки[канал];
        if (!ч) return true;
        return ч[раздел] !== false;
    };

    /**
     * ПЕРЕКЛЮЧИТЬ — отдаёт НОВЫЕ настройки, которые можно писать в базу.
     *
     * Не трогает то, что пришло: оба продукта делали «оптимистичную»
     * правку на месте и при неудаче возвращали значение обратно —
     * возвращать проще, когда прежний слепок цел.
     */
    API.переключить = function (настройки, канал, раздел, включить) {
        var н = {};
        var к;
        for (к in (настройки || {})) {
            if (Object.prototype.hasOwnProperty.call(настройки, к)) {
                н[к] = {};
                for (var р in настройки[к]) {
                    if (Object.prototype.hasOwnProperty.call(настройки[к], р)) {
                        н[к][р] = настройки[к][р];
                    }
                }
            }
        }
        if (!н[канал]) н[канал] = {};
        н[канал][раздел] = !!включить;
        return н;
    };

    /**
     * МОЖНО ЛИ ПОЛЬЗОВАТЬСЯ КАНАЛОМ.
     *
     * Без привязанного бота столбец телеграма бесполезен: человек
     * включал ползунок и ждал сообщений, которым неоткуда взяться. Это
     * правило было только у сайта (`dashboard.js:5735`), в приложении
     * его не было вовсе.
     */
    API.каналДоступен = function (канал, профиль) {
        if (канал !== 'tg') return true;
        return !!(профиль && профиль.telegram_chat_id);
    };

})(typeof window !== 'undefined' ? window : this);
