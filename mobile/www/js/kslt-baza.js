(function (global) {
    'use strict';

    var н = global.KSLT_DB || {};

    var API = global.KSLT_BAZA = {
        /* ПОДСТАВЛЕННОЕ СИЛЬНЕЕ ЗАШИТОГО. Ничего не подставили —
           работаем с боевой, как и должно быть у человека. */
        адрес: н.url || 'https://qqkzszesviukopgjbead.supabase.co',
        ключ: н.key || 'sb_publishable_JGfk-NkMln4w7iMzhYEigg_z1_2XK7G'
    };

    /**
     * ИМЯ ПРОЕКТА — ПЕРВОЕ СЛОВО АДРЕСА.
     *
     * Считается из адреса, а не вписывается: подставили другую базу —
     * имя записи с сессией поехало за ней само.
     */
    API.проект = function () {
        return String(API.адрес || '').replace(/^https?:\/\//, '').split('.')[0];
    };

    /** ИМЯ ЗАПИСИ, В КОТОРОЙ БРАУЗЕР ДЕРЖИТ СЕССИЮ. */
    API.имяЗаписи = function () {
        return 'sb-' + API.проект() + '-auth-token';
    };

    /**
     * ЗАПИСЬ СЕССИИ ИЗ БРАУЗЕРА — или `null`.
     *
     * Никогда не бросает: записи может не быть, она может быть чужой
     * или испорченной, а хранилище — закрытым настройками браузера.
     * Разбор молчит, потому что отсутствие сессии — это не ошибка.
     */
    API.запись = function () {
        try {
            var сырое = global.localStorage.getItem(API.имяЗаписи());
            if (!сырое) return null;
            var з = JSON.parse(сырое);
            return (з && з.access_token) ? з : null;
        } catch (e) {
            return null;
        }
    };

    /**
     * ВОШЁЛ ЛИ ЧЕЛОВЕК — ПО ЗАПИСИ В БРАУЗЕРЕ, БЕЗ ЗОВА СЕРВЕРА.
     *
     * Это быстрый ответ для разметки: показать кнопку «Войти» или меню.
     * Он НЕ ЗАМЕНЯЕТ сервер — право на данные решает база своими
     * правилами, а просроченный токен здесь честно считается выходом.
     */
    API.вошёл = function () {
        var з = API.запись();
        if (!з || !з.expires_at) return false;
        return з.expires_at > Math.floor(Date.now() / 1000);
    };

    /** ГОСТЬ — обратное «вошёл». Заведено потому, что так его и зовут. */
    API.гость = function () {
        return !API.вошёл();
    };

    /**
     * СЕРВЕР СКАЗАЛ, ЧТО ЭТОГО ВХОДА БОЛЬШЕ НЕТ? ОДНО ОПРЕДЕЛЕНИЕ (31.10).
     *
     * ЗАЧЕМ ОН ЕСТЬ — ЖИВАЯ БЕДА, НАЙДЕННАЯ ЧТЕНИЕМ. Охрана страниц
     * (`js/auth-guard.js`) считала мёртвым входом ЛЮБУЮ ошибку от
     * `auth.getUser()` — и выходила из аккаунта: `signOut`, чистка
     * хранилища, увод на форму входа. «Сервер ответил, что входа нет» и
     * «до сервера не дошли» — ДВА РАЗНЫХ СОБЫТИЯ, а ветка была одна.
     * Значит человек с живой сессией, у которого на секунду просела сеть,
     * терял вход. Ночной прогон 30.10 показал это 118 раз подряд: под
     * нагрузкой запрос срывался, и страница выходила из аккаунта сама.
     *
     * КАК ОТВЕЧАЕТ, И ПОЧЕМУ ЭТО ПРОВЕРЯЕМО БЕЗ ЗНАНИЯ БИБЛИОТЕКИ.
     * `fetch` отклоняется ТОЛЬКО когда ответа не было вовсе — нет сети,
     * не разрешилось имя, прервали по сроку. Любой код HTTP — это ОТВЕТ.
     * Поэтому:
     *   · `401`/`403` → `true`: сервер ответил и ответ означает «токен
     *     больше не ваш»;
     *   · ответа не было, `5xx`, срок → `false`: это не ответ, а его
     *     отсутствие, и выходом из аккаунта на него отвечать нельзя;
     *   · `200` → `false`: вход как раз живой.
     * Разбирать классы ошибок `supabase-js` здесь НАРОЧНО не стали: они
     * её внутреннее дело и меняются с версией, а код HTTP — договор.
     *
     * ЧЕГО НЕ ДЕЛАЕТ: не трогает хранилище, не выходит, не показывает
     * надписей. Только отвечает да или нет — решает зовущий.
     */
    API.входОтозван = function (токен, пределМс) {
        if (!токен || typeof global.fetch !== 'function') return Promise.resolve(false);
        var прервать = (typeof global.AbortController === 'function')
            ? new global.AbortController() : null;
        var часы = прервать
            ? global.setTimeout(function () { прервать.abort(); }, пределМс || 8000)
            : null;
        return global.fetch(API.адрес + '/auth/v1/user', {
            headers: { apikey: API.ключ, Authorization: 'Bearer ' + токен },
            signal: прервать ? прервать.signal : undefined
        }).then(function (о) {
            return о.status === 401 || о.status === 403;
        }).catch(function () {
            return false;
        }).then(function (о) {
            if (часы) global.clearTimeout(часы);
            return о;
        });
    };

})(typeof window !== 'undefined' ? window : globalThis);
