/**
 * KSLT — СКЛАДКА: РАЗДЕЛ, КОТОРЫЙ СВОРАЧИВАЕТСЯ.
 *
 * ЗАЧЕМ. Слово Кости 02.11 о странице игрока в приложении: «есть тут
 * достижения — надо будет тоже раскрывашку сделать, матчи тоже и в
 * турнирах тоже». Три раздела подряд, каждый в десятки строк: сетка
 * значков на шесть рядов, десять матчей, список турниров. Человек на
 * телефоне прокручивает мимо всего, что ему сейчас не нужно.
 *
 * ПОЧЕМУ `<details>`, А НЕ СВОЙ МЕХАНИЗМ. Сворачивание есть в самой
 * платформе: `<details>` открывается нажатием и клавишей, сам говорит
 * диктору «свёрнуто/развёрнуто», работает без единой строки скрипта и
 * переживает перерисовку. Писать то же самое классом и слушателем
 * значит завести третье определение понятия, которое браузер уже знает,
 * — и потерять доступность, потому что `aria-expanded` руками ставят
 * не везде. НЕ ИЗОБРЕТАТЬ ТО, ЧТО ЕСТЬ В ПЛАТФОРМЕ.
 *
 * ЧЕМ ЭТО НЕ ЯВЛЯЕТСЯ. Это НЕ отсечка длинного списка: та показывает
 * первые десять строк и прячет остальные (`js/kslt-otsechka.js`,
 * «10 везде», слово Кости 06.10). Складка прячет РАЗДЕЛ ЦЕЛИКОМ за его
 * заголовком. Понятия разные, и живут они в разных домах: складка
 * может держать внутри себя отсечённый список, и наоборот.
 *
 * СЧЁТ В ЗАГОЛОВКЕ — ЧАСТЬ ЗАМЫСЛА, А НЕ УКРАШЕНИЕ. Свёрнутый раздел
 * молчит о том, что внутри: пусто там или двадцать матчей, не видно,
 * пока не нажмёшь. Число рядом с подписью отвечает на это заранее, и
 * ради него не нужно открывать.
 */
(function () {
    'use strict';

    var S = window.KSLT_SKLADKA = {};

    function экр(s) {
        return window.KSLT_экранировать
            ? window.KSLT_экранировать(s)
            : String(s == null ? '' : s).replace(/[&<>"']/g, function (c) {
                return { '&': '&amp;', '<': '&lt;', '>': '&gt;',
                         '"': '&quot;', "'": '&#39;' }[c];
            });
    }

    var СТРЕЛКА = '<svg class="kslt-skladka-strelka" width="14" height="14" ' +
        'viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2.5" ' +
        'aria-hidden="true"><path d="M6 9l6 6 6-6"/></svg>';

    /**
     * Разметка складки.
     *
     * о.знак       — значок перед подписью (необязателен)
     * о.подпись    — заголовок раздела
     * о.счёт       — число внутри; `null` или не передан — числа нет
     * о.содержимое — готовая разметка тела
     * о.открыта    — развернуть сразу
     * о.id         — `id` для тела, если его надо найти и заполнить позже
     * о.класс      — добавочный класс на корень
     *
     * ЗНАЧОК ПРЯЧЕТСЯ ОТ ДИКТОРА: он повторяет подпись картинкой, и
     * читать «трофей трофей турниры» незачем.
     */
    S.разметка = function (о) {
        о = о || {};
        var счёт = (о.счёт === null || о.счёт === undefined || о.счёт === '')
            ? '' : '<span class="kslt-skladka-schyot">' + экр(о.счёт) + '</span>';
        var знак = о.знак
            ? '<span class="kslt-skladka-znak" aria-hidden="true">' + экр(о.знак) + '</span>'
            : '';
        return '<details class="kslt-skladka' + (о.класс ? ' ' + о.класс : '') + '"' +
                   (о.открыта ? ' open' : '') + '>' +
            '<summary class="kslt-skladka-shapka">' +
                знак +
                '<span class="kslt-skladka-podpis">' + экр(о.подпись) + '</span>' +
                счёт + СТРЕЛКА +
            '</summary>' +
            '<div class="kslt-skladka-telo"' + (о.id ? ' id="' + экр(о.id) + '"' : '') + '>' +
                (о.содержимое || '') +
            '</div>' +
        '</details>';
    };

    /**
     * Поставить счёт в уже нарисованную складку.
     *
     * ЧИСЛО УЗНАЁТСЯ ПОЗЖЕ РАЗМЕТКИ: разделы рисуются сразу, а их
     * содержимое приходит ответом базы. Складка без счёта молчит о том,
     * что внутри, — и тогда её незачем было и заводить.
     *
     * Ищем ВНУТРИ переданного узла, а не по документу: складок на
     * странице несколько, и `getElementById` отдал бы первую попавшуюся.
     */
    S.счёт = function (узел, сколько) {
        if (!узел) return;
        var корень = узел.closest ? узел.closest('.kslt-skladka') : null;
        if (!корень) return;
        var место = корень.querySelector('.kslt-skladka-schyot');
        if (!место) {
            var подпись = корень.querySelector('.kslt-skladka-podpis');
            if (!подпись) return;
            место = document.createElement('span');
            место.className = 'kslt-skladka-schyot';
            подпись.parentNode.insertBefore(место, подпись.nextSibling);
        }
        место.textContent = (сколько === null || сколько === undefined) ? '' : String(сколько);
    };
})();
