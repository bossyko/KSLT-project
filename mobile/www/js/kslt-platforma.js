/**
 * ПЛАТФОРМА — ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ.
 *
 * Заведено 10.11 для куска Ю14: в сборке для iOS нельзя показывать цену
 * членства и способ оплаты. Признака платформы в приложении не было
 * ВОВСЕ — ни одной проверки, ни одного `getPlatform`.
 *
 * ОТКУДА БЕРЁТСЯ. Capacitor 8.6 вешает `Capacitor` на globalThis и
 * отдаёт `getPlatform()`, который сам различает мост:
 * `androidBridge` -> 'android', `webkit.messageHandlers.bridge` -> 'ios',
 * иначе 'web'. Проверено чтением `node_modules/@capacitor/core/dist/
 * capacitor.js`, а не по памяти.
 *
 * ПОЧЕМУ НЕ `isNativePlatform`. Нам нужна не «натива или нет», а именно
 * ЯБЛОКО: правила 3.1.1 и 3.1.3 — это правила App Store. Android живёт
 * по своим, и валить их в одну проверку значит завести беду на шве.
 *
 * ЗАПАСНОЕ ЗНАЧЕНИЕ — 'web', А НЕ ПУСТО: отсутствие моста означает
 * браузер, и это определённость, а не незнание.
 */
(function (global) {
  'use strict';

  function определить() {
    var C = global.Capacitor;
    if (C && typeof C.getPlatform === 'function') {
      try {
        var п = C.getPlatform();
        if (п === 'ios' || п === 'android' || п === 'web') return п;
      } catch (e) { /* мост ответил бедой — считаем браузером */ }
    }
    return 'web';
  }

  var ПЛАТФОРМА = определить();

  global.KSLT_PLATFORMA = {
    имя: ПЛАТФОРМА,
    яблоко: ПЛАТФОРМА === 'ios',
    андроид: ПЛАТФОРМА === 'android',
    браузер: ПЛАТФОРМА === 'web',
    /* ПРАВИЛО, А НЕ ПЛАТФОРМА, — вот что спрашивает код.
       `ценуПоказываем()` читается на месте вызова и говорит, ПОЧЕМУ
       скрыто, а не ГДЕ мы находимся. Решишь иначе — меняешь здесь одно
       место, а не семь по файлам. */
    ценуПоказываем: function () { return ПЛАТФОРМА !== 'ios'; }
  };
})(typeof window !== 'undefined' ? window : this);
