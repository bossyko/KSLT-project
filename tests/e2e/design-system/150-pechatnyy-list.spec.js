/**
 * КУСОК 150 — ПЕЧАТНЫЙ ЛИСТ ОТЧЁТА ОДИН НА ПРОДУКТ.
 *
 * ЧТО БЫЛО. Лист печатного отчёта существовал ТРИЖДЫ — «Пользователи»,
 * «Ваучеры», «Финансы», — и копией был не css, а ВЕСЬ ЛИСТ: открытие
 * окна, скелет документа, шапка, полоса плашек, таблица, подвал и зов
 * печати из `onload`. Замер: 13 из 17 правил совпадали ЗНАК В ЗНАК, тела
 * `vouchers`/`finances` — 0.99.
 *
 * ПОЧЕМУ ПРОБА НА СТЕНДЕ. Все три отчёта живут В АДМИНКЕ, за входом, и
 * пароля у меня нет. Лист открывается в НОВОМ ОКНЕ и печатается из его
 * `onload`: проверить его можно только нажав кнопку, поймав окно и
 * померив лист внутри. Стенд `maket/stend-pechatnyy-list.html` зовёт
 * НАСТОЯЩИЙ дом и настоящий дом экранирования. Это сказано вслух, а не
 * выдано за проверку живой админки.
 *
 * ГЛАВНОЕ, ЧТО ЭТА ПРОБА ДЕРЖИТ, — ШОВ ЭКРАНИРОВАНИЯ. Дом получает
 * заголовок, период и подписи ТЕКСТОМ и гасит их сам; `строки` и
 * `разбивка` приходят ГОТОВОЙ разметкой, и теги внутри обязаны дойти
 * живыми. Половина шва без другой половины бессмысленна, поэтому проба
 * держит обе: `<b>` в заголовке остаётся текстом, `<span>` в разбивке
 * остаётся тегом.
 */
const { test, expect } = require('@playwright/test');

const СТЕНД = '/maket/stend-pechatnyy-list.html';

async function открытьЛист(page, кнопка) {
    await page.goto(СТЕНД);
    await page.waitForFunction(
        () => !!(window.KSLT_ADMIN && window.KSLT_ADMIN.печатныйЛист) && !!window.СТЕНД,
        null, { timeout: 15000 });
    const [лист] = await Promise.all([
        page.waitForEvent('popup', { timeout: 15000 }),
        page.click('#' + кнопка)
    ]);
    await лист.waitForSelector('.report-header h1', { timeout: 15000 });
    return лист;
}

/* ЗАМЕР ЛИСТА ОДНОЙ МЕРКОЙ. Правила читаются из его `<style>`: лист живёт
   в отдельном окне, и своего css-файла у него нет вовсе. */
const СНЯТЬ = `() => {
    const стиль = (document.querySelector('style') || {}).textContent || '';
    /* ПРАВИЛО ИЩЕТСЯ ПОИСКОМ ПОДСТРОКИ, А НЕ РЕГУЛЯРКОЙ ИЗ СЕЛЕКТОРА.
       Первая запись собирала регулярку, экранируя селектор, и выкус
       съедал из него БУКВЫ: «.stat-box» превращался в «.stt-ox», правило
       не находилось никогда, а мерка молча отдавала null. Поймано сборкой
       мерки до прогона. СЕЛЕКТОР ЗДЕСЬ — ИЗВЕСТНЫЙ ЛИТЕРАЛ, и регулярка
       ему не нужна вовсе.
       И ВТОРОЕ, ЗА ОДИН ДЕНЬ ДВАЖДЫ: обратные кавычки в этом пояснении
       закрывали саму мерку — она ШАБЛОННАЯ СТРОКА. Правило было выведено
       на куске 149 и тут же нарушено мной на куске 150; теперь имена
       классов внутри мерки стоят в угловых кавычках. */
    const правило = (сел) => {
        const i = стиль.indexOf(сел + ' {');
        if (i === -1) return null;
        const j = стиль.indexOf('}', i);
        if (j === -1) return null;
        return стиль.slice(i + сел.length + 2, j).replace(/\\s+/g, ' ').trim();
    };
    const h1 = document.querySelector('.report-header h1');
    return {
        заголовок: h1 ? h1.textContent : null,
        теговВЗаголовке: h1 ? h1.children.length : null,
        период: (document.querySelector('.report-header .period') || {}).textContent || null,
        плашек: document.querySelectorAll('.stat-box').length,
        подписьПлашки: (document.querySelector('.stat-box .lbl') || {}).textContent || null,
        колонок: document.querySelectorAll('thead th').length,
        строк: document.querySelectorAll('tbody tr').length,
        разбивкаЕсть: !!document.querySelector('.breakdown'),
        разбивкаТегЖив: !!document.querySelector('.breakdown span'),
        правилоРазбивкиЕсть: /\\\\.breakdown\\\\s*\\\\{/.test(стиль),
        мёртвоеПравило: /\\\\.no-print\\\\s*\\\\{/.test(стиль),
        плашкаШирина: (/min-width:\\\\s*(\\\\d+)px/.exec(правило('.stat-box') || '') || [])[1] || null,
        полосаОтступ: (/margin-bottom:\\\\s*(\\\\d+)px/.exec(правило('.stats-grid') || '') || [])[1] || null,
        подвал: [...document.querySelectorAll('.report-footer span')].map(s => s.textContent),
        печатей: window.__печатей
    };
}`;

const замерить = (лист) => лист.evaluate(и => eval('(' + и + ')')(), СНЯТЬ);

test.describe('печатный лист отчёта: один на продукт', () => {

    /* ПЛОТНЫЙ ЛИСТ — СВОЙСТВО ОТЧЁТА, А НЕ ДОМА: у «Пользователей» плашки
       100 вместо 120 и полоса 16 вместо 24. Вид не меняли (правило 22.10),
       различие пришло доводом. */
    test('«Пользователи»: плотный лист и разбивка', async ({ page }) => {
        const лист = await открытьЛист(page, 'stPolzovateli');
        const м = await замерить(лист);

        expect(м.плашкаШирина, 'плашки не плотные').toBe('100');
        expect(м.полосаОтступ, 'полоса плашек не плотная').toBe('16');
        expect(м.плашек, 'плашек не три').toBe(3);
        expect(м.колонок, 'колонок не четыре').toBe(4);
        expect(м.строк, 'строк таблицы не две').toBe(2);
        expect(м.разбивкаЕсть, 'разбивки нет').toBe(true);
        expect(м.правилоРазбивкиЕсть, 'правил разбивки нет в листе').toBe(true);
        expect(м.подвал, 'подвал собрался не из двух частей').toHaveLength(2);
        await лист.close();
    });

    /* ОБЫЧНЫЙ ЛИСТ, И ПРАВИЛ РАЗБИВКИ В НЁМ БЫТЬ НЕ ДОЛЖНО ВОВСЕ: у двух
       отчётов из трёх разбивки нет, и правила лежали бы мёртвыми. */
    test('«Ваучеры»: обычный лист, пять плашек, мёртвого css нет', async ({ page }) => {
        const лист = await открытьЛист(page, 'stVauchery');
        const м = await замерить(лист);

        expect(м.плашкаШирина, 'плашки стали плотными').toBe('120');
        expect(м.полосаОтступ, 'полоса плашек стала плотной').toBe('24');
        expect(м.плашек, 'плашек не пять').toBe(5);
        expect(м.колонок, 'колонок не семь').toBe(7);
        expect(м.разбивкаЕсть, 'разбивка появилась там, где её нет').toBe(false);
        expect(м.правилоРазбивкиЕсть, 'правила разбивки лежат мёртвыми').toBe(false);
        expect(м.мёртвоеПравило, 'мёртвое `.no-print` вернулось в лист').toBe(false);
        await лист.close();
    });

    test('«Финансы»: четыре плашки и семь колонок', async ({ page }) => {
        const лист = await открытьЛист(page, 'stFinansy');
        const м = await замерить(лист);

        expect(м.плашек, 'плашек не четыре').toBe(4);
        expect(м.колонок, 'колонок не семь').toBe(7);
        expect(м.плашкаШирина, 'плашки стали плотными').toBe('120');
        expect(м.правилоРазбивкиЕсть, 'правила разбивки лежат мёртвыми').toBe(false);
        await лист.close();
    });

    /* ОБЕ ПОЛОВИНЫ ШВА СРАЗУ. Текст гасит дом, разметку отдаёт раздел. */
    test('шов экранирования: текст погашен, тег разбивки жив', async ({ page }) => {
        const лист = await открытьЛист(page, 'stPolzovateli');
        const м = await замерить(лист);

        expect(м.заголовок, 'заголовок дошёл не знак в знак')
            .toBe('Отчёт "за месяц" & <b>март</b>');
        expect(м.теговВЗаголовке, 'угловые скобки заголовка стали ТЕГОМ — дом не гасит текст')
            .toBe(0);
        expect(м.период, 'период дошёл не знак в знак')
            .toBe('Период: март & "апрель"');
        expect(м.подписьПлашки, 'амперсанд в подписи плашки потерялся')
            .toBe('Всего & людей');
        expect(м.разбивкаТегЖив, 'тег в готовой разметке разбивки погашен — это не её половина шва')
            .toBe(true);
        await лист.close();
    });

    /* ПЕЧАТЬ ЗОВЁТСЯ ИЗ `onload` И РОВНО ОДИН РАЗ. Раньше отрисовки — на
       бумагу уходит пустая страница; дважды — два диалога печати. */
    test('печать зовётся один раз и после отрисовки', async ({ page }) => {
        const лист = await открытьЛист(page, 'stVauchery');
        await лист.waitForFunction(() => window.__печатей >= 1, null, { timeout: 15000 });
        const м = await замерить(лист);

        expect(м.печатей, 'печать позвана не один раз').toBe(1);
        /* признак отрисовки ДО печати: таблица на месте в том же окне */
        expect(м.строк, 'на печать ушёл лист без строк').toBe(2);
        expect(м.плашек, 'на печать ушёл лист без плашек').toBe(5);
        await лист.close();
    });
});
