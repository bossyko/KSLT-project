// @ts-check
const { test, expect } = require('@playwright/test');

/**
 * КРАСКИ РОЛЕЙ: ЧТО ВИДНО, А НЕ ЧТО НАПИСАНО. Круг 21 ветки D.
 *
 * ЗАЧЕМ ПРОБА, ЕСЛИ ЕСТЬ СТОРОЖ. `tools/check-rol-v-inlaynah.js` читает
 * исходник: нет ли краски роли числом. Он не может сказать, ЧИТАЕТСЯ ли
 * то, что получилось. А главное число этого круга — контраст: белый текст
 * на красной кнопке ошибки давал 3.55 при пороге AA 4.5, и по исходнику
 * это не видно никак.
 *
 * ЧИТАЕТСЯ НАРИСОВАННОЕ: цвет берётся `getComputedStyle`, полупрозрачные
 * слои складываются, и контраст считается к тому, что видно. Объявленный
 * цвет подложки врёт: `--danger-subtle` — это 15 % поверх фона карточки.
 *
 * ПЯТЬ ВИДОВ. Краска от ширины окна не зависит — и проба требует, чтобы
 * не зависела: ни одно число не должно разойтись между видами.
 */

const ПОРОГ = 4.5;

async function стенд(page) {
    const беды = [];
    page.on('pageerror', e => беды.push('pageerror: ' + e.message));
    page.on('console', m => {
        const т = m.text();
        if (m.type() === 'error' && !/Failed to load resource|ERR_/.test(т)) {
            беды.push('console: ' + т);
        }
    });
    await page.goto('/maket/kraski-roley-zamer.html');
    await page.waitForFunction(() => !!window.ЗАМЕР, null, { timeout: 15000 });
    return { з: await page.evaluate(() => window.ЗАМЕР), беды };
}

test('после сведения ни одно место не ниже порога AA', async ({ page }) => {
    const { з, беды } = await стенд(page);
    expect(беды, 'страница ругается в консоль').toEqual([]);

    /* ГЛАВНОЕ ЧИСЛО КРУГА: было одно место ниже порога, стало ни одного. */
    expect(з.нижеПорогаСтало, 'места ниже порога 4.5 после сведения').toEqual([]);

    /* И проверяем САМУ ПРОБУ: если «было» вдруг окажется чистым, значит
       стенд перестал показывать прежнее состояние и мерить нечего. */
    expect(з.нижеПорогаБыло.length,
        'стенд должен показывать прежнее состояние — иначе сравнивать не с чем')
        .toBeGreaterThan(0);
});

test('кнопка ошибки: 3.55 было, не меньше 5.9 стало', async ({ page }) => {
    const { з } = await стенд(page);
    const м = з.места['кнопка ошибки — текст на заливке'];
    /* Белый на красном — единственное место ниже нормы во всём куске. */
    expect(м.было, 'прежний контраст белого на красном').toBeLessThan(ПОРОГ);
    expect(м.стало, 'контраст системной пары --danger + --danger-on')
        .toBeGreaterThanOrEqual(5.9);
});

test('сведение не ухудшило ни одного места', async ({ page }) => {
    const { з } = await стенд(page);
    /* ОТНОШЕНИЕ, А НЕ ЧИСЛО: системная роль обязана быть не хуже прежней
       краски в каждом месте. Числа могут поехать при правке токенов —
       правило от этого не должно падать, пока не хуже. */
    Object.keys(з.места).forEach(имя => {
        const м = з.места[имя];
        expect(м.стало, 'стало не хуже, чем было: ' + имя +
            ' (' + м.было + ' -> ' + м.стало + ')').toBeGreaterThanOrEqual(м.было);
    });
});
