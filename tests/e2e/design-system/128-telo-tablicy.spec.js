/**
 * КУСОК 127 — СЛУШАТЕЛЬ НА ТЕЛЕ ТАБЛИЦЫ РОВНО ОДИН.
 *
 * Сторож читает файл. Эта проба читает ПОВЕДЕНИЕ: стенд зовёт настоящий
 * `A.наТелоТаблицы` четыре раза подряд — столько же перерисовок, сколько
 * было в замере на боевой, — и считает, сколько раз сработает
 * обработчик на ОДНО нажатие.
 *
 * ЗАМЕРЕНО НА БОЕВОЙ 22.10, «Корты»: старым способом одно нажатие дало
 * ПЯТЬ запросов к базе. ОДНО ЗЕЛЁНОЕ НЕ ДОКАЗЫВАЕТ НИЧЕГО — ДОКАЗЫВАЕТ
 * РАЗНИЦА, поэтому вторая проверка ставит рядом старый способ и ждёт от
 * него четырёх срабатываний.
 *
 * Админка — десктоп и планшет (решение Кости 29.09).
 */
const { test, expect } = require('@playwright/test');

const ТЕЛЕФОННЫЕ = ['mobile', 'phone-landscape'];
const СТЕНД = '/maket/telo-tablicy-zamer.html';

test.describe('слушатель на теле таблицы', () => {

    test.beforeEach(({}, info) => {
        test.skip(ТЕЛЕФОННЫЕ.indexOf(info.project.name) !== -1,
            'админка — десктоп и планшет (слово Кости 29.09)');
    });

    test('четыре перерисовки оставляют ОДИН слушатель', async ({ page }) => {
        await page.goto(СТЕНД);
        await page.waitForSelector('#стол tbody tr', { timeout: 15000 });
        const сработало = await page.evaluate(() => window.НАЖАТЬ());
        expect(сработало, 'обработчик сработал больше одного раза — слушатели снова ' +
            'копятся, и каждое нажатие строки бьёт в базу столько раз, сколько было ' +
            'перерисовок').toBe(1);
    });

    test('старый способ на том же стенде даёт четыре — разница видна', async ({ page }) => {
        await page.goto(СТЕНД);
        await page.waitForSelector('#стол tbody tr', { timeout: 15000 });
        const счёт = await page.evaluate(() => {
            const t = document.createElement('table');
            const tb = document.createElement('tbody');
            t.appendChild(tb); document.body.appendChild(t);
            let с = 0;
            for (let i = 0; i < 4; i++) {
                tb.innerHTML = '<tr data-id="1"><td>x</td></tr>';
                tb.addEventListener('click', e => { if (e.target.closest('tr[data-id]')) с++; });
            }
            tb.querySelector('tr').click();
            t.remove();
            return с;
        });
        /* Это НЕ желаемое состояние, а доказательство, что проба умеет
           отличить одно от другого. Если здесь станет 1 — значит браузер
           перестал складывать слушатели, и первую проверку надо
           перепроверять заново, а не верить ей. */
        expect(счёт, 'старый способ перестал копить слушателей — первая проверка ' +
            'больше ничего не доказывает').toBe(4);
    });

});
