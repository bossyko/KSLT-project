/**
 * КУСОК 138 — КЫРГЫЗСКИЙ НАЗЫВАЕТСЯ ВСЛУХ, А НЕ ПАДАЕТ В РУССКИЙ.
 *
 * Сторож читает файлы и видит, что выбор назвал три языка. Эта проба
 * читает ЭКРАН: что на кыргызской странице НЕТ русских слов там, где
 * перевод есть, и что собранные из суффикса адреса ведут на кыргызские
 * страницы, а не на русские.
 *
 * РУССКОЕ СЛОВО НА КЫРГЫЗСКОЙ СТРАНИЦЕ — НЕ ВСЕГДА БЕДА: имя человека,
 * «сет», «гейм», «сом», «Плей-офф» в кыргызском те же. Поэтому проба
 * ищет не кириллицу вообще, а СПИСОК СЛОВ, у которых перевод ЕСТЬ в
 * продукте: их появление означает, что ветвь выбрана не та.
 *
 * ПРОБА ЖДЁТ ПРИЗНАК — сам дом языка: он есть на всех видах, потому что
 * это скрипт, а не вёрстка.
 */
const { test, expect } = require('../../fixtures');

/* Слова, у которых в продукте есть кыргызский перевод. Увидели их на
   кыргызской странице — значит выбор отдал русскую ветвь. */
const РУССКИЕ = ['Сохранить', 'Войти', 'Пароль', 'Загрузка', 'Тренеры',
                 'одиночка', 'Достижения', 'Членство', 'Профиль не найден'];

/* У КАЖДОЙ СТРАНИЦЫ СВОЙ ПРИЗНАК ЖИЗНИ, А НЕ ОБЩИЙ ПОРОГ ДЛИНЫ.
   ПОПРАВКА 30.10. Стояло «знаков на экране больше 200» — порог, и он
   соврал: у кыргызской страницы входа видимого текста всего около ста
   тридцати знаков (форма входа — это почта, пароль и четыре кнопки,
   остальные экраны спрятаны разметкой). Проба падала на пяти видах с
   «страница почти пуста — мерить нечего», хотя страница была целой.
   Порог там стоял за дело: без него проверка «русских слов нет» прошла
   бы и на пустой странице. Но мерить жизнь страницы длиной текста —
   это мерить не то. Теперь признак — СВОЁ КЫРГЫЗСКОЕ СЛОВО каждой
   страницы, взятое из её же разметки: оно и доказывает, что страница
   ожила, и что ожила она по-кыргызски.
   ПОРОГ ЗАМЕНЁН ОТНОШЕНИЕМ, А НЕ ПОДНЯТ.
   КАКОЕ СЛОВО ВЗЯТО И ПОЧЕМУ ИМЕННО ОНО — НАЗВАНО ЧЕСТНО. Первым
   побуждением было взять заголовок каждой страницы. Замер разметки это
   отменил: у тренеров, кортов и игроков заголовка в разметке НЕТ ВОВСЕ —
   его рисует js, — а слова вроде «Турнирлер» на кыргызских страницах
   лежат в `<title>` и `<meta>`, то есть в `innerText` не попадают вовсе
   и признаком быть не могут. Проверено чтением, а не предположением.
   Поэтому признак — слово общей кыргызской обвязки («Кирүү» в шапке,
   на странице входа оно же на вкладке). Он доказывает ДВА нужных
   утверждения: страница ожила и ожила по-кыргызски. Чего он НЕ
   доказывает — что отрисовалось СВОЁ содержимое страницы; это и не
   предмет этой пробы, её предмет — отсутствие русских слов. */
const СТРАНИЦЫ = [
    { адрес: '/pages/auth',        своё: 'Кирүү' },
    { адрес: '/pages/coaches',     своё: 'Кирүү' },
    { адрес: '/pages/courts',      своё: 'Кирүү' },
    { адрес: '/pages/tournaments', своё: 'Кирүү' },
    { адрес: '/pages/players',     своё: 'Кирүү' }
];

async function дом(page) {
    await page.waitForFunction(() => !!window.KSLT_YAZYK, null, { timeout: 15000 });
}

test.describe('кыргызский называется вслух', () => {

    for (const с of СТРАНИЦЫ) {
        test('кыргызская ' + с.адрес + ': русских слов с переводом на экране нет',
            async ({ page }) => {
            await page.goto(с.адрес + '-kg.html');
            await дом(page);
            await page.waitForSelector('body', { timeout: 15000 });

            const м = await page.evaluate(довод => {
                const т = document.body.innerText || '';
                return {
                    код: window.KSLT_YAZYK.код,
                    суффикс: window.KSLT_YAZYK.суффикс,
                    нашлись: довод.русские.filter(с => т.indexOf(с) !== -1),
                    своёВидно: т.indexOf(довод.своё) !== -1,
                    длина: т.length
                };
            }, { русские: РУССКИЕ, своё: с.своё });

            expect(м.код, 'дом ответил не кыргызским на кыргызской странице').toBe('kg');
            expect(м.суффикс, 'суффикс не кыргызский').toBe('-kg');
            /* ПРИЗНАК ЖИЗНИ — СВОЁ СЛОВО СТРАНИЦЫ, а не число знаков:
               оно же доказывает, что речь кыргызская. */
            expect(м.своёВидно, 'страница не ожила: на экране нет её слова «' +
                с.своё + '» (знаков всего ' + м.длина + ')').toBe(true);
            expect(м.нашлись, 'на кыргызской странице русские слова, у которых перевод есть').toEqual([]);
        });
    }

    /* СТРАНИЦА ВЗЯТА ТА, ГДЕ ДОМ ЕСТЬ — ПОПРАВКА 30.10.
       Стояла `/pages/coaches-kg.html`, и проба падала на пяти видах с
       «правил NTRP нет на странице». Замер: `kslt-rules.js` не подключён
       НИ НА ОДНОЙ странице тренеров (ru, en, kg), и правильно — NTRP там
       не показывают, `ntrpСтрока` зовут только `player.js` и
       `dashboard.js`. Проба спрашивала дом у страницы, которой он не
       нужен. Берём страницу игрока: она дом грузит и открыта гостю. */
    test('подписи NTRP на кыргызской странице кыргызские', async ({ page }) => {
        await page.goto('/pages/player-kg.html');
        await дом(page);
        const м = await page.evaluate(() => {
            const R = window.KSLT_RULES;
            return R && R.ntrpСтрока ? {
                kg: R.ntrpСтрока(4.5, 4.0, 'kg'),
                ru: R.ntrpСтрока(4.5, 4.0, 'ru'),
                en: R.ntrpСтрока(4.5, 4.0, 'en')
            } : null;
        });
        expect(м, 'правил NTRP нет на странице').not.toBeNull();
        expect(м.kg, 'кыргызская подпись NTRP не кыргызская').toContain('жекече');
        expect(м.kg).toContain('жуптук');
        /* ТРИ ЯЗЫКА — ТРИ РАЗНЫХ ОТВЕТА: совпадение означает, что одна из
           ветвей молча отдаёт чужую речь. */
        expect(new Set([м.kg, м.ru, м.en]).size, 'подписи NTRP совпали на разных языках').toBe(3);
    });

    test('код локали на кыргызской странице кыргызский', async ({ page }) => {
        await page.goto('/pages/courts-kg.html');
        await дом(page);
        const локаль = await page.evaluate(() => KSLT_YAZYK.выбрать('en-US', 'ky-KG', 'ru-RU'));
        expect(локаль, 'кыргызская страница просит русскую локаль').toBe('ky-KG');
    });

    test('адреса кабинета и цен с кыргызской страницы кыргызские', async ({ page }) => {
        await page.goto('/pages/courts-kg.html');
        await дом(page);
        const ответы = await page.evaluate(async () => {
            const с = KSLT_YAZYK.суффикс;
            const из = {};
            for (const и of ['dashboard', 'pricing', 'auth']) {
                const о = await fetch('/pages/' + и + с + '.html', { method: 'HEAD' });
                из[и + с] = о.status;
            }
            return из;
        });
        for (const [имя, статус] of Object.entries(ответы)) {
            expect(статус, 'адрес `' + имя + '` не отдал страницу').toBe(200);
        }
    });
});
