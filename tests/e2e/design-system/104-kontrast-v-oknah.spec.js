/**
 * КОНТРАСТ В ОТКРЫТЫХ СОСТОЯНИЯХ. 26.10, кусок 187.
 *
 * Запись 72л: «проба контраста не заглядывает в окна». Список страниц у
 * `92-tihiy-tekst.spec.js` — двенадцать обзорных страниц, и ни одна не
 * открывает ни окна, ни выпадашки. Между тем ВСЕ замеренные куском 185
 * места ниже AA живут именно там: модалка 4.20, окно H2H 4.39, строка
 * внутри окна 3.95. Проба была зелена честно — и смотрела не туда.
 *
 * СЧЁТ ТОТ ЖЕ. Формула не копируется: и замер, и признак открытия берутся
 * из `tools/kontrast.mjs`. ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ.
 *
 * ПРИЗНАК ОТКРЫТИЯ — ВИДИМЫЙ ПРЯМОУГОЛЬНИК, А НЕ КЛАСС И НЕ СВОЙСТВО.
 * Поймано при замере 26.10: выпадашка языка на 375px отвечала
 * `opacity: 1` после нажатия и «открывалась», лёжа внутри свёрнутой
 * десктопной шапки, невидимая никому. Число текстовых узлов при этом не
 * менялось — 220 до и 220 после. Поэтому здесь ДВА порога разом:
 * видимый признак И РОСТ ЧИСЛА УЗЛОВ. Состояние, которое не прибавило
 * видимого текста, не открылось, что бы ни говорил его класс.
 *
 * ГДЕ КАКОЙ ВИД. Шапка расходится ровно на 992 (замерено 26.10 на всех
 * пяти видах): до 992 — бургер, от 992 — ссылки и выбор языка. Это не
 * «так вышло», а ожидание: если шапка переедет на другую ширину, здесь
 * упадёт, а не промолчит.
 */
const { test, expect } = require('../../fixtures');

const ШИРОКИЕ = ['desktop', 'tablet-landscape'];
const УЗКИЕ   = ['tablet', 'mobile', 'phone-landscape'];
const ВСЕ     = ШИРОКИЕ.concat(УЗКИЕ);

const СОСТОЯНИЯ = [
    {
        имя: 'выпадашка языка',
        адрес: '/index.html',
        виды: ШИРОКИЕ,
        кнопка: '.lang-toggle',
        признак: '.lang-menu .lang-option'
    },
    {
        имя: 'боковое меню',
        адрес: '/index.html',
        виды: УЗКИЕ,
        кнопка: '.burger-menu',
        признак: '.mobile-nav.active a'
    },
    {
        имя: 'выпадашка фильтра кортов',
        адрес: '/pages/courts.html',
        виды: ВСЕ,
        кнопка: '.ct-dd-toggle',
        признак: '.ct-dd.open .ct-dd-item'
    },
    {
        имя: 'окно «зарегистрируйтесь» в рейтинге',
        адрес: '/pages/players.html',
        виды: ВСЕ,
        кнопка: '[data-guest-profile]',
        признак: '.pl-search-modal-overlay.visible'
    }
];

const ЗАМЕР = async page => page.evaluate(
    async () => (await import('/tools/kontrast.mjs')).замер(6));

const ВИДЕН = async (page, сел) => page.evaluate(
    async с => {
        const м = await import('/tools/kontrast.mjs');
        return м.виден(document.querySelector(с));
    }, сел);

/**
 * ЖДЁМ ПРИЗНАК ОПРОСОМ, А НЕ СНОМ. Список рейтинга приходит из сети, и
 * строки проявляются по прокрутке (`.pl-animate` -> `.pl-visible`):
 * фиксированная пауза либо коротка, либо тратится впустую. Опрос ждёт
 * РОВНО ДО ТОГО, как признак станет виден, и не дольше.
 *
 * Поймано прогоном 26.10: кнопка «зарегистрируйтесь» после паузы в
 * 1200 мс была ещё невидима на всех пяти видах, а через 2.5 с в том же
 * браузере видимы восемь строк из десяти. Это было не «кнопки нет» —
 * это «я спросил раньше, чем она появилась».
 */
async function ждатьВиден(page, сел, мс) {
    const до = Date.now() + (мс || 8000);
    for (;;) {
        if (await ВИДЕН(page, сел)) return true;
        if (Date.now() > до) return false;
        await page.waitForTimeout(250);
    }
}

async function открыть(page, адрес) {
    await page.goto(адрес);
    await page.waitForLoadState('domcontentloaded');
    await page.evaluate(() => document.fonts && document.fonts.ready);
    await page.waitForSelector('footer, .site-footer', { timeout: 15000 });
    await page.waitForTimeout(1200);
}

for (const с of СОСТОЯНИЯ) {
test(с.имя + ' — контраст внутри проходит AA', async ({ page }, инфо) => {
    const вид = инфо.project.name;
    await открыть(page, с.адрес);

    /* СНАЧАЛА ДОВЕСТИ ДО ВИДА, ПОТОМ СПРАШИВАТЬ, ВИДНА ЛИ. Строки рейтинга
       проявляются по прокрутке (`.pl-animate` -> `.pl-visible`): пока
       строка не попала в поле зрения, она прозрачна, и честный признак
       видимости скажет «нет» про кнопку, которая просто ниже экрана.
       Поймано 26.10 на замере в кадре: все десять кнопок «гостя» имели
       прямоугольник 113x41 и нулевую видимость. */
    const есть = await page.locator(с.кнопка).count();
    if (есть) { try { await page.locator(с.кнопка).first().scrollIntoViewIfNeeded({ timeout: 3000 }); }
                catch (e) { /* не доскроллилось — пусть решает признак ниже */ } }

    /* ОЖИДАНИЕ ВИДА — ПРОВЕРКА, А НЕ ПРОПУСК. Кнопка обязана быть видна
       ровно на тех видах, где она заявлена, и не видна на остальных.
       Там, где ждём видимую, — опрос до восьми секунд; там, где ждём
       невидимую, ждать нечего: короткая выдержка и ответ. */
    const ждёмВидну = с.виды.indexOf(вид) !== -1;
    let кнопкаВидна;
    if (ждёмВидну) {
        кнопкаВидна = await ждатьВиден(page, с.кнопка, 8000);
    } else {
        await page.waitForTimeout(600);
        кнопкаВидна = await ВИДЕН(page, с.кнопка);
    }
    expect(кнопкаВидна,
        'кнопка «' + с.кнопка + '» на виде ' + вид +
        (ждёмВидну ? ' должна быть видна, а её нет' : ' видна там, где не должна') +
        '. Шапка расходится на 992 — если точка переехала, поправить список видов здесь')
        .toBe(ждёмВидну);
    if (!ждёмВидну) return;

    const доЗамер = await ЗАМЕР(page);
    expect(доЗамер.узлов, 'ПОРОГ: текстовых узлов нет — мерить нечего').toBeGreaterThan(5);

    await page.locator(с.кнопка).first().click();

    /* ПЕРВЫЙ ПОРОГ: видимый признак — опросом, а не сном. */
    const признакВиден = await ждатьВиден(page, с.признак, 6000);
    expect(признакВиден,
        'состояние «' + с.имя + '» не открылось: признак «' + с.признак +
        '» невидим. Пустой замер закрытого состояния зелен всегда и не ' +
        'доказывает ничего').toBe(true);

    /* ВТОРОЙ ПОРОГ: видимого текста стало больше. */
    const послеЗамер = await ЗАМЕР(page);
    expect(послеЗамер.узлов,
        'состояние «' + с.имя + '» не прибавило ни одного видимого текстового ' +
        'узла (' + доЗамер.узлов + ' до, ' + послеЗамер.узлов + ' после). Класс ' +
        'сменился, а видно ничего не стало — так выпадашка языка на 375px ' +
        '«открывалась» внутри свёрнутой шапки')
        .toBeGreaterThan(доЗамер.узлов);

    expect(послеЗамер.неМерено,
        'текст поверх ФОТОГРАФИИ в открытом состоянии: ' +
        JSON.stringify(послеЗамер.неМереноПримеры)).toBe(0);
    expect(послеЗамер.нижеНормы,
        'текст ниже порога WCAG AA в состоянии «' + с.имя + '»: ' +
        JSON.stringify(послеЗамер.худшие)).toBe(0);
});
}
