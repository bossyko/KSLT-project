const { test, expect } = require('../../fixtures');

/**
 * ПОЛОСА ПРОГНОЗА ВЫКЛЮЧЕНА — РЕШЕНИЕ КОСТИ 02.10.
 *
 * Числа, по которым принято (чтение боевой базы, отбор «одиночные
 * рейтинговые»): 130 матчей, 3 турнира, 64 игрока, 4 матча на человека.
 * Десять матчей и больше — у ОДНОГО, двадцать — ни у кого. История 14
 * дней, архива прошлых лет нет. На таких объёмах проценты рядом с именами
 * читаются как знание, которого нет.
 *
 * ЧЕГО НЕ ВИДИТ ЗАМОРОЗКА. Правила читают файлы как текст: они держат, что
 * выключатель один и стоит в `false`. Но ОТРИСОВАЛАСЬ ли полоса на живой
 * странице, может сказать только прогон.
 *
 * Турнир `test-metka` подобран не случайно: его финал НЕ сыгран, и в нём
 * стоят двое известных игроков с очками — ровно то условие, при котором
 * полоса и рисовалась бы.
 */

const ТУРНИР = 'test-metka';

test.describe('Прогноз выключен до декабря', () => {

    test('полосы прогноза нет в сетке, хотя условия для неё сошлись',
        async ({ page }) => {
            await page.goto('/pages/tournament.html?id=' + ТУРНИР + '&tab=bracket');
            await page.waitForFunction(
                () => document.querySelectorAll('.td-match-player').length > 0,
                null, { timeout: 20000 });

            /* ПОРОГ ПЕРВЫМ: проверка, которая не может упасть, ничего не
               доказывает. Сначала убеждаемся, что клетка с двумя игроками
               и без счёта на странице есть — иначе полосе и так неоткуда
               взяться, и ноль ничего не значит. */
            const готовность = await page.evaluate(() => {
                const человек = т => !!т && т !== 'TBD' && т !== 'BYE';
                const клетки = [...document.querySelectorAll('.td-match')];
                const сДвумя = клетки.filter(к => {
                    const имена = [...к.querySelectorAll('.td-player-name')]
                        .map(э => э.textContent.trim());
                    return имена.length === 2 && имена.every(человек);
                });
                return { всего: клетки.length, сДвумя: сДвумя.length };
            });

            expect(готовность.сДвумя,
                'на странице нет ни одной клетки с двумя известными игроками — ' +
                'полосе и так неоткуда взяться, проверка прошла бы вхолостую')
                .toBeGreaterThanOrEqual(1);

            const полос = await page.locator('.td-prediction').count();
            expect(полос, 'полоса прогноза вернулась в сетку').toBe(0);
        });

    test('страница отвечает, что показ выключен',
        async ({ page }) => {
            await page.goto('/pages/tournament.html?id=' + ТУРНИР + '&tab=bracket');
            await page.waitForFunction(() => !!window.KSLT_PREDICTION, null, { timeout: 20000 });

            const ответ = await page.evaluate(() => ({
                есть: !!window.KSLT_PREDICTION,
                показывать: window.KSLT_PREDICTION.показывать(),
                считает: typeof window.KSLT_PREDICTION.calculate === 'function'
            }));

            expect(ответ.есть, 'модуль прогноза не загрузился вовсе').toBe(true);
            expect(ответ.показывать, 'выключатель на живой странице стоит во включённом').toBe(false);
            /* Код выключен, а не удалён: в декабре он основа для Glicko-2. */
            expect(ответ.считает, 'расчёт пропал со страницы — его выключили, а не выносили').toBe(true);
        });
});
