/**
 * КУСОК 141 — ЭКРАНИРОВАНИЕ ОДНО НА ПРОДУКТ.
 *
 * Сторож читает файлы и видит, что объявление одно. Эта проба читает
 * ЭКРАН: что дом есть на живых страницах, что он гасит все пять знаков и
 * что страница, собранная его зовами, не разваливается.
 *
 * ПРОВЕРЯЮТСЯ ИМЕННО КАВЫЧКИ. Текстовый узел переживает и голый текст;
 * беда начинается в ЗНАЧЕНИИ АТРИБУТА — `title=`, `alt=`, — а туда идут
 * имена игроков и названия клубов из базы, то есть то, что вводит
 * человек. Апостроф в фамилии О'Коннор и есть самый обычный случай.
 */
const { test, expect } = require('@playwright/test');

const СТРАНИЦЫ = ['/index.html', '/pages/courts.html', '/pages/players.html'];

test.describe('экранирование одно на продукт', () => {

    for (const адрес of СТРАНИЦЫ) {
        test('дом экранирования есть на ' + адрес, async ({ page }) => {
            await page.goto(адрес);
            await page.waitForFunction(() => typeof window.KSLT_экранировать === 'function',
                null, { timeout: 15000 });

            const м = await page.evaluate(() => {
                const э = window.KSLT_экранировать;
                return {
                    амперсанд: э('AT&T'),
                    разметка: э('<b>жирный</b>'),
                    двойная: э('клуб "Олимп"'),
                    одинарная: э("О'Коннор"),
                    пусто: э(null) + э(undefined),
                    ноль: э(0)
                };
            });

            expect(м.амперсанд, 'амперсанд не погашен').toBe('AT&amp;T');
            expect(м.разметка, 'угловые скобки не погашены').toBe('&lt;b&gt;жирный&lt;/b&gt;');
            expect(м.двойная, 'двойная кавычка не погашена').toBe('клуб &quot;Олимп&quot;');
            expect(м.одинарная, 'одинарная кавычка не погашена').toBe('О&#39;Коннор');
            /* `null` и `undefined` дают ПУСТО, а не слово «undefined» на экране. */
            expect(м.пусто, 'пустое значение показало слово вместо пустоты').toBe('');
            /* НОЛЬ — ЗАКОННОЕ ЗНАЧЕНИЕ, и он обязан остаться нулём. */
            expect(м.ноль, 'ноль пропал вместе с пустотой').toBe('0');
        });
    }

    test('страница, собранная зовами дома, цела', async ({ page }) => {
        await page.goto('/pages/courts.html');
        await page.waitForFunction(() => typeof window.KSLT_экранировать === 'function',
            null, { timeout: 15000 });
        await page.waitForSelector('.ct-grid', { timeout: 15000 });

        const м = await page.evaluate(async () => {
            await new Promise(ок => setTimeout(ок, 800));
            /* ПРИЗНАК ЦЕЛОСТИ — не «нет ошибок», а что разметка собралась:
               карточки на месте и ни одна не пуста. */
            const карточки = [...document.querySelectorAll('.ct-grid > *')];
            return {
                карточек: карточки.length,
                пустых: карточки.filter(к => !(к.textContent || '').trim()).length,
                скобокВТексте: (document.body.innerText.match(/&lt;|&gt;|&amp;|&quot;/g) || []).length
            };
        });

        expect(м.карточек, 'карточек нет — мерить нечего').toBeGreaterThan(0);
        expect(м.пустых, 'есть пустые карточки — разметка собралась не до конца').toBe(0);
        /* ДВАЖДЫ ЭКРАНИРОВАННОЕ ВИДНО ГЛАЗАМИ: человек читает `&amp;`
           вместо `&`. Ноль таких на экране. */
        expect(м.скобокВТексте, 'на экране видны следы двойного экранирования').toBe(0);
    });
});
