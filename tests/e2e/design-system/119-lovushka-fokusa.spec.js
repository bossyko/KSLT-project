const { test, expect } = require('@playwright/test');

/**
 * ЗАПИРАНИЕ ФОКУСА: ОДИН ДОМ, ОДИН СЛУШАТЕЛЬ, ЛЕСТНИЦА ОКОН.
 * Написана 21.10, ПЕРЕПИСАНА КУСКОМ 152 (23.10).
 *
 * ЧТО ИЗМЕНИЛОСЬ И ПОЧЕМУ ПРОБА ПЕРЕПИСАНА, А НЕ ПОДПРАВЛЕНА. Прежняя
 * морозила ЗАМЕРЕННОЕ: «при слушателе на подложке Tab из-под окна до
 * ловушки НЕ доходит» — и прямо говорила, что упадёт, если окна сайта
 * перевесят на `document`, и упадёт ПО ДЕЛУ. Кусок 152 их перевесил:
 * навешивание переехало в дом (`запереть`), слушатель стал один на все
 * окна, работает ВЕРХНЕЕ окно стека, снятие возвращается зовущему.
 *
 * СВИДЕТЕЛЬ ОСТАВЛЕН НАМЕРЕННО. Окно A на стенде по-прежнему навешано НА
 * ПОДЛОЖКУ, и проверка «ветвь до него не доходит» никуда не ушла: она
 * больше не про продукт, она про то, ПОЧЕМУ продукт сделан иначе. Если
 * однажды кто-то решит, что ловушку можно повесить на подложку, эта
 * проверка скажет числом, чем это кончается.
 *
 * МЕРИТСЯ СТЕНДОМ И НАСТОЯЩИМ НАЖАТИЕМ. Кабинет и админка за входом: страж
 * уводит кадр на `auth.html`, и замер говорит о странице входа. А Tab
 * проверяется `keyboard.press`, а не `dispatchEvent` и не `locator.press`:
 * собранное руками событие не ведёт себя как клавиша, а `locator.press`
 * СНАЧАЛА ставит фокус на элемент, по которому жмёт, — и уносит то, что
 * мерим (на этом проба падала на всех пяти видах 21.10).
 *
 * СТЕНД ОТКРЫВАЕТСЯ С УНИКАЛЬНЫМ АДРЕСОМ, И ЭТО НЕ УКРАШЕНИЕ: у страницы
 * стенда нет номера версии, и браузер отдал мне КЭШ после правки — замер
 * говорил о прежнем стенде. СТРАНИЦА БЕЗ НОМЕРА В АДРЕСЕ МЕРИТ КЭШ.
 */

async function стенд(page) {
    const беды = [];
    page.on('pageerror', e => беды.push('pageerror: ' + e.message));
    page.on('console', m => {
        const т = m.text();
        if (m.type() === 'error' && !/Failed to load resource|ERR_/.test(т)) беды.push('console: ' + т);
    });
    await page.goto('/maket/fokus-zamer.html?' + Date.now());
    await page.waitForFunction(() => !!(window.ЗАМЕР && window.СТЕНД), null, { timeout: 15000 });
    return { з: await page.evaluate(() => window.ЗАМЕР), беды };
}

const кто = page => page.evaluate(() => document.activeElement && document.activeElement.id);
const запереть = (page, ид) => page.evaluate(и => window.СТЕНД.запереть(и), ид);
const снять = (page, ид) => page.evaluate(и => window.СТЕНД.снять(и), ид);
const открытых = page => page.evaluate(() => window.СТЕНД.открытых());
const поставитьФокус = (page, ид) => page.evaluate(и => {
    const э = document.getElementById(и);
    if (!э.hasAttribute('tabindex') && !/^(A|BUTTON|INPUT|SELECT|TEXTAREA)$/.test(э.tagName)) {
        э.setAttribute('tabindex', '-1');
    }
    э.focus();
}, ид);

test('дом отдаёт запирание и видит поля, а не только кнопки и ссылки', async ({ page }) => {
    const { з, беды } = await стенд(page);
    expect(беды, 'стенд ругается в консоль').toEqual([]);
    expect(з.домЕсть, 'дом запирания подключён').toBe(true);

    /* ГЛАВНОЕ ЧИСЛО КУСКА 113. Бедный список видел бы в окне A только кнопку
       и ссылку — ДВА элемента из пяти, а поле, выбор и текст остались бы
       вне ловушки, и Tab с них уходил бы под окно. */
    expect(з.нашлосьВА, 'фокусируемого в окне с полями').toBe(5);
    expect(з.списокДома, 'дом перечисляет поля').toContain('input:not([disabled])');
    expect(з.списокДома, 'дом перечисляет выбор').toContain('select:not([disabled])');
    expect(з.списокДома, 'дом перечисляет текст').toContain('textarea:not([disabled])');
});

test('Tab с последнего заворачивает на первый, а не уходит под окно', async ({ page }) => {
    await стенд(page);
    await запереть(page, 'окноC');
    await поставитьФокус(page, 'cПосл');
    expect(await кто(page), 'фокус на последней ссылке').toBe('cПосл');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'Tab с последнего вернулся на первый').toBe('cПер');
});

test('Shift+Tab с первого заворачивает на последний', async ({ page }) => {
    await стенд(page);
    await запереть(page, 'окноC');
    await поставитьФокус(page, 'cПер');
    await page.keyboard.press('Shift+Tab');
    expect(await кто(page), 'Shift+Tab с первого ушёл на последний').toBe('cПосл');
});

test('поле внутри окна не выпускает фокус — ровно то, на чём расходились копии', async ({ page }) => {
    await стенд(page);
    /* У бедного списка `textarea` в ловушку не входила: Tab с неё шёл на
       ссылку, а со ссылки — уже НАРУЖУ, потому что бедный список считал
       последним её, а не текст. Проверяем проход по всем пяти. */
    await поставитьФокус(page, 'aПоле');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'Tab из поля — на выбор').toBe('aВыбор');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'Tab из выбора — на текст').toBe('aТекст');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'Tab из текста — на ссылку').toBe('aПосл');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'и по кругу, а не под окно').toBe('aПер');
});

test('фокус, оказавшийся ПОД окном, возвращается внутрь — ЭТО И ЕСТЬ КУСОК 152', async ({ page }) => {
    await стенд(page);
    /* ЭТОГО НЕ УМЕЛО НИ ОДНО ОКНО САЙТА — не потому, что дом не умел, а
       потому, что до него не доходило нажатие: ловушка висела на подложке,
       а нажатие происходит на элементе страницы ПОД окном и до подложки не
       всплывает. Замер 23.10 на пяти видах: фокус уходил в `BODY`. */
    await запереть(page, 'окноC');
    await поставитьФокус(page, 'подКнопка');
    expect(await кто(page), 'фокус под окном').toBe('подКнопка');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'Tab вернул фокус в окно').toBe('cПер');
});

test('свидетель: при слушателе на подложке Tab из-под окна до ловушки не доходит', async ({ page }) => {
    await стенд(page);
    /* ОКНО A НАВЕШАНО НА ПОДЛОЖКУ НАМЕРЕННО — так были навешаны все пять
       окон сайта до куска 152. Стек пуст, слушателя дома на странице нет, и
       ловушка окна A нажатия под окном не слышит. Проверка объясняет, ПОЧЕМУ
       навешивание переехало в дом. */
    expect(await открытых(page), 'стек пуст').toBe(0);
    await поставитьФокус(page, 'подКнопка');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'фокус НЕ вернулся в окно A — ловушка на подложке его не слышит')
        .not.toBe('aПер');
});

test('скрытая кнопка последней не выпускает Tab из окна', async ({ page }) => {
    const { з } = await стенд(page);
    /* НОВЫЙ ЗАМЕР 23.10. В окне D последними стоят СКРЫТАЯ кнопка и видимая
       `position: fixed`. До 152 дом не проверял видимость: последним считал
       скрытую, `activeElement` с ней не совпадал, гашения не было — и Tab
       уходил на страницу под окном. */
    expect(з.нашлосьВD, 'дом видит в окне D только видимое').toBe(3);
    expect(з.вDбезВидимости, 'голым селектором их на одного больше').toBe(4);
    await запереть(page, 'окноD');
    await поставитьФокус(page, 'dФикс');
    expect(await кто(page), 'фокус на последнем ВИДИМОМ').toBe('dФикс');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'Tab завернул внутрь окна, а не ушёл под него').toBe('dПер');
});

test('признак видимости — высота, а не offsetParent', async ({ page }) => {
    const { з } = await стенд(page);
    /* ПРИЗНАК ВЫБРАН ЗАМЕРОМ, А НЕ ВКУСОМ: `offsetParent` равен null И у
       скрытой кнопки, И у видимой фиксированной. Четыре рукодельные копии
       вне дома спрашивают именно его и ошиблись бы на фиксированной. */
    expect(з.скрытаяПоOffsetParent, 'у скрытой offsetParent пуст').toBe(true);
    expect(з.фиксПоOffsetParent, 'и у ВИДИМОЙ фиксированной тоже пуст').toBe(true);
    expect(з.скрытаяПоВысоте, 'высота скрытой').toBe(0);
    expect(з.фиксПоВысоте, 'высота видимой фиксированной больше нуля').toBeGreaterThan(0);
});

test('пустое окно гасит Tab, а не отпускает его наружу', async ({ page }) => {
    const { з } = await стенд(page);
    expect(з.нашлосьВB, 'фокусируемого в пустом окне').toBe(0);
    /* ПЯТЬ КОПИЙ ВЫХОДИЛИ МОЛЧА: `if (!сп.length) return;` — и Tab шёл
       гулять по странице под окном. Лучшая гасила нажатие и ставила фокус
       на само окно; дом списан с неё. */
    await запереть(page, 'окноB');
    await поставитьФокус(page, 'окноB');
    expect(await кто(page), 'фокус на пустом окне').toBe('окноB');
    await page.keyboard.press('Tab');
    const куда = await page.evaluate(() => {
        const a = document.activeElement;
        return { id: a && a.id, этоОкно: a === document.getElementById('окноB') };
    });
    expect(куда.этоОкно, 'фокус остался на пустом окне, а не ушёл под него').toBe(true);
    expect(куда.id, 'фокус точно не на кнопке страницы').not.toBe('подКнопка');
});

test('из двух открытых окон нажатие получает ВЕРХНЕЕ', async ({ page }) => {
    await стенд(page);
    /* ШОВ, НА КОТОРОМ СОВРАЛ ПЕРВЫЙ СТЕНД 21.10: два слушателя на
       `document` слышали нажатия друг друга, оба срабатывали на один Tab,
       победила последняя — фокус уехал в ЧУЖОЕ окно. Теперь это не
       везение, а порядок: стек. */
    await запереть(page, 'окноC');
    await запереть(page, 'окноE');
    expect(await открытых(page), 'открыто два окна').toBe(2);
    await поставитьФокус(page, 'подКнопка');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'фокус ушёл в ВЕРХНЕЕ окно, а не в нижнее').toBe('eПер');
    await снять(page, 'окноE');
    expect(await открытых(page), 'после снятия верхнего осталось одно').toBe(1);
    await поставитьФокус(page, 'подКнопка');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'и теперь верхним стало нижнее').toBe('cПер');
});

test('окно, закрытое мимо дома, снимается само — по признаку, а не по обещанию', async ({ page }) => {
    await стенд(page);
    /* ДЕВЯТЬ РУКОДЕЛЬНЫХ ОКОН закрывают себя своим же `overlay.remove()`, и
       дом об этом не узнаёт. Признак — узел ушёл из документа. Без него
       слушатель остался бы на `document` навсегда. */
    await запереть(page, 'окноC');
    await запереть(page, 'окноB');
    expect(await открытых(page), 'открыто два').toBe(2);
    await page.evaluate(() => window.СТЕНД.убратьУзел('окноB'));
    expect(await открытых(page), 'дом пока не знает: закрытия он не видит').toBe(2);
    await поставитьФокус(page, 'подКнопка');
    await page.keyboard.press('Tab');
    expect(await открытых(page), 'мёртвая запись снялась сама на первом же нажатии').toBe(1);
    expect(await кто(page), 'и нажатие получило оставшееся окно').toBe('cПер');
});

test('стек пустеет, и ловушка не остаётся на странице после закрытия', async ({ page }) => {
    await стенд(page);
    /* ЦЕНА ПЕРЕНОСА, НАЗВАННАЯ ДО КОДА: слушатель на `document` обязан
       сниматься при закрытии, иначе Tab заперт на всей странице. */
    await запереть(page, 'окноC');
    await снять(page, 'окноC');
    expect(await открытых(page), 'стек пуст').toBe(0);
    await поставитьФокус(page, 'подКнопка');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'фокус ушёл со страницы дальше, как и должен')
        .not.toBe('подКнопка');
    expect(await кто(page), 'и не был затянут в окно, которое закрыли')
        .not.toBe('cПер');
});
