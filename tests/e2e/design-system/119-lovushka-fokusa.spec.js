/**
 * ЛОВУШКА ФОКУСА: ОДИН ДОМ НА КАБИНЕТ, СТРАНИЦУ ИГРОКА И АДМИНКУ. 21.10.
 *
 * ЧТО СТОРОЖ НЕ МОЖЕТ. `tools/check-kopii-funkciy.js` читает исходник: нет
 * ли своей ловушки мимо дома и подключён ли дом. Он не может сказать, ДЕРЖИТ
 * ли Tab внутри окна. А вся цена куска именно в этом: под открытым окном
 * лежит страница с кнопками, которые меняют данные, и слепой обход по ней
 * из окна — нажатие вслепую.
 *
 * ШЕСТЬ КОПИЙ, И ОНИ УЖЕ РАЗОШЛИСЬ ТРИЖДЫ. Четыре в `dashboard.js`, одна в
 * `player.js`, одна в оболочке окна админки:
 *   1. две не перечисляли поля (`input`, `select`, `textarea`) — окна «игрок
 *      против игрока». Полей там сегодня нет, и бедой это НЕ БЫЛО; держалось
 *      на СОДЕРЖИМОМ окна, а не на правиле;
 *   2. пять не возвращали фокус, если он оказался ПОД окном;
 *   3. пять отпускали Tab наружу из пустого окна.
 * Сведено на ЛУЧШУЮ — админскую, — а не на первую попавшуюся.
 *
 * МЕРИТСЯ СТЕНДОМ И НАСТОЯЩИМ НАЖАТИЕМ. Кабинет и админка за входом: страж
 * уводит кадр на `auth.html`, и замер говорит о странице входа. А Tab
 * проверяется `keyboard.press`, а не `dispatchEvent`: событие, собранное
 * руками, не поведёт себя как клавиша (урок доски 109 про `:hover`).
 */

async function стенд(page) {
    const беды = [];
    page.on('pageerror', e => беды.push('pageerror: ' + e.message));
    page.on('console', m => {
        const т = m.text();
        if (m.type() === 'error' && !/Failed to load resource|ERR_/.test(т)) беды.push('console: ' + т);
    });
    await page.goto('/maket/fokus-zamer.html');
    await page.waitForFunction(() => !!(window.ЗАМЕР && window.ОТКРЫТЬ), null, { timeout: 15000 });
    return { з: await page.evaluate(() => window.ЗАМЕР), беды };
}

const кто = page => page.evaluate(() => document.activeElement && document.activeElement.id);

test('дом подключён и видит поля, а не только кнопки и ссылки', async ({ page }) => {
    const { з, беды } = await стенд(page);
    expect(беды, 'стенд ругается в консоль').toEqual([]);
    expect(з.домЕсть, 'дом ловушки подключён').toBe(true);

    /* ГЛАВНОЕ ЧИСЛО КУСКА. Бедный список видел бы в окне A только кнопку и
       ссылку — ДВА элемента из пяти, а поле, выбор и текст остались бы вне
       ловушки, и Tab с них уходил бы под окно. */
    expect(з.нашлосьВА, 'фокусируемого в окне с полями').toBe(5);
    expect(з.списокДома, 'дом перечисляет поля').toContain('input:not([disabled])');
    expect(з.списокДома, 'дом перечисляет выбор').toContain('select:not([disabled])');
    expect(з.списокДома, 'дом перечисляет текст').toContain('textarea:not([disabled])');
});

test('Tab с последнего заворачивает на первый, а не уходит под окно', async ({ page }) => {
    await стенд(page);
    await page.locator('#aПосл').focus();
    expect(await кто(page), 'фокус на последней ссылке').toBe('aПосл');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'Tab с последнего вернулся на первый').toBe('aПер');
});

test('Shift+Tab с первого заворачивает на последний', async ({ page }) => {
    await стенд(page);
    await page.locator('#aПер').focus();
    await page.keyboard.press('Shift+Tab');
    expect(await кто(page), 'Shift+Tab с первого ушёл на последний').toBe('aПосл');
});

test('поле внутри окна не выпускает фокус — ровно то, на чём расходились копии', async ({ page }) => {
    await стенд(page);
    /* У бедного списка `textarea` в ловушку не входила: Tab с неё шёл на
       ссылку, а со ссылки — уже НАРУЖУ, потому что бедный список считал
       последним её, а не текст. Проверяем проход по всем пяти. */
    await page.locator('#aПоле').focus();
    await page.keyboard.press('Tab');
    expect(await кто(page), 'Tab из поля — на выбор').toBe('aВыбор');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'Tab из выбора — на текст').toBe('aТекст');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'Tab из текста — на ссылку').toBe('aПосл');
    await page.keyboard.press('Tab');
    expect(await кто(page), 'и по кругу, а не под окно').toBe('aПер');
});

test('фокус, оказавшийся ПОД окном, возвращается внутрь — но только там, где слушатель на document', async ({ page }) => {
    await стенд(page);
    /* ЭТОГО НЕ УМЕЛИ ПЯТЬ КОПИЙ ИЗ ШЕСТИ. Но проба на этом И УПАЛА, и
       падение нашло настоящее: ПРИ СЛУШАТЕЛЕ НА ПОДЛОЖКЕ ЭТА ВЕТКА
       НЕДОСТИЖИМА ВООБЩЕ. Нажатие происходит на элементе страницы ПОД
       окном, до подложки не всплывает, и обработчик не зовётся — сколько
       бы дом ни умел. У пяти окон сайта (`overlay.addEventListener`) она
       поэтому мёртвая, у админского окна (`document.addEventListener`)
       живая. Записано в трекер отдельной находкой.
       Поэтому проверяем её на окне C — том, что навешано как админское. */
    await page.evaluate(() => window.ОТКРЫТЬ('окноC'));
    await page.locator('#подКнопка').focus();
    expect(await кто(page), 'фокус под окном').toBe('подКнопка');
    /* НАСТОЯЩЕЕ НАЖАТИЕ, А НЕ `locator.press`: тот СНАЧАЛА ставит фокус на
       элемент, по которому жмёт, — и своей же рукой уносит то, что мерим.
       Ровно на этом проба и упала на всех пяти видах. */
    await page.keyboard.press('Tab');
    expect(await кто(page), 'Tab вернул фокус в окно').toBe('cПер');
});

test('при слушателе на подложке Tab из-под окна до ловушки не доходит — это свойство продукта', async ({ page }) => {
    await стенд(page);
    /* ЗАМОРАЖИВАЕТСЯ ЗАМЕРЕННОЕ, А НЕ ЖЕЛАЕМОЕ. Окно A навешано как все
       пять окон сайта. Фокус под ним — и Tab уходит дальше по странице:
       обработчик не зовётся. Если однажды это изменится (окна сайта
       перевесят на `document`), проба упадёт — и упадёт ПО ДЕЛУ, потому
       что тогда появится обязанность снимать слушателя при закрытии. */
    await page.evaluate(() => window.ОТКРЫТЬ(null));
    await page.locator('#подКнопка').focus();
    await page.keyboard.press('Tab');
    const куда = await кто(page);
    expect(куда, 'фокус НЕ вернулся в окно A — ловушка на подложке его не слышит')
        .not.toBe('aПер');
});

test('пустое окно гасит Tab, а не отпускает его наружу', async ({ page }) => {
    const { з } = await стенд(page);
    expect(з.нашлосьВB, 'фокусируемого в пустом окне').toBe(0);
    /* ПЯТЬ КОПИЙ ВЫХОДИЛИ МОЛЧА: `if (!сп.length) return;` — и Tab шёл
       гулять по странице под окном. Лучшая гасила нажатие и ставила фокус
       на само окно. Проверяется на окне B — навешанном как админское, с
       `tabindex="-1"`, как оболочка и делает. */
    await page.evaluate(() => window.ОТКРЫТЬ('окноB'));
    await page.locator('#окноB').focus();
    expect(await кто(page), 'фокус на пустом окне').toBe('окноB');
    await page.keyboard.press('Tab');
    const куда = await page.evaluate(() => {
        const a = document.activeElement;
        return { id: a && a.id, этоОкно: a === document.getElementById('окноB') };
    });
    expect(куда.этоОкно, 'фокус остался на пустом окне, а не ушёл под него').toBe(true);
    expect(куда.id, 'фокус точно не на кнопке страницы').not.toBe('подКнопка');
});

test('без открытого окна ловушка молчит — она не висит на странице навсегда', async ({ page }) => {
    await стенд(page);
    /* СЛУШАТЕЛЬ НА `document` ЖИВЁТ РОВНО ПОКА ОКНО ОТКРЫТО. Если его не
       снять при закрытии, Tab останется в ловушке на всей странице — и
       это ровно та цена, которой пришлось бы заплатить за перенос окон
       сайта с подложки на document. */
    await page.evaluate(() => window.ОТКРЫТЬ(null));
    await page.locator('#подКнопка').focus();
    await page.keyboard.press('Tab');
    expect(await кто(page), 'фокус ушёл со страницы дальше, как и должен')
        .not.toBe('подКнопка');
});
