const { test, expect } = require('../../fixtures');

/**
 * ЛЕСТНИЦА РАЗРЯДОВ: БАЗА — ИСТОЧНИК, ЗАШИТЫЙ СПИСОК — ЗАПАСНОЙ. Кусок 116.
 *
 * ЧТО СТОРОЖ НЕ МОЖЕТ. `tools/check-lestnica-razryadov.js` читает исходник
 * и держит ЗАМЕРЕННЫЙ порядок числом. Он не может спросить БАЗУ — а именно
 * там живёт источник: `categories.sort_order`. Расхождение появится не от
 * правки кода, а от НОВОЙ КАТЕГОРИИ, заведённой в админке, и исходник об
 * этом не узнает никогда.
 * РЕЗУЛЬТАТ ЗАПРОСА ПРОВЕРЯЕТСЯ ЧТЕНИЕМ БАЗЫ.
 *
 * ЗАМЕР 21.10 (чтением боевой, только на чтение): sort_order сверху вниз —
 * promasters 5, masters 4, tour 3, challenger 2, futures 1, friendly 0. Дом
 * перечисляет те же пять в том же порядке, и ничто этого не держало.
 *
 * ДВЕ БЕДЫ, НАЙДЕННЫЕ ЭТИМ ЗАМЕРОМ:
 *   — `R.categoriesFor` брал категории ИЗ БАЗЫ, но строка `if (!c) return`
 *     оставляла только перечисленные в зашитом списке: категория из
 *     админки НЕ ПОЯВИЛАСЬ БЫ на сайте вовсе;
 *   — в запасном наборе страницы турниров имя стояло «Challengers», в базе
 *     «Challenger» — копии разошлись, и увидели бы это ровно тогда, когда
 *     база недоступна и показывается запасной.
 */

const ПОРЯДОК = ['promasters', 'masters', 'tour', 'challenger', 'futures'];
const ИМЕНА = { promasters: 'Pro-Masters', masters: 'Masters', tour: 'Tour',
                challenger: 'Challenger', futures: 'Futures' };

/* СПРАШИВАЕМ ТОЛЬКО ТО, ЧТО ЕСТЬ. Первая редакция запросила `is_rating`, и
   тестовая база ответила 400: колонки там нет. ТЕСТОВАЯ БАЗА — ЧАСТЬ
   ПРИБОРА, И ОНА СТАРЕЕТ; проба, спросившая лишнюю колонку, падает на
   приборе, а не на продукте.
   Страница берётся та, что ГРУЗИТ ДОМ ПРАВИЛ: на `index.html` его нет. */
async function база(page) {
    await page.goto('/pages/players.html');
    await page.waitForFunction(() => !!(window.KSLT_DB && window.KSLT_DB.url), null, { timeout: 15000 });
    return page.evaluate(async () => {
        const { url, key } = window.KSLT_DB;
        const r = await fetch(url + '/rest/v1/categories?select=id,name,sort_order&order=sort_order.desc',
            { headers: { apikey: key, Authorization: 'Bearer ' + key } });
        return { статус: r.status, строки: await r.json() };
    });
}

test('порядок разрядов в базе совпадает с домом', async ({ page }) => {
    const { статус, строки } = await база(page);
    expect(статус, 'база ответила').toBe(200);

    /* ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ, А НЕ СПИСОК. Первая редакция требовала в
       базе все пять разрядов — и упала: в ТЕСТОВОЙ их ТРИ. Это не беда
       продукта, это долг сева, записанный в трекере («пяти таблиц в
       тестовой нет вовсе»). ТЕСТОВАЯ БАЗА — ЧАСТЬ ПРИБОРА, И ОНА СТАРЕЕТ.
       Проба, требующая данных, которых в базе нет, падает НА ПРИБОРЕ.
       Поэтому сверяется ПЕРЕСЕЧЕНИЕ: те разряды, что есть и в базе, и в
       доме, обязаны идти в ОДНОМ относительном порядке. Это и есть то
       отношение, расхождение которого даёт разный ответ на вопрос «какая
       категория выше» у посева и у публичного рейтинга — а оно ловится и
       на трёх разрядах, и на пяти. */
    const рейтинговые = строки.filter(к => к.id !== 'friendly');
    expect(рейтинговые.length, 'ПОРОГ: рейтинговых разрядов в базе меньше двух — сверять нечего')
        .toBeGreaterThanOrEqual(2);

    const общие = рейтинговые.map(к => к.id).filter(ид => ПОРЯДОК.indexOf(ид) !== -1);
    expect(общие.length, 'ПОРОГ: ни один разряд базы не знаком дому')
        .toBeGreaterThanOrEqual(2);
    expect(общие, 'относительный порядок знакомых дому разрядов')
        .toEqual(ПОРЯДОК.filter(ид => общие.indexOf(ид) !== -1));

    /* И ОТДЕЛЬНО — ЧТО ПОРЯДОК ВООБЩЕ СТРОГИЙ: `sort_order` без повторов,
       иначе «выше» не определено, и ответ зависит от того, кто первый
       вернулся из базы. */
    const ступени = рейтинговые.map(к => Number(к.sort_order));
    expect(new Set(ступени).size, 'ступени sort_order без повторов: ' + ступени.join(' · '))
        .toBe(ступени.length);
});

/* ИМЕНА РАЗРЯДОВ ПРОБОЙ НЕ СВЕРЯЮТСЯ, И ЭТО НАЗВАНО.
   Проверка «имя в базе равно имени в запасном наборе» падала пятью видами:
   в ТЕСТОВОЙ базе разряд зовётся `FUTURES`, в боевой — `Futures`.
   ТЕСТОВАЯ БАЗА РАСХОДИТСЯ С БОЕВОЙ НЕ ТОЛЬКО СОСТАВОМ, НО И ЗНАЧЕНИЯМИ:
   состав там три разряда из пяти, а имена — свои. Сверять боевые имена с
   тестовой базы значит падать на приборе, а не на продукте.
   Поэтому имена держит СТОРОЖ `tools/check-lestnica-razryadov.js` числом,
   замеренным чтением БОЕВОЙ базы 21.10 (правило «имена в запасном наборе
   совпадают с замеренными в базе»), а проба держит то, что верно на любой
   базе: относительный порядок и строгость ступеней.
   ЧИСЛО, КОТОРОГО НЕ МОГУ ПОМЕРИТЬ ЗДЕСЬ, Я НЕ ВЫДУМЫВАЮ И НЕ ПЕРЕНОШУ. */

test('дом ставит незнакомый разряд в хвост, а не выбрасывает его', async ({ page }) => {
    await page.goto('/pages/players.html');
    await page.waitForFunction(() => !!(window.KSLT_RULES && window.KSLT_RULES.categoriesFor),
        null, { timeout: 15000 });
    /* ГЛАВНОЕ ЧИСЛО КУСКА: кормим дом СВОЕЙ таблицей, в которой есть
       категория, которой в зашитом списке нет вовсе. Она обязана дойти до
       ответа — иначе новая категория из админки не покажется на сайте. */
    const итог = await page.evaluate(() => {
        const свои = [
            { id: 'promasters', name: 'Pro-Masters', sort_order: 5 },
            { id: 'masters', name: 'Masters', sort_order: 4 },
            { id: 'tour', name: 'Tour', sort_order: 3 },
            { id: 'challenger', name: 'Challenger', sort_order: 2 },
            { id: 'futures', name: 'Futures', sort_order: 1 },
            { id: 'novaya', name: 'Новая лига', sort_order: 6 },
            { id: 'friendly', name: 'Friendly', sort_order: 0 }
        ];
        return {
            мужчины: window.KSLT_RULES.categoriesFor('men', свои).map(c => c.id),
            женщины: window.KSLT_RULES.categoriesFor('women', свои).map(c => c.id)
        };
    });
    expect(итог.мужчины, 'новая категория дошла и встала в хвост')
        .toEqual(['promasters', 'masters', 'tour', 'challenger', 'futures', 'novaya']);
    /* ФИЛЬТР ПОЛА ОСТАЛСЯ: у женщин разрядов три — решение клуба, и в базе
       пола у категорий нет вовсе. Незнакомая идёт обоим: выдумывать ей пол
       нельзя. */
    expect(итог.женщины, 'у женщин три разряда плюс незнакомая')
        .toEqual(['masters', 'tour', 'futures', 'novaya']);
    /* ДРУЖЕСКИЕ ОЧКОВ НЕ ДАЮТ — в таблицы не идут ни в каком виде. */
    expect(итог.мужчины.indexOf('friendly'), 'дружеские не попали').toBe(-1);
    expect(итог.женщины.indexOf('friendly'), 'дружеские не попали женщинам').toBe(-1);
});
