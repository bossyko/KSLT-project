// @ts-check
const { test, expect } = require('@playwright/test');

/**
 * БЕЙДЖ РОЛИ: ОДНА ФОРМА, А НЕ ЧЕТЫРЕ. Находка 96в, 19.10.
 *
 * ЗАЧЕМ ПРОБА, ЕСЛИ ЕСТЬ СТОРОЖ. `tools/check-rol-badzh.js` читает
 * исходник: одно ли определение, названы ли числа именами. Он не может
 * сказать, какой бейдж ВЫРОС на экране. А главное число этого куска —
 * именно высота: эталон (компонент Badge 27:53) требует 24, и я сам
 * поставил `border` вместо внутренней тени — замер дал 26. По исходнику
 * это не видно никак: обводка объявлена, высота объявлена, всё «правильно».
 *
 * ПЯТЬ ВИДОВ. Бейдж роли от ширины не зависит — и проба требует, чтобы не
 * зависел: ни одно число не должно разойтись между видами. Загрузка идёт
 * на нужной ширине, а не сжатием уже загруженного.
 *
 * ТРИ ЯЗЫКА на одном стенде: роль переводится, форма — нет. Кыргызское
 * «Колдонуучу» длиннее русского «Пользователь» в знаках, и если бейдж
 * начнёт переноситься, высота выдаст это сразу.
 *
 * ПОЧЕМУ СТЕНД, А НЕ АДМИНКА. Админка и кабинет за входом, пароля у пробы
 * нет. Стенд грузит те же `style.css` + `admin.css` + `dashboard.css` и
 * ПОДЛОЖКИ ПРОДУКТА (админка #0f1219, кабинет --bg-base) — контраст без
 * подложки посчитать нельзя вовсе, краски полупрозрачные.
 */

const ПОРОГ_AA = 4.5;   /* WCAG 1.4.3: 11px — мелкий текст */
const ВЫСОТА = 24;      /* --chip-h, эталон Badge 27:53 */

const ВИДЫ = [
    { имя: 'телефон вертикально', w: 390, h: 844 },
    { имя: 'телефон горизонтально', w: 844, h: 390 },
    { имя: 'планшет вертикально', w: 768, h: 1024 },
    { имя: 'планшет горизонтально', w: 1024, h: 768 },
    { имя: 'десктоп', w: 1440, h: 900 }
];

async function стенд(page) {
    const беды = [];
    page.on('pageerror', e => беды.push('pageerror: ' + e.message));
    page.on('console', m => {
        const т = m.text();
        if (m.type() === 'error' && !/Failed to load resource|ERR_/.test(т)) {
            беды.push('console: ' + т);
        }
    });
    await page.goto('/maket/rol-badzh-zamer.html');
    /* ЖДЁМ ПРИЗНАК, А НЕ ТИШИНУ СЕТИ: замер выставляется после шрифтов. */
    await page.waitForFunction(() => !!window.ЗАМЕР, null, { timeout: 15000 });
    return { з: await page.evaluate(() => window.ЗАМЕР), беды };
}

for (const вид of ВИДЫ) {
    test(`${вид.имя}: бейдж роли одной формы, высота ${ВЫСОТА}`, async ({ page }) => {
        await page.setViewportSize({ width: вид.w, height: вид.h });
        const { з, беды } = await стенд(page);
        expect(беды, 'страница ругается в консоль').toEqual([]);

        const ключи = Object.keys(з.роли);
        expect(ключи.length, 'роли на стенде не нашлись').toBeGreaterThan(3);

        /* ГЛАВНОЕ ЧИСЛО КУСКА. Было 18 · 19 · 19 · 21 четырьмя формами. */
        for (const к of ключи) {
            expect(з.роли[к].высота, `высота бейджа «${к}»`).toBe(ВЫСОТА);
        }

        /* ОДНА ФОРМА — это не «похожи», а побайтово один набор свойств.
           Кегль, вес, межбуквенный, радиус, отступы, капс: всё одно. */
        expect(з.формОдна, 'разных форм бейджа роли на экране').toBe(1);

        /* Перенос выдал бы, что слово не влезло: высота ушла бы за 26. */
        expect(з.переносов, 'бейджей, переехавших на вторую строку').toBe(0);
    });

    test(`${вид.имя}: каждая роль проходит AA`, async ({ page }) => {
        await page.setViewportSize({ width: вид.w, height: вид.h });
        const { з } = await стенд(page);
        for (const к of Object.keys(з.роли)) {
            expect(з.роли[к].контраст, `контраст роли «${к}» при пороге ${ПОРОГ_AA}`)
                .toBeGreaterThanOrEqual(ПОРОГ_AA);
        }
    });
}

test('обводка внутренней тенью: border добавил бы 2px к 24', async ({ page }) => {
    const { з } = await стенд(page);
    for (const к of Object.keys(з.роли)) {
        expect(з.роли[к].тень, `у роли «${к}» обводка внутренней тенью`).toBe(true);
        expect(з.роли[к].рамка, `у роли «${к}» нет border`).toBe(0);
    }
});

test('админ лаймом, и ни одна роль не красится как другая', async ({ page }) => {
    const { з } = await стенд(page);
    /* Контраст — отпечаток краски: у лайма он много выше, чем у остальных.
       Админ 11.99 в админке и 13.09 в кабинете — подложки разные. */
    const адм = з.роли['admin/админка'];
    expect(адм, 'роль админа на стенде').toBeTruthy();
    expect(адм.контраст, 'админ лаймом — слово Кости 19.10').toBeGreaterThan(10);

    /* Менеджер НЕ лаймовый: до 19.10 боковая панель красила его лаймом,
       а таблица — фиолетовым, и одно из двух было неправдой. */
    const мен = з.роли['manager/админка'];
    expect(мен.контраст, 'менеджер своей краской, а не лаймом админа')
        .toBeLessThan(адм.контраст - 2);

    /* Четыре роли — четыре разных краски, то есть четыре разных контраста. */
    const свои = ['admin/админка', 'manager/админка', 'player/админка', 'user/админка']
        .map(к => з.роли[к] && з.роли[к].контраст)
        .filter(v => v !== undefined);
    expect(свои.length, 'все четыре роли на стенде').toBe(4);
    expect(new Set(свои).size, 'четыре роли — четыре разные краски').toBe(4);
});

test('рост бейджа не раздвинул строку таблицы', async ({ page }) => {
    const { з } = await стенд(page);
    /* Я САМ НАЗВАЛ ЦЕНУ «строка станет выше на 5px» — и прибор её не нашёл.
       Строку держит её собственный отступ, бейдж укладывался с запасом. */
    expect(з.строкиБыло.length, 'таблица «было» на стенде').toBeGreaterThan(0);
    expect(з.строкиСтанет, 'строка со старым и с новым бейджем одной высоты')
        .toEqual(з.строкиБыло);
});

test('подложки взяты из продукта, а не из стенда', async ({ page }) => {
    const { з } = await стенд(page);
    /* Без этого контраст считался бы к чужому фону и врал бы в обе стороны:
       админка #0f1219 = 15,18,25, кабинет --bg-base = 10,10,10. */
    expect(з.фоны.админка, 'подложка админки — та, что в admin.css').toBe('15,18,25,1');
    expect(з.фоны.кабинет, 'подложка кабинета — --bg-base').toBe('10,10,10,1');
    expect(з.фоны.админка).not.toBe(з.фоны.кабинет);
});
