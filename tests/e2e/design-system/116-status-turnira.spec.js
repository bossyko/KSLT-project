const { test, expect } = require('@playwright/test');

/**
 * СТАТУС ТУРНИРА — ОДИН ОТВЕТ НА ВСЕХ СТРАНИЦАХ. 19.10.
 *
 * ЧТО СТОРОЖ НЕ МОЖЕТ. `tools/check-status-turnira.js` читает исходник:
 * одно ли определение, подключён ли дом, одна ли версия. Он не может
 * сказать, ОДИН ЛИ ОТВЕТ даёт статус на разных страницах — а это и есть
 * предмет: турнир, попавший в два списка по-разному, виден человеку.
 *
 * ПОЧЕМУ СРАВНЕНИЕ, А НЕ ПРОВЕРКА ОДНОГО ЗНАЧЕНИЯ. Копии были побайтово
 * одинаковы, значит и ответы совпадали. Беда была не в сегодняшнем
 * расхождении, а в том, что РАСХОДИТЬСЯ БЫЛО ЧЕМУ: четыре посредника под
 * двумя именами. Проба держит то, что теперь источник один — и упадёт,
 * если где-то снова появится свой.
 *
 * ДАТЫ ЗАДАНЫ ЯВНО, А НЕ ВЗЯТЫ ИЗ БАЗЫ: проба, которая ждёт данных,
 * падает на пустой базе, а не на продукте (урок 07.10).
 */

const СЛУЧАИ = [
    { имя: 'регистрация ещё не открыта', д: ['2026-11-01', '2026-11-10', '2026-11-20', '2026-11-22'], ждём: 'upcoming' },
    { имя: 'регистрация открыта',        д: ['2026-10-01', '2026-10-30', '2026-11-20', '2026-11-22'], ждём: 'registration_open' },
    { имя: 'регистрация закрыта',        д: ['2026-10-01', '2026-10-10', '2026-10-25', '2026-10-27'], ждём: 'registration_closed' },
    { имя: 'идёт сейчас',                д: ['2026-10-01', '2026-10-10', '2026-10-19', '2026-10-23'], ждём: 'ongoing' },
    { имя: 'завершён',                   д: ['2026-09-01', '2026-09-10', '2026-09-15', '2026-09-17'], ждём: 'completed' }
];

const СТРАНИЦЫ = ['/index.html', '/pages/tournaments-overview.html',
                  '/pages/tournament.html', '/pages/tournaments.html'];

async function дом(page, стр) {
    await page.goto(стр);
    await page.waitForFunction(() => !!(window.KSLT_STATUS && window.KSLT_STATUS.вычислить),
                               null, { timeout: 15000 });
    return page.evaluate((случаи) => ({
        ответы: случаи.map(с => window.KSLT_STATUS.вычислить(с.д[0], с.д[1], с.д[2], с.д[3])),
        /* Обёртки-посредника быть не должно ни под одним из двух имён. */
        посредники: ['computeStatus', 'computeTournamentStatus']
            .filter(и => typeof window[и] === 'function')
    }), СЛУЧАИ);
}

test.describe('статус считается домом и одинаково всюду', () => {
    for (const стр of СТРАНИЦЫ) {
        test(`${стр}: пять случаев и ни одного посредника`, async ({ page }) => {
            const { ответы, посредники } = await дом(page, стр);
            СЛУЧАИ.forEach((с, i) => {
                expect(ответы[i], с.имя).toBe(с.ждём);
            });
            expect(посредники, 'глобальных обёрток над домом нет').toEqual([]);
        });
    }

    test('все страницы дают один и тот же ответ', async ({ page }) => {
        const собрано = [];
        for (const стр of СТРАНИЦЫ) {
            const { ответы } = await дом(page, стр);
            собрано.push(ответы.join('|'));
        }
        /* ГЛАВНОЕ ЧИСЛО КУСКА: разных ответов ровно один набор. Разойдись
           источники — турнир попал бы в два списка по-разному. */
        expect(new Set(собрано).size, 'наборов ответов на ' + СТРАНИЦЫ.length + ' страницах').toBe(1);
    });
});

test('стенд итогов лиг не падает без дома: дом там подключён', async ({ page }) => {
    /* Беда СПАЛА: стенд звал tournament-detail.js, не подключив дом статуса.
       Сегодня статус там не доходил до зова, а первая же правка уронила бы
       стенд целиком. */
    const беды = [];
    page.on('pageerror', e => беды.push(e.message));
    await page.goto('/maket/proba-itogi-lig.html');
    await page.waitForFunction(() => document.readyState === 'complete', null, { timeout: 15000 });
    const есть = await page.evaluate(() =>
        !!(window.KSLT_STATUS && typeof window.KSLT_STATUS.вычислить === 'function'));
    expect(есть, 'дом статуса подключён на стенде').toBe(true);
    expect(беды, 'стенд ругается в консоль').toEqual([]);
});

test('подписи статусов берутся тем же домом', async ({ page }) => {
    await page.goto('/pages/tournaments-overview.html');
    await page.waitForFunction(() => !!(window.KSLT_STATUS && window.KSLT_STATUS.подписи),
                               null, { timeout: 15000 });
    const пары = await page.evaluate(() => {
        const ру = window.KSLT_STATUS.подписи('ru');
        const en = window.KSLT_STATUS.подписи('en');
        return { ключейРу: Object.keys(ру).length, ключейEn: Object.keys(en).length,
                 совпадаютКлючи: Object.keys(ру).join(',') === Object.keys(en).join(',') };
    });
    /* Подписи и вычисление — одно понятие: раньше админка звала то же
       состояние «Предстоящий», а сайт «Скоро» и «Скоро открытие». */
    expect(пары.ключейРу, 'подписей на русском').toBeGreaterThan(3);
    expect(пары.совпадаютКлючи, 'набор состояний одинаков на двух языках').toBe(true);
});
