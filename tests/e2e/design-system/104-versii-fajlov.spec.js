const { test, expect } = require('../../fixtures');

const ЯЗЫКИ = [
    { код: 'ru', хвост: '' },
    { код: 'en', хвост: '-en' },
    { код: 'kg', хвост: '-kg' }
];

/** Свой ресурс — тот, что лежит у нас, а не на чужом адресе. */
const СВОЙ = `(u, base) => {
    try {
        const a = new URL(u, base);
        if (a.origin !== new URL(base).origin) return null;
        const m = a.pathname.match(/\\/([\\w.-]+\\.(?:js|css))$/);
        if (!m) return null;
        return { имя: m[1], версия: a.searchParams.get('v'), путь: a.pathname };
    } catch (e) { return null; }
}`;

async function собрать(page, адрес) {
    const беды = [];
    page.on('response', r => {
        const u = r.url();
        if (!/\.(js|css)(\?|$)/.test(u)) return;
        if (r.status() >= 400) беды.push(r.status() + ' ' + u);
    });
    await page.goto(адрес);
    await page.waitForLoadState('domcontentloaded');
    await page.waitForTimeout(1200);
    /* Берём РЕАЛЬНО ЗАГРУЖЕННОЕ, а не разметку: performance видит и то,
       что добавил js после загрузки. */
    const данные = await page.evaluate(свойИсх => {
        const свой = eval('(' + свойИсх + ')');
        const свои = performance.getEntriesByType('resource').map(r => r.name)
            .map(u => свой(u, location.href)).filter(Boolean);
        const счёт = {};
        свои.forEach(с => { счёт[с.имя] = (счёт[с.имя] || 0) + 1; });
        return { свои, путь: location.pathname, дважды: Object.entries(счёт).filter(([, n]) => n > 1) };
    }, СВОЙ);
    return { беды, ...данные };
}

for (const язык of ЯЗЫКИ) {

test.describe('версии файлов · ' + язык.код, () => {

    for (const стр of ['/index' + язык.хвост + '.html', '/pages/tournaments-overview' + язык.хвост + '.html']) {

        test('свои файлы грузятся и каждый со своей версией · ' + стр, async ({ page }) => {
            const { беды, свои, путь } = await собрать(page, стр);

            expect(путь, 'страницу подменили переходом: просили ' + стр + ', оказались на ' + путь +
                '\nПроба молча померила бы чужую страницу.').toContain(стр.replace(/^\//, ''));
            expect(свои.length, 'ПОРОГ: своих файлов не загрузилось вовсе — страница не поднялась').toBeGreaterThan(3);

            expect(беды.join('\n'),
                'свой файл не отдался браузеру:\n' + беды.join('\n') +
                '\nНОМЕР ВЕРСИИ МОЖНО ПОДНЯТЬ У ИМЕНИ, КОТОРОГО НА ДИСКЕ НЕТ:\n' +
                'правило промолчит, а страница получит 404.').toBe('');

            const безВерсии = свои.filter(с => !с.версия).map(с => с.путь);
            expect(безВерсии.join(', '),
                'свои файлы приехали без версии: ' + безВерсии.join(', ') +
                '\nТАКОЕ ПОДКЛЮЧЕНИЕ МОГЛО ПРИЙТИ ИЗ JS, и в разметке его нет —\n' +
                'заморозка такого не видит по построению.').toBe('');
        });

        test('один файл не приехал дважды · ' + стр, async ({ page }) => {
            const { свои, путь, дважды: счёт } = await собрать(page, стр);
            expect(путь, 'страницу подменили переходом: просили ' + стр).toContain(стр.replace(/^\//, ''));
            expect(свои.length, 'ПОРОГ: своих файлов не загрузилось вовсе').toBeGreaterThan(3);
            expect(счёт.map(([и, n]) => и + ' ×' + n).join(', '),
                'один файл приехал несколько раз: ' + счёт.map(([и, n]) => и + ' ×' + n).join(', ') +
                '\nВторое подключение — это второе исполнение.').toBe('');
        });
    }

});

}
