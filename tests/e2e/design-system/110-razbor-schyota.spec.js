// @ts-check
const { test, expect } = require('@playwright/test');

/**
 * РАЗБОР СЧЁТА В НАСТОЯЩЕЙ АДМИНКЕ. Круг 20 ветки D.
 *
 * ЭТО ТРОГАЕТ ОЧКИ: из разобранного счёта считаются геймы, сеты и места
 * в группе.
 *
 * ЗАЧЕМ ПРОБА, ЕСЛИ ЕСТЬ СТОРОЖ. `tools/check-razbor-schyota.js` читает
 * исходник: одно ли объявление, любое ли тире, один ли признак
 * супер-тай-брейка. Он не может сказать, что ИЗ ЭТОГО НАРИСУЕТСЯ. А
 * беда была именно такой: счёт `7/6(5–7)` с длинным тире таблица группы
 * разбирала с тай-брейком, а сетка — без, и оба кода выглядели верными.
 *
 * Стенд `maket/setka-zamer.html?r=20` грузит НАСТОЯЩУЮ админку и
 * подменяет только клиента базы. Расклад 20 подаёт все виды счёта разом:
 * дефис, длинное тире, среднее тире, супер-тай-брейк третьим сетом и
 * счёт без тай-брейка. Базы здесь нет: прогон ничего не пишет.
 *
 * ПЯТЬ ВИДОВ — но админка живёт на трёх (десктоп и планшет, слово Кости
 * 29.09), поэтому телефонные раскладки проба пропускает сама.
 */

const ТЕЛЕФОННЫЕ = ['mobile', 'phone-landscape'];

async function стенд(page) {
    const беды = [];
    page.on('pageerror', e => беды.push('pageerror: ' + e.message));
    page.on('console', m => {
        const т = m.text();
        if (m.type() === 'error' && !/Failed to load resource|ERR_/.test(т)) {
            беды.push('console: ' + т);
        }
    });
    await page.goto('/maket/setka-zamer.html?r=20');
    await page.waitForSelector('.ad-brk-match', { timeout: 15000 });
    await page.waitForTimeout(600);
    return беды;
}

test('тай-брейк рисуется надстрочным при любом тире', async ({ page }, инфо) => {
    test.skip(ТЕЛЕФОННЫЕ.indexOf(инфо.project.name) !== -1, 'админка живёт на трёх видах');
    const беды = await стенд(page);
    expect(беды, 'страница ругается в консоль').toEqual([]);

    const клетки = await page.evaluate(() =>
        Array.from(document.querySelectorAll('.ad-brk-match')).map(м => ({
            sup: Array.from(м.querySelectorAll('sup')).map(s => s.textContent)
        })));

    /* Первая клетка получила счёт с ДЕФИСОМ, вторая — с ДЛИННЫМ ТИРЕ.
       До круга 20 вторая не дала бы надстрочного вовсе: образец сетки
       принимал только дефис. */
    const сТайбрейком = клетки.filter(к => к.sup.length > 0);
    expect(сТайбрейком.length, 'клеток с надстрочным тай-брейком').toBe(2);
    сТайбрейком.forEach(к => {
        expect(к.sup, 'надстрочные тай-брейка').toEqual(['5', '7']);
    });
});

test('признак супер-тай-брейка один и отвечает верно', async ({ page }, инфо) => {
    test.skip(ТЕЛЕФОННЫЕ.indexOf(инфо.project.name) !== -1, 'админка живёт на трёх видах');
    await стенд(page);

    const о = await page.evaluate(() => {
        const П = window.KSLT_RULES;
        return {
            есть: typeof П.этоСуперТБ,
            одиннадцатьДевять: П.этоСуперТБ(['6/4', '3/6', '11/9']),
            десятьВосемь: П.этоСуперТБ(['6/4', '3/6', '10/8']),
            обычныйСетСТБ: П.этоСуперТБ(['6/4', '3/6', '7/6(5-7)']),
            обычныйТретий: П.этоСуперТБ(['6/4', '3/6', '6/4']),
            нетТретьего: П.этоСуперТБ(['6/4', '3/6']),
            неТретийИндекс: П.этоСуперТБ(['11/9', '3/6', '6/4'], 0)
        };
    });

    expect(о.есть, 'дом правил отдаёт признак').toBe('function');
    /* Супер-ТБ: третий сет без скобок, где кто-то взял десять. */
    expect(о.одиннадцатьДевять).toBe(true);
    expect(о.десятьВосемь).toBe(true);
    /* А это НЕ супер-ТБ, и путать их нельзя: */
    expect(о.обычныйСетСТБ, 'сет со скобками — обычный, а не супер-ТБ').toBe(false);
    expect(о.обычныйТретий, 'третий 6/4 — обычный сет').toBe(false);
    expect(о.нетТретьего, 'третьего сета нет вовсе').toBe(false);
    expect(о.неТретийИндекс, 'десятка в ПЕРВОМ сете супер-ТБ не делает').toBe(false);
});

test('сетка и групповая таблица разбирают один счёт одинаково', async ({ page }, инфо) => {
    test.skip(ТЕЛЕФОННЫЕ.indexOf(инфо.project.name) !== -1, 'админка живёт на трёх видах');
    await стенд(page);

    /* ОДИН СЧЁТ, ДВА РАЗБОРЩИКА. Сетку рисует parseSets в bracket.js,
       таблицу группы — group-standings.js. Беда круга была ровно в том,
       что на одном счёте они расходились. */
    const о = await page.evaluate(() => {
        const счёт = '7/6(5–7) 6/4';   // длинное тире
        const м = { player1_id: 'a', player2_id: 'b', score: счёт, status: 'completed', winner_id: 'a' };
        const г = window.KSLT_GROUPS.расчёт(['a', 'b'], [м]);
        const свой = г.filter(s => s.playerId === 'a')[0];
        return { тбВзято: свой && свой.tbWon, геймы: свой && свой.gamesWon, сеты: свой && свой.setsWon };
    });
    /* Тай-брейк разобран: иначе его очки были бы нулём при 7/6 в счёте. */
    expect(о.тбВзято, 'очки тай-брейка у выигравшего сет 7/6(5–7)').toBeGreaterThan(0);
    expect(о.сеты, 'сетов выиграно').toBe(2);
});
