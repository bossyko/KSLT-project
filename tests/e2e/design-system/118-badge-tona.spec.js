// @ts-check
const { test, expect } = require('@playwright/test');

/**
 * ТОНА БЕЙДЖА АДМИНКИ: ЧТО НАРИСОВАЛОСЬ, А НЕ ЧТО НАПИСАНО. 21.10.
 *
 * ЧТО СТОРОЖ НЕ МОЖЕТ. `tools/check-badge-tona.js` читает исходник: нет ли
 * имени по цвету, нет ли двух имён на один тон, не объявлен ли тон ВЫШЕ
 * базового `.ad-badge`, не бьёт ли зов в пустоту. Он не может сказать,
 * ЧТО ВИДНО. А все четыре беды этого куска были именно видимыми:
 *
 *   1. `-out` объявлен ДВАЖДЫ — счётчик снятых перебивался подписью «в
 *      зачёт не берётся» и рисовался белым 0.5 ПУНКТИРОМ рядом с красным
 *      заголовком;
 *   2. `.ad-badge-success` ЗВАЛСЯ, НО НЕ СУЩЕСТВОВАЛ — статус «сыгран» в
 *      расписании выходил базовым серым;
 *   3. тона стояли ВЫШЕ базового класса и теряли фон при равной силе
 *      селектора — краска проходила, фон оставался серым;
 *   4. четыре имени на два тона.
 *
 * Беды 2 и 3 дают ОДИН И ТОТ ЖЕ вид: бейдж базового серого. Поэтому проба
 * сравнивает фон каждого тона с фоном базового класса — это единственная
 * проверка, которая ловит обе и в браузере.
 *
 * МЕРИТСЯ СТЕНДОМ, А НЕ АДМИНКОЙ. Админка закрыта входом: страж уводит
 * кадр на `auth.html`, и замер говорит о странице входа.
 *
 * СЛОИ СКЛАДЫВАЮТСЯ. Все тона — `rgba(...)` 15 % поверх `--bg-card`,
 * который сам лежит поверх `--bg-base`. Контраст по записанному в токене
 * цвету — ложь: он не знает, что под ним.
 */

const ПОРОГ = 4.5;
const ТОНА = ['ad-badge-accent', 'ad-badge-danger', 'ad-badge-warning',
              'ad-badge-success', 'ad-badge-info'];

async function стенд(page) {
    const беды = [];
    page.on('pageerror', e => беды.push('pageerror: ' + e.message));
    page.on('console', m => {
        const т = m.text();
        if (m.type() === 'error' && !/Failed to load resource|ERR_/.test(т)) {
            беды.push('console: ' + т);
        }
    });
    await page.goto('/maket/badge-tona-zamer.html');
    await page.waitForFunction(() => !!window.ЗАМЕР, null, { timeout: 15000 });
    return { з: await page.evaluate(() => window.ЗАМЕР), беды };
}

test('все пять тонов существуют и ни один не остался базовым серым', async ({ page }) => {
    const { з, беды } = await стенд(page);
    expect(беды, 'стенд ругается в консоль').toEqual([]);
    expect(з.домЕсть, 'базовый .ad-badge на стенде есть').toBe(true);

    /* ГЛАВНОЕ ЧИСЛО КУСКА. Зов в пустоту и тон выше базового дают один и
       тот же вид — фон базового класса. Равенство здесь = беда. */
    for (const имя of ТОНА) {
        const т = з.тона[имя];
        expect(т, 'тон ' + имя + ' нарисован').toBeTruthy();
        expect(т.фон, 'фон ' + имя + ' не равен базовому серому')
            .not.toBe(з.базовыйФон);
        expect(т.своёАльфа, 'у ' + имя + ' свой фон, а не прозрачность')
            .toBeGreaterThan(0);
    }
});

test('тона различаются между собой, а не только от базового', async ({ page }) => {
    const { з } = await стенд(page);
    /* ОДИН ТОН — ОДНО ИМЯ работает и наоборот: два имени не должны
       нарисоваться одной краской. Именно так поймались `-danger`/`-err`
       и `-warning`/`-warn` — краски совпали до байта. */
    const фоны = ТОНА.map(и => з.тона[и].фон);
    expect(new Set(фоны).size, 'разных фонов среди пяти тонов').toBe(ТОНА.length);
    const краски = ТОНА.map(и => з.тона[и].текст);
    expect(new Set(краски).size, 'разных красок текста среди пяти тонов').toBe(ТОНА.length);
});

test('каждый тон читается по WCAG AA на фактическом фоне', async ({ page }) => {
    const { з } = await стенд(page);
    const ниже = ТОНА.filter(и => з.тона[и].контраст < ПОРОГ)
        .map(и => и + ' = ' + з.тона[и].контраст);
    expect(ниже, 'тона ниже порога ' + ПОРОГ).toEqual([]);
});

test('лестница бейджа одна на все тона: кегль, вес, радиус, высота', async ({ page }) => {
    const { з } = await стенд(page);
    /* ЗАМОРАЖИВАЕТСЯ ОТНОШЕНИЕ: тон меняет ТОЛЬКО краску. Любое
       расхождение кегля, веса, радиуса или высоты между тонами значит,
       что тон полез в размеры — там ему делать нечего. */
    const б = з.тона['ad-badge'];
    for (const имя of ТОНА) {
        const т = з.тона[имя];
        expect(т.кегль,  'кегль ' + имя).toBe(б.кегль);
        expect(т.вес,    'вес ' + имя).toBe(б.вес);
        expect(т.радиус, 'радиус ' + имя).toBe(б.радиус);
        expect(т.высота, 'высота ' + имя).toBe(б.высота);
    }
    /* Радиус бейджа — пилюля, а не скругление: это признак того, что
       `--radius-full` дошёл, а не перебился числом. */
    expect(parseFloat(б.радиус), 'радиус базового бейджа — пилюля')
        .toBeGreaterThanOrEqual(б.высота / 2);
});

test('размер — тоже модификатор, и он работает', async ({ page }) => {
    const { з } = await стенд(page);
    /* ПЯТАЯ БЕДА ТОГО ЖЕ КУСКА, НАЙДЕНА ЗАМЕРОМ 21.10. `.ad-badge-sm`
       стоял ВЫШЕ базового `.ad-badge` при равном удельном весе — базовый
       возвращал кегль обратно, и мелкий бейдж рисовался обычным. Номер
       посева `[1]` в сетке выходил 12 вместо 11 при ЧЕТЫРЁХ ЖИВЫХ ЗОВАХ.
       Правило положения смотрело тогда только тоны, а `-sm` было из него
       исключено как «не тон» — ровно там беда и сидела. */
    expect(з.ловушка.мелкийВнеЗаголовка, 'мелкий бейдж мельче базового')
        .toBeLessThan(з.ловушка.вЗаголовке);

    /* И ВТОРАЯ ПОЛОВИНА ТОГО ЖЕ: вложенный `.ad-reg-section-title
       .ad-badge` повторял базовый кегль — на сегодняшних бейджах не менял
       НИЧЕГО, но тяжелее `-sm` удельным весом и вернул бы его обратно.
       Повтор того же значения не виден СЕГОДНЯ, и ровно поэтому опасен. */
    expect(з.ловушка.мелкийВЗаголовке,
        'мелкий бейдж в заголовке раздела не перебивается вложенным селектором')
        .toBe(з.ловушка.мелкийВнеЗаголовка);
    expect(з.ловушка.перебивает, 'вложенный селектор не перебивает размер').toBe(false);
});

test('лестница базового бейджа — решение Кости, а не эталон компонента', async ({ page }) => {
    const { з } = await стенд(page);
    /* ЗАМОРАЖИВАЕТСЯ ЗАМЕРЕННОЕ, А НЕ ЗАДУМАННОЕ. Эталонный компонент
       `Badge` 27:53 стоит на 11px / Medium / высоте 24. Базовый бейдж
       админки замерен 12px / вес 400 / высота 22 на 29 зовах, и КОСТЯ
       21.10 РЕШИЛ ОСТАВИТЬ КАК ЕСТЬ — расхождение НАМЕРЕННОЕ.
       Числа стоят здесь, чтобы следующая правка кегля была решением, а
       не случайностью. */
    const б = з.тона['ad-badge'];
    expect(б.кегль,  'кегль базового бейджа — решение 21.10').toBe(12);
    expect(б.вес,    'вес наследуется, а не задан').toBe('400');
    expect(parseFloat(б.радиус), 'радиус — пилюля').toBeGreaterThanOrEqual(б.высота / 2);
});

test('краска от ширины окна не зависит', async ({ page }) => {
    const { з } = await стенд(page);
    /* Числа одни на всех пяти видах: если проба упала только на телефоне,
       значит тон поехал на точке останова, чего быть не должно. */
    expect(з.тона['ad-badge-success'].контраст,
        'контраст успеха одинаков на любом виде').toBeGreaterThanOrEqual(ПОРОГ);
    expect(з.базовыйФон, 'фон базового бейджа один на всех видах').toBeTruthy();
});
