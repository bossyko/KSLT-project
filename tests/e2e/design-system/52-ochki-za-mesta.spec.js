// @ts-check
const { test, expect } = require('../../fixtures');

/**
 * ОЧКИ ЗА МЕСТА — ПРОГОНОМ, А НЕ ЧТЕНИЕМ ПРАВИЛ.
 *
 * Заморозка («очки и лиги», 17 откатов) держит ТЕКСТ: что граница названа
 * отношением, что олимпийка платит таблицей, что нижняя лига берёт свою.
 * Правила читают файл как текст и ни одного числа не считают. Посчитать
 * может только прогон — настоящими функциями настоящего файла, который
 * страница и отдаёт браузеру.
 *
 * ЧЕГО НЕ ДЕРЖИТ НИЧТО. Замер 02.10: `подписьМеста`, `поСноске` и
 * `РАЗМЕР_КРУГА` не встречаются в `tools/` ни разу. Полоса мест (решение
 * Кости 01.10) и сноска Положения не защищены ни правилом, ни тестом —
 * этот файл и есть их первая защита.
 *
 * ЧИСЛА ВЗЯТЫ ИЗ ПРИНЯТОГО, А НЕ ИЗ КОДА. 25 за победу, 10 за участие,
 * четыре места по таблице — решения Кости 30.09; полоса мест и «третье
 * место только из матча за третье» — 01.10. Таблица очков в проверке своя,
 * с заполненными местами 5-8: заплати код таблицей там, где должен платить
 * победами, — выйдет другое число, и проверка упадёт.
 *
 * ПРОПУСК ВИДА НАЗЫВАЕТСЯ ВСЛУХ: расчёт очков от ширины окна не зависит
 * вовсе, это чистые функции. Гоняем на одном виде; экранная часть —
 * таблица итогов под пьедесталом — мерится отдельным тестом на всех пяти.
 */

/** Любой существующий турнир: нужна лишь страница, которая отдаёт расчётчик. */
const СТРАНИЦА = '/pages/tournament.html?id=test-mesto';

/** Своя таблица: места 1-8 заполнены, чтобы подмена таблицей была видна. */
const ТАБЛИЦА = { 1: 360, 2: 215, 3: 150, 4: 130, 5: 111, 6: 111, 7: 111, 8: 111 };

test.describe('Очки за места', () => {

    test.beforeEach(async ({ page }, testInfo) => {
        test.skip(testInfo.project.name !== 'desktop',
            'расчёт очков не зависит от вида: чистые функции. Экран мерится в тесте итогов');
        await page.goto(СТРАНИЦА);
        await page.waitForFunction(() => typeof window.KSLT_POINTS !== 'undefined',
            null, { timeout: 20000 });
    });

    test('порог: расчётчик на странице один, и числа в нём те, что приняты',
        async ({ page }) => {
            const что = await page.evaluate(() => {
                const P = window.KSLT_POINTS;
                const имена = ['поСноске', 'заМесто', 'очки', 'поТурниру', 'победы',
                    'подписьРаунда', 'местоПоРаунду', 'подписьМеста', 'порядокРаунда'];
                return {
                    нехватает: имена.filter(и => typeof P[и] !== 'function'),
                    заПобеду: P.ЗА_ПОБЕДУ,
                    заУчастие: P.ЗА_УЧАСТИЕ,
                    местПоТаблице: P.МЕСТ_ПО_ТАБЛИЦЕ
                };
            });

            expect(что.нехватает, 'в расчётчике не хватает функций').toEqual([]);
            expect(что.заПобеду, '25 за победу — решение Кости 30.09').toBe(25);
            expect(что.заУчастие, '10 за участие — решение Кости 30.09').toBe(10);
            expect(что.местПоТаблице, 'таблица платит первые четыре места').toBe(4);
        });

    test('первые четыре места платятся только таблицей, остальным — только победы',
        async ({ page }) => {
            const р = await page.evaluate((т) => {
                const P = window.KSLT_POINTS;
                const гр = { заПобеды: true };
                const сч = (место, побед) => P.очки({ place: место, побед: побед }, т, гр);
                return {
                    первое: сч(1, 5), второе: сч(2, 4), третье: сч(3, 3), четвёртое: сч(4, 3),
                    пятое: сч(5, 3), шестое: сч(6, 1), седьмое: сч(7, 0),
                    таблицаПятого: т[5]
                };
            }, ТАБЛИЦА);

            /* МЕСТО УЖЕ ГОВОРИТ, СКОЛЬКО ЧЕЛОВЕК ВЫИГРАЛ: победы к таблице
               не прибавляются. Раньше прибавлялись, и победитель второй
               категории получал 360 плюс победы. */
            expect(р.первое, 'первое место платится не таблицей').toBe(360);
            expect(р.второе, 'второе место платится не таблицей').toBe(215);
            expect(р.третье, 'третье место платится не таблицей').toBe(150);
            expect(р.четвёртое, 'к четвёртому месту прибавились победы').toBe(130);

            /* ОСТАЛЬНЫМ ТАБЛИЦА НЕ ПЛАТИТ ВОВСЕ. Место 5 в таблице
               заполнено (111) — заплати код таблицей, число было бы 111. */
            expect(р.пятое, 'пятое место получило не победы').toBe(75);
            expect(р.пятое, 'пятое место заплачено таблицей').not.toBe(р.таблицаПятого);
            expect(р.шестое, 'одна победа — это 25').toBe(25);
            expect(р.седьмое, 'без побед платится участие').toBe(10);
        });

    test('олимпийка платит только таблицей: победы там отдельно не платятся',
        async ({ page }) => {
            const р = await page.evaluate((т) => {
                const P = window.KSLT_POINTS;
                const сч = (место, побед) => P.очки({ place: место, побед: побед }, т, {});
                return { пятое: сч(5, 3), восьмое: сч(8, 1), девяностое: сч(90, 0) };
            }, ТАБЛИЦА);

            expect(р.пятое, 'в олимпийке пятое место заплачено победами').toBe(111);
            expect(р.восьмое, 'в олимпийке восьмое место заплачено победами').toBe(111);
            expect(р.девяностое, 'за место вне таблицы начислено что-то').toBe(0);
        });

    test('неразыгранное место платится по последнему в полосе — сноска Положения',
        async ({ page }) => {
            const р = await page.evaluate(() => {
                const P = window.KSLT_POINTS;
                const двое = P.поСноске([
                    { playerId: 'a', place: 3, разыграно: false },
                    { playerId: 'b', place: 3, разыграно: false }
                ]).map(у => у.местоОплаты);
                const трое = P.поСноске([
                    { playerId: 'a', place: 5, разыграно: false },
                    { playerId: 'b', place: 5, разыграно: false },
                    { playerId: 'c', place: 5, разыграно: false }
                ]).map(у => у.местоОплаты);
                const разыграно = P.поСноске([
                    { playerId: 'a', place: 3, разыграно: true },
                    { playerId: 'b', place: 4, разыграно: true }
                ]).map(у => у.местоОплаты);
                return { двое, трое, разыграно };
            });

            /* БЕЗ МАТЧА ЗА ТРЕТЬЕ ОБА ПОЛУФИНАЛИСТА ПОЛУЧАЮТ КАК ЗА
               ЧЕТВЁРТОЕ: места между ними не разыграны, и платить одному
               больше нечем. */
            expect(р.двое, 'двое на неразыгранном третьем платятся не по четвёртому')
                .toEqual([4, 4]);
            expect(р.трое, 'трое на неразыгранном пятом платятся не по седьмому')
                .toEqual([7, 7, 7]);
            expect(р.разыграно, 'разыгранное место подменено полосой').toEqual([3, 4]);
        });

    test('проход без игры победой не считается, недоигранное тоже',
        async ({ page }) => {
            const р = await page.evaluate(() => {
                const P = window.KSLT_POINTS;
                const матчи = [
                    { status: 'completed', winner_id: 'a', score: '6/4 6/2' },
                    { status: 'completed', winner_id: 'a', score: 'BYE' },
                    { status: 'scheduled',  winner_id: 'a', score: null },
                    { status: 'completed', winner_id: 'b', score: '6/0 6/0' }
                ];
                return { a: P.победы('a', матчи), b: P.победы('b', матчи),
                         никто: P.победы(null, матчи), пусто: P.победы('a', []) };
            });

            expect(р.a, 'проход без игры или незавершённый матч посчитан победой').toBe(1);
            expect(р.b, 'чужая победа не посчитана').toBe(1);
            expect(р.никто, 'победы посчитаны тому, кого нет').toBe(0);
            expect(р.пусто, 'победы нашлись в пустом списке матчей').toBe(0);
        });

    test('этап даёт полосу, а где места нет — там и числа нет',
        async ({ page }) => {
            const р = await page.evaluate(() => {
                const P = window.KSLT_POINTS;
                const полоса = {};
                ['W', 'F', '3RD', '4TH', 'SF', 'QF', 'R16', 'R32', 'G2']
                    .forEach(к => { полоса[к] = P.подписьМеста(к); });
                return {
                    полоса,
                    местоГруппы: P.местоПоРаунду('G2'),
                    местоФиналиста: P.местоПоРаунду('F'),
                    подписи: {
                        ru: P.подписьРаунда('QF', 'ru'),
                        en: P.подписьРаунда('QF', 'en'),
                        kg: P.подписьРаунда('QF', 'kg'),
                        неизвестный: P.подписьРаунда('XYZ', 'ru')
                    },
                    порядок: ['W', 'F', 'SF', 'QF', 'R16'].map(к => P.порядокРаунда(к)),
                    порядокЧужого: P.порядокРаунда('XYZ')
                };
            });

            /* ЧЕТВЕРО ПРОИГРАВШИХ ЧЕТВЕРТЬФИНАЛ МЕЖДУ СОБОЙ НЕ ИГРАЛИ —
               все стоят на 5-8. Одно число «5» у всех четверых утверждает
               то, чего не было. */
            expect(р.полоса.W, 'победитель назван полосой').toBe('1');
            expect(р.полоса.F, 'финалист назван полосой').toBe('2');
            expect(р.полоса['3RD'], 'разыгранное третье названо полосой').toBe('3');
            expect(р.полоса['4TH'], 'разыгранное четвёртое названо полосой').toBe('4');
            expect(р.полоса.SF, 'полуфинал без матча за третье — это 3-4').toBe('3-4');
            expect(р.полоса.QF, 'четвертьфинал — это 5-8').toBe('5-8');
            expect(р.полоса.R16, 'восьмая финала — это 9-16').toBe('9-16');
            expect(р.полоса.R32, 'шестнадцатая финала — это 17-32').toBe('17-32');

            /* ТРЕТЬЕ МЕСТО ГРУППЫ A И ТРЕТЬЕ ГРУППЫ B — РАЗНЫЕ СТРОКИ
               ТАБЛИЦЫ, И ЧТО ВЫШЕ, РЕШАЕТ СИЛА, А НЕ БУКВА. Числа нет. */
            expect(р.полоса.G2, 'месту в группе выдан номер').toBeNull();
            expect(р.местоГруппы, 'место в группе выдано числом').toBeNull();
            expect(р.местоФиналиста, 'финалист не второй').toBe(2);

            const тр = [р.подписи.ru, р.подписи.en, р.подписи.kg];
            expect(тр.filter(Boolean).length, 'подпись этапа пуста на каком-то языке').toBe(3);
            expect(new Set(тр).size, 'три языка дали одну и ту же подпись').toBe(3);
            expect(р.подписи.неизвестный, 'неизвестный код не вернулся как есть').toBe('XYZ');

            const по = р.порядок;
            expect(по[0] < по[1] && по[1] < по[2] && по[2] < по[3] && по[3] < по[4],
                'порядок раундов не возрастает от победителя к первому кругу').toBe(true);
            expect(р.порядокЧужого > по[4], 'неизвестный раунд не ушёл в конец').toBe(true);
        });
});
