/**
 * КУСОК 143 — КАРТОЧКА ИГРОКА НЕ ЗАВОДИТСЯ СОТРУДНИКУ.
 *
 * ЧЕГО ЭТА ПРОБА НЕ ДЕЛАЕТ, И ЭТО СКАЗАНО ВСЛУХ: админка за входом, и
 * нажать «Сохранить» у профиля сотрудника проба не может. Отказ в
 * заведении карточки, причину вместо кнопки одобрения заявки и чтение
 * роли в запросе держат СТОРОЖ и ПРУВЕР — одиннадцать откатов, каждый
 * уронил своё правило. Проба держит то, что видно на экране: предикат на
 * настоящих файлах админки и фразы, которыми отказ говорится.
 *
 * СТЕНД НЕУДОБНЫЙ НАМЕРЕНО: роли подаются пустая, чужая, с заглавной и
 * по-русски — на них предикат, написанный поиском подстроки, врёт молча.
 */
const { test, expect } = require('@playwright/test');

const СТЕНД = '/maket/stend-admin-sotrudnik.html';

test.describe('карточка не заводится сотруднику', () => {

    test('предикат админки отвечает по роли, а не по похожести', async ({ page }) => {
        await page.goto(СТЕНД);
        await page.waitForSelector('#stRoli tbody tr', { timeout: 15000 });

        const ответы = await page.evaluate(() => {
            const из = {};
            document.querySelectorAll('#stRoli tbody tr').forEach(tr => {
                из[tr.children[0].textContent] = tr.children[1].textContent;
            });
            return из;
        });

        expect(ответы['admin'], 'админ — сотрудник клуба').toBe('true');
        expect(ответы['manager'], 'менеджер — сотрудник клуба').toBe('true');
        expect(ответы['user'], 'игрок сотрудником не становится').toBe('false');
        expect(ответы['(пусто)'], 'пустая роль — не сотрудник').toBe('false');
        expect(ответы['undefined'], 'роли нет — и сотрудника нет').toBe('false');
        expect(ответы['null'], 'роль null — не сотрудник').toBe('false');
        /* ПОХОЖЕЕ — НЕ ТО ЖЕ. Предикат сравнивает, а не ищет подстроку:
           «Admin» с заглавной и «админ» по-русски ролями не являются. */
        expect(ответы['Admin'], 'роль чувствительна к регистру — так в базе').toBe('false');
        expect(ответы['админ'], 'русского написания роли в базе нет').toBe('false');
    });

    test('отказ говорится словами из словаря, а не молчит', async ({ page }) => {
        await page.goto(СТЕНД);
        await page.waitForSelector('#stFrazy', { timeout: 15000 });

        const ф = await page.evaluate(() => {
            const p = document.getElementById('stFrazy');
            return { карточка: p.dataset.card, заявка: p.dataset.link };
        });

        expect(ф.карточка.length, 'фразы отказа в заведении карточки нет').toBeGreaterThan(20);
        expect(ф.заявка.length, 'фразы о заявке от сотрудника нет').toBeGreaterThan(5);
        /* ПРИЧИНА НАЗЫВАЕТСЯ, А НЕ «НЕЛЬЗЯ»: человек должен понять, почему
           отказ, и что делать — отдельный аккаунт для игры. */
        expect(ф.карточка, 'отказ не объясняет причину').toMatch(/не играет|не играют|ведёт клуб/);
        expect(ф.карточка, 'отказ не говорит, что делать').toMatch(/отдельный аккаунт/);
    });
});
