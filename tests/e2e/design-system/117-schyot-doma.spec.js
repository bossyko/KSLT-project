const { test, expect } = require('@playwright/test');

/**
 * СЧЁТ: ОДИН ДОМ НА СТРАНИЦУ ИГРОКА, КАБИНЕТ И АДМИНКУ. 19.10.
 *
 * ЧТО СТОРОЖ НЕ МОЖЕТ. `tools/check-schyot-doma.js` читает исходник. Он не
 * может сказать, ЧТО ПОСЧИТАЕТСЯ: что супер-тай-брейк `10/8` войдёт сетом,
 * что BYE не даст нулевой победы, что геймы сложатся правильно. А очки
 * считаются именно из этого.
 *
 * МЕРИТСЯ СТЕНДОМ, А НЕ СТРАНИЦЕЙ. Кабинет и админка закрыты входом: страж
 * `auth-guard.js` уводит кадр на `auth.html`, и замер начинает говорить о
 * СТРАНИЦЕ ВХОДА. Поймано 19.10 на себе же, через час после того, как это
 * правило было выведено на обходе движения.
 *
 * Страница игрока открыта всем — её проверяем напрямую, и отдельно
 * сверяем, что ответы стенда и страницы совпадают: дом один.
 */

const СЛУЧАИ = [
    { счёт: '6/4 6/3',           показ: '6:4 6:3',           сеты: [2, 0], геймы: [12, 7] },
    { счёт: '7/6(5-7) 4/6 10/8', показ: '7:6(5-7) 4:6 10:8', сеты: [2, 1], геймы: [21, 20] },
    { счёт: '6/0',               показ: '6:0',               сеты: [1, 0], геймы: [6, 0] },
    { счёт: '6/4 4/6 7/6',       показ: '6:4 4:6 7:6',       сеты: [2, 1], геймы: [17, 16] }
];

async function стенд(page) {
    const беды = [];
    page.on('pageerror', e => беды.push(e.message));
    await page.goto('/maket/schyot-zamer.html');
    await page.waitForFunction(() => !!window.ЗАМЕР, null, { timeout: 15000 });
    return { з: await page.evaluate(() => window.ЗАМЕР), беды };
}

test('дом считает счёт, и числа те, что заморожены', async ({ page }) => {
    const { з, беды } = await стенд(page);
    expect(беды, 'стенд ругается в консоль').toEqual([]);
    expect(з.домЕсть, 'дом правил подключён на стенде').toBe(true);

    for (const с of СЛУЧАИ) {
        const д = з.счёт[с.счёт];
        expect(д, 'случай ' + с.счёт).toBeTruthy();
        expect(д.показ, 'показ ' + с.счёт).toBe(с.показ);
        expect([д.разбор.p1Sets, д.разбор.p2Sets], 'сеты ' + с.счёт).toEqual(с.сеты);
        expect([д.разбор.p1Games, д.разбор.p2Games], 'геймы ' + с.счёт).toEqual(с.геймы);
    }
});

test('супер-тай-брейк входит сетом, а не теряется', async ({ page }) => {
    const { з } = await стенд(page);
    /* 7/6 4/6 10/8 — решающий сет сыгран супер-тай-брейком. Если бы 10/8
       не считался, вышло бы 1:1 и матч без победителя. */
    const д = з.счёт['7/6(5-7) 4/6 10/8'];
    expect(д.разбор.p1Sets, 'сетов у победителя').toBe(2);
    expect(д.разбор.p2Sets, 'сетов у проигравшего').toBe(1);
});

test('BYE — пропуск круга, а не нулевая победа', async ({ page }) => {
    const { з } = await стенд(page);
    /* ГЛАВНОЕ ЧИСЛО КУСКА, и вида оно не меняет: без проверки BYE дал бы
       0:0 по сетам и геймам, то есть вошёл бы в статистику сыгранным
       матчем, и средние по игроку поехали бы. */
    expect(з.счёт['BYE'].разбор, 'разбор BYE').toBeNull();
    expect(з.счёт['BYE'].показ, 'показ BYE остаётся как есть').toBe('BYE');
});

test('пустой счёт даёт тире, а не пустоту', async ({ page }) => {
    const { з } = await стенд(page);
    expect(з.счёт['пусто'].показ, 'показ пустого счёта').toBe('—');
    expect(з.счёт['пусто'].разбор, 'разбор пустого счёта').toBeNull();
});

test('переворот счёта меняет сторону, не меняя тай-брейка', async ({ page }) => {
    const { з } = await стенд(page);
    expect(з.счёт['6/4 6/3'].переворот, 'простой переворот').toBe('4/6 3/6');
    /* Скобка тай-брейка остаётся как есть: она описывает САМ тай-брейк, а
       не сторону, и переворачивать её нельзя. */
    expect(з.счёт['7/6(5-7) 4/6 10/8'].переворот, 'переворот с тай-брейком')
        .toBe('6/7(5-7) 6/4 8/10');
});

test('короткий формат ограничен шестью', async ({ page }) => {
    const { з } = await стенд(page);
    expect(з.годность['6:4/стандарт'], '6:4 стандарт').toBe(true);
    expect(з.годность['7:5/стандарт'], '7:5 стандарт').toBe(true);
    expect(з.годность['7:6/стандарт'], '7:6 стандарт').toBe(true);
    expect(з.годность['6:6/стандарт'], '6:6 стандарт — не победа').toBe(false);
    expect(з.годность['8:1/стандарт'], '8:1 — такого сета нет').toBe(false);
    /* В коротком формате при 6:5 играется тай-брейк, и семёрок не бывает. */
    expect(з.годность['6:5/short'], '6:5 короткий').toBe(true);
    expect(з.годность['7:5/short'], '7:5 короткий — такого нет').toBe(false);
    expect(з.годность['a:b/стандарт'], 'мусор вместо чисел').toBe(false);
});

test('страница игрока и стенд дают один и тот же счёт', async ({ page }) => {
    /* Дом один — значит ответы обязаны совпасть до знака. Страница игрока
       открыта всем, поэтому её можно спросить напрямую. */
    const { з } = await стенд(page);
    await page.goto('/pages/player.html');
    await page.waitForFunction(() => !!(window.KSLT_RULES && window.KSLT_RULES.показатьСчёт),
                               null, { timeout: 15000 });
    const свои = await page.evaluate(() => {
        const R = window.KSLT_RULES;
        return {
            показ: R.показатьСчёт('7/6(5-7) 4/6 10/8'),
            переворот: R.перевернутьСчёт('7/6(5-7) 4/6 10/8'),
            разбор: R.разборСчёта('7/6(5-7) 4/6 10/8'),
            bye: R.разборСчёта('BYE'),
            короткий75: R.сетГоден(7, 5, 'short')
        };
    });
    const наСтенде = з.счёт['7/6(5-7) 4/6 10/8'];
    expect(свои.показ, 'показ совпадает со стендом').toBe(наСтенде.показ);
    expect(свои.переворот, 'переворот совпадает со стендом').toBe(наСтенде.переворот);
    expect(свои.разбор, 'разбор совпадает со стендом').toEqual(наСтенде.разбор);
    expect(свои.bye, 'BYE и на странице ничего').toBeNull();
    expect(свои.короткий75, '7:5 коротким и на странице не годен').toBe(false);
});
