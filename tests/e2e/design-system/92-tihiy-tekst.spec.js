/**
 * ТИХИЙ ТЕКСТ ПРОХОДИТ AA. 13.10, кусок 73-й.
 * ГРАДИЕНТ ТЕПЕРЬ ТОЖЕ МЕРИТСЯ — 26.10, кусок 186.
 *
 * Решение Кости 06.10: «тихих уровней текста ТРИ: --text-dim уходит из
 * текста». Замер 13.10 нашёл его в 220 местах, из них 206 — цвет текста,
 * контраст 3.14-3.21 при норме AA 4.5. Переведено 215 мест; осталось
 * четыре неактивных и одна иконка.
 *
 * ЧТО ИЗМЕНИЛ КУСОК 186. Проба держала СВОЮ копию формулы контраста, и эта
 * копия считала узел на градиенте НЕ МЕРЕНЫМ: «картинка или градиент на
 * пути — узел не мерится». Так появилась запись 72г: «48 текстовых узлов
 * на градиенте не мерены из 1478, проходят они или нет — НЕ ЗНАЮ».
 * Теперь счёт ОДИН на весь продукт — `tools/kontrast.mjs`, — и градиент он
 * складывает: берёт ВСЕ остановки и худшую из них. Узел проходит, только
 * если проходит на самом светлом месте градиента.
 * ОДНО ОПРЕДЕЛЕНИЕ НА ОДНО ПОНЯТИЕ: своей формулы у пробы больше нет.
 *
 * ФОТОГРАФИЯ ПО-ПРЕЖНЕМУ НЕ МЕРИТСЯ, и это сказано вслух: её пиксели
 * числом не выводятся. Такие узлы считаются отдельно и ДОЛЖНЫ БЫТЬ НУЛЁМ —
 * текста поверх фотографии в продукте нет. Появится — проба упадёт и
 * назовёт его. Значок, нарисованный `data:`-картинкой (стрелка выпадашки),
 * подложкой текста не считается: он лежит поверх краски фона у края поля.
 *
 * ПОЧЕМУ ОДИН ЯЗЫК, А НЕ ТРИ. Контраст живёт в краске и кегле, а они
 * приходят из css, в котором НЕТ НИ ОДНОГО правила, завязанного на язык:
 * ни `:lang()`, ни `[lang=`, ни `html.en` — проверено чтением всех файлов
 * css 26.10, все 28 совпадений на `lang` оказались классом `.lang-*`
 * переключателя языков. Отдельная проверка ниже это и сторожит: если
 * краска начнёт зависеть от языка, она упадёт.
 *
 * ЧТО ПРОВЕРЯЕТ ПРОГОН, А НЕ ЗАМОРОЗКА:
 *
 *   • ЧТО ПОЛУЧИЛОСЬ ИЗ var(--…) В БРАУЗЕРЕ. Заморозка видит имя токена;
 *     цвет, альфу и фон под ним даёт только страница;
 *   • КОНТРАСТ СЧИТАЕТСЯ ПО ЖИВЫМ ПИКСЕЛЯМ. Фон у текста может прийти от
 *     любого предка, а не от того, что написано рядом;
 *   • ЧТО ЭТО ВИДИМЫЙ ТЕКСТ. Скрытое и пустое к порогу не относится;
 *   • ЧТО НЕАКТИВНОЕ ОСТАЛОСЬ НЕАКТИВНЫМ. WCAG 1.4.3 освобождает только
 *     его — и только там тихому уровню позволено быть ниже порога.
 *
 * ПОРОГ: нет текстовых узлов — проверка ПАДАЕТ, а не проходит вхолостую.
 * ВТОРОЙ ПОРОГ: если НИ НА ОДНОЙ странице не нашлось узла на градиенте,
 * значит складывание градиента отвалилось молча — и это тоже падение.
 */
const { test, expect } = require('../../fixtures');

const СТРАНИЦЫ = [
    '/index.html',
    '/pages/players.html',
    '/pages/news.html',
    '/pages/courts.html',
    '/pages/coaches.html',
    '/pages/services.html',
    '/pages/partners.html',
    '/pages/tournaments.html',
    '/pages/tournaments-overview.html',
    '/pages/info.html',
    '/pages/sponsors.html',
    '/pages/pricing.html'
];

/* Счёт живёт в ОДНОМ месте и зовётся отсюда. */
const ЗАМЕР = async page => page.evaluate(
    async () => (await import('/tools/kontrast.mjs')).замер(6));

async function открыть(page, адрес) {
    await page.goto(адрес);
    await page.waitForLoadState('domcontentloaded');
    await page.evaluate(() => document.fonts && document.fonts.ready);
    await page.waitForTimeout(500);
}

/* ПОРОГ ПРОТИВ ХОЛОСТОГО ПРОГОНА — НА СОДЕРЖИМОМ, А НЕ СЧЁТЧИКОМ.
   Первая попытка копила число градиентных узлов в переменной файла и
   проверяла его в afterAll. Прогон идёт в НЕСКОЛЬКИХ рабочих, счётчик
   границу рабочего не переживает, и порог упал на четырёх видах из пяти,
   ничего не доказав. Замерено 26.10: на главной 16 узлов на градиенте,
   на рейтинге 18. Якорь держится на этом, и каждый тест отвечает сам за
   себя. */
const ГРАДИЕНТНЫЕ = { '/index.html': 16, '/pages/players.html': 18 };

for (const адрес of СТРАНИЦЫ) {
test('контраст текста проходит AA · ' + адрес.split('/').pop(), async ({ page }) => {
    await открыть(page, адрес);
    const р = await ЗАМЕР(page);
    expect(р.узлов, 'ПОРОГ: текстовых узлов нет — мерить нечего').toBeGreaterThan(10);
    if (ГРАДИЕНТНЫЕ[адрес] !== undefined) {
        expect(р.наГрадиенте,
            'ПОРОГ: на этой странице 26.10 было ' + ГРАДИЕНТНЫЕ[адрес] +
            ' узлов на градиенте, а сейчас ноль. Это не «починили» — это ' +
            'складывание градиента отвалилось, и проба идёт вхолостую')
            .toBeGreaterThan(0);
    }
    expect(р.неМерено,
        'текст поверх ФОТОГРАФИИ: числом его не померить, и порог к нему не приложить. '
        + JSON.stringify(р.неМереноПримеры)).toBe(0);
    expect(р.нижеНормы,
        'текст ниже порога WCAG AA: ' + JSON.stringify(р.худшие)).toBe(0);
});
}

/* КРАСКА НЕ ЗАВИСИТ ОТ ЯЗЫКА — и потому контраст меряется на одном.
   Правило держится на ОТНОШЕНИИ: набор красок страницы на русском и на
   английском совпадает. Заведётся правило на :lang() — наборы разойдутся,
   и это упадёт здесь, а не через месяц на чужом экране. */
test('краска текста не зависит от языка', async ({ page }) => {
    const набор = async адрес => {
        await открыть(page, адрес);
        /* ЖДЁМ ПРИЗНАК, А НЕ ТИШИНУ. Полсекунды после domcontentloaded
           хватало на широком виде и не хватало на узком: список рейтинга
           приходит из сети, и на 375px одна страница успевала отрисоваться,
           а вторая нет — наборы расходились не языком, а временем. */
        await page.waitForSelector('.pl-row.pl-animate', { timeout: 15000 });
        await page.waitForFunction(
            () => document.querySelectorAll('.pl-row.pl-animate').length > 1,
            null, { timeout: 15000 });
        return page.evaluate(() => {
            const с = new Set();
            document.querySelectorAll('body *').forEach(э => {
                if (![...э.childNodes].some(n => n.nodeType === 3 && n.textContent.trim()))  return;
                const к = getComputedStyle(э);
                if (к.display === 'none' || к.visibility === 'hidden') return;
                с.add(к.color + '|' + к.fontSize + '|' + к.fontWeight);
            });
            return [...с].sort();
        });
    };
    const ру = await набор('/pages/players.html');
    const ен = await набор('/pages/players-en.html');
    expect(ру.length, 'ПОРОГ: красок не нашлось вовсе').toBeGreaterThan(3);
    const тольРу = ру.filter(с => ен.indexOf(с) === -1);
    const тольЕн = ен.filter(с => ру.indexOf(с) === -1);
    expect(тольРу.concat(тольЕн),
        'краска или кегль текста разошлись между языками — значит контраст ' +
        'надо мерить на всех трёх, а не на одном').toEqual([]);
});

test('тихий уровень в браузере даёт не меньше 4.5', async ({ page }) => {
    await открыть(page, '/pages/players.html');
    /* Формула — ТА ЖЕ, что у замера узлов: модуль один на весь продукт. */
    const р = await page.evaluate(async () => {
        const м = await import('/tools/kontrast.mjs');
        const кор = getComputedStyle(document.documentElement);
        const фон = м.раз(кор.getPropertyValue('--bg-base').trim()) || [10, 10, 10, 1];
        const о = {};
        ['--text-dim', '--text-muted', '--text-secondary'].forEach(т => {
            const ц = м.раз(кор.getPropertyValue(т).trim());
            if (!ц) return;
            const низ = [фон[0], фон[1], фон[2]];
            о[т] = Math.round(м.контраст(м.поверх(ц, низ), низ) * 100) / 100;
        });
        return о;
    });
    expect(р['--text-muted'], 'тихий уровень мимо AA: ' + JSON.stringify(р)).toBeGreaterThanOrEqual(4.5);
    /* ОТНОШЕНИЕ, А НЕ ЧИСЛО: три уровня идут по возрастанию. */
    expect(р['--text-dim'], 'лестница сломалась: ' + JSON.stringify(р))
        .toBeLessThan(р['--text-muted']);
    expect(р['--text-muted'], 'лестница сломалась: ' + JSON.stringify(р))
        .toBeLessThan(р['--text-secondary']);
});
