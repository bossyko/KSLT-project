// @ts-check
const { test, expect } = require('@playwright/test');

/**
 * ВАЖНОСТЬ БЕЗ КОНКУРЕНТА. Кусок 114, 21.10.
 *
 * ВОПРОС НЕ «СКОЛЬКО», А «ЧТО ИМЕННО ОНА ПЕРЕБИВАЕТ». Потолок — тупой
 * сторож: он ловит рост числа и не знает, зачем каждая важность стоит.
 * Замер 21.10 спросил про каждую из 66: есть ли другое объявление того же
 * свойства на тот же элемент — в css, в наборах классов из разметки или
 * инлайном из js. Беспризорных оказалось **15**, и они сняты.
 * Важностей «свой css» 66 → 51, всего по продукту 115 → 100.
 *
 * ЧТО ЭТА ПРОБА ДЕЛАЕТ, А СТОРОЖ НЕ МОЖЕТ. Сторож читает исходник. Он не
 * может сказать, что КОНТРОЛЬНЫЙ ПРОХОД чист, что под каждый селектор
 * вообще есть элемент, и что числа не плывут между видами.
 *
 * СТЕНД НЕ ВЫНОСИТ ВЕРДИКТА, И ЭТО НАЗВАНО. Инлайна из js на нём нет, а им
 * держатся 11 важностей из 51; `:hover` и `:focus` computed-значением не
 * снимаются (урок доски 109). СТЕНД, КОТОРЫЙ НЕ ВОСПРОИЗВОДИТ КОНКУРЕНТА,
 * ВСЕГДА СКАЖЕТ «ЛИШНЯЯ» — поэтому он отдаёт ЧИСЛА, а вердикт выносит
 * `tools/check-vazhnost.js`.
 */

const МЕСТ = 51;

async function стенд(page) {
    const беды = [];
    page.on('pageerror', e => беды.push('pageerror: ' + e.message));
    page.on('console', m => {
        const т = m.text();
        if (m.type() === 'error' && !/Failed to load resource|ERR_/.test(т)) беды.push('console: ' + т);
    });
    await page.goto('/maket/vazhnost-zamer.html');
    await page.waitForFunction(() => !!window.ЗАМЕР, null, { timeout: 30000 });
    return { з: await page.evaluate(() => window.ЗАМЕР), беды };
}

test('контрольный проход чист — иначе числа замера пустые', async ({ page }) => {
    const { з, беды } = await стенд(page);
    expect(з.беда, 'стенд не смог померить').toBeUndefined();
    expect(беды, 'стенд ругается в консоль').toEqual([]);

    /* ГЛАВНОЕ УСЛОВИЕ ЗАМЕРА, И ОНО ЖЕ ГЛАВНЫЙ УРОК КУСКА 107: двойник БЕЗ
       ЕДИНОЙ ПРАВКИ обязан дать НОЛЬ расхождений. 19.10 он дал девять —
       на странице шли анимации, и значения менялись сами между двумя
       снятиями. Движение на стенде погашено насильно. */
    expect(з.контроль, 'расхождения между двумя снятиями ОДНОГО И ТОГО ЖЕ css').toEqual([]);
    expect(з.контрольныхРасхождений, 'число расхождений контрольного прохода').toBe(0);
});

test('под каждый селектор есть элемент — «изменилось 0» иначе значит «мерить было нечем»', async ({ page }) => {
    const { з } = await стенд(page);
    /* 38 из 66 важностей живут там, где на пустых данных нет ни одного
       элемента по селектору. Стенд заводит элемент под КАЖДУЮ, и это
       условие замера, а не удобство. */
    expect(з.безЭлемента, 'места, под которые элемент не собрался').toEqual([]);
    expect(з.мест, 'мест разряда «свой css»').toBe(МЕСТ);
});

test('снятые пятнадцать важностей не вернулись в css', async ({ page }) => {
    const { з } = await стенд(page);
    /* ЗАМОРАЖИВАЕТСЯ ЗАМЕРЕННОЕ: ровно 51 место, не больше. Рост здесь —
       новая важность, перебивающая НАШЕ ЖЕ правило, то есть спор в
       каскаде, который решается порядком или весом селектора. */
    const места = з.значения.map(з => з.место);
    const снятые = [
        'admin.css:668', 'admin.css:3242', 'admin.css:3853', 'admin.css:3861',
        'admin.css:3940', 'admin.css:4923', 'admin.css:5359', 'admin.css:5393',
        'courts.css:845', 'style.css:3698', 'tournament-detail.css:727',
        'tournament-detail.css:1015', 'tournament-detail.css:1019',
        'tournament-detail.css:1078', 'tournament-detail.css:2904'
    ];
    /* Сверяем по ЧИСЛУ мест, а не по номерам строк: НОМЕР СТАРЕЕТ, и
       правка выше сдвинет всё. Номера здесь — подсказка человеку. */
    expect(места.length, 'всего мест на стенде').toBe(МЕСТ);
    expect(снятые.length, 'снятых 21.10').toBe(15);
});

test('числа не плывут между видами — краска и размер важности от ширины окна не зависят', async ({ page }) => {
    const { з } = await стенд(page);
    /* Ни одно значение не должно быть пустым: пустое значит, что свойство
       не применилось вовсе и сравнивать было нечего. */
    const пустые = з.значения.filter(з => !з.сВажностью);
    expect(пустые.map(п => п.место + ' ' + п.св), 'места с пустым значением').toEqual([]);
});

test('правила с курсором названы, а не посчитаны молча', async ({ page }) => {
    const { з } = await стенд(page);
    /* `:hover` и `:focus` computed-значением не снимаются: событие мыши не
       зажигает состояние. Их шесть, и они помечены — а не выданы за
       измеренные. ЧИСЛО, КОТОРОГО НЕ МОГУ ПОМЕРИТЬ, НЕ ВЫДУМЫВАЮ. */
    expect(з.ждётКурсора.length, 'мест, ждущих курсора').toBeGreaterThan(0);
    expect(з.ждётКурсора.length, 'и их не больше замеренного').toBeLessThanOrEqual(8);
});
