// @ts-check
const { test, expect } = require('@playwright/test');

/**
 * ЭКРАНИРОВАНИЕ: ЧТО ДОХОДИТ ДО АТРИБУТА. Круг 19 ветки D.
 *
 * ЗАЧЕМ ПРОБА, ЕСЛИ ЕСТЬ СТОРОЖ. `tools/check-ekranirovanie.js` читает
 * исходник и смотрит, гасит ли функция обе кавычки. Он не может сказать,
 * что из этого РАЗБЕРЁТ БРАУЗЕР. А вся беда была ровно в этом: слабый
 * приём через `textContent` безупречно работает, пока результат идёт в
 * ТЕКСТ, — потому он и прожил в продукте так долго, выглядя безопасным.
 *
 * Здесь каждый способ, какой встречался в продукте, подставляет имя с
 * кавычками внутрь атрибута, результат вставляется в живой DOM, и у
 * браузера спрашивается: уцелел ли атрибут целиком.
 *
 * КРАЙНИЙ СЛУЧАЙ, А НЕ УДОБНЫЙ: имя с двойной кавычкой, одинарной,
 * угловыми скобками и амперсандом — всё, что человек может ввести в
 * админке в названии клуба или имени игрока.
 *
 * ПЯТЬ ВИДОВ. Экранирование от ширины окна не зависит — и проба требует,
 * чтобы не зависело: вид не должен менять ни одного исхода.
 */

async function стенд(page) {
    const беды = [];
    page.on('pageerror', e => беды.push('pageerror: ' + e.message));
    page.on('console', m => {
        const т = m.text();
        if (m.type() === 'error' && !/Failed to load resource|ERR_/.test(т)) {
            беды.push('console: ' + т);
        }
    });
    await page.goto('/maket/ekranirovanie-zamer.html');
    await page.waitForFunction(() => !!window.ЗАМЕР, null, { timeout: 15000 });
    return { з: await page.evaluate(() => window.ЗАМЕР), беды };
}

test('для атрибута годен только полный способ — остальные рвут', async ({ page }) => {
    const { з, беды } = await стенд(page);
    expect(беды, 'страница ругается в консоль').toEqual([]);

    /* Имя-испытание должно нести все четыре опасных знака, иначе проба
       проверяет не то. Это проверка САМОГО ПРИБОРА. */
    expect(з.имя).toContain('"');
    expect(з.имя).toContain("'");
    expect(з.имя).toContain('<');
    expect(з.имя).toContain('&');

    /* ГЛАВНОЕ: годен ровно один способ, и это эталон продукта. */
    expect(з.годныеДляАтрибута, 'способы, годные для атрибута в любых кавычках')
        .toEqual(['эталон kslt-lenta']);

    /* И три прежних приёма рвут атрибут — каждый на своём месте. */
    expect(з.рвутАтрибут.sort()).toEqual([
        'createTextNode (слабый)', 'textContent (слабый)', 'без одинарной (частичный)'
    ].sort());
});

test('слабый приём безупречен в тексте — потому и жил так долго', async ({ page }) => {
    const { з } = await стенд(page);
    /* Это не придирка, а объяснение: как ТЕКСТ все четыре способа верны,
       и по виду кода разница незаметна. Разница видна только в атрибуте. */
    Object.keys(з.способы).forEach(к => {
        expect(з.способы[к].текстом.целоеИмя, 'как текст: ' + к).toBe(true);
    });
    /* А в атрибуте с двойными кавычками слабые приёмы уже рвут. */
    expect(з.способы['textContent (слабый)'].двойные.целоеИмя).toBe(false);
    expect(з.способы['createTextNode (слабый)'].двойные.целоеИмя).toBe(false);
    /* Частичный там держится — на этом и стояло соглашение, которое
       никто не сторожил. */
    expect(з.способы['без одинарной (частичный)'].двойные.целоеИмя).toBe(true);
    expect(з.способы['без одинарной (частичный)'].одинарные.целоеИмя).toBe(false);
});
