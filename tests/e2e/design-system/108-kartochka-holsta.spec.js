// @ts-check
const { test, expect } = require('@playwright/test');

/**
 * ПЕЧАТНАЯ КАРТОЧКА: ЧТО НА НЕЙ НАРИСОВАНО. Круг 18 ветки D, находка 96е.
 *
 * ЗАЧЕМ ПРОБА, ЕСЛИ ЕСТЬ СТОРОЖ. `tools/check-kartochka-holsta.js` читает
 * ИСХОДНИК: одно ли определение, домом ли краска, со шкалы ли кегли. Но
 * он не может сказать, ВИДНО ли нарисованное. А главная беда этого куска
 * была именно такой: `ctx.strokeStyle = 'var(--alpha-lime-20)'` стоял в
 * четырёх копиях, выглядел как заданная краска — и разделительная линия
 * не рисовалась НИ НА ОДНОЙ карточке. Исходник тут бессилен.
 *
 * ЧИТАЕТСЯ НАРИСОВАННОЕ: карточка строится настоящим домом продукта, а
 * затем её пиксели снимаются обратно, и контраст каждого текста считается
 * к фону ПОД ним — к тому месту градиента, где текст стоит, а не к
 * среднему по карточке.
 *
 * КРАЙНИЕ СЛУЧАИ, А НЕ УДОБНЫЕ: ваучер без скидки, без срока и без
 * заведения, с длинными кыргызскими строками. До круга 18 ваучер без
 * скидки рисовал «-undefined%» — проверку знала только копия кабинета.
 *
 * ПОРОГ СТРОЖЕ ЭКРАННОГО: это картинка, которую показывают с телефона,
 * случается — на солнце. AA 4.5 для мелкого текста, без поблажек.
 *
 * ПЯТЬ ВИДОВ. Карточка рисуется на холсте и от ширины окна не зависит —
 * и именно это проверяется: вид не должен менять ни одного числа.
 */

async function стенд(page) {
    const беды = [];
    page.on('pageerror', e => беды.push('pageerror: ' + e.message));
    page.on('console', m => {
        const т = m.text();
        if (m.type() === 'error' && !/Failed to load resource|ERR_|supabase/i.test(т)) {
            беды.push('console: ' + т);
        }
        /* Жалоба дома красок на ненайденный токен — провал, а не шум. */
        if (m.type() === 'warning' && /KSLT_KRASKA/.test(т)) беды.push('жалоба дома: ' + т);
    });
    await page.goto('/maket/vaucher-kartochka-zamer.html');
    await page.waitForFunction(() => !!window.ЗАМЕР, null, { timeout: 15000 });
    return { з: await page.evaluate(() => window.ЗАМЕР), беды };
}

test('карточка: разделитель нарисован, тексты читаемы, крайние случаи целы', async ({ page }) => {
    const { з, беды } = await стенд(page);

    expect(беды, 'страница ругается или дом не нашёл токен').toEqual([]);

    /* Пять случаев ваучера и три профиля — все построились. */
    expect(з.ваучер.length, 'случаев ваучера').toBe(5);
    expect(з.профиль.length, 'случаев профиля').toBe(3);

    /* 1. РАЗДЕЛИТЕЛЬ ЕСТЬ. Прежде стоял var() и не рисовался вовсе. */
    expect(з.разделительНеНарисован, 'разделитель не нарисован').toEqual([]);

    /* 2. НИ ОДНОГО ТЕКСТА НИЖЕ AA 4.5 — у нарисованного, не у задуманного. */
    expect(з.нижеПорога, 'текст ниже порога 4.5').toEqual([]);

    /* 2б. РАСШИФРОВКА НЕ ДОТЯНУЛАСЬ ДО КОНЦОВ РАЗДЕЛИТЕЛЯ. Русская строка
          длиннее английской на 77 пунктов ширины, и это единственное
          число, которым она могла сломать карточку: разделитель идёт от
          40 до ш−40, и текст, дошедший до 40, слился бы с линией.
          Замер 19.10: с аббревиатурой 320.2 при полосе 300 — не влезала. */
    expect(з.расшифровкаВылезла, 'расшифровка вылезла за полосу').toEqual([]);

    /* 3. Размеры карточек те же, что были: ваучер 380×520, профиль 380×480.
          Сведение копий не должно было менять размер. */
    з.ваучер.forEach(к => {
        expect(к.ш, 'ширина ваучера, случай ' + к.случай).toBe(380);
        expect(к.в, 'высота ваучера, случай ' + к.случай).toBe(520);
        expect(к.расшифровкаВПолосе, 'расшифровка в полосе, случай ' + к.случай).toBe(true);
    });
    з.профиль.forEach(к => {
        expect(к.ш, 'ширина профиля, случай ' + к.случай).toBe(380);
        expect(к.в, 'высота профиля, случай ' + к.случай).toBe(480);
    });

    /* 4. Контраст одинаков во ВСЕХ случаях: он свойство карточки, а не
          того, сколько в ней данных. Пустая скидка не должна его менять. */
    const подзаголовки = [...new Set(з.ваучер.map(к => к.подзаголовок.контраст))];
    expect(подзаголовки.length, 'контраст подзаголовка разный в разных случаях: ' +
        подзаголовки.join(', ')).toBe(1);
});

test('карточка: ни одной пустой краски и ни одного var() в холсте', async ({ page }) => {
    const { з } = await стенд(page);
    /* Пустая краска на холсте — прозрачность, то есть исчезнувший текст.
       Снимаем это через яркость: текст обязан быть светлее своего фона. */
    ['ваучер', 'профиль'].forEach(вид => {
        з[вид].forEach(к => {
            ['подзаголовок', 'подписьСкана', 'подписьСайта'].forEach(поле => {
                const п = к[поле];
                if (!п) return;
                expect(п.контраст, вид + '/' + к.случай + '/' + поле +
                    ' — текст не отличим от фона, значит не нарисован')
                    .toBeGreaterThan(1.5);
            });
        });
    });
});
