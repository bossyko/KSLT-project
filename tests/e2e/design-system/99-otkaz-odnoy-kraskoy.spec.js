/**
 * ОТКАЗ И ПРОИГРЫШ ОДНОЙ КРАСКОЙ. 15.10, ветка B, заход B3, круг 2, подкруг 2а.
 *
 * Замер: в публичной части 121 красное место и 16 РАЗНЫХ красок при живых
 * `--red-500`, `--danger`, `--danger-subtle`. Роль «отказ и проигрыш» —
 * 32 места, восемь красок — сведена в `var(--danger)`.
 *
 * ЧТО ПРОВЕРЯЕТ ПРОГОН, А НЕ ЗАМОРОЗКА:
 *
 *   • ЧТО РОЛЬ ГОВОРИТ ОДНОЙ КРАСКОЙ НА ЭКРАНЕ, а не в файле. Правило
 *     смотрит в блок по селектору; что на живой странице у всех узлов
 *     роли вышла ОДНА краска после всего каскада — показывает только
 *     загрузка. Раньше красок было восемь, и расходились они между
 *     страницами: у проигрыша матча `#ef4444`, у отказа в заявке
 *     `#f44336`, у ошибки входа `#ff6b6b` — три сигнала об одном;
 *   • КОНТРАСТ НА ФАКТИЧЕСКОЙ ПОДЛОЖКЕ. Контраст решает не имя краски, а
 *     то, ЧТО ПОД ТЕКСТОМ: у плашки проигрыша это тинт той же краски 15%
 *     поверх белого 4% поверх почти-чёрного. ПРОЗРАЧНАЯ КРАСКА
 *     СМЕШИВАЕТСЯ С ФОНОМ, и сложить слои может только браузер. Было 4.21
 *     при норме AA 4.5 — единственное место ниже нормы во всей публичной
 *     части. Стало 4.67, и запас всего 0.17.
 *
 * ПОЧЕМУ ПЛАШКА СОБИРАЕТСЯ ПРОГОНОМ, А НЕ БЕРЁТСЯ СО СТРАНИЦЫ.
 * `.pp-match-result` виден только ВОШЕДШЕМУ: гостю страница игрока
 * отдаёт обрезанный профиль (`.pp-guest-block`), и живых плашек в DOM
 * нет вовсе — это не поломка, а три режима доступа, заложенные Костей.
 * Прогон же ходит гостем. Поэтому узел собирается из тех же классов на
 * той же странице: css загружен, правила и каскад НАСТОЯЩИЕ, меряется
 * ровно то, что увидит вошедший. Сверено с живой страницей 15.10 —
 * 4.67 там и тут.
 *
 * ПОРОГ: узлов роли не нашлось — проверка ПАДАЕТ, а не проходит
 * вхолостую. Пустая страница не доказывает ничего.
 */
const { test, expect } = require('../../fixtures');

const ЯЗЫКИ = [
    { код: 'ru', хвост: '' },
    { код: 'en', хвост: '-en' },
    { код: 'kg', хвост: '-kg' }
];

/** Системный красный — то, чем роль обязана говорить. */
const DANGER = 'rgb(255, 71, 87)';

async function открыть(page, адрес, признак) {
    await page.goto(адрес);
    await page.waitForLoadState('domcontentloaded');
    await page.waitForFunction(с => document.querySelectorAll(с).length > 0, признак, { timeout: 20000 });
    await page.waitForTimeout(400);
}

for (const язык of ЯЗЫКИ) {

test.describe('отказ одной краской · ' + язык.код, () => {

    test('роль говорит одной краской на экране', async ({ page }) => {
        await открыть(page, '/pages/players' + язык.хвост + '.html', '.pl-form-loss, .pl-row');
        const м = await page.evaluate(() => {
            const узлы = [...document.querySelectorAll('.pl-form-loss, .pl-change-down')];
            const краски = {};
            узлы.forEach(э => {
                const s = getComputedStyle(э);
                /* берём ту краску, которой узел РИСУЕТ: у подписи это текст,
                   у точки формы — заливка */
                const к = (э.textContent || '').trim() ? s.color : s.backgroundColor;
                краски[к] = (краски[к] || 0) + 1;
            });
            return { узлов: узлы.length, краски };
        });
        expect(м.узлов, 'ПОРОГ: узлов роли не нашлось — страница недогружена').toBeGreaterThan(0);
        expect(Object.keys(м.краски),
            'роль «отказ и проигрыш» говорит НЕСКОЛЬКИМИ красками: ' + JSON.stringify(м.краски) +
            '\nДо 15.10 их было восемь, и они расходились между страницами.').toHaveLength(1);
        expect(Object.keys(м.краски)[0],
            'роль говорит не системным красным: ' + Object.keys(м.краски)[0]).toBe(DANGER);
    });

    test('плашка проигрыша проходит AA на фактической подложке', async ({ page }) => {
        await открыть(page, '/pages/player' + язык.хвост + '.html?id=kseniya-han', '.pp-hero, [class^="pp-"]');
        const м = await page.evaluate(() => {
            const лин = c => { c /= 255; return c <= 0.03928 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4); };
            const ярк = ([r, g, b]) => 0.2126 * лин(r) + 0.7152 * лин(g) + 0.0722 * лин(b);
            const K = (a, b) => { const x = Math.max(ярк(a), ярк(b)), y = Math.min(ярк(a), ярк(b)); return (x + 0.05) / (y + 0.05); };
            const разбор = s => { const m = String(s).match(/rgba?\(([^)]+)\)/); if (!m) return null;
                const ч = m[1].split(/[,\s/]+/).filter(Boolean).map(Number);
                return { rgb: ч.slice(0, 3), a: ч.length > 3 ? ч[3] : 1 }; };
            const поверх = (в, н, a) => в.map((v, i) => Math.round(v * a + н[i] * (1 - a)));

            /* живая плашка, если есть; иначе собираем из тех же классов —
               css и каскад настоящие, см. шапку файла */
            let э = document.querySelector('.pp-match-result.loss');
            let гнездо = null;
            if (!э) {
                гнездо = document.createElement('div');
                гнездо.className = 'pp-matches';
                гнездо.innerHTML = '<div class="pp-match"><div class="pp-match-result loss">L</div></div>';
                document.body.appendChild(гнездо);
                э = гнездо.querySelector('.pp-match-result.loss');
            }
            const s = getComputedStyle(э);
            /* СКЛАДЫВАЕМ СЛОИ СНИЗУ ВВЕРХ: иначе тинт поверх тинта
               посчитается как плотный цвет, и контраст соврёт в плюс */
            const слои = [];
            for (let у = э; у; у = у.parentElement) {
                const ц = разбор(getComputedStyle(у).backgroundColor);
                if (ц && ц.a > 0) { слои.push(ц); if (ц.a >= 0.999) break; }
                if (у === document.documentElement) break;
            }
            let низ = [10, 10, 10];
            for (let i = слои.length - 1; i >= 0; i--) низ = поверх(слои[i].rgb, низ, слои[i].a);
            const ц = разбор(s.color);
            const свой = ц.a < 0.999 ? поверх(ц.rgb, низ, ц.a) : ц.rgb;
            const из = { контраст: Math.round(K(свой, низ) * 100) / 100, подложка: низ, цвет: s.color,
                         фон: s.backgroundColor, кегль: parseFloat(s.fontSize), вес: s.fontWeight,
                         собрана: !!гнездо, слоёв: слои.length };
            if (гнездо) гнездо.remove();
            return из;
        });
        expect(м.слоёв, 'ПОРОГ: подложка не собралась — css страницы не загрузился').toBeGreaterThan(1);
        expect(м.цвет, 'плашка проигрыша красится не системным красным: ' + м.цвет).toBe(DANGER);
        const крупный = м.кегль >= 24 || (м.кегль >= 18.66 && +м.вес >= 700);
        expect(м.контраст,
            'плашка проигрыша не проходит AA: ' + JSON.stringify(м) +
            '\nДо 15.10 здесь было 4.21 — единственное место ниже нормы во всей\n' +
            'публичной части. Запас у 4.67 всего 0.17: любое потемнение\n' +
            '`--red-500` или утяжеление тинта уводит обратно под норму.')
            .toBeGreaterThanOrEqual(крупный ? 3 : 4.5);
    });

});

}
