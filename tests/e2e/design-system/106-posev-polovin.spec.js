const { test, expect } = require('@playwright/test');

/**
 * ПОСЕВ ПЛЕЙ-ОФФА: ЧЕТЫРЕ ПЛАНКИ, ВСЕ 42 РАСКЛАДА — В БРАУЗЕРЕ.
 *
 * ЗАЧЕМ ПРОБА, ЕСЛИ ЕСТЬ СТОРОЖ. `tools/check-posev-polovin.js` вырезает
 * `раскладСлотов` из файла и гоняет её в node — то есть мерит ТЕКСТ
 * функции. Здесь она исполняется в настоящем браузере, из настоящей
 * админки, со всеми своими зависимостями (`SEED_POSITIONS`, `KSLT_RULES`),
 * как у менеджера. Непрогнанный тест — непроверенный код.
 *
 * Стенд `maket/setka-zamer.html` грузит НАСТОЯЩУЮ админку и подменяет
 * только `A.client`. Базы здесь нет: прогон ничего не пишет и не ест квоту.
 *
 * ЯЗЫК ОДИН — РУССКИЙ: `pages/admin-en.html` это перенаправление, и в нём
 * написано почему. ВИДОВ ТРИ — админка десктоп и планшет (слово Кости
 * 29.09), телефонной раскладки в ней нет.
 *
 * ЧЕТЫРЕ ПЛАНКИ, И КАЖДАЯ — ОТНОШЕНИЕ, А НЕ ЧИСЛО:
 *   1 земляки встречаются не раньше решённого круга: при двоих выходящих
 *     только финал, при троих — финал или полуфинал (развести трёх членов
 *     группы по двум половинам невозможно в принципе);
 *   2 двое слабейших (Q и IG) не стоят в одной паре первого круга —
 *     непрошедшие ставятся по силе, решение Кости 29.09;
 *   3 сеяные стоят ровно на позициях посева, а проход без игры достаётся
 *     сеяным, пока сеяные есть;
 *   4 в сетке стоят ВСЕ, кто вышел из групп, — ни один не теряется.
 */

const ТЕЛЕФОННЫЕ = ['mobile', 'phone-landscape'];

const ВЫХОДЯТ = [1, 2, 3];
const ГРУПП = [2, 3, 4, 5, 6, 7, 8];
const ФОРМАТЫ = ['ig', 'direct'];

async function стенд(page) {
    const беды = [];
    page.on('pageerror', e => беды.push('pageerror: ' + e.message));
    page.on('console', m => {
        const т = m.text();
        if (m.type() === 'error' && !/Failed to load resource|ERR_/.test(т)) беды.push('console: ' + т);
    });
    await page.goto('/maket/setka-zamer.html?r=1');
    await page.waitForSelector('.ad-brk-match', { timeout: 15000 });
    return беды;
}

test.describe('посев плей-оффа — четыре планки на 42 раскладах', () => {
    test.beforeEach(({}, info) => {
        test.skip(ТЕЛЕФОННЫЕ.indexOf(info.project.name) !== -1,
            'админка — десктоп и планшет: телефонной раскладки в ней нет (слово Кости 29.09)');
    });

    test('все 42 расклада держат четыре планки', async ({ page }) => {
        const беды = await стенд(page);
        expect(беды, беды.join(' | ')).toHaveLength(0);

        // функция должна быть доступна из админки, а не пересказана тестом
        expect(await page.evaluate(() => typeof window.KSLT_ADMIN?.раскладСлотов))
            .toBe('function');

        const итог = await page.evaluate(({ ВЫХОДЯТ, ГРУПП, ФОРМАТЫ }) => {
            const A = window.KSLT_ADMIN;
            /* круг первой встречи двух слотов: пара — соседние индексы,
               ветка — общий предок при делении пополам */
            function кругПары(i, j, размер) {
                let a = i, b = j, к = 1, ш = размер;
                while (ш > 1) {
                    if ((a >> 1) === (b >> 1) && Math.abs(a - b) === 1) return к;
                    a >>= 1; b >>= 1; ш >>= 1; к++;
                }
                return к;
            }
            const бn = [];
            let раскладов = 0;
            for (const формат of ФОРМАТЫ) {
                for (const выходят of ВЫХОДЯТ) {
                    for (const групп of ГРУПП) {
                        раскладов++;
                        const имя = формат + ' ' + групп + '×' + выходят;
                        let р;
                        try {
                            р = A.раскладСлотов({ qualifiers_per_group: выходят, playoff_format: формат }, групп);
                        } catch (e) { бn.push(имя + ' — функция упала: ' + e.message); continue; }
                        if (!р) { бn.push(имя + ' — расклада нет'); continue; }
                        const сетка = р.сетка, размер = р.размер;
                        const кругов = Math.round(Math.log(размер) / Math.LN2);

                        // 1 · земляки
                        const планка = выходят >= 3 ? 1 : 0;
                        for (let i = 0; i < размер; i++) {
                            for (let j = i + 1; j < размер; j++) {
                                const a = сетка[i], b = сетка[j];
                                if (!a || !b || a.группа < 0 || a.группа !== b.группа) continue;
                                const доКонца = кругов - кругПары(i, j, размер);
                                if (доКонца > планка) {
                                    бn.push(имя + ' — земляки ' + a.метка + '/' + b.метка +
                                            ' сходятся за ' + доКонца + ' кругов до конца, планка ' + планка);
                                }
                            }
                        }

                        // 2 · слабейшие
                        for (let i = 0; i < размер; i += 2) {
                            const a = сетка[i], b = сетка[i + 1];
                            if (a && b && a.группа < 0 && b.группа < 0) {
                                бn.push(имя + ' — слабейшие ' + a.метка + ' и ' + b.метка + ' в одной паре первого круга');
                            }
                        }

                        // 3 · сеяные и проход без игры
                        const позиции = window.SEED_POSITIONS && window.SEED_POSITIONS[размер];
                        let сеяных = 0;
                        for (let п = 0; п < размер; п++) if (сетка[п] && сетка[п].посев) сеяных++;
                        if (позиции) {
                            for (let н = 1; н <= сеяных; н++) {
                                const ждём = позиции[н - 1] - 1;
                                const кто = сетка[ждём];
                                if (!кто || кто.посев !== н) {
                                    бn.push(имя + ' — сеяный №' + н + ' не на позиции ' + позиции[н - 1]);
                                    break;
                                }
                            }
                        }
                        const пустые = [];
                        for (let п = 0; п < размер; п++) if (!сетка[п]) пустые.push(п);
                        const вПарах = пустые.filter(п => {
                            const с = сетка[(п % 2 === 0) ? п + 1 : п - 1];
                            return с && с.посев;
                        }).length;
                        const ждёмBye = Math.min(пустые.length, сеяных);
                        if (вПарах < ждёмBye) {
                            бn.push(имя + ' — проход без игры достался сеяным ' + вПарах + ' раз из ' + ждёмBye);
                        }

                        // 4 · никто не потерян
                        const стоит = сетка.filter(к => к && к.группа >= 0).length;
                        if (стоит < групп * выходят) {
                            бn.push(имя + ' — потеряно ' + (групп * выходят - стоит) + ' из ' + (групп * выходят) + ' вышедших');
                        }
                    }
                }
            }
            return { раскладов, беды: бn };
        }, { ВЫХОДЯТ, ГРУПП, ФОРМАТЫ });

        expect(итог.раскладов).toBe(42);
        expect(итог.беды, итог.беды.slice(0, 12).join(' | ')).toHaveLength(0);
    });

    test('на экране стоят все, кто вышел из групп', async ({ page }) => {
        const беды = await стенд(page);
        expect(беды, беды.join(' | ')).toHaveLength(0);

        /* ПРИЗНАК, А НЕ ТИШИНА СЕТИ: клетки сетки уже дождались селектором
           выше. Здесь сверяем, что число подписанных источников в сетке не
           меньше числа мест, которые разыгрываются по настройке стенда. */
        const сверка = await page.evaluate(() => {
            const A = window.KSLT_ADMIN;
            const р = A.раскладСлотов({ qualifiers_per_group: 1, playoff_format: 'ig' }, 8);
            return {
                надо: 8,
                стоит: р.сетка.filter(к => к && к.группа >= 0).length,
                метки: р.сетка.filter(к => к && к.группа >= 0).map(к => к.метка).sort()
            };
        });
        expect(сверка.стоит, 'метки в сетке: ' + сверка.метки.join(' ')).toBe(сверка.надо);
        expect(сверка.метки).toEqual(['A1', 'B1', 'C1', 'D1', 'E1', 'F1', 'G1', 'H1']);
    });
});
