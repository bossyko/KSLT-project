// @ts-check
const { test, expect } = require('../../fixtures');

/**
 * ИТОГИ ТУРНИРА — ОДНА ТАБЛИЦА НА ВСЕ ЧЕТЫРЕ ТИПА СЕТКИ.
 *
 * Слово Кости 01.10: «надо будет отобразить так, как надо, чтобы все
 * видели». Под пьедесталом — все участники: место, игрок, этап, очки.
 *
 * До 02.10 эта таблица жила ТОЛЬКО у олимпийки и круговой. У сетки «все
 * места» под пьедесталом были номер и имя, ОЧКОВ НЕ БЫЛО ВОВСЕ; у двух лиг
 * — своя таблица из `rating_history`, где место подменял номер строки, а
 * этапа не было совсем. Одно понятие, три экрана.
 *
 * ЧЕГО ЗАМОРОЗКА НЕ ВИДИТ. Правила держат, что функция одна и что зовут её
 * три ветки. Но ЧТО ИМЕННО ВСТАЛО В КЛЕТКУ — полоса или число, «Полуфинал»
 * или «Матч за 5-6 место» — видно только прогоном. И только прогон
 * проверит, что на телефоне колонка этапа ушла, а не поехала.
 *
 * ПУБЛИЧНАЯ СТРАНИЦА МЕРИТСЯ НА ПЯТИ ВИДАХ И ТРЁХ ЯЗЫКАХ — пропусков тут
 * нет: это экран зрителя, а не админки.
 */

const ОЛИМПИЙКА = 'test-itogi';
const ВСЕ_МЕСТА = 'test-itogi-fic';

/** Страницы трёх языков — один и тот же экран. */
const ЯЗЫКИ = [
    { код: 'ru', стр: '/pages/tournament.html',    итог: 'Итоги турнира',
      этапQF: 'Четвертьфинал', матч56: 'Матч за 5-6 место' },
    { код: 'en', стр: '/pages/tournament-en.html', итог: 'Tournament results',
      этапQF: 'Quarterfinal',  матч56: 'Match for places 5-6' },
    { код: 'kg', стр: '/pages/tournament-kg.html', итог: 'Турнирдин жыйынтыгы',
      этапQF: 'Чейрек финал',  матч56: '5-6 орун үчүн оюн' }
];

/** Снять таблицу итогов целиком: заголовок и все строки по колонкам. */
async function снятьТаблицу(page, адрес) {
    await page.goto(адрес);
    await page.waitForSelector('.td-results-table', { timeout: 20000 });
    return page.evaluate(() => {
        const т = document.querySelector('.td-results-table');
        const заголовок = т.querySelector('.td-results-title');
        const этапЯчейка = т.querySelector('tbody .td-res-stage');
        const всеТаблицы = document.querySelectorAll('#resultsPodium table').length;
        const наши = т.querySelectorAll('table').length;
        return {
            заголовок: заголовок ? заголовок.textContent : '',
            колонок: т.querySelectorAll('thead th').length,
            строки: [...т.querySelectorAll('tbody tr')].map(стр => ({
                место: (стр.querySelector('.td-res-place') || {}).textContent || '',
                игрок: (стр.children[1] || {}).textContent || '',
                этап: (стр.querySelector('.td-res-stage') || {}).textContent || '',
                очки: (стр.querySelector('.td-res-pts') || {}).textContent || '',
                победитель: стр.className.indexOf('td-res-winner') !== -1
            })),
            этапВиден: !!этапЯчейка && getComputedStyle(этапЯчейка).display !== 'none',
            своихТаблиц: всеТаблицы - наши
        };
    });
}

test.describe('Итоги турнира под пьедесталом', () => {

    test('олимпийка: место полосой там, где его не разыгрывали',
        async ({ page }) => {
            const т = await снятьТаблицу(page, ЯЗЫКИ[0].стр + '?id=' + ОЛИМПИЙКА);

            /* ПОРОГ ПЕРВЫМ: пустую таблицу сверять не с чем. В севе восемь. */
            expect(т.строки.length, 'в таблице итогов не восемь строк — сверять нечего')
                .toBe(8);
            expect(т.колонок, 'колонок не четыре: место · игрок · этап · очки').toBe(4);

            const места = т.строки.map(с => с.место.replace(/[^\d\-—]/g, ''));
            expect(места.slice(0, 4), 'первые четыре места названы не числами')
                .toEqual(['1', '2', '3', '4']);

            /* ЧЕТВЕРО ПРОИГРАВШИХ ЧЕТВЕРТЬФИНАЛ МЕЖДУ СОБОЙ НЕ ИГРАЛИ.
               Одно число «5» у всех четверых утверждает то, чего не было. */
            expect(места.slice(4), 'места 5-8 названы числами, хотя их не разыгрывали')
                .toEqual(['5-8', '5-8', '5-8', '5-8']);

            expect(т.строки[0].очки.trim(), 'очки победителя не те, что в базе').toBe('360');
            expect(т.строки[0].победитель, 'строка победителя не помечена').toBe(true);
            expect(т.строки.filter(с => с.победитель).length,
                'помечена не одна строка победителя').toBe(1);

            /* МЕДАЛЬ ИЩЕТСЯ ВХОЖДЕНИЕМ, А НЕ КЛАССОМ СИМВОЛОВ. `[🥇🥈🥉]` в
               регулярке рвёт суррогатную пару и ловит половину символа:
               02.10 проверка упала, показав «▯» вместо медали, хотя на
               странице всё стояло верно. */
            const медаль = с => ['🥇', '🥈', '🥉'].find(м => с.место.indexOf(м) !== -1) || '';
            expect(т.строки.slice(0, 3).map(медаль), 'медали стоят не у первых трёх')
                .toEqual(['🥇', '🥈', '🥉']);
            expect(т.строки.slice(3).map(медаль).join(''),
                'медаль ушла ниже третьего места').toBe('');

            /* ОДНА ТАБЛИЦА НА ВСЕ ТИПЫ: своей, собранной руками, под
               пьедесталом быть не должно. */
            expect(т.своихТаблиц, 'под пьедесталом появилась вторая таблица').toBe(0);
        });

    test('все места: место точное, а этап называет матч за места',
        async ({ page }) => {
            const т = await снятьТаблицу(page, ЯЗЫКИ[0].стр + '?id=' + ВСЕ_МЕСТА);

            expect(т.строки.length, 'в таблице итогов не восемь строк — сверять нечего')
                .toBe(8);

            const места = т.строки.map(с => с.место.replace(/[^\d\-—]/g, ''));
            expect(места, 'в сетке «все места» место названо полосой, хотя его разыграли')
                .toEqual(['1', '2', '3', '4', '5', '6', '7', '8']);

            /* БУКВЕННЫЙ КОД ВЗЯТ РАДИ ОЧКОВ, А НЕ РАДИ ПОДПИСИ. У пятого в
               базе лежит `SF` — но полуфинала он не играл, он играл матч за
               5-6 место. Решение Кости 02.10. */
            expect(т.строки[4].этап.trim(), 'пятый назван полуфиналистом')
                .toBe('Матч за 5-6 место');
            expect(т.строки[5].этап.trim(), 'шестой назван не своим матчем')
                .toBe('Матч за 5-6 место');
            expect(т.строки[6].этап.trim(), 'седьмой назван четвертьфиналистом')
                .toBe('Матч за 7-8 место');
            expect(т.строки[0].этап.trim(), 'первая пара названа не финалом').toBe('Финал');

            /* ОЧКИ ЕСТЬ. Раньше у этой сетки колонки очков не было вовсе. */
            expect(т.строки.map(с => с.очки.trim()),
                'очки в сетке «все места» не те, что в базе')
                .toEqual(['360', '215', '150', '130', '111', '111', '90', '90']);

            expect(т.своихТаблиц, 'под пьедесталом осталась своя таблица мест').toBe(0);
        });

    ЯЗЫКИ.forEach(я => {
        test('три языка — один экран: ' + я.код, async ({ page }) => {
            const олимп = await снятьТаблицу(page, я.стр + '?id=' + ОЛИМПИЙКА);
            expect(олимп.заголовок.trim(), 'заголовок итогов не на своём языке')
                .toBe(я.итог);
            expect(олимп.строки[4].этап.trim(), 'подпись этапа не на своём языке')
                .toBe(я.этапQF);

            const фик = await снятьТаблицу(page, я.стр + '?id=' + ВСЕ_МЕСТА);
            expect(фик.строки[4].этап.trim(), 'матч за места не на своём языке')
                .toBe(я.матч56);
        });
    });

    test('лестница текста: каждый уровень на ступени шкалы',
        async ({ page }, testInfo) => {
            await page.goto(ЯЗЫКИ[0].стр + '?id=' + ОЛИМПИЙКА);
            await page.waitForSelector('.td-results-table', { timeout: 20000 });

            const л = await page.evaluate(() => {
                const снять = сел => {
                    const э = document.querySelector(сел);
                    if (!э) return null;
                    const с = getComputedStyle(э);
                    return { кегль: parseFloat(с.fontSize), вес: parseInt(с.fontWeight, 10),
                             межстрочный: с.lineHeight };
                };
                /* ЛЕСТНИЦА СНИМАЕТСЯ С ОБЫЧНОЙ СТРОКИ. Первая — строка
                   победителя, у неё свой вес, и сравнивать её уровни с
                   уровнями остальных значит сравнивать разное. */
                const обычная = 'tbody tr:not(.td-res-winner)';
                return {
                    заголовок: снять('.td-results-title'),
                    шапка: снять('.td-results-table thead th'),
                    имя: снять('.td-results-table ' + обычная + ' td:nth-child(2)'),
                    место: снять('.td-results-table ' + обычная + ' .td-res-place'),
                    очки: снять('.td-results-table ' + обычная + ' .td-res-pts'),
                    очкиПобедителя: снять('.td-results-table .td-res-winner .td-res-pts')
                };
            });

            /* ШКАЛА КЕГЛЕЙ — 11 · 12 · 14 · 16 · 18 · 21 · 26 · 32 · 40.
               Замораживается ОТНОШЕНИЕ, а не число: проверяем, что каждый
               уровень стоит НА ступени и что уровни не сравнялись, а не то,
               что кегль равен четырнадцати. */
            const ШКАЛА = [11, 12, 14, 16, 18, 21, 26, 32, 40];
            Object.keys(л).forEach(имя => {
                expect(л[имя], 'уровень «' + имя + '» со страницы не снялся').not.toBeNull();
                expect(ШКАЛА.indexOf(л[имя].кегль) !== -1,
                    'кегль уровня «' + имя + '» — ' + л[имя].кегль +
                    ', мимо шкалы, вид ' + testInfo.project.name).toBe(true);
            });

            expect(л.шапка.кегль < л.имя.кегль,
                'шапка таблицы сравнялась со строкой: ' + л.шапка.кегль + ' против ' +
                л.имя.кегль + ', вид ' + testInfo.project.name).toBe(true);
            expect(л.очки.вес > л.имя.вес,
                'очки не выделены весом: ' + л.очки.вес + ' против ' + л.имя.вес).toBe(true);
            expect(л.место.вес >= л.имя.вес,
                'место легче имени, хотя по нему таблицу и читают').toBe(true);
            expect(л.заголовок.вес >= л.шапка.вес,
                'заголовок таблицы легче её шапки').toBe(true);

            /* ПОБЕДИТЕЛЬ НЕ ТЕРЯЕТ ВЕС ТАМ, ГДЕ ЧИСЛО ВАЖНЕЕ ВСЕГО.
               Замер 02.10: `.td-res-winner td` (0,1,1) перебивал
               `.td-res-pts` (0,1,0), и очки победителя шли легче, чем у
               всех остальных. Поймала эта проверка. */
            expect(л.очкиПобедителя.вес >= л.очки.вес,
                'очки победителя легче, чем у остальных: ' + л.очкиПобедителя.вес +
                ' против ' + л.очки.вес + ', вид ' + testInfo.project.name).toBe(true);
        });

    test('на телефоне колонка этапа уходит, а не ломает строку',
        async ({ page }, testInfo) => {
            const т = await снятьТаблицу(page, ЯЗЫКИ[0].стр + '?id=' + ОЛИМПИЙКА);
            const узко = page.viewportSize().width <= 640;

            expect(т.этапВиден, узко
                ? 'на узком виде колонка этапа осталась: при четырёх колонках строка не держится'
                : 'на широком виде колонка этапа пропала').toBe(!узко);

            /* ПОЛОСЫ ПРОКРУТКИ ВБОК У ТАБЛИЦЫ НЕТ НИ НА ОДНОМ ВИДЕ. */
            const вылезла = await page.evaluate(() => {
                const т = document.querySelector('.td-results-table');
                return т.scrollWidth > т.clientWidth + 1;
            });
            expect(вылезла, 'таблица итогов шире своего места на виде ' +
                testInfo.project.name).toBe(false);
        });
});
