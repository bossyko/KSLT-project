// @ts-check
const { test, expect } = require('@playwright/test');

/**
 * КРАСКИ ХОЛСТА ДОХОДЯТ ДО ХОЛСТА. Круг 17 ветки D, находка 96б.
 *
 * ЗАЧЕМ ПРОБА, ЕСЛИ ЕСТЬ СТОРОЖ. `tools/check-kraski-holsta.js` читает
 * ИСХОДНИК: нет ли числа или `var(--…)` внутри `new Chart(…)`. Текст
 * может быть безупречен, а холст остаться пустым — и ровно так и вышло.
 * Прогон нашёл две беды, которых в исходнике не видно:
 *
 *   1 `ticks: { color: '#00BFFF' }` — сторож искал ключи со словом
 *     `Color`, а здесь ключ называется просто `color`. Прибор, читающий
 *     часть имён, не мерит ничего;
 *   2 склейка hex-хвоста `c.color + '38'`. По исходнику безобидна. Но
 *     стоило краске прийти в виде `rgba(...)` — холст отвечает «не
 *     разобрать цвет» и НЕ РИСУЕТ ГРАФИК ЦЕЛИКОМ. Поймано только здесь.
 *
 * ЧИТАЕТСЯ НАРИСОВАННОЕ, А НЕ ЗАДУМАННОЕ: краски берутся у живого
 * объекта Chart после отрисовки, а не из файла.
 *
 * ПЯТЬ ВИДОВ И ТРИ ЯЗЫКА. Краски от языка зависеть не должны — и это
 * проверяется прогоном, а не рассуждением.
 *
 * Стенд `maket/grafiki-krasok-zamer.html` грузит НАСТОЯЩИЙ рисовальщик
 * продукта и подменяет только клиента базы. Базы здесь нет: прогон
 * ничего не пишет и не ест квоту.
 *
 * ПЛАНКИ — ОТНОШЕНИЯ, А НЕ ЧИСЛА:
 *   1 график вообще нарисовался — ни одна краска не уронила отрисовку;
 *   2 ни одна краска не пустая: пустая строка на холсте — прозрачность,
 *     то есть исчезнувший ряд;
 *   3 `var(--…)` в холсте нет: его холст не понимает;
 *   4 дом не жаловался на ненайденный токен;
 *   5 подсказка на обоих графиках говорит ОДНИМ фоном — одно понятие
 *     одним именем;
 *   6 линия категории без своего цвета приглушена, а не прозрачна.
 */

const ЯЗЫКИ = ['ru', 'en', 'kg'];

async function замер(page, язык) {
    const беды = [];
    page.on('pageerror', e => беды.push('pageerror: ' + e.message));
    page.on('console', m => {
        const т = m.text();
        if (m.type() === 'error' && !/Failed to load resource|ERR_/.test(т)) {
            беды.push('console: ' + т);
        }
    });
    await page.goto('/maket/grafiki-krasok-zamer.html?lang=' + язык);
    await page.waitForFunction(() => !!window.ЗАМЕР, null, { timeout: 15000 });
    const з = await page.evaluate(() => window.ЗАМЕР);
    return { з, беды };
}

ЯЗЫКИ.forEach(язык => {
    test('краски холста доходят до холста — ' + язык, async ({ page }) => {
        const { з, беды } = await замер(page, язык);

        expect(беды, 'страница ругается в консоль').toEqual([]);
        expect(з.ошибка, 'рисование упало: ' + (з.стек || '')).toBeUndefined();

        /* 1. нарисовалось. Склейка hex-хвоста валит именно это. */
        expect(з.нарисовалось, 'график не нарисовался').toBe(true);

        /* 2. пустых красок нет: пустая строка = прозрачный ряд */
        expect(з.пустыхКрасок, 'краска пришла пустой — ряд нарисуется прозрачным').toBe(0);

        /* 3. var() в холсте нет: холст его не понимает */
        const вар = з.varВХолсте !== undefined ? з.varВХолсте : з.варВХолсте;
        expect(вар, 'var(--…) в настройках холста — рисуется НИЧЕМ').toBe(0);

        /* 4. дом не жаловался: жалоба значит ненайденный токен */
        expect(з.жалобыДома || [], 'дом красок не нашёл токен').toEqual([]);

        /* 5. подсказка — одно понятие одним именем на двух графиках */
        expect(з.очки.подсказка.фон, 'фон подсказки графика очков').toBeTruthy();
        expect(з.ntrp.подсказка.фон, 'фон подсказки графика NTRP')
            .toBe(з.очки.подсказка.фон);
        expect(з.ntrp.подсказка.тело, 'тело подсказки NTRP')
            .toBe(з.очки.подсказка.тело);

        /* 6. линия категории без своего цвета приглушена, а не прозрачна.
              В стенде у «Мастерс» и «Челленджер» цвета нет — они обязаны
              взять приглушённый текст, а у «Тур» цвет свой и остаётся. */
        const свой = з.очки.ряды.filter(р => /^#/.test(String(р.линия)));
        const безСвоего = з.очки.ряды.filter(р => !/^#/.test(String(р.линия)));
        expect(свой.length, 'ряд со своим цветом из данных').toBeGreaterThan(0);
        expect(безСвоего.length, 'ряд без своего цвета').toBeGreaterThan(0);
        безСвоего.forEach(р => {
            expect(String(р.линия), 'линия без своего цвета должна быть краской')
                .toMatch(/^rgba?\(/);
            expect(String(р.линия), 'линия не должна быть прозрачной')
                .not.toMatch(/,\s*0\s*\)$/);
        });

        /* Подписи осей и сетка — краской, а не пустотой */
        ['x', 'y'].forEach(ось => {
            expect(з.очки.оси[ось].подписи, 'подписи оси ' + ось).toBeTruthy();
        });
    });
});
