/**
 * TC-VHOD-DOM: вход — один дом (кусок A3.7е).
 *
 * `auth.js` был САМЫМ КРУПНЫМ расхождением продукта и последним долгом
 * переписи копий: 2162 строки против 1089. Экраны входа законно разные,
 * а одиннадцать понятий были написаны дважды и трижды — 34 места в
 * четырёх файлах.
 *
 * БАЗУ И СЕРВЕРНЫЕ ФУНКЦИИ ТЕСТ НЕ ЗОВЁТ. `fetch` подменяется на время
 * проверки и возвращается на место; клиент подставной. Так проверяется
 * ровно то, чего не видит заморозка: что уходит в посылке и что дом
 * делает с ответом.
 *
 * ЧТО ИМЕННО ДОКАЗЫВАЕТСЯ — ЧЕТЫРЕ РАСХОЖДЕНИЯ, ЖИВШИЕ В ПРОДУКТЕ:
 *   1. ЛЕСТНИЦА ПОВТОРА 30·60·120·300 против ПЛОСКИХ 60 в приложении:
 *      пять нажатий по минуте — и серверный предел блокировал человека
 *      на четверть часа за то, что письмо шло медленно;
 *   2. ЯЗЫК В `send-otp`: у приложения не уходил вовсе, и сервер не
 *      знал, на каком языке писать — а при регистрации профиля ещё нет,
 *      спросить ему некого;
 *   3. СЛЕПОЙ `r.json()`: на теле вроде `<html>502` человек получал
 *      SyntaxError вместо причины;
 *   4. ЗАШИТЫЙ АДРЕС БАЗЫ в трёх местах приложения с ПУСТЫМ ключом по
 *      умолчанию — молчаливый отказ сервера.
 *
 * ПЯТЬ ВИДОВ приходят из пяти проектов конфига.
 */

const СТРАНИЦЫ = [
    { язык: 'ru', адрес: '/pages/auth.html' },
    { язык: 'en', адрес: '/pages/auth-en.html' },
    { язык: 'kg', адрес: '/pages/auth-kg.html' }
];

const ПРИЛОЖЕНИЕ = '/mobile/www/index.html';

async function дождатьсяДома(page, адрес) {
    const ошибки = [];
    page.on('pageerror', e => ошибки.push(String(e.message || e)));
    await page.goto(адрес, { waitUntil: 'domcontentloaded' });
    try {
        await page.waitForFunction(
            () => window.KSLT_VHOD && typeof window.KSLT_VHOD.проверитьКод === 'function',
            null, { timeout: 20000 });
    } catch (e) {
        throw new Error('дом входа не объявился на ' + адрес +
            ' · ошибки страницы: ' + (ошибки.length ? ошибки.join(' | ') : 'нет'));
    }
    return ошибки;
}

function снятьДом(page) {
    return page.evaluate(async () => {
        const V = window.KSLT_VHOD;

        /* ПОДМЕНА `fetch` НА ВРЕМЯ И ВОЗВРАТ НА МЕСТО. */
        const былFetch = window.fetch;
        let поймано = [];
        const отвечать = (тело, ok, status) => {
            window.fetch = (u, o) => {
                поймано.push({ u: String(u), o: o });
                return Promise.resolve({
                    ok: ok !== false, status: status || 200,
                    text: () => Promise.resolve(тело),
                    json: () => Promise.resolve(JSON.parse(тело))
                });
            };
        };
        const клиент = (токен) => ({
            auth: { getSession: () => Promise.resolve({ data: { session: токен ? { access_token: токен } : null } }) }
        });

        const итог = {};
        try {
            // 1. почта
            итог.почта = {
                годные: ['a@b.co', 'x.y+z@a-b.c.dd'].map(а => V.почтой(а)),
                негодные: ['', 'a@b', 'a@b.c', '@b.co', 'a b@c.co'].map(а => V.почтой(а))
            };

            // 2. хеш и отпечаток — устойчивы и собраны из обозревателя и экрана
            итог.хеш = {
                дваждыОдно: V.хеш('проба') === V.хеш('проба'),
                разноеРазно: V.хеш('a') !== V.хеш('b'),
                отпечатокУстойчив: V.отпечаток() === V.отпечаток(),
                отпечатокСобран: V.отпечаток() ===
                    V.хеш(navigator.userAgent + '|' + screen.width + 'x' + screen.height)
            };

            // 3. ЛЕСТНИЦА — та самая беда приложения
            V.сбросПовтора();
            итог.лестница = {
                ступени: V.ЛЕСТНИЦА_ПОВТОРА.slice(),
                подряд: [V.задержкаПовтора(), V.задержкаПовтора(), V.задержкаПовтора(),
                         V.задержкаПовтора(), V.задержкаПовтора()]
            };
            V.сбросПовтора();
            итог.лестница.послеСброса = V.задержкаПовтора();
            V.сбросПовтора();

            // 4. send-otp: ЯЗЫК УХОДИТ ВСЕГДА
            поймано = []; отвечать('{"ok":true}');
            итог.кодОтправлен = await V.отправитьКод({
                поток: 'register', адресат: 'a@b.co', видАдресата: 'email', язык: 'kg'
            });
            итог.посылкаКода = { u: поймано[0].u, тело: JSON.parse(поймано[0].o.body),
                                 ключ: поймано[0].o.headers.apikey };
            поймано = [];
            await V.отправитьКод({ поток: 'login', адресат: 'a@b.co', видАдресата: 'email' });
            итог.языкПоУмолчанию = JSON.parse(поймано[0].o.body).lang;

            // 5. НЕ-JSON ОТВЕТ: внятная беда вместо SyntaxError
            const былErr = console.error;
            console.error = () => {};
            поймано = []; отвечать('<html>502 Bad Gateway</html>', false, 502);
            итог.неJson = '';
            try {
                await V.отправитьКод({ поток: 'register', адресат: 'a@b.co', видАдресата: 'email', язык: 'ru' });
            } catch (e) {
                итог.неJson = e.message;
            }
            console.error = былErr;

            // 6. verify-otp: поток и приложенное
            поймано = []; отвечать('{"ok":true}');
            await V.проверитьКод('forgot_password', 'a@b.co', '123456', { login_only: true, лишнее: undefined });
            итог.посылкаПроверки = { u: поймано[0].u, тело: JSON.parse(поймано[0].o.body) };

            // 7. карточка игрока: весь ответ и только статус
            поймано = []; отвечать('{"status":"candidate","candidate":{"id":7}}');
            итог.карточкаЦеликом = await V.карточкаИгрока(клиент('TOK'));
            поймано = []; отвечать('{"status":"created","player_id":9}');
            итог.карточкаСтатусом = await V.завестиКарточку(клиент('TOK'));
            поймано = [];
            итог.карточкаБезСессии = { ответ: await V.карточкаИгрока(клиент(null)), зовов: поймано.length };

            // 8. письмо безопасности
            поймано = []; отвечать('{"ok":true}');
            итог.письмо = await V.письмоБезопасности(клиент('TOK'), 'password_changed', { x: 1 });
            итог.посылкаПисьма = { u: поймано[0].u, тело: JSON.parse(поймано[0].o.body),
                                   токен: поймано[0].o.headers.Authorization };
            поймано = [];
            итог.письмоБезТокена = { ответ: await V.письмоБезопасности(клиент(null), 'x'), зовов: поймано.length };

            // 9. адрес базы — ТОЛЬКО из настроек страницы
            итог.адрес = { настройка: window.SUPABASE_URL,
                           вЗове: итог.посылкаПисьма.u.indexOf(window.SUPABASE_URL) === 0 };
        } finally {
            window.fetch = былFetch;
        }
        return итог;
    });
}

function проверить(д) {
    expect(д.почта.годные, 'годные адреса проходят').toEqual([true, true]);
    expect(д.почта.негодные, 'негодные не проходят').toEqual([false, false, false, false, false]);

    expect(д.хеш.дваждыОдно).toBe(true);
    expect(д.хеш.разноеРазно).toBe(true);
    expect(д.хеш.отпечатокУстойчив, 'отпечаток не плывёт между зовами').toBe(true);
    expect(д.хеш.отпечатокСобран, 'отпечаток — обозреватель плюс размер экрана').toBe(true);

    // ТА САМАЯ БЕДА: лестница, а не плоские 60
    expect(д.лестница.ступени).toEqual([30, 60, 120, 300]);
    expect(д.лестница.подряд, 'верхняя ступень держится и дальше')
        .toEqual([30, 60, 120, 300, 300]);
    expect(д.лестница.послеСброса, 'шаг сбрасывается при входе на экран кода').toBe(30);

    // ТА САМАЯ БЕДА: язык уходит всегда
    expect(д.посылкаКода.u).toContain('/functions/v1/send-otp');
    expect(д.посылкаКода.тело).toEqual({
        flow: 'register', identifier: 'a@b.co', identifier_type: 'email', lang: 'kg'
    });
    expect(д.посылкаКода.ключ, 'ключ из настроек, а не пустой').toBeTruthy();
    expect(д.языкПоУмолчанию, 'язык не называли — уходит ru, а не ничего').toBe('ru');

    // ТА САМАЯ БЕДА: не-JSON разбирается вслух
    expect(д.неJson, 'внятная беда вместо SyntaxError').toBe('send-otp: HTTP 502');

    expect(д.посылкаПроверки.u).toContain('/functions/v1/verify-otp');
    expect(д.посылкаПроверки.тело, 'undefined в посылку не кладётся')
        .toEqual({ flow: 'forgot_password', identifier: 'a@b.co', code: '123456', login_only: true });

    expect(д.карточкаЦеликом, 'кабинету нужен весь ответ')
        .toEqual({ status: 'candidate', candidate: { id: 7 } });
    expect(д.карточкаСтатусом, 'трём местам нужен только статус').toBe('created');
    expect(д.карточкаБезСессии.зовов, 'без сессии сервер не зовут вовсе').toBe(0);
    expect(д.карточкаБезСессии.ответ).toBeNull();

    expect(д.письмо).toBe(true);
    expect(д.посылкаПисьма.u).toContain('/functions/v1/security-notify');
    expect(д.посылкаПисьма.тело).toEqual({ event_type: 'password_changed', metadata: { x: 1 } });
    expect(д.посылкаПисьма.токен, 'письмо идёт от имени человека').toBe('Bearer TOK');
    expect(д.письмоБезТокена.зовов, 'без токена не зовут').toBe(0);
    expect(д.письмоБезТокена.ответ).toBe(false);

    // ТА САМАЯ БЕДА: адрес базы только из настроек
    expect(д.адрес.настройка, 'адрес базы объявлен страницей').toBeTruthy();
    expect(д.адрес.вЗове, 'дом зовёт по адресу из настроек, а не по зашитому').toBe(true);
}

test.describe('Вход — один дом', () => {

    for (const с of СТРАНИЦЫ) {
        test('дом доехал до страницы входа · ' + с.язык, async ({ page }) => {
            const ошибки = await дождатьсяДома(page, с.адрес);
            проверить(await снятьДом(page));
            expect(ошибки, 'страница без ошибок').toEqual([]);
        });
    }

    test('дом доехал до приложения — и четыре расхождения там закрыты', async ({ page }) => {
        const ошибки = await дождатьсяДома(page, ПРИЛОЖЕНИЕ);
        проверить(await снятьДом(page));
        expect(ошибки, 'страница без ошибок').toEqual([]);
    });

    test('ни одна страница входа не держит зашитый адрес базы', async ({ page }) => {
        await дождатьсяДома(page, ПРИЛОЖЕНИЕ);
        const свои = await page.evaluate(async () => {
            const пути = ['js/kslt-vhod.js', 'js/auth.js', 'js/tournament-register.js'];
            const найдено = {};
            for (const п of пути) {
                const т = await (await fetch(п)).text();
                найдено[п] = (т.match(/[a-z0-9]{15,}\.supabase\.co/g) || []).length;
            }
            return найдено;
        });
        for (const п of Object.keys(свои)) {
            expect(свои[п], 'зашитый адрес базы в ' + п).toBe(0);
        }
    });
});
