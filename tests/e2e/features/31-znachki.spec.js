const { test, expect } = require('../../fixtures');

/**
 * TC-ZNACHKI: значки у имени — один дом.
 *
 * ЧТО БЫЛО, ИЗМЕРЕНО ЧТЕНИЕМ. На сайте значки у имени в рейтинге живут
 * давно (`js/players.js`), в приложении на экране рейтинга их НЕ БЫЛО
 * ВОВСЕ — ноль упоминаний на 444 строки.
 *
 * ЧТО ДЕРЖИТ СТОРОЖ, А ЧТО ЗДЕСЬ. Сторож читает файлы: он видит, что
 * дом один, что копия побайтовая и что оба продукта его зовут. Он НЕ
 * ВИДИТ, сколько значков дом отдаст, в каком порядке их просит у базы и
 * что будет, если база откажет. Это работа прогона.
 *
 * БАЗУ ТЕСТ НЕ ЗОВЁТ: клиент подставной, и ОН ЖЕ записывает, какие
 * запросы у него спросили — так проверяется, что порядок задаёт БАЗА
 * (`order('earned_at', { ascending: true })`), а не мы.
 *
 * ОТДЕЛЬНО ПРОВЕРЯЕТСЯ БРОСОК НА МЕСТЕ. `client.from(...)` может
 * бросить СРАЗУ, и `.catch` такого не ловит — он ловит только отказ уже
 * созданного обещания. Нашёл это свой же тест, и без обёртки `try` один
 * сбой базы ронял бы весь экран рейтинга, а не значки.
 */

const СТРАНИЦЫ = [
    { язык: 'ru', адрес: '/pages/players.html' },
    { язык: 'en', адрес: '/pages/players-en.html' },
    { язык: 'kg', адрес: '/pages/players-kg.html' }
];

const ПРИЛОЖЕНИЕ = '/mobile/www/index.html';

async function дождаться(page, адрес) {
    const ошибки = [];
    page.on('pageerror', e => ошибки.push(String(e.message || e)));
    await page.goto(адрес, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(
        () => window.KSLT_ZNACHKI && typeof window.KSLT_ZNACHKI.загрузить === 'function',
        null, { timeout: 20000 });
    return ошибки;
}

function снять(page) {
    return page.evaluate(async () => {
        const Z = window.KSLT_ZNACHKI;
        const итог = {};

        /* Подставной клиент. Он же ведёт список того, о чём его
           спросили: имена таблиц, столбцы и порядок. */
        const спросили = [];
        const клиент = (ответы, бросать) => ({
            from: function (таблица) {
                if (бросать) throw new Error('связи нет');
                спросили.push({ таблица: таблица });
                const цепь = {
                    select: function (столбцы) {
                        спросили[спросили.length - 1].столбцы = столбцы;
                        const обещание = Promise.resolve({ data: ответы[таблица] || [] });
                        /* ПОРЯДОК СПРАШИВАЮТ НЕ У ВСЕХ ТАБЛИЦ, поэтому
                           `order` висит на самом обещании: у кого
                           спросили — тот и запишется. */
                        обещание.order = function (поле, как) {
                            спросили[спросили.length - 1].порядок = { поле: поле, как: как };
                            return Promise.resolve({ data: ответы[таблица] || [] });
                        };
                        return обещание;
                    }
                };
                return цепь;
            }
        });

        const ОПРЕДЕЛЕНИЯ = [
            { id: 'b1', icon: '🏆', name: 'Чемпион', name_en: 'Champion', name_kg: 'Чемпион KG' },
            { id: 'b2', icon: '🔥', name: 'Серия', name_en: 'Streak' },
            { id: 'b3', icon: '⭐', name: 'Звезда' }
        ];
        /* Шесть значков одному игроку — чтобы увидеть, что шестой не
           доходит до строки. Порядок здесь НАРОЧНО «как пришло из
           базы»: сортировать должна база. */
        const ЗНАЧКИ = [
            { player_id: 'P1', badge_id: 'b1', badge: { icon: '🏆' } },
            { player_id: 'P1', badge_id: 'b2', badge: { icon: '🔥' } },
            { player_id: 'P1', badge_id: 'b3', badge: { icon: '⭐' } },
            { player_id: 'P1', badge_id: 'b1', badge: { icon: '🏆' } },
            { player_id: 'P1', badge_id: 'b2', badge: { icon: '🔥' } },
            { player_id: 'P1', badge_id: 'b3', badge: null },
            { player_id: 'P2', badge_id: 'b1', badge: { icon: '🏆' } }
        ];

        итог.сколько = Z.СКОЛЬКО;

        const слепок = await Z.загрузить(клиент({
            badge_definitions: ОПРЕДЕЛЕНИЯ,
            player_badges: ЗНАЧКИ
        }));
        итог.спросили = спросили.slice();
        итог.определений = Object.keys(слепок.определения).length;
        итог.уP1 = (слепок.поИгрокам['P1'] || []).length;
        итог.уP2 = (слепок.поИгрокам['P2'] || []).length;
        итог.первыеP1 = Z.первые(слепок, 'P1').map(з => з.badge_id);
        итог.первыеДва = Z.первые(слепок, 'P1', 2).map(з => з.badge_id);
        итог.неизвестный = Z.первые(слепок, 'НЕТ-ТАКОГО');
        итог.пустойЗначок = Z.первые(слепок, 'P1', 6).map(з => з.icon);

        итог.имена = {
            ru: Z.название(слепок, 'b1', 'ru'),
            en: Z.название(слепок, 'b1', 'en'),
            kg: Z.название(слепок, 'b1', 'kg'),
            безKg: Z.название(слепок, 'b2', 'kg'),
            безОпределения: Z.название(слепок, 'b9', 'ru')
        };

        /* БЕЗ КЛИЕНТА — пустой слепок, а не бросок. */
        const пусто = await Z.загрузить(null);
        итог.безКлиента = { игроков: Object.keys(пусто.поИгрокам).length,
                            определений: Object.keys(пусто.определения).length };

        /* БРОСОК НА МЕСТЕ: `from` кидает сразу. */
        let упало = false;
        let слепокСбоя = null;
        try {
            слепокСбоя = await Z.загрузить(клиент({}, true));
        } catch (e) { упало = true; }
        итог.бросок = { упало: упало,
                        игроков: слепокСбоя ? Object.keys(слепокСбоя.поИгрокам).length : -1 };

        return итог;
    });
}

function проверить(д) {
    expect(д.сколько, 'пять — замер строки рейтинга, шестой выдавливает очки').toBe(5);

    expect(д.спросили.length, 'два запроса, а не по запросу на игрока').toBe(2);
    expect(д.спросили[0].таблица).toBe('badge_definitions');
    expect(д.спросили[1].таблица).toBe('player_badges');
    expect(д.спросили[1].столбцы, 'значок берётся вместе со своим icon')
        .toContain('badge:badge_definitions(icon)');
    expect(д.спросили[1].порядок, 'ПОРЯДОК ЗАДАЁТ БАЗА, иначе два продукта отсортируют по-разному')
        .toEqual({ поле: 'earned_at', как: { ascending: true } });

    expect(д.определений).toBe(3);
    expect(д.уP1, 'слепок держит всё, что отдала база').toBe(6);
    expect(д.уP2).toBe(1);

    expect(д.первыеP1, 'в строку идут первые пять, шестой не доходит')
        .toEqual(['b1', 'b2', 'b3', 'b1', 'b2']);
    expect(д.первыеДва, 'сколько просят — столько и отдают').toEqual(['b1', 'b2']);
    expect(д.неизвестный, 'у игрока без значков — пусто, а не падение').toEqual([]);
    expect(д.пустойЗначок[5], 'значок без определения даёт пустую строку, а не undefined').toBe('');

    expect(д.имена.ru).toBe('Чемпион');
    expect(д.имена.en).toBe('Champion');
    expect(д.имена.kg).toBe('Чемпион KG');
    expect(д.имена.безKg, 'нет кыргызского — берётся общее имя, а не номер').toBe('Серия');
    expect(д.имена.безОпределения, 'нет определения — номер: пустая подсказка хуже непонятной')
        .toBe('b9');

    expect(д.безКлиента, 'без клиента — пустой слепок, а не бросок')
        .toEqual({ игроков: 0, определений: 0 });

    expect(д.бросок.упало, 'БРОСОК НА МЕСТЕ не выходит наружу: значки — украшение списка')
        .toBe(false);
    expect(д.бросок.игроков, 'при сбое базы список рисуется без значков').toBe(0);
}

test.describe('Значки у имени — один дом', () => {

    for (const с of СТРАНИЦЫ) {
        test('рейтинг сайта · ' + с.язык, async ({ page }) => {
            const ошибки = await дождаться(page, с.адрес);
            проверить(await снять(page));
            expect(ошибки, 'страница без ошибок').toEqual([]);
        });
    }

    test('в приложении то же самое — а до этого куска значков там не было вовсе',
        async ({ page }) => {
            const ошибки = await дождаться(page, ПРИЛОЖЕНИЕ);
            проверить(await снять(page));
            expect(ошибки, 'страница без ошибок').toEqual([]);
        });

    test('экран рейтинга приложения зовёт дом, а не считает значки сам', async ({ page }) => {
        await дождаться(page, ПРИЛОЖЕНИЕ);
        const найдено = await page.evaluate(async () => {
            const т = await (await fetch('js/screens/rating.js')).text();
            const безКом = т.replace(/\/\*[\s\S]*?\*\//g, ' ')
                            .replace(/(^|[^:])\/\/[^\n]*/g, '$1 ');
            return {
                зовов: (безКом.match(/KSLT_ZNACHKI\./g) || []).length,
                своихПорядков: (безКом.match(/earned_at/g) || []).length,
                своихЧисел: (безКом.match(/slice\(0,\s*5\)/g) || []).length
            };
        });
        expect(найдено.зовов, 'экран рейтинга зовёт дом').toBeGreaterThan(0);
        expect(найдено.своихПорядков, 'своего порядка по earned_at у экрана нет').toBe(0);
        expect(найдено.своихЧисел, 'своего «пять» у экрана нет').toBe(0);
    });
});
