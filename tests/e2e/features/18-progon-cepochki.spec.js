// @ts-check
const { test, expect } = require('@playwright/test');

/**
 * ПРОГОН ЦЕПОЧКИ ЭТАПОВ — все годные настройки турнира, от жеребьёвки до
 * плей-офф, на НАСТОЯЩИХ функциях продукта.
 *
 * Вопрос Кости 30.09: дублей нет; групповой этап отражён целиком прежде, чем
 * появятся доп. матчи; потом плей-офф; и ручная правка с перестановкой мест
 * остаются рабочими.
 *
 * Стенд `maket/progon-cepochki.html` поднимает админку с ПИШУЩЕЙ заглушкой
 * базы. Заглушка умеет ровно те двенадцать обращений, что померены на этом
 * пути, и ПАДАЕТ на любом другом: прибор, который угадывает, проверяет
 * выдумку, а не продукт. Базы здесь нет, квота не тратится.
 *
 * ВИД ОДИН — ДЕСКТОП, И ЭТО СКАЗАНО ВСЛУХ. Здесь меряется логика этапов, а
 * не вёрстка: ни одного размера, цвета и отступа тест не трогает. Гонять
 * одно и то же на пяти видах значило бы впятеро дольше повторять один и тот
 * же ответ. ЯЗЫК ОДИН — РУССКИЙ: админка одноязычная.
 */

const ДОЛГО = 20 * 60 * 1000;

test.describe('прогон цепочки этапов', () => {
    test.beforeEach(({}, инфо) => {
        test.skip(инфо.project.name !== 'desktop',
            'логика этапов от ширины окна не зависит: меряем один раз, на десктопе');
    });

    test('все годные настройки: группы полны, порядок этапов держится, дублей нет', async ({ page }) => {
        test.setTimeout(ДОЛГО);

        const беды = [];
        page.on('pageerror', e => беды.push('pageerror: ' + e.message));
        page.on('console', m => {
            const т = m.text();
            if (m.type() === 'error' && !/Failed to load resource|ERR_/.test(т)) беды.push('console: ' + т);
        });

        await page.goto('/maket/progon-cepochki.html');
        await expect(page.locator('#progonGotov')).toHaveText('прогон готов', { timeout: 15000 });

        const настройки = await page.evaluate(() => window.ПРОГОН.годныеНастройки(45));
        expect(настройки.length, 'годных настроек стало меньше — судья настроек изменился').toBeGreaterThan(1000);

        const грязные = [];
        let сIG = 0, земляки = 0, свопДоехал = 0;

        for (const н of настройки) {
            const и = await page.evaluate(async (н) => {
                try { return await window.ПРОГОН.одинРасклад(н); }
                catch (e) { return { настройка: н, находки: ['ИСКЛЮЧЕНИЕ: ' + (e && e.message)], числа: {} }; }
            }, н);
            if (и.находки.length) грязные.push(JSON.stringify(и.настройка) + ' → ' + и.находки.join(' · '));
            if (и.числа.допМатчей > 0) сIG++;
            if (и.числа.земляковВПервомКруге > 0) земляки++;
            if (и.числа.перестановкаДоехала === true) свопДоехал++;
            if (грязные.length >= 8) break;
        }

        console.log('прогон: настроек ' + настройки.length + ' · с доп. матчами ' + сIG +
                    ' · с земляками в первом круге ' + земляки + ' · перестановка доехала ' + свопДоехал);

        expect(грязные, 'прогон цепочки нашёл беду:\n' + грязные.join('\n')).toEqual([]);
        expect(свопДоехал, 'ручная перестановка мест перестала доезжать до сетки').toBe(настройки.length);
        expect(сIG, 'ни одна настройка не породила доп. матчей — прогон перестал доходить до отбора').toBeGreaterThan(100);
        expect(беды, 'страница прогона ругалась в консоль').toEqual([]);
    });

    test('двадцать пятая группа — отказ, а не молчаливое число', async ({ page }) => {
        await page.goto('/maket/progon-cepochki.html');
        await expect(page.locator('#progonGotov')).toHaveText('прогон готов', { timeout: 15000 });

        const о = await page.evaluate(() => {
            const R = window.KSLT_RULES;
            return {
                букв: R.БУКВЫ_ГРУПП.length,
                естьI: R.БУКВЫ_ГРУПП.indexOf('I'),
                естьQ: R.БУКВЫ_ГРУПП.indexOf('Q'),
                двадцатьПятая: R.бедаНастройкиГрупп(R.БУКВЫ_ГРУПП.length + 1, 2, 100),
                последняя: R.бедаНастройкиГрупп(R.БУКВЫ_ГРУПП.length, 2, 100),
                буква9: R.букваГруппы(9),
                обратно9: R.группаПоБукве(R.букваГруппы(9)),
                вне: R.букваГруппы(R.БУКВЫ_ГРУПП.length + 1)
            };
        });

        expect(о.естьI, 'буква I вернулась в алфавит групп — метка IG станет неразличимой').toBe(-1);
        expect(о.естьQ, 'буква Q вернулась в алфавит групп — она занята добором').toBe(-1);
        expect(о.двадцатьПятая, 'группа за пределами алфавита больше не отказ').toBe('групп_много');
        expect(о.последняя, 'последняя группа алфавита перестала быть годной').toBeNull();
        expect(о.вне, 'буква вне таблицы снова возвращает не-null — молчаливое число и было бедой').toBeNull();
        expect(о.обратно9, 'перевод туда и обратно разошёлся').toBe(9);
        expect(typeof о.буква9, 'метка девятой группы снова не строка').toBe('string');
    });
});
