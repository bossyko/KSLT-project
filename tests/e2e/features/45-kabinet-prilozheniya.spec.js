const fs = require('fs');
const path = require('path');
const { test, expect } = require('../../fixtures');
const { playerState } = require('../../auth-setup');

const ПРИЛОЖЕНИЕ = '/mobile/www/index.html';

/* ── РАЗДЕЛЫ КАБИНЕТА ЧИТАЮТСЯ ИЗ ЭКРАНА ПРОФИЛЯ ── */
const ЭКРАН = path.join(__dirname, '..', '..', '..',
    'mobile', 'www', 'js', 'screens', 'profile.js');

/* ПИШЕТ В БАЗУ — НЕ НАЖИМАЕМ. Удаление аккаунта разбирается чтением кода
   (`pages/delete-account.html`, кусок 204), а не нажатием в прогоне. */
const НЕ_НАЖИМАЕМ = { profDeleteRow: 'удаляет аккаунт — пишет в базу' };

const РАЗДЕЛЫ = (function () {
    const текст = fs.readFileSync(ЭКРАН, 'utf8');
    const найдено = (текст.match(/bindRowClick\('([a-zA-Z]+)'/g) || [])
        .map(с => с.replace(/bindRowClick\('/, '').replace(/'/, ''));
    if (найдено.length < 12) {
        throw new Error('разделов кабинета прочитано ' + найдено.length +
            ' — список не прочитан, проверь `bindRowClick` в ' + ЭКРАН);
    }
    return найдено.filter(и => !НЕ_НАЖИМАЕМ[и]);
})();

/* НАЖАТИЕ СКВОЗЬ ПОМЕХИ переехало в общий помощник: той же помехой легла
   проба 46, и второй копии приёма быть не должно. */
const { нажатьСквозьПомехи } = require('../pomoshniki/nazhatie');

async function открытьКабинет(page) {
    /* ОТМЕТКА ЗНАКОМСТВА — ДО ПЕРВОЙ ЗАГРУЗКИ, иначе окно успевает встать
       поверх приложения и забрать себе все нажатия. */
    await page.addInitScript(() => {
        try { localStorage.setItem('kslt_onboarding_done', '1'); } catch (e) {}
    });
    const ошибки = [];
    page.on('pageerror', e => ошибки.push(String(e.message || e)));
    await page.goto(ПРИЛОЖЕНИЕ, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(() => !!window.KSLT_OKNO, null, { timeout: 20000 });
    /* ЗНАКОМСТВО ЗАКРЫВАЕТСЯ НАЖАТИЕМ, А НЕ СОКРЫТИЕМ.

       ТРИ ЗАХОДА ПОДРЯД УПАЛИ ИМЕННО ЗДЕСЬ, и увидел я это только глазами,
       на снимке: поверх приложения стояло окно «Добро пожаловать!» с
       кнопками «Далее» и «Пропустить». Оно ловило каждый клик, и нажатие
       на раздел профиля уходило в него.

       Я ПИСАЛ СВОЙ ПРИЁМ ВМЕСТО ГОТОВОГО: проба светлой темы закрывает
       знакомство нажатием `.onb-skip` до трёх раз и только ПОТОМ прячет
       остатки. Я скопировал вторую половину и выбросил первую.
       ПРОЦЕДУРА, НАПИСАННАЯ ЗАНОВО ВМЕСТО ГОТОВОЙ, ПОВТОРЯЕТ ЕЁ ОШИБКИ —
       а эта готовая была написана ровно потому, что на знакомстве уже
       попался прибор снимков. */
    /* ПРОВЕРКА НАЛИЧИЯ ДО ПОЯВЛЕНИЯ — ЭТО ВЫХОД ИЗ ЦИКЛА, А НЕ ПРОПУСК.
       Кнопку «Пропустить» рисует js ПОСЛЕ заставки (1500–2000 мс), а цикл
       спрашивал `.count()` сразу — получал ноль и выходил. Знакомство
       появлялось следом и ловило все нажатия: четвёртый заход лёг об него
       так же, как три предыдущих.

       ЗНАКОМСТВО — ЭТО СОСТОЯНИЕ, А НЕ ОКНО: приложение помнит отметку
       `kslt_onboarding_done`. Наш игрок не новичок, и отметка ставится ДО
       первой загрузки — тогда знакомству неоткуда взяться вовсе.
       Нажатие оставлено вторым путём, на случай чужой редакции. */
    for (let i = 0; i < 3; i++) {
        const к = page.locator('.onb-skip:visible').first();
        if (!(await к.count())) break;
        await к.click({ timeout: 2000 }).catch(() => {});
        await page.waitForTimeout(300);
    }
    await page.evaluate(() => {
        ['.onb-overlay', '.splash-overlay', '#onboarding'].forEach(с =>
            document.querySelectorAll(с).forEach(э => { э.style.display = 'none'; }));
    });
    /* ПЕРЕКЛЮЧЕНИЕ КЛАССОМ — НЕ ПЕРЕХОД: кабинет рисует
       `KSLT_PROFILE.load()`, которого зовёт `switchScreen` через
       `loadScreen`. Поэтому нажимаем кнопку раздела, как человек.

       НО КНОПКА РАБОТАЕТ НЕ С ПЕРВОГО КАДРА. Второй заход 09.11 упал так
       же: снимок показал ГЛАВНЫЙ экран — клик случился раньше, чем
       `app.js` навесил обработчики табов. НАЖАТИЕ ДО ОСНАСТКИ — ЭТО НЕ
       НАЖАТИЕ, и ждать надо ПРИЗНАК готовности, а не время. */
    await page.waitForFunction(
        () => !!(window.KSLT_APP && window.KSLT_APP.switchScreen),
        null, { timeout: 20000 });

    /* ЭКРАН ВХОДА ОТКРЫТ В РАЗМЕТКЕ ПО УМОЛЧАНИЮ (`index.html:436`), а
       снимается ТОЛЬКО ПОСЛЕ ОТВЕТА БАЗЫ о сессии (`auth.js:34`,
       `checkSession`). До ответа он лежит поверх всего и забирает нажатия:
       пятый заход висел 90 секунд на клике по вкладке, и браузер прямо
       назвал виновника — `DIV.auth-screen open` под точкой нажатия.

       ЭТО И ЕСТЬ НАСТОЯЩИЙ ПРИЗНАК ВХОДА: пока экран входа не ушёл, мы не
       вошли, сколько бы сессия ни лежала в хранилище. Ждём его, а не время,
       и говорим внятно, если не дождались. */
    await page.waitForFunction(() => {
        const э = document.querySelector('.auth-screen');
        return !э || !э.classList.contains('open');
    }, null, { timeout: 30000 }).catch(async () => {
        const с = await page.evaluate(() => ({
            сессия: Object.keys(localStorage).some(к => /^sb-.*-auth-token$/.test(к)),
            пользователь: !!(window.AUTH && window.AUTH.currentUser),
            база: !!window.KSLT_DB,
        }));
        throw new Error('экран входа не ушёл за 30 с. Сессия в хранилище: ' +
            с.сессия + ', пользователь в доме: ' + с.пользователь +
            ', адрес базы подставлен: ' + с.база);
    });

    /* ПОЗДРАВЛЕНИЕ — ЭТО ОЧЕРЕДЬ, А НЕ ОКНО. Войдя, тестовый игрок получает
       поздравления с достижениями: на снимке падения стояло «НОВОЕ
       ДОСТИЖЕНИЕ — Первый матч» и подпись «осталось ещё 2». Они лежат
       поверх всего и забирают нажатия — клик по вкладке висел 90 секунд.
       Это не беда продукта, а состояние аккаунта: так и встретит человека,
       у которого достижения накопились. Закрываем ВСЮ очередь, как он. */
    for (let i = 0; i < 12; i++) {
        const кнопка = page.locator('.ach-btn:visible').first();
        if (!(await кнопка.count())) break;
        await кнопка.click({ timeout: 3000 }).catch(() => {});
        await page.waitForTimeout(450);
    }
    /* ПРИЗНАК, ЧТО ОЧЕРЕДЬ КОНЧИЛАСЬ: карточки поздравления больше нет. */
    await page.waitForFunction(
        () => !document.querySelector('.ach-card'),
        null, { timeout: 15000 }).catch(() => {});

    /* ПОМЕХИ — ЭТО РАССКАЗ, А НЕ ПАДЕНИЕ. Первая редакция клала их в тот
       же массив `ошибки`, который проверяется на пустоту: собственная
       диагностика уронила пробу, хотя кабинет открылся.
       ПРИБОР, ПИШУЩИЙ В ПРОВЕРЯЕМОЕ, ПЕРЕСТАЁТ БЫТЬ ПРИБОРОМ. */
    const помехи = await нажатьСквозьПомехи(page,
        '.tab-item[data-screen="screenProfile"]');
    if (помехи.length) console.log('помехи на пути к вкладке: ' + помехи.join(' | '));
    /* ПРИЗНАК ПЕРЕХОДА — САМ ЭКРАН, А НЕ ПРОШЕДШЕЕ ВРЕМЯ. */
    await page.waitForFunction(() => {
        const э = document.getElementById('screenProfile');
        return !!э && э.classList.contains('active');
    }, null, { timeout: 20000 });
    return ошибки;
}

/* ОБХОД ШЕСТНАДЦАТИ РАЗДЕЛОВ ДОЛЬШЕ ОБЫЧНОЙ ПРОБЫ: каждый раздел ходит в
   базу. Запас взят такой же, как у других проб за входом. */
/* ЗАПАС ПОДНЯТ 90 -> 150 с. К обходу шестнадцати разделов прибавилась
   расчистка пути: экран входа плюс очередь поздравлений — до четырёх
   закрытий по 450 мс, и каждое ждёт ответа базы. Прогон 10.11 лёг в
   тайм-аут на самом обходе, уже ВОЙДЯ в кабинет. */
test.describe.configure({ timeout: 150000 });

test.use({ storageState: playerState });

test.describe('Кабинет приложения — под живым входом', () => {

    /* ══ СНИМОК СОСТОЯНИЯ: ОДИН ПРОГОН — ВСЯ КАРТИНА ═══════════════════
       Этот тест НИЧЕГО НЕ ТРЕБУЕТ и не падает. Он печатает, что на самом
       деле происходит в кабинете, и существует по одной причине: проверить
       пробу своими руками я не могу — тестовая база недоступна из моего
       окружения, и каждая догадка стоит Косте прогона. Шесть прогонов
       ушло на то, что один такой снимок показал бы сразу.
       ПРОБА, КОТОРУЮ НЕЛЬЗЯ ПРОВЕРИТЬ САМОМУ, ОБЯЗАНА РАССКАЗЫВАТЬ. */
    test('@снимок состояние кабинета', async ({ page }) => {
        const ошибки = await открытьКабинет(page).catch(e => ['СОРВАЛОСЬ: ' + e.message]);
        const о = await page.evaluate((разделы) => {
            const есть = и => !!document.getElementById(и);
            const экран = document.getElementById('screenProfile');
            return {
                сессия: Object.keys(localStorage).some(к => /^sb-.*-auth-token$/.test(к)),
                пользователь: !!(window.AUTH && window.AUTH.currentUser),
                экранВхода: !!document.querySelector('.auth-screen.open'),
                поздравление: !!document.querySelector('.ach-card'),
                профильАктивен: !!(экран && экран.classList.contains('active')),
                текстаВкабинете: экран ? экран.textContent.trim().length : 0,
                строкиЕсть: разделы.filter(есть),
                строкиНет: разделы.filter(и => !есть(и)),
                окон: document.querySelectorAll('.td-overlay, .gi-overlay').length,
            };
        }, РАЗДЕЛЫ).catch(e => ({ сорвалось: e.message }));

        console.log('\n──── СОСТОЯНИЕ КАБИНЕТА ────');
        console.log(JSON.stringify(о, null, 1));
        console.log('ошибок страницы: ' + (Array.isArray(ошибки) ? ошибки.length : '?'));
        if (Array.isArray(ошибки) && ошибки.length) console.log(ошибки.slice(0, 5).join('\n'));
        console.log('────────────────────────────\n');
    });


    test('кабинет не пуст: вход виден и разделы нарисованы', async ({ page }) => {
        const ошибки = await открытьКабинет(page);

        /* ПРИЗНАК, А НЕ ТИШИНА СЕТИ: ждём саму строку кабинета. */
        /* ЕСЛИ СТРОК НЕТ — СКАЗАТЬ, ВОШЛИ ЛИ: иначе падение молчит о том,
           что проверять дальше, и разбор начинается с нуля. */
        const вход = await page.evaluate(() => ({
            сессия: Object.keys(localStorage).some(к => /^sb-.*-auth-token$/.test(к)),
            пользователь: !!(window.AUTH && window.AUTH.currentUser),
        }));
        await page.waitForSelector('#' + РАЗДЕЛЫ[0], { timeout: 20000 })
            .catch(() => { throw new Error('строк кабинета нет. Сессия в хранилище: ' +
                вход.сессия + ', пользователь в доме: ' + вход.пользователь); });

        const снимок = await page.evaluate((разделы) => {
            const нет = разделы.filter(и => !document.getElementById(и));
            const п = document.getElementById('screenProfile');
            return {
                нет,
                строк: разделы.length - нет.length,
                естьИмя: !!(п && п.querySelector('.profile-avatar, .profile-name')),
                пусто: !!(п && п.textContent.trim().length < 40),
            };
        }, РАЗДЕЛЫ);

        expect(снимок.нет, 'все разделы кабинета нарисованы').toEqual([]);
        expect(снимок.естьИмя, 'в шапке кабинета виден вошедший').toBe(true);
        expect(снимок.пусто, 'кабинет не пуст — ровно это и случилось 02.11').toBe(false);
        expect(ошибки, 'страница без ошибок').toEqual([]);
    });

    test('каждый раздел открывается и получает оснастку окна', async ({ page }) => {
        const ошибки = await открытьКабинет(page);
        await page.waitForSelector('#' + РАЗДЕЛЫ[0], { timeout: 20000 });

        const итог = [];
        for (const ид of РАЗДЕЛЫ) {
            const строка = page.locator('#' + ид);
            if (!(await строка.count())) { итог.push({ ид, беда: 'строки нет' }); continue; }
            await строка.click();
            await page.waitForTimeout(900);
            итог.push(await page.evaluate(() => {
                const окно = [...document.querySelectorAll('.td-overlay, .gi-overlay, .bottom-sheet-overlay')]
                    .filter(э => э.classList.contains('open')).pop();
                if (!окно) return { беда: 'окно не открылось' };
                const тело = окно.querySelector('.prof-sub-content') || окно;
                const о = {
                    роль: окно.getAttribute('role'),
                    подпись: окно.getAttribute('aria-label') || окно.getAttribute('aria-labelledby'),
                    /* СПИННЕР, ОСТАВШИЙСЯ НАВСЕГДА, — ЭТО ПУСТОЙ РАЗДЕЛ,
                       а не загрузка: 900 мс хватает и на отказ. */
                    толькоСпиннер: !!тело.querySelector('.spinner') && тело.textContent.trim().length < 2,
                };
                document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }));
                return о;
            }));
            await page.waitForTimeout(350);
        }

        const неОткрылись = РАЗДЕЛЫ.filter((_, i) => итог[i] && итог[i].беда);
        const безРоли = РАЗДЕЛЫ.filter((_, i) => итог[i] && !итог[i].беда && итог[i].роль !== 'dialog');
        const безИмени = РАЗДЕЛЫ.filter((_, i) => итог[i] && !итог[i].беда && !итог[i].подпись);
        const висятСпиннером = РАЗДЕЛЫ.filter((_, i) => итог[i] && итог[i].толькоСпиннер);

        expect(неОткрылись, 'каждый раздел кабинета открывается').toEqual([]);
        expect(безРоли, 'диктору сказано, что это окно').toEqual([]);
        expect(безИмени, 'у окна раздела есть имя для диктора').toEqual([]);
        expect(висятСпиннером, 'раздел показал содержимое, а не вечный спиннер').toEqual([]);
        expect(ошибки, 'страница без ошибок').toEqual([]);
    });

    /* ЗА ВХОДОМ КОНТРАСТ НЕ МЕРИЛИ НИ РАЗУ. Проба светлой темы проверяет
       четыре состояния — всё, что видно ГОСТЮ. Половина продукта осталась
       непомеренной, и в ней же сидит известное 3.95 у личных встреч. */
    for (const тема of ['light', 'dark']) {
        test(`${тема}: надписи кабинета не ниже планки`, async ({ page }) => {
            await page.addInitScript(т => {
                try { localStorage.setItem('kslt-tema', т); } catch (e) {}
            }, тема);
            const ошибки = await открытьКабинет(page);
            await page.waitForSelector('#' + РАЗДЕЛЫ[0], { timeout: 20000 });

            const р = await page.evaluate(
                async () => (await import('/tools/kontrast.mjs')).замер(99));
            expect(Array.isArray(р.худшие),
                'модуль контраста отдал список: ключи ' + Object.keys(р).join(', ')).toBe(true);

            const список = р.худшие.map(о =>
                `  ${о.путь} «${о.текст}» — ${о.контраст} при ${о.порог} (${о.кегль}px)`).join('\n');
            expect(р.худшие.length,
                `надписи кабинета ниже планки в теме «${тема}»:\n${список}`).toBe(0);
            expect(ошибки, 'страница без ошибок').toEqual([]);
        });
    }
});
