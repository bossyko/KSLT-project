// @ts-check
const { test, expect, открытьЗакрытую } = require('../../fixtures');

/**
 * СОТРУДНИКУ КАБИНЕТ ИГРОКА НЕ ОТКРЫВАЕТСЯ (кусок «вход админа», 07.11).
 *
 * ЧТО ДЕРЖИТ ЭТА ПРОБА И ЧЕГО НЕ МОЖЕТ СТОРОЖ.
 * `tools/check-kabinet-ne-sotrudniku.js` читает файлы как текст: он видит,
 * что дверь написана, что роль берётся из базы, что увод стоит раньше
 * показа. Чего он не видит — ОКАЗЫВАЕТСЯ ЛИ сотрудник в админке. Между
 * правильным текстом и правильным поведением лежат охрана на `load`, три
 * сетевых запроса и порядок подключения скриптов; всё это решается только
 * настоящим бегунком. ЗАМОРОЗКА НЕ ЗАМЕНЯЕТ НИ ТЕСТЫ, НИ ГЛАЗА.
 *
 * ПОЧЕМУ ТРИ РЕДАКЦИИ, А НЕ ОДНА. Решение 27.02 отменялось ТРЕМЯ разными
 * путями, и один из них — переключатель языка внутри кабинета: закрыть
 * русскую редакцию и оставить открытыми английскую с кыргызской значит
 * починить треть беды. ПРОБА ВИДИТ ТОЛЬКО ТО, ЧТО ЕСТЬ В ДАННЫХ — поэтому
 * перечислены все три.
 *
 * ПОЧЕМУ `waitForURL`, А НЕ `открытьЗакрытую`. Дом ждёт `body.auth-ready`
 * на ТОЙ ЖЕ странице, а здесь продукт обязан УВЕСТИ на другую: признак,
 * которого мы ждём, — смена адреса. ТЕСТ ЖДЁТ ПРИЗНАК, А НЕ ТИШИНУ СЕТИ.
 *
 * ПЯТЬ ВИДОВ дают проекты `playwright.config.js` — свой `viewport` проба
 * не ставит: ВИД МЕРЯЕТСЯ ЗАГРУЗКОЙ НА НУЖНОЙ ШИРИНЕ, и загрузку делает
 * бегунок.
 */

const РЕДАКЦИИ = ['dashboard.html', 'dashboard-en.html', 'dashboard-kg.html'];
const В_АДМИНКЕ = /\/pages\/admin\.html(\?|#|$)/;

test.describe('сотрудник: кабинета игрока нет', () => {
    test.use({ storageState: require('../../auth-setup').adminState });

    for (const редакция of РЕДАКЦИИ) {
        test(`кабинет ${редакция} уводит сотрудника в админку`, async ({ page }) => {
            await page.goto('/pages/' + редакция, { waitUntil: 'domcontentloaded' });
            await page.waitForURL(В_АДМИНКЕ, { timeout: 20000 });
            expect(page.url(), 'сотрудник оказался в админке, а не в кабинете')
                .toMatch(В_АДМИНКЕ);
        });
    }

    /* ГЛАВНОЕ ЧИСЛО КУСКА. Ровно этим путём беда и приходила к Косте:
       охрана ставит `?return=` на любую защищённую страницу, и вход
       возвращал админа в кабинет, роль не глядя. */
    test('обратный адрес в кабинет сотруднику не возвращается', async ({ page }) => {
        await page.goto('/pages/auth.html?return=' +
            encodeURIComponent('/pages/dashboard.html'), { waitUntil: 'domcontentloaded' });
        await page.waitForURL(В_АДМИНКЕ, { timeout: 20000 });
        expect(page.url(), 'вход отдал админку, а не кабинет из обратного адреса')
            .toMatch(В_АДМИНКЕ);
    });

    /* ОБРАТНЫЙ АДРЕС НЕ В КАБИНЕТ УВАЖАЕТСЯ ПО-ПРЕЖНЕМУ. Без этой
       проверки «починка» могла бы оказаться правилом «сотруднику всегда
       админка» — и сломать ссылки на турнир, заявку, карточку игрока. */
    test('обратный адрес не в кабинет сотруднику отдаётся', async ({ page }) => {
        await page.goto('/pages/auth.html?return=' +
            encodeURIComponent('/pages/players.html'), { waitUntil: 'domcontentloaded' });
        await page.waitForURL(/\/pages\/players\.html/, { timeout: 20000 });
        expect(page.url(), 'обратный адрес на страницу игроков уважён')
            .toContain('players.html');
    });

    test('«назад» не возвращает сотрудника в кабинет', async ({ page }) => {
        await page.goto('/pages/players.html', { waitUntil: 'domcontentloaded' });
        await page.goto('/pages/dashboard.html', { waitUntil: 'domcontentloaded' });
        await page.waitForURL(В_АДМИНКЕ, { timeout: 20000 });
        await page.goBack();
        await page.waitForLoadState('domcontentloaded');
        /* Увод идёт `location.replace`, поэтому записи кабинета в истории
           не остаётся: «назад» ведёт туда, откуда пришли. С `href` человек
           стучался бы в запертую комнату, пока не закроет вкладку. */
        expect(page.url(), 'в истории нет записи кабинета')
            .not.toContain('dashboard');
    });

    /* ТА САМАЯ ВТОРАЯ КНОПКА. `querySelector('.btn-auth')` подменял первую,
       и в мобильном меню кабинета оставалось «Выйти». Проба держит смысл:
       у сотрудника КАЖДАЯ кнопка входа — вход в админку, сколько бы их на
       странице ни было. */
    test('все кнопки входа у сотрудника ведут в админку', async ({ page }) => {
        /* РОЛЬ КЛАДЁТСЯ В ХРАНИЛИЩЕ, ПОТОМУ ЧТО ТАК ДЕЛАЕТ ПРОДУКТ, А НЕ
           ПРИБОР (07.11). Первая редакция проверки упала на всех пяти
           видах, и снимок показал в шапке кружок с буквой — выпадашку
           ОБЫЧНОГО пользователя. Падение на приборе: `js/auth-nav.js`
           спрашивает роль у `localStorage.kslt_role`, а `kslt_role` пишет
           вход (`js/auth.js`) и охрана (`js/auth-guard.js`), которых на
           публичной странице нет. Обвязка же выдаёт сессию снимком
           (`tests/auth-setup.js` кладёт ОДИН ключ — сессию supabase) и
           через форму входа не ходит. ПРОБА ВИДИТ ТОЛЬКО ТО, ЧТО ЕСТЬ В
           ДАННЫХ: хранилище — часть прибора, и эту часть надо привести к
           тому, что бывает у живого человека после входа.

           НАХОДКА, ЗАПИСАННАЯ В ТРЕКЕР, А НЕ ПОЧИНЕННАЯ ЗДЕСЬ: шапка
           узнаёт сотрудника ИЗ ХРАНИЛИЩА, а не из базы. Почистил человек
           хранилище при живой сессии — и на 80 публичных страницах он
           обычный пользователь. Это тот самый долг `auth-nav.js:183`,
           названный в `js/kslt-dostup.js` ещё куском 142; его перевод на
           дом — свой кусок. Дверь кабинета от этого не зависит: она
           спрашивает базу. */
        await page.addInitScript(() => {
            try { localStorage.setItem('kslt_role', 'admin'); } catch (e) { /* приватное окно */ }
        });
        await page.goto('/index.html', { waitUntil: 'domcontentloaded' });
        await page.waitForFunction(
            () => !!document.querySelector('.admin-nav-dropdown'),
            null, { timeout: 20000 });
        const итог = await page.evaluate(() => {
            const все = Array.prototype.slice.call(document.querySelectorAll('.btn-auth'));
            return {
                всего: все.length,
                админки: все.filter(e => e.classList.contains('admin-nav-toggle')).length,
                адреса: все.map(e => e.getAttribute('href') || '')
            };
        });
        expect(итог.всего, 'ПОРОГ: кнопок входа на странице нет — мерить нечего')
            .toBeGreaterThan(0);
        expect(итог.админки, 'кнопок «Админка» ' + итог.админки + ' из ' + итог.всего)
            .toBe(итог.всего);
        expect(итог.адреса.every(а => а.indexOf('admin.html') !== -1),
            'адреса кнопок: ' + итог.адреса.join(' · ')).toBe(true);
    });
});

test.describe('игрок: кабинет открывается как прежде', () => {
    test.use({ storageState: require('../../auth-setup').playerState });

    /* ДВЕРЬ ЗАПЕРТА ДЛЯ СОТРУДНИКА, А НЕ ДЛЯ ВСЕХ. Эта половина пробы —
       не формальность: правило, запирающее кабинет, стоит в охране, то
       есть на пути КАЖДОГО вошедшего. */
    for (const редакция of РЕДАКЦИИ) {
        test(`кабинет ${редакция} игроку открыт`, async ({ page }) => {
            const состояние = await открытьЗакрытую(page, '/pages/' + редакция);
            expect(состояние).toBe('готово');
            expect(page.url(), 'игрок остался в кабинете').toContain(редакция);
        });
    }
});
