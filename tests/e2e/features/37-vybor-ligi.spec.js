// @ts-check
const { test, expect } = require('../../fixtures');

/**
 * TC-ВЫБОР-ЛИГИ: в группе из трёх пар лигу выбирает менеджер.
 *
 * СЛОВО КОСТИ 05.11: «в группе из 3 игроков админ-менеджер сам определяет,
 * кто куда идёт — в высшую или утешительную», и «переключатель нужен,
 * когда игры окончены в группе». Там же два ограничения, которые главнее
 * самой доработки: сетки стыковых показываются заранее как раньше, и
 * перестановка мест в четвёрках не трогается.
 *
 * ПОЧЕМУ ВЫБОР РУЧНОЙ, А НЕ ФОРМУЛОЙ. Второе место стоит разного: из
 * четвёрки это обычно две победы из трёх, из тройки — одна из двух. Но ни
 * «по номеру места», ни «по доле от размера группы» не берут оба случая
 * тройки сразу: с двумя сильными парами верно первое, с одной сильной —
 * второе. Угадать нельзя в принципе, потому что сила пары ВНЕ её группы
 * системе неизвестна: парного рейтинга у КСЛТ нет вовсе.
 *
 * ЧЕГО ЗАМОРОЗКА НЕ ВИДИТ — то и проверяется здесь. Сторож читает файл
 * как текст: он знает, что условие написано, и не знает, что вышло в
 * браузере. Что переключатель и правда стоит у тройки и правда не стоит у
 * четвёрки, что он показывает ту сторону, куда пара идёт сейчас, что у
 * него есть голос для диктора и видимый фокус — это замер, а не чтение.
 *
 * АДМИНКА — ДЕСКТОП И ПЛАНШЕТ, ТЕЛЕФОНА У НЕЁ НЕТ, ТОЛЬКО РУССКИЙ.
 * Виды `mobile` и `phone-landscape` пропускаются целиком — так же, как в
 * пробе завершённого турнира.
 *
 * ПЕРЕКЛЮЧАТЕЛЬ НЕ ТРОГАЕМ. Его смена ПИШЕТ В БАЗУ и пересобирает обе
 * сетки лиг: здесь он только ищется и меряется.
 *
 *   npx playwright test tests/e2e/features/37-vybor-ligi.spec.js
 */

test.use({ storageState: require('../../auth-setup').adminState });

/* Три расклада, и каждый отвечает за своё правило. Четвёртого нет
   намеренно: расклад, который ничего не различает, только удлиняет
   прогон. */
const ЕСТЬ_ВЫБОР   = 'test-vybor-ligi';          // тройка доиграна + четвёрка
const РАНО         = 'test-vybor-ligi-rano';     // тройка не доиграна
const ЕСТЬ_СЧЁТ    = 'test-vybor-ligi-schyot';   // в лигах уже есть счёт

const ВЫБОР = '.ad-league-side-select';
const ЗНАЧОК = '.ad-league-go';

/**
 * Открыть сетку турнира и дождаться ПРИЗНАКА, а не тишины сети.
 *
 * Вкладку жмём, а не просим адресом: `forceTab` приходит не из адреса, и
 * экран открывается там, где решил код, а не где хотели мы.
 */
async function открытьСетку(page, id) {
    await page.goto('/pages/admin.html#tournaments/bracket/' + id,
        { waitUntil: 'domcontentloaded' });

    const вкладка = page.locator('[data-trn-nav="bracket"]');
    await вкладка.waitFor({ state: 'visible', timeout: 20000 });
    await вкладка.click();

    /* Ждём САМУ ГРУППОВУЮ ТАБЛИЦУ, а не любую живую клетку: у группового
       экрана сетка лиг рисуется ниже, и дождавшись её, мы бы начали мерить
       раньше, чем встанет таблица, из-за которой пришли. */
    await page.waitForSelector('#adBrkBracketPanel .ad-grp-name',
        { state: 'visible', timeout: 20000 });
}

/**
 * Строки одной группы: таблицы групп идут в том же порядке, что группы.
 *
 * ИМЯ КЛАССА, А НЕ ПРОСТО `table`. На этом же экране ниже стоит таблица
 * расписания — безымянный `table` поймал бы и её, и счёт таблиц поехал
 * бы от того, заполнено расписание или нет.
 */
function таблицаГруппы(page, номер) {
    return page.locator('#adBrkBracketPanel .ad-grp-matrix').nth(номер - 1);
}

test.describe('Выбор лиги в группе из трёх', () => {
    test.beforeEach(async ({ page }, info) => {
        test.skip(/mobile|phone/.test(info.project.name),
            'админка: десктоп и планшет, телефона нет');
    });

    test('у доигранной тройки выбор стоит у каждой пары', async ({ page }) => {
        await открытьСетку(page, ЕСТЬ_ВЫБОР);

        const выборы = таблицаГруппы(page, 1).locator(ВЫБОР);
        await expect(выборы).toHaveCount(3);

        /* ВЫБОР ЗАМЕНЯЕТ ЗНАЧОК, А НЕ СТОИТ РЯДОМ С НИМ. Два голоса об
           одном и том же в одной ячейке — это вопрос «а какой из них
           правда», и отвечать на него человеку не должно приходиться. */
        await expect(таблицаГруппы(page, 1).locator(ЗНАЧОК)).toHaveCount(0);
    });

    test('выбор показывает ту сторону, куда пара идёт сейчас', async ({ page }) => {
        await открытьСетку(page, ЕСТЬ_ВЫБОР);

        const выборы = таблицаГруппы(page, 1).locator(ВЫБОР);
        /* Умолчание: первые два места наверх, третье вниз. Ручных отметок
           в севе нет, значит читается именно умолчание — и если оно уедет,
           проба скажет об этом раньше турнира. */
        await expect(выборы.nth(0)).toHaveValue('PL');
        await expect(выборы.nth(1)).toHaveValue('PL');
        await expect(выборы.nth(2)).toHaveValue('CL');
    });

    test('у четвёрки выбора нет — там всё как было', async ({ page }) => {
        await открытьСетку(page, ЕСТЬ_ВЫБОР);

        const четвёрка = таблицаГруппы(page, 2);
        await expect(четвёрка.locator('.ad-grp-name')).toHaveCount(4);
        await expect(четвёрка.locator(ВЫБОР)).toHaveCount(0);

        // Значок словом остаётся: куда идёт пара, видно и без выбора
        await expect(четвёрка.locator(ЗНАЧОК).first()).toBeVisible();
    });

    test('пока группа не доиграна, выбора нет', async ({ page }) => {
        await открытьСетку(page, РАНО);

        await expect(page.locator(ВЫБОР)).toHaveCount(0);
        /* И значка тоже нет: место, посчитанное по недоигранной группе,
           ещё не место. Иначе экран назвал бы лигу тому, кто может в ней
           и не оказаться. */
        await expect(page.locator(ЗНАЧОК)).toHaveCount(0);
    });

    test('когда в лигах есть счёт, выбор закрыт', async ({ page }) => {
        await открытьСетку(page, ЕСТЬ_СЧЁТ);

        /* Группа доиграна, тройка на месте — и всё же выбора нет:
           пересборка сеток стёрла бы уже сыгранное. */
        await expect(page.locator('#adBrkBracketPanel .ad-grp-name')).toHaveCount(3);
        await expect(page.locator(ВЫБОР)).toHaveCount(0);
        await expect(page.locator(ЗНАЧОК).first()).toBeVisible();
    });

    test('у выбора есть голос для диктора и подсказка почему', async ({ page }) => {
        await открытьСетку(page, ЕСТЬ_ВЫБОР);

        const первый = таблицаГруппы(page, 1).locator(ВЫБОР).first();
        await expect(первый).toHaveAttribute('aria-label', /лиг/i);

        /* Подсказка объясняет, ПОЧЕМУ выбор здесь вообще есть. Без неё
           менеджер не поймёт, отчего у четвёрок его нет, и решит, что
           экран сломался. */
        const подсказка = await первый.getAttribute('data-tip');
        expect(подсказка && подсказка.length).toBeTruthy();
        expect(подсказка).toMatch(/трёх|тройк/i);
    });

    test('фокус на выборе виден, и не только мышью', async ({ page }) => {
        await открытьСетку(page, ЕСТЬ_ВЫБОР);

        const первый = таблицаГруппы(page, 1).locator(ВЫБОР).first();
        await первый.scrollIntoViewIfNeeded();
        await первый.focus();

        /* :focus-visible рисует обводку. Берём ВЫЧИСЛЕННОЕ значение, а не
           наличие правила в css: правило может быть перекрыто соседом, и
           файл об этом не скажет. */
        const обводка = await первый.evaluate(э => {
            const с = getComputedStyle(э);
            return { ширина: с.outlineWidth, стиль: с.outlineStyle };
        });
        expect(обводка.стиль).not.toBe('none');
        expect(parseFloat(обводка.ширина)).toBeGreaterThan(0);
    });

    test('выбор не раздвигает строку группы', async ({ page }) => {
        await открытьСетку(page, ЕСТЬ_ВЫБОР);

        /* ПАРА, КОТОРАЯ ЧИТАЕТСЯ КАК ПАРА, ЕДЕТ ОДНОЙ ГРАНИЦЕЙ: строка с
           выбором и строка со значком стоят в одной таблице по соседству
           в разных группах, и если выбор выше значка, таблицы разъедутся
           на глаз. Порог в три пиксела — на округление шрифта, а не на
           «примерно похоже». */
        const сВыбором = await таблицаГруппы(page, 1)
            .locator('tbody tr').first().boundingBox();
        const соЗначком = await таблицаГруппы(page, 2)
            .locator('tbody tr').first().boundingBox();
        expect(Math.abs(сВыбором.height - соЗначком.height)).toBeLessThanOrEqual(3);
    });

    test('сетки стыковых стоят на месте — выбор их не убрал', async ({ page }) => {
        await открытьСетку(page, ЕСТЬ_ВЫБОР);

        /* Первое ограничение Кости: «оставить как сейчас есть — заранее
           показывать ВСЕ сетки стыковых игр». Проверяется тем же экраном,
           на котором появился выбор: если доработка их спрячет, скажет
           эта проба, а не турнир. */
        const лиги = page.locator('#adBrkBracketPanel .ad-league-bracket');
        await expect(лиги).toHaveCount(2);
        await expect(лиги.first()).toBeVisible();
    });
});
