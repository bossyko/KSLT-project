const { test, expect } = require('../../fixtures');

/**
 * TC-ONLAYN: «онлайн» снят с рейтинга, а правило «в сети» — одно.
 *
 * ЭТОТ КУСОК — СНЯТИЕ, А НЕ ПОСТРОЙКА, и мерить его надо именно так.
 * Онлайн в рейтинге был УКРАШЕНИЕМ БЕЗ ДАННЫХ: поле `online` в
 * `js/rankings-data.js` всегда было `false`, в `true` его не ставил
 * никто, а Костя снял показ словом 06.10. Точка, её пульсация, кнопка
 * письма и счётчик «сейчас онлайн» рисовались условием, которое никогда
 * не выполнялось.
 *
 * ЧТО ДЕРЖИТ СТОРОЖ, А ЧТО ЗДЕСЬ. Сторож читает файлы и видит, что
 * снятого в коде нет. Он НЕ ВИДИТ НАРИСОВАННОГО: что на живой странице
 * не осталось ни одного такого узла и что строка рейтинга без точки не
 * поехала. Это работа прогона — и он идёт на ПЯТИ ВИДАХ, потому что
 * строка рейтинга на телефоне и на десктопе собирается по-разному.
 *
 * ПОНЯТИЕ «В СЕТИ» ПРИ ЭТОМ ЖИВО И ОДНО: `KSLT_LICO.вСети(last_seen)` с
 * порогом `ПОРОГ_В_СЕТИ`. Его зовут услуги и партнёры, и здесь
 * проверяется, что правило ОДНО и считает по порогу, а не по своему
 * числу: если онлайн когда-нибудь вернут в рейтинг, второго правила
 * писать не надо.
 *
 * ВИД МЕРЯЕТСЯ ЗАГРУЗКОЙ НА НУЖНОЙ ШИРИНЕ, а не сжатием того, что уже
 * загружено: сжатое окно пересчитывает не всё.
 */

const ВИДЫ = [
    { имя: 'телефон стоя',      w: 390,  h: 844 },
    { имя: 'телефон лёжа',      w: 844,  h: 390 },
    { имя: 'планшет стоя',      w: 768,  h: 1024 },
    { имя: 'планшет лёжа',      w: 1024, h: 768 },
    { имя: 'десктоп',           w: 1440, h: 900 }
];

const СТРАНИЦЫ = [
    { язык: 'ru', адрес: '/pages/players.html',    слово: 'онлайн' },
    { язык: 'en', адрес: '/pages/players-en.html', слово: 'online' },
    { язык: 'kg', адрес: '/pages/players-kg.html', слово: 'онлайн' }
];

/* Дом лица подключён к странице партнёров — там живёт правило «в сети». */
const ПАРТНЁРЫ = '/pages/partners.html';

async function открыть(page, адрес, вид) {
    const ошибки = [];
    page.on('pageerror', e => ошибки.push(String(e.message || e)));
    await page.setViewportSize({ width: вид.w, height: вид.h });
    await page.goto(адрес, { waitUntil: 'domcontentloaded' });
    await page.waitForLoadState('networkidle').catch(() => {});
    return ошибки;
}

test.describe('«Онлайн» снят с рейтинга, правило «в сети» одно', () => {

    for (const с of СТРАНИЦЫ) {
        for (const вид of ВИДЫ) {
            test('рейтинг · ' + с.язык + ' · ' + вид.имя, async ({ page }) => {
                const ошибки = await открыть(page, с.адрес, вид);

                /* СПРАШИВАЕМ ПРО ТЕ ИМЕНА, КОТОРЫЕ В КОДЕ БЫЛИ. Счётчик
                   «сейчас онлайн» своего имени в разметке не имел —
                   `countOnline()` просто считал число, — поэтому его
                   снятие проверяется чтением кода ниже, а не пустым
                   запросом по выдуманному признаку. */
                const снято = await page.evaluate(() => ({
                    точек:     document.querySelectorAll('.pl-online-dot').length,
                    пульсаций: document.querySelectorAll('.pl-online-pulse').length,
                    писем:     document.querySelectorAll('.pl-btn-message').length
                }));
                expect(снято, 'снятое украшение не рисуется ни на одном виде')
                    .toEqual({ точек: 0, пульсаций: 0, писем: 0 });

                /* ПУЛЬСАЦИЯ СНЯТА И ИЗ СТИЛЕЙ, а не только из разметки:
                   мёртвое правило `@keyframes` не видно глазом и живёт
                   годами. Правило читается у САМОГО ДОКУМЕНТА, а не у
                   файла: так ловится и то, что приехало инлайном. */
                const кадры = await page.evaluate(() => {
                    let n = 0;
                    for (const л of Array.from(document.styleSheets)) {
                        let правила = [];
                        try { правила = Array.from(л.cssRules || []); } catch (e) { continue; }
                        for (const п of правила) {
                            if (п.type === CSSRule.KEYFRAMES_RULE && /pl-pulse/.test(п.name)) n++;
                        }
                    }
                    return n;
                });
                expect(кадры, '@keyframes pl-pulse снят из стилей, а не оставлен мёртвым').toBe(0);

                /* СЛОВО «ОНЛАЙН» УШЛО ИЗ ВИДИМОГО ТЕКСТА. Проверяется
                   текст страницы, а не словарь: словарь могли почистить,
                   а подпись оставить зашитой. */
                const текст = (await page.locator('body').innerText()).toLowerCase();
                expect(текст.includes(с.слово),
                    'подписи «' + с.слово + '» на странице рейтинга не осталось').toBe(false);

                /* СТРОКА БЕЗ ТОЧКИ НЕ ПОЕХАЛА: страница не шире окна. */
                const шире = await page.evaluate(() =>
                    document.documentElement.scrollWidth - document.documentElement.clientWidth);
                expect(шире, 'поперечной прокрутки нет').toBeLessThanOrEqual(1);

                expect(ошибки, 'страница без ошибок').toEqual([]);
            });
        }
    }

    test('ни поля `online`, ни счётчика онлайна в коде рейтинга не осталось',
        async ({ page }) => {
            await открыть(page, СТРАНИЦЫ[0].адрес, ВИДЫ[4]);
            const найдено = await page.evaluate(async () => {
                const безКом = т => т.replace(/\/\*[\s\S]*?\*\//g, ' ')
                                      .replace(/(^|[^:])\/\/[^\n]*/g, '$1 ');
                const чит = async п => безКом(await (await fetch(п)).text());
                const загрузчик = await чит('../js/rankings-data.js');
                const страница = await чит('../js/players.js');
                return {
                    полей:        (загрузчик.match(/\bonline\s*:/g) || []).length,
                    своихПорогов: (загрузчик.match(/last_seen/g) || []).length,
                    счётчиков:    (страница.match(/countOnline/g) || []).length,
                    своихВСети:   (страница.match(/ПОРОГ_В_СЕТИ|5\s*\*\s*60\s*\*\s*1000/g) || []).length
                };
            });
            expect(найдено.полей, 'поля `online`, которое всегда было false, больше нет').toBe(0);
            expect(найдено.своихПорогов, 'своего счёта «в сети» загрузчик не завёл').toBe(0);
            expect(найдено.счётчиков, '`countOnline()` — всегда ноль — снят').toBe(0);
            expect(найдено.своихВСети, 'своего порога «в сети» страница рейтинга не завела').toBe(0);
        });

    test('правило «в сети» одно и считает по порогу, а не по своему числу',
        async ({ page }) => {
            const ошибки = await открыть(page, ПАРТНЁРЫ, ВИДЫ[4]);
            await page.waitForFunction(
                () => window.KSLT_LICO && typeof window.KSLT_LICO.вСети === 'function',
                null, { timeout: 20000 });

            const д = await page.evaluate(() => {
                const L = window.KSLT_LICO;
                const порог = L.ПОРОГ_В_СЕТИ;
                const t = (сдвиг) => new Date(Date.now() - сдвиг).toISOString();
                return {
                    порог: порог,
                    только: порог - 1000,
                    свежий:   L.вСети(t(1000)),
                    впритык:  L.вСети(t(порог - 2000)),
                    старый:   L.вСети(t(порог + 2000)),
                    пусто:    L.вСети(null),
                    мусор:    L.вСети('не дата')
                };
            });

            expect(д.порог, 'порог «в сети» — пять минут, одно число на продукт').toBe(300000);
            expect(д.свежий,  'минуту назад — в сети').toBe(true);
            expect(д.впритык, 'внутри порога — в сети').toBe(true);
            expect(д.старый,  'за порогом — не в сети').toBe(false);
            expect(д.пусто,   'нет `last_seen` — не в сети, а не «в сети по умолчанию»').toBe(false);
            expect(д.мусор,   'мусор вместо даты — не в сети, и без падения').toBe(false);
            expect(ошибки, 'страница без ошибок').toEqual([]);
        });
});
