const { test, expect } = require('../../fixtures');

const СТРАНИЦЫ = [
    { к: 'ru', адрес: '/pages/auth.html' },
    { к: 'en', адрес: '/pages/auth-en.html' },
    { к: 'kg', адрес: '/pages/auth-kg.html' },
];

/* Уровни называются поимённо. НИ ОДИН НЕ ПРОПУСКАЕТСЯ: пропущенный — это
   тот, который потом и окажется кривым. */
const УРОВНИ = [
    ['вкладка',        '.auth-tab'],
    ['заголовок',      '.auth-screen-title, .auth-card h1, .auth-card h2'],
    ['подзаголовок',   '.auth-subtitle, .auth-screen-sub'],
    ['подпись поля',   '.auth-label, .auth-gender-option, .auth-checkbox'],
    ['поле',           '.auth-input'],
    ['клетка кода',    '.otp-digit'],
    ['главная кнопка', '.auth-btn'],
    ['кнопка способа', '.auth-social-btn, .auth-tg-app-btn, .auth-option-btn'],
    ['ссылка',         '.auth-forgot, .auth-back-link, .auth-card a'],
    ['мелкий текст',   '.auth-terms, .auth-hint, .auth-note, .auth-card small'],
];

for (const стр of СТРАНИЦЫ) {
    test(`${стр.к}: лестница входа снята полностью`, async ({ page }, инфо) => {
        await page.goto(стр.адрес, { waitUntil: 'domcontentloaded' });
        /* ЖДЁМ ПРИЗНАК, А НЕ ТИШИНУ СЕТИ. */
        await page.waitForSelector('.auth-card, #signinForm', { timeout: 15000 });

        const снимок = await page.evaluate(УРОВНИ => {
            const разбор = c => {
                const m = (c || '').match(/[\d.]+/g);
                if (!m) return null;
                return { r: +m[0], g: +m[1], b: +m[2], a: m.length > 3 ? +m[3] : 1 };
            };
            const поверх = (в, н) => ({
                r: в.r * в.a + н.r * (1 - в.a),
                g: в.g * в.a + н.g * (1 - в.a),
                b: в.b * в.a + н.b * (1 - в.a), a: 1,
            });
            /* ПОДЛОЖКА СОБИРАЕТСЯ ПО ВСЕЙ ЦЕПОЧКЕ РОДИТЕЛЕЙ до первого
               плотного фона и складывается сверху вниз. */
            const подложка = э => {
                const слои = [];
                let у = э;
                while (у) {
                    const c = разбор(getComputedStyle(у).backgroundColor);
                    if (c && c.a > 0) { слои.push(c); if (c.a === 1) break; }
                    у = у.parentElement;
                }
                let низ = (слои.length && слои[слои.length - 1].a === 1)
                    ? слои.pop() : { r: 255, g: 255, b: 255, a: 1 };
                for (let i = слои.length - 1; i >= 0; i--) низ = поверх(слои[i], низ);
                return низ;
            };
            const ярк = c => {
                const f = v => {
                    const s = v / 255;
                    return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
                };
                return 0.2126 * f(c.r) + 0.7152 * f(c.g) + 0.0722 * f(c.b);
            };
            const контраст = (кр, фон) => {
                const я1 = ярк(кр), я2 = ярк(фон);
                return (Math.max(я1, я2) + 0.05) / (Math.min(я1, я2) + 0.05);
            };
            const вне = э => {
                if (!э.getClientRects().length) return true;
                const c = getComputedStyle(э);
                return c.display === 'none' || c.visibility === 'hidden' || +c.opacity === 0;
            };

            const строки = [];
            for (const [имя, селектор] of УРОВНИ) {
                for (const э of Array.from(document.querySelectorAll(селектор)).filter(x => !вне(x))) {
                    const c = getComputedStyle(э), r = э.getBoundingClientRect();
                    const своё = (э.textContent || '').replace(/\s+/g, ' ').trim();
                    const изПодсказки = !своё && !!э.placeholder;
                    const текст = своё || э.placeholder || '';
                    const фон = подложка(э);
                    const кр0 = разбор(изПодсказки
                        ? getComputedStyle(э, '::placeholder').color : c.color);
                    const кр = кр0 ? поверх(кр0, фон) : null;
                    const кегль = Math.round(parseFloat(c.fontSize) * 10) / 10;
                    строки.push({
                        уровень: имя,
                        что: текст.slice(0, 26),
                        /* ДЛИНА СЧИТАЕТСЯ ЗНАКАМИ, А НЕ ЯЧЕЙКАМИ. */
                        знаков: [...текст].length,
                        кегль, вес: c.fontWeight, межстрочный: c.lineHeight,
                        ш: Math.round(r.width * 10) / 10,
                        в: Math.round(r.height * 10) / 10,
                        контраст: кр ? Math.round(контраст(кр, фон) * 100) / 100 : null,
                        планка: (кегль >= 18 || (кегль >= 14 && +c.fontWeight >= 700)) ? 3 : 4.5,
                        интерактивный: /BUTTON|INPUT|A/.test(э.tagName),
                    });
                }
            }
            return {
                строки, окно: innerWidth,
                едетВбок: document.documentElement.scrollWidth > innerWidth + 1,
            };
        }, УРОВНИ);

        /* ТАБЛИЦА ЧИСЕЛ, А НЕ «ПРИМЕРНО ТАК» — печатается до проверок. */
        console.log(`\n=== ВХОД · ${стр.к} · ${инфо.project.name} · окно ${снимок.окно} ===`);
        console.log('уровень          кегль  вес межстр        размер знаков  контраст  текст');
        for (const с of снимок.строки) {
            console.log([
                с.уровень.padEnd(15), String(с.кегль).padStart(5), String(с.вес).padStart(4),
                String(с.межстрочный).padStart(7), (с.ш + '×' + с.в).padStart(13),
                String(с.знаков).padStart(6), String(с.контраст).padStart(9), ' ' + с.что,
            ].join(' '));
        }

        const цели = снимок.строки.filter(с => с.интерактивный);
        const мелкие = цели.filter(с => с.в < 44);
        console.log(`--- цели нажатия: всего ${цели.length}, ниже 44 — ${мелкие.length}`);
        for (const м of мелкие) console.log(`    ${м.в}  ${м.уровень}  «${м.что}»`);

        /* ЧТО ДЕРЖАТЬСЯ ОБЯЗАНО. */
        expect(снимок.строки.length, 'уровни найдены, а не пустой экран').toBeGreaterThan(5);
        expect(снимок.едетВбок, `страница не поехала вбок (окно ${снимок.окно})`).toBe(false);

        const схлопнутые = снимок.строки.filter(с => с.знаков > 0 && с.в < 4);
        expect(схлопнутые.map(с => с.уровень + ':' + с.что).join(' | '),
            'ни один текстовый уровень не схлопнут').toBe('');

        /* Однознаковые надписи из счёта контраста исключены: знак — не
           текст, и его читаемость ничего не говорит о лестнице. */
        const тусклые = снимок.строки
            .filter(с => с.знаков > 1 && с.контраст !== null && с.контраст < с.планка)
            .map(с => `${с.уровень} «${с.что}» ${с.контраст} при планке ${с.планка}`);
        expect(тусклые.join(' | '), 'подписи читаемы по WCAG').toBe('');
    });
}
