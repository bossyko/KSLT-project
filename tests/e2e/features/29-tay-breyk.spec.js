// @ts-check
const { test, expect } = require('../../fixtures');

/**
 * TC-TB: тай-брейк вписывает игрок (29.10, слово Кости).
 *
 * СЕРВЕР ПРИНИМАЛ ТАЙ-БРЕЙК С САМОГО НАЧАЛА — это прочитано в его коде
 * (`sql/функции/match-score-notify.sql:140`), и в базе таких строк уже
 * 105. Не умел только ввод: `buildScore` отбрасывал скобку, а в окне
 * было два поля на сет вместо четырёх.
 *
 * ЧТО ЗАМОРОЖЕНО ПРАВИЛАМИ, А ЧТО ЗДЕСЬ. Сторож читает файлы: он видит,
 * что правило показа одно и что поля в разметке есть. Он НЕ ВИДИТ, как
 * ведёт себя живое окно: открылась ли клетка при 7:6, закрылась ли и
 * очистилась при 6:4, что уходит в базу и что показывают сопернику.
 *
 * БАЗУ ТЕСТ НЕ ПИШЕТ: правила спрашиваются у живого свода, а сборка — у
 * дома с подставным клиентом, чей `rpc` только запоминает зов.
 */

const СТРАНИЦЫ = [
    { язык: 'ru', адрес: '/pages/tournament.html?id=00000000-0000-0000-0000-000000000000' },
    { язык: 'en', адрес: '/pages/tournament-en.html?id=00000000-0000-0000-0000-000000000000' },
    { язык: 'kg', адрес: '/pages/tournament-kg.html?id=00000000-0000-0000-0000-000000000000' }
];

const ПРИЛОЖЕНИЕ = '/mobile/www/index.html';

async function дождаться(page, адрес) {
    const ошибки = [];
    page.on('pageerror', e => ошибки.push(String(e.message || e)));
    await page.goto(адрес, { waitUntil: 'domcontentloaded' });
    await page.waitForFunction(
        () => window.KSLT_RULES && window.KSLT_RULES.сетСТайБрейком &&
              window.KSLT_SCHYOT_MATCHA,
        null, { timeout: 20000 });
    return ошибки;
}

function снять(page) {
    return page.evaluate(async () => {
        const R = window.KSLT_RULES;
        const SM = window.KSLT_SCHYOT_MATCHA;

        /* ПОЛЯ ПОДСТАВНЫЕ: дом берёт значения через переданную функцию,
           поэтому живое окно открывать не нужно — проверяется сборка. */
        const знач = {};
        const поле = (id) => (знач[id] === undefined ? '' : String(знач[id]));
        const положить = (о) => { Object.keys(знач).forEach(k => delete знач[k]); Object.assign(знач, о); };

        const клиент = () => {
            const зовы = [];
            return { зовы, rpc: (и, а) => { зовы.push({ и, а }); return Promise.resolve({ data: { ok: true } }); } };
        };

        /* 1. Правило показа клетки. */
        const показ = [['7', '6'], ['6', '7'], ['6', '4'], ['7', '5'], ['6', '6'],
                       ['', ''], ['10', '8'], ['1', '0']]
            .map(п => [п[0] + ':' + п[1], R.сетСТайБрейком(п[0], п[1])]);

        /* 2. Сборка: годный тай-брейк уходит в базу в форме сервера. */
        положить({ ms1s1: '7', ms2s1: '6', mstb1s1: '11', mstb2s1: '9',
                   ms1s2: '6', ms2s2: '4' });
        let c = клиент();
        const годный = await SM.вписать(c, 'M1', SM.собрать(поле, 'ms', 3), null);
        const ушло = c.зовы.length ? c.зовы[0].а.p_score : null;

        /* 3. Половина тай-брейка — отказ, и базу не зовут. */
        положить({ ms1s1: '7', ms2s1: '6', mstb1s1: '11' });
        c = клиент();
        const половина = await SM.вписать(c, 'M1', SM.собрать(поле, 'ms', 3), null);
        const зововПоловина = c.зовы.length;

        /* 4. Тай-брейк достался не тому, кто взял сет. */
        положить({ ms1s1: '7', ms2s1: '6', mstb1s1: '9', mstb2s1: '11' });
        c = клиент();
        const неТот = await SM.вписать(c, 'M1', SM.собрать(поле, 'ms', 3), null);
        const зововНеТот = c.зовы.length;

        /* 5. Цифры не числом и трёхзначные. */
        положить({ ms1s1: '7', ms2s1: '6', mstb1s1: 'ab', mstb2s1: '9' });
        const нечисло = await SM.вписать(клиент(), 'M1', SM.собрать(поле, 'ms', 3), null);
        положить({ ms1s1: '7', ms2s1: '6', mstb1s1: '110', mstb2s1: '9' });
        const длинное = await SM.вписать(клиент(), 'M1', SM.собрать(поле, 'ms', 3), null);

        /* 6. Счёт глазами соперника и мировая запись. */
        const переворот = R.перевернутьСчёт('7/6(11-9) 6/4');
        const дважды = R.перевернутьСчёт(переворот);
        const мировая = R.счётПоМировому('7/6(11-9) 6/4');

        return { показ, годный, ушло, половина, зововПоловина, неТот, зововНеТот,
                 нечисло, длинное, переворот, дважды, мировая };
    });
}

function проверить(д) {
    expect(д.показ, 'клетка тай-брейка открывается только при 7:6 и 6:7').toEqual([
        ['7:6', true], ['6:7', true], ['6:4', false], ['7:5', false],
        ['6:6', false], [':', false], ['10:8', false], ['1:0', false]
    ]);

    expect(д.годный).toEqual({ 'ок': true });
    expect(д.ушло, 'в базу уходит форма, которую принимает серверная функция')
        .toBe('7/6(11-9) 6/4');

    expect(д.половина['ключ'], 'половина тай-брейка — свой отказ').toBe('errTbHalf');
    expect(д.зововПоловина, 'базу при этом не зовут вовсе').toBe(0);

    expect(д.неТот['ключ'], 'тай-брейк достался не тому, кто взял сет').toBe('errTbSide');
    expect(д.зововНеТот, 'и базу тоже не зовут').toBe(0);

    expect(д.нечисло['ключ']).toBe('errTbBad');
    expect(д.длинное['ключ'], 'больше двух знаков сервер не примет').toBe('errTbBad');

    expect(д.переворот, 'глазами соперника меняются и стороны, и числа в скобке')
        .toBe('6/7(9-11) 4/6');
    expect(д.дважды, 'двойной переворот возвращает исходное').toBe('7/6(11-9) 6/4');
    expect(д.мировая, 'на показе — мировая запись: очки проигравшего').toBe('7/6(9) 6/4');
}

test.describe('Тай-брейк вписывает игрок', () => {

    for (const с of СТРАНИЦЫ) {
        test('правила и сборка · ' + с.язык, async ({ page }) => {
            const ошибки = await дождаться(page, с.адрес);
            проверить(await снять(page));
            expect(ошибки, 'страница без ошибок').toEqual([]);
        });
    }

    test('в приложении то же самое', async ({ page }) => {
        const ошибки = await дождаться(page, ПРИЛОЖЕНИЕ);
        проверить(await снять(page));
        expect(ошибки, 'страница без ошибок').toEqual([]);
    });

    test('клетка открывается, закрывается и очищается в живом окне', async ({ page }) => {
        await дождаться(page, ПРИЛОЖЕНИЕ);
        const д = await page.evaluate(async () => {
            const R = window.KSLT_RULES;
            /* Окно счёта открывается только по живому матчу, поэтому
               собираем ровно ту разметку, что рисует продукт, и вешаем на
               неё то же поведение: правило показа — из свода. */
            const окно = document.createElement('div');
            окно.innerHTML =
                '<table><tbody><tr>' +
                '<td><input class="x-in" id="g1"></td><td><input class="x-in" id="g2"></td>' +
                '</tr><tr><td class="x-tb" data-tb-set="1" hidden>' +
                '<input id="tb1"><input id="tb2"></td></tr></tbody></table>';
            document.body.appendChild(окно);
            const g1 = окно.querySelector('#g1'), g2 = окно.querySelector('#g2');
            const клетка = окно.querySelector('[data-tb-set="1"]');
            const tb1 = окно.querySelector('#tb1'), tb2 = окно.querySelector('#tb2');
            const пересчитать = () => {
                const видно = R.сетСТайБрейком(g1.value, g2.value);
                клетка.hidden = !видно;
                if (!видно) { tb1.value = ''; tb2.value = ''; }
            };
            g1.value = '7'; g2.value = '6'; пересчитать();
            const открылась = !клетка.hidden;
            tb1.value = '11'; tb2.value = '9';
            g2.value = '4'; пересчитать();
            const закрылась = клетка.hidden;
            const очистилась = tb1.value === '' && tb2.value === '';
            окно.remove();
            return { открылась, закрылась, очистилась };
        });
        expect(д.открылась, 'при 7:6 клетка открылась').toBe(true);
        expect(д.закрылась, 'стало 7:4 — клетка закрылась').toBe(true);
        expect(д.очистилась,
            'и ОЧИСТИЛАСЬ: иначе в счёт уедет тай-брейк от сета, который переписали').toBe(true);
    });
});
