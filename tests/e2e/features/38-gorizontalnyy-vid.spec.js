const { test, expect } = require('../../fixtures');

/**
 * TC-GORIZONT: низкий горизонтальный вид приложения (05.11).
 *
 * ПОЧЕМУ ЭТА ПРОБА ЕСТЬ. Костя увидел глазами в Android Studio:
 * приложение лёжа разъезжается. Замер пяти видов загрузкой назвал
 * причину числами: лёжа (844×390) `body` не ограничено 600 — предел снят
 * нарочно куском 212, — и всё, чья высота считается ОТ ШИРИНЫ, выросло
 * вместе с ней:
 *
 *     афиша новости  4/3  →  812×609 при экране 390 — 156 % высоты
 *     видео новости 16/9  →  844×475 — 122 %
 *     карта баттла  (304) →  78 %
 *     график        (192) →  49 %
 *
 * ЧТО ЗАМОРОЖЕНО ПРАВИЛАМИ, А ЧТО ЗДЕСЬ. Сторож
 * `tools/check-gorizontalnyy-vid.js` читает css как ТЕКСТ и видит, что
 * правила написаны. Он не видит, доехало ли это до живого дерева: какой
 * высоты встала афиша, уцелела ли пропорция видео, не появилась ли
 * горизонтальная прокрутка. Это работа прогона.
 *
 * БАЗУ ПРОБА НЕ ТРОГАЕТ. Разметка рисуется ПРЯМО, ровно с теми классами,
 * что носит продукт: проверяется поведение одежды, а не путь, которым
 * продукт до экрана добирается.
 *
 * ПОРОГИ — ОТНОШЕНИЯ, А НЕ ЧИСЛА. «Афиша не выше половины экрана» живёт
 * дольше, чем «афиша равна 180»: второе придётся править при каждой
 * смене ступени, и проба станет врать раньше, чем код.
 */

const ПРИЛОЖЕНИЕ = '/mobile/www/index.html';

/* Низкий горизонтальный — это НЕ «ширина больше высоты». Граница одна на
   сайт и приложение: высота не больше 500 и поворот. Планшет лёжа
   (1024×768) под неё не подпадает, и это нарочно. */
function низкийГоризонтальный(вид) {
    return !!вид && вид.height <= 500 && вид.width > вид.height;
}

async function дождатьсяОдежды(page) {
    const ошибки = [];
    page.on('pageerror', e => ошибки.push(String(e.message || e)));
    await page.goto(ПРИЛОЖЕНИЕ, { waitUntil: 'domcontentloaded' });
    /* ПРИЗНАК, А НЕ ТИШИНА СЕТИ: ждём, что одежда приложения применилась
       к нижнему меню, — до этого мерить нечего. */
    await page.waitForFunction(() => {
        const t = document.querySelector('.tab-bar');
        return !!t && getComputedStyle(t).position === 'absolute';
    }, null, { timeout: 20000 });
    return ошибки;
}

/* Рисуем ровно те блоки, высота которых считается от ширины, плюс два с
   жёсткой высотой. Картинка — заливкой: сеть пробе не нужна. */
async function поставитьБлоки(page) {
    await page.evaluate(() => {
        /* ЗАСТАВКА СНИМАЕТСЯ ТЕМ ЖЕ КЛАССОМ, ЧТО И В ПРОДУКТЕ (`hide`).
           На числа она не влияет — размеры читаются из дерева, — но без
           этого СЛЕД ПРОГОНА показывает заставку вместо того, что
           померено, и снимок перестаёт быть доказательством. */
        const з = document.getElementById('splashOverlay');
        if (з) з.classList.add('hide');

        const окно = document.createElement('div');
        окно.className = 'td-overlay open';
        окно.id = 'probaOkno';
        окно.innerHTML =
            '<div class="td-topbar"><button class="td-back"><span>Назад</span></button>' +
            '<span class="td-topbar-title">Новость</span><span style="width:60px"></span></div>' +
            '<div class="nd-hero-img" id="probaAfisha" style="background-image:linear-gradient(135deg,#1d4ed8,#a3e635)"></div>' +
            '<div class="nd-body"><iframe id="probaVideo" src="about:blank"></iframe>' +
            '<div class="bd-map"><iframe id="probaKarta" src="about:blank"></iframe></div>' +
            '<div class="rc-wrap"><svg class="rc-svg" id="probaGrafik"></svg></div></div>';
        document.body.appendChild(окно);
    });
}

async function снять(page) {
    return page.evaluate(() => {
        const H = window.innerHeight, W = window.innerWidth;
        function о(id) {
            const el = document.getElementById(id);
            if (!el) return null;
            const r = el.getBoundingClientRect();
            return {
                ш: Math.round(r.width), в: Math.round(r.height),
                долиВысоты: r.height / H, долиШирины: r.width / W,
                слева: Math.round(r.left), справа: Math.round(W - r.right)
            };
        }
        return {
            экран: { W, H },
            афиша: о('probaAfisha'),
            видео: о('probaVideo'),
            карта: о('probaKarta'),
            график: о('probaGrafik'),
            прокруткаВбок: document.documentElement.scrollWidth > W + 1
        };
    });
}

test.describe('Низкий горизонтальный вид приложения', () => {

    test('афиша не съедает экран, и это не полоса у края', async ({ page }) => {
        const ошибки = await дождатьсяОдежды(page);
        await поставитьБлоки(page);
        const с = await снять(page);
        const вид = page.viewportSize();

        if (низкийГоризонтальный(вид)) {
            /* БЫЛО 156 % ВЫСОТЫ. Половина экрана — потолок, за которым
               от новости не остаётся ничего, кроме картинки. */
            expect(с.афиша.долиВысоты, 'афиша ' + с.афиша.ш + '×' + с.афиша.в +
                ' при экране ' + с.экран.W + '×' + с.экран.H).toBeLessThanOrEqual(0.5);
            /* И ВТОРАЯ ПОЛОВИНА БЕДЫ, НА КОТОРОЙ СПОТКНУЛСЯ ПЕРВЫЙ ЗАХОД:
               потолок высоты при живой пропорции сжимает ШИРИНУ, и афиша
               встаёт полосой 240×180 у левого края. */
            expect(с.афиша.долиШирины, 'афиша сжалась в полосу шириной ' +
                с.афиша.ш + ' при экране ' + с.экран.W).toBeGreaterThanOrEqual(0.7);
        } else {
            /* НА ПРОЧИХ ВИДАХ ПРАВИЛО НЕ ПРОТЕКАЕТ: пропорция 4/3 жива. */
            expect(с.афиша.ш / с.афиша.в, 'пропорция афиши на виде ' +
                с.экран.W + '×' + с.экран.H).toBeCloseTo(4 / 3, 1);
        }
        expect(ошибки, 'ошибки страницы').toEqual([]);
    });

    test('видео помещается в экран и не теряет пропорцию', async ({ page }) => {
        await дождатьсяОдежды(page);
        await поставитьБлоки(page);
        const с = await снять(page);
        const вид = page.viewportSize();

        /* ПРОПОРЦИЯ ВИДЕО СВЯЩЕННА НА ЛЮБОМ ВИДЕ: видео обрезать нельзя,
           поэтому лёжа ограничена ширина, а не высота. */
        expect(с.видео.ш / с.видео.в, 'пропорция видео ' + с.видео.ш + '×' + с.видео.в)
            .toBeCloseTo(16 / 9, 1);

        if (низкийГоризонтальный(вид)) {
            expect(с.видео.долиВысоты, 'видео ' + с.видео.ш + '×' + с.видео.в +
                ' при экране ' + с.экран.W + '×' + с.экран.H).toBeLessThanOrEqual(0.65);
            /* Уже экрана — значит по центру, а не прижато к краю. */
            expect(Math.abs(с.видео.слева - с.видео.справа),
                'видео не по центру: слева ' + с.видео.слева + ', справа ' + с.видео.справа)
                .toBeLessThanOrEqual(2);
        }
    });

    test('карта и график не занимают экран целиком', async ({ page }) => {
        await дождатьсяОдежды(page);
        await поставитьБлоки(page);
        const с = await снять(page);
        const вид = page.viewportSize();

        if (низкийГоризонтальный(вид)) {
            expect(с.карта.долиВысоты, 'карта высотой ' + с.карта.в +
                ' при экране ' + с.экран.H).toBeLessThanOrEqual(0.65);
            expect(с.график.долиВысоты, 'график высотой ' + с.график.в +
                ' при экране ' + с.экран.H).toBeLessThanOrEqual(0.5);
        } else {
            /* Жёсткие высоты на прочих видах остаются прежними. */
            expect(с.карта.в, 'карта вне низкого горизонтального').toBe(304);
            expect(с.график.в, 'график вне низкого горизонтального').toBe(192);
        }
    });

    test('горизонтальной прокрутки нет ни на одном виде', async ({ page }) => {
        await дождатьсяОдежды(page);
        await поставитьБлоки(page);
        const с = await снять(page);
        expect(с.прокруткаВбок, 'страница поехала вбок на ' +
            с.экран.W + '×' + с.экран.H).toBe(false);
    });
});
