/**
 * ОТКРЫТЬ ЗАКРЫТУЮ СТРАНИЦУ И ДОЖДАТЬСЯ ПРИЗНАКА, КОТОРЫЙ СТАВИТ САМ
 * ПРОДУКТ (кусок 31.10).
 *
 * ЗАМЕР, А НЕ ОПАСЕНИЕ. Ночной прогон 30.10 дал 118 падений на кабинете и
 * админке, и ни одно не от продукта: пробы мерили ФОРМУ ВХОДА, думая, что
 * мерят кабинет. Причина читается в `js/auth-guard.js`: охрана висит на
 * `load`, а не на `DOMContentLoaded`, и внутри делает СЕТЕВОЙ запрос
 * (`getSession`, затем `getUser`, затем профиль). До её конца на странице
 * ничего из кабинета нет. Пробы же шли `waitUntil: 'domcontentloaded'` и
 * тут же считали `count()` — то есть спрашивали разметку раньше, чем
 * охрана решила, пускать ли вообще.
 *
 * ПРИЗНАК БЫЛ ВСЁ ЭТО ВРЕМЯ, И ЕГО СТАВИТ ПРОДУКТ: `body.auth-ready`
 * (`js/auth-guard.js:62` и `:105`). Замер: страниц с охраной — 4, проб,
 * ходящих на них, — 30, проб, ждущих этот признак, — НОЛЬ.
 *
 * ДВА «ГОТОВО» РАЗВЕДЕНЫ, потому что признак ставится в ДВУХ местах.
 * На `:62` он ставится у ТУПИКА «вход живой, профиля в базе нет» — там
 * `body.innerHTML` затирается целиком, и ждать в нём разделов кабинета
 * бессмысленно. Поэтому дом смотрит ещё и на кнопку тупика.
 *
 * ПОЧЕМУ ПРЕДЕЛ 20 СЕКУНД, А НЕ 30. Предел теста — 30
 * (`playwright.config.js:12`). Ожидание, равное пределу теста, не
 * отличает «страница не открылась» от «тест кончился»: сообщение приходит
 * не своё, и причина теряется. 20 оставляет пробе 10 секунд на её
 * собственную работу и на СВОЙ отказ с именем.
 *
 * ОТКАЗ ИМЕНУЕТ СОСТОЯНИЕ, А НЕ ОТСУТСТВИЕ УЗЛА. «Увело на вход» и
 * «профиля нет» — это разные беды, и каждая названа. Прежние пробы
 * говорили «ожидали 1, получили 0», что не причина, а следствие.
 *
 *     const { test, expect, открытьЗакрытую } = require('../../fixtures');
 *     await открытьЗакрытую(page, '/pages/dashboard.html');
 */
async function открытьЗакрытую(page, адрес, предел) {
    await page.goto(адрес, { waitUntil: 'domcontentloaded' });
    const ручка = await page.waitForFunction(() => {
        if (/\/(auth|auth-en|auth-kg)\.html$/.test(location.pathname)) return 'вход';
        if (/\/index(-en|-kg)?\.html$/.test(location.pathname)) return 'домой';
        const b = document.body;
        if (!b || !b.classList.contains('auth-ready')) return null;
        if (document.getElementById('ksltDeadLogout')) return 'без профиля';
        return 'готово';
    }, null, { timeout: предел || 20000 });
    const состояние = await ручка.jsonValue();
    if (состояние === 'вход') {
        throw new Error('ПОРОГ: охрана увела на форму входа — сессия не принята. ' +
            'Это не отсутствие узла, а другая страница: ' + адрес);
    }
    if (состояние === 'домой') {
        throw new Error('ПОРОГ: охрана увела на главную — у этого входа нет прав ' +
            'на ' + адрес + ' (requireStaff/requireAdmin)');
    }
    if (состояние === 'без профиля') {
        throw new Error('ПОРОГ: вход живой, а профиля в базе нет — страница ' +
            'показала тупик вместо разделов (js/auth-guard.js:62)');
    }
    return состояние;
}

/**
 * КТО СТОИТ В ТОЧКЕ НАЖАТИЯ — ОДНО ОПРЕДЕЛЕНИЕ НА ВСЕ ПРОБЫ (31.10).
 *
 * ЗАМЕР. Прогон 31.10 (1760 проверок) оставил 15 падений, и ВСЕ —
 * про окна: обмен баллов, QR, окно кабинета. Сообщение у всех одно и
 * то же: «Test timeout of 60000ms exceeded» — то есть НИКАКОЕ. Я
 * поднимал этим файлам предел (30 → 60/75/90), и падения остались:
 * значит дело было не в сроке.
 *
 * ПРИЧИНА НАЗВАНА ТЕМ ЕДИНСТВЕННЫМ ФАЙЛОМ, У КОТОРОГО ЭТА ОБЁРТКА
 * УЖЕ БЫЛА. Проба 77 на десктопе сказала вслух: «нажатие по „переход в
 * другой раздел“ не прошло: сверху button.db-sidebar-link <
 * li.db-sidebar-item < ul.db-sidebar-nav». Нажатие не проходит, потому
 * что точку ПЕРЕКРЫВАЮТ, а голый `.click()` в этом случае молча ждёт
 * до общего срока. У проб 79, 80 и 81 обёртки не было — там стоял
 * голый `.click()`, и беда приходила без имени.
 *
 * ОДНО ПОНЯТИЕ ЖИЛО В ОДНОМ ФАЙЛЕ ИЗ ЧЕТЫРЁХ — поэтому переезжает
 * сюда, к `виден` и `открытьЗакрытую`.
 *
 * ЧЕГО ОБЁРТКА НЕ ДЕЛАЕТ: не гасит накладку и не обходит её. Она
 * только НАЗЫВАЕТ виновника, чтобы чинить его в продукте, а не
 * подпирать в пробе.
 */
async function ктоСверху(page, цель) {
    const к = await цель.boundingBox();
    if (!к) return null;
    return page.evaluate(([x, y]) => {
        const э = document.elementFromPoint(x, y);
        if (!э) return null;
        const пути = [];
        for (let у = э; у && у !== document.body; у = у.parentElement) {
            пути.push(у.tagName.toLowerCase() +
                (у.className ? '.' + String(у.className).trim().split(/\s+/).join('.') : ''));
        }
        return пути.slice(0, 3).join(' < ');
    }, [к.x + к.width / 2, к.y + к.height / 2]);
}

/**
 * Нажать, назвав перекрывшего, если нажатие не проходит.
 *
 * СРОК СВОЙ И КОРОТКИЙ — 5 секунд. Он намеренно меньше предела теста:
 * ожидание, равное пределу теста, не отличает «нажатие не прошло» от
 * «тест кончился», и сообщение приходит не своё.
 */
async function нажать(page, цель, имя) {
    const сверху = await ктоСверху(page, цель);
    try {
        await цель.click({ timeout: 5000 });
    } catch (e) {
        const есть = await цель.count().catch(() => 0);
        throw new Error('нажатие по «' + имя + '» не прошло: ' +
            (есть ? 'сверху ' + (сверху || 'неизвестно что') : 'элемента нет на странице') +
            '. Накладку надо гасить до проверки, а не ждать срока');
    }
}

