const HEAVY = /\.(png|jpe?g|gif|webp|avif|svg|ico|woff2?|ttf|otf|eot|mp4|webm)(\?|$)/i;

/**
 * ВИДИМ ЛИ УЗЕЛ — ОДНО ОПРЕДЕЛЕНИЕ НА ВСЕ ПРОБЫ (кусок 196, 27.10).
 *
 * ЗАМЕР: видимость считали САМИ 33 пробы, и считали ПО-РАЗНОМУ. Одни
 * смотрели только сам узел, другие поднимались по предкам. Разошлось это
 * не завтра, а уже: проба 94 брала `display` и `visibility` самого
 * кружка — а скрыт был РОДИТЕЛЬ, неактивная панель рейтинга
 * (`div.rankings-panel [display: none]`). Проба считала 16 кружков
 * «видимыми и схлопнутыми в 0x0» и падала — на правильной вёрстке.
 *
 * СВОЙСТВА УЗЛА НЕ ЗНАЮТ О ПРЕДКАХ. Ровно та же беда была у прибора
 * контраста 13.10: `opacity: 0` на родителе в свойствах узла не виден.
 * Третий раз на этих граблях — поэтому определение одно и живёт здесь.
 *
 * Объявляется ДО загрузки страницы, поэтому доступно любой пробе как
 * `window.КСЛТ_виден(узел)` без подключений и импортов.
 */
function виден(эл) {
    if (!эл) return false;
    var r = эл.getBoundingClientRect();
    if (!r.width || !r.height) return false;
    var вид = эл.ownerDocument.defaultView;
    var у = эл;
    while (у) {
        var c = вид.getComputedStyle(у);
        if (c.display === 'none' || c.visibility === 'hidden' || +c.opacity === 0) return false;
        у = у.parentElement;
    }
    return true;
}

/**
 * СЕССИЯ, ВЫДАННАЯ ОДИН РАЗ НА ВЕСЬ ПРОГОН, ЖИВЁТ МЕНЬШЕ ПРОГОНА (01.11).
 *
 * ЗАМЕР, А НЕ ОПАСЕНИЕ. Полный прогон 01.11: начало 16:19:01, срок
 * токена 17:19:02 (`expires_in` 3600), конец 18:30. **Час одиннадцать из
 * двух часов двенадцати прогон шёл с мёртвым токеном** — 54% времени. Из
 * 252 падений **187 были «охрана увела на форму входа»**, и ни одно не от
 * вёрстки. Короткие прогоны на 6–8 минут были зелёными: токен жив.
 *
 * ОДИН RE­FRESH-ТОКЕН НА ТРИ ВОРКЕРА — ЭТО ГОНКА, А НЕ ЗАПАС. Обновить
 * протухший токен `supabase-js` умеет сам, но `refresh_token` в файле
 * сессии ОДИН, а воркеров три: первый его тратит, остальным приходит
 * отказ, и сессия стирается. Отсюда 77 мерцающих проб — с повтора
 * иногда проходило.
 *
 * ЧТО ДЕЛАЕМ. Перед страницей обвязка смотрит сессию, которую положил
 * `storageState`, и если до срока осталось меньше ЗАПАСА — входит ЗАНОВО
 * тем же аккаунтом и кладёт свежую сессию своим `addInitScript`. У
 * каждого воркера своя сессия и свой `refresh_token`: гонки нет.
 *
 * ВХОД НЕ НА КАЖДУЮ ПРОБУ, А НА ВОРКЕР. Сессия кэшируется в памяти
 * процесса воркера, пока жива. За два часа это три входа на воркер, а не
 * пятнадцать тысяч.
 *
 * ПОЧЕМУ `addInitScript`, А НЕ ПОДМЕНА ФАЙЛА. Файл один на прогон и общий
 * для воркеров — писать в него значило бы вернуть ту же гонку, только в
 * файловой системе. `addInitScript` выполняется ПОСЛЕ применения
 * `storageState` и перед скриптами страницы, то есть побеждает честно.
 *
 * ЧЕГО НЕ ДЕЛАЕМ. Гостевые пробы не трогаем вовсе: нет ключа сессии —
 * нечего и обновлять.
 */
const ЗАПАС_СЕССИИ_МС = 15 * 60 * 1000;
const свежие = new Map();          /* email → сессия, на процесс воркера */

function ключСессии(состояние) {
    for (const о of (состояние.origins || [])) {
        for (const з of (о.localStorage || [])) {
            if (/^sb-.*-auth-token$/.test(з.name)) return з;
        }
    }
    return null;
}

async function сессияНаСрок(email) {
    const готовая = свежие.get(email);
    if (готовая && готовая.expires_at * 1000 - Date.now() > ЗАПАС_СЕССИИ_МС) {
        return готовая;
    }
    const настройка = require('./auth-setup');
    const аккаунт = (настройка.ACCOUNTS || []).find(а => а.email === email);
    /* НЕИЗВЕСТНЫЙ АККАУНТ — НЕ ПОВОД МОЛЧА ПОДСТАВИТЬ ЧУЖОЙ ВХОД. */
    if (!аккаунт) return null;
    const новая = await настройка.signIn(аккаунт);
    свежие.set(email, новая);
    return новая;
}

