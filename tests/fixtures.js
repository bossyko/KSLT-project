/**
 * ДОЖДАТЬСЯ АСИНХРОННОГО ЗАМЕРА И ВЕРНУТЬ ЕГО ЗНАЧЕНИЕ (кусок 01.11).
 *
 * ЗАЧЕМ ОН ЕСТЬ — СЛУЧАЙ, А НЕ ОПАСЕНИЕ. `page.waitForFunction(async () =>
 * …)` НЕ ЖДЁТ НИЧЕГО. Внутри бегунка стоит
 * `const success = predicate(); if (success) { fulfill(success); return; }`
 * (`playwright-core/lib/server/frames.js`) — а асинхронная проверка
 * возвращает ПРОМИС, и промис всегда истинен. Значит ожидание считает
 * «дождался» на ПЕРВОМ ЖЕ проходе и отдаёт то, чем промис разрешится, —
 * хоть `false`.
 *
 * ЗАМЕРЕНО, А НЕ ВЫЧИТАНО. Опыт на своём стенде: признак, становящийся
 * верным через 1200 мс. Асинхронный вернул `false` через 57 мс;
 * синхронный дождался и вернул значение через 1221 мс.
 *
 * ЦЕНА БЫЛА УПЛАЧЕНА ДВАЖДЫ. Пробы офлайн-службы читали `.адрес` у
 * `false` и падали с «received value must be a string». А третья проба
 * того же файла ЗЕЛЕНЕЛА ВСЛЕПУЮ: она тоже ничего не дождалась, но
 * значения не проверяла — служба успевала подняться сама.
 * **ПРОБА, КОТОРАЯ НЕ ЖДАЛА, ЗЕЛЕНА СЛУЧАЙНО.**
 *
 * ЧТО ДЕЛАЕМ. Ожидание и замер разделены: цикл зовёт `page.evaluate`,
 * который промисы ждать умеет, и возвращает САМО значение. Пустой ответ
 * (`false`, `null`, `undefined`) значит «ещё не готово».
 */
async function дождатьсяЗамера(page, замер, предел, шаг) {
    const срок = Date.now() + (предел || 30000);
    let последнее = null;
    for (;;) {
        последнее = await page.evaluate(замер);
        if (последнее) return последнее;
        if (Date.now() > срок) {
            throw new Error('замер не стал готов за ' + (предел || 30000) +
                ' мс: последнее значение ' + JSON.stringify(последнее) +
                '\n    ОЖИДАНИЕ И ЗАМЕР РАЗДЕЛЕНЫ НАРОЧНО: см. дождатьсяЗамера в tests/fixtures.js');
        }
        await page.waitForTimeout(шаг || 250);
    }
}

