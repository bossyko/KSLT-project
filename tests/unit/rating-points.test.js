// ============================================
// Очки рейтинга: правила Положения КСЛТ
// Таблица мест, сноска про неразыгранные места,
// очки за победы в группе
// ============================================

import { describe, it, expect } from 'vitest'
import ОЧКИ from '../../js/rating-points.js'

// Колонка «Высшая» из Приложения 2, места 1-16
const ВЫСШАЯ = {
  1: 1000, 2: 600, 3: 420, 4: 360, 5: 250, 6: 215, 7: 180, 8: 180,
  9: 145, 10: 125, 11: 110, 12: 110, 13: 90, 14: 90, 15: 90, 16: 90
}

// Колонка «Вторая» — обычная категория однодневного турнира
const ВТОРАЯ = {
  1: 360, 2: 215, 3: 150, 4: 130, 5: 90, 6: 78, 7: 65, 8: 65
}

describe('очки за место', () => {
  it('платит по таблице своей категории', () => {
    expect(ОЧКИ.заМесто(1, ВЫСШАЯ)).toBe(1000)
    expect(ОЧКИ.заМесто(3, ВЫСШАЯ)).toBe(420)
    expect(ОЧКИ.заМесто(1, ВТОРАЯ)).toBe(360)
  })

  it('за место дальше таблицы не платит', () => {
    expect(ОЧКИ.заМесто(99, ВЫСШАЯ)).toBe(0)
  })

  it('без места и без таблицы не падает', () => {
    expect(ОЧКИ.заМесто(null, ВЫСШАЯ)).toBe(0)
    expect(ОЧКИ.заМесто(1, null)).toBe(0)
  })
})

describe('сноска: места не разыгрывались', () => {
  it('без матча за третье оба полуфиналиста получают как за четвёртое', () => {
    const у = ОЧКИ.поТурниру([
      { place: 1, разыграно: true },
      { place: 2, разыграно: true },
      { place: 3, разыграно: false },
      { place: 3, разыграно: false }
    ], ВЫСШАЯ, {})

    expect(у[0].points_earned).toBe(1000)
    expect(у[1].points_earned).toBe(600)
    // Оба третьих занимают 3 и 4 место — платим за последнее, 360
    expect(у[2].points_earned).toBe(360)
    expect(у[3].points_earned).toBe(360)
  })

  it('с матчем за третье место третий и четвёртый различаются', () => {
    const у = ОЧКИ.поТурниру([
      { place: 3, разыграно: true },
      { place: 4, разыграно: true }
    ], ВЫСШАЯ, {})

    expect(у[0].points_earned).toBe(420)
    expect(у[1].points_earned).toBe(360)
  })

  it('четвёрка проигравших четвертьфиналы получает как за восьмое', () => {
    const у = ОЧКИ.поТурниру([
      { place: 5, разыграно: false },
      { place: 5, разыграно: false },
      { place: 5, разыграно: false },
      { place: 5, разыграно: false }
    ], ВЫСШАЯ, {})

    // Четверо занимают места 5-8, платим за последнее — 180
    у.forEach(у1 => expect(у1.points_earned).toBe(180))
  })

  it('разыгранное место не уравнивается с соседями', () => {
    const у = ОЧКИ.поТурниру([
      { place: 5, разыграно: true },
      { place: 6, разыграно: true }
    ], ВЫСШАЯ, {})

    expect(у[0].points_earned).toBe(250)
    expect(у[1].points_earned).toBe(215)
  })
})

describe('победы в группе', () => {
  const правила = { заПобеды: true }

  it('добавляет 25 за каждую победу', () => {
    const у = ОЧКИ.поТурниру([
      { place: 1, разыграно: true, побед: 5 }
    ], ВТОРАЯ, правила)

    expect(у[0].points_earned).toBe(360 + 5 * 25)
  })

  it('без побед даёт 10 за участие', () => {
    const у = ОЧКИ.поТурниру([
      { place: 20, разыграно: false, побед: 0 }
    ], ВТОРАЯ, правила)

    // Места 20 в таблице «Вторая» нет — только 10 за участие
    expect(у[0].points_earned).toBe(10)
  })

  it('в олимпийке победы отдельно не платятся', () => {
    const у = ОЧКИ.поТурниру([
      { place: 1, разыграно: true, побед: 4 }
    ], ВЫСШАЯ, {})

    expect(у[0].points_earned).toBe(1000)
  })
})

describe('подсчёт побед', () => {
  const матчи = [
    { status: 'completed', winner_id: 'a', score: '6/3' },
    { status: 'completed', winner_id: 'b', score: '6/4' },
    { status: 'completed', winner_id: 'a', score: 'BYE' },
    { status: 'upcoming', winner_id: null, score: null }
  ]

  it('считает выигранные встречи', () => {
    expect(ОЧКИ.победы('b', матчи)).toBe(1)
  })

  it('проход без игры победой не считает', () => {
    // У «a» две записи с победой, но одна из них BYE
    expect(ОЧКИ.победы('a', матчи)).toBe(1)
  })

  it('без игрока и без матчей не падает', () => {
    expect(ОЧКИ.победы(null, матчи)).toBe(0)
    expect(ОЧКИ.победы('a', null)).toBe(0)
  })
})
