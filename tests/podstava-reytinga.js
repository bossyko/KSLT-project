const РАЗРЯДЫ = [
    { ключ: 'men-promasters', имя: 'Pro-Masters', пол: 'men', людей: 24 },
    { ключ: 'men-masters',    имя: 'Masters',     пол: 'men', людей: 60 },
    { ключ: 'men-tour',       имя: 'Tour',        пол: 'men', людей: 12 },
    { ключ: 'men-challenger', имя: 'Challenger',  пол: 'men', людей: 8 },
    { ключ: 'women-masters',  имя: 'Masters',     пол: 'women', людей: 16 },
    { ключ: 'women-tour',     имя: 'Tour',        пол: 'women', людей: 9 },
];

const ИМЕНА = [
    'Константин Лазаренко-Мифтахутдинов',
    'Ли О',
    'Атхам Исраилов',
    'Эрлан Шекербеков',
    'Эльдар Сафиуллин',
    'Рамиль Мифтахутдинов',
    'Улугбек Салыков',
    'Роман Гуди',
];

function игроки(разряд) {
    const список = [];
    for (let i = 0; i < разряд.людей; i++) {
        список.push({
            id: разряд.ключ + '-' + (i + 1),
            name: ИМЕНА[i % ИМЕНА.length] + (i >= ИМЕНА.length ? ' ' + (i + 1) : ''),
            points: 1600 - i * 17,
            rank: i + 1,
            place: i + 1,
            category_id: разряд.ключ.split('-').slice(1).join('-'),
            gender: разряд.пол,
            country: 'KG',
            photo: null,
            online: i % 7 === 0,
            ntrp: 5.25 - i * 0.05,
            wins: 4, losses: i % 3,
            badges: [],
            form: ['w', 'w', 'l', 'w'],
            delta: 0,
            is_guest: false,
        });
    }
    return список;
}

function данные() {
    const карта = {};
    РАЗРЯДЫ.forEach(р => {
        карта[р.ключ] = {
            name: р.имя,
            gender: р.пол,
            players: игроки(р),
        };
    });
    return карта;
}

/**
 * Поставить подставу в контекст прогона. Зовётся ДО первого goto.
 * @param {import('@playwright/test').BrowserContext} контекст
 */
async function поставить(контекст) {
    await контекст.addInitScript(карта => {
        const подстава = {
            load: function () { return Promise.resolve(карта); },
            всегоИгроков: Object.keys(карта)
                .reduce((с, к) => с + карта[к].players.length, 0),
            подстава: true,
        };
        try {
            Object.defineProperty(window, 'KSLT_RANKINGS', {
                value: подстава, writable: false, configurable: false,
            });
        } catch (e) {
            window.KSLT_RANKINGS = подстава;
        }
    }, данные());
}

/**
 * Контекст с подставой и с адресом тестовой базы — ОДНОЙ СТРОКОЙ.
 * 06.10 я завёл подставу для проб и забыл применить её к прибору: он снял
 * шестьдесят страниц по пустой базе — ноль строк и ноль карточек подиума.
 * Теперь контекст заводится здесь, и забыть подставу нельзя: другого входа
 * для прибора нет.
 */
async function контекст(браузер, вид) {
    const db = require('./test-db');
    const ctx = await браузер.newContext(вид ? { viewport: вид } : {});
    await ctx.addInitScript(cfg => { window.KSLT_DB = cfg; }, { url: db.url, key: db.key });
    await поставить(ctx);
    return ctx;
}

module.exports = { поставить, контекст, данные, РАЗРЯДЫ };
